(* ========================================================================= *)
(* 4CT/present_eval.ml                                                       *)
(*                                                                           *)
(* The interpreter for Gonthier's presentation scripts present5.v to         *)
(* present11.v.  The scripts are step data (presentations_data.ml, 14421     *)
(* steps); each step applies one of the lemmas of present.ml and discharges  *)
(* its computational side condition by call-by-value evaluation:             *)
(*                                                                           *)
(*   Pcase lab: i[j] <= k / > k  -->  SUCCEED_BY_SPLIT i (j-1) k lo          *)
(*        (good_split evaluated; the two residual goals are the indented     *)
(*        block and the continuation, whose `successful p0l` hypothesis      *)
(*        gets the Coq label via LABEL_TAC)                                  *)
(*   Reducible                  -->  SUCCEED_BY_REDUCIBILITY                 *)
(*                                   (redpart ... = T)                       *)
(*   Hubcap hc                  -->  SUCCEED_BY_HUBCAP hc                    *)
(*                                   (hubcap_cover /\ hubcap_fit ... = T)    *)
(*   Similar to lab[n]          -->  SUCCEED_BY_SIMILARITY n mir ps with     *)
(*                                   the labelled hypothesis                 *)
(*                                   (size/cmp_part = T)                     *)
(*   Presentation red           -->  EXCLUDE_ARITY, DISCH                    *)
(*                                   (check_reducibility), CBV.              *)
(*                                                                           *)
(* The compset present_compset is redpart_compset with integer arithmetic    *)
(* (int_compute_add_convs), NUM_OF_INT_OF_NUM, dboundK and the_drule_fork    *)
(* 5..11 tabulated; prove_exclude n steps proves excluded_arity (:A) n.      *)
(*                                                                           *)
(* With parallel.ml loaded (OCaml 5, par_hook.ml), the side conditions of    *)
(* the Reducible, Hubcap and Similar steps are instead assumed while the     *)
(* script runs, then evaluated in parallel and discharged by PROVE_HYP       *)
(* (prove_exclude_parallel).  Otherwise everything is as described above.    *)
(* ========================================================================= *)

needs "4CT/redpart_eval.ml";;
needs "4CT/par_hook.ml";;

(* ------------------------------------------------------------------------- *)
(* Step data (type in present_steps_type.ml, data generated by               *)
(* gen_presentations.py).                                                    *)
(* ------------------------------------------------------------------------- *)

needs "4CT/present_steps_type.ml";;
needs "4CT/presentations_data.ml";;

let ploc_term = function
    Spoke -> `Pspoke` | Hat -> `Phat` | Fan1 -> `Pfan1` | Fan2 -> `Pfan2`
    | Fan3 -> `Pfan3`;;

let int_term b =
  if b < 0 then
    mk_comb(`(--):int->int`, mk_comb(`(&):num->int`, mk_small_numeral (-b)))
  else mk_comb(`(&):num->int`, mk_small_numeral b);;

(* Coq `$[j1,j2]<=b ... $`: Hubcap2 (j1-1) (j2-1) b (...), outermost first   *)
let hubcap_term items =
  itlist (fun it rest ->
            match it with
              Hc1(j,b) -> list_mk_comb(`Hubcap1`, [mk_small_numeral (j-1);
                                                   int_term b; rest])
            | Hc2(j1,j2,b) ->
                list_mk_comb(`Hubcap2`
       , [mk_small_numeral (j1-1); mk_small_numeral (j2-1); int_term b; rest]))
         items `Hubcap0`;;

(* ------------------------------------------------------------------------- *)
(* The compset.                                                              *)
(* ------------------------------------------------------------------------- *)

let present_compset () =
  let cs = redpart_compset() in
  int_compute_add_convs cs;
  Compute.add_thms [NUM_OF_INT_OF_NUM; dboundK; INT_NEG_0] cs;
  let forks = map
 (fun n -> Compute.CBV_CONV cs (mk_comb(`the_drule_fork`, mk_small_numeral n)))
   (5--11) in
  Compute.add_thms forks cs;
  cs;;

let the_present_compset = present_compset();;

(* ------------------------------------------------------------------------- *)
(* The step tactics. Goals have the form `succeeds_in (:A) p0 p` with the    *)
(* assumption `check_reducibility` and labelled `successful (:A) ps` facts.  *)
(* ------------------------------------------------------------------------- *)

let step_count = ref 0;;
let step_report = ref 500;;
let step_times = (Hashtbl.create 8 : (string, float * int) Hashtbl.t);;

let CBV_TAC cs = CONV_TAC(Compute.CBV_CONV cs);;

(* The side condition of a Reducible, Hubcap or Similar step: evaluated at   *)
(* once, or (parallel mode) assumed and recorded in side_conditions          *)
let side_conditions = ref ([]:term list);;

let SIDE_TAC cs (asl,w as g) =
  if !par_enabled then
    (side_conditions := w :: !side_conditions; ACCEPT_TAC (ASSUME w) g)
  else CBV_TAC cs g;;

(* count, report progress, accumulate the time per step kind, localize       *)
(* failures                                                                  *)
let count_step name tac g =
  incr step_count;
  if !step_count mod !step_report = 0 then
    Printf.printf "PRESENT_EVAL: step %d (%.0f s)\n%!" !step_count
      (Sys.time());
  let t0 = Sys.time() in
  let r = try tac g
          with Failure s -> failwith
         (Printf.sprintf "PRESENT_EVAL step %d (%s): %s" !step_count name s) in
  let (t,n) = try Hashtbl.find step_times name with Not_found -> (0.0,0) in
  Hashtbl.replace step_times name (t +. Sys.time() -. t0, n + 1);
  r;;

let report_step_times () =
  Hashtbl.iter
 (fun name (t,n) -> Printf.printf "PRESENT_EVAL:   %-10s %5d steps %8.1f s\n%!"
   name n t) step_times;;

let PCASE_TAC cs lab loc j k lo block cont =
  count_step "Pcase"
   (MATCH_MP_TAC(ISPECL
     [ploc_term loc; mk_small_numeral (j-1); mk_small_numeral k;
                         (if lo then `T` else `F`)] SUCCEED_BY_SPLIT) THEN
    CBV_TAC cs THEN CONJ_TAC) THENL
  [block;
   (if lab = "_" then DISCH_THEN(K ALL_TAC) else DISCH_THEN(LABEL_TAC lab))
     THEN cont];;

let REDUCIBLE_TAC cs =
  count_step "Reducible"
   (MATCH_MP_TAC SUCCEED_BY_REDUCIBILITY THEN CONJ_TAC THENL
     [FIRST_ASSUM ACCEPT_TAC; SIDE_TAC cs]);;

let HUBCAP_TAC cs items =
  count_step "Hubcap"
   (MATCH_MP_TAC(ISPEC (hubcap_term items) SUCCEED_BY_HUBCAP) THEN
   CONJ_TAC THENL
     [FIRST_ASSUM ACCEPT_TAC; SIDE_TAC cs]);;

let SIMILAR_TAC cs lab j mir =
  count_step "Similar"
   (USE_THEN lab (fun th ->
      MATCH_MP_TAC(ISPECL
        [mk_small_numeral j; (if mir then `T` else `F`); rand(concl th)]
                          SUCCEED_BY_SIMILARITY) THEN
      CONJ_TAC THENL [ACCEPT_TAC th; SIDE_TAC cs]));;

(* A block at depth d: Pcases at depth d (each followed by its indented      *)
(* block) ending with a terminal step at depth d.                            *)
let rec build_block cs d steps =
  match steps with
    (d', Pcase(lab,loc,j,k,lo)) :: rest when d' = d ->
      let (block, rest1) = build_block cs (d+1) rest in
      let (cont, rest2) = build_block cs d rest1 in
      (PCASE_TAC cs lab loc j k lo block cont, rest2)
  | (d', Reducible) :: rest when d' = d -> (REDUCIBLE_TAC cs, rest)
  | (d', Hubcap items) :: rest when d' = d -> (HUBCAP_TAC cs items, rest)
  | (d', Similar(lab,j,mir)) :: rest when d' = d ->
    (SIMILAR_TAC cs lab j mir, rest)
  | _ -> failwith "build_block: malformed presentation";;

let PRESENTATION_TAC cs steps =
  let (tac, rest) = build_block cs 0 steps in
  if rest <> [] then failwith "PRESENTATION_TAC: trailing steps" else
  MATCH_MP_TAC EXCLUDE_ARITY THEN DISCH_TAC THEN CBV_TAC cs THEN tac;;

(* excluded_arity (:A) n from the steps of present<n>.v, with timing         *)
let prove_exclude_sequential n steps =
  let t0 = Sys.time() in
  step_count := 0; Hashtbl.reset step_times;
  let th = prove(mk_comb(`excluded_arity (:A)`, mk_small_numeral n),
                 PRESENTATION_TAC the_present_compset steps) in
  Printf.printf "PRESENT_EVAL: exclude%d proved, %d steps, %.1f s\n%!" n
    !step_count (Sys.time() -. t0);
  report_step_times();
  th;;

(* ------------------------------------------------------------------------- *)
(* The parallel mode (par_hook.ml, parallel.ml): the script proves           *)
(* excluded_arity (:A) n from its side conditions (TAC_PROOF, since prove    *)
(* rejects hypotheses); these, almost all the work, are then evaluated by    *)
(* CBV in !par_domains domains, the expensive Hubcap ones first, and         *)
(* discharged by PROVE_HYP; a side condition that does not evaluate to T     *)
(* leaves a hypothesis, which is an error.  The domains share                *)
(* the_present_compset.  CBV only reads a compset, except that it enters     *)
(* every constant it meets that the compset does not know yet (with no       *)
(* rules); compset_saturate makes that impossible by entering all constants  *)
(* first, in the same way (set_skip with None makes the same empty entry).   *)
(* ------------------------------------------------------------------------- *)

let compset_saturate cs =
  let known = Hashtbl.create 10000 in
  List.iter (fun (c,_) -> Hashtbl.replace known c ()) (Compute.listItems cs);
  List.iter (fun (c,_) -> if not (Hashtbl.mem known c) then
                            (Hashtbl.replace known c ();
                             Compute.set_skip cs (mk_const(c,[])) None))
            (constants());;

let prove_exclude_parallel n steps =
  let t0 = !par_time() and c0 = Sys.time() in
  step_count := 0; Hashtbl.reset step_times; side_conditions := [];
  let tm = mk_comb(`excluded_arity (:A)`, mk_small_numeral n) in
  let th0 = TAC_PROOF(([],tm), PRESENTATION_TAC the_present_compset steps) in
  let t1 = !par_time() in
  let is_hubcap w = is_conj w && match strip_comb(lhand w) with
                                    Const("hubcap_cover",_),_ -> true
                                  | _ -> false in
  let hubcaps,others = partition is_hubcap (setify !side_conditions) in
  let sides = Array.of_list(hubcaps @ others) in
  compset_saturate the_present_compset;
  let eval _ w = EQT_ELIM(Compute.CBV_CONV the_present_compset w) in
  let ths = mapfilter (function Some th -> th | None -> fail())
     (Array.to_list((!par_mapper).par_map !par_domains eval sides)) in
  let t2 = !par_time() in
  let th = itlist PROVE_HYP ths th0 in
  let t3 = !par_time() in
  if hyp th <> [] then
    failwith (Printf.sprintf "prove_exclude %d: %d side conditions failed" n
                (length(hyp th))) else
  (Printf.printf "PRESENT_EVAL: exclude%d proved, %d steps, %d side \
                  conditions (%d distinct) in %d domains; wall %.1f s \
                  (script %.1f s, side conditions %.1f s, PROVE_HYP %.1f \
                  s), CPU %.1f s\n%!"
     n !step_count (length !side_conditions) (Array.length sides)
     (max 1 (min !par_domains (Array.length sides))) (t3 -. t0) (t1 -. t0)
     (t2 -. t1) (t3 -. t2) (Sys.time() -. c0);
   if concl th = tm then th else EQ_MP (ALPHA (concl th) tm) th);;

let prove_exclude n steps =
  if !par_enabled then prove_exclude_parallel n steps
  else prove_exclude_sequential n steps;;

