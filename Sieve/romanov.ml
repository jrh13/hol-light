  SUBGOAL_THEN `&0 <= PI` ASSUME_TAC THENL
   [EXPAND_TAC "PI" THEN REWRITE_TAC[REAL_POS]; ALL_TAC] THEN
  SUBGOAL_THEN `&K * PI <= &2 * &x / log(&a)` ASSUME_TAC THENL
