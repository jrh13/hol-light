        2 <= a /\ 2 <= x /\ 1 <= j /\ j < k
        ==> &(CARD {n | n IN 1..x /\ prime(n - a EXP k) /\
                        prime(n - a EXP j)})
            <= &448 * &x / log(&x) pow 2 *
               inv(product {p | prime p /\ p divides a EXP k - a EXP j}
                           (\p. &1 - inv(&p)) pow 2)`,
