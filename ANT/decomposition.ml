(* The residue ring of A at P, as the subring of b / Q generated by the      *)
(* image of A, is that image.                                                *)

let SUBRING_GENERATED_QUOTIENT_RING_IMAGE = prove
 (`!(h:A->B) k l b Q.
        ring_homomorphism(k,l) h /\
        subring_generated l (ring_carrier b) = b /\ ring_ideal b Q
        ==> ring_carrier
             (subring_generated (quotient_ring b Q)
               (IMAGE (ring_coset b Q o h)
                      {a | a IN ring_carrier k /\ h a IN ring_carrier b})) =
            {ring_coset b Q (h a) | a | a IN ring_carrier k /\
                                        h a IN ring_carrier b}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `IMAGE (ring_coset b Q o (h:A->B))
          {a | a IN ring_carrier k /\ h a IN ring_carrier b} =
    {ring_coset b Q (h a) | a | a IN ring_carrier k /\ h a IN ring_carrier b}`
  (SUBST1_TAC o SYM) THENL
   [REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM; o_THM] THEN MESON_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC CARRIER_SUBRING_GENERATED_SUBRING THEN
  ABBREV_TAC
   `A = {a | a IN ring_carrier k /\ (h:A->B) a IN ring_carrier b}` THEN
  SUBGOAL_THEN `(A:A->bool) subring_of k` ASSUME_TAC THENL
   [EXPAND_TAC "A" THEN MATCH_MP_TAC SUBRING_OF_HOMOMORPHIC_PREIMAGE THEN
    EXISTS_TAC `l:B ring` THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`]
      SUBRING_SUBRING_GENERATED) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `A = ring_carrier(subring_generated k (A:A->bool))`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING]; ALL_TAC] THEN
  MATCH_MP_TAC SUBRING_OF_HOMOMORPHIC_IMAGE THEN
  EXISTS_TAC `subring_generated k (A:A->bool)` THEN
  REWRITE_TAC[CARRIER_SUBRING_OF] THEN
  MATCH_MP_TAC RING_HOMOMORPHISM_COMPOSE THEN EXISTS_TAC `b:B ring` THEN
  ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET] THEN
  UNDISCH_TAC `subring_generated l (ring_carrier b) = (b:B ring)` THEN
  DISCH_THEN(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV) [SYM th]) THEN
  MATCH_MP_TAC RING_HOMOMORPHISM_BETWEEN_SUBRINGS THEN
  ASM_REWRITE_TAC[] THEN EXPAND_TAC "A" THEN SET_TAC[]);;

(* The residue ring of f(Q) is the image of that of Q under X |-> f(X).      *)

let GALOIS_GROUP_QUOTIENT_RING_IMAGE = prove
 (`!(h:A->B) k l b f Q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\ f IN group_carrier(galois_group(k,l) h)
        ==> ring_carrier(quotient_ring b (IMAGE f Q)) =
            IMAGE (IMAGE f) (ring_carrier(quotient_ring b Q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                 `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
