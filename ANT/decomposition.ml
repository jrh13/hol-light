    REWRITE_TAC[CONJUNCT2 DECOMPOSITION_GROUP; CONJUNCT2 GALOIS_GROUP] THEN
    CONJ_TAC THENL
     [X_GEN_TAC `f:B->B` THEN DISCH_TAC THEN
      USE_THEN "rho" (MP_TAC o C MATCH_MP
       (ASSUME `f IN group_carrier(decomposition_group(k,l) (h:A->B) Q)`)) THEN
      DISCH_THEN(STRIP_ASSUME_TAC o REWRITE_RULE[]) THEN
      ASM_REWRITE_TAC[IN_GALOIS_GROUP; I_THM] THEN
      EXPAND_TAC "kP" THEN
      MP_TAC(ISPECL
