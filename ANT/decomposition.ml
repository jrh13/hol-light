let frobenius_element = new_definition
 `frobenius_element (k:A ring,l:B ring) (h:A->B) (b:B ring) (Q:B->bool) =
    @f. f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q /\
