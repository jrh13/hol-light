  ASSUME_TAC THENL
   [REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[decomposition_group] THEN
  MATCH_MP_TAC SUBGROUP_OF_SUBGROUP_GENERATED THEN CONJ_TAC THENL
   [REWRITE_TAC[inertia_group; SUBGROUP_SUBGROUP_GENERATED];
    ASM_SIMP_TAC[INERTIA_GROUP] THEN SET_TAC[]]);;

(* The number of maximal ideals above the contraction of Q times |D_Q| is    *)
(* [l:k]; D_Q is the stabilizer of Q in the transitive action.               *)

let DECOMPOSITION_GROUP_INDEX = prove
 (`!(h:A->B) k l b Q.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q
        ==> FINITE {Q' | maximal_ideal b Q' /\
                         {a | a IN ring_carrier k /\ h a IN Q'} =
                         {a | a IN ring_carrier k /\ h a IN Q}} /\
            CARD {Q' | maximal_ideal b Q' /\
                       {a | a IN ring_carrier k /\ h a IN Q'} =
                       {a | a IN ring_carrier k /\ h a IN Q}} *
            CARD(group_carrier(decomposition_group(k,l) h Q)) =
            extension_degree(k,l) h`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `Q:B->bool`]
    GALOIS_GROUP_ORBIT_MAXIMAL_IDEAL) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`]
    GALOIS_GROUP_ACTION_SUBRING) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  SUBGOAL_THEN `FINITE(group_carrier(galois_group(k,l) (h:A->B)))`
  ASSUME_TAC THENL [ASM_SIMP_TAC[FINITE_GALOIS_GROUP]; ALL_TAC] THEN
  ASM_SIMP_TAC[FINITE_GROUP_ORBIT] THEN
  SUBGOAL_THEN
   `CARD(group_carrier(galois_group(k,l) (h:A->B))) = extension_degree(k,l) h`
  (SUBST1_TAC o SYM) THENL
   [ASM_MESON_TAC[GALOIS_EXTENSION_EQ_CARD]; ALL_TAC] THEN
  MP_TAC(ISPECL [`galois_group(k,l) (h:A->B)`;
                 `{Q | maximal_ideal b Q}:(B->bool)->bool`;
                 `IMAGE:(B->B)->(B->bool)->(B->bool)`; `Q:B->bool`]
    ORBIT_STABILIZER_MUL) THEN
  ASM_REWRITE_TAC[IN_ELIM_THM; group_stabilizer; DECOMPOSITION_GROUP]);;

let DECOMPOSITION_GROUP_CONJUGATE = prove
 (`!(h:A->B) k l f Q.
        f IN group_carrier(galois_group(k,l) h)
        ==> group_carrier(decomposition_group(k,l) h (IMAGE f Q)) =
            IMAGE (\g. f o g o inverse f)
                  (group_carrier(decomposition_group(k,l) h Q))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`galois_group(k,l) (h:A->B)`; `(:B->bool)`;
                 `IMAGE:(B->B)->(B->bool)->(B->bool)`; `f:B->B`; `Q:B->bool`]
    GROUP_STABILIZER_OF_ACTION) THEN
  ASM_REWRITE_TAC[GALOIS_GROUP_ACTION; IN_UNIV] THEN
  SUBGOAL_THEN `group_conjugation (galois_group(k,l) (h:A->B)) f =
                (\g. f o g o inverse f)` SUBST1_TAC THENL
   [REWRITE_TAC[FUN_EQ_THM; group_conjugation; CONJUNCT2 GALOIS_GROUP];
    REWRITE_TAC[group_stabilizer; DECOMPOSITION_GROUP]]);;

let INERTIA_GROUP_CONJUGATE = prove
 (`!(h:A->B) k l b f Q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\ f IN group_carrier(galois_group(k,l) h)
        ==> group_carrier(inertia_group(k,l) h b (IMAGE f Q)) =
            IMAGE (\g. f o g o inverse f)
                  (group_carrier(inertia_group(k,l) h b Q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                 `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[INERTIA_GROUP; DECOMPOSITION_GROUP; IN_ELIM_THM] THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
  DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
  SUBGOAL_THEN `!y:B. y IN IMAGE (f:B->B) Q <=> inverse f y IN Q`
    (fun th -> REWRITE_TAC[th]) THENL
   [REWRITE_TAC[IN_IMAGE] THEN ASM_MESON_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_homomorphism(l,l) (inverse(f:B->B)) /\
    ring_carrier b SUBSET ring_carrier l /\
    (!x. x IN ring_carrier b ==> f x IN ring_carrier b) /\
    (!x. x IN ring_carrier b ==> inverse f x IN ring_carrier b)`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_RING_AUTOMORPHISM; GALOIS_GROUP_INVERSE;
                    ring_automorphism; RING_ISOMORPHISM_IMP_HOMOMORPHISM];
      MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`]
        RING_CARRIER_SUBRING_GENERATED_SUBSET) THEN
      ASM_REWRITE_TAC[];
      ASM SET_TAC[];
      ASM_MESON_TAC[GALOIS_GROUP_INVERSE; SUBSET; IN_IMAGE]];
    ALL_TAC] THEN
  SUBGOAL_THEN `IMAGE (inverse f) (IMAGE (f:B->B) Q) = Q` ASSUME_TAC THENL
   [ASM SET_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `inverse(f:B->B)`]
    RING_HOMOMORPHISM_SUB) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `g:B->B` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN GEN_REWRITE_TAC RAND_CONV [IN_IMAGE] THEN
  REWRITE_TAC[IN_ELIM_THM] THEN EQ_TAC THENL
   [STRIP_TAC THEN EXISTS_TAC `inverse (f:B->B) o (g:B->B) o f` THEN
    ASM_SIMP_TAC[GALOIS_GROUP_COMPOSE; GALOIS_GROUP_INVERSE; IMAGE_o] THEN
    REWRITE_TAC[FUN_EQ_THM; o_THM] THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `x:B` THEN DISCH_TAC THEN
    UNDISCH_TAC
     `!x:B. x IN ring_carrier b
            ==> inverse (f:B->B) (ring_sub l ((g:B->B) x) x) IN Q` THEN
    DISCH_THEN(MP_TAC o SPEC `(f:B->B) x`) THEN
    FIRST_X_ASSUM(MP_TAC o SPECL [`(g:B->B) ((f:B->B) x)`; `(f:B->B) x`]) THEN
    ANTS_TAC THENL [ASM SET_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    ASM_SIMP_TAC[];
    DISCH_THEN(X_CHOOSE_THEN `g':B->B`
     (CONJUNCTS_THEN2 SUBST1_TAC STRIP_ASSUME_TAC)) THEN
    ASM_SIMP_TAC[GALOIS_GROUP_COMPOSE; GALOIS_GROUP_INVERSE; IMAGE_o] THEN
    X_GEN_TAC `x:B` THEN DISCH_TAC THEN REWRITE_TAC[o_THM] THEN
    FIRST_X_ASSUM(MP_TAC o SPECL
     [`(f:B->B) ((g':B->B) (inverse f (x:B)))`; `x:B`]) THEN
    ANTS_TAC THENL [ASM SET_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    ASM_SIMP_TAC[]]);;

let CARD_DECOMPOSITION_GROUP_CONJUGATE = prove
 (`!(h:A->B) k l b f Q.
        finite_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\ f IN group_carrier(galois_group(k,l) h)
        ==> CARD(group_carrier(decomposition_group(k,l) h (IMAGE f Q))) =
            CARD(group_carrier(decomposition_group(k,l) h Q)) /\
            CARD(group_carrier(inertia_group(k,l) h b (IMAGE f Q))) =
            CARD(group_carrier(inertia_group(k,l) h b Q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_SIMP_TAC[DECOMPOSITION_GROUP_CONJUGATE; INERTIA_GROUP_CONJUGATE] THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES o check (fun th ->
    concl th = `f IN group_carrier(galois_group(k,l) (h:A->B))`)) THEN
  DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
  CONJ_TAC THEN MATCH_MP_TAC CARD_IMAGE_INJ THEN
  (CONJ_TAC THENL
    [MAP_EVERY X_GEN_TAC [`g1:B->B`; `g2:B->B`] THEN
     REWRITE_TAC[FUN_EQ_THM; o_THM] THEN STRIP_TAC THEN
     X_GEN_TAC `z:B` THEN
     FIRST_X_ASSUM(MP_TAC o SPEC `(f:B->B) z`) THEN ASM_REWRITE_TAC[] THEN
     DISCH_THEN(MP_TAC o AP_TERM `inverse(f:B->B)`) THEN ASM_REWRITE_TAC[];
     MATCH_MP_TAC FINITE_SUBSET THEN
     EXISTS_TAC `group_carrier(galois_group(k,l) (h:A->B))` THEN
     ASM_SIMP_TAC[FINITE_GALOIS_GROUP] THEN
     REWRITE_TAC[decomposition_group; inertia_group;
                 GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET]]));;

