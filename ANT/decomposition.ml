          ALL_TAC] THEN
        SUBGOAL_THEN `ring_pow l y q IN (Q:B->bool)` ASSUME_TAC THENL
         [UNDISCH_TAC `ring_pow b = ring_pow (l:B ring)` THEN
          DISCH_THEN(SUBST1_TAC o SYM) THEN
          ASM_SIMP_TAC[RING_POW_IN_PRIME_IDEAL];
          ALL_TAC] THEN
