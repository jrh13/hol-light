       [ASM_MESON_TAC[]; ALL_TAC] THEN
      REWRITE_TAC[maximal_ideal; NOT_EXISTS_THM] THEN
      DISCH_THEN(MP_TAC o SPEC `Q:B->bool` o CONJUNCT2) THEN
