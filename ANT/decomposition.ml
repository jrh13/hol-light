      DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[]]]);;

(* The residue field of f(Q) is the image of that of Q under X |-> f(X), so  *)
(* it is finite with the same q, I_f(Q) is trivial and f Frob_Q f^-1 has the *)
(* defining property at f(Q).                                                *)

let FROBENIUS_ELEMENT_CONJUGATE = prove
 (`!(h:A->B) k l b Q f.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q /\ FINITE(ring_carrier(quotient_ring b Q)) /\
        group_carrier(inertia_group(k,l) h b Q) = {I} /\
        f IN group_carrier(galois_group(k,l) h)
        ==> frobenius_element (k,l) h b (IMAGE f Q) =
            f o frobenius_element (k,l) h b Q o inverse f`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_RING_IDEAL) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_IDEAL_IMP_SUBSET) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                 `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES o check (fun th ->
    concl th = `f IN group_carrier(galois_group(k,l) (h:A->B))`)) THEN
  DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
  SUBGOAL_THEN
   `ring_homomorphism(l,l) (f:B->B) /\
    ring_carrier b SUBSET ring_carrier l /\
    (!x. x IN ring_carrier b ==> f x IN ring_carrier b) /\
    (!x. x IN ring_carrier b ==> inverse f x IN ring_carrier b)`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_RING_AUTOMORPHISM; ring_automorphism;
                    RING_ISOMORPHISM_IMP_HOMOMORPHISM];
      MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`]
        RING_CARRIER_SUBRING_GENERATED_SUBSET) THEN
      ASM_REWRITE_TAC[];
      ASM SET_TAC[];
      ASM_MESON_TAC[GALOIS_GROUP_INVERSE; SUBSET; IN_IMAGE]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x. x IN ring_carrier b
        ==> IMAGE f (ring_coset b Q x) =
            ring_coset b (IMAGE (f:B->B) Q) (f x)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC GALOIS_GROUP_IMAGE_RING_COSET THEN
    MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`; `l:B ring`] THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `FINITE(ring_carrier(quotient_ring b (IMAGE (f:B->B) Q)))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC `IMAGE (IMAGE (f:B->B)) (ring_carrier(quotient_ring b Q))` THEN
    ASM_SIMP_TAC[FINITE_IMAGE; QUOTIENT_RING_CARRIER] THEN
    REWRITE_TAC[SUBSET; FORALL_IN_GSPEC] THEN X_GEN_TAC `y:B` THEN
    DISCH_TAC THEN REWRITE_TAC[IN_IMAGE; IN_ELIM_THM] THEN
    EXISTS_TAC `ring_coset b Q (inverse (f:B->B) y)` THEN
    ASM_SIMP_TAC[] THEN EXISTS_TAC `inverse (f:B->B) y` THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `group_carrier(inertia_group(k,l) (h:A->B) b (IMAGE (f:B->B) Q)) = {I}`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                   `Q:B->bool`] INERTIA_GROUP_CONJUGATE) THEN
    ASM_REWRITE_TAC[IMAGE_CLAUSES] THEN DISCH_THEN SUBST1_TAC THEN
    AP_THM_TAC THEN AP_TERM_TAC THEN
    ASM_REWRITE_TAC[FUN_EQ_THM; o_THM; I_THM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `{ring_coset b (IMAGE (f:B->B) Q) ((h:A->B) a) | a |
     a IN ring_carrier k /\ h a IN ring_carrier b} =
    IMAGE (IMAGE (f:B->B)) {ring_coset b Q (h a) | a |
                            a IN ring_carrier k /\ h a IN ring_carrier b}`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `!a. a IN ring_carrier k /\ (h:A->B) a IN ring_carrier b
          ==> IMAGE (f:B->B) (ring_coset b Q (h a)) =
              ring_coset b (IMAGE f Q) (h a)`
    ASSUME_TAC THENL
     [REPEAT STRIP_TAC THEN ASM_SIMP_TAC[] THEN
      ASM_MESON_TAC[GALOIS_GROUP_FIXES];
      ALL_TAC] THEN
    GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_IMAGE; IN_ELIM_THM] THEN
    ASM_MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `CARD {ring_coset b (IMAGE (f:B->B) Q) ((h:A->B) a) | a |
          a IN ring_carrier k /\ h a IN ring_carrier b} =
    CARD {ring_coset b Q (h a) | a |
          a IN ring_carrier k /\ h a IN ring_carrier b}`
  ASSUME_TAC THENL
   [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC CARD_IMAGE_INJ THEN CONJ_TAC THENL
     [MAP_EVERY X_GEN_TAC [`X:B->bool`; `Y:B->bool`] THEN STRIP_TAC THEN
      FIRST_X_ASSUM(MP_TAC o AP_TERM `IMAGE (inverse(f:B->B))`) THEN
      ASM_REWRITE_TAC[GSYM IMAGE_o; o_DEF; IMAGE_ID];
      MATCH_MP_TAC FINITE_SUBSET THEN
      EXISTS_TAC `ring_carrier(quotient_ring b (Q:B->bool))` THEN
      ASM_SIMP_TAC[QUOTIENT_RING_CARRIER] THEN
      REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN MESON_TAC[]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`;
                 `IMAGE (f:B->B) Q`] FROBENIUS_ELEMENT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o SPEC
   `(f:B->B) o frobenius_element (k,l) (h:A->B) b Q o inverse f` o
   CONJUNCT2) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `Q:B->bool`]
    FROBENIUS_ELEMENT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o SPEC `frobenius_element (k,l) (h:A->B) b Q` o
    CONJUNCT2) THEN
  REWRITE_TAC[] THEN
  ABBREV_TAC
   `q = CARD {ring_coset b Q ((h:A->B) a) | a |
              a IN ring_carrier k /\ h a IN ring_carrier b}` THEN
  ABBREV_TAC `fr = frobenius_element (k,l) (h:A->B) b Q` THEN
  STRIP_TAC THEN
  CONV_TAC(RAND_CONV SYM_CONV) THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[GALOIS_GROUP_COMPOSE; GALOIS_GROUP_INVERSE] THEN
  X_GEN_TAC `x:B` THEN DISCH_TAC THEN REWRITE_TAC[o_THM] THEN
  SUBGOAL_THEN `?y. y IN ring_carrier b /\ x = (f:B->B) y`
   (X_CHOOSE_THEN `y:B` (CONJUNCTS_THEN2 ASSUME_TAC SUBST_ALL_TAC))
  THENL [EXISTS_TAC `inverse (f:B->B) x` THEN ASM_SIMP_TAC[]; ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `(y:B) IN ring_carrier l /\ (fr:B->B) y IN ring_carrier l`
  STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
     [UNDISCH_TAC `ring_carrier b SUBSET ring_carrier(l:B ring)` THEN
      REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
      ASM_REWRITE_TAC[];
      ASM_MESON_TAC[GALOIS_GROUP_PERMUTES; PERMUTES_IN_IMAGE]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sub l ((f:B->B) (fr y)) (ring_pow l (f y) q) =
    f (ring_sub l ((fr:B->B) y) (ring_pow l y q))`
  SUBST1_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `f:B->B`]
      RING_HOMOMORPHISM_POW) THEN
    MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `f:B->B`]
      RING_HOMOMORPHISM_SUB) THEN
    ASM_SIMP_TAC[RING_POW];
    MATCH_MP_TAC FUN_IN_IMAGE THEN ASM_SIMP_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* Decomposition and inertia groups over intermediate fields, uniqueness     *)
(* above the decomposition field; the Frobenius congruence of                *)
(* frobenius_element and of its powers; a counting lemma for homomorphic     *)
(* images of subgroups.                                                      *)
(* ------------------------------------------------------------------------- *)

(* For an intermediate field M = subfield_generated l s the groups of l over *)
(* M are the intersections with Gal(l/M); the inertia version holds for any  *)
(* ideal Q of b.                                                             *)
let DECOMPOSITION_GROUP_INTERMEDIATE = prove
 (`!(h:A->B) k l s Q.
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
        ==> group_carrier(decomposition_group(subfield_generated l s,l) I Q) =
            group_carrier(decomposition_group(k,l) h Q) INTER
            group_carrier(galois_group(subfield_generated l s,l) I)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[DECOMPOSITION_GROUP] THEN
  REWRITE_TAC[EXTENSION; IN_INTER; IN_ELIM_THM] THEN
  ASM_MESON_TAC[IN_GALOIS_GROUP_INTERMEDIATE]);;

let INERTIA_GROUP_INTERMEDIATE = prove
 (`!(h:A->B) k l b s Q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
        ==> group_carrier(inertia_group(subfield_generated l s,l) I b Q) =
            group_carrier(inertia_group(k,l) h b Q) INTER
            group_carrier(galois_group(subfield_generated l s,l) I)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `!f. f IN group_carrier(galois_group(subfield_generated l s,l) (I:B->B))
        ==> f IN group_carrier(galois_group(k,l) (h:A->B))`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_GALOIS_GROUP_INTERMEDIATE]; ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `Q:B->bool`]
    (CONJUNCT1 INERTIA_GROUP)) THEN
  MP_TAC(ISPECL [`I:B->B`; `subfield_generated l (s:B->bool)`; `l:B ring`;
                 `b:B ring`; `Q:B->bool`] (CONJUNCT1 INERTIA_GROUP)) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  ANTS_TAC THENL
   [REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[EXTENSION; IN_INTER; IN_ELIM_THM] THEN ASM_MESON_TAC[]);;

(* For k -> l -> m the inertia groups of m over l are those over k           *)
(* intersected with Gal(m/l).                                                *)
let INERTIA_GROUP_TOWER = prove
 (`!(h:A->B) (j:B->C) k l m b Q.
        ring_homomorphism(k,l) h /\
        subring_generated m (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,m) (j o h))
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q
        ==> group_carrier(inertia_group(l,m) j b Q) =
            group_carrier(inertia_group(k,m) (j o h) b Q) INTER
            group_carrier(galois_group(l,m) j)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `group_carrier(galois_group(l,m) (j:B->C)) SUBSET
    group_carrier(galois_group(k,m) (j o (h:A->B)))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC GALOIS_GROUP_ANTIMONO THEN REWRITE_TAC[IMAGE_o] THEN
    MATCH_MP_TAC IMAGE_SUBSET THEN
    FIRST_ASSUM(ACCEPT_TAC o CONJUNCT1 o
      GEN_REWRITE_RULE I [ring_homomorphism]);
    ALL_TAC] THEN
  MP_TAC(ISPECL [`(j:B->C) o (h:A->B)`; `k:A ring`; `m:C ring`; `b:C ring`;
                 `Q:C->bool`] (CONJUNCT1 INERTIA_GROUP)) THEN
  MP_TAC(ISPECL [`j:B->C`; `l:B ring`; `m:C ring`; `b:C ring`;
                 `Q:C->bool`] (CONJUNCT1 INERTIA_GROUP)) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN
    X_GEN_TAC `f:C->C` THEN STRIP_TAC THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM SET_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[EXTENSION; IN_INTER; IN_ELIM_THM] THEN ASM SET_TAC[]);;

(* Q is the only maximal ideal of b with trace Q INTER s on s iff Gal(l/M)   *)
(* fixes Q, by the transitivity of Gal(l/M) on the maximal ideals above Q    *)
(* INTER s; in particular for the decomposition field.                       *)
let DECOMPOSITION_GROUP_INTERMEDIATE_UNIQUE = prove
 (`!(h:A->B) k l b s Q.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
        ==> ({Q' | maximal_ideal b Q' /\ Q' INTER s = Q INTER s} = {Q} <=>
             group_carrier(galois_group(subfield_generated l s,l) I) SUBSET
             group_carrier(decomposition_group(k,l) h Q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `!f. f IN group_carrier(galois_group(subfield_generated l s,l) (I:B->B))
        ==> f IN group_carrier(galois_group(k,l) (h:A->B))`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_GALOIS_GROUP_INTERMEDIATE]; ALL_TAC] THEN
  MP_TAC(ISPECL [`I:B->B`; `subfield_generated l (s:B->bool)`; `l:B ring`;
                 `b:B ring`; `Q:B->bool`] GALOIS_GROUP_ORBIT_MAXIMAL_IDEAL) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
     [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`]
        FINITE_EXTENSION_SUBFIELD_GENERATED) THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC GALOIS_EXTENSION_SUBFIELD_GENERATED THEN
      MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`] THEN ASM_REWRITE_TAC[];
      ASM_MESON_TAC[]];
    ALL_TAC] THEN
  ASM_SIMP_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD; I_THM] THEN
  SUBGOAL_THEN
   `!Q'. {a | a IN s /\ a IN Q'} = Q' INTER (s:B->bool)`
  (fun th -> REWRITE_TAC[th]) THENL [SET_TAC[]; ALL_TAC] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`I:B->B`; `subfield_generated l (s:B->bool)`; `l:B ring`;
                 `b:B ring`] GALOIS_GROUP_ACTION_SUBRING) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[]; STRIP_TAC] THEN
  ASM_SIMP_TAC[GROUP_ORBIT; IN_ELIM_THM] THEN
  REWRITE_TAC[DECOMPOSITION_GROUP; SUBSET; IN_ELIM_THM] THEN
  EQ_TAC THENL
   [DISCH_TAC THEN X_GEN_TAC `f:B->B` THEN DISCH_TAC THEN
    ASM_SIMP_TAC[] THEN
    FIRST_X_ASSUM(MP_TAC o AP_TERM `(IN) (IMAGE (f:B->B) Q)`) THEN
    REWRITE_TAC[IN_ELIM_THM; IN_SING] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    EXISTS_TAC `f:B->B` THEN ASM_REWRITE_TAC[];
    DISCH_TAC THEN GEN_REWRITE_TAC I [EXTENSION] THEN
    X_GEN_TAC `P:B->bool` THEN REWRITE_TAC[IN_ELIM_THM; IN_SING] THEN
    EQ_TAC THENL
     [DISCH_THEN(X_CHOOSE_THEN `f:B->B` STRIP_ASSUME_TAC) THEN
      ASM_MESON_TAC[];
      DISCH_THEN SUBST1_TAC THEN EXISTS_TAC `I:B->B` THEN
      REWRITE_TAC[GALOIS_GROUP_I; IMAGE_I]]]);;

let DECOMPOSITION_FIELD_UNIQUE_PRIME = prove
 (`!(h:A->B) k l b Q.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q
        ==> {Q' | maximal_ideal b Q' /\
                  Q' INTER
                  fixed_field l (group_carrier(decomposition_group(k,l) h Q)) =
                  Q INTER
                  fixed_field l (group_carrier(decomposition_group(k,l) h Q))} =
            {Q}`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
                 `group_carrier(decomposition_group(k,l) (h:A->B) Q)`]
    GALOIS_GROUP_FIXED_FIELD) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[decomposition_group; SUBGROUP_SUBGROUP_GENERATED];
    STRIP_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`;
                 `fixed_field l (group_carrier(decomposition_group(k,l)
                                   (h:A->B) Q))`; `Q:B->bool`]
    DECOMPOSITION_GROUP_INTERMEDIATE_UNIQUE) THEN
  ASM_REWRITE_TAC[SUBSET_REFL]);;

let FINITE_DECOMPOSITION_INERTIA_GROUPS = prove
 (`!(h:A->B) k l b Q.
        finite_extension(k,l) h
        ==> FINITE(group_carrier(decomposition_group(k,l) h Q)) /\
            ~(group_carrier(decomposition_group(k,l) h Q) = {}) /\
            FINITE(group_carrier(inertia_group(k,l) h b Q)) /\
            ~(group_carrier(inertia_group(k,l) h b Q) = {})`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN REWRITE_TAC[GSYM MEMBER_NOT_EMPTY] THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC `group_carrier(galois_group(k,l) (h:A->B))` THEN
    ASM_SIMP_TAC[FINITE_GALOIS_GROUP] THEN
    REWRITE_TAC[decomposition_group; GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET];
    MESON_TAC[GROUP_ID];
    MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC `group_carrier(galois_group(k,l) (h:A->B))` THEN
    ASM_SIMP_TAC[FINITE_GALOIS_GROUP] THEN
    REWRITE_TAC[inertia_group; GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET];
    MESON_TAC[GROUP_ID]]);;

(* The Frobenius element satisfies its defining congruence without assuming  *)
(* the inertia group trivial, by DECOMPOSITION_GROUP_FROBENIUS_EXISTS and    *)
(* the choice in its definition.                                             *)
let FROBENIUS_ELEMENT_IN_DECOMPOSITION_GROUP = prove
 (`!(h:A->B) k l b Q.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q /\ FINITE(ring_carrier(quotient_ring b Q))
        ==> frobenius_element (k,l) h b Q
            IN group_carrier(decomposition_group(k,l) h Q) /\
            !x. x IN ring_carrier b
                ==> ring_sub l (frobenius_element (k,l) h b Q x)
                     (ring_pow l x
                       (CARD {ring_coset b Q (h a) | a |
                              a IN ring_carrier k /\ h a IN ring_carrier b}))
                    IN Q`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP DECOMPOSITION_GROUP_FROBENIUS_EXISTS) THEN
  REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM; GSYM CONJ_ASSOC] THEN
  DISCH_THEN(MP_TAC o SELECT_RULE) THEN
  REWRITE_TAC[GSYM frobenius_element] THEN SIMP_TAC[]);;

(* Powers of an element of D_Q with a Frobenius congruence x -> x^q modulo Q *)
(* satisfy x -> x^(q^n); two elements of D_Q that agree modulo Q on b        *)
(* coincide when I_Q is trivial (the quotient lies in I_Q).                  *)
let DECOMPOSITION_GROUP_POW_CONGRUENCE = prove
 (`!(h:A->B) k l b Q f q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\
        f IN group_carrier(decomposition_group(k,l) h Q) /\
        (!x. x IN ring_carrier b ==> ring_sub l (f x) (ring_pow l x q) IN Q)
        ==> !n x. x IN ring_carrier b
                  ==> ring_sub l (group_pow (galois_group(k,l) h) f n x)
                                 (ring_pow l x (q EXP n)) IN Q`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o REWRITE_RULE[DECOMPOSITION_GROUP;
    IN_ELIM_THM] o check (fun th -> concl th =
      `f IN group_carrier(decomposition_group(k,l) (h:A->B) Q)`)) THEN
  SUBGOAL_THEN
   `ring_carrier b SUBSET ring_carrier l /\ ring_0 b = ring_0 l /\
    ring_add b = ring_add l /\
    ring_sub b = ring_sub l /\ ring_pow b = ring_pow (l:B ring)`
  STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `subring_generated l (ring_carrier b) = (b:B ring)` THEN
    DISCH_THEN(fun th -> ONCE_REWRITE_TAC[SYM th]) THEN
    REWRITE_TAC[RING_CARRIER_SUBRING_GENERATED_SUBSET; SUBRING_GENERATED;
                RING_SUB_SUBRING_GENERATED; RING_POW_SUBRING_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x y m. x IN ring_carrier b /\ y IN ring_carrier b /\
            ring_sub l x y IN Q
            ==> ring_sub l (ring_pow l x m) (ring_pow l y m) IN (Q:B->bool)`
  (LABEL_TAC "pow") THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`b:B ring`; `Q:B->bool`; `ring_pow b x m:B`;
                   `ring_pow b y m:B`] RING_COSET_EQ) THEN
    MP_TAC(ISPECL [`b:B ring`; `Q:B->bool`; `x:B`; `y:B`] RING_COSET_EQ) THEN
    ASM_SIMP_TAC[RING_POW] THEN
    MP_TAC(ISPECL [`b:B ring`; `quotient_ring b (Q:B->bool)`;
                   `ring_coset b (Q:B->bool)`] RING_HOMOMORPHISM_POW) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET] THEN
    REPEAT DISCH_TAC THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!g x. g IN group_carrier(galois_group(k,l) (h:A->B)) /\
          x IN ring_carrier b ==> g x IN ring_carrier b`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `g:B->B` o check (fun th ->
      is_forall(concl th) && can (find_term (fun t -> is_const t &&
        fst(dest_const t) = "IMAGE")) (concl th))) THEN
    ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN
    DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `!x:B. x IN ring_carrier b ==> x IN ring_carrier l`
  ASSUME_TAC THENL
   [MP_TAC(ASSUME `ring_carrier b SUBSET ring_carrier(l:B ring)`) THEN
    REWRITE_TAC[SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x. x IN ring_carrier b
        ==> ring_sub l ((f:B->B) x) (ring_pow l x q) IN (Q:B->bool)`
  (LABEL_TAC "frob") THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  INDUCT_TAC THENL
   [REWRITE_TAC[group_pow; GALOIS_GROUP; I_THM; EXP] THEN
    REPEAT STRIP_TAC THEN ASM_SIMP_TAC[RING_POW_1; RING_SUB_REFL] THEN
    UNDISCH_TAC `ring_0 b = ring_0(l:B ring)` THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    MATCH_MP_TAC IN_RING_IDEAL_0 THEN FIRST_ASSUM ACCEPT_TAC;
    ALL_TAC] THEN
  X_GEN_TAC `x:B` THEN DISCH_TAC THEN
  REWRITE_TAC[group_pow; GALOIS_GROUP; o_THM] THEN
  ABBREV_TAC `g = group_pow (galois_group(k,l) (h:A->B)) f n` THEN
  SUBGOAL_THEN `g IN group_carrier(galois_group(k,l) (h:A->B))` ASSUME_TAC
  THENL [EXPAND_TAC "g" THEN ASM_SIMP_TAC[GROUP_POW]; ALL_TAC] THEN
  SUBGOAL_THEN `(g:B->B) x IN ring_carrier b` ASSUME_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_pow l (ring_pow l x (q EXP n)) q = ring_pow l (x:B) (q EXP SUC n)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_POW_POW; EXP] THEN REWRITE_TAC[MULT_SYM]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sub l ((f:B->B) (g x)) (ring_pow l x (q EXP SUC n)) =
    ring_add l (ring_sub l (f (g x)) (ring_pow l (g x) q))
               (ring_sub l (ring_pow l (g x) q)
                           (ring_pow l (ring_pow l x (q EXP n)) q))`
  SUBST1_TAC THENL
   [FIRST_ASSUM(fun th -> REWRITE_TAC[th]) THEN
    CONV_TAC SYM_CONV THEN
    MATCH_MP_TAC(RING_RULE
     `ring_add r (ring_sub r a c) (ring_sub r c d) = ring_sub r a (d:B)`) THEN
    ASM_SIMP_TAC[RING_POW] THEN
    MP_TAC(ISPECL [`h:A->B`; `f:B->B`; `k:A ring`; `l:B ring`]
      GALOIS_GROUP_IN_CARRIER) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  UNDISCH_TAC `ring_add b = ring_add (l:B ring)` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC IN_RING_IDEAL_ADD THEN REPEAT CONJ_TAC THENL
   [FIRST_ASSUM ACCEPT_TAC;
    USE_THEN "frob" MATCH_MP_TAC THEN FIRST_ASSUM ACCEPT_TAC;
    USE_THEN "pow" MATCH_MP_TAC THEN
    CONJ_TAC THENL [FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
    CONJ_TAC THENL
     [UNDISCH_TAC `ring_pow b = ring_pow (l:B ring)` THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN ASM_SIMP_TAC[RING_POW];
      FIRST_X_ASSUM MATCH_MP_TAC THEN FIRST_ASSUM ACCEPT_TAC]]);;

let DECOMPOSITION_GROUP_CONGRUENT_EQ = prove
 (`!(h:A->B) k l b Q f g.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q /\
        group_carrier(inertia_group(k,l) h b Q) = {I} /\
        f IN group_carrier(decomposition_group(k,l) h Q) /\
        g IN group_carrier(decomposition_group(k,l) h Q) /\
        (!x. x IN ring_carrier b ==> ring_sub l (f x) (g x) IN Q)
        ==> f = g`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  RULE_ASSUM_TAC(REWRITE_RULE[DECOMPOSITION_GROUP; IN_ELIM_THM]) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES o CONJUNCT1 o
    check (fun th -> is_conj(concl th) &&
      lhand(concl th) = `g IN group_carrier(galois_group(k,l) (h:A->B))`)) THEN
  DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
  SUBGOAL_THEN `inverse(g:B->B) o f = I` MP_TAC THENL
   [SUBGOAL_THEN
     `inverse(g:B->B) o f IN group_carrier(inertia_group(k,l) (h:A->B) b Q)`
    MP_TAC THENL [ALL_TAC; ASM_REWRITE_TAC[IN_SING]] THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `Q:B->bool`]
      (CONJUNCT1 INERTIA_GROUP)) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN ASM_MESON_TAC[];
      DISCH_THEN SUBST1_TAC] THEN
    REWRITE_TAC[IN_ELIM_THM] THEN
    SUBGOAL_THEN
     `inverse(g:B->B) IN group_carrier(galois_group(k,l) (h:A->B)) /\
      IMAGE (inverse g) Q = Q`
    STRIP_ASSUME_TAC THENL
     [ASM_SIMP_TAC[GALOIS_GROUP_INVERSE] THEN
      MP_TAC(ISPECL [`h:A->B`; `g:B->B`; `k:A ring`; `l:B ring`;
                     `Q:B->bool`] GALOIS_GROUP_IMAGE_INVERSE) THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    ASM_SIMP_TAC[GALOIS_GROUP_COMPOSE; IMAGE_o] THEN
    X_GEN_TAC `x:B` THEN DISCH_TAC THEN REWRITE_TAC[o_THM] THEN
    SUBGOAL_THEN
     `ring_carrier b SUBSET ring_carrier(l:B ring)`
    ASSUME_TAC THENL
     [UNDISCH_TAC `subring_generated l (ring_carrier b) = (b:B ring)` THEN
      DISCH_THEN(fun th -> ONCE_REWRITE_TAC[SYM th]) THEN
      REWRITE_TAC[RING_CARRIER_SUBRING_GENERATED_SUBSET];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sub l (inverse g ((f:B->B) x)) x =
      inverse g (ring_sub l (f x) ((g:B->B) x))`
    SUBST1_TAC THENL
     [MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `inverse(g:B->B)`]
        RING_HOMOMORPHISM_SUB) THEN
      ANTS_TAC THENL
       [ASM_MESON_TAC[GALOIS_GROUP_RING_HOMOMORPHISM]; ALL_TAC] THEN
      DISCH_THEN(MP_TAC o SPECL [`(f:B->B) x`; `(g:B->B) x`]) THEN
      ANTS_TAC THENL
       [CONJ_TAC THEN MATCH_MP_TAC GALOIS_GROUP_IN_CARRIER THEN
        MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`] THEN
        ASM SET_TAC[];
        DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    UNDISCH_TAC `IMAGE (inverse g) Q = (Q:B->bool)` THEN
    DISCH_THEN(fun th -> GEN_REWRITE_TAC RAND_CONV [SYM th]) THEN
    MATCH_MP_TAC FUN_IN_IMAGE THEN ASM_SIMP_TAC[];
    REWRITE_TAC[FUN_EQ_THM; o_THM; I_THM] THEN DISCH_TAC THEN
    REWRITE_TAC[FUN_EQ_THM] THEN ASM_MESON_TAC[]]);;
