(* ------------------------------------------------------------------------- *)
(* The action of the Galois group on b and on its ideals.                    *)
(* ------------------------------------------------------------------------- *)

(* An f in G maps b onto b, as a ring automorphism, so it maps ideals, prime *)
(* ideals and maximal ideals of b to ideals of the same kind, with the same  *)
(* contraction since f fixes h(k), and cosets to cosets.                     *)

let GALOIS_GROUP_SUBRING_IMAGE = prove
 (`!(h:A->B) k l b f.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        f IN group_carrier(galois_group(k,l) h)
        ==> IMAGE f (ring_carrier b) = ring_carrier b /\
            ring_isomorphism(b,b) f`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ABBREV_TAC `B = ring_carrier(b:B ring)` THEN
  UNDISCH_TAC `subring_generated l B = (b:B ring)` THEN
  DISCH_THEN(SUBST_ALL_TAC o SYM) THEN
  SUBGOAL_THEN `(B:B->bool) subring_of l` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`; `B:B->bool`] SUBRING_SUBRING_GENERATED) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC SUBSET_ANTISYM THEN ASM_SIMP_TAC[] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
    DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `inverse(f:B->B)`) THEN
    ASM_SIMP_TAC[GALOIS_GROUP_INVERSE] THEN
    REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_IMAGE] THEN ASM_MESON_TAC[];
    DISCH_TAC THEN MATCH_MP_TAC RING_ISOMORPHISM_BETWEEN_SUBRINGS THEN
    ASM_REWRITE_TAC[] THEN
    CONJ_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_RING_AUTOMORPHISM; ring_automorphism];
      ASM_MESON_TAC[subring_of]]]);;

let GALOIS_GROUP_PRIME_IDEAL_IMAGE = prove
 (`!(h:A->B) k l b f Q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        f IN group_carrier(galois_group(k,l) h) /\ Q SUBSET ring_carrier b
        ==> (ring_ideal b (IMAGE f Q) <=> ring_ideal b Q) /\
            (prime_ideal b (IMAGE f Q) <=> prime_ideal b Q) /\
            (maximal_ideal b (IMAGE f Q) <=> maximal_ideal b Q) /\
            IMAGE f Q SUBSET ring_carrier b /\
            {a | a IN ring_carrier k /\ h a IN IMAGE f Q} =
            {a | a IN ring_carrier k /\ h a IN Q}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`]
    GALOIS_GROUP_SUBRING_IMAGE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[ISPECL [`b:B ring`; `b:B ring`] RING_IDEAL_ISOMORPHIC_IMAGE_EQ;
               ISPECL [`b:B ring`; `b:B ring`] PRIME_IDEAL_ISOMORPHIC_IMAGE_EQ;
               ISPECL [`b:B ring`; `b:B ring`]
                 MAXIMAL_IDEAL_ISOMORPHIC_IMAGE_EQ] THEN
  CONJ_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `a:A` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_CASES_TAC `(a:A) IN ring_carrier k` THEN ASM_REWRITE_TAC[] THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
  DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
  MP_TAC(ISPECL [`h:A->B`; `f:B->B`; `k:A ring`; `l:B ring`; `a:A`]
    GALOIS_GROUP_FIXES) THEN
  ASM_REWRITE_TAC[IN_IMAGE] THEN ASM_MESON_TAC[]);;

let GALOIS_GROUP_IMAGE_RING_COSET = prove
 (`!(h:A->B) k l b Q f x.
        subring_generated l (ring_carrier b) = b /\ Q SUBSET ring_carrier b /\
        f IN group_carrier(galois_group(k,l) h) /\ x IN ring_carrier b
        ==> IMAGE f (ring_coset b Q x) = ring_coset b (IMAGE f Q) (f x)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `ring_carrier b SUBSET ring_carrier l /\ ring_add b = ring_add (l:B ring)`
  STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `subring_generated l (ring_carrier b) = (b:B ring)` THEN
    DISCH_THEN(fun th -> ONCE_REWRITE_TAC[SYM th]) THEN
    REWRITE_TAC[RING_CARRIER_SUBRING_GENERATED_SUBSET;
                CONJUNCT2 SUBRING_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!y. y IN Q ==> (f:B->B) (ring_add l x y) = ring_add l (f x) (f y)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `f:B->B`]
      RING_HOMOMORPHISM_ADD) THEN
    ANTS_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_RING_AUTOMORPHISM; ring_automorphism;
                    RING_ISOMORPHISM_IMP_HOMOMORPHISM];
      DISCH_THEN MATCH_MP_TAC THEN ASM SET_TAC[]];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[ring_coset] THEN ASM SET_TAC[]);;

let GALOIS_GROUP_ACTION_SUBRING = prove
 (`!(h:A->B) k l b.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b)
        ==> group_action (galois_group(k,l) h) (ring_carrier b) (\f x. f x) /\
            group_action (galois_group(k,l) h) {Q | prime_ideal b Q} IMAGE /\
            group_action (galois_group(k,l) h) {Q | maximal_ideal b Q} IMAGE`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN REPEAT CONJ_TAC THEN
  MATCH_MP_TAC GROUP_ACTION_ON_SUBSET THENL
   [EXISTS_TAC `ring_carrier l:B->bool` THEN
    REWRITE_TAC[GALOIS_GROUP_ACTION] THEN CONJ_TAC THENL
     [MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`]
        RING_CARRIER_SUBRING_GENERATED_SUBSET) THEN
      ASM_REWRITE_TAC[];
      ASM SET_TAC[]];
    EXISTS_TAC `(:B->bool)`;
    EXISTS_TAC `(:B->bool)`] THEN
  REWRITE_TAC[GALOIS_GROUP_ACTION; SUBSET_UNIV; IN_ELIM_THM] THEN
  MAP_EVERY X_GEN_TAC [`f:B->B`; `Q:B->bool`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                 `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
  ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET; MAXIMAL_IMP_PRIME_IDEAL]);;

(* ------------------------------------------------------------------------- *)
(* Transitivity on the maximal ideals above a prime.                         *)
(* ------------------------------------------------------------------------- *)

(* Neukirch I.9.1. For the second maximal ideal: the product of the f(x)     *)
(* over G of an x in it is in b and in h(k), so in the common contraction    *)
(* and in Q; then that ideal is in the union of the f^-1(Q), so in one of    *)
(* them by prime avoidance, and equal to it by maximality.                   *)

let GALOIS_GROUP_TRANSITIVE_PRIME_IDEALS = prove
 (`!(h:A->B) k l b Q Q'.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        prime_ideal b Q /\ maximal_ideal b Q' /\
        {a | a IN ring_carrier k /\ h a IN Q'} =
        {a | a IN ring_carrier k /\ h a IN Q}
        ==> ?f. f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q'`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `FINITE(group_carrier(galois_group(k,l) (h:A->B)))`
  ASSUME_TAC THENL [ASM_SIMP_TAC[FINITE_GALOIS_GROUP]; ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_PRIME_IDEAL) THEN
  SUBGOAL_THEN
   `Q SUBSET ring_carrier b /\ Q' SUBSET ring_carrier b /\
    ring_carrier b SUBSET ring_carrier(l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET] THEN
    MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`]
      RING_CARRIER_SUBRING_GENERATED_SUBSET) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!f. f IN group_carrier(galois_group(k,l) (h:A->B))
        ==> prime_ideal b (IMAGE f Q)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                   `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `Q' SUBSET
    UNIONS {IMAGE f Q | f IN group_carrier(galois_group(k,l) (h:A->B))}`
  ASSUME_TAC THENL
   [REWRITE_TAC[SUBSET; IN_UNIONS; EXISTS_IN_GSPEC] THEN
    X_GEN_TAC `x:B` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(x:B) IN ring_carrier b /\ x IN ring_carrier l`
    STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!f. f IN group_carrier(galois_group(k,l) (h:A->B))
          ==> f x IN ring_carrier b`
    ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_product b (group_carrier(galois_group(k,l) (h:A->B))) (\f. f x) =
      ring_product l (group_carrier(galois_group(k,l) h)) (\f. f x)`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`l:B ring`; `ring_carrier(b:B ring)`;
                     `group_carrier(galois_group(k,l) (h:A->B))`;
                     `\f:B->B. f x`] RING_PRODUCT_SUBRING_GENERATED_GEN) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
      AP_THM_TAC THEN AP_TERM_TAC THEN
      REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN ASM_MESON_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_product b (group_carrier(galois_group(k,l) (h:A->B))) (\f. f x)
      IN Q'`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`b:B ring`; `Q':B->bool`;
                     `group_carrier(galois_group(k,l) (h:A->B))`;
                     `\f:B->B. f x`] RING_PRODUCT_IN_PRIME_IDEAL) THEN
      ANTS_TAC THENL [ASM_SIMP_TAC[]; DISCH_THEN SUBST1_TAC] THEN
      EXISTS_TAC `I:B->B` THEN ASM_REWRITE_TAC[GALOIS_GROUP_I; I_THM];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_product b (group_carrier(galois_group(k,l) (h:A->B))) (\f. f x)
      IN Q`
    MP_TAC THENL
     [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `x:B`]
        GALOIS_PRODUCT_IN_BASE) THEN
      ASM_REWRITE_TAC[IN_IMAGE] THEN
      DISCH_THEN(X_CHOOSE_THEN `a:A` STRIP_ASSUME_TAC o CONJUNCT1) THEN
      ASM_REWRITE_TAC[] THEN
      SUBGOAL_THEN `(h:A->B) a IN Q'` MP_TAC THENL
       [ASM_MESON_TAC[]; ALL_TAC] THEN
      UNDISCH_TAC
       `{a | a IN ring_carrier k /\ (h:A->B) a IN Q'} =
        {a | a IN ring_carrier k /\ h a IN Q}` THEN
      REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN ASM_MESON_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`b:B ring`; `Q:B->bool`;
                   `group_carrier(galois_group(k,l) (h:A->B))`;
                   `\f:B->B. f x`] RING_PRODUCT_IN_PRIME_IDEAL) THEN
    ANTS_TAC THENL [ASM_SIMP_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `f:B->B` STRIP_ASSUME_TAC) THEN
    EXISTS_TAC `inverse(f:B->B)` THEN ASM_SIMP_TAC[GALOIS_GROUP_INVERSE] THEN
    REWRITE_TAC[IN_IMAGE] THEN EXISTS_TAC `(f:B->B) x` THEN
    ASM_REWRITE_TAC[] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
    DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL
   [`b:B ring`; `Q':B->bool`;
    `{IMAGE f Q | f IN group_carrier(galois_group(k,l) (h:A->B))}`]
   PRIME_AVOIDANCE) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN
    ASM_SIMP_TAC[MAXIMAL_IMP_RING_IDEAL; SIMPLE_IMAGE; FINITE_IMAGE;
                 FORALL_IN_IMAGE];
    REWRITE_TAC[EXISTS_IN_GSPEC]] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `f:B->B` THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[] THEN
  UNDISCH_TAC `maximal_ideal b (Q':B->bool)` THEN
  REWRITE_TAC[maximal_ideal; NOT_EXISTS_THM] THEN
  DISCH_THEN(MP_TAC o SPEC `IMAGE (f:B->B) Q` o CONJUNCT2) THEN
  ASM_SIMP_TAC[PRIME_IMP_PROPER_IDEAL; PSUBSET] THEN ASM SET_TAC[]);;

let GALOIS_GROUP_ORBIT_MAXIMAL_IDEAL = prove
 (`!(h:A->B) k l b Q.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        maximal_ideal b Q
        ==> group_orbit (galois_group(k,l) h) {Q | maximal_ideal b Q} IMAGE Q =
            {Q' | maximal_ideal b Q' /\
                  {a | a IN ring_carrier k /\ h a IN Q'} =
                  {a | a IN ring_carrier k /\ h a IN Q}}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`]
    GALOIS_GROUP_ACTION_SUBRING) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[GROUP_ORBIT; IN_ELIM_THM] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `Q':B->bool` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN EQ_TAC THENL
   [DISCH_THEN(X_CHOOSE_THEN `f:B->B`
     (CONJUNCTS_THEN2 ASSUME_TAC SUBST1_TAC)) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`; `f:B->B`;
                   `Q:B->bool`] GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
    ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL; PRIME_IDEAL_IMP_SUBSET];
    STRIP_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `b:B ring`;
                   `Q:B->bool`; `Q':B->bool`]
      GALOIS_GROUP_TRANSITIVE_PRIME_IDEALS) THEN
    ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN MESON_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* Decomposition and inertia groups.                                         *)
(* ------------------------------------------------------------------------- *)

let decomposition_group = new_definition
 `decomposition_group (k:A ring,l:B ring) (h:A->B) (Q:B->bool) =
    subgroup_generated (galois_group(k,l) h)
      {f | f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q}`;;

let inertia_group = new_definition
 `inertia_group (k:A ring,l:B ring) (h:A->B) (b:B ring) (Q:B->bool) =
    subgroup_generated (galois_group(k,l) h)
      {f | f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q /\
           !x. x IN ring_carrier b ==> ring_sub l (f x) x IN Q}`;;

let DECOMPOSITION_GROUP = prove
 (`(!(h:A->B) k l Q.
        group_carrier(decomposition_group(k,l) h Q) =
        {f | f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q}) /\
   (!(h:A->B) k l Q. group_id(decomposition_group(k,l) h Q) = I) /\
   (!(h:A->B) k l Q. group_inv(decomposition_group(k,l) h Q) = inverse) /\
   (!(h:A->B) k l Q. group_mul(decomposition_group(k,l) h Q) = (o))`,
  REWRITE_TAC[decomposition_group; CONJUNCT2 SUBGROUP_GENERATED;
              CONJUNCT2 GALOIS_GROUP] THEN
  REPEAT GEN_TAC THEN MATCH_MP_TAC CARRIER_SUBGROUP_GENERATED_SUBGROUP THEN
  REWRITE_TAC[subgroup_of; SUBSET; IN_ELIM_THM] THEN
  REWRITE_TAC[CONJUNCT2 GALOIS_GROUP; GALOIS_GROUP_I; IMAGE_I] THEN
  SIMP_TAC[GALOIS_GROUP_INVERSE; GALOIS_GROUP_COMPOSE; IMAGE_o] THEN
  MESON_TAC[GALOIS_GROUP_IMAGE_INVERSE]);;

(* A version of GALOIS_GROUP_SUBRING_IMAGE asking only the elements of D_Q   *)
(* to preserve b, as for the valuation subrings of ANT/valuation_residue.ml; *)
(* the description of I_Q (INERTIA_GROUP) and the residue maps below need    *)
(* only this as well.                                                        *)

let DECOMPOSITION_GROUP_SUBRING_IMAGE = prove
 (`!(h:A->B) k l b Q f.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(decomposition_group(k,l) h Q)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        f IN group_carrier(decomposition_group(k,l) h Q)
        ==> IMAGE f (ring_carrier b) = ring_carrier b /\
            ring_isomorphism(b,b) f`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `f IN group_carrier(galois_group(k,l) (h:A->B)) /\
    inverse f IN group_carrier(decomposition_group(k,l) h Q)`
  STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `f IN group_carrier(decomposition_group(k,l) (h:A->B) Q)` THEN
    REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN
    MESON_TAC[GALOIS_GROUP_INVERSE; GALOIS_GROUP_IMAGE_INVERSE];
    ALL_TAC] THEN
  ABBREV_TAC `B = ring_carrier(b:B ring)` THEN
  UNDISCH_TAC `subring_generated l B = (b:B ring)` THEN
  DISCH_THEN(SUBST_ALL_TAC o SYM) THEN
  SUBGOAL_THEN `(B:B->bool) subring_of l` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`; `B:B->bool`] SUBRING_SUBRING_GENERATED) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC SUBSET_ANTISYM THEN ASM_SIMP_TAC[] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
    DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `inverse(f:B->B)`) THEN
    ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_IMAGE] THEN ASM_MESON_TAC[];
    DISCH_TAC THEN MATCH_MP_TAC RING_ISOMORPHISM_BETWEEN_SUBRINGS THEN
    ASM_REWRITE_TAC[] THEN
    CONJ_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_RING_AUTOMORPHISM; ring_automorphism];
      ASM_MESON_TAC[subring_of]]]);;

let INERTIA_GROUP = prove
 (`(!(h:A->B) k l b Q.
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(decomposition_group(k,l) h Q)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        ring_ideal b Q
        ==> group_carrier(inertia_group(k,l) h b Q) =
            {f | f IN group_carrier(galois_group(k,l) h) /\ IMAGE f Q = Q /\
                 !x. x IN ring_carrier b ==> ring_sub l (f x) x IN Q}) /\
   (!(h:A->B) k l b Q. group_id(inertia_group(k,l) h b Q) = I) /\
   (!(h:A->B) k l b Q. group_inv(inertia_group(k,l) h b Q) = inverse) /\
   (!(h:A->B) k l b Q. group_mul(inertia_group(k,l) h b Q) = (o))`,
  CONJ_TAC THENL
   [REWRITE_TAC[inertia_group] THEN
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    RULE_ASSUM_TAC(REWRITE_RULE[DECOMPOSITION_GROUP; IN_ELIM_THM]) THEN
    SUBGOAL_THEN
     `ring_carrier b SUBSET ring_carrier l /\ ring_0 (l:B ring) IN Q /\
      (!x. x IN Q ==> ring_neg l x IN Q) /\
      (!x y. x IN Q /\ y IN Q ==> ring_add l x y IN Q)`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `ring_ideal b (Q:B->bool)` THEN
      UNDISCH_TAC `subring_generated l (ring_carrier b) = (b:B ring)` THEN
      DISCH_THEN(fun th -> ONCE_REWRITE_TAC[SYM th]) THEN
      SIMP_TAC[ring_ideal; CONJUNCT2 SUBRING_GENERATED;
               RING_CARRIER_SUBRING_GENERATED_SUBSET];
      ALL_TAC] THEN
    MATCH_MP_TAC CARRIER_SUBGROUP_GENERATED_SUBGROUP THEN
    REWRITE_TAC[subgroup_of; SUBSET; IN_ELIM_THM] THEN
    REWRITE_TAC[CONJUNCT2 GALOIS_GROUP; GALOIS_GROUP_I; IMAGE_I; I_THM] THEN
    SIMP_TAC[GALOIS_GROUP_INVERSE; GALOIS_GROUP_COMPOSE; IMAGE_o; o_THM] THEN
    CONJ_TAC THENL [ASM_MESON_TAC[RING_SUB_REFL; SUBSET]; ALL_TAC] THEN
    CONJ_TAC THENL
     [X_GEN_TAC `f:B->B` THEN STRIP_TAC THEN
      FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_GROUP_PERMUTES) THEN
      DISCH_THEN(STRIP_ASSUME_TAC o MATCH_MP PERMUTES_INVERSES) THEN
      CONJ_TAC THENL [ASM_MESON_TAC[GALOIS_GROUP_IMAGE_INVERSE]; ALL_TAC] THEN
      X_GEN_TAC `x:B` THEN DISCH_TAC THEN
      SUBGOAL_THEN `inverse (f:B->B) x IN ring_carrier b` ASSUME_TAC THENL
       [ASM_MESON_TAC[GALOIS_GROUP_INVERSE; GALOIS_GROUP_IMAGE_INVERSE; SUBSET;
                      IN_IMAGE];
        ALL_TAC] THEN
      UNDISCH_TAC
       `!x. x IN ring_carrier b ==> ring_sub l ((f:B->B) x) x IN Q` THEN
      DISCH_THEN(MP_TAC o SPEC `inverse (f:B->B) x`) THEN
      ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
      MP_TAC(ISPECL [`l:B ring`; `x:B`; `inverse (f:B->B) x`] RING_NEG_SUB) THEN
      ANTS_TAC THENL [ASM SET_TAC[]; DISCH_THEN(SUBST1_TAC o SYM)] THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    MAP_EVERY X_GEN_TAC [`f:B->B`; `g:B->B`] THEN STRIP_TAC THEN
    X_GEN_TAC `x:B` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `IMAGE (f:B->B) (ring_carrier b) SUBSET ring_carrier b /\
      IMAGE (g:B->B) (ring_carrier b) SUBSET ring_carrier b`
    MP_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
    REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN STRIP_TAC THEN
    SUBGOAL_THEN `(g:B->B) x IN ring_carrier b /\ f(g x) IN ring_carrier b`
    STRIP_ASSUME_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sub l ((f:B->B) (g x)) x =
      ring_add l (ring_sub l (f (g x)) (g x)) (ring_sub l (g x) x)`
    SUBST1_TAC THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC(RING_RULE
       `ring_add r (ring_sub r a c) (ring_sub r c d) = ring_sub r a (d:A)`) THEN
      ASM SET_TAC[];
      ASM_SIMP_TAC[]];
    REWRITE_TAC[inertia_group; CONJUNCT2 SUBGROUP_GENERATED;
                CONJUNCT2 GALOIS_GROUP]]);;

let INERTIA_GROUP_SUBGROUP_OF_DECOMPOSITION_GROUP = prove
 (`!(h:A->B) k l b Q.
        subring_generated l (ring_carrier b) = b /\
