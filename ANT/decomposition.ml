        maximal_ideal b Q /\ FINITE(ring_carrier(quotient_ring b Q))
        ==> CARD(group_carrier(decomposition_group(k,l) h Q)) =
            CARD(group_carrier(inertia_group(k,l) h b Q)) *
            extension_degree
