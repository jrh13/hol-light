(* An automorphism s of k(Q) over k(P) maps x + Q to some g(x) + Q, g in G:  *)
(* x + Q is a root of the reduction of the product of the X - g(x) over the  *)
(* orbit of x, whose coefficients are in b and fixed by G, hence in h(k); so *)
(* s(x + Q) is a root too.                                                   *)

let GALOIS_GROUP_RESIDUE_CONJUGATE = prove
 (`!(h:A->B) k l b Q s x.
        finite_extension(k,l) h /\ galois_extension(k,l) h /\
        subring_generated l (ring_carrier b) = b /\
        (!f. f IN group_carrier(galois_group(k,l) h)
             ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b) /\
        prime_ideal b Q /\ x IN ring_carrier b /\
        s IN group_carrier
              (galois_group
