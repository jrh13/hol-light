(* ========================================================================= *)
(* Decomposition and inertia groups and Frobenius elements of a prime Q of a *)
(* ring b in a finite Galois extension (k,l) h, G = galois_group(k,l) h,     *)
(* where b is a subring of l stable under G:                                 *)
(*                                                                           *)
(*   subring_generated l (ring_carrier b) = b                                *)
(*   !f. f IN group_carrier(galois_group(k,l) h)                             *)
(*       ==> IMAGE f (ring_carrier b) SUBSET ring_carrier b                  *)
(*                                                                           *)
(* The base ring is A = {a | a IN ring_carrier k /\ h a IN ring_carrier b}   *)
(* and the prime below Q is its contraction P = {a | a IN ring_carrier k /\  *)
(* h a IN Q}. The main instances are the integral closure of a Dedekind      *)
(* domain in l and b = ring_of_integers l for number fields                  *)
(* (ANT/nf_decomposition.ml).                                                *)
(*                                                                           *)
(*   decomposition_group (k,l) h Q = D_Q, the f in G with f(Q) = Q           *)
(*   inertia_group (k,l) h b Q     = I_Q, the f in D_Q with f(x) == x        *)
(*                                   (mod Q) for all x in b                  *)
(*   frobenius_element (k,l) h b Q = Frob_Q, an f in D_Q with f(x) == x^q    *)
(*                                   (mod Q) for all x in b, q = |A / P|     *)
(*                                                                           *)
(* No constants for residue fields: k(Q) is quotient_ring b Q, k(P) its      *)
(* subring generated by the image of A, IMAGE (ring_coset b Q o h) {a | a IN *)
(* ring_carrier k /\ h a IN ring_carrier b}, as in residue_degree of         *)
(* ANT/prime_split.ml, and f in D_Q acts on k(Q) by \X. if X IN              *)
(* ring_carrier(quotient_ring b Q) then IMAGE f X else X.                    *)
(*                                                                           *)
(* G acts on b and on its prime and maximal ideals                           *)
(* (GALOIS_GROUP_ACTION_SUBRING), transitively on the maximal ideals above P *)
(* (GALOIS_GROUP_TRANSITIVE_PRIME_IDEALS, GALOIS_GROUP_ORBIT_MAXIMAL_IDEAL); *)
(* their number times |D_Q| is [l:k] (DECOMPOSITION_GROUP_INDEX).            *)
(* Conjugation: D_f(Q) = f D_Q f^-1 and I_f(Q) = f I_Q f^-1                  *)
(* (DECOMPOSITION_GROUP_CONJUGATE, INERTIA_GROUP_CONJUGATE,                  *)
(* CARD_DECOMPOSITION_GROUP_CONJUGATE). An f in D_Q induces an automorphism  *)
(* of k(Q) mapping x + Q to f(x) + Q                                         *)
(* (DECOMPOSITION_GROUP_RESIDUE_AUTOMORPHISM) and fixing k(P); this gives a  *)
(* homomorphism from D_Q to the Galois group of k(Q) over k(P) with kernel   *)
(* I_Q (DECOMPOSITION_GROUP_RESIDUE_HOMOMORPHISM), so I_Q is normal in D_Q   *)
(* (INERTIA_GROUP_NORMAL_SUBGROUP). For Q maximal with b / Q finite it is    *)
(* onto (DECOMPOSITION_GROUP_RESIDUE_EPIMORPHISM) and |D_Q| = |I_Q|          *)
(* [k(Q):k(P)] (CARD_DECOMPOSITION_GROUP), so that conjugate primes have the *)
(* same residue degree (EXTENSION_DEGREE_RESIDUE_CONJUGATE). Then some f in  *)
(* D_Q is a Frobenius, f(x) == x^q (mod Q)                                   *)
(* (DECOMPOSITION_GROUP_FROBENIUS_EXISTS), and if I_Q is trivial (Q          *)
(* unramified) frobenius_element is the unique one in G (FROBENIUS_ELEMENT), *)
(* with Frob_f(Q) = f Frob_Q f^-1 (FROBENIUS_ELEMENT_CONJUGATE).             *)
(*                                                                           *)
(* The description of I_Q (INERTIA_GROUP) and the residue maps               *)
(* (DECOMPOSITION_GROUP_RESIDUE_AUTOMORPHISM,                                *)
(* DECOMPOSITION_GROUP_RESIDUE_HOMOMORPHISM) need only the elements of       *)
(* D_Q to preserve b, as for valuation subrings in ANT/valuation_residue.ml. *)
(*                                                                           *)
(* Intermediate fields: for M = subfield_generated l s (s subfield_of l      *)
(* containing h(k)) and H = Gal(l/M) = group_carrier(galois_group(M,l) I),   *)
(* D_Q(l/M) = D_Q INTER H (DECOMPOSITION_GROUP_INTERMEDIATE) and I_Q(l/M) =  *)
(* I_Q INTER H for any ideal Q of b (INERTIA_GROUP_INTERMEDIATE, so also for *)
(* the higher ramification groups of ANT/ramification_groups.ml; for a tower *)
(* k -> l -> m with m Galois over k, the inertia group over l is that over k *)
(* intersected with Gal(m/l): INERTIA_GROUP_TOWER); for Q maximal, Q is the  *)
(* only maximal ideal of b above Q INTER s iff H SUBSET D_Q                  *)
(* (DECOMPOSITION_GROUP_INTERMEDIATE_UNIQUE), so Q is the only one above its *)
(* trace on the decomposition field fixed_field l D_Q                        *)
(* (DECOMPOSITION_FIELD_UNIQUE_PRIME). D_Q and I_Q are finite and nonempty   *)
(* (FINITE_DECOMPOSITION_INERTIA_GROUPS); frobenius_element is an element of *)
(* D_Q with the Frobenius congruence also when I_Q is not trivial            *)
(* (FROBENIUS_ELEMENT_IN_DECOMPOSITION_GROUP); if f in D_Q satisfies f(x) =  *)
(* x^q modulo Q on b then f^n(x) = x^(q^n)                                   *)
(* (DECOMPOSITION_GROUP_POW_CONGRUENCE), and two elements of D_Q that agree  *)
(* modulo Q on b are equal when I_Q = {I}                                    *)
(* (DECOMPOSITION_GROUP_CONGRUENT_EQ).                                       *)
(*                                                                           *)
(* Routes: transitivity needs no Dedekind hypotheses: for x in a maximal     *)
(* ideal Q1 with the same contraction as Q, the product of the f(x) over G   *)
(* is in b and in h(k) (GALOIS_PRODUCT_IN_BASE), so in Q; Q prime puts some  *)
(* f(x) in Q, so Q1 is in the union of the finitely many primes f^-1(Q),     *)
(* PRIME_AVOIDANCE puts it in one and maximality gives equality. The counts  *)
(* are orbit-stabilizer (ORBIT_STABILIZER_MUL), the conjugation of D_Q is    *)
(* GROUP_STABILIZER_OF_ACTION. The induced map on k(Q) is the homomorphism   *)
(* of QUOTIENT_RING_UNIVERSAL on cosets. Surjectivity: an automorphism s of  *)
(* k(Q) over k(P) maps x + Q to a root of the reduction of prod (X - g(x))   *)
(* over the orbit of x, whose coefficients are in b and h(k), so s(x + Q) =  *)
(* g(x) + Q for some g in G (GALOIS_GROUP_RESIDUE_CONJUGATE); for x reducing *)
(* to a primitive root of k(Q) and lying in the other conjugates of Q        *)
(* (CHINESE_REMAINDER_IDEALS), that g is in D_Q and induces s. The Frobenius *)
(* is the preimage of the q-power map (GALOIS_GROUP_FINITE_FIELD). The       *)
(* intermediate groups are the intersections by                              *)
(* IN_GALOIS_GROUP_INTERMEDIATE; uniqueness above Q INTER s is the           *)
(* transitivity of Gal(l/M) (GALOIS_GROUP_ORBIT_MAXIMAL_IDEAL).              *)
(*                                                                           *)
(* Uses: Library/grouptheory.ml (group actions), Library/galois.ml,          *)
(* Library/finite_fields.ml (FINITE_FIELD_PRIMITIVE_ROOT) and                *)
(* ANT/ideal_arith.ml (PRIME_AVOIDANCE, CHINESE_REMAINDER_IDEALS).           *)
(* ========================================================================= *)

