(* ========================================================================= *)
(* The Galois group of a Galois extension of Q is generated by the inertia   *)
(* groups of the primes (Narkiewicz Cor. 2 to Prop. 6.8): the group form of  *)
(* the theorem of Minkowski that Q has no unramified extension other than Q. *)
(*                                                                           *)
(* For a field k with [k:Q] = 1, that is extension_degree                    *)
(* (subfield_generated k {ring_0 k},k) I = 1, a number field l and           *)
(* ring_homomorphism(k,l) h:                                                 *)
(*                                                                           *)
(*   every nonzero prime of O_k is unramified in l ==> [l:k] = 1             *)
(*                                   (NUMBER_FIELD_UNRAMIFIED_RATIONAL)      *)
(*   for l Galois over k, G = galois_group(k,l) h is generated by the        *)
(*   inertia groups I_Q of the nonzero primes Q of O_l                       *)
(*                              (NUMBER_FIELD_INERTIA_GROUPS_GENERATE)       *)
(*                                                                           *)
(* Routes. The primes of O_k are unramified over Z, as e f <= [k:Q] = 1      *)
(* (NUMBER_FIELD_RATIONAL_RAMIFICATION_INDEX, by                             *)
(* RAMIFICATION_INDEX_PRIME_SUBFIELD); if l had degree > 1 over Q it would   *)
(* have a ramified prime P over some rational prime                          *)
(* (NUMBER_FIELD_RAMIFIED_PRIME_EXISTS of ANT/minkowski_theory.ml), and      *)
(* e(P|Z) = e(P|p) e(p|Z) (NUMBER_FIELD_RAMIFICATION_INDEX_TOWER_Q) for the  *)
(* prime p of O_k below P. The fixed field of the subgroup generated by the  *)
(* inertia groups is unramified over k                                       *)
(* (NUMBER_FIELD_UNRAMIFIED_INERTIA_FIXED_FIELD of                           *)
(* ANT/decomposition_field.ml), hence of degree 1, hence equal to h(k), and  *)
(* the Galois correspondence gives the whole group.                          *)
(*                                                                           *)
(* Uses: Library/galois.ml, ANT/relative_split.ml, ANT/relative_degree.ml,   *)
(* ANT/splitting_types.ml, ANT/minkowski_theory.ml and                       *)
(* ANT/decomposition_field.ml.                                               *)
(* ========================================================================= *)

needs "Library/galois.ml";;
needs "ANT/relative_split.ml";;
needs "ANT/relative_degree.ml";;
needs "ANT/splitting_types.ml";;
needs "ANT/minkowski_theory.ml";;
needs "ANT/decomposition_field.ml";;

(* ------------------------------------------------------------------------- *)
(* Q has no unramified extension, relative form; the inertia groups generate *)
(* the Galois group.                                                         *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_RATIONAL_RAMIFICATION_INDEX = prove
 (`!k:A ring p.
        number_field k /\
        extension_degree(subfield_generated k {ring_0 k},k) I = 1 /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> ramification_index (integer_ring,ring_of_integers k)
              (ring_of_int k) p = 1`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `p:A->bool`] RAMIFICATION_INDEX_PRIME_SUBFIELD)
    THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`subfield_generated k {ring_0(k:A ring)}`; `k:A ring`;
                 `I:A->A`; `p:A->bool`] RING_OF_INTEGERS_PRIME_IDEAL_BELOW) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
               EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `q:A->bool` STRIP_ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`subfield_generated k {ring_0(k:A ring)}`; `k:A ring`;
                 `I:A->A`; `q:A->bool`; `p:A->bool`]
    NUMBER_FIELD_RAMIFICATION_RESIDUE_BOUNDS) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION]
    THEN
  STRIP_TAC THEN
  MATCH_MP_TAC(ARITH_RULE `1 <= e /\ e <= 1 ==> e = 1`) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC LE_TRANS THEN
  EXISTS_TAC
   `ramification_index
     (ring_of_integers(subfield_generated k {ring_0 k}),ring_of_integers k)
     (I:A->A) p *
    residue_degree
     (ring_of_integers(subfield_generated k {ring_0 k}),ring_of_integers k)
     I p` THEN
  ASM_REWRITE_TAC[] THEN
  GEN_REWRITE_TAC LAND_CONV [ARITH_RULE `e:num = e * 1`] THEN
  MATCH_MP_TAC LE_MULT2 THEN ASM_REWRITE_TAC[LE_REFL]);;

let NUMBER_FIELD_UNRAMIFIED_RATIONAL = prove
 (`!(h:A->B) k l.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        extension_degree(subfield_generated k {ring_0 k},k) I = 1 /\
        (!p. prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
             ==> unramified (ring_of_integers k,ring_of_integers l) h p)
        ==> extension_degree(k,l) h = 1`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[MULT_CLAUSES] THEN
  DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT2) THEN
  MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
  MP_TAC(ISPEC `l:B ring` NUMBER_FIELD_RAMIFIED_PRIME_EXISTS) THEN
  ASM_REWRITE_TAC[NOT_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`q:num`; `P:B->bool`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(P = {ring_0(l:B ring)})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `ring_of_num l q IN {ring_0(l:B ring)}` THEN
    REWRITE_TAC[IN_SING; RING_OF_NUM_EQ_0] THEN
    FIRST_ASSUM(MP_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [number_field]) THEN
    DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[DIVIDES_ZERO] THEN
    ASM_MESON_TAC[PRIME_0];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `P:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_BELOW) THEN
  ASM_REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:A->bool` STRIP_ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`]
    NUMBER_FIELD_RAMIFICATION_INDEX_TOWER_Q) THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`k:A ring`; `p:A->bool`]
    NUMBER_FIELD_RATIONAL_RAMIFICATION_INDEX) THEN
  ANTS_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_HOMOMORPHIC_PREIMAGE]; DISCH_THEN SUBST1_TAC]
     THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `p:A->bool`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o MATCH_MP UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED) THEN
  REWRITE_TAC[weakly_unramified] THEN
  DISCH_THEN(MP_TAC o SPEC `P:B->bool`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN SUBST1_TAC THEN ASM_ARITH_TAC);;

let NUMBER_FIELD_INERTIA_GROUPS_GENERATE = prove
 (`!(h:A->B) k l.
        number_field l /\ galois_extension(k,l) h /\
        extension_degree(subfield_generated k {ring_0 k},k) I = 1
        ==> subgroup_generated (galois_group(k,l) h)
              (UNIONS {group_carrier
                        (inertia_group(k,l) h (ring_of_integers l) Q) |
                       Q | prime_ideal (ring_of_integers l) Q /\
                           ~(Q = {ring_0 l})}) =
            galois_group(k,l) h`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[GALOIS_IMP_FIELD_EXTENSION; field_extension;
                  RING_MONOMORPHISM_IMP_HOMOMORPHISM]; ALL_TAC] THEN
  SUBGOAL_THEN `finite_extension(k,l) (h:A->B)` ASSUME_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_TOWER_LAW]; ALL_TAC] THEN
  ABBREV_TAC
   `H = group_carrier(subgroup_generated (galois_group(k,l) (h:A->B))
          (UNIONS {group_carrier
                    (inertia_group(k,l) h (ring_of_integers l) Q) |
                   Q | prime_ideal (ring_of_integers l) Q /\
                       ~(Q = {ring_0 l})}))` THEN
  SUBGOAL_THEN `H subgroup_of galois_group(k,l) (h:A->B)` ASSUME_TAC THENL
   [EXPAND_TAC "H" THEN REWRITE_TAC[SUBGROUP_SUBGROUP_GENERATED]; ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`]
    GALOIS_GROUP_FIXED_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ABBREV_TAC `w = fixed_field l (H:(B->B)->bool)` THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `w:B->bool`]
    NUMBER_FIELD_UNRAMIFIED_INERTIA_FIXED_FIELD) THEN
  ASM_SIMP_TAC[SUBFIELD_OF_IMP_SUBSET; SUBSET_REFL] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (w:B->bool)`]
    NUMBER_FIELD_UNRAMIFIED_RATIONAL) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `w:B->bool`]
    NUMBER_FIELD_INTERMEDIATE_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  ASM_SIMP_TAC[EXTENSION_DEGREE_EQ_1; field_extension] THEN DISCH_TAC THEN
  REWRITE_TAC[SUBGROUP_GENERATED_EQ] THEN ASM_REWRITE_TAC[] THEN
  UNDISCH_TAC
   `group_carrier(galois_group(subfield_generated l w,l) (I:B->B)) = H` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  REWRITE_TAC[EXTENSION] THEN X_GEN_TAC `f:B->B` THEN
  ASM_SIMP_TAC[IN_GALOIS_GROUP_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD] THEN
  REWRITE_TAC[IN_GALOIS_GROUP] THEN
  UNDISCH_TAC `IMAGE (h:A->B) (ring_carrier k) = w` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN REWRITE_TAC[FORALL_IN_IMAGE]);;
