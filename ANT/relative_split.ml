let RESIDUE_DEGREE_QUOTIENT_RING = prove
 (`!r:A ring s:B ring h P.
        ring_homomorphism(r,s) h /\ ring_ideal s P
        ==> ?g. ring_monomorphism
                  (quotient_ring r {x | x IN ring_carrier r /\ h x IN P},
                   quotient_ring s P) g /\
                (!y. y IN ring_carrier r
                     ==> g(ring_coset r {x | x IN ring_carrier r /\ h x IN P}
                                      y) =
                         ring_coset s P (h y)) /\
                residue_degree (r,s) h P =
                extension_degree
                  (quotient_ring r {x | x IN ring_carrier r /\ h x IN P},
                   quotient_ring s P) g`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `p = {x | x IN ring_carrier r /\ (h:A->B) x IN P}` THEN
  SUBGOAL_THEN `ring_ideal r (p:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "p" THEN MATCH_MP_TAC RING_IDEAL_HOMOMORPHIC_PREIMAGE THEN
    ASM_MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x y:A. x IN ring_carrier r /\ y IN ring_carrier r
            ==> (ring_coset r p x = ring_coset r p y <=>
                 ring_coset s P (h x) = ring_coset s P ((h:A->B) y))`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [ring_homomorphism]) THEN
    SUBGOAL_THEN `(h:A->B) x IN ring_carrier s /\ h y IN ring_carrier s`
    STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_COSET_EQ] THEN EXPAND_TAC "p" THEN
    MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `h:A->B`]
      RING_HOMOMORPHISM_SUB) THEN
    ASM_SIMP_TAC[IN_ELIM_THM; RING_SUB];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_homomorphism(r:A ring,quotient_ring s P)
                                  (ring_coset s P o (h:A->B))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `quotient_ring s (P:B->bool)`]
      RING_HOMOMORPHISM_COMPOSE) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET];
