(* Digits in P^n give elements of Q^(e n).                                   *)
let DEDEKIND_EXTENSION_DIGITS_IN_IDEAL_POW = prove
 (`!r s (g:A->B) Q P e (f:num) t (w:num->B) E.
        dedekind_domain s /\ ring_monomorphism(r,s) g /\
        prime_ideal s Q /\ ~(Q = {ring_0 s}) /\
        P = {x | x IN ring_carrier r /\ g x IN Q} /\ ~(P = {ring_0 r}) /\
        e = ramification_index (r,s) g Q /\
        t IN ring_carrier s /\ (!i. i < f ==> w i IN ring_carrier s) /\
        (!a. E a = ring_sum s {j | j < e}
                    (\j. ring_mul s (ring_pow s t j)
                          (ring_sum s {i | i < f}
                            (\i. ring_mul s (g(a i j)) (w i)))))
        ==> !n a. (!i j. i < f /\ j < e ==> a i j IN ideal_pow r P n)
                  ==> E a IN ideal_pow s Q (e * n)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REPEAT(FIRST_X_ASSUM(MP_TAC o SYM o check (is_var o lhs o concl))) THEN
  REPEAT DISCH_TAC THEN
  MAP_EVERY X_GEN_TAC [`n:num`; `a:num->num->A`] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `n:num`]
    RAMIFICATION_INDEX_IMAGE_POW_SUBSET) THEN
  ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN DISCH_TAC THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_POW; IN_ELIM_THM] THEN
  X_GEN_TAC `j:num` THEN DISCH_TAC THEN
  MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; RING_POW] THEN
  MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_POW; IN_ELIM_THM] THEN
  X_GEN_TAC `i:num` THEN DISCH_TAC THEN
  MATCH_MP_TAC IN_RING_IDEAL_RMUL THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW]);;

(* Spanning modulo Q^(e n), by induction on n: y - E(a) in Q^(e n) is g(p^n) *)
(* b modulo Q^(e n + e), and b is E(c) modulo Q^e, so y is E(a + p^n c)      *)
(* modulo Q^(e (n + 1)).                                                     *)
let DEDEKIND_EXTENSION_DIGITS_SPAN = prove
 (`!r s (g:A->B) Q P e (f:num) t p (w:num->B) E.
        dedekind_domain r /\ dedekind_domain s /\ ring_monomorphism(r,s) g /\
        prime_ideal s Q /\ ~(Q = {ring_0 s}) /\
        P = {x | x IN ring_carrier r /\ g x IN Q} /\ ~(P = {ring_0 r}) /\
        e = ramification_index (r,s) g Q /\
        t IN Q /\ ~(t IN ideal_pow s Q 2) /\
        p IN P /\ ~(p IN ideal_pow r P 2) /\
        (!i. i < f ==> w i IN ring_carrier s) /\
        (!y. y IN ring_carrier s
             ==> ?a. (!i. a i IN ring_carrier r) /\
                     ring_sub s y
                      (ring_sum s {i | i < f} (\i. ring_mul s (g(a i)) (w i)))
                     IN Q) /\
        (!a. E a = ring_sum s {j | j < e}
                    (\j. ring_mul s (ring_pow s t j)
                          (ring_sum s {i | i < f}
                            (\i. ring_mul s (g(a i j)) (w i)))))
        ==> !n y. y IN ring_carrier s
                  ==> ?a. (!i j. a i j IN ring_carrier r) /\
                          ring_sub s y (E a) IN ideal_pow s Q (e * n)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REPEAT(FIRST_X_ASSUM(MP_TAC o SYM o check (is_var o lhs o concl))) THEN
  REPEAT DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN `prime_ideal r (P:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "P" THEN MATCH_MP_TAC PRIME_IDEAL_HOMOMORPHIC_PREIMAGE THEN
    EXISTS_TAC `s:B ring` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_ideal r (P:A->bool) /\ ring_ideal s (Q:B->bool)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]; ALL_TAC] THEN
  SUBGOAL_THEN `(p:A) IN ring_carrier r /\ (t:B) IN ring_carrier s`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `P:A->bool`;
                 `e:num`; `p:A`] DEDEKIND_EXTENSION_UNIFORMIZER_CRITERION) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  DISCH_THEN(LABEL_TAC "plift" o CONJUNCT1) THEN
  SUBGOAL_THEN
   `!n. (g:A->B)(ring_pow r p n) IN ideal_pow s Q (e * n)`
  ASSUME_TAC THENL
   [GEN_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `n:num`]
      RAMIFICATION_INDEX_IMAGE_POW_SUBSET) THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(SET_RULE
     `x IN s ==> IMAGE (g:A->B) s SUBSET t ==> g x IN t`) THEN
    ASM_SIMP_TAC[RING_POW_IN_IDEAL_POW];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `e:num`; `f:num`;
                 `t:B`; `w:num->B`; `E:(num->num->A)->B`]
    DEDEKIND_EXTENSION_DIGITS_LINEAR) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN(LABEL_TAC "lin")] THEN
  SUBGOAL_THEN
   `!y. y IN ring_carrier s
        ==> ?a. (!i j. (a:num->num->A) i j IN ring_carrier r) /\
                ring_sub s y ((E:(num->num->A)->B) a) IN
                ideal_pow s (Q:B->bool) e`
  (LABEL_TAC "a0") THENL
   [ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `t:B`;
                   `f:num`; `w:num->B`] DEDEKIND_UNIFORMIZER_DIGITS_SPAN) THEN
    ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN(ACCEPT_TAC o SPEC `e:num`)];
