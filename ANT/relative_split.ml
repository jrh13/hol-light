(* For an extension t of a Dedekind domain s and a prime Q of t with         *)
(* nonzero contraction P: v_Q(j t) = e(Q|P) v_P(j). Write j = P^n i with     *)
(* n = v_P(j) and i not inside P; then j t = (P t)^n (i t) and i t is not    *)
(* inside Q. Hence e multiplies along monomorphisms r -> s -> t of Dedekind  *)
(* domains (RAMIFICATION_INDEX_TOWER), and f multiplies along any            *)
(* homomorphisms with a finite residue field t/Q, by comparing               *)
(* N(Q) = N(P)^f(Q|P) = N(p)^(f(P|p) f(Q|P)) with N(Q) = N(p)^f(Q|p).        *)

let IDEAL_VALUATION_HOMOMORPHIC_IMAGE = prove
 (`!s:B ring t:C ring h Q j.
        dedekind_domain s /\ dedekind_domain t /\ ring_monomorphism(s,t) h /\
        prime_ideal t Q /\
        ~({y | y IN ring_carrier s /\ h y IN Q} = {ring_0 s}) /\
        ring_ideal s j /\ ~(j = {ring_0 s})
        ==> ideal_valuation t Q (ideal_generated t (IMAGE h j)) =
            ramification_index (s,t) h Q *
            ideal_valuation s {y | y IN ring_carrier s /\ h y IN Q} j`,
  let lemma = prove
   (`!r p j:A->bool.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?i. ring_ideal r i /\ ~(i = {ring_0 r}) /\ ~(i SUBSET p) /\
                ideal_prod r (ideal_pow r p (ideal_valuation r p j)) i = j`,
    REPEAT STRIP_TAC THEN
    ABBREV_TAC `n = ideal_valuation r p (j:A->bool)` THEN
    MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `ideal_pow r (p:A->bool) n`]
