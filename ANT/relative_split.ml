  ANTS_TAC THENL [ASM_SIMP_TAC[RING_POW]; DISCH_THEN SUBST1_TAC] THEN
  SUBGOAL_THEN
   `ring_sub s y (ring_add s ((E:(num->num->A)->B) a)
