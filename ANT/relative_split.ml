(* Let g : r -> s be a monomorphism of Dedekind domains, Q a nonzero prime   *)
(* of s with nonzero contraction P, e = e(Q|P), t a uniformizer of Q (in Q   *)
(* but not in Q^2) and p one of P, and w_i (i < f) elements of s whose       *)
(* combinations with coefficients g(a_i) represent every residue class       *)
(* modulo Q (spanning) and lie in Q only if every a_i lies in P              *)
(* (independence); RESIDUE_DEGREE_LIFTED_BASIS gives such w_i, with f the    *)
(* residue degree f(Q|P). Let E(a) be the sum over j < e of t^j times the    *)
(* sum of the g(a_ij) w_i. Then every y in s is congruent to some E(a)       *)
(* modulo Q^(e n) (DEDEKIND_EXTENSION_DIGITS_SPAN), and E(a) lies in Q^(e n) *)
(* iff every a_ij (i < f, j < e) lies in P^n                                 *)
(* (DEDEKIND_EXTENSION_DIGITS_IN_IDEAL_POW,                                  *)
(* DEDEKIND_EXTENSION_DIGITS_INDEPENDENT); DEDEKIND_EXTENSION_DIGITS states  *)
(* both halves.                                                              *)
(*                                                                           *)
(* At the first level the digits are the t-adic expansion modulo Q^m:        *)
(* spanning for every m (DEDEKIND_UNIFORMIZER_DIGITS_SPAN) and independence  *)
(* when g(P) lies in Q^m, that is for m <= e                                 *)
(* (DEDEKIND_UNIFORMIZER_DIGITS_INDEPENDENT). From n to n + 1 the digits of  *)
(* the next level are multiplied by p^n: g(p^n) has valuation e n at Q and   *)
(* acts on Q^(e n) as t^(e n) does                                           *)
(* (DEDEKIND_EXTENSION_UNIFORMIZER_CRITERION, from                           *)
(* DEDEKIND_VALUATION_LIFT_CANCEL), and E is semilinear                      *)
(* (DEDEKIND_EXTENSION_DIGITS_LINEAR).                                       *)

(* An element x of valuation d at P acts on P^d like a power of a            *)
(* uniformizer: every a in P^d is x b modulo P^(d + k), and x b in P^(d + k) *)
(* forces b in P^k.                                                          *)
