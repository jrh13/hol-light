    CONJ_TAC THEN DISCH_TAC THENL
     [UNDISCH_TAC
       `~(ideal_prod r (ideal_pow r p n) i = {ring_0(r:A ring)})` THEN
      ASM_SIMP_TAC[IDEAL_PROD_RZERO; RING_IDEAL_IMP_SUBSET;
                   RING_IDEAL_IDEAL_POW];
      MP_TAC(ISPECL [`r:A ring`; `p:A->bool`;
                     `ideal_prod r (ideal_pow r p n) (i:A->bool)`; `SUC n`]
        DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
      ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD; ARITH_RULE `~(SUC n <= n)`] THEN
      REWRITE_TAC[IDEAL_POW_SUC] THEN
      MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `ideal_pow r (p:A->bool) n`]
        IDEAL_PROD_COMM) THEN
      ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET; RING_IDEAL_IMP_SUBSET;
                   RING_IDEAL_IDEAL_POW] THEN
      DISCH_THEN(K ALL_TAC) THEN MATCH_MP_TAC IDEAL_PROD_MONO THEN
      ASM_REWRITE_TAC[SUBSET_REFL]]) in
  REPEAT STRIP_TAC THEN REWRITE_TAC[ramification_index] THEN
  ABBREV_TAC `P = {y | y IN ring_carrier s /\ (h:B->C) y IN Q}` THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN `prime_ideal s (P:B->bool)` ASSUME_TAC THENL
