  ASSUME_TAC THENL
   [FIRST_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV)
      [check (fun th -> is_eq(concl th) &&
                        lhs(concl th) = `a:num->num->A`) th]) THEN
    USE_THEN "lin" MATCH_MP_TAC THEN ASM_SIMP_TAC[RING_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN `(E:(num->num->A)->B) b IN ideal_pow s Q e` ASSUME_TAC THENL
   [USE_THEN "lc" (MATCH_MP_TAC o SPECL [`n:num`; `e:num`]) THEN
    CONJ_TAC THENL [ASM_REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_mul s ((g:A->B)(ring_pow r p n)) ((E:(num->num->A)->B) b) =
      ring_sub s (E a) (E c)`
    SUBST1_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
        is_eq(concl th) &&
        lhs(concl th) = `(E:(num->num->A)->B) a`)) THEN
      SUBGOAL_THEN
       `(E:(num->num->A)->B) b IN ring_carrier s /\ E c IN ring_carrier s`
      MP_TAC THENL [ASM_REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
      SUBGOAL_THEN `(g:A->B)(ring_pow r p n) IN ring_carrier s` MP_TAC THENL
