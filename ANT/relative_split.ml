    ASM_SIMP_TAC[RING_SUB; RING_SUM];
    POP_ASSUM(LABEL_TAC "ih")] THEN
  X_GEN_TAC `y:B` THEN DISCH_TAC THEN
  REMOVE_THEN "ih" (MP_TAC o C MATCH_MP (ASSUME `(y:B) IN ring_carrier s`) o
    SPEC `y:B`) THEN
  DISCH_THEN(X_CHOOSE_THEN `a:num->num->A` STRIP_ASSUME_TAC) THEN
  USE_THEN "plift" (MP_TAC o C MATCH_MP
   (ASSUME `ring_sub s (y:B) ((E:(num->num->A)->B) a) IN
            ideal_pow s Q (e * n)`) o
   SPECL [`n:num`; `e:num`; `ring_sub s (y:B) ((E:(num->num->A)->B) a)`]) THEN
  DISCH_THEN(X_CHOOSE_THEN `b:B` STRIP_ASSUME_TAC) THEN
  USE_THEN "a0" (MP_TAC o C MATCH_MP (ASSUME `(b:B) IN ring_carrier s`) o
    SPEC `b:B`) THEN
  DISCH_THEN(X_CHOOSE_THEN `c:num->num->A` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `\i j. ring_add r ((a:num->num->A) i j)
                    (ring_mul r (ring_pow r p n) ((c:num->num->A) i j))` THEN
  CONJ_TAC THENL
   [REPEAT GEN_TAC THEN REWRITE_TAC[] THEN
    ASM_SIMP_TAC[RING_ADD; RING_MUL; RING_POW];
    ALL_TAC] THEN
