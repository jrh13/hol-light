let RING_OF_INTEGERS_MONOMORPHIC_PREIMAGE = prove
 (`!k:A ring l:B ring h x.
        ring_monomorphism(k,l) h /\ x IN ring_carrier k
        ==> (h x IN ring_carrier(ring_of_integers l) <=>
             x IN ring_carrier(ring_of_integers k))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  REWRITE_TAC[RING_OF_INTEGERS_CARRIER; IN_ELIM_THM] THEN
  SUBGOAL_THEN `ring_of_int l = (h:A->B) o ring_of_int k` SUBST1_TAC THENL
   [REWRITE_TAC[FUN_EQ_THM; o_THM] THEN
    ASM_MESON_TAC[RING_HOMOMORPHISM_RING_OF_INT];
    EQ_TAC THEN DISCH_TAC] THENL
   [MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `l:B ring`;
                   `ring_of_int k:int->A`; `h:A->B`; `x:A`]
      INTEGRAL_ELEMENT_MONOMORPHIC_PREIMAGE);
    MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `l:B ring`;
                   `ring_of_int k:int->A`; `h:A->B`; `x:A`]
      INTEGRAL_ELEMENT_HOMOMORPHIC_IMAGE)] THEN
  ASM_SIMP_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT]);;

let RING_OF_INTEGERS_MONOMORPHIC_PREIMAGE_EQ = prove
 (`!k:A ring l:B ring h.
        ring_monomorphism(k,l) h
        ==> {a | a IN ring_carrier k /\
                 h a IN ring_carrier(ring_of_integers l)} =
            ring_carrier(ring_of_integers k)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN
  X_GEN_TAC `a:A` THEN ASM_CASES_TAC `(a:A) IN ring_carrier k` THEN
  ASM_SIMP_TAC[RING_OF_INTEGERS_MONOMORPHIC_PREIMAGE] THEN
  ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]);;

let RING_OF_INTEGERS_SUBFIELD_GENERATED = prove
 (`!(k:A ring) s.
        ring_carrier(ring_of_integers(subfield_generated k s)) =
        ring_carrier(ring_of_integers k) INTER
        ring_carrier(subfield_generated k s)`,
  REPEAT GEN_TAC THEN
  MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `k:A ring`; `I:A->A`]
    RING_OF_INTEGERS_MONOMORPHIC_PREIMAGE_EQ) THEN
  REWRITE_TAC[ring_monomorphism; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
              I_THM] THEN
  ANTS_TAC THENL [MESON_TAC[]; DISCH_THEN(SUBST1_TAC o SYM)] THEN
  SET_TAC[]);;

let NUMBER_FIELD_HOMOMORPHIC_PREIMAGE = prove
 (`!k:A ring l:B ring h.
        field k /\ number_field l /\ ring_homomorphism(k,l) h
        ==> number_field k`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`]
    PRIME_SUBFIELD_TOWER_LAW) THEN
  FIRST_X_ASSUM(fun th -> REWRITE_TAC[MATCH_MP NUMBER_FIELD_IMP_FIELD th] THEN
    MP_TAC(REWRITE_RULE[number_field] th)) THEN
  ASM_SIMP_TAC[number_field]);;

let NUMBER_FIELD_SUBFIELD_GENERATED = prove
 (`!(k:A ring) s.
        number_field k ==> number_field (subfield_generated k s)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `k:A ring`;
                       `I:A->A`] NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD;
               RING_HOMOMORPHISM_SUBFIELD_INCLUSION]);;

let NUMBER_FIELD_TOWER_LAW = prove
 (`!k:A ring l:B ring h.
        field k /\ number_field l /\ ring_homomorphism(k,l) h
        ==> finite_extension(k,l) h /\
            extension_degree(subfield_generated l {ring_0 l},l) I =
            extension_degree(subfield_generated k {ring_0 k},k) I *
            extension_degree(k,l) h`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`]
    PRIME_SUBFIELD_TOWER_LAW) THEN
  FIRST_X_ASSUM(fun th -> REWRITE_TAC[MATCH_MP NUMBER_FIELD_IMP_FIELD th] THEN
    MP_TAC(REWRITE_RULE[number_field] th)) THEN
  ASM_SIMP_TAC[]);;

let NUMBER_FIELD_SUBFIELD_DEGREE_POS = prove
 (`!(m:A ring) s t.
        number_field m /\
        ring_carrier(subfield_generated m s) SUBSET
        ring_carrier(subfield_generated m t)
        ==> 1 <= extension_degree(subfield_generated m s,
                                  subfield_generated m t) I`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPEC `subfield_generated m (t:A->bool)` NUMBER_FIELD_DEGREE_POS) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  MP_TAC(ISPECL [`m:A ring`; `{ring_0 m:A}`; `s:A->bool`; `t:A->bool`]
    EXTENSION_DEGREE_SUBFIELD_TOWER) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; SING_SUBSET] THEN
    ASM_MESON_TAC[RING_0; SUBFIELD_GENERATED; SUBSET];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[ARITH_RULE `1 <= n <=> ~(n:num = 0)`; MULT_EQ_0;
              DE_MORGAN_THM] THEN
  SIMP_TAC[]);;

let NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE = prove
 (`!(k:A ring) (m:B ring) j X.
        number_field k /\ field m /\ ring_homomorphism(k,m) j /\
        X SUBSET ring_carrier k
        ==> extension_degree(subfield_generated m {ring_0 m},
                             subfield_generated m (IMAGE j X)) I =
            extension_degree(subfield_generated k {ring_0 k},
                             subfield_generated k X) I /\
            number_field_discriminant(subfield_generated m (IMAGE j X)) =
            number_field_discriminant(subfield_generated k X)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `ring_monomorphism(k:A ring,m:B ring) j` ASSUME_TAC THENL
   [MATCH_MP_TAC FIELD_RING_HOMOMORPHISM_MONOMORPHISM THEN
    ASM_SIMP_TAC[FIELD_IMP_NONTRIVIAL_RING];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`j:A->B`; `subfield_generated k (X:A->bool)`; `m:B ring`]
    RING_ISOMORPHISM_ONTO_SUBFIELD_IMAGE) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
               RING_HOMOMORPHISM_FROM_SUBFIELD_GENERATED] THEN
  MP_TAC(ISPECL [`k:A ring`; `m:B ring`; `j:A->B`; `X:A->bool`]
    SUBFIELD_GENERATED_BY_MONOMORPHIC_IMAGE) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  REWRITE_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`subfield_generated k (X:A->bool)`;
                 `subfield_generated m (IMAGE (j:A->B) X)`; `j:A->B`]
    NUMBER_FIELD_ISOMORPHIC_IMAGE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED]);;

