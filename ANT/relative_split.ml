(* ========================================================================= *)
(* Splitting of primes in relative extensions. For a ring homomorphism h : r *)
(* -> s and an ideal P of s, with p = {x | x IN r /\ h x IN P} the           *)
(* contraction of P, ramification_index (r,s) h P = e(P|p) is the exponent   *)
(* of P in the extended ideal p s and residue_degree (r,s) h P = f(P|p) the  *)
(* degree of s/P over the image of r, that is [s/P : r/p] (both defined in   *)
(* ANT/prime_split.ml). The absolute notions over Z are the case of the map  *)
(* ring_of_int from integer_ring (ANT/prime_split.ml) and, for number        *)
(* fields, equivalently the case of the inclusion of the integers of the     *)
(* prime subfield (RAMIFICATION_INDEX_PRIME_SUBFIELD,                        *)
(* RESIDUE_DEGREE_PRIME_SUBFIELD). For number fields k, l (k only assumed to *)
(* be a field: it is then a number field) with a ring homomorphism h : k ->  *)
(* l, O_k = ring_of_integers k, O_l = ring_of_integers l: extension of       *)
(* ideals is multiplicative (ANT/ideal_arith.ml); h maps O_k into O_l        *)
(* (ANT/numfield.ml) and x IN O_k iff h x IN O_l; [l:Q] = [k:Q] [l:k]; every *)
(* nonzero prime P of O_l lies over exactly one nonzero prime p of O_k, its  *)
(* contraction, and a prime above a nonzero prime p is nonzero and maximal   *)
(* with finite residue field and contraction p                               *)
(* (NUMBER_FIELD_PRIME_IDEAL_ABOVE, NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO); *)
(* for a nonzero prime p of O_k the primes above p are finitely many, at     *)
(* least one, and p O_l is the product of their powers P^e(P|p); O_l/P is a  *)
(* field extension of O_k/p of degree f(P|p) and N(P) = N(p)^f(P|p), so the  *)
(* number of primes of O_l of prime norm m is the sum over the primes p of   *)
(* O_k of norm m of the number of primes above p of degree 1                 *)
(* (NUMBER_FIELD_PRIME_NORM_CARD); v_P(j O_l) = e(P|p) v_p(j)                *)
(* (NUMBER_FIELD_IDEAL_VALUATION_EXTENSION); e and f are multiplicative in   *)
(* towers. The fundamental identity is in ANT/relative_degree.ml.            *)
(*                                                                           *)
(* General tools proved on the way: for an extension of Dedekind domains,    *)
(* v_Q(j t) = e(Q|P) v_P(j) with P the contraction of Q                      *)
(* (IDEAL_VALUATION_HOMOMORPHIC_IMAGE), and v_Q(j x) = e(Q|P) v_P(x) for the *)
(* elements x of their fraction fields                                       *)
(* (DEDEKIND_VALUATION_RAMIFICATION_INDEX, for the valuations of             *)
(* ANT/dedekind_valuation.ml; for number fields                              *)
(* NUMBER_FIELD_VALUATION_RAMIFICATION_INDEX); e multiplies in towers of     *)
(* Dedekind domains (RAMIFICATION_INDEX_TOWER) and f in towers of arbitrary  *)
(* rings with a finite residue field (RESIDUE_DEGREE_TOWER). For an          *)
(* extension r -> s of Dedekind domains, uniformizers t of Q and p of its    *)
(* contraction P, and lifts w_i of a basis of the residue extension, the     *)
(* products t^j w_i (i < f, j < e) span s modulo Q^(e n) over r and are      *)
(* independent modulo P^n (DEDEKIND_EXTENSION_DIGITS). Route: the t-adic     *)
(* digits modulo Q^m (DEDEKIND_UNIFORMIZER_DIGITS_SPAN, and                  *)
(* DEDEKIND_UNIFORMIZER_DIGITS_INDEPENDENT for m <= e) are lifted from n to  *)
(* n + 1 with the image of p^n, which acts on Q^(e n) as a uniformizer acts  *)
(* on Q (DEDEKIND_EXTENSION_UNIFORMIZER_CRITERION):                          *)
(* DEDEKIND_EXTENSION_DIGITS_SPAN and DEDEKIND_EXTENSION_DIGITS_INDEPENDENT. *)
(* Subfields generated by subsets of a number field are number fields        *)
(* (NUMBER_FIELD_SUBFIELD_GENERATED), with the tower law                     *)
(* (EXTENSION_DEGREE_SUBFIELD_TOWER of Library/fieldtheory.ml) and positive  *)
(* degrees (NUMBER_FIELD_SUBFIELD_DEGREE_POS) between them; the subfield     *)
(* generated by the image of X under a homomorphism has the degree and       *)
(* discriminant of the subfield generated by X                               *)
(* (NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE).                                *)
(* Over the prime subfield, p O_Q is a nonzero prime of the integers of Q,   *)
(* contained in an ideal P of O_k iff p IN P                                 *)
(* (RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL).                                  *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml (extension_degree,    *)
(* CARD_EXTENSION_DEGREE, EXTENSION_DEGREE_EQ_IMAGE; the tower laws          *)
(* PRIME_SUBFIELD_TOWER_LAW over the prime subfields and                     *)
(* EXTENSION_DEGREE_SUBFIELD_TOWER), ANT/integral.ml, ANT/ideal_arith.ml     *)
(* (extension of ideals), ANT/dedekind.ml, ANT/dedekind_valuation.ml,        *)
(* ANT/ideal_norm.ml, ANT/numfield.ml, ANT/ring_of_integers.ml,              *)
(* ANT/classgroup.ml (NUMBER_FIELD_FINITE_PRIME_IDEALS_BOUNDED_NORM),        *)
(* ANT/prime_split.ml, ANT/discriminant.ml (number_field_discriminant) and   *)
(* ANT/trace_form.ml (NUMBER_FIELD_ISOMORPHIC_IMAGE).                        *)
(* ========================================================================= *)

