(* Lying over. The contraction of a prime P of O_l is a prime of O_k; a      *)
(* nonzero prime p of O_k inside it is equal to it (dimension one).          *)

let RING_OF_INTEGERS_PRIME_IDEAL_CONTRACTION = prove
 (`!k:A ring l:B ring h p P.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) P
        ==> (IMAGE h p SUBSET P <=>
             {x | x IN ring_carrier(ring_of_integers k) /\ h x IN P} = p)`,
  REPEAT STRIP_TAC THEN EQ_TAC THENL
   [DISCH_TAC; DISCH_THEN(SUBST1_TAC o SYM) THEN SET_TAC[]] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                 `{x | x IN ring_carrier(ring_of_integers k) /\
                       (h:A->B) x IN P}`;
                 `p:A->bool`] DEDEKIND_KRULL_DIMENSION_ONE) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN
  ANTS_TAC THENL [ALL_TAC; DISCH_THEN(ACCEPT_TAC o SYM)] THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC DEDEKIND_RING_OF_INTEGERS THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
      NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
    ASM_REWRITE_TAC[];
    MATCH_MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                         `ring_of_integers l:B ring`]
      PRIME_IDEAL_HOMOMORPHIC_PREIMAGE) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS];
    UNDISCH_TAC `IMAGE (h:A->B) p SUBSET P` THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
      PRIME_IDEAL_IMP_SUBSET) THEN
    ASM_REWRITE_TAC[] THEN SET_TAC[]]);;

let RING_OF_INTEGERS_PRIME_IDEAL_BELOW = prove
 (`!k:A ring l:B ring h P.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers l) P /\ ~(P = {ring_0 l})
        ==> ?!p. prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
                 IMAGE h p SUBSET P`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[EXISTS_UNIQUE_THM] THEN CONJ_TAC THENL
   [ALL_TAC;
    MAP_EVERY X_GEN_TAC [`p1:A->bool`; `p2:A->bool`] THEN STRIP_TAC THEN
    MAP_EVERY (fun t ->
      MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; t; `P:B->bool`]
        RING_OF_INTEGERS_PRIME_IDEAL_CONTRACTION))
     [`p1:A->bool`; `p2:A->bool`] THEN
    ASM_REWRITE_TAC[] THEN MESON_TAC[]] THEN
  EXISTS_TAC
   `{x | x IN ring_carrier(ring_of_integers k) /\ (h:A->B) x IN P}` THEN
  REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_ELIM_THM] THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                         `ring_of_integers l:B ring`]
      PRIME_IDEAL_HOMOMORPHIC_PREIMAGE) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ASM_REWRITE_TAC[number_field] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`l:B ring`; `P:B->bool`] RING_OF_INTEGERS_IDEAL_INTEGER) THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; NUMBER_FIELD_IMP_FIELD] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:int` STRIP_ASSUME_TAC) THEN
  MATCH_MP_TAC(SET_RULE
   `!x:A. x IN s /\ ~(x = a) ==> ~(s = {a})`) THEN
  EXISTS_TAC `ring_of_int k m:A` THEN
  ASM_SIMP_TAC[IN_ELIM_THM; RING_OF_INT_IN_RING_OF_INTEGERS;
               RING_OF_INT_EQ_0_CHAR_0] THEN
  FIRST_ASSUM(fun th ->
    ASM_REWRITE_TAC[MATCH_MP RING_HOMOMORPHISM_RING_OF_INT th]));;

(* A proper ideal of O_k extends to a proper ideal of O_l (Neukirch I.8):    *)
(* for a maximal ideal m and a nonzero a IN m take q with m q = (a) and      *)
(* b IN q outside (a); if m O_l = O_l then q O_l = (a) O_l, so h a divides   *)
(* h b in O_l, hence a divides b in O_k (O_l meets k in O_k): absurd.        *)

let RING_OF_INTEGERS_IDEAL_EXTENSION = prove
 (`!k:A ring l:B ring h j.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        ring_ideal (ring_of_integers k) j
        ==> (ideal_generated (ring_of_integers l) (IMAGE h j) =
             ring_carrier(ring_of_integers l) <=>
             j = ring_carrier(ring_of_integers k)) /\
            (ideal_generated (ring_of_integers l) (IMAGE h j) = {ring_0 l} <=>
             j = {ring_0 k})`,
  let lemma1 = prove
   (`!k:A ring l:B ring h a b.
        field k /\ field l /\ ring_monomorphism(k,l) h /\
        a IN ring_carrier(ring_of_integers k) /\ ~(a = ring_0 k) /\
        b IN ring_carrier(ring_of_integers k) /\
        h b IN ideal_generated (ring_of_integers l) {h a}
        ==> b IN ideal_generated (ring_of_integers k) {a}`,
    REPEAT STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
    MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN
    MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN
    REWRITE_TAC[SUBSET] THEN REPEAT DISCH_TAC THEN
    SUBGOAL_THEN `?y:B. y IN ring_carrier(ring_of_integers l) /\
                        (h:A->B) b = ring_mul l (h a) y`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC
       `(h:A->B) b IN ideal_generated (ring_of_integers l) {h a}` THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_of_integers l:B ring`;
                     `h:A->B`] RING_HOMOMORPHISM_IN_CARRIER) THEN
      ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS] THEN DISCH_TAC THEN
      ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING_EQ; ring_divides;
                   RING_OF_INTEGERS];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `a:A`; `b:A`] FIELD_DIVIDES) THEN
    ASM_SIMP_TAC[ring_divides; LEFT_IMP_EXISTS_THM] THEN
    X_GEN_TAC `c:A` THEN STRIP_TAC THEN
    SUBGOAL_THEN `(h:A->B) c = y` ASSUME_TAC THENL
     [MATCH_MP_TAC(ISPEC `l:B ring` INTEGRAL_DOMAIN_MUL_LCANCEL) THEN
      EXISTS_TAC `(h:A->B) a` THEN
      UNDISCH_TAC `(h:A->B) b = ring_mul l (h a) y` THEN
      MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:A`]
        RING_MONOMORPHISM_EQ_0) THEN
      MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
        RING_HOMOMORPHISM_IN_CARRIER) THEN
      MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
        RING_HOMOMORPHISM_MUL) THEN
      ASM_SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN];
      ALL_TAC] THEN
    SUBGOAL_THEN `(c:A) IN ring_carrier(ring_of_integers k)` ASSUME_TAC THENL
     [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `c:A`]
        RING_OF_INTEGERS_MONOMORPHIC_PREIMAGE) THEN
      ASM_REWRITE_TAC[];
      MATCH_MP_TAC IN_IDEAL_GENERATED_SING THEN
      REWRITE_TAC[ring_divides; RING_OF_INTEGERS] THEN ASM_MESON_TAC[]]) in
  let lemma2 = prove
   (`!k:A ring l:B ring h m.
        number_field k /\ field l /\ ring_monomorphism(k,l) h /\
        maximal_ideal (ring_of_integers k) m
        ==> ~(ideal_generated (ring_of_integers l) (IMAGE h m) =
              ring_carrier(ring_of_integers l))`,
    REPEAT STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_RING_OF_INTEGERS) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
    ASM_CASES_TAC `m = {ring_0 k:A}` THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_of_integers l:B ring`;
                     `h:A->B`; `m:A->bool`]
        IDEAL_GENERATED_MONOMORPHIC_IMAGE_EQ_0) THEN
      ASM_SIMP_TAC[MAXIMAL_IMP_RING_IDEAL; RING_OF_INTEGERS] THEN
      MP_TAC(ISPEC `ring_of_integers l:B ring` RING_1) THEN
      MP_TAC(ISPEC `l:B ring` FIELD_NONTRIVIAL) THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN SET_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `?a:A. a IN m /\ a IN ring_carrier(ring_of_integers k) /\ ~(a = ring_0 k)`
    STRIP_ASSUME_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `m:A->bool`]
        IN_RING_IDEAL_0) THEN
