   `!i j. i < f /\ j < e ==> (b:num->num->A) i j IN P`
  ASSUME_TAC THENL
   [USE_THEN "a1" MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
    USE_THEN "b" (fun th -> REWRITE_TAC[th]);
    ALL_TAC] THEN
  REPEAT STRIP_TAC THEN
  FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
    is_eq(concl th) && lhs(concl th) = `a:num->num->A`)) THEN
  REWRITE_TAC[] THEN MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW] THEN
  ONCE_REWRITE_TAC[ARITH_RULE `SUC n = n + 1`] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; RING_POW_IN_IDEAL_POW; IDEAL_POW_1]);;

(* Both halves: the t^j w_i (i < f, j < e) give a basis of s / Q^(e n) over  *)
(* r / P^n.                                                                  *)
let DEDEKIND_EXTENSION_DIGITS = prove
 (`!r s (g:A->B) Q P e (f:num) t p (w:num->B) E.
        dedekind_domain r /\ dedekind_domain s /\ ring_monomorphism(r,s) g /\
        prime_ideal s Q /\ ~(Q = {ring_0 s}) /\
        P = {x | x IN ring_carrier r /\ g x IN Q} /\ ~(P = {ring_0 r}) /\
        e = ramification_index (r,s) g Q /\
        t IN Q /\ ~(t IN ideal_pow s Q 2) /\
        p IN P /\ ~(p IN ideal_pow r P 2) /\
        (!i. i < f ==> w i IN ring_carrier s) /\
        (!y. y IN ring_carrier s
             ==> ?a. (!i. a i IN ring_carrier r) /\
                     ring_sub s y
                      (ring_sum s {i | i < f} (\i. ring_mul s (g(a i)) (w i)))
                     IN Q) /\
        (!a. (!i. a i IN ring_carrier r) /\
             ring_sum s {i | i < f} (\i. ring_mul s (g(a i)) (w i)) IN Q
             ==> !i. i < f ==> a i IN P) /\
        (!a. E a = ring_sum s {j | j < e}
                    (\j. ring_mul s (ring_pow s t j)
                          (ring_sum s {i | i < f}
                            (\i. ring_mul s (g(a i j)) (w i)))))
        ==> (!n y. y IN ring_carrier s
                   ==> ?a. (!i j. a i j IN ring_carrier r) /\
                           ring_sub s y (E a) IN ideal_pow s Q (e * n)) /\
            (!n a. (!i j. a i j IN ring_carrier r) /\
                   E a IN ideal_pow s Q (e * n)
                   ==> !i j. i < f /\ j < e ==> a i j IN ideal_pow r P n)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `P:A->bool`;
                   `e:num`; `f:num`; `t:B`; `p:A`; `w:num->B`;
                   `E:(num->num->A)->B`] DEDEKIND_EXTENSION_DIGITS_SPAN);
    MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `g:A->B`; `Q:B->bool`; `P:A->bool`;
                   `e:num`; `f:num`; `t:B`; `p:A`; `w:num->B`;
                   `E:(num->num->A)->B`] DEDEKIND_EXTENSION_DIGITS_INDEPENDENT)]
  THEN (ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN ACCEPT_TAC]));;

