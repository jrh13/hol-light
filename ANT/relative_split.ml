(* The extension of a nonzero prime p of O_k: proper, nonzero, with the      *)
(* primes above p as its nonzero prime divisors.                             *)

let RING_OF_INTEGERS_IDEAL_EXTENSION_PRIME = prove
 (`!k:A ring l:B ring h p.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> ~(ideal_generated (ring_of_integers l) (IMAGE h p) =
              ring_carrier(ring_of_integers l)) /\
            ~(ideal_generated (ring_of_integers l) (IMAGE h p) = {ring_0 l}) /\
            {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P} =
            {P | prime_ideal (ring_of_integers l) P /\ ~(P = {ring_0 l}) /\
                 ideal_generated (ring_of_integers l) (IMAGE h p) SUBSET P}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
    PRIME_IDEAL_IMP_PSUBSET) THEN
  ASM_REWRITE_TAC[PSUBSET] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    RING_OF_INTEGERS_IDEAL_EXTENSION) THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL] THEN STRIP_TAC THEN
  SUBGOAL_THEN `IMAGE (h:A->B) p SUBSET ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
      RING_HOMOMORPHISM_RING_OF_INTEGERS) THEN
    ASM_REWRITE_TAC[ring_homomorphism] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `P:B->bool` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_CASES_TAC `prime_ideal (ring_of_integers l) (P:B->bool)` THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL_EQ; PRIME_IMP_RING_IDEAL;
               SET_RULE `(s:B->bool) SUBSET t ==> t INTER s = s`] THEN
  ASM_CASES_TAC `P = {ring_0 l:B}` THEN ASM_REWRITE_TAC[] THEN
  DISCH_TAC THEN
  UNDISCH_TAC `~(ideal_generated (ring_of_integers l) (IMAGE (h:A->B) p) =
                 {ring_0 l})` THEN
  REWRITE_TAC[] THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPEC `ring_of_integers l:B ring` RING_IDEAL_0) THEN
    REWRITE_TAC[RING_OF_INTEGERS];
    MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                   `ideal_generated (ring_of_integers l) (IMAGE (h:A->B) p)`]
      IN_RING_IDEAL_0) THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; RING_OF_INTEGERS] THEN
    SET_TAC[]]);;

