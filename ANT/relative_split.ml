              RING_OF_INT_IN_SUBFIELD_GENERATED] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN SET_TAC[]);;

(* The ring of integers of the rational field (the prime subfield of the     *)
(* reals) is the integers (RING_OF_INTEGERS_RATIONAL_FIELD).                 *)
