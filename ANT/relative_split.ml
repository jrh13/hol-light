(* The absolute towers: the case Q_k -> k -> l, for Q_k the prime subfield   *)
(* of k, of NUMBER_FIELD_RAMIFICATION_INDEX_TOWER and                        *)
(* NUMBER_FIELD_RESIDUE_DEGREE_TOWER, by RAMIFICATION_INDEX_PRIME_SUBFIELD   *)
(* and RESIDUE_DEGREE_PRIME_SUBFIELD (h maps the integers of Q_k to the      *)
(* integers of l).                                                           *)

let NUMBER_FIELD_RAMIFICATION_INDEX_TOWER_Q = prove
 (`!k:A ring l:B ring h p P.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P
        ==> ramification_index (integer_ring,ring_of_integers l)
              (ring_of_int l) P =
            ramification_index
              (ring_of_integers k,ring_of_integers l) h P *
            ramification_index (integer_ring,ring_of_integers k)
              (ring_of_int k) p`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`subfield_generated k {ring_0 k}:A ring`; `k:A ring`;
                 `l:B ring`; `I:A->A`; `h:A->B`; `p:A->bool`; `P:B->bool`]
    NUMBER_FIELD_RAMIFICATION_INDEX_TOWER) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
               I_O_ID; RAMIFICATION_INDEX_PRIME_SUBFIELD;
               PRIME_IMP_RING_IDEAL] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_HOMOMORPHISM_RING_OF_INT) THEN
  ASM_SIMP_TAC[ramification_index; RING_OF_INTEGERS; INTEGER_RING;
               RING_OF_INTEGERS_PRIME_SUBFIELD_CARRIER] THEN
  REPEAT AP_TERM_TAC THEN ASM SET_TAC[]);;

