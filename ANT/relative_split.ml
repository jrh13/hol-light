     [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; DISCH_THEN SUBST1_TAC] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [free_basis]) THEN
  EXISTS_TAC `w:num->B` THEN REPEAT CONJ_TAC THENL
   [ASM_SIMP_TAC[];
    X_GEN_TAC `y:B` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `ring_coset s Q (y:B)` o check
     (fun th -> is_forall(concl th) &&
                is_imp(snd(dest_forall(concl th))) &&
                is_exists(rand(snd(dest_forall(concl th)))))) THEN
    ANTS_TAC THENL
     [MP_TAC(ISPECL [`s:B ring`; `Q:B->bool`] RING_HOMOMORPHISM_RING_COSET) THEN
      ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
      DISCH_THEN(X_CHOOSE_THEN `c:num->A->bool` STRIP_ASSUME_TAC)] THEN
    SUBGOAL_THEN
     `?a. !i. (a:num->A) i IN ring_carrier r /\
              (i < f ==> (c:num->A->bool) i = ring_coset r P (a i))`
    (X_CHOOSE_TAC `a:num->A`) THENL
     [REWRITE_TAC[GSYM SKOLEM_THM] THEN X_GEN_TAC `i:num` THEN
      ASM_CASES_TAC `(i:num) < f` THENL
       [SUBGOAL_THEN
         `(c:num->A->bool) i IN ring_carrier(quotient_ring r P)`
        MP_TAC THENL
         [FIRST_ASSUM(MATCH_MP_TAC o check (fun th ->
            is_forall(concl th) && free_in `c:num->A->bool` (concl th))) THEN
          ASM_REWRITE_TAC[];
          ALL_TAC] THEN
        SIMP_TAC[QUOTIENT_RING_CARRIER; ASSUME `ring_ideal r (P:A->bool)`;
                 IN_ELIM_THM] THEN
        ASM_REWRITE_TAC[] THEN MESON_TAC[];
        EXISTS_TAC `ring_0 r:A` THEN ASM_REWRITE_TAC[RING_0]];
      ALL_TAC] THEN
    EXISTS_TAC `a:num->A` THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`s:B ring`; `Q:B->bool`; `y:B`;
                   `ring_sum s {i | i < f}
                     (\i. ring_mul s ((g:A->B)((a:num->A) i)) (w i))`]
      RING_COSET_EQ) THEN
    ASM_REWRITE_TAC[RING_SUM] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    USE_THEN "sum" (MP_TAC o SPEC `a:num->A`) THEN
    ANTS_TAC THENL [ASM_MESON_TAC[]; DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN
    X_GEN_TAC `i:num` THEN DISCH_TAC THEN ASM_SIMP_TAC[];
    X_GEN_TAC `a:num->A` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `\i. ring_coset r P ((a:num->A) i)` o check
     (fun th -> is_forall(concl th) &&
                is_imp(snd(dest_forall(concl th))) &&
                is_forall(rand(snd(dest_forall(concl th)))))) THEN
    USE_THEN "sum" (fun th -> REWRITE_TAC[MATCH_MP th
     (ASSUME `!i. (a:num->A) i IN ring_carrier r`)]) THEN
    ASM_SIMP_TAC[QUOTIENT_RING_0; RING_COSET_EQ_IDEAL; RING_SUM] THEN
    ANTS_TAC THENL
     [X_GEN_TAC `i:num` THEN DISCH_TAC THEN
      MP_TAC(ISPECL [`r:A ring`; `P:A->bool`] RING_HOMOMORPHISM_RING_COSET) THEN
      ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
      ASM_SIMP_TAC[]]]);;

(* The t-adic digits modulo Q^m: if the combinations of the w_i with         *)
(* coefficients from g represent every residue class modulo Q, every y in s  *)
(* is congruent modulo Q^m to a sum of t^j times such combinations over j <  *)
(* m.                                                                        *)
let DEDEKIND_UNIFORMIZER_DIGITS_SPAN = prove
 (`!r s (g:A->B) Q t f (w:num->B).
        dedekind_domain s /\ prime_ideal s Q /\ ~(Q = {ring_0 s}) /\
        t IN Q /\ ~(t IN ideal_pow s Q 2) /\
        (!y. y IN ring_carrier s
             ==> ?a. (!i. a i IN ring_carrier r) /\
                     ring_sub s y
                      (ring_sum s {i | i < f} (\i. ring_mul s (g(a i)) (w i)))
                     IN Q)
        ==> !m y. y IN ring_carrier s
                  ==> ?a. (!i j. a i j IN ring_carrier r) /\
                          ring_sub s y
                           (ring_sum s {j | j < m}
                             (\j. ring_mul s (ring_pow s t j)
                                   (ring_sum s {i | i < f}
                                     (\i. ring_mul s (g(a i j)) (w i)))))
                          IN ideal_pow s Q m`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN POP_ASSUM(LABEL_TAC "span") THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(t:B) IN ring_carrier s` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`s:B ring`; `Q:B->bool`; `t:B`]
    DEDEKIND_UNIFORMIZER_CRITERION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(LABEL_TAC "tlift" o CONJUNCT1) THEN
  INDUCT_TAC THENL
   [REPEAT STRIP_TAC THEN EXISTS_TAC `\i:num j:num. ring_0 r:A` THEN
    REWRITE_TAC[RING_0; IDEAL_POW_0; LT; EMPTY_GSPEC; RING_SUM_CLAUSES] THEN
    ASM_SIMP_TAC[RING_SUB_RZERO];
    POP_ASSUM(LABEL_TAC "ih")] THEN
  X_GEN_TAC `y:B` THEN DISCH_TAC THEN
  REMOVE_THEN "ih" (MP_TAC o C MATCH_MP (ASSUME `(y:B) IN ring_carrier s`) o
    SPEC `y:B`) THEN
  DISCH_THEN(X_CHOOSE_THEN `a:num->num->A` STRIP_ASSUME_TAC) THEN
  ABBREV_TAC
   `sm = ring_sum s {j:num | j < m}
          (\j. ring_mul s (ring_pow s t j)
                (ring_sum s {i:num | i < f}
                  (\i. ring_mul s ((g:A->B)((a:num->num->A) i j))
                                  (w i))))` THEN
  USE_THEN "tlift" (MP_TAC o C MATCH_MP
   (ASSUME `ring_sub s (y:B) sm IN ideal_pow s Q m`) o SPECL
   [`m:num`; `1:num`; `ring_sub s (y:B) sm`]) THEN
  DISCH_THEN(X_CHOOSE_THEN `b:B` STRIP_ASSUME_TAC) THEN
  USE_THEN "span" (MP_TAC o C MATCH_MP (ASSUME `(b:B) IN ring_carrier s`) o
    SPEC `b:B`) THEN
  DISCH_THEN(X_CHOOSE_THEN `c:num->A` STRIP_ASSUME_TAC) THEN
  ABBREV_TAC
   `tc = ring_sum s {i:num | i < f}
          (\i. ring_mul s ((g:A->B)((c:num->A) i)) (w i))` THEN
  SUBGOAL_THEN `(sm:B) IN ring_carrier s /\ (tc:B) IN ring_carrier s`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["sm"; "tc"] THEN REWRITE_TAC[RING_SUM];
    ALL_TAC] THEN
  EXISTS_TAC `\i j:num. if j = m then (c:num->A) i
                        else (a:num->num->A) i j` THEN
  CONJ_TAC THENL
   [REPEAT GEN_TAC THEN REWRITE_TAC[] THEN COND_CASES_TAC THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `{j:num | j < SUC m} = m INSERT {j | j < m}`
  SUBST1_TAC THENL
   [REWRITE_TAC[EXTENSION; IN_INSERT; IN_ELIM_THM] THEN ARITH_TAC;
    ALL_TAC] THEN
  ASM_SIMP_TAC[RING_SUM_CLAUSES; FINITE_NUMSEG_LT; IN_ELIM_THM; LT_REFL;
               RING_MUL; RING_POW; RING_SUM] THEN
  SUBGOAL_THEN
   `ring_sum s {j:num | j < m}
     (\j. ring_mul s (ring_pow s t j)
           (ring_sum s {i:num | i < f}
             (\i. ring_mul s ((g:A->B)
                    (if j = m then (c:num->A) i
                     else (a:num->num->A) i j)) (w i)))) = sm`
  SUBST1_TAC THENL
   [EXPAND_TAC "sm" THEN
    MATCH_MP_TAC RING_SUM_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN
    X_GEN_TAC `j:num` THEN DISCH_TAC THEN
    ASM_SIMP_TAC[ARITH_RULE `j < m ==> ~(j = m:num)`];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `ring_sub s (y:B) (ring_add s (ring_mul s (ring_pow s t m) tc) sm) =
    ring_add s (ring_sub s (ring_sub s y sm) (ring_mul s (ring_pow s t m) b))
               (ring_mul s (ring_pow s (t:B) m) (ring_sub s (b:B) tc))`
  SUBST1_TAC THENL
   [SUBGOAL_THEN
     `(y:B) IN ring_carrier s /\ (b:B) IN ring_carrier s /\
      ring_pow s (t:B) m IN ring_carrier s /\ (sm:B) IN ring_carrier s /\
      (tc:B) IN ring_carrier s`
    MP_TAC THENL [ASM_SIMP_TAC[RING_POW]; ALL_TAC] THEN
    REPEAT(FIRST_X_ASSUM(K ALL_TAC o check (is_eq o concl))) THEN
    REPEAT STRIP_TAC THEN RING_TAC;
    ALL_TAC] THEN
  MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW; ADD1] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; RING_POW_IN_IDEAL_POW; IDEAL_POW_1]);;

(* If the w_i are independent modulo Q (coefficients in P) and g(P) lies in  *)
(* Q^m, a sum of t^j times combinations of the w_i over j < m lies in Q^m    *)
(* only if all its coefficients lie in P.                                    *)
let DEDEKIND_UNIFORMIZER_DIGITS_INDEPENDENT = prove
 (`!r s (g:A->B) Q P t f (w:num->B) m.
        dedekind_domain s /\ prime_ideal s Q /\ ~(Q = {ring_0 s}) /\
        t IN Q /\ ~(t IN ideal_pow s Q 2) /\
        (!i. i < f ==> w i IN ring_carrier s) /\
        (!a. (!i. a i IN ring_carrier r) /\
             ring_sum s {i | i < f} (\i. ring_mul s (g(a i)) (w i)) IN Q
             ==> !i. i < f ==> a i IN P) /\
        IMAGE g P SUBSET ideal_pow s Q m
        ==> !a. (!i j. a i j IN ring_carrier r) /\
                ring_sum s {j | j < m}
                 (\j. ring_mul s (ring_pow s t j)
                       (ring_sum s {i | i < f}
                         (\i. ring_mul s (g(a i j)) (w i))))
                IN ideal_pow s Q m
                ==> !i j. i < f /\ j < m ==> a i j IN P`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(LABEL_TAC "image" o check (is_binary "SUBSET" o concl)) THEN
  FIRST_X_ASSUM(LABEL_TAC "indep" o check (is_forall o concl)) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(t:B) IN ring_carrier s` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`s:B ring`; `Q:B->bool`; `t:B`]
    DEDEKIND_UNIFORMIZER_CRITERION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(LABEL_TAC "tcancel" o CONJUNCT2) THEN
  SUBGOAL_THEN
   `!(a:num->num->A) j.
        (!i. i < f ==> a i j IN P)
        ==> ring_sum s {i:num | i < f}
             (\i. ring_mul s ((g:A->B)(a i j)) (w i)) IN
            ideal_pow s Q m`
  (LABEL_TAC "sin") THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_POW; IN_ELIM_THM] THEN
    X_GEN_TAC `i:num` THEN DISCH_TAC THEN
    MATCH_MP_TAC IN_RING_IDEAL_RMUL THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW] THEN
    USE_THEN "image" (MATCH_MP_TAC o REWRITE_RULE[SUBSET; FORALL_IN_IMAGE]) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!n. n <= m
        ==> !a. (!i j. (a:num->num->A) i j IN ring_carrier r) /\
                ring_sum s {j:num | j < n}
                 (\j. ring_mul s (ring_pow s t j)
                       (ring_sum s {i:num | i < f}
                         (\i. ring_mul s ((g:A->B)(a i j)) (w i))))
                IN ideal_pow s Q n
                ==> !i j. i < f /\ j < n ==> a i j IN P`
  (fun th -> MESON_TAC[th; LE_REFL]) THEN
  INDUCT_TAC THENL [REWRITE_TAC[LT]; ALL_TAC] THEN
  DISCH_TAC THEN X_GEN_TAC `a:num->num->A` THEN STRIP_TAC THEN
  ABBREV_TAC
   `sm = ring_sum s {j:num | j < n}
          (\j. ring_mul s (ring_pow s t j)
                (ring_sum s {i:num | i < f}
                  (\i. ring_mul s ((g:A->B)((a:num->num->A) i j))
                                  (w i))))` THEN
  ABBREV_TAC
   `tm = ring_sum s {i:num | i < f}
          (\i. ring_mul s ((g:A->B)((a:num->num->A) i n)) (w i))` THEN
  SUBGOAL_THEN `(sm:B) IN ring_carrier s /\ (tm:B) IN ring_carrier s`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["sm"; "tm"] THEN REWRITE_TAC[RING_SUM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_add s (ring_mul s (ring_pow s t n) tm) sm IN
    ideal_pow s (Q:B->bool) (SUC n)`
  ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o check (fun th ->
      try fst(dest_const(fst(strip_comb(rand(concl th))))) = "ideal_pow" &&
          is_comb(lhand(concl th))
      with Failure _ -> false)) THEN
    SUBGOAL_THEN `{j:num | j < SUC n} = n INSERT {j | j < n}`
    SUBST1_TAC THENL
     [REWRITE_TAC[EXTENSION; IN_INSERT; IN_ELIM_THM] THEN ARITH_TAC;
      ALL_TAC] THEN
    ASM_SIMP_TAC[RING_SUM_CLAUSES; FINITE_NUMSEG_LT; IN_ELIM_THM; LT_REFL;
                 RING_MUL; RING_POW; RING_SUM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul s (ring_pow s t n) (tm:B) IN ideal_pow s (Q:B->bool) n`
  ASSUME_TAC THENL
   [MATCH_MP_TAC IN_RING_IDEAL_RMUL THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; RING_POW_IN_IDEAL_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN `(sm:B) IN ideal_pow s Q n` ASSUME_TAC THENL
   [SUBGOAL_THEN
     `sm = ring_sub s (ring_add s (ring_mul s (ring_pow s t n) tm) sm)
                      (ring_mul s (ring_pow s (t:B) n) tm)`
    SUBST1_TAC THENL
     [SUBGOAL_THEN `ring_pow s (t:B) n IN ring_carrier s` MP_TAC THENL
       [ASM_SIMP_TAC[RING_POW]; ALL_TAC] THEN
      REPEAT(FIRST_X_ASSUM(K ALL_TAC o check (is_eq o concl))) THEN
      REPEAT STRIP_TAC THEN RING_TAC;
      ALL_TAC] THEN
    MATCH_MP_TAC IN_RING_IDEAL_SUB THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN
    MATCH_MP_TAC(SET_RULE `!s t x:B. s SUBSET t /\ x IN s ==> x IN t`) THEN
    EXISTS_TAC `ideal_pow s (Q:B->bool) (SUC n)` THEN
    ASM_SIMP_TAC[IDEAL_POW_SUC_SUBSET];
    ALL_TAC] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `a:num->num->A` o
    C MATCH_MP (MP (ARITH_RULE `SUC n <= m ==> n <= m`)
                   (ASSUME `SUC n <= m`)) o check (is_imp o concl)) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN `(sm:B) IN ideal_pow s Q (SUC n)` ASSUME_TAC THENL
   [EXPAND_TAC "sm" THEN MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_POW; IN_ELIM_THM] THEN
    X_GEN_TAC `j:num` THEN DISCH_TAC THEN
    MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; RING_POW] THEN
    MATCH_MP_TAC(SET_RULE `!s t x:B. s SUBSET t /\ x IN s ==> x IN t`) THEN
    EXISTS_TAC `ideal_pow s (Q:B->bool) m` THEN CONJ_TAC THENL
     [MATCH_MP_TAC IDEAL_POW_ANTIMONO THEN
      ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET];
      USE_THEN "sin" MATCH_MP_TAC THEN ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul s (ring_pow s t n) (tm:B) IN ideal_pow s (Q:B->bool) (SUC n)`
  MP_TAC THENL
   [SUBGOAL_THEN
     `ring_mul s (ring_pow s t n) tm =
      ring_sub s (ring_add s (ring_mul s (ring_pow s (t:B) n) tm) sm)
                 (sm:B)`
    SUBST1_TAC THENL
     [SUBGOAL_THEN `ring_pow s (t:B) n IN ring_carrier s` MP_TAC THENL
       [ASM_SIMP_TAC[RING_POW]; ALL_TAC] THEN
      REPEAT(FIRST_X_ASSUM(K ALL_TAC o check (is_eq o concl))) THEN
      REPEAT STRIP_TAC THEN RING_TAC;
      ALL_TAC] THEN
    MATCH_MP_TAC IN_RING_IDEAL_SUB THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW];
    ALL_TAC] THEN
  REWRITE_TAC[ADD1] THEN DISCH_TAC THEN
  SUBGOAL_THEN `(tm:B) IN Q` ASSUME_TAC THENL
   [FIRST_ASSUM(SUBST1_TAC o SYM o MATCH_MP IDEAL_POW_1) THEN
    USE_THEN "tcancel" MATCH_MP_TAC THEN EXISTS_TAC `n:num` THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  REMOVE_THEN "indep" (MP_TAC o BETA_RULE o SPEC `\i. (a:num->num->A) i n`) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `j = n:num` THEN ASM_SIMP_TAC[] THEN
  SUBGOAL_THEN `j < n:num` (fun th -> ASM_SIMP_TAC[th]) THEN ASM_ARITH_TAC);;

(* The digit map E is semilinear along g: E(a + u c) = E(a) + g(u) E(c).     *)
let DEDEKIND_EXTENSION_DIGITS_LINEAR = prove
 (`!r s (g:A->B) e (f:num) t (w:num->B) E.
        ring_homomorphism(r,s) g /\ t IN ring_carrier s /\
        (!i. i < f ==> w i IN ring_carrier s) /\
        (!a. E a = ring_sum s {j | j < e}
                    (\j. ring_mul s (ring_pow s t j)
                          (ring_sum s {i | i < f}
                            (\i. ring_mul s (g(a i j)) (w i)))))
        ==> !a c u. (!i j. a i j IN ring_carrier r) /\
                    (!i j. c i j IN ring_carrier r) /\ u IN ring_carrier r
                    ==> E (\i j. ring_add r (a i j) (ring_mul r u (c i j))) =
                        ring_add s (E a) (ring_mul s (g u) (E c))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MAP_EVERY X_GEN_TAC [`a:num->num->A`; `c:num->num->A`; `u:A`] THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `!x. x IN ring_carrier r ==> (g:A->B) x IN ring_carrier s`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!k (x:num->B) y z.
        FINITE k /\ (!j. j IN k ==> x j IN ring_carrier s /\
                                    y j IN ring_carrier s) /\
        z IN ring_carrier s
        ==> ring_sum s k (\j. ring_add s (x j) (ring_mul s z (y j))) =
            ring_add s (ring_sum s k x) (ring_mul s z (ring_sum s k y))`
  (LABEL_TAC "slin") THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`s:B ring`; `x:num->B`;
                   `\j:num. ring_mul s z ((y:num->B) j)`;
                   `k:num->bool`] RING_SUM_ADD) THEN
    ASM_SIMP_TAC[RING_MUL] THEN DISCH_THEN SUBST1_TAC THEN
    AP_TERM_TAC THEN MATCH_MP_TAC RING_SUM_LMUL THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `ring_sum s {j | j < e}
     (\j. ring_add s
           (ring_mul s (ring_pow s t j)
             (ring_sum s {i | i < f}
               (\i. ring_mul s ((g:A->B)((a:num->num->A) i j)) (w i))))
           (ring_mul s (g u)
             (ring_mul s (ring_pow s t j)
               (ring_sum s {i | i < f}
                 (\i. ring_mul s (g((c:num->num->A) i j)) (w i))))))` THEN
  CONJ_TAC THENL
   [ALL_TAC;
    USE_THEN "slin" MATCH_MP_TAC THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; RING_MUL; RING_POW; RING_SUM]] THEN
  MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `j:num` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
  TRANS_TAC EQ_TRANS
   `ring_mul s (ring_pow s t j)
     (ring_add s
       (ring_sum s {i | i < f}
         (\i. ring_mul s ((g:A->B)((a:num->num->A) i j)) (w i)))
       (ring_mul s (g u)
         (ring_sum s {i | i < f}
           (\i. ring_mul s (g((c:num->num->A) i j)) (w i)))))` THEN
  CONJ_TAC THENL
   [AP_TERM_TAC THEN
    TRANS_TAC EQ_TRANS
     `ring_sum s {i | i < f}
       (\i. ring_add s (ring_mul s ((g:A->B)((a:num->num->A) i j)) (w i))
                       (ring_mul s (g u)
                         (ring_mul s (g((c:num->num->A) i j)) (w i))))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
