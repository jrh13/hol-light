                  RING_OF_NUM_SUBFIELD_GENERATED; SUBFIELD_GENERATED];
      ALL_TAC] THEN
    MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
     [ALL_TAC;
      MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
      ASM_SIMP_TAC[SING_SUBSET; PRIME_IMP_RING_IDEAL]] THEN
    MP_TAC(ISPECL [`O:A ring`; `P:A->bool`; `p:num`]
      RING_OF_INT_IN_PRIME_IDEAL) THEN
    ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
    REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `?n. x = ring_of_int k n:A` STRIP_ASSUME_TAC THENL
     [MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_PRIME_SUBFIELD_CARRIER) THEN
      ASM_REWRITE_TAC[] THEN
      FIRST_ASSUM(MP_TAC o MATCH_MP PRIME_IDEAL_IMP_SUBSET) THEN
      ASM SET_TAC[];
      ALL_TAC] THEN
    UNDISCH_TAC `(x:A) IN P` THEN ASM_REWRITE_TAC[int_divides] THEN
    DISCH_THEN(X_CHOOSE_THEN `m:int` SUBST1_TAC) THEN
    MATCH_MP_TAC IN_IDEAL_GENERATED_SING THEN
    REWRITE_TAC[ring_divides; RING_OF_INT_MUL; RING_OF_INT_OF_NUM] THEN
    ASM_MESON_TAC[RING_OF_INT; RING_OF_NUM; RING_MUL]) in
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_PRIME_SUBFIELD) THEN
