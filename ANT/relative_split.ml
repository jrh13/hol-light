  MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN CONJ_TAC THENL
   [FIRST_ASSUM ACCEPT_TAC;
    MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN
    REPEAT CONJ_TAC THEN TRY(FIRST_ASSUM ACCEPT_TAC) THEN
    ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET]]);;

(* Independence modulo P^n, by induction on n: with all a_ij in P^n write a  *)
(* = c + p^n b with all c_ij in P^(n + 1); then g(p^n) E(b) lies in Q^(e n + *)
(* e), so E(b) lies in Q^e and all b_ij lie in P.                            *)
let DEDEKIND_EXTENSION_DIGITS_INDEPENDENT = prove
 (`!r s (g:A->B) Q P e (f:num) t p (w:num->B) E.
