(* A nonzero polynomial over the prime subfield with a root of order n has   *)
(* degree at least phi(n); hence so has a divisor of the cyclotomic          *)
(* polynomial with a root in a number field extension, and every divisor of  *)
(* positive degree over the prime subfield (the root is in the prime         *)
(* subfield or in a simple extension, KRONECKER_SIMPLE_FIELD_EXTENSION).     *)
let PHI_LE_POLY_DEG_PRIMITIVE_ROOT = prove
 (`!(k:A ring) z n p.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        p IN ring_carrier(poly_ring (subfield_generated k {ring_0 k}) (:1)) /\
        ~(p = poly_0 k) /\ poly_eval k p z = ring_0 k
        ==> phi n <= poly_deg k p`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `n = 0` THEN ASM_REWRITE_TAC[PHI_0; LE_0] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`subfield_generated k {ring_0 k:A}`; `n:num`]
    CYCLOTOMIC_POLY_DEG) THEN
  ASM_SIMP_TAC[POLY_DEG_SUBFIELD_GENERATED; SUBFIELD_GENERATED;
               FIELD_NONTRIVIAL] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `z:A`; `p:(1->num)->A`] MINIMAL_POLYNOMIAL_DEG_LE) THEN
  ASM_SIMP_TAC[CYCLOTOMIC_POLY_MINIMAL_POLYNOMIAL;
               FIELD_EXTENSION_SUBFIELD_GENERATED;
               NUMBER_FIELD_ALGEBRAIC; POLY_DEG_SUBFIELD_GENERATED] THEN
  DISCH_THEN MATCH_MP_TAC THEN CONJ_TAC THENL
   [UNDISCH_TAC `~(p:(1->num)->A = poly_0 k)` THEN
    REWRITE_TAC[poly_0; poly_const; SUBFIELD_GENERATED];
    ASM_SIMP_TAC[POLY_EXTEND_EVALUATE; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
                 I_O_ID; GSYM poly_eval]]);;

let PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR_ROOT = prove
 (`!(r:A ring) (l:B ring) h n a w.
        field r /\ number_field l /\
        ring_monomorphism(subfield_generated r {ring_0 r},l) h /\
        ring_divides (poly_ring (subfield_generated r {ring_0 r}) (:1)) a
          (cyclotomic_poly (subfield_generated r {ring_0 r}) n) /\
        w IN ring_carrier l /\ poly_eval l (h o a) w = ring_0 l
        ==> phi n <= poly_deg (subfield_generated r {ring_0 r}) a`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC `Q = subfield_generated r {ring_0 r:A}` THEN STRIP_TAC THEN
  ASM_CASES_TAC `n = 0` THEN ASM_REWRITE_TAC[PHI_0; LE_0] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  FIRST_ASSUM(ASSUME_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [number_field]) THEN
  SUBGOAL_THEN `field(Q:A ring) /\ subfield_generated Q {ring_0 Q} = Q`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "Q" THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; PRIME_SUBFIELD_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [ring_divides]) THEN
  REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    (X_CHOOSE_THEN `b:(1->num)->A` STRIP_ASSUME_TAC))) THEN
  SUBGOAL_THEN `~(a:(1->num)->A = poly_0 Q)` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    MP_TAC(ISPECL [`Q:A ring`; `cyclotomic_poly Q n:(1->num)->A`]
      MONIC_IMP_NONZERO) THEN
    ASM_SIMP_TAC[CYCLOTOMIC_POLY_MONIC; FIELD_IMP_NONTRIVIAL_RING;
                 RING_POLYNOMIAL; POLY_MUL_0];
    ALL_TAC] THEN
  FIRST_ASSUM(fun th ->
   let hom t = MATCH_MP (REWRITE_RULE[IMP_CONJ] t) th in
   MP_TAC(ISPECL [`l:B ring`; `w:B`; `n:num`; `(h:A->B) o (a:(1->num)->A)`]
     PHI_LE_POLY_DEG_PRIMITIVE_ROOT) THEN
   ASM_SIMP_TAC[RING_POLYNOMIAL; hom POLY_DEG_MONOMORPHIC_IMAGE;
                hom POLY_EQ_0_MONOMORPHIC_IMAGE] THEN
   DISCH_THEN MATCH_MP_TAC) THEN
  CONJ_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`; `w:B`; `n:num`] CYCLOTOMIC_POLY_ROOT_EQ) THEN
    ASM_SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN; NUMBER_FIELD_IMP_FIELD;
                 RING_OF_NUM_EQ_0; DIVIDES_ZERO] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    FIRST_ASSUM(fun th ->
      let hom t = MATCH_MP (REWRITE_RULE[IMP_CONJ] t) th in
      REWRITE_TAC[GSYM(MATCH_MP CYCLOTOMIC_POLY_HOMOMORPHIC_IMAGE th)] THEN
      ASM_SIMP_TAC[hom POLY_COMPOSE_HOMOMORPHISM_MUL; POLY_EVAL_MUL;
                   RING_POLYNOMIAL_IMP_POWERSERIES; RING_POLYNOMIAL;
                   hom IN_RING_POLYNOMIAL_CARRIER_COMPOSE; RING_MUL_LZERO;
                   POLY_EVAL]);
    MATCH_MP_TAC IN_RING_POLYNOMIAL_CARRIER_COMPOSE THEN
    EXISTS_TAC `Q:A ring` THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`Q:A ring`; `l:B ring`;
                   `ring_carrier(subfield_generated l {ring_0 l:B})`;
                   `h:A->B`] RING_HOMOMORPHISM_INTO_SUBRING) THEN
    REWRITE_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED] THEN
    DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`Q:A ring`; `l:B ring`; `h:A->B`]
      PRIME_SUBFIELD_MONOMORPHIC_IMAGE) THEN
    ASM_SIMP_TAC[SUBSET_REFL]]);;

let PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR = prove
 (`!(r:A ring) n a.
        field r /\ ring_char r = 0 /\
        ~(poly_deg (subfield_generated r {ring_0 r}) a = 0) /\
        ring_divides (poly_ring (subfield_generated r {ring_0 r}) (:1)) a
          (cyclotomic_poly (subfield_generated r {ring_0 r}) n)
        ==> phi n <= poly_deg (subfield_generated r {ring_0 r}) a`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC `Q = subfield_generated r {ring_0 r:A}` THEN STRIP_TAC THEN
  ASM_CASES_TAC `n = 0` THEN ASM_REWRITE_TAC[PHI_0; LE_0] THEN
  SUBGOAL_THEN
   `field(Q:A ring) /\ number_field Q /\ ~(a = poly_0 Q) /\
    a IN ring_carrier(poly_ring Q (:1))`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[FIELD_SUBFIELD_GENERATED; NUMBER_FIELD_PRIME_SUBFIELD;
                  POLY_DEG_0; RING_DIVIDES_IN_CARRIER];
    ALL_TAC] THEN
  ASM_CASES_TAC `?x. x IN ring_carrier Q /\ poly_eval Q a x = ring_0(Q:A ring)`
  THENL
   [FIRST_X_ASSUM(X_CHOOSE_THEN `x:A` STRIP_ASSUME_TAC) THEN
    MP_TAC(ISPECL [`r:A ring`; `Q:A ring`; `I:A->A`; `n:num`;
                   `a:(1->num)->A`; `x:A`]
      PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR_ROOT) THEN
    ASM_REWRITE_TAC[I_O_ID; RING_MONOMORPHISM_I];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`Q:A ring`; `a:(1->num)->A`]
    KRONECKER_SIMPLE_FIELD_EXTENSION) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`l:(((1->num)->A)->bool)ring`;
                       `h:A->((1->num)->A)->bool`;
                       `w:((1->num)->A)->bool`] THEN
  STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `l:(((1->num)->A)->bool)ring`;
                 `h:A->((1->num)->A)->bool`; `n:num`; `a:(1->num)->A`;
                 `w:((1->num)->A)->bool`]
    PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR_ROOT) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN
  MATCH_MP_TAC NUMBER_FIELD_FINITE_EXTENSION THEN
  MAP_EVERY EXISTS_TAC [`Q:A ring`; `h:A->((1->num)->A)->bool`] THEN
  MP_TAC(ISPECL [`h:A->((1->num)->A)->bool`; `Q:A ring`;
                 `l:(((1->num)->A)->bool)ring`; `w:((1->num)->A)->bool`]
    FINITE_SIMPLE_ALGEBRAIC_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN
  ASM_REWRITE_TAC[algebraic_over] THEN EXISTS_TAC `a:(1->num)->A` THEN
  ASM_SIMP_TAC[POLY_EXTEND_EVALUATE; GSYM poly_eval; POLY_RING_CLAUSES;
               RING_MONOMORPHISM_IMP_HOMOMORPHISM]);;

let CYCLOTOMIC_POLY_IRREDUCIBLE_PRIME_SUBFIELD = prove
 (`!(r:A ring) n.
        field r /\ ring_char r = 0 /\ ~(n = 0)
        ==> ring_irreducible (poly_ring (subfield_generated r {ring_0 r}) (:1))
              (cyclotomic_poly (subfield_generated r {ring_0 r}) n)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `n:num`] PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC `Q = subfield_generated r {ring_0 r:A}` THEN DISCH_TAC THEN
  SUBGOAL_THEN `field(Q:A ring)` ASSUME_TAC THENL
   [EXPAND_TAC "Q" THEN ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED]; ALL_TAC] THEN
  SUBGOAL_THEN `poly_deg (Q:A ring) (cyclotomic_poly Q n) = phi n`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[CYCLOTOMIC_POLY_DEG; FIELD_NONTRIVIAL]; ALL_TAC] THEN
  SUBGOAL_THEN `~(cyclotomic_poly Q n = poly_0(Q:A ring))` ASSUME_TAC THENL
   [MATCH_MP_TAC MONIC_IMP_NONZERO THEN
    ASM_SIMP_TAC[CYCLOTOMIC_POLY_MONIC; FIELD_IMP_NONTRIVIAL_RING;
                 RING_POLYNOMIAL; CYCLOTOMIC_POLY_IN_CARRIER];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[ring_irreducible; CYCLOTOMIC_POLY_IN_CARRIER;
                  CONJUNCT2 POLY_RING_CLAUSES] THEN
  CONJ_TAC THENL
   [DISCH_THEN(MP_TAC o MATCH_MP POLY_DEG_UNIT o
      CONJ (MATCH_MP FIELD_IMP_INTEGRAL_DOMAIN (ASSUME `field(Q:A ring)`))) THEN
    ASM_REWRITE_TAC[PHI_EQ_0];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`a:(1->num)->A`; `b:(1->num)->A`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(a:(1->num)->A = poly_0 Q) /\ ~(b:(1->num)->A = poly_0 Q)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `~(cyclotomic_poly Q n = poly_0(Q:A ring))` THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
    ASM_SIMP_TAC[POLY_MUL_0; RING_POLYNOMIAL];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`Q:A ring`; `a:(1->num)->A`; `b:(1->num)->A`]
    POLY_DEG_MUL) THEN
  ASM_SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN; RING_POLYNOMIAL] THEN
  DISCH_TAC THEN
  MP_TAC(ISPECL [`Q:A ring`; `b:(1->num)->A`] FIELD_POLY_DEG_EQ_0) THEN
  MP_TAC(ISPECL [`Q:A ring`; `a:(1->num)->A`] FIELD_POLY_DEG_EQ_0) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_CASES_TAC `poly_deg Q (a:(1->num)->A) = 0` THEN ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `a:(1->num)->A`) THEN ANTS_TAC THENL
   [ASM_REWRITE_TAC[ring_divides; CYCLOTOMIC_POLY_IN_CARRIER] THEN
    EXISTS_TAC `b:(1->num)->A` THEN ASM_REWRITE_TAC[POLY_RING_CLAUSES];
    ASM_ARITH_TAC]);;

(* Over Z: map a factorization to the prime subfield of real_ring.           *)
let CYCLOTOMIC_POLY_IRREDUCIBLE = prove
 (`!n. ~(n = 0)
       ==> ring_irreducible (poly_ring integer_ring (:1))
             (cyclotomic_poly integer_ring n)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`real_ring`; `n:num`]
    CYCLOTOMIC_POLY_IRREDUCIBLE_PRIME_SUBFIELD) THEN
  ASM_REWRITE_TAC[FIELD_REAL_RING; REAL_RING_CHAR] THEN
  ABBREV_TAC `Q = subfield_generated real_ring {ring_0 real_ring}` THEN
  SUBGOAL_THEN
   `field(Q:real ring) /\ ring_monomorphism(integer_ring,Q) (ring_of_int Q)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "Q" THEN
    SIMP_TAC[FIELD_SUBFIELD_GENERATED; FIELD_REAL_RING; REAL_RING_CHAR;
             RING_MONOMORPHISM_INTEGER_RING_OF_INT;
             RING_CHAR_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  REWRITE_TAC[GSYM(MATCH_MP CYCLOTOMIC_POLY_HOMOMORPHIC_IMAGE
    (ISPEC `Q:real ring` RING_HOMOMORPHISM_INTEGER_RING_OF_INT))] THEN
  REWRITE_TAC[ring_irreducible; CYCLOTOMIC_POLY_IN_CARRIER;
              CONJUNCT2 POLY_RING_CLAUSES] THEN
  STRIP_TAC THEN REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC MONIC_IMP_NONZERO THEN
    REWRITE_TAC[CYCLOTOMIC_POLY_MONIC; RING_POLYNOMIAL;
                CYCLOTOMIC_POLY_IN_CARRIER; TRIVIAL_RING_10; INTEGER_RING] THEN
    INT_ARITH_TAC;
    DISCH_TAC THEN
    UNDISCH_TAC `~ring_unit (poly_ring (Q:real ring) (:1))
                  (ring_of_int Q o cyclotomic_poly integer_ring n)` THEN
    REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`poly_ring integer_ring (:1)`;
                   `poly_ring (Q:real ring) (:1)`;
                   `\p:(1->num)->int. ring_of_int (Q:real ring) o p`;
                   `cyclotomic_poly integer_ring n`]
      RING_UNIT_HOMOMORPHIC_IMAGE) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_POLY_RINGS];
    MAP_EVERY X_GEN_TAC [`a:(1->num)->int`; `b:(1->num)->int`] THEN
    STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPECL
     [`ring_of_int (Q:real ring) o (a:(1->num)->int)`;
      `ring_of_int (Q:real ring) o (b:(1->num)->int)`]) THEN
    FIRST_ASSUM(fun th ->
     let hom t = MATCH_MP (REWRITE_RULE[IMP_CONJ] t) th in
     ASM_SIMP_TAC[hom IN_RING_POLYNOMIAL_CARRIER_COMPOSE] THEN
     ANTS_TAC THENL
      [FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
       ASM_SIMP_TAC[hom POLY_COMPOSE_HOMOMORPHISM_MUL;
                    RING_POLYNOMIAL_IMP_POWERSERIES; RING_POLYNOMIAL];
       ALL_TAC]) THEN
    MATCH_MP_TAC MONO_OR THEN CONJ_TAC THEN DISCH_TAC THEN
    MATCH_MP_TAC RING_UNIT_POLY_DIVIDES_MONIC THEN
    EXISTS_TAC `cyclotomic_poly integer_ring n` THEN
    FIRST_X_ASSUM(MP_TAC o MATCH_MP POLY_DEG_UNIT o CONJ
      (MATCH_MP FIELD_IMP_INTEGRAL_DOMAIN (ASSUME `field(Q:real ring)`))) THEN
    FIRST_ASSUM(fun th -> ASM_SIMP_TAC[RING_POLYNOMIAL; MATCH_MP
      (REWRITE_RULE[IMP_CONJ] POLY_DEG_MONOMORPHIC_IMAGE) th]) THEN
    DISCH_TAC THEN
    ASM_REWRITE_TAC[CYCLOTOMIC_POLY_MONIC; ring_divides;
                    CYCLOTOMIC_POLY_IN_CARRIER; CONJUNCT2 POLY_RING_CLAUSES]
    THENL
     [EXISTS_TAC `b:(1->num)->int`; EXISTS_TAC `a:(1->num)->int`] THEN
    ASM_SIMP_TAC[POLY_MUL_SYM; RING_POLYNOMIAL_IMP_POWERSERIES;
                 RING_POLYNOMIAL]]);;

(* ------------------------------------------------------------------------- *)
(* The degree and the power basis of a cyclotomic field.                     *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_FIELD_DEGREE = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> extension_degree (subfield_generated k {ring_0 k},k) I = phi n`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `z:A`] EXTENSION_DEGREE_SIMPLE) THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`] SUBFIELD_GENERATED_SING_ALGEBRAIC) THEN
  ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED;
               NUMBER_FIELD_ALGEBRAIC; NUMBER_FIELD_IMP_FIELD] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[CYCLOTOMIC_POLY_MINIMAL_POLYNOMIAL; CYCLOTOMIC_POLY_DEG;
               SUBFIELD_GENERATED; FIELD_NONTRIVIAL; NUMBER_FIELD_IMP_FIELD]);;

(* The powers of z form a Q-basis: deg Phi_n = phi(n) = [k:Q]                *)
(* (NUMBER_FIELD_FREE_BASIS_POWERS).                                         *)
let CYCLOTOMIC_FIELD_FREE_BASIS = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> free_basis (subfield_generated k {ring_0 k},k) I (phi n)
                       (\i. ring_pow k z i)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`] NUMBER_FIELD_FREE_BASIS_POWERS) THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`] CYCLOTOMIC_FIELD_DEGREE) THEN
  ASM_SIMP_TAC[CYCLOTOMIC_POLY_MINIMAL_POLYNOMIAL; CYCLOTOMIC_POLY_DEG;
               SUBFIELD_GENERATED; FIELD_NONTRIVIAL; NUMBER_FIELD_IMP_FIELD]);;
