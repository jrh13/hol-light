      ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_ADD th;
                   MATCH_MP RING_HOMOMORPHISM_MUL th; RING_MUL;
                   RING_MUL_RZERO; RING_ADD_LZERO; POLY_EXTEND]);
    ALL_TAC] THEN
  SUBGOAL_THEN `s = ring_0(poly_ring integer_ring (:1))` SUBST_ALL_TAC THENL
   [FIRST_X_ASSUM(DISJ_CASES_THEN2 MP_TAC ACCEPT_TAC o
      check (is_disj o concl)) THEN
    ONCE_REWRITE_TAC[GSYM CONTRAPOS_THM] THEN
    REWRITE_TAC[NOT_LT; CONJUNCT2 POLY_RING_CLAUSES] THEN DISCH_TAC THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                   `z:A`;
                   `ring_of_int(subfield_generated k {ring_0 k:A}) o
                    (s:(1->num)->int)`]
      MINIMAL_POLYNOMIAL_DEG_LE) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED;
                   NUMBER_FIELD_ALGEBRAIC] THEN
      REPEAT CONJ_TAC THENL
       [MATCH_MP_TAC IN_RING_POLYNOMIAL_CARRIER_COMPOSE THEN
        EXISTS_TAC `integer_ring` THEN
        ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT];
        MP_TAC(ISPECL [`integer_ring`; `subfield_generated k {ring_0 k:A}`;
                       `ring_of_int(subfield_generated k {ring_0 k:A})`;
                       `s:(1->num)->int`] POLY_EQ_0_MONOMORPHIC_IMAGE) THEN
        ASM_REWRITE_TAC[RING_MONOMORPHISM_INTEGER_RING_OF_INT;
                        RING_CHAR_SUBFIELD_GENERATED; RING_POLYNOMIAL];
        SIMP_TAC[POLY_EXTEND_EVALUATE; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
                 I_O_ID; RING_OF_INT_SUBFIELD_GENERATED] THEN
        ASM_REWRITE_TAC[GSYM(MATCH_MP POLY_EXTEND_EVALUATE
