  ASM_SIMP_TAC[RING_ADD_RZERO; RING_MUL] THEN
  MATCH_MP_TAC RING_MUL_SYM THEN ASM_REWRITE_TAC[]);;

let CYCLOTOMIC_POLY_MINIMAL_POLYNOMIAL = prove
