      (ISPECL [`k:A ring`; `{ring_0 k:A}`]
        RING_HOMOMORPHISM_SUBFIELD_INCLUSION)] THEN
    ASM_REWRITE_TAC[MATCH_MP CYCLOTOMIC_POLY_HOMOMORPHIC_IMAGE
      (ISPECL [`k:A ring`; `{ring_0 k:A}`]
        RING_HOMOMORPHISM_SUBFIELD_INCLUSION); GSYM poly_eval];
    ASM_REWRITE_TAC[CYCLOTOMIC_POLY_DEG; SUBFIELD_GENERATED] THEN
    ASM_SIMP_TAC[FIELD_NONTRIVIAL] THEN ASM_ARITH_TAC]);;

