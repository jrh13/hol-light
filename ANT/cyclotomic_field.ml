(* Evaluations of integer polynomials commute with ring homomorphisms.       *)
let POLY_EXTEND_INTEGER_RING_HOMOMORPHIC_IMAGE = prove
 (`!(r:A ring) (s:B ring) f x p.
        ring_homomorphism(r,s) f /\ x IN ring_carrier r /\
        p IN ring_carrier(poly_ring integer_ring (:1))
        ==> f(poly_extend (integer_ring,r) (ring_of_int r) (\v. x) p) =
            poly_extend (integer_ring,s) (ring_of_int s) (\v. f x) p`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`integer_ring`; `r:A ring`; `s:B ring`;
                 `ring_of_int r:int->A`; `(:1)`; `\v:1. (x:A)`; `f:A->B`;
                 `p:(1->num)->int`] POLY_EXTEND_HOMOMORPHIC_IMAGE) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; SUBSET;
                  FORALL_IN_IMAGE] THEN
  DISCH_THEN SUBST1_TAC THEN AP_THM_TAC THEN BINOP_TAC THEN
  REWRITE_TAC[FUN_EQ_THM; o_THM] THEN
  ASM_MESON_TAC[RING_HOMOMORPHISM_RING_OF_INT]);;

let POLY_EXTEND_INTEGER_RING_VAR_POW_SUB_1 = prove
 (`!(r:A ring) x n.
        x IN ring_carrier r
        ==> poly_extend (integer_ring,r) (ring_of_int r) (\v. x)
              (poly_sub integer_ring
                (poly_pow integer_ring (poly_var integer_ring one) n)
                (poly_1 integer_ring)) =
            ring_sub r (ring_pow r x n) (ring_1 r)`,
  SIMP_TAC[POLY_EXTEND_SUB; RING_POLYNOMIAL_POW; RING_POLYNOMIAL_VAR;
           RING_POLYNOMIAL_1; RING_HOMOMORPHISM_INTEGER_RING_OF_INT;
           POLY_EXTEND_VARPOW] THEN
  REWRITE_TAC[GSYM POLY_CONST_1] THEN
  SIMP_TAC[POLY_EXTEND_CONST; RING_HOMOMORPHISM_INTEGER_RING_OF_INT; RING_1;
           INTEGER_RING; RING_OF_INT_1]);;

(* A divisor of degree 0 of a monic polynomial is a unit.                    *)
let RING_UNIT_POLY_DIVIDES_MONIC = prove
 (`!(r:A ring) p q.
        monic r q /\ ring_divides (poly_ring r (:1)) p q /\ poly_deg r p = 0
        ==> ring_unit (poly_ring r (:1)) p`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [ring_divides]) THEN
  REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    (X_CHOOSE_THEN `b:(1->num)->A`
      (CONJUNCTS_THEN2 ASSUME_TAC SUBST_ALL_TAC)))) THEN
  MP_TAC(ISPECL [`r:A ring`; `p:(1->num)->A`] POLY_DEG_EQ_0) THEN
  ASM_REWRITE_TAC[RING_POLYNOMIAL] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:A` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM SUBST_ALL_TAC THEN REWRITE_TAC[RING_UNIT_POLY_CONST] THEN
  UNDISCH_TAC `monic r (poly_mul r (poly_const r c) (b:(1->num)->A))` THEN
  ASM_SIMP_TAC[monic; COEFF_POLY_LMUL; RING_POLYNOMIAL_IMP_POWERSERIES;
               RING_POLYNOMIAL] THEN
  DISCH_TAC THEN REWRITE_TAC[ring_unit] THEN ASM_REWRITE_TAC[] THEN
  EXISTS_TAC `coeff (poly_deg r (poly_mul r (poly_const r c) b))
                    (b:(1->num)->A)` THEN
  ASM_SIMP_TAC[COEFF_IN_CARRIER; RING_POLYNOMIAL_IMP_POWERSERIES;
               RING_POLYNOMIAL]);;

(* A common root a of two factors of X^n - 1 is a double root, so the        *)
(* derivative n X^(n-1) vanishes at a, and a is a unit (a^n = 1).            *)
let POLY_VAR_POW_SUB_1_COMMON_ROOT = prove
 (`!(r:A ring) p q n a.
        p IN ring_carrier(poly_ring r (:1)) /\
        q IN ring_carrier(poly_ring r (:1)) /\
        poly_mul r p q =
        poly_sub r (poly_pow r (poly_var r one) n) (poly_1 r) /\
        a IN ring_carrier r /\
        poly_eval r p a = ring_0 r /\ poly_eval r q a = ring_0 r
        ==> ring_of_num r n = ring_0 r`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC `u = poly_sub r (poly_var r one) (poly_const r (a:A))` THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `ring_divides (poly_ring r (:1)) u (p:(1->num)->A) /\
                ring_divides (poly_ring r (:1)) u (q:(1->num)->A)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "u" THEN ASM_SIMP_TAC[POLY_DIVIDES_X_MINUS_ROOT]; ALL_TAC] THEN
  SUBGOAL_THEN `poly_pow r u 2 = poly_mul r u (u:(1->num)->A)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`poly_ring (r:A ring) (:1)`; `u:(1->num)->A`]
      RING_POW_2) THEN
    REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_MESON_TAC[RING_DIVIDES_IN_CARRIER];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `poly_mul r p q:(1->num)->A`; `a:A`]
    REPEATED_ROOT_POLY_DERIV_ZERO) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`poly_ring (r:A ring) (:1)`; `u:(1->num)->A`;
                   `p:(1->num)->A`; `u:(1->num)->A`; `q:(1->num)->A`]
      RING_DIVIDES_MUL2) THEN
    ASM_REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_pow r a n = ring_1 (r:A ring)` MP_TAC THENL
   [MP_TAC(AP_TERM `\p. poly_eval r p (a:A)` (ASSUME
     `poly_mul r p q = poly_sub r (poly_pow r (poly_var r one) n)
                                  (poly_1 (r:A ring))`)) THEN
    RULE_ASSUM_TAC(REWRITE_RULE[POLY_RING_CLAUSES; IN_ELIM_THM]) THEN
    ASM_SIMP_TAC[POLY_EVAL_MUL; POLY_EVAL_SUB; POLY_EVAL_POW; POLY_EVAL_VAR;
                 POLY_EVAL_1; RING_POLYNOMIAL_POW; RING_POLYNOMIAL_VAR;
                 RING_POLYNOMIAL_1; RING_MUL_LZERO; RING_0] THEN
    DISCH_THEN(MP_TAC o SYM) THEN ASM_SIMP_TAC[RING_SUB_EQ_0; RING_POW; RING_1];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  SIMP_TAC[POLY_DERIV_SUB; RING_POWERSERIES_POW; RING_POWERSERIES_VAR;
           RING_POWERSERIES_1; POLY_DERIV_VAR_POW; POLY_DERIV_1] THEN
  ASM_SIMP_TAC[POLY_EVAL_SUB; POLY_EVAL_0; POLY_EVAL_MUL; POLY_EVAL_CONST;
               POLY_EVAL_POW; POLY_EVAL_VAR; RING_POLYNOMIAL_MUL;
               RING_POLYNOMIAL_CONST; RING_POLYNOMIAL_POW; RING_POLYNOMIAL_0;
               RING_POLYNOMIAL_VAR; RING_OF_NUM; RING_SUB_RZERO; RING_MUL;
               RING_POW] THEN
  DISJ_CASES_THEN2 SUBST1_TAC (X_CHOOSE_THEN `m:num` SUBST1_TAC)
   (SPEC `n:num` num_CASES) THEN
  REWRITE_TAC[RING_OF_NUM_0; SUC_SUB1; ring_pow] THEN REPEAT STRIP_TAC THEN
  MATCH_MP_TAC(RING_RULE
   `!r:A ring a b c.
        a IN ring_carrier r /\ b IN ring_carrier r /\ c IN ring_carrier r /\
        ring_mul r a b = ring_1 r /\ ring_mul r c b = ring_0 r
        ==> c = ring_0 r`) THEN
  MAP_EVERY EXISTS_TAC [`a:A`; `ring_pow r (a:A) m`] THEN
  ASM_SIMP_TAC[RING_POW; RING_OF_NUM]);;

(* In prime characteristic p the Frobenius fixes the integers, so for a root *)
(* x of q the power x^p is a common root of q and g.                         *)
let POLY_VAR_POW_SUB_1_FROBENIUS_ROOT = prove
 (`!(r:A ring) q g n x.
        prime(ring_char r) /\
        q IN ring_carrier(poly_ring integer_ring (:1)) /\
        g IN ring_carrier(poly_ring integer_ring (:1)) /\
        poly_mul integer_ring q g =
        poly_sub integer_ring
          (poly_pow integer_ring (poly_var integer_ring one) n)
          (poly_1 integer_ring) /\
        x IN ring_carrier r /\
        poly_extend (integer_ring,r) (ring_of_int r) (\v. x) q = ring_0 r /\
        poly_extend (integer_ring,r) (ring_of_int r)
          (\v. ring_pow r x (ring_char r)) g = ring_0 r
        ==> ring_char r divides n`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[GSYM RING_OF_NUM_EQ_0] THEN
  MATCH_MP_TAC POLY_VAR_POW_SUB_1_COMMON_ROOT THEN
  MAP_EVERY EXISTS_TAC [`ring_of_int (r:A ring) o (q:(1->num)->int)`;
                        `ring_of_int (r:A ring) o (g:(1->num)->int)`;
                        `ring_pow r (x:A) (ring_char r)`] THEN
  MP_TAC(ISPEC `r:A ring` RING_HOMOMORPHISM_INTEGER_RING_OF_INT) THEN
  DISCH_THEN(fun th ->
    let hom t = MATCH_MP (REWRITE_RULE[IMP_CONJ] t) th in
    REWRITE_TAC[poly_eval; GSYM(MATCH_MP POLY_EXTEND_EVALUATE th)] THEN
    ASM_SIMP_TAC[RING_POW; hom IN_RING_POLYNOMIAL_CARRIER_COMPOSE] THEN
    CONJ_TAC THENL
     [MP_TAC(BETA_RULE(AP_TERM `\p:(1->num)->int. ring_of_int (r:A ring) o p`
        (ASSUME `poly_mul integer_ring q g =
                 poly_sub integer_ring
                   (poly_pow integer_ring (poly_var integer_ring one) n)
                   (poly_1 integer_ring)`))) THEN
      ASM_SIMP_TAC[hom POLY_COMPOSE_HOMOMORPHISM_MUL;
                   RING_POLYNOMIAL_IMP_POWERSERIES; RING_POLYNOMIAL;
                   MATCH_MP POLY_VAR_POW_SUB_1_HOMOMORPHIC_IMAGE th];
      ALL_TAC]) THEN
  MP_TAC(ISPECL [`r:A ring`; `r:A ring`; `\y:A. ring_pow r y (ring_char r)`;
                 `x:A`; `q:(1->num)->int`]
    POLY_EXTEND_INTEGER_RING_HOMOMORPHIC_IMAGE) THEN
  ASM_SIMP_TAC[GSYM ring_endomorphism; RING_ENDOMORPHISM_FROBENIUS] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[RING_POW_ZERO; PRIME_IMP_NZ]);;

