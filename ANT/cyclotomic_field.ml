      MATCH_MP_TAC(ARITH_RULE `b:num = c ==> a <= b ==> a <= c`) THEN
      MATCH_MP_TAC POLY_DEG_MONOMORPHIC_IMAGE THEN
      ASM_REWRITE_TAC[RING_MONOMORPHISM_INTEGER_RING_OF_INT; RING_POLYNOMIAL;
