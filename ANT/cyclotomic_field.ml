(* The integer model q of the minimal polynomial divides in Z[X] every       *)
(* integer polynomial vanishing at z: the remainder modulo the monic q       *)
(* vanishes at z and has smaller degree than the minimal polynomial.         *)
let NUMBER_FIELD_INTEGER_MINIMAL_POLYNOMIAL_DIVIDES = prove
 (`!(k:A ring) z q p.
        number_field k /\ z IN ring_carrier k /\
        q IN ring_carrier(poly_ring integer_ring (:1)) /\
        monic integer_ring q /\
        poly_deg integer_ring q =
        poly_deg (subfield_generated k {ring_0 k})
          (minimal_polynomial (subfield_generated k {ring_0 k},k) I z) /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. z) q = ring_0 k /\
        p IN ring_carrier(poly_ring integer_ring (:1)) /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. z) p = ring_0 k
        ==> ring_divides (poly_ring integer_ring (:1)) q p`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [number_field]) THEN
  MP_TAC(ISPECL [`integer_ring`; `p:(1->num)->int`; `q:(1->num)->int`]
    POLY_DIV_REM) THEN
  ANTS_TAC THENL
   [RULE_ASSUM_TAC(REWRITE_RULE[monic]) THEN
    ASM_REWRITE_TAC[RING_UNIT_1];
    ALL_TAC] THEN
  MAP_EVERY ABBREV_TAC [`d = poly_div integer_ring p q`;
                        `s = poly_rem integer_ring p q`] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC ASSUME_TAC))) THEN
  MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `(:1)`; `ring_of_int k:int->A`;
                 `\v:1. (z:A)`] RING_HOMOMORPHISM_POLY_EXTEND) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `poly_extend (integer_ring,k) (ring_of_int k) (\v. z)
