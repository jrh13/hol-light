(* ========================================================================= *)
(* Cyclotomic fields, abstractly (no complex numbers), in the style of       *)
(* ANT/quadratic.ml: a number field k with an element z of exact order n     *)
(* (ring_order k z = n, n <> 0) generating k (subfield_generated k {z} = k). *)
(* The minimal polynomial over Q of any element of order n of a number field *)
(* is the cyclotomic polynomial (CYCLOTOMIC_POLY_MINIMAL_POLYNOMIAL), so     *)
(* Phi_n is irreducible over the prime field of every field of               *)
(* characteristic 0 and over Z (CYCLOTOMIC_POLY_IRREDUCIBLE_PRIME_SUBFIELD,  *)
(* CYCLOTOMIC_POLY_IRREDUCIBLE); [k:Q] = phi(n) (CYCLOTOMIC_FIELD_DEGREE)    *)
(* with the Q-basis 1, z, ..., z^(phi(n)-1) (CYCLOTOMIC_FIELD_FREE_BASIS).   *)
(* Subfields generated by elements are number fields                         *)
(* (NUMBER_FIELD_SUBFIELD_GENERATED of ANT/relative_split.ml), with the same *)
(* orders of elements (RING_ORDER_SUBFIELD_GENERATED of                      *)
(* Library/fieldtheory.ml), so the setting passes to the subfields Q(z^d);   *)
(* finite extensions of number fields are number fields                      *)
(* (NUMBER_FIELD_FINITE_EXTENSION), and the subfield generated by an         *)
(* algebraic element z is the ring generated by z and the prime subfield     *)
(* (SUBFIELD_GENERATED_SING_ALGEBRAIC of Library/fieldtheory.ml).            *)
(*                                                                           *)
(* Route (Dedekind, no Galois theory). The element z is integral (a root of  *)
(* the monic integer polynomial Phi_n), so its minimal polynomial f has a    *)
(* monic integer model q (RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL),      *)
(* which divides X^n - 1 in Z[X]                                             *)
(* (NUMBER_FIELD_INTEGER_MINIMAL_POLYNOMIAL_DIVIDES). For a prime p not      *)
(* dividing n, z^p is again a root of q                                      *)
(* (NUMBER_FIELD_VAR_POW_SUB_1_DIVISOR_ROOT_POW): otherwise X^n - 1 = q g    *)
(* with g(z^p) = 0, and in the residue field O/P of a prime P above p the    *)
(* Frobenius fixes the integers, so the image of z^p is a common root of q   *)
(* and g (POLY_VAR_POW_SUB_1_FROBENIUS_ROOT), which kills n                  *)
(* (POLY_VAR_POW_SUB_1_COMMON_ROOT, via REPEATED_ROOT_POLY_DERIV_ZERO),      *)
(* hence p divides n. By induction on the prime factors, q(z^c) = 0 for all  *)
(* c coprime to n; these phi(n) roots are distinct, so deg f >= phi(n)       *)
(* (NUMBER_FIELD_VAR_POW_SUB_1_DIVISOR_DEG, by POLY_ROOT_BOUND), while f     *)
(* divides Phi_n (CYCLOTOMIC_POLY_ROOT, MINIMAL_POLYNOMIAL_DIVIDES), which   *)
(* is monic of degree phi(n): f = Phi_n (MONIC_DIVIDES_EQ of                 *)
(* Library/ringtheory.ml). Over the prime subfield, a divisor of positive    *)
(* degree of Phi_n has a root in the prime subfield or in a simple extension *)
(* (KRONECKER_SIMPLE_FIELD_EXTENSION), a number field in which the root has  *)
(* order n (CYCLOTOMIC_POLY_ROOT_EQ), so its degree is at least phi(n)       *)
(* (PHI_LE_POLY_DEG_CYCLOTOMIC_DIVISOR) and the cofactor is a unit. Over Z,  *)
(* a factorization maps to one over the prime subfield of real_ring, and     *)
(* constant divisors of the monic Phi_n are units                            *)
(* (RING_UNIT_POLY_DIVIDES_MONIC). Degree: EXTENSION_DEGREE_SIMPLE of        *)
(* Library/fieldtheory.ml; basis: NUMBER_FIELD_FREE_BASIS_POWERS of          *)
(* ANT/power_basis.ml.                                                       *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (MONIC_DIVIDES_EQ), Library/fieldtheory.ml    *)
(* (minimal polynomials, KRONECKER_SIMPLE_FIELD_EXTENSION,                   *)
(* EXTENSION_DEGREE_SIMPLE, SUBFIELD_GENERATED_SING_ALGEBRAIC,               *)
(* PRIME_SUBFIELD_MONOMORPHIC_IMAGE, PRIME_SUBFIELD_TOWER_LAW),              *)
(* Library/ring_det.ml (free_basis), ANT/integral.ml, ANT/numfield.ml,       *)
(* ANT/prime_split.ml (NUMBER_FIELD_PRIME_IDEALS_ABOVE_Q,                    *)
(* RING_OF_NUM_IN_PRIME_IDEAL), ANT/dedekind_kummer.ml                       *)
(* (RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL), ANT/cyclotomic_poly.ml and *)
(* ANT/power_basis.ml (NUMBER_FIELD_FREE_BASIS_POWERS).                      *)
(* ========================================================================= *)

