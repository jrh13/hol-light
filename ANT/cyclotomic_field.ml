(* The same in a number field, through the residue field O/P of a prime P    *)
(* above p, of characteristic p.                                             *)
let NUMBER_FIELD_VAR_POW_SUB_1_FROBENIUS_ROOT = prove
 (`!(k:A ring) q g n p w.
        number_field k /\ prime p /\
        q IN ring_carrier(poly_ring integer_ring (:1)) /\
        g IN ring_carrier(poly_ring integer_ring (:1)) /\
        poly_mul integer_ring q g =
        poly_sub integer_ring
          (poly_pow integer_ring (poly_var integer_ring one) n)
          (poly_1 integer_ring) /\
        w IN ring_carrier(ring_of_integers k) /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. w) q = ring_0 k /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. ring_pow k w p) g =
        ring_0 k
        ==> p divides n`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `p:num`] NUMBER_FIELD_PRIME_IDEALS_ABOVE_Q) THEN
  ASM_REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `P:A->bool` STRIP_ASSUME_TAC o
    CONJUNCT1 o CONJUNCT2) THEN
  ABBREV_TAC `R = quotient_ring (ring_of_integers k) (P:A->bool)` THEN
  ABBREV_TAC `h = ring_coset (ring_of_integers k) (P:A->bool)` THEN
  SUBGOAL_THEN
   `ring_homomorphism(ring_of_integers k,R) (h:A->A->bool) /\
    ring_char R = p`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["R"; "h"] THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET; PRIME_IMP_RING_IDEAL] THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `P:A->bool`; `p:num`]
      RING_OF_NUM_IN_PRIME_IDEAL) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x f. x IN ring_carrier(ring_of_integers k) /\
          f IN ring_carrier(poly_ring integer_ring (:1))
          ==> (h:A->A->bool)
                (poly_extend (integer_ring,k) (ring_of_int k) (\v. x) f) =
              poly_extend (integer_ring,R) (ring_of_int R) (\v. h x) f`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `\v:1. (x:A)`; `f:(1->num)->int`]
      POLY_EXTEND_RING_OF_INTEGERS) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT1) THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `R:(A->bool)ring`;
                   `h:A->A->bool`; `x:A`; `f:(1->num)->int`]
      POLY_EXTEND_INTEGER_RING_HOMOMORPHIC_IMAGE) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  FIRST_ASSUM(fun th -> GEN_REWRITE_TAC LAND_CONV [SYM th]) THEN
  MATCH_MP_TAC POLY_VAR_POW_SUB_1_FROBENIUS_ROOT THEN
  MAP_EVERY EXISTS_TAC [`q:(1->num)->int`; `g:(1->num)->int`;
                        `(h:A->A->bool) w`] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `ring_pow R ((h:A->A->bool) w) p = h(ring_pow k w p) /\
                h(ring_0 k) = ring_0 R /\
                ring_pow k w p IN ring_carrier(ring_of_integers k)`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `w:A`; `p:num`] RING_POW) THEN
    MP_TAC(MATCH_MP RING_HOMOMORPHISM_POW (ASSUME
     `ring_homomorphism(ring_of_integers k,R) (h:A->A->bool)`)) THEN
    MP_TAC(MATCH_MP RING_HOMOMORPHISM_0 (ASSUME
     `ring_homomorphism(ring_of_integers k,R) (h:A->A->bool)`)) THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
    FIRST_X_ASSUM(MP_TAC o SPECL [`w:A`; `q:(1->num)->int`]);
    FIRST_X_ASSUM(MP_TAC o SPECL [`ring_pow k w p:A`; `g:(1->num)->int`])] THEN
  ANTS_TAC THEN ASM_REWRITE_TAC[] THEN DISCH_THEN(ACCEPT_TAC o SYM));;

(* Dedekind: if w is a root of a monic integer divisor q of X^n - 1 and p a  *)
(* prime not dividing n, so is w^p (otherwise w^p is a root of the           *)
(* cofactor). By induction on the prime factors the same holds for w^c, c    *)
(* coprime to n, giving phi(n) distinct roots.                               *)
let NUMBER_FIELD_VAR_POW_SUB_1_DIVISOR_ROOT_POW = prove
 (`!(k:A ring) q n p w.
        number_field k /\ monic integer_ring q /\
        ring_divides (poly_ring integer_ring (:1)) q
          (poly_sub integer_ring
             (poly_pow integer_ring (poly_var integer_ring one) n)
             (poly_1 integer_ring)) /\
        w IN ring_carrier k /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. w) q = ring_0 k /\
        prime p /\ ~(p divides n)
        ==> poly_extend (integer_ring,k) (ring_of_int k)
              (\v. ring_pow k w p) q = ring_0 k`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [ring_divides]) THEN
  REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    (X_CHOOSE_THEN `g:(1->num)->int`
      (CONJUNCTS_THEN2 ASSUME_TAC (ASSUME_TAC o SYM))))) THEN
  SUBGOAL_THEN
   `!x. x IN ring_carrier(k:A ring)
        ==> ring_mul k
              (poly_extend (integer_ring,k) (ring_of_int k) (\v. x)
                           (q:(1->num)->int))
              (poly_extend (integer_ring,k) (ring_of_int k) (\v. x)
                           (g:(1->num)->int)) =
            ring_sub k (ring_pow k x n) (ring_1 k)`
  ASSUME_TAC THENL
   [X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `(:1)`; `ring_of_int k:int->A`;
                   `\v:1. (x:A)`] RING_HOMOMORPHISM_POLY_EXTEND) THEN
    ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
    DISCH_THEN(MP_TAC o SPECL [`q:(1->num)->int`; `g:(1->num)->int`] o
      MATCH_MP RING_HOMOMORPHISM_MUL) THEN
    ASM_REWRITE_TAC[CONJUNCT2 POLY_RING_CLAUSES] THEN
