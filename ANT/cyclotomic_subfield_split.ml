(* The decomposition law in the subfields K = subfield_generated k s of      *)
(* k = Q(z), for primes p not dividing the order n of z.                     *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_SUBFIELD_RESIDUE_DEGREE = prove
 (`!(k:A ring) z n s p Q.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        subfield_generated k {z} = k /\ prime p /\ ~(p divides n) /\
        prime_ideal (ring_of_integers k) Q /\ ring_of_num k p IN Q
        ==> prime_ideal (ring_of_integers(subfield_generated k s))
              (Q INTER ring_carrier(subfield_generated k s)) /\
            ring_of_num (subfield_generated k s) p IN
            Q INTER ring_carrier(subfield_generated k s) /\
            ramification_index
              (integer_ring,ring_of_integers(subfield_generated k s))
              (ring_of_int(subfield_generated k s))
              (Q INTER ring_carrier(subfield_generated k s)) = 1 /\
            !d. residue_degree
                  (integer_ring,ring_of_integers(subfield_generated k s))
                  (ring_of_int(subfield_generated k s))
                  (Q INTER ring_carrier(subfield_generated k s)) divides d <=>
                !g x. g IN group_carrier(galois_group
                                   (subfield_generated k {ring_0 k},k) I) /\
                      g z = ring_pow k z (p EXP d) /\ x IN s
                      ==> g x = x`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `~(n:num = 0)` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN UNDISCH_TAC `~((p:num) divides 0)` THEN
    CONV_TAC NUMBER_RULE;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `p:num`]
    RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC
   `p0 = ideal_generated (ring_of_integers(subfield_generated k {ring_0 k}))
                         {ring_of_num k p:A}` THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `IMAGE (I:A->A) p0 SUBSET Q` ASSUME_TAC THENL
   [ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]; ALL_TAC] THEN
  SUBGOAL_THEN `~(Q = {ring_0(k:A ring)})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `ring_of_num k p IN {ring_0 k:A}` THEN
    REWRITE_TAC[IN_SING; RING_OF_NUM_EQ_0] THEN
    FIRST_ASSUM(fun th ->
      REWRITE_TAC[CONJUNCT1(REWRITE_RULE[number_field] th)]) THEN
    ASM_SIMP_TAC[DIVIDES_ZERO; PRIME_IMP_NZ];
    ALL_TAC] THEN
  SUBGOAL_THEN `maximal_ideal (ring_of_integers k) (Q:A->bool)` ASSUME_TAC THENL
   [MATCH_MP_TAC DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL THEN
    ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS; RING_OF_INTEGERS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `p:num`; `Q:A->bool`]
    CYCLOTOMIC_FIELD_INERTIA_GROUP) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `p:num`; `Q:A->bool`]
    CYCLOTOMIC_FIELD_FROBENIUS_ELEMENT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  ABBREV_TAC `Q0 = subfield_generated k {ring_0 k:A}` THEN
  SUBGOAL_THEN
   `field(Q0:A ring) /\ ring_homomorphism(Q0,k) (I:A->A) /\
    ring_0 Q0 = ring_0 k`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "Q0" THEN
    SIMP_TAC[FIELD_SUBFIELD_GENERATED; ASSUME `field(k:A ring)`;
             RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
             CONJUNCT2 SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ramification_index (ring_of_integers Q0,ring_of_integers k) (I:A->A) Q =
    1`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`I:A->A`; `Q0:A ring`; `k:A ring`; `p0:A->bool`;
                   `Q:A->bool`] NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP) THEN
    ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `Q0:A ring`; `k:A ring`; `p0:A->bool`; `Q:A->bool`]
    NUMBER_FIELD_FROBENIUS_ELEMENT) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN
  DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  ABBREV_TAC `fr = frobenius_element (Q0,k) (I:A->A) (ring_of_integers k) Q`
  THEN
  SUBGOAL_THEN `fr IN group_carrier(galois_group(Q0,k) (I:A->A))`
  ASSUME_TAC THENL
   [UNDISCH_TAC `fr IN group_carrier(decomposition_group(Q0,k) (I:A->A) Q)`
    THEN REWRITE_TAC[DECOMPOSITION_GROUP; IN_ELIM_THM] THEN SIMP_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC `K = subfield_generated k (s:A->bool)` THEN
  ABBREV_TAC `t = ring_carrier(K:A ring)` THEN
  SUBGOAL_THEN
   `t subfield_of (k:A ring) /\ IMAGE (I:A->A) (ring_carrier Q0) SUBSET t /\
    subfield_generated k t = K`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["t"; "K"; "Q0"] THEN
    SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; IMAGE_I; PRIME_SUBFIELD_MINIMAL;
             SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED;
             ASSUME `field(k:A ring)`];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `subfield_generated K {ring_0 K} = (Q0:A ring) /\
    ring_0 K = ring_0(k:A ring) /\ ring_of_num K = ring_of_num(k:A ring) /\
    number_field(K:A ring)`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "Q0"] THEN
    SIMP_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED; CONJUNCT2 SUBFIELD_GENERATED;
             RING_OF_NUM_SUBFIELD_GENERATED; NUMBER_FIELD_SUBFIELD_GENERATED;
             ASSUME `number_field(k:A ring)`];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `Q0:A ring`; `k:A ring`; `t:A->bool`; `p0:A->bool`;
                 `Q:A->bool`] NUMBER_FIELD_PRIME_IDEAL_INTERMEDIATE) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `Q0:A ring`; `k:A ring`; `t:A->bool`; `p0:A->bool`;
                 `Q:A->bool`] NUMBER_FIELD_INTERMEDIATE_FROBENIUS_ORDER) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`K:A ring`; `Q INTER (t:A->bool)`]
    RAMIFICATION_INDEX_PRIME_SUBFIELD) THEN
  MP_TAC(ISPECL [`K:A ring`; `Q INTER (t:A->bool)`]
    RESIDUE_DEGREE_PRIME_SUBFIELD) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD; PRIME_IMP_RING_IDEAL] THEN
  REPEAT(DISCH_THEN(SUBST1_TAC o SYM)) THEN
  CONJ_TAC THENL
   [REWRITE_TAC[IN_INTER] THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`K:A ring`; `p:num`] RING_OF_NUM) THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  X_GEN_TAC `d:num` THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `d:num` o check (fun th ->
    is_forall(concl th) &&
    can (find_term (fun t -> is_const t && fst(dest_const t) = "group_pow"))
        (concl th))) THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  ABBREV_TAC `gd = group_pow (galois_group(Q0,k) (I:A->A)) fr d` THEN
  SUBGOAL_THEN
   `(gd:A->A) IN group_carrier(galois_group(Q0,k) I) /\
    gd z = ring_pow k z (p EXP d)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "gd" THEN CONJ_TAC THENL
     [MATCH_MP_TAC GROUP_POW THEN FIRST_ASSUM ACCEPT_TAC;
      MATCH_MP_TAC GALOIS_GROUP_POW_ROOT THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBST1_TAC(SYM(ASSUME `subfield_generated k s = (K:A ring)`)) THEN
  SIMP_TAC[IN_GALOIS_GROUP_SUBFIELD_GENERATED; ASSUME `field(k:A ring)`] THEN
  SUBGOAL_THEN `(gd:A->A) permutes ring_carrier k /\ ring_automorphism k gd`
  (fun th -> REWRITE_TAC[th]) THENL
   [UNDISCH_TAC `(gd:A->A) IN group_carrier(galois_group(Q0,k) I)` THEN
    SIMP_TAC[IN_GALOIS_GROUP];
    ALL_TAC] THEN
  EQ_TAC THENL
   [DISCH_TAC THEN MAP_EVERY X_GEN_TAC [`g:A->A`; `x:A`] THEN
    STRIP_TAC THEN
    SUBGOAL_THEN `g:A->A = gd` SUBST1_TAC THENL
     [MATCH_MP_TAC CYCLOTOMIC_FIELD_GALOIS_GROUP_EQ THEN
      MAP_EVERY EXISTS_TAC [`k:A ring`; `z:A`] THEN ASM_REWRITE_TAC[];
      ASM_SIMP_TAC[]];
    DISCH_TAC THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[]]);;

let CYCLOTOMIC_SUBFIELD_PRIME_DECOMPOSITION = prove
 (`!(k:A ring) z n s p.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        subfield_generated k {z} = k /\ prime p /\ ~(p divides n)
        ==> ?f. (!d. f divides d <=>
                     !g x. g IN group_carrier(galois_group
                                     (subfield_generated k {ring_0 k},k) I) /\
                           g z = ring_pow k z (p EXP d) /\ x IN s
                           ==> g x = x) /\
                (!P. prime_ideal (ring_of_integers(subfield_generated k s)) P /\
                     ring_of_num (subfield_generated k s) p IN P
                     ==> ramification_index
                           (integer_ring,
                            ring_of_integers(subfield_generated k s))
                           (ring_of_int(subfield_generated k s)) P = 1 /\
                         residue_degree
                           (integer_ring,
                            ring_of_integers(subfield_generated k s))
                           (ring_of_int(subfield_generated k s)) P = f) /\
                CARD {P | prime_ideal
                            (ring_of_integers(subfield_generated k s)) P /\
                          ring_of_num (subfield_generated k s) p IN P} * f =
                extension_degree(subfield_generated k {ring_0 k},
                                 subfield_generated k s) I`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
  MP_TAC(ISPECL [`k:A ring`; `p:num`] NUMBER_FIELD_PRIME_DECOMPOSITION_Q) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o CONJUNCT1 o CONJUNCT2) THEN
  REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `Q1:A->bool` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `s:A->bool`; `p:num`;
                 `Q1:A->bool`] CYCLOTOMIC_SUBFIELD_RESIDUE_DEGREE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ABBREV_TAC `K = subfield_generated k (s:A->bool)` THEN
  EXISTS_TAC
   `residue_degree (integer_ring,ring_of_integers K) (ring_of_int K)
      (Q1 INTER ring_carrier(K:A ring))` THEN
  ABBREV_TAC
   `f = residue_degree (integer_ring,ring_of_integers K) (ring_of_int K)
          (Q1 INTER ring_carrier(K:A ring))` THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `!P. prime_ideal (ring_of_integers K) P /\ ring_of_num k p IN P
        ==> ramification_index (integer_ring,ring_of_integers K)
              (ring_of_int K) P = 1 /\
            residue_degree (integer_ring,ring_of_integers K)
              (ring_of_int (K:A ring)) P = f`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `p:num`]
      NUMBER_FIELD_SUBFIELD_PRIME_IDEALS_ABOVE) THEN
    ASM_REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
    DISCH_THEN(MP_TAC o AP_TERM `(IN) (P:A->bool)`) THEN
    ASM_REWRITE_TAC[IN_ELIM_THM] THEN
    DISCH_THEN(X_CHOOSE_THEN `Q:A->bool`
     (CONJUNCTS_THEN2 STRIP_ASSUME_TAC SUBST_ALL_TAC)) THEN
    MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `s:A->bool`; `p:num`;
                   `Q:A->bool`] CYCLOTOMIC_SUBFIELD_RESIDUE_DEGREE) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(MESON[DIVIDES_ANTISYM; DIVIDES_REFL]
     `!a b:num. (!d. a divides d <=> b divides d) ==> a = b`) THEN
    ASM_REWRITE_TAC[];
    ASM_REWRITE_TAC[]] THEN
  SUBGOAL_THEN
   `number_field(K:A ring) /\ ring_of_num K = ring_of_num(k:A ring) /\
    subfield_generated K {ring_0 K} = subfield_generated k {ring_0 k}`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "K" THEN
    SIMP_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED; RING_OF_NUM_SUBFIELD_GENERATED;
             NUMBER_FIELD_SUBFIELD_GENERATED; ASSUME `number_field(k:A ring)`];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`K:A ring`; `p:num`] NUMBER_FIELD_FUNDAMENTAL_IDENTITY_Q) THEN
  MP_TAC(ISPECL [`K:A ring`; `p:num`] NUMBER_FIELD_PRIME_DECOMPOSITION_Q) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  TRANS_TAC EQ_TRANS
   `nsum {P | prime_ideal (ring_of_integers K) P /\ ring_of_num k p IN P}
         (\P:A->bool. f)` THEN
  CONJ_TAC THENL
   [ASM_SIMP_TAC[NSUM_CONST];
    MATCH_MP_TAC NSUM_EQ THEN ASM_SIMP_TAC[IN_ELIM_THM; MULT_CLAUSES]]);;

let CYCLOTOMIC_SUBFIELD_SPLITTING_TYPES = prove
 (`!(k:A ring) z n s p.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        subfield_generated k {z} = k /\ prime p /\ ~(p divides n)
        ==> unramified (integer_ring,ring_of_integers(subfield_generated k s))
              (ring_of_int(subfield_generated k s))
              (ideal_generated integer_ring {&p}) /\
            (totally_split
              (integer_ring,ring_of_integers(subfield_generated k s))
              (ring_of_int(subfield_generated k s))
              (ideal_generated integer_ring {&p}) <=>
             !g x. g IN group_carrier(galois_group
                             (subfield_generated k {ring_0 k},k) I) /\
                   g z = ring_pow k z p /\ x IN s
                   ==> g x = x)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `s:A->bool`; `p:num`]
    CYCLOTOMIC_SUBFIELD_PRIME_DECOMPOSITION) THEN
  ASM_REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
  DISCH_THEN(X_CHOOSE_THEN `f:num` (CONJUNCTS_THEN2 (MP_TAC o SPEC `1:num`)
    (CONJUNCTS_THEN2 ASSUME_TAC (K ALL_TAC)))) THEN
  REWRITE_TAC[DIVIDES_ONE; EXP_1] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `p:num`]
    NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_Q) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED; PRIME_IMP_NZ] THEN
  DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers(subfield_generated k s):A ring`; `p:num`]
    SPLITTING_TYPES_INTEGER_RING) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_OF_NUM_SUBFIELD_GENERATED] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  SUBGOAL_THEN
   `?P. prime_ideal (ring_of_integers(subfield_generated k s)) P /\
        ring_of_num k p IN (P:A->bool)`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `p:num`]
      NUMBER_FIELD_PRIME_DECOMPOSITION_Q) THEN
    ANTS_TAC THENL [ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED]; ALL_TAC] THEN
    DISCH_THEN(MP_TAC o CONJUNCT1 o CONJUNCT2) THEN
    REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM;
                RING_OF_NUM_SUBFIELD_GENERATED] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  CONJ_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN EQ_TAC THENL
   [DISCH_THEN(MP_TAC o SPEC `P:A->bool`) THEN ASM_SIMP_TAC[];
    ASM_SIMP_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* The fixed field of a subgroup H of the units mod n: f is the order        *)
(* of p mod n modulo H.                                                      *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_FIXED_FIELD_PRIME_DECOMPOSITION = prove
 (`!(k:A ring) z n H s p.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        subfield_generated k {z} = k /\ H subgroup_of modmul_group n /\
        fixed_field k
          {g | g IN group_carrier(galois_group
                                   (subfield_generated k {ring_0 k},k) I) /\
               ?c. c IN H /\ g z = ring_pow k z c} = s /\
        prime p /\ ~(p divides n)
        ==> extension_degree(subfield_generated k {ring_0 k},
                             subfield_generated k s) I * CARD H = phi n /\
            ?f. (!d. f divides d <=> ?c. c IN H /\ (p EXP d == c) (mod n)) /\
                (!P. prime_ideal (ring_of_integers(subfield_generated k s)) P /\
                     ring_of_num (subfield_generated k s) p IN P
                     ==> ramification_index
                           (integer_ring,
                            ring_of_integers(subfield_generated k s))
                           (ring_of_int(subfield_generated k s)) P = 1 /\
                         residue_degree
                           (integer_ring,
                            ring_of_integers(subfield_generated k s))
                           (ring_of_int(subfield_generated k s)) P = f) /\
                CARD {P | prime_ideal
                            (ring_of_integers(subfield_generated k s)) P /\
                          ring_of_num (subfield_generated k s) p IN P} * f =
                extension_degree(subfield_generated k {ring_0 k},
                                 subfield_generated k s) I`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `~(n:num = 0)` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN UNDISCH_TAC `~((p:num) divides 0)` THEN
    CONV_TAC NUMBER_RULE;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->A)->num` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_GROUP_HAS_SIZE) THEN
  ASM_REWRITE_TAC[HAS_SIZE] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  ABBREV_TAC
   `Hg = {g | g IN group_carrier(galois_group
                                   (subfield_generated k {ring_0 k},k) I) /\
              ?c. c IN H /\ g z = ring_pow k (z:A) c}` THEN
  SUBGOAL_THEN
   `!a b. ring_pow k z a = ring_pow k (z:A) b <=> (a == b) (mod n)`
  ASSUME_TAC THENL
   [REPEAT GEN_TAC THEN UNDISCH_TAC `ring_order k (z:A) = n` THEN
    DISCH_THEN(fun th -> SUBST1_TAC(SYM th) THEN ASSUME_TAC th) THEN
    MATCH_MP_TAC RING_POW_EQ_GEN THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `Hg = {g | g IN group_carrier(galois_group
                                   (subfield_generated k {ring_0 k},k) I) /\
              (e:(A->A)->num) g IN H}`
  ASSUME_TAC THENL
   [EXPAND_TAC "Hg" THEN GEN_REWRITE_TAC I [EXTENSION] THEN
    X_GEN_TAC `g:A->A` THEN REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_CASES_TAC
     `(g:A->A) IN group_carrier(galois_group
                                 (subfield_generated k {ring_0 k},k) I)` THEN
    ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `(e:(A->A)->num) g IN group_carrier(modmul_group n)`
    ASSUME_TAC THENL
     [FIRST_ASSUM(MP_TAC o MATCH_MP GROUP_ISOMORPHISM_IMP_HOMOMORPHISM) THEN
      REWRITE_TAC[group_homomorphism; SUBSET; FORALL_IN_IMAGE] THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    ASM_SIMP_TAC[] THEN EQ_TAC THENL
     [DISCH_THEN(X_CHOOSE_THEN `c:num` STRIP_ASSUME_TAC) THEN
      SUBGOAL_THEN `(e:(A->A)->num) g = c` (fun th -> ASM_REWRITE_TAC[th]) THEN
      MATCH_MP_TAC MODMUL_GROUP_CONG_EQ THEN EXISTS_TAC `n:num` THEN
      ASM_REWRITE_TAC[] THEN
      ASM_MESON_TAC[subgroup_of; SUBSET];
      DISCH_TAC THEN EXISTS_TAC `(e:(A->A)->num) g` THEN
      ASM_REWRITE_TAC[CONG_REFL]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `finite_extension(subfield_generated k {ring_0 k},k) (I:A->A)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated k {ring_0 k:A}`; `k:A ring`; `I:A->A`]
      NUMBER_FIELD_TOWER_LAW) THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(Hg:(A->A)->bool) subgroup_of
    galois_group(subfield_generated k {ring_0 k},k) I /\
    CARD Hg = CARD(H:num->bool)`
  STRIP_ASSUME_TAC THENL
   [FIRST_ASSUM(SUBST1_TAC o check (fun th -> is_eq(concl th) &&
      lhs(concl th) = `Hg:(A->A)->bool`)) THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SUBGROUP_OF_HOMOMORPHIC_PREIMAGE THEN
      EXISTS_TAC `modmul_group n` THEN
      ASM_SIMP_TAC[GROUP_ISOMORPHISM_IMP_HOMOMORPHISM];
      ALL_TAC] THEN
    FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [GROUP_ISOMORPHISM] o
      check (fun th -> is_const(fst(strip_comb(concl th))) &&
             fst(dest_const(fst(strip_comb(concl th)))) =
             "group_isomorphism")) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP SUBGROUP_OF_IMP_SUBSET o
      check (fun th -> concl th = `H subgroup_of modmul_group n`)) THEN
    TRANS_TAC EQ_TRANS
     `CARD(IMAGE (e:(A->A)->num)
        {g | g IN group_carrier(galois_group
                                 (subfield_generated k {ring_0 k},k) I) /\
             e g IN H})` THEN
    CONJ_TAC THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC CARD_IMAGE_INJ THEN CONJ_TAC THENL
       [REWRITE_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
        FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC FINITE_SUBSET THEN
        EXISTS_TAC
         `group_carrier(galois_group
                         (subfield_generated k {ring_0 k},k) (I:A->A))` THEN
        ASM_REWRITE_TAC[] THEN SET_TAC[]];
      AP_TERM_TAC THEN
      UNDISCH_TAC
       `IMAGE (e:(A->A)->num)
          (group_carrier(galois_group
                          (subfield_generated k {ring_0 k},k) I)) =
        group_carrier(modmul_group n)` THEN
      UNDISCH_TAC `H SUBSET group_carrier(modmul_group n)` THEN
      SET_TAC[]];
    ALL_TAC] THEN
  FIRST_X_ASSUM(K ALL_TAC o check (fun th -> is_eq(concl th) &&
    lhs(concl th) = `Hg:(A->A)->bool`)) THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `Hg:(A->A)->bool`] GALOIS_GROUP_FIXED_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `s:A->bool`] GALOIS_CORRESPONDENCE_DEGREE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT2) THEN
  CONJ_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `s:A->bool`; `p:num`]
    CYCLOTOMIC_SUBFIELD_PRIME_DECOMPOSITION) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!d. (!g x. g IN group_carrier(galois_group
                                  (subfield_generated k {ring_0 k},k) I) /\
               g z = ring_pow k (z:A) (p EXP d) /\ x IN s
               ==> g x = x) <=>
        (?c. c IN H /\ (p EXP d == c) (mod n))`
  (fun th -> REWRITE_TAC[th]) THEN
  X_GEN_TAC `d:num` THEN EQ_TAC THENL
   [DISCH_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `p EXP d`]
      CYCLOTOMIC_FIELD_GALOIS_GROUP_EXISTS) THEN
    ASM_SIMP_TAC[COPRIME_LEXP; PRIME_COPRIME_EQ] THEN
    DISCH_THEN(X_CHOOSE_THEN `g0:A->A` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN `(g0:A->A) IN Hg` MP_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th -> is_eq(concl th) &&
        lhs(concl th) =
        `group_carrier(galois_group(subfield_generated k s,k) (I:A->A))`)) THEN
      MP_TAC(ISPECL [`I:A->A`; `g0:A->A`; `subfield_generated k {ring_0 k:A}`;
                     `k:A ring`; `s:A->bool`] IN_GALOIS_GROUP_INTERMEDIATE) THEN
      ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN SUBST1_TAC] THEN
      ASM_REWRITE_TAC[] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[CONG_REFL];
      ALL_TAC] THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th -> is_eq(concl th) &&
      rhs(concl th) = `Hg:(A->A)->bool` &&
      can (find_term ((=) `ring_pow:A ring->A->num->A`)) (lhs(concl th)))) THEN
    ASM_REWRITE_TAC[IN_ELIM_THM];
    DISCH_THEN(X_CHOOSE_THEN `c:num` STRIP_ASSUME_TAC) THEN
    MAP_EVERY X_GEN_TAC [`g:A->A`; `x:A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN `(g:A->A) IN Hg` ASSUME_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th -> is_eq(concl th) &&
        rhs(concl th) = `Hg:(A->A)->bool` &&
        can (find_term ((=) `ring_pow:A ring->A->num->A`))
            (lhs(concl th)))) THEN
      REWRITE_TAC[IN_ELIM_THM] THEN ASM_REWRITE_TAC[] THEN
      EXISTS_TAC `c:num` THEN ASM_REWRITE_TAC[];
      UNDISCH_TAC `(x:A) IN s` THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th -> is_eq(concl th) &&
        rhs(concl th) = `s:A->bool` &&
        can (find_term ((=) `fixed_field:A ring->((A->A)->bool)->A->bool`))
            (lhs(concl th)))) THEN
      REWRITE_TAC[IN_FIXED_FIELD] THEN ASM_SIMP_TAC[]]]);;

let CYCLOTOMIC_FIXED_FIELD_TOTALLY_SPLIT = prove
 (`!(k:A ring) z n H s p.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        subfield_generated k {z} = k /\ H subgroup_of modmul_group n /\
        fixed_field k
          {g | g IN group_carrier(galois_group
                                   (subfield_generated k {ring_0 k},k) I) /\
               ?c. c IN H /\ g z = ring_pow k z c} = s /\
        prime p /\ ~(p divides n)
        ==> (totally_split
              (integer_ring,ring_of_integers(subfield_generated k s))
              (ring_of_int(subfield_generated k s))
              (ideal_generated integer_ring {&p}) <=>
             ?c. c IN H /\ (p == c) (mod n))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`; `H:num->bool`; `s:A->bool`;
                 `p:num`] CYCLOTOMIC_FIXED_FIELD_PRIME_DECOMPOSITION) THEN
  ASM_REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
  DISCH_THEN(X_CHOOSE_THEN `f:num` (CONJUNCTS_THEN2 (MP_TAC o SPEC `1:num`)
    (CONJUNCTS_THEN2 ASSUME_TAC (K ALL_TAC))) o CONJUNCT2) THEN
  REWRITE_TAC[DIVIDES_ONE; EXP_1] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`ring_of_integers(subfield_generated k s):A ring`; `p:num`]
    SPLITTING_TYPES_INTEGER_RING) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_OF_NUM_SUBFIELD_GENERATED] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  SUBGOAL_THEN
   `?P. prime_ideal (ring_of_integers(subfield_generated k s)) P /\
        ring_of_num k p IN (P:A->bool)`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `p:num`]
      NUMBER_FIELD_PRIME_DECOMPOSITION_Q) THEN
    ANTS_TAC THENL [ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED]; ALL_TAC] THEN
    DISCH_THEN(MP_TAC o CONJUNCT1 o CONJUNCT2) THEN
    REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM;
                RING_OF_NUM_SUBFIELD_GENERATED] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  EQ_TAC THENL
   [DISCH_THEN(MP_TAC o SPEC `P:A->bool`) THEN ASM_SIMP_TAC[];
    ASM_SIMP_TAC[]]);;
