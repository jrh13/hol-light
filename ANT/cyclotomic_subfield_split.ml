(* ========================================================================= *)
(* The decomposition law in subfields of cyclotomic fields.                  *)
(*                                                                           *)
(* Let k = Q(z) be a number field generated by an element z of finite order  *)
(* n (subfield_generated k {z} = k, ring_order k z = n), Q =                 *)
(* subfield_generated k {ring_0 k}, G = galois_group(Q,k) I, and p a prime   *)
(* not dividing n; for d >= 0 let g_d be the element of G with g_d(z) =      *)
(* z^(p^d) (CYCLOTOMIC_FIELD_GALOIS_GROUP_EXISTS). The decomposition law in  *)
(* k (CYCLOTOMIC_FIELD_PRIME_DECOMPOSITION of ANT/cyclotomic_split.ml: f =   *)
(* the order of p mod n) extends to the subfields K = subfield_generated k   *)
(* s:                                                                        *)
(*                                                                           *)
(*   p is unramified in K, all primes P of O_K above p have the same residue *)
(*   degree f(P|p) = f and (number of P) f = [K:Q], where f divides d iff    *)
(*   g_d fixes s; so f is the least d >= 1 with g_d IN Gal(k/K), the order   *)
(*   of the class of g_1 in G/Gal(k/K)                                       *)
(*                             (CYCLOTOMIC_SUBFIELD_PRIME_DECOMPOSITION)     *)
(*   p splits completely in K iff g_1 : z |-> z^p fixes s                    *)
(*                             (CYCLOTOMIC_SUBFIELD_SPLITTING_TYPES)         *)
(*                                                                           *)
(* With the units mod n (modmul_group n): for a subgroup H of modmul_group n *)
(* and K the fixed field of the g IN G with g(z) = z^c for some c IN H,      *)
(* [K:Q] |H| = phi(n), and f is the order of p mod n modulo H: f divides d   *)
(* iff p^d == c (mod n) for some c IN H                                      *)
(* (CYCLOTOMIC_FIXED_FIELD_PRIME_DECOMPOSITION); p splits completely in K    *)
(* iff p == c (mod n) for some c IN H                                        *)
(* (CYCLOTOMIC_FIXED_FIELD_TOTALLY_SPLIT).                                   *)
(*                                                                           *)
(* The general step is NUMBER_FIELD_INTERMEDIATE_FROBENIUS_ORDER of          *)
(* ANT/decomposition_field.ml (for a Galois extension l of a number field k, *)
(* an intermediate field M and a prime Q of O_l with e(Q|p) = 1, f(Q INTER   *)
(* s|p) is the order of the Frobenius element modulo Gal(l/M)); the primes   *)
(* of O_K above p are the Q INTER K                                          *)
(* (NUMBER_FIELD_SUBFIELD_PRIME_IDEALS_ABOVE of ANT/decomposition_field.ml), *)
(* and p O_Q is a nonzero prime of the integers of the prime subfield        *)
(* (RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL of ANT/relative_split.ml). Also:   *)
(* the powers of g IN G with g(z) = z^c (GALOIS_GROUP_POW_ROOT of            *)
(* Library/galois.ml); elements of modmul_group n congruent mod n are equal  *)
(* (MODMUL_GROUP_CONG_EQ of Library/modmul_group.ml).                        *)
(*                                                                           *)
(* Routes. In k = Q(z) the inertia groups of the primes above p are trivial  *)
(* and their Frobenius element is g_1 (CYCLOTOMIC_FIELD_INERTIA_GROUP,       *)
(* CYCLOTOMIC_FIELD_FROBENIUS_ELEMENT of ANT/cyclotomic_frobenius.ml), so    *)
(* phi^d = g_d, which is determined by its value at z                        *)
(* (CYCLOTOMIC_FIELD_GALOIS_GROUP_EQ); the residue degrees and ramification  *)
(* indices over Z are those over the integers of the prime subfield          *)
(* (RESIDUE_DEGREE_PRIME_SUBFIELD, RAMIFICATION_INDEX_PRIME_SUBFIELD), and   *)
(* the count is the fundamental identity                                     *)
(* (NUMBER_FIELD_FUNDAMENTAL_IDENTITY_Q); p is then unramified in K, the     *)
(* residue fields being finite                                               *)
(* (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_Q). Fixed fields: the       *)
(* isomorphism e of G onto modmul_group n with g(z) = z^(e g)                *)
(* (CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL) makes the g with g(z) = z^c, c IN  *)
(* H, the subgroup e^-1(H) of G with |H| elements; it is the Galois group of *)
(* its fixed field K (GALOIS_GROUP_FIXED_FIELD), and [K:Q] |H| = |G| =       *)
(* phi(n) (GALOIS_CORRESPONDENCE_DEGREE).                                    *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml,                      *)
(* Library/grouptheory.ml (subgroups, preimages under homomorphisms),        *)
(* Library/galois.ml (fixed fields, the Galois correspondence,               *)
(* GALOIS_GROUP_POW_ROOT), Library/modmul_group.ml (MODMUL_GROUP_CONG_EQ),   *)
(* ANT/dedekind.ml, ANT/numfield.ml, ANT/ring_of_integers.ml,                *)
(* ANT/prime_split.ml, ANT/relative_split.ml, ANT/splitting_types.ml         *)
(* (unramified, totally_split), ANT/decomposition.ml,                        *)
(* ANT/nf_decomposition.ml, ANT/decomposition_field.ml,                      *)
(* ANT/cyclotomic_galois.ml and ANT/cyclotomic_frobenius.ml.                 *)
(* ========================================================================= *)

