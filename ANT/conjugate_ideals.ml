(* ========================================================================= *)
(* Galois conjugates of ideals in Galois extensions of number fields. Let    *)
(* (k,l) h be a Galois extension of number fields with Galois group G =      *)
(* galois_group(k,l) h. For a nonzero prime p of O_k and a prime P of O_l    *)
(* above p, the product of the conjugates f(P), f in G, is the power         *)
(* (pO_l)^f(P|p) of the extended ideal (NUMBER_FIELD_GALOIS_PRODUCT_PRIME).  *)
(* Over Q, for a number field k Galois over its prime field and a nonzero    *)
(* ideal j of O_k, the product of the conjugates of j is the principal ideal *)
(* generated by its norm, prod_(f in G) f(j) = N(j) O_k                      *)
(* (NUMBER_FIELD_GALOIS_PRODUCT_IDEAL).                                      *)
(*                                                                           *)
(* The action of G on the ideals of O_l                                      *)
(* (GALOIS_GROUP_RING_OF_INTEGERS_IDEAL, CARD_GALOIS_GROUP_IMAGE_FIBER,      *)
(* NUMBER_FIELD_IDEAL_NORM_GALOIS_IMAGE) is in ANT/nf_decomposition.ml; the  *)
(* induction on the factorization of ideals (DEDEKIND_IDEAL_INDUCT) and the  *)
(* valuation of finite products (IDEAL_VALUATION_IDEAL_PRODUCT) are in       *)
(* ANT/dedekind.ml.                                                          *)
(*                                                                           *)
(* Routes. Prime case by valuations (DEDEKIND_IDEAL_EQ_VALUATION): at a      *)
(* nonzero prime Q of O_l the product of the f(P) has valuation the number   *)
(* of f with f(P) = Q; for Q above p this is |D_P| = e f                     *)
(* (NUMBER_FIELD_GALOIS_GROUP_TRANSITIVE, NUMBER_FIELD_DECOMPOSITION_GROUP), *)
(* and (pO_l)^f has valuation f e(Q|p) with e(Q|p) = e(P|p)                  *)
(* (NUMBER_FIELD_RAMIFICATION_INDEX_CONJUGATE); for Q not above p both are   *)
(* 0. Ideal case by induction on the factorization: the product over G is    *)
(* multiplicative (IDEAL_PRODUCT_MUL), and so is the norm                    *)
(* (NUMBER_FIELD_IDEAL_NORM_MUL_Q); for a prime P above the rational prime p *)
(* the relative case over the prime field gives (p)^f = (p^f) = (N(P)), by   *)
(* RESIDUE_DEGREE_PRIME_SUBFIELD and RING_OF_INTEGERS_IDEAL_NORM_PRIME_Q.    *)
(*                                                                           *)
(* Uses: Library/galois.ml, ANT/ideal_arith.ml, ANT/dedekind.ml,             *)
(* ANT/ideal_norm.ml, ANT/numfield.ml, ANT/ring_of_integers.ml,              *)
(* ANT/norm_index.ml, ANT/prime_split.ml, ANT/relative_split.ml,             *)
(* ANT/decomposition.ml and ANT/nf_decomposition.ml.                         *)
(* ========================================================================= *)

