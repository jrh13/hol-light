(* ------------------------------------------------------------------------- *)
(* The product of the conjugates of a prime and of an ideal.                 *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_GALOIS_PRODUCT_PRIME = prove
 (`!(h:A->B) k l p P.
        number_field l /\ galois_extension(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P
        ==> ideal_product (ring_of_integers l)
              (group_carrier(galois_group(k,l) h)) (\f. IMAGE f P) =
            ideal_pow (ring_of_integers l)
              (ideal_generated (ring_of_integers l) (IMAGE h p))
              (residue_degree (ring_of_integers k,ring_of_integers l) h P)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_IMP_FIELD_EXTENSION) THEN
    SIMP_TAC[field_extension; RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN `FINITE(group_carrier(galois_group(k:A ring,l:B ring) h))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_GALOIS_GROUP THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `ring_monomorphism(k:A ring,l:B ring) h` ASSUME_TAC THENL
   [ASM_MESON_TAC[finite_extension; field_extension]; ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_RING_OF_INTEGERS) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  SUBGOAL_THEN `(p:A->bool) SUBSET ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_IDEAL_IMP_SUBSET; RING_OF_INTEGERS_SUBSET;
                  SUBSET_TRANS];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!f. f IN group_carrier(galois_group(k:A ring,l:B ring) h)
        ==> IMAGE f (ring_carrier(ring_of_integers l)) SUBSET
            ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL [MESON_TAC[GALOIS_GROUP_RING_OF_INTEGERS]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!f. f IN group_carrier(galois_group(k:A ring,l:B ring) h)
        ==> prime_ideal (ring_of_integers l) (IMAGE f P) /\
            IMAGE h p SUBSET IMAGE f P /\
            ~(IMAGE f P = {ring_0 l})`
  ASSUME_TAC THENL
   [X_GEN_TAC `f:B->B` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
                   `ring_of_integers l:B ring`; `f:B->B`; `P:B->bool`]
      GALOIS_GROUP_PRIME_IDEAL_IMAGE) THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS_SUBRING; PRIME_IDEAL_IMP_SUBSET] THEN
    STRIP_TAC THEN
    SUBGOAL_THEN `IMAGE (h:A->B) p SUBSET IMAGE (f:B->B) P` ASSUME_TAC THENL
     [REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_IMAGE] THEN
      X_GEN_TAC `x:A` THEN DISCH_TAC THEN EXISTS_TAC `(h:A->B) x` THEN
      CONJ_TAC THENL
       [CONV_TAC SYM_CONV THEN MATCH_MP_TAC GALOIS_GROUP_FIXES THEN
        ASM SET_TAC[];
        ASM SET_TAC[]];
      ASM_REWRITE_TAC[]] THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                   `IMAGE (f:B->B) P`] NUMBER_FIELD_PRIME_IDEAL_ABOVE) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC
   `E = ideal_generated (ring_of_integers l) (IMAGE (h:A->B) p)` THEN
  SUBGOAL_THEN `ring_ideal (ring_of_integers l) (E:B->bool) /\
                ~(E = {ring_0 l})`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "E" THEN REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_of_integers l:B ring`;
                   `h:A->B`; `p:A->bool`]
      IDEAL_GENERATED_MONOMORPHIC_IMAGE_EQ_0) THEN
    ASM_SIMP_TAC[RING_MONOMORPHISM_RING_OF_INTEGERS; PRIME_IMP_RING_IDEAL;
                 RING_OF_INTEGERS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                 `ideal_product (ring_of_integers l)
                    (group_carrier(galois_group(k:A ring,l:B ring) h))
                    (\f:B->B. IMAGE f P)`;
                 `ideal_pow (ring_of_integers l) (E:B->bool)
                    (residue_degree (ring_of_integers k,ring_of_integers l)
                                    (h:A->B) P)`]
    DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IDEAL_PRODUCT; RING_IDEAL_IDEAL_POW;
                 IDEAL_POW_EQ_ZERO; RING_OF_INTEGERS] THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                   `group_carrier(galois_group(k:A ring,l:B ring) h)`;
                   `\f:B->B. IMAGE f P`] IDEAL_PRODUCT_EQ_ZERO) THEN
    ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; RING_OF_INTEGERS] THEN
    DISCH_THEN(K ALL_TAC) THEN REWRITE_TAC[NOT_EXISTS_THM] THEN
    X_GEN_TAC `f:B->B` THEN FIRST_ASSUM(MP_TAC o SPEC `f:B->B`) THEN
    CONV_TAC TAUT;
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN
  X_GEN_TAC `Q:B->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`;
                 `group_carrier(galois_group(k:A ring,l:B ring) h)`;
                 `\f:B->B. IMAGE f P`] IDEAL_VALUATION_IDEAL_PRODUCT) THEN
  ASM_SIMP_TAC[RING_OF_INTEGERS; PRIME_IMP_RING_IDEAL] THEN
  DISCH_THEN SUBST1_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_POW; RING_OF_INTEGERS] THEN
  SUBGOAL_THEN
   `nsum (group_carrier(galois_group(k:A ring,l:B ring) h))
         (\f:B->B. ideal_valuation (ring_of_integers l) Q (IMAGE f P)) =
    CARD {f | f IN group_carrier(galois_group(k,l) h) /\ IMAGE f P = Q}`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[CARD_EQ_NSUM; FINITE_RESTRICT; NSUM_RESTRICT_SET] THEN
    MATCH_MP_TAC NSUM_EQ THEN X_GEN_TAC `f:B->B` THEN DISCH_TAC THEN
    REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`;
                   `IMAGE (f:B->B) P`] IDEAL_VALUATION_PRIME) THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  ASM_CASES_TAC `IMAGE (h:A->B) p SUBSET Q` THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                   `P:B->bool`; `Q:B->bool`]
      NUMBER_FIELD_GALOIS_GROUP_TRANSITIVE) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `g:B->B` (CONJUNCTS_THEN2 ASSUME_TAC
      (SUBST_ALL_TAC o SYM))) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `P:B->bool`; `g:B->B`]
      CARD_GALOIS_GROUP_IMAGE_FIBER) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                   `P:B->bool`] NUMBER_FIELD_DECOMPOSITION_GROUP) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o CONJUNCT1) THEN
    SUBGOAL_THEN
     `!R. prime_ideal (ring_of_integers l) R /\ IMAGE (h:A->B) p SUBSET R
          ==> {x | x IN ring_carrier(ring_of_integers k) /\ h x IN R} = p`
    ASSUME_TAC THENL
     [X_GEN_TAC `R:B->bool` THEN STRIP_TAC THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                     `R:B->bool`] NUMBER_FIELD_PRIME_IDEAL_ABOVE) THEN
      ASM_REWRITE_TAC[] THEN
      DISCH_THEN(MP_TAC o CONJUNCT2 o CONJUNCT2 o CONJUNCT2) THEN
      MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
        PRIME_IDEAL_IMP_SUBSET) THEN
      ASM_REWRITE_TAC[] THEN SET_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ideal_valuation (ring_of_integers l) (IMAGE (g:B->B) P) E =
      ramification_index (ring_of_integers k,ring_of_integers l) (h:A->B)
        (IMAGE g P)`
    SUBST1_TAC THENL
     [REWRITE_TAC[ramification_index] THEN EXPAND_TAC "E" THEN
      AP_TERM_TAC THEN AP_TERM_TAC THEN AP_TERM_TAC THEN
      CONV_TAC SYM_CONV THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `g:B->B`; `P:B->bool`]
      NUMBER_FIELD_RAMIFICATION_INDEX_CONJUGATE) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[] THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `P:B->bool`) THEN ASM_SIMP_TAC[];
      DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[MULT_SYM]];
    SUBGOAL_THEN
     `{f | f IN group_carrier(galois_group(k:A ring,l:B ring) h) /\
           IMAGE f P = Q} = {}`
    SUBST1_TAC THENL
     [ONCE_REWRITE_TAC[EXTENSION] THEN REWRITE_TAC[NOT_IN_EMPTY] THEN
      X_GEN_TAC `f:B->B` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
      UNDISCH_TAC `~(IMAGE (h:A->B) p SUBSET Q)` THEN REWRITE_TAC[] THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN ASM_SIMP_TAC[];
      REWRITE_TAC[CARD_CLAUSES]] THEN
    SUBGOAL_THEN `ideal_valuation (ring_of_integers l) Q (E:B->bool) = 0`
     (fun th -> REWRITE_TAC[th; MULT_CLAUSES]) THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`; `E:B->bool`]
      IDEAL_VALUATION_EQ_0) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN SUBST1_TAC THEN
    UNDISCH_TAC `~(IMAGE (h:A->B) p SUBSET Q)` THEN
    REWRITE_TAC[CONTRAPOS_THM] THEN DISCH_TAC THEN
    TRANS_TAC SUBSET_TRANS `E:B->bool` THEN ASM_REWRITE_TAC[] THEN
    EXPAND_TAC "E" THEN REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC IDEAL_GENERATED_INC THEN ASM_REWRITE_TAC[] THEN
    TRANS_TAC SUBSET_TRANS `P:B->bool` THEN
    ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET]]);;

let NUMBER_FIELD_GALOIS_PRODUCT_IDEAL = prove
 (`!k:A ring j.
        number_field k /\
        galois_extension (subfield_generated k {ring_0 k},k) I /\
        ring_ideal (ring_of_integers k) j /\ ~(j = {ring_0 k})
        ==> ideal_product (ring_of_integers k)
              (group_carrier(galois_group(subfield_generated k {ring_0 k},k) I))
              (\f. IMAGE f j) =
            ideal_generated (ring_of_integers k)
              {ring_of_num k (ideal_norm (ring_of_integers k) j)}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_RING_OF_INTEGERS) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN
   `FINITE(group_carrier(galois_group
      (subfield_generated k {ring_0 k},k) (I:A->A)))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_GALOIS_GROUP THEN
    FIRST_ASSUM(MP_TAC o GEN_REWRITE_RULE I [number_field]) THEN SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!q. prime_ideal (ring_of_integers (k:A ring)) q /\ ~(q = {ring_0 k})
        ==> ideal_product (ring_of_integers k)
              (group_carrier(galois_group
                 (subfield_generated k {ring_0 k},k) I))
              (\f. IMAGE f q) =
            ideal_generated (ring_of_integers k)
              {ring_of_num k (ideal_norm (ring_of_integers k) q)}`
  ASSUME_TAC THENL
   [X_GEN_TAC `q:A->bool` THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `q:A->bool`]
      RING_OF_INTEGERS_PRIME_IDEAL_ABOVE) THEN
    ASM_REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
    DISCH_THEN(X_CHOOSE_THEN `p:num` STRIP_ASSUME_TAC o CONJUNCT1) THEN
    MP_TAC(ISPECL [`k:A ring`; `q:A->bool`; `p:num`]
      RING_OF_INTEGERS_IDEAL_NORM_PRIME_Q) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `q:A->bool`]
      RESIDUE_DEGREE_PRIME_SUBFIELD) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    SUBGOAL_THEN
     `ring_homomorphism(subfield_generated k {ring_0 k},k) (I:A->A) /\
      ring_homomorphism(ring_of_integers(subfield_generated k {ring_0 k}),
                        ring_of_integers k) (I:A->A)`
    STRIP_ASSUME_TAC THENL
     [REWRITE_TAC[RING_HOMOMORPHISM_SUBFIELD_INCLUSION] THEN
      MATCH_MP_TAC RING_HOMOMORPHISM_RING_OF_INTEGERS THEN
      REWRITE_TAC[RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_of_num k p IN
      ring_carrier(ring_of_integers(subfield_generated k {ring_0 k:A}))`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers(subfield_generated k {ring_0 k:A})`;
                     `p:num`] RING_OF_NUM) THEN
      REWRITE_TAC[RING_OF_INTEGERS; RING_OF_NUM_SUBFIELD_GENERATED];
      ALL_TAC] THEN
    MP_TAC(ISPECL
     [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
      `ideal_generated (ring_of_integers(subfield_generated k {ring_0 k}))
                       {ring_of_num k p:A}`; `q:A->bool`]
      NUMBER_FIELD_GALOIS_PRODUCT_PRIME) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; CONJUNCT2 SUBFIELD_GENERATED] THEN
      MP_TAC(ISPECL [`k:A ring`; `p:num`]
        RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL) THEN
      ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL];
      DISCH_THEN SUBST1_TAC] THEN
    MP_TAC(ISPECL
     [`ring_of_integers(subfield_generated k {ring_0 k}):A ring`;
      `ring_of_integers k:A ring`; `I:A->A`; `{ring_of_num k p:A}`]
     IDEAL_GENERATED_IMAGE_IDEAL_GENERATED) THEN
    ASM_REWRITE_TAC[SING_SUBSET; IMAGE_I] THEN DISCH_THEN SUBST1_TAC THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:num`] RING_OF_NUM) THEN
    REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_TAC THEN
    ASM_SIMP_TAC[IDEAL_POW_PRINCIPAL] THEN
    REWRITE_TAC[RING_OF_INTEGERS; RING_OF_NUM_EXP];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!j. ring_ideal (ring_of_integers (k:A ring)) j /\
        ~(j = {ring_0(ring_of_integers k)})
        ==> ideal_product (ring_of_integers k)
              (group_carrier(galois_group
                 (subfield_generated k {ring_0 k},k) I))
              (\f. IMAGE f j) =
            ideal_generated (ring_of_integers k)
              {ring_of_num k (ideal_norm (ring_of_integers k) j)}`
   (fun th -> ASM_SIMP_TAC[th; RING_OF_INTEGERS]) THEN
  MATCH_MP_TAC DEDEKIND_IDEAL_INDUCT THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN CONJ_TAC THENL
   [REWRITE_TAC[IDEAL_NORM_CARRIER; RING_OF_NUM_1] THEN
    SUBGOAL_THEN
     `ideal_generated (ring_of_integers k) {ring_1 k} =
      ring_carrier(ring_of_integers(k:A ring))`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_1 k:A`]
        IDEAL_GENERATED_SING_EQ_CARRIER) THEN
      MP_TAC(ISPEC `ring_of_integers k:A ring` RING_1) THEN
      MP_TAC(ISPEC `ring_of_integers k:A ring` RING_UNIT_1) THEN
      REWRITE_TAC[RING_OF_INTEGERS] THEN SIMP_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ideal_product (ring_of_integers k)
        (group_carrier(galois_group
           (subfield_generated k {ring_0 k},k) (I:A->A)))
        (\f. ring_carrier(ring_of_integers k)) =
      ring_carrier(ring_of_integers k)`
    ASSUME_TAC THENL
     [FIRST_X_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o ONCE_DEPTH_CONV)
        [SYM th] THEN GEN_REWRITE_TAC RAND_CONV [SYM th]) THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                     `group_carrier(galois_group
                        (subfield_generated k {ring_0 k},k) (I:A->A))`;
                     `\f:A->A. ring_1 k:A`] IDEAL_PRODUCT_PRINCIPAL) THEN
      MP_TAC(ISPEC `ring_of_integers k:A ring` RING_1) THEN
      REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_TAC THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                     `group_carrier(galois_group
                        (subfield_generated k {ring_0 k},k) (I:A->A))`]
        RING_PRODUCT_1) THEN
      REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN SUBST1_TAC THEN
      REFL_TAC;
      ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN
    FIRST_X_ASSUM(fun th -> GEN_REWRITE_TAC RAND_CONV [SYM th]) THEN
    MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN X_GEN_TAC `f:A->A` THEN
    DISCH_TAC THEN REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                   `f:A->A`] GALOIS_GROUP_RING_OF_INTEGERS_AUTOMORPHISM) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`q:A->bool`; `i:A->bool`] THEN STRIP_TAC THEN
  TRANS_TAC EQ_TRANS
   `ideal_product (ring_of_integers k)
      (group_carrier(galois_group
         (subfield_generated k {ring_0 k},k) (I:A->A)))
      (\f. ideal_prod (ring_of_integers k) (IMAGE f q) (IMAGE f i))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN X_GEN_TAC `f:A->A` THEN DISCH_TAC THEN
