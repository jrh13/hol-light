(* The S-units are the units of O_S.                                         *)
let S_UNIT_GROUP_RING_OF_S_INTEGERS = prove
 (`!k:A ring S.
        number_field k
        ==> s_unit_group k S =
            subgroup_generated (unit_group k)
              {x | ring_unit (ring_of_s_integers (ring_of_integers k,k) I S)
                             x} /\
            group_isomorphism
             (unit_group(ring_of_s_integers (ring_of_integers k,k) I S),
              s_unit_group k S) I`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_FRACTION_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [REWRITE_TAC[s_unit_group] THEN AP_TERM_TAC THEN
    GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `x:A` THEN
    ASM_SIMP_TAC[IN_ELIM_THM; RING_UNIT_RING_OF_S_INTEGERS; RING_OF_INTEGERS;
                 I_THM];
    DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[ring_of_s_integers] THEN
    REWRITE_TAC[UNIT_GROUP_SUBRING_GENERATED]]);;

let FINITELY_GENERATED_UNIT_GROUP_RING_OF_S_INTEGERS = prove
 (`!k:A ring S.
        number_field k /\ FINITE S
        ==> finitely_generated_group
             (unit_group(ring_of_s_integers (ring_of_integers k,k) I S))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `S:(A->bool)->bool`]
    S_UNIT_GROUP_RING_OF_S_INTEGERS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o MATCH_MP GROUP_ISOMORPHISM_IMP_ISOMORPHIC o
    CONJUNCT2) THEN
  DISCH_THEN(SUBST1_TAC o MATCH_MP ISOMORPHIC_GROUP_FINITE_GENERATION) THEN
  ASM_SIMP_TAC[FINITELY_GENERATED_S_UNIT_GROUP]);;
