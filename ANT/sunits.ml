(* ========================================================================= *)
(* S-units of a number field k and the finiteness of K(S,m) (Silverman,      *)
(* The Arithmetic of Elliptic Curves, VIII.1.6), for a set S of nonzero      *)
(* primes of O = ring_of_integers k (elements of S that are not nonzero      *)
(* primes are ignored).                                                      *)
(*                                                                           *)
(*   s_unit_group k S = the subgroup of the multiplicative group of k of the *)
(*                      x with v_P(x) = 0 for every nonzero prime P NOTIN S  *)
(*                                                                           *)
(* (v_P(x) is dedekind_valuation (ring_of_integers k,k) I P x, as in         *)
(* ANT/nf_valuation.ml.) Main results: the characterization S_UNIT_GROUP     *)
(* (and S_UNIT_GROUP_POW; products in the group are products in k,           *)
(* S_UNIT_GROUP_SUM), commutativity, the S-units for S = {} are the units of *)
(* O (S_UNIT_GROUP_EMPTY), monotonicity in S; for finite S the S-unit group  *)
(* is finitely generated (FINITELY_GENERATED_S_UNIT_GROUP, and explicitly    *)
(* S_UNIT_GROUP_GENERATORS), with one finite set t of generators such that   *)
(* for every m >= 1 each S-unit is prod_{v IN t} v^(n v) times the m-th      *)
(* power of an S-unit, all n v < m (S_UNIT_GROUP_GENERATORS_MOD_POW). For a  *)
(* finite set t of primes (independent of S, m and x) every nonzero x with m *)
(* dividing v_P(x) for all P NOTIN S is u y^m with u an (S UNION t)-unit     *)
(* (NUMBER_FIELD_POW_S_UNIT_DECOMPOSITION); so for finite S and m >= 1 these *)
(* x lie in finitely many classes modulo m-th powers: x = c y^m with c in a  *)
(* fixed finite set of such elements (NUMBER_FIELD_KSM_FINITE), equivalently *)
(* their cosets modulo the m-th powers form a finite set                     *)
(* (NUMBER_FIELD_KSM_QUOTIENT_FINITE). The S-units are the units of the ring *)
(* of S-integers ring_of_s_integers (O,k) I S, defined in ANT/s_integers.ml: *)
(* S_UNIT_GROUP_RING_OF_S_INTEGERS; for finite S its unit group is finitely  *)
(* generated (FINITELY_GENERATED_UNIT_GROUP_RING_OF_S_INTEGERS).             *)
(*                                                                           *)
(* Routes. Generation: the valuations at the finitely many primes of S give  *)
(* a homomorphism into a product of copies of integer_group; its image is a  *)
(* subgroup of a finitely generated abelian group                            *)
(* (FINITELY_GENERATED_ABELIAN_SUBGROUP), its kernel the units of O          *)
(* (NUMBER_FIELD_VALUATION_UNIT, UNIT_GROUP_SUBRING_GENERATED), finitely     *)
(* generated by NUMBER_FIELD_UNIT_GROUP_FINITELY_GENERATED; then             *)
(* FINITELY_GENERATED_GROUP_EXTENSION. Generators modulo m-th powers: the    *)
(* exponents for the generators of FINITELY_GENERATED_ABELIAN_GROUP_POW      *)
(* of Library/grouptheory.ml divided by m. K(S,m): take the finite set t of  *)
(* NUMBER_FIELD_VALUATION_PRINCIPAL_OUTSIDE and y with v_P(y) = v_P(x) / m   *)
(* for P NOTIN S UNION t; then x / y^m is an (S UNION t)-unit, and the       *)
(* (S UNION t)-units are finitely many cosets of their m-th powers           *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW).                               *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/grouptheory.ml                       *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_POW), ANT/numfield.ml,                  *)
(* ANT/nf_valuation.ml, ANT/fingen_group.ml                                  *)
(* (FINITELY_GENERATED_GROUP_EXTENSION,                                      *)
(* FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW), Library/ring_groups.ml         *)
(* (unit_group), ANT/s_integers.ml (ring_of_s_integers) and                  *)
(* ANT/complex_embeddings.ml (NUMBER_FIELD_UNIT_GROUP_FINITELY_GENERATED;    *)
(* hence Multivariate).                                                      *)
(* ========================================================================= *)

