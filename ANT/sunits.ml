let s_unit_group = new_definition
 `s_unit_group (k:A ring) (S:(A->bool)->bool) =
  subgroup_generated (unit_group k)
   {x | x IN ring_carrier k /\ ~(x = ring_0 k) /\
        !P. prime_ideal (ring_of_integers k) P /\ ~(P = {ring_0 k}) /\
            ~(P IN S)
            ==> dedekind_valuation (ring_of_integers k,k) I P x = &0}`;;

(* ------------------------------------------------------------------------- *)
(* The S-unit group.                                                         *)
(* ------------------------------------------------------------------------- *)

let S_UNIT_GROUP = prove
 (`!k:A ring S.
        number_field k
        ==> group_carrier(s_unit_group k S) =
            {x | x IN ring_carrier k /\ ~(x = ring_0 k) /\
                 !P. prime_ideal (ring_of_integers k) P /\
                     ~(P = {ring_0 k}) /\ ~(P IN S)
                     ==> dedekind_valuation (ring_of_integers k,k) I P x =
                         &0} /\
            group_id(s_unit_group k S) = ring_1 k /\
            group_inv(s_unit_group k S) = ring_inv k /\
            group_mul(s_unit_group k S) = ring_mul k`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  REWRITE_TAC[s_unit_group; CONJUNCT2 SUBGROUP_GENERATED; UNIT_GROUP] THEN
  MATCH_MP_TAC CARRIER_SUBGROUP_GENERATED_SUBGROUP THEN
  REWRITE_TAC[subgroup_of; UNIT_GROUP; SUBSET; IN_ELIM_THM] THEN
  ASM_SIMP_TAC[FIELD_UNIT; RING_1; FIELD_NONTRIVIAL;
               NUMBER_FIELD_VALUATION_1] THEN
  CONJ_TAC THEN REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_SIMP_TAC[RING_INV; RING_MUL; FIELD_INV_EQ_0; INTEGRAL_DOMAIN_MUL_EQ_0;
               FIELD_IMP_INTEGRAL_DOMAIN; NUMBER_FIELD_VALUATION_INV;
               NUMBER_FIELD_VALUATION_MUL; INT_NEG_0; INT_ADD_LID]);;

let S_UNIT_GROUP_POW = prove
 (`!k:A ring S x n. group_pow (s_unit_group k S) x n = ring_pow k x n`,
  REWRITE_TAC[s_unit_group; GROUP_POW_SUBGROUP_GENERATED; UNIT_GROUP_POW]);;

let ABELIAN_S_UNIT_GROUP = prove
 (`!k:A ring S. abelian_group(s_unit_group k S)`,
  SIMP_TAC[s_unit_group; ABELIAN_SUBGROUP_GENERATED; ABELIAN_UNIT_GROUP]);;

let S_UNIT_GROUP_EMPTY = prove
 (`!k:A ring.
        number_field k
        ==> group_carrier(s_unit_group k {}) =
            {x | ring_unit (ring_of_integers k) x}`,
  SIMP_TAC[S_UNIT_GROUP; NOT_IN_EMPTY] THEN REPEAT STRIP_TAC THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `x:A` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN ASM_CASES_TAC `(x:A) IN ring_carrier k` THEN
  ASM_SIMP_TAC[NUMBER_FIELD_VALUATION_UNIT] THEN
  ASM_MESON_TAC[RING_UNIT_IN_CARRIER; RING_OF_INTEGERS_SUBSET; SUBSET]);;

let S_UNIT_GROUP_MONO = prove
 (`!k:A ring S S'.
        S SUBSET S'
        ==> group_carrier(s_unit_group k S) SUBSET
            group_carrier(s_unit_group k S')`,
  REWRITE_TAC[s_unit_group] THEN REPEAT STRIP_TAC THEN
  MATCH_MP_TAC SUBGROUP_GENERATED_MONO THEN ASM SET_TAC[]);;

let S_UNIT_GROUP_SUM = prove
 (`!k:A ring S s (f:K->A).
        FINITE s /\ (!i. i IN s ==> f i IN group_carrier(s_unit_group k S))
        ==> group_sum (s_unit_group k S) s f = ring_product k s f`,
  GEN_TAC THEN GEN_TAC THEN GEN_REWRITE_TAC I [SWAP_FORALL_THM] THEN
  GEN_TAC THEN REWRITE_TAC[IMP_CONJ] THEN
  MATCH_MP_TAC FINITE_INDUCT_STRONG THEN
  SIMP_TAC[CONJUNCT1(SPEC_ALL GROUP_SUM_CLAUSES_EXISTS); FINITE_RESTRICT;
           ABELIAN_GROUP_SUM_CLAUSES; ABELIAN_S_UNIT_GROUP; FORALL_IN_INSERT;
           RING_PRODUCT_CLAUSES] THEN
  REWRITE_TAC[s_unit_group; CONJUNCT2 SUBGROUP_GENERATED; UNIT_GROUP] THEN
  REPEAT STRIP_TAC THEN FIRST_X_ASSUM(MP_TAC o MATCH_MP
   (REWRITE_RULE[SUBSET] GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET)) THEN
  SIMP_TAC[UNIT_GROUP; IN_ELIM_THM; RING_UNIT_IN_CARRIER]);;

(* ------------------------------------------------------------------------- *)
(* Finite generation.                                                        *)
(* ------------------------------------------------------------------------- *)

(* The valuations at the nonzero primes in S give a homomorphism from the    *)
(* S-units to a finite product of copies of integer_group whose kernel is    *)
(* the carrier of s_unit_group k {}, the units of O.                         *)

let FINITELY_GENERATED_S_UNIT_GROUP = prove
 (`!k:A ring S.
        number_field k /\ FINITE S
        ==> finitely_generated_group(s_unit_group k S)`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `S' = {P | P IN S /\ prime_ideal (ring_of_integers k) P /\
                        ~(P = {ring_0 k:A})}` THEN
  MP_TAC(ISPECL [`s_unit_group (k:A ring) S`;
                 `product_group S' (\P:A->bool. integer_group)`;
                 `\x:A. RESTRICTION S'
                         (\P. dedekind_valuation (ring_of_integers k,k) I P x)`]
       FINITELY_GENERATED_GROUP_EXTENSION) THEN
  DISCH_THEN MATCH_MP_TAC THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q /\ r) ==> p /\ q /\ r`) THEN CONJ_TAC THENL
   [REWRITE_TAC[GROUP_HOMOMORPHISM; SUBSET; FORALL_IN_IMAGE; PRODUCT_GROUP;
                RESTRICTION_IN_CARTESIAN_PRODUCT; INTEGER_GROUP; IN_UNIV;
                RESTRICTION_EXTENSION] THEN
    ASM_SIMP_TAC[S_UNIT_GROUP; IN_ELIM_THM; RESTRICTION] THEN
    EXPAND_TAC "S'" THEN SIMP_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC NUMBER_FIELD_VALUATION_MUL THEN ASM_REWRITE_TAC[];
    DISCH_TAC THEN CONJ_TAC] THENL
   [REWRITE_TAC[s_unit_group] THEN
    SIMP_TAC[SUBGROUP_GENERATED_IDEMPOT_GEN; GROUP_KERNEL_SUBSET_CARRIER] THEN
    REWRITE_TAC[GSYM s_unit_group] THEN
    SUBGOAL_THEN
     `group_kernel (s_unit_group k S,product_group S' (\P. integer_group))
       (\x:A. RESTRICTION S'
               (\P. dedekind_valuation (ring_of_integers k,k) I P x)) =
      group_carrier(s_unit_group k {})`
    SUBST1_TAC THENL
     [REWRITE_TAC[group_kernel; PRODUCT_GROUP; INTEGER_GROUP;
                  RESTRICTION_EXTENSION] THEN
      ASM_SIMP_TAC[S_UNIT_GROUP; NOT_IN_EMPTY] THEN
      GEN_REWRITE_TAC I [EXTENSION] THEN EXPAND_TAC "S'" THEN
      REWRITE_TAC[IN_ELIM_THM] THEN MESON_TAC[];
      MP_TAC(ISPECL [`k:A ring`; `ring_carrier(ring_of_integers k:A ring)`]
        UNIT_GROUP_SUBRING_GENERATED) THEN
      ASM_SIMP_TAC[RING_OF_INTEGERS_SUBRING; S_UNIT_GROUP_EMPTY] THEN
      DISCH_THEN(MP_TAC o MATCH_MP ISOMORPHIC_GROUP_FINITE_GENERATION o
        MATCH_MP GROUP_ISOMORPHISM_IMP_ISOMORPHIC o CONJUNCT2) THEN
      ASM_SIMP_TAC[NUMBER_FIELD_UNIT_GROUP_FINITELY_GENERATED]];
    MATCH_MP_TAC FINITELY_GENERATED_ABELIAN_SUBGROUP THEN
    ASM_SIMP_TAC[SUBGROUP_GROUP_IMAGE; FINITELY_GENERATED_PRODUCT_GROUP;
                 ABELIAN_PRODUCT_GROUP; ABELIAN_INTEGER_GROUP;
                 CYCLIC_IMP_FINITELY_GENERATED_GROUP; CYCLIC_INTEGER_GROUP] THEN
    MATCH_MP_TAC FINITE_SUBSET THEN EXISTS_TAC `S:(A->bool)->bool` THEN
    ASM SET_TAC[]]);;

let S_UNIT_GROUP_GENERATORS = prove
 (`!k:A ring S.
        number_field k /\ FINITE S
        ==> ?t. FINITE t /\ t SUBSET group_carrier(s_unit_group k S) /\
                !x. x IN group_carrier(s_unit_group k S)
                    ==> ?n. x = ring_product k t (\y. ring_pow k y (n y))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `s_unit_group (k:A ring) S`
    FINITELY_GENERATED_ABELIAN_GROUP_POW) THEN
  ASM_SIMP_TAC[ABELIAN_S_UNIT_GROUP; FINITELY_GENERATED_S_UNIT_GROUP] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `t:A->bool` THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[] THEN X_GEN_TAC `x:A` THEN
  DISCH_THEN(fun th -> FIRST_X_ASSUM(MP_TAC o C MATCH_MP th)) THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `n:A->num` THEN
  DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[S_UNIT_GROUP_POW] THEN
  MATCH_MP_TAC S_UNIT_GROUP_SUM THEN ASM_REWRITE_TAC[] THEN
  X_GEN_TAC `y:A` THEN DISCH_TAC THEN
  REWRITE_TAC[GSYM(ISPECL [`k:A ring`; `S:(A->bool)->bool`]
                   S_UNIT_GROUP_POW)] THEN
  MATCH_MP_TAC GROUP_POW THEN ASM SET_TAC[]);;

let S_UNIT_GROUP_GENERATORS_MOD_POW = prove
 (`!k:A ring S.
        number_field k /\ FINITE S
        ==> ?t. FINITE t /\ t SUBSET group_carrier(s_unit_group k S) /\
                !m x. ~(m = 0) /\ x IN group_carrier(s_unit_group k S)
                      ==> ?n y. (!v. n v < m) /\
                                y IN group_carrier(s_unit_group k S) /\
                                x = ring_mul k
                                     (ring_product k t (\v. ring_pow k v (n v)))
                                     (ring_pow k y m)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `s_unit_group (k:A ring) S`
    FINITELY_GENERATED_ABELIAN_GROUP_POW) THEN
  ASM_SIMP_TAC[ABELIAN_S_UNIT_GROUP; FINITELY_GENERATED_S_UNIT_GROUP] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `t:A->bool` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MAP_EVERY X_GEN_TAC [`m:num`; `x:A`] THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `n:A->num` SUBST1_TAC) THEN
  MAP_EVERY EXISTS_TAC
   [`\v:A. n v MOD m`;
    `group_sum (s_unit_group k S) t
      (\v:A. group_pow (s_unit_group k S) v (n v DIV m))`] THEN
  ASM_REWRITE_TAC[MOD_LT_EQ; GROUP_SUM] THEN
  MP_TAC(ISPECL [`k:A ring`; `S:(A->bool)->bool`] S_UNIT_GROUP) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(fun th ->
    REWRITE_TAC[GSYM(CONJUNCT2(CONJUNCT2(CONJUNCT2 th)))]) THEN
  REWRITE_TAC[GSYM S_UNIT_GROUP_POW] THEN
  ASM_SIMP_TAC[GSYM S_UNIT_GROUP_SUM; GROUP_POW; REWRITE_RULE[SUBSET]
    (ASSUME `t SUBSET group_carrier(s_unit_group (k:A ring) S)`)] THEN
  MP_TAC(ISPECL [`k:A ring`; `S:(A->bool)->bool`] ABELIAN_S_UNIT_GROUP) THEN
  UNDISCH_TAC `t SUBSET group_carrier(s_unit_group (k:A ring) S)` THEN
  SPEC_TAC(`s_unit_group (k:A ring) S`,`G:A group`) THEN
  REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN
  W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_POW o
    rand o rand o snd) THEN
  ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_MUL o rand o snd) THEN
  ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC GROUP_SUM_EQ THEN
  ASM_SIMP_TAC[GROUP_POW_POW; GSYM GROUP_POW_ADD] THEN
  X_GEN_TAC `y:A` THEN DISCH_TAC THEN AP_TERM_TAC THEN
  MP_TAC(SPECL [`(n:A->num) y`; `m:num`] DIVISION) THEN
  ASM_REWRITE_TAC[] THEN ARITH_TAC);;

(* ------------------------------------------------------------------------- *)
(* The finiteness of K(S,m).                                                 *)
(* ------------------------------------------------------------------------- *)

(* For t as in NUMBER_FIELD_VALUATION_PRINCIPAL_OUTSIDE, every x with m      *)
(* dividing v_P(x) for all P NOTIN S is an (S UNION t)-unit times an m-th    *)
(* power y^m, where v_P(y) = v_P(x) div m for P NOTIN S UNION t.             *)

let NUMBER_FIELD_POW_S_UNIT_DECOMPOSITION = prove
 (`!k:A ring.
        number_field k
        ==> ?t. FINITE t /\
                !S m x. x IN ring_carrier k /\ ~(x = ring_0 k) /\
                        (!P. prime_ideal (ring_of_integers k) P /\
                             ~(P = {ring_0 k}) /\ ~(P IN S)
                             ==> &m divides dedekind_valuation
                                             (ring_of_integers k,k) I P x)
                        ==> ?y u. y IN ring_carrier k /\ ~(y = ring_0 k) /\
                                  u IN group_carrier
                                        (s_unit_group k (S UNION t)) /\
                                  x = ring_mul k u (ring_pow k y m)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP NUMBER_FIELD_VALUATION_PRINCIPAL_OUTSIDE) THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `t:(A->bool)->bool` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MAP_EVERY X_GEN_TAC [`S:(A->bool)->bool`; `m:num`; `x:A`] THEN
  STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC
   `\P. if P IN S then &0
        else dedekind_valuation (ring_of_integers k,k) I P (x:A) div &m`) THEN
  REWRITE_TAC[] THEN ANTS_TAC THENL
   [MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC `{P | prime_ideal (ring_of_integers k) P /\
                     ~(P = {ring_0 k}) /\
                     ~(dedekind_valuation (ring_of_integers k,k) I P (x:A) =
                       &0)}` THEN
    ASM_SIMP_TAC[NUMBER_FIELD_VALUATION_FINITE; SUBSET; IN_ELIM_THM] THEN
    MESON_TAC[INT_DIV_ZERO];
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `y:A` THEN STRIP_TAC] THEN
  EXISTS_TAC `ring_div k x (ring_pow k y m):A` THEN
  SUBGOAL_THEN `ring_pow k (y:A) m IN ring_carrier k /\
                ~(ring_pow k y m = ring_0 k)` STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_POW; FIELD_POW_EQ_0]; ALL_TAC] THEN
  ASM_SIMP_TAC[S_UNIT_GROUP; IN_ELIM_THM; RING_DIV; FIELD_DIV_EQ_0;
               IN_UNION; DE_MORGAN_THM; NUMBER_FIELD_VALUATION_DIV;
               NUMBER_FIELD_VALUATION_POW] THEN
  CONJ_TAC THENL
   [REPEAT STRIP_TAC THEN REWRITE_TAC[INT_SUB_0] THEN
    CONV_TAC SYM_CONV THEN REWRITE_TAC[INT_MUL_DIV_EQ] THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
    REWRITE_TAC[ring_div] THEN
    ASM_SIMP_TAC[GSYM RING_MUL_ASSOC; RING_INV; FIELD_MUL_LINV;
                 RING_MUL_RID]]);;

(* The (S UNION t)-units are finitely many cosets of their m-th powers       *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW).                               *)

let NUMBER_FIELD_KSM_FINITE = prove
 (`!k:A ring S m.
        number_field k /\ FINITE S /\ ~(m = 0)
        ==> ?t. FINITE t /\
                (!c. c IN t
                     ==> c IN ring_carrier k /\ ~(c = ring_0 k) /\
                         !P. prime_ideal (ring_of_integers k) P /\
                             ~(P = {ring_0 k}) /\ ~(P IN S)
                             ==> &m divides dedekind_valuation
                                             (ring_of_integers k,k) I P c) /\
                !x. x IN ring_carrier k /\ ~(x = ring_0 k) /\
                    (!P. prime_ideal (ring_of_integers k) P /\
                         ~(P = {ring_0 k}) /\ ~(P IN S)
                         ==> &m divides dedekind_valuation
                                         (ring_of_integers k,k) I P x)
                    ==> ?c y. c IN t /\ y IN ring_carrier k /\
                              ~(y = ring_0 k) /\
                              x = ring_mul k c (ring_pow k y m)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(X_CHOOSE_THEN `t0:(A->bool)->bool` STRIP_ASSUME_TAC o
    MATCH_MP NUMBER_FIELD_POW_S_UNIT_DECOMPOSITION) THEN
  MP_TAC(ISPECL [`s_unit_group (k:A ring) (S UNION t0)`; `m:num`]
    FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW) THEN
  ASM_SIMP_TAC[ABELIAN_S_UNIT_GROUP; FINITELY_GENERATED_S_UNIT_GROUP;
               FINITE_UNION; S_UNIT_GROUP_POW; S_UNIT_GROUP] THEN
  DISCH_THEN(X_CHOOSE_THEN `s0:A->bool` (CONJUNCTS_THEN2 ASSUME_TAC
    (CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "*")))) THEN
  EXISTS_TAC
   `{c:A | c IN s0 /\ c IN ring_carrier k /\ ~(c = ring_0 k) /\
           !P. prime_ideal (ring_of_integers k) P /\
               ~(P = {ring_0 k}) /\ ~(P IN S)
               ==> &m divides dedekind_valuation
                               (ring_of_integers k,k) I P c}` THEN
  SIMP_TAC[FINITE_RESTRICT; IN_ELIM_THM; ASSUME `FINITE(s0:A->bool)`] THEN
  X_GEN_TAC `x:A` THEN DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
    (CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "x"))) THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`S:(A->bool)->bool`; `m:num`; `x:A`]) THEN
  ASM_SIMP_TAC[S_UNIT_GROUP; LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`y:A`; `u:A`] THEN STRIP_TAC THEN
  REMOVE_THEN "*" (MP_TAC o SPEC `u:A`) THEN ASM_REWRITE_TAC[IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `a:A` (X_CHOOSE_THEN `w:A` STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier k /\ ~(a = ring_0 k)`
  STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC [`a:A`; `ring_mul k w y:A`] THEN
  ASM_SIMP_TAC[RING_MUL; INTEGRAL_DOMAIN_MUL_EQ_0; FIELD_IMP_INTEGRAL_DOMAIN;
               RING_MUL_POW; RING_POW; RING_MUL_ASSOC] THEN
  X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
  REMOVE_THEN "x" (MP_TAC o SPEC `P:A->bool`) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_VALUATION_MUL; NUMBER_FIELD_VALUATION_POW;
               RING_MUL; RING_POW; FIELD_POW_EQ_0; INTEGRAL_DOMAIN_MUL_EQ_0;
               FIELD_IMP_INTEGRAL_DOMAIN] THEN
  CONV_TAC INTEGER_RULE);;

(* The m-th powers of nonzero elements are the image of the m-th power map   *)
(* of the abelian group unit_group k, hence a subgroup, and x = c y^m has    *)
(* the coset of c.                                                           *)

let NUMBER_FIELD_KSM_QUOTIENT_FINITE = prove
 (`!k:A ring S m.
        number_field k /\ FINITE S /\ ~(m = 0)
        ==> FINITE {right_coset (unit_group k)
                     {ring_pow k y m | y | y IN ring_carrier k /\
                                           ~(y = ring_0 k)} x |
                    x | x IN ring_carrier k /\ ~(x = ring_0 k) /\
                        !P. prime_ideal (ring_of_integers k) P /\
                            ~(P = {ring_0 k}) /\ ~(P IN S)
                            ==> &m divides dedekind_valuation
                                            (ring_of_integers k,k) I P x}`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `S:(A->bool)->bool`; `m:num`]
    NUMBER_FIELD_KSM_FINITE) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `t:A->bool` STRIP_ASSUME_TAC) THEN
  ABBREV_TAC `H = {ring_pow k y m | y | y IN ring_carrier k /\
                                       ~(y = ring_0 k:A)}` THEN
  SUBGOAL_THEN `(H:A->bool) subgroup_of unit_group k` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`unit_group k:A group`; `m:num`]
      ABELIAN_GROUP_HOMOMORPHISM_POWERING) THEN
    REWRITE_TAC[ABELIAN_UNIT_GROUP] THEN
    DISCH_THEN(MP_TAC o MATCH_MP SUBGROUP_GROUP_IMAGE) THEN
    MATCH_MP_TAC(TAUT `(p <=> q) ==> p ==> q`) THEN
    AP_THM_TAC THEN AP_TERM_TAC THEN EXPAND_TAC "H" THEN
    SIMP_TAC[group_image; FIELD_UNIT_GROUP; UNIT_GROUP_POW;
             ASSUME `field(k:A ring)`] THEN
    REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM; IN_DIFF; IN_SING] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC FINITE_SUBSET THEN
  EXISTS_TAC `IMAGE (right_coset (unit_group k) (H:A->bool)) t` THEN
  ASM_SIMP_TAC[FINITE_IMAGE] THEN
  REWRITE_TAC[SUBSET; FORALL_IN_GSPEC; IN_IMAGE] THEN
  X_GEN_TAC `x:A` THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:A` (X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC)) THEN
  EXISTS_TAC `c:A` THEN ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `c:A`) THEN ASM_REWRITE_TAC[] THEN
  STRIP_TAC THEN
  MP_TAC(ISPECL [`unit_group k:A group`; `H:A->bool`;
                 `ring_mul k c (ring_pow k y m):A`; `c:A`] RIGHT_COSET_EQ) THEN
  ASM_SIMP_TAC[FIELD_UNIT_GROUP; IN_DIFF; IN_SING; RING_MUL; RING_POW;
               FIELD_IMP_INTEGRAL_DOMAIN;
               INTEGRAL_DOMAIN_MUL_EQ_0; INTEGRAL_DOMAIN_POW_EQ_0] THEN
  DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[group_div; UNIT_GROUP] THEN EXPAND_TAC "H" THEN
  REWRITE_TAC[IN_ELIM_THM] THEN EXISTS_TAC `y:A` THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `ring_inv k (c:A) IN ring_carrier k /\
                ring_mul k (ring_inv k c) c = ring_1 k`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_INV; FIELD_MUL_LINV]; ALL_TAC] THEN
  RING_TAC);;

