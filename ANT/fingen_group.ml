(* ------------------------------------------------------------------------- *)
(* Extensions and m-th powers.                                               *)
(* ------------------------------------------------------------------------- *)

let FINITELY_GENERATED_GROUP_EXTENSION = prove
 (`!G H (f:A->B).
        group_homomorphism(G,H) f /\
        finitely_generated_group(subgroup_generated G (group_kernel(G,H) f)) /\
        finitely_generated_group(subgroup_generated H (group_image(G,H) f))
        ==> finitely_generated_group G`,
  let lemma = prove
   (`!G h:A->bool.
        h subgroup_of G /\ finitely_generated_group(subgroup_generated G h)
        ==> ?s. FINITE s /\ s SUBSET h /\
                group_carrier(subgroup_generated G s) = h`,
    REWRITE_TAC[FINITELY_GENERATED_GROUP] THEN
    MESON_TAC[SUBGROUP_GENERATED_IDEMPOT_GEN;
              CARRIER_SUBGROUP_GENERATED_SUBGROUP]) in
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`H:B group`; `group_image(G,H) (f:A->B)`] lemma) THEN
  MP_TAC(ISPECL [`G:A group`; `group_kernel(G,H) (f:A->B)`] lemma) THEN
  ASM_SIMP_TAC[SUBGROUP_GROUP_KERNEL; SUBGROUP_GROUP_IMAGE] THEN
  DISCH_THEN(X_CHOOSE_THEN `s:A->bool` STRIP_ASSUME_TAC) THEN
  REWRITE_TAC[group_image; CONJ_ASSOC; FINITE_SUBSET_IMAGE] THEN
  REWRITE_TAC[LEFT_AND_EXISTS_THM; LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`t:B->bool`; `u:A->bool`] THEN
  DISCH_THEN(CONJUNCTS_THEN2 STRIP_ASSUME_TAC MP_TAC) THEN
  ASM_SIMP_TAC[SUBGROUP_GENERATED_BY_HOMOMORPHIC_IMAGE] THEN DISCH_TAC THEN
  REWRITE_TAC[FINITELY_GENERATED_GROUP] THEN
  EXISTS_TAC `s UNION u:A->bool` THEN
  ASM_REWRITE_TAC[FINITE_UNION; UNION_SUBSET; SUBGROUP_GENERATED_SUPERSET] THEN
  CONJ_TAC THENL
   [ASM_MESON_TAC[GROUP_KERNEL_SUBSET_CARRIER; SUBSET_TRANS]; ALL_TAC] THEN
  MP_TAC(ISPECL [`G:A group`; `H:B group`; `f:A->B`;
                 `group_carrier(subgroup_generated G (s UNION u:A->bool))`]
    GROUP_HOMOMORPHISM_PREIMAGE_IMAGE) THEN
  MP_TAC(ISPECL [`G:A group`; `s:A->bool`; `s UNION u:A->bool`]
    SUBGROUP_GENERATED_MONO) THEN
  MP_TAC(ISPECL [`G:A group`; `u:A->bool`; `s UNION u:A->bool`]
    SUBGROUP_GENERATED_MONO) THEN
  ASM_REWRITE_TAC[SUBGROUP_SUBGROUP_GENERATED; SUBSET_UNION] THEN
  UNDISCH_TAC
   `IMAGE (f:A->B) (group_carrier(subgroup_generated G u)) =
    IMAGE f (group_carrier G)` THEN
  SET_TAC[]);;

let FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW = prove
 (`!G:A group m.
        abelian_group G /\ finitely_generated_group G /\ ~(m = 0)
        ==> ?s. FINITE s /\ s SUBSET group_carrier G /\
                !x. x IN group_carrier G
                    ==> ?a y. a IN s /\ y IN group_carrier G /\
                              x = group_mul G a (group_pow G y m)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `G:A group` FINITELY_GENERATED_ABELIAN_GROUP_POW) THEN
  ASM_REWRITE_TAC[SUBSET] THEN
  DISCH_THEN(X_CHOOSE_THEN `t:A->bool` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `IMAGE (\r. group_sum G t (\y. group_pow G y (r y)))
                    {r | (!y:A. y IN t ==> r y IN {i | i < m}) /\
                         (!y. ~(y IN t) ==> r y = 0)}` THEN
  ASM_SIMP_TAC[FINITE_IMAGE; FINITE_FUNSPACE; FINITE_NUMSEG_LT] THEN
  REWRITE_TAC[FORALL_IN_IMAGE; GROUP_SUM] THEN
  X_GEN_TAC `x:A` THEN DISCH_THEN(fun th ->
    FIRST_X_ASSUM(X_CHOOSE_THEN `n:A->num` SUBST1_TAC o C MATCH_MP th)) THEN
  MAP_EVERY EXISTS_TAC
   [`group_sum G t (\y:A. group_pow G y (n y MOD m))`;
    `group_sum G t (\y:A. group_pow G y (n y DIV m))`] THEN
  REWRITE_TAC[GROUP_SUM; IN_IMAGE; IN_ELIM_THM] THEN CONJ_TAC THENL
   [EXISTS_TAC `\y:A. if y IN t then n y MOD m else 0` THEN
    ASM_SIMP_TAC[MOD_LT_EQ];
    ALL_TAC] THEN
  W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_POW o
    rand o rand o snd) THEN
  ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_MUL o rand o snd) THEN
  ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC GROUP_SUM_EQ THEN
  ASM_SIMP_TAC[GROUP_POW_POW; GSYM GROUP_POW_ADD] THEN
  X_GEN_TAC `y:A` THEN DISCH_TAC THEN AP_TERM_TAC THEN
  MP_TAC(SPECL [`(n:A->num) y`; `m:num`] DIVISION) THEN
  ASM_REWRITE_TAC[] THEN ARITH_TAC);;

