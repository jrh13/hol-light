(* A uniform bound 2^(L * N * CARD t) for the sizes of the products of       *)
(* powers x^(n x), 0 <= n x <= N, of the elements x of a finite set t.       *)

let GROUP_SUM_POW_REAL_MULTIPLICATIVE_BOUND =
  let lemma = prove
   (`!w:real->bool. FINITE w ==> ?L. !y. y IN w ==> y <= &2 pow L`,
    MATCH_MP_TAC FINITE_INDUCT_STRONG THEN
    REWRITE_TAC[NOT_IN_EMPTY; FORALL_IN_INSERT] THEN
    MAP_EVERY X_GEN_TAC [`z:real`; `w:real->bool`] THEN
    DISCH_THEN(X_CHOOSE_TAC `L:num` o CONJUNCT1) THEN
    X_CHOOSE_TAC `M:num` (SPEC `z:real` REAL_ARCH_POW2) THEN
    EXISTS_TAC `L + M:num` THEN
    MP_TAC(SPECL [`L:num`; `L + M:num`; `&2:real`] REAL_POW_MONO) THEN
    MP_TAC(SPECL [`M:num`; `L + M:num`; `&2:real`] REAL_POW_MONO) THEN
    REWRITE_TAC[LE_ADD; LE_ADDR; REAL_OF_NUM_LE; ARITH] THEN
    ASM_MESON_TAC[REAL_LE_TRANS; REAL_LT_IMP_LE])
  and bound = prove
   (`!G (g:A->real) t (n:A->num) b N.
        abelian_group G /\
        (!x. x IN group_carrier G ==> &0 < g x) /\
        (!x y. x IN group_carrier G /\ y IN group_carrier G
               ==> g(group_mul G x y) = g x * g y) /\
        FINITE t /\
        (!x. x IN t
             ==> x IN group_carrier G /\ inv b <= g x /\ g x <= b /\ n x <= N)
        ==> inv(b pow (N * CARD t)) <=
            g(group_sum G t (\x. group_pow G x (n x))) /\
            g(group_sum G t (\x. group_pow G x (n x))) <= b pow (N * CARD t)`,
    REPEAT GEN_TAC THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
     (CONJUNCTS_THEN2 ASSUME_TAC MP_TAC))) THEN
    MP_TAC(ISPECL [`G:A group`; `g:A->real`]
      GROUP_REAL_MULTIPLICATIVE_ID_INV_POW) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    REWRITE_TAC[IMP_CONJ] THEN SPEC_TAC(`t:A->bool`,`t:A->bool`) THEN
    MATCH_MP_TAC FINITE_INDUCT_STRONG THEN
    ASM_SIMP_TAC[CONJUNCT1(SPEC_ALL GROUP_SUM_CLAUSES_EXISTS); CARD_CLAUSES;
                 ABELIAN_GROUP_SUM_CLAUSES; FINITE_RESTRICT;
                 FORALL_IN_INSERT] THEN
    REWRITE_TAC[MULT_CLAUSES; real_pow; REAL_INV_1; REAL_LE_REFL] THEN
    MAP_EVERY X_GEN_TAC [`x:A`; `t:A->bool`] THEN
    DISCH_THEN(CONJUNCTS_THEN2 MP_TAC STRIP_ASSUME_TAC) THEN
    DISCH_THEN(fun ih -> DISCH_THEN(CONJUNCTS_THEN2 STRIP_ASSUME_TAC
      (MP_TAC o MATCH_MP ih))) THEN
    ASM_SIMP_TAC[GROUP_POW; GROUP_SUM; REAL_POW_ADD; REAL_INV_MUL] THEN
    STRIP_TAC THEN
    SUBGOAL_THEN `&0 < (g:A->real) x` ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `&0:real <= b /\ &1 <= b` STRIP_ASSUME_TAC THENL
     [MP_TAC(SPEC `b:real` REAL_INV_1_LT) THEN ASM_REAL_ARITH_TAC;
      ALL_TAC] THEN
    SUBGOAL_THEN
     `inv(b pow N) <= (g:A->real) x pow n x /\ g x pow n x <= b pow N`
    STRIP_ASSUME_TAC THENL
     [REWRITE_TAC[GSYM REAL_POW_INV] THEN CONJ_TAC THEN
      MATCH_MP_TAC REAL_LE_TRANS THENL
       [EXISTS_TAC `inv(b:real) pow (n:A->num) x`;
        EXISTS_TAC `(b:real) pow (n:A->num) x`] THEN
      ASM_SIMP_TAC[REAL_POW_LE2; REAL_POW_MONO; REAL_POW_MONO_INV;
                   REAL_LE_INV_EQ; REAL_INV_LE_1; REAL_LT_IMP_LE];
      CONJ_TAC THEN MATCH_MP_TAC REAL_LE_MUL2 THEN
      ASM_SIMP_TAC[REAL_LE_INV_EQ; REAL_POW_LE; REAL_LT_IMP_LE; GROUP_SUM]])
  in
  prove
   (`!G (s:K->bool) (f:K->A->real) t.
        abelian_group G /\ FINITE s /\
        (!i x. i IN s /\ x IN group_carrier G ==> &0 < f i x) /\
        (!i x y. i IN s /\ x IN group_carrier G /\ y IN group_carrier G
                 ==> f i (group_mul G x y) = f i x * f i y) /\
        FINITE t /\ t SUBSET group_carrier G
        ==> ?L. !i n N.
                  i IN s /\ (!x. x IN t ==> n x <= N)
                  ==> inv(&2 pow (L * N * CARD t)) <=
                      f i (group_sum G t (\x. group_pow G x (n x))) /\
                      f i (group_sum G t (\x. group_pow G x (n x))) <=
                      &2 pow (L * N * CARD t)`,
    REPEAT GEN_TAC THEN REWRITE_TAC[SUBSET] THEN STRIP_TAC THEN
    MP_TAC(ISPEC `{max ((f:K->A->real) i x) (inv(f i x)) | i IN s /\ x IN t}`
      lemma) THEN
    ASM_SIMP_TAC[FINITE_PRODUCT_DEPENDENT; FORALL_IN_GSPEC; REAL_MAX_LE] THEN
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `L:num` THEN DISCH_TAC THEN
    MAP_EVERY X_GEN_TAC [`i:K`; `n:A->num`; `N:num`] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`G:A group`; `(f:K->A->real) i`; `t:A->bool`; `n:A->num`;
                   `(&2:real) pow L`; `N:num`] bound) THEN
    ASM_SIMP_TAC[REAL_POW_POW] THEN DISCH_THEN MATCH_MP_TAC THEN
    X_GEN_TAC `x:A` THEN DISCH_TAC THEN ASM_SIMP_TAC[] THEN
    GEN_REWRITE_TAC RAND_CONV [GSYM REAL_INV_INV] THEN
    MATCH_MP_TAC REAL_LE_INV2 THEN ASM_SIMP_TAC[REAL_LT_INV_EQ]);;

(* Polynomial growth: the elements with all sizes in [2^-k, 2^k] lie in at   *)
(* most (2 k + 1)^CARD s dyadic cells, and a cell containing y lies in the   *)
(* translate by y of the elements with all sizes in [1 / 2, 2].              *)

let GROUP_REAL_MULTIPLICATIVE_BOX_COUNT =
  let dyadic = prove
   (`!y k. inv(&2 pow k) <= y /\ y <= &2 pow k
           ==> ?j. j <= 2 * k /\ &2 pow j <= &2 pow k * y /\
                   &2 pow k * y < &2 * &2 pow j`,
    REPEAT STRIP_TAC THEN
    SUBGOAL_THEN `&0:real < &2 pow k` ASSUME_TAC THENL
     [SIMP_TAC[REAL_POW_LT; REAL_OF_NUM_LT; ARITH]; ALL_TAC] THEN
    SUBGOAL_THEN `&1:real <= &2 pow k * y /\ &2 pow k * y < &2 * &2 pow (2 * k)`
    STRIP_ASSUME_TAC THENL
     [REWRITE_TAC[MULT_2; REAL_POW_ADD] THEN CONJ_TAC THENL
       [TRANS_TAC REAL_LE_TRANS `&2 pow k * inv(&2 pow k)` THEN
        ASM_SIMP_TAC[REAL_LE_LMUL; REAL_LT_IMP_LE; REAL_MUL_RINV;
                     REAL_LT_IMP_NZ; REAL_LE_REFL];
        TRANS_TAC REAL_LET_TRANS `(&2:real) pow k * &2 pow k` THEN
        ASM_SIMP_TAC[REAL_LE_LMUL; REAL_LT_IMP_LE; REAL_LT_MUL; REAL_ARITH
         `&0:real < x ==> x < &2 * x`]];
      ALL_TAC] THEN
    SUBGOAL_THEN `?j. (&2:real) pow k * y < &2 * &2 pow j` MP_TAC THENL
     [ASM_MESON_TAC[]; GEN_REWRITE_TAC LAND_CONV [num_WOP]] THEN
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [REWRITE_TAC[GSYM NOT_LT] THEN ASM_MESON_TAC[];
      ASM_CASES_TAC `j = 0` THEN ASM_REWRITE_TAC[real_pow] THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `j - 1`) THEN
      ASM_SIMP_TAC[GSYM(CONJUNCT2 real_pow); ARITH_RULE
       `~(j = 0) ==> SUC(j - 1) = j /\ j - 1 < j`] THEN
      REAL_ARITH_TAC])
  and ratio = prove
   (`!a b u v. &0 < b /\ &0 < v /\ a <= b * u /\ b * u < &2 * a /\
               a <= b * v /\ b * v < &2 * a
               ==> inv(&2) <= u * inv v /\ u * inv v <= &2`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    ASM_SIMP_TAC[GSYM real_div; REAL_LE_LDIV_EQ; REAL_LE_RDIV_EQ] THEN
    CONJ_TAC THEN MATCH_MP_TAC REAL_LT_IMP_LE THEN
    ONCE_REWRITE_TAC[GSYM(MATCH_MP REAL_LT_LMUL_EQ (ASSUME `&0:real < b`))] THEN
    ASM_REAL_ARITH_TAC)
  and translate = prove
   (`!c z (h:A->A->A).
        FINITE z /\ (!y. y IN c ==> c SUBSET IMAGE (h y) z)
        ==> FINITE c /\ CARD c <= CARD z`,
    REPEAT GEN_TAC THEN ASM_CASES_TAC `c:A->bool = {}` THEN
    ASM_REWRITE_TAC[FINITE_EMPTY; CARD_CLAUSES; LE_0] THEN
    FIRST_X_ASSUM(X_CHOOSE_TAC `y:A` o REWRITE_RULE[GSYM MEMBER_NOT_EMPTY]) THEN
    STRIP_TAC THEN FIRST_X_ASSUM(MP_TAC o SPEC `y:A`) THEN
    ASM_MESON_TAC[FINITE_SUBSET; FINITE_IMAGE; CARD_SUBSET; CARD_IMAGE_LE;
                  LE_TRANS]) in
  let cell = prove
   (`!G (s:K->bool) (f:K->A->real) k c.
        (!i x. i IN s /\ x IN group_carrier G ==> &0 < f i x) /\
        (!i x y. i IN s /\ x IN group_carrier G /\ y IN group_carrier G
                 ==> f i (group_mul G x y) = f i x * f i y) /\
        FINITE {x | x IN group_carrier G /\
                    !i. i IN s ==> inv(&2) <= f i x /\ f i x <= &2}
        ==> FINITE {x | x IN group_carrier G /\
                        !i. i IN s ==> &2 pow c i <= &2 pow k * f i x /\
                                       &2 pow k * f i x < &2 * &2 pow c i} /\
            CARD {x | x IN group_carrier G /\
                      !i. i IN s ==> &2 pow c i <= &2 pow k * f i x /\
                                     &2 pow k * f i x < &2 * &2 pow c i} <=
            CARD {x | x IN group_carrier G /\
                      !i. i IN s ==> inv(&2) <= f i x /\ f i x <= &2}`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN MATCH_MP_TAC translate THEN
    EXISTS_TAC `\y z:A. group_mul G z y` THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `y:A` THEN REWRITE_TAC[IN_ELIM_THM; SUBSET; IN_IMAGE] THEN
    STRIP_TAC THEN X_GEN_TAC `x:A` THEN STRIP_TAC THEN
    EXISTS_TAC `group_mul G x (group_inv G y):A` THEN
    ASM_SIMP_TAC[GSYM GROUP_MUL_ASSOC; GROUP_MUL_LINV; GROUP_MUL_RID;
                 GROUP_INV; GROUP_MUL] THEN
    X_GEN_TAC `i:K` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`G:A group`; `(f:K->A->real) i`]
      GROUP_REAL_MULTIPLICATIVE_ID_INV_POW) THEN
    ASM_SIMP_TAC[GROUP_INV] THEN DISCH_THEN(K ALL_TAC) THEN
    MATCH_MP_TAC ratio THEN
    MAP_EVERY EXISTS_TAC [`(&2:real) pow (c:K->num) i`; `(&2:real) pow k`] THEN
    ASM_SIMP_TAC[REAL_POW_LT; REAL_OF_NUM_LT; ARITH]) in
  prove
   (`!G (s:K->bool) (f:K->A->real) k.
        FINITE s /\
        (!i x. i IN s /\ x IN group_carrier G ==> &0 < f i x) /\
        (!i x y. i IN s /\ x IN group_carrier G /\ y IN group_carrier G
                 ==> f i (group_mul G x y) = f i x * f i y) /\
        FINITE {x | x IN group_carrier G /\
                    !i. i IN s ==> inv(&2) <= f i x /\ f i x <= &2}
        ==> FINITE {x | x IN group_carrier G /\
                        !i. i IN s ==> inv(&2 pow k) <= f i x /\
                                       f i x <= &2 pow k} /\
            CARD {x | x IN group_carrier G /\
                      !i. i IN s ==> inv(&2 pow k) <= f i x /\
                                     f i x <= &2 pow k}
            <= (2 * k + 1) EXP CARD s *
               CARD {x | x IN group_carrier G /\
                         !i. i IN s ==> inv(&2) <= f i x /\ f i x <= &2}`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    MATCH_MP_TAC(MESON[FINITE_SUBSET; CARD_SUBSET; LE_TRANS]
     `!u:A->bool. FINITE u /\ s SUBSET u /\ CARD u <= n
                  ==> FINITE s /\ CARD s <= n`) THEN
    EXISTS_TAC
     `UNIONS {{x | x IN group_carrier G /\
                   !i. i IN s ==> &2 pow c i <= &2 pow k * (f:K->A->real) i x /\
                                  &2 pow k * f i x < &2 * &2 pow c i} |
              c | c IN {c | (!i. i IN s ==> c i IN 0..2 * k) /\
                        (!i. ~(i IN s) ==> c i = 0)}}` THEN
    REPEAT CONJ_TAC THENL
     [ASM_SIMP_TAC[FINITE_UNIONS; SIMPLE_IMAGE; FINITE_IMAGE; FORALL_IN_IMAGE;
                   FINITE_FUNSPACE; FINITE_NUMSEG; cell];
      REWRITE_TAC[SUBSET; SIMPLE_IMAGE; UNIONS_IMAGE; IN_ELIM_THM; IN_NUMSEG;
                  LE_0] THEN
      X_GEN_TAC `x:A` THEN STRIP_TAC THEN
      SUBGOAL_THEN
       `!i. ?j. i IN s
                ==> j <= 2 * k /\
                    &2 pow j <= &2 pow k * (f:K->A->real) i x /\
                    &2 pow k * f i x < &2 * &2 pow j`
      MP_TAC THENL
       [REWRITE_TAC[RIGHT_EXISTS_IMP_THM] THEN REPEAT STRIP_TAC THEN
        MATCH_MP_TAC dyadic THEN ASM_SIMP_TAC[];
        REWRITE_TAC[SKOLEM_THM] THEN
        DISCH_THEN(X_CHOOSE_TAC `c:K->num`)] THEN
      EXISTS_TAC `\i. if i IN s then (c:K->num) i else 0` THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC CARD_UNIONS_LE THEN ASM_SIMP_TAC[cell] THEN
      MATCH_MP_TAC HAS_SIZE_FUNSPACE THEN
      ASM_REWRITE_TAC[HAS_SIZE; CARD_NUMSEG; FINITE_NUMSEG] THEN
      ARITH_TAC]);;

(* ------------------------------------------------------------------------- *)
(* Abelian groups with finitely many discrete multiplicative sizes.          *)
(* ------------------------------------------------------------------------- *)

(* Pigeonhole: the (N + 1)^CARD t products P(a), 0 <= a x <= N, lie in the   *)
(* box [2^-K, 2^K] with K = L * N * CARD t, which has at most                *)
(* (2 K + 1)^CARD s T elements, T the number of elements with all sizes in   *)
(* [1 / 2, 2]; for N large this is less than (N + 1)^CARD t.                 *)

let ABELIAN_GROUP_DISCRETE_DEPENDENT =
  let count = prove
   (`!a c m. ?N. a * (c * N + 1) EXP m < (N + 1) EXP (m + 1)`,
    REPEAT GEN_TAC THEN EXISTS_TAC `a * (c + 1) EXP m + 1` THEN
    ABBREV_TAC `N = a * (c + 1) EXP m + 1` THEN
    TRANS_TAC LET_TRANS `(a * (c + 1) EXP m) * N EXP m` THEN CONJ_TAC THENL
     [REWRITE_TAC[GSYM MULT_ASSOC; GSYM MULT_EXP; LE_MULT_LCANCEL] THEN
      DISJ2_TAC THEN MATCH_MP_TAC EXP_MONO_LE_IMP THEN EXPAND_TAC "N" THEN
      ARITH_TAC;
      TRANS_TAC LTE_TRANS `N * N EXP m` THEN CONJ_TAC THENL
       [REWRITE_TAC[LT_MULT_RCANCEL; EXP_EQ_0] THEN EXPAND_TAC "N" THEN
        ARITH_TAC;
        REWRITE_TAC[GSYM(CONJUNCT2 EXP); ADD1] THEN
        MATCH_MP_TAC EXP_MONO_LE_IMP THEN ARITH_TAC]])
  and relation = prove
   (`!G t (a:A->num) b.
        abelian_group G /\ FINITE t /\ t SUBSET group_carrier G /\
        (!x. ~(x IN t) ==> a x = 0 /\ b x = 0) /\ ~(a = b) /\
        group_sum G t (\x. group_pow G x (a x)) =
        group_sum G t (\x. group_pow G x (b x))
        ==> ?n. (?x. x IN t /\ ~(n x = &0)) /\
                group_sum G t (\x. group_zpow G x (n x)) = group_id G`,
    REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN
    EXISTS_TAC `\x:A. &((a:A->num) x) - &(b x):int` THEN REWRITE_TAC[] THEN
    CONJ_TAC THENL
     [UNDISCH_TAC `~(a:A->num = b)` THEN
      REWRITE_TAC[FUN_EQ_THM; NOT_FORALL_THM; INT_SUB_0; INT_OF_NUM_EQ] THEN
      ASM_MESON_TAC[];
      ALL_TAC] THEN
    TRANS_TAC EQ_TRANS
     `group_sum G t (\x. group_mul G (group_pow G x ((a:A->num) x))
                                     (group_inv G (group_pow G x (b x))))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC GROUP_SUM_EQ THEN
      ASM_SIMP_TAC[GROUP_ZPOW_SUB; GROUP_NPOW; group_div];
      ALL_TAC] THEN
    W(MP_TAC o PART_MATCH (lhand o rand) ABELIAN_GROUP_SUM_MUL o
      lhand o snd) THEN
    ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW; GROUP_INV] THEN
    DISCH_THEN SUBST1_TAC THEN
    W(MP_TAC o PART_MATCH (lhand o rand) ABELIAN_GROUP_SUM_INV o
      rand o lhand o snd) THEN
    ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_POW] THEN DISCH_THEN SUBST1_TAC THEN
    ASM_SIMP_TAC[GROUP_MUL_RINV; GROUP_SUM]) in
  prove
   (`!G:A group (s:K->bool) (f:K->A->real) t.
        abelian_group G /\ FINITE s /\
        (!i x. i IN s /\ x IN group_carrier G ==> &0 < f i x) /\
        (!i x y. i IN s /\ x IN group_carrier G /\ y IN group_carrier G
                 ==> f i (group_mul G x y) = f i x * f i y) /\
        (!b. FINITE {x | x IN group_carrier G /\
                         !i. i IN s ==> inv b <= f i x /\ f i x <= b}) /\
        FINITE t /\ t SUBSET group_carrier G /\ CARD s < CARD t
        ==> ?n. (?x. x IN t /\ ~(n x = &0)) /\
                group_sum G t (\x. group_zpow G x (n x)) = group_id G`,
    REPEAT STRIP_TAC THEN MATCH_MP_TAC relation THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`G:A group`; `s:K->bool`; `f:K->A->real`; `t:A->bool`]
      GROUP_SUM_POW_REAL_MULTIPLICATIVE_BOUND) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_TAC `L:num`) THEN
    MP_TAC(SPECL
     [`CARD {x | x IN group_carrier G /\
                 !i. i IN s ==> inv(&2) <= (f:K->A->real) i x /\ f i x <= &2}`;
      `2 * L * CARD(t:A->bool)`; `CARD(s:K->bool)`] count) THEN
    DISCH_THEN(X_CHOOSE_TAC `N:num`) THEN
    ABBREV_TAC `D = {a | (!x:A. x IN t ==> a x IN 0..N) /\
                         (!x. ~(x IN t) ==> a x = 0)}` THEN
    SUBGOAL_THEN `?a b. a IN D /\ b IN D /\ ~(a = b) /\
                        group_sum G t (\x. group_pow G x (a x)) =
                        group_sum G t (\x:A. group_pow G x (b x))`
    MP_TAC THENL
     [ALL_TAC;
      EXPAND_TAC "D" THEN REWRITE_TAC[IN_ELIM_THM] THEN MESON_TAC[]] THEN
    REWRITE_TAC[MESON[]
     `(?a b:A->num. P a /\ P b /\ ~(a = b) /\ (Q a:B) = Q b) <=>
      ~(!a b. P a /\ P b /\ Q a = Q b ==> a = b)`] THEN
    DISCH_TAC THEN
    MP_TAC(ISPECL [`G:A group`; `s:K->bool`; `f:K->A->real`;
                   `L * N * CARD(t:A->bool)`]
      GROUP_REAL_MULTIPLICATIVE_BOX_COUNT) THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(ARITH_RULE `!x y z:num. x < y /\ y <= z ==> ~(z <= x)`) THEN
    EXISTS_TAC `(N + 1) EXP CARD(t:A->bool)` THEN CONJ_TAC THENL
     [REWRITE_TAC[ARITH_RULE
       `2 * L * N * CARD(t:A->bool) + 1 = (2 * L * CARD t) * N + 1`] THEN
      TRANS_TAC LTE_TRANS `(N + 1) EXP (CARD(s:K->bool) + 1)` THEN
      ASM_REWRITE_TAC[LE_EXP; ADD_EQ_0; ARITH_EQ] THEN
      CONJ_TAC THENL [ALL_TAC; ASM_ARITH_TAC] THEN
      MATCH_MP_TAC(ARITH_RULE `!a b c:num. b * a < c ==> a * b < c`) THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN `(D:(A->num)->bool) HAS_SIZE (N + 1) EXP CARD(t:A->bool)`
    MP_TAC THENL
     [EXPAND_TAC "D" THEN MATCH_MP_TAC HAS_SIZE_FUNSPACE THEN
      ASM_REWRITE_TAC[HAS_SIZE; FINITE_NUMSEG; CARD_NUMSEG] THEN ARITH_TAC;
      REWRITE_TAC[HAS_SIZE] THEN STRIP_TAC THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM)] THEN
    TRANS_TAC LE_TRANS
     `CARD(IMAGE (\a. group_sum G t (\x:A. group_pow G x (a x))) D)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC EQ_IMP_LE THEN CONV_TAC SYM_CONV THEN
      MATCH_MP_TAC CARD_IMAGE_INJ THEN ASM_REWRITE_TAC[];
      MATCH_MP_TAC CARD_SUBSET THEN ASM_REWRITE_TAC[]] THEN
    REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_ELIM_THM; GROUP_SUM] THEN
    X_GEN_TAC `a:A->num` THEN EXPAND_TAC "D" THEN
    REWRITE_TAC[IN_ELIM_THM; IN_NUMSEG; LE_0] THEN STRIP_TAC THEN
    ASM_SIMP_TAC[]);;

(* A maximal independent finite set B (CARD B <= CARD s by the rank bound);  *)
(* for x outside B a dependence of x INSERT B gives some x^q in terms of B;  *)
(* division with remainder of the exponents; generation by B and the         *)
(* elements of a fixed box.                                                  *)

let FINITELY_GENERATED_ABELIAN_GROUP_DISCRETE =
  let maximal = prove
   (`!G:A group m.
        (!t. FINITE t /\ t SUBSET group_carrier G /\ m < CARD t
             ==> ?n. (?x. x IN t /\ ~(n x = &0)) /\
                     group_sum G t (\x. group_zpow G x (n x)) = group_id G)
        ==> ?B. FINITE B /\ B SUBSET group_carrier G /\
                ~(?n. (?x. x IN B /\ ~(n x = &0)) /\
                      group_sum G B (\x. group_zpow G x (n x)) = group_id G) /\
                !x. x IN group_carrier G /\ ~(x IN B)
                    ==> ?n. (?y. y IN x INSERT B /\ ~(n y = &0)) /\
                            group_sum G (x INSERT B)
                                      (\y. group_zpow G y (n y)) =
                            group_id G`,
    REPEAT STRIP_TAC THEN
    MP_TAC(ISPEC
     `\k. ?B. FINITE B /\ B SUBSET group_carrier G /\ CARD B = k /\
              ~(?n. (?x:A. x IN B /\ ~(n x = &0)) /\
                    group_sum G B (\x. group_zpow G x (n x)) = group_id G)`
     num_MAX) THEN
    REWRITE_TAC[] THEN
    MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN
    CONJ_TAC THENL
     [CONJ_TAC THENL
       [MAP_EVERY EXISTS_TAC [`0`; `{}:A->bool`] THEN
        REWRITE_TAC[FINITE_EMPTY; EMPTY_SUBSET; CARD_CLAUSES; NOT_IN_EMPTY];
        EXISTS_TAC `m:num` THEN X_GEN_TAC `j:num` THEN
        DISCH_THEN(X_CHOOSE_THEN `C:A->bool` STRIP_ASSUME_TAC) THEN
        FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN REWRITE_TAC[GSYM NOT_LT] THEN
        DISCH_TAC THEN UNDISCH_TAC
         `~(?n. (?x:A. x IN C /\ ~(n x = &0)) /\
                group_sum G C (\x. group_zpow G x (n x)) = group_id G)` THEN
        REWRITE_TAC[] THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
        ASM_REWRITE_TAC[]];
      DISCH_THEN(X_CHOOSE_THEN `k:num` (CONJUNCTS_THEN2
        (X_CHOOSE_THEN `B:A->bool` STRIP_ASSUME_TAC) ASSUME_TAC))] THEN
    EXISTS_TAC `B:A->bool` THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `x:A` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `CARD((x:A) INSERT B)`) THEN
    ASM_SIMP_TAC[CARD_CLAUSES; ARITH_RULE `~(SUC k <= k)`; NOT_EXISTS_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `(x:A) INSERT B`) THEN
    ASM_SIMP_TAC[FINITE_INSERT; INSERT_SUBSET; CARD_CLAUSES; NOT_FORALL_THM])
  and power = prove
   (`!G B (x:A) n.
        abelian_group G /\ FINITE B /\ B SUBSET group_carrier G /\
        x IN group_carrier G /\ ~(x IN B) /\
        ~(?n. (?y. y IN B /\ ~(n y = &0)) /\
              group_sum G B (\y. group_zpow G y (n y)) = group_id G) /\
        (?y. y IN x INSERT B /\ ~(n y = &0)) /\
        group_sum G (x INSERT B) (\y. group_zpow G y (n y)) = group_id G
        ==> ?q d. ~(q = 0) /\
                  group_pow G x q = group_sum G B (\y. group_zpow G y (d y))`,
    REPEAT GEN_TAC THEN REWRITE_TAC[SUBSET] THEN
    DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
    UNDISCH_TAC `group_sum G ((x:A) INSERT B)
                   (\y. group_zpow G y ((n:A->int) y)) = group_id G` THEN
    ASM_SIMP_TAC[ABELIAN_GROUP_SUM_CLAUSES; FINITE_RESTRICT; GROUP_ZPOW] THEN
    ASM_CASES_TAC `(n:A->int) x = &0` THENL
     [ASM_SIMP_TAC[GROUP_ZPOW_0; GROUP_MUL_LID; GROUP_SUM] THEN
      ASM_MESON_TAC[IN_INSERT];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `group_sum G B (\y. group_zpow G y (--(n y))) =
      group_inv G (group_sum G B (\y:A. group_zpow G y (n y)))`
    ASSUME_TAC THENL
     [TRANS_TAC EQ_TRANS
       `group_sum G B (\y. group_inv G (group_zpow G y ((n:A->int) y)))` THEN
      CONJ_TAC THENL
       [MATCH_MP_TAC GROUP_SUM_EQ THEN ASM_SIMP_TAC[GROUP_ZPOW_NEG];
        MATCH_MP_TAC ABELIAN_GROUP_SUM_INV THEN
        ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_ZPOW]];
      ALL_TAC] THEN
    DISJ_CASES_THEN (X_CHOOSE_THEN `q:num` SUBST_ALL_TAC)
     (SPEC `(n:A->int) x` INT_IMAGE) THEN
    RULE_ASSUM_TAC(REWRITE_RULE[INT_NEG_EQ_0; INT_OF_NUM_EQ]) THEN
    ASM_SIMP_TAC[GROUP_ZPOW_NEG; GROUP_NPOW] THEN DISCH_TAC THEN
    EXISTS_TAC `q:num` THEN ASM_REWRITE_TAC[] THENL
     [EXISTS_TAC `\y. --((n:A->int) y)`; EXISTS_TAC `n:A->int`] THEN
    ASM_REWRITE_TAC[] THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC GROUP_RINV_UNIQUE;
      MP_TAC(ISPECL [`G:A group`; `group_inv G (group_pow G x q):A`;
        `group_sum G B (\y:A. group_zpow G y ((n:A->int) y))`]
        GROUP_LINV_UNIQUE)] THEN
    ASM_SIMP_TAC[GROUP_INV_INV; GROUP_INV; GROUP_POW; GROUP_SUM])
  and remainder = prove
   (`!G B (x:A) q d.
        abelian_group G /\ FINITE B /\ B SUBSET group_carrier G /\
        x IN group_carrier G /\ ~(q = 0) /\
        group_pow G x q = group_sum G B (\y. group_zpow G y (d y))
        ==> ?z r. z IN group_carrier G /\ (!y. r y <= q) /\
                  group_pow G z q = group_sum G B (\y. group_pow G y (r y)) /\
                  x IN group_carrier(subgroup_generated G (z INSERT B))`,
    REPEAT GEN_TAC THEN REWRITE_TAC[SUBSET] THEN STRIP_TAC THEN
    ABBREV_TAC
     `w = group_sum G B (\y:A. group_zpow G y (--(d y div &q)))` THEN
    SUBGOAL_THEN `(w:A) IN group_carrier G` ASSUME_TAC THENL
     [EXPAND_TAC "w" THEN REWRITE_TAC[GROUP_SUM]; ALL_TAC] THEN
    MAP_EVERY EXISTS_TAC
     [`group_mul G x w:A`; `\y:A. num_of_int(d y rem &q)`] THEN
    ASM_SIMP_TAC[GROUP_MUL] THEN REPEAT CONJ_TAC THENL
     [X_GEN_TAC `y:A` THEN
      MP_TAC(SPECL [`(d:A->int) y`; `&q:int`] INT_DIVISION) THEN
      ASM_REWRITE_TAC[INT_OF_NUM_EQ; INT_ABS_NUM] THEN STRIP_TAC THEN
      ASM_SIMP_TAC[GSYM INT_OF_NUM_LE; INT_OF_NUM_OF_INT; INT_LT_IMP_LE];
      UNDISCH_THEN
       `group_sum G B (\y:A. group_zpow G y (--(d y div &q))) = w`
       (SUBST1_TAC o SYM) THEN
      ASM_SIMP_TAC[ABELIAN_GROUP_MUL_POW; GROUP_SUM] THEN
      W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_POW o
        rand o lhand o snd) THEN
      ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_ZPOW] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      W(MP_TAC o PART_MATCH (rand o rand) ABELIAN_GROUP_SUM_MUL o
        lhand o snd) THEN
      ASM_SIMP_TAC[FINITE_RESTRICT; GROUP_ZPOW; GROUP_POW] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      MATCH_MP_TAC GROUP_SUM_EQ THEN X_GEN_TAC `y:A` THEN DISCH_TAC THEN
      ASM_SIMP_TAC[GSYM GROUP_NPOW; GSYM GROUP_ZPOW_MUL;
                   GSYM GROUP_ZPOW_ADD] THEN
      AP_TERM_TAC THEN
      MP_TAC(SPECL [`(d:A->int) y`; `&q:int`] INT_DIVISION) THEN
      ASM_SIMP_TAC[INT_OF_NUM_EQ; INT_OF_NUM_OF_INT] THEN INT_ARITH_TAC;
      SUBGOAL_THEN `x = group_mul G (group_mul G x w) (group_inv G w):A`
       (fun th -> GEN_REWRITE_TAC LAND_CONV [th]) THENL
       [ASM_SIMP_TAC[GSYM GROUP_MUL_ASSOC; GROUP_INV; GROUP_MUL_RINV;
                     GROUP_MUL_RID];
        MATCH_MP_TAC IN_SUBGROUP_MUL THEN
        REWRITE_TAC[SUBGROUP_SUBGROUP_GENERATED]] THEN
      CONJ_TAC THENL
       [MATCH_MP_TAC SUBGROUP_GENERATED_INC_GEN THEN
        ASM_SIMP_TAC[GROUP_MUL; IN_INSERT];
        MATCH_MP_TAC IN_SUBGROUP_INV THEN
        REWRITE_TAC[SUBGROUP_SUBGROUP_GENERATED]] THEN
      EXPAND_TAC "w" THEN MATCH_MP_TAC IN_SUBGROUP_SUM THEN
      REWRITE_TAC[SUBGROUP_SUBGROUP_GENERATED] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_SUBGROUP_ZPOW THEN
      ASM_SIMP_TAC[SUBGROUP_SUBGROUP_GENERATED; SUBGROUP_GENERATED_INC_GEN;
                   IN_INSERT]]) in
  prove
   (`!G:A group (s:K->bool) (f:K->A->real).
        abelian_group G /\ FINITE s /\
        (!i x. i IN s /\ x IN group_carrier G ==> &0 < f i x) /\
        (!i x y. i IN s /\ x IN group_carrier G /\ y IN group_carrier G
                 ==> f i (group_mul G x y) = f i x * f i y) /\
        (!b. FINITE {x | x IN group_carrier G /\
                         !i. i IN s ==> inv b <= f i x /\ f i x <= b})
        ==> finitely_generated_group G`,
    REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`G:A group`; `CARD(s:K->bool)`] maximal) THEN
    ANTS_TAC THENL
     [REPEAT STRIP_TAC THEN MATCH_MP_TAC ABELIAN_GROUP_DISCRETE_DEPENDENT THEN
      MAP_EVERY EXISTS_TAC [`s:K->bool`; `f:K->A->real`] THEN
      ASM_REWRITE_TAC[];
      DISCH_THEN(X_CHOOSE_THEN `B:A->bool` STRIP_ASSUME_TAC)] THEN
    MP_TAC(ISPECL [`G:A group`; `s:K->bool`; `f:K->A->real`; `B:A->bool`]
      GROUP_SUM_POW_REAL_MULTIPLICATIVE_BOUND) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_TAC `L:num`) THEN
    FIRST_ASSUM(MP_TAC o SPEC `(&2:real) pow (L * CARD(B:A->bool))`) THEN
    ABBREV_TAC
     `Z = {x | x IN group_carrier G /\
               !i. i IN s ==> inv(&2 pow (L * CARD B)) <= (f:K->A->real) i x /\
                              f i x <= &2 pow (L * CARD(B:A->bool))}` THEN
    DISCH_TAC THEN REWRITE_TAC[FINITELY_GENERATED_GROUP] THEN
    EXISTS_TAC `B UNION Z:A->bool` THEN
    SUBGOAL_THEN `(Z:A->bool) SUBSET group_carrier G` ASSUME_TAC THENL
     [EXPAND_TAC "Z" THEN REWRITE_TAC[SUBSET_RESTRICT]; ALL_TAC] THEN
    ASM_REWRITE_TAC[FINITE_UNION; UNION_SUBSET;
                    SUBGROUP_GENERATED_SUPERSET] THEN
    REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    ASM_CASES_TAC `(x:A) IN B` THENL
     [MATCH_MP_TAC SUBGROUP_GENERATED_INC_GEN THEN ASM_REWRITE_TAC[IN_UNION];
      FIRST_X_ASSUM(MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[]] THEN
    DISCH_THEN(X_CHOOSE_THEN `n:A->int` (CONJUNCTS_THEN ASSUME_TAC)) THEN
    MP_TAC(ISPECL [`G:A group`; `B:A->bool`; `x:A`; `n:A->int`] power) THEN
    ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`q:num`; `d:A->int`] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`G:A group`; `B:A->bool`; `x:A`; `q:num`; `d:A->int`]
      remainder) THEN
    ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`z:A`; `r:A->num`] THEN STRIP_TAC THEN
    SUBGOAL_THEN `(z:A) IN Z` ASSUME_TAC THENL
     [EXPAND_TAC "Z" THEN REWRITE_TAC[IN_ELIM_THM] THEN
      CONJ_TAC THENL [ASM_REWRITE_TAC[]; X_GEN_TAC `i:K` THEN DISCH_TAC] THEN
      FIRST_X_ASSUM(MP_TAC o SPECL [`i:K`; `r:A->num`; `q:num`]) THEN
      UNDISCH_THEN
       `group_pow G z q = group_sum G B (\y:A. group_pow G y (r y))`
       (SUBST1_TAC o SYM) THEN
      MP_TAC(ISPECL [`G:A group`; `(f:K->A->real) i`]
        GROUP_REAL_MULTIPLICATIVE_ID_INV_POW) THEN
      ASM_SIMP_TAC[] THEN DISCH_THEN(K ALL_TAC) THEN
      SUBGOAL_THEN
       `(&2:real) pow (L * q * CARD(B:A->bool)) = (&2 pow (L * CARD B)) pow q`
      SUBST1_TAC THENL
       [REWRITE_TAC[REAL_POW_POW] THEN AP_TERM_TAC THEN ARITH_TAC;
        REWRITE_TAC[GSYM REAL_POW_INV]] THEN
      STRIP_TAC THEN CONJ_TAC THEN MATCH_MP_TAC REAL_POW_LE2_REV THEN
      EXISTS_TAC `q:num` THEN
      ASM_SIMP_TAC[REAL_LT_IMP_LE; REAL_POW_LE; REAL_POS];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`G:A group`; `(z:A) INSERT B`; `B UNION Z:A->bool`]
      SUBGROUP_GENERATED_MONO) THEN
    ASM_REWRITE_TAC[INSERT_SUBSET; IN_UNION; SUBSET_UNION] THEN
    MATCH_MP_TAC(SET_RULE `(x:A) IN s ==> s SUBSET t ==> x IN t`) THEN
    ASM_REWRITE_TAC[]);;

