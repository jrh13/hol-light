(* A finite independent set t of elements of infinite order such that every  *)
(* element is a torsion element times a product of integer powers of the     *)
(* elements of t, and no independent set is larger. Route: by                *)
(* FINITELY_GENERATED_ABELIAN_GROUP_EXPONENTS, G is the internal direct sum  *)
(* of the cyclic subgroups generated by the elements x of a finite set t0,   *)
(* the exponent E x y of the component of y at x being additive in y when x  *)
(* has infinite order; t is the set of the elements of t0 of infinite order, *)
(* and an independent set s with more than CARD t elements would satisfy a   *)
(* relation by ABELIAN_GROUP_DISCRETE_DEPENDENT with the sizes 2 zpow (E x   *)
(* y), x in t (local lemma zpowbound).                                       *)
let FINITELY_GENERATED_ABELIAN_GROUP_INDEPENDENT_BASIS =
  let zpowbound = prove
   (`!a b N. inv b <= &2 zpow a /\ &2 zpow a <= b /\ b <= &N
             ==> --(&N) <= a /\ a <= &N`,
    SUBGOAL_THEN `!n (b:real) N. &2 pow n <= b /\ b <= &N ==> n <= N` ASSUME_TAC
    THENL
     [REPEAT STRIP_TAC THEN REWRITE_TAC[GSYM REAL_OF_NUM_LE] THEN
      TRANS_TAC REAL_LE_TRANS `b:real` THEN ASM_REWRITE_TAC[] THEN
      TRANS_TAC REAL_LE_TRANS `(&2:real) pow n` THEN ASM_REWRITE_TAC[] THEN
      REWRITE_TAC[REAL_OF_NUM_POW; REAL_OF_NUM_LE] THEN
      MATCH_MP_TAC LT_IMP_LE THEN REWRITE_TAC[LT_POW2_REFL];
      ALL_TAC] THEN
    REWRITE_TAC[FORALL_INT_CASES; REAL_ZPOW_NEG; REAL_ZPOW_NUM] THEN
    REWRITE_TAC[INT_LE_NEG2; INT_OF_NUM_LE] THEN CONJ_TAC THEN
    REPEAT GEN_TAC THEN STRIP_TAC THENL
     [CONJ_TAC THENL [INT_ARITH_TAC; ASM_MESON_TAC[]];
      CONJ_TAC THENL [ALL_TAC; INT_ARITH_TAC] THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN EXISTS_TAC `b:real` THEN
      ASM_REWRITE_TAC[] THEN
      MP_TAC(ISPECL [`inv b:real`; `inv(&2 pow n):real`] REAL_LE_INV2) THEN
