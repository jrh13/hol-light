(* ========================================================================= *)
(* Finite generation of groups: extensions, abelian groups modulo m-th       *)
(* powers, a discreteness criterion for abelian groups, and independent sets *)
(* of maximal size.                                                          *)
(*                                                                           *)
(* Main results: a group is finitely generated if the kernel and the image   *)
(* of a homomorphism are (FINITELY_GENERATED_GROUP_EXTENSION); every element *)
(* of a finitely generated abelian group lies in one of finitely many cosets *)
(* of the m-th powers (FINITELY_GENERATED_ABELIAN_GROUP_MOD_POW, from the    *)
(* products of natural powers of FINITELY_GENERATED_ABELIAN_GROUP_POW of     *)
(* Library/grouptheory.ml). An abelian group with                            *)
(* finitely many positive real multiplicative size functions f i, such that  *)
(* only finitely many elements have all sizes in [1 / b, b] for each b, has  *)
(* rank at most the number of size functions                                 *)
(* (ABELIAN_GROUP_DISCRETE_DEPENDENT) and is finitely generated              *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_DISCRETE). With the logarithms of the   *)
(* sizes this is the theorem that a discrete subgroup of R^n with finite     *)
(* fibres is finitely generated; no logarithm is needed in the proof. A      *)
(* finitely generated abelian group has a finite independent set t of        *)
(* elements of infinite order such that every element is a torsion element   *)
(* times a product of integer powers of the elements of t and no independent *)
(* set has more elements than t                                              *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_INDEPENDENT_BASIS). The laws of         *)
(* positive real multiplicative functions on a group (the identity,          *)
(* inverses, powers and finite products:                                     *)
(* GROUP_REAL_MULTIPLICATIVE_ID_INV_POW, GROUP_REAL_MULTIPLICATIVE_ZPOW,     *)
(* GROUP_REAL_MULTIPLICATIVE_SUM) and the finite generation of unit groups   *)
(* (FINITELY_GENERATED_UNIT_GROUP) are in Library/ring_groups.ml.            *)
(*                                                                           *)
(* Route of the criterion. The elements with all sizes in [2^-k, 2^k] are    *)
(* at most (2 k + 1)^CARD s times as many as those with all sizes in         *)
(* [1 / 2, 2] (dyadic cells, GROUP_REAL_MULTIPLICATIVE_BOX_COUNT). For t     *)
(* with CARD t > CARD s the products P(a) = prod_{x IN t} x^(a x),           *)
(* 0 <= a x <= N, have sizes in [2^-k, 2^k] with k linear in N, so for large *)
(* N two of them coincide, P(a) = P(b) with a <> b. For the generation take  *)
(* a maximal independent finite set B; every x outside B has some power      *)
(* x^q = prod_{y IN B} y^(d y), q >= 1, and z = x * prod y^-(d y div q) has  *)
(* z^q = prod y^(d y rem q), so the sizes of z are bounded independently of  *)
(* x: G is generated by B and finitely many such z.                          *)
(*                                                                           *)
(* Uses: Library/grouptheory.ml                                              *)
(* (FINITELY_GENERATED_ABELIAN_GROUP_EXPONENTS,                              *)
(* FINITELY_GENERATED_ABELIAN_GROUP_POW) and Library/ring_groups.ml          *)
(* (GROUP_REAL_MULTIPLICATIVE_ID_INV_POW).                                   *)
(* ========================================================================= *)

needs "Library/products.ml";;
