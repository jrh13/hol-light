(* ========================================================================= *)
(* The ring of integers O_K of a number field K: free of rank n = [K:Q] over *)
(* Z (integral bases), noetherian, integrally closed, every nonzero ideal    *)
(* contains a nonzero integer and has finite index, hence O_K is a Dedekind  *)
(* domain; |O_K / m O_K| = |m|^n.                                            *)
(*                                                                           *)
(* Main results: RING_OF_INTEGERS_FREE, RING_OF_INTEGERS_FREE_BASIS_FIELD,   *)
(* NOETHERIAN_RING_OF_INTEGERS, INTEGRALLY_CLOSED_RING_OF_INTEGERS,          *)
(* RING_OF_INTEGERS_IDEAL_INTEGER, RING_OF_INTEGERS_FINITE_QUOTIENT,         *)
(* RING_OF_INTEGERS_IDEAL_NORM_INTEGER and DEDEKIND_RING_OF_INTEGERS.        *)
(*                                                                           *)
(* Proof route. A ring r that is the image of Z^s under an additive map psi  *)
(* (for example the integer coordinates of an integral basis) is noetherian: *)
(* an ideal j is generated by the images of the columns of a matrix for the  *)
(* lattice of the coordinate vectors of its elements                         *)
(* (NOETHERIAN_RING_INT_LINEAR); the cosets of j are those of that lattice   *)
(* (QUOTIENT_RING_HAS_SIZE_INT_LINEAR); and for an injective psi the ideal   *)
(* (m) is the image of the diagonal matrix m, with index |m|^|s|             *)
(* (QUOTIENT_RING_INTEGER_INT_LINEAR). For a number field, a Q-basis g of    *)
(* integers has a nonzero integral discriminant D, and D O_K lies in the     *)
(* integer span of g by Cramer (RING_OF_INTEGERS_DISCRIMINANT); then O_K     *)
(* lies between that span and its multiples by 1 / D and has an integral     *)
(* basis by RING_INT_LINCOMB_SANDWICH (numfield.ml).                         *)
(*                                                                           *)
(* Helpers for rings with an integral basis:                                 *)
(* FREE_BASIS_QUOTIENT_RING_HAS_SIZE, FREE_BASIS_INTEGER_RING_COORDINATES,   *)
(* FREE_BASIS_IMP_NOETHERIAN_RING, FREE_BASIS_QUOTIENT_RING_INTEGER and      *)
(* FREE_BASIS_INTEGER_RING_SUBRING_GENERATED.                                *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml,                      *)
(* Library/ring_det.ml, ANT/integral.ml, ANT/dedekind.ml (dedekind_domain),  *)
(* ANT/ideal_norm.ml (ideal_norm, FINITE_QUOTIENT_RING_MONO),                *)
(* ANT/zlattice.ml and ANT/numfield.ml.                                      *)
(* ========================================================================= *)

