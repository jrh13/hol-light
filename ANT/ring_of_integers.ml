   [UNDISCH_TAC `(x:A) IN ok` THEN EXPAND_TAC "ok" THEN
    REWRITE_TAC[RING_OF_INTEGERS_CARRIER; IN_ELIM_THM];
    DISCH_THEN(X_CHOOSE_THEN `n:num` (X_CHOOSE_THEN `c:num->int`
      STRIP_ASSUME_TAC) o CONJUNCT2)] THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`n:num`; `c:num->int`]) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:int` (X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC)) THEN
  EXISTS_TAC `m:int` THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `j:A->bool`; `x:A`; `y:A`]
    IN_RING_IDEAL_RMUL) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_OF_INTEGERS_SUBRING]);;

let RING_OF_INTEGERS_FINITE_QUOTIENT = prove
 (`!k:A ring j.
        number_field k /\ ring_ideal (ring_of_integers k) j /\
        ~(j = {ring_0 k})
        ==> FINITE(ring_carrier(quotient_ring (ring_of_integers k) j))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `j:A->bool`] RING_OF_INTEGERS_IDEAL_INTEGER) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:int` STRIP_ASSUME_TAC) THEN
  FIRST_ASSUM(X_CHOOSE_TAC `w:num->A` o MATCH_MP RING_OF_INTEGERS_FREE) THEN
  MATCH_MP_TAC FINITE_QUOTIENT_RING_MONO THEN
  EXISTS_TAC
   `ideal_generated (ring_of_integers k) {ring_of_int (k:A ring) m}` THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[SING_SUBSET];
    MP_TAC(ISPECL
     [`ring_of_integers k:A ring`;
      `extension_degree (subfield_generated (k:A ring) {ring_0 k},k) I`;
      `w:num->A`; `m:int`] FREE_BASIS_QUOTIENT_RING_INTEGER) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_OF_INTEGERS_SUBRING] THEN
    SIMP_TAC[HAS_SIZE]]);;

let RING_OF_INTEGERS_FINITE_RESIDUE_FIELDS = prove
 (`!k:A ring.
        number_field k
        ==> !P. prime_ideal (ring_of_integers k) P /\
                ~(P = {ring_0(ring_of_integers k)})
                ==> FINITE(ring_carrier(quotient_ring (ring_of_integers k) P))`,
  REWRITE_TAC[RING_OF_INTEGERS] THEN REPEAT STRIP_TAC THEN
  MATCH_MP_TAC RING_OF_INTEGERS_FINITE_QUOTIENT THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]);;

let RING_OF_INTEGERS_IDEAL_NORM_INTEGER = prove
 (`!k:A ring m.
        number_field k /\ ~(m = &0)
        ==> ideal_norm (ring_of_integers k)
              (ideal_generated (ring_of_integers k) {ring_of_int k m}) =
            num_of_int(abs m) EXP
            extension_degree (subfield_generated k {ring_0 k},k) I`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(X_CHOOSE_TAC `w:num->A` o MATCH_MP RING_OF_INTEGERS_FREE) THEN
  MP_TAC(ISPECL
   [`ring_of_integers k:A ring`;
    `extension_degree (subfield_generated (k:A ring) {ring_0 k},k) I`;
    `w:num->A`; `m:int`] FREE_BASIS_QUOTIENT_RING_INTEGER) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_OF_INTEGERS_SUBRING] THEN
  SIMP_TAC[HAS_SIZE; ideal_norm]);;

let DEDEKIND_RING_OF_INTEGERS = prove
 (`!k:A ring. number_field k ==> dedekind_domain(ring_of_integers k)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[dedekind_domain] THEN
  ASM_SIMP_TAC[INTEGRAL_DOMAIN_RING_OF_INTEGERS; NUMBER_FIELD_IMP_FIELD;
               NOETHERIAN_RING_OF_INTEGERS;
               INTEGRALLY_CLOSED_RING_OF_INTEGERS] THEN
  X_GEN_TAC `p:A->bool` THEN
  REWRITE_TAC[RING_OF_INTEGERS; RING_OF_INTEGERS_SUBRING] THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `ring_ideal (ring_of_integers k) (p:A->bool)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]; ALL_TAC] THEN
  ASM_SIMP_TAC[GSYM FIELD_QUOTIENT_RING] THEN
  MATCH_MP_TAC FINITE_INTEGRAL_DOMAIN_IMP_FIELD THEN
  ASM_SIMP_TAC[INTEGRAL_DOMAIN_QUOTIENT_RING;
               RING_OF_INTEGERS_FINITE_QUOTIENT]);;
