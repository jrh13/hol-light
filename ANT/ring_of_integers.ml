(* ------------------------------------------------------------------------- *)
(* Rings that are integer linear images of Z^s: cosets of ideals,            *)
(* noetherianity, the quotient by an integer.                                *)
(* ------------------------------------------------------------------------- *)

let QUOTIENT_RING_HAS_SIZE_INT_LINEAR = prove
 (`!r:A ring j (psi:(K->int)->A) s N.
        ring_ideal r j /\
        (!z. psi z IN ring_carrier r) /\
        (!x y. psi (\i. x i - y i) = ring_sub r (psi x) (psi y)) /\
        (!x. x IN ring_carrier r
             ==> ?z. (!i. ~(i IN s) ==> z i = &0) /\ psi z = x)
        ==> (ring_carrier(quotient_ring r j) HAS_SIZE N <=>
             int_cosets s {z | (!i. ~(i IN s) ==> z i = &0) /\ psi z IN j}
             HAS_SIZE N)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `ring_carrier(quotient_ring r j) =
    IMAGE (\z. ring_coset r j ((psi:(K->int)->A) z))
          {z | !i. ~(i IN s) ==> z i = &0}`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[QUOTIENT_RING_CARRIER] THEN
    GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_ELIM_THM; IN_IMAGE] THEN
    X_GEN_TAC `c:A->bool` THEN EQ_TAC THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[] THENL
     [FIRST_X_ASSUM(MP_TAC o SPEC `a:A`) THEN ASM_REWRITE_TAC[] THEN
      DISCH_THEN(X_CHOOSE_THEN `z:K->int` STRIP_ASSUME_TAC) THEN
      EXISTS_TAC `z:K->int` THEN ASM_REWRITE_TAC[];
      EXISTS_TAC `(psi:(K->int)->A) x` THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `int_cosets s
      {z | (!i. ~(i IN s) ==> z i = &0) /\ (psi:(K->int)->A) z IN j} =
    IMAGE (\x. {y | (!i. ~(i IN s) ==> y i = &0) /\
                    ring_sub r (psi y) (psi x) IN j})
          {z | !i. ~(i IN s) ==> z i = &0}`
  SUBST1_TAC THENL
   [REWRITE_TAC[int_cosets] THEN
    GEN_REWRITE_TAC LAND_CONV [SIMPLE_IMAGE_GEN] THEN
    MATCH_MP_TAC IMAGE_EQ THEN X_GEN_TAC `x:K->int` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN X_GEN_TAC `y:K->int` THEN
    ASM_CASES_TAC `!i. ~(i IN s) ==> (y:K->int) i = &0` THEN
    ASM_SIMP_TAC[INT_SUB_REFL];
    ALL_TAC] THEN
  MATCH_MP_TAC CARD_HAS_SIZE_CONG THEN MATCH_MP_TAC CARD_EQ_IMAGES THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  MAP_EVERY X_GEN_TAC [`x:K->int`; `y:K->int`] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[RING_COSET_EQ; EXTENSION; IN_ELIM_THM] THEN EQ_TAC THENL
   [DISCH_TAC THEN X_GEN_TAC `z:K->int` THEN
    ASM_CASES_TAC `!i. ~(i IN s) ==> (z:K->int) i = &0` THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`r:A ring`; `(psi:(K->int)->A) z`; `(psi:(K->int)->A) x`;
                   `(psi:(K->int)->A) y`]
      (RING_RULE `!r a b c:A.
         a IN ring_carrier r /\ b IN ring_carrier r /\ c IN ring_carrier r
         ==> ring_sub r a c = ring_add r (ring_sub r a b) (ring_sub r b c) /\
             ring_sub r a b =
             ring_sub r (ring_sub r a c) (ring_sub r b c)`)) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(fun th -> EQ_TAC THEN DISCH_TAC THEN ONCE_REWRITE_TAC[th]) THENL
     [MATCH_MP_TAC IN_RING_IDEAL_ADD; MATCH_MP_TAC IN_RING_IDEAL_SUB] THEN
    ASM_REWRITE_TAC[];
    DISCH_THEN(MP_TAC o SPEC `x:K->int`) THEN
    ASM_SIMP_TAC[RING_SUB_REFL; IN_RING_IDEAL_0]]);;

(* If moreover psi is Z-linear and s is finite, r is noetherian: an ideal is *)
(* generated by the images of the columns of a matrix whose image is the     *)
(* lattice of vectors mapped into it.                                        *)
let NOETHERIAN_RING_INT_LINEAR = prove
 (`!r:A ring (psi:(K->int)->A) s.
        FINITE s /\
        (!z. psi z IN ring_carrier r) /\
        (!x y. psi (\i. x i - y i) = ring_sub r (psi x) (psi y)) /\
        (!M z. psi (\i. isum s (\j. M i j * z j)) =
               ring_sum r s
                 (\j. ring_mul r (ring_of_int r (z j)) (psi (\i. M i j)))) /\
        (!z z'. (!i. i IN s ==> z i = z' i) ==> psi z = psi z') /\
        (!x. x IN ring_carrier r
             ==> ?z. (!i. ~(i IN s) ==> z i = &0) /\ psi z = x)
        ==> noetherian_ring r`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `(psi:(K->int)->A) (\i. &0) = ring_0 r` ASSUME_TAC THENL
   [MP_TAC(SPECL [`\i:K. (&0:int)`; `\i:K. (&0:int)`] (ASSUME
     `!x y. (psi:(K->int)->A) (\i. x i - y i) =
            ring_sub r (psi x) (psi y)`)) THEN
    REWRITE_TAC[INT_SUB_REFL] THEN ASM_SIMP_TAC[RING_SUB_REFL];
    ALL_TAC] THEN
  REWRITE_TAC[noetherian_ring; finitely_generated_ideal] THEN
  X_GEN_TAC `j:A->bool` THEN DISCH_TAC THEN
  MP_TAC(ISPECL
   [`s:K->bool`;
    `{z | (!i. ~(i IN s) ==> z i = &0) /\ (psi:(K->int)->A) z IN j}`]
   INT_LATTICE_MATRIX_IMAGE) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[int_lattice; SUBSET; IN_ELIM_THM] THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0; IN_RING_IDEAL_SUB; INT_SUB_REFL];
    DISCH_THEN(X_CHOOSE_TAC `M:K->K->int`)] THEN
  EXISTS_TAC `IMAGE (\l:K. (psi:(K->int)->A) (\i. (M:K->K->int) i l))
                    (s:K->bool)` THEN
  ASM_SIMP_TAC[FINITE_IMAGE; SUBSET; FORALL_IN_IMAGE] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN
    X_GEN_TAC `l:K` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `(\i. if i IN s then (M:K->K->int) i l else &0) IN int_matrix_image s M`
    MP_TAC THENL
     [REWRITE_TAC[int_matrix_image; IN_IMAGE; IN_UNIV] THEN
      EXISTS_TAC `\j:K. if j = l then (&1:int) else &0` THEN
      REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `i:K` THEN
      COND_CASES_TAC THEN
      ASM_REWRITE_TAC[COND_RAND; INT_MUL_RID; INT_MUL_RZERO;
                      ISUM_DELTA_GEN];
      FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN REWRITE_TAC[IN_ELIM_THM] THEN
      DISCH_THEN(MP_TAC o CONJUNCT2) THEN MATCH_MP_TAC EQ_IMP THEN
      AP_THM_TAC THEN AP_TERM_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
      SIMP_TAC[]];
    REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `c:K->int` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN
     `(c:K->int) IN
      {z | (!i. ~(i IN s) ==> z i = &0) /\ (psi:(K->int)->A) z IN j}`
    MP_TAC THENL [ASM_REWRITE_TAC[IN_ELIM_THM]; ASM_REWRITE_TAC[]] THEN
    REWRITE_TAC[int_matrix_image; IN_IMAGE; IN_UNIV] THEN
    DISCH_THEN(X_CHOOSE_THEN `z:K->int` ASSUME_TAC) THEN
    SUBGOAL_THEN
     `x = (psi:(K->int)->A) (\i. isum s (\j. (M:K->K->int) i j * z j))`
    SUBST1_TAC THENL
     [TRANS_TAC EQ_TRANS `(psi:(K->int)->A) c` THEN
      CONJ_TAC THENL [ASM_REWRITE_TAC[]; FIRST_ASSUM MATCH_MP_TAC] THEN
      ASM_SIMP_TAC[];
      ASM_REWRITE_TAC[]] THEN
    MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    X_GEN_TAC `l:K` THEN DISCH_TAC THEN
    MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; RING_OF_INT] THEN
    MATCH_MP_TAC IDEAL_GENERATED_INC THEN
    ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN
    REWRITE_TAC[IN_IMAGE] THEN EXISTS_TAC `l:K` THEN ASM_REWRITE_TAC[]]);;

(* If moreover psi is injective, the quotient by an integer m has |m|^|s|    *)
(* elements.                                                                 *)
let QUOTIENT_RING_INTEGER_INT_LINEAR = prove
 (`!r:A ring (psi:(K->int)->A) s m.
        FINITE s /\ ~(m = &0) /\
        (!z. psi z IN ring_carrier r) /\
        (!x y. psi (\i. x i - y i) = ring_sub r (psi x) (psi y)) /\
        (!c x. psi (\i. c * x i) = ring_mul r (ring_of_int r c) (psi x)) /\
        (!z z'. (!i. i IN s ==> z i = z' i) ==> psi z = psi z') /\
        (!x. x IN ring_carrier r
             ==> ?z. (!i. ~(i IN s) ==> z i = &0) /\ psi z = x) /\
        (!z. psi z = ring_0 r ==> !i. i IN s ==> z i = &0)
        ==> ring_carrier(quotient_ring r (ideal_generated r {ring_of_int r m}))
            HAS_SIZE (num_of_int(abs m) EXP CARD s)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `!x y. (!i. ~(i IN s) ==> x i = &0) /\ (!i. ~(i IN s) ==> y i = &0) /\
          (psi:(K->int)->A) x = psi y
          ==> x = y`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `i:K` THEN
    ASM_CASES_TAC `(i:K) IN s` THEN ASM_SIMP_TAC[] THEN
    MP_TAC(SPEC `\i:K. (x:K->int) i - y i` (ASSUME
     `!z. (psi:(K->int)->A) z = ring_0 r ==> !i. i IN s ==> z i = &0`)) THEN
    ASM_SIMP_TAC[RING_SUB_REFL] THEN DISCH_THEN(MP_TAC o SPEC `i:K`) THEN
    ASM_REWRITE_TAC[] THEN INT_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`;
                 `ideal_generated (r:A ring) {ring_of_int r (m:int)}`;
                 `psi:(K->int)->A`; `s:K->bool`;
                 `num_of_int(abs m) EXP CARD(s:K->bool)`]
    QUOTIENT_RING_HAS_SIZE_INT_LINEAR) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN DISCH_THEN SUBST1_TAC THEN
  SUBGOAL_THEN
   `{z | (!i. ~(i IN s) ==> z i = &0) /\
         (psi:(K->int)->A) z IN ideal_generated r {ring_of_int r m}} =
    int_matrix_image s (\i j:K. if i = j then m else &0)`
  SUBST1_TAC THENL
   [SIMP_TAC[IDEAL_GENERATED_SING_ALT; RING_OF_INT] THEN
    SUBGOAL_THEN
     `int_matrix_image s (\i j:K. if i = j then m else &0) =
      IMAGE (\z i. if i IN s then m * z i else &0) (:K->int)`
    SUBST1_TAC THENL
     [REWRITE_TAC[int_matrix_image] THEN MATCH_MP_TAC IMAGE_EQ THEN
      X_GEN_TAC `z:K->int` THEN DISCH_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN
      X_GEN_TAC `i:K` THEN COND_CASES_TAC THEN REWRITE_TAC[] THEN
      TRANS_TAC EQ_TRANS
       `isum s (\j. if j = i then m * (z:K->int) j else &0)` THEN
      CONJ_TAC THENL
       [AP_TERM_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `j:K` THEN
        ASM_CASES_TAC `j:K = i` THEN ASM_REWRITE_TAC[INT_MUL_LZERO];
        ASM_REWRITE_TAC[ISUM_DELTA_GEN]];
      ALL_TAC] THEN
    REWRITE_TAC[EXTENSION; IN_ELIM_THM; IN_IMAGE; IN_UNIV] THEN
    X_GEN_TAC `z:K->int` THEN EQ_TAC THENL
     [DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
       (X_CHOOSE_THEN `x:A` STRIP_ASSUME_TAC)) THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[] THEN
      DISCH_THEN(X_CHOOSE_THEN `c:K->int` STRIP_ASSUME_TAC) THEN
      EXISTS_TAC `c:K->int` THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
      ASM_SIMP_TAC[] THEN
      TRANS_TAC EQ_TRANS `(psi:(K->int)->A) (\i. m * c i)` THEN
      CONJ_TAC THENL [ASM_REWRITE_TAC[]; FIRST_ASSUM MATCH_MP_TAC] THEN
      SIMP_TAC[];
      DISCH_THEN(X_CHOOSE_THEN `c:K->int` SUBST1_TAC) THEN
      CONJ_TAC THENL [SIMP_TAC[]; ALL_TAC] THEN
      EXISTS_TAC `(psi:(K->int)->A) c` THEN ASM_REWRITE_TAC[] THEN
      TRANS_TAC EQ_TRANS `(psi:(K->int)->A) (\i. m * c i)` THEN
      CONJ_TAC THENL [FIRST_ASSUM MATCH_MP_TAC THEN SIMP_TAC[];
                      ASM_REWRITE_TAC[]]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`s:K->bool`; `\i j:K. if i = j then (m:int) else &0`]
    INT_COSETS_MATRIX_IMAGE) THEN
  SUBGOAL_THEN
   `ring_det integer_ring s (\i j:K. if i = j then m else &0) = m pow CARD s`
  SUBST1_TAC THENL
   [W(MP_TAC o PART_MATCH (lhand o rand) RING_DET_DIAGONAL o lhand o snd) THEN
    ASM_REWRITE_TAC[INTEGER_RING] THEN ANTS_TAC THENL
     [SIMP_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    ASM_SIMP_TAC[RING_PRODUCT_CONST; INTEGER_RING; IN_UNIV; INTEGER_RING_POW];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[INT_POW_EQ_0] THEN
  SIMP_TAC[INT_ABS_POW; NUM_OF_INT_POW; INT_ABS_POS]);;

