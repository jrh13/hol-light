let FREE_BASIS_INTEGER_RING_SUBRING_GENERATED = prove
 (`!k:A ring t n w.
        t subring_of k
        ==> (free_basis (integer_ring,subring_generated k t) (ring_of_int k)
                        n w <=>
             (!i. i < n ==> w i IN t) /\
             (!x. x IN t
                  ==> ?c. x = ring_sum k {i | i < n}
                               (\i. ring_mul k (ring_of_int k (c i)) (w i))) /\
             (!c. ring_sum k {i | i < n}
                    (\i. ring_mul k (ring_of_int k (c i)) (w i)) = ring_0 k
                  ==> !i. i < n ==> c i = &0))`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[free_basis; INTEGER_RING; IN_UNIV;
               CARRIER_SUBRING_GENERATED_SUBRING;
               CONJUNCT2 SUBRING_GENERATED; RING_SUM_SUBRING_GENERATED] THEN
  ASM_CASES_TAC `!i. i < n ==> (w:num->A) i IN t` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `!c. {i | i IN {i | i < n} /\
             ring_mul k (ring_of_int k (c i)) ((w:num->A) i) IN t} =
        {i | i < n}`
   (fun th -> REWRITE_TAC[th]) THEN
  REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN
  ASM_MESON_TAC[IN_SUBRING_MUL; IN_SUBRING_INT]);;

(* The cosets of an ideal correspond to those of its coordinate lattice.     *)
let FREE_BASIS_QUOTIENT_RING_HAS_SIZE = prove
 (`!r:A ring n w j N.
        free_basis (integer_ring,r) (ring_of_int r) n w /\ ring_ideal r j
        ==> (ring_carrier(quotient_ring r j) HAS_SIZE N <=>
             int_cosets {i | i < n}
              {z | (!i. ~(i < n) ==> z i = &0) /\
                   ring_sum r {i | i < n}
                     (\i. ring_mul r (ring_of_int r (z i)) (w i)) IN j}
             HAS_SIZE N)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[free_basis; INTEGER_RING; IN_UNIV] THEN
  STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `{i:num | i < n}`; `w:num->A`]
    RING_INT_LINCOMB) THEN
  ASM_REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN STRIP_TAC THEN
  MP_TAC(ISPECL
   [`r:A ring`; `j:A->bool`;
    `\z:num->int. ring_sum r {i | i < n}
                    (\i. ring_mul r (ring_of_int r (z i)) ((w:num->A) i))`;
    `{i:num | i < n}`; `N:num`] QUOTIENT_RING_HAS_SIZE_INT_LINEAR) THEN
  ASM_REWRITE_TAC[IN_ELIM_THM; RING_SUM] THEN DISCH_THEN MATCH_MP_TAC THEN
  X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `x:A` o check (is_imp o snd o strip_forall o
    concl)) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `c:num->int` SUBST1_TAC) THEN
  EXISTS_TAC `\i. if i < n then (c:num->int) i else &0` THEN
  SIMP_TAC[] THEN MATCH_MP_TAC RING_SUM_EQ THEN SIMP_TAC[IN_ELIM_THM]);;

(* The integer coordinate map z |-> sum_i z_i w_i of an integral basis.      *)
let FREE_BASIS_INTEGER_RING_COORDINATES = prove
 (`!r:A ring n w.
        free_basis (integer_ring,r) (ring_of_int r) n w
        ==> (!z. ring_sum r {i | i < n}
                   (\i. ring_mul r (ring_of_int r (z i)) (w i))
                 IN ring_carrier r) /\
            (!z z'. (!i. i IN {i | i < n} ==> z i = z' i)
                    ==> ring_sum r {i | i < n}
                          (\i. ring_mul r (ring_of_int r (z i)) (w i)) =
                        ring_sum r {i | i < n}
                          (\i. ring_mul r (ring_of_int r (z' i)) (w i))) /\
            (!x. x IN ring_carrier r
                 ==> ?z. (!i. ~(i IN {i | i < n}) ==> z i = &0) /\
                         ring_sum r {i | i < n}
                           (\i. ring_mul r (ring_of_int r (z i)) (w i)) = x) /\
            (!z. ring_sum r {i | i < n}
                   (\i. ring_mul r (ring_of_int r (z i)) (w i)) = ring_0 r
                 ==> !i. i IN {i | i < n} ==> z i = &0)`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[free_basis; INTEGER_RING; IN_UNIV; IN_ELIM_THM] THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[RING_SUM] THEN CONJ_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_SUM_EQ THEN
    ASM_SIMP_TAC[IN_ELIM_THM];
    X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `x:A` o check (is_imp o snd o strip_forall o
      concl)) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `c:num->int` SUBST1_TAC) THEN
    EXISTS_TAC `\i. if i < n then (c:num->int) i else &0` THEN
    SIMP_TAC[] THEN MATCH_MP_TAC RING_SUM_EQ THEN SIMP_TAC[IN_ELIM_THM]]);;

let FREE_BASIS_IMP_NOETHERIAN_RING = prove
 (`!r:A ring n w.
        free_basis (integer_ring,r) (ring_of_int r) n w ==> noetherian_ring r`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FREE_BASIS_INTEGER_RING_COORDINATES) THEN
