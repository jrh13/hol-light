(* Local generators of the different at p: an element d of D with the        *)
(* valuations of D at the primes above p, so v_p(N(d)) = v_p(N(D)), and t    *)
(* in O_k outside p with h(t) d^-1 in the codifferent (D = d J with J prime  *)
(* to p, and t = N(y) for some y in J with N(y) outside p).                  *)
let NUMBER_FIELD_DIFFERENT_LOCAL_GENERATOR = prove
 (`!k:A ring l:B ring h p.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> ?d t. d IN number_field_different (k,l) h /\ ~(d = ring_0 l) /\
                  ideal_valuation (ring_of_integers k) p
                    (ideal_generated (ring_of_integers k)
                       {algebra_norm (k,l) h d}) =
                  ideal_valuation (ring_of_integers k) p
                    (number_field_ideal_norm (k,l) h
                       (number_field_different (k,l) h)) /\
                  t IN ring_carrier(ring_of_integers k) /\ ~(t IN p) /\
                  ring_mul l (h t) (ring_inv l d) IN
                  number_field_codifferent (k,l) h`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  SUBGOAL_THEN
   `dedekind_domain(ring_of_integers k:A ring) /\
    dedekind_domain(ring_of_integers l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    RING_IDEAL_NUMBER_FIELD_DIFFERENT) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_DIFFERENT_NONZERO) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_CODIFFERENT_DIFFERENT) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC `D = number_field_different (k:A ring,l:B ring) h` THEN
  REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(D:B->bool) SUBSET ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL [ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN
   `!P. prime_ideal (ring_of_integers l) P /\ IMAGE (h:A->B) p SUBSET P
        ==> ~(P = {ring_0 l})`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`]
      NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                 `{P | prime_ideal (ring_of_integers l) P /\
                       IMAGE (h:A->B) p SUBSET P}`;
                 `D:B->bool`] DEDEKIND_IDEAL_WEAK_APPROXIMATION) THEN
  ASM_SIMP_TAC[RING_OF_INTEGERS; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `d:B` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `(d:B) IN ring_carrier(ring_of_integers l) /\
                d IN ring_carrier l`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ideal_valuation (ring_of_integers k) p
      (ideal_generated (ring_of_integers k) {algebra_norm (k,l) (h:A->B) d}) =
    ideal_valuation (ring_of_integers k) p
      (number_field_ideal_norm (k,l) h D)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `d:B`]
      NUMBER_FIELD_NORM_VALUATION) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_VALUATION] THEN
    MATCH_MP_TAC NSUM_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  EXISTS_TAC `d:B` THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                 `ideal_generated (ring_of_integers l) {d:B}`; `D:B->bool`]
    DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
  MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[SING_SUBSET];
    DISCH_THEN(X_CHOOSE_THEN `J:B->bool` STRIP_ASSUME_TAC)] THEN
  SUBGOAL_THEN `~(J = {ring_0 l:B})` ASSUME_TAC THENL
   [DISCH_TAC THEN
    UNDISCH_TAC
     `ideal_prod (ring_of_integers l) D J =
      ideal_generated (ring_of_integers l) {d:B}` THEN
    ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; REWRITE_RULE[RING_OF_INTEGERS]
     (ISPEC `ring_of_integers l:B ring` IDEAL_PROD_RZERO)] THEN
    DISCH_THEN(MP_TAC o SYM) THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS_IDEAL_GENERATED_SING_EQ_0];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!P. prime_ideal (ring_of_integers l) P /\ IMAGE (h:A->B) p SUBSET P
        ==> ideal_valuation (ring_of_integers l) P J = 0`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `P:B->bool`; `D:B->bool`;
                   `J:B->bool`] IDEAL_VALUATION_IDEAL_PROD) THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS] THEN ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `~(number_field_ideal_norm (k,l) (h:A->B) J SUBSET p)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`;
                   `number_field_ideal_norm (k:A ring,l:B ring) h J`; `1`]
      DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL; RING_OF_INTEGERS;
                 NUMBER_FIELD_IDEAL_NORM_IDEAL;
                 NUMBER_FIELD_IDEAL_NORM_EQ_0;
                 NUMBER_FIELD_IDEAL_NORM_VALUATION] THEN
    DISCH_THEN(K ALL_TAC) THEN
    MATCH_MP_TAC(ARITH_RULE `(n:num) = 0 ==> ~(1 <= n)`) THEN
    MATCH_MP_TAC NSUM_EQ_0 THEN REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_SIMP_TAC[MULT_CLAUSES];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `?y. y IN J /\ ~(algebra_norm (k,l) (h:A->B) y IN p)`
  STRIP_ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o check (fun th -> is_neg(concl th) &&
      can (find_term ((=) `number_field_ideal_norm:(A ring#B ring)->(A->B)->
                            (B->bool)->A->bool`)) (concl th))) THEN
    ONCE_REWRITE_TAC[GSYM CONTRAPOS_THM] THEN
    REWRITE_TAC[NOT_EXISTS_THM; TAUT `~(p /\ ~q) <=> p ==> q`] THEN
    DISCH_TAC THEN REWRITE_TAC[number_field_ideal_norm] THEN
    MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; SUBSET; FORALL_IN_GSPEC];
    ALL_TAC] THEN
  SUBGOAL_THEN `(y:B) IN ring_carrier(ring_of_integers l)` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  EXISTS_TAC `algebra_norm (k,l) (h:A->B) y` THEN
  ASM_SIMP_TAC[NUMBER_FIELD_NORM_INTEGRAL] THEN
  ABBREV_TAC `t = algebra_norm (k,l) (h:A->B) y` THEN
  SUBGOAL_THEN `(h:A->B) t IN J` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `y:B`]
      NUMBER_FIELD_NORM_MULTIPLE) THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(SET_RULE `s SUBSET t ==> (x:B) IN s ==> x IN t`) THEN
    MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[SING_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN `(h:A->B) t IN ring_carrier(ring_of_integers l) /\
                h t IN ring_carrier l`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET; RING_OF_INTEGERS_SUBSET];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_SIMP_TAC[RING_MUL; RING_INV] THEN
  X_GEN_TAC `z:B` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(z:B) IN ring_carrier(ring_of_integers l) /\
                z IN ring_carrier l`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul l z ((h:A->B) t) IN ideal_generated (ring_of_integers l) {d}`
  MP_TAC THENL
   [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) &&
      rand(concl th) = `ideal_generated (ring_of_integers l) {d:B}`)) THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `D:B->bool`; `J:B->bool`;
                   `z:B`; `(h:A->B) t`] RING_MUL_IN_IDEAL_PROD) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_SING_ALT; IN_ELIM_THM] THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN
  DISCH_THEN(X_CHOOSE_THEN `w:B` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `(w:B) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul l (ring_mul l ((h:A->B) t) (ring_inv l d)) z =
    ring_mul l (ring_mul l (ring_inv l d) d) w`
  SUBST1_TAC THENL
   [TRANS_TAC EQ_TRANS
     `ring_mul l (ring_inv l d) (ring_mul l z ((h:A->B) t))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `ring_mul (r:B ring) (ring_mul r a b) c =
        ring_mul r b (ring_mul r c a)`) THEN
      ASM_SIMP_TAC[RING_INV];
      ASM_REWRITE_TAC[] THEN MATCH_MP_TAC RING_MUL_ASSOC THEN
      ASM_SIMP_TAC[RING_INV]];
    ASM_SIMP_TAC[FIELD_MUL_LINV; RING_MUL_LID]]);;

(* ------------------------------------------------------------------------- *)
(* The relative discriminant and the discriminants of bases.                 *)
(* ------------------------------------------------------------------------- *)

(* The discriminant of every basis of l over k in O_l lies in N(D): at each  *)
(* p, det(Tr(u w_i w_j)) is in O_k for u = h(t) d^-1 in the codifferent      *)
(* (NUMBER_FIELD_DIFFERENT_LOCAL_GENERATOR), and N(d) det = t^n d(w).        *)
let NUMBER_FIELD_BASIS_DISCRIMINANT_IN_NORM_DIFFERENT = prove
 (`!k:A ring l:B ring h n w.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        free_basis (k,l) h n w /\
        (!i. i < n ==> w i IN ring_carrier(ring_of_integers l))
        ==> basis_discriminant (k,l) h n w IN
            number_field_ideal_norm (k,l) h (number_field_different (k,l) h)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  SUBGOAL_THEN
   `dedekind_domain(ring_of_integers k:A ring) /\
    dedekind_domain(ring_of_integers l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `n:num`; `w:num->B`;
                 `ring_1 l:B`] NUMBER_FIELD_CODIFFERENT_BASIS_DISCRIMINANT) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
      RING_OF_INTEGERS_SUBSET_CODIFFERENT) THEN
    ASM_REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    REWRITE_TAC[REWRITE_RULE[RING_OF_INTEGERS]
     (ISPEC `ring_of_integers l:B ring` RING_1)];
    STRIP_TAC] THEN
  ABBREV_TAC `e = basis_discriminant (k,l) (h:A->B) n w` THEN
  ABBREV_TAC
   `N = number_field_ideal_norm (k,l) (h:A->B)
          (number_field_different (k,l) h)` THEN
  SUBGOAL_THEN
   `ring_ideal (ring_of_integers k) (N:A->bool) /\ ~(N = {ring_0 k})`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "N" THEN
    ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_IDEAL;
                 NUMBER_FIELD_IDEAL_NORM_EQ_0;
                 RING_IDEAL_NUMBER_FIELD_DIFFERENT;
                 NUMBER_FIELD_DIFFERENT_NONZERO];
    ALL_TAC] THEN
  SUBGOAL_THEN `ideal_generated (ring_of_integers k) {e:A} SUBSET N`
  MP_TAC THENL
   [ALL_TAC;
    REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                 `ideal_generated (ring_of_integers k) {e:A}`; `N:A->bool`]
    DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; RING_OF_INTEGERS;
