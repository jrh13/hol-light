              (number_field_different (k,m) (h2 o h1)) =
            ideal_prod (ring_of_integers k)
              (ideal_pow (ring_of_integers k)
                 (number_field_ideal_norm (k,l) h1
                    (number_field_different (k,l) h1))
                 (extension_degree(l,m) h2))
