(* ========================================================================= *)
(* The relative discriminant of an extension of number fields. For a field k *)
(* with a ring homomorphism h into a number field l, the relative            *)
(* discriminant is the ideal norm of the relative different (no new          *)
(* constant), an ideal of O_k (ANT/ideal_norm_extension.ml,                  *)
(* ANT/different_extension.ml):                                              *)
(*                                                                           *)
(*   d_(l/k) = N_(l/k)(D_(l/k)) =                                            *)
(*   number_field_ideal_norm (k,l) h (number_field_different (k,l) h).       *)
(*                                                                           *)
(* It is the ideal generated by the discriminants of the bases of l over k   *)
(* inside O_l (NUMBER_FIELD_DISCRIMINANT_BASES); a nonzero prime p           *)
(* of O_k divides it iff p ramifies in l                                     *)
(* (NUMBER_FIELD_DISCRIMINANT_RAMIFIED); d_(m/k) = d_(l/k)^[m:l]             *)
(* N_(l/k)(d_(m/l)) for k -> l -> m                                          *)
(* (NUMBER_FIELD_DISCRIMINANT_TOWER);                                        *)
(* for the absolute discriminants |d_l| = |d_k|^[l:k] N(d_(l/k)), so         *)
(* d_k^[l:k] divides d_l (NUMBER_FIELD_DISCRIMINANT_TOWER_Q,                 *)
(* NUMBER_FIELD_DISCRIMINANT_POW_DIVIDES).                                   *)
(*                                                                           *)
(* On the way, with det(Tr(x g_i g_j)) = N(x) d(g) for a free basis g        *)
(* (BASIS_DISCRIMINANT_MUL of Library/ring_det.ml) and the trace dual basis  *)
(* of a basis with unit discriminant (ALGEBRA_TRACE_DUAL_BASIS_EXISTS of     *)
(* Library/ring_det.ml): local generators of D at                            *)
(* p: d in D with the valuations of D at the primes above p, and t in O_k    *)
(* outside p with h(t) d^-1 in the codifferent                               *)
(* (NUMBER_FIELD_DIFFERENT_LOCAL_GENERATOR); s times the trace dual of a     *)
(* local basis lies in the codifferent                                       *)
(* (NUMBER_FIELD_CODIFFERENT_LOCAL_DUAL).                                    *)
(*                                                                           *)
(* Routes. For u = h(t) d^-1 in the codifferent and a basis w of l over k in *)
(* O_l, the matrix (Tr(u w_i w_j)) has entries in O_k and its determinant a  *)
(* satisfies N(d) a = t^n d(w) (NUMBER_FIELD_BASIS_DISCRIMINANT_TWIST), so   *)
(* v_p(d(w)) >= v_p(N(d)) = v_p(d_(l/k)) at every p: d(w) is in d_(l/k)      *)
(* (NUMBER_FIELD_BASIS_DISCRIMINANT_IN_NORM_DIFFERENT). For a local basis w  *)
(* at p (RING_OF_INTEGERS_LOCAL_BASIS of ANT/different_extension.ml) a is a  *)
(* unit at p. The local trace-dual computation: with v the trace dual basis  *)
(* of w, the coordinates of the s d s v_i form a matrix B over O_k with B    *)
(* (Tr(u w_i w_j)) = t s^2 I, so det(B) a = (t s^2)^n                        *)
(* (NUMBER_FIELD_BASIS_DISCRIMINANT_TWIST_LOCAL). Its ideal-norm             *)
(* interpretation: t and s lie outside p, so v_p(a) = 0 and v_p(d(w)) =      *)
(* v_p(N(d)) = v_p(d_(l/k)) (NUMBER_FIELD_NORM_DIFFERENT_LOCAL_BASIS). The   *)
(* ramification criterion is the valuation formula for the norm with         *)
(* NUMBER_FIELD_DIFFERENT_RAMIFIED; the towers come from                     *)
(* NUMBER_FIELD_DIFFERENT_TOWER, over the prime subfields for the absolute   *)
(* discriminants (NUMBER_FIELD_CODIFFERENT_EQ_IMAGE,                         *)
(* NUMBER_FIELD_IDEAL_NORM_DIFFERENT).                                       *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml, Library/ring_det.ml  *)
(* (ring_det, basis_discriminant, RING_DET_MUL, BASIS_DISCRIMINANT_MUL,      *)
(* ALGEBRA_TRACE_DUAL_BASIS_EXISTS), ANT/ideal_arith.ml, ANT/dedekind.ml,    *)
(* ANT/dedekind_struct.ml (DEDEKIND_IDEAL_WEAK_APPROXIMATION),               *)
(* ANT/ideal_norm.ml, ANT/numfield.ml, ANT/ring_of_integers.ml,              *)
(* ANT/norm_index.ml, ANT/discriminant.ml, ANT/relative_split.ml,            *)
(* ANT/relative_degree.ml, ANT/integrality.ml, ANT/different.ml,             *)
(* ANT/different_extension.ml and ANT/ideal_norm_extension.ml.               *)
(* ========================================================================= *)

