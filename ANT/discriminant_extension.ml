(* The tower formula d_(m/k) = d_(l/k)^[m:l] N_(l/k)(d_(m/l)), with          *)
(* d_(l/k) = N_(l/k)(D_(l/k)).                                               *)
let NUMBER_FIELD_DISCRIMINANT_TOWER = prove
