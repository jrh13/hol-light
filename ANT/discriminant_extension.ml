  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION o CONJUNCT1) THEN
  SUBGOAL_THEN
   `ideal_norm (ring_of_integers l)
      (number_field_different (subfield_generated l {ring_0 l},l) (I:B->B)) =
    ideal_norm (ring_of_integers k)
      (number_field_different (subfield_generated k {ring_0 k},k) (I:A->A))
    EXP extension_degree(k,l) (h:A->B) *
    ideal_norm (ring_of_integers k)
      (number_field_ideal_norm (k,l) h (number_field_different (k,l) h))`
  MP_TAC THENL
   [ALL_TAC;
    ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_DIFFERENT] THEN
    DISCH_THEN(MP_TAC o AP_TERM `int_of_num`) THEN
    REWRITE_TAC[GSYM INT_OF_NUM_MUL; GSYM INT_OF_NUM_POW] THEN
    SIMP_TAC[INT_OF_NUM_OF_INT; INT_ABS_POS]] THEN
  SUBGOAL_THEN
   `number_field_different (subfield_generated l {ring_0 l},l) (I:B->B) =
    number_field_different (subfield_generated k {ring_0 k},l)
      ((h:A->B) o I)`
  SUBST1_TAC THENL
   [CONV_TAC SYM_CONV THEN
    MP_TAC(ISPECL [`subfield_generated k {ring_0 k:A}`;
                   `subfield_generated l {ring_0 l:B}`; `l:B ring`;
                   `(h:A->B) o I`; `I:B->B`]
      NUMBER_FIELD_CODIFFERENT_EQ_IMAGE) THEN
    ANTS_TAC THENL [ALL_TAC; SIMP_TAC[]] THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
                 IMAGE_I] THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC RING_HOMOMORPHISM_COMPOSE THEN
      EXISTS_TAC `k:A ring` THEN
      ASM_REWRITE_TAC[RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
      REWRITE_TAC[IMAGE_o; IMAGE_I] THEN
      MATCH_MP_TAC PRIME_SUBFIELD_MONOMORPHIC_IMAGE THEN
      ASM_MESON_TAC[field_extension]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`subfield_generated k {ring_0 k:A}`; `k:A ring`; `l:B ring`;
                 `I:A->A`; `h:A->B`] NUMBER_FIELD_DIFFERENT_TOWER) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
               RING_HOMOMORPHISM_SUBFIELD_INCLUSION] THEN
  DISCH_THEN SUBST1_TAC THEN
  SUBGOAL_THEN
   `ring_ideal (ring_of_integers k)
      (number_field_different (subfield_generated k {ring_0 k},k) (I:A->A)) /\
    ~(number_field_different (subfield_generated k {ring_0 k},k) (I:A->A) =
      {ring_0 k}) /\
    ring_ideal (ring_of_integers l) (number_field_different (k,l) (h:A->B)) /\
    ~(number_field_different (k,l) (h:A->B) = {ring_0 l})`
  STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[RING_IDEAL_NUMBER_FIELD_DIFFERENT] THEN
    ASM_SIMP_TAC[NUMBER_FIELD_DIFFERENT_NONZERO; FIELD_SUBFIELD_GENERATED;
                 NUMBER_FIELD_IMP_FIELD;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`;
                 `number_field_different (subfield_generated k {ring_0 k},k)
                    (I:A->A)`] RING_OF_INTEGERS_IDEAL_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`l:B ring`; `number_field_different (k,l) (h:A->B)`;
                 `ideal_generated (ring_of_integers l)
                   (IMAGE (h:A->B)
                     (number_field_different
                       (subfield_generated k {ring_0 k},k) I))`]
    NUMBER_FIELD_IDEAL_NORM_MUL_Q) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN DISCH_THEN SUBST1_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_EXTENSION_Q;
               NUMBER_FIELD_IDEAL_NORM_IDEAL_NORM] THEN
  REWRITE_TAC[MULT_SYM]);;

let NUMBER_FIELD_DISCRIMINANT_POW_DIVIDES = prove
 (`!k:A ring l:B ring h.
        field k /\ number_field l /\ ring_homomorphism(k,l) h
        ==> (number_field_discriminant k pow extension_degree(k,l) h) divides
            number_field_discriminant l`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC(INTEGER_RULE `abs(a:int) divides abs(b) ==> a divides b`) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_DISCRIMINANT_TOWER_Q; INT_ABS_POW] THEN
  CONV_TAC INTEGER_RULE);;
