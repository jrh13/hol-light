(* ------------------------------------------------------------------------- *)
(* Discriminants of twisted trace forms.                                     *)
(* ------------------------------------------------------------------------- *)

(* With u = h(t) d^-1: N(d) det(Tr(u w_i w_j)) = t^n d(w).                   *)
let NUMBER_FIELD_BASIS_DISCRIMINANT_TWIST = prove
 (`!k:A ring l:B ring h n w t d.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        free_basis (k,l) h n w /\
        t IN ring_carrier k /\ d IN ring_carrier l /\ ~(d = ring_0 l)
        ==> ring_mul k (algebra_norm (k,l) h d)
              (ring_det k {i | i < n}
                (\i j. algebra_trace (k,l) h
                         (ring_mul l (ring_mul l (h t) (ring_inv l d))
                                     (ring_mul l (w i) (w j))))) =
            ring_mul k (ring_pow k t n) (basis_discriminant (k,l) h n w)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o REWRITE_RULE[field_extension] o
    check (fun th -> concl th = `field_extension(k:A ring,l:B ring) h`)) THEN
  SUBGOAL_THEN `n = extension_degree(k:A ring,l:B ring) h` ASSUME_TAC THENL
   [MATCH_MP_TAC FREE_BASIS_EXTENSION_DEGREE THEN
    EXISTS_TAC `w:num->B` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(h:A->B) t IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
  ASM_SIMP_TAC[BASIS_DISCRIMINANT_MUL; RING_MUL; RING_INV] THEN
  ASM_SIMP_TAC[ALGEBRA_NORM_MUL; RING_INV; ALGEBRA_NORM_INV;
               ALGEBRA_TRACE_NORM_BASE] THEN
  SUBGOAL_THEN `~(algebra_norm (k,l) (h:A->B) d = ring_0 k)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[ALGEBRA_NORM_EQ_0]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `algebra_norm (k,l) (h:A->B) d`]
    FIELD_MUL_RINV) THEN
  ASM_REWRITE_TAC[ALGEBRA_TRACE_NORM_IN_CARRIER] THEN
  MATCH_MP_TAC(RING_RULE
   `ring_mul (r:A ring) a b = ring_1 r
    ==> ring_mul r a (ring_mul r (ring_mul r c b) e) = ring_mul r c e`) THEN
  ASM_SIMP_TAC[RING_POW; RING_INV; ALGEBRA_TRACE_NORM_IN_CARRIER] THEN
  REWRITE_TAC[basis_discriminant; RING_DET]);;

