  MP_TAC(ISPECL [`r:A ring`; `k:B ring`; `h:A->B`; `S:(A->bool)->bool`]
    RING_OF_S_INTEGERS_CLASS_GROUP) THEN
  ASM_REWRITE_TAC[group_epimorphism; LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `f:((A->bool)->bool)->((B->bool)->bool)` THEN
  DISCH_THEN(CONJUNCTS_THEN2 (CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM))
    (CONJUNCTS_THEN2 ASSUME_TAC (K ALL_TAC))) THEN
  MATCH_MP_TAC(SET_RULE
   `!f s (z:B). (!x:A. x IN s ==> f x = z) /\ (?x. x IN s)
                ==> IMAGE f s = {z}`) THEN
  CONJ_TAC THENL
   [ALL_TAC;
    EXISTS_TAC `group_id(class_group(r:A ring))` THEN
    REWRITE_TAC[GROUP_ID]] THEN
  ASM_SIMP_TAC[CONJUNCT1 CLASS_GROUP] THEN
  X_GEN_TAC `c:(A->bool)->bool` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `c:(A->bool)->bool`) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_X_ASSUM(SUBST1_TAC o check (is_eq o concl)) THEN
  ASM_SIMP_TAC[] THEN
  SUBGOAL_THEN
   `ideal_generated (ring_of_s_integers (r,k) h S)
      (IMAGE (h:A->B) ((J:((A->bool)->bool)->A->bool) c)) =
    ring_carrier(ring_of_s_integers (r,k) h S)`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[RING_OF_S_INTEGERS_IDEAL_EXTENSION_EQ_CARRIER] THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MATCH_MP_TAC o GEN_REWRITE_RULE I [SUBSET]) THEN
    REWRITE_TAC[IN_UNIONS; EXISTS_IN_IMAGE; IN_ELIM_THM] THEN
    EXISTS_TAC `c:(A->bool)->bool` THEN ASM_REWRITE_TAC[];
    ASM_SIMP_TAC[CLASS_GROUP]]);;

