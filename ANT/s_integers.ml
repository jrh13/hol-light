     [ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; IDEAL_POW_EQ_ZERO;
                   PRIME_IMP_RING_IDEAL];
      ALL_TAC] THEN
    EXPAND_TAC "O" THEN
    ASM_SIMP_TAC[RING_OF_S_INTEGERS_IDEAL_EXTENSION] THEN
    SUBGOAL_THEN
