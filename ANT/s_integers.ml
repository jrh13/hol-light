      FIRST_X_ASSUM(MP_TAC o SPEC `Q:A->bool`) THEN ASM_REWRITE_TAC[] THEN
      ASM_CASES_TAC `x:B = ring_0 k` THEN ASM_REWRITE_TAC[] THEN
      COND_CASES_TAC THENL
       [FIRST_X_ASSUM(SUBST_ALL_TAC o SYM) THEN
        UNDISCH_TAC `m <= ideal_valuation r P (j:A->bool)` THEN
        REWRITE_TAC[GSYM INT_OF_NUM_LE] THEN INT_ARITH_TAC;
        MP_TAC(ISPEC `ideal_valuation r Q (j:A->bool)` INT_POS) THEN
        INT_ARITH_TAC]] THEN
    SUBGOAL_THEN
     `?c:A. c IN j /\ ~(c IN ideal_pow r P (SUC(ideal_valuation r P j)))`
    STRIP_ASSUME_TAC THENL
     [MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `j:A->bool`;
                     `SUC(ideal_valuation r P (j:A->bool))`]
        DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
      ASM_REWRITE_TAC[ARITH_RULE `~(SUC n <= n)`] THEN SET_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN `(c:A) IN ring_carrier r /\ ~(c = ring_0 r)`
    STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL
       [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET];
        DISCH_THEN SUBST_ALL_TAC THEN
