(* ========================================================================= *)
(* The ring of S-integers of a Dedekind domain and of a number field, its    *)
(* ideals, primes and valuations, its units (the S-units) and its class      *)
(* group.                                                                    *)
(*                                                                           *)
(* For a Dedekind domain r with a field of fractions k along h               *)
(* (field_of_fractions (r,k) h) and a set S of ideals of r (only its nonzero *)
(* primes matter, as in s_unit_group of ANT/sunits.ml), with v_P =           *)
(* dedekind_valuation (r,k) h P:                                             *)
(*                                                                           *)
(*   ring_of_s_integers (r,k) h S = the subring of k of the x with           *)
(*                                  x = 0 or v_P(x) >= 0 for all nonzero     *)
(*                                  primes P of r outside S                  *)
(*                                                                           *)
(* For a number field k the ring O_S of S-integers is ring_of_s_integers     *)
(* (ring_of_integers k,k) I S. The case S = {} is the image of r             *)
(* (RING_OF_S_INTEGERS_EMPTY; NUMBER_FIELD_RING_OF_S_INTEGERS_EMPTY: O_k     *)
(* itself), the case S = all nonzero primes but P is the valuation ring of   *)
(* v_P, a DVR (RING_OF_S_INTEGERS_COMPLEMENT_SING).                          *)
(*                                                                           *)
(* Main results, for r Dedekind with field of fractions k: the operations    *)
(* and the carrier (RING_OF_S_INTEGERS, RING_OF_S_INTEGERS_CARRIER), h is a  *)
(* monomorphism into O_S (RING_MONOMORPHISM_RING_OF_S_INTEGERS) and k is a   *)
(* field of fractions of O_S (FIELD_OF_FRACTIONS_RING_OF_S_INTEGERS); x is a *)
(* unit of O_S iff v_P(x) = 0 for all P outside S                            *)
(* (RING_UNIT_RING_OF_S_INTEGERS). Ideals: for a nonzero ideal j of r, j O_S *)
(* is the set of x with v_P(x) >= v_P(j) outside S                           *)
(* (RING_OF_S_INTEGERS_IDEAL_EXTENSION), every ideal J of O_S is the         *)
(* extension of its contraction (RING_OF_S_INTEGERS_IDEAL_CONTRACTION), j    *)
(* O_S = O_S iff every prime containing j is in S                            *)
(* (RING_OF_S_INTEGERS_IDEAL_EXTENSION_EQ_CARRIER). O_S is a Dedekind domain *)
(* (DEDEKIND_RING_OF_S_INTEGERS); its nonzero primes are the P O_S for the   *)
(* nonzero primes P of r outside S, with contraction P                       *)
(* (PRIME_IDEAL_RING_OF_S_INTEGERS_EXTENSION,                                *)
(* RING_OF_S_INTEGERS_PRIME_IDEALS), and the valuations of O_S at P O_S are  *)
(* those of r at P, for ideals and for elements of k                         *)
(* (IDEAL_VALUATION_RING_OF_S_INTEGERS,                                      *)
(* DEDEKIND_VALUATION_RING_OF_S_INTEGERS); j O_S is principal iff some       *)
(* element of k has the valuations of j outside S                            *)
(* (RING_OF_S_INTEGERS_EXTENSION_PRINCIPAL).                                 *)
(*                                                                           *)
(* Class groups: extension of ideals is an epimorphism Cl(r) -> Cl(O_S)      *)
(* whose kernel is generated by the classes of the primes in S               *)
(* (RING_OF_S_INTEGERS_CLASS_GROUP), so Cl(O_S) is Cl(r) modulo that         *)
(* subgroup (RING_OF_S_INTEGERS_CLASS_GROUP_QUOTIENT) and O_S is a PID iff   *)
(* the classes of the primes in S generate Cl(r)                             *)
(* (RING_OF_S_INTEGERS_PID_EQ). For finite S there is the exact sequence     *)
(*                                                                           *)
(*   1 -> r^* -> O_S^* -> Z^S -> Cl(r) -> Cl(O_S) -> 1                       *)
(*                                                                           *)
(* with the valuations at the primes of S and n |-> prod_(P IN S) [P]^n(P),  *)
(* Z^S = product_group S (\P. integer_group)                                 *)
(* (RING_OF_S_INTEGERS_CLASS_GROUP_EXACT). If Cl(r) is finite, so is         *)
(* Cl(O_S), with class number dividing that of r                             *)
(* (RING_OF_S_INTEGERS_CLASS_NUMBER_DIVIDES), and O_S is a PID for every S   *)
(* containing a suitable finite set of primes (RING_OF_S_INTEGERS_PID). The  *)
(* classes of products of primes are computed by                             *)
(* FRACTIONAL_IDEAL_CLASS_PRIME_SUM, CLASS_GROUP_SUM_PRIME_CLASSES_EQ_ID and *)
(* IDEAL_CLASS_EQ_SUM_PRIME_CLASSES of ANT/fractional_ideals.ml.             *)
(*                                                                           *)
(* Number fields: the class group of O_S is finite with class number         *)
(* dividing h_k (NUMBER_FIELD_CLASS_GROUP_RING_OF_S_INTEGERS), and there is  *)
(* a finite set S0 of nonzero primes such that O_S is a PID for every S      *)
(* containing S0 (NUMBER_FIELD_RING_OF_S_INTEGERS_PID). The S-unit group     *)
(* s_unit_group k S is the unit group of O_S                                 *)
(* (S_UNIT_GROUP_RING_OF_S_INTEGERS of ANT/sunits.ml, which loads later: it  *)
(* needs the complex embeddings).                                            *)
(*                                                                           *)
(* Routes. Extension: the set of x with v_P(x) >= v_P(j) outside S is an     *)
(* ideal of O_S containing h(j); conversely, for j m = (c)                   *)
(* (DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) the t in r with h(t) x / h(c) in  *)
(* j O_S form an ideal containing the products a b, a in j, b in m, hence c. *)
(* Contraction: for x in J and P outside S, x = h(a) / h(b) with b outside P *)
(* (DEDEKIND_VALUATION_POS), and a lies in the contraction. Dedekind: every  *)
(* nonzero ideal j O_S has the principal multiple (j m) O_S = (h c)          *)
(* (DEDEKIND_EQ_IDEALS_INVERTIBLE of ANT/dedekind_criteria.ml). Valuations:  *)
(* (j O_S) SUBSET (P O_S)^n iff n <= v_P(j), by the description of extended  *)
(* ideals (IDEAL_VALUATION_UNIQUE). Class groups: the class homomorphism of  *)
(* extensions (DEDEKIND_CLASS_GROUP_EXTENSION of ANT/classgroup_group.ml);   *)
(* the kernel and the exact sequence through the fractional ideals of r      *)
(* (FRACTIONAL_IDEAL_CLASS_GROUP_EXACT, FRACTIONAL_IDEAL_EQ_VALUATION,       *)
(* FRACTIONAL_IDEAL_VALUATION_PRIME_PRODUCT of ANT/fractional_ideals.ml): j  *)
(* O_S = (y) gives v_P(y) = v_P(j) outside S, so j (y)^-1 is a product of    *)
(* powers of primes in S. PID: one ideal j_c in each class c; S0 is the set  *)
(* of primes containing some j_c, and the classes [j_c O_S] are trivial.     *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/grouptheory.ml (product_group,       *)
(* group_exactness, subgroup_generated), Library/ring_groups.ml              *)
(* (unit_group), ANT/ideal_arith.ml, ANT/dedekind.ml, ANT/dedekind_struct.ml *)
(* (ideal_class, DVR), ANT/dedekind_valuation.ml, ANT/classgroup.ml,         *)
(* ANT/classgroup_group.ml, ANT/fractional_ideals.ml,                        *)
(* ANT/dedekind_criteria.ml, ANT/numfield.ml, ANT/ring_of_integers.ml, and   *)
(* ANT/nf_valuation.ml (RING_OF_INTEGERS_FRACTION_FIELD).                    *)
(* ========================================================================= *)

