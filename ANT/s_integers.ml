                      if P = Q then m else 0`
    ASSUME_TAC THENL
     [REPEAT STRIP_TAC THEN
      ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_POW; PRIME_IMP_RING_IDEAL;
