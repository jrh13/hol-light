(* Number fields: the ring of S-integers of O_k and its class group.         *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_RING_OF_S_INTEGERS_EMPTY = prove
 (`!k:A ring.
        number_field k
        ==> ring_of_s_integers (ring_of_integers k,k) I {} =
            ring_of_integers k`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_FRACTION_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `k:A ring`; `I:A->A`;
                 `{}:(A->bool)->bool`] RING_OF_S_INTEGERS_SUBRING) THEN
  ASM_SIMP_TAC[RING_OF_S_INTEGERS_EMPTY; IMAGE_I] THEN
  DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT2) THEN
  REWRITE_TAC[RING_OF_INTEGERS_SUBRING]);;

let NUMBER_FIELD_CLASS_GROUP_RING_OF_S_INTEGERS = prove
 (`!k:A ring S.
        number_field k
        ==> FINITE(group_carrier(class_group
                    (ring_of_s_integers (ring_of_integers k,k) I S))) /\
            class_number(ring_of_s_integers (ring_of_integers k,k) I S)
            divides class_number(ring_of_integers k)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_FRACTION_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `k:A ring`; `I:A->A`;
                 `S:(A->bool)->bool`]
    RING_OF_S_INTEGERS_CLASS_NUMBER_DIVIDES) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_CLASS_GROUP_FINITE; CLASS_GROUP;
               DEDEKIND_RING_OF_S_INTEGERS]);;

let NUMBER_FIELD_RING_OF_S_INTEGERS_PID = prove
 (`!k:A ring.
        number_field k
        ==> ?S0. FINITE S0 /\
                 (!P. P IN S0
                      ==> prime_ideal (ring_of_integers k) P /\
                          ~(P = {ring_0 k})) /\
                 !S. S0 SUBSET S
                     ==> PID(ring_of_s_integers (ring_of_integers k,k) I S)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_FRACTION_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `k:A ring`; `I:A->A`]
    RING_OF_S_INTEGERS_PID) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_CLASS_GROUP_FINITE; RING_OF_INTEGERS]);;
