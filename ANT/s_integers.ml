let ring_of_s_integers = new_definition
 `ring_of_s_integers (r:A ring,k:B ring) (h:A->B) S =
  subring_generated k
   {x | x IN ring_carrier k /\
        !P. prime_ideal r P /\ ~(P = {ring_0 r}) /\ ~(P IN S)
            ==> x = ring_0 k \/ &0 <= dedekind_valuation (r,k) h P x}`;;

let RING_OF_S_INTEGERS = prove
 (`(!r k (h:A->B) S. ring_0(ring_of_s_integers (r,k) h S) = ring_0 k) /\
   (!r k (h:A->B) S. ring_1(ring_of_s_integers (r,k) h S) = ring_1 k) /\
   (!r k (h:A->B) S. ring_neg(ring_of_s_integers (r,k) h S) = ring_neg k) /\
   (!r k (h:A->B) S. ring_add(ring_of_s_integers (r,k) h S) = ring_add k) /\
   (!r k (h:A->B) S. ring_mul(ring_of_s_integers (r,k) h S) = ring_mul k) /\
   (!r k (h:A->B) S. ring_sub(ring_of_s_integers (r,k) h S) = ring_sub k) /\
   (!r k (h:A->B) S. ring_pow(ring_of_s_integers (r,k) h S) = ring_pow k) /\
   (!r k (h:A->B) S.
        ring_of_num(ring_of_s_integers (r,k) h S) = ring_of_num k) /\
   (!r k (h:A->B) S.
        ring_of_int(ring_of_s_integers (r,k) h S) = ring_of_int k)`,
  REWRITE_TAC[ring_of_s_integers; SUBRING_GENERATED;
              RING_SUB_SUBRING_GENERATED; RING_POW_SUBRING_GENERATED;
              RING_OF_NUM_SUBRING_GENERATED; RING_OF_INT_SUBRING_GENERATED]);;

let RING_OF_S_INTEGERS_SUBSET = prove
 (`!r k (h:A->B) S.
        ring_carrier(ring_of_s_integers (r,k) h S) SUBSET ring_carrier k`,
  REWRITE_TAC[ring_of_s_integers; RING_CARRIER_SUBRING_GENERATED_SUBSET]);;

let RING_OF_S_INTEGERS_SUBRING_OF = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> {x | x IN ring_carrier k /\
                 !P. prime_ideal r P /\ ~(P = {ring_0 r}) /\ ~(P IN S)
                     ==> x = ring_0 k \/
                         &0 <= dedekind_valuation (r,k) h P x}
            subring_of k`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  REWRITE_TAC[subring_of; SUBSET; IN_ELIM_THM] THEN
  SIMP_TAC[RING_0; RING_1; RING_NEG; RING_ADD; RING_MUL] THEN
  REPEAT CONJ_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_VALUATION_1; INT_LE_REFL];
    REPEAT STRIP_TAC THEN ASM_SIMP_TAC[DEDEKIND_VALUATION_NEG; RING_NEG_EQ_0];
    MAP_EVERY X_GEN_TAC [`x:B`; `y:B`] THEN STRIP_TAC THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    REPEAT(FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`)) THEN
    ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `x:B = ring_0 k` THEN ASM_SIMP_TAC[RING_ADD_LZERO] THEN
    ASM_CASES_TAC `y:B = ring_0 k` THEN ASM_SIMP_TAC[RING_ADD_RZERO] THEN
    REPEAT DISCH_TAC THEN
    ASM_CASES_TAC `ring_add k x y = ring_0 k:B` THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`r:A ring`; `k:B ring`; `h:A->B`; `P:A->bool`;
                   `x:B`; `y:B`] DEDEKIND_VALUATION_ADD) THEN
    ASM_REWRITE_TAC[] THEN ASM_INT_ARITH_TAC;
    MAP_EVERY X_GEN_TAC [`x:B`; `y:B`] THEN STRIP_TAC THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    REPEAT(FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`)) THEN
    ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `x:B = ring_0 k` THEN ASM_SIMP_TAC[RING_MUL_LZERO] THEN
    ASM_CASES_TAC `y:B = ring_0 k` THEN ASM_SIMP_TAC[RING_MUL_RZERO] THEN
    ASM_SIMP_TAC[DEDEKIND_VALUATION_MUL] THEN INT_ARITH_TAC]);;

let RING_OF_S_INTEGERS_CARRIER = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> ring_carrier(ring_of_s_integers (r,k) h S) =
            {x | x IN ring_carrier k /\
                 !P. prime_ideal r P /\ ~(P = {ring_0 r}) /\ ~(P IN S)
                     ==> x = ring_0 k \/
                         &0 <= dedekind_valuation (r,k) h P x}`,
  SIMP_TAC[ring_of_s_integers; CARRIER_SUBRING_GENERATED_SUBRING;
           RING_OF_S_INTEGERS_SUBRING_OF]);;

let RING_OF_S_INTEGERS_SUBRING = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> ring_carrier(ring_of_s_integers (r,k) h S) subring_of k /\
            subring_generated k (ring_carrier(ring_of_s_integers (r,k) h S)) =
            ring_of_s_integers (r,k) h S`,
  SIMP_TAC[RING_OF_S_INTEGERS_CARRIER; RING_OF_S_INTEGERS_SUBRING_OF] THEN
  REWRITE_TAC[ring_of_s_integers]);;

let INTEGRAL_DOMAIN_RING_OF_S_INTEGERS = prove
 (`!r k (h:A->B) S.
        field k ==> integral_domain(ring_of_s_integers (r,k) h S)`,
  SIMP_TAC[ring_of_s_integers; INTEGRAL_DOMAIN_SUBRING_GENERATED;
           FIELD_IMP_INTEGRAL_DOMAIN]);;

let RING_OF_S_INTEGERS_MONO = prove
 (`!r k (h:A->B) S S'.
        S SUBSET S'
        ==> ring_carrier(ring_of_s_integers (r,k) h S) SUBSET
            ring_carrier(ring_of_s_integers (r,k) h S')`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ring_of_s_integers] THEN
  MATCH_MP_TAC SUBRING_GENERATED_MONO THEN ASM SET_TAC[]);;

let RING_OF_S_INTEGERS_IMAGE = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> IMAGE h (ring_carrier r) SUBSET
            ring_carrier(ring_of_s_integers (r,k) h S)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  ASM_SIMP_TAC[RING_OF_S_INTEGERS_CARRIER; SUBSET; FORALL_IN_IMAGE;
               IN_ELIM_THM] THEN
  X_GEN_TAC `a:A` THEN DISCH_TAC THEN
  CONJ_TAC THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
  X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
  ASM_CASES_TAC `a:A = ring_0 r` THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_0]; DISJ2_TAC] THEN
  ASM_SIMP_TAC[DEDEKIND_VALUATION_IMAGE; INT_POS]);;

let RING_MONOMORPHISM_RING_OF_S_INTEGERS = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> ring_monomorphism(r,ring_of_s_integers (r,k) h S) h`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  MP_TAC(ISPECL [`r:A ring`; `k:B ring`; `h:A->B`; `S:(A->bool)->bool`]
    RING_OF_S_INTEGERS_IMAGE) THEN
  ASM_SIMP_TAC[RING_OF_S_INTEGERS_CARRIER] THEN DISCH_TAC THEN
  REWRITE_TAC[ring_of_s_integers] THEN
  MATCH_MP_TAC RING_MONOMORPHISM_INTO_SUBRING THEN ASM_REWRITE_TAC[]);;

let FIELD_OF_FRACTIONS_RING_OF_S_INTEGERS = prove
 (`!r k (h:A->B) S.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> field_of_fractions (ring_of_s_integers (r,k) h S,k) I`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  MP_TAC(ISPECL [`r:A ring`; `k:B ring`; `h:A->B`; `S:(A->bool)->bool`]
    RING_OF_S_INTEGERS_IMAGE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  REWRITE_TAC[field_of_fractions] THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL
   [REWRITE_TAC[ring_of_s_integers;
                REWRITE_RULE[GSYM I_DEF] RING_MONOMORPHISM_INCLUSION];
    ALL_TAC] THEN
  X_GEN_TAC `x:B` THEN DISCH_TAC THEN
  FIRST_ASSUM(MP_TAC o SPEC `x:B` o CONJUNCT2 o CONJUNCT2 o
    GEN_REWRITE_RULE I [field_of_fractions]) THEN
  ASM_REWRITE_TAC[I_THM] THEN
  REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN STRIP_TAC THEN
  MAP_EVERY EXISTS_TAC [`(h:A->B) a`; `(h:A->B) b`] THEN
  ASM_REWRITE_TAC[RING_OF_S_INTEGERS] THEN
  REPEAT CONJ_TAC THENL
   [ASM SET_TAC[]; ASM SET_TAC[];
    ASM_MESON_TAC[RING_MONOMORPHISM_EQ_0]]);;

let RING_OF_S_INTEGERS_EMPTY = prove
 (`!r k (h:A->B).
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> ring_carrier(ring_of_s_integers (r,k) h {}) =
            IMAGE h (ring_carrier r)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  ASM_SIMP_TAC[RING_OF_S_INTEGERS_CARRIER; NOT_IN_EMPTY] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `x:B` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_CASES_TAC `(x:B) IN ring_carrier k` THENL
   [ASM_REWRITE_TAC[];
    ASM_REWRITE_TAC[IN_IMAGE] THEN
    ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]] THEN
  ASM_CASES_TAC `x:B = ring_0 k` THENL
   [ASM_REWRITE_TAC[IN_IMAGE] THEN EXISTS_TAC `ring_0 r:A` THEN
    ASM_MESON_TAC[RING_HOMOMORPHISM_0; RING_0];
    ASM_SIMP_TAC[DEDEKIND_VALUATION_INTEGRAL]]);;

let RING_UNIT_RING_OF_S_INTEGERS = prove
 (`!r k (h:A->B) S x.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> (ring_unit (ring_of_s_integers (r,k) h S) x <=>
             x IN ring_carrier k /\ ~(x = ring_0 k) /\
             !P. prime_ideal r P /\ ~(P = {ring_0 r}) /\ ~(P IN S)
                 ==> dedekind_valuation (r,k) h P x = &0)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  REWRITE_TAC[ring_of_s_integers] THEN
  ASM_SIMP_TAC[RING_UNIT_SUBRING_GENERATED; RING_OF_S_INTEGERS_SUBRING_OF;
               FIELD_UNIT] THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_CASES_TAC `(x:B) IN ring_carrier k` THEN ASM_REWRITE_TAC[] THEN
  ASM_CASES_TAC `x:B = ring_0 k` THEN ASM_REWRITE_TAC[] THEN
  ASM_SIMP_TAC[RING_INV; FIELD_INV_EQ_0; DEDEKIND_VALUATION_INV] THEN
  REWRITE_TAC[GSYM FORALL_AND_THM] THEN AP_TERM_TAC THEN ABS_TAC THEN
  REWRITE_TAC[TAUT `(p ==> q) /\ (p ==> r) <=> p ==> q /\ r`] THEN
  AP_TERM_TAC THEN INT_ARITH_TAC);;

(* For S the set of all ideals but one nonzero prime P, the S-integers       *)
(* are the valuation ring of v_P, a DVR.                                     *)
let RING_OF_S_INTEGERS_COMPLEMENT_SING = prove
 (`!r k (h:A->B) P.
        dedekind_domain r /\ field_of_fractions (r,k) h /\
        prime_ideal r P /\ ~(P = {ring_0 r})
        ==> ring_of_s_integers (r,k) h {Q | ~(Q = P)} =
            subring_generated k
              {x | x IN ring_carrier k /\
                   (x = ring_0 k \/ &0 <= dedekind_valuation (r,k) h P x)} /\
            DVR(ring_of_s_integers (r,k) h {Q | ~(Q = P)})`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [REWRITE_TAC[ring_of_s_integers; IN_ELIM_THM] THEN
    AP_TERM_TAC THEN GEN_REWRITE_TAC I [EXTENSION] THEN
    REWRITE_TAC[IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC THEN MATCH_MP_TAC DEDEKIND_VALUATION_RING_DVR THEN
    ASM_REWRITE_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* Ideals of the ring of S-integers: extension and contraction.              *)
(* ------------------------------------------------------------------------- *)

let RING_OF_S_INTEGERS_VALUATION_IDEAL = prove
 (`!r k (h:A->B) S n.
        dedekind_domain r /\ field_of_fractions (r,k) h
        ==> ring_ideal (ring_of_s_integers (r,k) h S)
             {x | x IN ring_carrier k /\
                  !P. prime_ideal r P /\ ~(P = {ring_0 r}) /\ ~(P IN S)
                      ==> x = ring_0 k \/
                          &(n P) <= dedekind_valuation (r,k) h P x}`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    MATCH_MP FIELD_OF_FRACTIONS_IMP_MONOMORPHISM) THEN
  ASM_SIMP_TAC[ring_ideal; RING_OF_S_INTEGERS_CARRIER; RING_OF_S_INTEGERS;
               SUBSET; IN_ELIM_THM; RING_0; RING_NEG; RING_ADD; RING_MUL] THEN
  REPEAT CONJ_TAC THENL
   [X_GEN_TAC `x:B` THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`) THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPEC `(n:(A->bool)->num) P` INT_POS) THEN
    ASM_CASES_TAC `x:B = ring_0 k` THEN ASM_REWRITE_TAC[] THEN INT_ARITH_TAC;
    REPEAT STRIP_TAC THEN ASM_SIMP_TAC[DEDEKIND_VALUATION_NEG; RING_NEG_EQ_0];
    MAP_EVERY X_GEN_TAC [`x:B`; `y:B`] THEN STRIP_TAC THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    REPEAT(FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`)) THEN
    ASM_REWRITE_TAC[] THEN
