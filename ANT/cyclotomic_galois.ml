(* ========================================================================= *)
(* The Galois group of a cyclotomic field. In general, for l generated over  *)
(* the image of a field k by an element z of finite order n, the Galois      *)
(* group of l over k embeds into the group modmul_group n of the units mod n *)
(* by f |-> e f, where f z = z^(e f), and this monomorphism is an            *)
(* isomorphism exactly when [l:k] = phi(n) (CYCLOTOMIC_GALOIS_GROUP_MODMUL,  *)
(* CYCLOTOMIC_GALOIS_GROUP_MODMUL_ISOMORPHISM of Library/cyclotomic.ml). The *)
(* unit group of the integers mod n is isomorphic to modmul_group n          *)
(* (GROUP_ISOMORPHISM_MODMUL_UNIT_GROUP; its carrier:                        *)
(* UNIT_GROUP_INTEGER_MOD_RING).                                             *)
(*                                                                           *)
(* Now let k be a number field generated by an element z of finite order n   *)
(* (k = Q(z), Q the prime field subfield_generated k {ring_0 k}, as in       *)
(* CYCLOTOMIC_FIELD_DEGREE). Then k is a Galois extension of Q               *)
(* (CYCLOTOMIC_FIELD_GALOIS_EXTENSION), the monomorphism above is an         *)
(* isomorphism of galois_group (Q,k) I onto modmul_group n                   *)
(* (CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL), the group has phi(n) elements     *)
(* (CYCLOTOMIC_FIELD_GALOIS_GROUP_HAS_SIZE), c |-> (z |-> z^c) is an         *)
(* isomorphism from the unit group of the integers mod n onto it             *)
(* (CYCLOTOMIC_FIELD_GALOIS_GROUP); so for every c coprime to n there is an  *)
(* element with z |-> z^c (CYCLOTOMIC_FIELD_GALOIS_GROUP_EXISTS), every      *)
(* element is of this form with c < n (CYCLOTOMIC_FIELD_GALOIS_GROUP_ROOT)   *)
(* and is determined by the image of z (CYCLOTOMIC_FIELD_GALOIS_GROUP_EQ).   *)
(* In particular the Galois group is isomorphic to the unit group and        *)
(* abelian (CYCLOTOMIC_FIELD_GALOIS_GROUP_ISOMORPHIC, _ABELIAN).             *)
(*                                                                           *)
(* Routes. z generates k over Q (SUBFIELD_GENERATED_INSERT_PRIME_SUBFIELD),  *)
(* so the extension is Galois (CYCLOTOMIC_EXTENSION_ABELIAN), and [k:Q] =    *)
(* phi(n) (CYCLOTOMIC_FIELD_DEGREE, the irreducibility of Phi_n over Q)      *)
(* gives the modmul form; composed with GROUP_ISOMORPHISM_MODMUL_UNIT_GROUP  *)
(* (a |-> &a rem &n) and inverted, it gives the unit group form, since z^a   *)
(* depends only on a mod n (RING_POW_MOD_ORDER). Existence and form: the     *)
(* units of integer_mod_ring n are the &c with c < n coprime to n            *)
(* (UNIT_GROUP_INTEGER_MOD_RING). Uniqueness: z generates k                  *)
(* (GALOIS_GROUP_EQ_ON_GENERATORS). For n = 1 (k = Q, z = 1) modmul_group 1  *)
(* is {1} and the unit group of the zero ring integer_mod_ring 1 is {&0}.    *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (ring_order, integer_mod_ring),               *)
(* Library/fieldtheory.ml (generated subfields), Library/grouptheory.ml      *)
(* (group isomorphisms), Library/galois.ml (galois_group, galois_extension,  *)
(* CYCLOTOMIC_EXTENSION_ABELIAN, GALOIS_GROUP_EQ_ON_GENERATORS),             *)
(* Library/cyclotomic.ml (CYCLOTOMIC_GALOIS_GROUP_MODMUL_ISOMORPHISM),       *)
(* Library/modmul_group.ml (modmul_group, loaded by Library/cyclotomic.ml),  *)
(* ANT/numfield.ml, Library/ring_groups.ml (unit_group) and                  *)
(* ANT/cyclotomic_field.ml (CYCLOTOMIC_FIELD_DEGREE).                        *)
(* ========================================================================= *)

needs "Library/ringtheory.ml";;
needs "Library/fieldtheory.ml";;
needs "Library/grouptheory.ml";;
