(* ------------------------------------------------------------------------- *)
(* The units of the integers mod n: the &a with a < n coprime to n, and the  *)
(* unit group is isomorphic to modmul_group n by a |-> &a rem &n (for n = 1  *)
(* the groups {1} and {&0}).                                                 *)
(* ------------------------------------------------------------------------- *)

let UNIT_GROUP_INTEGER_MOD_RING = prove
 (`!n. ~(n = 0)
       ==> group_carrier(unit_group(integer_mod_ring n)) =
           IMAGE (&) {a | a < n /\ coprime(a,n)}`,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM; UNIT_GROUP;
              INTEGER_MOD_RING_UNIT; IN_INTEGER_MOD_RING_CARRIER] THEN
  ASM_REWRITE_TAC[INT_OF_NUM_EQ] THEN X_GEN_TAC `c:int` THEN
  EQ_TAC THENL
   [STRIP_TAC THEN EXISTS_TAC `num_of_int c` THEN
    ASM_SIMP_TAC[INT_OF_NUM_OF_INT; GSYM INT_OF_NUM_LT; num_coprime];
    STRIP_TAC THEN
    ASM_REWRITE_TAC[INT_POS; INT_OF_NUM_LT; GSYM num_coprime]]);;

let GROUP_ISOMORPHISM_MODMUL_UNIT_GROUP = prove
 (`!n. ~(n = 0)
       ==> group_isomorphism(modmul_group n,unit_group(integer_mod_ring n))
                            (\a. &a rem &n)`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[GROUP_ISOMORPHISM; GROUP_HOMOMORPHISM;
               UNIT_GROUP_INTEGER_MOD_RING; UNIT_GROUP;
               INTEGER_MOD_RING_CLAUSES; INT_OF_NUM_REM; INT_OF_NUM_MUL;
               MOD_MULT_MOD2; INT_OF_NUM_EQ; MODMUL_GROUP] THEN
  COND_CASES_TAC THENL
   [SUBGOAL_THEN `n = 1` SUBST1_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[MOD_1; IN_SING; ARITH_RULE `a < 1 <=> a = 0`; COPRIME_1] THEN
    SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `IMAGE (\a. &(a MOD n)) {m | m < n /\ coprime(m,n)} =
    IMAGE ((&):num->int) {a | a < n /\ coprime(a,n)}`
  SUBST1_TAC THENL
   [REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM] THEN MESON_TAC[MOD_LT];
    SIMP_TAC[SUBSET_REFL; IN_ELIM_THM; MOD_MOD_REFL] THEN MESON_TAC[MOD_LT]]);;

(* ------------------------------------------------------------------------- *)
(* The Galois group of a cyclotomic field.                                   *)
(* ------------------------------------------------------------------------- *)

(* The prime subfield lies in every subfield, so z generates k over it       *)
(* exactly when z generates k.                                               *)
let SUBFIELD_GENERATED_INSERT_PRIME_SUBFIELD = prove
 (`!(k:A ring) z.
        subfield_generated k
          (z INSERT IMAGE I (ring_carrier(subfield_generated k {ring_0 k}))) =
        subfield_generated k {z}`,
  REWRITE_TAC[IMAGE_I; SUBFIELD_GENERATED_INSERT] THEN
  REPEAT GEN_TAC THEN MATCH_MP_TAC SUBFIELDS_GENERATED_EQ THEN
  REWRITE_TAC[SUBSET; IN_INTER; IN_INSERT; NOT_IN_EMPTY] THEN
  MESON_TAC[IN_SUBFIELD_0; RING_0]);;

let CYCLOTOMIC_FIELD_GALOIS_EXTENSION = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> galois_extension (subfield_generated k {ring_0 k},k) I`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `z:A`; `n:num`] CYCLOTOMIC_EXTENSION_ABELIAN) THEN
  ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD;
               SUBFIELD_GENERATED_INSERT_PRIME_SUBFIELD; RING_POW_EQ_1;
               DIVIDES_REFL]);;

(* The form of CYCLOTOMIC_FIELD_GALOIS_GROUP with modmul_group n: the        *)
(* criterion with [k:Q] = phi(n) (CYCLOTOMIC_FIELD_DEGREE).                  *)
let CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> ?e. group_isomorphism
                  (galois_group (subfield_generated k {ring_0 k},k) I,
                   modmul_group n) e /\
                !f. f IN
                    group_carrier(galois_group
                                    (subfield_generated k {ring_0 k},k) I)
                    ==> f z = ring_pow k z (e f)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `z:A`; `n:num`]
    CYCLOTOMIC_GALOIS_GROUP_MODMUL_ISOMORPHISM) THEN
  ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD;
               SUBFIELD_GENERATED_INSERT_PRIME_SUBFIELD] THEN
  DISCH_THEN SUBST1_TAC THEN ASM_MESON_TAC[CYCLOTOMIC_FIELD_DEGREE]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_HAS_SIZE = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> group_carrier(galois_group (subfield_generated k {ring_0 k},k) I)
            HAS_SIZE phi n`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CHOOSE_THEN (MP_TAC o MATCH_MP GROUP_ISOMORPHISM_IMP_ISOMORPHIC o
    CONJUNCT1)) THEN
  ASM_MESON_TAC[ISOMORPHIC_GROUP_HAS_ORDER; HAS_SIZE_MODMUL_GROUP]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> ?f. group_isomorphism
                  (unit_group(integer_mod_ring n),
                   galois_group (subfield_generated k {ring_0 k},k) I) f /\
                !c. c IN group_carrier(unit_group(integer_mod_ring n))
                    ==> f c z = ring_pow k z (num_of_int c)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPEC `n:num` GROUP_ISOMORPHISM_MODMUL_UNIT_GROUP) THEN
  MP_TAC(SPECL [`k:A ring`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `e:(A->A)->num` THEN
  DISCH_THEN(CONJUNCTS_THEN2 (fun th -> DISCH_THEN(MP_TAC o
    MATCH_MP GROUP_ISOMORPHISM_COMPOSE o CONJ th)) ASSUME_TAC) THEN
  REWRITE_TAC[group_isomorphism; LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `f:int->A->A` THEN
  GEN_REWRITE_TAC LAND_CONV [GROUP_ISOMORPHISMS_SYM] THEN DISCH_TAC THEN
  EXISTS_TAC `f:int->A->A` THEN CONJ_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  FIRST_X_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [group_isomorphisms]) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[GROUP_HOMOMORPHISM; SUBSET; FORALL_IN_IMAGE;
                              o_THM]) THEN
  X_GEN_TAC `c:int` THEN DISCH_TAC THEN
  SUBGOAL_THEN `num_of_int c = (e:(A->A)->num) (f c) MOD n` SUBST1_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o SPEC `c:int`) THEN
    ASM_REWRITE_TAC[INT_OF_NUM_REM] THEN
    DISCH_THEN(MP_TAC o AP_TERM `num_of_int`) THEN
    REWRITE_TAC[NUM_OF_INT_OF_NUM] THEN DISCH_THEN(ACCEPT_TAC o SYM);
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(f:int->A->A) c IN
    group_carrier(galois_group (subfield_generated k {ring_0 k},k) I)`
  ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  UNDISCH_TAC `ring_order k (z:A) = n` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN ASM_SIMP_TAC[RING_POW_MOD_ORDER] THEN
  ASM_MESON_TAC[]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_EXISTS = prove
 (`!(k:A ring) z n c.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k /\
        coprime(c,n)
        ==> ?sigma. sigma IN
                    group_carrier(galois_group
                                    (subfield_generated k {ring_0 k},k) I) /\
                    sigma z = ring_pow k z c`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`k:A ring`; `z:A`; `n:num`] CYCLOTOMIC_FIELD_GALOIS_GROUP) THEN
  ASM_SIMP_TAC[GROUP_ISOMORPHISM; GROUP_HOMOMORPHISM; SUBSET;
               FORALL_IN_IMAGE; UNIT_GROUP_INTEGER_MOD_RING; IN_ELIM_THM;
               NUM_OF_INT_OF_NUM] THEN
  DISCH_THEN(X_CHOOSE_THEN `f:int->A->A` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `(f:int->A->A)(&(c MOD n))` THEN
  ASM_SIMP_TAC[MOD_LT_EQ; COPRIME_LMOD] THEN
  UNDISCH_TAC `ring_order k (z:A) = n` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN ASM_SIMP_TAC[RING_POW_MOD_ORDER]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_ROOT = prove
 (`!(k:A ring) z n sigma.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k /\
        sigma IN
        group_carrier(galois_group (subfield_generated k {ring_0 k},k) I)
        ==> ?c. c < n /\ coprime(c,n) /\ sigma z = ring_pow k z c`,
  MAP_EVERY X_GEN_TAC [`k:A ring`; `z:A`; `n:num`; `g:A->A`] THEN
  STRIP_TAC THEN
  MP_TAC(SPECL [`k:A ring`; `z:A`; `n:num`] CYCLOTOMIC_FIELD_GALOIS_GROUP) THEN
  ASM_SIMP_TAC[GROUP_ISOMORPHISM; UNIT_GROUP_INTEGER_MOD_RING] THEN
  DISCH_THEN(X_CHOOSE_THEN `f:int->A->A` (CONJUNCTS_THEN2
   (MP_TAC o CONJUNCT1 o CONJUNCT2) MP_TAC)) THEN
  REWRITE_TAC[FORALL_IN_IMAGE; IN_ELIM_THM; NUM_OF_INT_OF_NUM] THEN
  DISCH_TAC THEN REWRITE_TAC[EXTENSION] THEN
  DISCH_THEN(MP_TAC o SPEC `g:A->A`) THEN
  ASM_REWRITE_TAC[IN_IMAGE; IN_ELIM_THM] THEN
  STRIP_TAC THEN ASM_MESON_TAC[]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_EQ = prove
 (`!(k:A ring) z sigma tau.
        field k /\ z IN ring_carrier k /\ subfield_generated k {z} = k /\
        sigma IN
        group_carrier(galois_group (subfield_generated k {ring_0 k},k) I) /\
        tau IN
        group_carrier(galois_group (subfield_generated k {ring_0 k},k) I) /\
        sigma z = tau z
        ==> sigma = tau`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC GALOIS_GROUP_EQ_ON_GENERATORS THEN
  MAP_EVERY EXISTS_TAC
   [`I:A->A`; `subfield_generated (k:A ring) {ring_0 k}`; `k:A ring`;
    `{z:A}`] THEN
  ASM_REWRITE_TAC[IN_SING; FORALL_UNWIND_THM2;
                  SET_RULE `(s:A->bool) UNION {a} = a INSERT s`;
                  SUBFIELD_GENERATED_INSERT_PRIME_SUBFIELD]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_ISOMORPHIC = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> galois_group (subfield_generated k {ring_0 k},k) I
            isomorphic_group unit_group(integer_mod_ring n)`,
  REPEAT GEN_TAC THEN
  DISCH_THEN(MP_TAC o MATCH_MP CYCLOTOMIC_FIELD_GALOIS_GROUP) THEN
  MESON_TAC[GROUP_ISOMORPHISM_IMP_ISOMORPHIC; ISOMORPHIC_GROUP_SYM]);;

let CYCLOTOMIC_FIELD_GALOIS_GROUP_ABELIAN = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\
        ring_order k z = n /\ ~(n = 0) /\ subfield_generated k {z} = k
        ==> abelian_group(galois_group (subfield_generated k {ring_0 k},k) I)`,
  REPEAT GEN_TAC THEN
  DISCH_THEN(MP_TAC o MATCH_MP CYCLOTOMIC_FIELD_GALOIS_GROUP_ISOMORPHIC) THEN
  MESON_TAC[ISOMORPHIC_GROUP_ABELIANNESS; ABELIAN_UNIT_GROUP]);;
