(* ========================================================================= *)
(* Localization of Dedekind domains.                                         *)
(*                                                                           *)
(* Extended ideals are written as in the localization section of             *)
(* ringtheory.ml: for an ideal j of r the set                                *)
(*   {ring_localequiv r s (a,b) | a,b | a IN j /\ b IN s}                    *)
(* is the ideal generated by j in ring_localization r s (the case            *)
(* s = ring_carrier r DIFF p is the localization R_p at a prime p).          *)
(*                                                                           *)
(* Main results: a localization of a Dedekind domain at a multiplicative set *)
(* not containing 0 is a Dedekind domain (DEDEKIND_LOCALIZATION, from        *)
(* NOETHERIAN_RING_LOCALIZATION, INTEGRALLY_CLOSED_LOCALIZATION and the      *)
(* prime ideal correspondence of ringtheory.ml); the localization at a       *)
(* nonzero prime is a DVR (DVR_LOCALIZATION); valuations are preserved: the  *)
(* valuation of the extended ideal of j at the extended ideal of p is the    *)
(* valuation of j at p (IDEAL_VALUATION_LOCALIZATION), and the extended      *)
(* ideal of j in R_p is the power of the maximal ideal with that exponent    *)
(* (DEDEKIND_LOCALIZATION_IDEAL_POW). Auxiliary facts in any ring: the       *)
(* extension of a maximal ideal disjoint from s is maximal                   *)
(* (MAXIMAL_IDEAL_LOCALIZATION), extension commutes with products and        *)
(* powers of ideals (IDEAL_PROD_LOCALIZATION, IDEAL_POW_LOCALIZATION) and    *)
(* only the zero ideal extends to zero when s consists of regular elements   *)
(* (IDEAL_LOCALIZATION_EQ_ZERO).                                             *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (ring_localization, ring_fractionate, the     *)
(* prime ideal correspondence), ANT/integral.ml                              *)
(* (INTEGRALLY_CLOSED_LOCALIZATION, RING_REGULAR_MUL_EQ_0),                  *)
(* ANT/ideal_arith.ml (ideal_prod, ideal_pow), ANT/dedekind.ml (valuations)  *)
(* and ANT/dedekind_struct.ml (DVR).                                         *)
(* ========================================================================= *)

needs "Library/ringtheory.ml";;
needs "ANT/integral.ml";;
needs "ANT/ideal_arith.ml";;
needs "ANT/dedekind.ml";;
needs "ANT/dedekind_struct.ml";;

(* ------------------------------------------------------------------------- *)
(* Extended ideals, in any ring.                                             *)
(* ------------------------------------------------------------------------- *)

let MAXIMAL_IDEAL_LOCALIZATION = prove
 (`!r s m:A->bool.
        ring_multsys r s /\ maximal_ideal r m /\ m INTER s = {}
        ==> maximal_ideal (ring_localization r s)
              {ring_localequiv r s (a,b) | a,b | a IN m /\ b IN s}`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[MAXIMAL_AMONG_PRIME_IDEALS] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_PRIME_IDEAL) THEN
  ASM_SIMP_TAC[PRIME_IDEAL_LOCALIZATION] THEN
  ASM_SIMP_TAC[RING_LOCALIZATION_PRIME_IDEAL_CORRESPONDENCE] THEN
  REWRITE_TAC[NOT_EXISTS_THM; LEFT_AND_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`q:(A#A->bool)->bool`; `p:A->bool`] THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `p:A->bool = m` SUBST_ALL_TAC THENL
   [ALL_TAC; ASM SET_TAC[]] THEN
  MATCH_MP_TAC(SET_RULE
   `(m:A->bool) SUBSET p /\ ~(m PSUBSET p) ==> p = m`) THEN
  CONJ_TAC THENL
   [UNDISCH_THEN
     `{x | x IN ring_carrier r /\ ring_fractionate r s x IN q} = (p:A->bool)`
     (SUBST1_TAC o SYM) THEN
    REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    CONJ_TAC THENL [ASM_MESON_TAC[PRIME_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    FIRST_X_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET] o CONJUNCT1 o
      REWRITE_RULE[PSUBSET]) THEN
    REWRITE_TAC[ring_fractionate; IN_ELIM_THM] THEN
    ASM_MESON_TAC[RING_1_IN_MULTSYS];
    FIRST_X_ASSUM(MP_TAC o CONJUNCT2 o GEN_REWRITE_RULE I [maximal_ideal]) THEN
    ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL]]);;

let IDEAL_LOCALIZATION_EQ_ZERO = prove
 (`!r s j:A->bool.
        ring_multsys r s /\ s SUBSET {a | ring_regular r a} /\
        j SUBSET ring_carrier r
        ==> ({ring_localequiv r s (a,b) | a,b | a IN j /\ b IN s} =
             {ring_0 (ring_localization r s)} <=>
             j = {ring_0 r})`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_1_IN_MULTSYS) THEN
  SUBGOAL_THEN
   `!a b:A. a IN j /\ b IN s
            ==> (ring_localequiv r s (a,b) = ring_0 (ring_localization r s) <=>
                 a = ring_0 r)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM SET_TAC[]; ASM_SIMP_TAC[RING_LOCALEQUIV_EQ_0_GEN]] THEN
    EQ_TAC THENL
     [DISCH_THEN(X_CHOOSE_THEN `c:A` STRIP_ASSUME_TAC) THEN
      MP_TAC(ISPECL [`r:A ring`; `c:A`; `a:A`] RING_REGULAR_MUL_EQ_0) THEN
      ANTS_TAC THENL [ASM SET_TAC[]; ASM_MESON_TAC[]];
      DISCH_THEN SUBST1_TAC THEN EXISTS_TAC `ring_1 r:A` THEN
      ASM_SIMP_TAC[RING_MUL_RZERO; RING_1]];
    ALL_TAC] THEN
  EQ_TAC THEN DISCH_TAC THENL
   [MATCH_MP_TAC(SET_RULE
     `(!a:A. a IN j ==> a = z) /\ z IN j ==> j = {z}`) THEN
    FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [EXTENSION]) THEN
    REWRITE_TAC[IN_SING; IN_ELIM_THM] THEN DISCH_TAC THEN CONJ_TAC THENL
     [X_GEN_TAC `a:A` THEN DISCH_TAC THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `ring_localequiv r s (a:A,ring_1 r)`) THEN
      ASM_MESON_TAC[];
      FIRST_X_ASSUM(MP_TAC o
        SPEC `ring_0(ring_localization r (s:A->bool))`) THEN
      ASM_MESON_TAC[]];
    FIRST_X_ASSUM(SUBST_ALL_TAC o check (is_var o lhand o concl)) THEN
    GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_ELIM_THM; IN_SING] THEN
    X_GEN_TAC `z:A#A->bool` THEN EQ_TAC THENL
     [STRIP_TAC THEN ASM_MESON_TAC[IN_SING];
      DISCH_THEN SUBST1_TAC THEN
      MAP_EVERY EXISTS_TAC [`ring_0 r:A`; `ring_1 r:A`] THEN
      ASM_SIMP_TAC[RING_LOCALIZATION_0]]]);;

let IDEAL_PROD_LOCALIZATION = prove
 (`!r s j k:A->bool.
        ring_multsys r s /\ j SUBSET ring_carrier r /\ k SUBSET ring_carrier r
        ==> {ring_localequiv r s (a,b) | a,b |
             a IN ideal_prod r j k /\ b IN s} =
            ideal_prod (ring_localization r s)
              {ring_localequiv r s (a,b) | a,b | a IN j /\ b IN s}
              {ring_localequiv r s (a,b) | a,b | a IN k /\ b IN s}`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [GEN_REWRITE_TAC (LAND_CONV o ONCE_DEPTH_CONV) [ideal_prod] THEN
    W(MP_TAC o PART_MATCH (rand o rand) IDEAL_GENERATED_RING_LOCALIZATION o
      lhand o snd) THEN
    ASM_SIMP_TAC[RING_SETMUL] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_PROD; SUBSET; FORALL_IN_IMAGE] THEN
    REWRITE_TAC[ring_setmul; FORALL_IN_GSPEC] THEN
    MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier r /\ (b:A) IN ring_carrier r`
    STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    FIRST_ASSUM(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_MUL
      (MATCH_MP RING_HOMOMORPHISM_FRACTIONATE th)]) THEN
    MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
    ASM_SIMP_TAC[RING_FRACTIONATE_IN_CARRIER] THEN
    REWRITE_TAC[ring_fractionate; IN_ELIM_THM] THEN
    ASM_MESON_TAC[RING_1_IN_MULTSYS];
    MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
    ASM_SIMP_TAC[RING_IDEAL_LOCALIZATION; RING_IDEAL_IDEAL_PROD] THEN
    REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM; FORALL_IN_GSPEC] THEN
    X_GEN_TAC `a:A` THEN DISCH_TAC THEN X_GEN_TAC `u:A` THEN DISCH_TAC THEN
    X_GEN_TAC `b:A` THEN DISCH_TAC THEN X_GEN_TAC `v:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier r /\ (b:A) IN ring_carrier r`
    STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_LOCALIZATION_MUL; IN_ELIM_THM] THEN
    MAP_EVERY EXISTS_TAC [`ring_mul r a b:A`; `ring_mul r u v:A`] THEN
    ASM_SIMP_TAC[RING_MUL_IN_IDEAL_PROD; RING_MUL_IN_MULTSYS]]);;

let IDEAL_POW_LOCALIZATION = prove
 (`!r s (j:A->bool) n.
        ring_multsys r s /\ j SUBSET ring_carrier r
        ==> {ring_localequiv r s (a,b) | a,b | a IN ideal_pow r j n /\ b IN s} =
            ideal_pow (ring_localization r s)
              {ring_localequiv r s (a,b) | a,b | a IN j /\ b IN s} n`,
  REWRITE_TAC[RIGHT_FORALL_IMP_THM] THEN REPEAT GEN_TAC THEN STRIP_TAC THEN
  INDUCT_TAC THEN REWRITE_TAC[IDEAL_POW_0; IDEAL_POW_SUC] THEN
  ASM_SIMP_TAC[RING_LOCALIZATION_CARRIER; IDEAL_PROD_LOCALIZATION;
               RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_POW]);;

