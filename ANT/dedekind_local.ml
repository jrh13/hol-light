let DEDEKIND_LOCALIZATION = prove
 (`!r s:A->bool.
        dedekind_domain r /\ ring_multsys r s /\ ~(ring_0 r IN s)
        ==> dedekind_domain (ring_localization r s)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [dedekind_domain]) THEN
  ASM_SIMP_TAC[dedekind_domain; INTEGRAL_DOMAIN_LOCALIZATION;
               NOETHERIAN_RING_LOCALIZATION;
               INTEGRALLY_CLOSED_LOCALIZATION] THEN
  X_GEN_TAC `q:(A#A->bool)->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `s:A->bool`; `q:(A#A->bool)->bool`]
    PRIME_IDEAL_LOCALIZATION_EXISTS) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN X_GEN_TAC `p:A->bool` THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    SUBST_ALL_TAC)) THEN
  MATCH_MP_TAC MAXIMAL_IDEAL_LOCALIZATION THEN ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN SUBST_ALL_TAC THEN
  SUBGOAL_THEN `(s:A->bool) SUBSET {a | ring_regular r a}` ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_ELIM_THM; INTEGRAL_DOMAIN_REGULAR] THEN
    ASM_MESON_TAC[RING_MULTSYS];
    ALL_TAC] THEN
  UNDISCH_TAC
   `~({ring_localequiv r s (a,b) | a,b | a IN {ring_0 r} /\ b IN s} =
      {ring_0 (ring_localization r (s:A->bool))})` THEN
  ASM_SIMP_TAC[IDEAL_LOCALIZATION_EQ_ZERO; SING_SUBSET; RING_0]);;

let DVR_LOCALIZATION = prove
 (`!r p:A->bool.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r})
        ==> DVR (ring_localization r (ring_carrier r DIFF p))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MULTSYS_NONPRIME) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `~(ring_0 r IN ring_carrier r DIFF (p:A->bool)) /\
                ring_carrier r DIFF p SUBSET {a | ring_regular r a}`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_DIFF; IN_ELIM_THM; INTEGRAL_DOMAIN_REGULAR;
                 DEDEKIND_IMP_INTEGRAL_DOMAIN; IN_RING_IDEAL_0] THEN
    ASM_MESON_TAC[IN_RING_IDEAL_0];
    ALL_TAC] THEN
  ASM_SIMP_TAC[DVR_IFF_LOCAL_DEDEKIND; DEDEKIND_LOCALIZATION;
               LOCAL_RING_LOCALIZATION; FIELD_EQ_TRIVIAL_IDEALS] THEN
  REWRITE_TAC[DE_MORGAN_THM; NOT_FORALL_THM; NOT_IMP] THEN DISJ2_TAC THEN
  EXISTS_TAC `{ring_localequiv r (ring_carrier r DIFF p) (a,b) | a,b |
               a IN p /\ b IN ring_carrier r DIFF (p:A->bool)}` THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `p:A->bool`]
    PROPER_IDEAL_LOCALIZATION) THEN
  ASM_SIMP_TAC[SET_RULE `(p:A->bool) INTER (c DIFF p) = {}`; proper_ideal;
               IDEAL_LOCALIZATION_EQ_ZERO; RING_IDEAL_IMP_SUBSET] THEN
  SET_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* Valuations of extended ideals.                                            *)
(* ------------------------------------------------------------------------- *)

(* For a nonzero prime p, write j = p^v l with v the valuation of j at p     *)
(* and l not inside p; extension commutes with products and powers, and the *)
(* extension of l is not inside that of p. The zero prime is degenerate:     *)
(* both valuations are 0 (the local lemma).                                  *)

let IDEAL_VALUATION_LOCALIZATION = prove
 (`!r s p j:A->bool.
        dedekind_domain r /\ ring_multsys r s /\
        prime_ideal r p /\ p INTER s = {} /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ideal_valuation (ring_localization r s)
              {ring_localequiv r s (a,b) | a,b | a IN p /\ b IN s}
              {ring_localequiv r s (a,b) | a,b | a IN j /\ b IN s} =
            ideal_valuation r p j`,
  let lemma = prove
   (`!r j:A->bool.
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ideal_valuation r {ring_0 r} j = 0`,
    REPEAT STRIP_TAC THEN MATCH_MP_TAC IDEAL_VALUATION_UNIQUE THEN
    REWRITE_TAC[RING_IDEAL_0; IDEAL_POW_SUC; IDEAL_POW_0] THEN
    ASM_SIMP_TAC[IDEAL_PROD_LZERO; SUBSET_REFL; RING_IDEAL_IMP_SUBSET] THEN
    ASM_MESON_TAC[IN_RING_IDEAL_0; SUBSET_ANTISYM; SING_SUBSET]) in
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `~(ring_0 r IN (s:A->bool))` ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; IN_INTER; NOT_IN_EMPTY]; ALL_TAC] THEN
  SUBGOAL_THEN `(s:A->bool) SUBSET {a | ring_regular r a}` ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_ELIM_THM; INTEGRAL_DOMAIN_REGULAR] THEN
    ASM_MESON_TAC[RING_MULTSYS];
    ALL_TAC] THEN
  ASM_CASES_TAC `p = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `s:A->bool`; `{ring_0 r:A}`]
      IDEAL_LOCALIZATION_EQ_ZERO) THEN
    ASM_SIMP_TAC[SING_SUBSET; RING_0] THEN DISCH_THEN SUBST1_TAC THEN
    MATCH_MP_TAC(MESON[] `x = 0 /\ y = 0 ==> x = y`) THEN CONJ_TAC THEN
    MATCH_MP_TAC lemma THEN
    ASM_SIMP_TAC[RING_IDEAL_LOCALIZATION; IDEAL_LOCALIZATION_EQ_ZERO;
                 RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  ABBREV_TAC `v = ideal_valuation r p (j:A->bool)` THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `ideal_pow r p v:A->bool`]
    DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; DEDEKIND_IDEAL_SUBSET_POW_VALUATION;
               LE_REFL; LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `l:A->bool` THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(l = {ring_0 r:A})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN UNDISCH_TAC `~(j = {ring_0 r:A})` THEN
    EXPAND_TAC "j" THEN
    SIMP_TAC[IDEAL_PROD_RZERO; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(l SUBSET (p:A->bool))` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `ideal_pow r p v:A->bool`;
                   `l:A->bool`] IDEAL_VALUATION_IDEAL_PROD) THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; IDEAL_POW_EQ_ZERO;
                 IDEAL_VALUATION_IDEAL_POW; IDEAL_VALUATION_PRIME;
                 GSYM IDEAL_VALUATION_EQ_0] THEN
    ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `s:A->bool`; `ideal_pow r p v:A->bool`;
                 `l:A->bool`] IDEAL_PROD_LOCALIZATION) THEN
  ASM_SIMP_TAC[IDEAL_POW_LOCALIZATION; RING_IDEAL_IMP_SUBSET;
               RING_IDEAL_IDEAL_POW] THEN
  DISCH_THEN SUBST1_TAC THEN
  SUBGOAL_THEN
   `dedekind_domain (ring_localization r (s:A->bool)) /\
    prime_ideal (ring_localization r s)
      {ring_localequiv r s (a,b) | a,b | a IN p /\ b IN s} /\
    ring_ideal (ring_localization r s)
      {ring_localequiv r s (a,b) | a,b | a IN l /\ b IN s} /\
    ~({ring_localequiv r s (a,b) | a,b | a IN p /\ b IN s} =
      {ring_0 (ring_localization r s)}) /\
    ~({ring_localequiv r s (a,b) | a,b | a IN l /\ b IN s} =
      {ring_0 (ring_localization r s)})`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_LOCALIZATION; PRIME_IDEAL_LOCALIZATION;
                 RING_IDEAL_LOCALIZATION; IDEAL_LOCALIZATION_EQ_ZERO;
                 RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ideal_valuation (ring_localization r s)
      {ring_localequiv r s (a,b) | a,b | a IN p /\ b IN s}
      {ring_localequiv r s (a,b) | a,b | a IN l /\ b IN (s:A->bool)} = 0`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[IDEAL_VALUATION_EQ_0] THEN
    UNDISCH_TAC `~(l SUBSET (p:A->bool))` THEN
    REWRITE_TAC[SUBSET; NOT_FORALL_THM; NOT_IMP] THEN
    DISCH_THEN(X_CHOOSE_THEN `x:A` STRIP_ASSUME_TAC) THEN
    EXISTS_TAC `ring_fractionate r s (x:A)` THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_SIMP_TAC[PRIME_IDEAL_LOCALIZATION_CONTRACTION] THEN
    REWRITE_TAC[ring_fractionate; IN_ELIM_THM] THEN
    ASM_MESON_TAC[RING_1_IN_MULTSYS];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PROD; IDEAL_VALUATION_IDEAL_POW;
               IDEAL_VALUATION_PRIME; RING_IDEAL_IDEAL_POW; IDEAL_POW_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN; PRIME_IMP_RING_IDEAL] THEN
  ARITH_TAC);;

(* In R_p the extended ideal of j is the power of the maximal ideal p R_p    *)
(* with exponent the valuation of j at p.                                    *)

let DEDEKIND_LOCALIZATION_IDEAL_POW = prove
 (`!r p j:A->bool.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> {ring_localequiv r (ring_carrier r DIFF p) (a,b) | a,b |
             a IN j /\ b IN ring_carrier r DIFF p} =
            ideal_pow (ring_localization r (ring_carrier r DIFF p))
              {ring_localequiv r (ring_carrier r DIFF p) (a,b) | a,b |
               a IN p /\ b IN ring_carrier r DIFF p}
              (ideal_valuation r p j)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `ring_carrier r DIFF p SUBSET {a:A | ring_regular r a}`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_DIFF; IN_ELIM_THM; INTEGRAL_DOMAIN_REGULAR;
                 DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
    ASM_MESON_TAC[IN_RING_IDEAL_0];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`] DVR_LOCALIZATION) THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `p:A->bool`;
                 `j:A->bool`] IDEAL_VALUATION_LOCALIZATION) THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `p:A->bool`]
    MAXIMAL_IDEAL_LOCALIZATION) THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `p:A->bool`]
    IDEAL_LOCALIZATION_EQ_ZERO) THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `j:A->bool`]
    IDEAL_LOCALIZATION_EQ_ZERO) THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_carrier r DIFF p:A->bool`; `j:A->bool`]
    RING_IDEAL_LOCALIZATION) THEN
  ASM_SIMP_TAC[RING_MULTSYS_NONPRIME; SET_RULE
   `(p:A->bool) INTER (c DIFF p) = {}`; DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL;
   RING_IDEAL_IMP_SUBSET] THEN
  ABBREV_TAC `l = ring_localization r (ring_carrier r DIFF p:A->bool)` THEN
  ABBREV_TAC `q = {ring_localequiv r (ring_carrier r DIFF p) (a,b) | a,b |
                   a IN p /\ b IN ring_carrier r DIFF (p:A->bool)}` THEN
  ABBREV_TAC `k = {ring_localequiv r (ring_carrier r DIFF p) (a,b) | a,b |
                   a IN j /\ b IN ring_carrier r DIFF (p:A->bool)}` THEN
  REPEAT STRIP_TAC THEN
