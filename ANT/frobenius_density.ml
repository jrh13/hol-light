                  RING_MONOMORPHISM_IMP_HOMOMORPHISM]; ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `a:B->B`]
    NUMBER_FIELD_FROBENIUS_DENSITY) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MATCH_MP_TAC o MATCH_MP
   (ONCE_REWRITE_RULE[IMP_CONJ] HAS_DIRICHLET_DENSITY_INFINITE)) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  ABBREV_TAC `G = galois_group(k,l) (h:A->B)` THEN
  SUBGOAL_THEN `FINITE(group_carrier(G:(B->B)group))` ASSUME_TAC THENL
   [EXPAND_TAC "G" THEN ASM_SIMP_TAC[FINITE_GALOIS_GROUP]; ALL_TAC] THEN
  REWRITE_TAC[REAL_DIV_EQ_0; REAL_OF_NUM_EQ; DE_MORGAN_THM] THEN
  ASM_SIMP_TAC[CARD_EQ_0; FINITE_RESTRICT; GROUP_CARRIER_NONEMPTY] THEN
  REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
  EXISTS_TAC `a:B->B` THEN ASM_REWRITE_TAC[] THEN
  EXISTS_TAC `group_id G:B->B` THEN REWRITE_TAC[GROUP_ID] THEN
  CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC(SET_RULE
   `(!x. x IN s ==> f x = x) ==> IMAGE (f:B->B) s = s`) THEN
  REPEAT STRIP_TAC THEN MATCH_MP_TAC GROUP_CONJUGATION_BY_ID THEN
  ASM_MESON_TAC[GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET; SUBSET]);;

let NUMBER_FIELD_TOTALLY_SPLIT_DENSITY = prove
 (`!(h:A->B) k l.
        number_field l /\ galois_extension(k,l) h
        ==> has_dirichlet_density k
             {p | prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
                  totally_split (ring_of_integers k,ring_of_integers l) h p}
             (&1 / &(extension_degree(k,l) h))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[GALOIS_IMP_FIELD_EXTENSION; field_extension;
                  RING_MONOMORPHISM_IMP_HOMOMORPHISM]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN
   `CARD(group_carrier(galois_group(k,l) (h:A->B))) = extension_degree(k,l) h`
  ASSUME_TAC THENL [ASM_MESON_TAC[GALOIS_EXTENSION_EQ_CARD]; ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `I:B->B`]
    NUMBER_FIELD_FROBENIUS_DENSITY) THEN
  ABBREV_TAC `G = galois_group(k,l) (h:A->B)` THEN
  SUBGOAL_THEN `group_id G = (I:B->B)` ASSUME_TAC THENL
   [EXPAND_TAC "G" THEN REWRITE_TAC[GALOIS_GROUP]; ALL_TAC] THEN
  SUBGOAL_THEN `(I:B->B) IN group_carrier G` ASSUME_TAC THENL
   [ASM_MESON_TAC[GROUP_ID]; ALL_TAC] THEN
  SUBGOAL_THEN `group_carrier(subgroup_generated G {I:B->B}) = {I}`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[CARRIER_SUBGROUP_GENERATED_SUBGROUP; TRIVIAL_SUBGROUP_OF];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN group_carrier G
        ==> IMAGE (group_conjugation G g) {I:B->B} = {I}`
  ASSUME_TAC THENL
   [REWRITE_TAC[IMAGE_CLAUSES] THEN
    ASM_MESON_TAC[GROUP_CONJUGATION_EQ_ID; GROUP_ID];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!t. t IN group_carrier G
        ==> (group_carrier(subgroup_generated G {t}) = {I:B->B} <=> t = I)`
  ASSUME_TAC THENL
   [X_GEN_TAC `t:B->B` THEN DISCH_TAC THEN EQ_TAC THENL
     [DISCH_TAC THEN
      MP_TAC(ISPECL [`G:(B->B)group`; `{t:B->B}`; `t:B->B`]
        SUBGROUP_GENERATED_INC) THEN
      ASM_REWRITE_TAC[SING_SUBSET; IN_SING];
      DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  ASM_SIMP_TAC[ASSUME `(I:B->B) IN group_carrier G`] THEN
  MATCH_MP_TAC(MESON[]
   `!S1 S2 d1 d2. S1 = S2 /\ d1 = d2
                  ==> has_dirichlet_density (k:A ring) S1 d1
                      ==> has_dirichlet_density k S2 d2`) THEN
  CONJ_TAC THENL
   [GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `p:A->bool` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_CASES_TAC `prime_ideal (ring_of_integers k) (p:A->bool)` THEN
    ASM_REWRITE_TAC[] THEN ASM_CASES_TAC `p = {ring_0(k:A ring)}` THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
      NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
    ASM_REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
    DISCH_THEN(X_CHOOSE_THEN `Q0:B->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
    EQ_TAC THENL
     [DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
       (X_CHOOSE_THEN `Q:B->bool` (X_CHOOSE_THEN `g:B->B`
         STRIP_ASSUME_TAC))) THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                     `Q:B->bool`] NUMBER_FIELD_GALOIS_SPLITTING_TYPES) THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                     `Q:B->bool`]
        NUMBER_FIELD_DECOMPOSITION_GROUP_FROBENIUS) THEN
      ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
       [ASM_MESON_TAC[UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED; weakly_unramified];
        ALL_TAC] THEN
      DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT1) THEN
      ASM_SIMP_TAC[];
      DISCH_TAC THEN
      SUBGOAL_THEN
       `unramified (ring_of_integers k,ring_of_integers l) (h:A->B) p`
      ASSUME_TAC THENL
       [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
          NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED) THEN
        ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL] THEN DISCH_THEN SUBST1_TAC THEN
        UNDISCH_TAC
         `totally_split (ring_of_integers k,ring_of_integers l) (h:A->B) p` THEN
        REWRITE_TAC[totally_split; weakly_unramified] THEN MESON_TAC[];
        ALL_TAC] THEN
      ASM_REWRITE_TAC[] THEN
      MAP_EVERY EXISTS_TAC [`Q0:B->bool`; `I:B->B`] THEN
      ASM_SIMP_TAC[] THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                     `Q0:B->bool`] NUMBER_FIELD_GALOIS_SPLITTING_TYPES) THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                     `Q0:B->bool`]
        NUMBER_FIELD_DECOMPOSITION_GROUP_FROBENIUS) THEN
      ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
       [ASM_MESON_TAC[UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED; weakly_unramified];
        ALL_TAC] THEN
      DISCH_THEN(SUBST1_TAC o CONJUNCT1) THEN ASM_SIMP_TAC[]];
    SUBGOAL_THEN
     `{t | t IN group_carrier G /\
           ?g. g IN group_carrier G /\
               group_carrier(subgroup_generated G {t}) =
               IMAGE (group_conjugation G g) {I:B->B}} = {I}`
    SUBST1_TAC THENL
     [GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `t:B->B` THEN
      REWRITE_TAC[IN_ELIM_THM; IN_SING] THEN ASM_MESON_TAC[];
      REWRITE_TAC[CARD_SING]]]);;
