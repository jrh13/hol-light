(* ========================================================================= *)
(* The Frobenius density theorem (Frobenius 1896; the weak form of the       *)
(* Chebotarev density theorem, Neukirch, Algebraic Number Theory, VII.13.4): *)
(* for a Galois extension l / k of number fields with group G and a in G,    *)
(* the nonzero primes p of O_k unramified in l whose Frobenius element at a  *)
(* prime Q above p generates a conjugate of the cyclic group <a> have the    *)
(* Dirichlet density #{t in G : <t> is conjugate to <a>} / #G. In particular *)
(* the primes of O_k that split completely in l have density 1 / [l:k]       *)
(* (Neukirch VII.13.6, Lang, Algebraic Number Theory, VIII.4), and every     *)
(* conjugacy class of cyclic subgroups of G is generated by Frobenius        *)
(* elements of infinitely many primes.                                       *)
(*                                                                           *)
(* Main results, for a field k and a number field l with h : k -> l Galois,  *)
(* G = galois_group(k,l) h, a in G, Frob_Q the Frobenius element             *)
(* frobenius_element (k,l) h (ring_of_integers l) Q:                         *)
(*   NUMBER_FIELD_FROBENIUS_DENSITY_LOG: the sum of N(p)^-s over the         *)
(*     nonzero unramified primes p with <Frob_Q> = g <a> g^-1 for some Q     *)
(*     above p and g in G is -(#{t : <t> conjugate to <a>} / #G) log(s - 1)  *)
(*     + O(1) for 1 < s <= 2                                                 *)
(*   NUMBER_FIELD_FROBENIUS_DENSITY: the same set of primes has Dirichlet    *)
(*     density #{t in G : <t> conjugate to <a>} / #G                         *)
(*   NUMBER_FIELD_FROBENIUS_INFINITE: this set of primes is infinite         *)
(*   NUMBER_FIELD_TOTALLY_SPLIT_DENSITY: the nonzero primes of O_k totally   *)
(*     split in O_l have Dirichlet density 1 / [l:k]                         *)
(*   NUMBER_FIELD_FIXED_FIELD_FROBENIUS_LOG: for a subgroup H of G, the sum  *)
(*     over the unramified p of prime norm of                                *)
(*     #{g in G : g Frob_Q g^-1 in H} N(p)^-s is -#H log(s - 1) + O(1)       *)
(* On the way (with NUMBER_FIELD_FROBENIUS_CONJUGATE_PRIME of                *)
(* ANT/nf_decomposition.ml: the Frobenius element at g(Q) is g Frob_Q g^-1,  *)
(* and NUMBER_FIELD_PRIME_NORM_CARD of ANT/relative_split.ml: the primes of  *)
(* O_l of prime norm m are counted by the primes p of O_k of norm m and the  *)
(* primes of residue degree one above them):                                 *)
(*   NUMBER_FIELD_FIXED_FIELD_DEGREE_ONE_CARD: for unramified p and M the    *)
(*     fixed field of H, #H times the number of primes of O_M above p of     *)
(*     residue degree one is #{g in G : g Frob_Q g^-1 in H}                  *)
(*   DIRICHLET_SERIES_DIVISOR_INDUCTION: estimates for the divisor sums of a *)
(*     family of Dirichlet series give estimates for each member             *)
(*   DIRICHLET_SERIES_CYCLIC_CONJUGATES: for a finite group G, a in G and    *)
(*     elements fr(p) of G indexed by finite sets S(m): if for every         *)
(*     subgroup H of <a> the series with the coefficients                    *)
(*     sum_(p in S(m)) #{g in G : g fr(p) g^-1 in H} is -#H log(s - 1) +     *)
(*     O(1), then the series counting the p in S(m) with <fr(p)> conjugate   *)
(*     to <a> is -(#{t : <t> conjugate to <a>} / #G) log(s - 1) + O(1)       *)
(*   NUMBER_FIELD_NONPRIME_NORM_SERIES: the primes of nonprime norm give a   *)
(*     bounded contribution, at most 2 [k:Q]; so a log estimate for the      *)
(*     primes of prime norm in a set of primes holds for the whole set       *)
(*     (NUMBER_FIELD_NONPRIME_NORM_LOG)                                      *)
(*                                                                           *)
(* Routes. For a subgroup H with fixed field M, the primes of degree one of  *)
(* O_M have density one (NUMBER_FIELD_DEGREE_ONE_PRIMES_LOG over M). Those   *)
(* of prime norm m lie over the primes p of O_k of norm m, and above an      *)
(* unramified p there are #{g : g Frob_Q g^-1 in H} / #H of them: they are   *)
(* the intersections of M with the conjugates g(Q), of residue degree one    *)
(* iff the decomposition group g <Frob_Q> g^-1 lies in H; the finitely many  *)
(* ramified p change the sums by O(1). This is                               *)
(* NUMBER_FIELD_FIXED_FIELD_FROBENIUS_LOG. The rest is a statement about a   *)
(* finite group G, DIRICHLET_SERIES_CYCLIC_CONJUGATES: for elements fr(p) of *)
(* G indexed by finite sets S(m), it passes from such estimates for the      *)
(* subgroups H_d of the elements of <a> of order dividing d, for the         *)
(* divisors d of n, the order of a, to the estimate for the p with <fr(p)>   *)
(* conjugate to <a>. With w(e) the series weighted by the number of the g    *)
(* conjugating fr(p) to an element of order e of <a>, the sum of the w(e)    *)
(* over the divisors e of d is the series of H_d                             *)
(* (CARD_CONJUGATES_IN_TORSION_NSUM of Library/grouptheory.ml), and #H_d is  *)
(* the sum over e dividing d of the number of elements of order e of <a>     *)
(* (CARD_RESTRICT_POW_EQ_ID of Library/grouptheory.ml). Strong               *)
(* induction over the divisors (DIRICHLET_SERIES_DIVISOR_INDUCTION, in place *)
(* of Moebius inversion) gives w(n) = -c log(s - 1) + O(1), c the number of  *)
(* generators of <a>. The number of the g conjugating fr(p) to a generator   *)
(* of <a> is the order of the normalizer of <a> if <fr(p)> is conjugate to   *)
(* <a>, and 0 otherwise (CARD_CONJUGATES_INTO_CYCLIC_GENERATORS of           *)
(* Library/grouptheory.ml); so w(n) counts the p in question with this       *)
(* weight, and CARD_CYCLIC_SUBGROUP_DIVISION of Library/grouptheory.ml turns *)
(* c over the order of the normalizer into the density. In                   *)
(* NUMBER_FIELD_FROBENIUS_DENSITY_LOG, S(m) is the set                       *)
(* of the unramified p of prime norm m and fr(p) the Frobenius element at a  *)
(* prime Q above p, chosen with <Frob_Q> conjugate to <a> if there is such   *)
(* a Q; the primes of nonprime norm change the sums by O(1)                  *)
(* (NUMBER_FIELD_NONPRIME_NORM_LOG). The totally split primes are the case   *)
(* a = 1 (NUMBER_FIELD_GALOIS_SPLITTING_TYPES: totally split iff             *)
(* D_Q = 1, and D_Q = <Frob_Q> for unramified Q,                             *)
(* NUMBER_FIELD_DECOMPOSITION_GROUP_FROBENIUS).                              *)
(*                                                                           *)
(* Uses: Library/grouptheory.ml (cyclic subgroups, conjugation,              *)
(* normalizers, CARD_CYCLIC_SUBGROUP_DIVISION,                               *)
(* CARD_CONJUGATES_IN_TORSION_NSUM, CARD_RESTRICT_POW_EQ_ID,                 *)
(* CARD_CONJUGATES_INTO_CYCLIC_GENERATORS), Library/galois.ml (Galois        *)
(* groups, fixed fields), Multivariate/realanalysis.ml                       *)
(* (REAL_SERIES_FINITE_SUM, REAL_SUMMABLE_POS_PARTIAL_BOUND,                 *)
(* DIRICHLET_SERIES_FINITE_PERTURBATION), ANT/classgroup.ml                  *)
(* (NUMBER_FIELD_FINITE_PRIME_IDEALS_BOUNDED_NORM), ANT/relative_split.ml    *)
(* (towers, relative norms), ANT/splitting_types.ml (unramified, totally     *)
(* split), ANT/decomposition.ml and ANT/nf_decomposition.ml (decomposition   *)
(* groups, Frobenius elements, transitivity of the Galois action),           *)
(* ANT/decomposition_field.ml (primes in intermediate fields, splitting      *)
(* types in Galois extensions) and ANT/dedekind_zeta.ml (prime ideal sums,   *)
(* Dirichlet densities). Also Multivariate/transcendentals.ml (log, rpow).   *)
(* ========================================================================= *)

