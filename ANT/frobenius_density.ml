                              (\m. sum {e | e divides d} (\e. w e m) /
                                   &m rpow s) +
                             &(nsum {e | e divides d} c) * log(s - &1))
                         <= C)
        ==> !d. d divides n
                ==> ?C. !s. &1 < s /\ s <= &2
                        ==> real_summable (from 1) (\m. w d m / &m rpow s) /\
                            abs(real_infsum (from 1)
                                 (\m. w d m / &m rpow s) +
                                &(c d) * log(s - &1)) <= C`,
