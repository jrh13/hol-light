     [MATCH_MP_TAC GALOIS_GROUP_PERMUTES THEN
      MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`] THEN
      EXPAND_TAC "G" THEN ASM SET_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN `IMAGE (r:B->B) Q SUBSET ring_carrier l` ASSUME_TAC THENL
     [FIRST_ASSUM(MP_TAC o SPEC `r:B->B` o check (fun th ->
