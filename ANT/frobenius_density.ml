(* The primes of residue degree one of a fixed field.                        *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_FIXED_FIELD_PRIME_DEGREE_ONE = prove
 (`!(h:A->B) k l H p Q g.
        number_field l /\ galois_extension(k,l) h /\
        H subgroup_of galois_group(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        unramified (ring_of_integers k,ring_of_integers l) h p /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h p SUBSET Q /\
        g IN group_carrier(galois_group(k,l) h)
        ==> prime_ideal
             (ring_of_integers(subfield_generated l (fixed_field l H)))
             (IMAGE g Q INTER fixed_field l H) /\
            ~(IMAGE g Q INTER fixed_field l H = {ring_0 l}) /\
            IMAGE h p SUBSET IMAGE g Q INTER fixed_field l H /\
            (residue_degree
              (ring_of_integers k,
               ring_of_integers(subfield_generated l (fixed_field l H)))
              h (IMAGE g Q INTER fixed_field l H) = 1 <=>
             group_conjugation (galois_group(k,l) h) g
               (frobenius_element (k,l) h (ring_of_integers l) Q) IN H)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_IMP_FIELD_EXTENSION) THEN
    SIMP_TAC[field_extension; RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`;
                 `p:A->bool`; `Q:B->bool`; `g:B->B`]
    NUMBER_FIELD_FROBENIUS_CONJUGATE_PRIME) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`]
    GALOIS_GROUP_FIXED_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `fixed_field l H:B->bool`;
                 `p:A->bool`; `IMAGE (g:B->B) Q`]
    NUMBER_FIELD_PRIME_IDEAL_INTERMEDIATE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `fixed_field l H:B->bool`;
                 `p:A->bool`; `IMAGE (g:B->B) Q`]
    NUMBER_FIELD_INTERMEDIATE_SPLITTING) THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `group_carrier(inertia_group(k,l) (h:A->B) (ring_of_integers l)
                   (IMAGE (g:B->B) Q)) SUBSET H`
  (fun th -> REWRITE_TAC[th]) THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                   `IMAGE (g:B->B) Q`]
      NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP) THEN
    ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `ramification_index (ring_of_integers k,ring_of_integers l) (h:A->B)
        (IMAGE (g:B->B) Q) = 1`
    (fun th -> REWRITE_TAC[th]) THENL
     [ASM_MESON_TAC[UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED; weakly_unramified];
      DISCH_THEN SUBST1_TAC] THEN
    REWRITE_TAC[SING_SUBSET] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP SUBGROUP_OF_IMP_SUBSET o check (fun th ->
      can (term_match [] `H subgroup_of (G:(B->B)group)`) (concl th))) THEN
    FIRST_ASSUM(MP_TAC o CONJUNCT1 o CONJUNCT2 o
      GEN_REWRITE_RULE I [subgroup_of] o check (fun th ->
      can (term_match [] `H subgroup_of (G:(B->B)group)`) (concl th))) THEN
    REWRITE_TAC[GALOIS_GROUP] THEN SIMP_TAC[];
    ALL_TAC] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC MP_TAC) THEN ASM_REWRITE_TAC[]);;
let NUMBER_FIELD_FIXED_FIELD_DEGREE_ONE_CARD = prove
 (`!(h:A->B) k l H p Q.
        number_field l /\ galois_extension(k,l) h /\
        H subgroup_of galois_group(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        unramified (ring_of_integers k,ring_of_integers l) h p /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h p SUBSET Q
        ==> CARD H *
            CARD {P | prime_ideal
                       (ring_of_integers
                         (subfield_generated l (fixed_field l H))) P /\
                      IMAGE h p SUBSET P /\
                      residue_degree
                       (ring_of_integers k,
                        ring_of_integers
                         (subfield_generated l (fixed_field l H)))
                       h P = 1} =
            CARD {g | g IN group_carrier(galois_group(k,l) h) /\
                      group_conjugation (galois_group(k,l) h) g
                        (frobenius_element (k,l) h (ring_of_integers l) Q)
                      IN H}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_IMP_FIELD_EXTENSION) THEN
    SIMP_TAC[field_extension; RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`]
    GALOIS_GROUP_FIXED_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `fixed_field l H:B->bool`]
    NUMBER_FIELD_INTERMEDIATE_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `galois_extension(subfield_generated l (fixed_field l H),l) (I:B->B)`
  ASSUME_TAC THENL
   [MATCH_MP_TAC GALOIS_EXTENSION_SUBFIELD_GENERATED THEN
    MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`] THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC `G = galois_group(k,l) (h:A->B)` THEN
  ABBREV_TAC `s = fixed_field l (H:(B->B)->bool)` THEN
  ABBREV_TAC `M = subfield_generated l (s:B->bool)` THEN
  ABBREV_TAC
   `Fr = frobenius_element (k,l) (h:A->B) (ring_of_integers l) Q` THEN
  ABBREV_TAC
   `S1 = {P | prime_ideal (ring_of_integers M) P /\
              IMAGE (h:A->B) p SUBSET P /\
              residue_degree (ring_of_integers k,ring_of_integers M) h P =
              1}` THEN
  ABBREV_TAC
   `X = {g | g IN group_carrier G /\
             group_conjugation G g (Fr:B->B) IN (H:(B->B)->bool)}` THEN
  ABBREV_TAC `c = \g:B->B. IMAGE g Q INTER (s:B->bool)` THEN
  SUBGOAL_THEN
   `group_mul G = ((o):(B->B)->(B->B)->(B->B)) /\
    group_inv G = (inverse:(B->B)->(B->B)) /\
    group_id G = (I:B->B)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "G" THEN REWRITE_TAC[GALOIS_GROUP]; ALL_TAC] THEN
  SUBGOAL_THEN
   `FINITE(group_carrier(G:(B->B)group)) /\ H SUBSET group_carrier G /\
    FINITE(H:(B->B)->bool)`
  STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `FINITE(group_carrier(G:(B->B)group))` ASSUME_TAC THENL
     [EXPAND_TAC "G" THEN ASM_SIMP_TAC[FINITE_GALOIS_GROUP]; ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
     [ASM_MESON_TAC[SUBGROUP_OF_IMP_SUBSET];
      ASM_MESON_TAC[FINITE_SUBSET]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN group_carrier G
        ==> prime_ideal (ring_of_integers l) (IMAGE g Q) /\
            IMAGE (h:A->B) p SUBSET IMAGE g Q /\
            prime_ideal (ring_of_integers M) ((c:(B->B)->B->bool) g) /\
            ~(c g = {ring_0 l}) /\
            IMAGE h p SUBSET c g /\
            (c g IN S1 <=> g IN X) /\
            (group_carrier(decomposition_group(k,l) h (IMAGE g Q))
             SUBSET H <=> g IN X)`
  ASSUME_TAC THENL
   [X_GEN_TAC `g:B->B` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`;
                   `p:A->bool`; `Q:B->bool`; `g:B->B`]
      NUMBER_FIELD_FROBENIUS_CONJUGATE_PRIME) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`;
                   `p:A->bool`; `Q:B->bool`; `g:B->B`]
      NUMBER_FIELD_FIXED_FIELD_PRIME_DEGREE_ONE) THEN
    ASM_REWRITE_TAC[] THEN REPEAT(DISCH_THEN STRIP_ASSUME_TAC) THEN
    EXPAND_TAC "c" THEN MAP_EVERY EXPAND_TAC ["S1"; "X"] THEN
    ASM_REWRITE_TAC[IN_ELIM_THM];
    ALL_TAC] THEN
  SUBGOAL_THEN `!P. P IN S1 ==> ?g. g IN X /\ (c:(B->B)->B->bool) g = P`
  MP_TAC THENL
   [X_GEN_TAC `P:B->bool` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`; `p:A->bool`]
      NUMBER_FIELD_PRIME_IDEALS_INTERMEDIATE) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(MP_TAC o SPEC `P:B->bool` o GEN_REWRITE_RULE I [EXTENSION]) THEN
    UNDISCH_TAC `(P:B->bool) IN S1` THEN EXPAND_TAC "S1" THEN
    REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `Q':B->bool` STRIP_ASSUME_TAC) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`;
                   `Q:B->bool`; `Q':B->bool`]
      NUMBER_FIELD_GALOIS_GROUP_TRANSITIVE) THEN
    ASM_REWRITE_TAC[] THEN MATCH_MP_TAC MONO_EXISTS THEN
    X_GEN_TAC `g:B->B` THEN STRIP_TAC THEN
    SUBGOAL_THEN `(c:(B->B)->B->bool) g = P` ASSUME_TAC THENL
     [EXPAND_TAC "c" THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN
