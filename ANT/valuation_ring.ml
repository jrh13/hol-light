  ASSUME_TAC THENL [ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING];
                    ALL_TAC] THEN
  SUBGOAL_THEN
   `p SUBSET a /\ a SUBSET ring_carrier k /\ ring_1 k IN a /\
    ring_0 k IN (p:A->bool) /\ ~(ring_1 k IN p) /\
    (!x y. x IN a /\ y IN a ==> ring_mul k x y IN a) /\
    (!x y. x IN a /\ y IN a /\ ring_mul k x y IN p ==> x IN p \/ y IN p)`
