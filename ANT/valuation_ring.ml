(* Extending a homomorphism by one element (the step of A-M 5.21). Let g map *)
(* a subring s of a field k into an algebraically closed field l, with s     *)
(* containing the inverses of its elements outside the kernel of g. If 1 is  *)
(* not in the ideal of s[y] generated by the kernel, some w in l satisfies,  *)
(* under g, every polynomial relation of y over s                            *)
(* (RING_HOMOMORPHISM_ADJOIN_ROOT): the relations form an ideal of s[X], the *)
(* kernel of the evaluation at y; an image under g that is a nonzero         *)
(* constant would put 1 in that ideal of s[y]                                *)
(* (IDEAL_GENERATED_ADJOIN_ROOT_UNIT), so the images have a common root w    *)
(* (RING_IDEAL_POLY_COMMON_ROOT).                                            *)
let RING_HOMOMORPHISM_ADJOIN_ROOT = prove
 (`!(k:A ring) (l:B ring) s g y.
        field k /\ algebraically_closed_field l /\ s subring_of k /\
        ring_homomorphism(subring_generated k s,l) g /\
        (!z. z IN s /\ ~(g z = ring_0 l) ==> ring_inv k z IN s) /\
        y IN ring_carrier k /\
        ~(ring_1 k IN ideal_generated (subring_generated k (y INSERT s))
                       {z | z IN s /\ g z = ring_0 l})
        ==> ?w. w IN ring_carrier l /\
                !n a. (!i. a i IN s) /\
                      ring_sum k (0..n)
                        (\i. ring_mul k (a i) (ring_pow k y i)) = ring_0 k
                      ==> ring_sum l (0..n)
                            (\i. ring_mul l (g(a i)) (ring_pow l w i)) =
                          ring_0 l`,
  let sum_lemma = prove
   (`!(r:A ring) (r':C ring) h x (c:num->A) n.
        ring_homomorphism(r,r') h /\ x IN ring_carrier r' /\
        (!i. c i IN ring_carrier r)
        ==> poly_extend (r,r') h (\v:1. x)
              (ring_sum (poly_ring r (:1)) (0..n)
                 (\i. poly_mul r (poly_const r (c i))
                        (poly_pow r (poly_var r one) i))) =
            ring_sum r' (0..n) (\i. ring_mul r' (h(c i)) (ring_pow r' x i))`,
    REPEAT STRIP_TAC THEN
    W(MP_TAC o PART_MATCH (lhand o rand) POLY_EXTEND_RING_SUM o
      lhand o snd) THEN
    ASM_REWRITE_TAC[FINITE_NUMSEG; GSYM RING_POLYNOMIAL] THEN ANTS_TAC THENL
     [ASM_SIMP_TAC[RING_POLYNOMIAL_MUL; RING_POLYNOMIAL_CONST;
                   RING_POLYNOMIAL_POW; RING_POLYNOMIAL_VAR];
      DISCH_THEN SUBST1_TAC] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN ASM_SIMP_TAC[POLY_EXTEND_CONST_VARPOW]) in
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP ALGEBRAICALLY_CLOSED_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `ring_carrier(subring_generated k s) = (s:A->bool)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_ideal (subring_generated k s) {z:A | z IN s /\ (g:A->B) z = ring_0 l}`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `{z:A | z IN s /\ (g:A->B) z = ring_0 l} =
      ring_kernel(subring_generated k s,l) g`
    SUBST1_TAC THENL
     [ASM_REWRITE_TAC[ring_kernel];
      MATCH_MP_TAC RING_IDEAL_RING_KERNEL THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  (* the ideal j of the relations of y *)
  ABBREV_TAC
   `j = ring_kernel (poly_ring (subring_generated k s) (:1),k)
          (poly_extend (subring_generated k s,k) (\x:A. x) (\v:1. y))` THEN
  MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `l:B ring`; `g:A->B`;
                 `j:((1->num)->A)->bool`] RING_IDEAL_POLY_COMMON_ROOT) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [EXPAND_TAC "j" THEN MATCH_MP_TAC RING_IDEAL_RING_KERNEL THEN
      MATCH_MP_TAC RING_HOMOMORPHISM_POLY_EXTEND THEN
      ASM_REWRITE_TAC[RING_HOMOMORPHISM_INCLUSION];
      ALL_TAC] THEN
    (* an image that is a nonzero constant would put 1 in the ideal *)
    X_GEN_TAC `p:(1->num)->A` THEN EXPAND_TAC "j" THEN
    REWRITE_TAC[ring_kernel; IN_ELIM_THM] THEN STRIP_TAC THEN
    MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `ring_polynomial (subring_generated k s) (p:(1->num)->A) /\
      ring_polynomial l ((g:A->B) o p)`
    STRIP_ASSUME_TAC THENL
     [ASM_REWRITE_TAC[RING_POLYNOMIAL] THEN
      MATCH_MP_TAC IN_RING_POLYNOMIAL_CARRIER_COMPOSE THEN
      EXISTS_TAC `subring_generated k (s:A->bool)` THEN ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN `!i. coeff i (p:(1->num)->A) IN s` ASSUME_TAC THENL
     [GEN_TAC THEN
      SUBST1_TAC(SYM(ASSUME `ring_carrier(subring_generated k s) =
                             (s:A->bool)`)) THEN
      MATCH_MP_TAC COEFF_IN_CARRIER_ALT THEN ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `~(coeff 0 ((g:A->B) o (p:(1->num)->A)) = ring_0 l) /\
      (!i. 1 <= i ==> coeff i ((g:A->B) o (p:(1->num)->A)) = ring_0 l)`
    MP_TAC THENL
     [CONJ_TAC THENL
       [MP_TAC(ISPECL [`l:B ring`; `(g:A->B) o (p:(1->num)->A)`]
          POLY_TOP_EQ_0) THEN ASM_REWRITE_TAC[];
        REPEAT STRIP_TAC THEN MATCH_MP_TAC COEFF_ABOVE_DEG THEN
        ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC];
      REWRITE_TAC[COEFF_COMPOSE] THEN STRIP_TAC] THEN
    SUBGOAL_THEN
     `(coeff 0 (p:(1->num)->A)) IN ring_carrier k /\
      ~(coeff 0 (p:(1->num)->A) = ring_0 k)`
    STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL
       [ASM_MESON_TAC[subring_of; SUBSET];
        DISCH_TAC THEN UNDISCH_TAC
         `~((g:A->B)(coeff 0 (p:(1->num)->A)) = ring_0 l)` THEN
        ASM_REWRITE_TAC[] THEN
        FIRST_ASSUM(MP_TAC o MATCH_MP RING_HOMOMORPHISM_0) THEN
        REWRITE_TAC[CONJUNCT2 SUBRING_GENERATED]];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum k (0..poly_deg (subring_generated k s) p)
        (\i. ring_mul k (coeff i (p:(1->num)->A)) (ring_pow k y i)) =
      ring_0 k`
    ASSUME_TAC THENL
     [UNDISCH_TAC
       `poly_extend (subring_generated k s,k) (\x:A. x) (\v:1. y) p =
        ring_0 k` THEN
      MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `k:A ring`;
                     `\x:A. x`; `\v:1. (y:A)`; `p:(1->num)->A`]
        POLY_EXTEND_UNIVARIATE) THEN
      ASM_REWRITE_TAC[RING_HOMOMORPHISM_INCLUSION] THEN
      DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[];
      ALL_TAC] THEN
    UNDISCH_TAC
     `~(ring_1 k IN ideal_generated (subring_generated k (y INSERT s))
                     {z:A | z IN s /\ (g:A->B) z = ring_0 l})` THEN
    REWRITE_TAC[] THEN MATCH_MP_TAC IDEAL_GENERATED_ADJOIN_ROOT_UNIT THEN
    MAP_EVERY EXISTS_TAC
     [`poly_deg (subring_generated k s) (p:(1->num)->A)`;
      `\i. coeff i (p:(1->num)->A)`;
      `ring_inv k (coeff 0 (p:(1->num)->A))`] THEN
    ASM_SIMP_TAC[FIELD_MUL_LINV; IN_ELIM_THM];
    ALL_TAC] THEN
  (* a relation of y gives a polynomial in j *)
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `w:B` THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[] THEN MAP_EVERY X_GEN_TAC [`n:num`; `a:num->A`] THEN
  STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC
   `ring_sum (poly_ring (subring_generated k s) (:1)) (0..n)
      (\i. poly_mul (subring_generated k s)
             (poly_const (subring_generated k s) ((a:num->A) i))
             (poly_pow (subring_generated k s)
                (poly_var (subring_generated k s) one) i))` o
    check (fun th -> is_forall(concl th) &&
                     can (find_term ((=) `j:((1->num)->A)->bool`))
                         (concl th))) THEN
  EXPAND_TAC "j" THEN REWRITE_TAC[ring_kernel; IN_ELIM_THM; RING_SUM] THEN
  ASM_SIMP_TAC[sum_lemma; RING_HOMOMORPHISM_INCLUSION] THEN
  MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `l:B ring`; `g:A->B`;
     `\v:1. (w:B)`;
     `ring_sum (poly_ring (subring_generated k s) (:1)) (0..n)
        (\i. poly_mul (subring_generated k s)
               (poly_const (subring_generated k s) ((a:num->A) i))
               (poly_pow (subring_generated k s)
                  (poly_var (subring_generated k s) one) i))`]
    POLY_EXTEND_EVALUATE) THEN
  ASM_REWRITE_TAC[GSYM poly_eval] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[sum_lemma]);;

