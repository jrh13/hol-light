(* The Chevalley extension theorem in the domination form (Matsumura 10.2,   *)
(* A-M 5.21): for a prime p of a subring a of a field k there is a valuation *)
(* subring of k containing a whose maximal ideal meets a in p. By the Zorn   *)
(* lemma on the subrings R containing a with no element of a\p in pR; a      *)
(* maximal R is local and, by A-M 5.23, a valuation ring.                    *)
(* ------------------------------------------------------------------------- *)

let VALUATION_SUBRING_DOMINATES = prove
 (`!k a p:A->bool.
        field k /\ a subring_of k /\ prime_ideal (subring_generated k a) p
