(* ------------------------------------------------------------------------- *)
(* Adjoining an element x or its inverse to a subring r of a field k. The    *)
(* ideal generated by an ideal j of r in r[x] consists of the polynomials in *)
(* x with coefficients in j (IDEAL_GENERATED_ADJOIN_EXPLICIT, in             *)
(* Library/ringtheory.ml); for a local r with maximal ideal m, mr[x] or      *)
(* mr[1/x] is proper (A-M 5.23); a root x of a polynomial over r whose       *)
(* constant term is a unit and whose other coefficients lie in j makes jr[x] *)
(* the unit ideal (IDEAL_GENERATED_ADJOIN_ROOT_UNIT, in                      *)
(* Library/ringtheory.ml).                                                   *)
(* ------------------------------------------------------------------------- *)

(* A-M 5.23, with x y = 1: if 1 = sum_{i <= n} c_i x^i and 1 = sum_{j <= q}  *)
(* d_j y^j with all coefficients in m and q <= n, then (1 - d_0) x^q is a    *)
(* combination of lower powers of x with coefficients in m, 1 - d_0 is a     *)
(* unit, and c_n x^n can be eliminated from the first relation. By induction *)
(* on n + q both relations cannot exist.                                     *)

let IDEAL_GENERATED_ADJOIN_OR_INV = prove
 (`!(k:A ring) r m x.
        field k /\ r subring_of k /\ ring_ideal (subring_generated k r) m /\
        (!z. z IN r /\ ~(z IN m) ==> ring_inv k z IN r) /\ ~(ring_1 k IN m) /\
        x IN ring_carrier k /\ ~(x = ring_0 k)
        ==> ~(ring_1 k IN
              ideal_generated (subring_generated k (x INSERT r)) m) \/
            ~(ring_1 k IN
              ideal_generated (subring_generated k (ring_inv k x INSERT r)) m)`,
  let mul_lemma = prove
   (`!r cn dj a b e:A.
        cn IN ring_carrier r /\ dj IN ring_carrier r /\ a IN ring_carrier r /\
        b IN ring_carrier r /\ e IN ring_carrier r /\ ring_mul r b e = ring_1 r
        ==> ring_mul r (ring_mul r cn (ring_mul r a b)) (ring_mul r dj e) =
            ring_mul r (ring_mul r cn dj) a`,
    REPEAT STRIP_TAC THEN RING_TAC)
  and split_lemma = prove
   (`!r cn d0 a s:A.
        cn IN ring_carrier r /\ d0 IN ring_carrier r /\ a IN ring_carrier r /\
        s IN ring_carrier r /\
        ring_add r (ring_mul r (ring_mul r cn d0) a) s = ring_mul r cn a
        ==> s = ring_mul r (ring_sub r (ring_1 r) d0) (ring_mul r cn a)`,
    REPEAT STRIP_TAC THEN RING_TAC)
  and term1_lemma = prove
   (`!r w u ci e xi:A.
        w IN ring_carrier r /\ u IN ring_carrier r /\ ci IN ring_carrier r /\
        e IN ring_carrier r /\ xi IN ring_carrier r
        ==> ring_mul r (ring_mul r w (ring_add r (ring_mul r u ci) e)) xi =
            ring_mul r w (ring_add r (ring_mul r u (ring_mul r ci xi))
                                     (ring_mul r e xi))`,
    REPEAT STRIP_TAC THEN RING_TAC)
  and term0_lemma = prove
   (`!r w u ci xi:A.
        w IN ring_carrier r /\ u IN ring_carrier r /\ ci IN ring_carrier r /\
        xi IN ring_carrier r
        ==> ring_mul r (ring_mul r w (ring_add r (ring_mul r u ci) (ring_0 r)))
                       xi =
            ring_mul r w (ring_add r (ring_mul r u (ring_mul r ci xi))
                                     (ring_0 r))`,
    REPEAT STRIP_TAC THEN RING_TAC)
  and final_lemma = prove
   (`!r w u s cx:A.
        w IN ring_carrier r /\ u IN ring_carrier r /\ s IN ring_carrier r /\
        cx IN ring_carrier r /\
        ring_mul r w u = ring_1 r /\ ring_add r s cx = ring_1 r
        ==> ring_mul r w (ring_add r (ring_mul r u s) (ring_mul r u cx)) =
            ring_1 r`,
    REPEAT STRIP_TAC THEN RING_TAC) in
  let reduce_lemma = prove
   (`!k r m x y (c:num->A) d n q.
        field k /\ r subring_of k /\ ring_ideal (subring_generated k r) m /\
        (!z. z IN r /\ ~(z IN m) ==> ring_inv k z IN r) /\ ~(ring_1 k IN m) /\
        x IN ring_carrier k /\ y IN ring_carrier k /\
        ring_mul k x y = ring_1 k /\
        (!i. c i IN m) /\ (!j. d j IN m) /\
        ring_sum k (0..n) (\i. ring_mul k (c i) (ring_pow k x i)) = ring_1 k /\
        ring_sum k (0..q) (\j. ring_mul k (d j) (ring_pow k y j)) = ring_1 k /\
        q <= n
        ==> ~(n = 0) /\
            ?c'. (!i. c' i IN m) /\
                 ring_sum k (0..n-1) (\i. ring_mul k (c' i) (ring_pow k x i)) =
                 ring_1 k`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    SUBGOAL_THEN `ring_carrier(subring_generated k r) = (r:A->bool)`
    ASSUME_TAC THENL
     [ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING]; ALL_TAC] THEN
    UNDISCH_TAC `ring_ideal (subring_generated k r) (m:A->bool)` THEN
    ASM_REWRITE_TAC[ring_ideal; CONJUNCT2 SUBRING_GENERATED] THEN STRIP_TAC THEN
    UNDISCH_TAC `(r:A->bool) subring_of k` THEN
    REWRITE_TAC[subring_of] THEN STRIP_TAC THEN
    SUBGOAL_THEN `!u:A. u IN m ==> u IN r /\ u IN ring_carrier k`
    ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `~(q = 0)` ASSUME_TAC THENL
     [DISCH_THEN SUBST_ALL_TAC THEN
      UNDISCH_TAC
       `ring_sum k (0..0) (\j. ring_mul k (d j) (ring_pow k (y:A) j)) =
        ring_1 k` THEN
      REWRITE_TAC[RING_SUM_CLAUSES_NUMSEG; ring_pow] THEN
      ASM_SIMP_TAC[RING_MUL_RID; RING_MUL; RING_1] THEN ASM_MESON_TAC[];
      ALL_TAC] THEN
    CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    ABBREV_TAC `u = ring_sub k (ring_1 k) ((d:num->A) 0)` THEN
    SUBGOAL_THEN `(u:A) IN r /\ ~(u IN m)` STRIP_ASSUME_TAC THENL
     [SUBGOAL_THEN `(d:num->A) 0 IN r /\ d 0 IN ring_carrier k`
      STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
      EXPAND_TAC "u" THEN REWRITE_TAC[ring_sub] THEN CONJ_TAC THENL
       [ASM_MESON_TAC[]; DISCH_TAC] THEN
      UNDISCH_TAC `~(ring_1 k IN (m:A->bool))` THEN REWRITE_TAC[] THEN
      SUBGOAL_THEN
       `ring_1 k = ring_add k (ring_add k (ring_1 k) (ring_neg k (d 0)))
                              ((d:num->A) 0)`
      SUBST1_TAC THENL
       [ASM_SIMP_TAC[GSYM RING_ADD_ASSOC; RING_ADD_LNEG; RING_ADD_RZERO;
                     RING_NEG; RING_1];
        ASM_MESON_TAC[]];
      ALL_TAC] THEN
    SUBGOAL_THEN `(u:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[SUBSET]; ALL_TAC] THEN
    SUBGOAL_THEN `~(u:A = ring_0 k)` ASSUME_TAC THENL
     [DISCH_THEN SUBST_ALL_TAC THEN ASM_MESON_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `ring_inv k (u:A) IN r` ASSUME_TAC THENL
     [ASM_MESON_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `ring_mul k (ring_inv k u) (u:A) = ring_1 k` ASSUME_TAC THENL
     [ASM_SIMP_TAC[FIELD_MUL_LINV]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!j. ring_mul k (ring_pow k x j) (ring_pow k (y:A) j) = ring_1 k`
    ASSUME_TAC THENL
     [ASM_SIMP_TAC[GSYM RING_MUL_POW; RING_POW_ONE]; ALL_TAC] THEN
    SUBGOAL_THEN `(c:num->A) n IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum k (0..q)
        (\j. ring_mul k (ring_mul k ((c:num->A) n) (d j))
                        (ring_pow k x (n - j))) =
      ring_mul k (c n) (ring_pow k x n)`
    ASSUME_TAC THENL
     [TRANS_TAC EQ_TRANS
       `ring_mul k (ring_mul k ((c:num->A) n) (ring_pow k x n))
                   (ring_sum k (0..q)
                      (\j. ring_mul k (d j) (ring_pow k (y:A) j)))` THEN
      CONJ_TAC THENL
       [ALL_TAC;
        ASM_REWRITE_TAC[] THEN MATCH_MP_TAC RING_MUL_RID THEN
        ASM_MESON_TAC[RING_MUL; RING_POW]] THEN
      ASM_SIMP_TAC[GSYM RING_SUM_LMUL; FINITE_NUMSEG; RING_MUL; RING_POW] THEN
      MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `j:num` THEN
      REWRITE_TAC[IN_NUMSEG] THEN STRIP_TAC THEN
      SUBGOAL_THEN `(d:num->A) j IN ring_carrier k` ASSUME_TAC THENL
       [ASM_MESON_TAC[]; ALL_TAC] THEN
      SUBGOAL_THEN
       `ring_pow k x n =
        ring_mul k (ring_pow k x (n - j)) (ring_pow k (x:A) j)`
      SUBST1_TAC THENL
       [ASM_SIMP_TAC[GSYM RING_POW_ADD] THEN AP_TERM_TAC THEN ASM_ARITH_TAC;
        ALL_TAC] THEN
      CONV_TAC SYM_CONV THEN MATCH_MP_TAC mul_lemma THEN
      ASM_SIMP_TAC[RING_POW];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_add k
       (ring_mul k (ring_mul k ((c:num->A) n) (d 0)) (ring_pow k x n))
       (ring_sum k (1..q)
         (\j. ring_mul k (ring_mul k (c n) (d j)) (ring_pow k x (n - j)))) =
      ring_mul k (c n) (ring_pow k x n)`
    ASSUME_TAC THENL
     [UNDISCH_TAC
       `ring_sum k (0..q)
         (\j. ring_mul k (ring_mul k ((c:num->A) n) (d j))
                         (ring_pow k x (n - j))) =
        ring_mul k (c n) (ring_pow k x n)` THEN
      DISCH_THEN(fun th -> GEN_REWRITE_TAC RAND_CONV [SYM th]) THEN
      CONV_TAC SYM_CONV THEN
      MP_TAC(ISPECL [`k:A ring`;
                     `\j. ring_mul k (ring_mul k ((c:num->A) n) (d j))
                                     (ring_pow k x (n - j))`;
                     `0`; `q:num`] RING_SUM_CLAUSES_LEFT) THEN
      REWRITE_TAC[LE_0; ADD_CLAUSES; SUB_0] THEN
      SUBGOAL_THEN `(d:num->A) 0 IN ring_carrier k` ASSUME_TAC THENL
       [ASM_MESON_TAC[]; ALL_TAC] THEN
      ASM_SIMP_TAC[RING_MUL; RING_POW];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum k (1..q)
        (\j. ring_mul k (ring_mul k ((c:num->A) n) (d j))
                        (ring_pow k x (n - j))) =
      ring_mul k u (ring_mul k (c n) (ring_pow k x n))`
    ASSUME_TAC THENL
     [EXPAND_TAC "u" THEN MATCH_MP_TAC split_lemma THEN
      ASM_SIMP_TAC[RING_SUM; RING_POW] THEN ASM_MESON_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum k (0..n-1)
        (\i. if n <= i + q
             then ring_mul k (ring_mul k ((c:num->A) n) (d (n - i)))
                             (ring_pow k x i)
             else ring_0 k) =
      ring_mul k u (ring_mul k (c n) (ring_pow k x n))`
    ASSUME_TAC THENL
     [UNDISCH_TAC
       `ring_sum k (1..q)
         (\j. ring_mul k (ring_mul k ((c:num->A) n) (d j))
                         (ring_pow k x (n - j))) =
        ring_mul k u (ring_mul k (c n) (ring_pow k x n))` THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      REWRITE_TAC[GSYM RING_SUM_RESTRICT_SET] THEN
      MATCH_MP_TAC RING_SUM_EQ_GENERAL_INVERSES THEN
      MAP_EVERY EXISTS_TAC [`\i:num. n - i`; `\j:num. n - j`] THEN
      REWRITE_TAC[IN_ELIM_THM; IN_NUMSEG] THEN
      CONJ_TAC THEN X_GEN_TAC `i:num` THEN STRIP_TAC THENL
       [ASM_ARITH_TAC;
        SUBGOAL_THEN `n - (n - i) = i:num` SUBST1_TAC THENL
         [ASM_ARITH_TAC; REWRITE_TAC[] THEN ASM_ARITH_TAC]];
      ALL_TAC] THEN
    EXISTS_TAC
     `\i. ring_mul k (ring_inv k u)
           (ring_add k (ring_mul k u ((c:num->A) i))
              (if n <= i + q then ring_mul k (c n) (d (n - i))
               else ring_0 k))` THEN
    REWRITE_TAC[] THEN CONJ_TAC THENL
     [X_GEN_TAC `i:num` THEN
      MATCH_MP_TAC(ASSUME
       `!x y:A. x IN r /\ y IN m ==> ring_mul k x y IN m`) THEN
      ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC(ASSUME
       `!x y:A. x IN m /\ y IN m ==> ring_add k x y IN m`) THEN
      CONJ_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
      COND_CASES_TAC THEN ASM_MESON_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_add k (ring_sum k (0..n-1)
                    (\i. ring_mul k ((c:num->A) i) (ring_pow k x i)))
                 (ring_mul k (c n) (ring_pow k x n)) = ring_1 k`
    ASSUME_TAC THENL
     [UNDISCH_TAC
       `ring_sum k (0..n) (\i. ring_mul k ((c:num->A) i) (ring_pow k x i)) =
        ring_1 k` THEN
      MP_TAC(ISPECL [`k:A ring`;
                     `\i. ring_mul k ((c:num->A) i) (ring_pow k x i)`;
                     `0`; `n:num`] RING_SUM_CLAUSES_RIGHT) THEN
      ANTS_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
      ASM_SIMP_TAC[RING_MUL; RING_POW];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `(!i. (c:num->A) i IN ring_carrier k) /\
      (!j. (d:num->A) j IN ring_carrier k)`
    STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!i. (if n <= i + q
           then ring_mul k (ring_mul k ((c:num->A) n) (d (n - i)))
                           (ring_pow k x i)
           else ring_0 k) IN ring_carrier k`
    ASSUME_TAC THENL
     [GEN_TAC THEN COND_CASES_TAC THEN
      ASM_SIMP_TAC[RING_0; RING_MUL; RING_POW];
      ALL_TAC] THEN
    SUBGOAL_THEN `ring_inv k (u:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[SUBSET]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!i. ring_mul k ((c:num->A) i) (ring_pow k x i) IN ring_carrier k`
    ASSUME_TAC THENL [ASM_SIMP_TAC[RING_MUL; RING_POW]; ALL_TAC] THEN
    TRANS_TAC EQ_TRANS
     `ring_sum k (0..n-1)
       (\i. ring_mul k (ring_inv k u)
             (ring_add k (ring_mul k u (ring_mul k ((c:num->A) i)
                                                   (ring_pow k x i)))
                (if n <= i + q
                 then ring_mul k (ring_mul k (c n) (d (n - i)))
                                 (ring_pow k x i)
                 else ring_0 k)))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN DISCH_TAC THEN
      REWRITE_TAC[] THEN COND_CASES_TAC THEN REWRITE_TAC[] THENL
       [MATCH_MP_TAC term1_lemma; MATCH_MP_TAC term0_lemma] THEN
      ASM_SIMP_TAC[RING_POW; RING_MUL];
      ALL_TAC] THEN
    ASM_SIMP_TAC[RING_SUM_LMUL; RING_SUM_ADD; FINITE_NUMSEG; RING_MUL;
                 RING_POW; RING_ADD] THEN
    MATCH_MP_TAC final_lemma THEN
    ASM_SIMP_TAC[RING_SUM; RING_MUL; RING_POW]) in
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `ring_inv k (x:A) IN ring_carrier k /\
    ring_mul k x (ring_inv k x) = ring_1 k /\
    ring_mul k (ring_inv k x) x = ring_1 k`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_INV; FIELD_MUL_RINV; FIELD_MUL_LINV]; ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_ADJOIN_EXPLICIT] THEN
  REWRITE_TAC[TAUT `~p \/ ~q <=> ~(p /\ q)`] THEN
  ABBREV_TAC `y = ring_inv k (x:A)` THEN
  ONCE_REWRITE_TAC[EQ_SYM_EQ] THEN
  SUBGOAL_THEN
   `!N n q (c:num->A) d.
        n + q = N /\ (!i. c i IN m) /\ (!j. d j IN m) /\
        ring_sum k (0..n) (\i. ring_mul k (c i) (ring_pow k x i)) = ring_1 k /\
        ring_sum k (0..q) (\j. ring_mul k (d j) (ring_pow k y j)) = ring_1 k
        ==> F`
  (fun th -> MESON_TAC[th]) THEN
