(* ------------------------------------------------------------------------- *)
(* Valuation rings. Intrinsically (Cohn, Matsumura section 10), an integral  *)
(* domain in which any two elements are comparable under divisibility; for   *)
(* a subring b of a field k (Atiyah-Macdonald chapter 5), every nonzero x    *)
(* of k has x or 1/x in b.                                                   *)
(* ------------------------------------------------------------------------- *)

let valuation_ring = new_definition
 `valuation_ring (r:A ring) <=>
        integral_domain r /\
        !a b. a IN ring_carrier r /\ b IN ring_carrier r
              ==> ring_divides r a b \/ ring_divides r b a`;;

let valuation_subring = new_definition
 `valuation_subring (k:A ring) (b:A->bool) <=>
        field k /\ b subring_of k /\
        !x. x IN ring_carrier k /\ ~(x = ring_0 k)
            ==> x IN b \/ ring_inv k x IN b`;;

let VALUATION_RING_IMP_INTEGRAL_DOMAIN = prove
 (`!r:A ring. valuation_ring r ==> integral_domain r`,
  SIMP_TAC[valuation_ring]);;

(* ------------------------------------------------------------------------- *)
(* The ideals of a valuation ring are totally ordered, so it is local, and   *)
(* it is integrally closed. Quotients by primes are again valuation rings.   *)
(* ------------------------------------------------------------------------- *)

let VALUATION_RING_IDEALS_TOTALLY_ORDERED = prove
 (`!r i j:A->bool.
        valuation_ring r /\ ring_ideal r i /\ ring_ideal r j
        ==> i SUBSET j \/ j SUBSET i`,
  REWRITE_TAC[valuation_ring] THEN REPEAT STRIP_TAC THEN
  REWRITE_TAC[SET_RULE
   `s SUBSET t \/ t SUBSET s <=>
    ~(?a b:A. a IN s /\ ~(a IN t) /\ b IN t /\ ~(b IN s))`] THEN
  STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`a:A`; `b:A`]) THEN
  ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET; ring_divides;
                IN_RING_IDEAL_RMUL]);;

let VALUATION_RING_IMP_LOCAL = prove
 (`!r:A ring. valuation_ring r ==> local_ring r`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[local_ring; EXISTS_UNIQUE] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP VALUATION_RING_IMP_INTEGRAL_DOMAIN) THEN
  MP_TAC(ISPEC `r:A ring` MAXIMAL_IDEAL_EXISTS) THEN
  ASM_SIMP_TAC[INTEGRAL_DOMAIN_IMP_NONTRIVIAL_RING] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `m:A->bool` THEN DISCH_TAC THEN
  ASM_REWRITE_TAC[] THEN X_GEN_TAC `n:A->bool` THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `n:A->bool`]
    VALUATION_RING_IDEALS_TOTALLY_ORDERED) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_RING_IDEAL] THEN
  ASM_MESON_TAC[maximal_ideal; PSUBSET; SUBSET_ANTISYM]);;

let VALUATION_RING_IMP_INTEGRALLY_CLOSED = prove
 (`!r:A ring. valuation_ring r ==> integrally_closed r`,
  GEN_TAC THEN REWRITE_TAC[valuation_ring; INTEGRALLY_CLOSED_ALT] THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MAP_EVERY X_GEN_TAC [`a:A`; `b:A`; `c:num->A`; `n:num`] THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`a:A`; `b:A`]) THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC(TAUT `(p ==> q) ==> p \/ q ==> q`) THEN
  GEN_REWRITE_TAC LAND_CONV [ring_divides] THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `d:A` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM SUBST_ALL_TAC THEN
  ASM_CASES_TAC `a:A = ring_0 r` THENL
   [ASM_SIMP_TAC[RING_DIVIDES_0; RING_MUL; RING_0]; ALL_TAC] THEN
  ABBREV_TAC
   `s = ring_sum r {i | i < n}
         (\i. ring_mul r (c i) (ring_pow r (d:A) (n - i)))` THEN
  SUBGOAL_THEN `(s:A) IN ring_carrier r` ASSUME_TAC THENL
   [EXPAND_TAC "s" THEN REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sum r {i | i < n}
     (\i. ring_mul r (c i) (ring_mul r (ring_pow r a i)
                    (ring_pow r (ring_mul r a d) (n - i)))) =
    ring_mul r (ring_pow r a n) (s:A)`
  ASSUME_TAC THENL
   [EXPAND_TAC "s" THEN
    W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_LMUL o rand o snd) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[RING_POW; FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[RING_POW];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    SUBGOAL_THEN `(c:num->A) i IN ring_carrier r` ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_MUL_POW] THEN
    SUBGOAL_THEN
     `ring_pow r (a:A) n = ring_mul r (ring_pow r a i) (ring_pow r a (n - i))`
    SUBST1_TAC THENL
     [ASM_SIMP_TAC[GSYM RING_POW_ADD] THEN AP_TERM_TAC THEN ASM_ARITH_TAC;
      ALL_TAC] THEN
    ASM_SIMP_TAC[RING_POW; RING_RULE
     `ring_mul r c (ring_mul r x (ring_mul r y z)) =
      ring_mul r (ring_mul r x y) (ring_mul r c (z:A))`];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_add r (ring_1 r) (s:A) = ring_0 r` ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o check (fun th ->
      is_eq(concl th) && rand(concl th) = `ring_0 r:A`)) THEN
    ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `ring_pow r (a:A) n`;
                   `ring_add r (ring_1 r) (s:A)`]
      INTEGRAL_DOMAIN_MUL_EQ_0) THEN
    ASM_SIMP_TAC[RING_POW; RING_ADD; RING_1; INTEGRAL_DOMAIN_POW_EQ_0;
                 RING_RULE
     `ring_mul r x (ring_add r (ring_1 r) y) =
      ring_add r x (ring_mul r x (y:A))`];
    ALL_TAC] THEN
  ASM_CASES_TAC `n = 0` THENL
   [UNDISCH_TAC `ring_add r (ring_1 r) (s:A) = ring_0 r` THEN
    EXPAND_TAC "s" THEN
    REWRITE_TAC[ASSUME `n = 0`; LT; EMPTY_GSPEC; RING_SUM_CLAUSES] THEN
    ASM_SIMP_TAC[RING_ADD_RZERO; RING_1; GSYM TRIVIAL_RING_10;
                 INTEGRAL_DOMAIN_IMP_NONTRIVIAL_RING];
    ALL_TAC] THEN
  ABBREV_TAC
   `t = ring_sum r {i | i < n}
         (\i. ring_mul r (c i) (ring_pow r (d:A) (n - 1 - i)))` THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r /\ s = ring_mul r d t`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "t" THEN REWRITE_TAC[RING_SUM] THEN EXPAND_TAC "s" THEN
    W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_LMUL o rand o snd) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[RING_POW];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    SUBGOAL_THEN `(c:num->A) i IN ring_carrier r` ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `n - i = SUC(n - 1 - i)` SUBST1_TAC THENL
     [ASM_ARITH_TAC; REWRITE_TAC[ring_pow]] THEN
    ASM_SIMP_TAC[RING_POW; RING_RULE
     `ring_mul r c (ring_mul r d x) = ring_mul r d (ring_mul r c (x:A))`];
    ALL_TAC] THEN
  REWRITE_TAC[ring_divides] THEN ASM_SIMP_TAC[RING_MUL] THEN
  EXISTS_TAC `ring_neg r (t:A)` THEN ASM_SIMP_TAC[RING_NEG] THEN
  UNDISCH_TAC `ring_add r (ring_1 r) (s:A) = ring_0 r` THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(RING_RULE
   `ring_add r (ring_1 r) (ring_mul r d t) = ring_0 r
    ==> a = ring_mul r (ring_mul r a d) (ring_neg r (t:A))`) THEN
  ASM_SIMP_TAC[]);;

let VALUATION_RING_QUOTIENT_RING = prove
 (`!r p:A->bool.
        valuation_ring r /\ prime_ideal r p
        ==> valuation_ring (quotient_ring r p)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[valuation_ring] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  ASM_SIMP_TAC[INTEGRAL_DOMAIN_QUOTIENT_RING; QUOTIENT_RING_CARRIER] THEN
  REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM; FORALL_IN_GSPEC] THEN
  X_GEN_TAC `a:A` THEN DISCH_TAC THEN X_GEN_TAC `b:A` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`a:A`; `b:A`]) THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC MONO_OR THEN CONJ_TAC THEN DISCH_TAC THEN
  MATCH_MP_TAC RING_DIVIDES_HOMOMORPHIC_IMAGE THEN EXISTS_TAC `r:A ring` THEN
  ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET]);;

(* ------------------------------------------------------------------------- *)
(* Valuation subrings of a field (A-M 5.18): they are valuation rings, so    *)
(* local, with the nonunits as maximal ideal; every subring above one is     *)
(* again one; and they are integrally closed in the field.                   *)
(* ------------------------------------------------------------------------- *)

let VALUATION_SUBRING_SUPERSET = prove
 (`!k b c:A->bool.
        valuation_subring k b /\ b SUBSET c /\ c subring_of k
        ==> valuation_subring k c`,
  REWRITE_TAC[valuation_subring] THEN SET_TAC[]);;

let VALUATION_SUBRING_IMP_VALUATION_RING = prove
 (`!k b:A->bool.
        valuation_subring k b ==> valuation_ring (subring_generated k b)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[valuation_subring; valuation_ring] THEN
  STRIP_TAC THEN CONJ_TAC THENL
   [ASM_SIMP_TAC[INTEGRAL_DOMAIN_SUBRING_GENERATED; FIELD_IMP_INTEGRAL_DOMAIN];
    ALL_TAC] THEN
  ASM_SIMP_TAC[ring_divides; CARRIER_SUBRING_GENERATED_SUBRING;
               CONJUNCT2 SUBRING_GENERATED] THEN
  MAP_EVERY X_GEN_TAC [`x:A`; `y:A`] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k /\ y IN ring_carrier k /\
                ring_0 k IN b`
  STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[subring_of; SUBSET]; ALL_TAC] THEN
  ASM_CASES_TAC `x:A = ring_0 k` THENL
   [DISJ2_TAC THEN EXISTS_TAC `ring_0 k:A` THEN ASM_SIMP_TAC[RING_MUL_RZERO];
    ALL_TAC] THEN
  ASM_CASES_TAC `y:A = ring_0 k` THENL
   [DISJ1_TAC THEN EXISTS_TAC `ring_0 k:A` THEN ASM_SIMP_TAC[RING_MUL_RZERO];
    ALL_TAC] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `ring_mul k y (ring_inv k x):A`) THEN
  ASM_SIMP_TAC[RING_MUL; RING_INV; FIELD_IMP_INTEGRAL_DOMAIN;
               INTEGRAL_DOMAIN_MUL_EQ_0; FIELD_INV_EQ_0] THEN
  SUBGOAL_THEN `ring_unit k (x:A) /\ ring_unit k (y:A)` STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[FIELD_UNIT]; ALL_TAC] THEN
  ASM_SIMP_TAC[RING_INV_MUL; RING_INV; RING_INV_INV] THEN
  STRIP_TAC THENL
   [DISJ1_TAC THEN EXISTS_TAC `ring_mul k y (ring_inv k x):A` THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(RING_RULE
     `ring_mul k x (ring_inv k x) = ring_1 k
      ==> y = ring_mul k x (ring_mul k y (ring_inv k (x:A)))`) THEN
    ASM_SIMP_TAC[RING_INV; FIELD_MUL_RINV];
    DISJ2_TAC THEN EXISTS_TAC `ring_mul k (ring_inv k y) x:A` THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(RING_RULE
     `ring_mul k y (ring_inv k y) = ring_1 k
      ==> x = ring_mul k y (ring_mul k (ring_inv k y) (x:A))`) THEN
    ASM_SIMP_TAC[RING_INV; FIELD_MUL_RINV]]);;

let VALUATION_SUBRING_IMP_LOCAL = prove
 (`!k b:A->bool.
        valuation_subring k b ==> local_ring (subring_generated k b)`,
  SIMP_TAC[VALUATION_SUBRING_IMP_VALUATION_RING; VALUATION_RING_IMP_LOCAL]);;

let VALUATION_SUBRING_MAXIMAL_IDEAL = prove
 (`!k b m:A->bool.
        valuation_subring k b
        ==> (maximal_ideal (subring_generated k b) m <=>
             m = {x | x IN b /\ (x = ring_0 k \/ ~(ring_inv k x IN b))})`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring]) THEN
  ASM_SIMP_TAC[LOCAL_RING_MAXIMAL_IDEAL_NONUNITS; VALUATION_SUBRING_IMP_LOCAL;
               CARRIER_SUBRING_GENERATED_SUBRING] THEN
  AP_TERM_TAC THEN GEN_REWRITE_TAC I [EXTENSION] THEN
  REWRITE_TAC[IN_ELIM_THM] THEN X_GEN_TAC `x:A` THEN
  ASM_CASES_TAC `(x:A) IN b` THEN ASM_SIMP_TAC[RING_UNIT_SUBRING_OF_FIELD] THEN
  CONV_TAC TAUT);;

let VALUATION_SUBRING_INV_MAXIMAL_IDEAL = prove
 (`!(k:A ring) v m x.
        valuation_subring k v /\ maximal_ideal (subring_generated k v) m /\
        x IN ring_carrier k
        ==> (x IN v <=> x = ring_0 k \/ ~(ring_inv k x IN m))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `v:A->bool`; `m:A->bool`]
    VALUATION_SUBRING_MAXIMAL_IDEAL) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring]) THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_CASES_TAC `x:A = ring_0 k` THEN ASM_REWRITE_TAC[] THENL
   [ASM_MESON_TAC[subring_of]; ALL_TAC] THEN
  SUBGOAL_THEN
   `~(ring_inv k (x:A) = ring_0 k) /\ ring_inv k (ring_inv k x) = x`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[FIELD_INV_EQ_0] THEN MATCH_MP_TAC RING_INV_INV THEN
    ASM_SIMP_TAC[FIELD_UNIT];
    ASM_REWRITE_TAC[]] THEN
  ASM_MESON_TAC[]);;

let VALUATION_SUBRING_SUBFIELD = prove
 (`!(k:A ring) v m l.
        valuation_subring k v /\ maximal_ideal (subring_generated k v) m /\
        l subfield_of k
        ==> valuation_subring (subfield_generated k l) (v INTER l) /\
            maximal_ideal
             (subring_generated (subfield_generated k l) (v INTER l))
             (m INTER l)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring]) THEN
  SUBGOAL_THEN
   `field(subfield_generated k l) /\
    ring_carrier(subfield_generated k l) = (l:A->bool) /\
    l SUBSET ring_carrier k /\
    !x:A. x IN l /\ ~(x = ring_0 k)
          ==> ring_inv (subfield_generated k l) x = ring_inv k x /\
              ring_inv k x IN l`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; CARRIER_SUBFIELD_GENERATED_SUBFIELD;
                 IN_SUBFIELD_INV; SUBFIELD_OF_IMP_SUBSET] THEN
    REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_INV_SUBFIELD_GENERATED THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
                 CARRIER_SUBFIELD_GENERATED_SUBFIELD];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [ASM_REWRITE_TAC[valuation_subring; SUBFIELD_GENERATED] THEN
    CONJ_TAC THENL
     [UNDISCH_TAC `(v:A->bool) subring_of k` THEN
      FIRST_ASSUM(MP_TAC o MATCH_MP SUBFIELD_IMP_SUBRING_OF) THEN
      ASM_REWRITE_TAC[subring_of; SUBFIELD_GENERATED] THEN SET_TAC[];
      ASM_SIMP_TAC[IN_INTER] THEN ASM SET_TAC[]];
    DISCH_TAC THEN ASM_SIMP_TAC[VALUATION_SUBRING_MAXIMAL_IDEAL] THEN
    MP_TAC(ISPECL [`k:A ring`; `v:A->bool`; `m:A->bool`]
      VALUATION_SUBRING_MAXIMAL_IDEAL) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[SUBFIELD_GENERATED; EXTENSION; IN_INTER; IN_ELIM_THM] THEN
    ASM_MESON_TAC[]]);;

let VALUATION_SUBRING_INTEGRAL_ELEMENT = prove
 (`!k b x:A.
        valuation_subring k b /\
        integral_element (subring_generated k b,k) I x
        ==> x IN b`,
  REPEAT STRIP_TAC THEN
  FIRST_X_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring]) THEN
  MP_TAC(ISPECL [`subring_generated k (b:A->bool)`; `k:A ring`; `I:A->A`;
                 `x:A`] INTEGRAL_ELEMENT_EXPLICIT) THEN
  REWRITE_TAC[I_DEF; RING_HOMOMORPHISM_INCLUSION] THEN
  REWRITE_TAC[GSYM I_DEF; I_THM] THEN ASM_REWRITE_TAC[] THEN
  ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
   (X_CHOOSE_THEN `n:num` (X_CHOOSE_THEN `c:num->A` STRIP_ASSUME_TAC))) THEN
  MATCH_MP_TAC(TAUT `(~p ==> p) ==> p`) THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `(!y:A. y IN b ==> y IN ring_carrier k) /\ ring_0 k IN b /\
    ring_1 k IN b /\ (!y:A. y IN b ==> ring_neg k y IN b) /\
    (!y z:A. y IN b /\ z IN b ==> ring_mul k y z IN b)`
  STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `(b:A->bool) subring_of k` THEN SIMP_TAC[subring_of; SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(x:A = ring_0 k)` ASSUME_TAC THENL
   [ASM_MESON_TAC[]; ALL_TAC] THEN
  ABBREV_TAC `y = ring_inv k (x:A)` THEN
  SUBGOAL_THEN `(y:A) IN b /\ ring_mul k y x = ring_1 k` STRIP_ASSUME_TAC
  THENL [ASM_MESON_TAC[FIELD_MUL_LINV]; ALL_TAC] THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `!i. i < n ==> (c:num->A) i IN ring_carrier k` ASSUME_TAC
  THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!i. ring_mul k (ring_pow k y i) (ring_pow k x i) = ring_1 k:A`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[GSYM RING_MUL_POW; RING_POW_ONE]; ALL_TAC] THEN
  ABBREV_TAC
   `t = ring_sum k {i | i < n}
         (\i. ring_mul k (c i) (ring_pow k (y:A) (n - 1 - i)))` THEN
  SUBGOAL_THEN `(t:A) IN b` ASSUME_TAC THENL
   [EXPAND_TAC "t" THEN
    MP_TAC(ISPECL [`k:A ring`; `b:A->bool`; `{i:num | i < n}`;
                   `\i. ring_mul k (c i) (ring_pow k (y:A) (n - 1 - i))`]
      RING_SUM_SUBRING_GENERATED) THEN
    REWRITE_TAC[ASSUME `(b:A->bool) subring_of k`] THEN
    SUBGOAL_THEN
     `{j | j IN {i:num | i < n} /\
           ring_mul k (c j) (ring_pow k (y:A) (n - 1 - j)) IN b} =
      {i | i < n}`
    SUBST1_TAC THENL
     [REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN X_GEN_TAC `j:num` THEN
      EQ_TAC THEN SIMP_TAC[] THEN DISCH_TAC THEN
      FIRST_ASSUM MATCH_MP_TAC THEN ASM_SIMP_TAC[] THEN
      SPEC_TAC(`n - 1 - j`,`m:num`) THEN INDUCT_TAC THEN
      ASM_SIMP_TAC[ring_pow];
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      MP_TAC(ISPECL [`subring_generated k (b:A->bool)`; `{i:num | i < n}`;
                     `\i. ring_mul k (c i) (ring_pow k (y:A) (n - 1 - i))`]
        RING_SUM) THEN
      SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING;
               ASSUME `(b:A->bool) subring_of k`]];
    ALL_TAC] THEN
  SUBGOAL_THEN `x = ring_neg k (t:A)` SUBST1_TAC THENL
   [ALL_TAC; ASM_SIMP_TAC[]] THEN
  SUBGOAL_THEN `ring_add k x (t:A) = ring_0 k` MP_TAC THENL
   [ALL_TAC;
    MP_TAC(RING_RULE `ring_add k x t = ring_0 k ==> x = ring_neg k (t:A)`) THEN
    ASM_SIMP_TAC[]] THEN
  FIRST_X_ASSUM(MP_TAC o AP_TERM `ring_mul k (ring_pow k (y:A) (n - 1))` o
    check (fun th -> is_eq(concl th) && rand(concl th) = `ring_0 k:A`)) THEN
  ASM_SIMP_TAC[RING_MUL_RZERO; RING_POW] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[RING_ADD_LDISTRIB; RING_POW; RING_SUM] THEN
  BINOP_TAC THENL
   [SUBGOAL_THEN `n = (n - 1) + 1` SUBST1_TAC THENL
     [ASM_ARITH_TAC; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_POW_ADD; RING_POW_1; ADD_SUB; RING_POW; RING_RULE
     `ring_mul k a b = ring_1 k ==> ring_mul k a (ring_mul k b x) = (x:A)`];
    ALL_TAC] THEN
  W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_LMUL o rand o snd) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[RING_POW; FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
    REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[RING_POW];
    DISCH_THEN(SUBST1_TAC o SYM)] THEN
  EXPAND_TAC "t" THEN
  MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
  SUBGOAL_THEN `ring_pow k (y:A) (n - 1) =
                ring_mul k (ring_pow k y (n - 1 - i)) (ring_pow k y i)`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[GSYM RING_POW_ADD] THEN AP_TERM_TAC THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(c:num->A) i IN ring_carrier k` ASSUME_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[RING_POW; RING_RULE
   `ring_mul k b d = ring_1 k
    ==> ring_mul k (ring_mul k a b) (ring_mul k c d) = ring_mul k c (a:A)`]);;

