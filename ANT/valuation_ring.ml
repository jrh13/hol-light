let INTEGRAL_CLOSURE_EQ_INTERS_VALUATION_SUBRINGS = prove
 (`!k a:A->bool.
        field k /\ a subring_of k
        ==> {x | integral_element (subring_generated k a,k) I x} =
            INTERS {b | valuation_subring k b /\ a SUBSET b}`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `ring_homomorphism(subring_generated k a,k) (I:A->A)`
  ASSUME_TAC THENL
   [REWRITE_TAC[I_DEF; RING_HOMOMORPHISM_INCLUSION]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_carrier(subring_generated k a) = (a:A->bool) /\
    a SUBSET ring_carrier k /\ ring_0 k IN a`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING] THEN
    UNDISCH_TAC `(a:A->bool) subring_of k` THEN SIMP_TAC[subring_of];
    ALL_TAC] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN
  REWRITE_TAC[IN_INTERS; IN_ELIM_THM] THEN
  X_GEN_TAC `x:A` THEN EQ_TAC THENL
   [DISCH_TAC THEN X_GEN_TAC `b:A->bool` THEN STRIP_TAC THEN
    MATCH_MP_TAC VALUATION_SUBRING_INTEGRAL_ELEMENT THEN
    EXISTS_TAC `k:A ring` THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC INTEGRAL_ELEMENT_OVER_SUBRING THEN
    MAP_EVERY EXISTS_TAC [`subring_generated k (a:A->bool)`; `I:A->A`] THEN
    ASM_REWRITE_TAC[IMAGE_I] THEN
    FIRST_X_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring] o
      check (fun th -> try fst(dest_const(fst(strip_comb(concl th)))) =
                            "valuation_subring" with Failure _ -> false)) THEN
    ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING];
    DISCH_TAC] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [FIRST_X_ASSUM MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[valuation_subring; CARRIER_SUBRING_OF] THEN
    REWRITE_TAC[SUBSET_REFL] THEN MESON_TAC[];
    ALL_TAC] THEN
  ASM_CASES_TAC `x:A = ring_0 k` THENL
   [MP_TAC(ISPECL [`subring_generated k (a:A->bool)`; `k:A ring`; `I:A->A`;
                   `ring_0 k:A`] INTEGRAL_ELEMENT_IMAGE) THEN
    ASM_REWRITE_TAC[I_THM];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
  ABBREV_TAC `y = ring_inv k (x:A)` THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier k /\ ~(y = ring_0 k) /\
                ring_inv k y = x`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "y" THEN
    ASM_SIMP_TAC[RING_INV; FIELD_INV_EQ_0; RING_INV_INV; FIELD_UNIT];
    ALL_TAC] THEN
  ABBREV_TAC `a' = ring_carrier(subring_generated k ((y:A) INSERT a))` THEN
  SUBGOAL_THEN
   `a' subring_of (k:A ring) /\ subring_generated k a' =
    subring_generated k ((y:A) INSERT a) /\ a SUBSET a' /\ (y:A) IN a' /\
    ~(x IN a')`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "a'" THEN
    REWRITE_TAC[SUBRING_SUBRING_GENERATED;
                SUBRING_GENERATED_BY_SUBRING_GENERATED] THEN
    REPEAT CONJ_TAC THENL
     [REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN
      MATCH_MP_TAC SUBRING_GENERATED_INC_GEN THEN
      ASM_REWRITE_TAC[IN_INSERT] THEN ASM SET_TAC[];
      MATCH_MP_TAC SUBRING_GENERATED_INC_GEN THEN
      ASM_REWRITE_TAC[IN_INSERT];
      DISCH_TAC THEN UNDISCH_TAC
       `~integral_element (subring_generated k a,k) I (x:A)` THEN
      REWRITE_TAC[] THEN MATCH_MP_TAC INTEGRAL_ELEMENT_IN_ADJOIN_INV THEN
      ASM_REWRITE_TAC[] THEN EXPAND_TAC "a'" THEN FIRST_ASSUM ACCEPT_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `~ring_unit (subring_generated k a') (y:A)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_UNIT_SUBRING_OF_FIELD]; ALL_TAC] THEN
  MP_TAC(ISPECL [`subring_generated k (a':A->bool)`;
                 `ideal_generated (subring_generated k a') {y:A}`]
    MAXIMAL_SUPERIDEAL_EXISTS) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[PROPER_IDEAL_IDEAL_GENERATED_SING;
                 CARRIER_SUBRING_GENERATED_SUBRING];
    DISCH_THEN(X_CHOOSE_THEN `m':A->bool` STRIP_ASSUME_TAC)] THEN
  SUBGOAL_THEN `(y:A) IN m'` ASSUME_TAC THENL
   [UNDISCH_TAC
     `ideal_generated (subring_generated k a') {y:A} SUBSET m'` THEN
    REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    MATCH_MP_TAC IDEAL_GENERATED_INC THEN
    ASM_SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING; IN_SING; SING_SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `a':A->bool`; `m':A->bool`]
    VALUATION_SUBRING_DOMINATES) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL];
    DISCH_THEN(X_CHOOSE_THEN `b:A->bool` (X_CHOOSE_THEN `m:A->bool`
      STRIP_ASSUME_TAC))] THEN
  SUBGOAL_THEN `(x:A) IN b /\ (y:A) IN m` STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC SUBSET_TRANS THEN EXISTS_TAC `a':A->bool` THEN
      ASM_REWRITE_TAC[];
      UNDISCH_TAC `a' INTER m = (m':A->bool)` THEN
      UNDISCH_TAC `(y:A) IN m'` THEN SET_TAC[]];
    ALL_TAC] THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [valuation_subring] o
    check (fun th -> try fst(dest_const(fst(strip_comb(concl th)))) =
                          "valuation_subring" with Failure _ -> false)) THEN
  MP_TAC(ISPECL [`subring_generated k (b:A->bool)`; `m:A->bool`;
                 `ring_1(subring_generated k b):A`]
    RING_UNIT_NOT_IN_PRIME_IDEAL) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL; RING_UNIT_1] THEN
  REWRITE_TAC[CONJUNCT2 SUBRING_GENERATED] THEN
  SUBGOAL_THEN `ring_1 k = ring_mul k (x:A) y` SUBST1_TAC THENL
   [EXPAND_TAC "y" THEN CONV_TAC SYM_CONV THEN
    MATCH_MP_TAC FIELD_MUL_RINV THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`subring_generated k (b:A->bool)`; `m:A->bool`;
                 `x:A`; `y:A`] IN_RING_IDEAL_LMUL) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_RING_IDEAL; CARRIER_SUBRING_GENERATED_SUBRING;
               CONJUNCT2 SUBRING_GENERATED]);;

(* ------------------------------------------------------------------------- *)
(* Discrete valuation rings, with DVR of ANT/dedekind_struct.ml: a local PID *)
(* that is not a field. A valuation ring is a Bezout ring, so a Noetherian   *)
(* valuation ring that is not a field is a DVR, and conversely (Matsumura    *)
(* 11.1). For a Noetherian local domain of dimension one, being a DVR is     *)
(* equivalent to being integrally closed, and to being a valuation ring      *)
(* (Atiyah-Macdonald 9.2 (i)<=>(ii), Matsumura 11.2 (1)<=>(4)). In a DVR     *)
(* whose maximal ideal is generated by q every nonzero element divides a     *)
(* power of q (DVR_DIVIDES_UNIFORMIZER_POW).                                 *)
(* ------------------------------------------------------------------------- *)

let VALUATION_RING_IMP_BEZOUT_RING = prove
 (`!r:A ring. valuation_ring r ==> bezout_ring r`,
  SUBGOAL_THEN
   `!r a b:A. b IN ring_carrier r /\ ring_divides r a b
              ==> ideal_generated r {a,b} = ideal_generated r {a}`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
     [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
      REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; INSERT_SUBSET; EMPTY_SUBSET] THEN
      CONJ_TAC THENL
       [ASM_MESON_TAC[ring_divides; IN_IDEAL_GENERATED_SELF];
        ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING]];
      MATCH_MP_TAC IDEAL_GENERATED_MONO THEN SET_TAC[]];
    ALL_TAC] THEN
  REWRITE_TAC[valuation_ring; BEZOUT_RING_2; principal_ideal] THEN
  REPEAT STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`a:A`; `b:A`]) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THENL
   [EXISTS_TAC `a:A` THEN ASM_SIMP_TAC[];
    EXISTS_TAC `b:A` THEN ONCE_REWRITE_TAC[SET_RULE `{a:A,b} = {b,a}`] THEN
    ASM_SIMP_TAC[]]);;

let DVR_IMP_VALUATION_RING = prove
 (`!r:A ring. DVR r ==> valuation_ring r`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[valuation_ring] THEN CONJ_TAC THENL
   [ASM_MESON_TAC[DVR; PID_IMP_INTEGRAL_DOMAIN]; ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`;
                 `ideal_generated r {b:A}`] DVR_IDEALS_TOTALLY_ORDERED) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
  DISCH_THEN DISJ_CASES_TAC THENL [DISJ2_TAC; DISJ1_TAC] THEN
  ASM_SIMP_TAC[GSYM IN_IDEAL_GENERATED_SING_EQ] THEN
  FIRST_X_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET]) THEN
  ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]);;

let DVR_EQ_NOETHERIAN_VALUATION_RING = prove
 (`!r:A ring. DVR r <=> valuation_ring r /\ noetherian_ring r /\ ~(field r)`,
  GEN_TAC THEN EQ_TAC THEN STRIP_TAC THENL
   [ASM_SIMP_TAC[DVR_IMP_VALUATION_RING] THEN
    ASM_MESON_TAC[DVR; PID_IMP_NOETHERIAN_RING];
    ASM_SIMP_TAC[DVR; VALUATION_RING_IMP_LOCAL; PID_EQ_NOETHERIAN_BEZOUT_DOMAIN;
                 VALUATION_RING_IMP_BEZOUT_RING;
                 VALUATION_RING_IMP_INTEGRAL_DOMAIN]]);;

let DVR_EQ_INTEGRALLY_CLOSED = prove
 (`!r:A ring.
        integral_domain r /\ noetherian_ring r /\ local_ring r /\
        ~(field r) /\
        (!p. prime_ideal r p /\ ~(p = {ring_0 r}) ==> maximal_ideal r p)
        ==> (DVR r <=> integrally_closed r) /\ (DVR r <=> valuation_ring r)`,
  REPEAT STRIP_TAC THENL
   [ASM_SIMP_TAC[DVR_IFF_LOCAL_DEDEKIND; dedekind_domain];
    ASM_SIMP_TAC[DVR_EQ_NOETHERIAN_VALUATION_RING]]);;

let DVR_DIVIDES_UNIFORMIZER_POW = prove
 (`!r (q:A) a.
        DVR r /\ maximal_ideal r (ideal_generated r {q}) /\
        q IN ring_carrier r /\ a IN ring_carrier r /\ ~(a = ring_0 r)
        ==> ?s d. d IN ring_carrier r /\ ring_mul r a d = ring_pow r q s`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {q:A}`;
                 `ideal_generated r {a:A}`] DVR_IDEAL_MAXIMAL_POW) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0] THEN
  DISCH_THEN(X_CHOOSE_TAC `n:num`) THEN
  MAP_EVERY EXISTS_TAC [`n:num`] THEN
  SUBGOAL_THEN `ring_pow r (q:A) n IN ideal_generated r {a}` MP_TAC THENL
   [ASM_SIMP_TAC[IDEAL_POW_PRINCIPAL; IN_IDEAL_GENERATED_SELF; RING_POW];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING_EQ; ring_divides] THEN
  MESON_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The valuation ring of a discrete valuation of a Dedekind domain.          *)
(* ------------------------------------------------------------------------- *)

let VALUATION_SUBRING_DEDEKIND_VALUATION = prove
 (`!r k (h:A->B) P.
        dedekind_domain r /\ field_of_fractions (r,k) h /\
        prime_ideal r P /\ ~(P = {ring_0 r})
        ==> valuation_subring k
             {x | x IN ring_carrier k /\
                  (x = ring_0 k \/ &0 <= dedekind_valuation (r,k) h P x)}`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_of_fractions]) THEN
  REWRITE_TAC[valuation_subring] THEN
  ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `k:B ring`; `h:A->B`; `P:A->bool`]
      DEDEKIND_VALUATION_RING_LOCALIZATION) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `g:(A#A->bool)->B` STRIP_ASSUME_TAC) THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
    MP_TAC(ISPECL [`ring_localization r (ring_carrier r DIFF P:A->bool)`;
                   `k:B ring`; `g:(A#A->bool)->B`] SUBRING_RING_IMAGE) THEN
    ASM_SIMP_TAC[RING_MONOMORPHISM_IMP_HOMOMORPHISM; ring_image];
    ALL_TAC] THEN
  X_GEN_TAC `x:B` THEN STRIP_TAC THEN REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_SIMP_TAC[RING_INV; FIELD_INV_EQ_0; DEDEKIND_VALUATION_INV] THEN
  INT_ARITH_TAC);;
