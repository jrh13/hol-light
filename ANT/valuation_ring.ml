(* ========================================================================= *)
(* Valuation rings, intrinsically and as valuation subrings of a field; the  *)
(* Chevalley extension theorem, the integral closure as an intersection of   *)
(* valuation subrings, and discrete valuation rings. No module theory is     *)
(* used.                                                                     *)
(*                                                                           *)
(*   valuation_ring r      <=> r is an integral domain in which of any two   *)
(*                             elements one divides the other                *)
(*   valuation_subring k b <=> k is a field and b a subring of k with        *)
(*                             x IN b or 1 / x IN b for nonzero x in k       *)
(*                                                                           *)
(* Main results: a valuation ring is local and integrally closed, its ideals *)
(* are totally ordered, and its quotients by primes are valuation rings; a   *)
(* valuation subring is a valuation ring whose maximal ideal consists of the *)
(* elements with no inverse in it (VALUATION_SUBRING_MAXIMAL_IDEAL), every   *)
(* subring of k above it is one, and it is integrally closed in k            *)
(* (VALUATION_SUBRING_INTEGRAL_CLOSURE). Chevalley: a prime p of a subring a *)
(* of k is the trace on a of the maximal ideal of some valuation subring     *)
(* containing a (VALUATION_SUBRING_DOMINATES; Matsumura 10.2, A-M 5.21), so  *)
(* the integral closure of a in k is the intersection of the valuation       *)
(* subrings containing a (INTEGRAL_CLOSURE_EQ_INTERS_VALUATION_SUBRINGS, A-M *)
(* 5.22); a homomorphism of a subring of k into an algebraically closed      *)
(* field extends to a valuation subring of k with its maximal ideal as       *)
(* kernel (VALUATION_SUBRING_EXTEND_HOMOMORPHISM, A-M 5.21). A DVR is a      *)
(* Noetherian valuation ring that is not a field and conversely              *)
(* (DVR_EQ_NOETHERIAN_VALUATION_RING, Matsumura 11.1); for a Noetherian      *)
(* local domain of dimension one, not a field, being a DVR is equivalent to  *)
(* being integrally closed and to being a valuation ring                     *)
(* (DVR_EQ_INTEGRALLY_CLOSED, A-M 9.2). The valuation ring of a discrete     *)
(* valuation of ANT/dedekind_valuation.ml is a valuation subring             *)
(* (VALUATION_SUBRING_DEDEKIND_VALUATION).                                   *)
(*                                                                           *)
(* Route for the Chevalley theorem: the Zorn lemma on the subrings R of k    *)
(* containing a such that no element of a outside p lies in the ideal        *)
(* generated by p in R. A maximal R is local, with a maximal ideal m over p, *)
(* and for x NOTIN R some t of a outside p lies in pR[x], so 1 is in mR[x].  *)
(* By A-M 5.23 (IDEAL_GENERATED_ADJOIN_OR_INV: for such a local R, mR[x] or  *)
(* mR[1/x] is a proper ideal; of two relations 1 = sum c_i x^i and 1 = sum   *)
(* d_j x^(-j) with all coefficients in m, the one of larger degree can be    *)
(* shortened) mR[1/x] is proper, so R[1/x] is in the family and 1/x IN R.    *)
(* The ideals of R[x] are described by polynomials in x                      *)
(* (IDEAL_GENERATED_ADJOIN_EXPLICIT), and this replaces lying over. For the  *)
(* homomorphism form, the Zorn lemma on the graphs of extensions of f; a     *)
(* maximal one is defined on a local ring s, and adjoining y or 1/y (A-M     *)
(* 5.23) extends it (RING_HOMOMORPHISM_ADJOIN_ROOT): the relations of y over *)
(* s form an ideal of s[X], whose images under g have a common root in l     *)
(* unless one of them is a nonzero constant (RING_IDEAL_POLY_COMMON_ROOT of  *)
(* Library/fieldtheory.ml), and such an image would put 1 in the ideal of    *)
(* s[y] generated by the kernel of g (IDEAL_GENERATED_ADJOIN_ROOT_UNIT of    *)
(* Library/ringtheory.ml).                                                   *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (the Zorn lemma, Bezout rings and PIDs,       *)
(* IDEAL_GENERATED_ADJOIN_ROOT_UNIT), Library/fieldtheory.ml                 *)
(* (RING_IDEAL_POLY_COMMON_ROOT), ANT/integral.ml (integral_element,         *)
(* INTEGRALLY_CLOSED_ALT), ANT/dedekind_struct.ml (DVR,                      *)
(* DVR_IFF_LOCAL_DEDEKIND) and ANT/dedekind_valuation.ml (for the last       *)
(* result).                                                                  *)
(* ========================================================================= *)

