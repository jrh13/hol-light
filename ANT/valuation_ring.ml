     [EXPAND_TAC "G'" THEN MATCH_MP_TAC SUBRING_OF_HOMOMORPHIC_IMAGE THEN
      EXISTS_TAC `poly_ring (subring_generated k (s:A->bool)) (:1)` THEN
      REWRITE_TAC[CARRIER_SUBRING_OF; RING_HOMOMORPHISM_PAIRED; ETA_AX] THEN
      CONJ_TAC THEN MATCH_MP_TAC RING_HOMOMORPHISM_POLY_EXTEND THEN
      ASM_REWRITE_TAC[RING_HOMOMORPHISM_INCLUSION; IN_UNIV];
      ALL_TAC] THEN
    SUBGOAL_THEN `(G:A#B->bool) SUBSET G'` ASSUME_TAC THENL
     [REWRITE_TAC[SUBSET; FORALL_PAIR_THM] THEN
      MAP_EVERY X_GEN_TAC [`x:A`; `z:B`] THEN
      USE_THEN "gr" (fun th -> REWRITE_TAC[th]) THEN STRIP_TAC THEN
      EXPAND_TAC "G'" THEN REWRITE_TAC[IN_IMAGE; PAIR_EQ] THEN
      EXISTS_TAC `poly_const (subring_generated k s) (x:A):(1->num)->A` THEN
      ASM_SIMP_TAC[POLY_CONST; POLY_EXTEND_CONST; RING_HOMOMORPHISM_INCLUSION;
                   CARRIER_SUBRING_GENERATED_SUBRING];
      ALL_TAC] THEN
    SUBGOAL_THEN `!z. (ring_0 k,z) IN (G':A#B->bool) ==> z = ring_0 l`
    ASSUME_TAC THENL
     [X_GEN_TAC `z:B` THEN EXPAND_TAC "G'" THEN
      REWRITE_TAC[IN_IMAGE; PAIR_EQ] THEN
      DISCH_THEN(X_CHOOSE_THEN `p:(1->num)->A` (CONJUNCTS_THEN2
        (CONJUNCTS_THEN2 (ASSUME_TAC o SYM) SUBST1_TAC) ASSUME_TAC)) THEN
      MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `l:B ring`; `g:A->B`;
                     `\u:1. (w:B)`; `p:(1->num)->A`]
        POLY_EXTEND_UNIVARIATE) THEN
      ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN SUBST1_TAC] THEN
      REWRITE_TAC[] THEN
      FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
        is_forall(concl th) && can (find_term ((=) `w:B`)) (concl th))) THEN
      REWRITE_TAC[] THEN CONJ_TAC THENL
       [GEN_TAC THEN
        MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `p:(1->num)->A`;
                       `i:num`] COEFF_IN_CARRIER_ALT) THEN
        ASM_SIMP_TAC[RING_POLYNOMIAL; CARRIER_SUBRING_GENERATED_SUBRING];
        MP_TAC(ISPECL [`subring_generated k (s:A->bool)`; `k:A ring`;
                       `\x:A. x`; `\u:1. (y:A)`; `p:(1->num)->A`]
          POLY_EXTEND_UNIVARIATE) THEN
        ANTS_TAC THENL
         [ASM_REWRITE_TAC[RING_HOMOMORPHISM_INCLUSION]; ALL_TAC] THEN
        DISCH_THEN(SUBST1_TAC o SYM o BETA_RULE) THEN ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    SUBGOAL_THEN `(y:A,w:B) IN G` MP_TAC THENL
     [USE_THEN "maxp" MATCH_MP_TAC THEN EXISTS_TAC `G':A#B->bool` THEN
      ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
       [MP_TAC(ASSUME `!x. x IN r ==> (x,(f:A->B) x) IN G`) THEN
        UNDISCH_TAC `(G:A#B->bool) SUBSET G'` THEN REWRITE_TAC[SUBSET] THEN
        MESON_TAC[];
        EXPAND_TAC "G'" THEN REWRITE_TAC[IN_IMAGE; PAIR_EQ] THEN
        EXISTS_TAC `poly_var (subring_generated k (s:A->bool)) one` THEN
        ASM_SIMP_TAC[POLY_VAR; POLY_EXTEND_VAR; RING_HOMOMORPHISM_INCLUSION;
                     IN_UNIV]];
      USE_THEN "gr" (fun th -> REWRITE_TAC[th]) THEN SIMP_TAC[]];
    ALL_TAC] THEN
  (* s is local with maximal ideal ker g: adjoin 1/x with 1/g(x) *)
  SUBGOAL_THEN `!x:A. x IN s /\ ~((g:A->B) x = ring_0 l) ==> ring_inv k x IN s`
  (LABEL_TAC "loc") THENL
   [X_GEN_TAC `x:A` THEN STRIP_TAC THEN REMOVE_THEN "adj" MATCH_MP_TAC THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier k /\ ~(x = ring_0 k)`
    STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL
       [ASM_SIMP_TAC[];
        DISCH_TAC THEN UNDISCH_TAC `~((g:A->B) x = ring_0 l)` THEN
        ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    CONJ_TAC THENL [ASM_SIMP_TAC[RING_INV]; ALL_TAC] THEN
    EXISTS_TAC `ring_inv l ((g:A->B) x)` THEN CONJ_TAC THENL
     [ASM_SIMP_TAC[RING_INV]; ALL_TAC] THEN
    MAP_EVERY X_GEN_TAC [`n:num`; `a:num->A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN
     `!i. (a:num->A) i IN ring_carrier k /\ (g:A->B)(a i) IN ring_carrier l`
    ASSUME_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum k (0..n) (\i. ring_mul k ((a:num->A) i) (ring_pow k x (n - i))) =
      ring_0 k`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`k:A ring`; `x:A`; `a:num->A`; `n:num`]
        invpow_lemma) THEN
      ASM_SIMP_TAC[RING_MUL_RZERO; RING_POW] THEN
      DISCH_THEN(ACCEPT_TAC o SYM);
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_sum l (0..n)
        (\i. ring_mul l ((g:A->B)((a:num->A) i)) (ring_pow l (g x) (n - i))) =
      ring_0 l`
    ASSUME_TAC THENL
     [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `s:A->bool`; `g:A->B`;
                     `\i. ring_mul k ((a:num->A) i) (ring_pow k x (n - i))`;
                     `n:num`] hom_sum_lemma) THEN
      ASM_SIMP_TAC[IN_SUBRING_POW] THEN DISCH_THEN(ACCEPT_TAC o SYM);
      ALL_TAC] THEN
    MP_TAC(ISPECL [`l:B ring`; `(g:A->B) x`; `\i. (g:A->B)((a:num->A) i)`;
                   `n:num`] invpow_lemma) THEN
    ASM_SIMP_TAC[] THEN
    ASM_SIMP_TAC[INTEGRAL_DOMAIN_MUL_EQ_0; FIELD_IMP_INTEGRAL_DOMAIN; RING_POW;
                 RING_SUM; FIELD_POW_EQ_0];
    ALL_TAC] THEN
  (* s is a valuation subring (A-M 5.23) *)
  SUBGOAL_THEN `valuation_subring k (s:A->bool)` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[valuation_subring] THEN X_GEN_TAC `x:A` THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `s:A->bool`;
                   `{z:A | z IN s /\ (g:A->B) z = ring_0 l}`; `x:A`]
      IDEAL_GENERATED_ADJOIN_OR_INV) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[IN_ELIM_THM] THEN CONJ_TAC THENL
       [USE_THEN "loc" (fun th -> MESON_TAC[th]);
        MATCH_MP_TAC FIELD_NONTRIVIAL THEN ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    DISCH_THEN(DISJ_CASES_THEN ASSUME_TAC) THENL [DISJ1_TAC; DISJ2_TAC] THEN
    REMOVE_THEN "adj" MATCH_MP_TAC THEN
    (CONJ_TAC THENL
      [ASM_SIMP_TAC[RING_INV];
       MATCH_MP_TAC RING_HOMOMORPHISM_ADJOIN_ROOT THEN
       ASM_SIMP_TAC[RING_INV]]);
    ALL_TAC] THEN
  REMOVE_THEN "adj" (K ALL_TAC) THEN REMOVE_THEN "maxp" (K ALL_TAC) THEN
  (* the kernel of g is the maximal ideal *)
  MAP_EVERY EXISTS_TAC
   [`s:A->bool`; `{x:A | x IN s /\ (x = ring_0 k \/ ~(ring_inv k x IN s))}`;
    `g:A->B`] THEN
  ASM_SIMP_TAC[VALUATION_SUBRING_MAXIMAL_IDEAL] THEN
  X_GEN_TAC `x:A` THEN DISCH_TAC THEN REWRITE_TAC[IN_ELIM_THM] THEN
  ASM_REWRITE_TAC[] THEN EQ_TAC THENL
   [DISCH_TAC THEN ASM_CASES_TAC `x:A = ring_0 k` THEN ASM_REWRITE_TAC[] THEN
    DISCH_TAC THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    MP_TAC(ASSUME `(g:A->B)(ring_1 k) = ring_1 l`) THEN
    SUBGOAL_THEN `ring_1 k = ring_mul k x (ring_inv k (x:A))` SUBST1_TAC THENL
     [ASM_SIMP_TAC[FIELD_MUL_RINV]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_MUL_LZERO] THEN
    MP_TAC(MATCH_MP FIELD_NONTRIVIAL (ASSUME `field (l:B ring)`)) THEN
    MESON_TAC[];
    STRIP_TAC THENL
     [ASM_REWRITE_TAC[];
      REMOVE_THEN "loc" (MP_TAC o SPEC `x:A`) THEN ASM_REWRITE_TAC[]]]);;

