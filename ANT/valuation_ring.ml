      USE_THEN "gadd" MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
      USE_THEN "gneg" MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    USE_THEN "isg" (fun th -> DISCH_THEN(MP_TAC o MATCH_MP th)) THEN
    MP_TAC(ISPECL [`l:B ring`; `z:B`; `z':B`] RING_SUB_EQ_0) THEN
    ASM_REWRITE_TAC[] THEN MESON_TAC[];
    ALL_TAC] THEN
  REMOVE_THEN "isg" (K ALL_TAC) THEN
  (* its domain s and map g *)
  ABBREV_TAC `s = IMAGE FST (G:A#B->bool)` THEN
  ABBREV_TAC `g = \x:A. @z:B. (x,z) IN G` THEN
  SUBGOAL_THEN `!x:A z:B. (x,z) IN G <=> x IN s /\ g x = z`
  (LABEL_TAC "gr") THENL
   [REPEAT GEN_TAC THEN MAP_EVERY EXPAND_TAC ["s"; "g"] THEN
    REWRITE_TAC[IN_IMAGE; EXISTS_PAIR_THM; FST] THEN EQ_TAC THENL
     [DISCH_TAC THEN CONJ_TAC THENL
       [MAP_EVERY EXISTS_TAC [`x:A`; `z:B`] THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC SELECT_UNIQUE THEN REWRITE_TAC[] THEN
        X_GEN_TAC `u:B` THEN EQ_TAC THENL
         [DISCH_TAC THEN USE_THEN "func" MATCH_MP_TAC THEN
          EXISTS_TAC `x:A` THEN ASM_REWRITE_TAC[];
          DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[]]];
      DISCH_THEN(CONJUNCTS_THEN2
       (X_CHOOSE_THEN `a:A` (X_CHOOSE_THEN `b:B` STRIP_ASSUME_TAC))
       (SUBST1_TAC o SYM)) THEN
      CONV_TAC SELECT_CONV THEN EXISTS_TAC `b:B` THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(!x:A. x IN s ==> x IN ring_carrier k /\ (g:A->B) x IN ring_carrier l) /\
    (ring_0 k IN s /\ g(ring_0 k) = ring_0 l) /\
    (ring_1 k IN s /\ g(ring_1 k) = ring_1 l) /\
    (!x. x IN s ==> ring_neg k x IN s /\ g(ring_neg k x) = ring_neg l (g x)) /\
    (!x y. x IN s /\ y IN s
           ==> ring_add k x y IN s /\
               g(ring_add k x y) = ring_add l (g x) (g y)) /\
    (!x y. x IN s /\ y IN s
           ==> ring_mul k x y IN s /\
               g(ring_mul k x y) = ring_mul l (g x) (g y))`
  STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `!x:A. x IN s ==> (x,(g:A->B) x) IN G` (LABEL_TAC "gin")
    THENL [USE_THEN "gr" (fun th -> SIMP_TAC[th]); ALL_TAC] THEN
    USE_THEN "gr" (fun th -> REWRITE_TAC[GSYM th]) THEN
    REPEAT CONJ_TAC THENL
     [GEN_TAC THEN DISCH_TAC THEN USE_THEN "gcar" MATCH_MP_TAC THEN
      USE_THEN "gin" MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
      FIRST_ASSUM ACCEPT_TAC;
      FIRST_ASSUM ACCEPT_TAC;
      REPEAT STRIP_TAC THEN USE_THEN "gneg" MATCH_MP_TAC THEN
      USE_THEN "gin" MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
      REPEAT STRIP_TAC THEN USE_THEN "gadd" MATCH_MP_TAC THEN CONJ_TAC THEN
      USE_THEN "gin" MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
      REPEAT STRIP_TAC THEN USE_THEN "gmul" MATCH_MP_TAC THEN CONJ_TAC THEN
      USE_THEN "gin" MATCH_MP_TAC THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  MAP_EVERY (fun t -> REMOVE_THEN t (K ALL_TAC))
   ["func"; "gcar"; "gneg"; "gadd"; "gmul"] THEN
  SUBGOAL_THEN `(s:A->bool) subring_of k` ASSUME_TAC THENL
   [REWRITE_TAC[subring_of; SUBSET] THEN ASM_SIMP_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `ring_homomorphism(subring_generated k s,l) (g:A->B)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[ring_homomorphism; CARRIER_SUBRING_GENERATED_SUBRING;
                 CONJUNCT2 SUBRING_GENERATED; SUBSET; FORALL_IN_IMAGE];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x:A n. x IN s ==> (g:A->B)(ring_pow k x n) = ring_pow l (g x) n`
  ASSUME_TAC THENL
   [MP_TAC(MATCH_MP RING_HOMOMORPHISM_POW (ASSUME
     `ring_homomorphism(subring_generated k s,l) (g:A->B)`)) THEN
    ASM_SIMP_TAC[RING_POW_SUBRING_GENERATED;
                 CARRIER_SUBRING_GENERATED_SUBRING];
    ALL_TAC] THEN
  SUBGOAL_THEN `(r:A->bool) SUBSET s /\ !x. x IN r ==> (g:A->B) x = f x`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ASSUME `!x. x IN r ==> (x,(f:A->B) x) IN G`) THEN
    USE_THEN "gr" (fun th -> REWRITE_TAC[th]) THEN
    REWRITE_TAC[SUBSET] THEN MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_ideal (subring_generated k s) {z:A | z IN s /\ (g:A->B) z = ring_0 l}`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `{z:A | z IN s /\ (g:A->B) z = ring_0 l} =
      ring_kernel(subring_generated k s,l) g`
    SUBST1_TAC THENL
     [ASM_SIMP_TAC[ring_kernel; CARRIER_SUBRING_GENERATED_SUBRING];
      MATCH_MP_TAC RING_IDEAL_RING_KERNEL THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  (* adjoining y and w with the relations of y going to relations of w *)
  SUBGOAL_THEN
   `!y. y IN ring_carrier k /\
        (?w. w IN ring_carrier l /\
             !n a. (!i. a i IN s) /\
                   ring_sum k (0..n)
                     (\i. ring_mul k (a i) (ring_pow k y i)) = ring_0 k
                   ==> ring_sum l (0..n)
                         (\i. ring_mul l ((g:A->B)(a i)) (ring_pow l w i)) =
                       ring_0 l)
        ==> y IN s`
