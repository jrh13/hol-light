   [X_GEN_TAC `y:A` THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
     (X_CHOOSE_THEN `w:B` STRIP_ASSUME_TAC)) THEN
    ABBREV_TAC
     `G' = IMAGE (\p:(1->num)->A.
                    poly_extend (subring_generated k s,k) (\x:A. x) (\u:1. y) p,
