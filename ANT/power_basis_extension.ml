(* An element is determined by its traces against a basis.                   *)
let ALGEBRA_TRACE_FORM_INJECTIVE = prove
 (`!(h:A->B) k l n w x y.
        finite_extension(k,l) h /\ separable_extension(k,l) h /\
        free_basis (k,l) h n w /\
        x IN ring_carrier l /\ y IN ring_carrier l /\
        (!i. i < n
             ==> algebra_trace (k,l) h (ring_mul l (w i) x) =
                 algebra_trace (k,l) h (ring_mul l (w i) y))
        ==> x = y`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension] o
    MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
  MP_TAC(ISPECL [`l:B ring`; `x:B`; `y:B`] RING_SUB_EQ_0) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  SUBGOAL_THEN
   `!i. i < (n:num)
        ==> algebra_trace (k,l) (h:A->B)
              (ring_mul l (w i) (ring_sub l x y)) = ring_0 k`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    ASM_SIMP_TAC[RING_SUB_LDISTRIB; ALGEBRA_TRACE_SUB; RING_MUL] THEN
    MATCH_MP_TAC RING_SUB_REFL THEN
    REWRITE_TAC[ALGEBRA_TRACE_NORM_IN_CARRIER];
    ALL_TAC] THEN
  ABBREV_TAC `z = ring_sub l x (y:B)` THEN
  SUBGOAL_THEN `(z:B) IN ring_carrier l` ASSUME_TAC THENL
   [EXPAND_TAC "z" THEN ASM_SIMP_TAC[RING_SUB]; ALL_TAC] THEN
  ASM_CASES_TAC `z:B = ring_0 l` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `?u. u IN ring_carrier l /\ algebra_trace (k,l) (h:A->B) u = ring_1 k`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`]
      ALGEBRA_TRACE_SURJECTIVE) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(MP_TAC o SPEC `ring_1 k:A` o MATCH_MP (SET_RULE
     `IMAGE (f:B->A) s = t ==> !y. y IN t ==> ?x. x IN s /\ f x = y`)) THEN
    REWRITE_TAC[RING_1];
    ALL_TAC] THEN
  FIRST_ASSUM(MP_TAC o SPEC `ring_mul l (ring_inv l z) (u:B)` o
    CONJUNCT1 o CONJUNCT2 o GEN_REWRITE_RULE I [free_basis] o
    check (fun th -> concl th = `free_basis (k,l) (h:A->B) n w`)) THEN
  ASM_SIMP_TAC[RING_MUL; RING_INV] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:num->A` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `(u:B) = ring_mul l z (ring_mul l (ring_inv l z) u)`
