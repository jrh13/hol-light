(* ========================================================================= *)
(* The different of a power basis over any base field (Euler), and local     *)
(* power bases: monogenicity at a prime with only one prime above it.        *)
(*                                                                           *)
(* For fields k, l with a ring homomorphism h : k -> l, l a number field     *)
(* (then k is one), O_k, O_l the rings of integers, C and D the codifferent  *)
(* and the different number_field_codifferent (k,l) h and                    *)
(* number_field_different (k,l) h (ANT/different.ml), a in O_l with          *)
(* l = k(a), i.e. subring_generated l (a INSERT IMAGE h (ring_carrier k))    *)
(* = l, f its minimal polynomial over k, d = Df(a) (poly_extend (k,l) h      *)
(* applied to poly_deriv k f at a) and O_k[a] the subring of l generated by  *)
(* a and the image of O_k:                                                   *)
(*                                                                           *)
(*   the trace dual of O_k[a] is (1/d) O_k[a]                                *)
(*                 (NUMBER_FIELD_CODIFFERENT_POWER_BASIS)                    *)
(*   d IN D        (NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT)                    *)
(*   O_l = O_k[a] ==> C = (1/d) O_l and D = (d)                              *)
(*                 (NUMBER_FIELD_DIFFERENT_POWER_BASIS)                      *)
(*   h(s) O_l SUBSET O_k[a] for some s in O_k outside a nonzero prime p      *)
(*   ==> v_Q(D) = v_Q(d) for every prime Q of O_l above p                    *)
(*                 (NUMBER_FIELD_DIFFERENT_LOCAL_POWER_BASIS)                *)
(*                                                                           *)
(* and their case k = Q, the prime subfield of l, for Z[a] =                 *)
(* subring_generated l {a} and a minimal polynomial of degree [l:Q]          *)
(* (NUMBER_FIELD_CODIFFERENT_POWER_BASIS_Q,                                  *)
(* NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT_Q,                                   *)
(* NUMBER_FIELD_DIFFERENT_POWER_BASIS_Q): there O_Q[a] = Z[a] and l = Q(a).  *)
(* Local monogenicity, without completions or localizations: if Q is the     *)
(* only prime of O_l above a nonzero prime p of O_k then there are a in O_l  *)
(* and s in O_k outside p with l = k(a) and h(s) O_l SUBSET O_k[a]           *)
(* (NUMBER_FIELD_LOCAL_POWER_BASIS), i.e. the localization of O_l at p is    *)
(* generated over that of O_k by one element. More precisely every a in O_l  *)
(* with O_l = O_k[a] + pO_l does (NUMBER_FIELD_POWER_BASIS_MOD_PRIME), and   *)
(* such an a exists (NUMBER_FIELD_ONE_PRIME_GENERATOR). For Galois           *)
(* extensions this applies over the decomposition field of Q                 *)
(* (ANT/hilbert_formula.ml).                                                 *)
(*                                                                           *)
(* Routes. Euler: over an algebraic closure, the k-embeddings e_t of l are   *)
(* distinct on a, f = prod (X - e_t(a)) and Tr = sum of the e_t              *)
(* (FIELD_POWER_BASIS_EMBEDDINGS); with h(f) = (X - a) b, Lagrange           *)
(* interpolation gives Tr(a^i b_j / d) = 1 if i = j, 0 otherwise             *)
(* (ALGEBRA_TRACE_POWER_BASIS_DUAL), the b_j lie in O_k[a]                   *)
(* (FIELD_POLY_COFACTOR_COEFFS of Library/ringtheory.ml, Horner) and O_k[a]  *)
(* is spanned by the a^i, i < deg f (SUBRING_GENERATED_MONIC_ROOT_SPAN of    *)
(* Library/ringtheory.ml), so the dual of O_k[a] is (1/d) O_k[a]; locally    *)
(* h(s) D SUBSET (d) SUBSET D. Local monogenicity, in two steps. The choice  *)
(* of a (NUMBER_FIELD_ONE_PRIME_GENERATOR): a generator a of the residue     *)
(* field O_l/Q, of order q, chosen with a^q - a a uniformizer                *)
(* (DEDEKIND_RESIDUE_GENERATOR_UNIFORMIZER of ANT/ideal_euler.ml), makes     *)
(* O_k[a] dense at Q, the lifting from Q to its powers                       *)
(* (DEDEKIND_SUBRING_DENSE of ANT/dedekind.ml), and pO_l = Q^e gives         *)
(* O_l = O_k[a] + pO_l. From O_l = O_k[a] + pO_l                             *)
(* (NUMBER_FIELD_POWER_BASIS_MOD_PRIME): the a^i, i < deg f, span O_k[a]     *)
(* over O_k (RING_OF_INTEGERS_ADJOIN_SPAN), hence O_l modulo pO_l; elements  *)
(* spanning O_l modulo pO_l number at least n = [l:k], the dimension of      *)
(* O_l/pO_l over O_k/p (RING_OF_INTEGERS_SPAN_MOD_PRIME_DEGREE, by           *)
(* EXTENSION_DEGREE_LE_SPANNING of Library/fieldtheory.ml), so deg f = n and *)
(* l = k(a) (FINITE_EXTENSION_SIMPLE_EQ of Library/fieldtheory.ml); a basis  *)
(* of l inside O_l spanning O_l modulo pO_l spans it up to a denominator     *)
(* prime to p (RING_OF_INTEGERS_LOCAL_SPAN, the argument of                  *)
(* RING_OF_INTEGERS_LOCAL_BASIS of ANT/different_extension.ml for an         *)
(* arbitrary basis, with the lifting from p to its powers                    *)
(* IDEAL_EXTENSION_POW_SUPPLEMENT).                                          *)
