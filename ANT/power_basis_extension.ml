  SUBGOAL_THEN `ring_homomorphism(ring_of_integers k,l) (h:A->B)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
                   `{x | integral_element (integer_ring,k:A ring)
                                            (ring_of_int k) x}`]
      RING_HOMOMORPHISM_FROM_SUBRING_GENERATED) THEN
    ASM_SIMP_TAC[GSYM ring_of_integers];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `ring_of_integers k:A ring`; `l:B ring`; `a:B`;
