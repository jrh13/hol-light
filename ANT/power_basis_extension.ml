        ASM_REWRITE_TAC[]];
      EXPAND_TAC "f" THEN ASM_SIMP_TAC[MINIMAL_POLYNOMIAL_MONIC];
      EXPAND_TAC "f" THEN ASM_SIMP_TAC[MINIMAL_POLYNOMIAL_VANISHES]];
