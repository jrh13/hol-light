   [ASM_SIMP_TAC[RING_MUL_ASSOC; RING_INV; FIELD_MUL_RINV; RING_MUL_LID];
    ALL_TAC] THEN
  UNDISCH_TAC `algebra_trace (k,l) (h:A->B) u = ring_1 k` THEN
  FIRST_X_ASSUM(SUBST1_TAC o check (fun th -> lhs(concl th) = `u:B`)) THEN
  FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
    is_eq(concl th) &&
    lhs(concl th) = `ring_mul l (ring_inv l z) (u:B)`)) THEN
