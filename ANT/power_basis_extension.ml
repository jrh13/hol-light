(* Euler: for h(f) = (X - a) b the a^i b_j / Df(a) form a trace dual pair of *)
(* bases.                                                                    *)
let ALGEBRA_TRACE_POWER_BASIS_DUAL = prove
 (`!(h:A->B) k l a f d b.
        finite_extension(k,l) h /\ separable_extension(k,l) h /\
        a IN ring_carrier l /\
        subring_generated l (a INSERT IMAGE h (ring_carrier k)) = l /\
        f = minimal_polynomial (k,l) h a /\
        d = poly_extend (k,l) h (\v. a) (poly_deriv k f) /\
        b IN ring_carrier(poly_ring l (:1)) /\
        h o f = poly_mul l (poly_sub l (poly_var l one) (poly_const l a)) b
        ==> ~(d = ring_0 l) /\
            !i j. i < extension_degree(k,l) h /\ j < extension_degree(k,l) h
                  ==> algebra_trace (k,l) h
                        (ring_mul l (ring_inv l d)
                           (ring_mul l (ring_pow l a i) (coeff j b))) =
                      if j = i then ring_1 k else ring_0 k`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(ASSUME_TAC o SYM o check (fun th ->
    is_eq(concl th) && lhs(concl th) = `(h:A->B) o (f:(1->num)->A)`)) THEN
  FIRST_X_ASSUM(ASSUME_TAC o SYM o
    check (fun th -> lhs(concl th) = `d:B`)) THEN
  FIRST_X_ASSUM(ASSUME_TAC o SYM o
    check (fun th -> lhs(concl th) = `f:(1->num)->A`)) THEN
  ABBREV_TAC `n = extension_degree (k,l) (h:A->B)` THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN `algebraic_over (k,l) (h:A->B) a` ASSUME_TAC THENL
