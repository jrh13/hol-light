  ASM_REWRITE_TAC[]);;

(* If O_l = O_k[a] + pO_l then l = k(a) and h(s) O_l SUBSET O_k[a] for some  *)
(* s in O_k outside p: the powers of a span O_l modulo pO_l                  *)
(* (RING_OF_INTEGERS_ADJOIN_SPAN), so deg f = [l:k]                          *)
(* (RING_OF_INTEGERS_SPAN_MOD_PRIME_DEGREE, FINITE_EXTENSION_SIMPLE_EQ), and *)
(* the power basis spans O_l up to a denominator prime to p                  *)
(* (RING_OF_INTEGERS_LOCAL_SPAN).                                            *)
let NUMBER_FIELD_POWER_BASIS_MOD_PRIME = prove
 (`!k:A ring l:B ring h p a.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        a IN ring_carrier(ring_of_integers l) /\
        ring_setadd (ring_of_integers l)
          (ring_carrier(subring_generated l
             (a INSERT IMAGE h (ring_carrier(ring_of_integers k)))))
          (ideal_generated (ring_of_integers l) (IMAGE h p)) =
        ring_carrier(ring_of_integers l)
        ==> subring_generated l (a INSERT IMAGE h (ring_carrier k)) = l /\
            ?s. s IN ring_carrier(ring_of_integers k) /\ ~(s IN p) /\
                !y. y IN ring_carrier(ring_of_integers l)
                    ==> ring_mul l (h s) y IN
                        ring_carrier(subring_generated l
                       (a INSERT IMAGE h (ring_carrier(ring_of_integers k))))`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC
   `R = ring_carrier(subring_generated l
          (a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k))))` THEN
  ABBREV_TAC
   `J = ideal_generated (ring_of_integers l) (IMAGE (h:A->B) p)` THEN
  STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_SEPARABLE_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  SUBGOAL_THEN
   `(a:B) IN ring_carrier l /\ algebraic_over (k,l) (h:A->B) a`
  STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
     [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET];
      ASM_MESON_TAC[FINITE_IMP_ALGEBRAIC_EXTENSION; algebraic_extension]];
    ALL_TAC] THEN
  ABBREV_TAC `d = poly_deg k (minimal_polynomial (k,l) (h:A->B) a)` THEN
  ABBREV_TAC `n = extension_degree (k,l) (h:A->B)` THEN
  (* O_k[a] is the O_k-span of the a^i, i < d *)
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`]
    RING_OF_INTEGERS_ADJOIN_SPAN) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `!i. ring_pow l (a:B) i IN ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL
   [GEN_TAC THEN MP_TAC(ISPEC `ring_of_integers l:B ring` RING_POW) THEN
    REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  (* so O_l = O_k[a] + J makes the a^i, i < d, span O_l modulo J *)
  SUBGOAL_THEN
   `!y. y IN ring_carrier(ring_of_integers l)
        ==> ?c. (!i. c i IN ring_carrier(ring_of_integers k)) /\
                ring_sub l y
                  (ring_sum l {i | i < d}
                     (\i. ring_mul l ((h:A->B)(c i)) (ring_pow l a i))) IN J`
  ASSUME_TAC THENL
   [SUBGOAL_THEN `!j:B. j IN J ==> j IN ring_carrier l` ASSUME_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers l:B ring`; `J:B->bool`]
        RING_IDEAL_IMP_SUBSET) THEN
      EXPAND_TAC "J" THEN REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
      MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET];
      ALL_TAC] THEN
    X_GEN_TAC `y:B` THEN DISCH_TAC THEN
    UNDISCH_TAC
     `ring_setadd (ring_of_integers l) R J =
      ring_carrier(ring_of_integers(l:B ring))` THEN
    REWRITE_TAC[EXTENSION; ring_setadd; IN_ELIM_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `y:B`) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS; IN_ELIM_THM] THEN
    REWRITE_TAC[LEFT_AND_EXISTS_THM; LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`z:B`; `j:B`; `c:num->A`] THEN STRIP_TAC THEN
    EXISTS_TAC `c:num->A` THEN ASM_REWRITE_TAC[] THEN
    ASM_SIMP_TAC[RING_RULE `ring_sub r (ring_add r z j) z = (j:B)`;
                 RING_SUM];
    ALL_TAC] THEN
  (* counting residues, d = n, so l = k(a) *)
  SUBGOAL_THEN `d:num = n` ASSUME_TAC THENL
   [MATCH_MP_TAC(ARITH_RULE `d <= n /\ n <= d ==> d:num = n`) THEN
    CONJ_TAC THENL
     [MAP_EVERY EXPAND_TAC ["d"; "n"] THEN
      MATCH_MP_TAC MINIMAL_POLYNOMIAL_DEG_LE_EXTENSION_DEGREE THEN
      ASM_REWRITE_TAC[];
      EXPAND_TAC "n" THEN
      MATCH_MP_TAC RING_OF_INTEGERS_SPAN_MOD_PRIME_DEGREE THEN
      MAP_EVERY EXISTS_TAC [`p:A->bool`; `ring_pow l (a:B)`] THEN
      ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `subring_generated l (a INSERT IMAGE (h:A->B) (ring_carrier k)) = l`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `a:B`]
      FINITE_EXTENSION_SIMPLE_EQ) THEN
    ASM_REWRITE_TAC[];
    ASM_REWRITE_TAC[]] THEN
  (* the local span of the power basis *)
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`;
                 `ring_pow l (a:B)`] RING_OF_INTEGERS_LOCAL_SPAN) THEN
  ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
   [CONJ_TAC THENL
     [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`]
        FREE_BASIS_SIMPLE_EXTENSION) THEN
      ASM_REWRITE_TAC[];
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        concl th = `d:num = n`)) THEN
      ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `s:A` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[IN_ELIM_THM] THEN
  X_GEN_TAC `y:B` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o C MATCH_MP
    (ASSUME `(y:B) IN ring_carrier(ring_of_integers l)`) o check (fun th ->
      is_forall(concl th) &&
      can (find_term ((=) `ring_mul l ((h:A->B) s)`)) (concl th))) THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `c:num->A` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[]);;

(* If Q is the only prime of O_l above p then O_l = O_k[a] + pO_l for some a *)
(* in O_l.                                                                   *)
let NUMBER_FIELD_ONE_PRIME_GENERATOR = prove
 (`!k:A ring l:B ring h p Q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P} = {Q}
        ==> ?a. a IN ring_carrier(ring_of_integers l) /\
                ring_setadd (ring_of_integers l)
                  (ring_carrier(subring_generated l
                     (a INSERT IMAGE h (ring_carrier(ring_of_integers k)))))
                  (ideal_generated (ring_of_integers l) (IMAGE h p)) =
                ring_carrier(ring_of_integers l)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `prime_ideal (ring_of_integers l) (Q:B->bool) /\ IMAGE (h:A->B) p SUBSET Q`
  STRIP_ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o SPEC `Q:B->bool` o
      REWRITE_RULE[EXTENSION; IN_ELIM_THM; IN_SING] o check (fun th ->
        is_eq(concl th) && rhs(concl th) = `{Q:B->bool}`)) THEN
    MESON_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `p:A->bool`; `Q:B->bool`]
    NUMBER_FIELD_PRIME_IDEAL_ABOVE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_RING_OF_INTEGERS o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL o
    check (fun th ->
      concl th = `prime_ideal (ring_of_integers l) (Q:B->bool)`)) THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`]
    DEDEKIND_RESIDUE_GENERATOR_UNIFORMIZER) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN
  ABBREV_TAC
   `q = CARD(ring_carrier(quotient_ring (ring_of_integers l) (Q:B->bool)))` THEN
  DISCH_THEN(X_CHOOSE_THEN `a:B` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `a:B` THEN ASM_REWRITE_TAC[] THEN
  ABBREV_TAC
   `R = ring_carrier(subring_generated l
          (a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k))))` THEN
  ABBREV_TAC
   `J = ideal_generated (ring_of_integers l) (IMAGE (h:A->B) p)` THEN
  SUBGOAL_THEN
   `!z. z IN ring_carrier(ring_of_integers l) ==> (z:B) IN ring_carrier l`
  ASSUME_TAC THENL
   [MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!c. c IN ring_carrier(ring_of_integers k)
        ==> (h:A->B) c IN ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_HOMOMORPHISM_IN_CARRIER THEN
    EXISTS_TAC `ring_of_integers k:A ring` THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS];
    ALL_TAC] THEN
  SUBGOAL_THEN `(R:B->bool) SUBSET ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL
   [EXPAND_TAC "R" THEN MATCH_MP_TAC SUBRING_GENERATED_MINIMAL THEN
    REWRITE_TAC[RING_OF_INTEGERS_SUBRING] THEN
    ASM_SIMP_TAC[INSERT_SUBSET; SUBSET; FORALL_IN_IMAGE];
    ALL_TAC] THEN
  SUBGOAL_THEN `(R:B->bool) subring_of (ring_of_integers l)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`;
      `a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k))`]
      SUBRING_SUBRING_GENERATED) THEN
    ASM_REWRITE_TAC[subring_of; RING_OF_INTEGERS] THEN SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(a:B) IN R` ASSUME_TAC THENL
   [EXPAND_TAC "R" THEN MATCH_MP_TAC SUBRING_GENERATED_INC THEN
    ASM_SIMP_TAC[IN_INSERT; INSERT_SUBSET; SUBSET; FORALL_IN_IMAGE];
    ALL_TAC] THEN
  ABBREV_TAC `t = ring_sub l (ring_pow l a q) (a:B)` THEN
  SUBGOAL_THEN
   `(t:B) IN Q /\ ~(t IN ideal_pow (ring_of_integers l) Q 2)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "t" THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `(t:B) IN R` ASSUME_TAC THENL
   [EXPAND_TAC "t" THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `R:B->bool`;
                   `ring_pow (ring_of_integers l) a q:B`; `a:B`]
      IN_SUBRING_SUB) THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `R:B->bool`; `a:B`; `q:num`]
      IN_SUBRING_POW) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN MESON_TAC[];
    ALL_TAC] THEN
  (* every residue class modulo Q meets R, so R is dense *)
  SUBGOAL_THEN
   `!n y. y IN ring_carrier(ring_of_integers l)
          ==> ?z. z IN R /\
                  ring_sub l y z IN ideal_pow (ring_of_integers l) Q n:B->bool`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`; `t:B`; `R:B->bool`;
                   `n:num`; `y:B`] DEDEKIND_SUBRING_DENSE) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN MATCH_MP_TAC THEN
    X_GEN_TAC `w:B` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(DISJ_CASES_THEN MP_TAC o C MATCH_MP
      (ASSUME `(w:B) IN ring_carrier(ring_of_integers l)`) o check (fun th ->
        is_forall(concl th) && can (find_term is_disj) (concl th))) THENL
     [DISCH_TAC THEN EXISTS_TAC `ring_0 l:B` THEN
      UNDISCH_TAC `(R:B->bool) subring_of (ring_of_integers l)` THEN
      SIMP_TAC[subring_of; RING_OF_INTEGERS] THEN DISCH_TAC THEN
      ASM_SIMP_TAC[RING_SUB_RZERO];
      DISCH_THEN(X_CHOOSE_TAC `m:num`) THEN
      EXISTS_TAC `ring_pow l (a:B) m` THEN ASM_REWRITE_TAC[] THEN
      MP_TAC(ISPECL [`ring_of_integers l:B ring`; `R:B->bool`; `a:B`; `m:num`]
        IN_SUBRING_POW) THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS]];
    ALL_TAC] THEN
  (* p O_l = Q^e *)
  SUBGOAL_THEN
   `J = ideal_pow (ring_of_integers l) Q
          (ramification_index (ring_of_integers k,ring_of_integers l)
                              (h:A->B) Q)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
      NUMBER_FIELD_PRIME_FACTORIZATION) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    SIMP_TAC[IDEAL_PRODUCT_SING; RING_IDEAL_IDEAL_POW];
    ALL_TAC] THEN
  REWRITE_TAC[GSYM SUBSET_ANTISYM_EQ] THEN CONJ_TAC THENL
   [REWRITE_TAC[SUBSET; ring_setadd; FORALL_IN_GSPEC] THEN
    MAP_EVERY X_GEN_TAC [`z:B`; `j:B`] THEN STRIP_TAC THEN
    MP_TAC(ISPEC `ring_of_integers l:B ring` RING_ADD) THEN
    REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN MATCH_MP_TAC THEN
    CONJ_TAC THENL
     [FIRST_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET] o check (fun th ->
        concl th = `(R:B->bool) SUBSET ring_carrier(ring_of_integers l)`)) THEN
      ASM_REWRITE_TAC[];
      MP_TAC(ISPECL [`ring_of_integers l:B ring`; `J:B->bool`]
        RING_IDEAL_IMP_SUBSET) THEN
      ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW; SUBSET] THEN
      DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
      UNDISCH_TAC `(j:B) IN J` THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  REWRITE_TAC[SUBSET; ring_setadd; IN_ELIM_THM] THEN
  X_GEN_TAC `y:B` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o C MATCH_MP
    (ASSUME `(y:B) IN ring_carrier(ring_of_integers l)`) o SPEC
    `ramification_index (ring_of_integers k,ring_of_integers l) (h:A->B) Q` o
    check (fun th ->
      is_forall(concl th) && can (find_term ((=) `R:B->bool`)) (concl th) &&
      can (find_term ((=) `ideal_pow:(B ring)->(B->bool)->num->B->bool`))
        (concl th))) THEN
  DISCH_THEN(X_CHOOSE_THEN `z:B` STRIP_ASSUME_TAC) THEN
  MAP_EVERY EXISTS_TAC [`z:B`; `ring_sub l y (z:B)`] THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN
  SUBGOAL_THEN `(z:B) IN ring_carrier l /\ (y:B) IN ring_carrier l`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN FIRST_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
    FIRST_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET] o check (fun th ->
      concl th = `(R:B->bool) SUBSET ring_carrier(ring_of_integers l)`)) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC(RING_RULE `ring_add r z (ring_sub r y z) = (y:B)`) THEN
  ASM_REWRITE_TAC[]);;

(* Local monogenicity: if Q is the only prime of O_l above p then O_l is,   *)
(* up to a denominator s prime to p, O_k[a] for some a with l = k(a).      *)
let NUMBER_FIELD_LOCAL_POWER_BASIS = prove
 (`!k:A ring l:B ring h p Q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P} = {Q}
        ==> ?a s. a IN ring_carrier(ring_of_integers l) /\
                  subring_generated l (a INSERT IMAGE h (ring_carrier k)) = l /\
                  s IN ring_carrier(ring_of_integers k) /\ ~(s IN p) /\
                  !y. y IN ring_carrier(ring_of_integers l)
                      ==> ring_mul l (h s) y IN
                          ring_carrier(subring_generated l
                       (a INSERT IMAGE h (ring_carrier(ring_of_integers k))))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `Q:B->bool`]
    NUMBER_FIELD_ONE_PRIME_GENERATOR) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `a:B` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `a:B`]
    NUMBER_FIELD_POWER_BASIS_MOD_PRIME) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (X_CHOOSE_TAC `s:A`)) THEN
  MAP_EVERY EXISTS_TAC [`a:B`; `s:A`] THEN ASM_REWRITE_TAC[]);;
