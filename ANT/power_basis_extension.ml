(* For a in O_l, O_k[a] is the O_k-span of the powers a^i, i < deg f, f the  *)
(* minimal polynomial of a over k (its coefficients lie in O_k).             *)
let RING_OF_INTEGERS_ADJOIN_SPAN = prove
 (`!k:A ring l:B ring h a.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        a IN ring_carrier(ring_of_integers l)
        ==> ring_carrier(subring_generated l
              (a INSERT IMAGE h (ring_carrier(ring_of_integers k)))) =
            {ring_sum l {i | i < poly_deg k (minimal_polynomial (k,l) h a)}
               (\i. ring_mul l (h(c i)) (ring_pow l a i)) |
             c | !i. c i IN ring_carrier(ring_of_integers k)}`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_SEPARABLE_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  SUBGOAL_THEN `(a:B) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `algebraic_over (k,l) (h:A->B) a` ASSUME_TAC THENL
   [ASM_MESON_TAC[FINITE_IMP_ALGEBRAIC_EXTENSION; algebraic_extension];
    ALL_TAC] THEN
  ABBREV_TAC `f = minimal_polynomial (k,l) (h:A->B) a` THEN
  SUBGOAL_THEN
   `f IN ring_carrier(poly_ring (ring_of_integers k) (:1)) /\
    monic (ring_of_integers k) (f:(1->num)->A) /\
    poly_deg (ring_of_integers k) f = poly_deg k f /\
    poly_extend (ring_of_integers k,l) (h:A->B) (\v:1. a) f = ring_0 l`
  STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[ring_of_integers; MONIC_SUBRING_GENERATED;
                POLY_DEG_SUBRING_GENERATED;
                POLY_EXTEND_FROM_SUBRING_GENERATED] THEN
    ASM_REWRITE_TAC[GSYM RING_POLYNOMIAL] THEN
    REPEAT CONJ_TAC THENL
     [MATCH_MP_TAC RING_POLYNOMIAL_SUBRING_COEFF THEN
      REWRITE_TAC[GSYM ring_of_integers] THEN CONJ_TAC THENL
       [EXPAND_TAC "f" THEN
        ASM_SIMP_TAC[RING_POLYNOMIAL; MINIMAL_POLYNOMIAL_IN_CARRIER];
        MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`]
