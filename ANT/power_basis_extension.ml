 (`!k:A ring l:B ring h a s.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        a IN ring_carrier l /\ s IN ring_carrier k /\ ~(s = ring_0 k) /\
        (!y. y IN ring_carrier(ring_of_integers l)
             ==> ring_mul l (h s) y IN
                 ring_carrier(subring_generated l
                   (a INSERT IMAGE h (ring_carrier(ring_of_integers k)))))
        ==> subring_generated l (a INSERT IMAGE h (ring_carrier k)) = l`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[SUBRING_GENERATED_SUPERSET] THEN
  REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:B` THEN DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  SUBGOAL_THEN `number_field(k:A ring)` ASSUME_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_HOMOMORPHIC_PREIMAGE]; ALL_TAC] THEN
  SUBGOAL_THEN `!c. c IN ring_carrier k ==> (h:A->B) c IN ring_carrier l`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
  MP_TAC(ISPECL [`l:B ring`; `x:B`] NUMBER_FIELD_INTEGRAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:int` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `ring_mul l (ring_of_int l m) (x:B)` o
    check (fun th -> is_forall(concl th) &&
      can (find_term ((=) `ring_of_integers(l:B ring)`)) (concl th))) THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `ring_carrier(subring_generated l
      (a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k)))) SUBSET
    ring_carrier(subring_generated l (a INSERT IMAGE h (ring_carrier k)))`
  MP_TAC THENL
   [MATCH_MP_TAC SUBRING_GENERATED_MONO THEN
    MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
    REWRITE_TAC[SUBSET] THEN DISCH_THEN(fun th -> DISCH_THEN
      (MP_TAC o MATCH_MP th))] THEN
  ABBREV_TAC
   `S = ring_carrier(subring_generated l
          (a INSERT IMAGE (h:A->B) (ring_carrier k)))` THEN
  SUBGOAL_THEN `(S:B->bool) subring_of l` ASSUME_TAC THENL
   [EXPAND_TAC "S" THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED]; ALL_TAC] THEN
  SUBGOAL_THEN `!c. c IN ring_carrier k ==> (h:A->B) c IN S` ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN EXPAND_TAC "S" THEN
    MATCH_MP_TAC SUBRING_GENERATED_INC THEN
    ASM_SIMP_TAC[INSERT_SUBSET; SUBSET; FORALL_IN_IMAGE; IN_INSERT] THEN
    DISJ2_TAC THEN MATCH_MP_TAC FUN_IN_IMAGE THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC `t = ring_mul k s (ring_of_int k m:A)` THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier k /\ ~(t = ring_0 k)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "t" THEN
    ASM_SIMP_TAC[RING_MUL; RING_OF_INT; FIELD_MUL_EQ_0] THEN
    ASM_MESON_TAC[RING_OF_INT_EQ_0_CHAR_0; number_field];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul l ((h:A->B) s) (ring_mul l (ring_of_int l m) x) =
    ring_mul l (h t) x`
  SUBST1_TAC THENL
   [EXPAND_TAC "t" THEN
    FIRST_ASSUM(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_MUL th;
      RING_OF_INT; MATCH_MP RING_HOMOMORPHISM_RING_OF_INT th]) THEN
    ASM_SIMP_TAC[RING_MUL_ASSOC; RING_OF_INT];
    ALL_TAC] THEN
  DISCH_TAC THEN
  SUBGOAL_THEN `ring_mul l ((h:A->B)(ring_inv k t)) (h t) = ring_1 l`
  ASSUME_TAC THENL
   [FIRST_ASSUM(fun th -> ASM_SIMP_TAC[GSYM(MATCH_MP RING_HOMOMORPHISM_MUL th);
      RING_INV; FIELD_MUL_LINV; MATCH_MP RING_HOMOMORPHISM_1 th]);
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(x:B) = ring_mul l (h(ring_inv k t)) (ring_mul l ((h:A->B) t) x)`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[RING_MUL_ASSOC; RING_INV; RING_MUL_LID];
    MATCH_MP_TAC IN_SUBRING_MUL THEN ASM_SIMP_TAC[RING_INV]]);;

(* Df(a) lies in the different for a in O_l with l = k(a).                 *)
let NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT = prove
 (`!k:A ring l:B ring h a.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        a IN ring_carrier(ring_of_integers l) /\
        subring_generated l (a INSERT IMAGE h (ring_carrier k)) = l
        ==> poly_extend (k,l) h (\v. a)
              (poly_deriv k (minimal_polynomial (k,l) h a)) IN
            number_field_different (k,l) h`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `f = minimal_polynomial (k,l) (h:A->B) a` THEN
  ABBREV_TAC `d = poly_extend (k,l) (h:A->B) (\v. a) (poly_deriv k f)` THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`; `f:(1->num)->A`;
                 `d:B`] NUMBER_FIELD_POWER_BASIS_DATA) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`; `f:(1->num)->A`;
                 `d:B`] NUMBER_FIELD_CODIFFERENT_POWER_BASIS) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC
   `R = ring_carrier(subring_generated l
          (a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k))))` THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "codiff")) THEN
  DISCH_THEN(X_CHOOSE_THEN `b:(1->num)->B` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM(K ALL_TAC o check (fun th ->
    is_eq(concl th) && lhs(concl th) = `R:B->bool`)) THEN
  SUBGOAL_THEN
   `!z. z IN R ==> (z:B) IN ring_carrier(ring_of_integers l) /\
                   z IN ring_carrier l`
  ASSUME_TAC THENL
   [MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN
    UNDISCH_TAC `R SUBSET ring_carrier(ring_of_integers(l:B ring))` THEN
    SET_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[number_field_different; IN_ELIM_THM] THEN CONJ_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  X_GEN_TAC `y:B` THEN
  REWRITE_TAC[number_field_codifferent; IN_ELIM_THM] THEN STRIP_TAC THEN
  SUBGOAL_THEN `(y:B) IN IMAGE (ring_mul l (ring_inv l d)) R` MP_TAC THENL
   [USE_THEN "codiff" (SUBST1_TAC o SYM) THEN REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
    FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
      is_forall(concl th) &&
      can (find_term ((=) `ring_of_integers(l:B ring)`)) (concl th) &&
      can (find_term ((=) `y:B`)) (concl th))) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[IN_IMAGE] THEN
  DISCH_THEN(X_CHOOSE_THEN `w:B` (CONJUNCTS_THEN2 SUBST1_TAC ASSUME_TAC)) THEN
  SUBGOAL_THEN `(d:B) IN ring_carrier l /\ (w:B) IN ring_carrier l`
  STRIP_ASSUME_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  ASM_SIMP_TAC[RING_MUL_ASSOC; RING_INV; FIELD_MUL_RINV; RING_MUL_LID]);;

(* If O_l = O_k[a] then the codifferent is (1/Df(a)) O_l and D = (Df(a)).    *)
let NUMBER_FIELD_DIFFERENT_POWER_BASIS = prove
 (`!k:A ring l:B ring h a f d.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        a IN ring_carrier l /\
        ring_carrier(subring_generated l
          (a INSERT IMAGE h (ring_carrier(ring_of_integers k)))) =
        ring_carrier(ring_of_integers l) /\
        f = minimal_polynomial (k,l) h a /\
        d = poly_extend (k,l) h (\v. a) (poly_deriv k f)
        ==> number_field_codifferent (k,l) h =
            IMAGE (ring_mul l (ring_inv l d))
                  (ring_carrier(ring_of_integers l)) /\
            number_field_different (k,l) h =
            ideal_generated (ring_of_integers l) {d}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(ASSUME_TAC o SYM o
    check (fun th -> lhs(concl th) = `d:B`)) THEN
  FIRST_X_ASSUM(ASSUME_TAC o SYM o
    check (fun th -> lhs(concl th) = `f:(1->num)->A`)) THEN
  SUBGOAL_THEN `(a:B) IN ring_carrier(ring_of_integers l)` ASSUME_TAC THENL
   [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) &&
      rhs(concl th) = `ring_carrier(ring_of_integers(l:B ring))`)) THEN
    MATCH_MP_TAC SUBRING_GENERATED_INC THEN REWRITE_TAC[IN_INSERT] THEN
    REWRITE_TAC[INSERT_SUBSET; SUBSET; FORALL_IN_IMAGE] THEN
    ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER; RING_OF_INTEGERS_SUBSET;
                  SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `subring_generated l (a INSERT IMAGE (h:A->B) (ring_carrier k)) = l`
  ASSUME_TAC THENL
   [MATCH_MP_TAC NUMBER_FIELD_POWER_BASIS_GENERATOR THEN
    EXISTS_TAC `ring_1 k:A` THEN ASM_REWRITE_TAC[RING_1] THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
      check (fun th -> concl th = `number_field(l:B ring)`)) THEN
    ASM_SIMP_TAC[FIELD_NONTRIVIAL] THEN
    FIRST_ASSUM(fun th -> REWRITE_TAC[MATCH_MP RING_HOMOMORPHISM_1 th]) THEN
    MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN
    SIMP_TAC[SUBSET; RING_MUL_LID];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`; `f:(1->num)->A`;
                 `d:B`] NUMBER_FIELD_CODIFFERENT_POWER_BASIS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC MP_TAC) THEN
  REWRITE_TAC[GSYM number_field_codifferent] THEN DISCH_TAC THEN
  ASM_REWRITE_TAC[] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  SUBGOAL_THEN `(d:B) IN ring_carrier(ring_of_integers l)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:B`]
      NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT) THEN
    ASM_REWRITE_TAC[] THEN
    SIMP_TAC[number_field_different; IN_ELIM_THM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!z. z IN ring_carrier(ring_of_integers l) ==> (z:B) IN ring_carrier l`
  ASSUME_TAC THENL
   [MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_SING_ALT; RING_OF_INTEGERS] THEN
  REWRITE_TAC[number_field_different] THEN ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[FORALL_IN_IMAGE; EXTENSION; IN_ELIM_THM] THEN
  X_GEN_TAC `x:B` THEN EQ_TAC THENL
   [STRIP_TAC THEN
    EXISTS_TAC `ring_mul l x (ring_mul l (ring_inv l d) (ring_1 l:B))` THEN
    ASM_SIMP_TAC[RING_1; IN_SUBRING_1; RING_OF_INTEGERS_SUBRING] THEN
    ASM_SIMP_TAC[RING_MUL_RID; RING_INV; RING_MUL_ASSOC] THEN
    ONCE_REWRITE_TAC[MATCH_MP RING_MUL_SYM (CONJ
     (MATCH_MP (ASSUME `!z. z IN ring_carrier(ring_of_integers l)
                            ==> (z:B) IN ring_carrier l`)
               (ASSUME `(d:B) IN ring_carrier(ring_of_integers l)`))
     (MATCH_MP (ASSUME `!z. z IN ring_carrier(ring_of_integers l)
                            ==> (z:B) IN ring_carrier l`)
               (ASSUME `(x:B) IN ring_carrier(ring_of_integers l)`)))] THEN
    ASM_SIMP_TAC[GSYM RING_MUL_ASSOC; RING_INV; FIELD_MUL_RINV;
                 RING_MUL_RID];
    DISCH_THEN(X_CHOOSE_THEN `z:B` STRIP_ASSUME_TAC) THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [MATCH_MP_TAC IN_SUBRING_MUL THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBRING];
      X_GEN_TAC `w:B` THEN DISCH_TAC THEN
      SUBGOAL_THEN
       `ring_mul l (ring_mul l d z) (ring_mul l (ring_inv l d) w) =
        ring_mul l (z:B) w`
      SUBST1_TAC THENL
       [MP_TAC(RING_RULE
         `!(l:B ring) d e z w.
            ring_mul l d e = ring_1 l
            ==> ring_mul l (ring_mul l d z) (ring_mul l e w) =
                ring_mul l z w`) THEN
        DISCH_THEN(MP_TAC o SPECL
         [`l:B ring`; `d:B`; `ring_inv l d:B`; `z:B`; `w:B`]) THEN
        ASM_SIMP_TAC[RING_INV; FIELD_MUL_RINV];
        MATCH_MP_TAC IN_SUBRING_MUL THEN
        ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBRING]]]]);;

(* The case k = Q of NUMBER_FIELD_CODIFFERENT_POWER_BASIS,                   *)
(* NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT and                                  *)
(* NUMBER_FIELD_DIFFERENT_POWER_BASIS, for Q the prime subfield of k and     *)
(* Z[a] = subring_generated k {a}: for an algebraic integer a whose minimal  *)
(* polynomial f has degree [k:Q] the trace dual of Z[a] is Df(a)^-1 Z[a] and *)
(* Df(a) lies in the different; if O = Z[a] then the codifferent is Df(a)^-1 *)
(* O and the different is (Df(a)). Here O_Q[a] = Z[a] since O_Q is the image *)
(* of Z (RING_OF_INTEGERS_PRIME_SUBFIELD_CARRIER; lemma_zq), and f of degree *)
(* [k:Q] means k = Q(a) (FINITE_EXTENSION_SIMPLE_EQ).                        *)
let NUMBER_FIELD_CODIFFERENT_POWER_BASIS_Q,
    NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT_Q,
    NUMBER_FIELD_DIFFERENT_POWER_BASIS_Q =
  let lemma_zq = prove
   (`!k:A ring a.
          field k /\ a IN ring_carrier k
          ==> subring_generated k
                (a INSERT IMAGE I (ring_carrier(ring_of_integers
                  (subfield_generated k {ring_0 k})))) =
              subring_generated k {a}`,
    REPEAT STRIP_TAC THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS_PRIME_SUBFIELD_CARRIER; IMAGE_I] THEN
    REWRITE_TAC[RINGS_EQ; CONJUNCT2 SUBRING_GENERATED] THEN
    MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THEN
    MATCH_MP_TAC SUBRING_GENERATED_MINIMAL THEN
    REWRITE_TAC[SUBRING_SUBRING_GENERATED; INSERT_SUBSET; EMPTY_SUBSET] THEN
    ASM_SIMP_TAC[SUBRING_GENERATED_INC_GEN; IN_INSERT] THEN
    MATCH_MP_TAC PRIME_SUBRING_MINIMAL THEN
    REWRITE_TAC[SUBRING_SUBRING_GENERATED]) in
  let th1 = prove
   (`!(k:A ring) a f d.
          number_field k /\ a IN ring_carrier(ring_of_integers k) /\
          f = minimal_polynomial (subfield_generated k {ring_0 k},k) I a /\
          poly_deg (subfield_generated k {ring_0 k}) f =
          extension_degree (subfield_generated k {ring_0 k},k) I /\
          d = poly_extend (subfield_generated k {ring_0 k},k) I (\v. a)
                (poly_deriv (subfield_generated k {ring_0 k}) f)
          ==> ~(d = ring_0 k) /\
              {x | x IN ring_carrier k /\
                   !y. y IN ring_carrier(subring_generated k {a})
                       ==> algebra_trace (subfield_generated k {ring_0 k},k) I
                             (ring_mul k x y) IN
                           ring_carrier(ring_of_integers k)} =
              IMAGE (ring_mul k (ring_inv k d))
                    (ring_carrier(subring_generated k {a}))`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
    MP_TAC(ISPECL [`subfield_generated k {ring_0 k}:A ring`; `k:A ring`;
                   `I:A->A`; `a:A`; `f:(1->num)->A`; `d:A`]
      NUMBER_FIELD_CODIFFERENT_POWER_BASIS) THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION; lemma_zq] THEN
    ANTS_TAC THENL
     [ASM_MESON_TAC[FINITE_EXTENSION_SIMPLE_EQ; number_field];
      REWRITE_TAC[RING_OF_INTEGERS_SUBFIELD_GENERATED; IN_INTER;
                  ALGEBRA_TRACE_NORM_IN_CARRIER]]) in
  let th2 = prove
   (`!(k:A ring) a f d.
          number_field k /\ a IN ring_carrier(ring_of_integers k) /\
          f = minimal_polynomial (subfield_generated k {ring_0 k},k) I a /\
          poly_deg (subfield_generated k {ring_0 k}) f =
          extension_degree (subfield_generated k {ring_0 k},k) I /\
          d = poly_extend (subfield_generated k {ring_0 k},k) I (\v. a)
                (poly_deriv (subfield_generated k {ring_0 k}) f)
          ==> d IN
              number_field_different (subfield_generated k {ring_0 k},k) I`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC NUMBER_FIELD_DERIVATIVE_IN_DIFFERENT THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION] THEN
    ASM_MESON_TAC[FINITE_EXTENSION_SIMPLE_EQ; number_field]) in
  let th3 = prove
   (`!(k:A ring) a f d.
          number_field k /\ a IN ring_carrier k /\
          ring_carrier(subring_generated k {a}) =
          ring_carrier(ring_of_integers k) /\
          f = minimal_polynomial (subfield_generated k {ring_0 k},k) I a /\
          d = poly_extend (subfield_generated k {ring_0 k},k) I (\v. a)
                (poly_deriv (subfield_generated k {ring_0 k}) f)
          ==> number_field_codifferent (subfield_generated k {ring_0 k},k) I =
              IMAGE (ring_mul k (ring_inv k d))
                    (ring_carrier(ring_of_integers k)) /\
              number_field_different (subfield_generated k {ring_0 k},k) I =
              ideal_generated (ring_of_integers k) {d}`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
    MP_TAC(ISPECL [`subfield_generated k {ring_0 k}:A ring`; `k:A ring`;
                   `I:A->A`; `a:A`; `f:(1->num)->A`; `d:A`]
      NUMBER_FIELD_DIFFERENT_POWER_BASIS) THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION; lemma_zq]) in
  th1, th2, th3;;

(* If h(s) O_l SUBSET O_k[a] for some s in O_k outside p then D and (Df(a))  *)
(* have the same valuation at every prime Q of O_l above p.                  *)
let NUMBER_FIELD_DIFFERENT_LOCAL_POWER_BASIS = prove
 (`!k:A ring l:B ring h p a s Q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        a IN ring_carrier(ring_of_integers l) /\
        s IN ring_carrier(ring_of_integers k) /\ ~(s IN p) /\
        (!y. y IN ring_carrier(ring_of_integers l)
             ==> ring_mul l (h s) y IN
                 ring_carrier(subring_generated l
                   (a INSERT IMAGE h (ring_carrier(ring_of_integers k))))) /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h p SUBSET Q
        ==> ideal_valuation (ring_of_integers l) Q
              (number_field_different (k,l) h) =
            ideal_valuation (ring_of_integers l) Q
              (ideal_generated (ring_of_integers l)
                 {poly_extend (k,l) h (\v. a)
                    (poly_deriv k (minimal_polynomial (k,l) h a))})`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC
   `R = ring_carrier(subring_generated l
          (a INSERT IMAGE (h:A->B) (ring_carrier(ring_of_integers k))))` THEN
  STRIP_TAC THEN
  ABBREV_TAC `f = minimal_polynomial (k,l) (h:A->B) a` THEN
  ABBREV_TAC `d = poly_extend (k,l) (h:A->B) (\v. a) (poly_deriv k f)` THEN
  ABBREV_TAC `D = number_field_different (k,l) (h:A->B)` THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  SUBGOAL_THEN
   `!z. z IN ring_carrier(ring_of_integers l) ==> (z:B) IN ring_carrier l`
  ASSUME_TAC THENL
   [MP_TAC(ISPEC `l:B ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!c. c IN ring_carrier(ring_of_integers k) ==> (c:A) IN ring_carrier k`
  ASSUME_TAC THENL
   [MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
