              (ideal_product r (monomial_vars f) (\p. ideal_pow r p (f p)))`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[MONOMIAL_VARS_MUL] THEN
  TRANS_TAC EQ_TRANS
   `ideal_product r (monomial_vars e UNION monomial_vars f)
      (\p. ideal_prod r (ideal_pow r p (e p))
                        (ideal_pow r p ((f:(A->bool)->num) p)))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN
    ASM_SIMP_TAC[monomial_mul; IDEAL_POW_ADD; RING_IDEAL_IMP_SUBSET];
    ASM_SIMP_TAC[IDEAL_PRODUCT_MUL; FINITE_UNION; RING_IDEAL_IDEAL_POW] THEN
    BINOP_TAC THEN MATCH_MP_TAC IDEAL_PRODUCT_SUPERSET THEN
    ASM_SIMP_TAC[FINITE_UNION; RING_IDEAL_IDEAL_POW; SUBSET_UNION] THEN
    REWRITE_TAC[monomial_vars; IN_ELIM_THM] THEN SIMP_TAC[ideal_pow]]);;

