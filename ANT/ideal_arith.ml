(* Induction on s: j b is comaximal to the product of the j i, i IN s, and   *)
(* the two-ideal construction of CHINESE_REMAINDER_RING_ISOMORPHISM moves a  *)
(* solution y for s to a solution for b INSERT s.                            *)

let CHINESE_REMAINDER_IDEALS = prove
 (`!r s (j:K->A->bool) (a:K->A).
        FINITE s /\
        (!i. i IN s ==> ring_ideal r (j i) /\ a i IN ring_carrier r) /\
        pairwise (\i i'. ring_setadd r (j i) (j i') = ring_carrier r) s
        ==> ?x. x IN ring_carrier r /\
                !i. i IN s ==> ring_sub r x (a i) IN j i`,
  GEN_TAC THEN REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN
  MATCH_MP_TAC FINITE_INDUCT_STRONG THEN CONJ_TAC THENL
   [MESON_TAC[RING_0; NOT_IN_EMPTY]; ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`b:K`; `s:K->bool`] THEN STRIP_TAC THEN
  MAP_EVERY X_GEN_TAC [`j:K->A->bool`; `a:K->A`] THEN
  REWRITE_TAC[FORALL_IN_INSERT; PAIRWISE_INSERT] THEN REPEAT STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`j:K->A->bool`; `a:K->A`]) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`r:A ring`; `(j:K->A->bool) b`; `s:K->bool`; `j:K->A->bool`]
    COMAXIMAL_IDEAL_PRODUCT) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[RING_COMAXIMAL; RING_IDEAL_IDEAL_PRODUCT;
               LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`c:A`; `d:A`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `(c:A) IN ring_carrier r /\ d IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PRODUCT; SUBSET];
    ALL_TAC] THEN
  EXISTS_TAC `ring_add r (ring_mul r ((a:K->A) b) d) (ring_mul r y c)` THEN
  ASM_SIMP_TAC[RING_ADD; RING_MUL] THEN CONJ_TAC THENL
   [SUBGOAL_THEN
     `ring_sub r (ring_add r (ring_mul r (a b) d) (ring_mul r y c))
                 ((a:K->A) b) =
      ring_mul r (ring_sub r y (a b)) c`
    SUBST1_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `!u y c d:A.
          u IN ring_carrier r /\ y IN ring_carrier r /\
          c IN ring_carrier r /\ d IN ring_carrier r /\
          ring_add r c d = ring_1 r
          ==> ring_sub r (ring_add r (ring_mul r u d) (ring_mul r y c)) u =
              ring_mul r (ring_sub r y u) c`) THEN
      ASM_REWRITE_TAC[];
      ASM_SIMP_TAC[IN_RING_IDEAL_LMUL; RING_SUB]];
    X_GEN_TAC `i:K` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `ring_sub r (ring_add r (ring_mul r (a b) d) (ring_mul r y c))
                 ((a:K->A) i) =
      ring_add r (ring_mul r (ring_sub r (a b) y) d) (ring_sub r y (a i))`
    SUBST1_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `!u y c d z:A.
          u IN ring_carrier r /\ y IN ring_carrier r /\
          c IN ring_carrier r /\ d IN ring_carrier r /\
          z IN ring_carrier r /\ ring_add r c d = ring_1 r
          ==> ring_sub r (ring_add r (ring_mul r u d) (ring_mul r y c)) z =
              ring_add r (ring_mul r (ring_sub r u y) d) (ring_sub r y z)`) THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC IN_RING_IDEAL_ADD THEN ASM_SIMP_TAC[] THEN
      MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN ASM_SIMP_TAC[RING_SUB] THEN
      ASM_MESON_TAC[IDEAL_PRODUCT_SUBSET; SUBSET]]]);;

(* Products indexed by monomials: the ideal of a finite-support exponent     *)
(* function e is ideal_product r (monomial_vars e) (\p. ideal_pow r p (e p)) *)
(* and monomial_mul corresponds to the product of ideals.                    *)

let IDEAL_PRODUCT_MONOMIAL_MUL = prove
 (`!r (e:(A->bool)->num) f.
        FINITE(monomial_vars e) /\ FINITE(monomial_vars f) /\
        (!p. p IN monomial_vars e UNION monomial_vars f ==> ring_ideal r p)
