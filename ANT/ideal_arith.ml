(* The Chinese remainder theorem for finite families.                        *)
(* ------------------------------------------------------------------------- *)

(* For a finite pairwise comaximal family the product is the intersection    *)
(* (with ring_carrier r, so that also the empty family gives an ideal), and  *)
(* the quotient by it is the product of the quotients: the map to the        *)
(* product ring has this kernel and is onto by CHINESE_REMAINDER_IDEALS (the *)
(* simultaneous congruences). For two ideals these are IDEAL_PROD_COMAXIMAL  *)
(* and CHINESE_REMAINDER_RING_ISOMORPHISM.                                   *)

let IDEAL_PRODUCT_COMAXIMAL = prove
 (`!r s (f:K->A->bool).
        FINITE s /\ (!i. i IN s ==> ring_ideal r (f i)) /\
        pairwise (\i i'. ring_setadd r (f i) (f i') = ring_carrier r) s
        ==> ideal_product r s f = ring_carrier r INTER INTERS {f i | i IN s}`,
  GEN_TAC THEN REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN
  MATCH_MP_TAC FINITE_INDUCT_STRONG THEN
  REWRITE_TAC[IDEAL_PRODUCT_EMPTY; SIMPLE_IMAGE; IMAGE_CLAUSES; INTERS_0;
              INTER_UNIV] THEN
  MAP_EVERY X_GEN_TAC [`a:K`; `s:K->bool`] THEN STRIP_TAC THEN
  X_GEN_TAC `f:K->A->bool` THEN
  REWRITE_TAC[FORALL_IN_INSERT; PAIRWISE_INSERT] THEN REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `s:K->bool`; `f:K->A->bool`; `a:K`]
    IDEAL_PRODUCT_INSERT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  W(MP_TAC o PART_MATCH (lhand o rand) IDEAL_PROD_COMAXIMAL o lhand o snd) THEN
  ANTS_TAC THENL
