  DISCH_THEN(X_CHOOSE_THEN `s:A` (X_CHOOSE_THEN `t:A` STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN `(s:A) IN ring_carrier r /\ (t:A) IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_add r (ring_mul r a t) (ring_mul r b s) IN ring_carrier(r:A ring)`
  ASSUME_TAC THENL [ASM_SIMP_TAC[RING_ADD; RING_MUL]; ALL_TAC] THEN
  REWRITE_TAC[IN_IMAGE] THEN
  EXISTS_TAC `ring_coset r (j INTER k)
               (ring_add r (ring_mul r a t) (ring_mul r b s)):A->bool` THEN
  CONJ_TAC THENL
   [ALL_TAC; REWRITE_TAC[IN_ELIM_THM] THEN ASM_MESON_TAC[]] THEN
  ASM_SIMP_TAC[PAIR_EQ; RING_COSET_EQ] THEN
  CONJ_TAC THENL
   [SUBGOAL_THEN
     `ring_sub r a (ring_add r (ring_mul r a t) (ring_mul r b s)) =
      ring_mul r (ring_sub r a b) (s:A)`
    SUBST1_TAC THENL [RING_TAC; ASM_SIMP_TAC[IN_RING_IDEAL_LMUL; RING_SUB]];
    SUBGOAL_THEN
     `ring_sub r b (ring_add r (ring_mul r a t) (ring_mul r b s)) =
      ring_mul r (ring_sub r b a) (t:A)`
    SUBST1_TAC THENL [RING_TAC; ASM_SIMP_TAC[IN_RING_IDEAL_LMUL; RING_SUB]]]);;

(* ------------------------------------------------------------------------- *)
(* Ideal quotients (colon ideals).                                           *)
(* ------------------------------------------------------------------------- *)

let ideal_quotient = new_definition
 `ideal_quotient (r:A ring) (j:A->bool) (k:A->bool) =
  {x | x IN ring_carrier r /\
       !y. y IN k ==> ring_mul r x y IN j}`;;

let RING_IDEAL_IDEAL_QUOTIENT = prove
 (`!r:A ring j k.
        ring_ideal r j /\ k SUBSET ring_carrier r
        ==> ring_ideal r (ideal_quotient r j k)`,
  REWRITE_TAC[ring_ideal; ideal_quotient; SUBSET; IN_ELIM_THM] THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_SIMP_TAC[RING_0; RING_MUL_LZERO; RING_NEG; RING_MUL_LNEG; RING_ADD;
               RING_ADD_RDISTRIB; RING_MUL; GSYM RING_MUL_ASSOC]);;

let SUBSET_IDEAL_QUOTIENT = prove
 (`!r j k l:A->bool.
        ring_ideal r j /\ k SUBSET ring_carrier r /\ l SUBSET ring_carrier r
        ==> (l SUBSET ideal_quotient r j k <=> ideal_prod r l k SUBSET j)`,
  REPEAT STRIP_TAC THEN EQ_TAC THEN DISCH_TAC THENL
   [MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
    RULE_ASSUM_TAC(REWRITE_RULE[SUBSET; ideal_quotient; IN_ELIM_THM]) THEN
    ASM_MESON_TAC[];
    REWRITE_TAC[SUBSET; ideal_quotient; IN_ELIM_THM] THEN
    ASM_MESON_TAC[SUBSET; RING_MUL_IN_IDEAL_PROD]]);;

let IDEAL_SUBSET_IDEAL_QUOTIENT = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ k SUBSET ring_carrier r
        ==> j SUBSET ideal_quotient r j k`,
  REWRITE_TAC[ideal_quotient; SUBSET; IN_ELIM_THM] THEN
  MESON_TAC[IN_RING_IDEAL_RMUL; RING_IDEAL_IMP_SUBSET; SUBSET]);;

let IDEAL_QUOTIENT_MONO = prove
 (`!r j j' k k':A->bool.
        j SUBSET j' /\ k' SUBSET k
        ==> ideal_quotient r j k SUBSET ideal_quotient r j' k'`,
  REWRITE_TAC[ideal_quotient] THEN SET_TAC[]);;

let IDEAL_QUOTIENT_EQ_CARRIER = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ k SUBSET ring_carrier r
        ==> (ideal_quotient r j k = ring_carrier r <=> k SUBSET j)`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[RING_IDEAL_EQ_CARRIER; RING_IDEAL_IDEAL_QUOTIENT] THEN
  REWRITE_TAC[ideal_quotient; IN_ELIM_THM; RING_1] THEN
  ASM_MESON_TAC[RING_MUL_LID; SUBSET]);;

let IDEAL_QUOTIENT_CARRIER = prove
 (`!r j:A->bool.
        ring_ideal r j ==> ideal_quotient r j (ring_carrier r) = j`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_quotient; EXTENSION; IN_ELIM_THM] THEN
  ASM_MESON_TAC[RING_MUL_RID; RING_1; IN_RING_IDEAL_RMUL;
                RING_IDEAL_IMP_SUBSET; SUBSET]);;

(* By the adjunction SUBSET_IDEAL_QUOTIENT, applied to singletons.           *)

let IDEAL_QUOTIENT_IDEAL_PROD = prove
 (`!r j k l:A->bool.
        ring_ideal r j /\ k SUBSET ring_carrier r /\ l SUBSET ring_carrier r
        ==> ideal_quotient r j (ideal_prod r k l) =
            ideal_quotient r (ideal_quotient r j k) l`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[EXTENSION] THEN X_GEN_TAC `x:A` THEN
  ASM_CASES_TAC `(x:A) IN ring_carrier r` THENL
   [ONCE_REWRITE_TAC[GSYM SING_SUBSET];
    ASM_REWRITE_TAC[ideal_quotient; IN_ELIM_THM]] THEN
  SUBGOAL_THEN `{x:A} SUBSET ring_carrier r` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[SING_SUBSET]; ALL_TAC] THEN
  ASM_SIMP_TAC[SUBSET_IDEAL_QUOTIENT; RING_IDEAL_IDEAL_QUOTIENT;
               RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD] THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD]);;

let IDEAL_QUOTIENT_SETADD = prove
 (`!r j k l:A->bool.
        ring_ideal r j /\ ring_ideal r k /\ ring_ideal r l
        ==> ideal_quotient r j (ring_setadd r k l) =
            ideal_quotient r j k INTER ideal_quotient r j l`,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[ideal_quotient; ring_setadd; EXTENSION; IN_INTER;
              IN_ELIM_THM] THEN
  X_GEN_TAC `x:A` THEN ASM_CASES_TAC `(x:A) IN ring_carrier r` THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MP_TAC(ISPECL [`r:A ring`; `k:A->bool`] RING_IDEAL_IMP_SUBSET) THEN
  MP_TAC(ISPECL [`r:A ring`; `l:A->bool`] RING_IDEAL_IMP_SUBSET) THEN
  ASM_REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN EQ_TAC THENL
   [DISCH_TAC THEN CONJ_TAC THEN X_GEN_TAC `y:A` THEN DISCH_TAC THEN
    FIRST_X_ASSUM MATCH_MP_TAC THENL
     [MAP_EVERY EXISTS_TAC [`y:A`; `ring_0 r:A`];
      MAP_EVERY EXISTS_TAC [`ring_0 r:A`; `y:A`]] THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0; RING_ADD_RZERO; RING_ADD_LZERO];
    STRIP_TAC THEN MAP_EVERY X_GEN_TAC [`y:A`; `a:A`; `b:A`] THEN
    STRIP_TAC THEN ASM_SIMP_TAC[RING_ADD_LDISTRIB; IN_RING_IDEAL_ADD]]);;

let IDEAL_QUOTIENT_INTER = prove
 (`!r j k l:A->bool.
        ideal_quotient r (j INTER k) l =
        ideal_quotient r j l INTER ideal_quotient r k l`,
  REWRITE_TAC[ideal_quotient; EXTENSION; IN_INTER; IN_ELIM_THM] THEN
  MESON_TAC[]);;

let IDEAL_QUOTIENT_PRIME_IDEAL = prove
 (`!r p j:A->bool.
        prime_ideal r p /\ j SUBSET ring_carrier r /\ ~(j SUBSET p)
        ==> ideal_quotient r p j = p`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
  ASM_SIMP_TAC[IDEAL_SUBSET_IDEAL_QUOTIENT; PRIME_IMP_RING_IDEAL] THEN
  FIRST_X_ASSUM(X_CHOOSE_TAC `y:A` o
    REWRITE_RULE[SUBSET; NOT_FORALL_THM; NOT_IMP]) THEN
  REWRITE_TAC[ideal_quotient; SUBSET; IN_ELIM_THM] THEN
  ASM_MESON_TAC[RING_MUL_IN_PRIME_IDEAL; SUBSET]);;

(* ------------------------------------------------------------------------- *)
(* Powers of an ideal.                                                       *)
(* ------------------------------------------------------------------------- *)

let ideal_pow = new_recursive_definition num_RECURSION
 `(ideal_pow (r:A ring) (j:A->bool) 0 = ring_carrier r) /\
  (ideal_pow r j (SUC n) = ideal_prod r j (ideal_pow r j n))`;;

let IDEAL_POW_0 = prove
 (`!r:A ring j. ideal_pow r j 0 = ring_carrier r`,
  REWRITE_TAC[ideal_pow]);;

let IDEAL_POW_SUC = prove
 (`!r:A ring j n.
        ideal_pow r j (SUC n) = ideal_prod r j (ideal_pow r j n)`,
  REWRITE_TAC[ideal_pow]);;

let IDEAL_POW_ALT = prove
 (`!r:A ring j n.
        ideal_pow r j n =
        if n = 0 then ring_carrier r
        else ITLIST (ideal_prod r) (REPLICATE n j) (ring_carrier r)`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_REWRITE_TAC[ideal_pow; REPLICATE; ITLIST; NOT_SUC] THEN
  COND_CASES_TAC THEN ASM_REWRITE_TAC[REPLICATE; ITLIST]);;

let IDEAL_POW_1 = prove
 (`!r:A ring j.
        ring_ideal r j
        ==> ideal_pow r j 1 = j`,
  SIMP_TAC[num_CONV `1`; ideal_pow; IDEAL_PROD_CARRIER]);;

let IDEAL_POW_CARRIER = prove
 (`!r:A ring n. ideal_pow r (ring_carrier r) n = ring_carrier r`,
  GEN_TAC THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[IDEAL_POW_0; IDEAL_POW_SUC; IDEAL_PROD_CARRIER;
               RING_IDEAL_CARRIER]);;

let RING_IDEAL_IDEAL_POW = prove
 (`!r:A ring j n. ring_ideal r (ideal_pow r j n)`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  REWRITE_TAC[ideal_pow; RING_IDEAL_CARRIER; RING_IDEAL_IDEAL_PROD]);;

let IDEAL_POW_ADD = prove
 (`!r:A ring j m n.
        j SUBSET ring_carrier r
        ==> ideal_pow r j (m + n) =
            ideal_prod r (ideal_pow r j m) (ideal_pow r j n)`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ADD_CLAUSES; ideal_pow; IDEAL_PROD_CARRIER_LEFT;
               RING_IDEAL_IDEAL_POW; IDEAL_PROD_ASSOC; RING_IDEAL_IMP_SUBSET]);;

let IDEAL_POW_MUL = prove
 (`!r:A ring j m n.
        j SUBSET ring_carrier r
        ==> ideal_pow r j (m * n) = ideal_pow r (ideal_pow r j m) n`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN SPEC_TAC(`n:num`,`n:num`) THEN
  INDUCT_TAC THEN ASM_REWRITE_TAC[MULT_CLAUSES; IDEAL_POW_0; IDEAL_POW_SUC] THEN
  ASM_SIMP_TAC[IDEAL_POW_ADD] THEN MATCH_ACCEPT_TAC IDEAL_PROD_COMM);;

let RING_MUL_IN_IDEAL_POW = prove
 (`!r j (x:A) y m n.
        j SUBSET ring_carrier r /\
        x IN ideal_pow r j m /\ y IN ideal_pow r j n
        ==> ring_mul r x y IN ideal_pow r j (m + n)`,
  REPEAT STRIP_TAC THEN ASM_SIMP_TAC[IDEAL_POW_ADD] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN ASM_REWRITE_TAC[] THEN
  ASM_MESON_TAC[RING_IDEAL_IDEAL_POW; RING_IDEAL_IMP_SUBSET; SUBSET]);;

let RING_POW_IN_IDEAL_POW = prove
 (`!r (j:A->bool) x n.
        ring_ideal r j /\ x IN j ==> ring_pow r x n IN ideal_pow r j n`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SPEC_TAC(`n:num`,`n:num`) THEN
  INDUCT_TAC THEN REWRITE_TAC[ring_pow; IDEAL_POW_0; RING_1] THEN
  REWRITE_TAC[IDEAL_POW_SUC] THEN MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
  ASM_SIMP_TAC[RING_POW]);;

let IDEAL_POW_MONO = prove
 (`!r j k:A->bool n.
        j SUBSET k ==> ideal_pow r j n SUBSET ideal_pow r k n`,
  GEN_TAC THEN GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ideal_pow; SUBSET_REFL; IDEAL_PROD_MONO]);;

let IDEAL_POW_ANTIMONO = prove
 (`!r j:A->bool m n.
        j SUBSET ring_carrier r /\ m <= n
        ==> ideal_pow r j n SUBSET ideal_pow r j m`,
  GEN_TAC THEN GEN_TAC THEN
  REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN DISCH_TAC THEN
  MATCH_MP_TAC TRANSITIVE_STEPWISE_LE THEN
  REWRITE_TAC[SUBSET_REFL] THEN CONJ_TAC THENL [SET_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[ideal_pow; IDEAL_PROD_SUBSET_RIGHT; RING_IDEAL_IDEAL_POW]);;

let IDEAL_POW_SUC_SUBSET = prove
 (`!r j:A->bool n.
        ring_ideal r j ==> ideal_pow r j (SUC n) SUBSET ideal_pow r j n`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC IDEAL_POW_ANTIMONO THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN ARITH_TAC);;

let IDEAL_POW_HOMOMORPHIC_IMAGE_SUBSET = prove
 (`!r r' (f:A->B) j j' n.
        ring_homomorphism(r,r') f /\ ring_ideal r j /\ ring_ideal r' j' /\
        IMAGE f j SUBSET j'
        ==> IMAGE f (ideal_pow r j n) SUBSET ideal_pow r' j' n`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN SPEC_TAC(`n:num`,`n:num`) THEN
  INDUCT_TAC THENL
   [REWRITE_TAC[IDEAL_POW_0] THEN ASM_MESON_TAC[ring_homomorphism];
    ALL_TAC] THEN
  REWRITE_TAC[IDEAL_POW_SUC] THEN
  MP_TAC(ISPECL [`r:A ring`; `r':B ring`; `f:A->B`;
                 `ideal_prod r' j' (ideal_pow r' j' n):B->bool`]
    RING_IDEAL_HOMOMORPHIC_PREIMAGE) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN DISCH_TAC THEN
  MATCH_MP_TAC(SET_RULE
   `!t. s SUBSET {x | x IN t /\ (f:A->B) x IN u} ==> IMAGE f s SUBSET u`) THEN
  EXISTS_TAC `ring_carrier r:A->bool` THEN
  MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN ASM_REWRITE_TAC[] THEN
  MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r /\ (b:A) IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_POW; SUBSET];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IN_ELIM_THM; RING_MUL] THEN
  FIRST_ASSUM(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_MUL th]) THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
  ASM_MESON_TAC[ring_homomorphism; SUBSET; FUN_IN_IMAGE]);;

let IDEAL_POW_IDEAL_PROD = prove
 (`!r j k:A->bool n.
        j SUBSET ring_carrier r /\ k SUBSET ring_carrier r
        ==> ideal_pow r (ideal_prod r j k) n =
            ideal_prod r (ideal_pow r j n) (ideal_pow r k n)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SPEC_TAC(`n:num`,`n:num`) THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ideal_pow; IDEAL_PROD_CARRIER; RING_IDEAL_CARRIER] THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD;
               RING_IDEAL_IDEAL_POW]);;

let IDEAL_POW_PRINCIPAL = prove
 (`!r (a:A) n.
        a IN ring_carrier r
        ==> ideal_pow r (ideal_generated r {a}) n =
            ideal_generated r {ring_pow r a n}`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ideal_pow; ring_pow; IDEAL_PROD_PRINCIPAL; RING_POW] THEN
  ONCE_REWRITE_TAC[EQ_SYM_EQ] THEN
  SIMP_TAC[IDEAL_GENERATED_SING_EQ_CARRIER; RING_1; RING_UNIT_1]);;

let IDEAL_POW_EQ_ZERO = prove
 (`!r j:A->bool n.
        integral_domain r /\ ring_ideal r j
        ==> (ideal_pow r j n = {ring_0 r} <=> j = {ring_0 r} /\ ~(n = 0))`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ideal_pow; IDEAL_PROD_EQ_ZERO; RING_IDEAL_IDEAL_POW;
               NOT_SUC] THEN
  SIMP_TAC[GSYM trivial_ring; TRIVIAL_RING_10; INTEGRAL_DOMAIN_NONTRIVIAL] THEN
  CONV_TAC TAUT);;

let IDEAL_POW_SUBSET_PRIME_IDEAL = prove
 (`!r p j:A->bool n.
        prime_ideal r p /\ j SUBSET ring_carrier r
        ==> (ideal_pow r j n SUBSET p <=> j SUBSET p /\ ~(n = 0))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SPEC_TAC(`n:num`,`n:num`) THEN INDUCT_TAC THEN
  ASM_SIMP_TAC[ideal_pow; IDEAL_PROD_SUBSET_PRIME_IDEAL; NOT_SUC;
               RING_IDEAL_IDEAL_POW; RING_IDEAL_IMP_SUBSET] THENL
   [ASM_MESON_TAC[PRIME_IDEAL_IMP_PSUBSET;
                  SET_RULE `!s t:A->bool. s PSUBSET t ==> ~(t SUBSET s)`];
    CONV_TAC TAUT]);;

let RADICAL_IDEAL_PROD = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ ring_ideal r k
        ==> radical r (ideal_prod r j k) = radical r j INTER radical r k`,
  REPEAT STRIP_TAC THEN ASM_SIMP_TAC[GSYM RADICAL_INTER] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN
  ASM_SIMP_TAC[RADICAL_MONO; IDEAL_PROD_SUBSET_INTER] THEN
  REWRITE_TAC[radical; SUBSET; IN_ELIM_THM; IN_INTER] THEN
  X_GEN_TAC `x:A` THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  EXISTS_TAC `n + n:num` THEN ASM_SIMP_TAC[RING_POW_ADD; ADD_EQ_0] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN ASM_SIMP_TAC[RING_POW]);;

let RADICAL_IDEAL_POW = prove
 (`!r j:A->bool n.
        ring_ideal r j /\ ~(n = 0)
        ==> radical r (ideal_pow r j n) = radical r j`,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN REWRITE_TAC[NOT_SUC] THEN
  ASM_CASES_TAC `n = 0` THEN
  ASM_SIMP_TAC[ideal_pow; IDEAL_PROD_CARRIER; RADICAL_IDEAL_PROD;
               RING_IDEAL_IDEAL_POW; INTER_IDEMPOT]);;

let RADICAL_PRIME_IDEAL_POW = prove
 (`!r p:A->bool n.
        prime_ideal r p /\ ~(n = 0) ==> radical r (ideal_pow r p n) = p`,
  SIMP_TAC[RADICAL_IDEAL_POW; PRIME_IMP_RING_IDEAL; RADICAL_PRIME_IDEAL]);;

(* Positive powers have the same radicals, and comaximality only depends     *)
(* on the radicals (library COMAXIMAL_RADICALS).                             *)

let COMAXIMAL_IDEAL_POW = prove
 (`!r j k:A->bool m n.
        ring_ideal r j /\ ring_ideal r k /\
        ring_setadd r j k = ring_carrier r
        ==> ring_setadd r (ideal_pow r j m) (ideal_pow r k n) =
            ring_carrier r`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `ideal_pow r j m SUBSET ring_carrier r /\ ~(ideal_pow r j m = {}) /\
    ideal_pow r k n SUBSET ring_carrier r /\ ~(ideal_pow r k n:A->bool = {})`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IDEAL_POW; RING_IDEAL_IMP_SUBSET;
                  RING_IDEAL_IMP_NONEMPTY];
    ALL_TAC] THEN
  ASM_CASES_TAC `m = 0` THEN
  ASM_SIMP_TAC[IDEAL_POW_0; RING_SETADD_RSUBSET; RING_IDEAL_CARRIER] THEN
  ASM_CASES_TAC `n = 0` THEN
  ASM_SIMP_TAC[IDEAL_POW_0; RING_SETADD_LSUBSET; RING_IDEAL_CARRIER] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_pow r j m:A->bool`;
                 `ideal_pow r k n:A->bool`] COMAXIMAL_RADICALS) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; RADICAL_IDEAL_POW] THEN
  ASM_SIMP_TAC[COMAXIMAL_RADICALS]);;

let IDEAL_POW_SETADD_SUBSET = prove
 (`!r i j:A->bool n.
        ring_ideal r i /\ ring_ideal r j
        ==> ideal_pow r (ring_setadd r i j) n SUBSET
            ring_setadd r i (ideal_pow r j n)`,
  REWRITE_TAC[RIGHT_FORALL_IMP_THM] THEN REPEAT GEN_TAC THEN STRIP_TAC THEN
  INDUCT_TAC THEN REWRITE_TAC[IDEAL_POW_0; IDEAL_POW_SUC] THENL
   [REWRITE_TAC[SUBSET; ring_setadd; IN_ELIM_THM] THEN
    X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    MAP_EVERY EXISTS_TAC [`ring_0 r:A`; `x:A`] THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0; RING_ADD_LZERO];
    TRANS_TAC SUBSET_TRANS
     `ideal_prod r (ring_setadd r i j)
                   (ring_setadd r i (ideal_pow r j n)):A->bool` THEN
    ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL; IDEAL_PROD_SETADD_SUBSET;
                 RING_IDEAL_IDEAL_POW]]);;

(* ------------------------------------------------------------------------- *)
(* Products of finite families of ideals.                                    *)
(* ------------------------------------------------------------------------- *)

let ideal_product = new_definition
 `ideal_product (r:A ring) (s:K->bool) (f:K->A->bool) =
  ideal_generated r {ring_product r s a | a | !i. i IN s ==> a i IN f i}`;;

let RING_IDEAL_IDEAL_PRODUCT = prove
 (`!r:A ring s (f:K->A->bool). ring_ideal r (ideal_product r s f)`,
  REWRITE_TAC[ideal_product; RING_IDEAL_IDEAL_GENERATED]);;

let RING_PRODUCT_IN_IDEAL_PRODUCT = prove
 (`!r s (f:K->A->bool) (a:K->A).
        (!i. i IN s ==> a i IN f i)
        ==> ring_product r s a IN ideal_product r s f`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_product] THEN
  MATCH_MP_TAC IDEAL_GENERATED_INC_GEN THEN
  REWRITE_TAC[RING_PRODUCT; IN_ELIM_THM] THEN ASM_MESON_TAC[]);;

let IDEAL_PRODUCT_EMPTY = prove
 (`!r:A ring (f:K->A->bool). ideal_product r {} f = ring_carrier r`,
  REPEAT GEN_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `{}:K->bool`; `f:K->A->bool`;
                 `\i:K. ring_1 r:A`] RING_PRODUCT_IN_IDEAL_PRODUCT) THEN
