let MAXIMAL_IDEAL_COMAXIMAL_MUL = prove
 (`!r m j x w:A.
        maximal_ideal r m /\ ring_ideal r j /\
        ring_setadd r m j = ring_carrier r /\
        x IN ring_carrier r /\ ~(x IN m) /\ w IN ring_carrier r
        ==> ?y. y IN j /\ ring_sub r (ring_mul r x y) w IN m`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN
   `?a v:A. a IN m /\ v IN ring_carrier r /\
            ring_add r a (ring_mul r x v) = ring_1 r`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `ideal_generated r {x:A}`]
      MAXIMAL_IDEAL_COMAXIMAL) THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; RING_COMAXIMAL] THEN
    MATCH_MP_TAC(TAUT `~s /\ (e ==> g) ==> (e <=> ~s) ==> g`) THEN
    CONJ_TAC THENL
     [REWRITE_TAC[SUBSET] THEN DISCH_THEN(MP_TAC o SPEC `x:A`) THEN
      ASM_SIMP_TAC[IDEAL_GENERATED_INC_GEN; IN_SING];
      ASM_SIMP_TAC[IDEAL_GENERATED_SING_ALT; IN_ELIM_THM] THEN MESON_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_mul r w v IN ring_setadd r m (j:A->bool)` MP_TAC THENL
   [ASM_SIMP_TAC[RING_MUL]; ALL_TAC] THEN
  REWRITE_TAC[ring_setadd; IN_ELIM_THM; LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`b:A`; `y:A`] THEN STRIP_TAC THEN
  EXISTS_TAC `y:A` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r /\ b IN ring_carrier r /\
                y IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sub r (ring_mul r x y) w =
    ring_neg r (ring_add r (ring_mul r w a) (ring_mul r (x:A) b))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC(RING_RULE
     `!a b y v w x:A.
        a IN ring_carrier r /\ b IN ring_carrier r /\ y IN ring_carrier r /\
        v IN ring_carrier r /\ w IN ring_carrier r /\ x IN ring_carrier r /\
        ring_add r a (ring_mul r x v) = ring_1 r /\
        ring_mul r w v = ring_add r b y
        ==> ring_sub r (ring_mul r x y) w =
            ring_neg r (ring_add r (ring_mul r w a) (ring_mul r x b))`) THEN
    EXISTS_TAC `v:A` THEN ASM_REWRITE_TAC[];
    ASM_SIMP_TAC[IN_RING_IDEAL_NEG; IN_RING_IDEAL_ADD; IN_RING_IDEAL_LMUL]]);;

let IDEAL_PROD_COMAXIMAL = prove
