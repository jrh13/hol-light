(* Prime avoidance, by induction on the number of primes: if j lies in no    *)
(* p IN s, choose x p IN j outside the other primes (induction applied to    *)
(* s DELETE p); then x p1 + product of the x q (q <> p1) is in j and in no   *)
(* prime of s.                                                               *)

let PRIME_AVOIDANCE = prove
 (`!r (j:A->bool) s.
        ring_ideal r j /\ FINITE s /\ (!p. p IN s ==> prime_ideal r p) /\
        j SUBSET UNIONS s
        ==> ?p. p IN s /\ j SUBSET p`,
  let lemma1 = prove
   (`!r t (x:K->A) q i.
        FINITE t /\ q IN t /\ ring_ideal r i /\ x q IN i
        ==> ring_product r t x IN i`,
    REPEAT STRIP_TAC THEN
    SUBGOAL_THEN `t = (q:K) INSERT (t DELETE q)` SUBST1_TAC THENL
     [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `(x:K->A) q IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_PRODUCT_CLAUSES; FINITE_DELETE; IN_DELETE;
                 IN_RING_IDEAL_RMUL; RING_PRODUCT])
  and lemma2 = prove
   (`!r i u v:A.
        ring_ideal r i /\ u IN i /\ v IN ring_carrier r
        ==> (ring_add r u v IN i <=> v IN i) /\
            (ring_add r v u IN i <=> v IN i)`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    SUBGOAL_THEN `(u:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_ADD_SYM] THEN EQ_TAC THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_ADD] THEN DISCH_TAC THEN
    SUBGOAL_THEN `v = ring_sub r (ring_add r u v) (u:A)` SUBST1_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `!u v:A. u IN ring_carrier r /\ v IN ring_carrier r
                ==> v = ring_sub r (ring_add r u v) u`) THEN
      ASM_REWRITE_TAC[];
      ASM_SIMP_TAC[IN_RING_IDEAL_SUB]]) in
  REPLICATE_TAC 3 GEN_TAC THEN WF_INDUCT_TAC `CARD(s:(A->bool)->bool)` THEN
  STRIP_TAC THEN MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN
  DISCH_THEN(ASSUME_TAC o REWRITE_RULE[NOT_EXISTS_THM;
                                       TAUT `~(p /\ q) <=> p ==> ~q`]) THEN
  SUBGOAL_THEN `?p1 p2:A->bool. p1 IN s /\ p2 IN s /\ ~(p2 = p1)`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] IN_RING_IDEAL_0) THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!p. p IN s ==> ?x:A. x IN j /\ x IN p /\
                         !q. q IN s /\ ~(q = p) ==> ~(x IN q)`
  MP_TAC THENL
   [X_GEN_TAC `p:A->bool` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `s DELETE (p:A->bool)`) THEN
    ASM_SIMP_TAC[CARD_DELETE; FINITE_DELETE; IN_DELETE; CARD_EQ_0;
                 ARITH_RULE `n - 1 < n <=> ~(n = 0)`] THEN
    ANTS_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    MATCH_MP_TAC(TAUT `~q /\ (~p ==> r) ==> (p ==> q) ==> r`) THEN
    CONJ_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
    REWRITE_TAC[SUBSET; NOT_FORALL_THM; NOT_IMP; IN_UNIONS; IN_DELETE] THEN
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `x:A` THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL [ALL_TAC; ASM_MESON_TAC[]] THEN
    RULE_ASSUM_TAC(REWRITE_RULE[SUBSET; IN_UNIONS]) THEN ASM_MESON_TAC[];
    REWRITE_TAC[RIGHT_IMP_EXISTS_THM; SKOLEM_THM] THEN
    DISCH_THEN(X_CHOOSE_TAC `x:(A->bool)->A`)] THEN
  SUBGOAL_THEN `!p:A->bool. p IN s ==> (x:(A->bool)->A) p IN ring_carrier r`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  ABBREV_TAC
   `y = ring_add r ((x:(A->bool)->A) p1) (ring_product r (s DELETE p1) x)` THEN
  SUBGOAL_THEN `(y:A) IN j /\ !q. q IN s ==> ~(y IN q)` MP_TAC THENL
   [ALL_TAC; ASM SET_TAC[]] THEN
  EXPAND_TAC "y" THEN CONJ_TAC THENL
   [MATCH_MP_TAC IN_RING_IDEAL_ADD THEN ASM_SIMP_TAC[] THEN
    MATCH_MP_TAC lemma1 THEN EXISTS_TAC `p2:A->bool` THEN
    ASM_SIMP_TAC[FINITE_DELETE; IN_DELETE];
    X_GEN_TAC `q:A->bool` THEN DISCH_TAC THEN
    ASM_CASES_TAC `q:A->bool = p1` THENL
     [FIRST_X_ASSUM SUBST_ALL_TAC THEN
      ASM_SIMP_TAC[lemma2; PRIME_IMP_RING_IDEAL; RING_PRODUCT] THEN
      MP_TAC(ISPECL [`r:A ring`; `\z:A. ~(z IN p1)`; `x:(A->bool)->A`;
                     `s DELETE (p1:A->bool)`] RING_PRODUCT_CLOSED) THEN
      REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN
      ASM_SIMP_TAC[RING_1_NOT_IN_PRIME_IDEAL; RING_MUL_IN_PRIME_IDEAL;
                   IN_DELETE];
      SUBGOAL_THEN `ring_product r (s DELETE p1) (x:(A->bool)->A) IN q`
      ASSUME_TAC THENL
       [MATCH_MP_TAC lemma1 THEN EXISTS_TAC `q:A->bool` THEN
        ASM_SIMP_TAC[FINITE_DELETE; IN_DELETE; PRIME_IMP_RING_IDEAL];
        ASM_SIMP_TAC[lemma2; PRIME_IMP_RING_IDEAL]]]]);;

