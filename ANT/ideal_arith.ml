(* The determinant trick. Let t generate j, with j SUBSET k + ij. Modulo k   *)
(* each generator g is a sum of b g h * h (h IN t) with all b g h IN i. The  *)
(* matrix M = I - b is the identity modulo i, so a = det M is 1 modulo i,    *)
(* and M maps the vector of generators into k, so a h IN k for h IN t (the   *)
(* lemma: RING_DET_DEPENDENT_COLUMNS_MUL in quotient_ring r k).              *)

let NAKAYAMA_LEMMA = prove
 (`!r i j k:A->bool.
        ring_ideal r i /\ ring_ideal r k /\ finitely_generated_ideal r j /\
        j SUBSET ring_setadd r k (ideal_prod r i j)
        ==> ?a. a IN ring_carrier r /\ ring_sub r (ring_1 r) a IN i /\
                !x. x IN j ==> ring_mul r a x IN k`,
  REPEAT GEN_TAC THEN REWRITE_TAC[finitely_generated_ideal] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 (X_CHOOSE_THEN `t:A->bool` STRIP_ASSUME_TAC) MP_TAC))) THEN
  FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  SUBGOAL_THEN `!x:A. x IN t ==> x IN ring_carrier r` ASSUME_TAC THENL
   [ASM SET_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_PROD_IDEAL_GENERATED_FINITE; SUBSET; ring_setadd;
               IN_ELIM_THM] THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `!g:A. ?c. g IN t
              ==> (!h. h IN t ==> c h IN i /\ c h IN ring_carrier r) /\
                  ring_sub r g (ring_sum r t (\h. ring_mul r (c h) h)) IN k`
  MP_TAC THENL
   [X_GEN_TAC `g:A` THEN REWRITE_TAC[RIGHT_EXISTS_IMP_THM] THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `g:A`) THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_INC_GEN] THEN
    REWRITE_TAC[LEFT_IMP_EXISTS_THM; LEFT_AND_EXISTS_THM;
                RIGHT_AND_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`y:A`; `s:A`; `c:A->A`] THEN STRIP_TAC THEN
    EXISTS_TAC `c:A->A` THEN ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `(y:A) IN ring_carrier r /\ !h. h IN t ==> (c:A->A) h IN ring_carrier r`
    STRIP_ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_SIMP_TAC[RING_SUM; RING_RULE
     `y IN ring_carrier r /\ s IN ring_carrier r
      ==> ring_sub r (ring_add r y s) s = (y:A)`];
    REWRITE_TAC[SKOLEM_THM] THEN
    DISCH_THEN(X_CHOOSE_TAC `b:A->A->A`)] THEN
  ABBREV_TAC
   `M = \g h:A. ring_sub r (if g = h then ring_1 r else ring_0 r)
                          ((b:A->A->A) g h)` THEN
  SUBGOAL_THEN `!g h:A. g IN t /\ h IN t ==> (M:A->A->A) g h IN ring_carrier r`
  ASSUME_TAC THENL
   [EXPAND_TAC "M" THEN REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_SUB THEN
    ASM_SIMP_TAC[] THEN COND_CASES_TAC THEN REWRITE_TAC[RING_0; RING_1];
    ALL_TAC] THEN
  EXISTS_TAC `ring_det r t (M:A->A->A)` THEN REWRITE_TAC[RING_DET] THEN
  CONJ_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `quotient_ring r (i:A->bool)`;
                   `ring_coset r (i:A->bool)`; `t:A->bool`; `M:A->A->A`]
      RING_DET_HOMOMORPHISM) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET] THEN
    SUBGOAL_THEN
     `ring_det (quotient_ring r i) t (\g h. ring_coset r i ((M:A->A->A) g h)) =
      ring_det (quotient_ring r i) t
        (\g h. if g = h then ring_1 (quotient_ring r i)
               else ring_0 (quotient_ring r i))`
    SUBST1_TAC THENL
     [MATCH_MP_TAC RING_DET_EQ THEN MAP_EVERY X_GEN_TAC [`g:A`; `h:A`] THEN
      STRIP_TAC THEN EXPAND_TAC "M" THEN COND_CASES_TAC THEN
      ASM_SIMP_TAC[QUOTIENT_RING_1; QUOTIENT_RING_0; RING_COSET_EQ;
                   RING_COSET_EQ_IDEAL; RING_SUB; RING_0; RING_1;
                   RING_NEG; RING_SUB_LZERO; IN_RING_IDEAL_NEG; RING_RULE
       `x IN ring_carrier r /\ y IN ring_carrier r
        ==> ring_sub r (ring_sub r x y) x = ring_neg r (y:A)`];
      ASM_SIMP_TAC[RING_DET_I; QUOTIENT_RING_1] THEN
      DISCH_THEN(MP_TAC o SYM) THEN
      ASM_SIMP_TAC[RING_COSET_EQ; RING_1; RING_DET]];
    MP_TAC(ISPECL [`r:A ring`;
      `{x:A | x IN ring_carrier r /\
              ring_mul r (ring_det r t (M:A->A->A)) x IN k}`;
      `t:A->bool`] IDEAL_GENERATED_MINIMAL) THEN
    ASM_SIMP_TAC[RING_IDEAL_QUOTIENT_LMUL; RING_DET] THEN
    MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p ==> q) ==> r`) THEN
    CONJ_TAC THENL [ALL_TAC; SET_TAC[]] THEN
    REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN X_GEN_TAC `l:A` THEN DISCH_TAC THEN
    ASM_SIMP_TAC[] THEN
    MP_TAC(ISPECL [`r:A ring`; `k:A->bool`; `t:A->bool`; `M:A->A->A`;
                   `\h:A. h`; `l:A`] RING_DET_DEPENDENT_COLUMNS_MUL_IDEAL) THEN
    ASM_SIMP_TAC[RING_DET; RING_MUL_SYM] THEN
    DISCH_THEN MATCH_MP_TAC THEN X_GEN_TAC `g:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `ring_sum r t (\h. ring_mul r ((M:A->A->A) g h) h) =
      ring_sub r (ring_sum r t (\h. if h = g then g else ring_0 r))
                 (ring_sum r t (\h. ring_mul r (b g h) h))`
    SUBST1_TAC THENL
     [W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_SUB o rand o snd) THEN
      ANTS_TAC THENL
       [ASM_SIMP_TAC[RING_MUL] THEN REPEAT STRIP_TAC THEN
        COND_CASES_TAC THEN ASM_SIMP_TAC[RING_0];
        DISCH_THEN(SUBST1_TAC o SYM)] THEN
      MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `h:A` THEN DISCH_TAC THEN
      EXPAND_TAC "M" THEN ASM_CASES_TAC `h:A = g` THEN
      ASM_SIMP_TAC[RING_SUB_RDISTRIB; RING_MUL_LID; RING_MUL_LZERO; RING_0;
                   RING_1];
      ASM_SIMP_TAC[RING_SUM_DELTA]]]);;

(* For i inside every maximal ideal, a is a unit (else a and 1 - a lie in a  *)
(* common maximal ideal). The set i need not be an ideal: the ideal it       *)
(* generates gives the same products.                                        *)

let NAKAYAMA_LEMMA_MAXIMAL = prove
 (`!r i j k:A->bool.
        (!m. maximal_ideal r m ==> i SUBSET m) /\ ring_ideal r k /\
        finitely_generated_ideal r j /\
        j SUBSET ring_setadd r k (ideal_prod r i j)
        ==> j SUBSET k`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITELY_GENERATED_IMP_RING_IDEAL) THEN
  ASM_CASES_TAC `trivial_ring(r:A ring)` THENL
   [RULE_ASSUM_TAC(REWRITE_RULE[trivial_ring]) THEN
    MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] RING_IDEAL_IMP_SUBSET) THEN
    MP_TAC(ISPECL [`r:A ring`; `k:A->bool`] IN_RING_IDEAL_0) THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(i:A->bool) SUBSET ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[MAXIMAL_IDEAL_EXISTS; MAXIMAL_IDEAL_IMP_SUBSET;
                  SUBSET_TRANS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r (i:A->bool)`; `j:A->bool`;
                 `k:A->bool`] NAKAYAMA_LEMMA) THEN
  MP_TAC(ISPECL [`r:A ring`; `i:A->bool`; `j:A->bool`]
    IDEAL_PROD_IDEAL_GENERATED) THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_RING_IDEAL; RING_IDEAL_IMP_SUBSET;
               RING_IDEAL_IDEAL_GENERATED] THEN
  DISCH_THEN(K ALL_TAC) THEN
  DISCH_THEN(X_CHOOSE_THEN `a:A` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `ring_unit r (a:A)` MP_TAC THENL
   [MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
    MP_TAC(ISPEC `r:A ring` UNIONS_MAXIMAL_IDEALS) THEN
    REWRITE_TAC[EXTENSION; IN_UNIONS; IN_ELIM_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `a:A`) THEN ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `m:A->bool` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN `ideal_generated r i SUBSET (m:A->bool)` ASSUME_TAC THENL
     [ASM_MESON_TAC[IDEAL_GENERATED_MINIMAL; MAXIMAL_IMP_RING_IDEAL];
      ALL_TAC] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP MAXIMAL_IMP_PROPER_IDEAL) THEN
    REWRITE_TAC[PROPER_IDEAL] THEN STRIP_TAC THEN
    UNDISCH_TAC `~(ring_1 r IN (m:A->bool))` THEN REWRITE_TAC[] THEN
    SUBGOAL_THEN `ring_1 r = ring_add r (ring_sub r (ring_1 r) a) (a:A)`
    SUBST1_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `a IN ring_carrier r
        ==> ring_1 r = ring_add r (ring_sub r (ring_1 r) a) (a:A)`) THEN
      ASM_REWRITE_TAC[];
      MATCH_MP_TAC IN_RING_IDEAL_ADD THEN ASM SET_TAC[]];
    REWRITE_TAC[ring_unit] THEN
    DISCH_THEN(X_CHOOSE_THEN `v:A` STRIP_ASSUME_TAC o CONJUNCT2)] THEN
  REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN `x = ring_mul r v (ring_mul r a (x:A))` SUBST1_TAC THENL
   [MATCH_MP_TAC(RING_RULE
     `a IN ring_carrier r /\ v IN ring_carrier r /\ x IN ring_carrier r /\
      ring_mul r a v = ring_1 r
      ==> x = ring_mul r v (ring_mul r a (x:A))`) THEN
    ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET];
    ASM_SIMP_TAC[IN_RING_IDEAL_LMUL]]);;

(* In a local ring every proper ideal lies in the unique maximal ideal.      *)

let NAKAYAMA_LEMMA_LOCAL = prove
 (`!r i j k:A->bool.
        local_ring r /\ proper_ideal r i /\ ring_ideal r k /\
        finitely_generated_ideal r j /\
        j SUBSET ring_setadd r k (ideal_prod r i j)
        ==> j SUBSET k`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC NAKAYAMA_LEMMA_MAXIMAL THEN
  MAP_EVERY EXISTS_TAC [`r:A ring`; `i:A->bool`] THEN ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM(MP_TAC o MATCH_MP MAXIMAL_SUPERIDEAL_EXISTS) THEN
  FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [local_ring]) THEN
  REWRITE_TAC[EXISTS_UNIQUE_DEF] THEN MESON_TAC[]);;

(* In a local ring an element of m outside m^2 can replace one of any finite *)
(* set of generators of m.                                                   *)

let LOCAL_RING_GENERATORS_EXCHANGE = prove
 (`!r m s x:A.
        local_ring r /\ maximal_ideal r m /\
        FINITE s /\ s SUBSET m /\ ideal_generated r s = m /\
        x IN m /\ ~(x IN ideal_prod r m m)
        ==> ?y. y IN s /\ ideal_generated r (x INSERT (s DELETE y)) = m`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(m:A->bool) SUBSET ring_carrier r /\ s SUBSET ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET_TRANS]; ALL_TAC] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM SET_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `?c. (!i. i IN s ==> (c:A->A) i IN ring_carrier r) /\
        ring_sum r s (\i. ring_mul r (c i) i) = x`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `s:A->bool`] IDEAL_GENERATED_FINITE) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(fun th -> UNDISCH_TAC `(x:A) IN m` THEN
                         REWRITE_TAC[th; IN_ELIM_THM]) THEN
    MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `?y:A. y IN s /\ ~((c:A->A) y IN m)` STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(MESON[]
     `~(!y:A. y IN s ==> (c:A->A) y IN m) ==> ?y. y IN s /\ ~(c y IN m)`) THEN
    DISCH_TAC THEN UNDISCH_TAC `~((x:A) IN ideal_prod r m m)` THEN
    REWRITE_TAC[] THEN
    FIRST_X_ASSUM((fun th -> GEN_REWRITE_TAC LAND_CONV [SYM th]) o
      check (fun th -> rhs(concl th) = `x:A`)) THEN
    MATCH_MP_TAC(REWRITE_RULE[]
     (ISPECL [`r:A ring`; `\a:A. a IN ideal_prod r m m`] RING_SUM_CLOSED)) THEN
    SIMP_TAC[IN_RING_IDEAL_0; IN_RING_IDEAL_ADD; RING_IDEAL_IDEAL_PROD] THEN
    X_GEN_TAC `i:A` THEN DISCH_TAC THEN
    MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN ASM SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier r /\ (c:A->A) y IN ring_carrier r`
  STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `ring_unit r ((c:A->A) y)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `m:A->bool`] LOCAL_RING_JACOBSON_RADICAL) THEN
    ASM_SIMP_TAC[JACOBSON_RADICAL_LOCAL_RING] THEN
    DISCH_THEN(MP_TAC o SPEC `(c:A->A) y` o REWRITE_RULE[EXTENSION]) THEN
    ASM_SIMP_TAC[IN_ELIM_THM];
    ALL_TAC] THEN
  EXISTS_TAC `y:A` THEN ASM_REWRITE_TAC[] THEN
  ABBREV_TAC `K = ideal_generated r ((x:A) INSERT (s DELETE y))` THEN
  SUBGOAL_THEN
   `ring_ideal r (K:A->bool) /\ (x:A) IN K /\ (!i. i IN s DELETE y ==> i IN K)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "K" THEN REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    CONJ_TAC THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC IDEAL_GENERATED_INC THEN ASM SET_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC
   `q = ring_sum r (s DELETE y) (\i. ring_mul r ((c:A->A) i) i)` THEN
  SUBGOAL_THEN `(q:A) IN ring_carrier r /\ q IN K` STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN REWRITE_TAC[RING_SUM] THEN
    MATCH_MP_TAC(REWRITE_RULE[]
     (ISPECL [`r:A ring`; `\a:A. a IN K`] RING_SUM_CLOSED)) THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0; IN_RING_IDEAL_ADD] THEN
    REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
    ASM_SIMP_TAC[] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_add r (ring_mul r ((c:A->A) y) y) q = x` ASSUME_TAC THENL
   [FIRST_ASSUM((fun th -> GEN_REWRITE_TAC RAND_CONV [SYM th]) o
      check (fun th -> rhs(concl th) = `x:A` &&
                       is_comb(lhs(concl th)))) THEN
    MP_TAC(ISPECL [`y:A`; `s:A->bool`] INSERT_DELETE) THEN
    REWRITE_TAC[ASSUME `(y:A) IN s`] THEN DISCH_THEN(fun th ->
      GEN_REWRITE_TAC (RAND_CONV o ONCE_DEPTH_CONV) [SYM th]) THEN
    EXPAND_TAC "q" THEN
    ASM_SIMP_TAC[RING_SUM_CLAUSES; FINITE_DELETE; IN_DELETE; RING_MUL];
    ALL_TAC] THEN
  SUBGOAL_THEN `(y:A) IN K` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `(c:A->A) y`] RING_MUL_LINV) THEN
    ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
    SUBGOAL_THEN `ring_inv r ((c:A->A) y) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_SIMP_TAC[RING_INV]; ALL_TAC] THEN
    SUBGOAL_THEN
     `y = ring_mul r (ring_inv r ((c:A->A) y)) (ring_sub r x q)`
    SUBST1_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        rhs(concl th) = `x:A` && is_comb(lhs(concl th)) &&
        free_in `q:A` (concl th))) THEN
      TRANS_TAC EQ_TRANS
       `ring_mul r (ring_mul r (ring_inv r ((c:A->A) y)) (c y)) (y:A)` THEN
      CONJ_TAC THENL
       [ASM_SIMP_TAC[RING_MUL_LID];
        W(fun (asl,w) -> let th = RING_RULE w in
          MATCH_ACCEPT_TAC th ORELSE
          (MATCH_MP_TAC th THEN ASM_SIMP_TAC[]))];
      MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
      ASM_SIMP_TAC[IN_RING_IDEAL_SUB]];
    ALL_TAC] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [EXPAND_TAC "K" THEN MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    ASM SET_TAC[];
    FIRST_ASSUM((fun th -> GEN_REWRITE_TAC LAND_CONV [SYM th]) o
      check (fun th -> concl th = `ideal_generated r (s:A->bool) = m`)) THEN
    MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[SUBSET] THEN X_GEN_TAC `i:A` THEN DISCH_TAC THEN
    ASM_CASES_TAC `i:A = y` THEN ASM_REWRITE_TAC[] THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[IN_DELETE]]);;

(* A finitely generated idempotent ideal j is generated by an idempotent:    *)
(* for a as in NAKAYAMA_LEMMA (with i = j and k = 0) take e = 1 - a.         *)

let FINITELY_GENERATED_IDEAL_IDEMPOTENT = prove
 (`!r j:A->bool.
        finitely_generated_ideal r j /\ ideal_prod r j j = j <=>
        ?e. e IN ring_carrier r /\ ring_mul r e e = e /\
            ideal_generated r {e} = j`,
  REPEAT GEN_TAC THEN EQ_TAC THENL
   [STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITELY_GENERATED_IMP_RING_IDEAL) THEN
    MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `j:A->bool`; `{ring_0 r:A}`]
      NAKAYAMA_LEMMA) THEN
    ASM_SIMP_TAC[RING_IDEAL_0; RING_SETADD_LZERO; RING_IDEAL_IMP_SUBSET;
                 RING_IDEAL_IDEAL_PROD; IN_SING; SUBSET_REFL] THEN
    DISCH_THEN(X_CHOOSE_THEN `a:A` STRIP_ASSUME_TAC) THEN
    EXISTS_TAC `ring_sub r (ring_1 r) a:A` THEN
    ASM_SIMP_TAC[RING_SUB; RING_1] THEN CONJ_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `a IN ring_carrier r /\
        ring_mul r a (ring_sub r (ring_1 r) a) = ring_0 r
        ==> ring_mul r (ring_sub r (ring_1 r) a) (ring_sub r (ring_1 r) a) =
            ring_sub r (ring_1 r) (a:A)`) THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC SUBSET_ANTISYM THEN
      ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL; SING_SUBSET] THEN
      REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
      SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
       [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
      SUBGOAL_THEN `x = ring_mul r x (ring_sub r (ring_1 r) a:A)`
      SUBST1_TAC THENL
       [MATCH_MP_TAC(RING_RULE
         `a IN ring_carrier r /\ x IN ring_carrier r /\
          ring_mul r a x = ring_0 r
          ==> x = ring_mul r x (ring_sub r (ring_1 r) (a:A))`) THEN
        ASM_SIMP_TAC[];
        MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
        ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_INC_GEN;
                     IN_SING; RING_SUB; RING_1]]];
    DISCH_THEN(X_CHOOSE_THEN `e:A` STRIP_ASSUME_TAC) THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
    ASM_SIMP_TAC[IDEAL_PROD_PRINCIPAL; PRINCIPAL_IMP_FINITELY_GENERATED_IDEAL;
                 PRINCIPAL_IDEAL_IDEAL_GENERATED_SING]]);;
