(* ========================================================================= *)
(* Ideal arithmetic in an arbitrary (commutative) ring.                      *)
(*                                                                           *)
(*   ideal_prod r j k       the product ideal jk, generated by the products  *)
(*                          ring_mul r a b with a IN j, b IN k               *)
(*   ideal_quotient r j k   the colon ideal (j:k) = {x | x k SUBSET j}       *)
(*   ideal_pow r j n        the power j^n (j^0 = ring_carrier r)             *)
(*   ideal_product r s f    the product of the finite family f i, i IN s     *)
(*                                                                           *)
(* Main results: products are commutative and associative for arbitrary      *)
(* subsets of the carrier (IDEAL_PROD_AC, IDEAL_PROD_ASSOC), only depend on  *)
(* the generated ideals (IDEAL_PROD_IDEAL_GENERATED) and are the finite sums *)
(* of products (IDEAL_PROD_EXPLICIT); principal factors act by scaling       *)
(* (IDEAL_PROD_SCALE) and cancel in a domain; distributivity over sums;      *)
(* primes containing products and powers; products and powers of sums with a *)
(* fixed ideal ((i + j)(i + k) SUBSET i + jk: IDEAL_PROD_SETADD_SUBSET,      *)
(* IDEAL_POW_SETADD_SUBSET, IDEAL_PRODUCT_SETADD_SUBSET,                     *)
(* IDEAL_PRODUCT_POW_SETADD_SUBSET); comaximal ideals                        *)
(* (MAXIMAL_IDEAL_COMAXIMAL, MAXIMAL_IDEAL_COMAXIMAL_MUL,                    *)
(* COMAXIMAL_IDEAL_PROD, COMAXIMAL_IDEAL_POW) and the Chinese remainder      *)
(* theorem, for two ideals as a ring isomorphism (also the explicit          *)
(* isomorphism r -> r/j x r/k when j INTER k = {0}:                          *)
(* RING_ISOMORPHISM_PROD_QUOTIENT_RING) and for a finite pairwise comaximal  *)
(* family as simultaneous congruences (CHINESE_REMAINDER_IDEALS), the        *)
(* product as the intersection (IDEAL_PRODUCT_COMAXIMAL) and the quotient as *)
(* the product ring of the quotients (CHINESE_REMAINDER_PRODUCT_RING); the   *)
(* adjunction between products and colon ideals (SUBSET_IDEAL_QUOTIENT);     *)
(* radicals of products and powers (a positive power of a prime p has        *)
(* radical p: RADICAL_PRIME_IDEAL_POW); finite products of ideals, with      *)
(* their monomial form (IDEAL_PRODUCT_MONOMIAL_MUL: products of ideals       *)
(* indexed by finite-support exponent functions follow monomial_mul), finite *)
(* products of principal ideals (IDEAL_PRODUCT_PRINCIPAL) and reindexing     *)
(* (IDEAL_PRODUCT_IMAGE); the extension of ideals along a ring homomorphism  *)
(* h, j |-> the ideal generated by the image of j, commutes with generation, *)
(* products, powers and finite products                                      *)
(* (IDEAL_GENERATED_IMAGE_IDEAL_GENERATED, IDEAL_PROD_HOMOMORPHIC_IMAGE,     *)
(* IDEAL_POW_HOMOMORPHIC_IMAGE, IDEAL_PRODUCT_HOMOMORPHIC_IMAGE), along an   *)
(* epimorphism the image of a product is the product of the images           *)
(* (IDEAL_PROD_EPIMORPHIC_IMAGE), and along a monomorphism only the zero     *)
(* ideal extends to zero (IDEAL_GENERATED_MONOMORPHIC_IMAGE_EQ_0); a subset  *)
(* M of s closed under sums and h-multiples with s = M + j s satisfies s = M *)
(* + j^t s for all t (IDEAL_EXTENSION_POW_SUPPLEMENT); Noetherian induction  *)
(* (NOETHERIAN_RING_INDUCT); every ideal of a Noetherian ring contains a     *)
(* product of primes containing it (NOETHERIAN_PRIME_PRODUCT_SUBSET); prime  *)
(* avoidance (PRIME_AVOIDANCE); the Nakayama lemma for ideals by the         *)
(* determinant trick (NAKAYAMA_LEMMA: if j is finitely generated and j       *)
(* SUBSET k + ij then some a = 1 mod i has aj SUBSET k; k = 0 is the         *)
(* classical form), its forms for i inside every maximal ideal and for local *)
(* rings, where j SUBSET k + ij gives j SUBSET k (NAKAYAMA_LEMMA_MAXIMAL,    *)
(* NAKAYAMA_LEMMA_LOCAL), and finitely generated idempotent ideals are       *)
(* generated by idempotents (FINITELY_GENERATED_IDEAL_IDEMPOTENT). Also: the *)
(* powers of the unit ideal are the unit ideal (IDEAL_POW_CARRIER).          *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml; the Nakayama section also uses the           *)
(* determinants of Library/ring_det.ml                                       *)
(* (RING_DET_DEPENDENT_COLUMNS_MUL_IDEAL, RING_DET_HOMOMORPHISM,             *)
(* RING_DET_I).                                                              *)
(* ========================================================================= *)

needs "Library/ringtheory.ml";;
needs "Library/ring_det.ml";;

(* ------------------------------------------------------------------------- *)
(* Products of two ideals.                                                   *)
(* ------------------------------------------------------------------------- *)

let ideal_prod = new_definition
 `ideal_prod (r:A ring) (j:A->bool) (k:A->bool) =
  ideal_generated r (ring_setmul r j k)`;;

let RING_IDEAL_IDEAL_PROD = prove
 (`!r:A ring j k. ring_ideal r (ideal_prod r j k)`,
  REWRITE_TAC[ideal_prod; RING_IDEAL_IDEAL_GENERATED]);;

let RING_MUL_IN_IDEAL_PROD = prove
 (`!r j k a b:A.
        a IN j /\ b IN k /\ a IN ring_carrier r /\ b IN ring_carrier r
        ==> ring_mul r a b IN ideal_prod r j k`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_prod] THEN
  MATCH_MP_TAC IDEAL_GENERATED_INC_GEN THEN
  ASM_SIMP_TAC[RING_MUL; RING_MUL_IN_SETMUL]);;

let IDEAL_PROD_MINIMAL = prove
 (`!r j k l:A->bool.
        ring_ideal r l /\ (!a b. a IN j /\ b IN k ==> ring_mul r a b IN l)
        ==> ideal_prod r j k SUBSET l`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_prod] THEN
  MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
  ASM_SIMP_TAC[ring_setmul; SUBSET; FORALL_IN_GSPEC]);;

(* Products are the finite sums of products of elements (the analogue of the *)
(* library IDEAL_GENERATED_EXPLICIT).                                        *)

let IDEAL_PROD_EXPLICIT = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ ring_ideal r k
        ==> ideal_prod r j k =
            {ring_sum r {i | i < n} (\i:num. ring_mul r (u i) (v i)) | n,u,v |
             !i. i < n ==> u i IN j /\ v i IN k}`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [ALL_TAC;
    REWRITE_TAC[SUBSET; FORALL_IN_GSPEC] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC IN_RING_IDEAL_SUM THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_PROD; IN_ELIM_THM] THEN
    REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
    ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]] THEN
  REWRITE_TAC[SUBSET; ideal_prod; IDEAL_GENERATED_EXPLICIT;
              FORALL_IN_GSPEC] THEN
  MAP_EVERY X_GEN_TAC [`t:A->bool`; `cf:A->A`] THEN STRIP_TAC THEN
  REWRITE_TAC[IN_ELIM_THM] THEN
  (* Write each x IN t as p x * q x, then enumerate t. *)
  SUBGOAL_THEN
   `!x:A. ?p q. x IN t
                ==> p IN j /\ q IN k /\ p IN ring_carrier r /\
                    q IN ring_carrier r /\ ring_mul r p q = x`
  MP_TAC THENL
   [X_GEN_TAC `x:A` THEN REWRITE_TAC[RIGHT_EXISTS_IMP_THM] THEN
    DISCH_TAC THEN SUBGOAL_THEN `(x:A) IN ring_setmul r j k` MP_TAC THENL
     [ASM SET_TAC[]; REWRITE_TAC[ring_setmul; IN_ELIM_THM]] THEN
    ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET];
    REWRITE_TAC[SKOLEM_THM; LEFT_IMP_EXISTS_THM]] THEN
  MAP_EVERY X_GEN_TAC [`p:A->A`; `q:A->A`] THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `ring_sum r t (\i. ring_mul r (cf i) i) =
    ring_sum r t (\x. ring_mul r (ring_mul r (cf x) (p x)) (q x:A))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC RING_SUM_EQ THEN ASM_SIMP_TAC[GSYM RING_MUL_ASSOC];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`t:A->bool`; `CARD(t:A->bool)`] HAS_SIZE_INDEX) THEN
  ASM_REWRITE_TAC[HAS_SIZE; EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `f:num->A` STRIP_ASSUME_TAC) THEN
  MAP_EVERY EXISTS_TAC
   [`CARD(t:A->bool)`; `\i. ring_mul r (cf((f:num->A) i)) (p(f i):A)`;
    `\i. (q:A->A)((f:num->A) i)`] THEN
  REWRITE_TAC[] THEN CONJ_TAC THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_LMUL]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `f:num->A`;
                 `\x:A. ring_mul r (ring_mul r (cf x) (p x)) (q x:A)`;
                 `{i:num | i < CARD(t:A->bool)}`] RING_SUM_IMAGE) THEN
  ANTS_TAC THENL [REWRITE_TAC[IN_ELIM_THM] THEN ASM_MESON_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `IMAGE (f:num->A) {i | i < CARD(t:A->bool)} = t`
  SUBST1_TAC THENL
   [REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[o_DEF]]);;

let IDEAL_PROD_MONO = prove
 (`!r j j' k k':A->bool.
        j SUBSET j' /\ k SUBSET k'
        ==> ideal_prod r j k SUBSET ideal_prod r j' k'`,
  SIMP_TAC[ideal_prod; IDEAL_GENERATED_MONO; RING_SETMUL_MONO]);;

let IDEAL_PROD_COMM = prove
 (`!r:A ring j k.
        j SUBSET ring_carrier r /\ k SUBSET ring_carrier r
        ==> ideal_prod r j k = ideal_prod r k j`,
  SIMP_TAC[ideal_prod; RING_SETMUL_SYM]);;

(* Products only depend on the generated ideals. For a IN s the set of y     *)
(* with ring_mul r a y IN ideal_prod r s t is an ideal containing t, hence   *)
(* containing ideal_generated r t.                                           *)

let IDEAL_PROD_IDEAL_GENERATED = prove
 (`!r s t:A->bool.
        s SUBSET ring_carrier r /\ t SUBSET ring_carrier r
        ==> ideal_prod r (ideal_generated r s) (ideal_generated r t) =
            ideal_prod r s t`,
  let lemma = prove
   (`!r s t:A->bool.
        s SUBSET ring_carrier r /\ t SUBSET ring_carrier r
        ==> ideal_prod r s (ideal_generated r t) = ideal_prod r s t`,
    REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
    ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL;
                 IDEAL_GENERATED_SUBSET_CARRIER_SUBSET] THEN
    MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN
    MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM SET_TAC[]; ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `{x:A | x IN ring_carrier r /\
                     ring_mul r a x IN ideal_prod r s t}`; `t:A->bool`]
      IDEAL_GENERATED_MINIMAL) THEN
    ASM_SIMP_TAC[RING_IDEAL_QUOTIENT_LMUL; RING_IDEAL_IDEAL_PROD] THEN
    ANTS_TAC THENL [ALL_TAC; ASM SET_TAC[]] THEN
    REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN
    ASM_MESON_TAC[RING_MUL_IN_IDEAL_PROD; SUBSET]) in
  MESON_TAC[lemma; IDEAL_PROD_COMM; IDEAL_GENERATED_SUBSET]);;

(* Commutativity and associativity for arbitrary subsets of the carrier,     *)
(* in the form of the library RING_SETMUL_AC (for normalizing products with  *)
(* ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; ...]).                 *)

let IDEAL_PROD_AC = prove
 (`!r:A ring.
        (!j k. j SUBSET ring_carrier r /\ k SUBSET ring_carrier r
               ==> ideal_prod r j k = ideal_prod r k j) /\
        (!j k l. j SUBSET ring_carrier r /\ k SUBSET ring_carrier r /\
                 l SUBSET ring_carrier r
                 ==> ideal_prod r (ideal_prod r j k) l =
                     ideal_prod r j (ideal_prod r k l)) /\
        (!j k l. j SUBSET ring_carrier r /\ k SUBSET ring_carrier r /\
                 l SUBSET ring_carrier r
                 ==> ideal_prod r j (ideal_prod r k l) =
                     ideal_prod r k (ideal_prod r j l))`,
  let lemma = prove
   (`!r s t:A->bool.
        s SUBSET ring_carrier r /\ t SUBSET ring_carrier r
        ==> ideal_generated r (ring_setmul r (ideal_generated r s) t) =
            ideal_generated r (ring_setmul r s t) /\
            ideal_generated r (ring_setmul r s (ideal_generated r t)) =
            ideal_generated r (ring_setmul r s t)`,
    REWRITE_TAC[GSYM ideal_prod] THEN
    MESON_TAC[IDEAL_PROD_IDEAL_GENERATED; IDEAL_GENERATED_BY_IDEAL_GENERATED;
              IDEAL_GENERATED_SUBSET]) in
  let assoc = prove
   (`!r j k l:A->bool.
        j SUBSET ring_carrier r /\ k SUBSET ring_carrier r /\
        l SUBSET ring_carrier r
        ==> ideal_prod r (ideal_prod r j k) l =
            ideal_prod r j (ideal_prod r k l)`,
    SIMP_TAC[ideal_prod; lemma; RING_SETMUL; RING_SETMUL_ASSOC]) in
  MESON_TAC[IDEAL_PROD_COMM; assoc; RING_IDEAL_IMP_SUBSET;
            RING_IDEAL_IDEAL_PROD]);;

let IDEAL_PROD_ASSOC = prove
 (`!r p q s:A->bool.
        p SUBSET ring_carrier r /\ q SUBSET ring_carrier r /\
        s SUBSET ring_carrier r
        ==> ideal_prod r p (ideal_prod r q s) =
            ideal_prod r (ideal_prod r p q) s`,
  MESON_TAC[IDEAL_PROD_AC]);;

let IDEAL_PROD_SUBSET_LEFT = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ k SUBSET ring_carrier r
        ==> ideal_prod r j k SUBSET j`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_prod] THEN
  MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
  ASM_SIMP_TAC[RING_SETMUL_SUBSET_IDEAL; SUBSET_REFL]);;

let IDEAL_PROD_SUBSET_RIGHT = prove
 (`!r j k:A->bool.
        j SUBSET ring_carrier r /\ ring_ideal r k
        ==> ideal_prod r j k SUBSET k`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_prod] THEN
  MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
  ASM_SIMP_TAC[RING_SETMUL_SUBSET_IDEAL; SUBSET_REFL]);;

let IDEAL_PROD_CARRIER = prove
 (`!r:A ring j.
        ring_ideal r j
        ==> ideal_prod r j (ring_carrier r) = j`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
  ASM_SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; SUBSET_REFL; SUBSET] THEN
  X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  FIRST_ASSUM(SUBST1_TAC o SYM o MATCH_MP RING_MUL_RID) THEN
  ASM_SIMP_TAC[RING_MUL_IN_IDEAL_PROD; RING_1]);;

let IDEAL_PROD_CARRIER_LEFT = prove
 (`!r j:A->bool.
        ring_ideal r j ==> ideal_prod r (ring_carrier r) j = j`,
  MESON_TAC[IDEAL_PROD_CARRIER; IDEAL_PROD_COMM; SUBSET_REFL;
            RING_IDEAL_IMP_SUBSET]);;

let IDEAL_PROD_LZERO = prove
 (`!r j:A->bool.
        j SUBSET ring_carrier r ==> ideal_prod r {ring_0 r} j = {ring_0 r}`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
  SIMP_TAC[SING_SUBSET; IN_RING_IDEAL_0; RING_IDEAL_IDEAL_PROD] THEN
  MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN REWRITE_TAC[RING_IDEAL_0; IN_SING] THEN
  ASM_MESON_TAC[RING_MUL_LZERO; SUBSET]);;

let IDEAL_PROD_RZERO = prove
 (`!r j:A->bool.
        j SUBSET ring_carrier r ==> ideal_prod r j {ring_0 r} = {ring_0 r}`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
  SIMP_TAC[SING_SUBSET; IN_RING_IDEAL_0; RING_IDEAL_IDEAL_PROD] THEN
  MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN REWRITE_TAC[RING_IDEAL_0; IN_SING] THEN
  ASM_MESON_TAC[RING_MUL_RZERO; SUBSET]);;

let IDEAL_PROD_SUBSET_INTER = prove
 (`!r:A ring j k.
        ring_ideal r j /\ ring_ideal r k
        ==> ideal_prod r j k SUBSET (j INTER k)`,
  SIMP_TAC[SUBSET_INTER; IDEAL_PROD_SUBSET_LEFT; IDEAL_PROD_SUBSET_RIGHT;
           RING_IDEAL_IMP_SUBSET]);;

let IDEAL_PROD_EQ_CARRIER = prove
 (`!r j k:A->bool.
        ring_ideal r j /\ ring_ideal r k
        ==> (ideal_prod r j k = ring_carrier r <=>
             j = ring_carrier r /\ k = ring_carrier r)`,
  REPEAT STRIP_TAC THEN EQ_TAC THEN
  ASM_SIMP_TAC[IDEAL_PROD_CARRIER; RING_IDEAL_CARRIER] THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `k:A->bool`]
    IDEAL_PROD_SUBSET_INTER) THEN
  MP_TAC(ISPEC `r:A ring` RING_IDEAL_IMP_SUBSET) THEN ASM SET_TAC[]);;

let IDEAL_PROD_EQ_ZERO = prove
 (`!r:A ring j k.
        integral_domain r /\ ring_ideal r j /\ ring_ideal r k
        ==> (ideal_prod r j k = {ring_0 r} <=>
             j = {ring_0 r} \/ k = {ring_0 r})`,
  REPEAT STRIP_TAC THEN EQ_TAC THEN
  STRIP_TAC THEN ASM_SIMP_TAC[IDEAL_PROD_LZERO; IDEAL_PROD_RZERO;
                              RING_IDEAL_IMP_SUBSET] THEN
  MATCH_MP_TAC(TAUT `(~p /\ ~q ==> F) ==> p \/ q`) THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `?a b:A. a IN j /\ b IN k /\ ~(a = ring_0 r) /\ ~(b = ring_0 r)`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] IN_RING_IDEAL_0) THEN
    MP_TAC(ISPECL [`r:A ring`; `k:A->bool`] IN_RING_IDEAL_0) THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `k:A->bool`; `a:A`; `b:A`]
    RING_MUL_IN_IDEAL_PROD) THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r /\ b IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  ASM_SIMP_TAC[IN_SING; INTEGRAL_DOMAIN_MUL_EQ_0]);;

let IDEAL_PROD_PRINCIPAL = prove
 (`!r (a:A) b.
        a IN ring_carrier r /\ b IN ring_carrier r
        ==> ideal_prod r (ideal_generated r {a}) (ideal_generated r {b}) =
            ideal_generated r {ring_mul r a b}`,
  SIMP_TAC[IDEAL_PROD_IDEAL_GENERATED; SING_SUBSET] THEN
  REWRITE_TAC[ideal_prod; RING_SETMUL_SING]);;

(* A principal factor acts by scaling: (a) j = a j for an ideal j.           *)

let IDEAL_PROD_SCALE = prove
 (`!r (a:A) j.
        a IN ring_carrier r /\ ring_ideal r j
        ==> ideal_prod r (ideal_generated r {a}) j = IMAGE (ring_mul r a) j`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV)
   [GSYM(MATCH_MP IDEAL_GENERATED_RING_IDEAL th)]) THEN
  ASM_SIMP_TAC[IDEAL_PROD_IDEAL_GENERATED; SING_SUBSET;
               RING_IDEAL_IMP_SUBSET] THEN
  ASM_SIMP_TAC[ideal_prod; GSYM RING_SCALE_SETMUL; IDEAL_GENERATED_SCALE;
               RING_IDEAL_IMP_SUBSET; IDEAL_GENERATED_RING_IDEAL]);;

let IDEAL_PROD_PRINCIPAL_SUBSET_CANCEL = prove
 (`!r (a:A) j k.
        integral_domain r /\ a IN ring_carrier r /\ ~(a = ring_0 r) /\
        ring_ideal r j /\ ring_ideal r k
        ==> (ideal_prod r (ideal_generated r {a}) j SUBSET
             ideal_prod r (ideal_generated r {a}) k <=>
             j SUBSET k)`,
  REPEAT STRIP_TAC THEN ASM_SIMP_TAC[IDEAL_PROD_SCALE] THEN
  MATCH_MP_TAC(SET_RULE
   `!s (f:A->A) j k.
        (!x y. x IN s /\ y IN s /\ f x = f y ==> x = y) /\
        j SUBSET s /\ k SUBSET s
        ==> (IMAGE f j SUBSET IMAGE f k <=> j SUBSET k)`) THEN
  EXISTS_TAC `ring_carrier r:A->bool` THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN
  ASM_MESON_TAC[INTEGRAL_DOMAIN_MUL_LCANCEL]);;

let IDEAL_PROD_PRINCIPAL_CANCEL = prove
 (`!r (a:A) j k.
        integral_domain r /\ a IN ring_carrier r /\ ~(a = ring_0 r) /\
        ring_ideal r j /\ ring_ideal r k
        ==> (ideal_prod r (ideal_generated r {a}) j =
             ideal_prod r (ideal_generated r {a}) k <=>
             j = k)`,
  SIMP_TAC[GSYM SUBSET_ANTISYM_EQ; IDEAL_PROD_PRINCIPAL_SUBSET_CANCEL]);;

let IDEAL_PROD_PRINCIPAL_FACTOR = prove
 (`!r (a:A) j.
        a IN ring_carrier r /\ ring_ideal r j
        ==> (j SUBSET ideal_generated r {a} <=>
             ?k. ring_ideal r k /\ ideal_prod r (ideal_generated r {a}) k = j)`,
  REPEAT STRIP_TAC THEN EQ_TAC THENL
   [DISCH_TAC THEN
    EXISTS_TAC `{x:A | x IN ring_carrier r /\ ring_mul r a x IN j}` THEN
    ASM_SIMP_TAC[RING_IDEAL_QUOTIENT_LMUL; IDEAL_PROD_SCALE] THEN
    REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM] THEN
    X_GEN_TAC `y:A` THEN EQ_TAC THENL [MESON_TAC[]; DISCH_TAC] THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `y:A` o REWRITE_RULE[SUBSET]) THEN
    ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING_EQ; ring_divides] THEN
    ASM_MESON_TAC[];
    STRIP_TAC THEN FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
    ASM_SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; RING_IDEAL_IMP_SUBSET;
                 RING_IDEAL_IDEAL_GENERATED]]);;

let IDEAL_PROD_SETADD_LDISTRIB = prove
 (`!r j k l:A->bool.
        j SUBSET ring_carrier r /\ ring_ideal r k /\ ring_ideal r l
        ==> ideal_prod r j (ring_setadd r k l) =
            ring_setadd r (ideal_prod r j k) (ideal_prod r j l)`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
    SIMP_TAC[RING_IDEAL_SETADD; RING_IDEAL_IDEAL_PROD] THEN
    REWRITE_TAC[ring_setadd; IN_ELIM_THM] THEN
    MAP_EVERY X_GEN_TAC [`a:A`; `b:A`] THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
     (X_CHOOSE_THEN `y:A` (X_CHOOSE_THEN `z:A` STRIP_ASSUME_TAC))) THEN
