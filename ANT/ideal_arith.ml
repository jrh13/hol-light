(* The inclusion SUPERSET: for u IN f a the set of v with u v in the         *)
(* product over a INSERT s is an ideal, and it contains every generator of   *)
(* the product over s (update the family at a to u).                         *)

let IDEAL_PRODUCT_INSERT = prove
 (`!r:A ring s (f:K->A->bool) a.
        FINITE s /\ ~(a IN s) /\ ring_ideal r (f a)
