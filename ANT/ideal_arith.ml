    ASM_SIMP_TAC[RING_PRODUCT_CLAUSES] THEN
    MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
    ASM_SIMP_TAC[RING_PRODUCT; RING_PRODUCT_IN_IDEAL_PRODUCT];
    MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_PRODUCT] THEN
    X_GEN_TAC `u:A` THEN REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN
    DISCH_TAC THEN
    SUBGOAL_THEN `(u:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    MP_TAC(ISPECL
     [`r:A ring`;
      `{v:A | v IN ring_carrier r /\
              ring_mul r u v IN ideal_product r ((a:K) INSERT s) f}`;
      `{ring_product r s x | x | !i. i IN s ==> (x:K->A) i IN f i}`]
