(* Local lemma (primes): in a Dedekind domain the class of a nonzero ideal j *)
(* lies in the subgroup generated by the classes of the nonzero primes       *)
(* containing j (Noetherian induction).                                      *)
let NUMBER_FIELD_CLASS_GROUP_MINKOWSKI =
  let primes = prove
   (`!r j:A->bool.
          dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
          ==> ideal_class r j IN
              group_carrier(subgroup_generated (class_group r)
                {ideal_class r p | p | prime_ideal r p /\ ~(p = {ring_0 r}) /\
                                       j SUBSET p})`,
    REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN
    X_GEN_TAC `r:A ring` THEN DISCH_TAC THEN
    MATCH_MP_TAC NOETHERIAN_RING_INDUCT THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_NOETHERIAN] THEN
    X_GEN_TAC `j:A->bool` THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "ind")) THEN DISCH_TAC THEN
    ASM_CASES_TAC `j = ring_carrier(r:A ring)` THENL
     [ASM_SIMP_TAC[GSYM(CONJUNCT1(CONJUNCT2 CLASS_GROUP)); GROUP_ID_SUBGROUP];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] MAXIMAL_SUPERIDEAL_EXISTS) THEN
