(* Minkowski for the real linear forms Re(g x) + Im(g x), g in E, with a     *)
(* separate bound c_g for each embedding. Local lemmas: Cx is a ring         *)
(* homomorphism (cx_hom; for conjugation RING_HOMOMORPHISM_CNJ of            *)
(* Multivariate/complex_ring.ml); the others are explained where they are    *)
(* proved.                                                                   *)
let NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS =
  let cx_hom = prove
   (`ring_homomorphism(real_ring,complex_ring) Cx`,
    REWRITE_TAC[ring_homomorphism; COMPLEX_RING_CLAUSES; REAL_RING_CLAUSES;
                SUBSET_UNIV; IN_UNIV; CX_ADD; CX_MUL; CX_NEG])
  (* Re z + Im z = a z + b cnj z for a = (1 - ii) / 2 and b = (1 + ii) / 2; *)
  (* sums with two delta terms; the entries of B conj(B) = I below.          *)
  and reim = prove
   (`!z. (Cx(&1 / &2) * (Cx(&1) - ii)) * z +
         (Cx(&1 / &2) * (Cx(&1) + ii)) * cnj z =
         Cx(Re z + Im z)`,
    REWRITE_TAC[COMPLEX_EQ; RE_ADD; IM_ADD; complex_mul; RE; IM; RE_CX; IM_CX;
                RE_II; IM_II; RE_SUB; IM_SUB; RE_CNJ; IM_CNJ] THEN
    REAL_ARITH_TAC)
  and vsum_delta2 = prove
   (`!s i i' a b (X:K->complex).
          FINITE s /\ i IN s /\ i' IN s
          ==> vsum s (\l. ((if l = i then a else Cx(&0)) +
                           (if l = i' then b else Cx(&0))) * X l) =
              a * X i + b * X i'`,
    REPEAT STRIP_TAC THEN
    TRANS_TAC EQ_TRANS
     `vsum s (\l:K. (if l = i then a * X i else vec 0) +
                    (if l = i' then b * (X:K->complex) i' else vec 0))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC VSUM_EQ THEN REPEAT STRIP_TAC THEN
      REWRITE_TAC[COMPLEX_ADD_RDISTRIB] THEN BINOP_TAC THEN
      COND_CASES_TAC THEN ASM_REWRITE_TAC[COMPLEX_VEC_0; COMPLEX_MUL_LZERO];
      ASM_SIMP_TAC[VSUM_ADD; VSUM_DELTA]])
  and bb = prove
   (`!P Q. (Cx(&1 / &2) * (Cx(&1) - ii)) *
           ((if P then cnj(Cx(&1 / &2) * (Cx(&1) - ii)) else Cx(&0)) +
            (if Q then cnj(Cx(&1 / &2) * (Cx(&1) + ii)) else Cx(&0))) +
           (Cx(&1 / &2) * (Cx(&1) + ii)) *
           ((if Q then cnj(Cx(&1 / &2) * (Cx(&1) - ii)) else Cx(&0)) +
            (if P then cnj(Cx(&1 / &2) * (Cx(&1) + ii)) else Cx(&0))) =
           if P then Cx(&1) else Cx(&0)`,
    REWRITE_TAC[CNJ_MUL; CNJ_SUB; CNJ_ADD; CNJ_CX; CNJ_II] THEN
    REPEAT GEN_TAC THEN ASM_CASES_TAC `P:bool` THEN ASM_CASES_TAC `Q:bool` THEN
    ASM_REWRITE_TAC[] THEN MP_TAC COMPLEX_POW_II_2 THEN
    CONV_TAC COMPLEX_RING) in
  (* |det(Re M + Im M)| = |det M| when conjugation permutes the rows of M    *)
  (* by an involution p: Cx(Re M + Im M) = B M with B conj(B) = I for        *)
  (* B i l = a [l = i] + b [l = p i].                                        *)
  let det_reim = prove
   (`!s (p:K->K) (M:K->K->complex).
          FINITE s /\ (!i. i IN s ==> p i IN s /\ p(p i) = i) /\
          (!i j. i IN s /\ j IN s ==> M (p i) j = cnj(M i j))
          ==> norm(ring_det complex_ring s (\i j. Cx(Re(M i j) + Im(M i j)))) =
              norm(ring_det complex_ring s M)`,
    REPEAT STRIP_TAC THEN
    ABBREV_TAC `B = \i l:K. (if l = i then Cx(&1 / &2) * (Cx(&1) - ii)
                             else Cx(&0)) +
                            (if l = p i then Cx(&1 / &2) * (Cx(&1) + ii)
                             else Cx(&0))` THEN
    SUBGOAL_THEN
     `!X:K->complex i. i IN s
          ==> vsum s (\l. B i l * X l) =
              (Cx(&1 / &2) * (Cx(&1) - ii)) * X i +
              (Cx(&1 / &2) * (Cx(&1) + ii)) * X((p:K->K) i)`
    ASSUME_TAC THENL
     [REPEAT STRIP_TAC THEN EXPAND_TAC "B" THEN
      MATCH_MP_TAC vsum_delta2 THEN ASM_SIMP_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_det complex_ring s (\i j:K. Cx(Re(M i j) + Im(M i j))) =
      ring_mul complex_ring (ring_det complex_ring s B)
        (ring_det complex_ring s M)`
    SUBST1_TAC THENL
     [W(MP_TAC o PART_MATCH (rand o rand) RING_DET_MUL o rand o snd) THEN
      ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES; IN_UNIV] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN MATCH_MP_TAC RING_DET_EQ THEN
      REPEAT STRIP_TAC THEN ASM_SIMP_TAC[COMPLEX_RING_SUM] THEN
      REWRITE_TAC[reim];
      ALL_TAC] THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; COMPLEX_NORM_MUL] THEN
    MATCH_MP_TAC(REAL_RING `x:real = &1 ==> x * y = y`) THEN
    SUBGOAL_THEN
     `ring_mul complex_ring (ring_det complex_ring s B)
        (ring_det complex_ring s (\i l:K. cnj(B i l))) = Cx(&1)`
    MP_TAC THENL
     [W(MP_TAC o PART_MATCH (rand o rand) RING_DET_MUL o lhand o snd) THEN
      ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES; IN_UNIV] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      MP_TAC(ISPECL [`complex_ring`; `s:K->bool`] RING_DET_I) THEN
      ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN MATCH_MP_TAC RING_DET_EQ THEN
      MAP_EVERY X_GEN_TAC [`i:K`; `l:K`] THEN STRIP_TAC THEN
      ASM_SIMP_TAC[COMPLEX_RING_SUM] THEN EXPAND_TAC "B" THEN
      REWRITE_TAC[CNJ_ADD; CNJ_CX; MESON[]
       `!b x y. cnj(if b then x else y) = if b then cnj x else cnj y`] THEN
      ASM_SIMP_TAC[] THEN SUBST1_TAC(ISPECL [`i:K`; `l:K`] EQ_SYM_EQ) THEN
      REWRITE_TAC[bb];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`complex_ring`; `complex_ring`; `cnj`; `s:K->bool`;
                   `B:K->K->complex`] RING_DET_HOMOMORPHISM) THEN
    ASM_REWRITE_TAC[RING_HOMOMORPHISM_CNJ; COMPLEX_RING_CLAUSES; IN_UNIV] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    REWRITE_TAC[COMPLEX_MUL_CNJ; GSYM CX_POW; CX_INJ] THEN DISCH_TAC THEN
    MATCH_MP_TAC REAL_POW_EQ THEN EXISTS_TAC `2` THEN
    ASM_REWRITE_TAC[NORM_POS_LE; REAL_POS; REAL_POW_ONE; ARITH_EQ]) in
  (* For an enumeration e of E and an integral basis w, the real matrix      *)
  (* Re(e_i(w_j)) + Im(e_i(w_j)) has |det| = sqrt|d_K|.                      *)
  let det_disc = prove
   (`!k n w (e:num->A->complex).
          number_field k /\
          free_basis (integer_ring,ring_of_integers k) (ring_of_int k) n w /\
          (!i. i < n ==> e i IN complex_embeddings k) /\
          (!i j. i < n /\ j < n /\ e i = e j ==> i = j) /\
          (!g. g IN complex_embeddings k ==> ?i. i < n /\ e i = g)
          ==> abs(ring_det real_ring {i | i < n}
                    (\i j. Re(e i (w j)) + Im(e i (w j)))) =
              sqrt(abs(real_of_int(number_field_discriminant k)))`,
    REPEAT STRIP_TAC THEN
    SUBGOAL_THEN
     `?p. !i. i < n
              ==> p i < n /\
                  (e:num->A->complex)(p i) =
                  RESTRICTION (ring_carrier k) (cnj o e i)`
    STRIP_ASSUME_TAC THENL
     [REWRITE_TAC[GSYM SKOLEM_THM; RIGHT_EXISTS_IMP_THM] THEN
      ASM_MESON_TAC[COMPLEX_EMBEDDINGS_CNJ];
      ALL_TAC] THEN
    SUBGOAL_THEN `!j. j < n ==> (w:num->A) j IN ring_carrier k`
    ASSUME_TAC THENL
     [FIRST_ASSUM(MP_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
      MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN SET_TAC[];
      ALL_TAC] THEN
    REWRITE_TAC[GSYM COMPLEX_NORM_CX] THEN
    MP_TAC(BETA_RULE(ISPECL
     [`real_ring`; `complex_ring`; `Cx`; `{i:num | i < n}`;
      `\i j. Re((e:num->A->complex) i ((w:num->A) j)) + Im(e i (w j))`]
      RING_DET_HOMOMORPHISM)) THEN
    REWRITE_TAC[cx_hom; REAL_RING_CLAUSES; IN_UNIV; FINITE_NUMSEG_LT] THEN
    DISCH_THEN SUBST1_TAC THEN
    MP_TAC(BETA_RULE(ISPECL
     [`{i:num | i < n}`; `p:num->num`;
      `\i j. (e:num->A->complex) i ((w:num->A) j)`] det_reim)) THEN
    ANTS_TAC THENL
     [REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN CONJ_TAC THENL
       [X_GEN_TAC `i:num` THEN DISCH_TAC THEN ASM_SIMP_TAC[] THEN
        FIRST_ASSUM MATCH_MP_TAC THEN ASM_SIMP_TAC[] THEN
        ASM_MESON_TAC[COMPLEX_EMBEDDINGS_CNJ_CNJ];
        ASM_SIMP_TAC[RESTRICTION; o_THM]];
      DISCH_THEN SUBST1_TAC] THEN
    MATCH_MP_TAC(GSYM SQRT_UNIQUE) THEN REWRITE_TAC[NORM_POS_LE] THEN
    REWRITE_TAC[GSYM COMPLEX_NORM_POW; GSYM COMPLEX_NORM_CX] THEN
    AP_TERM_TAC THEN CONV_TAC SYM_CONV THEN
    MATCH_MP_TAC NUMBER_FIELD_DISCRIMINANT_EMBEDDINGS THEN
    ASM_REWRITE_TAC[]) in
  (* An ideal j of finite index in a ring free over Z with basis w contains  *)
  (* the elements with coordinates C z, for an integer matrix C spanning the *)
  (* coordinates of j; hence |det C| = N(j).                                 *)
  let lattice = prove
   (`!r:A ring n w j.
          free_basis (integer_ring,r) (ring_of_int r) n w /\
          ring_ideal r j /\ FINITE(ring_carrier(quotient_ring r j))
          ==> ?C. &(ideal_norm r j) =
                  abs(ring_det integer_ring {i | i < n} C) /\
                  !z. ring_sum r {i | i < n}
                        (\i. ring_mul r
                               (ring_of_int r
                                 (isum {l | l < n} (\l. C i l * z l)))
                               (w i)) IN j`,
    REPEAT STRIP_TAC THEN
    ABBREV_TAC `L = {z | (!i. ~(i < n) ==> z i = &0) /\
                         ring_sum r {i | i < n}
                           (\i. ring_mul r (ring_of_int r (z i)) ((w:num->A) i))
                         IN (j:A->bool)}` THEN
    SUBGOAL_THEN
     `int_lattice {i:num | i < n} L /\
      !x. (!i. ~(i IN {i:num | i < n}) ==> x i = &0)
          ==> (\i. &(ideal_norm r (j:A->bool)) * x i) IN L`
    STRIP_ASSUME_TAC THENL
     [FIRST_ASSUM(ASSUME_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
      MP_TAC(ISPECL [`r:A ring`; `{i:num | i < n}`; `w:num->A`]
        RING_INT_LINCOMB) THEN
      ASM_REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN STRIP_TAC THEN
      EXPAND_TAC "L" THEN
      ASM_SIMP_TAC[int_lattice; SUBSET; IN_ELIM_THM; IN_RING_IDEAL_0;
                   IN_RING_IDEAL_SUB; INT_SUB_REFL; INT_MUL_RZERO] THEN
      REWRITE_TAC[GSYM RING_OF_INT_OF_NUM] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_RING_IDEAL_RMUL THEN
      ASM_SIMP_TAC[RING_SUM; RING_OF_INT_OF_NUM; IDEAL_NORM_IN_IDEAL];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`{i:num | i < n}`; `L:(num->int)->bool`]
      INT_LATTICE_MATRIX_IMAGE) THEN
    ASM_REWRITE_TAC[FINITE_NUMSEG_LT] THEN
    DISCH_THEN(X_CHOOSE_TAC `C:num->num->int`) THEN
    EXISTS_TAC `C:num->num->int` THEN CONJ_TAC THENL
     [MP_TAC(ISPECL [`{i:num | i < n}`; `C:num->num->int`]
        INT_COSETS_MATRIX_IMAGE) THEN
      REWRITE_TAC[FINITE_NUMSEG_LT] THEN ANTS_TAC THENL
       [MATCH_MP_TAC INT_LATTICE_FULL_RANK THEN
        MAP_EVERY EXISTS_TAC [`L:(num->int)->bool`;
                              `&(ideal_norm r (j:A->bool)):int`] THEN
        ASM_REWRITE_TAC[FINITE_NUMSEG_LT; INT_OF_NUM_EQ] THEN
        ASM_SIMP_TAC[IDEAL_NORM_POS; ARITH_RULE `1 <= n ==> ~(n = 0)`];
        ALL_TAC] THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check (is_eq o concl)) THEN
      MP_TAC(ISPECL [`r:A ring`; `n:num`; `w:num->A`; `j:A->bool`;
                     `num_of_int(abs(ring_det integer_ring {i:num | i < n}
                                      (C:num->num->int)))`]
        FREE_BASIS_QUOTIENT_RING_HAS_SIZE) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
      SIMP_TAC[HAS_SIZE; ideal_norm] THEN
      DISCH_THEN(SUBST1_TAC o CONJUNCT2) THEN
      SIMP_TAC[INT_OF_NUM_OF_INT; INT_ABS_POS];
      X_GEN_TAC `z:num->int` THEN
      SUBGOAL_THEN
       `(\i. if i IN {i:num | i < n}
             then isum {l | l < n} (\l. (C:num->num->int) i l * z l)
             else &0) IN L`
      MP_TAC THENL
       [ASM_REWRITE_TAC[INT_MATRIX_IMAGE_IN] THEN MESON_TAC[]; ALL_TAC] THEN
      EXPAND_TAC "L" THEN REWRITE_TAC[IN_ELIM_THM] THEN
      MATCH_MP_TAC(SET_RULE `(x:A) = y ==> P /\ x IN j ==> y IN j`) THEN
      MATCH_MP_TAC RING_SUM_EQ THEN SIMP_TAC[IN_ELIM_THM]]) in
  (* Re + Im of an embedding on an integer combination.                      *)
  let lincomb = prove
   (`!k (g:A->complex) s (a:K->int) w.
          g IN complex_embeddings k /\ FINITE s /\
          (!i. i IN s ==> w i IN ring_carrier k)
          ==> Re(g(ring_sum k s (\i. ring_mul k (ring_of_int k (a i)) (w i)))) +
              Im(g(ring_sum k s (\i. ring_mul k (ring_of_int k (a i)) (w i)))) =
              sum s (\i. real_of_int(a i) * (Re(g(w i)) + Im(g(w i))))`,
    REWRITE_TAC[complex_embeddings; IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
    SUBGOAL_THEN
     `g(ring_sum k s (\i. ring_mul k (ring_of_int k (a i)) ((w:K->A) i))) =
      vsum s (\i. Cx(real_of_int(a i)) * (g:A->complex)(w i))`
    SUBST1_TAC THENL
     [FIRST_ASSUM(fun th ->
        ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_SUM th; RING_MUL;
                     RING_OF_INT]) THEN
      ASM_SIMP_TAC[COMPLEX_RING_SUM] THEN MATCH_MP_TAC VSUM_EQ THEN
      X_GEN_TAC `i:K` THEN DISCH_TAC THEN REWRITE_TAC[o_THM] THEN
      FIRST_ASSUM(fun th ->
        ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_MUL th; RING_OF_INT;
                     MATCH_MP RING_HOMOMORPHISM_RING_OF_INT th]) THEN
      REWRITE_TAC[COMPLEX_RING_OF_INT; COMPLEX_RING_CLAUSES];
      ASM_SIMP_TAC[RE_VSUM; IM_VSUM; RE_MUL_CX; IM_MUL_CX; GSYM SUM_ADD;
                   REAL_ADD_LDISTRIB]]) in
  (* The theorem for the forms Re(e_i x) + Im(e_i x) and bounds c_i: apply   *)
  (* MINKOWSKI_LINEAR_FORMS to the matrix L C.                               *)
  let box = prove
   (`!k j n w (e:num->A->complex) c.
          number_field k /\
          ring_ideal (ring_of_integers k) j /\ ~(j = {ring_0 k}) /\
          free_basis (integer_ring,ring_of_integers k) (ring_of_int k) n w /\
          (!i. i < n ==> e i IN complex_embeddings k) /\
          (!i j. i < n /\ j < n /\ e i = e j ==> i = j) /\
          (!g. g IN complex_embeddings k ==> ?i. i < n /\ e i = g) /\
          (!i. i < n ==> &0 < c i) /\
          sqrt(abs(real_of_int(number_field_discriminant k))) *
          &(ideal_norm (ring_of_integers k) j) <= product {i | i < n} c
          ==> ?x. x IN j /\ ~(x = ring_0 k) /\
                  !i. i < n ==> abs(Re(e i x) + Im(e i x)) <= c i`,
    REPEAT STRIP_TAC THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
    SUBGOAL_THEN `!i. i < n ==> (w:num->A) i IN ring_carrier k` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!y. ring_sum (ring_of_integers k) {i | i < n}
            (\i. ring_mul k (ring_of_int k (y i)) ((w:num->A) i)) =
