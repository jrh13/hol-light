let NUMBER_FIELD_RAMIFIED_PRIME_EXISTS = prove
 (`!k:A ring.
        number_field k /\
        ~(extension_degree (subfield_generated k {ring_0 k},k) I = 1)
        ==> ?p P. prime p /\ prime_ideal (ring_of_integers k) P /\
                  ring_of_num k p IN P /\
                  1 < ramification_index (integer_ring,ring_of_integers k)
                        (ring_of_int k) P`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_DISCRIMINANT_ABS_GT_1) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MP_TAC(SPEC `num_of_int(abs(number_field_discriminant(k:A ring)))`
    PRIME_FACTOR) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[GSYM INT_OF_NUM_EQ] THEN
    SIMP_TAC[INT_OF_NUM_OF_INT; INT_ABS_POS] THEN ASM_INT_ARITH_TAC;
    DISCH_THEN(X_CHOOSE_THEN `p:num` STRIP_ASSUME_TAC)] THEN
  MAP_EVERY EXISTS_TAC [`p:num`] THEN
  MP_TAC(ISPECL [`k:A ring`; `p:num`] NUMBER_FIELD_RAMIFIED_DISCRIMINANT) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC(TAUT `q ==> (p <=> q) ==> p`) THEN
  UNDISCH_TAC
   `p divides num_of_int(abs(number_field_discriminant(k:A ring)))` THEN
  REWRITE_TAC[num_divides] THEN
  SIMP_TAC[INT_OF_NUM_OF_INT; INT_ABS_POS; INT_DIVIDES_RABS]);;

(* ------------------------------------------------------------------------- *)
(* Sums of squared absolute values: sum_l |sum_j c_j M_lj|^2 is the real     *)
(* quadratic form in the c_j with coefficients Re(sum_l cnj(M_li) M_lj)      *)
(* (COMPLEX_NORM_POW_2_VSUM_FORM).                                           *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_NORM_POW_2_VSUM_FORM = prove
 (`!s t (M:L->K->complex) (c:K->real).
        FINITE s /\ FINITE t
        ==> sum s (\l. norm(vsum t (\j. Cx(c j) * M l j)) pow 2) =
            sum t (\i. sum t (\j. Re(vsum s (\l. cnj(M l i) * M l j)) *
                                  c i * c j))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `!l. norm(vsum t (\j. Cx(c j) * (M:L->K->complex) l j)) pow 2 =
        sum t (\i. sum t (\j. Re(cnj(M l i) * M l j) * c i * c j))`
  (fun th -> REWRITE_TAC[th]) THENL
   [X_GEN_TAC `l:L` THEN
    GEN_REWRITE_TAC LAND_CONV [GSYM RE_CX] THEN
    REWRITE_TAC[CX_POW; GSYM(CONJUNCT1(SPEC_ALL COMPLEX_MUL_CNJ))] THEN
    ASM_SIMP_TAC[CNJ_VSUM; CNJ_MUL; CNJ_CX] THEN
    ASM_SIMP_TAC[GSYM VSUM_COMPLEX_RMUL; GSYM VSUM_COMPLEX_LMUL; RE_VSUM] THEN
    MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `i:K` THEN DISCH_TAC THEN
    REWRITE_TAC[] THEN MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `j:K` THEN
    DISCH_TAC THEN REWRITE_TAC[] THEN
    REWRITE_TAC[prove
     (`!a b x y. (Cx a * x) * (Cx b * y) = Cx(a * b) * (x * y)`,
      REWRITE_TAC[CX_MUL] THEN CONV_TAC COMPLEX_RING)] THEN
    REWRITE_TAC[RE_MUL_CX] THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `sum t (\i. sum s (\l. sum t (\j.
       Re(cnj((M:L->K->complex) l i) * M l j) * c i * c j)))` THEN
  CONJ_TAC THENL
   [GEN_REWRITE_TAC LAND_CONV
     [MATCH_MP SUM_SWAP (CONJ (ASSUME `FINITE(s:L->bool)`)
                              (ASSUME `FINITE(t:K->bool)`))] THEN
    REWRITE_TAC[];
    MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `i:K` THEN DISCH_TAC THEN
    REWRITE_TAC[] THEN
    GEN_REWRITE_TAC LAND_CONV
     [MATCH_MP SUM_SWAP (CONJ (ASSUME `FINITE(s:L->bool)`)
                              (ASSUME `FINITE(t:K->bool)`))] THEN
    REWRITE_TAC[] THEN
    MATCH_MP_TAC SUM_EQ THEN X_GEN_TAC `j:K` THEN DISCH_TAC THEN
    ASM_SIMP_TAC[REWRITE_RULE[ETA_AX] RE_VSUM; SUM_RMUL]]);;
