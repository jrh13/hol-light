let NUMBER_FIELD_DISCRIMINANT_ABS_GT_1 =
  let product_eq = prove
   (`!s (f:K->real) c.
          FINITE s /\ (!i. i IN s ==> &0 <= f i /\ f i <= c i /\ &0 < c i) /\
