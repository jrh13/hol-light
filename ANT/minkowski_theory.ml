(* ========================================================================= *)
(* Minkowski theory of a number field k with ring of integers O, by boxes    *)
(* (no measure theory and no type of dimension [k:Q]).                       *)
(* E = complex_embeddings k, d_K = number_field_discriminant k,              *)
(* N = ideal_norm O.                                                         *)
(*                                                                           *)
(* Main results: every nonzero ideal j of O contains x <> 0 with |Re(g x) +  *)
(* Im(g x)| <= c_g for all g in E, for any positive c_g, one for each        *)
(* embedding, with prod c_g >= sqrt|d_K| N(j)                                *)
(* (NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS), and x <> 0 with |g x| <= c_g *)
(* for all g in E when c is constant on the infinite places                  *)
(* (NUMBER_FIELD_IDEAL_MINKOWSKI; Neukirch I.5.3 with boxes in place of      *)
(* discs); hence N((x)) <= sqrt|d_K| N(j) for some x <> 0 in j               *)
(* (NUMBER_FIELD_IDEAL_MINKOWSKI_NORM), every ideal class contains an        *)
(* integral ideal of norm at most sqrt|d_K|                                  *)
(* (NUMBER_FIELD_IDEAL_CLASS_MINKOWSKI), the class group is generated by the *)
(* classes of the primes of norm at most sqrt|d_K|                           *)
(* (NUMBER_FIELD_CLASS_GROUP_MINKOWSKI), and O is a PID if all those primes  *)
(* are principal (NUMBER_FIELD_PID_MINKOWSKI). Minkowski: d_K = 1 if [k:Q] = *)
(* 1 (NUMBER_FIELD_DISCRIMINANT_DEGREE_1) and |d_K| > 1 otherwise            *)
(* (NUMBER_FIELD_DISCRIMINANT_ABS_GT_1), so some prime ramifies in every     *)
(* number field other than Q (NUMBER_FIELD_RAMIFIED_PRIME_EXISTS).           *)
(*                                                                           *)
(* Routes. Enumerate E as e_0, ..., e_(n-1) and take an integral basis w.    *)
(* The real linear forms l_i(x) = Re(e_i x) + Im(e_i x) have the matrix L    *)
(* with Cx o L = B M, where M = (e_i(w_j)), B = ((1 - ii) I + (1 + ii)       *)
(* P) / 2 and P permutes the rows by conjugation; B conj(B) = I, so |det L|  *)
(* = |det M| = sqrt|d_K| (NUMBER_FIELD_DISCRIMINANT_EMBEDDINGS). The         *)
(* coordinates of the elements of j form int_matrix_image n C with |det C| = *)
(* N(j) (INT_LATTICE_MATRIX_IMAGE, INT_LATTICE_FULL_RANK,                    *)
(* INT_COSETS_MATRIX_IMAGE, FREE_BASIS_QUOTIENT_RING_HAS_SIZE).              *)
(* MINKOWSKI_LINEAR_FORMS for the matrix L C and the bounds c(e_i) gives x   *)
(* in j with |l_i(x)| <= c(e_i); when c is constant on the places, for g and *)
(* its conjugate this says |Re(g x)| + |Im(g x)| <= c g, so |g x| <= c g.    *)
(* The class of an ideal lies in the subgroup generated by the classes of    *)
(* the primes containing it (Noetherian induction; containment is            *)
(* divisibility). If |d_K| = 1 and k has two places v1 <> v2 (always the     *)
(* case for [k:Q] >= 3), the bounds t^e2 on v1, t^(-e1) on v2 and 1          *)
(* elsewhere (e_i the number of embeddings of v_i) have product 1, so the    *)
(* element x_t has |g x_t| = c_t(g) for all g (as N((x_t)) >= 1); the x_t    *)
(* for t = 1 + 1 / (m + 1) are pairwise distinct with bounded conjugates,    *)
(* contradicting RING_OF_INTEGERS_BOUNDED_CONJUGATES_FINITE. For [k:Q] = 2   *)
(* use QUADRATIC_FIELD_DISCRIMINANT; ramified primes come from               *)
(* NUMBER_FIELD_RAMIFIED_DISCRIMINANT.                                       *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (REAL_RING_SUM), Library/fieldtheory.ml,      *)
(* Library/isum.ml, Library/products.ml (product), Library/grouptheory.ml    *)
(* (subgroup_generated), Library/ring_det.ml, ANT/ideal_arith.ml,            *)
(* ANT/dedekind.ml, ANT/dedekind_struct.ml, ANT/ideal_norm.ml,               *)
(* ANT/zlattice.ml, ANT/linear_forms.ml (MINKOWSKI_LINEAR_FORMS),            *)
(* ANT/numfield.ml, ANT/ring_of_integers.ml, ANT/norm_index.ml,              *)
(* ANT/classgroup.ml, ANT/classgroup_group.ml, ANT/prime_split.ml,           *)
(* ANT/discriminant.ml, ANT/ramification.ml, ANT/quadratic.ml,               *)
(* ANT/complex_embeddings.ml (and with it Multivariate/cauchy.ml: the        *)
(* complex numbers) and ANT/infinite_places.ml (COMPLEX_EMBEDDINGS_CNJ_CNJ,  *)
(* NUMBER_FIELD_DISCRIMINANT_EMBEDDINGS). Also Multivariate/complex_ring.ml  *)
(* (complex_ring, RING_HOMOMORPHISM_CNJ) and Multivariate/transcendentals.ml *)
(* (root).                                                                   *)
