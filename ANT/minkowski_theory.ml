(* Bounds constant on the infinite places: |Re(g x)| + |Im(g x)| <= c_g at g *)
(* and at its conjugate give |g x| <= c_g.                                   *)
let NUMBER_FIELD_IDEAL_MINKOWSKI = prove
 (`!k j (c:(A->complex)->real).
        number_field k /\
        ring_ideal (ring_of_integers k) j /\ ~(j = {ring_0 k}) /\
        (!g. g IN complex_embeddings k ==> &0 < c g) /\
        (!g h. g IN complex_embeddings k /\ h IN complex_embeddings k /\
               (!x. x IN ring_carrier k ==> norm(h x) = norm(g x))
               ==> c h = c g) /\
        sqrt(abs(real_of_int(number_field_discriminant k))) *
        &(ideal_norm (ring_of_integers k) j)
        <= product (complex_embeddings k) c
        ==> ?x. x IN j /\ ~(x = ring_0 k) /\
                !g. g IN complex_embeddings k ==> norm(g x) <= c g`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `j:A->bool`; `c:(A->complex)->real`]
    NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `x:A` THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [UNDISCH_TAC `(x:A) IN j` THEN
    MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP RING_IDEAL_IMP_SUBSET) THEN SET_TAC[];
    ALL_TAC] THEN
  X_GEN_TAC `g:A->complex` THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `(c:(A->complex)->real)(RESTRICTION (ring_carrier k) (cnj o g)) = c g`
  ASSUME_TAC THENL
   [FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
      can (find_term ((=) `norm:complex->real`)) (concl th))) THEN
    ASM_SIMP_TAC[COMPLEX_EMBEDDINGS_CNJ; RESTRICTION; o_THM;
                 COMPLEX_NORM_CNJ];
    ALL_TAC] THEN
  FIRST_ASSUM(MP_TAC o SPEC
   `RESTRICTION (ring_carrier k) (cnj o (g:A->complex))`) THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `g:A->complex`) THEN
  ASM_SIMP_TAC[COMPLEX_EMBEDDINGS_CNJ; RESTRICTION; o_THM; RE_CNJ;
               IM_CNJ] THEN
  MP_TAC(SPEC `(g:A->complex) x` COMPLEX_NORM_LE_RE_IM) THEN
  REAL_ARITH_TAC);;

