(* Composita and intersections of cyclotomic subfields.                      *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_SUBFIELD_COMPOSITUM = prove
 (`!(l:A ring) z w.
        field l /\ z IN ring_carrier l /\ w IN ring_carrier l /\
        ~(ring_order l z = 0) /\ ~(ring_order l w = 0)
        ==> (?v. v IN ring_carrier(subfield_generated l {z,w}) /\
                 ring_order l v = lcm(ring_order l z,ring_order l w)) /\
            !v. v IN ring_carrier l /\
                ring_order l v = lcm(ring_order l z,ring_order l w)
                ==> subfield_generated l {z,w} = subfield_generated l {v}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `(z:A) IN ring_carrier(subfield_generated l {z,w}) /\
    (w:A) IN ring_carrier(subfield_generated l {z,w})`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated l {z:A,w}`; `z:A`; `w:A`]
      RING_ORDER_LCM_EXISTS) THEN
    ASM_SIMP_TAC[RING_ORDER_SUBFIELD_GENERATED] THEN
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `v:A` THEN
    MESON_TAC[RING_ORDER_SUBFIELD_GENERATED];
    DISCH_THEN(X_CHOOSE_THEN `u:A` STRIP_ASSUME_TAC)] THEN
  X_GEN_TAC `v:A` THEN STRIP_TAC THEN
  ABBREV_TAC `N = lcm(ring_order l (z:A),ring_order l w)` THEN
  SUBGOAL_THEN `~(N = 0)` ASSUME_TAC THENL
   [EXPAND_TAC "N" THEN ASM_REWRITE_TAC[LCM_ZERO]; ALL_TAC] THEN
  SUBGOAL_THEN `(u:A) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET; SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_pow l (z:A) N = ring_1 l /\ ring_pow l (w:A) N = ring_1 l`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`l:A ring`; `z:A`; `N:num`] RING_ORDER_DIVIDES) THEN
    MP_TAC(ISPECL [`l:A ring`; `w:A`; `N:num`] RING_ORDER_DIVIDES) THEN
    ASM_REWRITE_TAC[] THEN EXPAND_TAC "N" THEN
    REWRITE_TAC[NUMBER_RULE `!m n:num. m divides lcm(m,n) /\
                                       n divides lcm(m,n)`] THEN
    SIMP_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC SUBFIELD_GENERATED_SUBSET_EQ THEN
  ASM_REWRITE_TAC[INSERT_SUBSET; EMPTY_SUBSET] THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_ROOT_OF_UNITY THEN
    EXISTS_TAC `N:num` THEN ASM_REWRITE_TAC[];
    MATCH_MP_TAC SUBFIELD_GENERATED_ROOT_OF_UNITY THEN
    EXISTS_TAC `N:num` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`l:A ring`; `u:A`; `v:A`]
    SUBFIELD_GENERATED_ROOT_OF_UNITY_EQ) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN `(v:A) IN ring_carrier(subfield_generated l {u})` MP_TAC THENL
   [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC(SET_RULE `(s:A->bool) SUBSET t ==> (x:A) IN s ==> x IN t`) THEN
  MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
  ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED_EQ; FIELD_SUBFIELD_GENERATED] THEN
  ASM SET_TAC[]);;

let CYCLOTOMIC_SUBFIELD_DEGREE = prove
 (`!(l:A ring) z n.
        field l /\ ring_char l = 0 /\ z IN ring_carrier l /\
        ring_order l z = n /\ ~(n = 0)
        ==> number_field(subfield_generated l {z}) /\
            extension_degree
              (subfield_generated l {ring_0 l},subfield_generated l {z}) I =
            phi n`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC NUMBER_FIELD_SUBFIELD_GENERATED_ALGEBRAIC THEN
    ASM_REWRITE_TAC[FINITE_SING; IN_SING; FORALL_UNWIND_THM2] THEN
    MATCH_MP_TAC RING_OF_INTEGERS_ALGEBRAIC THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC ROOT_OF_UNITY_IN_RING_OF_INTEGERS THEN
    EXISTS_TAC `n:num` THEN ASM_MESON_TAC[RING_POW_RING_ORDER];
    DISCH_TAC] THEN
  MP_TAC(ISPECL [`subfield_generated l {z:A}`; `z:A`; `n:num`]
    CYCLOTOMIC_FIELD_DEGREE) THEN
  ASM_SIMP_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED; SUBFIELD_GENERATED_IDEMPOT;
               RING_ORDER_SUBFIELD_GENERATED; SUBFIELD_GENERATED_INC;
               SING_SUBSET; IN_SING]);;

let CYCLOTOMIC_SUBFIELD_INTER = prove
 (`!(l:A ring) z w.
        field l /\ ring_char l = 0 /\
        z IN ring_carrier l /\ w IN ring_carrier l /\
        ~(ring_order l z = 0) /\ ~(ring_order l w = 0)
        ==> (?u. u IN ring_carrier(subfield_generated l {z}) /\
                 ring_order l u = gcd(ring_order l z,ring_order l w)) /\
            !u. u IN ring_carrier l /\
                ring_order l u = gcd(ring_order l z,ring_order l w)
                ==> ring_carrier(subfield_generated l {z}) INTER
                    ring_carrier(subfield_generated l {w}) =
                    ring_carrier(subfield_generated l {u})`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MAP_EVERY ABBREV_TAC
   [`m = ring_order l (z:A)`; `n = ring_order l (w:A)`] THEN
  ABBREV_TAC `g = gcd(m:num,n)` THEN
  SUBGOAL_THEN `~((g:num) = 0) /\ g divides m /\ g divides n`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "g" THEN CONJ_TAC THENL
     [ASM_REWRITE_TAC[GCD_ZERO]; CONV_TAC NUMBER_RULE];
    ALL_TAC] THEN
  CONJ_TAC THENL
   [EXISTS_TAC `ring_pow l (z:A) (m DIV g)` THEN CONJ_TAC THENL
     [MP_TAC(ISPECL [`subfield_generated l {z:A}`; `z:A`; `m DIV g`]
        RING_POW) THEN
      REWRITE_TAC[RING_POW_SUBFIELD_GENERATED] THEN
      DISCH_THEN MATCH_MP_TAC THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
      ASM SET_TAC[];
      ALL_TAC] THEN
    FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [divides] o check
     (fun th -> concl th = `(g:num) divides m`)) THEN
    DISCH_THEN(X_CHOOSE_THEN `q:num` SUBST_ALL_TAC) THEN
    RULE_ASSUM_TAC(REWRITE_RULE[MULT_EQ_0; DE_MORGAN_THM]) THEN
    ASM_SIMP_TAC[DIV_MULT] THEN
    MP_TAC(ISPECL [`l:A ring`; `z:A`; `q:num`] RING_ORDER_POW) THEN
    ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
     [CONV_TAC NUMBER_RULE; DISCH_THEN SUBST1_TAC] THEN
    ONCE_REWRITE_TAC[MULT_SYM] THEN ASM_SIMP_TAC[DIV_MULT];
    ALL_TAC] THEN
  X_GEN_TAC `u:A` THEN STRIP_TAC THEN
  ABBREV_TAC `N = lcm(m:num,n)` THEN
  SUBGOAL_THEN `~((N:num) = 0)` ASSUME_TAC THENL
   [EXPAND_TAC "N" THEN ASM_REWRITE_TAC[LCM_ZERO]; ALL_TAC] THEN
  MP_TAC(ISPECL [`l:A ring`; `z:A`; `w:A`] CYCLOTOMIC_SUBFIELD_COMPOSITUM) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(CONJUNCTS_THEN2 (X_CHOOSE_THEN `v:A` STRIP_ASSUME_TAC)
    (MP_TAC o SPEC `v:A`)) THEN
  SUBGOAL_THEN `(v:A) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET; SUBSET];
    ASM_REWRITE_TAC[] THEN DISCH_TAC] THEN
  SUBGOAL_THEN
   `!x:A. x IN ring_carrier l
          ==> ring_carrier(subfield_generated l {x}) subfield_of l /\
              ring_carrier(subfield_generated l {ring_0 l}) SUBSET
              ring_carrier(subfield_generated l {x})`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED_EQ; FIELD_SUBFIELD_GENERATED] THEN
    MATCH_MP_TAC PRIME_SUBFIELD_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED_EQ; FIELD_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  ABBREV_TAC
   `J = ring_carrier(subfield_generated l {z:A}) INTER
        ring_carrier(subfield_generated l {w})` THEN
  SUBGOAL_THEN `(J:A->bool) subfield_of l` ASSUME_TAC THENL
   [EXPAND_TAC "J" THEN MATCH_MP_TAC SUBFIELD_OF_INTER THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_carrier(subfield_generated l {u:A}) SUBSET J`
  ASSUME_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[] THEN
    EXPAND_TAC "J" THEN REWRITE_TAC[SING_SUBSET; IN_INTER] THEN
    CONJ_TAC THEN MATCH_MP_TAC SUBFIELD_GENERATED_ROOT_OF_UNITY THENL
     [EXISTS_TAC `m:num`; EXISTS_TAC `n:num`] THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`l:A ring`; `u:A`] RING_ORDER_DIVIDES) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(fun th -> REWRITE_TAC[GSYM th]) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`l:A ring`; `z:A`; `m:num`] CYCLOTOMIC_SUBFIELD_DEGREE) THEN
  MP_TAC(ISPECL [`l:A ring`; `w:A`; `n:num`] CYCLOTOMIC_SUBFIELD_DEGREE) THEN
  MP_TAC(ISPECL [`l:A ring`; `u:A`; `g:num`] CYCLOTOMIC_SUBFIELD_DEGREE) THEN
  MP_TAC(ISPECL [`l:A ring`; `v:A`; `N:num`] CYCLOTOMIC_SUBFIELD_DEGREE) THEN
  ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `finite_extension(subfield_generated l {ring_0 l},
                     subfield_generated l {z:A}) I /\
    galois_extension(subfield_generated l {ring_0 l},
                     subfield_generated l {z:A}) I`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated l {z:A}`; `z:A`; `m:num`]
      CYCLOTOMIC_FIELD_GALOIS_EXTENSION) THEN
    UNDISCH_TAC `number_field(subfield_generated l {z:A})` THEN
    SIMP_TAC[number_field; PRIME_SUBFIELD_SUBFIELD_GENERATED;
             SUBFIELD_GENERATED_IDEMPOT] THEN
    ASM_SIMP_TAC[RING_ORDER_SUBFIELD_GENERATED; SUBFIELD_GENERATED_INC;
                 SING_SUBSET; IN_SING];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated l {ring_0 l:A}`; `l:A ring`;
                 `ring_carrier(subfield_generated l {z:A})`;
                 `ring_carrier(subfield_generated l {w:A})`]
    GALOIS_COMPOSITUM_DEGREE) THEN
  ASM_SIMP_TAC[IMAGE_I; SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED;
               SUBFIELD_GENERATED_UNION] THEN
  REWRITE_TAC[SET_RULE `{a:A} UNION {b} = {a,b}`] THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN
   `ring_carrier(subfield_generated l {w:A}) SUBSET
    ring_carrier(subfield_generated l {v}) /\
    ring_carrier(subfield_generated l {ring_0 l}) SUBSET J /\
    J SUBSET ring_carrier(subfield_generated l {z:A})`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        rhs(concl th) = `subfield_generated l {v:A}`)) THEN
      MATCH_MP_TAC SUBFIELD_GENERATED_MONO THEN SET_TAC[];
      EXPAND_TAC "J" THEN REWRITE_TAC[SUBSET_INTER] THEN ASM_SIMP_TAC[];
      EXPAND_TAC "J" THEN SET_TAC[]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `I:A->A`; `subfield_generated l {ring_0 l:A}`;
                 `subfield_generated l {w:A}`; `subfield_generated l {v:A}`]
    EXTENSION_DEGREE_TOWER_LAW) THEN
  MP_TAC(ISPECL [`I:A->A`; `I:A->A`; `subfield_generated l {ring_0 l:A}`;
                 `subfield_generated l (J:A->bool)`;
                 `subfield_generated l {z:A}`]
    EXTENSION_DEGREE_TOWER_LAW) THEN
  MP_TAC(ISPECL [`I:A->A`; `I:A->A`; `subfield_generated l {ring_0 l:A}`;
                 `subfield_generated l {u:A}`;
                 `subfield_generated l (J:A->bool)`]
    EXTENSION_DEGREE_TOWER_LAW) THEN
  ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED_SUBSET; I_O_ID;
               CARRIER_SUBFIELD_GENERATED_SUBFIELD] THEN
  ABBREV_TAC
   `x = extension_degree
          (subfield_generated l {u:A},subfield_generated l J) I` THEN
  ABBREV_TAC
   `t = extension_degree
          (subfield_generated l J,subfield_generated l {z:A}) I` THEN
  REPEAT DISCH_TAC THEN
  SUBGOAL_THEN `x = 1` ASSUME_TAC THENL
   [MP_TAC(SPECL [`m:num`; `n:num`] PHI_LCM_GCD) THEN
    ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
    MP_TAC(SPEC `N:num` PHI_EQ_0) THEN MP_TAC(SPEC `g:num` PHI_EQ_0) THEN
    ASM_REWRITE_TAC[] THEN REPEAT DISCH_TAC THEN
    MATCH_MP_TAC(MESON[EQ_MULT_LCANCEL]
     `!a x:num. ~(a = 0) /\ a * x = a * 1 ==> x = 1`) THEN
    EXISTS_TAC `phi g * t * phi n` THEN CONJ_TAC THENL
     [REWRITE_TAC[MULT_EQ_0] THEN ASM_MESON_TAC[MULT_EQ_0];
      FIRST_X_ASSUM(MP_TAC o check (fun th ->
        is_eq(concl th) && is_comb(lhs(concl th)) &&
        rand(lhs(concl th)) = `phi n`)) THEN
      CONV_TAC NUM_RING];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated l {u:A}`;
                 `subfield_generated l (J:A->bool)`] EXTENSION_DEGREE_EQ_1) THEN
  ASM_SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED_SUBSET;
               CARRIER_SUBFIELD_GENERATED_SUBFIELD; IMAGE_I] THEN
  MESON_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* Cyclotomic fields with a cyclic Galois group: one subfield of each        *)
(* degree.                                                                   *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_FIELD_SUBFIELD_UNIQUE = prove
 (`!(k:A ring) z n s t.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        ~(n = 0) /\ subfield_generated k {z} = k /\
        cyclic_group(modmul_group n) /\
        s subfield_of k /\ t subfield_of k /\
        extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k s) I =
        extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k t) I
        ==> s = t`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC GALOIS_CYCLIC_INTERMEDIATE_UNIQUE THEN
  MAP_EVERY EXISTS_TAC
   [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`] THEN
  ASM_SIMP_TAC[IMAGE_I; PRIME_SUBFIELD_MINIMAL] THEN
  REPEAT CONJ_TAC THENL
   [ASM_MESON_TAC[number_field];
    MATCH_MP_TAC CYCLOTOMIC_FIELD_GALOIS_EXTENSION THEN
    MAP_EVERY EXISTS_TAC [`z:A`; `n:num`] THEN ASM_REWRITE_TAC[];
    MP_TAC(ISPECL [`k:A ring`; `z:A`; `n:num`]
      CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `e:(A->A)->num` (ASSUME_TAC o CONJUNCT1)) THEN
    MP_TAC(ISPECL [`galois_group(subfield_generated k {ring_0 k},k) (I:A->A)`;
                   `modmul_group n`] ISOMORPHIC_GROUP_CYCLICITY) THEN
    ASM_REWRITE_TAC[isomorphic_group] THEN
    ANTS_TAC THENL [ASM_MESON_TAC[]; SIMP_TAC[]]]);;

(* ------------------------------------------------------------------------- *)
(* The real subfield Q(z + z^-1) and its ring of integers.                   *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_FIELD_INVERSION_EXISTS = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        ~(n = 0) /\ subfield_generated k {z} = k
        ==> ?c. c IN group_carrier
                  (galois_group (subfield_generated k {ring_0 k},k) I) /\
                c z = ring_inv k z`,
  REPEAT STRIP_TAC THEN
