let CYCLOTOMIC_UNIT = prove
 (`!(k:A ring) z n a.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        2 <= n /\ coprime(a,n)
        ==> ring_associates (ring_of_integers k)
              (ring_sub k (ring_1 k) z)
              (ring_sub k (ring_1 k) (ring_pow k z a)) /\
            ring_unit (ring_of_integers k)
              (ring_div k (ring_sub k (ring_1 k) (ring_pow k z a))
                          (ring_sub k (ring_1 k) z))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP INTEGRAL_DOMAIN_RING_OF_INTEGERS) THEN
  SUBGOAL_THEN `(z:A) IN ring_carrier(ring_of_integers k)` ASSUME_TAC THENL
   [MATCH_MP_TAC ROOT_OF_UNITY_IN_RING_OF_INTEGERS THEN
    EXISTS_TAC `n:num` THEN ASM_SIMP_TAC[ARITH_RULE `2 <= n ==> ~(n = 0)`] THEN
    ASM_MESON_TAC[RING_POW_RING_ORDER];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(z = ring_1 (k:A ring)) /\ ~(z = ring_0 k)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN DISCH_THEN SUBST_ALL_TAC THENL
     [RULE_ASSUM_TAC(REWRITE_RULE[RING_ORDER_1]) THEN ASM_ARITH_TAC;
      MP_TAC(ISPECL [`k:A ring`; `ring_0 k:A`] RING_POW_RING_ORDER) THEN
      ASM_REWRITE_TAC[RING_POW_ZERO; RING_0] THEN
      COND_CASES_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
      ASM_MESON_TAC[FIELD_NONTRIVIAL]];
    ALL_TAC] THEN
  SUBGOAL_THEN `~((a:num) = 0)` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    RULE_ASSUM_TAC(REWRITE_RULE[COPRIME_0]) THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(SPECL [`a:num`; `1`; `n:num`] CONG_SOLVE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_TAC `b:num`) THEN
  SUBGOAL_THEN `~((b:num) = 0)` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    RULE_ASSUM_TAC(REWRITE_RULE[MULT_CLAUSES;
      NUMBER_RULE `(0 == 1) (mod n) <=> n = 1`]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPEC `ring_of_integers k:A ring` RING_1) THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `z:A`] RING_POW) THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN REPEAT DISCH_TAC THEN
  SUBGOAL_THEN
   `ring_associates (ring_of_integers k)
      (ring_sub k (ring_1 k) z)
      (ring_sub (k:A ring) (ring_1 k) (ring_pow k z a))`
  ASSUME_TAC THENL
   [REWRITE_TAC[ring_associates] THEN CONJ_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_1 k:A`; `z:A`;
                     `a:num`] RING_DIVIDES_SUB_POW) THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_POW_ONE];
      SUBGOAL_THEN `ring_pow k (ring_pow k (z:A) a) b = z` MP_TAC THENL
       [ASM_SIMP_TAC[RING_POW_POW] THEN
        MP_TAC(ISPECL [`k:A ring`; `z:A`; `a * b:num`; `1`] RING_POW_EQ) THEN
        ASM_SIMP_TAC[INTEGRAL_DOMAIN_REGULAR; FIELD_IMP_INTEGRAL_DOMAIN;
                     RING_POW_1];
        DISCH_TAC] THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_1 k:A`;
                     `ring_pow k z a:A`; `b:num`] RING_DIVIDES_SUB_POW) THEN
      ASM_SIMP_TAC[RING_OF_INTEGERS; RING_POW_ONE]];
    ASM_REWRITE_TAC[]] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                 `ring_sub k (ring_1 k) (z:A)`;
                 `ring_sub k (ring_1 k) (ring_pow k z a):A`]
    INTEGRAL_DOMAIN_ASSOCIATES) THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    (X_CHOOSE_THEN `u:A` STRIP_ASSUME_TAC))) THEN
  SUBGOAL_THEN `(u:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[ring_unit; RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_div k (ring_sub k (ring_1 k) (ring_pow k z a))
               (ring_sub k (ring_1 k) z) = (u:A)`
   (fun th -> ASM_REWRITE_TAC[th]) THEN
  MATCH_MP_TAC FIELD_DIV_EQ_MUL THEN
  ASM_SIMP_TAC[RING_SUB; RING_1; RING_POW; RING_SUB_EQ_0] THEN
  ASM_MESON_TAC[]);;

let ROOT_OF_UNITY_ONE_SUB_UNIT = prove
 (`!(k:A ring) z n.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = n /\
        ~(n = 0)
        ==> (ring_unit (ring_of_integers k) (ring_sub k (ring_1 k) z) <=>
             ~(?p j. prime p /\ n = p EXP j))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP INTEGRAL_DOMAIN_RING_OF_INTEGERS) THEN
  SUBGOAL_THEN `(z:A) IN ring_carrier(ring_of_integers k)` ASSUME_TAC THENL
   [MATCH_MP_TAC ROOT_OF_UNITY_IN_RING_OF_INTEGERS THEN
    EXISTS_TAC `n:num` THEN ASM_MESON_TAC[RING_POW_RING_ORDER];
    ALL_TAC] THEN
  MP_TAC(ISPEC `ring_of_integers k:A ring` RING_1) THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `z:A`] RING_POW) THEN
  MP_TAC(ISPEC `ring_of_integers k:A ring` RING_SUB) THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN REPEAT DISCH_TAC THEN
