     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `z:A`; `p:num`; `j:num`]
        RING_ASSOCIATES_PRIME_POWER_ORDER) THEN
      ASM_REWRITE_TAC[] THEN
      DISCH_THEN(MP_TAC o MATCH_MP RING_ASSOCIATES_UNIT) THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                     `ring_sub (ring_of_integers k)
                        (ring_1 (ring_of_integers k)) (z:A)`;
                     `phi(p EXP j)`] RING_UNIT_POW) THEN
      REWRITE_TAC[RING_OF_INTEGERS] THEN ASM_SIMP_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `p:num`] NUMBER_FIELD_PRIME_IDEALS_ABOVE_Q) THEN
