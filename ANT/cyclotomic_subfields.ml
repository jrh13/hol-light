    STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    ASM_CASES_TAC `v = ring_0 (k:A ring)` THENL
     [ASM_SIMP_TAC[RING_MUL_LZERO; RING_ADD_RZERO];
      ALL_TAC] THEN
    UNDISCH_TAC `~((z:A) IN ring_carrier(subfield_generated k {t}))` THEN
    MATCH_MP_TAC(TAUT `p ==> ~p ==> q`) THEN
    SUBGOAL_THEN
     `z = ring_div k (ring_sub k (ring_add k u (ring_mul k v z)) u) (v:A)`
    SUBST1_TAC THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC FIELD_DIV_EQ_MUL THEN
      ASM_SIMP_TAC[RING_SUB; RING_ADD; RING_MUL] THEN
      MATCH_MP_TAC(RING_RULE
       `!r u v z:A. u IN ring_carrier r /\ v IN ring_carrier r /\
                    z IN ring_carrier r
                    ==> ring_sub r (ring_add r u (ring_mul r v z)) u =
                        ring_mul r v z`) THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    MATCH_MP_TAC RING_DIV_IN_SUBFIELD_GENERATED THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED] THEN
    MP_TAC(ISPECL [`subfield_generated k {t:A}`;
                   `ring_add k u (ring_mul k v z):A`; `u:A`] RING_SUB) THEN
    ASM_REWRITE_TAC[RING_SUB_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  REWRITE_TAC[RINGS_EQ] THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS; CONJUNCT2 SUBFIELD_GENERATED;
                  CONJUNCT2 SUBRING_GENERATED]);;

