(* ========================================================================= *)
(* Subfields of cyclotomic fields and cyclotomic units.                      *)
(*                                                                           *)
(* Roots of unity in a field l: if z has finite order n, every w with        *)
(* w^n = 1 lies in the subfield generated by z, so elements of the same      *)
(* finite order generate the same subfield                                   *)
(* (SUBFIELD_GENERATED_ROOT_OF_UNITY, SUBFIELD_GENERATED_ROOT_OF_UNITY_EQ of *)
(* Library/fieldtheory.ml). Write Q(x) for subfield_generated l {x}; for z,  *)
(* w of finite orders m, n:                                                  *)
(*   the compositum Q(z,w) is Q(v) for every v of order lcm(m,n), and such   *)
(*   v exist in Q(z,w) (CYCLOTOMIC_SUBFIELD_COMPOSITUM, any field);          *)
(*   in characteristic 0, Q(z) has degree phi(m) over the prime field        *)
(*   (CYCLOTOMIC_SUBFIELD_DEGREE) and Q(z) INTER Q(w) = Q(u) for every u of  *)
(*   order gcd(m,n), such u existing in Q(z) (CYCLOTOMIC_SUBFIELD_INTER).    *)
(* The degree count uses phi(m) phi(n) = phi(lcm(m,n)) phi(gcd(m,n))         *)
(* (PHI_LCM_GCD of Library/multiplicative.ml).                               *)
(*                                                                           *)
(* In a finite Galois extension with cyclic Galois group, intermediate       *)
(* fields of the same degree are equal (GALOIS_CYCLIC_INTERMEDIATE_UNIQUE of *)
(* Library/galois.ml). Hence a cyclotomic field k = Q(z), z of order n, with *)
(* modmul_group n cyclic (n = 1, 2, 4, p^j or 2 p^j, p an odd prime) has at  *)
(* most one subfield of each degree (CYCLOTOMIC_FIELD_SUBFIELD_UNIQUE).      *)
(*                                                                           *)
(* The real subfield. For k = Q(z) there is c in the Galois group with       *)
(* c(z) = z^-1 (CYCLOTOMIC_FIELD_INVERSION_EXISTS). For n > 2 such a c is    *)
(* not the identity, the Galois group of k over K+ = Q(z + z^-1) is {I,c},   *)
(* K+ is the fixed field of c, [k:K+] = 2 and 2 [K+:Q] = phi(n)              *)
(* (CYCLOTOMIC_FIELD_REAL_SUBFIELD); the ring of integers of K+ is           *)
(* Z[z + z^-1] (CYCLOTOMIC_FIELD_REAL_SUBFIELD_RING_OF_INTEGERS).            *)
(*                                                                           *)
(* Cyclotomic units. For z of order n >= 2 in a number field k and a         *)
(* coprime to n, 1 - z and 1 - z^a are associates in O_k, so that            *)
(* (1 - z^a) / (1 - z) is a unit (CYCLOTOMIC_UNIT); 1 - z is a unit of O_k   *)
(* iff n is not a prime power (ROOT_OF_UNITY_ONE_SUB_UNIT).                  *)
(*                                                                           *)
(* Routes. Compositum: an element of order lcm(m,n) in Q(z,w)                *)
(* (RING_ORDER_LCM_EXISTS) generates all lcm(m,n)-th roots of unity.         *)
(* Intersection: natural irrationalities (GALOIS_COMPOSITUM_DEGREE,          *)
(* [Q(z,w):Q(w)] = [Q(z):Q(z) INTER Q(w)]) and the tower law give            *)
(* [Q(z) INTER Q(w):Q] = phi(m) phi(n) / phi(lcm(m,n)) = phi(gcd(m,n)),      *)
(* the degree of Q(u), which lies in the intersection. Uniqueness:           *)
(* GALOIS_CYCLIC_INTERMEDIATE_UNIQUE, the Galois group being isomorphic to   *)
(* modmul_group n (CYCLOTOMIC_FIELD_GALOIS_GROUP_MODMUL). Real subfield: an  *)
(* f in the Galois group fixing z + z^-1 has f(z) + f(z)^-1 = z + z^-1, so   *)
(* f(z) is z or z^-1 (FIELD_ADD_INV_EQ of Library/ringtheory.ml); for the    *)
(* integers, O_k = Z[z] (CYCLOTOMIC_FIELD_RING_OF_INTEGERS) is Z[t] + z Z[t] *)
(* for t = z + z^-1, since z^2 = t z - 1, and u + v z with v <> 0 is not     *)
(* fixed by c. Units: 1 - z divides 1 - z^a, and 1 - z^a divides             *)
(* 1 - z^(a b) = 1 - z when a b == 1 (mod n) (RING_DIVIDES_SUB_POW). If n    *)
(* has two distinct prime factors, the product of the 1 - z^j, j coprime to  *)
(* n, is Phi_n(1) = 1 (CYCLOTOMIC_POLY_SPLITS, CYCLOTOMIC_POLY_EVAL_1); if   *)
(* n = p^j, then (1 - z)^phi(n) is associated to p                           *)
(* (RING_ASSOCIATES_PRIME_POWER_ORDER), which is not a unit of O_k (it lies  *)
(* in a prime above p).                                                      *)
(*                                                                           *)
(* Uses: Library/multiplicative.ml (PHI_LCM_GCD), Library/pocklington.ml     *)
(* (phi), Library/prime.ml (lcm, prime factors), Library/ringtheory.ml (ring *)
(* orders, roots of unity, products, FIELD_ADD_INV_EQ), Library/ring_det.ml  *)
(* (RING_PRODUCT_DELETE), Library/fieldtheory.ml (generated subfields,       *)
(* degrees, SUBFIELD_GENERATED_ROOT_OF_UNITY_EQ), Library/grouptheory.ml     *)
(* (cyclic groups), Library/galois.ml (the Galois correspondence, composita, *)
(* GALOIS_CYCLIC_INTERMEDIATE_UNIQUE), Library/modmul_group.ml,              *)
(* ANT/numfield.ml, ANT/prime_split.ml (primes above p),                     *)
(* ANT/relative_split.ml, ANT/cyclotomic_poly.ml, ANT/cyclotomic_field.ml,   *)
(* ANT/cyclotomic_integers.ml (O = Z[z], RING_ASSOCIATES_PRIME_POWER_ORDER)  *)
(* and ANT/cyclotomic_galois.ml (Gal(Q(z)/Q), the units mod n).              *)
(* ========================================================================= *)

