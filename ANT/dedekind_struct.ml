let ideal_class = new_definition
 `ideal_class (r:A ring) (j:A->bool) =
    {k | ring_ideal r j /\ ring_ideal r k /\
         ~(j = {ring_0 r}) /\ ~(k = {ring_0 r}) /\
         ?a b. a IN ring_carrier r /\ b IN ring_carrier r /\
               ~(a = ring_0 r) /\ ~(b = ring_0 r) /\
               ideal_prod r (ideal_generated r {a}) j =
               ideal_prod r (ideal_generated r {b}) k}`;;

let IN_IDEAL_CLASS = prove
 (`!r:A ring j k.
        k IN ideal_class r j <=>
        ring_ideal r j /\ ring_ideal r k /\
        ~(j = {ring_0 r}) /\ ~(k = {ring_0 r}) /\
        ?a b. a IN ring_carrier r /\ b IN ring_carrier r /\
              ~(a = ring_0 r) /\ ~(b = ring_0 r) /\
              ideal_prod r (ideal_generated r {a}) j =
              ideal_prod r (ideal_generated r {b}) k`,
  REWRITE_TAC[ideal_class; IN_ELIM_THM]);;

let IDEAL_CLASS_REFL = prove
 (`!r:A ring j.
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> j IN ideal_class r j`,
  REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[IN_IDEAL_CLASS] THEN
  SUBGOAL_THEN `?a:A. a IN j /\ ~(a = ring_0 r)` STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; SET_RULE
     `(z:A) IN s /\ ~(s = {z}) ==> ?a. a IN s /\ ~(a = z)`];
    MAP_EVERY EXISTS_TAC [`a:A`; `a:A`] THEN
    ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]]);;

let IDEAL_CLASS_SYM = prove
 (`!r:A ring j k.
        k IN ideal_class r j ==> j IN ideal_class r k`,
  REWRITE_TAC[IN_IDEAL_CLASS] THEN MESON_TAC[]);;

let IDEAL_CLASS_TRANS = prove
 (`!r:A ring j k l.
        integral_domain r /\
        k IN ideal_class r j /\ l IN ideal_class r k
        ==> l IN ideal_class r j`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IN_IDEAL_CLASS] THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[] THEN
  MAP_EVERY EXISTS_TAC [`ring_mul r a' a:A`; `ring_mul r b b':A`] THEN
  ASM_SIMP_TAC[RING_MUL; INTEGRAL_DOMAIN_MUL_EQ_0;
               GSYM IDEAL_PROD_PRINCIPAL] THEN
  FIRST_X_ASSUM(MP_TAC o AP_TERM `ideal_prod r (ideal_generated r {b:A})`) THEN
  FIRST_X_ASSUM(MP_TAC o AP_TERM `ideal_prod r (ideal_generated r {a':A})`) THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD;
               RING_IDEAL_IDEAL_GENERATED]);;

let IDEAL_CLASS_MUL = prove
 (`!r:A ring j1 j2 k1 k2.
        integral_domain r /\
        k1 IN ideal_class r j1 /\ k2 IN ideal_class r j2
        ==> ideal_prod r k1 k2 IN ideal_class r (ideal_prod r j1 j2)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IN_IDEAL_CLASS] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_PROD; IDEAL_PROD_EQ_ZERO] THEN
  MAP_EVERY EXISTS_TAC [`ring_mul r a a':A`; `ring_mul r b b':A`] THEN
  ASM_SIMP_TAC[RING_MUL; INTEGRAL_DOMAIN_MUL_EQ_0;
               GSYM IDEAL_PROD_PRINCIPAL] THEN
  SUBGOAL_THEN
   `ideal_prod r (ideal_prod r (ideal_generated r {a}) j1)
                 (ideal_prod r (ideal_generated r {a'}) j2) =
    ideal_prod r (ideal_prod r (ideal_generated r {b:A}) k1)
                 (ideal_prod r (ideal_generated r {b'}) k2)`
  MP_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD;
               RING_IDEAL_IDEAL_GENERATED]);;

let IN_IDEAL_CLASS_ISOMORPHIC_IMAGE = prove
 (`!r s (h:A->B) j k.
        ring_isomorphism(r,s) h /\ k IN ideal_class r j
        ==> IMAGE h k IN ideal_class s (IMAGE h j)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IN_IDEAL_CLASS] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_ISOMORPHISM_IMP_EPIMORPHISM) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_ISOMORPHISM_IMP_MONOMORPHISM) THEN
  SUBGOAL_THEN
   `!i. ring_ideal r i
        ==> ring_ideal s (IMAGE (h:A->B) i) /\
            (IMAGE h i = {ring_0 s} <=> i = {ring_0 r})`
  (fun th -> ASM_SIMP_TAC[th]) THENL
   [X_GEN_TAC `i:A->bool` THEN DISCH_TAC THEN
    SUBGOAL_THEN `ring_ideal s (IMAGE (h:A->B) i)` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_EPIMORPHIC_IMAGE]; ASM_REWRITE_TAC[]] THEN
    MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `h:A->B`; `i:A->bool`]
      IDEAL_GENERATED_MONOMORPHIC_IMAGE_EQ_0) THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_RING_IDEAL];
    MAP_EVERY EXISTS_TAC [`(h:A->B) a`; `(h:A->B) b`]] THEN
  REWRITE_TAC[CONJ_ASSOC] THEN CONJ_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER; RING_MONOMORPHISM_EQ_0;
                  RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!c i. c IN ring_carrier r /\ ring_ideal r i
          ==> ideal_prod s (ideal_generated s {(h:A->B) c}) (IMAGE h i) =
              IMAGE h (ideal_prod r (ideal_generated r {c}) i)`
   (fun th -> ASM_SIMP_TAC[th]) THEN
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `h:A->B`; `{c:A}`]
    IDEAL_GENERATED_BY_EPIMORPHIC_IMAGE) THEN
  ASM_REWRITE_TAC[SING_SUBSET; IMAGE_CLAUSES] THEN DISCH_THEN SUBST1_TAC THEN
  CONV_TAC SYM_CONV THEN MATCH_MP_TAC IDEAL_PROD_EPIMORPHIC_IMAGE THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; IDEAL_GENERATED_SUBSET]);;

let IDEAL_CLASS_PRINCIPAL = prove
 (`!r:A ring j.
        integral_domain r /\
        ring_carrier r IN ideal_class r j
        ==> principal_ideal r j`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IN_IDEAL_CLASS] THEN STRIP_TAC THEN
  UNDISCH_TAC
   `ideal_prod r (ideal_generated r {a:A}) j =
    ideal_prod r (ideal_generated r {b}) (ring_carrier r)` THEN
  SIMP_TAC[IDEAL_PROD_CARRIER; RING_IDEAL_IDEAL_GENERATED] THEN
  ASM_SIMP_TAC[IDEAL_PROD_SCALE] THEN DISCH_TAC THEN
  SUBGOAL_THEN `(b:A) IN IMAGE (ring_mul r a) j` MP_TAC THENL
   [ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]; REWRITE_TAC[IN_IMAGE]] THEN
  DISCH_THEN(X_CHOOSE_THEN `y:A`
   (CONJUNCTS_THEN2 SUBST_ALL_TAC ASSUME_TAC)) THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  REWRITE_TAC[principal_ideal] THEN EXISTS_TAC `y:A` THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `ideal_generated r {y:A}`; `j:A->bool`]
    IDEAL_PROD_PRINCIPAL_CANCEL) THEN
  ASM_SIMP_TAC[IDEAL_PROD_PRINCIPAL; RING_IDEAL_IDEAL_GENERATED] THEN
  ASM_SIMP_TAC[IDEAL_PROD_SCALE]);;

let PRINCIPAL_IDEAL_CLASS = prove
 (`!r:A ring j.
        ~(j = {ring_0 r}) /\ principal_ideal r j
        ==> ring_carrier r IN ideal_class r j`,
  REPEAT GEN_TAC THEN REWRITE_TAC[principal_ideal] THEN
  STRIP_TAC THEN FIRST_X_ASSUM(SUBST_ALL_TAC o SYM) THEN
  SUBGOAL_THEN `~(a = ring_0 r:A) /\ ~(ring_1 r = ring_0 r:A)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL [ASM_MESON_TAC[IDEAL_GENERATED_0]; ALL_TAC] THEN
    DISCH_TAC THEN UNDISCH_TAC `~(ideal_generated r {a:A} = {ring_0 r})` THEN
    REWRITE_TAC[IDEAL_GENERATED_EQ_0] THEN
    ASM_MESON_TAC[TRIVIAL_RING_10; trivial_ring; IN_SING];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[IN_IDEAL_CLASS; RING_IDEAL_CARRIER; GSYM trivial_ring;
                  RING_IDEAL_IDEAL_GENERATED; TRIVIAL_RING_10] THEN
  MAP_EVERY EXISTS_TAC [`ring_1 r:A`; `a:A`] THEN
  ASM_SIMP_TAC[RING_1; IDEAL_PROD_PRINCIPAL; IDEAL_PROD_CARRIER;
               RING_IDEAL_IDEAL_GENERATED; RING_MUL_LID]);;

let DEDEKIND_IDEAL_CLASS_INVERSE = prove
 (`!r:A ring j.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?k. ring_ideal r k /\ ~(k = {ring_0 r}) /\
                ring_carrier r IN ideal_class r (ideal_prod r j k)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC MONO_EXISTS THEN
  X_GEN_TAC `k:A->bool` THEN
  DISCH_THEN(X_CHOOSE_THEN `a:A` STRIP_ASSUME_TAC) THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC PRINCIPAL_IDEAL_CLASS THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_EQ_0; PRINCIPAL_IDEAL_IDEAL_GENERATED_SING]);;

let DEDEKIND_PID_IFF_TRIVIAL_CLASS_GROUP = prove
 (`!r:A ring.
        dedekind_domain r
        ==> (PID r <=>
             !j. ring_ideal r j /\ ~(j = {ring_0 r}) /\ ~(j = ring_carrier r)
                 ==> ring_carrier r IN ideal_class r j)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  ASM_REWRITE_TAC[PID] THEN EQ_TAC THEN DISCH_TAC THEN
  X_GEN_TAC `j:A->bool` THEN STRIP_TAC THENL
   [MATCH_MP_TAC PRINCIPAL_IDEAL_CLASS THEN ASM_SIMP_TAC[];
    ASM_CASES_TAC `j = {ring_0 r:A}` THEN
    ASM_REWRITE_TAC[PRINCIPAL_IDEAL_0] THEN
    ASM_CASES_TAC `j:A->bool = ring_carrier r` THEN
    ASM_REWRITE_TAC[PRINCIPAL_IDEAL_CARRIER] THEN
    MATCH_MP_TAC IDEAL_CLASS_PRINCIPAL THEN ASM_SIMP_TAC[]]);;

let DEDEKIND_IDEAL_CLASS_COPRIME = prove
 (`!r i j:A->bool.
        dedekind_domain r /\ ring_ideal r i /\ ~(i = {ring_0 r}) /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?k. k IN ideal_class r i /\ ring_setadd r k j = ring_carrier r`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  MP_TAC(ISPECL [`r:A ring`; `i:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`i':A->bool`; `b:A`] THEN STRIP_TAC THEN
  ABBREV_TAC
   `s = {P | prime_ideal r P /\ ~(P = {ring_0 r}) /\
             (j SUBSET P \/ (i':A->bool) SUBSET P)}` THEN
  SUBGOAL_THEN `FINITE(s:(A->bool)->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "s" THEN
    SUBGOAL_THEN
     `{P | prime_ideal r P /\ ~(P = {ring_0 r}) /\
           (j SUBSET P \/ (i':A->bool) SUBSET P)} =
      {P | prime_ideal r P /\ ~(P = {ring_0 r}) /\ j SUBSET P} UNION
      {P | prime_ideal r P /\ ~(P = {ring_0 r}) /\ i' SUBSET P}`
    SUBST1_TAC THENL
     [REWRITE_TAC[EXTENSION; IN_UNION; IN_ELIM_THM] THEN MESON_TAC[];
      ASM_SIMP_TAC[FINITE_UNION; DEDEKIND_IDEAL_FACTORIZATION]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `s:(A->bool)->bool`;
                 `\P. ideal_valuation r P (i':A->bool)`]
    DEDEKIND_WEAK_APPROXIMATION) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN EXPAND_TAC "s" THEN SIMP_TAC[IN_ELIM_THM];
    REWRITE_TAC[LEFT_IMP_EXISTS_THM]] THEN
  X_GEN_TAC `a:A` THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(ideal_generated r {a:A} = {ring_0 r})` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[IDEAL_GENERATED_EQ_0]; ALL_TAC] THEN
  SUBGOAL_THEN `ideal_generated r {a:A} SUBSET i'` MP_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_IDEAL_SUBSET_VALUATION;
                 RING_IDEAL_IDEAL_GENERATED] THEN
    X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    ASM_CASES_TAC `(P:A->bool) IN s` THEN ASM_SIMP_TAC[LE_REFL] THEN
    MATCH_MP_TAC(ARITH_RULE `n = 0 ==> n <= m`) THEN
    ASM_SIMP_TAC[IDEAL_VALUATION_EQ_0] THEN
    UNDISCH_TAC `~((P:A->bool) IN s)` THEN EXPAND_TAC "s" THEN
    ASM_REWRITE_TAC[IN_ELIM_THM] THEN MESON_TAC[];
    ASM_SIMP_TAC[DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES;
                 RING_IDEAL_IDEAL_GENERATED; LEFT_IMP_EXISTS_THM]] THEN
  X_GEN_TAC `k:A->bool` THEN STRIP_TAC THEN EXISTS_TAC `k:A->bool` THEN
  SUBGOAL_THEN `~(k = {ring_0 r:A})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `~(ideal_generated r {a:A} = {ring_0 r})` THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      rand(concl th) = `ideal_generated r {a:A}`)) THEN
    ASM_SIMP_TAC[IDEAL_PROD_RZERO; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  CONJ_TAC THENL
   [ASM_REWRITE_TAC[IN_IDEAL_CLASS] THEN
    MAP_EVERY EXISTS_TAC [`a:A`; `b:A`] THEN ASM_REWRITE_TAC[] THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      rand(concl th) = `ideal_generated r {a:A}`)) THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      rand(concl th) = `ideal_generated r {b:A}`)) THEN
    ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD;
                 RING_IDEAL_IDEAL_GENERATED];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `ring_setadd r k (j:A->bool)`]
    MAXIMAL_SUPERIDEAL_EXISTS) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[proper_ideal; RING_IDEAL_SETADD; PSUBSET] THEN
    ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; RING_IDEAL_SETADD];
    DISCH_THEN(X_CHOOSE_THEN `P:A->bool` STRIP_ASSUME_TAC)] THEN
  SUBGOAL_THEN `prime_ideal r (P:A->bool) /\ ~(P = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `~(j = {ring_0 r:A})` THEN REWRITE_TAC[] THEN
    MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
     [ASM_MESON_TAC[RING_SETADD_SUPERSET_RIGHT; SUBSET_TRANS;
                    RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0];
      ASM_MESON_TAC[IN_RING_IDEAL_0; SING_SUBSET]];
    ALL_TAC] THEN
  SUBGOAL_THEN `(P:A->bool) IN s` ASSUME_TAC THENL
   [EXPAND_TAC "s" THEN ASM_REWRITE_TAC[IN_ELIM_THM] THEN DISJ1_TAC THEN
    ASM_MESON_TAC[RING_SETADD_SUPERSET_RIGHT; SUBSET_TRANS;
                  RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0];
