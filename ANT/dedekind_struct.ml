(* Approximation and two generators.                                         *)
(* ------------------------------------------------------------------------- *)

(* Route: pick x_p IN p^(n p) DIFF p^(n p + 1) and solve x == x_p modulo     *)
(* the pairwise comaximal ideals p^(n p + 1) (CHINESE_REMAINDER_IDEALS).     *)

let DEDEKIND_WEAK_APPROXIMATION = prove
 (`!r s (n:(A->bool)->num).
        dedekind_domain r /\ FINITE s /\
        (!p. p IN s ==> prime_ideal r p /\ ~(p = {ring_0 r}))
        ==> ?a. a IN ring_carrier r /\ ~(a = ring_0 r) /\
                !p. p IN s
                    ==> ideal_valuation r p (ideal_generated r {a}) = n p`,
  let lemma = prove
   (`!r i k u y:A.
        ring_ideal r i /\ ring_ideal r k /\ k SUBSET i /\
        u IN i /\ ~(u IN k) /\ y IN ring_carrier r /\ ring_sub r y u IN k
        ==> y IN i /\ ~(y IN k)`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    SUBGOAL_THEN `(u:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; CONJ_TAC] THENL
     [SUBGOAL_THEN `y = ring_add r (ring_sub r y u) (u:A)` SUBST1_TAC THENL
       [ASM_SIMP_TAC[RING_RULE `ring_add r (ring_sub r y u) u = (y:A)`];
        ASM_MESON_TAC[IN_RING_IDEAL_ADD; SUBSET]];
      DISCH_TAC THEN UNDISCH_TAC `~((u:A) IN k)` THEN REWRITE_TAC[] THEN
      SUBGOAL_THEN `u = ring_sub r y (ring_sub r y u:A)` SUBST1_TAC THENL
       [ASM_SIMP_TAC[RING_RULE `ring_sub r y (ring_sub r y u) = (u:A)`];
        ASM_SIMP_TAC[IN_RING_IDEAL_SUB]]]) in
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `s:(A->bool)->bool = {}` THENL
   [EXISTS_TAC `ring_1 r:A` THEN
    ASM_MESON_TAC[NOT_IN_EMPTY; RING_1; DEDEKIND_IMP_INTEGRAL_DOMAIN;
                  integral_domain];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!p:A->bool. p IN s
                ==> ring_ideal r p /\ ~(p = ring_carrier r) /\
                    maximal_ideal r p`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL; PROPER_IDEAL_ALT;
                  DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!p. ?x:A. p IN s
              ==> x IN ideal_pow r p (n p) /\
                  ~(x IN ideal_pow r p (SUC(n p)))`
  MP_TAC THENL
   [X_GEN_TAC `p:A->bool` THEN REWRITE_TAC[RIGHT_EXISTS_IMP_THM] THEN
    DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `(n:(A->bool)->num) p`;
                   `SUC((n:(A->bool)->num) p)`] DEDEKIND_IDEAL_POW_SUBSET) THEN
    ASM_SIMP_TAC[ARITH_RULE `~(SUC n <= n)`] THEN SET_TAC[];
    REWRITE_TAC[SKOLEM_THM; LEFT_IMP_EXISTS_THM]] THEN
  X_GEN_TAC `x:(A->bool)->A` THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `s:(A->bool)->bool`;
                 `\p:A->bool. ideal_pow r p (SUC(n p))`;
                 `x:(A->bool)->A`] CHINESE_REMAINDER_IDEALS) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW] THEN ANTS_TAC THENL
   [CONJ_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_POW; SUBSET];
      REWRITE_TAC[pairwise]] THEN
    MAP_EVERY X_GEN_TAC [`p:A->bool`; `q:A->bool`] THEN STRIP_TAC THEN
    MATCH_MP_TAC COMAXIMAL_IDEAL_POW THEN
    ASM_SIMP_TAC[MAXIMAL_IDEAL_COMAXIMAL] THEN
    ASM_MESON_TAC[DEDEKIND_KRULL_DIMENSION_ONE];
    DISCH_THEN(X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC)] THEN
  SUBGOAL_THEN
   `!p:A->bool. p IN s
                ==> y IN ideal_pow r p (n p) /\
                    ~(y IN ideal_pow r p (SUC(n p)))`
  ASSUME_TAC THENL
   [X_GEN_TAC `p:A->bool` THEN DISCH_TAC THEN
    MATCH_MP_TAC(ISPEC `r:A ring` lemma) THEN
    EXISTS_TAC `(x:(A->bool)->A) p` THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; IDEAL_POW_ANTIMONO;
                 RING_IDEAL_IMP_SUBSET; ARITH_RULE `n <= SUC n`];
    ALL_TAC] THEN
  EXISTS_TAC `y:A` THEN ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [GSYM MEMBER_NOT_EMPTY]) THEN
    ASM_MESON_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_POW];
    X_GEN_TAC `p:A->bool` THEN DISCH_TAC THEN
    MATCH_MP_TAC IDEAL_VALUATION_UNIQUE THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL_EQ; RING_IDEAL_IDEAL_POW; SET_RULE
     `(y:A) IN s ==> (s INTER {y} SUBSET u <=> y IN u)`]]);;

(* A nonzero ideal J of a Dedekind domain has nonzero elements x with        *)
(* v_P(x) = v_P(J) at finitely many given nonzero primes P (prescribe the    *)
(* valuations of J also at its own primes, DEDEKIND_WEAK_APPROXIMATION).     *)
let DEDEKIND_IDEAL_WEAK_APPROXIMATION = prove
 (`!r s (J:A->bool).
        dedekind_domain r /\ FINITE s /\
        (!P. P IN s ==> prime_ideal r P /\ ~(P = {ring_0 r})) /\
        ring_ideal r J /\ ~(J = {ring_0 r})
        ==> ?x. x IN J /\ ~(x = ring_0 r) /\
                !P. P IN s
                    ==> ideal_valuation r P (ideal_generated r {x}) =
                        ideal_valuation r P J`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`;
                 `s UNION {P | prime_ideal r P /\ ~(P = {ring_0 r}) /\
                               ~(ideal_valuation r P (J:A->bool) = 0)}`;
                 `\P. ideal_valuation r P (J:A->bool)`]
    DEDEKIND_WEAK_APPROXIMATION) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[FINITE_UNION; IDEAL_VALUATION_FINITE_SUPPORT] THEN
    REWRITE_TAC[IN_UNION; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `a:A` THEN
  REWRITE_TAC[IN_UNION; IN_ELIM_THM] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[] THEN
  SUBGOAL_THEN `ideal_generated r {a:A} SUBSET J` MP_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`; `J:A->bool`]
      DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0] THEN
    DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
    ASM_CASES_TAC `ideal_valuation r P (J:A->bool) = 0` THEN
    ASM_SIMP_TAC[LE_0; LE_REFL];
    REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]]);;

(* Route: approximate v_p(j) at the finitely many primes p above (a) by an  *)
(* element b; the valuations then give (b) SUBSET j and j SUBSET (a) + (b). *)

let DEDEKIND_TWO_GENERATORS_STRONG = prove
 (`!r j (a:A).
        dedekind_domain r /\ ring_ideal r j /\ a IN j /\ ~(a = ring_0 r)
        ==> ?b. b IN j /\ ideal_generated r {a,b} = j`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r /\ ~(j = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET; IN_SING]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!x:A. x IN ring_carrier r /\ ~(x = ring_0 r)
          ==> ring_ideal r (ideal_generated r {x}) /\
              ~(ideal_generated r {x} = {ring_0 r})`
  ASSUME_TAC THENL
   [SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!p. prime_ideal r p /\ ~(p = {ring_0 r}) /\
        ~(ideal_generated r {a:A} SUBSET p)
        ==> ideal_valuation r p (ideal_generated r {a}) = 0 /\
            ideal_valuation r p j = 0`
  ASSUME_TAC THENL
   [REPEAT GEN_TAC THEN STRIP_TAC THEN
    MATCH_MP_TAC(ARITH_RULE `y <= x /\ x = 0 ==> x = 0 /\ y = 0`) THEN
    ASM_SIMP_TAC[IDEAL_VALUATION_EQ_0] THEN
    MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`; `j:A->bool`]
      DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL; SING_SUBSET] THEN
    DISCH_THEN(MP_TAC o SPEC `p:A->bool`) THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`]
    DEDEKIND_IDEAL_FACTORIZATION) THEN
  ASM_SIMP_TAC[] THEN DISCH_THEN(MP_TAC o CONJUNCT1) THEN
  ABBREV_TAC `s = {p | prime_ideal r p /\ ~(p = {ring_0 r}) /\
                       ideal_generated r {a:A} SUBSET p}` THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `!p. prime_ideal r p /\ ~(p = {ring_0 r}) /\ ~(p IN s)
        ==> ~(ideal_generated r {a:A} SUBSET p)`
  ASSUME_TAC THENL
   [EXPAND_TAC "s" THEN REWRITE_TAC[IN_ELIM_THM] THEN MESON_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `s:(A->bool)->bool`;
                 `\p:A->bool. ideal_valuation r p j`]
    DEDEKIND_WEAK_APPROXIMATION) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN EXPAND_TAC "s" THEN SIMP_TAC[IN_ELIM_THM];
    DISCH_THEN(X_CHOOSE_THEN `b:A` STRIP_ASSUME_TAC o BETA_RULE)] THEN
  SUBGOAL_THEN `ideal_generated r {b:A} SUBSET j` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {b:A}`; `j:A->bool`]
      DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
    ANTS_TAC THENL [ASM_SIMP_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
    ASM_CASES_TAC `(p:A->bool) IN s` THEN ASM_SIMP_TAC[LE_REFL; LE_0];
    ALL_TAC] THEN
  SUBGOAL_THEN `(b:A) IN j` ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_IDEAL_GENERATED_SELF; SUBSET]; ALL_TAC] THEN
  EXISTS_TAC `b:A` THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL; INSERT_SUBSET; EMPTY_SUBSET] THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `ideal_generated r {a:A,b}`]
    DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    ASM_MESON_TAC[IDEAL_GENERATED_INC_GEN; IN_INSERT; IN_SING];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[SET_RULE `{a:A,b} = {a} UNION {b}`; IDEAL_GENERATED_UNION] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_SETADD] THEN
  ASM_CASES_TAC `(p:A->bool) IN s` THEN ASM_SIMP_TAC[] THEN ARITH_TAC);;

let DEDEKIND_TWO_GENERATORS = prove
 (`!r (j:A->bool).
    dedekind_domain r /\ ring_ideal r j
    ==> ?a b. a IN ring_carrier r /\ b IN ring_carrier r /\
              ideal_generated r {a, b} = j`,
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `j = {ring_0 r:A}` THENL
   [MAP_EVERY EXISTS_TAC [`ring_0 r:A`; `ring_0 r:A`] THEN
    ASM_REWRITE_TAC[RING_0; INSERT_INSERT; IDEAL_GENERATED_0];
    ALL_TAC] THEN
  SUBGOAL_THEN `?a:A. a IN j /\ ~(a = ring_0 r)` STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; SET_RULE
     `(z:A) IN s /\ ~(s = {z}) ==> ?a. a IN s /\ ~(a = z)`];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `a:A`]
    DEDEKIND_TWO_GENERATORS_STRONG) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `b:A` STRIP_ASSUME_TAC) THEN
  MAP_EVERY EXISTS_TAC [`a:A`; `b:A`] THEN
  ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]);;

(* ------------------------------------------------------------------------- *)
(* Quotient rings; UFDs and Bezout domains.                                  *)
(* ------------------------------------------------------------------------- *)

(* An ideal of R/j comes from an ideal i containing j; with a nonzero a IN j *)
(* write i = (a,b); the coset of a is zero, so the image is generated by the *)
(* coset of b.                                                               *)

let DEDEKIND_QUOTIENT_PRINCIPAL = prove
 (`!r (j:A->bool).
    dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
    ==> !k. ring_ideal (quotient_ring r j) k
            ==> principal_ideal (quotient_ring r j) k`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_SIMP_TAC[QUOTIENT_RING_IDEAL_CORRESPONDENCE; LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `k:(A->bool)->bool` THEN X_GEN_TAC `i:A->bool` THEN
  STRIP_TAC THEN FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  SUBGOAL_THEN `?a:A. a IN j /\ ~(a = ring_0 r)` STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; SET_RULE
     `(z:A) IN s /\ ~(s = {z}) ==> ?a. a IN s /\ ~(a = z)`];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `i:A->bool`; `a:A`]
    DEDEKIND_TWO_GENERATORS_STRONG) THEN
  ANTS_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `b:A` (CONJUNCTS_THEN2 ASSUME_TAC
   (SUBST1_TAC o SYM))) THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r /\ b IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `quotient_ring r (j:A->bool)`;
                 `ring_coset r (j:A->bool)`; `{a:A,b}`]
    IDEAL_GENERATED_BY_EPIMORPHIC_IMAGE) THEN
  ASM_SIMP_TAC[RING_EPIMORPHISM_RING_COSET; INSERT_SUBSET; EMPTY_SUBSET] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN REWRITE_TAC[IMAGE_CLAUSES] THEN
  SUBGOAL_THEN `ring_coset r j (a:A) = ring_0(quotient_ring r j)`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[QUOTIENT_RING_0; RING_COSET_EQ_IDEAL]; ALL_TAC] THEN
  REWRITE_TAC[IDEAL_GENERATED_INSERT_ZERO;
              PRINCIPAL_IDEAL_IDEAL_GENERATED_SING]);;

(* A maximal ideal of R/p^n comes from a maximal ideal containing p^n, so    *)
(* containing p, so equal to p.                                              *)

let DEDEKIND_LOCAL_QUOTIENT_PRIME_POW = prove
 (`!r p:A->bool n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        ~(n = 0)
        ==> local_ring (quotient_ring r (ideal_pow r p n))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN
   `ring_ideal r (ideal_pow r p n) /\ ideal_pow r (p:A->bool) n SUBSET p`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; IDEAL_POW_SUBSET_PRIME_IDEAL;
                 RING_IDEAL_IMP_SUBSET; SUBSET_REFL];
    ALL_TAC] THEN
  REWRITE_TAC[local_ring; EXISTS_UNIQUE_THM] THEN CONJ_TAC THENL
   [ASM_SIMP_TAC[MAXIMAL_IDEAL_EXISTS; TRIVIAL_QUOTIENT_RING; PROPER_IDEAL] THEN
    ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL; PROPER_IDEAL; SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!m. maximal_ideal (quotient_ring r (ideal_pow r p n)) m
        ==> m = IMAGE (ring_coset r (ideal_pow r p n)) (p:A->bool)`
  (fun th -> MESON_TAC[th]) THEN
  X_GEN_TAC `m:(A->bool)->bool` THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_pow r (p:A->bool) n`; `m:(A->bool)->bool`]
    QUOTIENT_RING_IDEAL_CORRESPONDENCE) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_RING_IDEAL; LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `i:A->bool` THEN STRIP_TAC THEN
  SUBGOAL_THEN `maximal_ideal r (i:A->bool)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `quotient_ring r (ideal_pow r (p:A->bool) n)`;
                   `ring_coset r (ideal_pow r (p:A->bool) n)`;
                   `i:A->bool`; `m:(A->bool)->bool`]
      MAXIMAL_IDEAL_CORRESPONDENCE) THEN
    ASM_SIMP_TAC[RING_EPIMORPHISM_RING_COSET; MAXIMAL_IMP_RING_IDEAL];
    ALL_TAC] THEN
  SUBGOAL_THEN `(p:A->bool) SUBSET i` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `i:A->bool`; `p:A->bool`; `n:num`]
      IDEAL_POW_SUBSET_PRIME_IDEAL) THEN
    ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN `maximal_ideal r (p:A->bool)` MP_TAC THENL
   [ASM_MESON_TAC[DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL]; ALL_TAC] THEN
  REWRITE_TAC[maximal_ideal; NOT_EXISTS_THM] THEN
  DISCH_THEN(MP_TAC o SPEC `i:A->bool` o CONJUNCT2) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PROPER_IDEAL; PSUBSET] THEN
  DISCH_THEN(SUBST_ALL_TAC o SYM) THEN ASM_REWRITE_TAC[]);;

let DEDEKIND_UFD_IFF_PID = prove
 (`!r:A ring. dedekind_domain r ==> (UFD r <=> PID r)`,
  SIMP_TAC[dedekind_domain; PID_EQ_UFD_PRIME_MAXIMAL]);;

let DEDEKIND_BEZOUT_IFF_PID = prove
 (`!r:A ring. dedekind_domain r ==> (bezout_ring r <=> PID r)`,
  SIMP_TAC[dedekind_domain; PID_EQ_NOETHERIAN_BEZOUT_DOMAIN]);;

