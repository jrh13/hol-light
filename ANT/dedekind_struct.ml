(* ========================================================================= *)
(* Further structure of Dedekind domains.                                    *)
(*                                                                           *)
(* Definitions: DVR (discrete valuation ring), ideal_class (the class of a   *)
(* nonzero ideal j: the nonzero ideals k with (a) j = (b) k for nonzero a,   *)
(* b).                                                                       *)
(*                                                                           *)
(* Main results: a DVR is a local Dedekind domain that is not a field, and   *)
(* its nonzero ideals are the powers of the maximal ideal                    *)
(* (DVR_IFF_LOCAL_DEDEKIND, DVR_IDEAL_MAXIMAL_POW); weak approximation       *)
(* (DEDEKIND_WEAK_APPROXIMATION; a nonzero ideal has nonzero elements with   *)
(* its valuations at finitely many given primes,                             *)
(* DEDEKIND_IDEAL_WEAK_APPROXIMATION); every ideal is generated by any of    *)
(* its nonzero elements together with one more element                       *)
(* (DEDEKIND_TWO_GENERATORS_STRONG); proper quotients are principal ideal    *)
(* rings and R/p^n is local; a Dedekind domain is a UFD, or a Bezout domain, *)
(* iff it is a PID; the relation k IN ideal_class r j is an equivalence      *)
(* compatible with products and with ring isomorphisms (IN_IDEAL_CLASS,      *)
(* IN_IDEAL_CLASS_ISOMORPHIC_IMAGE), classes have inverses, and PID means    *)
(* trivial class group (DEDEKIND_PID_IFF_TRIVIAL_CLASS_GROUP). Auxiliary     *)
(* fact: DEDEKIND_LOCAL_IDEAL_MAXIMAL_POW. Every ideal class contains an     *)
(* ideal prime to a given nonzero ideal (DEDEKIND_IDEAL_CLASS_COPRIME).      *)
(* Fractional ideals and their group are in ANT/fractional_ideals.ml.        *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, ANT/ideal_arith.ml, ANT/dedekind.ml          *)
(* (valuations, factorization, principal multiples).                         *)
(* ========================================================================= *)

needs "Library/ringtheory.ml";;
needs "ANT/ideal_arith.ml";;
needs "ANT/dedekind.ml";;

(* ------------------------------------------------------------------------- *)
(* Discrete valuation rings.                                                 *)
(* ------------------------------------------------------------------------- *)

let DVR = new_definition
 `DVR (r:A ring) <=> PID r /\ local_ring r /\ ~(field r)`;;

let DVR_IMP_DEDEKIND = prove
 (`!r:A ring. DVR r ==> dedekind_domain r`,
  SIMP_TAC[DVR; PID_IMP_DEDEKIND]);;

(* In a local Dedekind domain every nonzero ideal is a power of the maximal  *)
(* ideal (for a field: the unit ideal, the zeroth power of {0}).             *)

let DEDEKIND_LOCAL_IDEAL_MAXIMAL_POW = prove
 (`!r m j:A->bool.
        dedekind_domain r /\ local_ring r /\ maximal_ideal r m /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?n. j = ideal_pow r m n`,
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `m = {ring_0 r:A}` THENL
   [EXISTS_TAC `0` THEN REWRITE_TAC[IDEAL_POW_0] THEN
    ASM_MESON_TAC[MAXIMAL_IDEAL_0; FIELD_EQ_TRIVIAL_IDEALS];
    EXISTS_TAC `ideal_valuation r m (j:A->bool)`] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_PRIME_IDEAL) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`;
                 `ideal_pow r m (ideal_valuation r m (j:A->bool))`]
         DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; IDEAL_POW_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  SUBGOAL_THEN `p:A->bool = m` SUBST1_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [local_ring]) THEN
    REWRITE_TAC[EXISTS_UNIQUE_DEF] THEN
    ASM_MESON_TAC[DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL];
    ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_POW; IDEAL_VALUATION_PRIME] THEN
    ARITH_TAC]);;

let DVR_IFF_LOCAL_DEDEKIND = prove
 (`!r:A ring. DVR r <=> dedekind_domain r /\ local_ring r /\ ~(field r)`,
  GEN_TAC THEN EQ_TAC THENL [SIMP_TAC[DVR; PID_IMP_DEDEKIND]; STRIP_TAC] THEN
  ASM_SIMP_TAC[DVR; PID; DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  FIRST_ASSUM(MP_TAC o GEN_REWRITE_RULE I [local_ring]) THEN
  REWRITE_TAC[EXISTS_UNIQUE_DEF] THEN
  DISCH_THEN(X_CHOOSE_TAC `m:A->bool` o CONJUNCT1) THEN
  SUBGOAL_THEN `ring_ideal r (m:A->bool) /\ ~(m = {ring_0 r}) /\
                ~(m = ring_carrier r)` STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[MAXIMAL_IDEAL_0; MAXIMAL_IMP_PROPER_IDEAL; PROPER_IDEAL_ALT];
    ALL_TAC] THEN
  (* A uniformizer: t IN m, t NOTIN m^2, generates m. *)
  SUBGOAL_THEN `?t:A. t IN m /\ ~(t IN ideal_pow r m 2)` STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `1`; `2`]
      DEDEKIND_IDEAL_POW_SUBSET) THEN
    ASM_SIMP_TAC[IDEAL_POW_1] THEN CONV_TAC NUM_REDUCE_CONV THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `ideal_generated r {t:A} = m` ASSUME_TAC THENL
   [SUBGOAL_THEN
     `ideal_generated r {t:A} SUBSET m /\
      ~(ideal_generated r {t} SUBSET ideal_pow r m 2) /\
      ~(ideal_generated r {t} = {ring_0 r})`
    STRIP_ASSUME_TAC THENL
     [ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL_EQ; RING_IDEAL_IDEAL_POW;
                   IDEAL_GENERATED_EQ_0; SET_RULE
       `(t:A) IN s ==> (s INTER {t} SUBSET u <=> t IN u)`] THEN
      DISCH_THEN SUBST_ALL_TAC THEN
      UNDISCH_TAC `~(ring_0 r IN ideal_pow r (m:A->bool) 2)` THEN
      ASM_SIMP_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_POW];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `ideal_generated r {t:A}`]
      DEDEKIND_LOCAL_IDEAL_MAXIMAL_POW) THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    DISCH_THEN(X_CHOOSE_THEN `v:num` SUBST_ALL_TAC) THEN
    MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `v:num`; `1`]
      DEDEKIND_IDEAL_POW_SUBSET) THEN
    MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `v:num`; `2`]
      DEDEKIND_IDEAL_POW_SUBSET) THEN
    ASM_SIMP_TAC[IDEAL_POW_1] THEN REPEAT DISCH_TAC THEN
    SUBGOAL_THEN `v = 1` (fun th -> ASM_SIMP_TAC[th; IDEAL_POW_1]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  X_GEN_TAC `j:A->bool` THEN DISCH_TAC THEN
  ASM_CASES_TAC `j = {ring_0 r:A}` THEN ASM_REWRITE_TAC[PRINCIPAL_IDEAL_0] THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `j:A->bool`]
    DEDEKIND_LOCAL_IDEAL_MAXIMAL_POW) THEN
  ASM_REWRITE_TAC[principal_ideal] THEN
  DISCH_THEN(X_CHOOSE_THEN `n:num` SUBST1_TAC) THEN
  EXISTS_TAC `ring_pow r (t:A) n` THEN
  FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[RING_POW; IDEAL_POW_PRINCIPAL]);;

let DVR_IDEAL_MAXIMAL_POW = prove
 (`!r m j:A->bool.
        DVR r /\ maximal_ideal r m /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?n. j = ideal_pow r m n`,
  REWRITE_TAC[DVR_IFF_LOCAL_DEDEKIND] THEN
  MESON_TAC[DEDEKIND_LOCAL_IDEAL_MAXIMAL_POW]);;

let DVR_IDEALS_TOTALLY_ORDERED = prove
 (`!r j k:A->bool.
        DVR r /\ ring_ideal r j /\ ring_ideal r k
        ==> j SUBSET k \/ k SUBSET j`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `j = {ring_0 r:A}` THENL
   [ASM_SIMP_TAC[SING_SUBSET; IN_RING_IDEAL_0]; ALL_TAC] THEN
  ASM_CASES_TAC `k = {ring_0 r:A}` THENL
   [ASM_SIMP_TAC[SING_SUBSET; IN_RING_IDEAL_0]; ALL_TAC] THEN
  FIRST_ASSUM(MP_TAC o CONJUNCT1 o CONJUNCT2 o GEN_REWRITE_RULE I [DVR]) THEN
  REWRITE_TAC[local_ring; EXISTS_UNIQUE_DEF] THEN
  DISCH_THEN(X_CHOOSE_TAC `m:A->bool` o CONJUNCT1) THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `k:A->bool`]
    DVR_IDEAL_MAXIMAL_POW) THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `j:A->bool`]
    DVR_IDEAL_MAXIMAL_POW) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  X_GEN_TAC `a:num` THEN DISCH_THEN SUBST1_TAC THEN
  X_GEN_TAC `b:num` THEN DISCH_THEN SUBST1_TAC THEN
  ASM_MESON_TAC[IDEAL_POW_ANTIMONO; LE_CASES; MAXIMAL_IDEAL_IMP_SUBSET]);;

