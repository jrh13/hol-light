(* Number fields: intermediate fields, the prime below Q, the ramification   *)
(* index and residue degree of Q INTER s through D_Q and I_Q.                *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_INTERMEDIATE_FIELD = prove
 (`!(h:A->B) k l s.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
        ==> field(subfield_generated l s) /\
            ring_carrier(subfield_generated l s) = s /\
            number_field(subfield_generated l s) /\
            ring_monomorphism(k,subfield_generated l s) h /\
            ring_monomorphism(subfield_generated l s,l) I /\
            ring_homomorphism(k,subfield_generated l s) h /\
            ring_homomorphism(subfield_generated l s,l) I /\
            ring_carrier(ring_of_integers(subfield_generated l s)) =
            ring_carrier(ring_of_integers l) INTER s`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN
   `field(subfield_generated l (s:B->bool)) /\
    ring_carrier(subfield_generated l s) = s /\
    ring_homomorphism(subfield_generated l s,l) (I:B->B)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; CARRIER_SUBFIELD_GENERATED_SUBFIELD;
                 RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_monomorphism(k:A ring,l:B ring) h` ASSUME_TAC THENL
   [MATCH_MP_TAC FIELD_RING_HOMOMORPHISM_MONOMORPHISM THEN
    ASM_SIMP_TAC[FIELD_IMP_NONTRIVIAL_RING];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_monomorphism(k,subfield_generated l s) (h:A->B)`
  ASSUME_TAC THENL
   [ONCE_REWRITE_TAC[GSYM SUBRING_GENERATED_BY_SUBFIELD_GENERATED] THEN
    MATCH_MP_TAC RING_MONOMORPHISM_INTO_SUBRING THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[RING_MONOMORPHISM_IMP_HOMOMORPHISM] THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC NUMBER_FIELD_HOMOMORPHIC_PREIMAGE THEN
    MAP_EVERY EXISTS_TAC [`l:B ring`; `I:B->B`] THEN ASM_REWRITE_TAC[];
    MATCH_MP_TAC FIELD_RING_HOMOMORPHISM_MONOMORPHISM THEN
    ASM_SIMP_TAC[FIELD_IMP_NONTRIVIAL_RING];
    ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBFIELD_GENERATED]]);;

let NUMBER_FIELD_GALOIS_INTERMEDIATE = prove
 (`!(h:A->B) k l s.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s /\
        normal_extension(k,subfield_generated l s) h
        ==> galois_extension(k,subfield_generated l s) h`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_REWRITE_TAC[galois_extension] THEN
  MATCH_MP_TAC SEPARABLE_EXTENSION_CHAR0 THEN
  ASM_SIMP_TAC[NORMAL_IMP_ALGEBRAIC_EXTENSION] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ASM_SIMP_TAC[number_field]);;

let NUMBER_FIELD_PRIME_IDEAL_INTERMEDIATE = prove
 (`!(h:A->B) k l s p Q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h p SUBSET Q
        ==> Q INTER ring_carrier(ring_of_integers(subfield_generated l s)) =
            Q INTER s /\
            prime_ideal (ring_of_integers(subfield_generated l s))
                        (Q INTER s) /\
            ~(Q INTER s = {ring_0 l}) /\
            IMAGE h p SUBSET Q INTER s`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`]
    NUMBER_FIELD_INTERMEDIATE_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  SUBGOAL_THEN `(Q:B->bool) SUBSET ring_carrier(ring_of_integers l)`
  ASSUME_TAC THENL [ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET]; ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) /\ r /\ s ==> p /\ q /\ r /\ s`) THEN
  REPEAT CONJ_TAC THENL
   [ASM SET_TAC[];
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    SUBGOAL_THEN
     `Q INTER ring_carrier(ring_of_integers(subfield_generated l s)) =
      {x | x IN ring_carrier(ring_of_integers(subfield_generated l s)) /\
           (I:B->B) x IN Q}`
    SUBST1_TAC THENL [REWRITE_TAC[I_THM] THEN SET_TAC[]; ALL_TAC] THEN
    MATCH_MP_TAC PRIME_IDEAL_HOMOMORPHIC_PREIMAGE THEN
    EXISTS_TAC `ring_of_integers l:B ring` THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS];
    SUBGOAL_THEN `?a:A. a IN p /\ ~(a = ring_0 k)` STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `~(p = {ring_0(k:A ring)})` THEN
      MATCH_MP_TAC(SET_RULE
       `(z:A) IN s ==> ~(s = {z}) ==> ?a. a IN s /\ ~(a = z)`) THEN
      MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
        IN_RING_IDEAL_0) THEN
      ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; RING_OF_INTEGERS];
      ALL_TAC] THEN
    SUBGOAL_THEN `(a:A) IN ring_carrier k` ASSUME_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
        PRIME_IDEAL_IMP_SUBSET) THEN
      MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN
      ASM_REWRITE_TAC[] THEN ASM SET_TAC[];
      ALL_TAC] THEN
    DISCH_TAC THEN
    SUBGOAL_THEN `(h:A->B) a IN Q INTER s` MP_TAC THENL
     [ASM SET_TAC[]; ASM_REWRITE_TAC[IN_SING]] THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `a:A`]
      RING_MONOMORPHISM_EQ_0) THEN
    ANTS_TAC THENL [ALL_TAC; ASM_REWRITE_TAC[]] THEN
    ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC FIELD_RING_HOMOMORPHISM_MONOMORPHISM THEN
    ASM_SIMP_TAC[FIELD_IMP_NONTRIVIAL_RING; NUMBER_FIELD_IMP_FIELD];
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`]
        PRIME_IDEAL_IMP_SUBSET) THEN
    MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN
    ASM_REWRITE_TAC[] THEN ASM SET_TAC[]]);;

let NUMBER_FIELD_PRIME_IDEALS_INTERMEDIATE = prove
 (`!(h:A->B) k l s p.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> {P | prime_ideal (ring_of_integers(subfield_generated l s)) P /\
                 IMAGE h p SUBSET P} =
            {Q INTER s | Q | prime_ideal (ring_of_integers l) Q /\
                             IMAGE h p SUBSET Q}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`]
    NUMBER_FIELD_INTERMEDIATE_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ABBREV_TAC `M = subfield_generated l (s:B->bool)` THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `P:B->bool` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN EQ_TAC THENL
   [STRIP_TAC THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `M:B ring`; `p:A->bool`;
                   `P:B->bool`] NUMBER_FIELD_PRIME_IDEAL_ABOVE) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`M:B ring`; `l:B ring`; `I:B->B`; `P:B->bool`]
      NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
    ASM_REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM; IMAGE_I] THEN
    DISCH_THEN(X_CHOOSE_THEN `Q:B->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
    EXISTS_TAC `Q:B->bool` THEN ASM_REWRITE_TAC[] THEN
    CONJ_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    MP_TAC(ISPECL [`M:B ring`; `l:B ring`; `I:B->B`; `P:B->bool`;
                   `Q:B->bool`] RING_OF_INTEGERS_PRIME_IDEAL_CONTRACTION) THEN
    ASM_REWRITE_TAC[IMAGE_I; I_THM] THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `Q:B->bool`]
      PRIME_IDEAL_IMP_SUBSET) THEN
    ASM_REWRITE_TAC[] THEN SET_TAC[];
    DISCH_THEN(X_CHOOSE_THEN `Q:B->bool` STRIP_ASSUME_TAC) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`; `p:A->bool`;
                   `Q:B->bool`] NUMBER_FIELD_PRIME_IDEAL_INTERMEDIATE) THEN
    ASM_REWRITE_TAC[] THEN SIMP_TAC[]]);;

let NUMBER_FIELD_SUBFIELD_PRIME_IDEALS_ABOVE = prove
 (`!(k:A ring) s p.
        number_field k /\ prime p
        ==> {P | prime_ideal (ring_of_integers(subfield_generated k s)) P /\
                 ring_of_num (subfield_generated k s) p IN P} =
            {Q INTER ring_carrier(subfield_generated k s) | Q |
             prime_ideal (ring_of_integers k) Q /\ ring_of_num k p IN Q}`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[RING_OF_NUM_SUBFIELD_GENERATED] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `p:num`]
    RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL) THEN
  MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `p:num`]
    RING_OF_INTEGERS_PRIME_SUBFIELD_IDEAL) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED;
               RING_OF_NUM_SUBFIELD_GENERATED] THEN
  ABBREV_TAC
   `p0 = ideal_generated (ring_of_integers(subfield_generated k {ring_0 k}))
                         {ring_of_num k p:A}` THEN
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                 `ring_carrier(subfield_generated k (s:A->bool))`;
                 `p0:A->bool`] NUMBER_FIELD_PRIME_IDEALS_INTERMEDIATE) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
               SUBFIELD_SUBFIELD_GENERATED; IMAGE_I; PRIME_SUBFIELD_MINIMAL;
               SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED;
               CONJUNCT2 SUBFIELD_GENERATED] THEN
  MATCH_MP_TAC(SET_RULE
   `(!P:A->bool. A P ==> (B P <=> C P)) /\
    (!P:A->bool. A' P ==> (B' P <=> C' P))
    ==> {P | A P /\ B P} = {(g:(A->bool)->(A->bool)) P | P | A' P /\ B' P}
        ==> {P | A P /\ C P} = {g P | P | A' P /\ C' P}`) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[IMAGE_I]) THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]);;

(* Neukirch I.9.6 relative to M: |D_Q INTER Gal(l/M)| = e(Q|Q INTER s) f(Q|Q *)
(* INTER s), |I_Q INTER Gal(l/M)| = e(Q|Q INTER s), and with the tower laws  *)
(* the indices of D_Q INTER Gal(l/M) in D_Q and of I_Q INTER Gal(l/M) in I_Q *)
(* are e f and e of Q INTER s over p.                                        *)
let NUMBER_FIELD_DECOMPOSITION_GROUP_INTERMEDIATE = prove
 (`!(h:A->B) k l s p Q.
        number_field l /\ galois_extension(k,l) h /\
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h p SUBSET Q
        ==> CARD(group_carrier(decomposition_group(k,l) h Q) INTER
                 group_carrier(galois_group(subfield_generated l s,l) I)) =
            ramification_index
              (ring_of_integers(subfield_generated l s),ring_of_integers l)
              I Q *
            residue_degree
              (ring_of_integers(subfield_generated l s),ring_of_integers l)
              I Q /\
            CARD(group_carrier(inertia_group(k,l) h (ring_of_integers l) Q)
                 INTER
                 group_carrier(galois_group(subfield_generated l s,l) I)) =
            ramification_index
              (ring_of_integers(subfield_generated l s),ring_of_integers l)
              I Q /\
            CARD(group_carrier(decomposition_group(k,l) h Q) INTER
                 group_carrier(galois_group(subfield_generated l s,l) I)) *
            ramification_index
              (ring_of_integers k,ring_of_integers(subfield_generated l s)) h
              (Q INTER s) *
            residue_degree
              (ring_of_integers k,ring_of_integers(subfield_generated l s)) h
              (Q INTER s) =
            CARD(group_carrier(decomposition_group(k,l) h Q)) /\
            CARD(group_carrier(inertia_group(k,l) h (ring_of_integers l) Q)
                 INTER
                 group_carrier(galois_group(subfield_generated l s,l) I)) *
            ramification_index
              (ring_of_integers k,ring_of_integers(subfield_generated l s)) h
              (Q INTER s) =
            CARD(group_carrier(inertia_group(k,l) h (ring_of_integers l) Q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP GALOIS_IMP_FIELD_EXTENSION) THEN
    SIMP_TAC[field_extension; RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`]
    NUMBER_FIELD_INTERMEDIATE_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
