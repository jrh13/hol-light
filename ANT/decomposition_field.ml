(* ========================================================================= *)
(* Complements to the Hilbert theory of ANT/decomposition.ml and             *)
(* ANT/nf_decomposition.ml for number fields: decomposition and inertia      *)
(* groups over intermediate fields and in Galois subextensions, the          *)
(* decomposition field and the inertia field, the splitting types of a       *)
(* Galois extension read off D and I, abelian extensions (the Artin symbol), *)
(* composita, normal closures and the maximal unramified subextension.       *)
(*                                                                           *)
(* The general complements are at the end of ANT/decomposition.ml: for an    *)
(* intermediate field M = subfield_generated l s (s subfield_of l containing *)
(* h(k)) with H = Gal(l/M) = group_carrier(galois_group(M,l) I), D_Q(l/M) =  *)
(* D_Q INTER H and I_Q(l/M) = I_Q INTER H (DECOMPOSITION_GROUP_INTERMEDIATE, *)
(* INERTIA_GROUP_INTERMEDIATE), Q is the only maximal ideal above Q INTER s  *)
(* iff H SUBSET D_Q (DECOMPOSITION_GROUP_INTERMEDIATE_UNIQUE,                *)
(* DECOMPOSITION_FIELD_UNIQUE_PRIME), and the Frobenius congruence of        *)
(* frobenius_element and of its powers                                       *)
(* (FROBENIUS_ELEMENT_IN_DECOMPOSITION_GROUP,                                *)
(* DECOMPOSITION_GROUP_POW_CONGRUENCE, DECOMPOSITION_GROUP_CONGRUENT_EQ).    *)
(*                                                                           *)
(* Number fields: number_field l and galois_extension(k,l) h (which gives    *)
(* field k and ring_homomorphism(k,l) h), a nonzero prime p of O_k =         *)
(* ring_of_integers k and a prime Q of O_l above p (IMAGE h p SUBSET Q), e = *)
(* e(Q|p), f = f(Q|p) and r the number of primes of O_l above p. For M as    *)
(* above the prime of O_M below Q is Q INTER s                               *)
(* (NUMBER_FIELD_PRIME_IDEAL_INTERMEDIATE), every prime of O_M above p is of *)
(* this form (NUMBER_FIELD_PRIME_IDEALS_INTERMEDIATE; for the subfields of a *)
(* number field and a rational prime p,                                      *)
(* NUMBER_FIELD_SUBFIELD_PRIME_IDEALS_ABOVE), and                            *)
(*                                                                           *)
(*   |D_Q INTER H| e(Q INTER s|p) f(Q INTER s|p) = |D_Q|,                    *)
(*   |I_Q INTER H| e(Q INTER s|p) = |I_Q|                                    *)
(*                      (NUMBER_FIELD_DECOMPOSITION_GROUP_INTERMEDIATE)      *)
(*                                                                           *)
(* so e(Q INTER s|p) = 1 iff I_Q SUBSET H, and e = f = 1 for Q INTER s iff   *)
(* D_Q SUBSET H (NUMBER_FIELD_INTERMEDIATE_SPLITTING). Hence p is unramified *)
(* (totally split) in M iff the inertia groups (decomposition groups) of all *)
(* primes of O_l above p fix s pointwise                                     *)
(* (NUMBER_FIELD_INTERMEDIATE_SPLITTING_TYPES,                               *)
(* NUMBER_FIELD_GENERATED_SPLITTING_TYPES for the subfield generated by any  *)
(* set; p unramified in the subfield generated by Y is unramified in that    *)
(* generated by any X SUBSET Y, NUMBER_FIELD_GALOIS_UNRAMIFIED_MONO). In l   *)
(* itself (NUMBER_FIELD_GALOIS_SPLITTING_TYPES):                             *)
(*                                                                           *)
(*   p unramified        iff  I_Q = {I}                                      *)
(*   p totally split     iff  D_Q = {I}                                      *)
(*   p inert             iff  D_Q = G and I_Q = {I}                          *)
(*   p totally ramified  iff  I_Q = G                                        *)
(*                                                                           *)
(* For G abelian, D_Q, I_Q and (for p unramified) the Frobenius element      *)
(* depend only on p, not on Q (NUMBER_FIELD_ABELIAN_DECOMPOSITION_GROUP: the *)
(* Artin symbol of p).                                                       *)
(*                                                                           *)
(* Decomposition field Z = fixed_field l D_Q and inertia field T =           *)
(* fixed_field l I_Q: Gal(l/Z) = D_Q, Q INTER Z is a prime of O_Z with e = f *)
(* = 1 over p, Q is the only prime of O_l above it, e(Q|Q INTER Z) = e,      *)
(* f(Q|Q INTER Z) = f and [Z:k] = r (NUMBER_FIELD_DECOMPOSITION_FIELD); Z    *)
(* SUBSET T, Gal(l/T) = I_Q, [T:Z] = f, [l:T] = e, Q INTER Z is inert in T   *)
(* with e = 1 and f = f for Q INTER T, and Q INTER T is totally ramified in  *)
(* l with e(Q|Q INTER T) = e and f(Q|Q INTER T) = 1                          *)
(* (NUMBER_FIELD_INERTIA_DECOMPOSITION_TOWER; the inertia field part e(Q     *)
(* INTER T|p) = 1 is NUMBER_FIELD_INERTIA_FIELD of ANT/nf_decomposition.ml). *)
(*                                                                           *)
(* Frobenius elements over an intermediate field: for Q unramified over p    *)
(* the Frobenius element of Q over M is phi^m, phi the Frobenius element     *)
(* over k and m = f(Q INTER s|p)                                             *)
(* (NUMBER_FIELD_FROBENIUS_ELEMENT_INTERMEDIATE); for e(Q|p) = 1, e(Q INTER  *)
(* s|p) = 1 and phi^d IN Gal(l/M) iff f(Q INTER s|p) divides d, so f(Q INTER *)
(* s|p) is the order of phi modulo Gal(l/M)                                  *)
(* (NUMBER_FIELD_INTERMEDIATE_FROBENIUS_ORDER). Galois subextensions: for M  *)
(* normal over k (then Galois over k, as k has characteristic 0, already for *)
(* any extension of number fields: NUMBER_FIELD_GALOIS_INTERMEDIATE)         *)
(* restriction to s maps D_Q onto D_(Q INTER s) and I_Q onto I_(Q INTER s)   *)
(* (NUMBER_FIELD_DECOMPOSITION_GROUP_RESTRICTION), and the Frobenius element *)
(* of Q to that of Q INTER s when Q INTER s is unramified over p             *)
(* (NUMBER_FIELD_FROBENIUS_ELEMENT_RESTRICTION).                             *)
(*                                                                           *)
(* Composita and normal closures inside l: p is unramified (totally split)   *)
(* in the compositum of s and t iff it is in both                            *)
(* (NUMBER_FIELD_COMPOSITUM_SPLITTING_TYPES), and in s iff in the normal     *)
(* closure of s in l, the field generated by all f(s), f in G                *)
(* (NUMBER_FIELD_NORMAL_CLOSURE_SPLITTING_TYPES). A subextension is          *)
(* unramified over k at all nonzero primes iff it lies in the fixed field of *)
(* the subgroup generated by all the inertia groups                          *)
(* (NUMBER_FIELD_UNRAMIFIED_INERTIA_FIXED_FIELD; for k = Q that subgroup is  *)
(* G, ANT/inertia_generators.ml).                                            *)
(*                                                                           *)
(* Routes: the counts compare NUMBER_FIELD_DECOMPOSITION_GROUP for l/k and   *)
(* for l/M with the tower laws NUMBER_FIELD_RAMIFICATION_INDEX_TOWER,        *)
(* NUMBER_FIELD_RESIDUE_DEGREE_TOWER; a subset of a finite set of the same   *)
(* size is the set. For the textbook notion unramified the residue fields    *)
(* are finite, so it is weakly_unramified, e = 1 at every prime above p      *)
(* (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED). A normal intermediate     *)
(* field is separable over k, of characteristic 0                            *)
(* (SEPARABLE_EXTENSION_CHAR0). The splitting types use TOTALLY_SPLIT_CARD,  *)
(* INERT_RESIDUE_DEGREE and TOTALLY_RAMIFIED_RAMIFICATION_INDEX with r e f = *)
(* [l:k] and the constancy of e on the G-orbit                               *)
(* (NUMBER_FIELD_RAMIFICATION_INDEX_CONJUGATE). The surjectivity of the      *)
(* restrictions is by counting: |rho(D_Q)| |D_Q INTER Gal(l/M)| = |D_Q| for  *)
(* the restriction rho with kernel Gal(l/M) (CARD_IMAGE_SUBGROUP_KERNEL of   *)
(* Library/grouptheory.ml, GALOIS_GROUP_RESTRICTION of Library/galois.ml),   *)
(* and the same for I_Q. Normal closures: conjugate primes have conjugate    *)
(* decomposition and inertia groups (DECOMPOSITION_GROUP_CONJUGATE,          *)
(* INERTIA_GROUP_CONJUGATE). Intermediate Frobenius elements: phi^m lies in  *)
(* D_Q and satisfies the congruence modulo N(Q INTER s) = N(p)^m             *)
(* (IDEAL_NORM_RESIDUE_DEGREE), so it is the Frobenius element over M by     *)
(* DECOMPOSITION_GROUP_CONGRUENT_EQ; it generates the decomposition group of *)
(* Q over M, D_Q INTER Gal(l/M) (NUMBER_FIELD_DECOMPOSITION_GROUP_FROBENIUS, *)
(* DECOMPOSITION_GROUP_INTERMEDIATE), so phi^d IN Gal(l/M) gives phi^d =     *)
(* phi^(m j) for an integer j, d == m j modulo the order f(Q|p) of phi, and  *)
(* m divides f(Q|p) (NUMBER_FIELD_RESIDUE_DEGREE_TOWER).                     *)
(*                                                                           *)
(* Uses: Library/grouptheory.ml (CARD_IMAGE_SUBGROUP_KERNEL),                *)
(* Library/fieldtheory.ml (SEPARABLE_EXTENSION_CHAR0), Library/galois.ml     *)
(* (GALOIS_GROUP_RESTRICTION), ANT/decomposition.ml,                         *)
(* ANT/nf_decomposition.ml, ANT/relative_split.ml, ANT/relative_degree.ml    *)
(* and ANT/splitting_types.ml                                                *)
(* (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED).                           *)
(* ========================================================================= *)

