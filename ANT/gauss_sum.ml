(* ========================================================================= *)
(* Quadratic Gauss sums and the quadratic subfield of a cyclotomic field.    *)
(*                                                                           *)
(* Let r be an integral domain, p an odd prime and z in r of order p. The    *)
(* quadratic Gauss sum g = sum_{a < p} (a/p) z^a, with the Legendre symbol   *)
(* (a/p) = jacobi(a,p), satisfies g^2 = p* = (-1)^((p-1)/2) p                *)
(* (QUADRATIC_GAUSS_SUM), and for a ring homomorphism s from r to itself     *)
(* with s(z) = z^c, c coprime to p, s(g) = (c/p) g                           *)
(* (QUADRATIC_GAUSS_SUM_HOMOMORPHISM).                                       *)
(*                                                                           *)
(* An element of a number field outside the prime field Q whose square is in *)
(* Q generates a subfield of degree 2 (NUMBER_FIELD_SQRT_DEGREE). Let k =    *)
(* Q(z) be the cyclotomic field of an element z of odd prime order p. Every  *)
(* y in k with y^2 = p* generates the unique quadratic subfield of k         *)
(* (CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD), and the Gauss sum is such a y:     *)
(* the quadratic subfields of k are exactly Q(g), the field generated by a   *)
(* square root of p* (CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD_GAUSS_SUM).        *)
(*                                                                           *)
(* Routes. For a < p, ((a/p) z^a) g = sum_{t < p} (t/p) z^((1 + t) a): for a *)
(* = 0 both sides are 0, otherwise reindex g by b = a t mod p and use        *)
(* (a/p)^2 = 1. Summing over a and exchanging the sums, g^2 = sum_{t < p}    *)
(* (t/p) sum_{a < p} z^((1 + t) a) = ((p - 1)/p) p, since sum_{a < p}        *)
(* z^(c a) is p or 0 as p divides c or not (RING_SUM_ROOT_OF_UNITY_POWERS of *)
(* Library/ringtheory.ml) and the Legendre symbols sum to 0                  *)
(* (JACOBI_SUM_RESIDUES of Library/jacobi.ml), and                           *)
(* ((p - 1)/p) = (-1)^((p-1)/2) (JACOBI_MINUS1). Degree 2: the               *)
(* minimal polynomial divides X^2 - y^2 and has no root in Q                 *)
(* (MINIMAL_POLYNOMIAL_DEG_LE, EXTENSION_DEGREE_SIMPLE), where p* is not a   *)
(* square in Q, p being squarefree (SQRT_SQUAREFREE_NOT_IN_PRIME_SUBFIELD).  *)
(* Uniqueness: the Galois group of k is cyclic (CYCLIC_MODMUL_GROUP), so k   *)
(* has only one subfield of degree 2 (CYCLOTOMIC_FIELD_SUBFIELD_UNIQUE). For *)
(* s(z) = z^c: (c/p) s(g) = sum_a (c a/p) z^(c a) = g by reindexing a |-> c  *)
(* a mod p (RING_SUM_MOD_MULT_REINDEX of Library/ringtheory.ml) and          *)
(* (c/p)^2 = 1.                                                              *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (finite sums, ring_order,                     *)
(* RING_SUM_ROOT_OF_UNITY_POWERS, RING_SUM_MOD_MULT_REINDEX),                *)
(* Library/pocklington.ml (squarefree), Library/jacobi.ml (the Jacobi        *)
(* symbol, JACOBI_SUM_RESIDUES), Library/fieldtheory.ml (minimal             *)
(* polynomials, degrees), Library/modmul_group.ml (CYCLIC_MODMUL_GROUP),     *)
(* ANT/numfield.ml, ANT/quadratic.ml, ANT/quadratic_split.ml (the            *)
(* polynomials X^2 + b X + c) and ANT/cyclotomic_subfields.ml                *)
(* (CYCLOTOMIC_FIELD_SUBFIELD_UNIQUE).                                       *)
(* ========================================================================= *)

