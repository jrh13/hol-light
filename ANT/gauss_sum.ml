(* ------------------------------------------------------------------------- *)
(* The quadratic Gauss sum: g^2 = (-1)^((p-1)/2) p.                          *)
(* ------------------------------------------------------------------------- *)

let QUADRATIC_GAUSS_SUM = prove
 (`!(r:A ring) z p.
        integral_domain r /\ prime p /\ ~(p = 2) /\
        z IN ring_carrier r /\ ring_order r z = p
        ==> ring_pow r (ring_sum r {a | a < p}
                          (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                                          (ring_pow r z a))) 2 =
            ring_of_int r (--(&1) pow ((p - 1) DIV 2) * &p)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_NZ) THEN
  ABBREV_TAC
   `g = ring_sum r {a | a < p}
          (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                          (ring_pow r (z:A) a))` THEN
  SUBGOAL_THEN `(g:A) IN ring_carrier r` ASSUME_TAC THENL
   [EXPAND_TAC "g" THEN REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!a. a < p
        ==> ring_mul r (ring_mul r (ring_of_int r (jacobi(a,p)))
                                   (ring_pow r z a)) g =
            ring_sum r {t | t < p}
              (\t. ring_mul r (ring_of_int r (jacobi(t,p)))
                              (ring_pow r (z:A) ((1 + t) * a)))`
  ASSUME_TAC THENL
   [X_GEN_TAC `a:num` THEN DISCH_TAC THEN
    ASM_CASES_TAC `a = 0` THENL
     [ASM_REWRITE_TAC[MULT_CLAUSES; ring_pow] THEN
      SUBGOAL_THEN `jacobi(0,p) = &0` SUBST1_TAC THENL
       [REWRITE_TAC[JACOBI_EQ_0; COPRIME_0] THEN
        ASM_MESON_TAC[PRIME_1];
        ALL_TAC] THEN
      ASM_SIMP_TAC[RING_OF_INT_0; RING_MUL_LZERO; RING_1] THEN
      SIMP_TAC[RING_MUL_RID; RING_OF_INT] THEN
      ASM_SIMP_TAC[GSYM RING_OF_INT_ISUM; FINITE_NUMSEG_LT;
                   JACOBI_SUM_RESIDUES; RING_OF_INT_0];
      ALL_TAC] THEN
    SUBGOAL_THEN `coprime((a:num),p)` ASSUME_TAC THENL
     [ONCE_REWRITE_TAC[COPRIME_SYM] THEN ASM_SIMP_TAC[PRIME_COPRIME_EQ] THEN
      DISCH_THEN(MP_TAC o MATCH_MP DIVIDES_LE) THEN ASM_ARITH_TAC;
      ALL_TAC] THEN
    SUBGOAL_THEN
     `g = ring_sum r {t | t < p}
            (\t. ring_mul r
                   (ring_mul r (ring_of_int r (jacobi(a,p)))
                               (ring_of_int r (jacobi(t,p))))
                   (ring_pow r (z:A) (a * t)))`
    SUBST1_TAC THENL
     [EXPAND_TAC "g" THEN
      MP_TAC(ISPECL [`r:A ring`; `p:num`; `a:num`;
        `\b. ring_mul r (ring_of_int r (jacobi(b,p))) (ring_pow r (z:A) b)`]
        RING_SUM_MOD_MULT_REINDEX) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
      MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `t:num` THEN DISCH_TAC THEN
      REWRITE_TAC[JACOBI_MOD; JACOBI_LMUL; RING_OF_INT_MUL] THEN
      AP_TERM_TAC THEN
      MP_TAC(ISPECL [`r:A ring`; `z:A`; `a * t:num`] RING_POW_MOD_ORDER) THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_mul r (ring_of_int r (jacobi(a,p))) (ring_of_int r (jacobi(a,p))) =
      ring_1 (r:A ring)`
    ASSUME_TAC THENL
     [REWRITE_TAC[GSYM RING_OF_INT_MUL; GSYM JACOBI_LMUL] THEN
      REWRITE_TAC[GSYM EXP_2; JACOBI_SQUARED] THEN
      ASM_REWRITE_TAC[RING_OF_INT_1];
      ALL_TAC] THEN
    SIMP_TAC[GSYM RING_SUM_LMUL; FINITE_NUMSEG_LT; RING_MUL; RING_OF_INT;
             RING_POW; ASSUME `(z:A) IN ring_carrier r`] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `t:num` THEN DISCH_TAC THEN
    REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `ring_pow r (z:A) ((1 + t) * a) =
      ring_mul r (ring_pow r z a) (ring_pow r z (a * t))`
    SUBST1_TAC THENL
     [ASM_SIMP_TAC[GSYM RING_POW_ADD] THEN AP_TERM_TAC THEN ARITH_TAC;
      ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `ring_of_int r (jacobi(a,p)):A`;
                   `ring_of_int r (jacobi(t,p)):A`; `ring_pow r (z:A) a`;
                   `ring_pow r (z:A) (a * t)`] (RING_RULE
     `!r u v x y:A.
        u IN ring_carrier r /\ v IN ring_carrier r /\
        x IN ring_carrier r /\ y IN ring_carrier r /\
        ring_mul r u u = ring_1 r
        ==> ring_mul r (ring_mul r u x) (ring_mul r (ring_mul r u v) y) =
            ring_mul r v (ring_mul r x y)`)) THEN
    ASM_SIMP_TAC[RING_OF_INT; RING_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_pow r g 2 =
    ring_sum r {t | t < p}
      (\t. ring_mul r (ring_of_int r (jacobi(t,p)))
             (ring_sum r {a | a < p} (\a. ring_pow r (z:A) ((1 + t) * a))))`
  SUBST1_TAC THENL
   [ASM_SIMP_TAC[RING_POW_2] THEN
    FIRST_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o LAND_CONV) [SYM th]) THEN
    MP_TAC(ISPECL [`r:A ring`;
        `\a. ring_mul r (ring_of_int r (jacobi(a,p))) (ring_pow r (z:A) a)`;
        `g:A`; `{a:num | a < p}`] RING_SUM_RMUL) THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; RING_MUL; RING_OF_INT; RING_POW] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    TRANS_TAC EQ_TRANS
     `ring_sum r {a | a < p}
        (\a. ring_sum r {t | t < p}
               (\t. ring_mul r (ring_of_int r (jacobi(t,p)))
                               (ring_pow r (z:A) ((1 + t) * a))))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC RING_SUM_EQ THEN ASM_SIMP_TAC[IN_ELIM_THM]; ALL_TAC] THEN
    W(MP_TAC o PART_MATCH (lhand o rand) RING_SUM_SWAP o lhand o snd) THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; RING_MUL; RING_OF_INT; RING_POW] THEN
    DISCH_THEN SUBST1_TAC THEN MATCH_MP_TAC RING_SUM_EQ THEN
    X_GEN_TAC `t:num` THEN DISCH_TAC THEN REWRITE_TAC[] THEN
    MATCH_MP_TAC RING_SUM_LMUL THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; RING_OF_INT; RING_POW];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `z:A`; `p:num`] RING_SUM_ROOT_OF_UNITY_POWERS) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  TRANS_TAC EQ_TRANS
   `ring_sum r {t | t < p}
      (\t. if t = p - 1
           then ring_mul r (ring_of_int r (jacobi(p - 1,p))) (ring_of_num r p)
           else ring_0 (r:A ring))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `t:num` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    SUBGOAL_THEN `(p:num) divides (1 + t) <=> t = p - 1` SUBST1_TAC THENL
     [EQ_TAC THENL
       [DISCH_THEN(MP_TAC o MATCH_MP DIVIDES_LE) THEN ASM_ARITH_TAC;
        DISCH_THEN SUBST1_TAC THEN
        ASM_SIMP_TAC[ARITH_RULE `~(p = 0) ==> 1 + (p - 1) = p`;
                     DIVIDES_REFL]];
      COND_CASES_TAC THEN ASM_SIMP_TAC[RING_MUL_RZERO; RING_OF_INT]];
    ALL_TAC] THEN
  REWRITE_TAC[RING_SUM_DELTA; IN_ELIM_THM] THEN
  ASM_SIMP_TAC[ARITH_RULE `~(p = 0) ==> p - 1 < p`; RING_MUL; RING_OF_INT;
               RING_OF_NUM] THEN
  MP_TAC(SPEC `p:num` JACOBI_MINUS1) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[PRIME_ODD]; DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[RING_OF_INT_MUL; RING_OF_INT_OF_NUM]);;

(* A homomorphism with z |-> z^c, c coprime to p, multiplies the quadratic   *)
(* Gauss sum by the Legendre symbol (c/p).                                   *)
let QUADRATIC_GAUSS_SUM_HOMOMORPHISM = prove
 (`!(r:A ring) s z p c.
        prime p /\ z IN ring_carrier r /\ ring_order r z = p /\
        ring_homomorphism(r,r) s /\ s z = ring_pow r z c /\ coprime(c,p)
        ==> s(ring_sum r {a | a < p}
               (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                               (ring_pow r z a))) =
            ring_mul r (ring_of_int r (jacobi(c,p)))
              (ring_sum r {a | a < p}
                (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                                (ring_pow r z a)))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_NZ) THEN
  SUBGOAL_THEN
   `(s:A->A) (ring_sum r {a | a < p}
                (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                                (ring_pow r z a))) =
    ring_sum r {a | a < p}
      (\a. ring_mul r (ring_of_int r (jacobi(a,p))) (ring_pow r z (c * a)))`
  SUBST1_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `r:A ring`; `s:A->A`]
     (INST_TYPE [`:num`,`:K`] RING_HOMOMORPHISM_SUM)) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(MP_TAC o SPECL
     [`\a. ring_mul (r:A ring) (ring_of_int r (jacobi(a,p)))
                               (ring_pow r z a)`; `{a:num | a < p}`]) THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; RING_MUL; RING_OF_INT; RING_POW] THEN
    DISCH_THEN SUBST1_TAC THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `a:num` THEN DISCH_TAC THEN
    REWRITE_TAC[o_THM] THEN
    FIRST_ASSUM(fun th -> ASM_SIMP_TAC
     [MATCH_MP RING_HOMOMORPHISM_MUL th; MATCH_MP RING_HOMOMORPHISM_POW th;
      RING_OF_INT; RING_POW]) THEN
    FIRST_ASSUM(fun th ->
      REWRITE_TAC[MATCH_MP RING_HOMOMORPHISM_RING_OF_INT th]) THEN
    ASM_SIMP_TAC[RING_POW_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul r (ring_of_int r (jacobi(c,p)))
      (ring_sum r {a | a < p}
        (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                        (ring_pow r z (c * a)))) =
    ring_sum (r:A ring) {a | a < p}
      (\a. ring_mul r (ring_of_int r (jacobi(a,p))) (ring_pow r z a))`
  MP_TAC THENL
   [ASM_SIMP_TAC[GSYM RING_SUM_LMUL; RING_OF_INT; RING_MUL; RING_POW;
                 FINITE_NUMSEG_LT] THEN
    MP_TAC(ISPECL [`r:A ring`; `p:num`; `c:num`;
                   `\t. ring_mul (r:A ring) (ring_of_int r (jacobi(t,p)))
                                 (ring_pow r z t)`]
      RING_SUM_MOD_MULT_REINDEX) THEN
    ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `a:num` THEN DISCH_TAC THEN
    REWRITE_TAC[JACOBI_MOD] THEN
    MP_TAC(ISPECL [`r:A ring`; `z:A`; `c * a:num`] RING_POW_MOD_ORDER) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
    ASM_SIMP_TAC[RING_MUL_ASSOC; RING_OF_INT; RING_POW] THEN
    REWRITE_TAC[GSYM RING_OF_INT_MUL; JACOBI_LMUL];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul r (ring_of_int r (jacobi(c,p))) (ring_of_int r (jacobi(c,p))) =
    ring_1 (r:A ring)`
  MP_TAC THENL
   [REWRITE_TAC[GSYM RING_OF_INT_MUL; GSYM RING_OF_INT_1] THEN
    AP_TERM_TAC THEN ASM_SIMP_TAC[JACOBI_PRIME] THEN
    COND_CASES_TAC THENL
     [ASM_MESON_TAC[PRIME_COPRIME_EQ; COPRIME_SYM]; ALL_TAC] THEN
    COND_CASES_TAC THEN INT_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sum r {a | a < p}
      (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                      (ring_pow r z (c * a))) IN ring_carrier (r:A ring) /\
    ring_of_int r (jacobi(c,p)) IN ring_carrier r`
  MP_TAC THENL [REWRITE_TAC[RING_SUM; RING_OF_INT]; ALL_TAC] THEN
  SPEC_TAC(`ring_sum r {a | a < p}
             (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                             (ring_pow r z a)):A`,`g:A`) THEN
  SPEC_TAC(`ring_of_int r (jacobi(c,p)):A`,`e:A`) THEN
  SPEC_TAC(`ring_sum r {a | a < p}
             (\a. ring_mul r (ring_of_int r (jacobi(a,p)))
                             (ring_pow r z (c * a))):A`,`u:A`) THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN DISCH_TAC THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[RING_MUL_ASSOC; RING_MUL_LID]);;

