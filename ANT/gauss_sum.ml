let NUMBER_FIELD_SQRT_DEGREE = prove
 (`!k:A ring x.
        number_field k /\ x IN ring_carrier k /\
        ~(x IN ring_carrier(subfield_generated k {ring_0 k})) /\
        ring_pow k x 2 IN ring_carrier(subfield_generated k {ring_0 k})
        ==> extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k {x}) I = 2`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `x:A`] NUMBER_FIELD_ALGEBRAIC) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  ABBREV_TAC `q = subfield_generated (k:A ring) {ring_0 k}` THEN
  SUBGOAL_THEN `field(q:A ring) /\ field_extension(q,k) (I:A->A)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN
    ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; FIELD_EXTENSION_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN `poly_deg q (minimal_polynomial (q,k) (I:A->A) x) = 2`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `k:A ring`; `x:A`;
      `ring_sub (poly_ring q (:1))
         (ring_pow (poly_ring q (:1)) (poly_var q one) 2)
         (ring_add (poly_ring q (:1))
           (ring_mul (poly_ring q (:1)) (poly_const q (ring_0 q))
             (poly_var q one))
           (poly_const q (ring_pow k x 2:A)))`] MINIMAL_POLYNOMIAL_DEG_LE) THEN
    MP_TAC(ISPECL [`q:A ring`; `ring_0 q:A`; `ring_pow k x 2:A`]
      QUADRATIC_POLY_DEG) THEN
    MP_TAC(ISPECL [`q:A ring`; `ring_0 q:A`; `ring_pow k x 2:A`]
      QUADRATIC_POLY_IN_CARRIER) THEN
    MP_TAC(ISPECL [`q:A ring`; `k:A ring`; `I:A->A`; `x:A`; `ring_0 q:A`;
                   `ring_pow k x 2:A`] QUADRATIC_POLY_EXTEND) THEN
    ASM_SIMP_TAC[RING_0; FIELD_IMP_NONTRIVIAL_RING;
                 FIELD_EXTENSION_IMP_HOMOMORPHISM] THEN
    REPEAT DISCH_TAC THEN
    MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `k:A ring`; `x:A`]
      MINIMAL_POLYNOMIAL_DEG_EQ_1) THEN
    MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `k:A ring`; `x:A`]
      MINIMAL_POLYNOMIAL_IRREDUCIBLE) THEN
    ASM_SIMP_TAC[IMAGE_I] THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o MATCH_MP IRREDUCIBLE_IMP_POLY_DEG_NZ o
      CONJ (ASSUME `field(q:A ring)`)) THEN
    MATCH_MP_TAC(ARITH_RULE
     `d <= 2 ==> ~(d = 0) ==> ~(d = 1) ==> d = 2`) THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN CONJ_TAC THENL
     [DISCH_THEN(MP_TAC o AP_TERM `poly_deg (q:A ring):((1->num)->A)->num`) THEN
      ASM_REWRITE_TAC[POLY_DEG_0] THEN ARITH_TAC;
      EXPAND_TAC "q" THEN REWRITE_TAC[I_THM; CONJUNCT2 SUBFIELD_GENERATED] THEN
      ASM_SIMP_TAC[RING_MUL_LZERO; RING_ADD_LZERO; RING_POW; RING_SUB_REFL]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `k:A ring`; `x:A`]
    EXTENSION_DEGREE_SIMPLE) THEN
  MP_TAC(ISPECL [`k:A ring`; `x:A`] SUBFIELD_GENERATED_SING_ALGEBRAIC) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  ASM_REWRITE_TAC[IMAGE_I]);;

let CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD = prove
 (`!(k:A ring) z p y.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = p /\
        prime p /\ ~(p = 2) /\ subfield_generated k {z} = k /\
        y IN ring_carrier k /\
        ring_pow k y 2 = ring_of_int k (--(&1) pow ((p - 1) DIV 2) * &p)
        ==> extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k {y}) I = 2 /\
            !s. s subfield_of k /\
                extension_degree (subfield_generated k {ring_0 k},
                                  subfield_generated k s) I = 2
                ==> s = ring_carrier(subfield_generated k {y})`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_NZ) THEN
  SUBGOAL_THEN
   `~((y:A) IN ring_carrier(subfield_generated k {ring_0 k}))`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `y:A`;
                   `--(&1) pow ((p - 1) DIV 2) * &p:int`]
      SQRT_SQUAREFREE_NOT_IN_PRIME_SUBFIELD) THEN
    MATCH_MP_TAC(TAUT `p ==> (p ==> q) ==> q`) THEN
    ASM_REWRITE_TAC[INT_ABS_MUL; INT_ABS_POW; INT_ABS_NEG; INT_ABS_NUM;
                    INT_POW_ONE; INT_MUL_LID; NUM_OF_INT_OF_NUM] THEN
    ASM_SIMP_TAC[PRIME_IMP_SQUAREFREE] THEN
    CONJ_TAC THENL [ASM_MESON_TAC[number_field]; ALL_TAC] THEN
    DISCH_THEN(MP_TAC o AP_TERM `abs:int->int`) THEN
    REWRITE_TAC[INT_ABS_MUL; INT_ABS_POW; INT_ABS_NEG; INT_ABS_NUM;
                INT_POW_ONE; INT_MUL_LID; INT_OF_NUM_EQ] THEN
    ASM_MESON_TAC[PRIME_1];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC NUMBER_FIELD_SQRT_DEGREE THEN
    ASM_REWRITE_TAC[RING_OF_INT_IN_SUBFIELD_GENERATED];
    DISCH_TAC] THEN
  X_GEN_TAC `s:A->bool` THEN STRIP_TAC THEN
  MATCH_MP_TAC CYCLOTOMIC_FIELD_SUBFIELD_UNIQUE THEN
  MAP_EVERY EXISTS_TAC [`k:A ring`; `z:A`; `p:num`] THEN
  ASM_REWRITE_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED] THEN
  ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED_EQ; FIELD_SUBFIELD_GENERATED] THEN
  REWRITE_TAC[CYCLIC_MODMUL_GROUP] THEN
  REPEAT DISJ2_TAC THEN MAP_EVERY EXISTS_TAC [`p:num`; `1`] THEN
  ASM_REWRITE_TAC[EXP_1] THEN
  MP_TAC(SPEC `p:num` PRIME_GE_2) THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC);;

let CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD_GAUSS_SUM = prove
 (`!(k:A ring) z p s.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = p /\
        prime p /\ ~(p = 2) /\ subfield_generated k {z} = k
        ==> (s subfield_of k /\
             extension_degree (subfield_generated k {ring_0 k},
                               subfield_generated k s) I = 2 <=>
             s = ring_carrier
                   (subfield_generated k
                     {ring_sum k {a | a < p}
                        (\a. ring_mul k (ring_of_int k (jacobi(a,p)))
                                        (ring_pow k z a))}))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ABBREV_TAC `g = ring_sum (k:A ring) {a | a < p}
                    (\a. ring_mul k (ring_of_int k (jacobi(a,p)))
                                    (ring_pow k z a))` THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `(g:A) IN ring_carrier k` ASSUME_TAC THENL
   [EXPAND_TAC "g" THEN REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`] QUADRATIC_GAUSS_SUM) THEN
  ASM_SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`; `g:A`]
    CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN EQ_TAC THENL
   [ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED;
                 SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED]]);;
