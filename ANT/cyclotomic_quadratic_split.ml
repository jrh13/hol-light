(* ------------------------------------------------------------------------- *)
(* The decomposition law in quadratic fields, with totally_split.            *)
(* ------------------------------------------------------------------------- *)

let QUADRATIC_FIELD_TOTALLY_SPLIT_ODD_PRIME = prove
 (`!k:A ring x d p.
        number_field k /\
        extension_degree (subfield_generated k {ring_0 k},k) I = 2 /\
        x IN ring_carrier k /\ ring_pow k x 2 = ring_of_int k d /\
        squarefree(num_of_int(abs d)) /\ ~(d = &1) /\
        prime p /\ ~(p = 2) /\ ~(&p divides d)
        ==> (totally_split (integer_ring,ring_of_integers k) (ring_of_int k)
               (ideal_generated integer_ring {&p}) <=>
             ?y. (y pow 2 == d) (mod &p))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`k:A ring`; `x:A`; `d:int`; `p:num`]
    QUADRATIC_FIELD_ODD_PRIME) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ASM_CASES_TAC `?y. ((y:int) pow 2 == d) (mod &p)` THEN
  ASM_REWRITE_TAC[] THENL
   [ALL_TAC;
    MP_TAC(ISPECL [`k:A ring`; `p:num`]
      NUMBER_FIELD_SPLITTING_TYPES_EXCLUSIVE) THEN
    ASM_REWRITE_TAC[ARITH_RULE `1 < 2`] THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:num`]
      SPLITTING_TYPES_INTEGER_RING) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[] THEN MESON_TAC[]] THEN
  SUBGOAL_THEN
   `?P Q. prime_ideal (ring_of_integers k) P /\
          prime_ideal (ring_of_integers k) Q /\ ~(P = Q) /\
          ideal_generated (ring_of_integers k) {ring_of_num k p} =
          ideal_prod (ring_of_integers k) P (Q:A->bool)`
  STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  ASM_SIMP_TAC[NUMBER_FIELD_TOTALLY_SPLIT_CARD] THEN
  SUBGOAL_THEN `dedekind_domain(ring_of_integers k:A ring)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  SUBGOAL_THEN `(ring_of_num k p:A) IN ring_carrier(ring_of_integers k)`
  ASSUME_TAC THENL
   [MESON_TAC[RING_OF_NUM; RING_OF_INTEGERS]; ALL_TAC] THEN
  SUBGOAL_THEN `~(P = {ring_0 k:A}) /\ ~(Q = {ring_0 k:A})`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `P:A->bool`; `Q:A->bool`]
      IDEAL_PROD_EQ_ZERO) THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN; PRIME_IMP_RING_IDEAL;
                 RING_OF_INTEGERS] THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) && is_comb(rand(concl th)) &&
      can (find_term ((=) `P:A->bool`)) (rand(concl th)))) THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_EQ_0; DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
    REWRITE_TAC[RING_OF_INTEGERS; RING_OF_NUM_EQ_0] THEN
    UNDISCH_TAC `number_field(k:A ring)` THEN
    SIMP_TAC[number_field; DIVIDES_ZERO] THEN
    ASM_MESON_TAC[PRIME_IMP_NZ];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `{R | prime_ideal (ring_of_integers k) R /\ ring_of_num k p IN R} =
    {P,Q:A->bool}`
  SUBST1_TAC THENL
   [GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `R:A->bool` THEN
    REWRITE_TAC[IN_ELIM_THM; IN_INSERT; NOT_IN_EMPTY] THEN EQ_TAC THENL
     [STRIP_TAC THEN
      SUBGOAL_THEN
       `ideal_prod (ring_of_integers k) P Q SUBSET (R:A->bool)`
      MP_TAC THENL
       [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
          is_eq(concl th) && is_comb(rand(concl th)) &&
          can (find_term ((=) `P:A->bool`)) (rand(concl th)))) THEN
        MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
        ASM_SIMP_TAC[SING_SUBSET; PRIME_IMP_RING_IDEAL];
        ALL_TAC] THEN
      ASM_SIMP_TAC[IDEAL_PROD_SUBSET_PRIME_IDEAL; PRIME_IMP_RING_IDEAL;
                   RING_IDEAL_IMP_SUBSET] THEN
      STRIP_TAC THENL
       [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `R:A->bool`; `P:A->bool`]
          DEDEKIND_KRULL_DIMENSION_ONE);
        MP_TAC(ISPECL [`ring_of_integers k:A ring`; `R:A->bool`; `Q:A->bool`]
          DEDEKIND_KRULL_DIMENSION_ONE)] THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN MESON_TAC[];
      ALL_TAC] THEN
    DISCH_THEN(DISJ_CASES_THEN SUBST_ALL_TAC) THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(SET_RULE
     `!j:A->bool. x IN j /\ j SUBSET R ==> x IN R`) THEN
    EXISTS_TAC `ideal_generated (ring_of_integers k) {ring_of_num k p:A}` THEN
    ASM_SIMP_TAC[IN_IDEAL_GENERATED_SELF] THEN
    ASM_SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; IDEAL_PROD_SUBSET_RIGHT;
                 PRIME_IMP_RING_IDEAL; RING_IDEAL_IMP_SUBSET];
    ASM_SIMP_TAC[CARD_CLAUSES; FINITE_INSERT; FINITE_EMPTY; IN_INSERT;
                 NOT_IN_EMPTY] THEN
    CONV_TAC NUM_REDUCE_CONV]);;

(* ------------------------------------------------------------------------- *)
(* The quadratic subfield of the cyclotomic field of an odd prime.           *)
(* ------------------------------------------------------------------------- *)

let CYCLOTOMIC_QUADRATIC_SUBFIELD_TOTALLY_SPLIT = prove
 (`!(k:A ring) z p y q.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = p /\
        prime p /\ ~(p = 2) /\ subfield_generated k {z} = k /\
        y IN ring_carrier k /\
        ring_pow k y 2 = ring_of_int k (--(&1) pow ((p - 1) DIV 2) * &p) /\
        prime q /\ ~(q = p)
        ==> (totally_split
              (integer_ring,ring_of_integers(subfield_generated k {y}))
              (ring_of_int(subfield_generated k {y}))
              (ideal_generated integer_ring {&q}) <=>
             ?x. (x EXP 2 == q) (mod p))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FIELD_IMP_INTEGRAL_DOMAIN) THEN
  SUBGOAL_THEN `ring_char(k:A ring) = 0` ASSUME_TAC THENL
   [ASM_MESON_TAC[number_field]; ALL_TAC] THEN
  SUBGOAL_THEN `~(q divides (p:num)) /\ coprime(q,p) /\ ~(p divides q)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_COPRIME_EQ; COPRIME_SYM; DIVIDES_PRIME_PRIME];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`; `{y:A}`; `q:num`]
    CYCLOTOMIC_SUBFIELD_SPLITTING_TYPES) THEN
  ASM_REWRITE_TAC[IN_SING] THEN DISCH_THEN(SUBST1_TAC o CONJUNCT2) THEN
  REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM; FORALL_UNWIND_THM2] THEN
  ABBREV_TAC
   `w = ring_sum (k:A ring) {a | a < p}
          (\a. ring_mul k (ring_of_int k (jacobi(a,p))) (ring_pow k z a))` THEN
  SUBGOAL_THEN `(w:A) IN ring_carrier k` ASSUME_TAC THENL
   [EXPAND_TAC "w" THEN REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`] QUADRATIC_GAUSS_SUM) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN `y = w \/ y = ring_neg k (w:A)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `y:A`; `w:A`] INTEGRAL_DOMAIN_SQUARE_EQ) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(y:A = ring_0 k)` ASSUME_TAC THENL
   [DISCH_TAC THEN
    UNDISCH_TAC
     `ring_pow k (y:A) 2 = ring_of_int k (--(&1) pow ((p - 1) DIV 2) * &p)` THEN
    ASM_REWRITE_TAC[RING_POW_ZERO; ARITH_EQ] THEN
    DISCH_THEN(MP_TAC o SYM) THEN
    ASM_REWRITE_TAC[RING_OF_INT_EQ_0; INT_DIVIDES_ZERO] THEN
    REWRITE_TAC[INT_ENTIRE; INT_POW_EQ_0; INT_NEG_EQ_0; INT_OF_NUM_EQ;
                ARITH_EQ] THEN
    ASM_SIMP_TAC[PRIME_IMP_NZ];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN group_carrier(galois_group
                             (subfield_generated k {ring_0 k},k) I) /\
        g z = ring_pow k z q
        ==> g y = ring_mul k (ring_of_int k (jacobi(q,p))) (y:A)`
  ASSUME_TAC THENL
   [X_GEN_TAC `g:A->A` THEN REWRITE_TAC[GALOIS_GROUP; IN_ELIM_THM] THEN
    STRIP_TAC THEN
    SUBGOAL_THEN `ring_homomorphism (k,k) (g:A->A)` ASSUME_TAC THENL
     [ASM_MESON_TAC[ring_automorphism; RING_ISOMORPHISM_IMP_HOMOMORPHISM];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `g:A->A`; `z:A`; `p:num`; `q:num`]
      QUADRATIC_GAUSS_SUM_HOMOMORPHISM) THEN
    ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
    FIRST_X_ASSUM(DISJ_CASES_THEN SUBST1_TAC o check (is_disj o concl)) THEN
    ASM_REWRITE_TAC[] THEN
    FIRST_ASSUM(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_NEG th]) THEN
    ASM_SIMP_TAC[RING_MUL_RNEG; RING_OF_INT];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`; `q:num`]
    CYCLOTOMIC_FIELD_GALOIS_GROUP_EXISTS) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[PRIME_IMP_NZ]; ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `g0:A->A` STRIP_ASSUME_TAC) THEN
  TRANS_TAC EQ_TRANS `ring_mul k (ring_of_int k (jacobi(q,p))) (y:A) = y` THEN
  CONJ_TAC THENL
   [EQ_TAC THENL
     [DISCH_THEN(MP_TAC o SPEC `g0:A->A`) THEN ASM_SIMP_TAC[];
      REPEAT STRIP_TAC THEN ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  MP_TAC(SPECL [`q:num`; `p:num`] JACOBI_PRIME) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  COND_CASES_TAC THEN ASM_SIMP_TAC[RING_OF_INT_1; RING_MUL_LID] THEN
  REWRITE_TAC[RING_OF_INT_NEG; RING_OF_INT_1] THEN
  ASM_SIMP_TAC[RING_MUL_LNEG; RING_MUL_LID; RING_1] THEN
  DISCH_TAC THEN
  SUBGOAL_THEN `ring_mul k (ring_of_num k 2) (y:A) = ring_0 k` MP_TAC THENL
   [TRANS_TAC EQ_TRANS `ring_sub k y (ring_neg k (y:A))` THEN CONJ_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `!k:A ring y. y IN ring_carrier k
                     ==> ring_mul k (ring_of_num k 2) y =
                         ring_sub k y (ring_neg k y)`) THEN
      ASM_REWRITE_TAC[];
      ASM_SIMP_TAC[RING_SUB_REFL]];
    ASM_SIMP_TAC[INTEGRAL_DOMAIN_MUL_EQ_0; RING_OF_NUM; RING_OF_NUM_EQ_0;
                 DIVIDES_ZERO] THEN
    CONV_TAC NUM_REDUCE_CONV]);;

(* Both descriptions of the splitting of an odd prime q <> p in the          *)
(* quadratic subfield generated by a square root of p* (q is a square mod p, *)
(* p* is a square mod q).                                                    *)
let CYCLOTOMIC_QUADRATIC_SUBFIELD_DECOMPOSITION = prove
 (`!(k:A ring) z p y q.
        number_field k /\ z IN ring_carrier k /\ ring_order k z = p /\
        prime p /\ ~(p = 2) /\ subfield_generated k {z} = k /\
        y IN ring_carrier k /\
        ring_pow k y 2 = ring_of_int k (--(&1) pow ((p - 1) DIV 2) * &p) /\
        prime q /\ ~(q = 2) /\ ~(q = p)
        ==> (totally_split
              (integer_ring,ring_of_integers(subfield_generated k {y}))
              (ring_of_int(subfield_generated k {y}))
              (ideal_generated integer_ring {&q}) <=>
             ?x. (x EXP 2 == q) (mod p)) /\
            (totally_split
              (integer_ring,ring_of_integers(subfield_generated k {y}))
              (ring_of_int(subfield_generated k {y}))
              (ideal_generated integer_ring {&q}) <=>
             ?x:int. (x pow 2 == --(&1) pow ((p - 1) DIV 2) * &p) (mod &q))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN CONJ_TAC THENL
   [MATCH_MP_TAC CYCLOTOMIC_QUADRATIC_SUBFIELD_TOTALLY_SPLIT THEN
    EXISTS_TAC `z:A` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`subfield_generated k {y:A}`; `y:A`;
                 `--(&1) pow ((p - 1) DIV 2) * &p:int`; `q:num`]
    QUADRATIC_FIELD_TOTALLY_SPLIT_ODD_PRIME) THEN
  DISCH_THEN MATCH_MP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED;
               RING_POW_SUBFIELD_GENERATED; RING_OF_INT_SUBFIELD_GENERATED] THEN
  REPEAT CONJ_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `z:A`; `p:num`; `y:A`]
      CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD) THEN
    ASM_SIMP_TAC[];
    MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN ASM SET_TAC[];
    REWRITE_TAC[INT_ABS_MUL; INT_ABS_POW; INT_ABS_NEG; INT_ABS_NUM;
                INT_POW_ONE; INT_MUL_LID; NUM_OF_INT_OF_NUM] THEN
    ASM_SIMP_TAC[PRIME_IMP_SQUAREFREE];
    DISCH_THEN(MP_TAC o AP_TERM `abs:int->int`) THEN
    REWRITE_TAC[INT_ABS_MUL; INT_ABS_POW; INT_ABS_NEG; INT_ABS_NUM;
                INT_POW_ONE; INT_MUL_LID; INT_OF_NUM_EQ] THEN
    ASM_MESON_TAC[PRIME_1];
    DISCH_TAC THEN
    SUBGOAL_THEN `(q:num) divides p` MP_TAC THENL
     [REWRITE_TAC[num_divides] THEN
      UNDISCH_TAC `&q divides --(&1) pow ((p - 1) DIV 2) * &p` THEN
      SPEC_TAC(`(p - 1) DIV 2`,`n:num`) THEN INDUCT_TAC THEN
      REWRITE_TAC[INT_POW; INT_MUL_LID] THEN
      REWRITE_TAC[GSYM INT_MUL_ASSOC; INT_MUL_LNEG; INT_MUL_LID] THEN
      REWRITE_TAC[INT_DIVIDES_LNEG; INT_DIVIDES_RNEG] THEN
      ASM_REWRITE_TAC[];
      ASM_MESON_TAC[DIVIDES_PRIME_PRIME]]]);;
