(* ========================================================================= *)
(* The decomposition law in the quadratic subfield of the cyclotomic field   *)
(* of an odd prime.                                                          *)
(*                                                                           *)
(* Let k = Q(z) be the cyclotomic field of an element z of odd prime order p *)
(* (number_field k, ring_order k z = p, subfield_generated k {z} = k), p* =  *)
(* (-1)^((p-1)/2) p and y in k with y^2 = p*, so that K = subfield_generated *)
(* k {y} is the quadratic subfield of k (CYCLOTOMIC_FIELD_QUADRATIC_SUBFIELD *)
(* of ANT/gauss_sum.ml). For a prime q <> p:                                 *)
(*                                                                           *)
(*   q splits completely in K iff q is a square mod p                        *)
(*                        (CYCLOTOMIC_QUADRATIC_SUBFIELD_TOTALLY_SPLIT)      *)
(*                                                                           *)
(* and for q odd, comparing with the decomposition law of the quadratic      *)
(* field K, generated by a square root of p*, both descriptions together     *)
(* (CYCLOTOMIC_QUADRATIC_SUBFIELD_DECOMPOSITION):                            *)
(*                                                                           *)
(*   q splits completely in K iff q is a square mod p                        *)
(*                            iff p* is a square mod q                       *)
(*                                                                           *)
(* This is the quadratic reciprocity law in the form of a decomposition law  *)
(* (the law itself is JACOBI_RECIPROCITY of Library/jacobi.ml).              *)
(*                                                                           *)
(* On the way: in a quadratic field Q(x), x^2 = d squarefree, d <> 1, an odd *)
(* prime q not dividing d splits completely iff d is a square mod q          *)
(* (QUADRATIC_FIELD_TOTALLY_SPLIT_ODD_PRIME, the form with totally_split of  *)
(* QUADRATIC_FIELD_ODD_PRIME of ANT/quadratic_split.ml).                     *)
(*                                                                           *)
(* Routes. Splitting: q splits completely in K iff the automorphism z |->    *)
(* z^q fixes y (CYCLOTOMIC_SUBFIELD_SPLITTING_TYPES of                       *)
(* ANT/cyclotomic_subfield_split.ml); y = g or y = -g (QUADRATIC_GAUSS_SUM,  *)
(* INTEGRAL_DOMAIN_SQUARE_EQ), so it maps y to (q/p) y                       *)
(* (QUADRATIC_GAUSS_SUM_HOMOMORPHISM of ANT/gauss_sum.ml), and y <> -y in    *)
(* characteristic 0; (q/p) = 1 iff q is a square mod p (JACOBI_PRIME).       *)
(* Quadratic fields: totally split primes are not inert                      *)
(* (NUMBER_FIELD_SPLITTING_TYPES_EXCLUSIVE), and q O = P Q with P <> Q makes *)
(* P and Q the only primes above q (IDEAL_PROD_SUBSET_PRIME_IDEAL), so their *)
(* number is the degree 2 (NUMBER_FIELD_TOTALLY_SPLIT_CARD).                 *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml, Library/jacobi.ml    *)
(* (jacobi, JACOBI_PRIME), Library/galois.ml (galois_group),                 *)
(* ANT/ideal_arith.ml, ANT/dedekind.ml, ANT/numfield.ml,                     *)
(* ANT/ring_of_integers.ml, ANT/prime_split.ml, ANT/splitting_types.ml,      *)
(* ANT/quadratic.ml, ANT/quadratic_split.ml, ANT/cyclotomic_galois.ml,       *)
(* ANT/cyclotomic_subfield_split.ml and ANT/gauss_sum.ml.                    *)
(* ========================================================================= *)

