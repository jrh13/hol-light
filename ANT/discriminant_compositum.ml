(* Inside a number field m Galois over Q: subfields K and L with coprime    *)
(* discriminants are linearly disjoint, [KL:Q] = [K:Q][L:Q].                *)
let NUMBER_FIELD_COMPOSITUM_DEGREE_GALOIS = prove
 (`!(m:A ring) s t.
        number_field m /\
        galois_extension(subfield_generated m {ring_0 m},m) I /\
        coprime(number_field_discriminant(subfield_generated m s),
                number_field_discriminant(subfield_generated m t))
        ==> extension_degree(subfield_generated m {ring_0 m},
                             subfield_generated m (s UNION t)) I =
            extension_degree(subfield_generated m {ring_0 m},
                             subfield_generated m s) I *
            extension_degree(subfield_generated m {ring_0 m},
                             subfield_generated m t) I`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [number_field]) THEN
  ABBREV_TAC `Q = subfield_generated m {ring_0 m:A}` THEN
  ABBREV_TAC `K = ring_carrier(subfield_generated m (s:A->bool))` THEN
  ABBREV_TAC `L = ring_carrier(subfield_generated m (t:A->bool))` THEN
  ABBREV_TAC `KL = ring_carrier(subfield_generated m (s UNION t:A->bool))` THEN
  ABBREV_TAC
   `N = UNIONS {IMAGE f L |
                f IN group_carrier(galois_group(Q,m) (I:A->A))}` THEN
  SUBGOAL_THEN
   `subfield_generated m (s:A->bool) = subfield_generated m K /\
    subfield_generated m (t:A->bool) = subfield_generated m L /\
    subfield_generated m (s UNION t:A->bool) = subfield_generated m KL`
  (fun th -> ONCE_REWRITE_TAC[th]) THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"; "KL"] THEN
    REWRITE_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_carrier Q SUBSET (K:A->bool) /\ ring_carrier Q SUBSET L /\
    K SUBSET KL /\ L SUBSET KL /\
    K SUBSET ring_carrier m /\ L SUBSET ring_carrier m /\
    KL SUBSET ring_carrier m`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["Q"; "K"; "L"; "KL"] THEN
    REWRITE_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET] THEN
    REPEAT CONJ_TAC THENL
     [MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
      SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; SING_SUBSET;
               ASSUME `field(m:A ring)`; RING_0_IN_SUBFIELD_GENERATED];
      MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
      SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; SING_SUBSET;
