(* ========================================================================= *)
(* Composita of number fields with coprime discriminants.                    *)
(*                                                                           *)
(* Let k be a number field generated by two subfields K = subfield_generated *)
(* k s and L = subfield_generated k t (subfield_generated k (s UNION t) =    *)
(* k), Q = subfield_generated k {ring_0 k}, with coprime discriminants d_K   *)
(* and d_L (number_field_discriminant). Then [k:Q] = [K:Q] [L:Q]             *)
(* (NUMBER_FIELD_COMPOSITUM_DEGREE_COPRIME, for any number field k, with the *)
(* subfield generated by s UNION t in place of k), and (Marcus, Number       *)
(* Fields, Theorem 12; Neukirch, Algebraic Number Theory, III.2):            *)
(*                                                                           *)
(*   for integral bases e_0, ..., e_(n-1) of O_K and f_0, ..., f_(m-1) of    *)
(*   O_L the products e_i f_j (indexed by u = i + n j, i = u MOD n,          *)
(*   j = u DIV n) form an integral basis of O_k                              *)
(*                           (NUMBER_FIELD_COMPOSITUM_INTEGRAL_BASIS), and   *)
(*   d_k = d_K^[L:Q] d_L^[K:Q]        (NUMBER_FIELD_COMPOSITUM_DISCRIMINANT) *)
(*   O_k = O_K O_L, the subring generated by O_K and O_L                     *)
(*                           (NUMBER_FIELD_COMPOSITUM_RING_OF_INTEGERS)      *)
(*   p ramifies in k iff p ramifies in K or in L                             *)
(*                           (NUMBER_FIELD_COMPOSITUM_RAMIFIED)              *)
(*                                                                           *)
(* This generalizes CYCLOTOMIC_FIELD_DISCRIMINANT_COMPOSITUM of              *)
(* ANT/cyclotomic_integers.ml. The inequality [k:Q] <= [K:Q] [L:Q] holds for *)
(* any k generated by K and L (NUMBER_FIELD_COMPOSITUM_DEGREE_LE). Along the *)
(* way: the products of Q-bases of K and L span k over Q                     *)
(* (NUMBER_FIELD_COMPOSITUM_PRODUCT_SPAN), so they form a Q-basis of k when  *)
(* [k:Q] = [K:Q] [L:Q] (NUMBER_FIELD_COMPOSITUM_PRODUCT_BASIS), with         *)
(* discriminant disc(e)^m disc(f)^n (BASIS_DISCRIMINANT_PRODUCT_BASIS); an   *)
(* integral basis of a subfield is a Q-basis in O_k with discriminant d_K    *)
(* (NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) and the Q-coordinates in it of the *)
(* elements of O_k are integers                                              *)
(* (NUMBER_FIELD_SUBFIELD_INTEGRAL_COORDINATES); there are [K:Q]             *)
(* homomorphisms of k into a field which agree with a monomorphism g on L    *)
(* and are distinct on K (NUMBER_FIELD_COMPOSITUM_HOMOMORPHISMS); the        *)
(* Q-coordinates c_ij of an element of O_k in the products e_i f_j satisfy   *)
(* d_K c_ij IN Z when [k:Q] = [K:Q] [L:Q]                                    *)
(* (NUMBER_FIELD_COMPOSITUM_COORDINATES).                                    *)
(*                                                                           *)
(* Routes. Degree: inside a Galois closure m of k                            *)
(* (NUMBER_FIELD_GALOIS_CLOSURE_Q of ANT/split_primes.ml, degrees and        *)
(* discriminants carried over by NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE of  *)
(* ANT/relative_split.ml) let N be the normal closure of L, the subfield     *)
(* generated by the conjugates of L; it is Galois over Q                     *)
(* (GALOIS_EXTENSION_GENERATED_CONJUGATES of Library/galois.ml) and has the  *)
(* same unramified primes as L (NUMBER_FIELD_NORMAL_CLOSURE_SPLITTING_TYPES  *)
(* of ANT/decomposition_field.ml). Every prime is unramified in K or in L,   *)
(* hence in K INTER N, so K INTER N = Q (NUMBER_FIELD_UNRAMIFIED_RATIONAL of *)
(* ANT/inertia_generators.ml: Q has no unramified extension). For N Galois,  *)
(* [KN:K] = [N:K INTER N] = [N:Q] and [KN:KL] = [N:N INTER KL]               *)
(* (GALOIS_COMPOSITUM_DEGREE), so the tower laws give [KL:K] = [N INTER      *)
(* KL:L] [L:Q] >= [L:Q] (NUMBER_FIELD_COMPOSITUM_DEGREE_GALOIS), and         *)
(* NUMBER_FIELD_COMPOSITUM_DEGREE_LE gives equality. Q-basis: the Q-span W   *)
(* of the products contains every x y with x in K and y in L, so it is a     *)
(* subring; inverses of the algebraic elements of W are polynomials in them, *)
(* so W is a subfield containing K and L, hence W = k, so [k:Q] <= nm        *)
(* (RING_INDEPENDENT_LE_SPAN), and nm spanning vectors in a space of         *)
(* dimension nm are a basis (FREE_BASIS_SPANNING_DEGREE). Discriminant of    *)
(* the product basis: Tr(x y) = Tr(x) Tr(y) for x in K and y in L            *)
(* (ALGEBRA_TRACE_PRODUCT_BASIS), so the trace matrix is a Kronecker product *)
(* (RING_DET_KRONECKER_MOD_DIV). Integrality (Marcus): write alpha in O_k as *)
(* sum_i x_i e_i with x_i in L and apply the [K:Q] homomorphisms sig_r,      *)
(* which extend g restricted to L (HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS,    *)
(* [k:L] = [K:Q]); the Cramer rule over a subring (RING_DET_CRAMER_SUBRING   *)
(* of Library/ring_det.ml) for the matrix A = (sig_r(e_i)) with              *)
(* det(A)^2 = g(d_K) (NUMBER_FIELD_DISCRIMINANT_HOMOMORPHISMS) shows that    *)
(* g(d_K x_i) is integral, so d_K x_i is in O_L and has integer coordinates  *)
(* in f. By symmetry d_L c_ij is an integer too, and a Bezout relation u d_K *)
(* + v d_L = 1 makes c_ij an integer. Ramification:                          *)
(* NUMBER_FIELD_RAMIFIED_DISCRIMINANT of ANT/ramification.ml and the         *)
(* discriminant formula.                                                     *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml (subfield_generated,  *)
(* extension_degree, ring homomorphism extensions, algebraic closures,       *)
(* EXTENSION_DEGREE_SUBFIELD_TOWER,                                          *)
(* FIELD_EXTENSION_SUBFIELD_GENERATED_SUBSET, SUBFIELD_GENERATED_SUBSET_EQ,  *)
(* RING_SUM_SUBFIELD_GENERATED), Library/ring_det.ml (ring_det, free_basis,  *)
(* basis_discriminant, algebra_trace, RING_DET_KRONECKER_MOD_DIV,            *)
(* RING_DET_CRAMER_SUBRING, RING_SUM_PRODUCT_INDEX),                         *)
(* Library/integer.ml (Bezout), Library/prime.ml, Library/primitive.ml       *)
(* (INT_PRIME), Library/galois.ml (GALOIS_COMPOSITUM_DEGREE, the Galois      *)
(* correspondence for normal subextensions,                                  *)
(* GALOIS_EXTENSION_GENERATED_CONJUGATES), ANT/integral.ml,                  *)
(* ANT/numfield.ml, ANT/ring_of_integers.ml (RING_OF_INTEGERS_FREE),         *)
(* ANT/discriminant.ml, ANT/ramification.ml                                  *)
(* (NUMBER_FIELD_RAMIFIED_DISCRIMINANT), ANT/relative_split.ml               *)
(* (RING_OF_INTEGERS_SUBFIELD_GENERATED, NUMBER_FIELD_SUBFIELD_GENERATED,    *)
(* NUMBER_FIELD_TOWER_LAW, NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE),         *)
(* ANT/power_basis.ml (NUMBER_FIELD_DISCRIMINANT_HOMOMORPHISMS,              *)
(* ALGEBRA_TRACE_PRODUCT_BASIS), ANT/splitting_types.ml,                     *)
(* ANT/decomposition_field.ml, ANT/split_primes.ml and                       *)
(* ANT/inertia_generators.ml.                                                *)
