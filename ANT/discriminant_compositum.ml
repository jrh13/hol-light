(* An integral basis of a subfield K = subfield_generated k s of a number    *)
(* field k is a Q-basis of K in O_k whose discriminant is the image of d_K. *)
let NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS = prove
 (`!(k:A ring) s n e.
        number_field k /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k s))
                   (ring_of_int(subfield_generated k s)) n e
        ==> number_field(subfield_generated k s) /\
            extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k s) I = n /\
            free_basis (subfield_generated k {ring_0 k},subfield_generated k s)
                       I n e /\
            (!i. i < n ==> e i IN ring_carrier(subfield_generated k s)) /\
            (!i. i < n ==> e i IN ring_carrier(ring_of_integers k)) /\
            ring_of_int k (number_field_discriminant(subfield_generated k s)) =
            basis_discriminant (subfield_generated k {ring_0 k},
                                subfield_generated k s) I n e`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `number_field(subfield_generated k (s:A->bool))` ASSUME_TAC
  THENL [ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED]; ASM_REWRITE_TAC[]] THEN
  MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `n:num`; `e:num->A`]
    RING_OF_INTEGERS_FREE_BASIS_FIELD) THEN
  MP_TAC(ISPECL [`subfield_generated k (s:A->bool)`; `n:num`; `e:num->A`]
    NUMBER_FIELD_DISCRIMINANT_BASIS_FIELD) THEN
  ASM_REWRITE_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED;
                  RING_OF_INT_SUBFIELD_GENERATED] THEN
  DISCH_THEN SUBST1_TAC THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FREE_BASIS_IN_CARRIER o
    check (fun th -> can (find_term ((=) `integer_ring`)) (concl th))) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[RING_OF_INTEGERS_SUBFIELD_GENERATED;
                              IN_INTER]) THEN
  ASM_SIMP_TAC[]);;


(* For an integral basis f of a subfield L of a number field k, an element  *)
(* of O_k in L whose coordinates in f over Q are c has integer c_j.         *)
let NUMBER_FIELD_SUBFIELD_INTEGRAL_COORDINATES = prove
 (`!(k:A ring) t m f c.
        number_field k /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k t))
                   (ring_of_int(subfield_generated k t)) m f /\
        (!j. j < m ==> c j IN ring_carrier(subfield_generated k {ring_0 k})) /\
        ring_sum k {j | j < m} (\j. ring_mul k (c j) (f j)) IN
        ring_carrier(ring_of_integers k)
        ==> !j. j < m ==> ?w. c j = ring_of_int k w`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `t:A->bool`; `m:num`; `f:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `ring_carrier(subfield_generated k t) subfield_of (k:A ring) /\
    ring_carrier(subfield_generated k {ring_0 k}) SUBSET
    ring_carrier(subfield_generated k (t:A->bool))`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED] THEN
    MATCH_MP_TAC PRIME_SUBFIELD_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  ABBREV_TAC
   `z = ring_sum k {j | j < m} (\j. ring_mul k (c j) ((f:num->A) j))` THEN
  ABBREV_TAC `L = subfield_generated k (t:A->bool)` THEN
  ABBREV_TAC `q = subfield_generated k {ring_0 k:A}` THEN
  SUBGOAL_THEN
   `ring_mul L = ring_mul (k:A ring) /\ ring_of_int L = ring_of_int k /\
    ring_mul (ring_of_integers L) = ring_mul k`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "L" THEN
    REWRITE_TAC[SUBFIELD_GENERATED; RING_OF_INT_SUBFIELD_GENERATED;
                RING_OF_INTEGERS];
    ALL_TAC] THEN
  SUBGOAL_THEN `!j. j < m ==> (f:num->A) j IN ring_carrier(ring_of_integers L)`
  ASSUME_TAC THENL
   [FIRST_ASSUM(ACCEPT_TAC o MATCH_MP FREE_BASIS_IN_CARRIER o check (fun th ->
      can (find_term ((=) `integer_ring`)) (concl th)));
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x:A. x IN ring_carrier(ring_of_integers L) ==> x IN ring_carrier L`
  ASSUME_TAC THENL
   [MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `(z:A) IN ring_carrier(ring_of_integers L)` ASSUME_TAC THENL
   [EXPAND_TAC "L" THEN
    REWRITE_TAC[RING_OF_INTEGERS_SUBFIELD_GENERATED; IN_INTER] THEN
    ASM_REWRITE_TAC[] THEN EXPAND_TAC "z" THEN
    MATCH_MP_TAC IN_SUBFIELD_SUM THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `j:num` THEN REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`ring_of_int L:int->A`; `integer_ring`;
                 `ring_of_integers L:A ring`; `m:num`; `f:num->A`; `z:A`]
    BASIS_COORDINATES) THEN
  ASM_REWRITE_TAC[INTEGER_RING; IN_UNIV] THEN
  ABBREV_TAC
   `w = basis_coordinates (integer_ring,ring_of_integers L)
          (ring_of_int k) m (f:num->A) z` THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `!j. j < m
        ==> ring_mul k (ring_of_int k ((w:num->int) j)) ((f:num->A) j) IN
            ring_carrier(ring_of_integers L)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    SUBGOAL_THEN
     `ring_of_int k ((w:num->int) j):A IN ring_carrier(ring_of_integers L)`
    ASSUME_TAC THENL
     [FIRST_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        concl th = `ring_of_int L = ring_of_int (k:A ring)`)) THEN
      REWRITE_TAC[RING_OF_INT_IN_RING_OF_INTEGERS];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`ring_of_integers L:A ring`;
                   `ring_of_int k ((w:num->int) j):A`; `(f:num->A) j`]
      RING_MUL) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sum L {j | j < m}
      (\j. ring_mul k (ring_of_int k ((w:num->int) j)) ((f:num->A) j)) =
    z`
  ASSUME_TAC THENL
   [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) && rhs(concl th) = `z:A` &&
      can (find_term ((=) `ring_of_integers L:A ring`)) (concl th))) THEN
    ASM_REWRITE_TAC[I_THM] THEN
    MP_TAC(ISPECL [`L:A ring`; `{j:num | j < m}`;
                   `\j. ring_mul k (ring_of_int k ((w:num->int) j))
                                   ((f:num->A) j)`]
      RING_SUM_RING_OF_INTEGERS) THEN
    ANTS_TAC THENL [ASM_SIMP_TAC[IN_ELIM_THM]; DISCH_THEN SUBST1_TAC] THEN
    REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sum L {j | j < m} (\j. ring_mul k (c j) ((f:num->A) j)) = z`
  ASSUME_TAC THENL
   [ASM_REWRITE_TAC[I_THM] THEN
    FIRST_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) && rhs(concl th) = `z:A` &&
      can (find_term ((=) `c:num->A`)) (concl th))) THEN
    EXPAND_TAC "L" THEN MATCH_MP_TAC RING_SUM_SUBFIELD_GENERATED THEN
    REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
    REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `L:A ring`; `m:num`; `f:num->A`;
                 `z:A`; `c:num->A`] BASIS_COORDINATES_UNIQUE) THEN
  MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `L:A ring`; `m:num`; `f:num->A`;
                 `z:A`; `\j. ring_of_int k ((w:num->int) j):A`]
    BASIS_COORDINATES_UNIQUE) THEN
  ASM_REWRITE_TAC[I_THM] THEN
  SUBGOAL_THEN `ring_homomorphism(q,L) (I:A->A)` (fun th -> REWRITE_TAC[th])
  THENL
   [MAP_EVERY EXPAND_TAC ["q"; "L"] THEN
    GEN_REWRITE_TAC (RATOR_CONV o RAND_CONV o LAND_CONV)
     [GSYM(ISPECL [`k:A ring`; `t:A->bool`]
        PRIME_SUBFIELD_SUBFIELD_GENERATED)] THEN
    REWRITE_TAC[RING_HOMOMORPHISM_SUBFIELD_INCLUSION];
    ALL_TAC] THEN
  EXPAND_TAC "q" THEN REWRITE_TAC[RING_OF_INT_IN_SUBFIELD_GENERATED] THEN
  ASM_SIMP_TAC[] THEN MESON_TAC[]);;


