    ALL_TAC] THEN
  ASM_SIMP_TAC[] THEN
  MAP_EVERY X_GEN_TAC [`i:num`; `j:num`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `(sig:num->A->A#num) i = sig j` MP_TAC THENL
   [MATCH_MP_TAC EXTENSIONAL_EQ THEN EXISTS_TAC `ring_carrier k:A->bool` THEN
    ASM_SIMP_TAC[] THEN
    MP_TAC(ISPECL [`(sig:num->A->A#num) i`; `(sig:num->A->A#num) j`;
                   `k:A ring`; `l:(A#num)ring`; `s UNION t:A->bool`]
      RING_HOMOMORPHISMS_EQ_FROM_SUBFIELD_GENERATED) THEN
    ASM_SIMP_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN
    X_GEN_TAC `x:A` THEN REWRITE_TAC[IN_UNION] THEN STRIP_TAC THENL
     [FIRST_X_ASSUM MATCH_MP_TAC THEN
      MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN ASM_REWRITE_TAC[];
      SUBGOAL_THEN `(x:A) IN ring_carrier(subfield_generated k t)`
      ASSUME_TAC THENL
       [MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN ASM_REWRITE_TAC[];
        ASM_SIMP_TAC[]]];
    ASM_MESON_TAC[]]);;


(* The key estimate (Marcus, Theorem 12): with [k:Q] = [K:Q][L:Q] and        *)
(* integral bases e of K and f of L, the Q-coordinates c_ij of an algebraic  *)
(* integer alpha = sum c_ij e_i f_j satisfy d_K c_ij IN Z. Write alpha =     *)
(* sum x_i e_i with x_i in L, apply the [K:Q] homomorphisms sig_r of k into  *)
(* an algebraic closure that agree with g on L and are distinct on K, and    *)
(* solve the system with the matrix A = (sig_r(e_i)) by Cramer: d_K = det(A) *)
(* squared, so g(d_K x_i) is integral, hence d_K x_i IN O_L, whose           *)
(* coordinates in f are integers.                                            *)
let NUMBER_FIELD_COMPOSITUM_COORDINATES = prove
 (`!(k:A ring) s t n m e f alpha c.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        extension_degree (subfield_generated k {ring_0 k},k) I = n * m /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k s))
                   (ring_of_int(subfield_generated k s)) n e /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k t))
                   (ring_of_int(subfield_generated k t)) m f /\
        alpha IN ring_carrier(ring_of_integers k) /\
        (!i j. i < n /\ j < m
               ==> c i j IN ring_carrier(subfield_generated k {ring_0 k})) /\
        alpha = ring_sum k {i | i < n}
                  (\i. ring_sum k {j | j < m}
                         (\j. ring_mul k (c i j) (ring_mul k (e i) (f j))))
        ==> !i j. i < n /\ j < m
                  ==> ?z. ring_mul k
                            (ring_of_int k (number_field_discriminant
                                              (subfield_generated k s)))
                            (c i j) =
                          ring_of_int k z`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `n:num`; `e:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  MP_TAC(ISPECL [`k:A ring`; `t:A->bool`; `m:num`; `f:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`]
    NUMBER_FIELD_COMPOSITUM_HOMOMORPHISMS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `l:(A#num)ring` (X_CHOOSE_THEN `g:A->A#num`
    (X_CHOOSE_THEN `sig:num->A->A#num` STRIP_ASSUME_TAC))) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN
   `ring_carrier(subfield_generated k s) subfield_of (k:A ring) /\
    ring_carrier(subfield_generated k t) subfield_of (k:A ring) /\
    ring_carrier(subfield_generated k {ring_0 k}) SUBSET
    ring_carrier(subfield_generated k (s:A->bool)) /\
    ring_carrier(subfield_generated k {ring_0 k}) SUBSET
    ring_carrier(subfield_generated k (t:A->bool))`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED] THEN CONJ_TAC THEN
    MATCH_MP_TAC PRIME_SUBFIELD_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`]
    PRIME_SUBFIELD_SUBFIELD_GENERATED) THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `!hh:A->A#num. ring_homomorphism(k,l) hh
                  ==> ring_homomorphism(subfield_generated k s,l) hh`
  ASSUME_TAC THENL
   [REWRITE_TAC[RING_HOMOMORPHISM_FROM_SUBFIELD_GENERATED]; ALL_TAC] THEN
  ABBREV_TAC `K = subfield_generated k (s:A->bool)` THEN
  ABBREV_TAC `L = subfield_generated k (t:A->bool)` THEN
  ABBREV_TAC `q = subfield_generated k {ring_0 k:A}` THEN
  ABBREV_TAC `d = number_field_discriminant (K:A ring)` THEN
  SUBGOAL_THEN
   `(!x:A. x IN ring_carrier K ==> x IN ring_carrier k) /\
    (!x:A. x IN ring_carrier L ==> x IN ring_carrier k) /\
    (!x:A. x IN ring_carrier q ==> x IN ring_carrier k)`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"; "q"] THEN
    MESON_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET; SUBSET];
    ALL_TAC] THEN
  ABBREV_TAC
   `x = \i. ring_sum k {j | j < m}
              (\j. ring_mul k ((c:num->num->A) i j) ((f:num->A) j))` THEN
  SUBGOAL_THEN `!i. i < n ==> (x:num->A) i IN ring_carrier L` ASSUME_TAC THENL
   [X_GEN_TAC `i:num` THEN DISCH_TAC THEN EXPAND_TAC "x" THEN
    REWRITE_TAC[] THEN MATCH_MP_TAC IN_SUBFIELD_SUM THEN
    ASM_REWRITE_TAC[] THEN X_GEN_TAC `j:num` THEN REWRITE_TAC[IN_ELIM_THM] THEN
    DISCH_TAC THEN MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sum k {i | i < n}
      (\i. ring_mul k ((x:num->A) i) ((e:num->A) i)) = alpha`
  ASSUME_TAC THENL
   [CONV_TAC SYM_CONV THEN FIRST_ASSUM(SUBST1_TAC o check (fun th ->
      is_eq(concl th) && lhs(concl th) = `alpha:A` &&
      can (find_term ((=) `c:num->num->A`)) (concl th))) THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN EXPAND_TAC "x" THEN
    REWRITE_TAC[] THEN
    W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_RMUL o rand o snd) THEN
    ANTS_TAC THENL
     [REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
      ASM_SIMP_TAC[] THEN REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN
      ASM_SIMP_TAC[];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `j:num` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN REWRITE_TAC[] THEN
    MATCH_MP_TAC(RING_RULE
     `ring_mul r c (ring_mul r e f) = ring_mul r (ring_mul r c f) (e:A)`) THEN
