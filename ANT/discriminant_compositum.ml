(* The discriminant of a product basis: with the trace of products x y,     *)
(* x in K and y in L, the product of the traces (ALGEBRA_TRACE_PRODUCT_     *)
(* BASIS), the trace matrix is a Kronecker product (RING_DET_KRONECKER_     *)
(* MOD_DIV).                                                                 *)
let BASIS_DISCRIMINANT_PRODUCT_BASIS = prove
 (`!(k:A ring) s t n m e f.
        field k /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k s)
                   I n e /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k t)
                   I m f /\
        free_basis (subfield_generated k {ring_0 k},k) I (n * m)
                   (\u. ring_mul k (e(u MOD n)) (f(u DIV n)))
        ==> basis_discriminant (subfield_generated k {ring_0 k},k) I (n * m)
              (\u. ring_mul k (e(u MOD n)) (f(u DIV n))) =
            ring_mul k
              (ring_pow k
                 (basis_discriminant (subfield_generated k {ring_0 k},
                                      subfield_generated k s) I n e) m)
              (ring_pow k
                 (basis_discriminant (subfield_generated k {ring_0 k},
                                      subfield_generated k t) I m f) n)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `!x y. x IN ring_carrier(subfield_generated k s) /\
          y IN ring_carrier(subfield_generated k t)
          ==> algebra_trace (subfield_generated k {ring_0 k},k) I
                (ring_mul k x y) =
              ring_mul k
                (algebra_trace (subfield_generated k {ring_0 k},
                                subfield_generated k s) I x)
                (algebra_trace (subfield_generated k {ring_0 k},
                                subfield_generated k t) I (y:A))`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC ALGEBRA_TRACE_PRODUCT_BASIS THEN
    MAP_EVERY EXISTS_TAC [`n:num`; `m:num`; `e:num->A`; `f:num->A`] THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC `q = subfield_generated k {ring_0 k:A}` THEN
  ABBREV_TAC `K = subfield_generated k (s:A->bool)` THEN
  ABBREV_TAC `L = subfield_generated k (t:A->bool)` THEN
  SUBGOAL_THEN
   `ring_mul q = ring_mul (k:A ring) /\ ring_pow q = ring_pow k /\
    ring_mul K = ring_mul k /\ ring_mul L = ring_mul k`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["q"; "K"; "L"] THEN
    REWRITE_TAC[CONJUNCT2 SUBFIELD_GENERATED; RING_POW_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(!i. i < n ==> (e:num->A) i IN ring_carrier K) /\
    (!j. j < m ==> (f:num->A) j IN ring_carrier L)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[FREE_BASIS_IN_CARRIER]; ALL_TAC] THEN
  MP_TAC(ISPECL
   [`q:A ring`; `n:num`; `m:num`;
    `\i j. algebra_trace (q,K) I (ring_mul K ((e:num->A) i) (e j))`;
    `\i j. algebra_trace (q,L) I (ring_mul L ((f:num->A) i) (f j))`]
    RING_DET_KRONECKER_MOD_DIV) THEN
  REWRITE_TAC[ALGEBRA_TRACE_NORM_IN_CARRIER] THEN
  ASM_REWRITE_TAC[basis_discriminant] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC RING_DET_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN
  MAP_EVERY X_GEN_TAC [`a:num`; `b:num`] THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `a MOD n < n /\ a DIV n < m /\ b MOD n < n /\ b DIV n < m`
  STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `~(n = 0)` ASSUME_TAC THENL
     [DISCH_THEN SUBST_ALL_TAC THEN ASM_ARITH_TAC; ALL_TAC] THEN
    ASM_SIMP_TAC[MOD_LT_EQ; RDIV_LT_EQ];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x:A. x IN ring_carrier K \/ x IN ring_carrier L
          ==> x IN ring_carrier k`
  ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"] THEN
    MESON_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET; SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul k (ring_mul k (e(a MOD n)) (f(a DIV n)))
               (ring_mul k (e(b MOD n)) (f(b DIV n))) =
    ring_mul k (ring_mul k ((e:num->A)(a MOD n)) (e(b MOD n)))
               (ring_mul k ((f:num->A)(a DIV n)) (f(b DIV n)))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC(RING_RULE
     `ring_mul r (ring_mul r a b) (ring_mul r c d) =
      ring_mul r (ring_mul r a c) (ring_mul r b (d:A))`) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
    is_forall(concl th) &&
    can (find_term ((=) `algebra_trace:(A ring#A ring)->(A->A)->A->A`))
        (concl th))) THEN
  CONJ_TAC THENL
   [MP_TAC(ISPECL [`K:A ring`; `(e:num->A)(a MOD n)`; `(e:num->A)(b MOD n)`]
      RING_MUL);
    MP_TAC(ISPECL [`L:A ring`; `(f:num->A)(a DIV n)`; `(f:num->A)(b DIV n)`]
      RING_MUL)] THEN
  ASM_SIMP_TAC[]);;


