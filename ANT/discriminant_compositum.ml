(* Product bases of a compositum and their discriminants.                    *)
(* ------------------------------------------------------------------------- *)

(* If k is generated by subfields K and L, the products of Q-bases of K and *)
(* L span k over Q: their Q-span W contains the products x y (x in K, y in  *)
(* L), so it is a subring, hence a subfield (inverses of algebraic elements *)
(* are polynomials), so W = k.                                               *)
let NUMBER_FIELD_COMPOSITUM_PRODUCT_SPAN = prove
 (`!(k:A ring) s t n m e f.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k s)
                   I n e /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k t)
                   I m f
        ==> !x. x IN ring_carrier k
                ==> ?c. (!u. u < n * m
                             ==> c u IN ring_carrier
                                          (subfield_generated k {ring_0 k})) /\
                        x = ring_sum k {u | u < n * m}
                              (\u. ring_mul k (c u)
                                     (ring_mul k (e(u MOD n)) (f(u DIV n))))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  SUBGOAL_THEN `~(n = 0) /\ ~(m = 0)` STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`;
                   `subfield_generated k (t:A->bool)`; `m:num`; `f:num->A`]
      FREE_BASIS_EXTENSION_DEGREE) THEN
    MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`;
                   `subfield_generated k (s:A->bool)`; `n:num`; `e:num->A`]
      FREE_BASIS_EXTENSION_DEGREE) THEN
    MP_TAC(ISPEC `subfield_generated k (t:A->bool)`
      NUMBER_FIELD_DEGREE_POS) THEN
    MP_TAC(ISPEC `subfield_generated k (s:A->bool)`
      NUMBER_FIELD_DEGREE_POS) THEN
    ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
                 PRIME_SUBFIELD_SUBFIELD_GENERATED;
                 FIELD_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD] THEN
    REWRITE_TAC[GEN_ALL(REWRITE_RULE[PRIME_SUBFIELD_SUBFIELD_GENERATED]
     (ISPECL [`subfield_generated k (u:A->bool)`;
              `{ring_0(subfield_generated k (u:A->bool))}`]
       RING_HOMOMORPHISM_SUBFIELD_INCLUSION))] THEN
    ARITH_TAC;
    ALL_TAC] THEN
  ABBREV_TAC `q = subfield_generated k {ring_0 k:A}` THEN
  ABBREV_TAC `K = subfield_generated k (s:A->bool)` THEN
  ABBREV_TAC `L = subfield_generated k (t:A->bool)` THEN
  SUBGOAL_THEN
   `ring_carrier K subfield_of (k:A ring) /\ ring_carrier L subfield_of k /\
    ring_carrier q subfield_of k`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"; "q"] THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_carrier q SUBSET ring_carrier K /\
    ring_carrier q SUBSET ring_carrier (L:A ring)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN CONJ_TAC THEN MATCH_MP_TAC PRIME_SUBFIELD_MINIMAL THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul K = ring_mul (k:A ring) /\ ring_mul L = ring_mul k`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"] THEN REWRITE_TAC[SUBFIELD_GENERATED];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(!i. i < n ==> (e:num->A) i IN ring_carrier K) /\
    (!j. j < m ==> (f:num->A) j IN ring_carrier L)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[FREE_BASIS_IN_CARRIER]; ALL_TAC] THEN
  SUBGOAL_THEN
   `(!x:A. x IN ring_carrier K ==> x IN ring_carrier k) /\
    (!x:A. x IN ring_carrier L ==> x IN ring_carrier k) /\
    (!x:A. x IN ring_carrier q ==> x IN ring_carrier k)`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"; "q"] THEN
    MESON_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET; SUBSET];
    ALL_TAC] THEN
  ABBREV_TAC
   `B = \u. ring_mul k ((e:num->A)(u MOD n)) (f(u DIV n))` THEN
  SUBGOAL_THEN
   `!u. u < n * m ==> u MOD n < n /\ u DIV n < m`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[MOD_LT_EQ; RDIV_LT_EQ]; ALL_TAC] THEN
  SUBGOAL_THEN `!u. u < n * m ==> (B:num->A) u IN ring_carrier k`
  ASSUME_TAC THENL
   [EXPAND_TAC "B" THEN REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN
    ASM_MESON_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC
   `W = {x:A | ?c. (!u. u < n * m:num ==> c u IN ring_carrier q) /\
                   x = ring_sum k {u | u < n * m}
                         (\u. ring_mul k (c u) (B u))}` THEN
  SUBGOAL_THEN `!x:A. x IN W ==> x IN ring_carrier k` ASSUME_TAC THENL
   [EXPAND_TAC "W" THEN REWRITE_TAC[IN_ELIM_THM] THEN
    REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[RING_SUM];
    ALL_TAC] THEN
  SUBGOAL_THEN `(ring_0 k:A) IN W` ASSUME_TAC THENL
   [EXPAND_TAC "W" THEN REWRITE_TAC[IN_ELIM_THM] THEN
    EXISTS_TAC `\u:num. ring_0 k:A` THEN REWRITE_TAC[] THEN CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_SUBFIELD_0 THEN
      ASM_REWRITE_TAC[];
      CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_SUM_EQ_0 THEN
      REWRITE_TAC[IN_ELIM_THM] THEN ASM_SIMP_TAC[RING_MUL_LZERO]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x y:A. x IN W /\ y IN W ==> ring_add k x y IN W`
  ASSUME_TAC THENL
   [EXPAND_TAC "W" THEN REWRITE_TAC[IN_ELIM_THM] THEN
    MAP_EVERY X_GEN_TAC [`x:A`; `y:A`] THEN
    DISCH_THEN(CONJUNCTS_THEN2 (X_CHOOSE_THEN `c:num->A` STRIP_ASSUME_TAC)
      (X_CHOOSE_THEN `d:num->A` STRIP_ASSUME_TAC)) THEN
    EXISTS_TAC `\u. ring_add k ((c:num->A) u) (d u)` THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_SUBFIELD_ADD THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `\u. ring_mul k ((c:num->A) u) (B u)`;
                   `\u. ring_mul k ((d:num->A) u) (B u)`;
                   `{u:num | u < n * m}`] RING_SUM_ADD) THEN
    ANTS_TAC THENL
     [REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
      MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    MATCH_MP_TAC RING_SUM_EQ THEN REWRITE_TAC[IN_ELIM_THM] THEN
    REPEAT STRIP_TAC THEN REWRITE_TAC[] THEN CONV_TAC SYM_CONV THEN
    MATCH_MP_TAC RING_ADD_RDISTRIB THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!(g:num->A) r. (!i. i IN r ==> g i IN W) ==> ring_sum k r g IN W`
  (LABEL_TAC "sum") THENL
   [REPEAT STRIP_TAC THEN
    MATCH_MP_TAC(REWRITE_RULE[] (ISPECL [`k:A ring`; `\x:A. x IN W`]
      RING_SUM_CLOSED)) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x y:A. x IN ring_carrier K /\ y IN ring_carrier L
            ==> ring_mul k x y IN W`
  (LABEL_TAC "prod") THENL
   [MAP_EVERY X_GEN_TAC [`x:A`; `y:A`] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `K:A ring`; `n:num`; `e:num->A`;
                   `x:A`] BASIS_COORDINATES) THEN
    MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `L:A ring`; `m:num`; `f:num->A`;
                   `y:A`] BASIS_COORDINATES) THEN
    ASM_REWRITE_TAC[I_THM] THEN
    ABBREV_TAC `b = basis_coordinates (q,L) (I:A->A) m f y` THEN
    ABBREV_TAC `a = basis_coordinates (q,K) (I:A->A) n e x` THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "y")) THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "x")) THEN
    SUBGOAL_THEN
     `x = ring_sum k {i | i < n} (\i. ring_mul k ((a:num->A) i) (e i)) /\
      y = ring_sum k {j | j < m} (\j. ring_mul k ((b:num->A) j) (f j))`
    (CONJUNCTS_THEN SUBST1_TAC) THENL
     [CONJ_TAC THENL
       [USE_THEN "x" (SUBST1_TAC o SYM) THEN EXPAND_TAC "K" THEN
        MATCH_MP_TAC RING_SUM_SUBFIELD_GENERATED THEN
        REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
        ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
        MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN ASM SET_TAC[];
        USE_THEN "y" (SUBST1_TAC o SYM) THEN EXPAND_TAC "L" THEN
        MATCH_MP_TAC RING_SUM_SUBFIELD_GENERATED THEN
        REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
        ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
        MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN ASM SET_TAC[]];
      ALL_TAC] THEN
    EXPAND_TAC "W" THEN REWRITE_TAC[IN_ELIM_THM] THEN
    EXISTS_TAC `\u. ring_mul k ((a:num->A)(u MOD n)) (b(u DIV n))` THEN
    REWRITE_TAC[] THEN CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_SUBFIELD_MUL THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    EXPAND_TAC "B" THEN REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`k:A ring`; `n:num`; `m:num`;
      `\i j. ring_mul k (ring_mul k ((a:num->A) i) ((b:num->A) j))
                        (ring_mul k ((e:num->A) i) ((f:num->A) j))`]
      RING_SUM_MOD_DIV) THEN
    REWRITE_TAC[] THEN ANTS_TAC THENL
     [REPEAT STRIP_TAC THEN REPEAT(MATCH_MP_TAC RING_MUL THEN CONJ_TAC) THEN
      ASM_SIMP_TAC[];
      DISCH_THEN SUBST1_TAC] THEN
    SUBGOAL_THEN
     `(!i. i < n ==> ring_mul k ((a:num->A) i) (e i) IN ring_carrier k) /\
      (!j. j < m ==> ring_mul k ((b:num->A) j) (f j) IN ring_carrier k)`
    STRIP_ASSUME_TAC THENL
     [CONJ_TAC THEN REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    TRANS_TAC EQ_TRANS
     `ring_sum k {j | j < m}
        (\j. ring_mul k (ring_sum k {i | i < n}
                           (\i. ring_mul k ((a:num->A) i) (e i)))
                        (ring_mul k ((b:num->A) j) (f j)))` THEN
    CONJ_TAC THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_SUM_LMUL THEN
      ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM; RING_SUM];
      MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `j:num` THEN
      REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN REWRITE_TAC[] THEN
      W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_RMUL o lhand o snd) THEN
      ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
      REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN REWRITE_TAC[] THEN
      MATCH_MP_TAC(RING_RULE
       `ring_mul r (ring_mul r a e) (ring_mul r b f) =
        ring_mul r (ring_mul r a b) (ring_mul r e (f:A))`) THEN
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!a:A. a IN ring_carrier q ==> a IN W`
  ASSUME_TAC THENL
   [X_GEN_TAC `a:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `a = ring_mul k a (ring_1 k:A)` SUBST1_TAC THENL
     [CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_MUL_RID THEN ASM_SIMP_TAC[];
      USE_THEN "prod" MATCH_MP_TAC THEN CONJ_TAC THENL
       [ASM SET_TAC[]; MATCH_MP_TAC IN_SUBFIELD_1 THEN ASM_REWRITE_TAC[]]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!x y z:A. x IN ring_carrier K /\ y IN ring_carrier L /\ z IN W
              ==> ring_mul k (ring_mul k x y) z IN W`
  ASSUME_TAC THENL
   [MAP_EVERY X_GEN_TAC [`x:A`; `y:A`; `z:A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN
     `?d. (!u. u < n * m ==> d u IN ring_carrier q) /\
          z = ring_sum k {u | u < n * m}
                (\u. ring_mul k (d u) ((B:num->A) u))`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `(z:A) IN W` THEN EXPAND_TAC "W" THEN
      REWRITE_TAC[IN_ELIM_THM];
      ALL_TAC] THEN
    FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
      is_eq(concl th) && lhs(concl th) = `z:A`)) THEN
    W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_LMUL o lhand o snd) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM; RING_MUL] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    USE_THEN "sum" MATCH_MP_TAC THEN
    X_GEN_TAC `u:num` THEN REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    EXPAND_TAC "B" THEN REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `ring_mul k (ring_mul k x y)
        (ring_mul k ((d:num->A) u) (ring_mul k (e(u MOD n)) (f(u DIV n)))) =
      ring_mul k (ring_mul k x (ring_mul k (d u) (e(u MOD n))))
                 (ring_mul k y (f(u DIV n)))`
    SUBST1_TAC THENL
     [MATCH_MP_TAC(RING_RULE
       `ring_mul r (ring_mul r x y) (ring_mul r d (ring_mul r e f)) =
        ring_mul r (ring_mul r x (ring_mul r d e)) (ring_mul r y (f:A))`) THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    USE_THEN "prod" MATCH_MP_TAC THEN
    SUBGOAL_THEN `u MOD n < n /\ u DIV n < m` STRIP_ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN
      FIRST_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET] o check (fun th ->
        concl th = `ring_carrier q SUBSET ring_carrier (K:A ring)`)) THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `!x z:A. x IN W /\ z IN W ==> ring_mul k x z IN W`
  ASSUME_TAC THENL
   [MAP_EVERY X_GEN_TAC [`x:A`; `z:A`] THEN STRIP_TAC THEN
    SUBGOAL_THEN
     `?c. (!u. u < n * m ==> c u IN ring_carrier q) /\
          x = ring_sum k {u | u < n * m}
                (\u. ring_mul k (c u) ((B:num->A) u))`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `(x:A) IN W` THEN EXPAND_TAC "W" THEN
      REWRITE_TAC[IN_ELIM_THM];
      ALL_TAC] THEN
    FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
      is_eq(concl th) && lhs(concl th) = `x:A`)) THEN
    W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_RMUL o lhand o snd) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM] THEN
      REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN ASM_SIMP_TAC[];
      DISCH_THEN(SUBST1_TAC o SYM)] THEN
    USE_THEN "sum" MATCH_MP_TAC THEN
    X_GEN_TAC `u:num` THEN REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN
    SUBGOAL_THEN `u MOD n < n /\ u DIV n < m` STRIP_ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    EXPAND_TAC "B" THEN REWRITE_TAC[] THEN
    SUBGOAL_THEN
     `ring_mul k (ring_mul k ((c:num->A) u)
                    (ring_mul k (e(u MOD n)) (f(u DIV n)))) z =
      ring_mul k (ring_mul k (ring_mul k (c u) (e(u MOD n))) (f(u DIV n)))
                 (z:A)`
    SUBST1_TAC THENL
     [AP_THM_TAC THEN AP_TERM_TAC THEN
      MATCH_MP_TAC(RING_RULE
       `ring_mul r c (ring_mul r e f) = ring_mul r (ring_mul r c e) (f:A)`) THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
      is_forall(concl th) && length(fst(strip_forall(concl th))) = 3)) THEN
    ASM_SIMP_TAC[] THEN MATCH_MP_TAC IN_SUBFIELD_MUL THEN ASM_SIMP_TAC[] THEN
    FIRST_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET] o check (fun th ->
      concl th = `ring_carrier q SUBSET ring_carrier (K:A ring)`)) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(W:A->bool) subring_of k` ASSUME_TAC THENL
   [REWRITE_TAC[subring_of] THEN ASM_SIMP_TAC[SUBSET] THEN
    SUBGOAL_THEN `ring_1 k IN ring_carrier q /\ ring_neg k (ring_1 k:A) IN
                  ring_carrier q`
    STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL
       [MATCH_MP_TAC IN_SUBFIELD_1 THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC IN_SUBFIELD_NEG THEN ASM_REWRITE_TAC[] THEN
        MATCH_MP_TAC IN_SUBFIELD_1 THEN ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    ASM_SIMP_TAC[] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `ring_neg k x = ring_mul k (ring_neg k (ring_1 k)) (x:A)`
    SUBST1_TAC THENL
     [CONV_TAC SYM_CONV THEN
      MATCH_MP_TAC(RING_RULE
       `ring_mul r (ring_neg r (ring_1 r)) x = ring_neg r (x:A)`) THEN
      ASM_SIMP_TAC[];
      FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
        is_forall(concl th) && length(fst(strip_forall(concl th))) = 2 &&
        can (find_term ((=) `ring_mul:(A ring)->A->A->A`)) (concl th) &&
        not(can (find_term ((=) `K:A ring`)) (concl th)))) THEN
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `(W:A->bool) subfield_of k` ASSUME_TAC THENL
   [MATCH_MP_TAC SUBFIELD_OF_FIELD_INV THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    ASM_CASES_TAC `x = ring_0 (k:A ring)` THEN
    ASM_REWRITE_TAC[RING_INV_0] THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
     [ASM_SIMP_TAC[]; ALL_TAC] THEN
    MP_TAC(ISPECL [`I:A->A`; `q:A ring`; `k:A ring`; `x:A`]
      SUBFIELD_GENERATED_SIMPLE_ALGEBRAIC) THEN
    ANTS_TAC THENL
     [EXPAND_TAC "q" THEN
      ASM_SIMP_TAC[NUMBER_FIELD_ALGEBRAIC; FIELD_EXTENSION_SUBFIELD_GENERATED];
      DISCH_THEN(ASSUME_TAC o CONJUNCT1)] THEN
    MATCH_MP_TAC(SET_RULE
     `!t. y IN t /\ t SUBSET W ==> (y:A) IN W`) THEN
    EXISTS_TAC
     `ring_carrier(subring_generated k
        ((x:A) INSERT IMAGE I (ring_carrier q)))` THEN
    CONJ_TAC THENL
     [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC IN_SUBFIELD_INV THEN
      ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED] THEN
      MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
      ASM_REWRITE_TAC[IN_INSERT];
      MATCH_MP_TAC SUBRING_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[] THEN
      REWRITE_TAC[INSERT_SUBSET; IMAGE_I] THEN ASM_SIMP_TAC[SUBSET]];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_carrier k SUBSET (W:A->bool)` ASSUME_TAC THENL
   [FIRST_X_ASSUM((fun th ->
      GEN_REWRITE_TAC (LAND_CONV o RAND_CONV) [SYM th]) o check (fun th ->
        concl th = `subfield_generated k (s UNION t) = (k:A ring)`)) THEN
    ONCE_REWRITE_TAC[SUBFIELD_GENERATED_RESTRICT] THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[SUBSET; IN_INTER; IN_UNION] THEN X_GEN_TAC `x:A` THEN
    STRIP_TAC THENL
     [SUBGOAL_THEN `(x:A) IN ring_carrier K` ASSUME_TAC THENL
       [EXPAND_TAC "K" THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
        ASM_REWRITE_TAC[];
        ALL_TAC] THEN
      SUBGOAL_THEN `x = ring_mul k x (ring_1 k:A)` SUBST1_TAC THENL
       [CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_MUL_RID THEN
        ASM_REWRITE_TAC[];
        USE_THEN "prod" MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
        MATCH_MP_TAC IN_SUBFIELD_1 THEN ASM_REWRITE_TAC[]];
      SUBGOAL_THEN `(x:A) IN ring_carrier L` ASSUME_TAC THENL
       [EXPAND_TAC "L" THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
        ASM_REWRITE_TAC[];
        ALL_TAC] THEN
      SUBGOAL_THEN `x = ring_mul k (ring_1 k) (x:A)` SUBST1_TAC THENL
       [CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_MUL_LID THEN
        ASM_REWRITE_TAC[];
        USE_THEN "prod" MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
        MATCH_MP_TAC IN_SUBFIELD_1 THEN ASM_REWRITE_TAC[]]];
    ALL_TAC] THEN
  X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(x:A) IN W` MP_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  EXPAND_TAC "W" THEN EXPAND_TAC "B" THEN REWRITE_TAC[IN_ELIM_THM]);;


(* With [k:Q] = [K:Q][L:Q] the products form a Q-basis of k.                *)
let NUMBER_FIELD_COMPOSITUM_PRODUCT_BASIS = prove
 (`!(k:A ring) s t n m e f.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k s)
                   I n e /\
        free_basis (subfield_generated k {ring_0 k},subfield_generated k t)
                   I m f /\
        extension_degree (subfield_generated k {ring_0 k},k) I = n * m
        ==> free_basis (subfield_generated k {ring_0 k},k) I (n * m)
              (\u. ring_mul k (e(u MOD n)) (f(u DIV n)))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                 `e:num->A`; `f:num->A`]
    NUMBER_FIELD_COMPOSITUM_PRODUCT_SPAN) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MATCH_MP_TAC FREE_BASIS_SPANNING_DEGREE THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; NUMBER_FIELD_IMP_FIELD;
               RING_HOMOMORPHISM_SUBFIELD_INCLUSION; I_THM] THEN
  X_GEN_TAC `u:num` THEN DISCH_TAC THEN MATCH_MP_TAC RING_MUL THEN
  SUBGOAL_THEN `~(n = 0)` ASSUME_TAC THENL
   [UNDISCH_TAC `u < n * m:num` THEN ASM_CASES_TAC `n = 0` THEN
    ASM_REWRITE_TAC[MULT_CLAUSES; LT];
    ALL_TAC] THEN
  SUBGOAL_THEN `u MOD n < n /\ u DIV n < m` STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[MOD_LT_EQ; RDIV_LT_EQ]; ALL_TAC] THEN
  CONJ_TAC THEN MATCH_MP_TAC(SET_RULE
   `!t. x IN t /\ t SUBSET ring_carrier(k:A ring)
        ==> x IN ring_carrier k`) THENL
   [EXISTS_TAC `ring_carrier(subfield_generated k (s:A->bool))`;
    EXISTS_TAC `ring_carrier(subfield_generated k (t:A->bool))`] THEN
  REWRITE_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET] THEN
  FIRST_ASSUM(MATCH_MP_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
  ASM_REWRITE_TAC[]);;


(* The degree of a compositum: [k:Q] <= [K:Q][L:Q].                         *)
let NUMBER_FIELD_COMPOSITUM_DEGREE_LE = prove
 (`!(k:A ring) s t.
        number_field k /\ subfield_generated k (s UNION t) = k
        ==> extension_degree (subfield_generated k {ring_0 k},k) I <=
            extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k s) I *
            extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k t) I`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `subfield_generated k (s:A->bool)` RING_OF_INTEGERS_FREE) THEN
  MP_TAC(ISPEC `subfield_generated k (t:A->bool)` RING_OF_INTEGERS_FREE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  ABBREV_TAC
   `n = extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k s) (I:A->A)` THEN
  ABBREV_TAC
   `m = extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k t) (I:A->A)` THEN
  DISCH_THEN(X_CHOOSE_TAC `f:num->A`) THEN
  DISCH_THEN(X_CHOOSE_TAC `e:num->A`) THEN
  MP_TAC(ISPECL [`k:A ring`; `t:A->bool`; `m:num`; `f:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `n:num`; `e:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                 `e:num->A`; `f:num->A`]
    NUMBER_FIELD_COMPOSITUM_PRODUCT_SPAN) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  ASSUME_TAC(MATCH_MP NUMBER_FIELD_IMP_FIELD
    (ASSUME `number_field(k:A ring)`)) THEN
  ABBREV_TAC `q = subfield_generated k {ring_0 k:A}` THEN
  SUBGOAL_THEN
   `field(q:A ring) /\ ring_homomorphism(q,k) (I:A->A) /\
    (!a:A. a IN ring_carrier q ==> a IN ring_carrier k)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN
    SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
             ASSUME `field(k:A ring)`] THEN
    REWRITE_TAC[GSYM SUBSET; RING_CARRIER_SUBFIELD_GENERATED_SUBSET];
    ALL_TAC] THEN
  ABBREV_TAC
