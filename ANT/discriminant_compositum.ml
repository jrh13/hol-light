               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  ABBREV_TAC `a = extension_degree (subfield_generated m K,
                                    subfield_generated m (KL:A->bool)) I` THEN
  ABBREV_TAC `b = extension_degree
                    (subfield_generated m (ring_carrier Nf INTER (KL:A->bool)),
