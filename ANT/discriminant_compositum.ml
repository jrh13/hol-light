  SUBGOAL_THEN
   `subfield_generated (m:A ring) (ring_carrier Q) = Q`
  ASSUME_TAC THENL
   [EXPAND_TAC "Q" THEN REWRITE_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `Q:A ring`; `m:A ring`; `L:A->bool`]
