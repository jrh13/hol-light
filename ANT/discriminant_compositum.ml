    HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS) THEN
  ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
   [ASM_SIMP_TAC[RING_HOMOMORPHISM_FROM_SUBFIELD_GENERATED] THEN
    MATCH_MP_TAC SEPARABLE_EXTENSION_CHAR0 THEN
    ASM_SIMP_TAC[FINITE_IMP_ALGEBRAIC_EXTENSION; RING_CHAR_SUBFIELD_GENERATED];
    ALL_TAC] THEN
  DISCH_THEN(MP_TAC o MATCH_MP HAS_SIZE_INDEX) THEN
  REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
