      MATCH_MP_TAC SUBFIELD_GENERATED_MONO THEN FIRST_ASSUM ACCEPT_TAC];
    ASM_REWRITE_TAC[] THEN DISCH_TAC] THEN
  MP_TAC(ISPECL [`m:A ring`; `{ring_0 m:A}`; `K:A->bool`; `KL:A->bool`]
