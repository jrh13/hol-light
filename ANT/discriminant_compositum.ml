  ABBREV_TAC
   `m = extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k t) (I:A->A)` THEN
  MP_TAC(ISPEC `k:A ring` ALGEBRAIC_CLOSURE_EXISTS_BIGENOUGH) THEN
  ASM_REWRITE_TAC[algebraic_extension; field_extension] THEN
  DISCH_THEN(X_CHOOSE_THEN `l:(A#num)ring` (X_CHOOSE_THEN `g:A->A#num`
    STRIP_ASSUME_TAC)) THEN
  MAP_EVERY EXISTS_TAC [`l:(A#num)ring`; `g:A->A#num`] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP ALGEBRAICALLY_CLOSED_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`subfield_generated k (t:A->bool)`; `k:A ring`; `I:A->A`]
    NUMBER_FIELD_TOWER_LAW) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  STRIP_TAC THEN
  SUBGOAL_THEN
   `extension_degree (subfield_generated k t,k) (I:A->A) = n`
  ASSUME_TAC THENL
   [SUBGOAL_THEN `~(m = 0)` ASSUME_TAC THENL
     [DISCH_THEN SUBST_ALL_TAC THEN
      MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_DEGREE_POS) THEN
      ASM_REWRITE_TAC[MULT_CLAUSES] THEN ARITH_TAC;
      ALL_TAC] THEN
    SUBGOAL_THEN
     `m * extension_degree (subfield_generated k t,k) (I:A->A) = m * n`
    MP_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        is_eq(concl th) && lhs(concl th) = `n * m:num`)) THEN
      REWRITE_TAC[MULT_SYM];
      ASM_REWRITE_TAC[EQ_MULT_LCANCEL]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:A->A`; `g:A->A#num`; `subfield_generated k (t:A->bool)`;
