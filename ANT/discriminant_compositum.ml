  REWRITE_TAC[MULT_ASSOC] THEN DISCH_TAC THEN
  REWRITE_TAC[GSYM LE_ANTISYM] THEN ASM_REWRITE_TAC[] THEN
  GEN_REWRITE_TAC LAND_CONV [ARITH_RULE `x:num = x * 1`] THEN
  REWRITE_TAC[LE_MULT_LCANCEL] THEN ASM_REWRITE_TAC[]);;

(* The same in any number field k, through a Galois closure of k.          *)
let NUMBER_FIELD_COMPOSITUM_DEGREE_COPRIME = prove
 (`!(k:A ring) s t.
        number_field k /\
        coprime(number_field_discriminant(subfield_generated k s),
                number_field_discriminant(subfield_generated k t))
        ==> extension_degree(subfield_generated k {ring_0 k},
                             subfield_generated k (s UNION t)) I =
            extension_degree(subfield_generated k {ring_0 k},
                             subfield_generated k s) I *
            extension_degree(subfield_generated k {ring_0 k},
                             subfield_generated k t) I`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_GALOIS_CLOSURE_Q) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:(A#num)ring`
   (X_CHOOSE_THEN `j:A->A#num` STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN `field(m:(A#num)ring)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD]; ALL_TAC] THEN
  MP_TAC(ISPECL [`m:(A#num)ring`; `IMAGE (j:A->A#num) (ring_carrier k INTER s)`;
                 `IMAGE (j:A->A#num) (ring_carrier k INTER t)`]
    NUMBER_FIELD_COMPOSITUM_DEGREE_GALOIS) THEN
  REWRITE_TAC[GSYM IMAGE_UNION; GSYM UNION_OVER_INTER] THEN
  MP_TAC(ISPECL [`k:A ring`; `m:(A#num)ring`; `j:A->A#num`;
                 `ring_carrier k INTER (s:A->bool)`]
    NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE) THEN
  MP_TAC(ISPECL [`k:A ring`; `m:(A#num)ring`; `j:A->A#num`;
                 `ring_carrier k INTER (t:A->bool)`]
    NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE) THEN
  MP_TAC(ISPECL [`k:A ring`; `m:(A#num)ring`; `j:A->A#num`;
                 `ring_carrier k INTER (s UNION t:A->bool)`]
    NUMBER_FIELD_SUBFIELD_HOMOMORPHIC_IMAGE) THEN
  ASM_REWRITE_TAC[INTER_SUBSET; GSYM SUBFIELD_GENERATED_RESTRICT] THEN
  REPEAT(DISCH_THEN(CONJUNCTS_THEN SUBST1_TAC)) THEN
  ASM_REWRITE_TAC[]);;

