                 `ring_carrier Nf INTER (K:A->bool)`; `ring_carrier(Nf:A ring)`]
    EXTENSION_DEGREE_SUBFIELD_TOWER) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[ASSUME `field(m:A ring)`] THEN CONJ_TAC THENL
     [SUBST1_TAC(ASSUME `subfield_generated m {ring_0 m:A} = Q`) THEN
      FIRST_ASSUM MATCH_ACCEPT_TAC;
      MATCH_MP_TAC SUBFIELD_GENERATED_MONO THEN SET_TAC[]];
    ASM_REWRITE_TAC[] THEN DISCH_TAC] THEN
  MP_TAC(ISPECL [`m:A ring`; `K:A->bool`; `KL:A->bool`;
                 `ring_carrier Nf UNION (K:A->bool)`]
    EXTENSION_DEGREE_SUBFIELD_TOWER) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[ASSUME `field(m:A ring)`] THEN CONJ_TAC THENL
