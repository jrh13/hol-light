(* Composita with coprime discriminants (Marcus, Theorem 12; Neukirch,      *)
(* III.2): if k is generated by subfields K and L with d_K, d_L coprime     *)
(* (so [k:Q] = [K:Q][L:Q]), the products of integral bases of K and L form  *)
(* an integral basis of k and d_k = d_K^[L:Q] d_L^[K:Q].                    *)
let NUMBER_FIELD_COMPOSITUM_INTEGRAL_BASIS = prove
 (`!(k:A ring) s t n m e f.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        coprime(number_field_discriminant(subfield_generated k s),
                number_field_discriminant(subfield_generated k t)) /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k s))
                   (ring_of_int(subfield_generated k s)) n e /\
        free_basis (integer_ring,ring_of_integers(subfield_generated k t))
                   (ring_of_int(subfield_generated k t)) m f
        ==> free_basis (integer_ring,ring_of_integers k) (ring_of_int k)
              (n * m) (\u. ring_mul k (e(u MOD n)) (f(u DIV n))) /\
            number_field_discriminant k =
            number_field_discriminant(subfield_generated k s) pow m *
            number_field_discriminant(subfield_generated k t) pow n`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`]
    NUMBER_FIELD_COMPOSITUM_DEGREE_COPRIME) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [number_field]) THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `n:num`; `e:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  MP_TAC(ISPECL [`k:A ring`; `t:A->bool`; `m:num`; `f:num->A`]
    NUMBER_FIELD_SUBFIELD_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN STRIP_TAC THEN
  RULE_ASSUM_TAC(fun th -> let c = concl th in
    if is_eq c && can (term_match [] `ring_of_int k (x:int):A`) (lhs c)
    then SYM th else th) THEN
  SUBGOAL_THEN
   `extension_degree (subfield_generated k {ring_0 k},k) (I:A->A) = n * m`
  ASSUME_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                 `e:num->A`; `f:num->A`]
    NUMBER_FIELD_COMPOSITUM_PRODUCT_BASIS) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN `~(n = 0) /\ ~(m = 0)` STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_DEGREE_POS) THEN
    ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `n = 0` THEN ASM_REWRITE_TAC[MULT_CLAUSES] THEN
    ASM_CASES_TAC `m = 0` THEN ASM_REWRITE_TAC[MULT_CLAUSES] THEN ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!u. u < n * m ==> u MOD n < n /\ u DIV n < m /\
                      u MOD n + n * u DIV n = u`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[MOD_LT_EQ; RDIV_LT_EQ] THEN REPEAT STRIP_TAC THEN
    MP_TAC(SPECL [`u:num`; `n:num`] DIVISION) THEN ASM_REWRITE_TAC[] THEN
    ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_carrier(ring_of_integers k) subring_of (k:A ring)`
  ASSUME_TAC THENL [REWRITE_TAC[RING_OF_INTEGERS_SUBRING]; ALL_TAC] THEN
  ABBREV_TAC `B = \u. ring_mul k ((e:num->A)(u MOD n)) (f(u DIV n))` THEN
  SUBGOAL_THEN
   `!u. u < n * m ==> (B:num->A) u IN ring_carrier(ring_of_integers k)`
  ASSUME_TAC THENL
   [EXPAND_TAC "B" THEN REPEAT STRIP_TAC THEN MATCH_MP_TAC IN_SUBRING_MUL THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!alpha. alpha IN ring_carrier(ring_of_integers k)
            ==> ?w. alpha = ring_sum k {u | u < n * m}
                              (\u. ring_mul k (ring_of_int k (w u))
                                              ((B:num->A) u))`
  (LABEL_TAC "span") THENL
   [X_GEN_TAC `alpha:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(alpha:A) IN ring_carrier k` ASSUME_TAC THENL
     [MATCH_MP_TAC(SET_RULE `!s. x IN s /\ s SUBSET t ==> (x:A) IN t`) THEN
      EXISTS_TAC `ring_carrier(ring_of_integers k:A ring)` THEN
      ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBSET];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`; `k:A ring`;
                   `n * m:num`; `B:num->A`; `alpha:A`] BASIS_COORDINATES) THEN
    ASM_REWRITE_TAC[I_THM] THEN
    ABBREV_TAC
     `c = basis_coordinates (subfield_generated k {ring_0 k},k) (I:A->A)
            (n * m) (B:num->A) alpha` THEN
    STRIP_TAC THEN
    SUBGOAL_THEN
     `(!i. i < n ==> (e:num->A) i IN ring_carrier k) /\
      (!j. j < m ==> (f:num->A) j IN ring_carrier k) /\
      (!u. (c:num->A) u IN ring_carrier k)`
    STRIP_ASSUME_TAC THENL
     [REPEAT CONJ_TAC THEN REPEAT STRIP_TAC THEN
      MATCH_MP_TAC(SET_RULE `!s. x IN s /\ s SUBSET t ==> (x:A) IN t`) THENL
       [EXISTS_TAC `ring_carrier(ring_of_integers k:A ring)` THEN
        ASM_SIMP_TAC[RING_OF_INTEGERS_SUBSET];
        EXISTS_TAC `ring_carrier(ring_of_integers k:A ring)` THEN
        ASM_SIMP_TAC[RING_OF_INTEGERS_SUBSET];
        EXISTS_TAC `ring_carrier(subfield_generated k {ring_0 k:A})` THEN
        ASM_REWRITE_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET]];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `alpha = ring_sum k {i | i < n}
                (\i. ring_sum k {j | j < m}
                       (\j. ring_mul k ((c:num->A) (i + n * j))
                                       (ring_mul k ((e:num->A) i) (f j))))`
    ASSUME_TAC THENL
     [FIRST_ASSUM((fun th -> GEN_REWRITE_TAC LAND_CONV [SYM th]) o
        check (fun th -> is_eq(concl th) && rhs(concl th) = `alpha:A` &&
                         can (find_term ((=) `B:num->A`)) (concl th))) THEN
      EXPAND_TAC "B" THEN REWRITE_TAC[] THEN
      MATCH_MP_TAC RING_SUM_PRODUCT_INDEX THEN ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                   `e:num->A`; `f:num->A`; `alpha:A`;
                   `\i j. (c:num->A) (i + n * j)`]
      NUMBER_FIELD_COMPOSITUM_COORDINATES) THEN
    ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN(LABEL_TAC "zK")] THEN
    MP_TAC(ISPECL [`k:A ring`; `t:A->bool`; `s:A->bool`; `m:num`; `n:num`;
                   `f:num->A`; `e:num->A`; `alpha:A`;
                   `\j i. (c:num->A) (i + n * j)`]
      NUMBER_FIELD_COMPOSITUM_COORDINATES) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
       [ONCE_REWRITE_TAC[UNION_COMM] THEN ASM_REWRITE_TAC[];
        REWRITE_TAC[MULT_SYM];
        MP_TAC(ISPECL [`k:A ring`;
          `\i j. ring_mul k ((c:num->A) (i + n * j))
                   (ring_mul k ((e:num->A) i) ((f:num->A) j))`;
          `{i:num | i < n}`; `{j:num | j < m}`] RING_SUM_SWAP) THEN
        REWRITE_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM; ETA_AX] THEN
        ANTS_TAC THENL
         [REPEAT STRIP_TAC THEN MATCH_MP_TAC RING_MUL THEN
          ASM_SIMP_TAC[RING_MUL];
          DISCH_THEN SUBST1_TAC] THEN
        MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `j:num` THEN
        REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN REWRITE_TAC[] THEN
        MATCH_MP_TAC RING_SUM_EQ THEN X_GEN_TAC `i:num` THEN
        REWRITE_TAC[IN_ELIM_THM] THEN DISCH_TAC THEN REWRITE_TAC[] THEN
        AP_TERM_TAC THEN MATCH_MP_TAC RING_MUL_SYM THEN ASM_SIMP_TAC[]];
      DISCH_THEN(LABEL_TAC "zL")] THEN
    FIRST_ASSUM(MP_TAC o GEN_REWRITE_RULE I [INT_COPRIME_BEZOUT] o
      check (fun th -> can (term_match [] `coprime(a:int,b)`) (concl th))) THEN
    DISCH_THEN(X_CHOOSE_THEN `a:int` (X_CHOOSE_TAC `b:int`)) THEN
    SUBGOAL_THEN `!u. u < n * m ==> ?z. (c:num->A) u = ring_of_int k z`
    MP_TAC THENL
     [X_GEN_TAC `u:num` THEN DISCH_TAC THEN
      SUBGOAL_THEN `u MOD n < n /\ u DIV n < m /\ u MOD n + n * u DIV n = u`
      STRIP_ASSUME_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
      REMOVE_THEN "zK" (MP_TAC o SPECL [`u MOD n`; `u DIV n`]) THEN
      REMOVE_THEN "zL" (MP_TAC o SPECL [`u DIV n`; `u MOD n`]) THEN
      ASM_REWRITE_TAC[] THEN
      DISCH_THEN(X_CHOOSE_TAC `z2:int`) THEN
      DISCH_THEN(X_CHOOSE_TAC `z1:int`) THEN
      EXISTS_TAC `a * z1 + b * z2:int` THEN
      REWRITE_TAC[RING_OF_INT_ADD; RING_OF_INT_MUL] THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        is_eq(concl th) && rhs(concl th) = `ring_of_int k z1:A`)) THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
        is_eq(concl th) && rhs(concl th) = `ring_of_int k z2:A`)) THEN
      FIRST_X_ASSUM(MP_TAC o AP_TERM `ring_of_int k:int->A` o check (fun th ->
        is_eq(concl th) && rhs(concl th) = `&1:int`)) THEN
      REWRITE_TAC[RING_OF_INT_ADD; RING_OF_INT_MUL; RING_OF_INT_1] THEN
      MATCH_MP_TAC(RING_RULE
       `ring_add r (ring_mul r dk a) (ring_mul r dl b) = ring_1 r
        ==> c = ring_add r (ring_mul r a (ring_mul r dk c))
                           (ring_mul r b (ring_mul r dl (c:A)))`) THEN
      ASM_REWRITE_TAC[RING_OF_INT];
      DISCH_THEN(MP_TAC o REWRITE_RULE[RIGHT_IMP_EXISTS_THM; SKOLEM_THM]) THEN
      DISCH_THEN(X_CHOOSE_TAC `w:num->int`) THEN EXISTS_TAC `w:num->int` THEN
      FIRST_ASSUM((fun th -> GEN_REWRITE_TAC LAND_CONV [SYM th]) o
        check (fun th -> is_eq(concl th) && rhs(concl th) = `alpha:A` &&
                         can (find_term ((=) `B:num->A`)) (concl th))) THEN
      MATCH_MP_TAC RING_SUM_EQ THEN ASM_SIMP_TAC[IN_ELIM_THM]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `free_basis (integer_ring,ring_of_integers k) (ring_of_int k) (n * m)
              (B:num->A)`
  ASSUME_TAC THENL
   [REWRITE_TAC[free_basis; INTEGER_RING; IN_UNIV; RING_OF_INTEGERS] THEN
    ASM_SIMP_TAC[] THEN CONJ_TAC THENL
     [X_GEN_TAC `alpha:A` THEN DISCH_TAC THEN
      USE_THEN "span" (MP_TAC o SPEC `alpha:A`) THEN
      ANTS_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
      DISCH_THEN(X_CHOOSE_THEN `w:num->int` SUBST1_TAC) THEN
      EXISTS_TAC `w:num->int` THEN
      CONV_TAC SYM_CONV THEN MATCH_MP_TAC RING_SUM_RING_OF_INTEGERS THEN
      REWRITE_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
      MATCH_MP_TAC IN_SUBRING_MUL THEN
      ASM_SIMP_TAC[RING_OF_INT_IN_RING_OF_INTEGERS];
      X_GEN_TAC `w:num->int` THEN DISCH_TAC THEN
      MP_TAC(ISPECL [`I:A->A`; `subfield_generated k {ring_0 k:A}`;
                     `k:A ring`; `n * m:num`; `B:num->A`;
                     `\u. ring_of_int k ((w:num->int) u):A`]
        FREE_BASIS_INDEPENDENT) THEN
      ASM_REWRITE_TAC[I_THM; RING_OF_INT_IN_SUBFIELD_GENERATED] THEN
      ANTS_TAC THENL
       [FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN CONV_TAC SYM_CONV THEN
        MATCH_MP_TAC RING_SUM_RING_OF_INTEGERS THEN
        REWRITE_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
        MATCH_MP_TAC IN_SUBRING_MUL THEN
        ASM_SIMP_TAC[RING_OF_INT_IN_RING_OF_INTEGERS];
        ASM_SIMP_TAC[SUBFIELD_GENERATED; RING_OF_INT_EQ_0_CHAR_0]]];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`k:A ring`; `n * m:num`; `B:num->A`]
    NUMBER_FIELD_DISCRIMINANT_BASIS_FIELD) THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                 `e:num->A`; `f:num->A`] BASIS_DISCRIMINANT_PRODUCT_BASIS) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[GSYM RING_OF_INT_POW; GSYM RING_OF_INT_MUL] THEN
  ASM_SIMP_TAC[RING_OF_INT_EQ_CHAR_0] THEN MESON_TAC[]);;


(* The discriminant of a compositum with coprime discriminants.             *)
let NUMBER_FIELD_COMPOSITUM_DISCRIMINANT = prove
 (`!(k:A ring) s t.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        coprime(number_field_discriminant(subfield_generated k s),
                number_field_discriminant(subfield_generated k t))
        ==> number_field_discriminant k =
            number_field_discriminant(subfield_generated k s) pow
            extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k t) I *
            number_field_discriminant(subfield_generated k t) pow
            extension_degree (subfield_generated k {ring_0 k},
                              subfield_generated k s) I`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `subfield_generated k (s:A->bool)` RING_OF_INTEGERS_FREE) THEN
  MP_TAC(ISPEC `subfield_generated k (t:A->bool)` RING_OF_INTEGERS_FREE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  DISCH_THEN(X_CHOOSE_TAC `f:num->A`) THEN
  DISCH_THEN(X_CHOOSE_TAC `e:num->A`) THEN
  MP_TAC(ISPECL
   [`k:A ring`; `s:A->bool`; `t:A->bool`;
    `extension_degree (subfield_generated k {ring_0 k},
                       subfield_generated k s) (I:A->A)`;
    `extension_degree (subfield_generated k {ring_0 k},
                       subfield_generated k t) (I:A->A)`;
    `e:num->A`; `f:num->A`] NUMBER_FIELD_COMPOSITUM_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN SIMP_TAC[]);;


(* The ring of integers of such a compositum is generated by those of the   *)
(* factors: O_k = O_K O_L.                                                   *)
let NUMBER_FIELD_COMPOSITUM_RING_OF_INTEGERS = prove
 (`!(k:A ring) s t.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        coprime(number_field_discriminant(subfield_generated k s),
                number_field_discriminant(subfield_generated k t))
        ==> ring_carrier(ring_of_integers k) =
            ring_carrier(subring_generated k
              (ring_carrier(ring_of_integers(subfield_generated k s)) UNION
               ring_carrier(ring_of_integers(subfield_generated k t))))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPEC `subfield_generated k (s:A->bool)` RING_OF_INTEGERS_FREE) THEN
  MP_TAC(ISPEC `subfield_generated k (t:A->bool)` RING_OF_INTEGERS_FREE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED;
               PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  ABBREV_TAC
   `n = extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k s) (I:A->A)` THEN
  ABBREV_TAC
   `m = extension_degree (subfield_generated k {ring_0 k},
                          subfield_generated k t) (I:A->A)` THEN
  DISCH_THEN(X_CHOOSE_TAC `f:num->A`) THEN
  DISCH_THEN(X_CHOOSE_TAC `e:num->A`) THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`; `n:num`; `m:num`;
                 `e:num->A`; `f:num->A`]
    NUMBER_FIELD_COMPOSITUM_INTEGRAL_BASIS) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o CONJUNCT1) THEN
  REWRITE_TAC[free_basis; INTEGER_RING; IN_UNIV; RING_OF_INTEGERS] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
    (K ALL_TAC))) THEN
  SUBGOAL_THEN
   `ring_carrier(ring_of_integers(subfield_generated k s)) UNION
    ring_carrier(ring_of_integers(subfield_generated k t)) SUBSET
    ring_carrier(ring_of_integers(k:A ring))`
  ASSUME_TAC THENL
   [REWRITE_TAC[RING_OF_INTEGERS_SUBFIELD_GENERATED] THEN SET_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [ALL_TAC;
    MATCH_MP_TAC SUBRING_GENERATED_MINIMAL THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBRING]] THEN
  REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `x:A` o check (fun th ->
    is_forall(concl th) && is_imp(snd(dest_forall(concl th))) &&
    is_exists(rand(snd(dest_forall(concl th)))))) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `w:num->int` SUBST1_TAC) THEN
  MP_TAC(ISPECL
   [`k:A ring`; `{u:num | u < n * m}`;
    `\u. ring_mul k (ring_of_int k ((w:num->int) u))
           (ring_mul k ((e:num->A)(u MOD n)) ((f:num->A)(u DIV n)))`]
   RING_SUM_RING_OF_INTEGERS) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC IN_SUBRING_MUL THEN
    ASM_SIMP_TAC[RING_OF_INTEGERS_SUBRING; IN_SUBRING_INT];
    DISCH_THEN SUBST1_TAC] THEN
  MATCH_MP_TAC IN_SUBRING_SUM THEN
  REWRITE_TAC[SUBRING_SUBRING_GENERATED; IN_ELIM_THM] THEN
  X_GEN_TAC `u:num` THEN DISCH_TAC THEN
  SUBGOAL_THEN `~(n = 0)` ASSUME_TAC THENL
   [UNDISCH_TAC `u < n * m:num` THEN ASM_CASES_TAC `n = 0` THEN
    ASM_REWRITE_TAC[MULT_CLAUSES; LT];
    ALL_TAC] THEN
  SUBGOAL_THEN `u MOD n < n /\ u DIV n < m` STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[MOD_LT_EQ; RDIV_LT_EQ]; ALL_TAC] THEN
  MATCH_MP_TAC IN_SUBRING_MUL THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED] THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC IN_SUBRING_INT THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED];
    ALL_TAC] THEN
  MATCH_MP_TAC IN_SUBRING_MUL THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED] THEN
  CONJ_TAC THEN MATCH_MP_TAC SUBRING_GENERATED_INC THEN
  (CONJ_TAC THENL
    [MP_TAC(ISPEC `k:A ring` RING_OF_INTEGERS_SUBSET) THEN ASM SET_TAC[];
     REWRITE_TAC[IN_UNION]]) THENL
   [DISJ1_TAC; DISJ2_TAC] THEN
  FIRST_ASSUM(MATCH_MP_TAC o MATCH_MP FREE_BASIS_IN_CARRIER) THEN
  ASM_REWRITE_TAC[]);;


(* The primes ramified in such a compositum are those ramified in K or L.   *)
let NUMBER_FIELD_COMPOSITUM_RAMIFIED = prove
 (`!(k:A ring) s t p.
        number_field k /\ subfield_generated k (s UNION t) = k /\
        coprime(number_field_discriminant(subfield_generated k s),
                number_field_discriminant(subfield_generated k t)) /\
        prime p
        ==> ((?P. prime_ideal (ring_of_integers k) P /\ ring_of_num k p IN P /\
                  1 < ramification_index (integer_ring,ring_of_integers k)
                        (ring_of_int k) P) <=>
             (?P. prime_ideal (ring_of_integers(subfield_generated k s)) P /\
                  ring_of_num (subfield_generated k s) p IN P /\
                  1 < ramification_index
                        (integer_ring,ring_of_integers(subfield_generated k s))
                        (ring_of_int(subfield_generated k s)) P) \/
             (?P. prime_ideal (ring_of_integers(subfield_generated k t)) P /\
                  ring_of_num (subfield_generated k t) p IN P /\
                  1 < ramification_index
                        (integer_ring,ring_of_integers(subfield_generated k t))
                        (ring_of_int(subfield_generated k t)) P))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `number_field(subfield_generated k (s:A->bool)) /\
    number_field(subfield_generated k (t:A->bool))`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[NUMBER_FIELD_SUBFIELD_GENERATED]; ALL_TAC] THEN
  ASM_SIMP_TAC[NUMBER_FIELD_RAMIFIED_DISCRIMINANT] THEN
  MP_TAC(ISPECL [`k:A ring`; `s:A->bool`; `t:A->bool`]
    NUMBER_FIELD_COMPOSITUM_DISCRIMINANT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPEC `subfield_generated k (s:A->bool)` NUMBER_FIELD_DEGREE_POS) THEN
  MP_TAC(ISPEC `subfield_generated k (t:A->bool)` NUMBER_FIELD_DEGREE_POS) THEN
  ASM_REWRITE_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  REPEAT DISCH_TAC THEN ASM_SIMP_TAC[PRIME_INT_DIVPROD_EQ] THEN
  MP_TAC(ISPEC `p:num` INT_PRIME) THEN ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  BINOP_TAC THEN
  ASM_MESON_TAC[INT_PRIME_DIVPOW; INT_DIVIDES_RPOW; LE_1]);;
