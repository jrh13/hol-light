   `!X:A->bool. ring_carrier Q SUBSET ring_carrier(subfield_generated m X)`
  ASSUME_TAC THENL
   [GEN_TAC THEN
    SUBST1_TAC(SYM(ASSUME `subfield_generated m {ring_0 m:A} = Q`)) THEN
