(* ========================================================================= *)
(* Extensions of number fields unramified outside a set of primes.           *)
(*                                                                           *)
(* For a field extension (k,l) h with k a number field and S a set of primes *)
(* of O_k, unramified_outside (k,l) h S e says that every nonzero prime of   *)
(* O_k outside S is unramified in the subfield generated by e (the usual     *)
(* condition when e is finite over k, as in all uses);                       *)
(* maximal_unramified_outside (k,l) h S is the union K_S of the finite       *)
(* Galois subextensions unramified outside S, a subfield of l containing     *)
(* h(k) (MAXIMAL_UNRAMIFIED_OUTSIDE), Galois over k for every ambient l      *)
(* (GALOIS_MAXIMAL_UNRAMIFIED_OUTSIDE; in general, a subfield of l which is  *)
(* a union of finite Galois subextensions is Galois over k,                  *)
(* GALOIS_EXTENSION_UNION_FINITE_GALOIS_SUBFIELDS of Library/galois.ml). For *)
(* l an algebraic closure of k, K_S is the usual maximal extension           *)
(* unramified outside S (ramification at the infinite places is              *)
(* unrestricted); for an ambient l not normal over k, a finite subextension  *)
(* unramified outside S need not lie in a finite Galois subextension of l,   *)
(* so K_S can be smaller than the union of all finite subextensions          *)
(* unramified outside S. An algebraic closure of a number field is Galois    *)
(* over it (NUMBER_FIELD_ALGEBRAIC_CLOSURE_GALOIS).                          *)
(*                                                                           *)
(* Uses: Library/fieldtheory.ml (generated subfields, finite extensions,     *)
(* perfect fields), Library/galois.ml (finite_galois_subfields,              *)
(* GALOIS_EXTENSION_UNION_FINITE_GALOIS_SUBFIELDS), ANT/numfield.ml,         *)
(* ANT/relative_split.ml (NUMBER_FIELD_PRIME_IDEALS_ABOVE,                   *)
(* NUMBER_FIELD_RAMIFICATION_INDEX_TOWER), ANT/splitting_types.ml            *)
(* (unramified, NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED),               *)
(* ANT/decomposition.ml (inertia_group) and ANT/nf_decomposition.ml          *)
(* (NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP).                                  *)
(* ========================================================================= *)

needs "ANT/relative_split.ml";;
needs "ANT/nf_decomposition.ml";;
needs "ANT/splitting_types.ml";;
needs "Library/galois.ml";;

(* ------------------------------------------------------------------------- *)
(* Unramified finite subextensions. A subfield e of l finite over k gives a  *)
(* number field subfield_generated l e (FINITE_SUBEXTENSION_NUMBER_FIELD).   *)
(* unramified_outside (k,l) h S e: every nonzero prime p of O_k not in S is  *)
(* unramified in subfield_generated l e, in the textbook sense of            *)
(* ANT/splitting_types.ml; the residue fields being finite, this says that   *)
(* every prime of its ring of integers above p has ramification index 1      *)
(* (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED). No condition is imposed   *)
(* at the archimedean places. The base field is unramified everywhere, its   *)
(* Galois group being trivial (UNRAMIFIED_OUTSIDE_BASE). For e within a      *)
(* finite f unramified outside S, a prime of O_e over p lies under a prime   *)
(* of O_f (NUMBER_FIELD_PRIME_IDEALS_ABOVE) and the ramification indices     *)
(* multiply (NUMBER_FIELD_RAMIFICATION_INDEX_TOWER), so e is unramified      *)
(* outside S (UNRAMIFIED_OUTSIDE_SUBFIELD). For finite Galois e within c and *)
(* a prime Q of O_c over p, an element of the inertia group of Q fixes e     *)
(* pointwise if p is unramified in e: its restriction to e lies in the       *)
(* inertia group of Q meet e, which is trivial                               *)
(* (INERTIA_GROUP_UNRAMIFIED_SUBFIELD). Hence the compositum of two finite   *)
(* Galois subextensions unramified outside S is one                          *)
(* (UNRAMIFIED_OUTSIDE_COMPOSITUM): its inertia groups fix both factors, so  *)
(* they are trivial (GALOIS_GROUP_EQ_ON_GENERATORS).                         *)
(* ------------------------------------------------------------------------- *)


let FINITE_SUBEXTENSION_NUMBER_FIELD = prove
 (`!(h:A->B) k l e.
        number_field k /\ field l /\ e subfield_of l /\
        finite_extension(k,subfield_generated l e) h
        ==> ring_carrier(subfield_generated l e) = e /\
            field(subfield_generated l e) /\
            number_field(subfield_generated l e) /\
            ring_homomorphism(k,subfield_generated l e) h`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ASM_SIMP_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD;
               FIELD_SUBFIELD_GENERATED] THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  REWRITE_TAC[field_extension] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[RING_MONOMORPHISM_IMP_HOMOMORPHISM] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (e:B->bool)`]
    PRIME_SUBFIELD_TOWER_LAW) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[number_field]) THEN
  ASM_SIMP_TAC[number_field; RING_MONOMORPHISM_IMP_HOMOMORPHISM]);;

let unramified_outside = new_definition
 `unramified_outside (k:A ring,l:B ring) (h:A->B) S e <=>
        !p. prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
            ~(p IN S)
            ==> unramified (ring_of_integers k,
                            ring_of_integers(subfield_generated l e)) h p`;;

let UNRAMIFIED_OUTSIDE_BASE = prove
 (`!(h:A->B) k l S.
        number_field k /\ field_extension(k,l) h
        ==> IMAGE h (ring_carrier k) IN finite_galois_subfields(k,l) h /\
            unramified_outside (k,l) h S (IMAGE h (ring_carrier k))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`]
    RING_ISOMORPHISM_ONTO_SUBFIELD_IMAGE) THEN
  ASM_SIMP_TAC[RING_MONOMORPHISM_IMP_HOMOMORPHISM] THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `IMAGE (h:A->B) (ring_carrier k) IN finite_galois_subfields(k,l) h`
  ASSUME_TAC THENL
   [ASM_REWRITE_TAC[IN_FINITE_GALOIS_SUBFIELDS; SUBSET_REFL] THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC FINITE_EXTENSION_ISOMORPHISM;
      MATCH_MP_TAC GALOIS_EXTENSION_ISOMORPHISM] THEN
    ASM_REWRITE_TAC[];
    ASM_REWRITE_TAC[]] THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    GEN_REWRITE_RULE I [IN_FINITE_GALOIS_SUBFIELDS]) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
                 `IMAGE (h:A->B) (ring_carrier k)`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  REWRITE_TAC[unramified_outside] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED;
               PRIME_IMP_RING_IDEAL; NUMBER_FIELD_IMP_FIELD] THEN
  REWRITE_TAC[weakly_unramified] THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL
   [`h:A->B`; `k:A ring`;
    `subfield_generated l (IMAGE (h:A->B) (ring_carrier k))`;
    `p:A->bool`; `P:B->bool`] NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD] THEN DISCH_THEN SUBST1_TAC THEN
  SUBGOAL_THEN
   `trivial_group(inertia_group
      (k,subfield_generated l (IMAGE (h:A->B) (ring_carrier k))) h
      (ring_of_integers
        (subfield_generated l (IMAGE (h:A->B) (ring_carrier k)))) P)`
  MP_TAC THENL
   [REWRITE_TAC[inertia_group] THEN
    MATCH_MP_TAC TRIVIAL_GROUP_SUBGROUP_GENERATED THEN
    MATCH_MP_TAC TRIVIAL_GALOIS_GROUP THEN ASM_REWRITE_TAC[SUBSET_REFL];
    REWRITE_TAC[trivial_group] THEN DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[inertia_group; SUBGROUP_GENERATED; GALOIS_GROUP]]);;

let UNRAMIFIED_OUTSIDE_SUBFIELD = prove
 (`!(h:A->B) k l S e e'.
        number_field k /\ field l /\ e subfield_of l /\ e' subfield_of l /\
        IMAGE h (ring_carrier k) SUBSET e /\ e SUBSET e' /\
        finite_extension(k,subfield_generated l e') h /\
        unramified_outside (k,l) h S e'
        ==> finite_extension(k,subfield_generated l e) h /\
            unramified_outside (k,l) h S e`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (e':B->bool)`;
                 `e:B->bool`] FINITE_EXTENSION_SUBFIELD_GENERATED) THEN
  SUBGOAL_THEN
   `subfield_generated (subfield_generated l e') e =
    subfield_generated l (e:B->bool)`
  SUBST1_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_IDEMPOT_GEN THEN
    ASM_SIMP_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM(MP_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  REWRITE_TAC[field_extension] THEN STRIP_TAC THEN
  FIRST_X_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e:B->bool`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e':B->bool`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
  REWRITE_TAC[unramified_outside] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED;
               PRIME_IMP_RING_IDEAL; NUMBER_FIELD_IMP_FIELD] THEN
  REWRITE_TAC[weakly_unramified] THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (e:B->bool)`;
                 `p:A->bool`; `P:B->bool`] NUMBER_FIELD_PRIME_IDEAL_ABOVE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`subfield_generated l (e:B->bool)`;
                 `subfield_generated l (e':B->bool)`; `I:B->B`; `P:B->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD; GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM;
               IMAGE_I] THEN
  DISCH_THEN(X_CHOOSE_THEN `Q:B->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
  MP_TAC(ISPECL [`k:A ring`; `subfield_generated l (e:B->bool)`;
                 `subfield_generated l (e':B->bool)`; `h:A->B`; `I:B->B`;
                 `P:B->bool`; `Q:B->bool`]
    NUMBER_FIELD_RAMIFICATION_INDEX_TOWER) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD; IMAGE_I; I_O_ID] THEN
  UNDISCH_TAC `unramified_outside (k,l) (h:A->B) S e'` THEN
  REWRITE_TAC[unramified_outside] THEN
  DISCH_THEN(MP_TAC o SPEC `p:A->bool`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o MATCH_MP UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED) THEN
  REWRITE_TAC[weakly_unramified] THEN
  DISCH_THEN(MP_TAC o SPEC `Q:B->bool`) THEN
  ANTS_TAC THENL [ASM SET_TAC[]; DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[EQ_SYM_EQ; MULT_EQ_1] THEN SIMP_TAC[]);;

let INERTIA_GROUP_UNRAMIFIED_SUBFIELD = prove
 (`!(h:A->B) k l e c p Q f.
        number_field k /\ field l /\
        e IN finite_galois_subfields(k,l) h /\
        c IN finite_galois_subfields(k,l) h /\ e SUBSET c /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers(subfield_generated l c)) Q /\
        IMAGE h p SUBSET Q /\
        unramified (ring_of_integers k,ring_of_integers(subfield_generated l e))
          h p /\
        f IN group_carrier(inertia_group(k,subfield_generated l c) h
                             (ring_of_integers(subfield_generated l c)) Q)
        ==> !x. x IN e ==> f x = x`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  RULE_ASSUM_TAC(REWRITE_RULE[IN_FINITE_GALOIS_SUBFIELDS]) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[IMP_CONJ]) THEN REPEAT(FIRST_X_ASSUM
   (CONJUNCTS_THEN ASSUME_TAC o check (is_conj o concl))) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e:B->bool`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `c:B->bool`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `subfield_generated (subfield_generated l c) e =
    subfield_generated l (e:B->bool)`
  ASSUME_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_IDEMPOT_GEN THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_homomorphism(ring_of_integers(subfield_generated l e),
                      ring_of_integers(subfield_generated l c)) (I:B->B)`
  ASSUME_TAC THENL
   [MATCH_MP_TAC RING_HOMOMORPHISM_RING_OF_INTEGERS THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (c:B->bool)`;
                   `e:B->bool`] FINITE_EXTENSION_SUBFIELD_GENERATED) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(MP_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION o last o
               CONJUNCTS) THEN
    SIMP_TAC[field_extension; RING_MONOMORPHISM_IMP_HOMOMORPHISM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_carrier(ring_of_integers(subfield_generated l e)) =
    ring_carrier(ring_of_integers(subfield_generated l c)) INTER (e:B->bool)`
  ASSUME_TAC THENL
   [ASM_REWRITE_TAC[RING_OF_INTEGERS_SUBFIELD_GENERATED] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (c:B->bool)`;
                 `ring_of_integers(subfield_generated l (c:B->bool))`;
                 `Q:B->bool`] (CONJUNCT1 INERTIA_GROUP)) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[RING_OF_INTEGERS_SUBRING;
                DECOMPOSITION_GROUP_RING_OF_INTEGERS] THEN
    ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  DISCH_THEN(fun th ->
    UNDISCH_TAC `(f:B->B) IN group_carrier(inertia_group
      (k:A ring,subfield_generated l c) (h:A->B)
      (ring_of_integers(subfield_generated l c)) Q)` THEN
    REWRITE_TAC[th; IN_ELIM_THM]) THEN
  REWRITE_TAC[RING_SUB_SUBFIELD_GENERATED] THEN STRIP_TAC THEN
  SUBGOAL_THEN `!x y. (f:B->B) x = f y <=> x = y` ASSUME_TAC THENL
   [MATCH_MP_TAC PERMUTES_INJECTIVE THEN
    EXISTS_TAC `ring_carrier(subfield_generated l (c:B->bool))` THEN
    MATCH_MP_TAC GALOIS_GROUP_PERMUTES THEN
    MAP_EVERY EXISTS_TAC [`h:A->B`; `k:A ring`] THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(\x. if x IN e then (f:B->B) x else x) IN
    group_carrier(galois_group(k:A ring,subfield_generated l e) (h:A->B)) /\
    IMAGE f e = e`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (c:B->bool)`;
                   `e:B->bool`] GALOIS_GROUP_RESTRICTION_NORMAL) THEN
    ASM_SIMP_TAC[GALOIS_IMP_NORMAL_EXTENSION; FINITE_IMP_FIELD_EXTENSION;
                 SUBFIELD_OF_SUBFIELD_GENERATED_SUBFIELD_EQ] THEN
    DISCH_THEN(CONJUNCTS_THEN2 (MP_TAC o SPEC `f:B->B`)
     (MP_TAC o SPEC `f:B->B` o CONJUNCT1 o
      REWRITE_RULE[group_homomorphism; SUBSET; FORALL_IN_IMAGE] o
      CONJUNCT1)) THEN
    ASM_REWRITE_TAC[] THEN SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `{x | x IN ring_carrier(ring_of_integers(subfield_generated l e)) /\
         (I:B->B) x IN Q} = Q INTER e`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`ring_of_integers(subfield_generated l (c:B->bool))`;
                   `Q:B->bool`] PRIME_IDEAL_IMP_SUBSET) THEN
    ASM_REWRITE_TAC[I_THM] THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `prime_ideal (ring_of_integers(subfield_generated l e)) (Q INTER e) /\
    IMAGE (h:A->B) p SUBSET Q INTER e`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o check
       (fun th -> rand(concl th) = `Q INTER (e:B->bool)`)) THEN
      MATCH_MP_TAC PRIME_IDEAL_HOMOMORPHIC_PREIMAGE THEN
      EXISTS_TAC `ring_of_integers(subfield_generated l (c:B->bool))` THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`k:A ring`; `subfield_generated l (e:B->bool)`; `h:A->B`]
      RING_HOMOMORPHISM_RING_OF_INTEGERS) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(MP_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [ring_homomorphism]) THEN
    MP_TAC(ISPECL [`ring_of_integers(k:A ring)`; `p:A->bool`]
      PRIME_IDEAL_IMP_SUBSET) THEN
    MP_TAC(ISPECL [`subfield_generated l (e:B->bool)`]
      RING_OF_INTEGERS_SUBSET) THEN
    ASM_REWRITE_TAC[] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (e:B->bool)`;
                 `p:A->bool`; `Q INTER (e:B->bool)`]
    NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD] THEN
  UNDISCH_TAC `unramified (ring_of_integers k,
                ring_of_integers(subfield_generated l e)) (h:A->B) p` THEN
  DISCH_THEN(MP_TAC o MATCH_MP UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED) THEN
  REWRITE_TAC[weakly_unramified] THEN
  DISCH_THEN(MP_TAC o SPEC `Q INTER (e:B->bool)`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (e:B->bool)`;
                 `ring_of_integers(subfield_generated l (e:B->bool))`;
                 `Q INTER (e:B->bool)`] (CONJUNCT1 INERTIA_GROUP)) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[RING_OF_INTEGERS_SUBRING;
                DECOMPOSITION_GROUP_RING_OF_INTEGERS] THEN
    ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL];
    DISCH_THEN SUBST1_TAC] THEN
  GEN_REWRITE_TAC LAND_CONV [EXTENSION] THEN
  REWRITE_TAC[IN_ELIM_THM; IN_SING] THEN
  DISCH_THEN(MP_TAC o SPEC `\x. if x IN e then (f:B->B) x else x`) THEN
  MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN
  CONJ_TAC THENL
   [ALL_TAC;
    REWRITE_TAC[FUN_EQ_THM; I_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `x:B`) THEN ASM_REWRITE_TAC[]] THEN
  ASM_REWRITE_TAC[RING_SUB_SUBFIELD_GENERATED] THEN CONJ_TAC THENL
   [SUBGOAL_THEN
     `IMAGE (\x. if x IN e then (f:B->B) x else x) (Q INTER e) =
      IMAGE f (Q INTER e)`
    SUBST1_TAC THENL
     [MATCH_MP_TAC IMAGE_EQ THEN SIMP_TAC[IN_INTER];
      ASM_SIMP_TAC[IMAGE_INTER_INJ]];
    ALL_TAC] THEN
  X_GEN_TAC `y:B` THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `(y:B) IN e /\
    y IN ring_carrier(ring_of_integers(subfield_generated l c))`
  STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  ASM_REWRITE_TAC[IN_INTER] THEN
  MP_TAC(ISPECL [`subfield_generated l (e:B->bool)`; `(f:B->B) y`; `y:B`]
    RING_SUB) THEN
  ASM_SIMP_TAC[RING_SUB_SUBFIELD_GENERATED] THEN
  ANTS_TAC THENL [ASM SET_TAC[]; SIMP_TAC[]]);;

let UNRAMIFIED_OUTSIDE_COMPOSITUM = prove
 (`!(h:A->B) k l S e1 e2.
        number_field k /\ field l /\
        e1 IN finite_galois_subfields(k,l) h /\
        e2 IN finite_galois_subfields(k,l) h /\
        unramified_outside (k,l) h S e1 /\ unramified_outside (k,l) h S e2
        ==> ring_carrier(subfield_generated l (e1 UNION e2)) IN
            finite_galois_subfields(k,l) h /\
            e1 SUBSET ring_carrier(subfield_generated l (e1 UNION e2)) /\
            e2 SUBSET ring_carrier(subfield_generated l (e1 UNION e2)) /\
            unramified_outside (k,l) h S
             (ring_carrier(subfield_generated l (e1 UNION e2)))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ABBREV_TAC `c = ring_carrier(subfield_generated l (e1 UNION e2:B->bool))` THEN
  SUBGOAL_THEN
   `c IN finite_galois_subfields(k,l) (h:A->B) /\ e1 SUBSET c /\ e2 SUBSET c`
  STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `e1 IN finite_galois_subfields(k,l) (h:A->B)` THEN
    UNDISCH_TAC `e2 IN finite_galois_subfields(k,l) (h:A->B)` THEN
    REWRITE_TAC[IN_FINITE_GALOIS_SUBFIELDS] THEN
    REPEAT(DISCH_THEN STRIP_ASSUME_TAC) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e1:B->bool`;
                   `e2:B->bool`] GALOIS_EXTENSION_COMPOSITUM) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN EXPAND_TAC "c" THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED;
                 SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED] THEN
    SUBGOAL_THEN
     `(e1 UNION e2:B->bool) SUBSET
      ring_carrier(subfield_generated l (e1 UNION e2))`
    MP_TAC THENL
     [REWRITE_TAC[SUBSET] THEN REPEAT STRIP_TAC THEN
      MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
      ASM_SIMP_TAC[UNION_SUBSET; SUBFIELD_OF_IMP_SUBSET];
      ASM SET_TAC[]];
    ASM_REWRITE_TAC[]] THEN
  MP_TAC(ASSUME `c IN finite_galois_subfields(k,l) (h:A->B)`) THEN
  REWRITE_TAC[IN_FINITE_GALOIS_SUBFIELDS] THEN STRIP_TAC THEN
  SUBGOAL_THEN `IMAGE (h:A->B) (ring_carrier k) SUBSET e1` ASSUME_TAC THENL
   [ASM_MESON_TAC[IN_FINITE_GALOIS_SUBFIELDS]; ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `c:B->bool`]
    FINITE_SUBEXTENSION_NUMBER_FIELD) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  REWRITE_TAC[unramified_outside] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED;
               PRIME_IMP_RING_IDEAL; NUMBER_FIELD_IMP_FIELD] THEN
  REWRITE_TAC[weakly_unramified] THEN
  SUBGOAL_THEN
   `unramified (ring_of_integers k,ring_of_integers(subfield_generated l e1))
      (h:A->B) p /\
    unramified (ring_of_integers k,ring_of_integers(subfield_generated l e2))
      h p`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[unramified_outside]; ALL_TAC] THEN
  X_GEN_TAC `Q:B->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `subfield_generated l (c:B->bool)`;
                 `p:A->bool`; `Q:B->bool`]
    NUMBER_FIELD_UNRAMIFIED_INERTIA_GROUP) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IMP_FIELD] THEN DISCH_THEN SUBST1_TAC THEN
  MATCH_MP_TAC(SET_RULE
   `(a:B->B) IN s /\ (!f. f IN s ==> f = a) ==> s = {a}`) THEN
  CONJ_TAC THENL
   [MP_TAC(ISPEC `inertia_group(k,subfield_generated l c) (h:A->B)
                   (ring_of_integers(subfield_generated l c)) Q` GROUP_ID) THEN
    REWRITE_TAC[CONJUNCT1(CONJUNCT2 INERTIA_GROUP)];
    X_GEN_TAC `f:B->B` THEN DISCH_TAC] THEN
  SUBGOAL_THEN `!x. x IN e1 UNION e2 ==> (f:B->B) x = I x` ASSUME_TAC THENL
   [REWRITE_TAC[IN_UNION; I_THM] THEN X_GEN_TAC `x:B` THEN STRIP_TAC THENL
     [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e1:B->bool`;
                     `c:B->bool`; `p:A->bool`; `Q:B->bool`; `f:B->B`]
        INERTIA_GROUP_UNRAMIFIED_SUBFIELD);
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e2:B->bool`;
                     `c:B->bool`; `p:A->bool`; `Q:B->bool`; `f:B->B`]
        INERTIA_GROUP_UNRAMIFIED_SUBFIELD)] THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC GALOIS_GROUP_EQ_ON_GENERATORS THEN
  MAP_EVERY EXISTS_TAC
   [`h:A->B`; `k:A ring`; `subfield_generated l (c:B->bool)`;
    `e1 UNION e2:B->bool`] THEN
  ASM_REWRITE_TAC[GALOIS_GROUP_I] THEN CONJ_TAC THENL
   [SUBGOAL_THEN
     `IMAGE (h:A->B) (ring_carrier k) UNION (e1 UNION e2) = e1 UNION e2`
    SUBST1_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    W(MP_TAC o PART_MATCH (lhand o rand) SUBFIELD_GENERATED_IDEMPOT_GEN o
      lhand o snd) THEN
    ANTS_TAC THENL [ASM SET_TAC[]; DISCH_THEN SUBST1_TAC] THEN
    UNDISCH_TAC
     `ring_carrier(subfield_generated l (e1 UNION e2:B->bool)) = c` THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    REWRITE_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED];
    UNDISCH_TAC `(f:B->B) IN group_carrier(inertia_group
      (k:A ring,subfield_generated l c) (h:A->B)
      (ring_of_integers(subfield_generated l c))
      Q)` THEN
    REWRITE_TAC[inertia_group] THEN
    MESON_TAC[GROUP_CARRIER_SUBGROUP_GENERATED_SUBSET; SUBSET]]);;

(* ------------------------------------------------------------------------- *)
(* The maximal extension unramified outside S. maximal_unramified_outside    *)
(* (k,l) h S is the union K_S of the finite Galois subextensions unramified  *)
(* outside S. A directed union of subfields is a subfield                    *)
(* (SUBFIELD_OF_UNIONS_DIRECTED); by the compositum lemma every finite       *)
(* subset of K_S lies in one such subextension                               *)
(* (MAXIMAL_UNRAMIFIED_OUTSIDE_FINITE_SUBSET), so K_S is a subfield of l     *)
(* containing h(k) (MAXIMAL_UNRAMIFIED_OUTSIDE). A finite subextension of l  *)
(* lies in K_S iff it lies in a finite Galois one unramified outside S, and  *)
(* then it is unramified outside S (MAXIMAL_UNRAMIFIED_OUTSIDE_SUBEXTENSION, *)
(* from FINITE_EXTENSION_SUBFIELD_GENERATORS); a finite Galois subextension  *)
(* lies in K_S iff it is unramified outside S                                *)
(* (MAXIMAL_UNRAMIFIED_OUTSIDE_FINITE_GALOIS). A subfield of l containing    *)
(* h(k) in which every element lies in a finite Galois subextension inside   *)
(* it is Galois over k (GALOIS_EXTENSION_UNION_FINITE_GALOIS_SUBFIELDS of    *)
(* Library/galois.ml), so K_S is Galois over k                               *)
(* for every ambient l (GALOIS_MAXIMAL_UNRAMIFIED_OUTSIDE). An algebraic     *)
(* closure of a number field is Galois over it                               *)
(* (NUMBER_FIELD_ALGEBRAIC_CLOSURE_GALOIS, characteristic 0 being perfect).  *)
(* ------------------------------------------------------------------------- *)


let maximal_unramified_outside = new_definition
 `maximal_unramified_outside (k:A ring,l:B ring) (h:A->B) S =
        UNIONS {e | e IN finite_galois_subfields(k,l) h /\
                    unramified_outside (k,l) h S e}`;;

let MAXIMAL_UNRAMIFIED_OUTSIDE_FINITE_SUBSET = prove
 (`!(h:A->B) k l S s.
        number_field k /\ field_extension(k,l) h /\
        FINITE s /\ s SUBSET maximal_unramified_outside (k,l) h S
        ==> ?e. e IN finite_galois_subfields(k,l) h /\
                unramified_outside (k,l) h S e /\ s SUBSET e`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IMP_CONJ] THEN
  DISCH_TAC THEN DISCH_TAC THEN SPEC_TAC(`s:B->bool`,`s:B->bool`) THEN
  MATCH_MP_TAC FINITE_INDUCT_STRONG THEN CONJ_TAC THENL
   [DISCH_TAC THEN EXISTS_TAC `IMAGE (h:A->B) (ring_carrier k)` THEN
    ASM_SIMP_TAC[UNRAMIFIED_OUTSIDE_BASE; EMPTY_SUBSET];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`x:B`; `t:B->bool`] THEN
  REWRITE_TAC[INSERT_SUBSET] THEN
  DISCH_THEN(CONJUNCTS_THEN2 MP_TAC STRIP_ASSUME_TAC) THEN
  DISCH_THEN(fun th -> STRIP_TAC THEN MP_TAC th) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e1:B->bool` STRIP_ASSUME_TAC) THEN
  UNDISCH_TAC `(x:B) IN maximal_unramified_outside (k:A ring,l) (h:A->B) S` THEN
  REWRITE_TAC[maximal_unramified_outside; IN_UNIONS; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `e2:B->bool` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`;
                 `e1:B->bool`; `e2:B->bool`] UNRAMIFIED_OUTSIDE_COMPOSITUM) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[field_extension]; STRIP_TAC] THEN
  EXISTS_TAC `ring_carrier(subfield_generated l (e1 UNION e2:B->bool))` THEN
  ASM_REWRITE_TAC[] THEN ASM SET_TAC[]);;

let MAXIMAL_UNRAMIFIED_OUTSIDE = prove
 (`!(h:A->B) k l S.
        number_field k /\ field_extension(k,l) h
        ==> maximal_unramified_outside (k,l) h S subfield_of l /\
            IMAGE h (ring_carrier k) SUBSET
            maximal_unramified_outside (k,l) h S`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`]
    UNRAMIFIED_OUTSIDE_BASE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  REWRITE_TAC[maximal_unramified_outside] THEN CONJ_TAC THENL
   [MATCH_MP_TAC SUBFIELD_OF_UNIONS_DIRECTED THEN
    REPEAT CONJ_TAC THENL
     [ASM_MESON_TAC[field_extension];
      REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN ASM_MESON_TAC[];
      SIMP_TAC[IN_ELIM_THM; IN_FINITE_GALOIS_SUBFIELDS];
      REWRITE_TAC[IN_ELIM_THM] THEN
      MAP_EVERY X_GEN_TAC [`e1:B->bool`; `e2:B->bool`] THEN STRIP_TAC THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`;
                     `e1:B->bool`; `e2:B->bool`]
        UNRAMIFIED_OUTSIDE_COMPOSITUM) THEN
      ANTS_TAC THENL [ASM_MESON_TAC[field_extension]; STRIP_TAC] THEN
      EXISTS_TAC `ring_carrier(subfield_generated l (e1 UNION e2:B->bool))` THEN
      ASM_REWRITE_TAC[]];
    MATCH_MP_TAC(SET_RULE `(x:B->bool) IN s ==> x SUBSET UNIONS s`) THEN
    ASM_REWRITE_TAC[IN_ELIM_THM]]);;

let MAXIMAL_UNRAMIFIED_OUTSIDE_SUBEXTENSION = prove
 (`!(h:A->B) k l S e.
        number_field k /\ field_extension(k,l) h /\
        e subfield_of l /\ IMAGE h (ring_carrier k) SUBSET e /\
        finite_extension(k,subfield_generated l e) h
        ==> (e SUBSET maximal_unramified_outside (k,l) h S <=>
             ?e'. e' IN finite_galois_subfields(k,l) h /\
                  unramified_outside (k,l) h S e' /\ e SUBSET e') /\
            (e SUBSET maximal_unramified_outside (k,l) h S
             ==> unramified_outside (k,l) h S e)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `(p <=> q) /\ (q ==> r) ==> (p <=> q) /\ (p ==> r)`) THEN
  CONJ_TAC THENL
   [EQ_TAC THENL
     [DISCH_TAC THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e:B->bool`]
        FINITE_EXTENSION_SUBFIELD_GENERATORS) THEN
      ASM_REWRITE_TAC[] THEN
      DISCH_THEN(X_CHOOSE_THEN `b:B->bool` STRIP_ASSUME_TAC) THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`;
                     `b:B->bool`] MAXIMAL_UNRAMIFIED_OUTSIDE_FINITE_SUBSET) THEN
      ANTS_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
      MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `e':B->bool` THEN
      STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM o check
       (fun th -> is_eq(concl th) && rand(concl th) = `e:B->bool`)) THEN
      MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
      ASM_MESON_TAC[IN_FINITE_GALOIS_SUBFIELDS; UNION_SUBSET; SUBSET_TRANS];
      DISCH_THEN(X_CHOOSE_THEN `e':B->bool` STRIP_ASSUME_TAC) THEN
      REWRITE_TAC[maximal_unramified_outside] THEN
      MATCH_MP_TAC(SET_RULE
       `!t. (e:B->bool) SUBSET t /\ t IN s ==> e SUBSET UNIONS s`)
      THEN EXISTS_TAC `e':B->bool` THEN ASM_REWRITE_TAC[IN_ELIM_THM]];
    DISCH_THEN(X_CHOOSE_THEN `e':B->bool` STRIP_ASSUME_TAC) THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`;
                   `e:B->bool`; `e':B->bool`] UNRAMIFIED_OUTSIDE_SUBFIELD) THEN
    ASM_MESON_TAC[IN_FINITE_GALOIS_SUBFIELDS; field_extension]]);;

let MAXIMAL_UNRAMIFIED_OUTSIDE_FINITE_GALOIS = prove
 (`!(h:A->B) k l S e.
        number_field k /\ field_extension(k,l) h /\
        e IN finite_galois_subfields(k,l) h
        ==> (e SUBSET maximal_unramified_outside (k,l) h S <=>
             unramified_outside (k,l) h S e)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN EQ_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `S:(A->bool)->bool`;
                   `e:B->bool`] MAXIMAL_UNRAMIFIED_OUTSIDE_SUBEXTENSION) THEN
    ANTS_TAC THENL [ASM_MESON_TAC[IN_FINITE_GALOIS_SUBFIELDS]; SIMP_TAC[]];
    DISCH_TAC THEN REWRITE_TAC[maximal_unramified_outside] THEN
    MATCH_MP_TAC(SET_RULE `(x:B->bool) IN s ==> x SUBSET UNIONS s`) THEN
    ASM_REWRITE_TAC[IN_ELIM_THM]]);;

let GALOIS_MAXIMAL_UNRAMIFIED_OUTSIDE = prove
 (`!(h:A->B) k l S.
        number_field k /\ field_extension(k,l) h
        ==> galois_extension
             (k,subfield_generated l (maximal_unramified_outside (k,l) h S)) h`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC GALOIS_EXTENSION_UNION_FINITE_GALOIS_SUBFIELDS THEN
  ASM_SIMP_TAC[MAXIMAL_UNRAMIFIED_OUTSIDE] THEN
  REWRITE_TAC[maximal_unramified_outside; IN_UNIONS; IN_ELIM_THM] THEN
  X_GEN_TAC `x:B` THEN
  DISCH_THEN(X_CHOOSE_THEN `e:B->bool` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `e:B->bool` THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC(SET_RULE `(e:B->bool) IN f ==> e SUBSET UNIONS f`) THEN
  ASM_REWRITE_TAC[IN_ELIM_THM]);;

let NUMBER_FIELD_ALGEBRAIC_CLOSURE_GALOIS = prove
 (`!(h:A->B) k l.
        number_field k /\ algebraic_extension(k,l) h /\
        algebraically_closed_field l
        ==> galois_extension(k,l) h`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[galois_extension] THEN
  ASM_SIMP_TAC[ALGEBRAICALLY_CLOSED_IMP_NORMAL_EXTENSION] THEN
  MATCH_MP_TAC PERFECT_FIELD_IMP_SEPARABLE_EXTENSION THEN
  ASM_REWRITE_TAC[] THEN
  RULE_ASSUM_TAC(REWRITE_RULE[number_field]) THEN
  ASM_SIMP_TAC[PERFECT_FIELD_CHAR_0] THEN
  ASM_MESON_TAC[ALGEBRAIC_IMP_FIELD_EXTENSION; field_extension]);;
