(* ========================================================================= *)
(* The ideal norm of an extension of number fields. For a field k with a     *)
(* ring homomorphism h into a number field l (as in ANT/relative_split.ml),  *)
(* O_k and O_l the rings of integers, e(P|p) and f(P|p) the ramification     *)
(* index and residue degree of ANT/prime_split.ml and [l:k] =                *)
(* extension_degree(k,l) h, the norm N(J) of a set J of elements of O_l is   *)
(* the ideal of O_k generated by the norms of its elements:                  *)
(*                                                                           *)
(*   number_field_ideal_norm (k,l) h J =                                     *)
(*   ideal_generated (ring_of_integers k) {algebra_norm (k,l) h x | x IN J}. *)
(*                                                                           *)
(* (A new notion: the absolute ideal_norm of ANT/ideal_norm.ml is a number,  *)
(* the index.) For ideals J of O_l and nonzero primes p of O_k:              *)
(*                                                                           *)
(*   v_p(N(J)) = sum of f(P|p) v_P(J) over the primes P above p, J nonzero   *)
(*   (NUMBER_FIELD_IDEAL_NORM_VALUATION), that is N(J) is the ideal          *)
(*   with these valuations (NUMBER_FIELD_IDEAL_NORM_VALUATIONS, the          *)
(*   definition by valuations); N(J) = 0 iff J = 0 (_EQ_0);                  *)
(*   N(J1 J2) = N(J1) N(J2) (_MUL); N(P) = p^f(P|p) for P above p (_PRIME);  *)
(*   N(J^m) = N(J)^m (_POW); N(j O_l) = j^[l:k] (_EXTENSION); N(O_l) = O_k   *)
(*   (_CARRIER); N(x O_l) = N_(l/k)(x) O_k (_PRINCIPAL), so principal ideals *)
(*   have principal norms; J divides its norm, N(J) O_l SUBSET J             *)
(*   (_EXTENSION_SUBSET); N_(m/k)(J) = N_(l/k)(N_(m/l)(J)) for k -> l -> m   *)
(*   (_TOWER); the absolute norm of N(J) is the absolute norm of J           *)
(*   (_IDEAL_NORM);                                                          *)
(*   for l Galois over k, the product of the conjugates g(J), g in the       *)
(*   Galois group, is N(J) O_l (NUMBER_FIELD_GALOIS_PRODUCT_IDEAL_NORM, the  *)
(*   relative form of NUMBER_FIELD_GALOIS_PRODUCT_IDEAL of                   *)
(*   ANT/conjugate_ideals.ml).                                               *)
(*                                                                           *)
(* On the way: the contraction of j O_l is j for every ideal j of O_k        *)
(* (RING_OF_INTEGERS_IDEAL_EXTENSION_CONTRACTION, the prime case is          *)
(* RING_OF_INTEGERS_IDEAL_EXTENSION_CONTRACTION_PRIME of                     *)
(* ANT/relative_degree.ml); v_p(N_(l/k)(x)) = sum of f(P|p) v_P(x O_l) for   *)
(* the nonzero elements x of O_l (NUMBER_FIELD_NORM_VALUATION). Used from    *)
(* earlier files: v_P(j O_l) = e(P|p) v_p(j)                                 *)
(* (NUMBER_FIELD_IDEAL_VALUATION_EXTENSION of ANT/relative_split.ml), x      *)
(* divides h(N_(l/k)(x)) in O_l (NUMBER_FIELD_NORM_MULTIPLE of               *)
(* ANT/integrality.ml), l embeds into a number field Galois over k           *)
(* (NUMBER_FIELD_GALOIS_CLOSURE of ANT/split_primes.ml) and weak             *)
(* approximation for a nonzero ideal (DEDEKIND_IDEAL_WEAK_APPROXIMATION of   *)
(* ANT/dedekind_struct.ml).                                                  *)
(*                                                                           *)
(* Routes. The exponent sum_(P | p) f(P|p) v_P(J) is additive in J           *)
(* (NUMBER_FIELD_NORM_EXPONENT_ADD), is f(Q|q) or 0 for a prime Q above q    *)
(* (_PRIME), is [l:k] v_p(j) for an extended ideal (_EXTENSION, by the       *)
(* fundamental identity NUMBER_FIELD_FUNDAMENTAL_IDENTITY) and composes in   *)
(* towers (_TOWER: the primes above p in m are grouped by their contractions *)
(* P to l, and f(Q|p) = f(Q|P) f(P|p)). For l Galois over k, v_Q of the      *)
(* product of the conjugates of J is e(Q|p) times the exponent               *)
(* (NUMBER_FIELD_GALOIS_PRODUCT_VALUATION, by induction on the factorization *)
(* of J from the prime case NUMBER_FIELD_GALOIS_PRODUCT_PRIME); with h(N(x)) *)
(* = prod_g g(x) (ALGEBRA_TRACE_NORM_GALOIS) this gives the exponent of N(x) *)
(* (NUMBER_FIELD_GALOIS_NORM_VALUATION). In general take m Galois over k     *)
(* containing l (NUMBER_FIELD_GALOIS_CLOSURE): N_(m/k)(x) = N_(l/k)(x)^[m:l] *)
(* (ALGEBRA_TRACE_NORM_INTERMEDIATE), and the exponent of x O_m is [m:l]     *)
(* times that of x O_l. For an ideal J the generators N(x), x in J, have at  *)
(* least the exponents of J (NUMBER_FIELD_NORM_EXPONENT_MONO), and an x in J *)
(* with v_P(x) = v_P(J) at the primes P above p attains them. The other      *)
(* properties compare valuations (DEDEKIND_IDEAL_EQ_VALUATION); the absolute *)
(* norm goes by induction on the factorization (DEDEKIND_IDEAL_INDUCT) with  *)
(* N(P) = N(p)^f(P|p) (RING_OF_INTEGERS_IDEAL_NORM_PRIME).                   *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml, Library/ring_det.ml  *)
(* (algebra_norm, ALGEBRA_NORM_MUL), Library/galois.ml (galois_group,        *)
(* ALGEBRA_TRACE_NORM_GALOIS), ANT/ideal_arith.ml, ANT/dedekind.ml,          *)
(* ANT/dedekind_struct.ml (DEDEKIND_IDEAL_WEAK_APPROXIMATION),               *)
(* ANT/dedekind_valuation.ml (ideal_of_valuations), ANT/ideal_norm.ml,       *)
(* ANT/numfield.ml, ANT/ring_of_integers.ml, ANT/norm_index.ml               *)
(* (NUMBER_FIELD_IDEAL_NORM_MUL_Q), ANT/prime_split.ml,                      *)
(* ANT/relative_split.ml, ANT/relative_degree.ml, ANT/integrality.ml         *)
(* (NUMBER_FIELD_NORM_INTEGRAL), ANT/nf_decomposition.ml (the                *)
(* Galois action on ideals), ANT/conjugate_ideals.ml and                     *)
(* ANT/split_primes.ml.                                                      *)
(* ========================================================================= *)

