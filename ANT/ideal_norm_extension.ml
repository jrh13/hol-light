(* Galois extensions: the product of the conjugates.                         *)
(* ------------------------------------------------------------------------- *)

(* In a Galois extension the product of the conjugates g(J) is N(J) O_l.     *)
let NUMBER_FIELD_GALOIS_PRODUCT_IDEAL_NORM = prove
 (`!k:A ring l:B ring h J.
        number_field l /\ galois_extension(k,l) h /\
        ring_ideal (ring_of_integers l) J /\ ~(J = {ring_0 l})
        ==> ideal_product (ring_of_integers l)
              (group_carrier(galois_group(k,l) h)) (\g. IMAGE g J) =
            ideal_generated (ring_of_integers l)
              (IMAGE h (number_field_ideal_norm (k,l) h J))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `field k /\ ring_homomorphism(k,l) (h:A->B)`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[GALOIS_IMP_FIELD_EXTENSION; field_extension;
                  RING_MONOMORPHISM_IMP_HOMOMORPHISM]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_GALOIS_GROUP) THEN
  SUBGOAL_THEN
   `dedekind_domain(ring_of_integers k:A ring) /\
    dedekind_domain(ring_of_integers l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN group_carrier(galois_group(k:A ring,l:B ring) h)
        ==> ring_ideal (ring_of_integers l) (IMAGE g J) /\
            ~(IMAGE g J = {ring_0 l})`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[GALOIS_GROUP_RING_OF_INTEGERS_IDEAL]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`;
                 `number_field_ideal_norm (k,l) (h:A->B) J`]
    RING_OF_INTEGERS_IDEAL_EXTENSION) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_IDEAL;
               NUMBER_FIELD_IDEAL_NORM_EQ_0] THEN
  DISCH_THEN(ASSUME_TAC o CONJUNCT2) THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                 `ideal_product (ring_of_integers l)
                    (group_carrier(galois_group(k:A ring,l:B ring) h))
                    (\g. IMAGE g (J:B->bool))`;
                 `ideal_generated (ring_of_integers l)
                    (IMAGE (h:A->B) (number_field_ideal_norm (k,l) h J))`]
    DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[RING_OF_INTEGERS; RING_IDEAL_IDEAL_GENERATED;
                    RING_IDEAL_IDEAL_PRODUCT] THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                   `group_carrier(galois_group(k:A ring,l:B ring) h)`;
                   `\g:B->B. IMAGE g (J:B->bool)`] IDEAL_PRODUCT_EQ_ZERO) THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN; RING_OF_INTEGERS] THEN
    ASM_MESON_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN
  X_GEN_TAC `Q:B->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `Q:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_BELOW) THEN
  ASM_REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `q:A->bool` STRIP_ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `q:A->bool`; `Q:B->bool`;
                 `J:B->bool`] NUMBER_FIELD_GALOIS_PRODUCT_VALUATION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `q:A->bool`; `Q:B->bool`;
                 `number_field_ideal_norm (k,l) (h:A->B) J`]
    NUMBER_FIELD_IDEAL_VALUATION_EXTENSION) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_IDEAL;
               NUMBER_FIELD_IDEAL_NORM_EQ_0] THEN
  DISCH_THEN SUBST1_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_VALUATION]);;
