                 `ideal_generated (ring_of_integers m) {(j:B->B#num) x}`]
    NUMBER_FIELD_NORM_EXPONENT_TOWER) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  SUBGOAL_THEN
