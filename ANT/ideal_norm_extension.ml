                  (ideal_generated (ring_of_integers l) {x})`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                   `ring_of_integers m:(B#num)ring`; `j:B->B#num`; `{x:B}`]
      IDEAL_GENERATED_IMAGE_IDEAL_GENERATED) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_OF_INTEGERS; SING_SUBSET;
                 IMAGE_CLAUSES] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    EXPAND_TAC "n" THEN MATCH_MP_TAC NUMBER_FIELD_NORM_EXPONENT_EXTENSION THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED;
                 RING_OF_INTEGERS_IDEAL_GENERATED_SING_EQ_0] THEN
