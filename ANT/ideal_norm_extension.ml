(* The exponent in a tower k -> l -> m: the primes Q of O_m above p are      *)
(* grouped by their contractions P to O_l, and f(Q|p) = f(Q|P) f(P|p).       *)
let NUMBER_FIELD_NORM_EXPONENT_TOWER = prove
 (`!k:A ring l:B ring m:C ring h1 h2 p J.
        field k /\ field l /\ number_field m /\
        ring_homomorphism(k,l) h1 /\ ring_homomorphism(l,m) h2 /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> nsum {Q | prime_ideal (ring_of_integers m) Q /\
                      IMAGE (h2 o h1) p SUBSET Q}
              (\Q. residue_degree (ring_of_integers k,ring_of_integers m)
                     (h2 o h1) Q *
                   ideal_valuation (ring_of_integers m) Q J) =
            nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h1 p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h1 P *
                   nsum {Q | prime_ideal (ring_of_integers m) Q /\
                             IMAGE h2 P SUBSET Q}
                     (\Q. residue_degree
                            (ring_of_integers l,ring_of_integers m) h2 Q *
                          ideal_valuation (ring_of_integers m) Q J))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `number_field(l:B ring)` ASSUME_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_HOMOMORPHIC_PREIMAGE]; ALL_TAC] THEN
  SUBGOAL_THEN `ring_homomorphism(k:A ring,m:C ring) ((h2:B->C) o (h1:A->B))`
  ASSUME_TAC
  THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_COMPOSE]; ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `m:C ring`; `(h2:B->C) o (h1:A->B)`; `p:A->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN
   `!x. x IN ring_carrier(ring_of_integers k)
