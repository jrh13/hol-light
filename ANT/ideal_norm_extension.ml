  SUBST1_TAC THENL
   [GEN_REWRITE_TAC RAND_CONV [GSYM NSUM_LMUL] THEN MATCH_MP_TAC NSUM_EQ THEN
    X_GEN_TAC `P:B->bool` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
    ASM_SIMP_TAC[] THEN ARITH_TAC;
    ALL_TAC] THEN
  ASM_REWRITE_TAC[EQ_MULT_LCANCEL] THEN MESON_TAC[]);;

