    ASM_REWRITE_TAC[] THEN
    USE_THEN "F2" (MATCH_MP_TAC o SPECL [`P:B->bool`; `Q:C->bool`]) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[GSYM NSUM_LMUL] THEN MATCH_MP_TAC NSUM_EQ THEN
  X_GEN_TAC `Q:C->bool` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `m:C ring`; `h1:A->B`; `h2:B->C`;
