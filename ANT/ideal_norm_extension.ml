(* The exponent sum_(P | p) f(P|p) v_P(J) is additive in J.                  *)
let NUMBER_FIELD_NORM_EXPONENT_ADD = prove
 (`!k:A ring l:B ring h p J1 J2.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        ring_ideal (ring_of_integers l) J1 /\ ~(J1 = {ring_0 l}) /\
        ring_ideal (ring_of_integers l) J2 /\ ~(J2 = {ring_0 l})
        ==> nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P
                     (ideal_prod (ring_of_integers l) J1 J2)) =
            nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P J1) +
            nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P J2)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[GSYM NSUM_ADD] THEN MATCH_MP_TAC NSUM_EQ THEN
  X_GEN_TAC `P:B->bool` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
  REWRITE_TAC[GSYM LEFT_ADD_DISTRIB] THEN AP_TERM_TAC THEN
  MATCH_MP_TAC IDEAL_VALUATION_IDEAL_PROD THEN
  ASM_SIMP_TAC[RING_OF_INTEGERS; DEDEKIND_RING_OF_INTEGERS] THEN
  MATCH_MP_TAC NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO THEN
  MAP_EVERY EXISTS_TAC [`k:A ring`; `h:A->B`; `p:A->bool`] THEN
  ASM_REWRITE_TAC[]);;

(* The exponent of p for a prime Q above q is f(Q|q) if q = p, else 0.       *)
let NUMBER_FIELD_NORM_EXPONENT_PRIME = prove
 (`!k:A ring l:B ring h p q Q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        prime_ideal (ring_of_integers k) q /\ ~(q = {ring_0 k}) /\
        prime_ideal (ring_of_integers l) Q /\ IMAGE h q SUBSET Q
        ==> nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P Q) =
            if q = p
            then residue_degree (ring_of_integers k,ring_of_integers l) h Q
            else 0`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(Q = {ring_0 l:B})` ASSUME_TAC THENL
   [MATCH_MP_TAC NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO THEN
    MAP_EVERY EXISTS_TAC [`k:A ring`; `h:A->B`; `q:A->bool`] THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE (h:A->B) p SUBSET P}
         (\P. if P = Q
              then residue_degree (ring_of_integers k,ring_of_integers l) h Q
              else 0)` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC NSUM_EQ THEN X_GEN_TAC `P:B->bool` THEN
    REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`ring_of_integers l:B ring`; `P:B->bool`; `Q:B->bool`]
      IDEAL_VALUATION_PRIME) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[RING_OF_INTEGERS; DEDEKIND_RING_OF_INTEGERS] THEN
      MATCH_MP_TAC NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO THEN
      MAP_EVERY EXISTS_TAC [`k:A ring`; `h:A->B`; `p:A->bool`] THEN
      ASM_REWRITE_TAC[];
      DISCH_THEN SUBST1_TAC] THEN
    ASM_CASES_TAC `P:B->bool = Q` THEN ASM_REWRITE_TAC[MULT_CLAUSES] THEN
    COND_CASES_TAC THEN ASM_REWRITE_TAC[MULT_CLAUSES] THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[NSUM_DELTA; IN_ELIM_THM] THEN ASM_REWRITE_TAC[] THEN
  AP_THM_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `Q:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_CONTRACTION) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `q:A->bool`; `Q:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_CONTRACTION) THEN
  ASM_REWRITE_TAC[] THEN MESON_TAC[]);;

(* The exponent for an extended ideal:                                       *)
(* sum_(P | p) f e v_p(j) = [l:k] v_p(j).                                    *)
let NUMBER_FIELD_NORM_EXPONENT_EXTENSION = prove
 (`!k:A ring l:B ring h p j.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        ring_ideal (ring_of_integers k) j /\ ~(j = {ring_0 k})
        ==> nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P
                     (ideal_generated (ring_of_integers l) (IMAGE h j))) =
            extension_degree(k,l) h * ideal_valuation (ring_of_integers k) p j`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    NUMBER_FIELD_FUNDAMENTAL_IDENTITY) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  REWRITE_TAC[GSYM NSUM_RMUL] THEN MATCH_MP_TAC NSUM_EQ THEN
  X_GEN_TAC `P:B->bool` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`;
                 `j:A->bool`] NUMBER_FIELD_IDEAL_VALUATION_EXTENSION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN ARITH_TAC);;

(* The exponent is antitone in J.                                            *)
let NUMBER_FIELD_NORM_EXPONENT_MONO = prove
 (`!k:A ring l:B ring h p J1 J2.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        ring_ideal (ring_of_integers l) J1 /\ ~(J1 = {ring_0 l}) /\
        ring_ideal (ring_of_integers l) J2 /\ J1 SUBSET J2
        ==> nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P J2) <=
            nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P J1)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MATCH_MP_TAC NSUM_LE THEN ASM_REWRITE_TAC[] THEN
  X_GEN_TAC `P:B->bool` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
  REWRITE_TAC[LE_MULT_LCANCEL] THEN DISJ2_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`; `J1:B->bool`; `J2:B->bool`]
    DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ASM_SIMP_TAC[RING_OF_INTEGERS; DEDEKIND_RING_OF_INTEGERS] THEN
  ANTS_TAC THENL
