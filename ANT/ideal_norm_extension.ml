    NUMBER_FIELD_GALOIS_NORM_VALUATION) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_THEN SUBST1_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `m:(B#num)ring`; `h:A->B`;
