            number_field_ideal_norm (k,l) h1
              (number_field_ideal_norm (l,m) h2 J)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `number_field(l:B ring)` ASSUME_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_HOMOMORPHIC_PREIMAGE]; ALL_TAC] THEN
  SUBGOAL_THEN `number_field(k:A ring)` ASSUME_TAC THENL
   [ASM_MESON_TAC[NUMBER_FIELD_HOMOMORPHIC_PREIMAGE]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_homomorphism(k:A ring,m:C ring) ((h2:B->C) o (h1:A->B))`
  ASSUME_TAC THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_COMPOSE]; ALL_TAC] THEN
  SUBGOAL_THEN
   `dedekind_domain(ring_of_integers k:A ring) /\
    dedekind_domain(ring_of_integers l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  ASM_CASES_TAC `J = {ring_0 m:C}` THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_0] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                 `number_field_ideal_norm (k,m) ((h2:B->C) o (h1:A->B)) J`;
                 `number_field_ideal_norm (k,l) (h1:A->B)
                    (number_field_ideal_norm (l,m) (h2:B->C) J)`]
    DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_IDEAL; RING_OF_INTEGERS;
                 NUMBER_FIELD_IDEAL_NORM_EQ_0];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_VALUATION;
               NUMBER_FIELD_IDEAL_NORM_IDEAL;
               NUMBER_FIELD_IDEAL_NORM_EQ_0] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `m:C ring`; `h1:A->B`; `h2:B->C`;
                 `p:A->bool`; `J:C->bool`]
    NUMBER_FIELD_NORM_EXPONENT_TOWER) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  MATCH_MP_TAC NSUM_EQ THEN X_GEN_TAC `P:B->bool` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN REWRITE_TAC[] THEN
  AP_TERM_TAC THEN CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC NUMBER_FIELD_IDEAL_NORM_VALUATION THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO THEN
  MAP_EVERY EXISTS_TAC [`k:A ring`; `h1:A->B`; `p:A->bool`] THEN
  ASM_REWRITE_TAC[]);;

(* Compatibility with the absolute norm: N(N_(l/k)(J)) = N(J).               *)
let NUMBER_FIELD_IDEAL_NORM_IDEAL_NORM = prove
 (`!k:A ring l:B ring h J.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        ring_ideal (ring_of_integers l) J /\ ~(J = {ring_0 l})
        ==> ideal_norm (ring_of_integers k)
              (number_field_ideal_norm (k,l) h J) =
            ideal_norm (ring_of_integers l) J`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[TAUT `a /\ b /\ c /\ d /\ e ==> f <=>
                    a /\ b /\ c ==> d /\ e ==> f`] THEN
  STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  SUBGOAL_THEN
   `dedekind_domain(ring_of_integers k:A ring) /\
    dedekind_domain(ring_of_integers l:B ring)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS]; ALL_TAC] THEN
  SPEC_TAC(`J:B->bool`,`J:B->bool`) THEN
  MP_TAC(ISPEC `ring_of_integers l:B ring` DEDEKIND_IDEAL_INDUCT) THEN
  REWRITE_TAC[RING_OF_INTEGERS] THEN DISCH_THEN MATCH_MP_TAC THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_CARRIER;
               IDEAL_NORM_CARRIER] THEN
  MAP_EVERY X_GEN_TAC [`P:B->bool`; `J:B->bool`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `P:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_BELOW) THEN
  ASM_REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:A->bool` STRIP_ASSUME_TAC o CONJUNCT1) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_IDEAL_NORM_MUL; PRIME_IMP_RING_IDEAL] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`]
    NUMBER_FIELD_IDEAL_NORM_PRIME) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPECL [`k:A ring`;
                 `ideal_pow (ring_of_integers k) p
                    (residue_degree (ring_of_integers k,ring_of_integers l)
                       (h:A->B) P)`;
                 `number_field_ideal_norm (k,l) (h:A->B) J`]
    NUMBER_FIELD_IDEAL_NORM_MUL_Q) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; NUMBER_FIELD_IDEAL_NORM_IDEAL;
                 NUMBER_FIELD_IDEAL_NORM_EQ_0; PRIME_IMP_RING_IDEAL;
                 DEDEKIND_IMP_INTEGRAL_DOMAIN;
                 REWRITE_RULE[RING_OF_INTEGERS]
                  (ISPEC `ring_of_integers k:A ring` IDEAL_POW_EQ_ZERO)];
    DISCH_THEN SUBST1_TAC] THEN
  MP_TAC(ISPECL [`l:B ring`; `P:B->bool`; `J:B->bool`]
    NUMBER_FIELD_IDEAL_NORM_MUL_Q) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL]; DISCH_THEN SUBST1_TAC] THEN
  ASM_REWRITE_TAC[] THEN AP_THM_TAC THEN AP_TERM_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`]
    RING_OF_INTEGERS_IDEAL_NORM_PRIME) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `p:A->bool`;
                 `residue_degree (ring_of_integers k,ring_of_integers l)
                    (h:A->B) P`] IDEAL_NORM_IDEAL_POW) THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; RING_OF_INTEGERS;
               RING_OF_INTEGERS_FINITE_QUOTIENT]);;

