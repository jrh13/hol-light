(* The contraction of the extension j O_l of an ideal j of O_k is j.         *)
let RING_OF_INTEGERS_IDEAL_EXTENSION_CONTRACTION = prove
 (`!k:A ring l:B ring h j.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        ring_ideal (ring_of_integers k) j
        ==> {x | x IN ring_carrier(ring_of_integers k) /\
                 h x IN ideal_generated (ring_of_integers l) (IMAGE h j)} =
            j`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  DISCH_THEN(MP_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION o CONJUNCT1) THEN
  REWRITE_TAC[field_extension] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_RING_OF_INTEGERS) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM o
    check (fun th -> concl th =
     `ring_monomorphism(ring_of_integers k,ring_of_integers l) (h:A->B)`)) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP
   (REWRITE_RULE[IMP_CONJ] RING_HOMOMORPHISM_IN_CARRIER) o check (fun th ->
     concl th =
     `ring_homomorphism(ring_of_integers k,ring_of_integers l) (h:A->B)`)) THEN
  ABBREV_TAC `J = ideal_generated (ring_of_integers l) (IMAGE (h:A->B) j)` THEN
  SUBGOAL_THEN `(j:A->bool) SUBSET ring_carrier(ring_of_integers k)`
  ASSUME_TAC THENL [ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET]; ALL_TAC] THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN X_GEN_TAC `x:A` THEN
  REWRITE_TAC[IN_ELIM_THM] THEN EQ_TAC THENL
   [STRIP_TAC;
    DISCH_TAC THEN CONJ_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    EXPAND_TAC "J" THEN MATCH_MP_TAC IDEAL_GENERATED_INC THEN
    ASM_SIMP_TAC[FUN_IN_IMAGE] THEN ASM SET_TAC[]] THEN
  ASM_CASES_TAC `x = ring_0 k:A` THENL
   [ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `j:A->bool`]
      IN_RING_IDEAL_0) THEN
    ASM_REWRITE_TAC[RING_OF_INTEGERS];
    ALL_TAC] THEN
  ASM_CASES_TAC `j = {ring_0 k:A}` THENL
   [UNDISCH_TAC `(h:A->B) x IN J` THEN EXPAND_TAC "J" THEN
    REWRITE_TAC[ASSUME `j = {ring_0 k:A}`; IMAGE_CLAUSES] THEN
    REWRITE_TAC[MATCH_MP RING_HOMOMORPHISM_0
     (ASSUME `ring_homomorphism(k:A ring,l:B ring) h`)] THEN
    REWRITE_TAC[REWRITE_RULE[RING_OF_INTEGERS]
     (ISPEC `ring_of_integers l:B ring` IDEAL_GENERATED_0); IN_SING] THEN
    MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `x:A`]
      RING_MONOMORPHISM_EQ_0) THEN
    ANTS_TAC THENL
     [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
    DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[IN_SING];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`;
                 `ideal_generated (ring_of_integers k) {x:A}`; `j:A->bool`]
    DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS; RING_IDEAL_IDEAL_GENERATED;
               IDEAL_GENERATED_EQ_0; RING_OF_INTEGERS] THEN
  MATCH_MP_TAC(TAUT `q /\ (p ==> r) ==> (p <=> q) ==> r`) THEN CONJ_TAC THENL
   [ALL_TAC;
    DISCH_THEN(MATCH_MP_TAC o REWRITE_RULE[SUBSET]) THEN
    ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]] THEN
  X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
    NUMBER_FIELD_PRIME_IDEALS_ABOVE) THEN
  ASM_REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `P:B->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
  SUBGOAL_THEN `~(P = {ring_0 l:B})` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`]
      RING_OF_INTEGERS_IDEAL_EXTENSION_PRIME) THEN
    ASM_REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `P:B->bool` o last o CONJUNCTS) THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`]
    NUMBER_FIELD_RAMIFICATION_RESIDUE_BOUNDS) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`;
                 `ideal_generated (ring_of_integers k) {x:A}`]
    NUMBER_FIELD_IDEAL_VALUATION_EXTENSION) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p:A->bool`; `P:B->bool`;
                 `j:A->bool`] NUMBER_FIELD_IDEAL_VALUATION_EXTENSION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; REWRITE_RULE[RING_OF_INTEGERS]
    (ISPEC `ring_of_integers k:A ring` IDEAL_GENERATED_EQ_0)] THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `ring_of_integers l:B ring`;
                 `h:A->B`; `{x:A}`] IDEAL_GENERATED_IMAGE_IDEAL_GENERATED) THEN
  ASM_SIMP_TAC[SING_SUBSET; IMAGE_CLAUSES] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  REPEAT DISCH_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers l:B ring`;
                 `ideal_generated (ring_of_integers l) {(h:A->B) x}`;
                 `J:B->bool`] DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS; RING_IDEAL_IDEAL_GENERATED;
                 IDEAL_GENERATED_EQ_0; RING_OF_INTEGERS] THEN
    CONJ_TAC THENL
     [ASM_MESON_TAC[RING_MONOMORPHISM_EQ_0; RING_OF_INTEGERS_SUBSET; SUBSET];
      EXPAND_TAC "J" THEN REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
      MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `j:A->bool`]
        RING_OF_INTEGERS_IDEAL_EXTENSION) THEN
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN CONJ_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    ASM_REWRITE_TAC[SING_SUBSET] THEN EXPAND_TAC "J" THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED];
    DISCH_THEN(MP_TAC o SPEC `P:B->bool`)] THEN
  ASM_REWRITE_TAC[RING_OF_INTEGERS] THEN
  SIMP_TAC[LE_MULT_LCANCEL] THEN ASM_ARITH_TAC);;

