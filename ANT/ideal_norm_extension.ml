(* v_p(N(x)) = sum_(P | p) f(P|p) v_P(x O_l), through a Galois closure m of  *)
(* l over k: N_(m/k)(x) = N_(l/k)(x)^[m:l], and the exponent of p for x O_m  *)
(* is [m:l] times the one for x O_l.                                         *)
let NUMBER_FIELD_NORM_VALUATION = prove
 (`!k:A ring l:B ring h p x.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k}) /\
        x IN ring_carrier(ring_of_integers l) /\ ~(x = ring_0 l)
        ==> ideal_valuation (ring_of_integers k) p
              (ideal_generated (ring_of_integers k)
                 {algebra_norm (k,l) h x}) =
            nsum {P | prime_ideal (ring_of_integers l) P /\ IMAGE h p SUBSET P}
              (\P. residue_degree (ring_of_integers k,ring_of_integers l) h P *
                   ideal_valuation (ring_of_integers l) P
                     (ideal_generated (ring_of_integers l) {x}))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_GALOIS_CLOSURE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`m:(B#num)ring`; `j:B->B#num`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    NUMBER_FIELD_HOMOMORPHIC_PREIMAGE) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[]; DISCH_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD o
    check (fun th -> concl th = `number_field(l:B ring)`)) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`l:B ring`; `m:(B#num)ring`; `j:B->B#num`]
    NUMBER_FIELD_TOWER_LAW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  SUBGOAL_THEN
   `field_extension(k:A ring,l:B ring) h /\
    field_extension(l:B ring,m:(B#num)ring) j`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[FINITE_IMP_FIELD_EXTENSION]; ALL_TAC] THEN
  ABBREV_TAC `n = extension_degree(l:B ring,m:(B#num)ring) j` THEN
  SUBGOAL_THEN `~(n = 0)` ASSUME_TAC THENL
   [EXPAND_TAC "n" THEN ASM_SIMP_TAC[EXTENSION_DEGREE_EQ_0]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_homomorphism(k:A ring,m:(B#num)ring) ((j:B->B#num) o (h:A->B))`
  ASSUME_TAC THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_COMPOSE]; ALL_TAC] THEN
  SUBGOAL_THEN `(x:B) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `algebra_norm (k,l) (h:A->B) x IN ring_carrier(ring_of_integers k) /\
    ~(algebra_norm (k,l) h x = ring_0 k)`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[ALGEBRA_NORM_EQ_0] THEN
    MATCH_MP_TAC NUMBER_FIELD_NORM_INTEGRAL THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(j:B->B#num) x IN ring_carrier(ring_of_integers m) /\ ~(j x = ring_0 m)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [MP_TAC(ISPECL [`l:B ring`; `m:(B#num)ring`; `j:B->B#num`]
        RING_HOMOMORPHISM_RING_OF_INTEGERS) THEN
      ASM_REWRITE_TAC[] THEN ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
      ASM_MESON_TAC[RING_MONOMORPHISM_EQ_0; field_extension]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ideal_valuation (ring_of_integers k) p
      (ideal_generated (ring_of_integers k)
         {algebra_norm (k,m) ((j:B->B#num) o (h:A->B)) (j x)}) =
    n * ideal_valuation (ring_of_integers k) p
          (ideal_generated (ring_of_integers k) {algebra_norm (k,l) h x})`
  MP_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `j:B->B#num`; `k:A ring`; `l:B ring`;
