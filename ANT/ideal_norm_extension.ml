    SUBGOAL_THEN `~(Q = {ring_0 m:C})` ASSUME_TAC THENL
     [MATCH_MP_TAC NUMBER_FIELD_PRIME_IDEAL_ABOVE_NONZERO THEN
      MAP_EVERY EXISTS_TAC
       [`k:A ring`; `(h2:B->C) o (h1:A->B)`; `p:A->bool`] THEN
      ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    CONJ_TAC THENL
     [MP_TAC(ISPECL [`l:B ring`; `m:C ring`; `h2:B->C`; `Q:C->bool`]
