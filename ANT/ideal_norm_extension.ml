    ASM_SIMP_TAC[DEDEKIND_RING_OF_INTEGERS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `m:(B#num)ring`; `(j:B->B#num) o (h:A->B)`;
