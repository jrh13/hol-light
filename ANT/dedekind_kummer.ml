(* ------------------------------------------------------------------------- *)
(* The Dedekind-Kummer theorem for a ring homomorphism h : r -> s into a     *)
(* Dedekind domain, the residue field given by an epimorphism f : r -> k     *)
(* onto a finite field with kernel p. For an ideal j of s containing p s the *)
(* map g~ |-> g(x) + j is an epimorphism k[X] -> s/j; for j = p s its kernel *)
(* contains f o m and both s/p s and k[X]/(f o m) have |k|^deg m elements.   *)
(* For j = (p, g(x)) with g~ dividing f o m the kernel is (g~), the preimage *)
(* of the ideal generated by g(x) + p s. The product of the P_i^e_i lies in  *)
(* p s and has the same norm, hence equals p s.                              *)
(* ------------------------------------------------------------------------- *)

let DEDEKIND_KUMMER_EPIMORPHISM = prove
 (`!r s (h:A->B) k (f:A->C) p x j.
        ring_homomorphism(r,s) h /\ ring_epimorphism(r,k) f /\
        ring_kernel(r,k) f = p /\ x IN ring_carrier s /\
        ring_ideal s j /\ IMAGE h p SUBSET j /\
        ring_setadd s
          (ring_carrier
            (subring_generated s (x INSERT IMAGE h (ring_carrier r))))
          j = ring_carrier s
        ==> ?ph. ring_epimorphism(poly_ring k (:1),quotient_ring s j) ph /\
                  !g. g IN ring_carrier(poly_ring r (:1))
                      ==> ph(f o g) =
                          ring_coset s j (poly_extend (r,s) h (\v. x) g)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_EPIMORPHISM_IMP_HOMOMORPHISM) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_HOMOMORPHISM_RING_COSET) THEN
  MP_TAC(ISPECL [`r:A ring`; `k:C ring`; `quotient_ring s (j:B->bool)`;
                 `f:A->C`; `ring_coset s (j:B->bool) o (h:A->B)`]
    RING_HOMOMORPHISM_EPIMORPHISM_FACTOR) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [MATCH_MP_TAC RING_HOMOMORPHISM_COMPOSE THEN
      EXISTS_TAC `s:B ring` THEN ASM_REWRITE_TAC[];
      REWRITE_TAC[SUBSET] THEN X_GEN_TAC `y:A` THEN
      ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
      SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
       [UNDISCH_TAC `(y:A) IN p` THEN
        FIRST_X_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV)
         [SYM th]) THEN
        SIMP_TAC[ring_kernel; IN_ELIM_THM];
        ALL_TAC] THEN
