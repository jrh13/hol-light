  ASSUME_TAC THENL
   [X_GEN_TAC `g:(1->num)->A` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `k:C ring`; `quotient_ring s (j:B->bool)`;
