let RING_EPIMORPHISM_KERNEL_EQ = prove
 (`!r r' (f:A->B) j.
        ring_epimorphism(r,r') f /\ ring_ideal r j /\
        j SUBSET ring_kernel(r,r') f /\
        FINITE(ring_carrier(quotient_ring r j)) /\
        CARD(ring_carrier(quotient_ring r j)) = CARD(ring_carrier r')
        ==> ring_kernel(r,r') f = j`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_EPIMORPHISM_IMP_HOMOMORPHISM) THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `ring_kernel(r,r') (f:A->B)`]
    IDEAL_NORM_SUBSET_EQ) THEN
  ASM_SIMP_TAC[RING_IDEAL_RING_KERNEL] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_REWRITE_TAC[ideal_norm] THEN MATCH_MP_TAC ISOMORPHIC_RING_CARD THEN
  ASM_SIMP_TAC[FIRST_RING_EPIMORPHISM_THEOREM] THEN
  DISJ1_TAC THEN MATCH_MP_TAC FINITE_QUOTIENT_RING_MONO THEN
  EXISTS_TAC `j:A->bool` THEN ASM_SIMP_TAC[RING_IDEAL_RING_KERNEL]);;

(* ------------------------------------------------------------------------- *)
(* Integer polynomials, their reductions mod n and their values. A           *)
(* polynomial over integer_mod_ring n is an integer polynomial, and          *)
(* poly_extend only uses the coefficient ring for its zero, so it can be     *)
(* evaluated through integer_ring.                                           *)
(* ------------------------------------------------------------------------- *)

let POLY_RING_INTEGER_MOD_RING_SUBSET = prove
 (`!n (v:V->bool).
        ring_carrier(poly_ring (integer_mod_ring n) v) SUBSET
        ring_carrier(poly_ring integer_ring v)`,
  REWRITE_TAC[SUBSET; RING_CARRIER_POLY_RING; IN_ELIM_THM; INTEGER_RING;
              INTEGER_MOD_RING_CLAUSES; IN_UNIV] THEN
  MESON_TAC[]);;

let POLY_EXTEND_INTEGER_MOD_RING = prove
 (`!n (s:B ring).
        poly_extend (integer_mod_ring n,s):
          (int->B)->(V->B)->((V->num)->int)->B =
        poly_extend (integer_ring,s)`,
  REWRITE_TAC[FUN_EQ_THM; poly_extend; INTEGER_MOD_RING_CLAUSES;
              INTEGER_RING]);;

let RING_HOMOMORPHISM_POLY_EXTEND_INTEGER_MOD_RING = prove
 (`!(s:B ring) n v (x:V->B).
        ring_char s divides n /\ (!i. i IN v ==> x i IN ring_carrier s)
        ==> ring_homomorphism (poly_ring (integer_mod_ring n) v,s)
                              (poly_extend (integer_ring,s) (ring_of_int s) x)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[GSYM POLY_EXTEND_INTEGER_MOD_RING] THEN
  MATCH_MP_TAC RING_HOMOMORPHISM_POLY_EXTEND THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_MOD_RING_OF_INT]);;

let POLY_EXTEND_INTEGER_MOD_RING_OF_INT = prove
 (`!(s:B ring) n (x:V->B) p.
        ring_char s divides n
        ==> poly_extend (integer_ring,s) (ring_of_int s) x
              (ring_of_int (integer_mod_ring n) o p) =
            poly_extend (integer_ring,s) (ring_of_int s) x p`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `!z. ring_of_int s (ring_of_int (integer_mod_ring n) z) =
        ring_of_int (s:B ring) z`
  ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_HOMOMORPHISM_RING_OF_INT;
                  RING_HOMOMORPHISM_INTEGER_MOD_RING_OF_INT];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`{m | ~((p:(V->num)->int) m = &0)}`; `integer_ring`;
                 `s:B ring`; `ring_of_int s:int->B`]
         POLY_EXTEND_SUPERSET) THEN
  REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
  DISCH_THEN(fun th ->
    MP_TAC(ISPECL [`p:(V->num)->int`; `x:V->B`] th) THEN
    MP_TAC(ISPECL [`ring_of_int (integer_mod_ring n) o (p:(V->num)->int)`;
                   `x:V->B`] th)) THEN
  REWRITE_TAC[INTEGER_RING; SUBSET_REFL; o_THM] THEN ANTS_TAC THENL
   [REWRITE_TAC[SUBSET; IN_ELIM_THM; INTEGER_MOD_RING_OF_INT] THEN
    MESON_TAC[INT_REM_ZERO];
    REPEAT(DISCH_THEN SUBST1_TAC) THEN ASM_REWRITE_TAC[]]);;

let POLY_EXTEND_FROM_COEFFS = prove
 (`!r r' (h:A->B) x c d.
        ring_homomorphism(r,r') h /\ x IN ring_carrier r' /\
        (!i. i < d ==> c i IN ring_carrier r)
        ==> (\u:1->num. if u one < d then c(u one) else ring_0 r) IN
            ring_carrier(poly_ring r (:1)) /\
            poly_extend (r,r') h (\v. x)
              (\u:1->num. if u one < d then c(u one) else ring_0 r) =
            ring_sum r' {i | i < d}
              (\i. ring_mul r' (h(c i)) (ring_pow r' x i))`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ABBREV_TAC
   `q = \u:1->num. if u one < d then (c:num->A)(u one) else ring_0 r` THEN
  SUBGOAL_THEN `!i. coeff i q = if i < d then (c:num->A) i else ring_0 r`
  ASSUME_TAC THENL [EXPAND_TAC "q" THEN REWRITE_TAC[coeff]; ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [REWRITE_TAC[GSYM RING_POLYNOMIAL; RING_POLYNOMIAL_COEFF] THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [GEN_TAC THEN COND_CASES_TAC THEN ASM_SIMP_TAC[RING_0];
      MATCH_MP_TAC FINITE_SUBSET THEN EXISTS_TAC `{i:num | i < d}` THEN
      REWRITE_TAC[FINITE_NUMSEG_LT; SUBSET; IN_ELIM_THM] THEN MESON_TAC[]];
    DISCH_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `r':B ring`; `h:A->B`; `\v:1. (x:B)`;
                 `q:(1->num)->A`] POLY_EXTEND_UNIVARIATE) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[]; DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[]] THEN
  SUBGOAL_THEN
   `!i. ~(i < d /\ i <= poly_deg r q)
        ==> ring_mul r' ((h:A->B)(coeff i q)) (ring_pow r' x i) = ring_0 r'`
  ASSUME_TAC THENL
   [X_GEN_TAC `i:num` THEN DISCH_TAC THEN
    SUBGOAL_THEN `coeff i (q:(1->num)->A) = ring_0 r` SUBST1_TAC THENL
     [ASM_CASES_TAC `i:num < d` THENL [ALL_TAC; ASM_REWRITE_TAC[]] THEN
      MATCH_MP_TAC COEFF_ABOVE_DEG THEN
      ASM_REWRITE_TAC[RING_POLYNOMIAL] THEN ASM_ARITH_TAC;
      FIRST_ASSUM(fun th -> REWRITE_TAC[MATCH_MP RING_HOMOMORPHISM_0 th]) THEN
      ASM_SIMP_TAC[RING_MUL_LZERO; RING_POW]];
    ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `ring_sum r' {i | i < d /\ i <= poly_deg r q}
      (\i. ring_mul r' ((h:A->B)(coeff i q)) (ring_pow r' x i))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC RING_SUM_SUPERSET THEN
    ASM_SIMP_TAC[SUBSET; IN_ELIM_THM; IN_NUMSEG; LE_0];
    CONV_TAC SYM_CONV THEN TRANS_TAC EQ_TRANS
     `ring_sum r' {i | i < d}
        (\i. ring_mul r' ((h:A->B)(coeff i q)) (ring_pow r' x i))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC RING_SUM_EQ THEN ASM_SIMP_TAC[IN_ELIM_THM];
      MATCH_MP_TAC RING_SUM_SUPERSET THEN
      ASM_SIMP_TAC[SUBSET; IN_ELIM_THM]]]);;

let IMAGE_POLY_EXTEND_INTEGER_RING = prove
 (`!k:A ring a.
        a IN ring_carrier k
        ==> IMAGE (poly_extend (integer_ring,k) (ring_of_int k) (\v. a))
                  (ring_carrier(poly_ring integer_ring (:1))) =
            ring_carrier(subring_generated k {a})`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_int k:int->A`; `integer_ring`; `k:A ring`; `a:A`]
    IMAGE_POLY_EXTEND_1) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
  DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[INTEGER_RING; GSYM SIMPLE_IMAGE;
              GSYM RING_CARRIER_SUBRING_GENERATED_0;
              SUBRING_GENERATED_INSERT] THEN
  ONCE_REWRITE_TAC[INSERT_COMM] THEN
  REWRITE_TAC[SUBRING_GENERATED_INSERT_ZERO]);;

let SUBRING_GENERATED_INT_LINCOMB = prove
 (`!k:A ring a q.
        a IN ring_carrier k /\
        q IN ring_carrier(poly_ring integer_ring (:1)) /\
        monic integer_ring q /\
        poly_extend (integer_ring,k) (ring_of_int k) (\v. a) q = ring_0 k
        ==> ring_carrier(subring_generated k {a}) =
            {ring_sum k {i | i < poly_deg integer_ring q}
               (\i. ring_mul k (ring_of_int k (c i)) (ring_pow k a i)) |
             c IN (:num->int)}`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[GSYM IMAGE_POLY_EXTEND_INTEGER_RING] THEN
  ABBREV_TAC `d = poly_deg integer_ring (q:(1->num)->int)` THEN
  MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `ring_of_int k:int->A`; `a:A`]
    POLY_EXTEND_FROM_COEFFS) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; INTEGER_RING;
                  IN_UNIV] THEN
  DISCH_TAC THEN
  GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_IMAGE; IN_ELIM_THM] THEN
  X_GEN_TAC `z:A` THEN EQ_TAC THENL
   [ALL_TAC;
    DISCH_THEN(X_CHOOSE_THEN `c:num->int` SUBST1_TAC) THEN
    EXISTS_TAC `\u:1->num. if u one < d then (c:num->int)(u one) else &0` THEN
    ASM_REWRITE_TAC[]] THEN
  DISCH_THEN(X_CHOOSE_THEN `h:(1->num)->int` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `\i. coeff i (poly_rem integer_ring h q)` THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`\i. coeff i (poly_rem integer_ring h q)`;
                                `d:num`]) THEN
  DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT2) THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `poly_rem integer_ring h q IN ring_carrier(poly_ring integer_ring (:1)) /\
    (poly_deg integer_ring (poly_rem integer_ring h q) < d \/
     poly_rem integer_ring h q = ring_0(poly_ring integer_ring (:1)))`
  (CONJUNCTS_THEN ASSUME_TAC) THENL
   [ASM_SIMP_TAC[POLY_REM] THEN EXPAND_TAC "d" THEN
    MATCH_MP_TAC POLY_DEG_REM THEN
    RULE_ASSUM_TAC(REWRITE_RULE[monic]) THEN
    ASM_REWRITE_TAC[RING_UNIT_1];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(\u:1->num. if u one < d then coeff (u one) (poly_rem integer_ring h q)
                else &0) = poly_rem integer_ring h q`
  SUBST1_TAC THENL
   [REWRITE_TAC[FUN_EQ_THM; coeff] THEN X_GEN_TAC `u:1->num` THEN
    SUBGOAL_THEN `(\v:1. (u:1->num) one) = u` SUBST1_TAC THENL
     [REWRITE_TAC[FUN_EQ_THM] THEN MESON_TAC[one]; ALL_TAC] THEN
    COND_CASES_TAC THEN REWRITE_TAC[] THEN
    FIRST_X_ASSUM(DISJ_CASES_THEN ASSUME_TAC o check (is_disj o concl)) THENL
     [MP_TAC(ISPECL [`integer_ring`; `poly_rem integer_ring h q`;
                     `(u:1->num) one`] COEFF_ABOVE_DEG) THEN
      ANTS_TAC THENL
       [ASM_REWRITE_TAC[RING_POLYNOMIAL] THEN ASM_ARITH_TAC; ALL_TAC] THEN
      REWRITE_TAC[coeff; INTEGER_RING] THEN
      SUBGOAL_THEN `(\v:1. (u:1->num) one) = u` SUBST1_TAC THENL
       [REWRITE_TAC[FUN_EQ_THM] THEN MESON_TAC[one]; SIMP_TAC[]];
      ASM_REWRITE_TAC[POLY_RING_CLAUSES; POLY_0; INTEGER_RING]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`integer_ring`; `h:(1->num)->int`; `q:(1->num)->int`]
    POLY_DIV_REM_SIMP) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV) [SYM th]) THEN
  MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `(:1)`; `ring_of_int k:int->A`;
                 `\v:1. (a:A)`] RING_HOMOMORPHISM_POLY_EXTEND) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
  DISCH_THEN(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_ADD th;
                                    MATCH_MP RING_HOMOMORPHISM_MUL th;
                                    RING_MUL; POLY_DIV]) THEN
  ASM_SIMP_TAC[RING_MUL_RZERO; POLY_EXTEND; RING_ADD_LZERO]);;

let RING_EPIMORPHISM_POLY_EXTEND_QUOTIENT_RING = prove
 (`!r:A ring a n j.
        a IN ring_carrier r /\ ring_ideal r j /\ ring_of_num r n IN j /\
        ring_setadd r (ring_carrier(subring_generated r {a})) j =
        ring_carrier r
        ==> ring_epimorphism
             (poly_ring (integer_mod_ring n) (:1),quotient_ring r j)
             (poly_extend (integer_ring,quotient_ring r j)
                (ring_of_int (quotient_ring r j)) (\v. ring_coset r j a)) /\
            (!g. poly_extend (integer_ring,quotient_ring r j)
                   (ring_of_int (quotient_ring r j)) (\v:1. ring_coset r j a)
                   (ring_of_int (integer_mod_ring n) o g) =
                 poly_extend (integer_ring,quotient_ring r j)
                   (ring_of_int (quotient_ring r j)) (\v. ring_coset r j a)
                   g) /\
            (!g. g IN ring_carrier(poly_ring integer_ring (:1))
                 ==> ring_coset r j
                       (poly_extend (integer_ring,r) (ring_of_int r) (\v. a)
                          g) =
                     poly_extend (integer_ring,quotient_ring r j)
                       (ring_of_int (quotient_ring r j)) (\v. ring_coset r j a)
                       g)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_HOMOMORPHISM_RING_COSET) THEN
  SUBGOAL_THEN `ring_char(quotient_ring r (j:A->bool)) divides n`
  ASSUME_TAC THENL
   [REWRITE_TAC[GSYM RING_OF_NUM_EQ_0] THEN
    FIRST_ASSUM(fun th -> REWRITE_TAC[GSYM(MATCH_MP
      RING_HOMOMORPHISM_RING_OF_NUM th)]) THEN
    ASM_SIMP_TAC[QUOTIENT_RING_0; RING_COSET_EQ_IDEAL; RING_OF_NUM];
    ALL_TAC] THEN
  ASM_SIMP_TAC[POLY_EXTEND_INTEGER_MOD_RING_OF_INT] THEN
  MATCH_MP_TAC(TAUT `q /\ (q ==> p) ==> p /\ q`) THEN CONJ_TAC THENL
   [X_GEN_TAC `g:(1->num)->int` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`integer_ring`; `r:A ring`; `quotient_ring r (j:A->bool)`;
                   `ring_of_int r:int->A`; `(:1)`; `\v:1. (a:A)`;
                   `ring_coset r (j:A->bool)`; `g:(1->num)->int`]
      POLY_EXTEND_HOMOMORPHIC_IMAGE) THEN
    ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; SUBSET;
                    FORALL_IN_IMAGE] THEN
    DISCH_THEN SUBST1_TAC THEN AP_THM_TAC THEN BINOP_TAC THEN
    REWRITE_TAC[FUN_EQ_THM; o_THM] THEN
    ASM_MESON_TAC[RING_HOMOMORPHISM_RING_OF_INT];
    DISCH_TAC] THEN
  REWRITE_TAC[ring_epimorphism] THEN
  MP_TAC(ISPECL [`quotient_ring r (j:A->bool)`; `n:num`; `(:1)`;
                 `\v:1. ring_coset r j (a:A)`]
    RING_HOMOMORPHISM_POLY_EXTEND_INTEGER_MOD_RING) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[QUOTIENT_RING_CARRIER; IN_ELIM_THM] THEN ASM_MESON_TAC[];
    DISCH_TAC] THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [FIRST_ASSUM(ACCEPT_TAC o CONJUNCT1 o
      GEN_REWRITE_RULE I [RING_HOMOMORPHISM]);
    ALL_TAC] THEN
  ASM_SIMP_TAC[QUOTIENT_RING_CARRIER; SUBSET; FORALL_IN_GSPEC] THEN
  X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `(x:A) IN ring_setadd r (ring_carrier(subring_generated r {a})) j`
  MP_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
