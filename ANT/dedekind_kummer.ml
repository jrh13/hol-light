  X_GEN_TAC `z:B` THEN X_GEN_TAC `w:B` THEN REWRITE_TAC[IN_IMAGE] THEN
  DISCH_THEN(X_CHOOSE_THEN `g:(1->num)->A`
   (CONJUNCTS_THEN2 SUBST1_TAC ASSUME_TAC)) THEN
  DISCH_TAC THEN DISCH_THEN SUBST1_TAC THEN
  EXISTS_TAC `(f:A->C) o (g:(1->num)->A)` THEN
  CONJ_TAC THENL
   [ALL_TAC;
    MATCH_MP_TAC IN_RING_POLYNOMIAL_CARRIER_COMPOSE THEN
