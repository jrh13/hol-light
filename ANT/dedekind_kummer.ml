(* ========================================================================= *)
(* The Dedekind-Kummer theorem, for extensions of number fields and over Z.  *)
(*                                                                           *)
(* Extensions of number fields (NUMBER_FIELD_DEDEKIND_KUMMER, Neukirch       *)
(* I.8.3): let h : k -> l be a ring homomorphism of fields with l a number   *)
(* field, O_k and O_l the rings of integers, x an element of l that is a     *)
(* root of a monic m in O_k[X] of degree [l:k] (so m is the minimal          *)
(* polynomial of x over k and l = k(x)), and p a nonzero prime of O_k with   *)
(* O_l = O_k[x] + p O_l. Write g~ = ring_coset O_k p o g for the reduction   *)
(* of g in O_k[X] mod p. If m~ = g_1~^e_1 ... g_r~^e_r with monic            *)
(* irreducible pairwise distinct g_i~ over O_k/p (the g_i in O_k[X] any      *)
(* lifts), then the ideals P_i = (p, g_i(x)) of O_l are the distinct primes  *)
(* above p, p O_l = P_1^e_1 ... P_r^e_r, f(P_i|p) = deg g_i~ and e(P_i|p) =  *)
(* e_i. Also O_l/p O_l is isomorphic to (O_k/p)[X]/(m~)                      *)
(* (NUMBER_FIELD_DEDEKIND_KUMMER_QUOTIENT_RING), and every irreducible       *)
(* factor g~ of m~ alone gives a maximal ideal (p, g(x)) above p of residue  *)
(* degree deg g~ (NUMBER_FIELD_DEDEKIND_KUMMER_FACTOR).                      *)
(*                                                                           *)
(* Number fields over Z (DEDEKIND_KUMMER_Q): the case of a root a of a monic *)
(* m in Z[X] of degree [k:Q] and a prime p with O = Z[a] + pO (equivalently: *)
(* the index [O : Z[a]] is prime to p, SUBRING_GENERATED_INDEX_COPRIME),     *)
(* with the factors g_i given over F_p = integer_mod_ring p. Polynomials     *)
(* over integer_mod_ring p have integer coefficients in 0..p-1, so g_i(a) is *)
(* evaluated by poly_extend (integer_ring,k) (ring_of_int k) (\v. a); the    *)
(* reduction of m is ring_of_int (integer_mod_ring p) o m. Also O/pO is      *)
(* isomorphic to F_p[X]/(m mod p) (DEDEKIND_KUMMER_QUOTIENT_RING_Q), one     *)
(* factor gives one prime (DEDEKIND_KUMMER_FACTOR_Q), and for a linear       *)
(* factor X - y the prime (p, g(a)) is (p, a - y)                            *)
(* (DEDEKIND_KUMMER_LINEAR_IDEAL).                                           *)
(*                                                                           *)
(* Both are instances of one theorem for a ring homomorphism h : r -> s into *)
(* a Dedekind domain s (DEDEKIND_KUMMER), with the reduction given by        *)
(* any ring epimorphism f : r -> k onto a finite field k with kernel p (for  *)
(* O_k the map ring_coset O_k p onto O_k/p, for Z the map ring_of_int onto   *)
(* integer_mod_ring p): for x in s, m monic in r[X] with m(x) = 0, the ideal *)
(* p s nonzero with |s/p s| = |k|^deg m and s = r[x] + p s, a factorization  *)
(* of f o m as above gives that of p s. The steps: g~ |-> g(x) + j is a ring *)
(* epimorphism k[X] -> s/j for every ideal j of s containing p s             *)
(* (DEDEKIND_KUMMER_EPIMORPHISM); for j = p s its kernel is (f o m) by       *)
(* counting (DEDEKIND_KUMMER_KERNEL, DEDEKIND_KUMMER_QUOTIENT_RING);         *)
(* for j = (p, g(x)) it is (g~), the preimage of the ideal generated by g(x) *)
(* + p s, so j is maximal with |s/j| = |k|^deg g~ and residue degree deg g~  *)
(* (DEDEKIND_KUMMER_FACTOR, by IDEAL_NORM_RESIDUE_DEGREE); the               *)
(* product of the P_i^e_i lies in p s and has the same norm, hence equals p  *)
(* s, and unique factorization gives the rest. The norm condition is         *)
(* NUMBER_FIELD_IDEAL_NORM_EXTENSION_Q for number fields and                 *)
(* RING_OF_INTEGERS_IDEAL_NORM_INTEGER over Z. Also: |R[X]/(g)| = |R|^deg g  *)
(* for a finite ring R and g with unit leading coefficient                   *)
(* (QUOTIENT_POLY_RING_HAS_SIZE, Library/ringtheory.ml), and polynomial      *)
(* coefficients can be lifted along an epimorphism                           *)
(* (RING_EPIMORPHISM_POLY_RINGS, Library/ringtheory.ml).                     *)
(*                                                                           *)
(* The general lemmas on polynomials, quotient rings and epimorphisms are in *)
(* Library/ringtheory.ml, except those of the first two sections: the        *)
(* generic RING_EPIMORPHISM_KERNEL_EQ (it uses ideal norms) and the          *)
(* polynomial lemmas over integer_mod_ring                                   *)
(* (POLY_RING_INTEGER_MOD_RING_SUBSET, POLY_EXTEND_INTEGER_MOD_RING, ...).   *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (polynomials, integer_mod_ring),              *)
(* Library/fieldtheory.ml (minimal polynomials),                             *)
(* ANT/integral.ml, ANT/ideal_arith.ml, ANT/dedekind.ml, ANT/ideal_norm.ml,  *)
(* ANT/numfield.ml, ANT/ring_of_integers.ml, ANT/prime_split.ml,             *)
(* ANT/discriminant.ml, ANT/relative_split.ml (IDEAL_NORM_RESIDUE_DEGREE,    *)
(* RING_OF_INTEGERS_IDEAL_EXTENSION), ANT/relative_degree.ml                 *)
(* (NUMBER_FIELD_IDEAL_NORM_EXTENSION_Q) and ANT/integrality.ml              *)
(* (RING_OF_INTEGERS_INTEGRAL_ELEMENT).                                      *)
(* ========================================================================= *)

