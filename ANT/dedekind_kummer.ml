      W(MP_TAC o PART_MATCH (lhand o rand) RING_COSET_EQ_IDEAL o snd) THEN
      ANTS_TAC THENL
       [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; DISCH_THEN SUBST1_TAC] THEN
      ASM SET_TAC[]];
    DISCH_THEN(X_CHOOSE_THEN `hb:C->B->bool` STRIP_ASSUME_TAC)] THEN
  EXISTS_TAC `poly_extend (k,quotient_ring s j) (hb:C->B->bool)
                (\v:1. ring_coset s j (x:B))` THEN
  SUBGOAL_THEN
   `!g. g IN ring_carrier(poly_ring r (:1))
        ==> poly_extend (k,quotient_ring s j) (hb:C->B->bool)
              (\v:1. ring_coset s j (x:B)) (f o g) =
