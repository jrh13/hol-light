(* ========================================================================= *)
(* Splitting types of primes: unramified, weakly unramified, totally split,  *)
(* inert and totally ramified primes, in a ring extension and for number     *)
(* fields.                                                                   *)
(*                                                                           *)
(* For a ring homomorphism h : r -> s and an ideal p of r, with e(P|p) =     *)
(* ramification_index (r,s) h P and f(P|p) = residue_degree (r,s) h P of     *)
(* ANT/prime_split.ml, P above p meaning prime_ideal s P /\ IMAGE h p SUBSET *)
(* P, and the residue extension of P the extension of s/P over the subring   *)
(* generated by the image of r (whose degree is f(P|p)):                     *)
(*                                                                           *)
(*   unramified (r,s) h p         every P above p has e(P|p) = 1 and a       *)
(*                                separable residue extension                *)
(*   weakly_unramified (r,s) h p  every P above p has e(P|p) = 1             *)
(*   totally_split (r,s) h p      every P above p has e = f = 1              *)
(*   inert (r,s) h p              p s is a prime ideal                       *)
(*   totally_ramified (r,s) h p   exactly one prime P above p, and           *)
(*                                f(P|p) = 1                                 *)
(*                                                                           *)
(* unramified is the textbook notion (Neukirch, Algebraic Number Theory,     *)
(* I.8, p. 44: P is unramified if e = 1 and the residue class field          *)
(* extension is separable); weakly_unramified asks only e = 1 (Stacks        *)
(* Project, Definition 09E4; Lemma 09E7 and Example 09EX show the            *)
(* difference, an inseparable residue extension with e = 1). There is no     *)
(* degree argument, and the universal definitions (unramified,               *)
(* weakly_unramified, totally_split) hold vacuously when no prime lies above *)
(* p. An unramified ideal is weakly unramified                               *)
(* (UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED), and the two notions agree when every  *)
(* residue ring s/P above p is finite                                        *)
(* (UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_FINITE), when p is maximal, r/p is       *)
(* perfect and the residue extensions are algebraic                          *)
(* (UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_PERFECT), and so for rings of integers:  *)
(* into O_k for any set whose image is nonzero                               *)
(* (RING_OF_INTEGERS_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED), for a nonzero ideal   *)
(* of O_k in O_l (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED) and for a    *)
(* rational p <> 0 (NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_Q). The     *)
(* results on general ring extensions (SPLITTING_TYPES_PRINCIPAL,            *)
(* SPLITTING_TYPES_INTEGER_RING) are stated with weakly_unramified, those on *)
(* number fields with unramified.                                            *)
(*                                                                           *)
(* For a rational prime p in a number field k the types are those over Z,    *)
(* with the arguments (integer_ring,ring_of_integers k) (ring_of_int k) and  *)
(* the ideal ideal_generated integer_ring {&p}; SPLITTING_TYPES_INTEGER_RING *)
(* restates them for any ring r with e and f over Z (the map ring_of_int r). *)
(* For an extension of number fields h : k -> l the arguments are            *)
(* (ring_of_integers k,ring_of_integers l) h p.                              *)
(*                                                                           *)
(* Main results (n = [k:Q] for a rational prime p, n = [l:k] for a nonzero   *)
(* prime p of O_k; O the ring of integers above): p is unramified iff p O is *)
(* the product of the distinct primes above p; totally split iff there are n *)
(* primes above p; inert iff there is one prime above p, with residue degree *)
(* n; totally ramified iff there is one prime above p, with ramification     *)
(* index n, iff p O = P^n for a prime P; inert primes are unramified; for n  *)
(* > 1 the types totally split, inert and totally ramified exclude each      *)
(* other and totally ramified primes ramify. A rational prime is unramified  *)
(* in k iff it does not divide d_K; only finitely many primes of O_k ramify  *)
(* in l, and none above a rational prime not dividing d_L. The types over Z  *)
(* are those over the prime subfield, and a rational prime not dividing the  *)
(* discriminant of a subfield K is unramified in K over the prime subfield   *)
(* (NUMBER_FIELD_SUBFIELD_UNRAMIFIED_DISCRIMINANT).                          *)
(*                                                                           *)
(* Route: every characterization follows, by one abstract lemma              *)
(* (IDEAL_PRODUCT_SPLITTING_TYPES), from the factorization of p O into the   *)
(* powers P^e of the primes above p, its uniqueness and the fundamental      *)
(* identity sum e f = n with all e, f >= 1 (ANT/prime_split.ml over Z,       *)
(* ANT/relative_split.ml and ANT/relative_degree.ml for number fields), for  *)
(* weakly_unramified; the number-field forms of unramified follow by the     *)
(* bridges. These use that a finite integral domain is a field, that a       *)
(* finite field is perfect (FINITE_FIELD_IMP_PERFECT,                        *)
(* PERFECT_FIELD_IMP_SEPARABLE_EXTENSION), the finiteness of O/P for P <> 0  *)
(* (RING_OF_INTEGERS_FINITE_QUOTIENT), and for the perfect case              *)
(* FIRST_RING_ISOMORPHISM_THEOREM and ISOMORPHIC_RING_PERFECT_FIELD. A prime *)
(* P of O_l is unramified over k if it is unramified over Q, since e(P) =    *)
(* e(P|p) e(p).                                                              *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml, Library/fieldtheory.ml                       *)
(* (RING_HOMOMORPHISM_SUBFIELD_INCLUSION, separable_extension,               *)
(* perfect_field), ANT/ideal_arith.ml, ANT/numfield.ml,                      *)
(* ANT/ring_of_integers.ml (through ANT/prime_split.ml), ANT/prime_split.ml, *)
(* ANT/discriminant.ml, ANT/ramification.ml                                  *)
(* (NUMBER_FIELD_RAMIFIED_DISCRIMINANT), ANT/relative_split.ml and           *)
(* ANT/relative_degree.ml.                                                   *)
(* ========================================================================= *)

