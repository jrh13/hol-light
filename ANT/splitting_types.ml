let UNRAMIFIED_DISCRIMINANT = prove
 (`!k:A ring l:B ring h p q.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        prime q /\ ring_of_num k q IN p /\
        ~(&q divides number_field_discriminant l)
        ==> unramified (ring_of_integers k,ring_of_integers l) h p`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_of_integers k:A ring`; `l:B ring`; `h:A->B`;
                 `p:A->bool`] RING_OF_INTEGERS_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED)
  THEN ANTS_TAC THENL
   [ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_SING; NOT_FORALL_THM;
                    NOT_IMP] THEN
    EXISTS_TAC `ring_of_num k q:A` THEN ASM_REWRITE_TAC[] THEN
    FIRST_ASSUM(SUBST1_TAC o SPEC `q:num` o
      MATCH_MP RING_HOMOMORPHISM_RING_OF_NUM) THEN
    REWRITE_TAC[RING_OF_NUM_EQ_0] THEN
    FIRST_ASSUM(fun th ->
      REWRITE_TAC[CONJUNCT1(REWRITE_RULE[number_field] th)]) THEN
    ASM_SIMP_TAC[DIVIDES_ZERO; PRIME_IMP_NZ];
    DISCH_THEN SUBST1_TAC] THEN
  REWRITE_TAC[weakly_unramified] THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  SUBGOAL_THEN `ring_of_num l q IN (P:B->bool)` ASSUME_TAC THENL
   [FIRST_ASSUM(SUBST1_TAC o SYM o SPEC `q:num` o
      MATCH_MP RING_HOMOMORPHISM_RING_OF_NUM) THEN
    UNDISCH_TAC `IMAGE (h:A->B) p SUBSET P` THEN
    UNDISCH_TAC `ring_of_num k q IN (p:A->bool)` THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(P = {ring_0 l:B})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN
    UNDISCH_TAC `ring_of_num l q IN {ring_0 l:B}` THEN
    REWRITE_TAC[IN_SING; RING_OF_NUM_EQ_0] THEN
    FIRST_ASSUM(fun th -> REWRITE_TAC[CONJUNCT1(REWRITE_RULE[number_field] th)])
    THEN ASM_SIMP_TAC[DIVIDES_ZERO; PRIME_IMP_NZ];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `P:B->bool`]
    RING_OF_INTEGERS_PRIME_IDEAL_BELOW) THEN
  ASM_REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `p':A->bool` STRIP_ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `p':A->bool`;
                 `P:B->bool`] NUMBER_FIELD_RAMIFICATION_INDEX_TOWER_Q) THEN
  MP_TAC(ISPECL [`l:B ring`; `P:B->bool`; `q:num`]
    NUMBER_FIELD_RAMIFICATION_RESIDUE_BOUNDS_Q) THEN
  MP_TAC(ISPECL [`l:B ring`; `q:num`] NUMBER_FIELD_RAMIFIED_DISCRIMINANT) THEN
  ASM_REWRITE_TAC[NOT_EXISTS_THM] THEN
  DISCH_THEN(MP_TAC o SPEC `P:B->bool`) THEN ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[NOT_LT; IMP_IMP] THEN
  DISCH_THEN(MP_TAC o MATCH_MP (ARITH_RULE
   `(a <= 1 /\ 1 <= a /\ c) /\ a = b ==> b = 1`)) THEN
  REWRITE_TAC[MULT_EQ_1] THEN SIMP_TAC[]);;

