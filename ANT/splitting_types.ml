(* ------------------------------------------------------------------------- *)
(* Splitting types of an ideal in a ring extension.                          *)
(* ------------------------------------------------------------------------- *)

let weakly_unramified = new_definition
 `weakly_unramified (r:A ring,s:B ring) (h:A->B) p <=>
  !P. prime_ideal s P /\ IMAGE h p SUBSET P
      ==> ramification_index (r,s) h P = 1`;;

let unramified = new_definition
 `unramified (r:A ring,s:B ring) (h:A->B) p <=>
  !P. prime_ideal s P /\ IMAGE h p SUBSET P
      ==> ramification_index (r,s) h P = 1 /\
          separable_extension
           (subring_generated (quotient_ring s P)
              (IMAGE (ring_coset s P o h) (ring_carrier r)),
            quotient_ring s P) I`;;

let totally_split = new_definition
 `totally_split (r:A ring,s:B ring) (h:A->B) p <=>
  !P. prime_ideal s P /\ IMAGE h p SUBSET P
      ==> ramification_index (r,s) h P = 1 /\
          residue_degree (r,s) h P = 1`;;

let inert = new_definition
 `inert (r:A ring,s:B ring) (h:A->B) p <=>
  prime_ideal s (ideal_generated s (IMAGE h p))`;;

let totally_ramified = new_definition
 `totally_ramified (r:A ring,s:B ring) (h:A->B) p <=>
  ?P. {Q | prime_ideal s Q /\ IMAGE h p SUBSET Q} = {P} /\
      residue_degree (r,s) h P = 1`;;

(* ------------------------------------------------------------------------- *)
(* Unramified and weakly unramified. The two agree when the residue rings    *)
(* above p are finite (finite fields are perfect), when the residue field    *)
(* below is perfect and the residue extensions are algebraic, and so for the *)
(* nonzero primes of rings of integers.                                      *)
(* ------------------------------------------------------------------------- *)

let UNRAMIFIED_IMP_WEAKLY_UNRAMIFIED = prove
 (`!r:A ring s:B ring h p.
        unramified (r,s) h p ==> weakly_unramified (r,s) h p`,
  SIMP_TAC[unramified; weakly_unramified]);;

let UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_FINITE = prove
 (`!r:A ring s:B ring h p.
        (!P. prime_ideal s P /\ IMAGE h p SUBSET P
             ==> FINITE(ring_carrier(quotient_ring s P)))
        ==> (unramified (r,s) h p <=> weakly_unramified (r,s) h p)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  REWRITE_TAC[unramified; weakly_unramified] THEN
  MATCH_MP_TAC(MESON[]
   `!a b c. (!P:B->bool. a P ==> c P)
            ==> ((!P. a P ==> b P /\ c P) <=> (!P. a P ==> b P))`) THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `P:B->bool`) THEN ASM_REWRITE_TAC[] THEN
  ABBREV_TAC `X = IMAGE (ring_coset s P o (h:A->B)) (ring_carrier r)` THEN
  DISCH_TAC THEN
  SUBGOAL_THEN `field(quotient_ring s (P:B->bool))` ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_INTEGRAL_DOMAIN_IMP_FIELD THEN
    ASM_MESON_TAC[INTEGRAL_DOMAIN_QUOTIENT_RING; PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`quotient_ring s (P:B->bool)`; `X:(B->bool)->bool`]
    FIELD_EXTENSION_SUBRING_GENERATED_FINITE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MATCH_MP_TAC PERFECT_FIELD_IMP_SEPARABLE_EXTENSION THEN CONJ_TAC THENL
   [MATCH_MP_TAC FINITE_FIELD_IMP_PERFECT THEN
    ASM_SIMP_TAC[FINITE_SUBRING_GENERATED] THEN
    ASM_MESON_TAC[field_extension];
    MATCH_MP_TAC FINITE_IMP_ALGEBRAIC_EXTENSION THEN
    ASM_SIMP_TAC[FINITE_EQ_FIELD_EXTENSION]]);;

(* For p maximal the image of r in s/P is isomorphic to r/p, by              *)
(* FIRST_RING_ISOMORPHISM_THEOREM with the kernel {x | h x IN P} = p, so it  *)
(* is perfect along with r/p.                                                *)

let UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_PERFECT = prove
 (`!r:A ring s:B ring h p.
        ring_homomorphism(r,s) h /\ maximal_ideal r p /\
        perfect_field(quotient_ring r p) /\
        (!P. prime_ideal s P /\ IMAGE h p SUBSET P
             ==> algebraic_extension
                  (subring_generated (quotient_ring s P)
                     (IMAGE (ring_coset s P o h) (ring_carrier r)),
                   quotient_ring s P) I)
        ==> (unramified (r,s) h p <=> weakly_unramified (r,s) h p)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[unramified; weakly_unramified] THEN
  MATCH_MP_TAC(MESON[]
   `!a b c. (!P:B->bool. a P ==> c P)
            ==> ((!P. a P ==> b P /\ c P) <=> (!P. a P ==> b P))`) THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  MATCH_MP_TAC PERFECT_FIELD_IMP_SEPARABLE_EXTENSION THEN ASM_SIMP_TAC[] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN
   `ring_homomorphism(r,quotient_ring s P) (ring_coset s P o (h:A->B))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC RING_HOMOMORPHISM_COMPOSE THEN EXISTS_TAC `s:B ring` THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_RING_COSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_kernel (r,quotient_ring s P) (ring_coset s P o (h:A->B)) = p`
  ASSUME_TAC THENL
   [FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [maximal_ideal]) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP PROPER_IMP_RING_IDEAL) THEN
    SUBGOAL_THEN
     `ring_kernel (r,quotient_ring s P) (ring_coset s P o (h:A->B)) =
      {x | x IN ring_carrier r /\ h x IN P}`
    SUBST1_TAC THENL
     [REWRITE_TAC[ring_kernel] THEN GEN_REWRITE_TAC I [EXTENSION] THEN
      REWRITE_TAC[IN_ELIM_THM; o_THM] THEN
      X_GEN_TAC `x:A` THEN ASM_CASES_TAC `(x:A) IN ring_carrier r` THEN
      ASM_SIMP_TAC[QUOTIENT_RING_0] THEN MATCH_MP_TAC RING_COSET_EQ_IDEAL THEN
      ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
      ALL_TAC] THEN
    FIRST_X_ASSUM(MP_TAC o
      SPEC `{x | x IN ring_carrier r /\ (h:A->B) x IN P}` o
      REWRITE_RULE[NOT_EXISTS_THM]) THEN
    MATCH_MP_TAC(SET_RULE
     `(a:A->bool) SUBSET b /\ c ==> ~(c /\ a PSUBSET b) ==> b = a`) THEN
    CONJ_TAC THENL
     [MP_TAC(ISPECL [`r:A ring`; `p:A->bool`] RING_IDEAL_IMP_SUBSET) THEN
      ASM SET_TAC[];
      ALL_TAC] THEN
    REWRITE_TAC[PROPER_IDEAL] THEN CONJ_TAC THENL
     [MATCH_MP_TAC RING_IDEAL_HOMOMORPHIC_PREIMAGE THEN
      EXISTS_TAC `s:B ring` THEN ASM_REWRITE_TAC[];
      REWRITE_TAC[IN_ELIM_THM; RING_1] THEN
      MP_TAC(ISPECL [`r:A ring`; `s:B ring`; `h:A->B`] RING_HOMOMORPHISM_1) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
      UNDISCH_TAC `prime_ideal s (P:B->bool)` THEN
      SIMP_TAC[prime_ideal; PROPER_IDEAL]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `quotient_ring s (P:B->bool)`;
                 `ring_coset s P o (h:A->B)`]
    FIRST_RING_ISOMORPHISM_THEOREM) THEN
  ASM_REWRITE_TAC[ring_image] THEN
  DISCH_THEN(SUBST1_TAC o SYM o MATCH_MP ISOMORPHIC_RING_PERFECT_FIELD) THEN
  ASM_REWRITE_TAC[]);;

(* Into a ring of integers, every prime above a set with a nonzero image is  *)
(* nonzero, so its residue ring is finite                                    *)
(* (RING_OF_INTEGERS_FINITE_QUOTIENT).                                       *)

let RING_OF_INTEGERS_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED = prove
 (`!r:A ring k:B ring h p.
        number_field k /\ ~(IMAGE h p SUBSET {ring_0 k})
        ==> (unramified (r,ring_of_integers k) h p <=>
             weakly_unramified (r,ring_of_integers k) h p)`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_FINITE THEN
  X_GEN_TAC `P:B->bool` THEN STRIP_TAC THEN
  MATCH_MP_TAC RING_OF_INTEGERS_FINITE_QUOTIENT THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL] THEN
  DISCH_THEN SUBST_ALL_TAC THEN ASM_MESON_TAC[]);;

let NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED_Q = prove
 (`!k:A ring p.
        number_field k /\ ~(p = 0)
        ==> (unramified (integer_ring,ring_of_integers k) (ring_of_int k)
               (ideal_generated integer_ring {&p}) <=>
             weakly_unramified (integer_ring,ring_of_integers k)
               (ring_of_int k) (ideal_generated integer_ring {&p}))`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC RING_OF_INTEGERS_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED THEN
  ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_SING; NOT_FORALL_THM;
                  NOT_IMP] THEN
  EXISTS_TAC `&p:int` THEN
  SIMP_TAC[IDEAL_GENERATED_INC; INTEGER_RING; SUBSET_UNIV; IN_SING] THEN
  REWRITE_TAC[RING_OF_INT_OF_NUM; RING_OF_NUM_EQ_0] THEN
  FIRST_ASSUM(fun th -> REWRITE_TAC[CONJUNCT1(REWRITE_RULE[number_field] th)])
  THEN ASM_REWRITE_TAC[DIVIDES_ZERO]);;

let NUMBER_FIELD_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED = prove
 (`!k:A ring l:B ring h p.
        field k /\ number_field l /\ ring_homomorphism(k,l) h /\
        ring_ideal (ring_of_integers k) p /\ ~(p = {ring_0 k})
        ==> (unramified (ring_of_integers k,ring_of_integers l) h p <=>
             weakly_unramified (ring_of_integers k,ring_of_integers l) h p)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC RING_OF_INTEGERS_UNRAMIFIED_EQ_WEAKLY_UNRAMIFIED THEN
  ASM_REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_SING] THEN DISCH_TAC THEN
  UNDISCH_TAC `~(p = {ring_0(k:A ring)})` THEN REWRITE_TAC[] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [ALL_TAC;
    REWRITE_TAC[SING_SUBSET] THEN
    ASM_MESON_TAC[IN_RING_IDEAL_0; RING_OF_INTEGERS]] THEN
  REWRITE_TAC[SUBSET; IN_SING] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; RING_OF_INTEGERS_SUBSET; SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`]
    FIELD_RING_HOMOMORPHISM_MONOMORPHISM) THEN
  ASM_SIMP_TAC[FIELD_IMP_NONTRIVIAL_RING; NUMBER_FIELD_IMP_FIELD] THEN
  REWRITE_TAC[ring_monomorphism] THEN STRIP_TAC THEN
  FIRST_X_ASSUM MATCH_MP_TAC THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`] RING_HOMOMORPHISM_0) THEN
  ASM_SIMP_TAC[RING_0]);;

(* ------------------------------------------------------------------------- *)
(* The types when the extended ideal is principal; the case of Z.            *)
(* ------------------------------------------------------------------------- *)

(* If p s = (c), the primes above p are those containing c, and the types    *)
(* can be read off any functions e, f equal to e(P|p), f(P|p) on them.       *)

let SPLITTING_TYPES_PRINCIPAL = prove
 (`!r:A ring s:B ring h p c e f.
        IMAGE h p SUBSET ring_carrier s /\ c IN ring_carrier s /\
        ideal_generated s (IMAGE h p) = ideal_generated s {c} /\
        (!P. prime_ideal s P /\ c IN P
             ==> ramification_index (r,s) h P = e P /\
                 residue_degree (r,s) h P = f P)
        ==> (weakly_unramified (r,s) h p <=>
             !P. prime_ideal s P /\ c IN P ==> e P = 1) /\
            (totally_split (r,s) h p <=>
             !P. prime_ideal s P /\ c IN P ==> e P = 1 /\ f P = 1) /\
            (inert (r,s) h p <=>
             prime_ideal s (ideal_generated s {c})) /\
            (totally_ramified (r,s) h p <=>
             ?P. {Q | prime_ideal s Q /\ c IN Q} = {P} /\ f P = 1)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `!P. prime_ideal s P ==> (IMAGE (h:A->B) p SUBSET P <=> c IN P)`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:B->bool` THEN
    DISCH_THEN(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
    TRANS_TAC EQ_TRANS `ideal_generated s (IMAGE (h:A->B) p) SUBSET P` THEN
    CONJ_TAC THENL [ALL_TAC; ASM_REWRITE_TAC[]] THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL_EQ] THEN ASM SET_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[weakly_unramified; totally_split; inert;
              totally_ramified] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `{Q | prime_ideal s Q /\ IMAGE (h:A->B) p SUBSET Q} =
    {Q | prime_ideal s Q /\ c IN Q}`
  SUBST1_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  REPEAT CONJ_TAC THEN AP_TERM_TAC THEN ABS_TAC THENL
   [ASM_CASES_TAC `prime_ideal s (P:B->bool)` THEN ASM_SIMP_TAC[];
    ASM_CASES_TAC `prime_ideal s (P:B->bool)` THEN ASM_SIMP_TAC[];
    ASM_CASES_TAC `{Q | prime_ideal s Q /\ c IN Q} = {P:B->bool}` THEN
    ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN `(P:B->bool) IN {Q | prime_ideal s Q /\ c IN Q}` MP_TAC
    THENL [ASM_REWRITE_TAC[IN_SING]; REWRITE_TAC[IN_ELIM_THM]] THEN
    DISCH_THEN(fun th -> ASM_SIMP_TAC[th])]);;

let SPLITTING_TYPES_INTEGER_RING = prove
 (`!r:A ring p.
        prime p
        ==> (weakly_unramified (integer_ring,r) (ring_of_int r)
               (ideal_generated integer_ring {&p}) <=>
             !P. prime_ideal r P /\ ring_of_num r p IN P
                 ==> ramification_index (integer_ring,r) (ring_of_int r) P =
                     1) /\
            (totally_split (integer_ring,r) (ring_of_int r)
               (ideal_generated integer_ring {&p}) <=>
             !P. prime_ideal r P /\ ring_of_num r p IN P
                 ==> ramification_index (integer_ring,r) (ring_of_int r) P =
                     1 /\
                     residue_degree (integer_ring,r) (ring_of_int r) P = 1) /\
            (inert (integer_ring,r) (ring_of_int r)
               (ideal_generated integer_ring {&p}) <=>
             prime_ideal r (ideal_generated r {ring_of_num r p})) /\
            (totally_ramified (integer_ring,r) (ring_of_int r)
               (ideal_generated integer_ring {&p}) <=>
             ?P. {Q | prime_ideal r Q /\ ring_of_num r p IN Q} = {P} /\
                 residue_degree (integer_ring,r) (ring_of_int r) P = 1)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  MATCH_MP_TAC SPLITTING_TYPES_PRINCIPAL THEN
  REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; RING_OF_INT; RING_OF_NUM] THEN
  MP_TAC(ISPECL [`integer_ring`; `r:A ring`; `ring_of_int r:int->A`;
                 `{&p:int}`] IDEAL_GENERATED_IMAGE_IDEAL_GENERATED) THEN
  REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; INTEGER_RING;
              SUBSET_UNIV; IMAGE_CLAUSES; RING_OF_INT_OF_NUM]);;

(* ------------------------------------------------------------------------- *)
(* The characterizations, from a factorization and the identity.             *)
(* ------------------------------------------------------------------------- *)

(* The types in terms of a finite set S of primes with exponents e and       *)
(* degrees f >= 1, such that j = product of the P^e(P) over S is the only    *)
(* such factorization of j, and the identity sum e f = n.                    *)

let IDEAL_PRODUCT_SPLITTING_TYPES = prove
 (`!s:B ring S j e f n.
        FINITE S /\ ~(S = {}) /\
        (!P. P IN S ==> prime_ideal s P /\ 1 <= e P /\ 1 <= f P) /\
        j = ideal_product s S (\P. ideal_pow s P (e P)) /\
        (!t d. FINITE t /\ (!P. P IN t ==> prime_ideal s P /\ ~(d P = 0)) /\
               j = ideal_product s t (\P. ideal_pow s P (d P))
               ==> t = S /\ !P. P IN t ==> e P = d P) /\
        nsum S (\P. e P * f P) = n
        ==> ((!P. P IN S ==> e P = 1) <=> j = ideal_product s S (\P. P)) /\
            ((!P. P IN S ==> e P = 1 /\ f P = 1) <=> CARD S = n) /\
            (prime_ideal s j <=> ?P. S = {P} /\ f P = n) /\
            ((?P. S = {P} /\ f P = 1) <=> ?P. S = {P} /\ e P = n) /\
            ((?P. S = {P} /\ f P = 1) <=>
             ?P. prime_ideal s P /\ j = ideal_pow s P n) /\
            (prime_ideal s j ==> !P. P IN S ==> e P = 1) /\
            (1 < n
             ==> ((?P. S = {P} /\ f P = 1) ==> ~(!P. P IN S ==> e P = 1)) /\
                 ~((!P. P IN S ==> e P = 1 /\ f P = 1) /\ prime_ideal s j) /\
                 ~((!P. P IN S ==> e P = 1 /\ f P = 1) /\
                   (?P. S = {P} /\ f P = 1)) /\
                 ~(prime_ideal s j /\ (?P. S = {P} /\ f P = 1)))`,
  REPEAT GEN_TAC THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 (ASSUME_TAC o SYM)
   (CONJUNCTS_THEN2 MP_TAC ASSUME_TAC))))) THEN
  (* Counting: n = CARD S + the sum of the e f - 1. *)
  SUBGOAL_THEN
   `~(n = 0) /\
    ((!P. P IN S ==> (e:(B->bool)->num) P = 1 /\ (f:(B->bool)->num) P = 1) <=>
     CARD(S:(B->bool)->bool) = n)`
  STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `n = CARD(S:(B->bool)->bool) +
                      nsum S (\P. (e:(B->bool)->num) P * f P - 1)`
    SUBST1_TAC THENL
     [FIRST_X_ASSUM(SUBST1_TAC o SYM o
        check (fun th -> rhs(concl th) = `n:num`)) THEN
      ASM_SIMP_TAC[CARD_EQ_NSUM; GSYM NSUM_ADD] THEN
      MATCH_MP_TAC NSUM_EQ THEN X_GEN_TAC `P:B->bool` THEN
      DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN
      REWRITE_TAC[] THEN STRIP_TAC THEN
      MATCH_MP_TAC(ARITH_RULE `~(x = 0) ==> x = 1 + (x - 1)`) THEN
      REWRITE_TAC[MULT_EQ_0; DE_MORGAN_THM] THEN
      UNDISCH_TAC `1 <= (e:(B->bool)->num) P` THEN
      UNDISCH_TAC `1 <= (f:(B->bool)->num) P` THEN ARITH_TAC;
      ASM_SIMP_TAC[ARITH_RULE `a + b = 0 <=> a = 0 /\ b = 0`; CARD_EQ_0;
                   ARITH_RULE `a = a + b <=> b = 0`; NSUM_EQ_0_IFF] THEN
      AP_TERM_TAC THEN ABS_TAC THEN
      ASM_CASES_TAC `(P:B->bool) IN S` THEN ASM_REWRITE_TAC[] THEN
      FIRST_ASSUM(MP_TAC o C MATCH_MP (ASSUME `(P:B->bool) IN S`)) THEN
      REWRITE_TAC[ARITH_RULE `x - 1 = 0 <=> x = 0 \/ x = 1`; MULT_EQ_0;
                  MULT_EQ_1] THEN
      ARITH_TAC];
    ALL_TAC] THEN
  (* Two instances of the uniqueness: exponents 1, and a single prime. *)
  DISCH_THEN(fun th ->
    MP_TAC(SPECL [`S:(B->bool)->bool`; `\P:B->bool. 1`] th) THEN
    MP_TAC(GEN `P:B->bool` (GEN `m:num`
      (SPECL [`{P:B->bool}`; `\Q:B->bool. (m:num)`] th)))) THEN
  REWRITE_TAC[FINITE_SING; FORALL_IN_INSERT; NOT_IN_EMPTY] THEN
  SIMP_TAC[IDEAL_PRODUCT_SING; RING_IDEAL_IDEAL_POW] THEN DISCH_TAC THEN
  REWRITE_TAC[ARITH_EQ; IMP_CONJ; ASSUME `FINITE(S:(B->bool)->bool)`] THEN
  ANTS_TAC THENL
   [X_GEN_TAC `P:B->bool` THEN
    DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN SIMP_TAC[];
    DISCH_TAC] THEN
  (* Unramified. *)
  SUBGOAL_THEN
   `(!P. P IN S ==> (e:(B->bool)->num) P = 1) <=>
    j = ideal_product (s:B ring) S (\P. P)`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `ideal_product s S (\P. P) =
      ideal_product (s:B ring) S (\P. ideal_pow s P 1)`
    SUBST1_TAC THENL
     [MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN X_GEN_TAC `P:B->bool` THEN
      DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN
      SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL];
      EQ_TAC THEN ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
      FIRST_ASSUM(SUBST1_TAC o SYM o
        check (fun th -> rhs(concl th) = `j:B->bool`)) THEN
      MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN X_GEN_TAC `P:B->bool` THEN
      DISCH_THEN(fun th -> FIRST_X_ASSUM(MP_TAC o C MATCH_MP th)) THEN
      SIMP_TAC[]];
    ALL_TAC] THEN
  (* A single prime above p; the case of j prime. *)
  SUBGOAL_THEN
   `!P. S = {P}
        ==> prime_ideal (s:B ring) P /\ j = ideal_pow s P (e P) /\
            e P * (f:(B->bool)->num) P = n /\ 1 <= e P /\ 1 <= f P`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:B->bool` THEN DISCH_THEN SUBST_ALL_TAC THEN
    RULE_ASSUM_TAC(SIMP_RULE[NSUM_SING; FORALL_IN_INSERT; NOT_IN_EMPTY;
                             IDEAL_PRODUCT_SING; RING_IDEAL_IDEAL_POW]) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `prime_ideal (s:B ring) j
    ==> (S:(B->bool)->bool) = {j} /\ (e:(B->bool)->num) j = 1`
  ASSUME_TAC THENL
   [DISCH_TAC THEN FIRST_ASSUM(MP_TAC o SPECL [`j:B->bool`; `1`]) THEN
    SIMP_TAC[ARITH_EQ; IDEAL_POW_1; PRIME_IMP_RING_IDEAL;
             ASSUME `prime_ideal (s:B ring) j`] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  (* Inert. *)
  SUBGOAL_THEN
   `prime_ideal (s:B ring) j <=>
    ?P. (S:(B->bool)->bool) = {P} /\ (f:(B->bool)->num) P = n`
  ASSUME_TAC THENL
   [EQ_TAC THENL
     [DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN
      DISCH_THEN(fun th -> EXISTS_TAC `j:B->bool` THEN
        REWRITE_TAC[CONJUNCT1 th] THEN
        FIRST_ASSUM(MP_TAC o CONJUNCT1 o CONJUNCT2 o CONJUNCT2 o
                    C MATCH_MP (CONJUNCT1 th)) THEN
        REWRITE_TAC[CONJUNCT2 th; MULT_CLAUSES]);
      DISCH_THEN(X_CHOOSE_THEN `P:B->bool` STRIP_ASSUME_TAC) THEN
      FIRST_ASSUM(MP_TAC o C MATCH_MP (ASSUME `S = {P:B->bool}`)) THEN
      ASM_REWRITE_TAC[] THEN
      REWRITE_TAC[ARITH_RULE `a * b = b <=> a * b = 1 * b`;
                  EQ_MULT_RCANCEL] THEN
      ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
      ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL]];
    ALL_TAC] THEN
  (* Totally ramified: for a single prime, f = 1 iff e = n. *)
  SUBGOAL_THEN
   `!P. S = {P} ==> ((f:(B->bool)->num) P = 1 <=> (e:(B->bool)->num) P = n)`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:B->bool` THEN
    DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN
    STRIP_TAC THEN FIRST_X_ASSUM(SUBST1_TAC o SYM o
      check (fun th -> rhs(concl th) = `n:num`)) THEN
    REWRITE_TAC[ARITH_RULE `a = a * b <=> a * b = a * 1`; EQ_MULT_LCANCEL] THEN
    UNDISCH_TAC `1 <= (e:(B->bool)->num) P` THEN ARITH_TAC;
    ALL_TAC] THEN
  REPEAT CONJ_TAC THEN TRY(FIRST_ASSUM ACCEPT_TAC) THENL
   [AP_TERM_TAC THEN ABS_TAC THEN
    MATCH_MP_TAC(TAUT `(a ==> (b <=> c)) ==> (a /\ b <=> a /\ c)`) THEN
    FIRST_ASSUM MATCH_ACCEPT_TAC;
    EQ_TAC THEN DISCH_THEN(X_CHOOSE_THEN `P:B->bool` STRIP_ASSUME_TAC) THEN
    EXISTS_TAC `P:B->bool` THENL
     [FIRST_ASSUM(MP_TAC o C MATCH_MP (ASSUME `S = {P:B->bool}`) o
                  check (is_conj o rand o snd o strip_forall o concl)) THEN
      ASM_REWRITE_TAC[MULT_CLAUSES] THEN STRIP_TAC THEN ASM_REWRITE_TAC[];
      FIRST_ASSUM(MP_TAC o SPECL [`P:B->bool`; `n:num`]) THEN
      REWRITE_TAC[ASSUME `prime_ideal (s:B ring) P`; ASSUME `~(n = 0)`;
                  ASSUME `j = ideal_pow (s:B ring) P n`] THEN
      DISCH_THEN(CONJUNCTS_THEN2 (ASSUME_TAC o SYM) ASSUME_TAC) THEN
      ASM_REWRITE_TAC[] THEN
      FIRST_ASSUM(MP_TAC o C MATCH_MP (ASSUME `S = {P:B->bool}`)) THEN
      ASM_REWRITE_TAC[]];
    DISCH_THEN(fun th -> FIRST_ASSUM(MP_TAC o C MATCH_MP th)) THEN
    DISCH_THEN(CONJUNCTS_THEN2 SUBST1_TAC ASSUME_TAC) THEN
    REWRITE_TAC[IN_SING] THEN GEN_TAC THEN DISCH_THEN SUBST1_TAC THEN
    ASM_REWRITE_TAC[];
    DISCH_TAC THEN REPEAT CONJ_TAC THENL
     [DISCH_THEN(X_CHOOSE_THEN `P:B->bool` STRIP_ASSUME_TAC) THEN
      DISCH_THEN(MP_TAC o SPEC `P:B->bool`) THEN
      FIRST_ASSUM(MP_TAC o C MATCH_MP (ASSUME `S = {P:B->bool}`)) THEN
      ASM_REWRITE_TAC[IN_SING] THEN UNDISCH_TAC `1 < n` THEN ARITH_TAC;
      ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
      UNDISCH_TAC `CARD(S:(B->bool)->bool) = n` THEN
      ASM_REWRITE_TAC[CARD_SING] THEN UNDISCH_TAC `1 < n` THEN ARITH_TAC;
      ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
      UNDISCH_TAC `CARD(S:(B->bool)->bool) = n` THEN
      ASM_REWRITE_TAC[CARD_SING] THEN UNDISCH_TAC `1 < n` THEN ARITH_TAC;
      ASM_REWRITE_TAC[] THEN
      DISCH_THEN(CONJUNCTS_THEN2
       (X_CHOOSE_THEN `P:B->bool` STRIP_ASSUME_TAC)
       (X_CHOOSE_THEN `Q:B->bool` STRIP_ASSUME_TAC)) THEN
      SUBGOAL_THEN `(P:B->bool) IN S` MP_TAC THENL
       [REWRITE_TAC[ASSUME `S = {P:B->bool}`; IN_SING]; ALL_TAC] THEN
      REWRITE_TAC[ASSUME `S = {Q:B->bool}`; IN_SING] THEN
      DISCH_THEN SUBST_ALL_TAC THEN
      UNDISCH_TAC `(f:(B->bool)->num) Q = n` THEN ASM_REWRITE_TAC[] THEN
      UNDISCH_TAC `1 < n` THEN ARITH_TAC]]);;

