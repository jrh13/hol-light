  ASM_SIMP_TAC[RING_IDEAL_IDEAL_PROD; RING_MUL; IDEAL_PROD_EQ_ZERO;
               INTEGRAL_DOMAIN_MUL_EQ_0] THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC(SET_RULE
     `!a z s:A->bool. a IN s /\ ~(a = z) ==> ~(s = {z})`) THEN
    EXISTS_TAC `b:A` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[IDEAL_PRODUCT_PRIME_MONOMIAL_MUL; MONOMIAL_VAR; IN_ELIM_THM;
               IDEAL_PRODUCT_MONOMIAL_VAR; PRIME_IMP_RING_IDEAL;
               GSYM IDEAL_PROD_PRINCIPAL] THEN
  UNDISCH_THEN `ideal_prod r p q = ideal_generated r {b:A}`
   (SUBST1_TAC o SYM) THEN
  FIRST_X_ASSUM(SUBST1_TAC o SYM o
    check ((=) `ideal_generated r {a:A}` o rand o concl)) THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; PRIME_IMP_RING_IDEAL;
               RING_IDEAL_IDEAL_PRODUCT; RING_IDEAL_IDEAL_PROD]);;

(* Invertibility in ring terms: c = sum u_i v_i with u_i IN j, and c divides *)
(* a v_i for all a IN j (so the v_i / c lie in the inverse of j).            *)

let DEDEKIND_IDEAL_INVERTIBLE = prove
 (`!r j:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?c n u v.
              c IN ring_carrier r /\ ~(c = ring_0 r) /\
              (!i. i < n:num
                   ==> u i IN j /\ v i IN ring_carrier r /\
                       !a. a IN j ==> ring_divides r c (ring_mul r a (v i))) /\
              ring_sum r {i | i < n} (\i. ring_mul r (u i) (v i)) = c`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`l:A->bool`; `c:A`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `l:A->bool`] IDEAL_PROD_EXPLICIT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o AP_TERM `(IN) (c:A)`) THEN
  ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF; IN_ELIM_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `n:num` (X_CHOOSE_THEN `u:num->A`
   (X_CHOOSE_THEN `v:num->A` (CONJUNCTS_THEN2 ASSUME_TAC
     (ASSUME_TAC o SYM))))) THEN
  MAP_EVERY EXISTS_TAC [`c:A`; `n:num`; `u:num->A`; `v:num->A`] THEN
  ASM_REWRITE_TAC[] THEN X_GEN_TAC `i:num` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(u:num->A) i IN j /\ (v:num->A) i IN l` STRIP_ASSUME_TAC
  THENL [ASM_SIMP_TAC[]; ASM_REWRITE_TAC[]] THEN
  SUBGOAL_THEN `(v:num->A) i IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ASM_REWRITE_TAC[]] THEN
  X_GEN_TAC `a:A` THEN DISCH_TAC THEN
  ASM_SIMP_TAC[GSYM IN_IDEAL_GENERATED_SING_EQ] THEN
  UNDISCH_TAC `ideal_prod r j l = ideal_generated r {c:A}` THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
  ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]);;

