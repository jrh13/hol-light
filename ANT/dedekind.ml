               IDEAL_VALUATION_PRIME] THEN
  DISCH_THEN(K ALL_TAC) THEN X_GEN_TAC `q:A->bool` THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `q:A->bool`) THEN ASM_REWRITE_TAC[] THEN
  COND_CASES_TAC THEN ASM_REWRITE_TAC[] THEN ARITH_TAC);;

(* ------------------------------------------------------------------------- *)
(* Radical ideals: a nonzero ideal is radical iff no prime occurs twice in   *)
(* its factorization, iff the quotient ring is reduced.                      *)
(* ------------------------------------------------------------------------- *)

(* In a radical ideal of a Dedekind domain no prime occurs twice: if P^2    *)
(* divided j, an element x of the ideal quotient (j : P) outside j would     *)
(* have its square in P (j : P) = j.                                         *)
let DEDEKIND_RADICAL_IDEAL_VALUATION = prove
 (`!r j P:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r}) /\
        radical r j = j /\ prime_ideal r P /\ ~(P = {ring_0 r})
        ==> ideal_valuation r P j <= 1`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[GSYM NOT_LT] THEN DISCH_TAC THEN
  SUBGOAL_THEN `(j:A->bool) SUBSET P` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `j:A->bool`; `1`]
      DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL] THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  ABBREV_TAC `k = ideal_quotient r j (P:A->bool)` THEN
  SUBGOAL_THEN `ring_ideal r (k:A->bool) /\ (j:A->bool) SUBSET k`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "k" THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_QUOTIENT; IDEAL_SUBSET_IDEAL_QUOTIENT;
                 PRIME_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(k = {ring_0 r:A})` ASSUME_TAC THENL
   [DISCH_THEN SUBST_ALL_TAC THEN UNDISCH_TAC `~(j = {ring_0 r:A})` THEN
    REWRITE_TAC[] THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
    ASM_SIMP_TAC[SING_SUBSET; IN_RING_IDEAL_0];
    ALL_TAC] THEN
  SUBGOAL_THEN `ideal_prod r P k = (j:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "k" THEN MATCH_MP_TAC DEDEKIND_IDEAL_PROD_IDEAL_QUOTIENT THEN
    ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ideal_valuation r P (j:A->bool) = 1 + ideal_valuation r P k`
  ASSUME_TAC THENL
   [FIRST_X_ASSUM(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV)
      [SYM th]) THEN
    ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PROD; IDEAL_VALUATION_PRIME;
                 PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  SUBGOAL_THEN `(k:A->bool) SUBSET P` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `k:A->bool`; `1`]
      DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL] THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `?x:A. x IN k /\ ~(x IN j)` STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(SET_RULE
     `~(k SUBSET j) ==> ?x:A. x IN k /\ ~(x IN j)`) THEN
    DISCH_TAC THEN SUBGOAL_THEN `k:A->bool = j` SUBST_ALL_TAC THENL
     [ASM_REWRITE_TAC[GSYM SUBSET_ANTISYM_EQ]; ASM_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `k:A->bool`] RING_IDEAL_IMP_SUBSET) THEN
    ASM_REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(x:A) IN radical r j` MP_TAC THENL
   [REWRITE_TAC[radical; IN_ELIM_THM] THEN ASM_REWRITE_TAC[] THEN
    EXISTS_TAC `2` THEN ASM_SIMP_TAC[RING_POW_2; ARITH_EQ] THEN
    UNDISCH_THEN `ideal_prod r P k = (j:A->bool)` (SUBST1_TAC o SYM) THEN
    MATCH_MP_TAC(SET_RULE `!s t. x IN s /\ s SUBSET t ==> (x:A) IN t`) THEN
    EXISTS_TAC `ideal_prod r k (k:A->bool)` THEN
    ASM_SIMP_TAC[RING_MUL_IN_IDEAL_PROD; IDEAL_PROD_MONO; SUBSET_REFL];
    ASM_REWRITE_TAC[]]);;

(* The radical ideals of a Dedekind domain are the squarefree ideals.       *)
let DEDEKIND_RADICAL_IDEAL = prove
 (`!r j:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> (radical r j = j <=>
             !P. prime_ideal r P /\ ~(P = {ring_0 r})
                 ==> ideal_valuation r P j <= 1)`,
  REPEAT STRIP_TAC THEN EQ_TAC THENL
   [REPEAT STRIP_TAC THEN MATCH_MP_TAC DEDEKIND_RADICAL_IDEAL_VALUATION THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!P. prime_ideal r P /\ ~(P = {ring_0 r})
        ==> (j SUBSET P <=> 1 <= ideal_valuation r P (j:A->bool))`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `j:A->bool`; `1`]
      DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  DISCH_TAC THEN REWRITE_TAC[GSYM SUBSET_ANTISYM_EQ] THEN
  ASM_SIMP_TAC[RADICAL_SUBSET; RING_IDEAL_IMP_SUBSET] THEN
  REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN
  REWRITE_TAC[radical; IN_ELIM_THM] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
   (X_CHOOSE_THEN `N:num` STRIP_ASSUME_TAC)) THEN
  ASM_CASES_TAC `x = ring_0 r:A` THEN ASM_SIMP_TAC[IN_RING_IDEAL_0] THEN
  SUBGOAL_THEN `ideal_generated r {x:A} SUBSET j` MP_TAC THENL
   [ALL_TAC;
    MATCH_MP_TAC(SET_RULE `x IN s ==> s SUBSET t ==> (x:A) IN t`) THEN
    MATCH_MP_TAC IDEAL_GENERATED_INC THEN
    ASM_REWRITE_TAC[SING_SUBSET; IN_SING]] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {x:A}`; `j:A->bool`]
    DEDEKIND_IDEAL_SUBSET_VALUATION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0] THEN
  DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`) THEN ASM_REWRITE_TAC[] THEN
  ASM_CASES_TAC `ideal_valuation r P (j:A->bool) = 0` THEN
  ASM_REWRITE_TAC[LE_0] THEN DISCH_TAC THEN
  SUBGOAL_THEN `ideal_valuation r P (j:A->bool) = 1` SUBST1_TAC THENL
   [ASM_ARITH_TAC; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `ideal_generated r {x:A}`; `1`]
    DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
  ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL; RING_IDEAL_IDEAL_GENERATED;
               IDEAL_GENERATED_EQ_0] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; SING_SUBSET] THEN
  MP_TAC(ISPECL [`r:A ring`; `P:A->bool`] RADICAL_PRIME_IDEAL) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  REWRITE_TAC[radical; IN_ELIM_THM] THEN ASM_REWRITE_TAC[] THEN
  EXISTS_TAC `N:num` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(j:A->bool) SUBSET P` MP_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool`) THEN ASM_REWRITE_TAC[] THEN
    DISCH_THEN SUBST1_TAC THEN ASM_ARITH_TAC;
    REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[]]);;

let DEDEKIND_QUOTIENT_RING_REDUCED = prove
 (`!r j:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ((!x. ring_nilpotent (quotient_ring r j) x
                  ==> x = ring_0(quotient_ring r j)) <=>
             !P. prime_ideal r P /\ ~(P = {ring_0 r})
                 ==> ideal_valuation r P j <= 1)`,
  SIMP_TAC[QUOTIENT_RING_REDUCED; DEDEKIND_RADICAL_IDEAL]);;

(* ------------------------------------------------------------------------- *)
(* Sums, intersections and products.                                         *)
(* ------------------------------------------------------------------------- *)

let DEDEKIND_IDEAL_PROD_SETADD_INTER = prove
 (`!r j k:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ring_ideal r k
        ==> ideal_prod r (ring_setadd r j k) (j INTER k) = ideal_prod r j k`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `j = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    ASM_SIMP_TAC[RING_SETADD_LZERO; IDEAL_PROD_LZERO; IDEAL_PROD_RZERO;
                 RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0;
                 SET_RULE `(z:A) IN k ==> {z} INTER k = {z}`];
    ALL_TAC] THEN
  ASM_CASES_TAC `k = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    ASM_SIMP_TAC[RING_SETADD_RZERO; IDEAL_PROD_RZERO;
                 RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0;
                 SET_RULE `(z:A) IN j ==> j INTER {z} = {z}`];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_ideal r (ring_setadd r j k) /\ ~(ring_setadd r j k = {ring_0 r}) /\
    ring_ideal r (j INTER k) /\ ~(j INTER k = {ring_0 r:A})`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_SETADD; RING_IDEAL_INTER] THEN
    CONJ_TAC THEN MATCH_MP_TAC(SET_RULE
     `!j k z:A. j SUBSET k /\ ~(j = {z}) /\ z IN j ==> ~(k = {z})`) THENL
     [EXISTS_TAC `j:A->bool` THEN
      ASM_SIMP_TAC[RING_SETADD_SUPERSET_LEFT; RING_IDEAL_IMP_SUBSET;
                   IN_RING_IDEAL_0];
      EXISTS_TAC `ideal_prod r j k:A->bool` THEN
      ASM_SIMP_TAC[IDEAL_PROD_SUBSET_INTER; IDEAL_PROD_EQ_ZERO;
                   DEDEKIND_IMP_INTEGRAL_DOMAIN; IN_RING_IDEAL_0;
                   RING_IDEAL_IDEAL_PROD]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`;
                 `ideal_prod r (ring_setadd r j k) (j INTER k):A->bool`;
                 `ideal_prod r j k:A->bool`] DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_PROD; IDEAL_PROD_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PROD; IDEAL_VALUATION_SETADD;
               IDEAL_VALUATION_INTER] THEN
  ARITH_TAC);;

let DEDEKIND_IDEAL_PROD_INTER = prove
 (`!r j k l:A->bool.
        dedekind_domain r /\
        ring_ideal r j /\ ring_ideal r k /\ ring_ideal r l
        ==> ideal_prod r j (k INTER l) =
            ideal_prod r j k INTER ideal_prod r j l`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `j = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    ASM_SIMP_TAC[IDEAL_PROD_LZERO; RING_IDEAL_IMP_SUBSET; RING_IDEAL_INTER;
                 INTER_IDEMPOT];
    ALL_TAC] THEN
  ASM_CASES_TAC `k = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    ASM_SIMP_TAC[IDEAL_PROD_RZERO; RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0;
                 RING_IDEAL_IDEAL_PROD;
                 SET_RULE `(z:A) IN k ==> {z} INTER k = {z}`];
    ALL_TAC] THEN
  ASM_CASES_TAC `l = {ring_0 r:A}` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN
    ASM_SIMP_TAC[IDEAL_PROD_RZERO; RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0;
                 RING_IDEAL_IDEAL_PROD;
                 SET_RULE `(z:A) IN k ==> k INTER {z} = {z}`];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_ideal r (k INTER l) /\ ~(k INTER l = {ring_0 r:A}) /\
    ring_ideal r (ideal_prod r j k INTER ideal_prod r j l) /\
    ~(ideal_prod r j k INTER ideal_prod r j l = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_INTER; RING_IDEAL_IDEAL_PROD] THEN
    CONJ_TAC THEN MATCH_MP_TAC(SET_RULE
     `!j k z:A. j SUBSET k /\ ~(j = {z}) /\ z IN j ==> ~(k = {z})`) THENL
     [EXISTS_TAC `ideal_prod r k l:A->bool`;
      EXISTS_TAC
       `ideal_prod r (ideal_prod r j k) (ideal_prod r j l):A->bool`] THEN
    ASM_SIMP_TAC[IDEAL_PROD_SUBSET_INTER; IDEAL_PROD_EQ_ZERO;
                 DEDEKIND_IMP_INTEGRAL_DOMAIN; IN_RING_IDEAL_0;
                 RING_IDEAL_IDEAL_PROD];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_prod r j (k INTER l):A->bool`;
                 `ideal_prod r j k INTER ideal_prod r j l:A->bool`]
    DEDEKIND_IDEAL_EQ_VALUATION) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_PROD; IDEAL_PROD_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `p:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PROD; IDEAL_VALUATION_INTER;
               RING_IDEAL_IDEAL_PROD; IDEAL_PROD_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  ARITH_TAC);;

let DEDEKIND_IDEAL_COPRIME_PROD_POW = prove
 (`!r i j c:A->bool n.
        dedekind_domain r /\ ring_ideal r i /\ ring_ideal r j /\
        ring_ideal r c /\ ~(n = 0) /\
        ring_setadd r i j = ring_carrier r /\
        ideal_prod r i j = ideal_pow r c n
        ==> ?a b. ring_ideal r a /\ ring_ideal r b /\
                  i = ideal_pow r a n /\ j = ideal_pow r b n /\
                  c = ideal_prod r a b`,
  let lemma = prove
   (`!n vi vj vc.
        ~(n = 0) /\ vi + vj = n * vc /\ (vi = 0 \/ vj = 0)
        ==> vi = n * MIN vi vc /\ vj = n * MIN vj vc /\
            vc = MIN vi vc + MIN vj vc`,
    REPEAT GEN_TAC THEN DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC MP_TAC) THEN
    SUBGOAL_THEN `vc <= n * vc:num` ASSUME_TAC THENL
     [MATCH_MP_TAC(ARITH_RULE `1 * x <= y ==> x <= y:num`) THEN
      REWRITE_TAC[LE_MULT_RCANCEL] THEN ASM_ARITH_TAC;
      ALL_TAC] THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (DISJ_CASES_THEN SUBST_ALL_TAC)) THEN
    RULE_ASSUM_TAC(REWRITE_RULE[ADD_CLAUSES]) THEN
    FIRST_X_ASSUM(SUBST_ALL_TAC o check (is_eq o concl)) THEN
    ASM_SIMP_TAC[ARITH_RULE `MIN 0 x = 0`; ARITH_RULE `x <= y ==> MIN y x = x`;
                 MULT_CLAUSES; ADD_CLAUSES]) in
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  ASM_CASES_TAC `c = {ring_0 r:A}` THENL
   [MP_TAC(ISPECL [`r:A ring`; `i:A->bool`; `j:A->bool`]
      IDEAL_PROD_EQ_ZERO) THEN
    ASM_SIMP_TAC[IDEAL_POW_EQ_ZERO; RING_IDEAL_0] THEN
    SUBGOAL_THEN `ideal_pow r {ring_0 r:A} n = {ring_0 r}` ASSUME_TAC THENL
     [ASM_SIMP_TAC[IDEAL_POW_EQ_ZERO; RING_IDEAL_0]; ALL_TAC] THEN
    STRIP_TAC THEN
    FIRST_X_ASSUM SUBST_ALL_TAC THENL
     [SUBGOAL_THEN `j = ring_carrier r:A->bool` SUBST1_TAC THENL
       [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (is_eq o concl) o
          check (fun th -> rand(concl th) = `ring_carrier r:A->bool`)) THEN
        ASM_SIMP_TAC[RING_SETADD_LZERO; RING_IDEAL_IMP_SUBSET];
        ALL_TAC] THEN
      MAP_EVERY EXISTS_TAC [`{ring_0 r:A}`; `ring_carrier r:A->bool`] THEN
      ASM_SIMP_TAC[RING_IDEAL_0; RING_IDEAL_CARRIER; IDEAL_POW_EQ_ZERO;
                   IDEAL_POW_CARRIER; IDEAL_PROD_LZERO; SUBSET_REFL];
      SUBGOAL_THEN `i = ring_carrier r:A->bool` SUBST1_TAC THENL
       [FIRST_X_ASSUM(SUBST1_TAC o SYM o check (is_eq o concl) o
          check (fun th -> rand(concl th) = `ring_carrier r:A->bool`)) THEN
        ASM_SIMP_TAC[RING_SETADD_RZERO; RING_IDEAL_IMP_SUBSET];
        ALL_TAC] THEN
      MAP_EVERY EXISTS_TAC [`ring_carrier r:A->bool`; `{ring_0 r:A}`] THEN
      ASM_SIMP_TAC[RING_IDEAL_0; RING_IDEAL_CARRIER; IDEAL_POW_EQ_ZERO;
                   IDEAL_POW_CARRIER; IDEAL_PROD_RZERO; SUBSET_REFL]];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(i = {ring_0 r:A}) /\ ~(j = {ring_0 r})` STRIP_ASSUME_TAC
  THENL
   [MP_TAC(ISPECL [`r:A ring`; `i:A->bool`; `j:A->bool`]
      IDEAL_PROD_EQ_ZERO) THEN
    ASM_SIMP_TAC[IDEAL_POW_EQ_ZERO] THEN MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!P. prime_ideal r P /\ ~(P = {ring_0 r:A})
        ==> ideal_valuation r P i + ideal_valuation r P j =
            n * ideal_valuation r P c /\
            (ideal_valuation r P i = 0 \/ ideal_valuation r P j = 0)`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN CONJ_TAC THENL
     [FIRST_X_ASSUM(MP_TAC o AP_TERM `ideal_valuation r (P:A->bool)` o
        check (fun th -> lhand(concl th) = `ideal_prod r i (j:A->bool)`)) THEN
      ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PROD; IDEAL_VALUATION_IDEAL_POW];
      ASM_SIMP_TAC[IDEAL_VALUATION_EQ_0] THEN
      REWRITE_TAC[GSYM DE_MORGAN_THM] THEN STRIP_TAC THEN
      SUBGOAL_THEN `ring_setadd r i j SUBSET (P:A->bool)` MP_TAC THENL
       [MATCH_MP_TAC RING_SETADD_SUBSET_IDEAL THEN
        ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL];
        ASM_REWRITE_TAC[] THEN
        UNDISCH_TAC `prime_ideal r (P:A->bool)` THEN
        REWRITE_TAC[prime_ideal; proper_ideal] THEN SET_TAC[]]];
    ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC [`ring_setadd r i (c:A->bool)`;
                        `ring_setadd r j (c:A->bool)`] THEN
  ASM_SIMP_TAC[RING_IDEAL_SETADD] THEN
  SUBGOAL_THEN
   `~(ring_setadd r i c = {ring_0 r:A}) /\ ~(ring_setadd r j c = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN DISCH_TAC THENL
     [UNDISCH_TAC `~(i = {ring_0 r:A})`; UNDISCH_TAC `~(j = {ring_0 r:A})`] THEN
    REWRITE_TAC[] THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
    (CONJ_TAC THENL
      [FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
       MATCH_MP_TAC RING_SETADD_SUPERSET_LEFT THEN
       ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; IN_RING_IDEAL_0];
       ASM_MESON_TAC[IN_RING_IDEAL_0; SING_SUBSET]]);
    ALL_TAC] THEN
  REPEAT CONJ_TAC THEN
  W(MP_TAC o PART_MATCH (lhand o rand) DEDEKIND_IDEAL_EQ_VALUATION o snd) THEN
  ASM_SIMP_TAC[RING_IDEAL_SETADD; RING_IDEAL_IDEAL_POW; RING_IDEAL_IDEAL_PROD;
               IDEAL_POW_EQ_ZERO; IDEAL_PROD_EQ_ZERO] THEN
  DISCH_THEN SUBST1_TAC THEN X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_POW; IDEAL_VALUATION_IDEAL_PROD;
               IDEAL_VALUATION_SETADD; RING_IDEAL_SETADD] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `P:A->bool` o check (fun th ->
    is_forall(concl th) && is_imp(snd(dest_forall(concl th))) &&
    is_conj(rand(snd(dest_forall(concl th)))))) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MP_TAC o MATCH_MP lemma o CONJ (ASSUME `~(n = 0)`)) THEN
  MESON_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The ideals containing a power of a nonzero prime.                         *)
(* ------------------------------------------------------------------------- *)

let DEDEKIND_IDEALS_SUPERSET_PRIME_POW = prove
 (`!r p:A->bool n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r})
        ==> {j | ring_ideal r j /\ ideal_pow r p n SUBSET j} =
            {ideal_pow r p m | m <= n} /\
            {j | ring_ideal r j /\ ideal_pow r p n SUBSET j} HAS_SIZE (n + 1)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `p /\ (p ==> q) ==> p /\ q`) THEN CONJ_TAC THENL
   [GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_ELIM_THM] THEN
    X_GEN_TAC `j:A->bool` THEN EQ_TAC THENL
     [STRIP_TAC THEN MATCH_MP_TAC DEDEKIND_IDEAL_SUPERSET_PRIME_POW THEN
      ASM_REWRITE_TAC[];
      DISCH_THEN(X_CHOOSE_THEN `m:num` STRIP_ASSUME_TAC) THEN
      ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL;
                   IDEAL_POW_ANTIMONO; PRIME_IDEAL_IMP_SUBSET]];
    DISCH_THEN SUBST1_TAC THEN ONCE_REWRITE_TAC[SIMPLE_IMAGE_GEN] THEN
    MATCH_MP_TAC HAS_SIZE_IMAGE_INJ THEN REWRITE_TAC[HAS_SIZE_NUMSEG_LE] THEN
    SUBGOAL_THEN `~(p = ring_carrier r:A->bool)` ASSUME_TAC THENL
     [ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL; PROPER_IDEAL_ALT];
      ASM_SIMP_TAC[DEDEKIND_IDEAL_POW_EQ; PRIME_IMP_RING_IDEAL]]]);;

