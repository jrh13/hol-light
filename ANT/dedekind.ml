(* ========================================================================= *)
(* Dedekind domains: invertibility of nonzero ideals, cancellation,          *)
(* containment is divisibility, unique factorization into prime ideals and   *)
(* valuations.                                                               *)
(*                                                                           *)
(*   dedekind_domain r      <=> r is a Noetherian, integrally closed         *)
(*                              integral domain whose nonzero prime ideals   *)
(*                              are maximal (fields included)                *)
(*   ideal_valuation r p j   =  the exponent of p in j: the n with           *)
(*                              j SUBSET p^n but not j SUBSET p^(n+1)        *)
(*                                                                           *)
(* Factorizations are exponent functions: monomials e (in the sense of the   *)
(* library monomial monoid) over the set of nonzero prime ideals, and the    *)
(* ideal of e is ideal_product r (monomial_vars e) (\p. ideal_pow r p (e p)) *)
(* so that monomial_mul corresponds to the product of ideals.                *)
(*                                                                           *)
(* Main results: every nonzero ideal has a nonzero principal multiple        *)
(* (DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) and is invertible                 *)
(* (DEDEKIND_IDEAL_INVERTIBLE, in ring terms), cancellation (so a family of  *)
(* elements, not all 0, has a multiple b_i t = e u_i with e <> 0 and some    *)
(* u_i outside a given proper ideal: DEDEKIND_PRIMITIVE_MULTIPLE),           *)
(* containment is divisibility (DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES), unique   *)
(* factorization (DEDEKIND_IDEAL_FACTORIZATION,                              *)
(* DEDEKIND_IDEAL_FACTORIZATION_UNIQUE; for a finite family of primes, the   *)
(* primes and exponents of a nonzero product of prime powers are determined  *)
(* by the product: DEDEKIND_IDEAL_PRODUCT_PRIME_POW_UNIQUE), containment and *)
(* equality by valuations, valuations of products (also of principal ideals: *)
(* IDEAL_VALUATION_PRINCIPAL_MUL), powers, sums and intersections, ideals    *)
(* containing a prime power; a nonzero ideal is radical iff no prime occurs  *)
(* twice in its factorization (DEDEKIND_RADICAL_IDEAL), iff the quotient     *)
(* ring is reduced (DEDEKIND_QUOTIENT_RING_REDUCED).                         *)
(*                                                                           *)
(* Further corollaries of unique factorization (the last sections): (j +     *)
(* k)(j INTER k) = jk (DEDEKIND_IDEAL_PROD_SETADD_INTER), j(k INTER l) = jk  *)
(* INTER jl (DEDEKIND_IDEAL_PROD_INTER); the ideals containing p^n for a     *)
(* nonzero prime p are exactly p^0, ..., p^n, and there are n + 1 of them    *)
(* (DEDEKIND_IDEALS_SUPERSET_PRIME_POW); valuations of elements, as          *)
(* valuations of principal ideals: x IN p^n iff n <= v_p((x)) for x <> 0     *)
(* (DEDEKIND_IN_IDEAL_POW_VALUATION), divisibility                           *)
(* (DEDEKIND_RING_DIVIDES_VALUATION), the ultrametric inequality and its     *)
(* strict form (IDEAL_VALUATION_PRINCIPAL_ADD,                               *)
(* IDEAL_VALUATION_PRINCIPAL_ADD_STRICT). A property of ideals that holds    *)
(* for the unit ideal and is stable under multiplication by nonzero primes   *)
(* holds for all nonzero ideals (DEDEKIND_IDEAL_INDUCT); the valuation of a  *)
(* finite product of nonzero ideals is the sum of the valuations             *)
(* (IDEAL_VALUATION_IDEAL_PRODUCT) and v_P((a^n)) = n v_P((a)) for nonzero a *)
(* (IDEAL_VALUATION_PRINCIPAL_POW); comaximal ideals whose product is an     *)
(* n-th power c^n, n <> 0, are n-th powers a^n and b^n with c = a b          *)
(* (DEDEKIND_IDEAL_COPRIME_PROD_POW). A nonzero ideal lies in only finitely  *)
(* many primes (IDEAL_VALUATION_FINITE_SUPPORT), the product of the p^e(p)   *)
(* over a finite set of nonzero primes has the valuations e                  *)
(* (DEDEKIND_IDEAL_PRODUCT_PRIME_POWERS), the valuation of a finite product  *)
(* of nonzero elements is the sum (IDEAL_VALUATION_PRINCIPAL_PRODUCT), and   *)
(* if p b = (c) with b generated by t then u IN p iff y u IN (c) for all y   *)
(* in t (DEDEKIND_IDEAL_MEMBER_PRINCIPAL_MULTIPLE). Powers of a nonzero      *)
(* prime p and a uniformizer t IN p DIFF p^2: cancellation                   *)
(* (DEDEKIND_IDEAL_POW_MUL_CANCEL), an s NOTIN p with s p SUBSET (t)         *)
(* (DEDEKIND_PRIME_IDEAL_LOCAL_GENERATOR), p^(n+1) = t p^n + p^(n+2)         *)
(* elementwise (DEDEKIND_IDEAL_POW_UNIFORMIZER_SPLIT), every element of p^n  *)
(* is t^n c modulo p^(n+1) (DEDEKIND_IDEAL_POW_UNIFORMIZER_POW), and a       *)
(* subring containing t and meeting every class modulo p meets every class   *)
(* modulo p^n (DEDEKIND_SUBRING_DENSE).                                      *)
(*                                                                           *)
(* Route: integral closure is used only in INTEGRALLY_CLOSED_DIVIDES_IDEAL   *)
(* (x j SUBSET a j for a nonzero finitely generated ideal j forces a to      *)
(* divide x; the determinant trick in the fraction field). With it, for a    *)
(* maximal ideal m and a nonzero a in m the colon ideal (a):m is an inverse  *)
(* of m up to (a); Noetherian induction then gives the factorization, and    *)
(* monomial induction the invertibility of every nonzero ideal. Valuations   *)
(* are computed on exponent functions (DEDEKIND_IDEAL_PRODUCT_SUBSET_POW).   *)
(* The corollaries of the last sections compare valuations                   *)
(* (DEDEKIND_IDEAL_EQ_VALUATION) with those of sums (MIN), intersections     *)
(* (MAX) and products (sums), zero ideals separately; for elements, x IN p^n *)
(* iff (x) SUBSET p^n (DEDEKIND_IDEAL_SUBSET_POW_VALUATION).                 *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (QUOTIENT_RING_REDUCED),                      *)
(* ANT/integral.ml (integrally_closed, INTEGRAL_ELEMENT_FINITE_MODULE,       *)
(* PID_IMP_INTEGRALLY_CLOSED) and ANT/ideal_arith.ml (products, quotients,   *)
(* powers and finite products of ideals, Noetherian induction).              *)
(* ========================================================================= *)

