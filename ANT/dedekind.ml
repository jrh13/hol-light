  ASM_REWRITE_TAC[PROPER_IDEAL_ALT] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:A->bool` STRIP_ASSUME_TAC) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP (SET_RULE
   `!j z:A. ~(j = {z}) ==> z IN j ==> ?a. a IN j /\ ~(a = z)`)) THEN
  ANTS_TAC THENL [ASM_SIMP_TAC[IN_RING_IDEAL_0]; STRIP_TAC] THEN
  SUBGOAL_THEN `(a:A) IN m /\ a IN ring_carrier r` STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `a:A`]
    DEDEKIND_MAXIMAL_IDEAL_INVERSE) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `q:A->bool` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM(LABEL_TAC "strict" o check (is_forall o concl)) THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `ideal_prod r j q:A->bool`]
    IDEAL_PROD_PRINCIPAL_FACTOR) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN
  DISCH_THEN(MP_TAC o fst o EQ_IMP_RULE) THEN ANTS_TAC THENL
   [UNDISCH_THEN `ideal_prod r m q = ideal_generated r {a:A}`
     (SUBST1_TAC o SYM) THEN
    ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL];
    DISCH_THEN(X_CHOOSE_THEN `l:A->bool` STRIP_ASSUME_TAC)] THEN
  SUBGOAL_THEN `ideal_prod r m l = (j:A->bool)` ASSUME_TAC THENL
   [MATCH_MP_TAC IDEAL_PROD_PRINCIPAL_COFACTOR THEN
    MAP_EVERY EXISTS_TAC [`a:A`; `q:A->bool`] THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN; MAXIMAL_IMP_RING_IDEAL];
    ALL_TAC] THEN
  SUBGOAL_THEN `(j:A->bool) PSUBSET l` ASSUME_TAC THENL
   [REWRITE_TAC[PSUBSET] THEN CONJ_TAC THENL
     [MP_TAC(ISPECL [`r:A ring`; `a:A`; `j:A->bool`; `l:A->bool`]
        IDEAL_PROD_PRINCIPAL_SUBSET_CANCEL) THEN
      ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
      DISCH_THEN(SUBST1_TAC o SYM) THEN
      TRANS_TAC SUBSET_TRANS `ideal_prod r j (ideal_generated r {a:A})` THEN
      ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL] THEN
      MATCH_MP_TAC(SET_RULE `!s t:A->bool. s = t ==> s SUBSET t`) THEN
      MATCH_MP_TAC IDEAL_PROD_COMM THEN
      ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; IDEAL_GENERATED_SUBSET];
      DISCH_THEN SUBST_ALL_TAC THEN
      REMOVE_THEN "strict" (MP_TAC o SPEC `l:A->bool`) THEN
      ASM_REWRITE_TAC[SUBSET_REFL]];
    ALL_TAC] THEN
  REMOVE_THEN "ind" (MP_TAC o SPEC `l:A->bool`) THEN
  ASM_REWRITE_TAC[] THEN ANTS_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->bool)->num` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `prime_ideal r m /\ ~(m = {ring_0(r:A ring)})`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL] THEN
    MATCH_MP_TAC(SET_RULE
     `!a z s:A->bool. a IN s /\ ~(a = z) ==> ~(s = {z})`) THEN
    EXISTS_TAC `a:A` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  EXISTS_TAC `monomial_mul (monomial_var m) (e:(A->bool)->num)` THEN
  ASM_SIMP_TAC[MONOMIAL_MUL; MONOMIAL_VAR; IN_ELIM_THM; PRIME_IMP_RING_IDEAL;
               IDEAL_PRODUCT_PRIME_MONOMIAL_MUL; IDEAL_PRODUCT_MONOMIAL_VAR]);;

