(* The only use of integral closure: x j SUBSET a j for a nonzero finitely   *)
(* generated ideal j forces a to divide x. With j generated by t and a       *)
(* nonzero b in j, the elements g / b (g IN t) of the fraction field span 1  *)
(* and their span is stable under z = x / a, so z is integral                *)
(* (INTEGRAL_ELEMENT_FINITE_MODULE) and hence z is in r. The local lemma     *)
(* does this computation along any ring homomorphism h, given inverses u     *)
(* and w of h(a) and h(b).                                                   *)

let INTEGRALLY_CLOSED_DIVIDES_IDEAL = prove
 (`!r j (a:A) x.
        integrally_closed r /\ finitely_generated_ideal r j /\
        ~(j = {ring_0 r}) /\ a IN ring_carrier r /\ x IN ring_carrier r /\
        IMAGE (ring_mul r x) j SUBSET IMAGE (ring_mul r a) j
        ==> ring_divides r a x`,
  let lemma = prove
   (`!r r' (h:A->B) t a b x u w.
        ring_homomorphism(r,r') h /\ FINITE t /\ t SUBSET ring_carrier r /\
        a IN ring_carrier r /\ x IN ring_carrier r /\
        b IN ideal_generated r t /\
        u IN ring_carrier r' /\ ring_mul r' (h a) u = ring_1 r' /\
        w IN ring_carrier r' /\ ring_mul r' (h b) w = ring_1 r'
        ==> (!y. y IN ideal_generated r t
                 ==> ?z. ring_mul r x y = ring_mul r a z /\
                         z IN ideal_generated r t)
            ==> integral_element (r,r') h (ring_mul r' (h x) u)`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN DISCH_THEN(LABEL_TAC "mul") THEN
    SUBGOAL_THEN `!y. y IN ring_carrier r ==> (h:A->B) y IN ring_carrier r'`
    ASSUME_TAC THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
    SUBGOAL_THEN `!i:A. i IN t ==> i IN ring_carrier r` ASSUME_TAC THENL
     [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN
     `!y. y IN ideal_generated r t
          ==> ?c. (!i. i IN t ==> c i IN ring_carrier r) /\
                  ring_mul r' ((h:A->B) y) w =
                  ring_sum r' t
                   (\i. ring_mul r' (h(c i)) (ring_mul r' (h i) w))`
    (LABEL_TAC "span") THENL
     [MP_TAC(ISPECL [`r:A ring`; `t:A->bool`] IDEAL_GENERATED_FINITE) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN
      REWRITE_TAC[FORALL_IN_GSPEC] THEN X_GEN_TAC `c:A->A` THEN
      DISCH_TAC THEN EXISTS_TAC `c:A->A` THEN ASM_REWRITE_TAC[] THEN
      FIRST_ASSUM(MP_TAC o ISPECL [`\i:A. ring_mul r (c i:A) i`; `t:A->bool`] o
        MATCH_MP RING_HOMOMORPHISM_SUM) THEN
      ASM_SIMP_TAC[RING_MUL] THEN DISCH_THEN SUBST1_TAC THEN
      W(MP_TAC o PART_MATCH (rand o rand) RING_SUM_RMUL o lhand o snd) THEN
      ASM_SIMP_TAC[o_THM; RING_MUL] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
      MATCH_MP_TAC RING_SUM_EQ THEN
      FIRST_ASSUM(fun th -> ASM_SIMP_TAC[o_THM; RING_MUL_ASSOC;
                                         MATCH_MP RING_HOMOMORPHISM_MUL th]);
      ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `r':B ring`; `h:A->B`;
                   `ring_mul r' ((h:A->B) x) u`; `t:A->bool`;
                   `\g:A. ring_mul r' ((h:A->B) g) w`]
           INTEGRAL_ELEMENT_FINITE_MODULE) THEN
    DISCH_THEN MATCH_MP_TAC THEN ASM_SIMP_TAC[RING_MUL] THEN CONJ_TAC THENL
     [REMOVE_THEN "span" (MP_TAC o SPEC `b:A`) THEN ASM_REWRITE_TAC[];
      X_GEN_TAC `g:A` THEN DISCH_TAC THEN
      REMOVE_THEN "mul" (MP_TAC o SPEC `g:A`) THEN
      ASM_SIMP_TAC[IDEAL_GENERATED_INC_GEN] THEN
      DISCH_THEN(X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC) THEN
      SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
       [ASM_MESON_TAC[IDEAL_GENERATED_SUBSET; SUBSET]; ALL_TAC] THEN
      REMOVE_THEN "span" (MP_TAC o SPEC `y:A`) THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `c:A->A` THEN
      DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM)) THEN
      ASM_REWRITE_TAC[] THEN
      MP_TAC(ISPECL [`r':B ring`; `(h:A->B) x`; `u:B`; `(h:A->B) g`;
                     `w:B`; `(h:A->B) a`; `(h:A->B) y`] (RING_RULE
       `!r:B ring hx u hg w ha hy.
          ring_mul r ha u = ring_1 r /\ ring_mul r hx hg = ring_mul r ha hy
          ==> ring_mul r (ring_mul r hx u) (ring_mul r hg w) =
              ring_mul r hy w`)) THEN
      DISCH_THEN(MATCH_MP_TAC o REWRITE_RULE[IMP_IMP]) THEN
      ASM_SIMP_TAC[] THEN
      FIRST_ASSUM(fun th ->
        ASM_SIMP_TAC[GSYM(MATCH_MP RING_HOMOMORPHISM_MUL th)])]) in
  REPEAT GEN_TAC THEN
  REWRITE_TAC[finitely_generated_ideal; IMP_CONJ; LEFT_IMP_EXISTS_THM] THEN
  DISCH_TAC THEN X_GEN_TAC `t:A->bool` THEN
  REPLICATE_TAC 2 DISCH_TAC THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  REPLICATE_TAC 3 DISCH_TAC THEN
  REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_IMAGE] THEN DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o CONJUNCT1 o
    GEN_REWRITE_RULE I [integrally_closed]) THEN
  MP_TAC(SPECL [`ideal_generated r t:A->bool`; `ring_0 r:A`] (SET_RULE
   `!j z:A. ~(j = {z}) /\ z IN j ==> ?b. b IN j /\ ~(b = z)`)) THEN
  ASM_SIMP_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_GENERATED] THEN
  DISCH_THEN(X_CHOOSE_THEN `b:A` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `(b:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[IDEAL_GENERATED_SUBSET; SUBSET]; ALL_TAC] THEN
  ASM_CASES_TAC `a:A = ring_0 r` THENL
   [FIRST_X_ASSUM SUBST_ALL_TAC THEN REWRITE_TAC[RING_DIVIDES_ZERO] THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `b:A` o check (is_forall o concl)) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `y:A` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN `ring_mul r x b = ring_0 r:A` MP_TAC THENL
     [ASM_MESON_TAC[RING_MUL_LZERO; IDEAL_GENERATED_SUBSET; SUBSET];
      ASM_SIMP_TAC[INTEGRAL_DOMAIN_MUL_EQ_0]];
    ALL_TAC] THEN
  MP_TAC(ISPEC `r:A ring` RING_MONOMORPHISM_FRACTIONATE) THEN
  FIRST_X_ASSUM(MP_TAC o CONJUNCT2 o
    GEN_REWRITE_RULE I [integrally_closed]) THEN
  SUBGOAL_THEN
   `!c:A. c IN ring_carrier r /\ ~(c = ring_0 r)
          ==> ring_unit (fraction_ring r)
                (ring_fractionate r {a | ring_regular r a} c)`
  MP_TAC THENL
   [REPEAT STRIP_TAC THEN REWRITE_TAC[fraction_ring] THEN
    MATCH_MP_TAC RING_UNIT_FRACTIONATE THEN
    ASM_SIMP_TAC[RING_MULTSYS_REGULAR; IN_ELIM_THM; INTEGRAL_DOMAIN_REGULAR];
    ALL_TAC] THEN
  SPEC_TAC(`ring_fractionate r {a:A | ring_regular r a}`,`h:A->A#A->bool`) THEN
  SPEC_TAC(`fraction_ring r:(A#A->bool)ring`,`r':(A#A->bool)ring`) THEN
  X_GEN_TAC `r':(A#A->bool)ring` THEN X_GEN_TAC `h:A->A#A->bool` THEN
  DISCH_THEN(LABEL_TAC "unit") THEN REPEAT DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN
   `!y:A. y IN ring_carrier r ==> (h:A->A#A->bool) y IN ring_carrier r'`
  ASSUME_TAC THENL [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
  REMOVE_THEN "unit" (fun th -> MP_TAC(SPEC `a:A` th) THEN
                                MP_TAC(SPEC `b:A` th)) THEN
  ASM_REWRITE_TAC[ring_unit] THEN
  DISCH_THEN(X_CHOOSE_THEN `w:A#A->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
  DISCH_THEN(X_CHOOSE_THEN `u:A#A->bool` STRIP_ASSUME_TAC o CONJUNCT2) THEN
  MP_TAC(ISPECL [`r:A ring`; `r':(A#A->bool)ring`; `h:A->A#A->bool`;
                 `t:A->bool`; `a:A`; `b:A`; `x:A`; `u:A#A->bool`;
                 `w:A#A->bool`] lemma) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(fun th -> FIRST_X_ASSUM(MP_TAC o C MATCH_MP th)) THEN
  REWRITE_TAC[IN_IMAGE; ring_divides] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:A` STRIP_ASSUME_TAC) THEN
  ASM_REWRITE_TAC[] THEN EXISTS_TAC `c:A` THEN ASM_REWRITE_TAC[] THEN
  FIRST_ASSUM(MP_TAC o SPECL [`x:A`; `ring_mul r a c:A`] o MATCH_MP
    (REWRITE_RULE[IMP_CONJ] RING_MONOMORPHISM_INJECTIVE_EQ)) THEN
  ASM_SIMP_TAC[RING_MUL] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  FIRST_ASSUM(fun th -> ASM_SIMP_TAC[MATCH_MP RING_HOMOMORPHISM_MUL th]) THEN
  MP_TAC(ISPECL [`r':(A#A->bool)ring`; `(h:A->A#A->bool) x`; `u:A#A->bool`;
                 `(h:A->A#A->bool) a`; `(h:A->A#A->bool) c`] (RING_RULE
   `!r:B ring hx u ha hc.
      ring_mul r ha u = ring_1 r /\ ring_mul r hx u = hc
      ==> hx = ring_mul r ha hc`)) THEN
  ASM_SIMP_TAC[IMP_IMP]);;

(* The ideal of the exponent function of a single prime, and of a product   *)
(* of exponent functions over the nonzero primes.                            *)

let IDEAL_PRODUCT_MONOMIAL_VAR = prove
 (`!r p:A->bool.
        ring_ideal r p
        ==> ideal_product r (monomial_vars(monomial_var p))
                            (\q. ideal_pow r q (monomial_var p q)) = p`,
  SIMP_TAC[MONOMIAL_VARS_VAR; IDEAL_PRODUCT_SING; RING_IDEAL_IDEAL_POW] THEN
  SIMP_TAC[monomial_var; IDEAL_POW_1]);;

let IDEAL_PRODUCT_PRIME_MONOMIAL_MUL = prove
 (`!r e f:(A->bool)->num.
        monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} e /\
        monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} f
        ==> ideal_product r (monomial_vars(monomial_mul e f))
                            (\p. ideal_pow r p (monomial_mul e f p)) =
            ideal_prod r
              (ideal_product r (monomial_vars e) (\p. ideal_pow r p (e p)))
              (ideal_product r (monomial_vars f) (\p. ideal_pow r p (f p)))`,
  REWRITE_TAC[monomial; SUBSET; IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
  MATCH_MP_TAC IDEAL_PRODUCT_MONOMIAL_MUL THEN
  ASM_MESON_TAC[IN_UNION; PRIME_IMP_RING_IDEAL]);;

(* For a maximal ideal m and a nonzero a in m, the colon ideal (a):m is      *)
(* strictly larger than (a). If not, then b m^n SUBSET (a) gives b SUBSET    *)
(* (a) for all n; applied to a product of primes containing a inside (a),   *)
(* written as m^k b, this puts b inside m, so one of the other primes of     *)
(* the product lies in m and equals m (Krull dimension one).                 *)

let DEDEKIND_IDEAL_QUOTIENT_MAXIMAL_PSUBSET = prove
 (`!r m (a:A).
        dedekind_domain r /\ maximal_ideal r m /\ a IN m /\ ~(a = ring_0 r)
        ==> ideal_generated r {a} PSUBSET
            ideal_quotient r (ideal_generated r {a}) m`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MATCH_MP_TAC(SET_RULE
   `!s t:A->bool. s SUBSET t /\ ~(t SUBSET s) ==> s PSUBSET t`) THEN
  ASM_SIMP_TAC[IDEAL_SUBSET_IDEAL_QUOTIENT; RING_IDEAL_IDEAL_GENERATED;
               RING_IDEAL_IMP_SUBSET] THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `!n b. ring_ideal r b /\
          ideal_prod r (ideal_pow r m n) b SUBSET ideal_generated r {a:A}
          ==> b SUBSET ideal_generated r {a}`
  ASSUME_TAC THENL
   [INDUCT_TAC THENL
     [SIMP_TAC[IDEAL_POW_0; IDEAL_PROD_CARRIER_LEFT; IMP_CONJ]; ALL_TAC] THEN
    X_GEN_TAC `b:A->bool` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `ideal_prod r b (m:A->bool)`) THEN
    ANTS_TAC THENL
     [REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN
      UNDISCH_TAC `ideal_prod r (ideal_pow r m (SUC n)) b SUBSET
                   ideal_generated r {a:A}` THEN
      ASM_SIMP_TAC[IDEAL_POW_SUC; IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET;
                   RING_IDEAL_IDEAL_POW; RING_IDEAL_IDEAL_PROD];
      DISCH_TAC] THEN
    TRANS_TAC SUBSET_TRANS
     `ideal_quotient r (ideal_generated r {a:A}) m` THEN
    ASM_SIMP_TAC[SUBSET_IDEAL_QUOTIENT; RING_IDEAL_IDEAL_GENERATED;
                 RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`]
    NOETHERIAN_PRIME_PRODUCT_SUBSET) THEN
  ASM_SIMP_TAC[DEDEKIND_IMP_NOETHERIAN; RING_IDEAL_IDEAL_GENERATED] THEN
  REWRITE_TAC[monomial; GSYM CONJ_ASSOC; SET_RULE
   `!s P. s SUBSET {x:A->bool | P x} <=> !x. x IN s ==> P x`] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->bool)->num` (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 (LABEL_TAC "vars") MP_TAC))) THEN
  SUBGOAL_THEN `!p:A->bool. p IN m INSERT monomial_vars e
                            ==> ring_ideal r (ideal_pow r p (e p))`
  ASSUME_TAC THENL
   [REWRITE_TAC[FORALL_IN_INSERT] THEN
    ASM_MESON_TAC[RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ideal_product r (monomial_vars e) (\p:A->bool. ideal_pow r p (e p)) =
    ideal_prod r (ideal_pow r m (e m))
     (ideal_product r (monomial_vars e DELETE m) (\p. ideal_pow r p (e p)))`
  SUBST1_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `monomial_vars e DELETE (m:A->bool)`;
                   `\p:A->bool. ideal_pow r p (e p)`; `m:A->bool`]
       IDEAL_PRODUCT_INSERT) THEN
    ASM_SIMP_TAC[FINITE_DELETE; IN_DELETE; IN_INSERT] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    REWRITE_TAC[SET_RULE
     `!x:A->bool s. x INSERT (s DELETE x) = x INSERT s`] THEN
    CONV_TAC SYM_CONV THEN MATCH_MP_TAC IDEAL_PRODUCT_SUPERSET THEN
    ASM_REWRITE_TAC[FINITE_INSERT;
                    SET_RULE `!x:A->bool s. s SUBSET x INSERT s`] THEN
    SIMP_TAC[IN_INSERT; monomial_vars; IN_ELIM_THM; IDEAL_POW_0];
    ALL_TAC] THEN
  DISCH_TAC THEN
  SUBGOAL_THEN
   `ideal_product r (monomial_vars e DELETE m)
      (\p:A->bool. ideal_pow r p (e p)) SUBSET ideal_generated r {a}`
  ASSUME_TAC THENL
   [FIRST_X_ASSUM(MATCH_MP_TAC o SPEC `e(m:A->bool):num`) THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PRODUCT];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`;
                 `monomial_vars e DELETE (m:A->bool)`;
                 `\p:A->bool. ideal_pow r p (e p)`]
     IDEAL_PRODUCT_SUBSET_PRIME_IDEAL) THEN
  ASM_SIMP_TAC[MAXIMAL_IMP_PRIME_IDEAL; FINITE_DELETE; IN_DELETE;
               IN_INSERT] THEN
  MATCH_MP_TAC(TAUT `p /\ ~q ==> ~(p <=> q)`) THEN CONJ_TAC THENL
   [TRANS_TAC SUBSET_TRANS `ideal_generated r {a:A}` THEN
    ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL; SING_SUBSET];
    REWRITE_TAC[NOT_EXISTS_THM] THEN X_GEN_TAC `p:A->bool` THEN
    STRIP_TAC] THEN
  USE_THEN "vars" (STRIP_ASSUME_TAC o C MATCH_MP
   (ASSUME `(p:A->bool) IN monomial_vars e`)) THEN
  MP_TAC(ISPECL [`r:A ring`; `m:A->bool`; `p:A->bool`]
    DEDEKIND_KRULL_DIMENSION_ONE) THEN
  UNDISCH_TAC `ideal_pow r p (e p) SUBSET (m:A->bool)` THEN
  ASM_SIMP_TAC[IDEAL_POW_SUBSET_PRIME_IDEAL; MAXIMAL_IMP_PRIME_IDEAL;
               PRIME_IDEAL_IMP_SUBSET] THEN
  SUBGOAL_THEN `(a:A) IN p` MP_TAC THENL
   [MATCH_MP_TAC(SET_RULE `!x:A s t. x IN s /\ s SUBSET t ==> x IN t`) THEN
    EXISTS_TAC `ideal_generated r {a:A}` THEN
    ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF];
    MAP_EVERY UNDISCH_TAC [`(a:A) IN m`; `~(a:A = ring_0 r)`] THEN
    SET_TAC[]]);;

(* Hence q = (a):m satisfies m q = (a): m q = (a) l with m SUBSET l, and     *)
(* l = m is impossible since then x m SUBSET a m for x IN q, so a divides x *)
(* (INTEGRALLY_CLOSED_DIVIDES_IDEAL) and q SUBSET (a). The same argument     *)
(* shows that j q is never inside (a) j for a nonzero ideal j.               *)

let DEDEKIND_MAXIMAL_IDEAL_INVERSE = prove
 (`!r m (a:A).
        dedekind_domain r /\ maximal_ideal r m /\ a IN m /\ ~(a = ring_0 r)
        ==> ?q. ring_ideal r q /\ ideal_generated r {a} SUBSET q /\
                ideal_prod r m q = ideal_generated r {a} /\
                !j. ring_ideal r j /\ ~(j = {ring_0 r})
                    ==> ~(ideal_prod r j q SUBSET
                          ideal_prod r (ideal_generated r {a}) j)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP MAXIMAL_IMP_RING_IDEAL) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  SUBGOAL_THEN `(a:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(SPECL [`r:A ring`; `m:A->bool`; `a:A`]
    DEDEKIND_IDEAL_QUOTIENT_MAXIMAL_PSUBSET) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(ASSUME_TAC o MATCH_MP (SET_RULE
   `!s t:A->bool. s PSUBSET t ==> ~(t SUBSET s)`)) THEN
  EXISTS_TAC `ideal_quotient r (ideal_generated r {a:A}) m` THEN
  ABBREV_TAC `q = ideal_quotient r (ideal_generated r {a:A}) m` THEN
  SUBGOAL_THEN `ring_ideal r (q:A->bool) /\ ideal_generated r {a} SUBSET q`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_QUOTIENT; IDEAL_SUBSET_IDEAL_QUOTIENT;
                 RING_IDEAL_IDEAL_GENERATED; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!j. ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ~(ideal_prod r j q SUBSET
              ideal_prod r (ideal_generated r {a:A}) j)`
  (LABEL_TAC "strict") THENL
   [X_GEN_TAC `j:A->bool` THEN STRIP_TAC THEN DISCH_TAC THEN
    UNDISCH_TAC `~(q SUBSET ideal_generated r {a:A})` THEN
    REWRITE_TAC[SUBSET] THEN X_GEN_TAC `x:A` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
    ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING_EQ] THEN
    MATCH_MP_TAC INTEGRALLY_CLOSED_DIVIDES_IDEAL THEN
    EXISTS_TAC `j:A->bool` THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRALLY_CLOSED; GSYM IDEAL_PROD_SCALE] THEN
    CONJ_TAC THENL
     [ASM_MESON_TAC[noetherian_ring; DEDEKIND_IMP_NOETHERIAN]; ALL_TAC] THEN
    TRANS_TAC SUBSET_TRANS `ideal_prod r j (q:A->bool)` THEN
    ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN `ideal_prod r (ideal_generated r {x}) j =
                  ideal_prod r j (ideal_generated r {x:A})`
    SUBST1_TAC THENL
     [MATCH_MP_TAC IDEAL_PROD_COMM THEN
      ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; IDEAL_GENERATED_SUBSET];
      MATCH_MP_TAC IDEAL_PROD_MONO THEN
      ASM_SIMP_TAC[SUBSET_REFL; IDEAL_GENERATED_MINIMAL; SING_SUBSET]];
    ASM_REWRITE_TAC[]] THEN
  SUBGOAL_THEN `ideal_prod r m q SUBSET ideal_generated r {a:A}`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `ideal_generated r {a:A}`; `m:A->bool`;
                   `q:A->bool`] SUBSET_IDEAL_QUOTIENT) THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED; RING_IDEAL_IMP_SUBSET;
                 SUBSET_REFL] THEN
    ASM_SIMP_TAC[IDEAL_PROD_COMM; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `ideal_prod r m q:A->bool`]
    IDEAL_PROD_PRINCIPAL_FACTOR) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN
  DISCH_THEN(X_CHOOSE_THEN `l:A->bool` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `m SUBSET (l:A->bool)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `a:A`; `m:A->bool`; `l:A->bool`]
      IDEAL_PROD_PRINCIPAL_SUBSET_CANCEL) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    TRANS_TAC SUBSET_TRANS `ideal_prod r m (ideal_generated r {a:A})` THEN
    ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL] THEN
    MATCH_MP_TAC(SET_RULE `!s t:A->bool. s = t ==> s SUBSET t`) THEN
    MATCH_MP_TAC IDEAL_PROD_COMM THEN
    ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; IDEAL_GENERATED_SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN `l = (m:A->bool) \/ l = ring_carrier r` STRIP_ASSUME_TAC THENL
   [UNDISCH_TAC `maximal_ideal r (m:A->bool)` THEN
    REWRITE_TAC[maximal_ideal; PROPER_IDEAL_ALT; NOT_EXISTS_THM] THEN
    DISCH_THEN(MP_TAC o SPEC `l:A->bool` o CONJUNCT2) THEN
    ASM_REWRITE_TAC[PSUBSET] THEN MESON_TAC[];
    REMOVE_THEN "strict" (MP_TAC o SPEC `m:A->bool`) THEN
    FIRST_X_ASSUM SUBST_ALL_TAC THEN ASM_REWRITE_TAC[SUBSET_REFL] THEN
    MATCH_MP_TAC(TAUT `~p ==> p ==> q`) THEN
    MATCH_MP_TAC(SET_RULE
     `!a z s:A->bool. a IN s /\ ~(a = z) ==> ~(s = {z})`) THEN
    EXISTS_TAC `a:A` THEN ASM_REWRITE_TAC[];
    FIRST_X_ASSUM SUBST_ALL_TAC THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o
      check ((=) `ideal_prod r m (q:A->bool)` o rand o concl)) THEN
    ASM_SIMP_TAC[IDEAL_PROD_CARRIER; RING_IDEAL_IDEAL_GENERATED]]);;

(* Cancellation of a principal factor: if k q = (a) and (a) l = j q then     *)
(* k l = j. With k = m maximal and q = (a):m this writes a nonzero ideal j   *)
(* inside m as m l with l strictly larger than j, which drives the           *)
(* Noetherian induction for the existence of factorizations; multiplying    *)
(* the inverses of the prime factors then gives principal multiples.         *)

let IDEAL_PROD_PRINCIPAL_COFACTOR = prove
 (`!r (a:A) j k q l.
        integral_domain r /\ a IN ring_carrier r /\ ~(a = ring_0 r) /\
        ring_ideal r j /\ ring_ideal r k /\ ring_ideal r q /\ ring_ideal r l /\
        ideal_prod r k q = ideal_generated r {a} /\
        ideal_prod r (ideal_generated r {a}) l = ideal_prod r j q
        ==> ideal_prod r k l = j`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `ideal_prod r k l:A->bool`; `j:A->bool`]
    IDEAL_PROD_PRINCIPAL_CANCEL) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  UNDISCH_THEN `ideal_prod r k q = ideal_generated r {a:A}`
   (fun th -> GEN_REWRITE_TAC (RAND_CONV o LAND_CONV) [SYM th]) THEN
  UNDISCH_THEN
   `ideal_prod r (ideal_generated r {a:A}) l = ideal_prod r j q`
   (MP_TAC o AP_TERM `ideal_prod r (k:A->bool)`) THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET;
               RING_IDEAL_IDEAL_GENERATED; RING_IDEAL_IDEAL_PROD]);;

let DEDEKIND_IDEAL_FACTORIZATION_EXISTS = prove
 (`!r j:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> ?e. monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} e /\
