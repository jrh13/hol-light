  ARITH_TAC);;

let DEDEKIND_IDEAL_FACTORIZATION = prove
 (`!r j:A->bool.
     dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
     ==> FINITE {p | prime_ideal r p /\ ~(p = {ring_0 r}) /\ j SUBSET p} /\
         ideal_product r
           {p | prime_ideal r p /\ ~(p = {ring_0 r}) /\ j SUBSET p}
           (\p. ideal_pow r p (ideal_valuation r p j)) = j`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_FACTORIZATION_EXISTS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->bool)->num`
   (CONJUNCTS_THEN2 ASSUME_TAC (SUBST_ALL_TAC o SYM))) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    REWRITE_RULE[monomial; SUBSET; IN_ELIM_THM]) THEN
  SUBGOAL_THEN
   `{p | prime_ideal r p /\ ~(p = {ring_0 r}) /\
         ideal_product r (monomial_vars e) (\p. ideal_pow r p (e p))
         SUBSET p} =
    monomial_vars (e:(A->bool)->num)`
  SUBST1_TAC THENL
   [GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_ELIM_THM; CONJ_ASSOC] THEN
    X_GEN_TAC `p:A->bool` THEN
    ASM_CASES_TAC `prime_ideal r (p:A->bool) /\ ~(p = {ring_0 r})` THEN
    ASM_REWRITE_TAC[] THENL
     [MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `e:(A->bool)->num`; `1`]
        DEDEKIND_IDEAL_PRODUCT_SUBSET_POW) THEN
      ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL] THEN
      DISCH_THEN(K ALL_TAC) THEN
      REWRITE_TAC[monomial_vars; IN_ELIM_THM] THEN ARITH_TAC;
      ASM_MESON_TAC[]];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN
  X_GEN_TAC `p:A->bool` THEN DISCH_TAC THEN REWRITE_TAC[] THEN
  AP_TERM_TAC THEN MATCH_MP_TAC IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL THEN
  ASM_SIMP_TAC[]);;

let DEDEKIND_IDEAL_FACTORIZATION_UNIQUE = prove
 (`!r j:A->bool.
     dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
     ==> ?!e. monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} e /\
              ideal_product r (monomial_vars e)
                                   (\p. ideal_pow r p (e p)) = j`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
  ASM_SIMP_TAC[DEDEKIND_IDEAL_FACTORIZATION_EXISTS] THEN
  MAP_EVERY X_GEN_TAC [`e:(A->bool)->num`; `f:(A->bool)->num`] THEN
  STRIP_TAC THEN REWRITE_TAC[FUN_EQ_THM] THEN X_GEN_TAC `p:A->bool` THEN
  ASM_CASES_TAC `prime_ideal r (p:A->bool) /\ ~(p = {ring_0 r})` THENL
   [MP_TAC(ISPECL [`r:A ring`; `e:(A->bool)->num`; `p:A->bool`]
      IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL) THEN
    MP_TAC(ISPECL [`r:A ring`; `f:(A->bool)->num`; `p:A->bool`]
      IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL) THEN
    ASM_REWRITE_TAC[] THEN ARITH_TAC;
    RULE_ASSUM_TAC(REWRITE_RULE[monomial; SUBSET; monomial_vars;
                                IN_ELIM_THM]) THEN
    ASM_MESON_TAC[]]);;

let DEDEKIND_IDEAL_SUBSET_POW_VALUATION = prove
 (`!r p (j:A->bool) n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        ring_ideal r j /\ ~(j = {ring_0 r})
        ==> (j SUBSET ideal_pow r p n <=> n <= ideal_valuation r p j)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_FACTORIZATION_EXISTS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->bool)->num`
   (CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM))) THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL;
               DEDEKIND_IDEAL_PRODUCT_SUBSET_POW]);;

let IDEAL_VALUATION_EQ_0 = prove
 (`!r p j:A->bool.
     dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
     ring_ideal r j /\ ~(j = {ring_0 r})
     ==> (ideal_valuation r p j = 0 <=> ~(j SUBSET p))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `j:A->bool`; `1`]
    DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
  ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL] THEN
  DISCH_THEN SUBST1_TAC THEN ARITH_TAC);;

let IDEAL_VALUATION_FINITE_SUPPORT = prove
 (`!r j:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r})
        ==> FINITE {P | prime_ideal r P /\ ~(P = {ring_0 r}) /\
                        ~(ideal_valuation r P j = 0)}`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] DEDEKIND_IDEAL_FACTORIZATION) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o CONJUNCT1) THEN
  MATCH_MP_TAC(REWRITE_RULE[IMP_CONJ_ALT] FINITE_SUBSET) THEN
  GEN_REWRITE_TAC I [SUBSET] THEN REWRITE_TAC[IN_ELIM_THM] THEN
  X_GEN_TAC `P:A->bool` THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `j:A->bool`]
    IDEAL_VALUATION_EQ_0) THEN
  ASM_REWRITE_TAC[]);;

(* The primes and exponents of a nonzero finite product of prime powers are  *)
(* determined by the product: the primes are those containing it, the        *)
(* exponents its valuations.                                                 *)

let DEDEKIND_IDEAL_PRODUCT_PRIME_POW_UNIQUE = prove
 (`!r s (e:(A->bool)->num).
        dedekind_domain r /\ FINITE s /\
        (!P. P IN s ==> prime_ideal r P /\ ~(e P = 0)) /\
        ~(ideal_product r s (\P. ideal_pow r P (e P)) = {ring_0 r})
        ==> (!Q. Q IN s <=>
                 prime_ideal r Q /\ ~(Q = {ring_0 r}) /\
                 ideal_product r s (\P. ideal_pow r P (e P)) SUBSET Q) /\
            (!Q. prime_ideal r Q /\ ~(Q = {ring_0 r})
                 ==> ideal_valuation r Q
                       (ideal_product r s (\P. ideal_pow r P (e P))) =
                     if Q IN s then e Q else 0)`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC `j = ideal_product r s (\P:A->bool. ideal_pow r P (e P))` THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `ring_ideal r (j:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "j" THEN REWRITE_TAC[RING_IDEAL_IDEAL_PRODUCT]; ALL_TAC] THEN
  SUBGOAL_THEN `!P:A->bool. P IN s ==> j SUBSET P /\ ~(P = {ring_0 r})`
  ASSUME_TAC THENL
   [X_GEN_TAC `P:A->bool` THEN DISCH_TAC THEN
    MATCH_MP_TAC(SET_RULE
     `ring_0 r IN j /\ ~(j = {ring_0 r}) /\ j SUBSET P
      ==> j SUBSET P /\ ~(P = {ring_0 r:A})`) THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0] THEN EXPAND_TAC "j" THEN
    TRANS_TAC SUBSET_TRANS `ideal_pow r (P:A->bool) (e P)` THEN
    CONJ_TAC THENL
     [MP_TAC(ISPECL [`r:A ring`; `s:(A->bool)->bool`;
                     `\P. ideal_pow r P ((e:(A->bool)->num) P)`;
                     `P:A->bool`] IDEAL_PRODUCT_SUBSET) THEN
      ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW];
      MP_TAC(ISPECL [`r:A ring`; `P:A->bool`; `P:A->bool`;
                     `(e:(A->bool)->num) P`]
        IDEAL_POW_SUBSET_PRIME_IDEAL) THEN
      ASM_SIMP_TAC[SUBSET_REFL; PRIME_IDEAL_IMP_SUBSET]];
    ALL_TAC] THEN
  MATCH_MP_TAC(TAUT `q /\ (q ==> p) ==> p /\ q`) THEN CONJ_TAC THENL
   [X_GEN_TAC `Q:A->bool` THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `\P:A->bool. if P IN s then e P else 0`;
                   `Q:A->bool`] IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL) THEN
    SUBGOAL_THEN `monomial_vars (\P:A->bool. if P IN s then e P else 0) = s`
    ASSUME_TAC THENL
     [REWRITE_TAC[monomial_vars; EXTENSION; IN_ELIM_THM] THEN
      X_GEN_TAC `P:A->bool` THEN COND_CASES_TAC THEN ASM_SIMP_TAC[];
      ASM_SIMP_TAC[monomial; SUBSET; IN_ELIM_THM]] THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN
    AP_TERM_TAC THEN EXPAND_TAC "j" THEN
    MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN SIMP_TAC[];
    DISCH_TAC THEN X_GEN_TAC `Q:A->bool` THEN
    ASM_CASES_TAC `(Q:A->bool) IN s` THEN ASM_SIMP_TAC[] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `Q:A->bool`; `j:A->bool`]
      IDEAL_VALUATION_EQ_0) THEN
    ASM_SIMP_TAC[]]);;

let DEDEKIND_IDEAL_PRODUCT_PRIME_POWERS = prove
 (`!r t (e:(A->bool)->num).
        dedekind_domain r /\ FINITE t /\
        (!P. P IN t ==> prime_ideal r P /\ ~(P = {ring_0 r}))
        ==> ring_ideal r (ideal_product r t (\P. ideal_pow r P (e P))) /\
            ~(ideal_product r t (\P. ideal_pow r P (e P)) = {ring_0 r}) /\
