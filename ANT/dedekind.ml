let DEDEKIND_IDEAL_POW_MUL_CANCEL = prove
 (`!r p (s:A) x m n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        s IN ring_carrier r /\ ~(s IN ideal_pow r p (m + 1)) /\
        x IN ring_carrier r /\ ring_mul r s x IN ideal_pow r p (m + n)
        ==> x IN ideal_pow r p n`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
  ASM_CASES_TAC `x:A = ring_0 r` THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_POW]; ALL_TAC] THEN
  ASM_CASES_TAC `s:A = ring_0 r` THENL
   [ASM_MESON_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_POW]; ALL_TAC] THEN
  SUBGOAL_THEN `~(ring_mul r s x:A = ring_0 r)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[INTEGRAL_DOMAIN_MUL_EQ_0]; ALL_TAC] THEN
  MAP_EVERY UNDISCH_TAC
   [`ring_mul r (s:A) x IN ideal_pow r p (m + n)`;
    `~((s:A) IN ideal_pow r p (m + 1))`] THEN
  ASM_SIMP_TAC[DEDEKIND_IN_IDEAL_POW_VALUATION; RING_MUL;
               IDEAL_VALUATION_PRINCIPAL_MUL] THEN
  ARITH_TAC);;

let DEDEKIND_PRIME_IDEAL_LOCAL_GENERATOR = prove
 (`!r p (t:A).
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        t IN p /\ ~(t IN ideal_pow r p 2)
        ==> ?s. s IN ring_carrier r /\ ~(s IN p) /\
                !y. y IN p
                    ==> ?z. z IN ring_carrier r /\
                            ring_mul r s y = ring_mul r t z`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `ideal_generated r {t:A} SUBSET p` MP_TAC THENL
   [MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN ASM_REWRITE_TAC[SING_SUBSET];
    ASM_SIMP_TAC[DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES;
                 RING_IDEAL_IDEAL_GENERATED]] THEN
  DISCH_THEN(X_CHOOSE_THEN `j:A->bool` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `~(j SUBSET (p:A->bool))` MP_TAC THENL
   [DISCH_TAC THEN UNDISCH_TAC `~((t:A) IN ideal_pow r p 2)` THEN
    REWRITE_TAC[] THEN
    SUBGOAL_THEN `ideal_prod r p (j:A->bool) SUBSET ideal_pow r p 2`
    MP_TAC THENL
     [REWRITE_TAC[num_CONV `2:num`; IDEAL_POW_SUC] THEN
      MATCH_MP_TAC IDEAL_PROD_MONO THEN
      ASM_SIMP_TAC[IDEAL_POW_1; SUBSET_REFL];
      ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC(SET_RULE `(x:A) IN s ==> s SUBSET t ==> x IN t`) THEN
      ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]];
    ALL_TAC] THEN
  REWRITE_TAC[SUBSET; NOT_FORALL_THM; NOT_IMP] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `s:A` THEN STRIP_TAC THEN
  SUBGOAL_THEN `(s:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN X_GEN_TAC `y:A` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `j:A->bool`; `y:A`; `s:A`]
    RING_MUL_IN_IDEAL_PROD) THEN
  ASM_SIMP_TAC[IN_IDEAL_GENERATED_SING_EQ; ring_divides; RING_MUL] THEN
  ASM_MESON_TAC[RING_MUL_SYM]);;

let DEDEKIND_IDEAL_POW_UNIFORMIZER_SPLIT = prove
 (`!r p (t:A) y n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        t IN p /\ ~(t IN ideal_pow r p 2) /\ y IN ideal_pow r p (n + 1)
        ==> ?a w. a IN ideal_pow r p n /\ w IN ideal_pow r p (n + 2) /\
                  y = ring_add r (ring_mul r t a) w`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `maximal_ideal r (p:A->bool)` ASSUME_TAC THENL
   [ASM_MESON_TAC[DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL]; ALL_TAC] THEN
  SUBGOAL_THEN `ideal_pow r p (n + 1) SUBSET (p:A->bool)` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `1:num`; `n + 1:num`]
      IDEAL_POW_ANTIMONO) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; RING_IDEAL_IMP_SUBSET] THEN
    DISCH_THEN MATCH_MP_TAC THEN ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r /\ (y:A) IN p /\ y IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `t:A`]
    DEDEKIND_PRIME_IDEAL_LOCAL_GENERATOR) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `s:A` (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC (MP_TAC o SPEC `y:A`)))) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `z:A` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `(z:A) IN ideal_pow r p n` ASSUME_TAC THENL
   [MATCH_MP_TAC DEDEKIND_IDEAL_POW_MUL_CANCEL THEN
    MAP_EVERY EXISTS_TAC [`t:A`; `1:num`] THEN ASM_REWRITE_TAC[ARITH] THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN ONCE_REWRITE_TAC[ADD_SYM] THEN
    MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `ring_carrier r:A->bool`; `s:A`;
                 `ring_1 r:A`] MAXIMAL_IDEAL_COMAXIMAL_MUL) THEN
  ASM_SIMP_TAC[MAXIMAL_IDEAL_COMAXIMAL; RING_IDEAL_CARRIER; RING_1] THEN
  ANTS_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL; proper_ideal; PSUBSET;
                  SUBSET_ANTISYM];
    ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `u:A` STRIP_ASSUME_TAC) THEN
  MAP_EVERY EXISTS_TAC
   [`ring_mul r u z:A`;
    `ring_neg r
      (ring_mul r (ring_sub r (ring_mul r s u) (ring_1 r)) y):A`] THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC IN_RING_IDEAL_LMUL THEN
    ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW];
    MATCH_MP_TAC IN_RING_IDEAL_NEG THEN REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN
    SUBGOAL_THEN `n + 2 = 1 + (n + 1:num)` SUBST1_TAC THENL
     [ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN
    ASM_SIMP_TAC[IDEAL_POW_1; RING_IDEAL_IMP_SUBSET];
    MATCH_MP_TAC(RING_RULE
     `!r s y t z u:A.
        s IN ring_carrier r /\ y IN ring_carrier r /\ t IN ring_carrier r /\
        z IN ring_carrier r /\ u IN ring_carrier r /\
        ring_mul r s y = ring_mul r t z
        ==> y = ring_add r (ring_mul r t (ring_mul r u z))
                  (ring_neg r (ring_mul r
                     (ring_sub r (ring_mul r s u) (ring_1 r)) y))`) THEN
    ASM_REWRITE_TAC[]]);;

(* An element of p^n is t^n c modulo p^(n+1), for a uniformizer t.          *)
let DEDEKIND_IDEAL_POW_UNIFORMIZER_POW = prove
 (`!r p (t:A) n w.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        t IN p /\ ~(t IN ideal_pow r p 2) /\ w IN ideal_pow r p n
        ==> ?c. c IN ring_carrier r /\
                ring_sub r w (ring_mul r (ring_pow r t n) c) IN
                ideal_pow r p (n + 1)`,
  REPLICATE_TAC 3 GEN_TAC THEN
  REWRITE_TAC[RIGHT_FORALL_IMP_THM; IMP_CONJ] THEN
  REPEAT DISCH_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(p:A->bool) SUBSET ring_carrier r` ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM SET_TAC[]; ALL_TAC] THEN
  INDUCT_TAC THENL
   [X_GEN_TAC `w:A` THEN REWRITE_TAC[IDEAL_POW_0] THEN DISCH_TAC THEN
    EXISTS_TAC `w:A` THEN
    ASM_SIMP_TAC[ring_pow; RING_MUL_LID; RING_SUB_REFL; ADD_CLAUSES;
                 IDEAL_POW_1] THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0];
    ALL_TAC] THEN
  X_GEN_TAC `w:A` THEN REWRITE_TAC[ADD1] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `t:A`; `w:A`; `n:num`]
    DEDEKIND_IDEAL_POW_UNIFORMIZER_SPLIT) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`b:A`; `v:A`] THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `b:A`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:A` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `c:A` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(b:A) IN ring_carrier r /\ (v:A) IN ring_carrier r`
  STRIP_ASSUME_TAC THENL
   [ASM_MESON_TAC[IDEAL_POW_CARRIER; RING_IDEAL_IMP_SUBSET;
                  RING_IDEAL_IDEAL_POW; SUBSET];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sub r (ring_add r (ring_mul r t b) v)
      (ring_mul r (ring_pow r t (n + 1)) c) =
    ring_add r (ring_mul r t (ring_sub r b (ring_mul r (ring_pow r t n) c)))
               (v:A)`
  SUBST1_TAC THENL
   [REWRITE_TAC[GSYM ADD1; ring_pow] THEN
    MATCH_MP_TAC(RING_RULE
     `ring_sub r (ring_add r (ring_mul r t b) v)
                 (ring_mul r (ring_mul r t u) c) =
      ring_add r (ring_mul r t (ring_sub r b (ring_mul r u c))) (v:A)`) THEN
    ASM_SIMP_TAC[RING_POW];
    ALL_TAC] THEN
  MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN CONJ_TAC THENL
   [REWRITE_TAC[ARITH_RULE `(n + 1) + 1 = 1 + n + 1`] THEN
    MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN ASM_SIMP_TAC[IDEAL_POW_1];
    FIRST_ASSUM(MP_TAC o check (fun th ->
      concl th = `(v:A) IN ideal_pow r p (n + 2)`)) THEN
    REWRITE_TAC[ARITH_RULE `n + 2 = (n + 1) + 1`]]);;

(* A subring S of a Dedekind domain r meeting every class modulo p and      *)
(* containing a uniformizer is dense: r = S + p^n for all n.                *)
let DEDEKIND_SUBRING_DENSE = prove
 (`!r p (t:A) S n y.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        S subring_of r /\ t IN S /\ t IN p /\ ~(t IN ideal_pow r p 2) /\
        (!y. y IN ring_carrier r ==> ?z. z IN S /\ ring_sub r y z IN p) /\
        y IN ring_carrier r
        ==> ?z. z IN S /\ ring_sub r y z IN ideal_pow r p n`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_IMP_RING_IDEAL) THEN
  SUBGOAL_THEN `(S:A->bool) SUBSET ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[subring_of]; ALL_TAC] THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM SET_TAC[]; ALL_TAC] THEN
  SPEC_TAC(`n:num`,`n:num`) THEN INDUCT_TAC THENL
   [EXISTS_TAC `ring_0 r:A` THEN
    ASM_SIMP_TAC[IN_SUBRING_0; IDEAL_POW_0; RING_SUB; RING_0];
    ALL_TAC] THEN
  FIRST_X_ASSUM(X_CHOOSE_THEN `z:A` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `t:A`; `n:num`;
                 `ring_sub r y (z:A)`] DEDEKIND_IDEAL_POW_UNIFORMIZER_POW) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `c:A` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `c:A` o check (fun th ->
    is_forall(concl th) && can (find_term ((=) `S:A->bool`)) (concl th))) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `c':A` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `ring_add r z (ring_mul r (ring_pow r t n) (c':A))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC IN_SUBRING_ADD THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC IN_SUBRING_MUL THEN ASM_SIMP_TAC[IN_SUBRING_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN `(z:A) IN ring_carrier r /\ (c':A) IN ring_carrier r`
  STRIP_ASSUME_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_sub r y (ring_add r z (ring_mul r (ring_pow r t n) c')) =
    ring_add r (ring_sub r (ring_sub r y z) (ring_mul r (ring_pow r t n) c))
               (ring_mul r (ring_pow r t n) (ring_sub r c (c':A)))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC(RING_RULE
     `ring_sub r y (ring_add r z (ring_mul r u c')) =
      ring_add r (ring_sub r (ring_sub r y z) (ring_mul r u c))
                 (ring_mul r u (ring_sub r c (c':A)))`) THEN
    ASM_SIMP_TAC[RING_POW];
    ALL_TAC] THEN
  REWRITE_TAC[ADD1] THEN MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_POW THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; RING_POW_IN_IDEAL_POW; IDEAL_POW_1]);;
