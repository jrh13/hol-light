let DEDEKIND_IN_IDEAL_POW_VALUATION = prove
 (`!r p (x:A) n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        x IN ring_carrier r /\ ~(x = ring_0 r)
        ==> (x IN ideal_pow r p n <=>
             n <= ideal_valuation r p (ideal_generated r {x}))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `ideal_generated r {x:A}`;
                 `n:num`] DEDEKIND_IDEAL_SUBSET_POW_VALUATION) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[IDEAL_GENERATED_MINIMAL_EQ; RING_IDEAL_IDEAL_POW;
               PRIME_IMP_RING_IDEAL; SING_SUBSET;
               SET_RULE `(x:A) IN s ==> s INTER {x} = {x}`]);;

let DEDEKIND_RING_DIVIDES_VALUATION = prove
 (`!r a b:A.
        dedekind_domain r /\
        a IN ring_carrier r /\ ~(a = ring_0 r) /\
        b IN ring_carrier r /\ ~(b = ring_0 r)
        ==> (ring_divides r a b <=>
             !p. prime_ideal r p /\ ~(p = {ring_0 r})
                 ==> ideal_valuation r p (ideal_generated r {a}) <=
                     ideal_valuation r p (ideal_generated r {b}))`,
  REPEAT STRIP_TAC THEN ASM_SIMP_TAC[GSYM SUBSET_IDEALS_GENERATED_SING] THEN
  MATCH_MP_TAC DEDEKIND_IDEAL_SUBSET_VALUATION THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; IDEAL_GENERATED_EQ_0]);;

let IDEAL_VALUATION_PRINCIPAL_ADD = prove
 (`!r p a b:A.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        a IN ring_carrier r /\ b IN ring_carrier r /\
        ~(ring_add r a b = ring_0 r)
        ==> MIN (ideal_valuation r p (ideal_generated r {a}))
                (ideal_valuation r p (ideal_generated r {b})) <=
            ideal_valuation r p (ideal_generated r {ring_add r a b})`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `a = ring_0 r:A` THEN
  ASM_SIMP_TAC[RING_ADD_LZERO; ARITH_RULE `MIN m n <= n`] THEN
  ASM_CASES_TAC `b = ring_0 r:A` THEN
  ASM_SIMP_TAC[RING_ADD_RZERO; ARITH_RULE `MIN m n <= m`] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `ring_add r a b:A`;
                 `MIN (ideal_valuation r p (ideal_generated r {a:A}))
                      (ideal_valuation r p (ideal_generated r {b}))`]
    DEDEKIND_IN_IDEAL_POW_VALUATION) THEN
  ASM_SIMP_TAC[RING_ADD] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC IN_RING_IDEAL_ADD THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL;
               DEDEKIND_IN_IDEAL_POW_VALUATION] THEN
  ARITH_TAC);;

(* With n = v_p((a)) and b <> 0: b IN p^(n + 1) but not a, hence not        *)
(* a + b (a = (a + b) - b), so a + b <> 0 and v_p((a + b)) <= n; the other   *)
(* inequality is IDEAL_VALUATION_PRINCIPAL_ADD.                              *)

let IDEAL_VALUATION_PRINCIPAL_ADD_STRICT = prove
 (`!r p a b:A.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        a IN ring_carrier r /\ ~(a = ring_0 r) /\ b IN ring_carrier r /\
        ideal_valuation r p (ideal_generated r {a}) <
        ideal_valuation r p (ideal_generated r {b})
        ==> ideal_valuation r p (ideal_generated r {ring_add r a b}) =
            ideal_valuation r p (ideal_generated r {a})`,
  REPEAT STRIP_TAC THEN
  ASM_CASES_TAC `b = ring_0 r:A` THEN ASM_SIMP_TAC[RING_ADD_RZERO] THEN
  ABBREV_TAC `n = ideal_valuation r p (ideal_generated r {a:A})` THEN
  SUBGOAL_THEN `ring_ideal r (ideal_pow r p (SUC n):A->bool)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL]; ALL_TAC] THEN
  SUBGOAL_THEN `~((ring_add r a b:A) IN ideal_pow r p (SUC n))` ASSUME_TAC THENL
   [DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `ideal_pow r p (SUC n):A->bool`;
                   `ring_add r a b:A`; `b:A`] IN_RING_IDEAL_SUB) THEN
    ASM_SIMP_TAC[RING_RULE `ring_sub r (ring_add r x y) y = x:A`;
                 DEDEKIND_IN_IDEAL_POW_VALUATION] THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `~(ring_add r a b = ring_0 r:A)` ASSUME_TAC THENL
   [DISCH_TAC THEN
    UNDISCH_TAC `~((ring_add r a b:A) IN ideal_pow r p (SUC n))` THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `a:A`; `b:A`]
    IDEAL_VALUATION_PRINCIPAL_ADD) THEN
  UNDISCH_TAC `~((ring_add r a b:A) IN ideal_pow r p (SUC n))` THEN
  ASM_SIMP_TAC[DEDEKIND_IN_IDEAL_POW_VALUATION; RING_ADD] THEN
  ASM_ARITH_TAC);;

