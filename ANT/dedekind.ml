  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "l" THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_PRODUCT; RING_IDEAL_INTER];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(l = {ring_0(r:A ring)}) /\ ~(j INTER k = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THEN MATCH_MP_TAC(SET_RULE
     `!j k z:A. j SUBSET k /\ ~(j = {z}) /\ z IN j ==> ~(k = {z})`) THEN
    EXISTS_TAC `ideal_prod r j (k:A->bool)` THEN
    ASM_SIMP_TAC[IN_RING_IDEAL_0; RING_IDEAL_IDEAL_PROD;
