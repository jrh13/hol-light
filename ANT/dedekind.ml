                ==> ideal_valuation r Q
                      (ideal_product r t (\P. ideal_pow r P (e P))) =
                    if Q IN t then e Q else 0`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_PRODUCT] THEN CONJ_TAC THENL
   [FIRST_ASSUM(ASSUME_TAC o MATCH_MP DEDEKIND_IMP_INTEGRAL_DOMAIN) THEN
    ASM_SIMP_TAC[IDEAL_PRODUCT_EQ_ZERO; RING_IDEAL_IDEAL_POW] THEN
    REWRITE_TAC[NOT_EXISTS_THM] THEN X_GEN_TAC `P:A->bool` THEN
    ASM_CASES_TAC `(P:A->bool) IN t` THEN ASM_REWRITE_TAC[] THEN
    ASM_SIMP_TAC[IDEAL_POW_EQ_ZERO; PRIME_IMP_RING_IDEAL];
    ALL_TAC] THEN
  ABBREV_TAC `f = \P:A->bool. if P IN t then (e:(A->bool)->num) P else 0` THEN
  SUBGOAL_THEN
   `ideal_product r t (\P. ideal_pow r P ((e:(A->bool)->num) P)) =
    ideal_product r (monomial_vars f) (\P. ideal_pow r P (f P))`
  SUBST1_TAC THENL
   [TRANS_TAC EQ_TRANS
     `ideal_product r t (\P:A->bool. ideal_pow r P (f P))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC IDEAL_PRODUCT_EQ THEN EXPAND_TAC "f" THEN SIMP_TAC[];
      MATCH_MP_TAC IDEAL_PRODUCT_SUPERSET THEN
      ASM_REWRITE_TAC[RING_IDEAL_IDEAL_POW] THEN
      EXPAND_TAC "f" THEN
      REWRITE_TAC[monomial_vars; SUBSET; IN_ELIM_THM] THEN
      CONJ_TAC THENL [MESON_TAC[]; ALL_TAC] THEN
      SIMP_TAC[IDEAL_POW_0]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `monomial {P | prime_ideal r P /\ ~(P = {ring_0 r})} (f:(A->bool)->num)`
  ASSUME_TAC THENL
   [REWRITE_TAC[monomial; monomial_vars] THEN EXPAND_TAC "f" THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC FINITE_SUBSET THEN EXISTS_TAC `t:(A->bool)->bool` THEN
      ASM_REWRITE_TAC[] THEN SET_TAC[];
      REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN ASM_MESON_TAC[]];
    ALL_TAC] THEN
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL] THEN EXPAND_TAC "f" THEN
  REWRITE_TAC[]);;

let IDEAL_VALUATION_IDEAL_PROD = prove
 (`!r p j k:A->bool.
     dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
     ring_ideal r j /\ ~(j = {ring_0 r}) /\
     ring_ideal r k /\ ~(k = {ring_0 r})
     ==> ideal_valuation r p (ideal_prod r j k) =
         ideal_valuation r p j + ideal_valuation r p k`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `k:A->bool`]
    DEDEKIND_IDEAL_FACTORIZATION_EXISTS) THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_FACTORIZATION_EXISTS) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:(A->bool)->num`
   (CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM))) THEN
  DISCH_THEN(X_CHOOSE_THEN `f:(A->bool)->num`
   (CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM))) THEN
  MP_TAC(ISPECL [`r:A ring`; `e:(A->bool)->num`; `f:(A->bool)->num`]
    IDEAL_PRODUCT_PRIME_MONOMIAL_MUL) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL; MONOMIAL_MUL] THEN
