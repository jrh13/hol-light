let ideal_valuation = new_definition
 `ideal_valuation (r:A ring) (p:A->bool) (j:A->bool) =
  @n. j SUBSET ideal_pow r p n /\ ~(j SUBSET ideal_pow r p (SUC n))`;;

let IDEAL_VALUATION_UNIQUE = prove
 (`!r p (j:A->bool) n.
        ring_ideal r p /\
        j SUBSET ideal_pow r p n /\ ~(j SUBSET ideal_pow r p (SUC n))
        ==> ideal_valuation r p j = n`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ideal_valuation] THEN
  MATCH_MP_TAC SELECT_UNIQUE THEN X_GEN_TAC `m:num` THEN EQ_TAC THEN
  SIMP_TAC[] THEN ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  REFUTE_THEN(DISJ_CASES_TAC o MATCH_MP (ARITH_RULE
   `~(m = n) ==> SUC m <= n \/ SUC n <= m`)) THEN
  ASM_MESON_TAC[IDEAL_POW_ANTIMONO; RING_IDEAL_IMP_SUBSET; SUBSET_TRANS]);;

let IDEAL_VALUATION_CARRIER = prove
 (`!r p:A->bool.
        ring_ideal r p /\ ~(p = ring_carrier r)
        ==> ideal_valuation r p (ring_carrier r) = 0`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC IDEAL_VALUATION_UNIQUE THEN
  ASM_SIMP_TAC[IDEAL_POW_0; IDEAL_POW_1; SUBSET_REFL; GSYM ONE] THEN
  ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET_ANTISYM]);;

let IDEAL_PRODUCT_PRIME_MONOMIAL_DIVIDES = prove
 (`!r e f:(A->bool)->num.
        monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} e /\
        monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} f /\
        monomial_divides f e
        ==> ideal_product r (monomial_vars e) (\p. ideal_pow r p (e p)) SUBSET
            ideal_product r (monomial_vars f) (\p. ideal_pow r p (f p))`,
  REPEAT STRIP_TAC THEN
  FIRST_X_ASSUM(SUBST1_TAC o SYM o MATCH_MP MONOMIAL_DIV_LMUL) THEN
  ASM_SIMP_TAC[IDEAL_PRODUCT_PRIME_MONOMIAL_MUL; MONOMIAL_DIV] THEN
  SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; RING_IDEAL_IDEAL_PRODUCT;
           RING_IDEAL_IMP_SUBSET]);;

(* The key computation: the ideal of a monomial e lies in p^n iff n <= e p.  *)

let DEDEKIND_IDEAL_PRODUCT_SUBSET_POW = prove
 (`!r p (e:(A->bool)->num) n.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r}) /\
        monomial {q | prime_ideal r q /\ ~(q = {ring_0 r})} e
        ==> (ideal_product r (monomial_vars e) (\q. ideal_pow r q (e q))
             SUBSET ideal_pow r p n <=> n <= e p)`,
  GEN_TAC THEN GEN_TAC THEN
  REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM] THEN REPEAT DISCH_TAC THEN
  MATCH_MP_TAC MONOMIAL_INDUCT THEN CONJ_TAC THENL
   [REWRITE_TAC[MONOMIAL_VARS_1; IDEAL_PRODUCT_EMPTY; monomial_1; LE] THEN
    X_GEN_TAC `n:num` THEN ASM_CASES_TAC `n = 0` THEN
    ASM_REWRITE_TAC[IDEAL_POW_0; SUBSET_REFL] THEN
    MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `p:A->bool`; `n:num`]
      IDEAL_POW_SUBSET_PRIME_IDEAL) THEN
    ASM_SIMP_TAC[PRIME_IDEAL_IMP_SUBSET; SUBSET_REFL] THEN
    ASM_MESON_TAC[SUBSET_TRANS; PRIME_IDEAL_IMP_PSUBSET; PSUBSET;
                  SUBSET_ANTISYM];
    ALL_TAC] THEN
  MAP_EVERY X_GEN_TAC [`e:(A->bool)->num`; `q:A->bool`] THEN
  REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
  ASM_SIMP_TAC[IDEAL_PRODUCT_PRIME_MONOMIAL_MUL; MONOMIAL_VAR; IN_ELIM_THM;
               IDEAL_PRODUCT_MONOMIAL_VAR; PRIME_IMP_RING_IDEAL] THEN
  REWRITE_TAC[monomial_mul; monomial_var] THEN
  ABBREV_TAC
   `k = ideal_product r (monomial_vars e)
          (\q:A->bool. ideal_pow r q (e q))` THEN
  SUBGOAL_THEN `ring_ideal r (k:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "k" THEN REWRITE_TAC[RING_IDEAL_IDEAL_PRODUCT]; ALL_TAC] THEN
  ASM_CASES_TAC `p:A->bool = q` THENL
   [FIRST_X_ASSUM(SUBST_ALL_TAC o SYM) THEN REWRITE_TAC[] THEN
    X_GEN_TAC `n:num` THEN STRUCT_CASES_TAC(SPEC `n:num` num_CASES) THEN
    ASM_SIMP_TAC[IDEAL_POW_0; LE_0; RING_IDEAL_IMP_SUBSET;
                 RING_IDEAL_IDEAL_PROD] THEN
    ASM_SIMP_TAC[IDEAL_POW_SUC; DEDEKIND_IDEAL_PROD_SUBSET_CANCEL;
                 RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL] THEN
    ARITH_TAC;
    ASM_REWRITE_TAC[ADD_CLAUSES] THEN X_GEN_TAC `n:num` THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o SPEC `n:num`) THEN
    EQ_TAC THEN DISCH_TAC THENL
     [ALL_TAC;
      TRANS_TAC SUBSET_TRANS `k:A->bool` THEN
      ASM_SIMP_TAC[IDEAL_PROD_SUBSET_RIGHT; PRIME_IDEAL_IMP_SUBSET]]] THEN
  SUBGOAL_THEN `ring_setadd r q (ideal_pow r p n) = ring_carrier(r:A ring)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `p:A->bool`; `1`; `n:num`]
      COMAXIMAL_IDEAL_POW) THEN
    ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL] THEN
    DISCH_THEN MATCH_MP_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `p:A->bool`]
      MAXIMAL_IDEAL_COMAXIMAL) THEN
    ASM_SIMP_TAC[DEDEKIND_NONZERO_PRIME_IMP_MAXIMAL; PRIME_IMP_RING_IDEAL] THEN
    DISCH_THEN SUBST1_TAC THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `p:A->bool`]
      DEDEKIND_KRULL_DIMENSION_ONE) THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `ideal_pow r p n:A->bool`;
                 `k:A->bool`] IDEAL_PROD_SETADD_RDISTRIB) THEN
  ASM_SIMP_TAC[PRIME_IMP_RING_IDEAL; RING_IDEAL_IDEAL_POW;
               RING_IDEAL_IMP_SUBSET; IDEAL_PROD_CARRIER_LEFT] THEN
  DISCH_THEN SUBST1_TAC THEN MATCH_MP_TAC RING_SETADD_SUBSET_IDEAL THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; PRIME_IMP_RING_IDEAL;
               IDEAL_PROD_SUBSET_LEFT; RING_IDEAL_IMP_SUBSET]);;

let IDEAL_VALUATION_IDEAL_PRODUCT_MONOMIAL = prove
 (`!r (e:(A->bool)->num) p.
     dedekind_domain r /\
     monomial {p | prime_ideal r p /\ ~(p = {ring_0 r})} e /\
     prime_ideal r p /\ ~(p = {ring_0 r})
     ==> ideal_valuation r p
           (ideal_product r (monomial_vars e)
