let DEDEKIND_IDEAL_PROD_SUBSET_CANCEL = prove
 (`!r j k l:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r}) /\
        ring_ideal r k /\ ring_ideal r l
        ==> (ideal_prod r j k SUBSET ideal_prod r j l <=> k SUBSET l)`,
  REPEAT STRIP_TAC THEN EQ_TAC THEN SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL] THEN
  DISCH_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`j':A->bool`; `a:A`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `k:A->bool`; `l:A->bool`]
    IDEAL_PROD_PRINCIPAL_SUBSET_CANCEL) THEN
  ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN] THEN
  DISCH_THEN(SUBST1_TAC o SYM) THEN
  UNDISCH_THEN `ideal_prod r j j' = ideal_generated r {a:A}`
   (SUBST1_TAC o SYM) THEN
  MP_TAC(ISPECL [`r:A ring`; `j':A->bool`; `j':A->bool`;
                 `ideal_prod r j k:A->bool`; `ideal_prod r j l:A->bool`]
    IDEAL_PROD_MONO) THEN
  ASM_REWRITE_TAC[SUBSET_REFL] THEN
  ASM_SIMP_TAC[IDEAL_PROD_AC; RING_IDEAL_IMP_SUBSET; RING_IDEAL_IDEAL_PROD]);;

let DEDEKIND_IDEAL_PROD_CANCEL = prove
 (`!r:A ring j k l.
        dedekind_domain r /\ ring_ideal r j /\ ~(j = {ring_0 r}) /\
        ring_ideal r k /\ ring_ideal r l /\
        ideal_prod r j k = ideal_prod r j l
        ==> k = l`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `k:A->bool`; `l:A->bool`]
    DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `l:A->bool`; `k:A->bool`]
    DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  ASM_REWRITE_TAC[SUBSET_REFL] THEN SET_TAC[]);;

let DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES = prove
 (`!r:A ring j k.
        dedekind_domain r /\ ring_ideal r j /\ ring_ideal r k
        ==> (j SUBSET k <=>
             ?l. ring_ideal r l /\ ideal_prod r k l = j)`,
  REPEAT STRIP_TAC THEN EQ_TAC THENL
   [DISCH_TAC;
    DISCH_THEN(X_CHOOSE_THEN `l:A->bool`
     (CONJUNCTS_THEN2 ASSUME_TAC (SUBST1_TAC o SYM))) THEN
    ASM_SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; RING_IDEAL_IMP_SUBSET]] THEN
  ASM_CASES_TAC `k = {ring_0 r:A}` THENL
   [EXISTS_TAC `ring_carrier r:A->bool` THEN
    ASM_SIMP_TAC[RING_IDEAL_CARRIER; IDEAL_PROD_LZERO; SUBSET_REFL] THEN
    MP_TAC(ISPECL [`r:A ring`; `j:A->bool`] IN_RING_IDEAL_0) THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `k:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`k':A->bool`; `a:A`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `a:A`; `ideal_prod r j k':A->bool`]
    IDEAL_PROD_PRINCIPAL_FACTOR) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_PROD] THEN
  DISCH_THEN(MP_TAC o fst o EQ_IMP_RULE) THEN ANTS_TAC THENL
   [UNDISCH_THEN `ideal_prod r k k' = ideal_generated r {a:A}`
     (SUBST1_TAC o SYM) THEN
    ASM_SIMP_TAC[IDEAL_PROD_MONO; SUBSET_REFL];
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `l:A->bool` THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[] THEN MATCH_MP_TAC IDEAL_PROD_PRINCIPAL_COFACTOR THEN
    MAP_EVERY EXISTS_TAC [`a:A`; `k':A->bool`] THEN
    ASM_SIMP_TAC[DEDEKIND_IMP_INTEGRAL_DOMAIN]]);;

let DEDEKIND_IDEAL_PROD_IDEAL_QUOTIENT = prove
 (`!r j k:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ring_ideal r k /\ j SUBSET k
        ==> ideal_prod r k (ideal_quotient r j k) = j`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `ring_ideal r (ideal_quotient r j (k:A->bool))` ASSUME_TAC THENL
   [ASM_SIMP_TAC[RING_IDEAL_IDEAL_QUOTIENT; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `k:A->bool`;
                   `ideal_quotient r j k:A->bool`] SUBSET_IDEAL_QUOTIENT) THEN
    ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; SUBSET_REFL] THEN
    ASM_SIMP_TAC[IDEAL_PROD_COMM; RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `j:A->bool`; `k:A->bool`]
    DEDEKIND_IDEAL_SUBSET_IFF_DIVIDES) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `l:A->bool` STRIP_ASSUME_TAC) THEN
  FIRST_X_ASSUM(SUBST_ALL_TAC o SYM) THEN
  MATCH_MP_TAC IDEAL_PROD_MONO THEN REWRITE_TAC[SUBSET_REFL] THEN
  ASM_SIMP_TAC[SUBSET_IDEAL_QUOTIENT; RING_IDEAL_IMP_SUBSET] THEN
  MATCH_MP_TAC(SET_RULE `!s t:A->bool. s = t ==> s SUBSET t`) THEN
  MATCH_MP_TAC IDEAL_PROD_COMM THEN ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET]);;

let DEDEKIND_IDEAL_QUOTIENT_CANCEL = prove
 (`!r j k:A->bool.
        dedekind_domain r /\ ring_ideal r j /\ ring_ideal r k /\
        ~(k = {ring_0 r})
        ==> ideal_quotient r (ideal_prod r j k) k = j`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `q = ideal_quotient r (ideal_prod r j k) (k:A->bool)` THEN
  SUBGOAL_THEN `ring_ideal r (q:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "q" THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_QUOTIENT; RING_IDEAL_IDEAL_PROD;
                 RING_IDEAL_IMP_SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_prod r j k:A->bool`; `k:A->bool`]
    SUBSET_IDEAL_QUOTIENT) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_PROD; RING_IDEAL_IMP_SUBSET] THEN
  DISCH_THEN(fun th -> MP_TAC(SPEC `q:A->bool` th) THEN
                       MP_TAC(SPEC `j:A->bool` th)) THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; SUBSET_REFL] THEN
  DISCH_TAC THEN DISCH_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN
  ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`r:A ring`; `k:A->bool`; `q:A->bool`; `j:A->bool`]
    DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  UNDISCH_TAC `ideal_prod r q k SUBSET ideal_prod r j (k:A->bool)` THEN
  ASM_SIMP_TAC[IDEAL_PROD_COMM; RING_IDEAL_IMP_SUBSET]);;

(* If p b = (c) with b nonzero generated by t, u is in p iff y u is in (c)   *)
(* for all y in t (multiply u r SUBSET p by b and cancel).                   *)
let DEDEKIND_IDEAL_MEMBER_PRINCIPAL_MULTIPLE = prove
 (`!r p t (c:A) u.
        dedekind_domain r /\ ring_ideal r p /\ t SUBSET ring_carrier r /\
        ~(ideal_generated r t = {ring_0 r}) /\ c IN ring_carrier r /\
        ideal_prod r p (ideal_generated r t) = ideal_generated r {c} /\
        u IN ring_carrier r
        ==> (u IN p <=>
             !y. y IN t ==> ring_mul r y u IN ideal_generated r {c})`,
  REPEAT STRIP_TAC THEN EQ_TAC THENL
   [REPEAT STRIP_TAC THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      is_eq(concl th) &&
      rand(concl th) = `ideal_generated r {c:A}`)) THEN
    SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
     [ASM SET_TAC[]; ALL_TAC] THEN
    SUBGOAL_THEN `ring_mul r y u = ring_mul r u (y:A)` SUBST1_TAC THENL
     [MATCH_MP_TAC RING_MUL_SYM THEN ASM_REWRITE_TAC[];
      MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
      ASM_SIMP_TAC[IDEAL_GENERATED_INC]];
    DISCH_TAC] THEN
  ABBREV_TAC `b = ideal_generated r (t:A->bool)` THEN
  SUBGOAL_THEN `ring_ideal r (b:A->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "b" THEN REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!y. y IN b ==> ring_mul r y u IN ideal_generated r {c:A}`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `b SUBSET {y | y IN ring_carrier r /\
                    ring_mul r y u IN ideal_generated r {c:A}}`
    MP_TAC THENL [ALL_TAC; SET_TAC[]] THEN
    EXPAND_TAC "b" THEN MATCH_MP_TAC IDEAL_GENERATED_MINIMAL THEN
    CONJ_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
    MP_TAC(ISPECL [`r:A ring`; `{c:A}`] RING_IDEAL_IDEAL_GENERATED) THEN
    REWRITE_TAC[ring_ideal; SUBSET; IN_ELIM_THM] THEN STRIP_TAC THEN
    ASM_SIMP_TAC[RING_0; RING_NEG; RING_ADD; RING_MUL; RING_MUL_LZERO;
                 RING_MUL_LNEG; RING_ADD_RDISTRIB; GSYM RING_MUL_ASSOC];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `b:A->bool`; `ideal_generated r {u:A}`;
                 `p:A->bool`] DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
  MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN CONJ_TAC THENL
   [ALL_TAC;
    DISCH_TAC THEN FIRST_X_ASSUM(MATCH_MP_TAC o REWRITE_RULE[SUBSET]) THEN
    ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]] THEN
  MP_TAC(ISPECL [`r:A ring`; `b:A->bool`; `p:A->bool`] IDEAL_PROD_COMM) THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN DISCH_THEN SUBST1_TAC THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
  MAP_EVERY X_GEN_TAC [`y:A`; `v:A`] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `u:A`] IDEAL_GENERATED_SING_ALT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(fun th ->
    UNDISCH_TAC `(v:A) IN ideal_generated r {u}` THEN
    REWRITE_TAC[th; IN_ELIM_THM]) THEN
  DISCH_THEN(X_CHOOSE_THEN `s:A` STRIP_ASSUME_TAC) THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(y:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `ring_mul r y (ring_mul r u s) = ring_mul r (ring_mul r y u) (s:A)`
  SUBST1_TAC THENL
   [MATCH_MP_TAC RING_MUL_ASSOC THEN ASM_REWRITE_TAC[];
    MATCH_MP_TAC IN_RING_IDEAL_RMUL THEN
    ASM_SIMP_TAC[RING_IDEAL_IDEAL_GENERATED]]);;

(* A family b_i, not all 0, has a multiple b_i t = e u_i with e <> 0 and     *)
(* some u_i outside a given proper ideal j: if c b = (e) for the ideal b     *)
(* generated by the family, take t in c but not in c j.                      *)

let DEDEKIND_PRIMITIVE_MULTIPLE = prove
 (`!r j s (b:K->A).
        dedekind_domain r /\ ring_ideal r j /\ ~(j = ring_carrier r) /\
        (!i. i IN s ==> b i IN ring_carrier r) /\
        (?i. i IN s /\ ~(b i = ring_0 r))
        ==> ?t e u. t IN ring_carrier r /\
                    e IN ring_carrier r /\ ~(e = ring_0 r) /\
                    (!i. i IN s
                         ==> u i IN ring_carrier r /\
                             ring_mul r (b i) t = ring_mul r e (u i)) /\
                    ?i. i IN s /\ ~(u i IN j)`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `q = ideal_generated r (IMAGE (b:K->A) s)` THEN
  SUBGOAL_THEN
   `ring_ideal r (q:A->bool) /\ (!i. i IN s ==> (b:K->A) i IN q) /\
    ~(q = {ring_0 r})`
  STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(SET_RULE
     `!P s (b:K->A) q z i0.
        P /\ (!i. i IN s ==> b i IN q) /\ i0 IN s /\ ~(b i0 = z)
        ==> P /\ (!i. i IN s ==> b i IN q) /\ ~(q = {z})`) THEN
    EXISTS_TAC `i:K` THEN ASM_REWRITE_TAC[] THEN EXPAND_TAC "q" THEN
    REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
    REPEAT STRIP_TAC THEN MATCH_MP_TAC IDEAL_GENERATED_INC THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`r:A ring`; `q:A->bool`]
    DEDEKIND_IDEAL_HAS_PRINCIPAL_MULTIPLE) THEN
  ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`c:A->bool`; `e:A`] THEN STRIP_TAC THEN
  SUBGOAL_THEN `?t:A. t IN c /\ ~(t IN ideal_prod r c j)` STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`r:A ring`; `c:A->bool`; `ring_carrier r:A->bool`;
                   `j:A->bool`] DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
    ASM_SIMP_TAC[IDEAL_PROD_CARRIER; RING_IDEAL_CARRIER] THEN
    FIRST_ASSUM(MP_TAC o MATCH_MP RING_IDEAL_IMP_SUBSET o
      check (fun th -> concl th = `ring_ideal r (j:A->bool)`)) THEN
    UNDISCH_TAC `~(j = ring_carrier r:A->bool)` THEN SET_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `(t:A) IN ring_carrier r` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_IDEAL_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC [`t:A`; `e:A`] THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `?u:K->A. !i. i IN s
                 ==> u i IN ring_carrier r /\
                     ring_mul r ((b:K->A) i) t = ring_mul r e (u i)`
  MP_TAC THENL
   [REWRITE_TAC[GSYM SKOLEM_THM; RIGHT_EXISTS_IMP_THM] THEN
    X_GEN_TAC `x:K` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `c:A->bool`; `(b:K->A) x`;
                   `t:A`] RING_MUL_IN_IDEAL_PROD) THEN
    ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET; IN_IDEAL_GENERATED_SING_EQ;
                 ring_divides] THEN
    MESON_TAC[];
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `u:K->A` THEN STRIP_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[TAUT `p /\ ~q <=> ~(p ==> q)`; GSYM NOT_FORALL_THM] THEN
  DISCH_TAC THEN
  UNDISCH_TAC `~((t:A) IN ideal_prod r c j)` THEN REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`r:A ring`; `q:A->bool`; `ideal_generated r {t:A}`;
                 `ideal_prod r c j:A->bool`]
    DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED; RING_IDEAL_IDEAL_PROD] THEN
  MATCH_MP_TAC(TAUT `p /\ (q ==> r) ==> (p <=> q) ==> r`) THEN
  CONJ_TAC THENL
   [ALL_TAC; ASM_MESON_TAC[IN_IDEAL_GENERATED_SELF; SUBSET]] THEN
  W(MP_TAC o PART_MATCH (lhand o rand) IDEAL_PROD_ASSOC o rand o snd) THEN
  ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN
  DISCH_THEN SUBST1_TAC THEN EXPAND_TAC "q" THEN
  W(MP_TAC o PART_MATCH (lhand o rand) IDEAL_PROD_IDEAL_GENERATED o
    lhand o snd) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[SING_SUBSET; SUBSET; FORALL_IN_IMAGE] THEN ASM_SIMP_TAC[];
    DISCH_THEN SUBST1_TAC] THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC IDEAL_PROD_MINIMAL THEN
  REWRITE_TAC[RING_IDEAL_IDEAL_PROD; IMP_CONJ; RIGHT_FORALL_IMP_THM;
              FORALL_IN_IMAGE; IN_SING] THEN
  X_GEN_TAC `x:K` THEN DISCH_TAC THEN X_GEN_TAC `y:A` THEN
  DISCH_THEN SUBST1_TAC THEN ASM_SIMP_TAC[] THEN
  MATCH_MP_TAC RING_MUL_IN_IDEAL_PROD THEN
  ASM_SIMP_TAC[IN_IDEAL_GENERATED_SELF]);;

let DEDEKIND_IDEAL_POW_SUBSET = prove
 (`!r j:A->bool m n.
        dedekind_domain r /\ ring_ideal r j /\
        ~(j = {ring_0 r}) /\ ~(j = ring_carrier r)
        ==> (ideal_pow r j m SUBSET ideal_pow r j n <=> n <= m)`,
  REPEAT STRIP_TAC THEN EQ_TAC THEN
  ASM_SIMP_TAC[IDEAL_POW_ANTIMONO; RING_IDEAL_IMP_SUBSET] THEN
  ONCE_REWRITE_TAC[GSYM CONTRAPOS_THM] THEN REWRITE_TAC[NOT_LE; LT_EXISTS] THEN
  DISCH_THEN(X_CHOOSE_THEN `d:num` SUBST1_TAC) THEN
  ASM_SIMP_TAC[IDEAL_POW_ADD; RING_IDEAL_IMP_SUBSET] THEN
  MP_TAC(ISPECL [`r:A ring`; `ideal_pow r j m:A->bool`;
                 `ring_carrier r:A->bool`; `ideal_pow r j (SUC d):A->bool`]
    DEDEKIND_IDEAL_PROD_SUBSET_CANCEL) THEN
  ASM_SIMP_TAC[RING_IDEAL_IDEAL_POW; RING_IDEAL_CARRIER; IDEAL_POW_EQ_ZERO;
               DEDEKIND_IMP_INTEGRAL_DOMAIN; IDEAL_PROD_CARRIER] THEN
  DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[IDEAL_POW_SUC] THEN DISCH_TAC THEN
  UNDISCH_TAC `~(j = ring_carrier(r:A ring))` THEN REWRITE_TAC[] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN ASM_SIMP_TAC[RING_IDEAL_IMP_SUBSET] THEN
  TRANS_TAC SUBSET_TRANS `ideal_prod r j (ideal_pow r j d):A->bool` THEN
  ASM_SIMP_TAC[IDEAL_PROD_SUBSET_LEFT; RING_IDEAL_IMP_SUBSET;
               RING_IDEAL_IDEAL_POW]);;

let DEDEKIND_IDEAL_POW_EQ = prove
 (`!r j:A->bool m n.
        dedekind_domain r /\ ring_ideal r j /\
        ~(j = {ring_0 r}) /\ ~(j = ring_carrier r)
        ==> (ideal_pow r j m = ideal_pow r j n <=> m = n)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[GSYM SUBSET_ANTISYM_EQ] THEN
  ASM_SIMP_TAC[DEDEKIND_IDEAL_POW_SUBSET] THEN ARITH_TAC);;

let DEDEKIND_PRIME_IDEAL_UNIFORMIZER = prove
 (`!r p:A->bool.
        dedekind_domain r /\ prime_ideal r p /\ ~(p = {ring_0 r})
        ==> ?t. t IN p /\ ~(t IN ideal_pow r p 2)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`r:A ring`; `p:A->bool`; `1:num`; `2:num`]
    DEDEKIND_IDEAL_POW_SUBSET) THEN
  ASM_SIMP_TAC[IDEAL_POW_1; PRIME_IMP_RING_IDEAL; ARITH] THEN
  ANTS_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_PROPER_IDEAL; proper_ideal; PSUBSET];
    SET_TAC[]]);;

