let RING_OF_INTEGERS_NORM_PRODUCT_GE_1 = prove
 (`!k x:A.
        number_field k /\ x IN ring_carrier(ring_of_integers k) /\
        ~(x = ring_0 k)
        ==> &1 <= product (complex_embeddings k) (\g. norm(g x))`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[GSYM NUMBER_FIELD_IDEAL_NORM_PRINCIPAL_EMBEDDINGS] THEN
  REWRITE_TAC[REAL_OF_NUM_LE] THEN MATCH_MP_TAC IDEAL_NORM_POS THEN
  MATCH_MP_TAC RING_OF_INTEGERS_FINITE_QUOTIENT THEN
  ASM_REWRITE_TAC[RING_IDEAL_IDEAL_GENERATED] THEN
  MATCH_MP_TAC(SET_RULE
   `!x:A s z. x IN s /\ ~(x = z) ==> ~(s = {z})`) THEN
  EXISTS_TAC `x:A` THEN ASM_REWRITE_TAC[IN_IDEAL_GENERATED_SELF]);;

(* By AM-GM (AGM_ROOT of Multivariate/realanalysis.ml) and the previous      *)
(* result, the squares |g x|^2 have sum at least [k:Q].                      *)
let RING_OF_INTEGERS_SUM_NORM_POW_2 = prove
 (`!k x:A.
        number_field k /\ x IN ring_carrier(ring_of_integers k) /\
        ~(x = ring_0 k)
        ==> &(extension_degree (subfield_generated k {ring_0 k},k) I) <=
            sum (complex_embeddings k) (\g. norm(g x) pow 2)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_DEGREE_POS) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP COMPLEX_EMBEDDINGS_HAS_SIZE) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_COMPLEX_EMBEDDINGS) THEN
  MP_TAC(ISPECL [`k:A ring`; `x:A`] RING_OF_INTEGERS_NORM_PRODUCT_GE_1) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  ABBREV_TAC
   `n = extension_degree (subfield_generated k {ring_0 k},k:A ring) I` THEN
  SUBGOAL_THEN
   `&1 <= product (complex_embeddings k) (\g. norm((g:A->complex) x) pow 2)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[REAL_POW_2; PRODUCT_MUL] THEN
    GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
    MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[REAL_POS];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`complex_embeddings(k:A ring)`;
                 `\g:A->complex. norm(g x) pow 2`; `n:num`] AGM_ROOT) THEN
  ASM_REWRITE_TAC[REAL_LE_POW_2] THEN
  ANTS_TAC THENL [ASM_ARITH_TAC; DISCH_TAC] THEN
  MP_TAC(SPECL [`n:num`; `(&1:real)`;
    `product (complex_embeddings k) (\g. norm((g:A->complex) x) pow 2)`]
    ROOT_MONO_LE) THEN
  ASM_REWRITE_TAC[ROOT_1] THEN DISCH_TAC THEN
  SUBGOAL_THEN
   `&1 <= sum (complex_embeddings k) (\g. norm((g:A->complex) x) pow 2) / &n`
  MP_TAC THENL [ASM_MESON_TAC[REAL_LE_TRANS]; ALL_TAC] THEN
  ASM_SIMP_TAC[REAL_LE_RDIV_EQ; REAL_OF_NUM_LT; LE_1; REAL_MUL_LID]);;

