                              (ring_of_int k) n (w:num->A)`))))) THEN
    ASM_REWRITE_TAC[INTEGER_RING; IN_UNIV; RING_OF_INTEGERS] THEN
    RULE_ASSUM_TAC(REWRITE_RULE[IN_ELIM_THM]) THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!l. l < n
        ==> (e:num->A->complex) l x =
            vsum {j | j < n} (\j. Cx(real_of_int((c:num->int) j)) *
                                  e l ((w:num->A) j))`
  ASSUME_TAC THENL
   [X_GEN_TAC `l:num` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `ring_homomorphism(ring_of_integers k,complex_ring)
        ((e:num->A->complex) l)`
    ASSUME_TAC THENL
     [REWRITE_TAC[ring_of_integers] THEN
      MATCH_MP_TAC RING_HOMOMORPHISM_FROM_SUBRING_GENERATED THEN
      ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM];
      ALL_TAC] THEN
    EXPAND_TAC "x" THEN
    MP_TAC(ISPECL [`ring_of_integers k:A ring`; `complex_ring`;
                   `(e:num->A->complex) l`; `{j:num | j < n}`;
                   `\j. ring_of_int k ((c:num->int) j):A`; `w:num->A`]
      RING_HOMOMORPHISM_SUM_MUL) THEN
    ASM_SIMP_TAC[FINITE_NUMSEG_LT; IN_ELIM_THM; COMPLEX_RING_SUM] THEN
    DISCH_THEN SUBST1_TAC THEN MATCH_MP_TAC VSUM_EQ THEN
    REWRITE_TAC[IN_ELIM_THM; COMPLEX_RING_CLAUSES] THEN
    X_GEN_TAC `j:num` THEN DISCH_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `complex_ring`; `(e:num->A->complex) l`]
      RING_HOMOMORPHISM_RING_OF_INT) THEN
    ANTS_TAC THENL
     [ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM];
      SIMP_TAC[COMPLEX_RING_OF_INT]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `x:A`] RING_OF_INTEGERS_SUM_NORM_POW_2) THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `sum (complex_embeddings k) (\g. norm((g:A->complex) x) pow 2) =
    sum {i | i < n} (\i. sum {i | i < n} (\j.
      Re(vsum {l | l < n} (\l. cnj(e l ((w:num->A) i)) * e l (w j))) *
