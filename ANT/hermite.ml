(* ========================================================================= *)
(* Hermite: only finitely many number fields have a given degree and a       *)
(* bounded discriminant; Hermite lower bound for the discriminant. For a     *)
(* number field k: E = complex_embeddings k, n = [k:Q], d_K =                *)
(* number_field_discriminant k, O = ring_of_integers k, N = ideal_norm O.    *)
(*                                                                           *)
(* Main results: for x <> 0 in O the product of the |g x| is at least 1      *)
(* (RING_OF_INTEGERS_NORM_PRODUCT_GE_1) and the sum of the |g x|^2 is at     *)
(* least n (RING_OF_INTEGERS_SUM_NORM_POW_2). Hermite bound: n^(2 n) <=      *)
(* (4/3)^(n (n - 1)) d_K^2 (NUMBER_FIELD_DISCRIMINANT_HERMITE_BOUND); it     *)
(* gives |d_K| > 1 for 2 <= n <= 22 only, while                              *)
(* NUMBER_FIELD_DISCRIMINANT_ABS_GT_1 of ANT/minkowski_theory.ml has |d_K| > *)
(* 1 for all n >= 2. An element x generates k iff its conjugates g x, g in   *)
(* E, are distinct, iff one of them is taken by only one g in E              *)
(* (NUMBER_FIELD_GENERATOR_CONJUGATES). Every number field is k = Q(x) for   *)
(* an algebraic integer x with |g x| <= 2^(n - 1) sqrt|d_K| for all g in E   *)
(* (NUMBER_FIELD_HERMITE_GENERATOR), a root of a monic integer polynomial of *)
(* degree n with coefficients bounded by (1 + 2^(n - 1) sqrt|d_K|)^n         *)
(* (NUMBER_FIELD_HERMITE_POLYNOMIAL). Hermite: for given n and X there is a  *)
(* finite set of monic integer polynomials of degree n such that every       *)
(* number field k of degree n with |d_K| <= X (of any type) is generated by  *)
(* a root of one of them (NUMBER_FIELD_HERMITE_POLYNOMIALS), so that k is    *)
(* isomorphic to Q[t]/(p) for one of finitely many p; in any integral domain *)
(* l (C, or any field) the subfields that are number fields of degree n with *)
(* |d_K| <= X are finitely many (NUMBER_FIELD_HERMITE), and finitely many    *)
(* subfields of C represent all these number fields up to isomorphism        *)
(* (NUMBER_FIELD_HERMITE_ISOMORPHIC).                                        *)
(*                                                                           *)
(* Routes. Hermite bound: for an integral basis w the Gram matrix G i j =    *)
(* Re(sum_g cnj(g w_i) g w_j) is the matrix of the form sum_g |g x|^2        *)
(* (COMPLEX_NORM_POW_2_VSUM_FORM) with det(G)^2 = d_K^2                      *)
(* (NUMBER_FIELD_EMBEDDING_GRAM_DET), and the form is positive definite;     *)
(* HERMITE_INEQUALITY of ANT/hermite_inequality.ml gives x <> 0 in O with    *)
(* (sum_g |g x|^2)^(2 n) <= (4/3)^(n (n - 1)) d_K^2, while sum_g |g x|^2 >=  *)
(* n by AM-GM (AGM_ROOT of Multivariate/realanalysis.ml) and |N(x)| >= 1.    *)
(* Generator (Neukirch III.2, Narkiewicz 2.24): fix g0 in E with conjugate   *)
(* g1 and apply Minkowski with a separate bound for each embedding           *)
(* (NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS of ANT/minkowski_theory.ml)    *)
(* with the bounds c_g0 = 2^(n - 1) sqrt|d_K| and c_g = 1/2 for g <> g0; the *)
(* element x gives |g x| <= 1/2 for g not in {g0, g1} (from the bounds at g  *)
(* and its conjugate) and |g0 x| > 1/2 (as |N(x)| >= 1); if g1 <> g0, the    *)
(* bound |Re(g0 x) - Im(g0 x)| <= 1/2 at g1 makes g0 x non-real. So g0 is    *)
(* the only embedding with value g0 x, and the extensions to k of g0 on L =  *)
(* Q(x) number [k:L] = 1 (HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS).            *)
(* Polynomials: the minimal polynomial p over Z of x                         *)
(* (RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL of ANT/dedekind_kummer.ml)   *)
(* has the n distinct conjugates of x as complex roots, so it has degree n   *)
(* and no other roots (COMPLEX_POLYFUN_ROOTBOUND), and                       *)
(* COMPLEX_POLYFUN_MONIC_COEFF_BOUND bounds its coefficients. Subfields:     *)
(* each is the subfield generated by a root in l of one of the finitely many *)
(* polynomials, and these have finitely many roots in l (POLY_ROOT_BOUND);   *)
(* up to isomorphism, k is the image of an embedding g                       *)
(* (RING_ISOMORPHISM_ONTO_SUBFIELD_IMAGE), generated by the complex root g   *)
(* x.                                                                        *)
(*                                                                           *)
(* Uses: Library/ringtheory.ml (polynomials, POLY_ROOT_BOUND, poly_extend),  *)
(* Library/fieldtheory.ml (subfields, extension degrees,                     *)
(* HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS,                                    *)
(* MINIMAL_POLYNOMIAL_DEG_LE_EXTENSION_DEGREE), Library/products.ml,         *)
(* Library/ring_det.ml, ANT/ideal_norm.ml, ANT/hermite_inequality.ml         *)
(* (HERMITE_INEQUALITY), ANT/numfield.ml, ANT/ring_of_integers.ml,           *)
(* ANT/classgroup.ml (INTEGRAL_DOMAIN_UNIT_IDEAL), ANT/discriminant.ml,      *)
(* ANT/dedekind_kummer.ml (RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL),     *)
(* ANT/complex_embeddings.ml (and with it Multivariate/cauchy.ml: the        *)
(* complex numbers, sqrt, root; COMPLEX_POLYFUN_MONIC_COEFF_BOUND),          *)
(* ANT/infinite_places.ml and ANT/minkowski_theory.ml                        *)
(* (NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS,                               *)
(* COMPLEX_NORM_POW_2_VSUM_FORM). Also Multivariate/complex_ring.ml          *)
(* (complex_ring), Multivariate/complex_field.ml                             *)
(* (ALGEBRAICALLY_CLOSED_FIELD_COMPLEX_RING),                                *)
(* Multivariate/transcendentals.ml (root) and Multivariate/realanalysis.ml   *)
(* (AGM_ROOT).                                                               *)
