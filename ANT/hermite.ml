(* The minimal polynomial over Z of the generator of                         *)
(* NUMBER_FIELD_HERMITE_GENERATOR                                            *)
(* (RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL of ANT/dedekind_kummer.ml)   *)
(* has the [k:Q] distinct conjugates of x as roots                           *)
(* (NUMBER_FIELD_GENERATOR_CONJUGATES), so it has degree [k:Q] and no other  *)
(* complex roots, and its coefficients are bounded by                        *)
(* COMPLEX_POLYFUN_MONIC_COEFF_BOUND.                                        *)
let NUMBER_FIELD_HERMITE_POLYNOMIAL = prove
 (`!(k:A ring) n.
        number_field k /\
        extension_degree (subfield_generated k {ring_0 k},k) I = n
        ==> ?x p. x IN ring_carrier(ring_of_integers k) /\
                  subfield_generated k {x} = k /\
                  p IN ring_carrier(poly_ring integer_ring (:1)) /\
                  monic integer_ring p /\ poly_deg integer_ring p = n /\
                  (!i. abs(real_of_int(coeff i p)) <=
                       (&1 + &2 pow (n - 1) *
                             sqrt(abs(real_of_int
                                    (number_field_discriminant k)))) pow n) /\
                  poly_extend (integer_ring,k) (ring_of_int k) (\v. x) p =
                  ring_0 k`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [number_field]) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP COMPLEX_EMBEDDINGS_HAS_SIZE) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_COMPLEX_EMBEDDINGS) THEN
  MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_HERMITE_GENERATOR) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC
   `R = &2 pow (n - 1) *
        sqrt(abs(real_of_int(number_field_discriminant(k:A ring))))` THEN
  DISCH_THEN(X_CHOOSE_THEN `x:A` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:A ring`; `x:A`]
    RING_OF_INTEGERS_INTEGER_MINIMAL_POLYNOMIAL) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:(1->num)->int` (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 (LABEL_TAC "deg")
     ASSUME_TAC)))) THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `poly_deg integer_ring (p:(1->num)->int) <= n` ASSUME_TAC THENL
   [REMOVE_THEN "deg" SUBST1_TAC THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (fun th ->
      rand(concl th) = `n:num`)) THEN
    MATCH_MP_TAC MINIMAL_POLYNOMIAL_DEG_LE_EXTENSION_DEGREE THEN
    ASM_REWRITE_TAC[];
    REMOVE_THEN "deg" (K ALL_TAC)] THEN
  MAP_EVERY EXISTS_TAC [`x:A`; `p:(1->num)->int`] THEN ASM_REWRITE_TAC[] THEN
  ABBREV_TAC `d = poly_deg integer_ring (p:(1->num)->int)` THEN
  SUBGOAL_THEN `coeff d (p:(1->num)->int) = &1` ASSUME_TAC THENL
   [UNDISCH_TAC `monic integer_ring (p:(1->num)->int)` THEN
    ASM_REWRITE_TAC[monic; INTEGER_RING];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!z. vsum(0..d) (\i. Cx(real_of_int(coeff i (p:(1->num)->int))) *
                        z pow i) =
        poly_extend (integer_ring,complex_ring) (ring_of_int complex_ring)
                    (\v:1. z) p`
  (LABEL_TAC "ext") THENL
   [GEN_TAC THEN
    MP_TAC(ISPECL [`integer_ring`; `complex_ring`;
                   `ring_of_int complex_ring:int->complex`; `\v:1. (z:complex)`;
                   `p:(1->num)->int`] POLY_EXTEND_UNIVARIATE) THEN
    REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; COMPLEX_RING_CLAUSES;
      IN_UNIV; ASSUME `poly_deg integer_ring (p:(1->num)->int) = d`;
      ASSUME `(p:(1->num)->int) IN ring_carrier(poly_ring integer_ring (:1))`]
    THEN DISCH_THEN SUBST1_TAC THEN
    SIMP_TAC[COMPLEX_RING_SUM; FINITE_NUMSEG; COMPLEX_RING_CLAUSES;
             COMPLEX_RING_OF_INT; COMPLEX_RING_POW];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN complex_embeddings k
        ==> vsum(0..d) (\i. Cx(real_of_int(coeff i (p:(1->num)->int))) *
                            (g:A->complex) x pow i) = Cx(&0)`
  ASSUME_TAC THENL
   [X_GEN_TAC `g:A->complex` THEN DISCH_TAC THEN
    SUBGOAL_THEN `ring_homomorphism(k,complex_ring) (g:A->complex)`
    ASSUME_TAC THENL
     [UNDISCH_TAC `(g:A->complex) IN complex_embeddings k` THEN
      SIMP_TAC[complex_embeddings; IN_ELIM_THM];
      ALL_TAC] THEN
    USE_THEN "ext" (fun th -> REWRITE_TAC[th]) THEN
    MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `complex_ring`;
                   `ring_of_int k:int->A`; `(:1)`; `\v:1. (x:A)`;
