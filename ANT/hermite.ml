  SUBST1_TAC THENL
   [TRANS_TAC EQ_TRANS
     `sum {l | l < n} (\l. norm((e:num->A->complex) l x) pow 2)` THEN
    CONJ_TAC THENL
     [SUBGOAL_THEN
       `complex_embeddings (k:A ring) = IMAGE (e:num->A->complex) {i | i < n}`
      SUBST1_TAC THENL
       [REWRITE_TAC[EXTENSION; IN_IMAGE; IN_ELIM_THM] THEN ASM_MESON_TAC[];
        ALL_TAC] THEN
      W(MP_TAC o PART_MATCH (lhand o rand) SUM_IMAGE o lhand o snd) THEN
      ANTS_TAC THENL
       [REWRITE_TAC[IN_ELIM_THM] THEN ASM_REWRITE_TAC[];
        DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[o_DEF]];
      ALL_TAC] THEN
    TRANS_TAC EQ_TRANS
     `sum {l | l < n} (\l. norm(vsum {j | j < n}
