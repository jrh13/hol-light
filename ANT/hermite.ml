(* For an integral basis w and an enumeration e of the embeddings, the Gram  *)
(* matrix G i j = Re(sum_l cnj(e_l(w_i)) e_l(w_j)) of the form sum_g |g x|^2 *)
(* (COMPLEX_NORM_POW_2_VSUM_FORM) has det(G)^2 = d_K^2                       *)
(* (NUMBER_FIELD_EMBEDDING_GRAM_DET); HERMITE_INEQUALITY gives x <> 0 in O   *)
(* with a small value, and the value is at least [k:Q]                       *)
(* (RING_OF_INTEGERS_SUM_NORM_POW_2).                                        *)
let NUMBER_FIELD_DISCRIMINANT_HERMITE_BOUND = prove
 (`!k:A ring.
        number_field k
        ==> &(extension_degree (subfield_generated k {ring_0 k},k) I) pow
            (2 * extension_degree (subfield_generated k {ring_0 k},k) I) <=
            (&4 / &3) pow
            (extension_degree (subfield_generated k {ring_0 k},k) I *
             (extension_degree (subfield_generated k {ring_0 k},k) I - 1)) *
            real_of_int(number_field_discriminant k) pow 2`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(X_CHOOSE_TAC `w:num->A` o MATCH_MP RING_OF_INTEGERS_FREE) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_DEGREE_POS) THEN
  MP_TAC(ISPEC `k:A ring` COMPLEX_EMBEDDINGS_HAS_SIZE) THEN
  ASM_REWRITE_TAC[] THEN
  ABBREV_TAC
   `n = extension_degree (subfield_generated k {ring_0 k},k:A ring) I` THEN
  DISCH_THEN(MP_TAC o MATCH_MP HAS_SIZE_INDEX) THEN
  DISCH_THEN(X_CHOOSE_THEN `e:num->A->complex` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN
   `!i j. i < n /\ j < n /\ (e:num->A->complex) i = e j ==> i = j`
  ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `!i. i < n ==> (w:num->A) i IN ring_carrier k` ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o MATCH_MP FREE_BASIS_IN_CARRIER o check (fun th ->
      free_in `w:num->A` (concl th) && not(is_forall(concl th)))) THEN
    MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET];
    ALL_TAC] THEN
  MP_TAC(ISPECL
   [`{i:num | i < n}`;
    `\i j. Re(vsum {l | l < n}
               (\l. cnj((e:num->A->complex) l ((w:num->A) i)) * e l (w j)))`]
   HERMITE_INEQUALITY) THEN
  REWRITE_TAC[FINITE_NUMSEG_LT; CARD_NUMSEG_LT] THEN ANTS_TAC THENL
   [REPEAT CONJ_TAC THENL
     [REWRITE_TAC[GSYM MEMBER_NOT_EMPTY; IN_ELIM_THM] THEN
      EXISTS_TAC `0` THEN ASM_ARITH_TAC;
      REWRITE_TAC[IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
      GEN_REWRITE_TAC RAND_CONV [GSYM RE_CNJ] THEN AP_TERM_TAC THEN
      SIMP_TAC[CNJ_VSUM; FINITE_NUMSEG_LT; CNJ_MUL; CNJ_CNJ] THEN
      MATCH_MP_TAC VSUM_EQ THEN SIMP_TAC[COMPLEX_MUL_SYM];
      X_GEN_TAC `c:num->real` THEN REWRITE_TAC[IN_ELIM_THM] THEN STRIP_TAC THEN
      MP_TAC(BETA_RULE(ISPECL
       [`{l:num | l < n}`; `{j:num | j < n}`;
        `\l j. (e:num->A->complex) l ((w:num->A) j)`; `c:num->real`]
       COMPLEX_NORM_POW_2_VSUM_FORM)) THEN
      REWRITE_TAC[FINITE_NUMSEG_LT] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
      MATCH_MP_TAC(REAL_ARITH `&0 <= x /\ ~(x = &0) ==> &0 < x:real`) THEN
      SIMP_TAC[SUM_POS_LE; FINITE_NUMSEG_LT; REAL_LE_POW_2] THEN
      DISCH_TAC THEN
      MP_TAC(ISPECL
       [`\l. norm(vsum {j | j < n}
                   (\j. Cx(c j) * (e:num->A->complex) l ((w:num->A) j))) pow 2`;
        `{l:num | l < n}`] SUM_POS_EQ_0) THEN
      ASM_REWRITE_TAC[FINITE_NUMSEG_LT; REAL_LE_POW_2; IN_ELIM_THM] THEN
      REWRITE_TAC[REAL_POW_EQ_0; COMPLEX_NORM_ZERO] THEN
      CONV_TAC NUM_REDUCE_CONV THEN DISCH_TAC THEN
      MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_DISCRIMINANT_NONZERO) THEN
      ASM_REWRITE_TAC[] THEN
      MP_TAC(ISPECL [`k:A ring`; `n:num`; `w:num->A`; `e:num->A->complex`]
        NUMBER_FIELD_DISCRIMINANT_EMBEDDINGS) THEN
      ASM_REWRITE_TAC[] THEN
      SUBGOAL_THEN
       `ring_det complex_ring {i | i < n}
          (\i j. (e:num->A->complex) i ((w:num->A) j)) = Cx(&0)`
      SUBST1_TAC THENL
       [MP_TAC(ISPECL [`complex_ring`; `{i:num | i < n}`;
                       `\l j. (e:num->A->complex) l ((w:num->A) j)`;
                       `\j. Cx((c:num->real) j)`]
          RING_DET_DEPENDENT_COLUMNS) THEN
        SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN; FIELD_COMPLEX_RING;
                 FINITE_NUMSEG_LT; COMPLEX_RING_CLAUSES; IN_UNIV;
                 COMPLEX_RING_SUM] THEN
        DISCH_THEN MATCH_MP_TAC THEN REWRITE_TAC[IN_ELIM_THM; CX_INJ] THEN
        CONJ_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
        X_GEN_TAC `l:num` THEN DISCH_TAC THEN
        FIRST_X_ASSUM(MP_TAC o SPEC `l:num` o check (fun th ->
          is_forall(concl th) && free_in `c:num->real` (concl th))) THEN
        ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
        MATCH_MP_TAC VSUM_EQ THEN SIMP_TAC[COMPLEX_MUL_SYM];
        REWRITE_TAC[COMPLEX_POW_ZERO] THEN CONV_TAC NUM_REDUCE_CONV THEN
        REWRITE_TAC[CX_INJ] THEN DISCH_THEN(MP_TAC o SYM) THEN
        REWRITE_TAC[int_eq; int_of_num_th]]];
    ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:num->int` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`k:A ring`; `n:num`; `w:num->A`; `e:num->A->complex`]
    NUMBER_FIELD_EMBEDDING_GRAM_DET) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(fun th -> RULE_ASSUM_TAC(REWRITE_RULE[th])) THEN
  ABBREV_TAC
   `x = ring_sum (ring_of_integers k) {j | j < n}
          (\j. ring_mul (ring_of_integers k) (ring_of_int k ((c:num->int) j))
                        ((w:num->A) j))` THEN
  SUBGOAL_THEN
   `!j. j < n ==> ring_of_int k ((c:num->int) j) IN
                  ring_carrier(ring_of_integers (k:A ring)) /\
                  (w:num->A) j IN ring_carrier(ring_of_integers k)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THENL
     [MP_TAC(ISPECL [`ring_of_integers k:A ring`; `(c:num->int) j`]
        RING_OF_INT) THEN
      REWRITE_TAC[RING_OF_INTEGERS];
      ASM_MESON_TAC[FREE_BASIS_IN_CARRIER]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(x:A) IN ring_carrier(ring_of_integers k) /\ ~(x = ring_0 k)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL [EXPAND_TAC "x" THEN REWRITE_TAC[RING_SUM]; ALL_TAC] THEN
    DISCH_TAC THEN
    MP_TAC(SPEC `c:num->int` (CONJUNCT2(CONJUNCT2(GEN_REWRITE_RULE I
