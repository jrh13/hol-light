             (e:num->A->complex) l ((w:num->A) j))) pow 2)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SUM_EQ THEN ASM_SIMP_TAC[IN_ELIM_THM]; ALL_TAC] THEN
    MP_TAC(BETA_RULE(ISPECL
     [`{l:num | l < n}`; `{j:num | j < n}`;
      `\l j. (e:num->A->complex) l ((w:num->A) j)`;
      `\j. real_of_int((c:num->int) j)`] COMPLEX_NORM_POW_2_VSUM_FORM)) THEN
    REWRITE_TAC[FINITE_NUMSEG_LT];
    ALL_TAC] THEN
  DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o check (fun th ->
    free_in `number_field_discriminant (k:A ring)` (concl th) &&
    free_in `c:num->int` (concl th))) THEN
  MATCH_MP_TAC(REAL_ARITH `a <= b ==> b <= c ==> a <= c:real`) THEN
  MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[REAL_POS]);;

(* ------------------------------------------------------------------------- *)
(* A generator with bounded conjugates.                                      *)
(* ------------------------------------------------------------------------- *)

(* x generates k iff its conjugates g x, g in E, are distinct, iff one of    *)
(* them is taken by only one embedding g. Local lemma (simple): the last     *)
(* condition suffices, as the extensions to k of the restriction of g to     *)
(* L = Q(x) agree with g at x, so there is only one of them, while their     *)
(* number is [k:L] (HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS).                  *)
let NUMBER_FIELD_GENERATOR_CONJUGATES =
  let simple = prove
   (`!k (x:A) g.
          number_field k /\ x IN ring_carrier k /\ g IN complex_embeddings k /\
          (!h. h IN complex_embeddings k /\ h x = g x ==> h = g)
          ==> subfield_generated k {x} = k`,
    REPEAT STRIP_TAC THEN
    FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [number_field]) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
    ABBREV_TAC
     `L = subfield_generated k
           ((x:A) INSERT ring_carrier(subfield_generated k {ring_0 k}))` THEN
    SUBGOAL_THEN `finite_extension (L,k) (I:A->A)` ASSUME_TAC THENL
     [EXPAND_TAC "L" THEN
      MP_TAC(ISPECL
       [`I:A->A`; `subfield_generated k {ring_0 k}:A ring`; `k:A ring`;
        `(x:A) INSERT ring_carrier(subfield_generated k {ring_0 k})`]
        FINITE_EXTENSION_SUBFIELD_GENERATED) THEN
      ASM_SIMP_TAC[IMAGE_I; SET_RULE `s SUBSET (x:A) INSERT s`];
      ALL_TAC] THEN
    SUBGOAL_THEN `(x:A) IN ring_carrier L` ASSUME_TAC THENL
     [EXPAND_TAC "L" THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
      ASM_REWRITE_TAC[IN_INSERT];
      ALL_TAC] THEN
    SUBGOAL_THEN `ring_homomorphism(k,complex_ring) (g:A->complex)`
    ASSUME_TAC THENL
     [ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM]; ALL_TAC] THEN
    MP_TAC(ISPECL [`I:A->A`; `g:A->complex`; `L:A ring`; `k:A ring`;
                   `complex_ring`] HAS_SIZE_RING_HOMOMORPHISM_EXTENSIONS) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[ALGEBRAICALLY_CLOSED_FIELD_COMPLEX_RING] THEN
      CONJ_TAC THENL
       [MATCH_MP_TAC SEPARABLE_EXTENSION_CHAR0 THEN
        ASM_SIMP_TAC[FINITE_IMP_ALGEBRAIC_EXTENSION] THEN
        EXPAND_TAC "L" THEN ASM_REWRITE_TAC[RING_CHAR_SUBFIELD_GENERATED];
        EXPAND_TAC "L" THEN
        ASM_SIMP_TAC[RING_HOMOMORPHISM_FROM_SUBFIELD_GENERATED]];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `ring_homomorphism_extensions (L,k,complex_ring) (I,g:A->complex) = {g}`
    SUBST1_TAC THENL
     [REWRITE_TAC[ring_homomorphism_extensions; EXTENSION; IN_ELIM_THM;
                  IN_SING; I_THM] THEN
      X_GEN_TAC `f:A->complex` THEN EQ_TAC THENL
       [STRIP_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
        ASM_SIMP_TAC[complex_embeddings; IN_ELIM_THM];
        DISCH_THEN SUBST1_TAC THEN
        ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM]];
      ALL_TAC] THEN
    REWRITE_TAC[HAS_SIZE; FINITE_SING; CARD_SING] THEN
    DISCH_THEN(ASSUME_TAC o SYM) THEN
    MP_TAC(ISPECL [`I:A->A`; `L:A ring`; `k:A ring`] EXTENSION_DEGREE_EQ_1) THEN
    ANTS_TAC THENL
     [EXPAND_TAC "L" THEN ASM_REWRITE_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED];
      ASM_REWRITE_TAC[IMAGE_I]] THEN
    DISCH_TAC THEN REWRITE_TAC[SUBFIELD_GENERATED_SUPERSET] THEN
    FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN EXPAND_TAC "L" THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; INSERT_SUBSET] THEN
    ASM_SIMP_TAC[SUBFIELD_GENERATED_INC_GEN; IN_SING] THEN
    MATCH_MP_TAC PRIME_SUBFIELD_MINIMAL THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED]) in
  prove
   (`!k x:A.
        number_field k /\ x IN ring_carrier k
        ==> (subfield_generated k {x} = k <=>
             !g h. g IN complex_embeddings k /\ h IN complex_embeddings k /\
                   g x = h x
                   ==> g = h) /\
            (subfield_generated k {x} = k <=>
             ?g. g IN complex_embeddings k /\
                 !h. h IN complex_embeddings k /\ h x = g x ==> h = g)`,
    REPEAT GEN_TAC THEN STRIP_TAC THEN
    MATCH_MP_TAC(TAUT
     `(a ==> b) /\ (b ==> c) /\ (c ==> a) ==> (a <=> b) /\ (a <=> c)`) THEN
    REPEAT CONJ_TAC THENL
     [DISCH_TAC THEN MAP_EVERY X_GEN_TAC [`g:A->complex`; `h:A->complex`] THEN
      STRIP_TAC THEN MATCH_MP_TAC EXTENSIONAL_EQ THEN
      EXISTS_TAC `ring_carrier k:A->bool` THEN
      REPEAT CONJ_TAC THENL
       [ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM];
        ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM];
        ALL_TAC] THEN
      MP_TAC(ISPECL [`g:A->complex`; `h:A->complex`; `k:A ring`;
                     `complex_ring`; `{x:A}`]
        RING_HOMOMORPHISMS_EQ_FROM_SUBFIELD_GENERATED) THEN
      ASM_REWRITE_TAC[IN_SING] THEN ANTS_TAC THENL
       [ASM_MESON_TAC[complex_embeddings; IN_ELIM_THM; NUMBER_FIELD_IMP_FIELD];
        SIMP_TAC[]];
      DISCH_TAC THEN
      FIRST_ASSUM(X_CHOOSE_TAC `g:A->complex` o
        REWRITE_RULE[GSYM MEMBER_NOT_EMPTY] o
        MATCH_MP COMPLEX_EMBEDDINGS_NONEMPTY) THEN
      EXISTS_TAC `g:A->complex` THEN ASM_MESON_TAC[];
      DISCH_THEN(X_CHOOSE_THEN `g:A->complex` STRIP_ASSUME_TAC) THEN
      MATCH_MP_TAC simple THEN EXISTS_TAC `g:A->complex` THEN
      ASM_REWRITE_TAC[]]);;

(* Minkowski with the bound C = 2^(n-1) sqrt|d_K| at one embedding g0 and    *)
(* 1/2 at the others gives x <> 0 in O with |g x| <= 1/2 for g not g0 or its *)
(* conjugate g1, |g0 x| <= C, and, as |N(x)| >= 1, |g0 x| > 1/2; when g1 is  *)
(* not g0, |Re(g0 x) - Im(g0 x)| <= 1/2 forces g0 x to be non-real. So only  *)
(* g0 takes the value g0 x, and x generates k                                *)
(* (NUMBER_FIELD_GENERATOR_CONJUGATES).                                      *)
let NUMBER_FIELD_HERMITE_GENERATOR = prove
 (`!k:A ring.
        number_field k
        ==> ?x. x IN ring_carrier(ring_of_integers k) /\
                subfield_generated k {x} = k /\
                !g. g IN complex_embeddings k
                    ==> norm(g x) <=
                        &2 pow
                        (extension_degree (subfield_generated k {ring_0 k},k) I
                         - 1) *
                        sqrt(abs(real_of_int(number_field_discriminant k)))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_DEGREE_POS) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP COMPLEX_EMBEDDINGS_HAS_SIZE) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_COMPLEX_EMBEDDINGS) THEN
  ABBREV_TAC
   `n = extension_degree (subfield_generated k {ring_0 k},k:A ring) I` THEN
  ABBREV_TAC
   `D = sqrt(abs(real_of_int(number_field_discriminant(k:A ring))))` THEN
  SUBGOAL_THEN `&1 <= (D:real)` ASSUME_TAC THENL
   [EXPAND_TAC "D" THEN MATCH_MP_TAC REAL_LE_RSQRT THEN
    REWRITE_TAC[REAL_POW_ONE] THEN
    MP_TAC(ISPEC `k:A ring` NUMBER_FIELD_DISCRIMINANT_NONZERO) THEN
    ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[GSYM int_of_num_th; GSYM int_abs_th; GSYM int_le] THEN
    INT_ARITH_TAC;
    ALL_TAC] THEN
  FIRST_ASSUM(X_CHOOSE_TAC `g0:A->complex` o
    REWRITE_RULE[GSYM MEMBER_NOT_EMPTY] o
    MATCH_MP COMPLEX_EMBEDDINGS_NONEMPTY) THEN
  ABBREV_TAC `(C:real) = &2 pow (n - 1) * D` THEN
  SUBGOAL_THEN `&1 <= (C:real)` ASSUME_TAC THENL
   [EXPAND_TAC "C" THEN GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
    MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[REAL_POS] THEN
    MATCH_MP_TAC REAL_POW_LE_1 THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`k:A ring`; `ring_carrier(ring_of_integers k):A->bool`;
                 `\g:A->complex. if g = g0 then C else &1 / &2`]
    NUMBER_FIELD_IDEAL_MINKOWSKI_LINEAR_FORMS) THEN
  ASM_REWRITE_TAC[IDEAL_NORM_CARRIER; REAL_MUL_RID] THEN ANTS_TAC THENL
   [REPEAT CONJ_TAC THENL
     [MP_TAC(ISPEC `ring_of_integers k:A ring` INTEGRAL_DOMAIN_UNIT_IDEAL) THEN
      ASM_SIMP_TAC[INTEGRAL_DOMAIN_RING_OF_INTEGERS; RING_OF_INTEGERS];
      MP_TAC(ISPEC `ring_of_integers k:A ring` INTEGRAL_DOMAIN_UNIT_IDEAL) THEN
      ASM_SIMP_TAC[INTEGRAL_DOMAIN_RING_OF_INTEGERS; RING_OF_INTEGERS];
      GEN_TAC THEN COND_CASES_TAC THEN ASM_REAL_ARITH_TAC;
      ALL_TAC] THEN
    MP_TAC(ISPECL [`\g:A->complex. if g = g0 then C else &1 / &2`;
                   `complex_embeddings(k:A ring)`; `g0:A->complex`]
      PRODUCT_DELETE) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    SUBGOAL_THEN
     `product (complex_embeddings k DELETE g0)
        (\g:A->complex. if g = g0 then C else &1 / &2) =
      (&1 / &2) pow (n - 1)`
    SUBST1_TAC THENL
     [TRANS_TAC EQ_TRANS
       `product (complex_embeddings k DELETE (g0:A->complex)) (\g. &1 / &2)`
      THEN CONJ_TAC THENL
       [MATCH_MP_TAC PRODUCT_EQ THEN SIMP_TAC[IN_DELETE];
        ASM_SIMP_TAC[PRODUCT_CONST; FINITE_DELETE; CARD_DELETE] THEN
        RULE_ASSUM_TAC(REWRITE_RULE[HAS_SIZE]) THEN ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    SUBGOAL_THEN `&2 pow (n - 1) * (&1 / &2) pow (n - 1) = &1` MP_TAC THENL
     [REWRITE_TAC[GSYM REAL_POW_MUL] THEN CONV_TAC REAL_RAT_REDUCE_CONV THEN
      REWRITE_TAC[REAL_POW_ONE];
      EXPAND_TAC "C" THEN
      REWRITE_TAC[REAL_ARITH `(a * d) * b:real = d * (a * b)`] THEN
      SIMP_TAC[REAL_MUL_RID; REAL_LE_REFL]];
    ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `x:A` (CONJUNCTS_THEN2 ASSUME_TAC
    (CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "bd")))) THEN
  EXISTS_TAC `x:A` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN complex_embeddings k
        ==> RESTRICTION (ring_carrier k) (cnj o g) IN complex_embeddings k /\
            RESTRICTION (ring_carrier k) (cnj o g) x = cnj((g:A->complex) x)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[COMPLEX_EMBEDDINGS_CNJ; RESTRICTION; o_THM]; ALL_TAC] THEN
  ABBREV_TAC `g1 = RESTRICTION (ring_carrier k) (cnj o (g0:A->complex))` THEN
  SUBGOAL_THEN
   `(g1:A->complex) IN complex_embeddings k /\ g1 x = cnj((g0:A->complex) x)`
  STRIP_ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!g. g IN complex_embeddings k /\ ~(g = g0) /\ ~(g = g1)
        ==> norm((g:A->complex) x) <= &1 / &2`
  ASSUME_TAC THENL
   [X_GEN_TAC `g:A->complex` THEN STRIP_TAC THEN
    SUBGOAL_THEN
     `~(RESTRICTION (ring_carrier k) (cnj o (g:A->complex)) = g0)`
    ASSUME_TAC THENL
     [DISCH_TAC THEN UNDISCH_TAC `~((g:A->complex) = g1)` THEN
      REWRITE_TAC[] THEN EXPAND_TAC "g1" THEN
      FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
      ASM_SIMP_TAC[COMPLEX_EMBEDDINGS_CNJ_CNJ];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `RESTRICTION (ring_carrier k) (cnj o (g:A->complex)) IN
      complex_embeddings k /\
      RESTRICTION (ring_carrier k) (cnj o g) x = cnj(g x)`
    STRIP_ASSUME_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
    USE_THEN "bd" (fun th ->
      MP_TAC(MP (SPEC `g:A->complex` th)
                (ASSUME `(g:A->complex) IN complex_embeddings k`)) THEN
      MP_TAC(MP (SPEC `RESTRICTION (ring_carrier k) (cnj o (g:A->complex))` th)
                (ASSUME `RESTRICTION (ring_carrier k) (cnj o (g:A->complex)) IN
                         complex_embeddings k`))) THEN
    REWRITE_TAC[ASSUME `~((g:A->complex) = g0)`;
      ASSUME `~(RESTRICTION (ring_carrier k) (cnj o (g:A->complex)) = g0)`;
      ASSUME `RESTRICTION (ring_carrier k) (cnj o (g:A->complex)) x =
              cnj(g x)`; RE_CNJ; IM_CNJ] THEN
    MP_TAC(SPEC `(g:A->complex) x` COMPLEX_NORM_LE_RE_IM) THEN
    REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `norm((g0:A->complex) x) <= C` ASSUME_TAC THENL
   [USE_THEN "bd" (fun th ->
      MP_TAC(MP (SPEC `g0:A->complex` th)
                (ASSUME `(g0:A->complex) IN complex_embeddings k`)) THEN
      MP_TAC(MP (SPEC `g1:A->complex` th)
                (ASSUME `(g1:A->complex) IN complex_embeddings k`))) THEN
    REWRITE_TAC[ASSUME `(g1:A->complex) x = cnj((g0:A->complex) x)`;
                RE_CNJ; IM_CNJ] THEN
    MP_TAC(SPEC `(g0:A->complex) x` COMPLEX_NORM_LE_RE_IM) THEN
    UNDISCH_TAC `&1 <= (C:real)` THEN COND_CASES_TAC THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 / &2 < norm((g0:A->complex) x)` ASSUME_TAC THENL
   [REWRITE_TAC[GSYM REAL_NOT_LE] THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `x:A`] RING_OF_INTEGERS_NORM_PRODUCT_GE_1) THEN
    ASM_REWRITE_TAC[REAL_NOT_LE] THEN
    TRANS_TAC REAL_LET_TRANS
     `product (complex_embeddings k) (\g:A->complex. &1 / &2)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC PRODUCT_LE THEN ASM_REWRITE_TAC[NORM_POS_LE] THEN
      X_GEN_TAC `g:A->complex` THEN DISCH_TAC THEN
      ASM_CASES_TAC `g:A->complex = g0` THEN ASM_REWRITE_TAC[] THEN
      ASM_CASES_TAC `g:A->complex = g1` THEN
      ASM_SIMP_TAC[COMPLEX_NORM_CNJ];
      ASM_SIMP_TAC[PRODUCT_CONST] THEN
      RULE_ASSUM_TAC(REWRITE_RULE[HAS_SIZE]) THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC REAL_POW_1_LT THEN
      CONJ_TAC THENL [ASM_ARITH_TAC; REAL_ARITH_TAC]];
    ALL_TAC] THEN
  CONJ_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `x:A`] NUMBER_FIELD_GENERATOR_CONJUGATES) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN(SUBST1_TAC o CONJUNCT2) THEN
    EXISTS_TAC `g0:A->complex` THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `h:A->complex` THEN STRIP_TAC THEN
    MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
    ASM_CASES_TAC `h:A->complex = g1` THENL
     [SUBGOAL_THEN `~(g1:A->complex = g0)` ASSUME_TAC THENL
       [ASM_MESON_TAC[]; ALL_TAC] THEN
      SUBGOAL_THEN `Im((g0:A->complex) x) = &0` ASSUME_TAC THENL
       [SUBGOAL_THEN `cnj((g0:A->complex) x) = g0 x` MP_TAC THENL
         [ASM_MESON_TAC[]; ALL_TAC] THEN
        REWRITE_TAC[COMPLEX_EQ; RE_CNJ; IM_CNJ] THEN REAL_ARITH_TAC;
        ALL_TAC] THEN
      USE_THEN "bd" (fun th ->
        MP_TAC(MP (SPEC `g1:A->complex` th)
                  (ASSUME `(g1:A->complex) IN complex_embeddings k`))) THEN
      REWRITE_TAC[ASSUME `(g1:A->complex) x = cnj((g0:A->complex) x)`;
                  ASSUME `~((g1:A->complex) = g0)`; RE_CNJ; IM_CNJ] THEN
      MP_TAC(SPEC `(g0:A->complex) x` COMPLEX_NORM_LE_RE_IM) THEN
      UNDISCH_TAC `&1 / &2 < norm((g0:A->complex) x)` THEN
      UNDISCH_TAC `Im((g0:A->complex) x) = &0` THEN REAL_ARITH_TAC;
      FIRST_X_ASSUM(MP_TAC o SPEC `h:A->complex` o check (fun th ->
        free_in `g1:A->complex` (concl th) && is_forall(concl th))) THEN
      ASM_REWRITE_TAC[] THEN
      UNDISCH_TAC `&1 / &2 < norm((g0:A->complex) x)` THEN REAL_ARITH_TAC];
    X_GEN_TAC `g:A->complex` THEN DISCH_TAC THEN
    ASM_CASES_TAC `g:A->complex = g0` THEN ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `g:A->complex = g1` THEN
    ASM_SIMP_TAC[COMPLEX_NORM_CNJ] THEN
    MATCH_MP_TAC REAL_LE_TRANS THEN EXISTS_TAC `&1 / &2` THEN CONJ_TAC THENL
     [FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
        free_in `g1:A->complex` (concl th) && is_forall(concl th))) THEN
      ASM_REWRITE_TAC[];
      UNDISCH_TAC `&1 <= (C:real)` THEN REAL_ARITH_TAC]]);;

