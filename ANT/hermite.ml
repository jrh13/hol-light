(* Hermite, in the form of a finite set of polynomials: one finite set P of  *)
(* monic integer polynomials of degree n serves for all number fields of     *)
(* degree n with |d_K| <= X (in any type): each of them is generated by a    *)
(* root of a member of P, so it is isomorphic to Q[t]/(p) for some p in P.   *)
let NUMBER_FIELD_HERMITE_POLYNOMIALS = prove
 (`!n X. ?P. FINITE P /\
             (!p. p IN P
                  ==> p IN ring_carrier(poly_ring integer_ring (:1)) /\
                      monic integer_ring p /\ poly_deg integer_ring p = n) /\
             !k:A ring.
                number_field k /\
                extension_degree (subfield_generated k {ring_0 k},k) I = n /\
                abs(real_of_int(number_field_discriminant k)) <= X
                ==> ?p x. p IN P /\ x IN ring_carrier(ring_of_integers k) /\
                          subfield_generated k {x} = k /\
                          poly_extend (integer_ring,k) (ring_of_int k)
                                      (\v. x) p =
                          ring_0 k`,
  REPEAT GEN_TAC THEN
  ABBREV_TAC `B = (&1 + &2 pow (n - 1) * sqrt X) pow n` THEN
  EXISTS_TAC
   `{p | p IN ring_carrier(poly_ring integer_ring (:1)) /\
         monic integer_ring p /\ poly_deg integer_ring p = n /\
         !i. abs(real_of_int(coeff i p)) <= B}` THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC
     `IMAGE (\c:num->int m:1->num. c(m one))
            {c | (!i. i IN 0..n ==> c i IN {u:int | abs(real_of_int u) <= B}) /\
                 (!i. ~(i IN 0..n) ==> c i = &0)}` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC FINITE_IMAGE THEN MATCH_MP_TAC FINITE_FUNSPACE THEN
      REWRITE_TAC[FINITE_NUMSEG] THEN
      MP_TAC(SPEC `B:real` REAL_ARCH_SIMPLE) THEN
      DISCH_THEN(X_CHOOSE_TAC `N:num`) THEN MATCH_MP_TAC FINITE_SUBSET THEN
      EXISTS_TAC `{u:int | --(&N) <= u /\ u <= &N}` THEN
      REWRITE_TAC[FINITE_INT_SEG; SUBSET; IN_ELIM_THM; GSYM INT_ABS_BOUNDS] THEN
      REWRITE_TAC[int_le; int_abs_th; int_of_num_th] THEN
      ASM_MESON_TAC[REAL_LE_TRANS];
      ALL_TAC] THEN
    REWRITE_TAC[SUBSET; IN_ELIM_THM; IN_IMAGE; IN_NUMSEG; LE_0; NOT_LE] THEN
    X_GEN_TAC `p:(1->num)->int` THEN STRIP_TAC THEN
    EXISTS_TAC `\i. coeff i (p:(1->num)->int)` THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [REWRITE_TAC[GSYM FUN_EQ_COEFF] THEN REWRITE_TAC[coeff];
      REPEAT STRIP_TAC THEN
      MP_TAC(ISPECL [`integer_ring`; `p:(1->num)->int`; `i:num`]
        COEFF_ABOVE_DEG) THEN
      ASM_REWRITE_TAC[RING_POLYNOMIAL; INTEGER_RING]];
    SIMP_TAC[IN_ELIM_THM];
    X_GEN_TAC `k:A ring` THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`k:A ring`; `n:num`] NUMBER_FIELD_HERMITE_POLYNOMIAL) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `x:A` (X_CHOOSE_THEN `p:(1->num)->int`
      STRIP_ASSUME_TAC)) THEN
    MAP_EVERY EXISTS_TAC [`p:(1->num)->int`; `x:A`] THEN
    ASM_REWRITE_TAC[IN_ELIM_THM] THEN
    X_GEN_TAC `i:num` THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `i:num` o check (fun th ->
      is_forall(concl th) && free_in `coeff:num->((1->num)->int)->int`
                                      (concl th))) THEN
    MATCH_MP_TAC(REAL_ARITH `b <= c ==> a <= b ==> a <= c:real`) THEN
    EXPAND_TAC "B" THEN MATCH_MP_TAC REAL_POW_LE2 THEN CONJ_TAC THENL
     [MATCH_MP_TAC(REAL_ARITH `&0 <= (x:real) ==> &0 <= &1 + x`) THEN
      MATCH_MP_TAC REAL_LE_MUL THEN
      SIMP_TAC[REAL_POW_LE; REAL_POS; SQRT_POS_LE; REAL_ABS_POS];
      REWRITE_TAC[REAL_LE_LADD] THEN MATCH_MP_TAC REAL_LE_LMUL THEN
      SIMP_TAC[REAL_POW_LE; REAL_POS] THEN MATCH_MP_TAC SQRT_MONO_LE THEN
      ASM_REWRITE_TAC[]]]);;

(* Hermite for subfields of an integral domain l: those that are number      *)
(* fields of degree n with |d_K| <= X are finitely many. The degree is taken *)
(* over the prime subfield of l, which is that of the subfield               *)
(* (PRIME_SUBFIELD_SUBFIELD_GENERATED). Each such subfield is generated by a *)
(* root in l of one of the polynomials of NUMBER_FIELD_HERMITE_POLYNOMIALS,  *)
(* and these have finitely many roots in l (POLY_ROOT_BOUND).                *)
let NUMBER_FIELD_HERMITE = prove
 (`!(l:B ring) n X.
        integral_domain l
        ==> FINITE {s | s subfield_of l /\
                        number_field(subfield_generated l s) /\
                        extension_degree (subfield_generated l {ring_0 l},
                                          subfield_generated l s) I = n /\
                        abs(real_of_int(number_field_discriminant
                                         (subfield_generated l s))) <= X}`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`n:num`; `X:real`]
    (INST_TYPE [`:B`,`:A`] NUMBER_FIELD_HERMITE_POLYNOMIALS)) THEN
  DISCH_THEN(X_CHOOSE_THEN `P:((1->num)->int)->bool` (CONJUNCTS_THEN2
    ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "P")))) THEN
  MATCH_MP_TAC FINITE_SUBSET THEN
  EXISTS_TAC
   `IMAGE (\x:B. ring_carrier(subfield_generated l {x}))
          (UNIONS (IMAGE (\p. {x | x IN ring_carrier l /\
                                   poly_eval l (ring_of_int l o p) x =
                                   ring_0 l}) P))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC FINITE_IMAGE THEN REWRITE_TAC[FINITE_UNIONS] THEN
    ASM_SIMP_TAC[FINITE_IMAGE; FORALL_IN_IMAGE] THEN
    X_GEN_TAC `p:(1->num)->int` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `p:(1->num)->int`) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`l:B ring`; `ring_of_int (l:B ring) o (p:(1->num)->int)`]
      POLY_ROOT_BOUND) THEN
    ASM_REWRITE_TAC[] THEN ANTS_TAC THENL [ALL_TAC; SIMP_TAC[]] THEN
    SUBGOAL_THEN `~trivial_ring(l:B ring)` ASSUME_TAC THENL
     [ASM_MESON_TAC[INTEGRAL_DOMAIN_IMP_NONTRIVIAL_RING]; ALL_TAC] THEN
    MP_TAC(ISPECL [`integer_ring`; `l:B ring`; `ring_of_int l:int->B`;
                   `p:(1->num)->int`] MONIC_HOMOMORPHIC_IMAGE) THEN
    MP_TAC(ISPECL [`integer_ring`; `l:B ring`; `ring_of_int l:int->B`;
                   `(:1)`; `p:(1->num)->int`]
      IN_RING_POLYNOMIAL_CARRIER_COMPOSE) THEN
    ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
    DISCH_TAC THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[POLY_RING_CLAUSES] THEN MATCH_MP_TAC MONIC_IMP_NONZERO THEN
    ASM_REWRITE_TAC[RING_POLYNOMIAL];
    ALL_TAC] THEN
  REWRITE_TAC[SUBSET; IN_ELIM_THM; IN_IMAGE; IN_UNIONS; EXISTS_IN_IMAGE] THEN
  X_GEN_TAC `s:B->bool` THEN STRIP_TAC THEN
  REMOVE_THEN "P" (MP_TAC o SPEC `subfield_generated l (s:B->bool)`) THEN
  ASM_REWRITE_TAC[PRIME_SUBFIELD_SUBFIELD_GENERATED] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:(1->num)->int` (X_CHOOSE_THEN `x:B`
    STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN `ring_carrier(subfield_generated l s) = (s:B->bool)`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD]; ALL_TAC] THEN
  SUBGOAL_THEN `(x:B) IN s` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN `(x:B) IN ring_carrier l` ASSUME_TAC THENL
   [ASM_MESON_TAC[SUBFIELD_OF_IMP_SUBSET; SUBSET]; ALL_TAC] THEN
  EXISTS_TAC `x:B` THEN CONJ_TAC THENL
   [ALL_TAC;
    EXISTS_TAC `p:(1->num)->int` THEN ASM_REWRITE_TAC[IN_ELIM_THM] THEN
    SUBGOAL_THEN
     `(p:(1->num)->int) IN ring_carrier(poly_ring integer_ring (:1))`
    ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
    REWRITE_TAC[poly_eval; poly_evaluate] THEN
    MP_TAC(ISPECL [`integer_ring`; `l:B ring`; `l:B ring`;
                   `ring_of_int l:int->B`; `I:B->B`; `\v:1. (x:B)`;
                   `p:(1->num)->int`] POLY_EXTEND_COMPOSE_COEFFS) THEN
    REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; RING_HOMOMORPHISM_I;
                I_O_ID] THEN
    DISCH_THEN SUBST1_TAC THEN
    MP_TAC(ISPECL [`integer_ring`; `l:B ring`; `s:B->bool`;
                   `ring_of_int l:int->B`; `(:1)`; `\v:1. (x:B)`;
                   `p:(1->num)->int`] POLY_EXTEND_INTO_SUBRING_GENERATED) THEN
    SUBGOAL_THEN `subring_generated l s = subfield_generated l (s:B->bool)`
    SUBST1_TAC THENL
     [ASM_MESON_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED]; ALL_TAC] THEN
    MP_TAC(ISPEC `subfield_generated l (s:B->bool)`
      RING_HOMOMORPHISM_INTEGER_RING_OF_INT) THEN
    REWRITE_TAC[RING_OF_INT_SUBFIELD_GENERATED] THEN DISCH_TAC THEN
    ASM_REWRITE_TAC[IN_UNIV] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    FIRST_X_ASSUM(MP_TAC o check (fun th ->
      free_in `poly_extend:(int ring#B ring)->(int->B)->(1->B)->
                           ((1->num)->int)->B` (concl th))) THEN
    REWRITE_TAC[RING_OF_INT_SUBFIELD_GENERATED;
                CONJUNCT2 SUBFIELD_GENERATED]] THEN
  SUBGOAL_THEN
   `ring_carrier(subfield_generated l {x:B}) SUBSET s`
  ASSUME_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN ASM SET_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `s = ring_carrier(subfield_generated (subfield_generated l s) {x:B})`
  SUBST1_TAC THENL [ASM_REWRITE_TAC[]; ALL_TAC] THEN
  MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
  REWRITE_TAC[SING_SUBSET] THEN CONJ_TAC THENL
   [MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN ASM_REWRITE_TAC[IN_SING];
    MATCH_MP_TAC SUBFIELD_OF_SUBFIELD_GENERATED THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[SUBFIELD_SUBFIELD_GENERATED_ALT] THEN
    EXISTS_TAC `s:B->bool` THEN ASM SET_TAC[]]);;

(* Hermite up to isomorphism: finitely many subfields of C represent all     *)
(* number fields k of degree n with |d_K| <= X (of any type). The image of k *)
(* under an embedding g is isomorphic to k                                   *)
(* (RING_ISOMORPHISM_ONTO_SUBFIELD_IMAGE) and is generated by g x, a complex *)
(* root of one of the polynomials of NUMBER_FIELD_HERMITE_POLYNOMIALS.       *)
let NUMBER_FIELD_HERMITE_ISOMORPHIC = prove
 (`!n X. ?F. FINITE F /\ (!s. s IN F ==> s subfield_of complex_ring) /\
             !k:A ring.
                number_field k /\
                extension_degree (subfield_generated k {ring_0 k},k) I = n /\
                abs(real_of_int(number_field_discriminant k)) <= X
                ==> ?s. s IN F /\
                        k isomorphic_ring subfield_generated complex_ring s`,
  REPEAT GEN_TAC THEN
  MP_TAC(ISPECL [`n:num`; `X:real`] NUMBER_FIELD_HERMITE_POLYNOMIALS) THEN
  DISCH_THEN(X_CHOOSE_THEN `P:((1->num)->int)->bool` (CONJUNCTS_THEN2
    ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC (LABEL_TAC "P")))) THEN
  EXISTS_TAC
   `IMAGE (\z. ring_carrier(subfield_generated complex_ring {z}))
          (UNIONS (IMAGE (\p. {z | z IN ring_carrier complex_ring /\
                                   poly_eval complex_ring
                                     (ring_of_int complex_ring o p) z =
                                   ring_0 complex_ring}) P))` THEN
  REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC FINITE_IMAGE THEN REWRITE_TAC[FINITE_UNIONS] THEN
    ASM_SIMP_TAC[FINITE_IMAGE; FORALL_IN_IMAGE] THEN
    X_GEN_TAC `p:(1->num)->int` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `p:(1->num)->int`) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    MP_TAC(ISPECL [`complex_ring`;
                   `ring_of_int complex_ring o (p:(1->num)->int)`]
      POLY_ROOT_BOUND) THEN
    SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN; FIELD_COMPLEX_RING] THEN
    ANTS_TAC THENL [ALL_TAC; SIMP_TAC[]] THEN
    MP_TAC(ISPECL [`integer_ring`; `complex_ring`;
                   `ring_of_int complex_ring:int->complex`;
                   `p:(1->num)->int`] MONIC_HOMOMORPHIC_IMAGE) THEN
    MP_TAC(ISPECL [`integer_ring`; `complex_ring`;
                   `ring_of_int complex_ring:int->complex`;
                   `(:1)`; `p:(1->num)->int`]
      IN_RING_POLYNOMIAL_CARRIER_COMPOSE) THEN
    ASM_SIMP_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; FIELD_COMPLEX_RING;
                 FIELD_IMP_NONTRIVIAL_RING] THEN
    DISCH_TAC THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[POLY_RING_CLAUSES] THEN MATCH_MP_TAC MONIC_IMP_NONZERO THEN
    ASM_SIMP_TAC[RING_POLYNOMIAL; FIELD_COMPLEX_RING;
                 FIELD_IMP_NONTRIVIAL_RING];
    REWRITE_TAC[FORALL_IN_IMAGE] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC SUBFIELD_SUBFIELD_GENERATED THEN
    REWRITE_TAC[FIELD_COMPLEX_RING];
    ALL_TAC] THEN
  X_GEN_TAC `k:A ring` THEN STRIP_TAC THEN
  REMOVE_THEN "P" (MP_TAC o SPEC `k:A ring`) THEN ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:(1->num)->int` (X_CHOOSE_THEN `x:A`
    STRIP_ASSUME_TAC)) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP NUMBER_FIELD_IMP_FIELD) THEN
  FIRST_ASSUM(X_CHOOSE_TAC `g:A->complex` o
    REWRITE_RULE[GSYM MEMBER_NOT_EMPTY] o
    MATCH_MP COMPLEX_EMBEDDINGS_NONEMPTY) THEN
  SUBGOAL_THEN `ring_homomorphism(k,complex_ring) (g:A->complex)`
  ASSUME_TAC THENL
   [UNDISCH_TAC `(g:A->complex) IN complex_embeddings k` THEN
    SIMP_TAC[complex_embeddings; IN_ELIM_THM];
    ALL_TAC] THEN
  SUBGOAL_THEN `(x:A) IN ring_carrier k` ASSUME_TAC THENL
   [ASM_MESON_TAC[RING_OF_INTEGERS_SUBSET; SUBSET]; ALL_TAC] THEN
  SUBGOAL_THEN
   `(p:(1->num)->int) IN ring_carrier(poly_ring integer_ring (:1))`
  ASSUME_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`g:A->complex`; `k:A ring`; `complex_ring`]
    RING_ISOMORPHISM_ONTO_SUBFIELD_IMAGE) THEN
  ASM_REWRITE_TAC[FIELD_COMPLEX_RING] THEN STRIP_TAC THEN
  EXISTS_TAC `IMAGE (g:A->complex) (ring_carrier k)` THEN CONJ_TAC THENL
   [ALL_TAC; ASM_MESON_TAC[isomorphic_ring]] THEN
  REWRITE_TAC[IN_IMAGE; IN_UNIONS; EXISTS_IN_IMAGE] THEN
  EXISTS_TAC `(g:A->complex) x` THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`k:A ring`; `complex_ring`; `g:A->complex`; `{x:A}`]
      SUBFIELD_GENERATED_BY_MONOMORPHIC_IMAGE) THEN
    ASM_REWRITE_TAC[IMAGE_CLAUSES; SING_SUBSET] THEN
    ASM_SIMP_TAC[COMPLEX_EMBEDDINGS_MONOMORPHISM];
    ALL_TAC] THEN
  EXISTS_TAC `p:(1->num)->int` THEN
  ASM_REWRITE_TAC[IN_ELIM_THM; COMPLEX_RING_CLAUSES; IN_UNIV] THEN
  REWRITE_TAC[poly_eval; poly_evaluate] THEN
  MP_TAC(ISPECL [`integer_ring`; `complex_ring`; `complex_ring`;
                 `ring_of_int complex_ring:int->complex`; `I:complex->complex`;
                 `\v:1. (g:A->complex) x`; `p:(1->num)->int`]
    POLY_EXTEND_COMPOSE_COEFFS) THEN
  REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; RING_HOMOMORPHISM_I;
              I_O_ID] THEN
  DISCH_THEN SUBST1_TAC THEN
  MP_TAC(ISPECL [`integer_ring`; `k:A ring`; `complex_ring`;
                 `ring_of_int k:int->A`; `(:1)`; `\v:1. (x:A)`;
                 `g:A->complex`; `p:(1->num)->int`]
    POLY_EXTEND_HOMOMORPHIC_IMAGE) THEN
  ASM_REWRITE_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT] THEN
  ANTS_TAC THENL
