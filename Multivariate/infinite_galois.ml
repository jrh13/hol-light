(* Restriction to normal subextensions, the inverse limit and compactness    *)
(* (Neukirch, Algebraic Number Theory, IV.2, Example 1). Restriction to an   *)
(* intermediate field s normal over k is the map \f x. if x IN s then f x    *)
(* else x of Library/galois.ml (GALOIS_GROUP_RESTRICTION_NORMAL), continuous *)
(* since its evaluations at points of s are evaluations of f; for l normal   *)
(* over k it is an epimorphism from the profinite Gal(l/k) onto the          *)
(* Hausdorff Gal(s/k), hence open and a quotient map. For e in               *)
(* finite_galois_subfields(k,l) h the group Gal(e/k) is finite, hence        *)
(* discrete, and the kernel Gal(l/e) is open. For s finite over k inside     *)
(* such an e, Gal(l/s) is the preimage of Gal(e/s), so its index is that of  *)
(* Gal(e/s) in Gal(e/k) (CARD_EQ_GROUP_COSETS_PREIMAGE), which is [s:k] by   *)
(* the finite theory (GALOIS_CORRESPONDENCE_INDEX). Compactness: if each e   *)
(* has a nonempty set S e of elements of Gal(e/k) and restriction maps S e1  *)
(* into S e for e SUBSET e1, the preimages of the S e are closed and have    *)
(* the finite intersection property, since finitely many e lie in a common   *)
(* one (FINITE_GALOIS_SUBFIELDS_UPPER_BOUNDS) and restriction to it is onto. *)
(* The inverse limit: a compatible family of elements of the Gal(e/k) glues  *)
(* to a permutation of l that is locally in the Galois group                 *)
(* (GALOIS_GROUP_LOCAL), and a continuous bijection from the compact         *)
(* Gal(l/k) onto a Hausdorff space is a homeomorphism.                       *)
(* ------------------------------------------------------------------------- *)

