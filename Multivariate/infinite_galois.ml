(* ------------------------------------------------------------------------- *)
(* Algebraic extensions of finite fields (Neukirch, Algebraic Number Theory, *)
(* IV.2). For l algebraic over a finite field k with q elements the          *)
(* Frobenius map x |-> x^q is in the Galois group: it is a ring endomorphism *)
(* fixing k (RING_ENDOMORPHISM_POW_CARD), injective since l is a field, and  *)
(* onto since it maps each finite subfield k(y) injectively into itself. Its *)
(* fixed points are the at most q roots of X^q - X                           *)
(* (RING_POW_FIXPOINTS_BOUND), that is the image of k, so the subgroup it    *)
(* generates has fixed field k and is dense: the Galois group is procyclic,  *)
(* topologically generated by the Frobenius map.                             *)
(* ------------------------------------------------------------------------- *)

let GALOIS_GROUP_FROBENIUS_DENSE = prove
 (`!(h:A->B) k l.
        algebraic_extension(k,l) h /\ FINITE(ring_carrier k)
        ==> (\x. if x IN ring_carrier l
                 then ring_pow l x (CARD(ring_carrier k)) else x)
            IN group_carrier(galois_group(k,l) h) /\
            (pointwise_topology(group_carrier(galois_group(k,l) h)))
            closure_of
            group_carrier
             (subgroup_generated (galois_group(k,l) h)
               {\x. if x IN ring_carrier l
                    then ring_pow l x (CARD(ring_carrier k)) else x}) =
            group_carrier(galois_group(k,l) h)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP ALGEBRAIC_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
  MP_TAC(ISPECL [`k:A ring`; `l:B ring`; `h:A->B`; `1`]
    RING_ENDOMORPHISM_POW_CARD) THEN
  ASM_REWRITE_TAC[EXP_1; ring_endomorphism] THEN STRIP_TAC THEN
  SUBGOAL_THEN `2 <= CARD(ring_carrier(k:A ring))` ASSUME_TAC THENL
   [ASM_SIMP_TAC[FINITE_FIELD_CARD_GE_2]; ALL_TAC] THEN
  ABBREV_TAC `q = CARD(ring_carrier(k:A ring))` THEN
  ABBREV_TAC
   `f = \x:B. if x IN ring_carrier l then ring_pow l x q else x` THEN
  SUBGOAL_THEN
   `(!x:B. x IN ring_carrier l ==> f x = ring_pow l x q) /\
    (!x:B. ~(x IN ring_carrier l) ==> f x = x)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "f" THEN SIMP_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `ring_monomorphism(l:B ring,l) f` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `f:B->B`]
      FIELD_HOMOMORPHISM_IMP_MONOMORPHISM) THEN
    ANTS_TAC THENL
     [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC RING_HOMOMORPHISM_EQ THEN
      EXISTS_TAC `\x:B. ring_pow l x q` THEN ASM_SIMP_TAC[];
      ALL_TAC] THEN
    MATCH_MP_TAC(TAUT `~p ==> p \/ q ==> q`) THEN
    DISCH_THEN(MP_TAC o SPEC `ring_1 l:B`) THEN
    ASM_SIMP_TAC[RING_1; RING_POW_ONE] THEN
    ASM_MESON_TAC[FIELD_NONTRIVIAL];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!y:B. y IN ring_carrier l ==> ?x. x IN ring_carrier l /\ f x = y`
  ASSUME_TAC THENL
   [X_GEN_TAC `y:B` THEN DISCH_TAC THEN
    SUBGOAL_THEN `algebraic_over(k,l) (h:A->B) y` ASSUME_TAC THENL
     [ASM_MESON_TAC[algebraic_extension]; ALL_TAC] THEN
    MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `y:B`]
      SUBFIELD_GENERATED_SIMPLE_ALGEBRAIC) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    ABBREV_TAC
     `s = ring_carrier
           (subfield_generated l
             (y INSERT IMAGE (h:A->B) (ring_carrier k)))` THEN
    SUBGOAL_THEN `FINITE(s:B->bool) /\ s SUBSET ring_carrier l`
    STRIP_ASSUME_TAC THENL
     [EXPAND_TAC "s" THEN
      REWRITE_TAC[RING_CARRIER_SUBFIELD_GENERATED_SUBSET] THEN
      MP_TAC(ISPECL [`h:A->B`; `k:A ring`;
                     `subfield_generated l (y INSERT IMAGE (h:A->B)
                                             (ring_carrier k))`]
        FINITE_FINITE_FIELD_EXTENSION) THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    SUBGOAL_THEN `IMAGE (f:B->B) s SUBSET s` ASSUME_TAC THENL
     [REWRITE_TAC[SUBSET; FORALL_IN_IMAGE] THEN X_GEN_TAC `x:B` THEN
      DISCH_TAC THEN
      SUBGOAL_THEN `(x:B) IN ring_carrier l` ASSUME_TAC THENL
       [ASM SET_TAC[]; ASM_SIMP_TAC[]] THEN
      MP_TAC(ISPECL
       [`subfield_generated l (y INSERT IMAGE (h:A->B) (ring_carrier k))`;
        `x:B`; `q:num`] RING_POW) THEN
      REWRITE_TAC[RING_POW_SUBFIELD_GENERATED] THEN ASM_REWRITE_TAC[];
      ALL_TAC] THEN
    MP_TAC(ISPECL [`s:B->bool`; `f:B->B`] SURJECTIVE_IFF_INJECTIVE) THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(TAUT `q /\ (p ==> r) ==> (p <=> q) ==> r`) THEN
    CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN
      MP_TAC(ISPECL [`l:B ring`; `l:B ring`; `f:B->B`; `x:B`; `y':B`]
        RING_MONOMORPHISM_INJECTIVE_EQ) THEN
      ASM_REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN ASM SET_TAC[];
      DISCH_THEN(MP_TAC o SPEC `y:B`) THEN
      ANTS_TAC THENL [ASM SET_TAC[]; ALL_TAC] THEN
      MATCH_MP_TAC MONO_EXISTS THEN ASM SET_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `(f:B->B) IN group_carrier(galois_group(k,l) (h:A->B))`
  ASSUME_TAC THENL
   [REWRITE_TAC[IN_GALOIS_GROUP] THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP RING_MONOMORPHISM_IMP_HOMOMORPHISM) THEN
    SUBGOAL_THEN `!x:B. x IN ring_carrier l ==> f x IN ring_carrier l`
    ASSUME_TAC THENL
     [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ALL_TAC] THEN
    REPEAT CONJ_TAC THENL
     [REWRITE_TAC[PERMUTES_ALT] THEN ASM_REWRITE_TAC[] THEN
      X_GEN_TAC `y:B` THEN DISCH_TAC THEN REWRITE_TAC[EXISTS_UNIQUE_THM] THEN
      CONJ_TAC THENL [ASM_MESON_TAC[]; ALL_TAC] THEN
      ASM_MESON_TAC[RING_MONOMORPHISM_INJECTIVE_EQ];
      REWRITE_TAC[ring_automorphism; RING_ISOMORPHISM] THEN
      ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
       [ASM SET_TAC[]; ASM_MESON_TAC[RING_MONOMORPHISM_INJECTIVE_EQ]];
      X_GEN_TAC `a:A` THEN DISCH_TAC THEN
      SUBGOAL_THEN `(h:A->B) a IN ring_carrier l` ASSUME_TAC THENL
       [ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER]; ASM_SIMP_TAC[]]];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `fixed_field l
     (group_carrier(subgroup_generated (galois_group(k,l) h) {f})) =
    IMAGE (h:A->B) (ring_carrier k)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `{f:B->B}`]
      FIXED_FIELD_SUBGROUP_GENERATED) THEN
    ASM_REWRITE_TAC[SING_SUBSET] THEN DISCH_THEN SUBST1_TAC THEN
    SUBGOAL_THEN
     `fixed_field l {f:B->B} =
      {x | x IN ring_carrier l /\ ring_pow l x q = x}`
    SUBST1_TAC THENL
     [REWRITE_TAC[EXTENSION; IN_FIXED_FIELD; IN_SING; FORALL_UNWIND_THM2;
                  IN_ELIM_THM] THEN
      X_GEN_TAC `x:B` THEN
      ASM_CASES_TAC `(x:B) IN ring_carrier l` THEN ASM_SIMP_TAC[];
      ALL_TAC] THEN
    CONV_TAC SYM_CONV THEN MATCH_MP_TAC CARD_SUBSET_EQ THEN
    MP_TAC(ISPECL [`l:B ring`; `q:num`] RING_POW_FIXPOINTS_BOUND) THEN
    ASM_SIMP_TAC[FIELD_IMP_INTEGRAL_DOMAIN] THEN STRIP_TAC THEN
    SUBGOAL_THEN `CARD(IMAGE (h:A->B) (ring_carrier k)) = q` ASSUME_TAC THENL
     [EXPAND_TAC "q" THEN MATCH_MP_TAC CARD_IMAGE_INJ THEN
      ASM_REWRITE_TAC[] THEN
      ASM_MESON_TAC[RING_MONOMORPHISM_INJECTIVE_EQ];
      ALL_TAC] THEN
    SUBGOAL_THEN
     `IMAGE (h:A->B) (ring_carrier k) SUBSET
      {x | x IN ring_carrier l /\ ring_pow l x q = x}`
    ASSUME_TAC THENL
     [REWRITE_TAC[SUBSET; FORALL_IN_IMAGE; IN_ELIM_THM] THEN
      ASM_MESON_TAC[RING_HOMOMORPHISM_IN_CARRIER];
      ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[GSYM LE_ANTISYM] THEN ASM_REWRITE_TAC[] THEN
    TRANS_TAC LE_TRANS `CARD(IMAGE (h:A->B) (ring_carrier k))` THEN
    CONJ_TAC THENL
     [ASM_REWRITE_TAC[LE_REFL];
      MATCH_MP_TAC CARD_SUBSET THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
