(* ========================================================================= *)
(* Infinite Galois theory: the Krull topology and the Galois correspondence  *)
(* for infinite extensions.                                                  *)
(*                                                                           *)
(* The Galois group galois_group(k,l) h of Library/galois.ml is a subgroup   *)
(* of symmetric_group(ring_carrier l), and its Krull topology is the         *)
(* topology of pointwise convergence                                         *)
(* pointwise_topology(group_carrier(galois_group(k,l) h)) of                 *)
(* Multivariate/metric.ml (no separate constant): the subgroups of the       *)
(* elements fixing a finite subset of l pointwise form a base of open        *)
(* neighbourhoods of 1, and an element is near another if they agree on a    *)
(* large finite set.                                                         *)
(*                                                                           *)
(*   Gal(l/k) is a topological group, profinite when l is algebraic over k   *)
(*      and discrete when l is finite over k                                 *)
(*      (TOPOLOGICAL_GROUP_GALOIS_GROUP, PROFINITE_GROUP_GALOIS_GROUP,       *)
(*      POINTWISE_TOPOLOGY_GALOIS_GROUP_FINITE)                              *)
(*   a subgroup is open iff it contains the elements fixing some finite set  *)
(*      (OPEN_IN_GALOIS_GROUP_SUBGROUP); for a Galois extension the          *)
(*      Gal(l/e), e finite and Galois over k, form a base at 1               *)
(*      (GALOIS_GROUP_NEIGHBOURHOOD_BASE)                                    *)
(*   Artin for infinite groups: if a group G of automorphisms of l has       *)
(*      finite orbits, l is Galois over the fixed field of G, with Galois    *)
(*      group the closure of G (ARTIN_FIXED_FIELD_FINITE_ORBITS; the Galois  *)
(*      part is GALOIS_EXTENSION_FIXED_FIELD_FINITE_ORBITS of                *)
(*      Library/galois.ml)                                                   *)
(*   for l algebraic over k the closure of a subgroup H is Gal(l/l^H), so H  *)
(*      is closed iff H = Gal(l/l^H) (CLOSURE_OF_GALOIS_GROUP_SUBGROUP,      *)
(*      CLOSED_IN_GALOIS_GROUP_SUBGROUP)                                     *)
(*                                                                           *)
(* For a Galois extension l of k (Neukirch, Algebraic Number Theory, IV.1,   *)
(* (1.1) and (1.2); Milne, Fields and Galois Theory, 7):                     *)
(*                                                                           *)
(*   s |-> Gal(l/s) and H |-> l^H are inverse bijections between the         *)
(*      intermediate fields and the closed subgroups                         *)
(*      (INFINITE_GALOIS_CORRESPONDENCE); Gal(l/s) is closed for every       *)
(*      intermediate field s (CLOSED_IN_GALOIS_GROUP_INTERMEDIATE)           *)
(*   Gal(l/s) is open iff s is finite over k                                 *)
(*      (OPEN_IN_GALOIS_GROUP_INTERMEDIATE), and then its index is [s:k]     *)
(*      (INFINITE_GALOIS_CORRESPONDENCE_INDEX)                               *)
(*   a closed subgroup H is normal iff l^H is Galois over k                  *)
(*      (INFINITE_GALOIS_CORRESPONDENCE_NORMAL)                              *)
(*   Gal(l/(s INTER t)) is the closure of the subgroup generated by Gal(l/s) *)
(*      and Gal(l/t), and the fixed field of G INTER H, for G and H closed,  *)
(*      is the compositum of the fixed fields (GALOIS_GROUP_INTER_CLOSURE,   *)
(*      FIXED_FIELD_INTER_CLOSED)                                            *)
(*                                                                           *)
(* Restriction to an intermediate field s normal over k is continuous        *)
(* (CONTINUOUS_MAP_GALOIS_GROUP_RESTRICTION) and, for l normal over k, an    *)
(* open map and a quotient map onto Gal(s/k)                                 *)
(* (GALOIS_GROUP_RESTRICTION_QUOTIENT_MAP), so that Gal(s/k) =               *)
(* Gal(l/k)/Gal(l/s) of Library/galois.ml (GALOIS_GROUP_QUOTIENT) holds as   *)
(* topological groups. Restriction to a finite Galois subextension e is a    *)
(* continuous epimorphism onto the discrete Gal(e/k) with open normal kernel *)
(* Gal(l/e) (CONTINUOUS_MAP_GALOIS_GROUP_RESTRICTION_FINITE,                 *)
(* GALOIS_GROUP_RESTRICTION_FINITE_GALOIS); the restrictions identify        *)
(* Gal(l/k), as a group and as a space, with the inverse limit of the        *)
(* Gal(e/k) over finite_galois_subfields(k,l) h                              *)
(* (GALOIS_GROUP_INVERSE_LIMIT); and, by compactness, a compatible family of *)
(* nonempty sets of elements of the Gal(e/k) has a common lift               *)
(* (GALOIS_GROUP_COMPATIBLE_RESTRICTIONS). For l algebraic over a finite     *)
(* field k the subgroup generated by the Frobenius map x |-> x^|k| is dense  *)
(* (GALOIS_GROUP_FROBENIUS_DENSE).                                           *)
(*                                                                           *)
(* Routes. The Galois group is closed in the product and has finite orbits,  *)
(* the orbit of x being a set of roots of its minimal polynomial             *)
(* (GALOIS_GROUP_ORBIT_FINITE, GALOIS_GROUP_LOCAL), so                       *)
(* PROFINITE_GROUP_POINTWISE_TOPOLOGY_LOCAL of                               *)
(* Multivariate/profinite_groups.ml applies. Closures: an f fixing l^H,      *)
(* restricted to a finite Galois e containing a given finite set, fixes the  *)
(* fixed field of the restriction of H, so it is the restriction of an       *)
(* element of H by the finite theorem of Artin (GALOIS_GROUP_FIXED_FIELD);   *)
(* for l only algebraic over k the extension l of l^H is Galois by           *)
(* GALOIS_EXTENSION_FIXED_FIELD_FINITE_ORBITS of Library/galois.ml, which    *)
(* reduces the general case to the Galois one. Openness of restriction:      *)
(* PROFINITE_GROUP_CONTINUOUS_EPIMORPHISM.                                   *)
(* ========================================================================= *)

needs "Library/galois.ml";;
needs "Multivariate/profinite_groups.ml";;

(* ------------------------------------------------------------------------- *)
(* The Krull topology. The Galois group generates itself in                  *)
(* symmetric_group(ring_carrier l) (SUBGROUP_GENERATED_GALOIS_GROUP), so the *)
(* results on groups of permutations of Multivariate/profinite_groups.ml     *)
(* apply: it is a topological group, profinite for an algebraic extension    *)
(* since every orbit {f x | f IN Gal} is finite and a permutation of l that  *)
(* agrees on each finite set with an element of the Galois group is in it.   *)
(* The Galois group over an intermediate field is a pointwise stabilizer,    *)
(* hence closed; a finite extension has a finite, hence discrete, Galois     *)
(* group; and for a Galois extension every finite set lies in a finite       *)
(* Galois subextension e (FINITE_GALOIS_SUBFIELDS_FINITE), so the Gal(l/e)   *)
(* form a base at 1.                                                         *)
(* ------------------------------------------------------------------------- *)

let TOPOLOGICAL_GROUP_GALOIS_GROUP = prove
 (`!(h:A->B) k l.
        topological_group (galois_group(k,l) h)
         (pointwise_topology(group_carrier(galois_group(k,l) h)))`,
  REPEAT GEN_TAC THEN
  MP_TAC(ISPECL [`ring_carrier(l:B ring)`;
                 `group_carrier(galois_group(k,l) (h:A->B))`]
                TOPOLOGICAL_GROUP_POINTWISE_TOPOLOGY) THEN
  REWRITE_TAC[GALOIS_GROUP_SUBGROUP; SUBGROUP_GENERATED_GALOIS_GROUP]);;

let PROFINITE_GROUP_GALOIS_GROUP = prove
 (`!(h:A->B) k l.
        algebraic_extension(k,l) h
        ==> profinite_group (galois_group(k,l) h)
             (pointwise_topology(group_carrier(galois_group(k,l) h)))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_carrier(l:B ring)`;
                 `group_carrier(galois_group(k,l) (h:A->B))`]
                PROFINITE_GROUP_POINTWISE_TOPOLOGY_LOCAL) THEN
  REWRITE_TAC[GALOIS_GROUP_SUBGROUP; SUBGROUP_GENERATED_GALOIS_GROUP] THEN
  DISCH_THEN MATCH_MP_TAC THEN CONJ_TAC THENL
   [ASM_SIMP_TAC[GALOIS_GROUP_ORBIT_FINITE];
    REPEAT STRIP_TAC THEN MATCH_MP_TAC GALOIS_GROUP_LOCAL THEN
    ASM_REWRITE_TAC[]]);;

let OPEN_IN_GALOIS_GROUP_SUBGROUP = prove
 (`!(h:A->B) k l H.
        H subgroup_of galois_group(k,l) h
        ==> (open_in (pointwise_topology(group_carrier(galois_group(k,l) h)))
                     H <=>
             ?s. FINITE s /\ s SUBSET ring_carrier l /\
                 {f | f IN group_carrier(galois_group(k,l) h) /\
                      !x. x IN s ==> f x = x} SUBSET H)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC OPEN_IN_POINTWISE_TOPOLOGY_SUBGROUP THEN
  ASM_REWRITE_TAC[GALOIS_GROUP_SUBGROUP; SUBGROUP_GENERATED_GALOIS_GROUP]);;

let CLOSED_IN_GALOIS_GROUP_INTERMEDIATE = prove
 (`!(h:A->B) k l s.
        s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
        ==> closed_in (pointwise_topology(group_carrier(galois_group(k,l) h)))
             (group_carrier(galois_group(subfield_generated l s,l) I))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `group_carrier(galois_group(subfield_generated l s,l) I) =
    {f | f IN group_carrier(galois_group(k,l) (h:A->B)) /\
         !x. x IN s ==> f x = x}`
  SUBST1_TAC THENL
   [GEN_REWRITE_TAC I [EXTENSION] THEN REWRITE_TAC[IN_ELIM_THM] THEN
    ASM_MESON_TAC[IN_GALOIS_GROUP_INTERMEDIATE];
    REWRITE_TAC[CLOSED_IN_POINTWISE_STABILIZER]]);;

let POINTWISE_TOPOLOGY_GALOIS_GROUP_FINITE = prove
 (`!(h:A->B) k l.
        finite_extension(k,l) h
        ==> pointwise_topology(group_carrier(galois_group(k,l) h)) =
            discrete_topology(group_carrier(galois_group(k,l) h))`,
  SIMP_TAC[POINTWISE_TOPOLOGY_FINITE; FINITE_GALOIS_GROUP]);;

let GALOIS_GROUP_NEIGHBOURHOOD_BASE = prove
 (`!(h:A->B) k l w.
        galois_extension(k,l) h /\
        open_in (pointwise_topology(group_carrier(galois_group(k,l) h))) w /\
        I IN w
        ==> ?e. e IN finite_galois_subfields(k,l) h /\
                group_carrier(galois_group(subfield_generated l e,l) I)
                SUBSET w`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_carrier l:B->bool`;
                 `group_carrier(galois_group(k,l) (h:A->B))`;
                 `w:(B->B)->bool`]
                POINTWISE_TOPOLOGY_NEIGHBOURHOOD_STABILIZER) THEN
  ASM_REWRITE_TAC[GALOIS_GROUP_SUBGROUP] THEN
  DISCH_THEN(X_CHOOSE_THEN `s:B->bool` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `s:B->bool`]
    FINITE_GALOIS_SUBFIELDS_FINITE) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `e:B->bool` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  TRANS_TAC SUBSET_TRANS
   `{f | f IN group_carrier(galois_group(k,l) (h:A->B)) /\
         !x. x IN s ==> f x = x}` THEN
  ASM_REWRITE_TAC[] THEN
  FIRST_X_ASSUM(STRIP_ASSUME_TAC o
    GEN_REWRITE_RULE I [IN_FINITE_GALOIS_SUBFIELDS]) THEN
  ASM_SIMP_TAC[SUBSET; IN_ELIM_THM; IN_GALOIS_GROUP_INTERMEDIATE] THEN
  ASM SET_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* Closures of subgroups and the theorem of Artin for groups with finite     *)
(* orbits. For a Galois extension the closure of a subgroup H is Gal(l/l^H): *)
(* an f fixing l^H, restricted to a finite Galois e containing a given       *)
(* finite set, fixes the fixed field of the restriction of H, so it is the   *)
(* restriction of an element of H by the finite theorem of Artin             *)
(* (GALOIS_GROUP_FIXED_FIELD). If a group G of automorphisms of l has finite *)
(* orbits, l is Galois over l^G (GALOIS_EXTENSION_FIXED_FIELD_FINITE_ORBITS  *)
(* of Library/galois.ml: every element of l is separable over l^G with split *)
(* minimal polynomial) and G is dense in Gal(l/l^G); for l algebraic over k  *)
(* this applies to every subgroup of the Galois group, and the closure of H  *)
(* is again Gal(l/l^H).                                                      *)
(* ------------------------------------------------------------------------- *)

let CLOSURE_OF_GALOIS_GROUP_SUBGROUP_GALOIS = prove
 (`!(h:A->B) k l H.
        galois_extension(k,l) h /\ H subgroup_of galois_group(k,l) h
        ==> (pointwise_topology(group_carrier(galois_group(k,l) h)))
            closure_of H =
            group_carrier
             (galois_group(subfield_generated l (fixed_field l H),l) I)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP GALOIS_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP SUBGROUP_OF_IMP_SUBSET) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`]
                FIXED_FIELD_GALOIS_SUBSET) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  ASM_SIMP_TAC[CLOSURE_OF_POINTWISE_TOPOLOGY] THEN
  ASM_SIMP_TAC[EXTENSION; IN_ELIM_THM; IN_GALOIS_GROUP_INTERMEDIATE;
               IN_FIXED_FIELD] THEN
  X_GEN_TAC `f:B->B` THEN
  ASM_CASES_TAC `(f:B->B) IN group_carrier(galois_group(k,l) (h:A->B))` THEN
  ASM_REWRITE_TAC[] THEN EQ_TAC THENL
   [DISCH_TAC THEN X_GEN_TAC `x:B` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `{x:B}`) THEN
    REWRITE_TAC[FINITE_SING; IN_SING; FORALL_UNWIND_THM2] THEN
    ASM_MESON_TAC[];
    DISCH_TAC THEN X_GEN_TAC `t:B->bool` THEN DISCH_TAC] THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`;
                 `t INTER ring_carrier(l:B ring)`]
                FINITE_GALOIS_SUBFIELDS_FINITE) THEN
  ASM_SIMP_TAC[FINITE_INTER; INTER_SUBSET; IN_FINITE_GALOIS_SUBFIELDS] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:B->bool` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `e:B->bool`]
                GALOIS_GROUP_RESTRICTION_HOMOMORPHISM) THEN
  ASM_SIMP_TAC[GALOIS_IMP_NORMAL_EXTENSION] THEN
  DISCH_THEN(ASSUME_TAC o CONJUNCT1) THEN
  MP_TAC(ISPECL
   [`h:A->B`; `k:A ring`; `subfield_generated l (e:B->bool)`;
    `IMAGE (\(g:B->B) x. if x IN e then g x else x) H`]
   GALOIS_GROUP_FIXED_FIELD) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC SUBGROUP_OF_HOMOMORPHIC_IMAGE THEN
    EXISTS_TAC `galois_group(k,l) (h:A->B)` THEN ASM_REWRITE_TAC[];
    STRIP_TAC] THEN
  SUBGOAL_THEN
   `(\x. if x IN e then (f:B->B) x else x) IN
    IMAGE (\(g:B->B) x. if x IN e then g x else x) H`
  MP_TAC THENL
   [FIRST_X_ASSUM(fun th -> GEN_REWRITE_TAC RAND_CONV [SYM th]) THEN
    W(MP_TAC o PART_MATCH (lhand o rand) IN_GALOIS_GROUP_INTERMEDIATE o
      snd) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN CONJ_TAC THENL
     [UNDISCH_TAC
       `group_homomorphism
         (galois_group(k,l) (h:A->B),galois_group(k,subfield_generated l e) h)
         (\(g:B->B) x. if x IN e then g x else x)` THEN
      REWRITE_TAC[group_homomorphism; SUBSET; FORALL_IN_IMAGE] THEN
      DISCH_THEN(MP_TAC o SPEC `f:B->B` o CONJUNCT1) THEN
      ASM_REWRITE_TAC[];
      REWRITE_TAC[IN_FIXED_FIELD; FORALL_IN_IMAGE] THEN
      ASM_SIMP_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD] THEN
      X_GEN_TAC `y:B` THEN
      ASM_CASES_TAC `(y:B) IN e` THEN ASM_REWRITE_TAC[] THEN
      ASM_MESON_TAC[SUBFIELD_OF_IMP_SUBSET; SUBSET]];
    ALL_TAC] THEN
  REWRITE_TAC[IN_IMAGE] THEN
  DISCH_THEN(X_CHOOSE_THEN `g:B->B` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `g:B->B` THEN ASM_REWRITE_TAC[] THEN
  X_GEN_TAC `x:B` THEN DISCH_TAC THEN
  ASM_CASES_TAC `(x:B) IN ring_carrier l` THENL
   [FIRST_X_ASSUM(MP_TAC o C AP_THM `x:B`) THEN
    SUBGOAL_THEN `(x:B) IN e` (fun th -> REWRITE_TAC[th]) THENL
     [ASM SET_TAC[]; MESON_TAC[]];
    SUBGOAL_THEN
     `(f:B->B) permutes ring_carrier l /\ (g:B->B) permutes ring_carrier l`
    MP_TAC THENL
     [ASM_MESON_TAC[GALOIS_GROUP_PERMUTES; SUBSET];
      DISCH_THEN(CONJUNCTS_THEN
       (MP_TAC o SPEC `x:B` o CONJUNCT1 o GEN_REWRITE_RULE I [permutes])) THEN
      ASM_REWRITE_TAC[] THEN MESON_TAC[]]]);;

let ARTIN_FIXED_FIELD_FINITE_ORBITS = prove
 (`!(l:B ring) G.
        field l /\ G subgroup_of symmetric_group(ring_carrier l) /\
        (!f. f IN G ==> ring_automorphism l f) /\
        (!x. x IN ring_carrier l ==> FINITE {f x | f IN G})
        ==> galois_extension(subfield_generated l (fixed_field l G),l) I /\
            (pointwise_topology
              (group_carrier
                (galois_group(subfield_generated l (fixed_field l G),l) I)))
            closure_of G =
            group_carrier
             (galois_group(subfield_generated l (fixed_field l G),l) I)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`l:B ring`; `G:(B->B)->bool`]
    GALOIS_EXTENSION_FIXED_FIELD_FINITE_ORBITS) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `!f:B->B. f IN G ==> f permutes ring_carrier l` ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o CONJUNCT1 o GEN_REWRITE_RULE I [subgroup_of] o
      check (fun th -> is_binary "subgroup_of" (concl th))) THEN
    REWRITE_TAC[SYMMETRIC_GROUP; SUBSET; IN_ELIM_THM];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `G SUBSET
    group_carrier(galois_group(subfield_generated l (fixed_field l G),l)
                               (I:B->B))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC SUBSET_GALOIS_GROUP_FIXED_FIELD THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:B->B`;
                 `subfield_generated l (fixed_field l (G:(B->B)->bool))`;
                 `l:B ring`; `G:(B->B)->bool`]
    CLOSURE_OF_GALOIS_GROUP_SUBGROUP_GALOIS) THEN
  ASM_REWRITE_TAC[SUBGROUP_OF_GALOIS_GROUP]);;

let CLOSURE_OF_GALOIS_GROUP_SUBGROUP = prove
 (`!(h:A->B) k l H.
        algebraic_extension(k,l) h /\ H subgroup_of galois_group(k,l) h
        ==> (pointwise_topology(group_carrier(galois_group(k,l) h)))
            closure_of H =
            group_carrier
             (galois_group(subfield_generated l (fixed_field l H),l) I)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP ALGEBRAIC_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [field_extension]) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o
    GEN_REWRITE_RULE I [SUBGROUP_OF_GALOIS_GROUP]) THEN
  MP_TAC(ISPECL [`h:A->B`; `k:A ring`; `l:B ring`; `H:(B->B)->bool`]
                FIXED_FIELD_GALOIS_SUBSET) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`l:B ring`; `H:(B->B)->bool`]
                ARTIN_FIXED_FIELD_FINITE_ORBITS) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [ASM_MESON_TAC[SUBSET; GALOIS_GROUP_RING_AUTOMORPHISM];
      REPEAT STRIP_TAC THEN MATCH_MP_TAC FINITE_SUBSET THEN
      EXISTS_TAC `{f x | f IN group_carrier(galois_group(k,l) (h:A->B))}` THEN
      ASM_SIMP_TAC[GALOIS_GROUP_ORBIT_FINITE] THEN ASM SET_TAC[]];
    DISCH_THEN(SUBST1_TAC o SYM o CONJUNCT2)] THEN
  SUBGOAL_THEN
   `group_carrier
     (galois_group(subfield_generated l (fixed_field l H),l) (I:B->B))
    SUBSET group_carrier(galois_group(k,l) (h:A->B))`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_GALOIS_GROUP_INTERMEDIATE]; ALL_TAC] THEN
  SUBGOAL_THEN
   `(H:(B->B)->bool) SUBSET
    group_carrier
     (galois_group(subfield_generated l (fixed_field l H),l) (I:B->B))`
  ASSUME_TAC THENL
   [ASM_SIMP_TAC[SUBSET; IN_GALOIS_GROUP_INTERMEDIATE; IN_FIXED_FIELD] THEN
    ASM SET_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[CLOSURE_OF_POINTWISE_TOPOLOGY] THEN
  REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN X_GEN_TAC `f:B->B` THEN
  EQ_TAC THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THENL
   [ASM_SIMP_TAC[IN_GALOIS_GROUP_INTERMEDIATE; IN_FIXED_FIELD] THEN
    X_GEN_TAC `x:B` THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `{x:B}`) THEN
    REWRITE_TAC[FINITE_SING; IN_SING; FORALL_UNWIND_THM2] THEN
    ASM_MESON_TAC[];
    ASM SET_TAC[]]);;

let CLOSED_IN_GALOIS_GROUP_SUBGROUP = prove
 (`!(h:A->B) k l H.
        algebraic_extension(k,l) h /\ H subgroup_of galois_group(k,l) h
        ==> (closed_in (pointwise_topology(group_carrier(galois_group(k,l) h)))
                       H <=>
             group_carrier
              (galois_group(subfield_generated l (fixed_field l H),l) I) =
             H)`,
  MESON_TAC[CLOSURE_OF_GALOIS_GROUP_SUBGROUP; CLOSURE_OF_EQ]);;

(* ------------------------------------------------------------------------- *)
(* The Galois correspondence for infinite Galois extensions (Neukirch,       *)
(* Algebraic Number Theory, IV.1, (1.2)). The closed subgroups correspond to *)
(* the intermediate fields (with FIXED_FIELD_GALOIS_GROUP_INTERMEDIATE of    *)
(* Library/galois.ml). Gal(l/s) is open iff s is finite over k: an open      *)
(* Gal(l/s) contains the stabilizer of a finite set t, which lies in a       *)
(* finite Galois e, and then s is inside the fixed field e of Gal(l/e);      *)
(* conversely s is generated over k by finitely many elements                *)
(* (FINITE_EXTENSION_SUBFIELD_GENERATORS). A closed subgroup is normal iff   *)
(* its fixed field is Galois over k (GALOIS_CORRESPONDENCE_NORMAL and        *)
(* GALOIS_EXTENSION_NORMAL_SUBGROUP of Library/galois.ml hold for infinite   *)
(* extensions). The lattice operations correspond up to closure: the         *)
(* subgroup generated by Gal(l/s) and Gal(l/t) has fixed field s INTER t     *)
(* (FIXED_FIELD_SUBGROUP_GENERATED), and Gal(l/s) INTER Gal(l/t) is the      *)
(* Galois group of the compositum (GALOIS_GROUP_COMPOSITUM).                 *)
(* ------------------------------------------------------------------------- *)

let INFINITE_GALOIS_CORRESPONDENCE = prove
 (`!(h:A->B) k l.
     galois_extension(k,l) h
     ==> (!H. H subgroup_of galois_group(k,l) h /\
              closed_in (pointwise_topology(group_carrier(galois_group(k,l) h)))
                        H
              ==> fixed_field l H subfield_of l /\
                  IMAGE h (ring_carrier k) SUBSET fixed_field l H /\
                  group_carrier(galois_group
                    (subfield_generated l (fixed_field l H),l) I) = H) /\
         (!s. s subfield_of l /\ IMAGE h (ring_carrier k) SUBSET s
              ==> group_carrier(galois_group(subfield_generated l s,l) I)
                  subgroup_of galois_group(k,l) h /\
                  closed_in
