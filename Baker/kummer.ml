(* ------------------------------------------------------------------------- *)
(* Roots of unity: the powers 1, w, ..., w^(p-1) of a p-th root of unity w   *)
(* <> 1 sum to 0. For a prime p a p-th root of unity other than 1 has order  *)
(* p (RING_ORDER_UNIQUE_PRIME), so the library facts on the roots of unity   *)
(* of a given order apply (ROOTS_OF_UNITY_RING_ORDER,                        *)
(* ROOTS_OF_UNITY_RING_ORDER_DIVISOR).                                       *)
(* ------------------------------------------------------------------------- *)

let UNITY_ROOT_SUM = prove
 (`!p w. 1 <= p /\ w pow p = Cx(&1) /\ ~(w = Cx(&1))
         ==> vsum(0..p-1) (\t. w pow t) = Cx(&0)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`w:complex`; `p - 1`] VSUM_GP_BASIC) THEN
  ASM_SIMP_TAC[ARITH_RULE `1 <= p ==> SUC(p - 1) = p`] THEN
  ASM_REWRITE_TAC[COMPLEX_SUB_REFL] THEN
  REWRITE_TAC[COMPLEX_ENTIRE; COMPLEX_SUB_0] THEN ASM_MESON_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* Small facts about powers and sums.                                        *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_POW_DIV_MOD = prove
 (`!(z:complex) p n.
        ~(p = 0) ==> z pow n = (z pow p) pow (n DIV p) * z pow (n MOD p)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o SPEC `n:num` o MATCH_MP DIVISION) THEN
  DISCH_THEN(fun th -> GEN_REWRITE_TAC (LAND_CONV o RAND_CONV)
   [CONJUNCT1 th]) THEN
  REWRITE_TAC[COMPLEX_POW_ADD; COMPLEX_POW_POW] THEN
  REWRITE_TAC[MULT_SYM]);;

let VSUM_DELTA_CX = prove
 (`!s (a:A) b (v:A->complex).
        a IN s ==> vsum s (\f. Cx(if f = a then b else &0) * v f) = Cx b * v a`,
  SIMP_TAC[COND_RAND; COND_RATOR; COMPLEX_MUL_LZERO; VSUM_DELTA_FUN]);;

(* ------------------------------------------------------------------------- *)
(* Subfields of C: closure properties (inv x and x / y for all x, y, since   *)
(* inv(Cx(&0)) = Cx(&0)); if h^p = b^d with h, b in s, b non-zero and d      *)
(* prime to p, then b is the p-th power of an element of s (Bezout).         *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBFIELD_CLOSED = prove
 (`!s. s subfield_of complex_ring
       ==> Cx(&0) IN s /\ Cx(&1) IN s /\
           (!x y. x IN s /\ y IN s ==> x + y IN s) /\
           (!x y. x IN s /\ y IN s ==> x - y IN s) /\
           (!x y. x IN s /\ y IN s ==> x * y IN s) /\
           (!x. x IN s ==> --x IN s) /\
           (!x n. x IN s ==> x pow n IN s) /\
           (!x. x IN s ==> inv x IN s) /\
           (!x y. x IN s /\ y IN s ==> x / y IN s)`,
  GEN_TAC THEN REWRITE_TAC[COMPLEX_SUBFIELD_OF] THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBRING_CLOSED) THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `!x:complex. x IN s ==> inv x IN s` ASSUME_TAC THENL
   [X_GEN_TAC `x:complex` THEN DISCH_TAC THEN
    ASM_CASES_TAC `x = Cx(&0)` THEN ASM_SIMP_TAC[COMPLEX_INV_0];
    ASM_SIMP_TAC[complex_div]]);;

let COMPLEX_SUBFIELD_POW_ROOT = prove
 (`!s b h d p.
        s subfield_of complex_ring /\ coprime(d,p) /\ ~(d = 0) /\
        b IN s /\ ~(b = Cx(&0)) /\ h IN s /\ h pow p = b pow d
        ==> ?g. g IN s /\ g pow p = b`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  MP_TAC(SPECL [`d:num`; `p:num`] BEZOUT_ADD_STRONG) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `e:num` (X_CHOOSE_THEN `x:num`
    (X_CHOOSE_THEN `y:num` STRIP_ASSUME_TAC))) THEN
  SUBGOAL_THEN `e = 1` SUBST_ALL_TAC THENL
   [ASM_MESON_TAC[COPRIME]; ALL_TAC] THEN
  EXISTS_TAC `(h:complex) pow x * inv(b) pow y` THEN
  CONJ_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
  REWRITE_TAC[COMPLEX_POW_MUL; COMPLEX_POW_POW] THEN
  SUBGOAL_THEN `(h:complex) pow (x * p) = b pow (p * y) * b` SUBST1_TAC THENL
   [SUBST1_TAC(SPECL [`x:num`; `p:num`] MULT_SYM) THEN
    ASM_REWRITE_TAC[GSYM COMPLEX_POW_POW] THEN
    ASM_REWRITE_TAC[COMPLEX_POW_POW; COMPLEX_POW_ADD; COMPLEX_POW_1];
    ALL_TAC] THEN
  SUBGOAL_THEN `inv(b:complex) pow (y * p) = inv(b pow (p * y))`
  SUBST1_TAC THENL
   [REWRITE_TAC[COMPLEX_POW_INV] THEN AP_TERM_TAC THEN AP_TERM_TAC THEN
    ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `~((b:complex) pow (p * y) = Cx(&0))` MP_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0]; CONV_TAC COMPLEX_FIELD]);;

(* ------------------------------------------------------------------------- *)
(* The degree bound. A non-zero polynomial with coefficients e j in a        *)
(* subfield s of C (j <= d) is a non-zero polynomial of degree at most d     *)
(* over the ring subfield_generated complex_ring s; a root z of it generates *)
(* a finite extension of degree at most d.                                   *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBFIELD_POLY = prove
 (`!s (e:num->complex) d.
        s subfield_of complex_ring /\ (!j. j <= d ==> e j IN s) /\
        ~(!j. j <= d ==> e j = Cx(&0))
        ==> ?p. p IN ring_carrier(poly_ring (subfield_generated complex_ring s)
                                            (:1)) /\
                ~(p = ring_0(poly_ring (subfield_generated complex_ring s)
                                       (:1))) /\
                poly_deg (subfield_generated complex_ring s) p <= d /\
                !z. poly_extend (subfield_generated complex_ring s,
                                 complex_ring) I (\v. z) p =
                    vsum(0..d) (\j. e j * z pow j)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP CARRIER_SUBFIELD_GENERATED_SUBFIELD) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  MP_TAC(SPECL [`d:num`; `e:num->complex`] COMPLEX_POLYFUN_POLY) THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `p:(1->num)->complex` THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC (ASSUME_TAC o GSYM)))) THEN
  ASM_REWRITE_TAC[poly_eval; poly_evaluate; poly_extend; poly_deg;
                  POLY_RING_CLAUSES; CONJUNCT2 SUBFIELD_GENERATED] THEN
  RULE_ASSUM_TAC(REWRITE_RULE[poly_deg]) THEN ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[IN_ELIM_THM; SUBSET_UNIV] THEN CONJ_TAC THENL
   [MATCH_MP_TAC RING_POLYNOMIAL_COEFF_BOUND THEN EXISTS_TAC `d:num` THEN
    ASM_REWRITE_TAC[RING_POWERSERIES_COEFF; CONJUNCT2 SUBFIELD_GENERATED;
                    COMPLEX_RING_CLAUSES] THEN
    CONJ_TAC THEN GEN_TAC THEN COND_CASES_TAC THEN ASM_SIMP_TAC[];
    FIRST_X_ASSUM(X_CHOOSE_THEN `j:num` STRIP_ASSUME_TAC o
      REWRITE_RULE[NOT_FORALL_THM; NOT_IMP] o check (is_neg o concl)) THEN
    DISCH_THEN(MP_TAC o AP_TERM `coeff j:((1->num)->complex)->complex`) THEN
    ASM_REWRITE_TAC[COEFF_POLY_0; CONJUNCT2 SUBFIELD_GENERATED;
                    COMPLEX_RING_CLAUSES]]);;

let COMPLEX_SUBFIELD_ROOT_DEGREE = prove
 (`!s (e:num->complex) d z.
        s subfield_of complex_ring /\ (!j. j <= d ==> e j IN s) /\
        ~(!j. j <= d ==> e j = Cx(&0)) /\
        vsum(0..d) (\j. e j * z pow j) = Cx(&0)
        ==> finite_extension(subfield_generated complex_ring s,
                             subfield_generated complex_ring (z INSERT s)) I /\
            extension_degree(subfield_generated complex_ring s,
                             subfield_generated complex_ring (z INSERT s)) I
            <= d`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`s:complex->bool`; `e:num->complex`; `d:num`]
    COMPLEX_SUBFIELD_POLY) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `p:(1->num)->complex` STRIP_ASSUME_TAC) THEN
  ABBREV_TAC `K = subfield_generated complex_ring s` THEN
  SUBGOAL_THEN
   `field_extension(K,complex_ring) I /\ algebraic_over (K,complex_ring) I z`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "K" THEN
    SIMP_TAC[FIELD_EXTENSION_SUBFIELD_GENERATED; FIELD_COMPLEX_RING] THEN
    REWRITE_TAC[algebraic_over; COMPLEX_RING_CLAUSES; IN_UNIV] THEN
    EXISTS_TAC `p:(1->num)->complex` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `subring_generated complex_ring (z INSERT IMAGE I (ring_carrier K)) =
    subfield_generated complex_ring (z INSERT s)`
  (SUBST1_TAC o SYM) THENL
   [MP_TAC(ISPECL [`I:complex->complex`; `K:complex ring`; `complex_ring`;
                   `z:complex`] FIELD_SIMPLE_ALGEBRAIC_EXTENSION) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(SUBST1_TAC o MATCH_MP SUBRING_EQ_SUBFIELD_GENERATED) THEN
    EXPAND_TAC "K" THEN REWRITE_TAC[IMAGE_I; SUBFIELD_GENERATED_INSERT];
    ALL_TAC] THEN
  ASM_SIMP_TAC[FINITE_SIMPLE_ALGEBRAIC_EXTENSION; EXTENSION_DEGREE_SIMPLE] THEN
  TRANS_TAC LE_TRANS `poly_deg K (p:(1->num)->complex)` THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC MINIMAL_POLYNOMIAL_DEG_LE THEN
  ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES] THEN
  UNDISCH_TAC `~(p = ring_0(poly_ring K (:1)):(1->num)->complex)` THEN
  REWRITE_TAC[POLY_RING]);;

(* ------------------------------------------------------------------------- *)
(* The norm step: if z is a root of a non-zero polynomial of degree less     *)
(* than p (p prime) with coefficients in s and x in s(z) has x^p in s, then  *)
(* x^p = g^p with g in s. The norm N(x) from s(z) to s lies in s and N(x)^p  *)
(* = N(x^p) = (x^p)^d with d = [s(z):s] in 1..p-1.                           *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBFIELD_NORM_POW_ROOT = prove
 (`!s p (e:num->complex) z x.
        s subfield_of complex_ring /\ prime p /\
        (!j. j < p ==> e j IN s) /\ ~(!j. j < p ==> e j = Cx(&0)) /\
        vsum(0..p-1) (\j. e j * z pow j) = Cx(&0) /\
        x IN ring_carrier(subfield_generated complex_ring (z INSERT s)) /\
        x pow p IN s
        ==> ?g. g IN s /\ g pow p = x pow p`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_GE_2) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  ASM_CASES_TAC `x = Cx(&0)` THENL
   [EXISTS_TAC `Cx(&0)` THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  MP_TAC(ISPECL [`s:complex->bool`; `e:num->complex`; `p - 1`; `z:complex`]
    COMPLEX_SUBFIELD_ROOT_DEGREE) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC;
      UNDISCH_TAC `~(!j. j < p ==> (e:num->complex) j = Cx(&0))` THEN
      REWRITE_TAC[CONTRAPOS_THM] THEN REPEAT STRIP_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC];
    ALL_TAC] THEN
  ABBREV_TAC `K = subfield_generated complex_ring s` THEN
  ABBREV_TAC `L = subfield_generated complex_ring (z INSERT s)` THEN
  ABBREV_TAC `d = extension_degree(K:complex ring,L) I` THEN
  STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FIELD_EXTENSION_IMP_HOMOMORPHISM) THEN
  SUBGOAL_THEN `ring_carrier K = (s:complex->bool) /\
                ring_pow K = (pow) /\ ring_pow (L:complex ring) = (pow)`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"] THEN
    REWRITE_TAC[RING_POW_SUBFIELD_GENERATED; COMPLEX_RING_POW] THEN
    MATCH_MP_TAC CARRIER_SUBFIELD_GENERATED_SUBFIELD THEN
    FIRST_ASSUM ACCEPT_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `~(d = 0)` ASSUME_TAC THENL
   [EXPAND_TAC "d" THEN ASM_SIMP_TAC[EXTENSION_DEGREE_EQ_0]; ALL_TAC] THEN
  MATCH_MP_TAC COMPLEX_SUBFIELD_POW_ROOT THEN
  MAP_EVERY EXISTS_TAC [`algebra_norm(K:complex ring,L) I x`; `d:num`] THEN
  ASM_REWRITE_TAC[COMPLEX_POW_EQ_0] THEN REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC PRIME_COPRIME_LT THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC;
    ASM_MESON_TAC[ALGEBRA_TRACE_NORM_IN_CARRIER];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`I:complex->complex`; `K:complex ring`; `L:complex ring`;
                 `x:complex`; `p:num`] ALGEBRA_NORM_POW) THEN
  MP_TAC(ISPECL [`I:complex->complex`; `K:complex ring`; `L:complex ring`;
                 `(x:complex) pow p`] ALGEBRA_TRACE_NORM_BASE) THEN
  ASM_REWRITE_TAC[I_THM] THEN MESON_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The Kummer step: let s be a subfield of C containing a p-th root of unity *)
(* zeta <> 1 (p prime) and w^p. If x in s(w) has x^p in s, then x = y w^t    *)
(* with y in s and t < p. Either w is in s, or a generator g of the cyclic   *)
(* Galois group of s(w) over s has g(w) = d w, g(x) = c x with p-th roots of *)
(* unity c, d of s, d <> 1 (else g fixes s(w)), so c = d^t and x / w^t is    *)
(* fixed by g.                                                               *)
(* ------------------------------------------------------------------------- *)

let KUMMER_STEP = prove
 (`!s p zeta w x.
        s subfield_of complex_ring /\ prime p /\
        zeta IN s /\ zeta pow p = Cx(&1) /\ ~(zeta = Cx(&1)) /\
        w pow p IN s /\
        x IN ring_carrier(subfield_generated complex_ring (w INSERT s)) /\
        x pow p IN s
        ==> ?t y. t < p /\ y IN s /\ x = y * w pow t`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_GE_2) THEN
  SUBGOAL_THEN `{x | x IN s /\ x pow p = Cx(&1)} HAS_SIZE p` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`complex_ring`; `s:complex->bool`; `zeta:complex`;
                   `p:num`; `p:num`] ROOTS_OF_UNITY_RING_ORDER_DIVISOR) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[INTEGRAL_DOMAIN_COMPLEX_RING; SUBFIELD_IMP_SUBRING_OF;
                   RING_ORDER_UNIQUE_PRIME; complex_field_clauses; IN_UNIV;
                   DIVIDES_REFL; PRIME_IMP_NZ];
      SIMP_TAC[complex_field_clauses]];
    ALL_TAC] THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  ASM_CASES_TAC `(w:complex) IN s` THENL
   [MAP_EVERY EXISTS_TAC [`0`; `x:complex`] THEN
    REWRITE_TAC[complex_pow; COMPLEX_MUL_RID] THEN
    CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    SUBGOAL_THEN `(w:complex) INSERT s = s` SUBST_ALL_TAC THENL
     [ASM SET_TAC[]; ALL_TAC] THEN
    ASM_MESON_TAC[CARRIER_SUBFIELD_GENERATED_SUBFIELD];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`complex_ring`; `s:complex->bool`; `w:complex`; `p:num`]
    KUMMER_EXTENSION_ABELIAN_INTERMEDIATE) THEN
  MP_TAC(ISPECL [`complex_ring`; `s:complex->bool`; `w:complex`; `p:num`]
    KUMMER_EXTENSION_CYCLIC_INTERMEDIATE) THEN
  ASM_REWRITE_TAC[FIELD_COMPLEX_RING; complex_field_clauses; IN_UNIV] THEN
  ABBREV_TAC `K = subfield_generated complex_ring s` THEN
  ABBREV_TAC `L = subfield_generated complex_ring (w INSERT s)` THEN
  REWRITE_TAC[cyclic_group] THEN
  DISCH_THEN(X_CHOOSE_THEN `g:complex->complex` STRIP_ASSUME_TAC o
    CONJUNCT1) THEN
  STRIP_TAC THEN
  SUBGOAL_THEN
   `ring_carrier K = (s:complex->bool) /\ ring_pow K = (pow) /\
    ring_1 K = Cx(&1) /\ ring_pow (L:complex ring) = (pow) /\
    ring_mul (L:complex ring) = ( * )`
  STRIP_ASSUME_TAC THENL
   [MAP_EVERY EXPAND_TAC ["K"; "L"] THEN
    REWRITE_TAC[RING_POW_SUBFIELD_GENERATED; CONJUNCT2 SUBFIELD_GENERATED;
                complex_field_clauses] THEN
    MATCH_MP_TAC CARRIER_SUBFIELD_GENERATED_SUBFIELD THEN
    FIRST_ASSUM ACCEPT_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(ring_carrier L) subfield_of complex_ring` ASSUME_TAC THENL
   [EXPAND_TAC "L" THEN
    SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING];
    ALL_TAC] THEN
  SUBGOAL_THEN `(w:complex) IN ring_carrier L` ASSUME_TAC THENL
   [EXPAND_TAC "L" THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; IN_UNIV; IN_INSERT];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(w = Cx(&0))` ASSUME_TAC THENL
   [DISCH_TAC THEN UNDISCH_TAC `~((w:complex) IN s)` THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `ring_homomorphism(L,L) (g:complex->complex)` ASSUME_TAC THENL
   [MATCH_MP_TAC(ISPECL [`I:complex->complex`; `g:complex->complex`;
                         `K:complex ring`; `L:complex ring`]
      GALOIS_GROUP_RING_HOMOMORPHISM) THEN
    FIRST_ASSUM ACCEPT_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `!y. y IN ring_carrier L /\ (g:complex->complex) y = y
                    ==> y IN s`
  (LABEL_TAC "fix") THENL
   [MP_TAC(ISPECL [`I:complex->complex`; `K:complex ring`; `L:complex ring`;
                   `{g:complex->complex}`]
      FIXED_FIELD_GALOIS_GROUP_GENERATORS) THEN
    ASM_REWRITE_TAC[SING_SUBSET; IMAGE_I] THEN
    REWRITE_TAC[EXTENSION; IN_FIXED_FIELD; IN_SING] THEN MESON_TAC[];
    ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP FINITE_IMP_FIELD_EXTENSION) THEN
  MP_TAC(ISPECL [`I:complex->complex`; `g:complex->complex`; `K:complex ring`;
                 `L:complex ring`; `w:complex`; `p:num`]
    GALOIS_GROUP_KUMMER_ROOT_OF_UNITY) THEN
  ASM_REWRITE_TAC[IMAGE_I; I_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `d:complex` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`I:complex->complex`; `g:complex->complex`; `K:complex ring`;
                 `L:complex ring`; `x:complex`; `p:num`]
    GALOIS_GROUP_KUMMER_ROOT_OF_UNITY) THEN
  ASM_REWRITE_TAC[IMAGE_I; I_THM] THEN
  DISCH_THEN(X_CHOOSE_THEN `c:complex` STRIP_ASSUME_TAC) THEN
  SUBGOAL_THEN `~(d = Cx(&1))` ASSUME_TAC THENL
   [DISCH_TAC THEN UNDISCH_TAC `~((w:complex) IN s)` THEN REWRITE_TAC[] THEN
    USE_THEN "fix" MATCH_MP_TAC THEN ASM_REWRITE_TAC[COMPLEX_MUL_LID];
    ALL_TAC] THEN
  SUBGOAL_THEN `~(d = Cx(&0))` ASSUME_TAC THENL
   [DISCH_TAC THEN UNDISCH_TAC `(d:complex) pow p = Cx(&1)` THEN
    ASM_SIMP_TAC[COMPLEX_POW_ZERO; PRIME_IMP_NZ; CX_INJ; REAL_OF_NUM_EQ;
                 ARITH_EQ];
    ALL_TAC] THEN
  SUBGOAL_THEN `?t. t < p /\ c = (d:complex) pow t` STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPECL [`complex_ring`; `d:complex`; `p:num`]
      ROOTS_OF_UNITY_RING_ORDER) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[INTEGRAL_DOMAIN_COMPLEX_RING; RING_ORDER_UNIQUE_PRIME;
                   complex_field_clauses; IN_UNIV; PRIME_IMP_NZ];
      DISCH_THEN(MP_TAC o SPEC `c:complex` o REWRITE_RULE[EXTENSION] o
        CONJUNCT1) THEN
      ASM_REWRITE_TAC[complex_field_clauses; IN_ELIM_THM; IN_UNIV;
                      IN_IMAGE] THEN
      MESON_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `~((w:complex) pow t = Cx(&0)) /\ ~((d:complex) pow t = Cx(&0))`
  STRIP_ASSUME_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0]; ALL_TAC] THEN
  MP_TAC(MATCH_MP COMPLEX_SUBFIELD_CLOSED
    (ASSUME `ring_carrier L subfield_of complex_ring`)) THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `x / (w:complex) pow t IN ring_carrier L` ASSUME_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC [`t:num`; `x / (w:complex) pow t`] THEN
  ASM_SIMP_TAC[COMPLEX_DIV_RMUL] THEN
  USE_THEN "fix" MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `(g:complex->complex)(x / w pow t * w pow t) =
    g(x / w pow t) * (g w) pow t`
  MP_TAC THENL
   [MP_TAC(ISPECL [`L:complex ring`; `L:complex ring`; `g:complex->complex`]
      RING_HOMOMORPHISM_MUL) THEN
    MP_TAC(ISPECL [`L:complex ring`; `L:complex ring`; `g:complex->complex`]
      RING_HOMOMORPHISM_POW) THEN
    ASM_REWRITE_TAC[] THEN REPEAT STRIP_TAC THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[COMPLEX_DIV_RMUL] THEN
  ABBREV_TAC `gy = (g:complex->complex)(x / w pow t)` THEN
  REWRITE_TAC[COMPLEX_POW_MUL] THEN
  UNDISCH_TAC `~((w:complex) pow t = Cx(&0))` THEN
  UNDISCH_TAC `~((d:complex) pow t = Cx(&0))` THEN
  CONV_TAC COMPLEX_FIELD);;

(* ------------------------------------------------------------------------- *)
(* The induction over the number m of radicals adjoined to s(zeta). The base *)
(* case m = 0 is the norm step with z = zeta, a root of 1 + X + ... +        *)
(* X^(p-1). The statement covers every x in the field whose p-th power lies  *)
(* in s, so no choice of roots is needed.                                    *)
(* ------------------------------------------------------------------------- *)

let KUMMER_COMPLEX_BASE = prove
 (`!s p zeta x.
        s subfield_of complex_ring /\ prime p /\
        zeta pow p = Cx(&1) /\ ~(zeta = Cx(&1)) /\
        x IN ring_carrier(subfield_generated complex_ring (zeta INSERT s)) /\
        x pow p IN s
        ==> ?g. g IN s /\ g pow p = x pow p`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_GE_2) THEN
  MATCH_MP_TAC COMPLEX_SUBFIELD_NORM_POW_ROOT THEN
  MAP_EVERY EXISTS_TAC [`(\j. Cx(&1)):num->complex`; `zeta:complex`] THEN
  ASM_REWRITE_TAC[COMPLEX_MUL_LID] THEN REPEAT CONJ_TAC THENL
   [ASM_MESON_TAC[COMPLEX_SUBFIELD_CLOSED];
    REWRITE_TAC[NOT_FORALL_THM; NOT_IMP; CX_INJ; REAL_OF_NUM_EQ; ARITH_EQ] THEN
    EXISTS_TAC `0` THEN ASM_ARITH_TAC;
    MATCH_MP_TAC UNITY_ROOT_SUM THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC]);;

let KUMMER_COMPLEX_INDUCT = prove
 (`!s p zeta (al:num->complex) (w:num->complex).
     s subfield_of complex_ring /\ prime p /\
     zeta pow p = Cx(&1) /\ ~(zeta = Cx(&1))
     ==> !m. (!r. 1 <= r /\ r <= m
                  ==> al r IN s /\ ~(al r = Cx(&0)) /\ w r pow p = al r)
             ==> !x. x IN ring_carrier(subfield_generated complex_ring
                                (zeta INSERT (s UNION IMAGE w (1..m)))) /\
                     x pow p IN s
                     ==> ?jj g. (!r. jj r < p) /\ g IN s /\
                                x pow p =
                                cproduct(1..m) (\r. al r pow jj r) * g pow p`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_GE_2) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  INDUCT_TAC THENL
   [DISCH_TAC THEN X_GEN_TAC `x:complex` THEN
    REWRITE_TAC[NUMSEG_CLAUSES; ARITH; IMAGE_CLAUSES; UNION_EMPTY] THEN
    STRIP_TAC THEN
    MP_TAC(SPECL [`s:complex->bool`; `p:num`; `zeta:complex`; `x:complex`]
      KUMMER_COMPLEX_BASE) THEN
    ASM_REWRITE_TAC[] THEN
    DISCH_THEN(X_CHOOSE_THEN `g:complex` STRIP_ASSUME_TAC) THEN
    MAP_EVERY EXISTS_TAC [`\r:num. 0`; `g:complex`] THEN
    ASM_REWRITE_TAC[CPRODUCT_CLAUSES; COMPLEX_MUL_LID] THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  DISCH_TAC THEN X_GEN_TAC `x:complex` THEN STRIP_TAC THEN
  FIRST_X_ASSUM(MP_TAC o check (is_imp o concl)) THEN
  ANTS_TAC THENL
   [ASM_MESON_TAC[ARITH_RULE `r <= m ==> r <= SUC m`]; ALL_TAC] THEN
  DISCH_THEN(LABEL_TAC "IH") THEN
  SUBGOAL_THEN
   `al(SUC m) IN s /\ ~(al(SUC m) = Cx(&0)) /\
    (w:num->complex)(SUC m) pow p = al(SUC m)`
  STRIP_ASSUME_TAC THENL
   [FIRST_X_ASSUM MATCH_MP_TAC THEN ARITH_TAC; ALL_TAC] THEN
  ABBREV_TAC
   `u = ring_carrier(subfield_generated complex_ring
          (zeta INSERT (s UNION IMAGE (w:num->complex) (1..m))))` THEN
  SUBGOAL_THEN
   `u subfield_of complex_ring /\ zeta IN u /\ !y. y IN s ==> y IN u`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "u" THEN
    SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING] THEN
    CONJ_TAC THENL [ALL_TAC; X_GEN_TAC `y:complex` THEN DISCH_TAC] THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
    ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES; IN_UNIV; IN_INSERT; IN_UNION];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `x IN ring_carrier(subfield_generated complex_ring
                       ((w:num->complex)(SUC m) INSERT u))`
  ASSUME_TAC THENL
   [SUBGOAL_THEN
     `subfield_generated complex_ring ((w:num->complex)(SUC m) INSERT u) =
      subfield_generated complex_ring
        (zeta INSERT (s UNION IMAGE w (1..SUC m)))`
     (fun th -> ASM_REWRITE_TAC[th]) THEN
    EXPAND_TAC "u" THEN REWRITE_TAC[SUBFIELD_GENERATED_INSERT] THEN
    AP_TERM_TAC THEN
    REWRITE_TAC[NUMSEG_CLAUSES; ARITH_RULE `1 <= SUC m`; IMAGE_CLAUSES] THEN
    SET_TAC[];
    ALL_TAC] THEN
  MP_TAC(SPECL [`u:complex->bool`; `p:num`; `zeta:complex`;
                `(w:num->complex)(SUC m)`; `x:complex`] KUMMER_STEP) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[]; ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `t:num` (X_CHOOSE_THEN `y:complex`
    STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN `(x:complex) pow p = y pow p * al(SUC m) pow t`
  ASSUME_TAC THENL
   [UNDISCH_TAC `x = y * (w:num->complex)(SUC m) pow t` THEN
    DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[COMPLEX_POW_MUL; COMPLEX_POW_POW] THEN
    ONCE_REWRITE_TAC[MULT_SYM] THEN
    ASM_REWRITE_TAC[GSYM COMPLEX_POW_POW];
    ALL_TAC] THEN
  UNDISCH_THEN `x = y * (w:num->complex)(SUC m) pow t` (K ALL_TAC) THEN
  SUBGOAL_THEN `~(al(SUC m) pow t = Cx(&0))` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0]; ALL_TAC] THEN
  SUBGOAL_THEN `(y:complex) pow p IN s` ASSUME_TAC THENL
   [SUBGOAL_THEN `(y:complex) pow p = x pow p / al(SUC m) pow t`
    SUBST1_TAC THENL
     [ASM_REWRITE_TAC[] THEN
      UNDISCH_TAC `~(al(SUC m) pow t = Cx(&0))` THEN CONV_TAC COMPLEX_FIELD;
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  REMOVE_THEN "IH" (MP_TAC o SPEC `y:complex`) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `jj:num->num`
   (X_CHOOSE_THEN `g:complex` STRIP_ASSUME_TAC)) THEN
  MAP_EVERY EXISTS_TAC
   [`\r. if r = SUC m then t else (jj:num->num) r`; `g:complex`] THEN
  REWRITE_TAC[CPRODUCT_CLAUSES_NUMSEG; ARITH_RULE `1 <= SUC m`] THEN
  REPEAT CONJ_TAC THENL
   [GEN_TAC THEN COND_CASES_TAC THEN ASM_REWRITE_TAC[];
    FIRST_ASSUM ACCEPT_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `cproduct(1..m) (\r. (al:num->complex) r pow
                        (if r = SUC m then t else jj r)) =
    cproduct(1..m) (\r. al r pow jj r)`
  SUBST1_TAC THENL
   [MATCH_MP_TAC CPRODUCT_EQ THEN REWRITE_TAC[IN_NUMSEG] THEN
    SIMP_TAC[ARITH_RULE `r <= m ==> ~(r = SUC m)`];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[COMPLEX_MUL_AC]);;

(* ------------------------------------------------------------------------- *)
(* Main results: Kummer theory for complex radicals over a subfield s of C   *)
(* (Baker and Stark 1971, Lemma 3) and the contrapositive. The coefficients  *)
(* E j lie in the field L generated by s, zeta and the w r, so the norm step *)
(* over L (z = w0) gives a p-th root of al0 in L, and the induction applies  *)
(* to it.                                                                    *)
(* ------------------------------------------------------------------------- *)

let KUMMER_COMPLEX = prove
 (`!p s (al:num->complex) (w:num->complex) m al0 w0 (E:num->complex).
        prime p /\ s subfield_of complex_ring /\
        (!r. 1 <= r /\ r <= m
             ==> al r IN s /\ ~(al r = Cx(&0)) /\ w r pow p = al r) /\
        al0 IN s /\ ~(al0 = Cx(&0)) /\ w0 pow p = al0 /\
        (!j. j < p ==> E j IN ring_carrier(subring_generated complex_ring
                                            (s UNION IMAGE w (1..m)))) /\
        vsum(0..p-1) (\j. E j * w0 pow j) = Cx(&0) /\
        ~(!j. j < p ==> E j = Cx(&0))
        ==> ?jj g. (!r. jj r < p) /\ g IN s /\
                   al0 = cproduct(1..m) (\r. al r pow jj r) * g pow p`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP PRIME_GE_2) THEN
  MP_TAC(SPEC `p:num` UNITY_ROOT_CEXP) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[PRIME_IMP_NZ]; ALL_TAC] THEN
  ABBREV_TAC `zeta = cexp(Cx(&2) * Cx pi * ii * Cx(&1 / &p))` THEN
  STRIP_TAC THEN
  SUBGOAL_THEN `~(zeta = Cx(&1))` ASSUME_TAC THENL
   [DISCH_TAC THEN FIRST_X_ASSUM(MP_TAC o SPECL [`1`; `0`]) THEN
    ASM_REWRITE_TAC[COMPLEX_POW_ONE; complex_pow] THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  ABBREV_TAC
   `L = ring_carrier(subfield_generated complex_ring
          (zeta INSERT (s UNION IMAGE (w:num->complex) (1..m))))` THEN
  SUBGOAL_THEN
   `zeta INSERT (s UNION IMAGE (w:num->complex) (1..m)) SUBSET L /\
    L subfield_of complex_ring`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "L" THEN
    SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING] THEN
    MP_TAC(ISPECL [`complex_ring`;
                   `zeta INSERT (s UNION IMAGE (w:num->complex) (1..m))`]
      SUBFIELD_GENERATED_SUBSET_CARRIER) THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; INTER_UNIV];
    ALL_TAC] THEN
  SUBGOAL_THEN `!j. j < p ==> (E:num->complex) j IN L` ASSUME_TAC THENL
   [X_GEN_TAC `j:num` THEN DISCH_TAC THEN
    MP_TAC(ISPECL [`complex_ring`; `L:complex->bool`;
                   `s UNION IMAGE (w:num->complex) (1..m)`]
      SUBRING_GENERATED_MINIMAL) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[SUBFIELD_IMP_SUBRING_OF] THEN ASM SET_TAC[];
      REWRITE_TAC[SUBSET] THEN DISCH_THEN MATCH_MP_TAC THEN ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  MP_TAC(SPECL [`L:complex->bool`; `p:num`; `E:num->complex`; `w0:complex`;
                `w0:complex`] COMPLEX_SUBFIELD_NORM_POW_ROOT) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
      REWRITE_TAC[COMPLEX_RING_CLAUSES; IN_UNIV; IN_INSERT];
      ASM SET_TAC[]];
    DISCH_THEN(X_CHOOSE_THEN `g1:complex` STRIP_ASSUME_TAC)] THEN
  MP_TAC(SPECL [`s:complex->bool`; `p:num`; `zeta:complex`;
                `al:num->complex`; `w:num->complex`]
    KUMMER_COMPLEX_INDUCT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o SPEC `m:num`) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o SPEC `g1:complex`) THEN
  ASM_REWRITE_TAC[]);;

let KUMMER_COMPLEX_INDEPENDENT = prove
 (`!p s (al:num->complex) (w:num->complex) m al0 w0 (E:num->complex).
        prime p /\ s subfield_of complex_ring /\
        (!r. 1 <= r /\ r <= m
             ==> al r IN s /\ ~(al r = Cx(&0)) /\ w r pow p = al r) /\
        al0 IN s /\ ~(al0 = Cx(&0)) /\ w0 pow p = al0 /\
        ~(?jj g. (!r. jj r < p) /\ g IN s /\
                 al0 = cproduct(1..m) (\r. al r pow jj r) * g pow p) /\
        (!j. j < p ==> E j IN ring_carrier(subring_generated complex_ring
                                            (s UNION IMAGE w (1..m)))) /\
        vsum(0..p-1) (\j. E j * w0 pow j) = Cx(&0)
        ==> !j. j < p ==> E j = Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  GEN_REWRITE_TAC I [TAUT `p <=> ~ ~p`] THEN DISCH_TAC THEN
  UNDISCH_TAC
   `~(?jj g. (!r. jj r < p) /\ g IN s /\
             al0 = cproduct(1..m) (\r. (al:num->complex) r pow jj r) *
                   g pow p)` THEN
  REWRITE_TAC[] THEN MATCH_MP_TAC KUMMER_COMPLEX THEN
  MAP_EVERY EXISTS_TAC [`w:num->complex`; `w0:complex`; `E:num->complex`] THEN
  ASM_REWRITE_TAC[]);;
