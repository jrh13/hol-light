(* ========================================================================= *)
(* Kummer theory for complex radicals over an arbitrary subfield s of C.     *)
(*                                                                           *)
(* Purpose: let p be a prime, s a subfield of C (s subfield_of               *)
(* complex_ring), w r (r = 1..m) and w0 any fixed p-th roots of non-zero     *)
(* numbers al r, al0 of s. If 1, w0, ..., w0^(p-1) are linearly dependent    *)
(* over the subring of C generated by s and the w r, then al0 is the product *)
(* of the al r^(jj r) (jj r < p) and of g^p for some g in s (Baker and Stark *)
(* 1971, Lemma 3; Baker, Sharpening I, Lemma 3; compare Siegel, Acta Arith   *)
(* 21 (1972) 59-64).                                                         *)
(*                                                                           *)
(* Method: the Kummer theory of Library/galois.ml and the norm of            *)
(* Library/ring_det.ml, with a primitive p-th root of unity zeta. The degree *)
(* bound: a root z of a non-zero polynomial of degree at most d with         *)
(* coefficients in a subfield k of C generates a finite extension k(z) of k  *)
(* of degree at most d (COMPLEX_SUBFIELD_ROOT_DEGREE). The norm step: if     *)
(* [k(z):k] < p and x in k(z) has x^p in k, the norm of x from k(z) to k     *)
(* satisfies N(x)^p = (x^p)^d with d = [k(z):k] prime to p, so x^p is the    *)
(* p-th power of an element of k (COMPLEX_SUBFIELD_NORM_POW_ROOT, Bezout for *)
(* d and p). The Kummer step (KUMMER_STEP): if k contains zeta and w^p, the  *)
(* Galois group of k(w) over k is cyclic                                     *)
(* (KUMMER_EXTENSION_CYCLIC_INTERMEDIATE); a generator multiplies w and      *)
(* every x in k(w) with x^p in k by p-th roots of unity of k                 *)
(* (GALOIS_GROUP_KUMMER_ROOT_OF_UNITY), so x / w^t is fixed by it for some t *)
(* < p and lies in k (FIXED_FIELD_GALOIS_GROUP_GENERATORS). The main         *)
(* theorem: the norm step over the field L generated by s, zeta and the w r  *)
(* (z = w0) gives a p-th root of al0 in L; the induction over the number m   *)
(* of radicals adjoined to s(zeta) (KUMMER_COMPLEX_INDUCT: the Kummer step,  *)
(* and for m = 0 the norm step over s with z = zeta, KUMMER_COMPLEX_BASE)    *)
(* gives the relation for every element of L whose p-th power lies in s.     *)
(* Kummer theory of several radicals at once is not needed.                  *)
(*                                                                           *)
(* Main results: KUMMER_COMPLEX, KUMMER_COMPLEX_INDEPENDENT (the             *)
(* contrapositive); KUMMER_STEP, KUMMER_COMPLEX_BASE, KUMMER_COMPLEX_INDUCT; *)
(* COMPLEX_SUBFIELD_POLY (a polynomial with coefficients in a subfield s of  *)
(* C as a polynomial over subfield_generated complex_ring s),                *)
(* COMPLEX_SUBFIELD_ROOT_DEGREE, COMPLEX_SUBFIELD_NORM_POW_ROOT,             *)
(* COMPLEX_SUBFIELD_POW_ROOT, COMPLEX_SUBFIELD_CLOSED; UNITY_ROOT_SUM,       *)
(* COMPLEX_POW_DIV_MOD, VSUM_DELTA_CX.                                       *)
(*                                                                           *)
(* Uses: Baker/lemmas.ml (COMPLEX_SUBFIELD_OF, COMPLEX_SUBRING_CLOSED,       *)
(* UNITY_ROOT_CEXP, VSUM_DELTA_FUN, COMPLEX_POLYFUN_POLY), Library/galois.ml *)
(* (KUMMER_EXTENSION_ABELIAN_INTERMEDIATE,                                   *)
(* KUMMER_EXTENSION_CYCLIC_INTERMEDIATE, GALOIS_GROUP_KUMMER_ROOT_OF_UNITY,  *)
(* FIXED_FIELD_GALOIS_GROUP_GENERATORS, GALOIS_GROUP_RING_HOMOMORPHISM,      *)
(* IN_FIXED_FIELD, cyclic_group of Library/grouptheory.ml),                  *)
(* Library/ring_det.ml (algebra_norm, ALGEBRA_NORM_POW,                      *)
(* ALGEBRA_TRACE_NORM_IN_CARRIER), Library/fieldtheory.ml                    *)
(* (ALGEBRA_TRACE_NORM_BASE, EXTENSION_DEGREE_SIMPLE, EXTENSION_DEGREE_EQ_0, *)
(* MINIMAL_POLYNOMIAL_DEG_LE, FIELD_SIMPLE_ALGEBRAIC_EXTENSION,              *)
(* FINITE_SIMPLE_ALGEBRAIC_EXTENSION, subfield_generated),                   *)
(* Library/ringtheory.ml (subring_generated, polynomial rings,               *)
(* RING_ORDER_UNIQUE_PRIME, ROOTS_OF_UNITY_RING_ORDER,                       *)
(* ROOTS_OF_UNITY_RING_ORDER_DIVISOR), Multivariate/complex_ring.ml          *)
(* (complex_ring, COMPLEX_RING_CLAUSES, COMPLEX_RING_SUM,                    *)
(* FIELD_COMPLEX_RING, INTEGRAL_DOMAIN_COMPLEX_RING, COMPLEX_RING_POW),      *)
(* 100/transcendence.ml (complex_field_clauses).                             *)
(* ========================================================================= *)

