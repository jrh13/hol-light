(* ------------------------------------------------------------------------- *)
(* Part 1, the tensor and polynomial phases of section 4 (generic in the     *)
(* logarithms lg r). The residues t l mod pr (t < pr) are distinct when pr   *)
(* is a prime not dividing l.                                                *)
(* ------------------------------------------------------------------------- *)

let MOD_MULT_PRIME_INJ = prove
 (`!pr l t1 t2.
        prime pr /\ ~(pr divides l) /\ t1 < pr /\ t2 < pr /\
        (t1 * l) MOD pr = (t2 * l) MOD pr
        ==> t1 = t2`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC CONG_IMP_EQ THEN
  EXISTS_TAC `pr:num` THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC CONG_MULT_RCANCEL THEN EXISTS_TAC `l:num` THEN
  ASM_REWRITE_TAC[CONG] THEN
  ONCE_REWRITE_TAC[COPRIME_SYM] THEN ASM_SIMP_TAC[PRIME_COPRIME_EQ]);;

(* ------------------------------------------------------------------------- *)
(* The normalized derivatives of the Feldman basis at the points l/pr are    *)
(* rational.                                                                 *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_BASIS_DERIV_RAT = prove
 (`!h a b m0 pr l.
        a <= h /\ ~(pr = 0)
        ==> ?q. rational q /\
                higher_complex_derivative m0 (feldman_basis h a b)
                  (Cx(&l) / Cx(&pr)) / Cx(&(FACT m0)) = Cx q`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`h:num`; `a:num`; `b:num`; `pr:num`; `l:num`;
                `nproduct(1..h) (\i. l + pr * i)`; `m0:num`]
         FELDMAN_BASIS_DERIV_RATIONAL) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN X_GEN_TAC `i:num` THEN STRIP_TAC THEN
    REWRITE_TAC[divides] THEN
    EXISTS_TAC `nproduct((1..h) DELETE i) (\i. l + pr * i)` THEN
    CONV_TAC SYM_CONV THEN
    MP_TAC(ISPECL [`\i. l + pr * i`; `1..h`; `i:num`] NPRODUCT_DELETE) THEN
    ASM_REWRITE_TAC[FINITE_NUMSEG; IN_NUMSEG];
    ALL_TAC] THEN
  ABBREV_TAC `N = nproduct(1..h) (\i. l + pr * i)` THEN
  SUBGOAL_THEN `~(N = 0)` ASSUME_TAC THENL
   [EXPAND_TAC "N" THEN REWRITE_TAC[NPRODUCT_EQ_0_NUMSEG] THEN
    REWRITE_TAC[ADD_EQ_0; MULT_EQ_0] THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  REWRITE_TAC[COMPLEX_INTEGER] THEN
  DISCH_THEN(X_CHOOSE_THEN `k:real` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `(k:real) / (&pr pow (2 * a + 2 * h * (b + 1)) * &N pow m0)` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC RATIONAL_DIV THEN ASM_SIMP_TAC[RATIONAL_INTEGER] THEN
    SIMP_TAC[RATIONAL_CLOSED];
    ALL_TAC] THEN
  REWRITE_TAC[CX_DIV; CX_MUL; CX_POW] THEN
  FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  SUBGOAL_THEN `~(Cx(&pr) pow (2 * a + 2 * h * (b + 1)) = Cx(&0))` MP_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0; CX_INJ; REAL_OF_NUM_EQ]; ALL_TAC] THEN
  SUBGOAL_THEN `~(Cx(&N) pow m0 = Cx(&0))` MP_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0; CX_INJ; REAL_OF_NUM_EQ]; ALL_TAC] THEN
  SPEC_TAC(`higher_complex_derivative m0 (feldman_basis h a b)
              (Cx(&l) / Cx(&pr)) / Cx(&(FACT m0))`,`x:complex`) THEN
  SPEC_TAC(`Cx(&pr) pow (2 * a + 2 * h * (b + 1))`,`e:complex`) THEN
  SPEC_TAC(`Cx(&N) pow m0`,`f:complex`) THEN
  CONV_TAC COMPLEX_FIELD);;

(* ------------------------------------------------------------------------- *)
(* Regrouping sums over sharp_index by t = mu_n and nu = (mu_1..mu_(n-1)):   *)
(* mu = ext t nu with ext t nu r = if r = n then t else nu r.                *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_CP_LAST = prove
 (`!n L Ln. cartesian_product (1..n-1) (\r. 0..(if r = n then Ln else L)) =
            cartesian_product (1..n-1) (\r. 0..L)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[CARTESIAN_PRODUCT_EQ] THEN DISJ2_TAC THEN
  REWRITE_TAC[IN_NUMSEG] THEN X_GEN_TAC `r:num` THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(r:num = n)` (fun th -> REWRITE_TAC[th]) THEN
  ASM_ARITH_TAC);;

let SHARP_SEC4_EXT_IN_INDEX = prove
 (`!h L0 (Lv:num->num) n t (nu:num->num) a b.
        1 <= n /\ a < h /\ b <= L0 /\ t <= Lv n /\
        nu IN cartesian_product (1..n-1) (\r. 0..Lv r)
        ==> (a,b,(\r. if r = n then t else nu r)) IN sharp_index h L0 Lv n`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[sharp_index; IN_CROSS; IN_ELIM_THM; IN_NUMSEG; LE_0;
              IN_CARTESIAN_PRODUCT; EXTENSIONAL] THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [X_GEN_TAC `x:num` THEN DISCH_TAC THEN COND_CASES_TAC THENL
     [ASM_ARITH_TAC;
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC];
    X_GEN_TAC `i:num` THEN STRIP_TAC THEN COND_CASES_TAC THENL
     [ASM_MESON_TAC[];
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC]]);;

let SHARP_SEC4_RESTRICTION_IN = prove
 (`!n (Lv:num->num) (mu:num->num).
        mu IN cartesian_product (1..n) (\r. 0..Lv r)
        ==> RESTRICTION (1..n-1) mu IN
              cartesian_product (1..n-1) (\r. 0..Lv r) /\
            (1 <= n ==> mu n <= Lv n)`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[RESTRICTION_IN_CARTESIAN_PRODUCT; IN_CARTESIAN_PRODUCT] THEN
  REWRITE_TAC[IN_NUMSEG; LE_0] THEN STRIP_TAC THEN CONJ_TAC THENL
   [X_GEN_TAC `i:num` THEN STRIP_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
    ASM_ARITH_TAC;
    DISCH_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC]);;

let SHARP_SEC4_EXT_RESTRICTION = prove
 (`!n (Lv:num->num) (mu:num->num).
        1 <= n /\ mu IN cartesian_product (1..n) (\r. 0..Lv r)
        ==> (\r. if r = n then mu n else RESTRICTION (1..n-1) mu r) = mu`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[IN_CARTESIAN_PRODUCT; EXTENSIONAL; IN_ELIM_THM; IN_NUMSEG] THEN
  STRIP_TAC THEN REWRITE_TAC[FUN_EQ_THM; RESTRICTION; IN_NUMSEG] THEN
  X_GEN_TAC `r:num` THEN COND_CASES_TAC THEN ASM_REWRITE_TAC[] THEN
  COND_CASES_TAC THEN ASM_REWRITE_TAC[] THEN
  CONV_TAC SYM_CONV THEN FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC);;

let SHARP_SEC4_RESTRICTION_EXT = prove
 (`!n t (nu:num->num) (s:num->num->bool).
        1 <= n /\ nu IN cartesian_product (1..n-1) s
        ==> RESTRICTION (1..n-1) (\r. if r = n then t else nu r) = nu`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[IN_CARTESIAN_PRODUCT; EXTENSIONAL; IN_ELIM_THM; IN_NUMSEG] THEN
  STRIP_TAC THEN REWRITE_TAC[FUN_EQ_THM; RESTRICTION; IN_NUMSEG] THEN
  X_GEN_TAC `r:num` THEN COND_CASES_TAC THENL
   [SUBGOAL_THEN `~(r:num = n)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    CONV_TAC SYM_CONV THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
    ASM_REWRITE_TAC[]]);;

let SHARP_SEC4_INDEX_VSUM_SPLIT = prove
 (`!h L0 (Lv:num->num) n (f:num#num#(num->num)->complex).
        1 <= n
        ==> vsum (sharp_index h L0 Lv n) f =
            vsum (0..Lv n)
             (\t. vsum (cartesian_product (1..n-1) (\r. 0..Lv r))
                   (\nu. vsum ({a | a < h} CROSS (0..L0))
                          (\ab. f(FST ab,SND ab,
                                  (\r. if r = n then t else nu r)))))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `FINITE(cartesian_product (1..n-1) (\r. 0..(Lv:num->num) r))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_CARTESIAN_PRODUCT_FINITE THEN
    REWRITE_TAC[FINITE_NUMSEG];
    ALL_TAC] THEN
  SUBGOAL_THEN `FINITE({a:num | a < h} CROSS (0..L0))` ASSUME_TAC THENL
   [SIMP_TAC[FINITE_CROSS; FINITE_NUMSEG_LT; FINITE_NUMSEG]; ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `vsum ((0..Lv n) CROSS
          (cartesian_product (1..n-1) (\r. 0..(Lv:num->num) r) CROSS
           ({a:num | a < h} CROSS (0..L0))))
         (\x. (f:num#num#(num->num)->complex)
                (FST(SND(SND x)),SND(SND(SND x)),
                 (\r. if r = n then FST x else FST(SND x) r)))` THEN
  CONJ_TAC THENL
   [CONV_TAC SYM_CONV THEN MATCH_MP_TAC VSUM_EQ_GENERAL_INVERSES THEN
    EXISTS_TAC `\x:num#(num->num)#num#num.
                  (FST(SND(SND x)),SND(SND(SND x)),
                   (\r. if r = n then FST x else FST(SND x) r))` THEN
    EXISTS_TAC `\y:num#num#(num->num).
                  (SND(SND y) n,RESTRICTION (1..n-1) (SND(SND y)),
                   FST y,FST(SND y))` THEN
    REWRITE_TAC[] THEN CONJ_TAC THENL
     [REWRITE_TAC[FORALL_PAIR_THM; FST; SND] THEN
      MAP_EVERY X_GEN_TAC [`a:num`; `b:num`; `mu:num->num`] THEN
      REWRITE_TAC[sharp_index; IN_CROSS; IN_ELIM_THM; IN_NUMSEG; LE_0;
                  PAIR_EQ] THEN
      STRIP_TAC THEN
      MP_TAC(SPECL [`n:num`; `Lv:num->num`; `mu:num->num`]
        SHARP_SEC4_RESTRICTION_IN) THEN
      MP_TAC(SPECL [`n:num`; `Lv:num->num`; `mu:num->num`]
        SHARP_SEC4_EXT_RESTRICTION) THEN
      ASM_SIMP_TAC[];
      REWRITE_TAC[FORALL_PAIR_THM; FST; SND; IN_CROSS; PAIR_EQ] THEN
      MAP_EVERY X_GEN_TAC [`t:num`; `nu:num->num`; `a:num`; `b:num`] THEN
      REWRITE_TAC[IN_ELIM_THM; IN_NUMSEG; LE_0] THEN STRIP_TAC THEN
      ASM_SIMP_TAC[SHARP_SEC4_EXT_IN_INDEX] THEN
      MATCH_MP_TAC SHARP_SEC4_RESTRICTION_EXT THEN
      EXISTS_TAC `\r. 0..(Lv:num->num) r` THEN ASM_REWRITE_TAC[]];
    ASM_SIMP_TAC[VSUM_CROSS; FINITE_CROSS; FINITE_NUMSEG] THEN
    REWRITE_TAC[FST; SND]]);;

(* ------------------------------------------------------------------------- *)
(* Step 2 of section 4, the tensor step with complex nodes. For fixed t and  *)
(* m_0 the group sum is sum_nu W(nu) prod_(r<n) Delta(bb_n nu_r - bb_r t;    *)
(* m_r); the nodes bb_n i - bb_r t are distinct in i because bb_n <> 0, so   *)
(* every W(nu) vanishes; W(nu) is sum_ab p(a,b,mu) [D^m0 B_ab](z)/m0! times  *)
(* a nonzero exponential.                                                    *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_ALGTERM_EXT = prove
 (`!n h (p:num#num#(num->num)->real) (bb:num->complex) (lg:num->complex)
    m0 (m':num->num) a b t (nu:num->num) z.
        sharp_algterm n h p bb lg (\i. if i = 0 then m0 else m' i)
          (a,b,(\r. if r = n then t else nu r)) z =
        (Cx(p(a,b,(\r. if r = n then t else nu r))) *
         higher_complex_derivative m0 (feldman_basis h a b) z /
         Cx(&(FACT m0))) *
        cexp(z * vsum(1..n) (\r. Cx(&(if r = n then t else nu r)) * lg r)) *
        cproduct(1..n-1)
          (\r. feldman_delta (m' r) (bb n * Cx(&(nu r)) - bb r * Cx(&t)))`,
  REPEAT GEN_TAC THEN REWRITE_TAC[sharp_algterm; sharp_x] THEN
  SUBGOAL_THEN
   `cproduct(1..n-1)
      (\r. feldman_delta (if r = 0 then m0 else (m':num->num) r)
             ((bb:num->complex) n *
              Cx(&(if r = n then t else (nu:num->num) r)) -
              bb r * Cx(&t))) =
    cproduct(1..n-1)
      (\r. feldman_delta (m' r) (bb n * Cx(&(nu r)) - bb r * Cx(&t)))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC CPRODUCT_EQ THEN REWRITE_TAC[IN_NUMSEG] THEN
    X_GEN_TAC `r:num` THEN STRIP_TAC THEN
    SUBGOAL_THEN `~(r = 0) /\ ~(r:num = n)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    CONV_TAC COMPLEX_RING]);;

let SHARP_SEC4_TENSOR_PHASE = prove
 (`!n h L0 L (p:num#num#(num->num)->real) (bb:num->complex)
    (lg:num->complex) t z m0.
        1 <= n /\ ~(bb n = Cx(&0)) /\
        (!m'. (!r. 1 <= r /\ r <= n - 1 ==> m' r <= L)
              ==> vsum (cartesian_product (1..n-1) (\r. 0..L))
                   (\nu. vsum ({a | a < h} CROSS (0..L0))
                          (\ab. sharp_algterm n h p bb lg
                                  (\i. if i = 0 then m0 else m' i)
                                  (FST ab,SND ab,
                                   (\r. if r = n then t else nu r)) z)) =
                  Cx(&0))
        ==> !nu. nu IN cartesian_product (1..n-1) (\r. 0..L)
                 ==> vsum ({a | a < h} CROSS (0..L0))
                      (\ab. Cx(p(FST ab,SND ab,
                                 (\r. if r = n then t else nu r))) *
                            higher_complex_derivative m0
                              (feldman_basis h (FST ab) (SND ab)) z /
                            Cx(&(FACT m0))) = Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(ISPECL
   [`n - 1`; `L:num`;
    `\r i. (bb:num->complex) n * Cx(&i) - bb r * Cx(&t)`;
    `\nu:num->num.
       vsum ({a | a < h} CROSS (0..L0))
         (\ab. Cx((p:num#num#(num->num)->real)
                    (FST ab,SND ab,(\r. if r = n then t else nu r))) *
               higher_complex_derivative m0
                 (feldman_basis h (FST ab) (SND ab)) z /
               Cx(&(FACT m0))) *
       cexp(z * vsum(1..n)
                  (\r. Cx(&(if r = n then t else nu r)) *
                       (lg:num->complex) r))`]
   FELDMAN_DELTA_TENSOR_SEPARATION) THEN
  REWRITE_TAC[] THEN ANTS_TAC THENL
   [CONJ_TAC THENL
     [REPEAT GEN_TAC THEN STRIP_TAC THEN
      UNDISCH_TAC
       `(bb:num->complex) n * Cx(&i) - bb r * Cx(&t) =
        bb n * Cx(&j) - bb r * Cx(&t)` THEN
      ASM_REWRITE_TAC[COMPLEX_EQ_MUL_LCANCEL; CX_INJ; REAL_OF_NUM_EQ;
        COMPLEX_RING `(b:complex) * x - c = b * y - c <=> b * x = b * y`];
      ALL_TAC] THEN
    X_GEN_TAC `m':num->num` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `m':num->num`) THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(MESON[] `(a:complex) = b ==> a = z ==> b = z`) THEN
    MATCH_MP_TAC VSUM_EQ THEN X_GEN_TAC `nu:num->num` THEN DISCH_TAC THEN
    REWRITE_TAC[SHARP_SEC4_ALGTERM_EXT] THEN
    SIMP_TAC[VSUM_COMPLEX_RMUL; FINITE_CROSS; FINITE_NUMSEG_LT;
             FINITE_NUMSEG] THEN
    REWRITE_TAC[COMPLEX_MUL_ASSOC];
    DISCH_TAC THEN X_GEN_TAC `nu:num->num` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `nu:num->num`) THEN
    ASM_REWRITE_TAC[COMPLEX_ENTIRE; CEXP_NZ]]);;

(* ------------------------------------------------------------------------- *)
(* Step 3 of section 4, multiple zeros. If sum_ab P(a,b) [D^m0               *)
(* B_ab](l/pr)/m0! = 0 for all m0 <= L and all admissible l, then all P(a,b) *)
(* = 0.                                                                      *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_POLY_PHASE = prove
 (`!h L0 L K pr (P:num#num->complex).
        ~(pr = 0) /\
        h * (L0 + 2) <=
        (L + 1) * CARD {l | 1 <= l /\ l <= K /\ ~(pr divides l)} /\
        (!l m0. 1 <= l /\ l <= K /\ ~(pr divides l) /\ m0 <= L
                ==> vsum ({a | a < h} CROSS (0..L0))
                      (\ab. P ab *
                            higher_complex_derivative m0
                              (feldman_basis h (FST ab) (SND ab))
                              (Cx(&l) / Cx(&pr)) /
                            Cx(&(FACT m0))) = Cx(&0))
        ==> !a b. a < h /\ b <= L0 ==> P(a,b) = Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MATCH_MP_TAC FELDMAN_BASIS_MULTIPLE_ZEROS THEN
  MAP_EVERY EXISTS_TAC
   [`L:num`;
    `IMAGE (\l. Cx(&l) / Cx(&pr))
           {l | 1 <= l /\ l <= K /\ ~(pr divides l)}`] THEN
  SUBGOAL_THEN `FINITE {l | 1 <= l /\ l <= K /\ ~(pr divides l)}`
  ASSUME_TAC THENL
   [MATCH_MP_TAC FINITE_SUBSET THEN EXISTS_TAC `1..K` THEN
    REWRITE_TAC[FINITE_NUMSEG; SUBSET; IN_ELIM_THM; IN_NUMSEG] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  ASM_SIMP_TAC[FINITE_IMAGE] THEN CONJ_TAC THENL
   [SUBGOAL_THEN
     `CARD(IMAGE (\l. Cx(&l) / Cx(&pr))
                 {l | 1 <= l /\ l <= K /\ ~(pr divides l)}) =
      CARD {l | 1 <= l /\ l <= K /\ ~(pr divides l)}`
     (fun th -> ASM_REWRITE_TAC[th]) THEN
    MATCH_MP_TAC CARD_IMAGE_INJ THEN ASM_REWRITE_TAC[] THEN
    MAP_EVERY X_GEN_TAC [`x:num`; `y:num`] THEN STRIP_TAC THEN
    UNDISCH_TAC `Cx(&x) / Cx(&pr) = Cx(&y) / Cx(&pr)` THEN
    REWRITE_TAC[GSYM REAL_OF_NUM_EQ; GSYM CX_INJ] THEN
    UNDISCH_TAC `~(pr = 0)` THEN
    REWRITE_TAC[GSYM REAL_OF_NUM_EQ; GSYM CX_INJ] THEN
    CONV_TAC COMPLEX_FIELD;
    ALL_TAC] THEN
  REWRITE_TAC[IMP_CONJ; RIGHT_FORALL_IMP_THM; FORALL_IN_IMAGE] THEN
  REWRITE_TAC[IN_ELIM_THM] THEN X_GEN_TAC `l:num` THEN STRIP_TAC THEN
  X_GEN_TAC `j:num` THEN DISCH_TAC THEN
  FIRST_X_ASSUM(MP_TAC o SPECL [`l:num`; `j:num`]) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC(SPEC `Cx(&(FACT j))` (COMPLEX_RING
   `!c. (a:complex) = c * b ==> b = Cx(&0) ==> a = Cx(&0)`)) THEN
  REWRITE_TAC[LAMBDA_PAIR; PAIR] THEN
  MP_TAC(ISPECL
   [`\i:num#num w. (P:num#num->complex) i *
                   feldman_basis h (FST i) (SND i) w`;
    `(:complex)`; `{a:num | a < h} CROSS (0..L0)`; `j:num`;
    `Cx(&l) / Cx(&pr)`] HIGHER_COMPLEX_DERIVATIVE_VSUM) THEN
  SIMP_TAC[FINITE_CROSS; FINITE_NUMSEG_LT; FINITE_NUMSEG; OPEN_UNIV; IN_UNIV;
           HOLOMORPHIC_ON_MUL; HOLOMORPHIC_ON_CONST; ETA_AX;
           HOLOMORPHIC_ON_FELDMAN_BASIS] THEN
  DISCH_THEN SUBST1_TAC THEN
  SIMP_TAC[GSYM VSUM_COMPLEX_LMUL; FINITE_CROSS; FINITE_NUMSEG_LT;
           FINITE_NUMSEG] THEN
  MATCH_MP_TAC VSUM_EQ THEN X_GEN_TAC `ab:num#num` THEN DISCH_TAC THEN
  REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`feldman_basis h (FST(ab:num#num)) (SND ab)`;
                 `(P:num#num->complex) ab`; `(:complex)`; `j:num`;
                 `Cx(&l) / Cx(&pr)`] HIGHER_COMPLEX_DERIVATIVE_LMUL) THEN
  REWRITE_TAC[OPEN_UNIV; IN_UNIV; HOLOMORPHIC_ON_FELDMAN_BASIS] THEN
  DISCH_THEN SUBST1_TAC THEN
  MP_TAC(SPEC `j:num` FACT_NZ) THEN
  REWRITE_TAC[GSYM REAL_OF_NUM_EQ; GSYM CX_INJ] THEN
  CONV_TAC COMPLEX_FIELD);;

(* ------------------------------------------------------------------------- *)
(* Part 2, the Kummer phase of section 4 over a subfield s of C, with the    *)
(* subring of C generated by s and the radicals z r (r IN ix). A sum of      *)
(* R-multiples of w is an R-multiple of w for any subring R of C; c times a  *)
(* monomial in the z r lies in the generated subring for c in s.             *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBRING_VSUM_MULTIPLE = prove
 (`!(k:A->bool) (g:A->complex) w R.
        R subring_of complex_ring /\ FINITE k /\
        (!x. x IN k ==> ?c. c IN R /\ g x = c * w)
        ==> ?c. c IN R /\ vsum k g = c * w`,
  REPEAT GEN_TAC THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
    (CONJUNCTS_THEN2 ASSUME_TAC MP_TAC)) THEN
  GEN_REWRITE_TAC (LAND_CONV o BINDER_CONV) [RIGHT_IMP_EXISTS_THM] THEN
  REWRITE_TAC[SKOLEM_THM] THEN
  DISCH_THEN(X_CHOOSE_TAC `cf:A->complex`) THEN
  EXISTS_TAC `vsum k (cf:A->complex)` THEN CONJ_TAC THENL
   [MATCH_MP_TAC COMPLEX_SUBRING_VSUM THEN ASM_SIMP_TAC[];
    ASM_SIMP_TAC[GSYM VSUM_COMPLEX_RMUL] THEN
    MATCH_MP_TAC VSUM_EQ THEN ASM_SIMP_TAC[]]);;

let COMPLEX_SUBRING_GENERATED_MONOMIAL = prove
 (`!s (z:num->complex) ix c f.
        FINITE ix /\ c IN s
        ==> c * cproduct ix (\r. z r pow f r) IN
            ring_carrier(subring_generated complex_ring (s UNION IMAGE z ix))`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `R = ring_carrier(subring_generated complex_ring
                                 (s UNION IMAGE (z:num->complex) ix))` THEN
  SUBGOAL_THEN `!x. x IN s UNION IMAGE (z:num->complex) ix ==> x IN R`
  (LABEL_TAC "inc") THENL
   [EXPAND_TAC "R" THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC SUBRING_GENERATED_INC THEN
    ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES; SUBSET_UNIV];
    ALL_TAC] THEN
  SUBGOAL_THEN `R subring_of complex_ring` ASSUME_TAC THENL
   [EXPAND_TAC "R" THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED]; ALL_TAC] THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBRING_CLOSED) THEN
  SUBGOAL_THEN `(c:complex) IN R` ASSUME_TAC THENL
   [USE_THEN "inc" MATCH_MP_TAC THEN ASM_REWRITE_TAC[IN_UNION]; ALL_TAC] THEN
  SUBGOAL_THEN `cproduct ix (\r. (z:num->complex) r pow f r) IN R`
  ASSUME_TAC THENL
   [MATCH_MP_TAC COMPLEX_SUBRING_CPRODUCT THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `r:num` THEN DISCH_TAC THEN
    SUBGOAL_THEN `(z:num->complex) r IN R` (fun th -> ASM_SIMP_TAC[th]) THEN
    USE_THEN "inc" MATCH_MP_TAC THEN
    REWRITE_TAC[IN_UNION; IN_IMAGE] THEN ASM_MESON_TAC[];
    ASM_SIMP_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* The Delta values at elements of a complex subfield: Delta(z; k) =         *)
(* prod_(j=1..k) (z + j) / k! lies in s whenever z does.                     *)
(* ------------------------------------------------------------------------- *)

let SHARP_FELDMAN_DELTA_SUBFIELD = prove
 (`!s k z. s subfield_of complex_ring /\ z IN s ==> feldman_delta k z IN s`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  SUBGOAL_THEN `!j. Cx(&j) IN s` ASSUME_TAC THENL
   [INDUCT_TAC THEN ASM_REWRITE_TAC[GSYM REAL_OF_NUM_SUC; CX_ADD] THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[feldman_delta] THEN
  SUBGOAL_THEN `cproduct(1..k) (\j. z + Cx(&j)) IN s` ASSUME_TAC THENL
   [MATCH_MP_TAC COMPLEX_SUBRING_CPRODUCT THEN
    REWRITE_TAC[FINITE_NUMSEG] THEN
    CONJ_TAC THENL [ASM_MESON_TAC[COMPLEX_SUBFIELD_OF]; ASM_SIMP_TAC[]];
    ASM_SIMP_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* The field of section 4: the subfield of C generated by the numbers        *)
(* cexp(lg r) and the coefficients bb r (r = 1..n). It is a subfield of C    *)
(* containing the rationals, every cexp(lg r) and every bb r.                *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_CEXP_SUBFIELD = prove
 (`!n (lg:num->complex) (bb:num->complex).
        (ring_carrier(subfield_generated complex_ring
                          (IMAGE (\r. cexp(lg r)) (1..n) UNION
                           IMAGE bb (1..n)))) subfield_of complex_ring /\
        (!q. rational q
             ==> Cx q IN ring_carrier(subfield_generated complex_ring
                          (IMAGE (\r. cexp(lg r)) (1..n) UNION
                           IMAGE bb (1..n)))) /\
        (!r. 1 <= r /\ r <= n
             ==> cexp(lg r) IN ring_carrier(subfield_generated complex_ring
                          (IMAGE (\r. cexp(lg r)) (1..n) UNION
                           IMAGE bb (1..n)))) /\
        (!r. r IN 1..n
             ==> bb r IN ring_carrier(subfield_generated complex_ring
                          (IMAGE (\r. cexp(lg r)) (1..n) UNION
                           IMAGE bb (1..n))))`,
  REPEAT GEN_TAC THEN REPEAT CONJ_TAC THENL
   [SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING];
    GEN_TAC THEN DISCH_TAC THEN MATCH_MP_TAC BRIDGE_NF_SUBFIELD_RATIONAL THEN
    ASM_REWRITE_TAC[];
    X_GEN_TAC `r:num` THEN STRIP_TAC THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; SUBSET_UNIV; IN_UNION; IN_IMAGE] THEN
    DISJ1_TAC THEN EXISTS_TAC `r:num` THEN ASM_REWRITE_TAC[IN_NUMSEG];
    X_GEN_TAC `r:num` THEN DISCH_TAC THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_INC THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; SUBSET_UNIV; IN_UNION; IN_IMAGE] THEN
    DISJ2_TAC THEN EXISTS_TAC `r:num` THEN ASM_REWRITE_TAC[]]);;

(* ------------------------------------------------------------------------- *)
(* Kummer separation over a subfield s of C: if sum_(t <= Ln) c_t w0^(t l) = *)
(* 0 with c_t in the subring of C generated by s and the w r (r = 1..M), w r *)
(* and w0 pr-th roots of non-zero al r, al0 IN s, Ln < pr, pr not dividing l *)
(* and no relation al0 = prod al_r^jj_r g^pr (g IN s) holds, then all c_t    *)
(* vanish.                                                                   *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_KUMMER_SEPARATION_ALG = prove
 (`!pr s (al:num->complex) (w:num->complex) M al0 w0 Ln l (c:num->complex).
        prime pr /\ s subfield_of complex_ring /\
        (!r. 1 <= r /\ r <= M
             ==> al r IN s /\ ~(al r = Cx(&0)) /\ w r pow pr = al r) /\
        al0 IN s /\ ~(al0 = Cx(&0)) /\ w0 pow pr = al0 /\
        ~(?jj g. (!r. jj r < pr) /\ g IN s /\
                 al0 = cproduct(1..M) (\r. al r pow jj r) * g pow pr) /\
        Ln < pr /\ ~(pr divides l) /\
        (!t. t <= Ln ==> c t IN ring_carrier(subring_generated complex_ring
                                               (s UNION IMAGE w (1..M)))) /\
        vsum(0..Ln) (\t. c t * w0 pow (t * l)) = Cx(&0)
        ==> !t. t <= Ln ==> c t = Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(pr = 0)` ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_NZ]; ALL_TAC] THEN
  SUBGOAL_THEN `s subring_of complex_ring` ASSUME_TAC THENL
   [ASM_MESON_TAC[COMPLEX_SUBFIELD_OF]; ALL_TAC] THEN
  ABBREV_TAC `R = ring_carrier(subring_generated complex_ring
                                 (s UNION IMAGE (w:num->complex) (1..M)))` THEN
  SUBGOAL_THEN `R subring_of complex_ring /\ (!k. (al0:complex) pow k IN R)`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "R" THEN REWRITE_TAC[SUBRING_SUBRING_GENERATED] THEN
    GEN_TAC THEN MATCH_MP_TAC SUBRING_GENERATED_INC THEN
    ASM_SIMP_TAC[COMPLEX_RING_CLAUSES; SUBSET_UNIV; IN_UNION;
                 COMPLEX_SUBRING_CLOSED];
    ALL_TAC] THEN
  ABBREV_TAC
   `E = \j. vsum(0..Ln)
              (\t. if (t * l) MOD pr = j
                   then (c:num->complex) t * al0 pow ((t * l) DIV pr)
                   else Cx(&0))` THEN
  MP_TAC(ISPECL [`pr:num`; `s:complex->bool`; `al:num->complex`;
                 `w:num->complex`; `M:num`; `al0:complex`; `w0:complex`;
                 `E:num->complex`] KUMMER_COMPLEX_INDEPENDENT) THEN
  ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
   [CONJ_TAC THENL
     [X_GEN_TAC `j:num` THEN DISCH_TAC THEN EXPAND_TAC "E" THEN
      REWRITE_TAC[] THEN MATCH_MP_TAC COMPLEX_SUBRING_VSUM THEN
      ASM_REWRITE_TAC[FINITE_NUMSEG; IN_NUMSEG; LE_0] THEN
      X_GEN_TAC `t:num` THEN DISCH_TAC THEN COND_CASES_TAC THEN
      ASM_SIMP_TAC[COMPLEX_SUBRING_CLOSED];
      ALL_TAC] THEN
    EXPAND_TAC "E" THEN REWRITE_TAC[] THEN
    SIMP_TAC[GSYM VSUM_COMPLEX_RMUL; FINITE_NUMSEG] THEN
    GEN_REWRITE_TAC LAND_CONV [VSUM_SWAP_NUMSEG] THEN
    TRANS_TAC EQ_TRANS
     `vsum(0..Ln) (\t. (c:num->complex) t * w0 pow (t * l))` THEN
    CONJ_TAC THENL [ALL_TAC; ASM_REWRITE_TAC[]] THEN
    MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `t:num` THEN STRIP_TAC THEN
    REWRITE_TAC[] THEN
    TRANS_TAC EQ_TRANS
     `vsum(0..pr-1) (\j. if j = (t * l) MOD pr
                         then (c:num->complex) t * al0 pow ((t * l) DIV pr) *
                              w0 pow ((t * l) MOD pr)
                         else Cx(&0))` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
      REWRITE_TAC[] THEN ASM_CASES_TAC `j = (t * l) MOD pr` THEN
      ASM_REWRITE_TAC[COMPLEX_MUL_LZERO; COMPLEX_MUL_ASSOC];
      ALL_TAC] THEN
    REWRITE_TAC[GSYM COMPLEX_VEC_0; VSUM_DELTA; IN_NUMSEG; LE_0] THEN
    SUBGOAL_THEN `(t * l) MOD pr <= pr - 1` (fun th -> REWRITE_TAC[th]) THENL
     [MP_TAC(SPECL [`t * l`; `pr:num`] MOD_LT_EQ) THEN
      UNDISCH_TAC `~(pr = 0)` THEN ARITH_TAC;
      ALL_TAC] THEN
    MP_TAC(ISPECL [`w0:complex`; `pr:num`; `t * l`] COMPLEX_POW_DIV_MOD) THEN
    ASM_REWRITE_TAC[] THEN DISCH_THEN SUBST1_TAC THEN REFL_TAC;
    ALL_TAC] THEN
  DISCH_THEN(fun th -> X_GEN_TAC `t0:num` THEN DISCH_TAC THEN
                       MP_TAC(SPEC `(t0 * l) MOD pr` th)) THEN
  ASM_REWRITE_TAC[MOD_LT_EQ] THEN EXPAND_TAC "E" THEN REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `vsum(0..Ln) (\t. if (t * l) MOD pr = (t0 * l) MOD pr
                     then (c:num->complex) t * al0 pow ((t * l) DIV pr)
                     else Cx(&0)) =
    vsum(0..Ln) (\t. if t = t0 then c t0 * al0 pow ((t0 * l) DIV pr)
                     else Cx(&0))`
  SUBST1_TAC THENL
   [MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `t:num` THEN STRIP_TAC THEN
    REWRITE_TAC[] THEN ASM_CASES_TAC `t:num = t0` THEN ASM_REWRITE_TAC[] THEN
    COND_CASES_TAC THEN REWRITE_TAC[] THEN
    UNDISCH_TAC `~(t:num = t0)` THEN MATCH_MP_TAC(TAUT `a ==> ~a ==> b`) THEN
    MATCH_MP_TAC MOD_MULT_PRIME_INJ THEN
    MAP_EVERY EXISTS_TAC [`pr:num`; `l:num`] THEN ASM_REWRITE_TAC[] THEN
    MAP_EVERY UNDISCH_TAC [`t <= Ln`; `t0 <= Ln`; `Ln < pr`] THEN ARITH_TAC;
    ALL_TAC] THEN
  REWRITE_TAC[GSYM COMPLEX_VEC_0; VSUM_DELTA; IN_NUMSEG; LE_0] THEN
  ASM_REWRITE_TAC[COMPLEX_VEC_0; COMPLEX_ENTIRE; COMPLEX_POW_EQ_0]);;

(* ------------------------------------------------------------------------- *)
(* The terms of sharp_algterm at l/pr: the exponential is a product of       *)
(* powers of the radicals cexp(lg r / pr), the normalized basis derivatives  *)
(* are rational and the Delta products lie in s (the coefficients bb r do).  *)
(* Hence every term is c w_n^(mu_n l) with c in the subring of C generated   *)
(* by s and the w r (r = 1..n-1), w r = cexp(lg r / pr), for any complex     *)
(* subfield s containing the bb r.                                           *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_ALGTERM_SUBRING = prove
 (`!s n h (p:num#num#(num->num)->real) (bb:num->complex) (lg:num->complex)
    m a b (mu:num->num) pr l.
        s subfield_of complex_ring /\ (!q. rational q ==> Cx q IN s) /\
        1 <= n /\ ~(pr = 0) /\ a <= h /\ integer(p(a,b,mu)) /\
        (!r. r IN 1..n ==> bb r IN s)
        ==> ?c. c IN ring_carrier(subring_generated complex_ring
                       (s UNION IMAGE (\r. cexp(lg r / Cx(&pr))) (1..n-1))) /\
                sharp_algterm n h p bb lg m (a,b,mu) (Cx(&l) / Cx(&pr)) =
                c * cexp(lg n / Cx(&pr)) pow (mu n * l)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[sharp_algterm] THEN
  MP_TAC(SPECL [`h:num`; `a:num`; `b:num`; `(m:num->num) 0`; `pr:num`;
                `l:num`] SHARP_SEC4_BASIS_DERIV_RAT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `q:real`
    (CONJUNCTS_THEN2 ASSUME_TAC SUBST1_TAC)) THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBFIELD_CLOSED) THEN
  SUBGOAL_THEN
   `cproduct(1..n-1)
      (\r. feldman_delta ((m:num->num) r) (sharp_x n bb mu r)) IN s`
  ASSUME_TAC THENL
   [MATCH_MP_TAC COMPLEX_SUBRING_CPRODUCT THEN
    CONJ_TAC THENL [ASM_MESON_TAC[COMPLEX_SUBFIELD_OF]; ALL_TAC] THEN
    REWRITE_TAC[FINITE_NUMSEG; IN_NUMSEG] THEN X_GEN_TAC `r:num` THEN
    STRIP_TAC THEN MATCH_MP_TAC SHARP_FELDMAN_DELTA_SUBFIELD THEN
    ASM_REWRITE_TAC[sharp_x] THEN
    SUBGOAL_THEN
     `(bb:num->complex) r IN s /\ bb n IN s /\
      Cx(&((mu:num->num) r)) IN s /\ Cx(&(mu n)) IN s`
    STRIP_ASSUME_TAC THENL
     [REPEAT CONJ_TAC THEN FIRST_ASSUM MATCH_MP_TAC THEN
      REWRITE_TAC[IN_NUMSEG; RATIONAL_NUM] THEN ASM_ARITH_TAC;
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `1 <= pr` ASSUME_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  SIMP_TAC[CEXP_LINEAR_COMBINATION_RATIONAL; FINITE_NUMSEG;
           ASSUME `1 <= pr`] THEN
  MP_TAC(ISPECL [`\r. cexp((lg:num->complex) r / Cx(&pr)) pow
                      ((mu:num->num) r * l)`;
                 `1`; `n:num`] CPRODUCT_CLAUSES_RIGHT) THEN
  ANTS_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[] THEN
  EXISTS_TAC
   `(Cx((p:num#num#(num->num)->real)(a,b,mu) * q) *
     cproduct(1..n-1)
       (\r. feldman_delta ((m:num->num) r) (sharp_x n bb mu r))) *
    cproduct(1..n-1)
      (\r. cexp((lg:num->complex) r / Cx(&pr)) pow ((mu:num->num) r * l))` THEN
  CONJ_TAC THENL
   [MP_TAC(ISPECL [`s:complex->bool`; `\r. cexp((lg:num->complex) r /
                                                 Cx(&pr))`;
                   `1..n-1`;
                   `Cx((p:num#num#(num->num)->real)(a,b,mu) * q) *
                    cproduct(1..n-1)
                      (\r. feldman_delta ((m:num->num) r)
                                         (sharp_x n bb mu r))`;
                   `\r. (mu:num->num) r * l`]
      COMPLEX_SUBRING_GENERATED_MONOMIAL) THEN
    REWRITE_TAC[FINITE_NUMSEG] THEN DISCH_THEN MATCH_MP_TAC THEN
    SUBGOAL_THEN `Cx((p:num#num#(num->num)->real)(a,b,mu) * q) IN s`
    ASSUME_TAC THENL
     [FIRST_ASSUM MATCH_MP_TAC THEN
      MATCH_MP_TAC RATIONAL_MUL THEN ASM_SIMP_TAC[RATIONAL_INTEGER];
      ASM_SIMP_TAC[]];
    REWRITE_TAC[CX_MUL; COMPLEX_MUL_AC]]);;

(* ------------------------------------------------------------------------- *)
(* The group sums: for fixed mu_n = t the sum over nu and (a,b) is c w_n^(t  *)
(* l) with c in the same subring.                                            *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_GROUP_SUBRING = prove
 (`!s n h L0 L Ln (p:num#num#(num->num)->real) (bb:num->complex)
    (lg:num->complex) m pr l t.
        s subfield_of complex_ring /\ (!q. rational q ==> Cx q IN s) /\
        1 <= n /\ ~(pr = 0) /\ t <= Ln /\
        (!r. r IN 1..n ==> bb r IN s) /\
        (!x. x IN sharp_index h L0 (\r. if r = n then Ln else L) n
             ==> integer(p x))
        ==> ?c. c IN ring_carrier(subring_generated complex_ring
                       (s UNION IMAGE (\r. cexp(lg r / Cx(&pr))) (1..n-1))) /\
                vsum (cartesian_product (1..n-1) (\r. 0..L))
                 (\nu. vsum ({a | a < h} CROSS (0..L0))
                        (\ab. sharp_algterm n h p bb lg m
                                (FST ab,SND ab,
                                 (\r. if r = n then t else nu r))
                                (Cx(&l) / Cx(&pr)))) =
                c * cexp(lg n / Cx(&pr)) pow (t * l)`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC COMPLEX_SUBRING_VSUM_MULTIPLE THEN
  SIMP_TAC[FINITE_CARTESIAN_PRODUCT_FINITE; FINITE_NUMSEG;
           SUBRING_SUBRING_GENERATED] THEN
  X_GEN_TAC `nu:num->num` THEN DISCH_TAC THEN
  MATCH_MP_TAC COMPLEX_SUBRING_VSUM_MULTIPLE THEN
  SIMP_TAC[FINITE_CROSS; FINITE_NUMSEG_LT; FINITE_NUMSEG;
           SUBRING_SUBRING_GENERATED] THEN
  REWRITE_TAC[FORALL_PAIR_THM; IN_CROSS; IN_ELIM_THM; IN_NUMSEG; LE_0;
              FST; SND] THEN
  MAP_EVERY X_GEN_TAC [`a:num`; `b:num`] THEN STRIP_TAC THEN
  MP_TAC(SPECL [`s:complex->bool`; `n:num`; `h:num`;
                `p:num#num#(num->num)->real`; `bb:num->complex`;
                `lg:num->complex`; `m:num->num`; `a:num`; `b:num`;
                `\r. if r = n then t else (nu:num->num) r`;
                `pr:num`; `l:num`] SHARP_SEC4_ALGTERM_SUBRING) THEN
  REWRITE_TAC[] THEN DISCH_THEN MATCH_MP_TAC THEN
  ASM_SIMP_TAC[LT_IMP_LE] THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
  MATCH_MP_TAC SHARP_SEC4_EXT_IN_INDEX THEN
  ASM_REWRITE_TAC[SHARP_SEC4_CP_LAST]);;

(* ------------------------------------------------------------------------- *)
(* Step 1 of section 4, the Kummer step over a subfield s of C containing    *)
(* the rationals, the numbers cexp(lg r) and the coefficients bb r. Grouping *)
(* sharp_alg(l/pr) by mu_n = t gives sum_t c_t w_n^(t l) with c_t in the     *)
(* subring of C generated by s and the radicals w_r; without a relation      *)
(* every group sum vanishes.                                                 *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4_KUMMER_PHASE_FIELD = prove
 (`!s n h L0 L Ln (p:num#num#(num->num)->real) (bb:num->complex)
    (lg:num->complex) pr m l.
        s subfield_of complex_ring /\ (!q. rational q ==> Cx q IN s) /\
        (!r. 1 <= r /\ r <= n ==> cexp(lg r) IN s) /\
        1 <= n /\ prime pr /\ Ln < pr /\ ~(pr divides l) /\
        (!r. r IN 1..n ==> bb r IN s) /\
        (!x. x IN sharp_index h L0 (\r. if r = n then Ln else L) n
             ==> integer(p x)) /\
        ~(?jj g. (!r. jj r < pr) /\ g IN s /\
                 cexp(lg n) =
                 cproduct(1..n-1) (\r. cexp(lg r) pow jj r) * g pow pr) /\
        sharp_alg n h L0 (\r. if r = n then Ln else L) p bb lg m
          (Cx(&l) / Cx(&pr)) = Cx(&0)
        ==> !t. t <= Ln
                ==> vsum (cartesian_product (1..n-1) (\r. 0..L))
                     (\nu. vsum ({a | a < h} CROSS (0..L0))
                            (\ab. sharp_algterm n h p bb lg m
                                    (FST ab,SND ab,
                                     (\r. if r = n then t else nu r))
                                    (Cx(&l) / Cx(&pr)))) = Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(pr = 0)` ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_NZ]; ALL_TAC] THEN
  MP_TAC(GEN `t:num` (SPECL
   [`s:complex->bool`; `n:num`; `h:num`; `L0:num`; `L:num`; `Ln:num`;
    `p:num#num#(num->num)->real`; `bb:num->complex`; `lg:num->complex`;
    `m:num->num`; `pr:num`; `l:num`; `t:num`]
   SHARP_SEC4_GROUP_SUBRING)) THEN
  ASM_REWRITE_TAC[] THEN REWRITE_TAC[RIGHT_IMP_EXISTS_THM; SKOLEM_THM] THEN
  DISCH_THEN(X_CHOOSE_TAC `c:num->complex`) THEN
  SUBGOAL_THEN
   `vsum(0..Ln) (\t. (c:num->complex) t *
                     cexp((lg:num->complex) n / Cx(&pr)) pow (t * l)) =
    Cx(&0)`
  ASSUME_TAC THENL
   [UNDISCH_TAC
     `sharp_alg n h L0 (\r. if r = n then Ln else L) p bb lg m
        (Cx(&l) / Cx(&pr)) = Cx(&0)` THEN
    REWRITE_TAC[sharp_alg] THEN
    ASM_SIMP_TAC[SHARP_SEC4_INDEX_VSUM_SPLIT] THEN
    REWRITE_TAC[SHARP_SEC4_CP_LAST] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
    MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `t:num` THEN STRIP_TAC THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`pr:num`; `s:complex->bool`;
                 `\r. cexp((lg:num->complex) r)`;
                 `\r. cexp((lg:num->complex) r / Cx(&pr))`; `n - 1`;
                 `cexp((lg:num->complex) n)`;
                 `cexp((lg:num->complex) n / Cx(&pr))`;
                 `Ln:num`; `l:num`; `c:num->complex`]
    SHARP_SEC4_KUMMER_SEPARATION_ALG) THEN
  REWRITE_TAC[] THEN ANTS_TAC THENL
   [SUBGOAL_THEN `1 <= pr` ASSUME_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    ASM_SIMP_TAC[CEXP_NZ; CEXP_DIV_POW; LE_REFL] THEN
    X_GEN_TAC `r:num` THEN STRIP_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  DISCH_TAC THEN X_GEN_TAC `t:num` THEN DISCH_TAC THEN
  ASM_SIMP_TAC[COMPLEX_MUL_LZERO]);;

(* ------------------------------------------------------------------------- *)
(* Section 4 of Sharpening I with complex coefficients: vanishing of         *)
(* sharp_alg at the points l/pr for all m with m_i <= L forces a             *)
(* multiplicative relation in the field generated by the numbers cexp(lg r)  *)
(* and the coefficients bb r.                                                *)
(* ------------------------------------------------------------------------- *)

let SHARP_SEC4 = prove
 (`!n h L0 L Ln (p:num#num#(num->num)->real) (bb:num->complex)
    (lg:num->complex) K pr.
     1 <= n /\ 1 <= h /\ prime pr /\ Ln < pr /\ ~(bb n = Cx(&0)) /\
     (!x. x IN sharp_index h L0 (\r. if r = n then Ln else L) n
          ==> integer(p x)) /\
     ~(!x. x IN sharp_index h L0 (\r. if r = n then Ln else L) n
           ==> p x = &0) /\
     h * (L0 + 2) <=
     (L + 1) * CARD {l | 1 <= l /\ l <= K /\ ~(pr divides l)} /\
     (!m l. (!i. i < n ==> m i <= L) /\ 1 <= l /\ l <= K /\ ~(pr divides l)
            ==> sharp_alg n h L0 (\r. if r = n then Ln else L) p bb lg m
                  (Cx(&l) / Cx(&pr)) = Cx(&0))
     ==> ?jj g. (!r. jj r < pr) /\
                g IN ring_carrier(subfield_generated complex_ring
                                   (IMAGE (\r. cexp(lg r)) (1..n) UNION
                                    IMAGE bb (1..n))) /\
                cexp(lg n) =
                cproduct(1..n-1) (\r. cexp(lg r) pow jj r) * g pow pr`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(SPECL [`n:num`; `lg:num->complex`; `bb:num->complex`]
    SHARP_SEC4_CEXP_SUBFIELD) THEN
  SPEC_TAC(`ring_carrier(subfield_generated complex_ring
                          (IMAGE (\r. cexp((lg:num->complex) r)) (1..n) UNION
                           IMAGE (bb:num->complex) (1..n)))`,
           `s:complex->bool`) THEN
  GEN_TAC THEN STRIP_TAC THEN
  GEN_REWRITE_TAC I [TAUT `p <=> ~ ~p`] THEN DISCH_TAC THEN
  SUBGOAL_THEN `~(pr = 0)` ASSUME_TAC THENL
   [ASM_MESON_TAC[PRIME_IMP_NZ]; ALL_TAC] THEN
  SUBGOAL_THEN
   `!t nu l m0.
      t <= Ln /\ nu IN cartesian_product (1..n-1) (\r. 0..L) /\
      1 <= l /\ l <= K /\ ~(pr divides l) /\ m0 <= L
      ==> vsum ({a | a < h} CROSS (0..L0))
           (\ab. Cx((p:num#num#(num->num)->real)
                      (FST ab,SND ab,(\r. if r = n then t else nu r))) *
                 higher_complex_derivative m0
                   (feldman_basis h (FST ab) (SND ab))
                   (Cx(&l) / Cx(&pr)) /
                 Cx(&(FACT m0))) = Cx(&0)`
  ASSUME_TAC THENL
   [REPEAT GEN_TAC THEN STRIP_TAC THEN
    MP_TAC(SPECL [`n:num`; `h:num`; `L0:num`; `L:num`;
                  `p:num#num#(num->num)->real`; `bb:num->complex`;
                  `lg:num->complex`; `t:num`; `Cx(&l) / Cx(&pr)`; `m0:num`]
           SHARP_SEC4_TENSOR_PHASE) THEN
    ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
     [X_GEN_TAC `m':num->num` THEN DISCH_TAC THEN
      MP_TAC(SPECL [`s:complex->bool`; `n:num`; `h:num`; `L0:num`; `L:num`;
                    `Ln:num`; `p:num#num#(num->num)->real`;
                    `bb:num->complex`; `lg:num->complex`; `pr:num`;
                    `\i. if i = 0 then m0 else (m':num->num) i`; `l:num`]
             SHARP_SEC4_KUMMER_PHASE_FIELD) THEN
      ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
       [FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
        X_GEN_TAC `i:num` THEN DISCH_TAC THEN REWRITE_TAC[] THEN
        COND_CASES_TAC THEN ASM_REWRITE_TAC[] THEN
        FIRST_X_ASSUM MATCH_MP_TAC THEN
        MAP_EVERY UNDISCH_TAC [`i < n`; `~(i = 0)`] THEN ARITH_TAC;
        DISCH_THEN(MP_TAC o SPEC `t:num`) THEN ASM_REWRITE_TAC[]];
      DISCH_THEN(MP_TAC o SPEC `nu:num->num`) THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  UNDISCH_TAC
   `~(!x. x IN sharp_index h L0 (\r. if r = n then Ln else L) n
          ==> (p:num#num#(num->num)->real) x = &0)` THEN
  REWRITE_TAC[FORALL_PAIR_THM] THEN
  MAP_EVERY X_GEN_TAC [`a:num`; `b:num`; `mu:num->num`] THEN
  REWRITE_TAC[sharp_index; IN_CROSS; IN_ELIM_THM; IN_NUMSEG; LE_0] THEN
  STRIP_TAC THEN
  MP_TAC(SPECL [`h:num`; `L0:num`; `L:num`; `K:num`; `pr:num`;
                `\ab:num#num. Cx((p:num#num#(num->num)->real)
                                   (FST ab,SND ab,mu))`]
         SHARP_SEC4_POLY_PHASE) THEN
  ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
   [MAP_EVERY X_GEN_TAC [`l:num`; `m0:num`] THEN STRIP_TAC THEN
    MP_TAC(SPECL [`n:num`; `\r:num. if r = n then Ln else L:num`;
                  `mu:num->num`]
      SHARP_SEC4_EXT_RESTRICTION) THEN
    MP_TAC(SPECL [`n:num`; `\r:num. if r = n then Ln else L:num`;
                  `mu:num->num`]
      SHARP_SEC4_RESTRICTION_IN) THEN
    ASM_REWRITE_TAC[SHARP_SEC4_CP_LAST] THEN STRIP_TAC THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPECL
      [`(mu:num->num) n`; `RESTRICTION (1..n-1) (mu:num->num)`;
       `l:num`; `m0:num`]) THEN
    ASM_REWRITE_TAC[];
    DISCH_THEN(MP_TAC o SPECL [`a:num`; `b:num`]) THEN
    ASM_REWRITE_TAC[CX_INJ; FST; SND]]);;

(* ------------------------------------------------------------------------- *)
(* Rational generators do not change a generated subfield of C: with         *)
(* rational coefficients bb r = Cx(b r) the field of SHARP_SEC4 is the       *)
(* subfield generated by the numbers cexp(lg r) alone.                       *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBFIELD_GENERATED_UNION_RATIONAL = prove
 (`!s t. (!z. z IN t ==> ?q. rational q /\ z = Cx q)
         ==> subfield_generated complex_ring (s UNION t) =
             subfield_generated complex_ring s`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SUBFIELDS_GENERATED_EQ THEN
  X_GEN_TAC `k:complex->bool` THEN DISCH_TAC THEN
  REWRITE_TAC[UNION_OVER_INTER; UNION_SUBSET] THEN
  SUBGOAL_THEN `ring_carrier complex_ring INTER t SUBSET k`
   (fun th -> REWRITE_TAC[th]) THEN
  REWRITE_TAC[SUBSET; IN_INTER] THEN
  ASM_MESON_TAC[RATIONAL_IN_COMPLEX_SUBFIELD]);;
