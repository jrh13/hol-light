(* ========================================================================= *)
(* Sharpening I: section 4 of the core (the Kummer step over the field of    *)
(* the alphas and the coefficients).                                         *)
(*                                                                           *)
(* Purpose: Baker, Sharpening I (Acta Arith. 21, 1972), sec. 4, and A        *)
(* central theorem in transcendence theory (1973), Lemma 3 over the field    *)
(* K = Q(alphas, betas), for the auxiliary function with complex             *)
(* coefficients bb r and any complex numbers lg r (neither the numbers       *)
(* cexp(lg r) nor the bb r need to be algebraic: Kummer theory runs over any *)
(* subfield of C). If the counterpart sharp_alg vanishes at all l/pr         *)
(* (1 <= l <= K, pr a prime not dividing l) for all derivative orders        *)
(* m_i <= L (i < n), then either the integer coefficients p vanish or        *)
(* cexp(lg n) = prod_(r<n) cexp(lg r)^jj_r g^pr with g in the subfield s of  *)
(* C generated by the numbers cexp(lg r) and the coefficients bb r. For      *)
(* integer (or rational) coefficients this is the field of the cexp(lg r)    *)
(* alone (COMPLEX_SUBFIELD_GENERATED_UNION_RATIONAL).                        *)
(*                                                                           *)
(* Method: three phases. The Kummer phase (Part 2): the term sharp_algterm   *)
(* at l/pr is c w_n^(mu_n l) with c in the subring of C generated by s and   *)
(* the radicals w_r = cexp(lg r / pr), r < n; the Feldman values are         *)
(* rational (SHARP_SEC4_BASIS_DERIV_RAT) and the Delta products              *)
(* prod_r Delta(x_r; m_r), x_r = bb n mu_r - bb r mu_n, lie in s             *)
(* (SHARP_FELDMAN_DELTA_SUBFIELD); the exponents t l are reduced modulo pr   *)
(* and SHARP_SEC4_KUMMER_SEPARATION_ALG (KUMMER_COMPLEX_INDEPENDENT)         *)
(* separates mu_n = t. The tensor phase (Part 1): the complex nodes          *)
(* bb n i - bb r t are distinct in i because bb n <> 0                       *)
(* (FELDMAN_DELTA_TENSOR_SEPARATION). The multiple zero count of the Feldman *)
(* basis (SHARP_SEC4_POLY_PHASE) ends the proof.                             *)
(*                                                                           *)
(* Main results: SHARP_SEC4; its Kummer phase SHARP_SEC4_KUMMER_PHASE_FIELD  *)
(* (over any subfield s of C containing the numbers cexp(lg r) and bb r) and *)
(* SHARP_SEC4_KUMMER_SEPARATION_ALG; SHARP_SEC4_TENSOR_PHASE,                *)
(* SHARP_SEC4_POLY_PHASE, SHARP_SEC4_BASIS_DERIV_RAT,                        *)
(* SHARP_SEC4_INDEX_VSUM_SPLIT, MOD_MULT_PRIME_INJ and the index helpers     *)
(* SHARP_SEC4_CP_LAST, SHARP_SEC4_EXT_IN_INDEX, SHARP_SEC4_RESTRICTION_IN,   *)
(* SHARP_SEC4_EXT_RESTRICTION, SHARP_SEC4_RESTRICTION_EXT;                   *)
(* SHARP_SEC4_ALGTERM_SUBRING, SHARP_SEC4_GROUP_SUBRING,                     *)
(* SHARP_SEC4_ALGTERM_EXT, SHARP_SEC4_CEXP_SUBFIELD (the field of the alphas *)
(* and betas), SHARP_FELDMAN_DELTA_SUBFIELD; COMPLEX_SUBRING_VSUM_MULTIPLE   *)
(* (sums of R-multiples of w, R a subring of C),                             *)
(* COMPLEX_SUBRING_GENERATED_MONOMIAL (monomials in the subring of C         *)
(* generated by s and finitely many numbers),                                *)
(* COMPLEX_SUBFIELD_GENERATED_UNION_RATIONAL (rational generators do not     *)
(* change a generated subfield of C).                                        *)
(*                                                                           *)
(* Uses: Baker/sharp_defs.ml (sharp_alg, sharp_algterm, sharp_index,         *)
(* sharp_x), Baker/kummer.ml (KUMMER_COMPLEX_INDEPENDENT,                    *)
(* COMPLEX_POW_DIV_MOD, COMPLEX_SUBFIELD_CLOSED), Baker/sharp_poly.ml        *)
(* (FELDMAN_DELTA_TENSOR_SEPARATION, FELDMAN_BASIS_MULTIPLE_ZEROS,           *)
(* FELDMAN_BASIS_DERIV_RATIONAL), Baker/aux_arith.ml                         *)
(* (CEXP_LINEAR_COMBINATION_RATIONAL, CEXP_DIV_POW), Baker/extrap.ml         *)
(* (HIGHER_COMPLEX_DERIVATIVE_VSUM), Baker/delta.ml (feldman_basis,          *)
(* feldman_delta, HOLOMORPHIC_ON_FELDMAN_BASIS,                              *)
(* HIGHER_COMPLEX_DERIVATIVE_LMUL), Baker/lemmas.ml (COMPLEX_SUBFIELD_OF,    *)
(* COMPLEX_SUBRING_CLOSED, COMPLEX_SUBRING_VSUM, COMPLEX_SUBRING_CPRODUCT,   *)
(* VSUM_CROSS), sets.ml (FINITE_CARTESIAN_PRODUCT_FINITE),                   *)
(* Baker/ant_bridge_complex.ml (BRIDGE_NF_SUBFIELD_RATIONAL,                 *)
(* RATIONAL_IN_COMPLEX_SUBFIELD), Library/fieldtheory.ml                     *)
(* (SUBFIELD_GENERATED_INC, SUBFIELD_SUBFIELD_GENERATED,                     *)
(* SUBFIELDS_GENERATED_EQ), Library/ringtheory.ml (subring_generated,        *)
(* SUBRING_SUBRING_GENERATED, SUBRING_GENERATED_INC), Library/floor.ml       *)
(* (RATIONAL_NUM, RATIONAL_INTEGER, RATIONAL_MUL),                           *)
(* Multivariate/complex_ring.ml (COMPLEX_RING_CLAUSES, FIELD_COMPLEX_RING).  *)
(* ========================================================================= *)

