   `&1 <= &(2 * n + 4) * (&pr + &1) /\
    &(2 * n + 4) * (&pr + &1) <= &(2 * n + 4) * (cB * g0 pow K1 + &1)`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_1_MUL THEN
      REWRITE_TAC[REAL_OF_NUM_LE; REAL_OF_NUM_ADD] THEN ARITH_TAC;
      MATCH_MP_TAC REAL_LE_LMUL THEN REWRITE_TAC[REAL_POS] THEN
      ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  FIRST_X_ASSUM(MP_TAC o SPEC `N - 1` o check (fun th ->
    is_forall(concl th) && free_in `N:num` (concl th))) THEN
  ANTS_TAC THENL [UNDISCH_TAC `1 <= N` THEN ARITH_TAC; ALL_TAC] THEN
  DISCH_THEN(MP_TAC o SPECL
   [`s:complex->bool`; `lg':num->complex`; `a':num->num->real`;
    `dd':num->num`; `bb':num->real`;
    `exp(log A / &2 + (&4 * &D pow 2 * (&n + &1)) * g0)`;
    `(&(2 * n + 4) * (&pr + &1)) * B`; `g0:real`]) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[LOG_EXP] THEN
    REWRITE_TAC[ASSUME
     `vsum(1..n+1) (\r. Cx((bb':num->real) r) * lg' r) =
      vsum(1..n+1) (\r. Cx((bb:num->real) r) * lg r)`] THEN
    ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[ASSUME `&4 * &D pow 2 * (&n + &1) = c`] THEN
    REPEAT CONJ_TAC THENL
     [REWRITE_TAC[GSYM(MATCH_MP REAL_OF_NUM_SUB (ASSUME `1 <= N`))] THEN
      MAP_EVERY UNDISCH_TAC
       [`log A <= &N`; `&4 * c * g0 < log A`; `&1 <= c * g0`] THEN
      REAL_ARITH_TAC;
      REWRITE_TAC[REAL_EXP_MONO_LE] THEN
      MAP_EVERY UNDISCH_TAC [`&1 <= log A`; `&1 <= c * g0`] THEN
      REAL_ARITH_TAC;
      TRANS_TAC REAL_LE_TRANS `B:real` THEN ASM_REWRITE_TAC[] THEN
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[]];
    REWRITE_TAC[LOG_EXP] THEN
    REWRITE_TAC[ASSUME
     `vsum(1..n+1) (\r. Cx((bb':num->real) r) * lg' r) =
      vsum(1..n+1) (\r. Cx((bb:num->real) r) * lg r)`] THEN
    DISCH_TAC] THEN
  UNDISCH_TAC
   `norm(vsum(1..n+1) (\r. Cx((bb:num->real) r) * lg r)) <
    exp(--(CC * g0 pow K * log A * log B))` THEN
  REWRITE_TAC[REAL_NOT_LT] THEN
  FIRST_X_ASSUM(MATCH_MP_TAC o MATCH_MP (REAL_ARITH
   `(b:real) <= x ==> a <= b ==> a <= x`)) THEN
  REWRITE_TAC[REAL_EXP_MONO_LE; REAL_LE_NEG2] THEN
  MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[ASSUME `&4 * &D pow 2 * (&n + &1) = c`] THEN
  MATCH_MP_TAC SHARP_DESCENT_LOGPROD THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL
   [UNDISCH_TAC `&1 <= c * g0` THEN REAL_ARITH_TAC; ALL_TAC] THEN
  TRANS_TAC REAL_LE_TRANS `(&(2 * n + 4) * (cB * g0 pow K1 + &1)) pow 3` THEN
  ASM_REWRITE_TAC[] THEN MATCH_MP_TAC REAL_POW_LE2 THEN
  ASM_REWRITE_TAC[] THEN
  UNDISCH_TAC `&1 <= &(2 * n + 4) * (&pr + &1)` THEN REAL_ARITH_TAC);;

