let SHARP_DESCENT_HEIGHT_ARITH = prove
 (`!d e N p x LA g0 lb lR ld l1.
        &1 <= d /\ &0 <= e /\ e <= d /\ &1 <= N /\ &4 * d pow 2 <= p /\
        &0 <= x /\ x <= d /\ &1 <= g0 /\ &0 <= LA /\
        &0 <= lb /\ &0 <= lR /\ &0 <= ld /\
        p * lb <= e * ld /\ ld <= LA + N * p * g0 /\
        p * lR <= l1 + N * p * (d + g0) /\ l1 <= d + LA
        ==> x * (&1 + lb + lR) <= LA / &2 + (&4 * d pow 2 * (N + &1)) * g0`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `&0 < p` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LTE_TRANS THEN EXISTS_TAC `&4 * d pow 2` THEN
    ASM_REWRITE_TAC[] THEN MATCH_MP_TAC REAL_LT_MUL THEN
    CONJ_TAC THENL [REAL_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC REAL_POW_LT THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  TRANS_TAC REAL_LE_TRANS `d * (&1 + lb + lR)` THEN CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  FIRST_ASSUM(fun th ->
    ONCE_REWRITE_TAC[GSYM(MATCH_MP REAL_LE_LMUL_EQ th)]) THEN
  SUBGOAL_THEN `d <= d * d /\ &0 <= d` STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL [ALL_TAC; ASM_REAL_ARITH_TAC] THEN
    GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_RID] THEN
    MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(d:real) * (p * lb) <= d * (d * (LA + N * p * g0))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
    TRANS_TAC REAL_LE_TRANS `(e:real) * ld` THEN ASM_REWRITE_TAC[] THEN
    TRANS_TAC REAL_LE_TRANS `(d:real) * ld` THEN CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[];
      MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `(d:real) * (p * lR) <= d * (d + LA + N * p * (d + g0))`
  ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= LA * (p - &2 * (d * d + d))` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REWRITE_TAC[REAL_SUB_LE] THEN
    UNDISCH_TAC `&4 * d pow 2 <= p` THEN UNDISCH_TAC `(d:real) <= d * d` THEN
    REWRITE_TAC[REAL_POW_2] THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= N * p * g0 /\ &0 <= p * g0 /\ &1 <= p * g0`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THEN
    REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
    TRY(ASM_REAL_ARITH_TAC) THEN
    MATCH_MP_TAC REAL_LE_1_MUL THEN CONJ_TAC THEN TRY(ASM_REAL_ARITH_TAC) THEN
    UNDISCH_TAC `&4 * d pow 2 <= p` THEN UNDISCH_TAC `(d:real) <= d * d` THEN
    REWRITE_TAC[REAL_POW_2] THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `&0 <= (d * d - d) * N * p * g0 /\ &0 <= (d * d - d) * p * g0 /\
    &0 <= d * d * N * p * (g0 - &1) /\ &0 <= d * p * (g0 - &1) /\
    &0 <= d * d * (p * g0 - &1) /\ &0 <= d * d * N * p * g0 /\
    &0 <= d * d * p * g0`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THEN
    REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  UNDISCH_TAC `(d:real) * (p * lb) <= d * (d * (LA + N * p * g0))` THEN
  UNDISCH_TAC `(d:real) * (p * lR) <= d * (d + LA + N * p * (d + g0))` THEN
  UNDISCH_TAC `&0 <= LA * (p - &2 * (d * d + d))` THEN
  REWRITE_TAC[REAL_POW_2] THEN ASM_REAL_ARITH_TAC);;

let SHARP_DESCENT_GPOW = prove
 (`!n (lg:num->complex) (jj:num->num) g pr.
        cexp(lg(n + 1)) = cproduct(1..n) (\r. cexp(lg r) pow jj r) * g pow pr
        ==> cexp(vsum(1..n+1) (\r. Cx(if r = n + 1 then &1 else --(&(jj r))) *
                                   lg r)) = g pow pr`,
  REPEAT GEN_TAC THEN REWRITE_TAC[GSYM ADD1] THEN DISCH_TAC THEN
  REWRITE_TAC[VSUM_CLAUSES_NUMSEG; ARITH_RULE `1 <= SUC n`] THEN
  SUBGOAL_THEN
   `vsum(1..n) (\r. Cx(if r = SUC n then &1 else --(&((jj:num->num) r))) *
                    (lg:num->complex) r) =
    vsum(1..n) (\r. Cx(--(&(jj r))) * lg r)`
  SUBST1_TAC THENL
   [MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `r:num` THEN STRIP_TAC THEN
    REWRITE_TAC[] THEN
    SUBGOAL_THEN `~(r = SUC n)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  REWRITE_TAC[CEXP_ADD; COMPLEX_MUL_LID] THEN
  SIMP_TAC[CEXP_VSUM; FINITE_NUMSEG] THEN
  REWRITE_TAC[CX_NEG; COMPLEX_MUL_LNEG; CEXP_NEG; CEXP_N] THEN
  SIMP_TAC[CPRODUCT_INV; FINITE_NUMSEG] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN
   `~(cproduct(1..n) (\r. cexp((lg:num->complex) r) pow (jj:num->num) r) =
      Cx(&0))`
  MP_TAC THENL
   [DISCH_TAC THEN
    MP_TAC(SPEC `(lg:num->complex)(SUC n)` CEXP_NZ) THEN
    ASM_REWRITE_TAC[COMPLEX_MUL_LZERO];
    MATCH_ACCEPT_TAC(COMPLEX_FIELD
     `!P z. ~(P = Cx(&0)) ==> inv P * P * z = z`)]);;

let SHARP_DESCENT_PRODUCT_BOUND = prove
 (`!n (f:num->real) X Y (jj:num->num) pr.
        &1 <= Y /\ &0 <= X /\ f(n + 1) = X /\
        (!r. r IN 1..n ==> f r = Y) /\ (!r. jj r < pr)
        ==> product(1..n+1) (\r. f r pow (if r = n + 1 then 1 else jj r)) <=
            Y pow (n * pr) * X`,
  REPEAT GEN_TAC THEN REWRITE_TAC[GSYM ADD1] THEN STRIP_TAC THEN
  REWRITE_TAC[PRODUCT_CLAUSES_NUMSEG; ARITH_RULE `1 <= SUC n`] THEN
  ASM_REWRITE_TAC[REAL_POW_1] THEN MATCH_MP_TAC REAL_LE_RMUL THEN
  ASM_REWRITE_TAC[] THEN
  TRANS_TAC REAL_LE_TRANS `product(1..n) (\r:num. (Y:real) pow pr)` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC PRODUCT_LE_NUMSEG THEN X_GEN_TAC `r:num` THEN STRIP_TAC THEN
    SUBGOAL_THEN `~(r = SUC n) /\ (f:num->real) r = Y` STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[IN_NUMSEG];
      ALL_TAC] THEN
    ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
     [MATCH_MP_TAC REAL_POW_LE THEN ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC LT_IMP_LE THEN ASM_REWRITE_TAC[]];
    REWRITE_TAC[PRODUCT_CONST_NUMSEG; ADD_SUB; REAL_POW_POW] THEN
    REWRITE_TAC[MULT_SYM; REAL_LE_REFL]]);;

let SHARP_DESCENT_HEIGHT_ALG = prove
 (`!n D s (lg:num->complex) (a:num->num->real) (dd:num->num) A g0 pr
    (jj:num->num) g.
        1 <= n /\ 1 <= D /\ FINITE s /\ (!z. z IN s ==> algebraic_number z) /\
        extension_degree (subfield_generated complex_ring {Cx(&0)},
                          subfield_generated complex_ring s) I <= D /\
        (!r. r IN 1..n+1
             ==> cexp(lg r) IN
                 ring_carrier(subfield_generated complex_ring s) /\
                 dd r <= D) /\
        &1 <= g0 /\ exp(&1) <= A /\
        sharp_algdata (n+1) lg a dd (\r. if r = n + 1 then A else exp g0) /\
        4 * D EXP 2 <= pr /\ (!r. jj r < pr) /\
        g IN ring_carrier(subfield_generated complex_ring s) /\
        cexp(lg(n+1)) = cproduct(1..n) (\r. cexp(lg r) pow jj r) * g pow pr
        ==> ?dx ax. 1 <= dx /\ dx <= D /\
                    (!j. integer(ax j) /\
                         abs(ax j) <= exp(log A / &2 +
                                          (&4 * &D pow 2 * (&n + &1)) * g0)) /\
                    ~(ax dx = &0) /\
                    vsum(0..dx) (\j. Cx(ax j) * g pow j) = Cx(&0)`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC
   `E = extension_degree (subfield_generated complex_ring {Cx(&0)},
                          subfield_generated complex_ring s) I` THEN
  SUBGOAL_THEN `1 <= pr` ASSUME_TAC THENL
   [MATCH_MP_TAC LE_TRANS THEN EXISTS_TAC `4 * D EXP 2` THEN
    ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC(ARITH_RULE `1 <= x ==> 1 <= 4 * x`) THEN
    REWRITE_TAC[ARITH_RULE `1 <= x <=> ~(x = 0)`; EXP_EQ_0] THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= log A /\ &0 < A /\ &1 <= exp g0` STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [SUBST1_TAC(SYM(SPEC `&1` LOG_EXP)) THEN MATCH_MP_TAC LOG_MONO_LE_IMP THEN
      ASM_REWRITE_TAC[REAL_EXP_POS_LT];
      MP_TAC(SPEC `&1` REAL_EXP_POS_LT) THEN ASM_REAL_ARITH_TAC;
      MP_TAC(SPEC `g0:real` REAL_EXP_LE_X) THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  RULE_ASSUM_TAC(BETA_RULE o REWRITE_RULE[sharp_algdata]) THEN
  MP_TAC(ISPECL [`s:complex->bool`; `n + 1`; `lg:num->complex`;
                 `a:num->num->real`; `dd:num->num`;
                 `\r. if r = n + 1 then A else exp g0`; `D:num`;
                 `\r. if r = n + 1 then &1 else --(&((jj:num->num) r))`;
                 `\r. if r = n + 1 then 1 else (jj:num->num) r`]
    SHARP_NFBOUND_CEXP_VSUM) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN X_GEN_TAC `r:num` THEN DISCH_TAC THEN
    ASM_SIMP_TAC[] THEN COND_CASES_TAC THEN
    SIMP_TAC[INTEGER_CLOSED; REAL_ABS_NEG; REAL_ABS_NUM];
    ALL_TAC] THEN
  BETA_TAC THEN
  MP_TAC(SPECL [`n:num`; `lg:num->complex`; `jj:num->num`; `g:complex`;
                `pr:num`] SHARP_DESCENT_GPOW) THEN
  ANTS_TAC THENL [FIRST_ASSUM ACCEPT_TAC; DISCH_THEN SUBST1_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `den:real` (CONJUNCTS_THEN2 ASSUME_TAC
    (STRIP_ASSUME_TAC o GEN_REWRITE_RULE I [sharp_nfbound]))) THEN
  SUBGOAL_THEN `den <= exp g0 pow (n * pr) * A` ASSUME_TAC THENL
   [FIRST_X_ASSUM(MATCH_MP_TAC o MATCH_MP (REAL_ARITH
     `(x:real) <= y ==> y <= z ==> x <= z`)) THEN
    MATCH_MP_TAC SHARP_DESCENT_PRODUCT_BOUND THEN ASM_REWRITE_TAC[] THEN
    CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    X_GEN_TAC `r:num` THEN REWRITE_TAC[IN_NUMSEG] THEN STRIP_TAC THEN
    SUBGOAL_THEN `~(r = n + 1)` (fun th -> REWRITE_TAC[th]) THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`s:complex->bool`; `g:complex`; `den:real`; `pr:num`]
    COMPLEX_ROOT_DENOMINATOR) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `b:real` STRIP_ASSUME_TAC) THEN
  ABBREV_TAC
   `R = exp((log((&1 + &D) * A) + &n * &pr * (&D + g0)) / &pr)` THEN
  SUBGOAL_THEN `&0 < &pr /\ &1 <= &1 + &D /\ &1 + &D <= exp(&D)`
  STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LT; REAL_EXP_LE_X] THEN
    CONJ_TAC THENL [ASM_ARITH_TAC; REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= (&1 + &D) * A` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_REWRITE_TAC[] THEN
    MP_TAC(SPEC `&1` REAL_EXP_LE_X) THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= log((&1 + &D) * A)` ASSUME_TAC THENL
   [MATCH_MP_TAC LOG_POS THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= &n * &pr * (&D + g0)` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
    MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= R` ASSUME_TAC THENL
   [EXPAND_TAC "R" THEN GEN_REWRITE_TAC LAND_CONV [GSYM REAL_EXP_0] THEN
    REWRITE_TAC[REAL_EXP_MONO_LE] THEN
    MATCH_MP_TAC REAL_LE_DIV THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!h. h IN complex_embeddings(subfield_generated complex_ring s)
        ==> norm((h:complex->complex) g) <= R`
  ASSUME_TAC THENL
   [X_GEN_TAC `h:complex->complex` THEN DISCH_TAC THEN
    MATCH_MP_TAC REAL_POW_LE2_REV THEN EXISTS_TAC `pr:num` THEN
    CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[GSYM COMPLEX_NORM_POW] THEN
    SUBGOAL_THEN `(h:complex->complex) g pow pr = h(g pow pr)` SUBST1_TAC THENL
     [FIRST_ASSUM(MP_TAC o MATCH_MP SHARP_NFBOUND_EMBEDDING) THEN
      DISCH_THEN(MP_TAC o SPECL [`g:complex`; `pr:num`] o CONJUNCT1 o
        CONJUNCT2) THEN
      ASM_SIMP_TAC[];
      ALL_TAC] THEN
    TRANS_TAC REAL_LE_TRANS
     `product(1..n+1) (\r. ((&1 + &D) * (if r = n + 1 then A else exp g0))
                           pow (if r = n + 1 then 1 else (jj:num->num) r))` THEN
    CONJ_TAC THENL [ASM_SIMP_TAC[]; ALL_TAC] THEN
    TRANS_TAC REAL_LE_TRANS
     `((&1 + &D) * exp g0) pow (n * pr) * ((&1 + &D) * A)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SHARP_DESCENT_PRODUCT_BOUND THEN
      REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
       [MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_REWRITE_TAC[];
        ASM_REAL_ARITH_TAC;
        X_GEN_TAC `r:num` THEN REWRITE_TAC[IN_NUMSEG] THEN STRIP_TAC THEN
        SUBGOAL_THEN `~(r = n + 1)` (fun th -> REWRITE_TAC[th]) THEN
        ASM_ARITH_TAC;
        ASM_REWRITE_TAC[]];
      ALL_TAC] THEN
    EXPAND_TAC "R" THEN REWRITE_TAC[GSYM REAL_EXP_N] THEN
    SUBGOAL_THEN
     `&pr * (log((&1 + &D) * A) + &n * &pr * (&D + g0)) / &pr =
      &(n * pr) * (&D + g0) + log((&1 + &D) * A)`
    SUBST1_TAC THENL
     [REWRITE_TAC[GSYM REAL_OF_NUM_MUL] THEN
      UNDISCH_TAC `&0 < &pr` THEN CONV_TAC REAL_FIELD;
      ALL_TAC] THEN
    REWRITE_TAC[REAL_EXP_ADD] THEN
    SUBGOAL_THEN `exp(log((&1 + &D) * A)) = (&1 + &D) * A` SUBST1_TAC THENL
     [MATCH_MP_TAC EXP_LOG THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC REAL_LE_RMUL THEN
    CONJ_TAC THENL [ALL_TAC; ASM_REAL_ARITH_TAC] THEN
    REWRITE_TAC[REAL_EXP_N] THEN MATCH_MP_TAC REAL_POW_LE2 THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[REAL_EXP_ADD] THEN MATCH_MP_TAC REAL_LE_RMUL THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`s:complex->bool`; `g:complex`; `b:real`; `R:real`]
    COMPLEX_SUBFIELD_ELEMENT_POLY) THEN
  ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `dx:num` THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `ax:num->real` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  X_GEN_TAC `j:num` THEN
  TRANS_TAC REAL_LE_TRANS `(&2 * b * R) pow dx` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `&0 < &2 * b * R` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LT_MUL THEN CONJ_TAC THENL [REAL_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC REAL_LT_MUL THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  FIRST_ASSUM(fun th ->
    GEN_REWRITE_TAC (LAND_CONV o LAND_CONV) [GSYM(MATCH_MP EXP_LOG th)]) THEN
  REWRITE_TAC[GSYM REAL_EXP_N; REAL_EXP_MONO_LE] THEN
  SUBGOAL_THEN `log(&2 * b * R) = log(&2) + log b + log R` SUBST1_TAC THENL
   [SUBGOAL_THEN `&0 < b /\ &0 < R` STRIP_ASSUME_TAC THENL
     [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    ASM_SIMP_TAC[LOG_MUL; REAL_LT_MUL; REAL_ARITH `&0 < &2`];
    ALL_TAC] THEN
  TRANS_TAC REAL_LE_TRANS `&dx * (&1 + log b + log R)` THEN CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_LMUL THEN REWRITE_TAC[REAL_POS] THEN
    MP_TAC LOG_2_LE_1 THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  MATCH_MP_TAC SHARP_DESCENT_HEIGHT_ARITH THEN
  MAP_EVERY EXISTS_TAC
