let SHARP_BAKER_ALGEBRAIC = prove
 (`!n d. 1 <= n ==> ?C K. sharp_bound_property_alg n d C K`,
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `d = 0` THENL
   [MAP_EVERY EXISTS_TAC [`&0`; `0`] THEN
    FIRST_X_ASSUM SUBST_ALL_TAC THEN
    REWRITE_TAC[sharp_bound_property_alg; sharp_algdata] THEN
    REPEAT STRIP_TAC THEN
    SUBGOAL_THEN `n IN 1..n` ASSUME_TAC THENL
     [REWRITE_TAC[IN_NUMSEG] THEN ASM_ARITH_TAC; ALL_TAC] THEN
    SUBGOAL_THEN `1 <= (dd:num->num) n /\ dd n <= 0` MP_TAC THENL
     [ASM_MESON_TAC[]; ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `1 <= d /\ 1 <= d EXP n /\ d <= d EXP n` STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [ASM_ARITH_TAC;
      REWRITE_TAC[ARITH_RULE `1 <= x <=> ~(x = 0)`; EXP_EQ_0] THEN
      ASM_REWRITE_TAC[];
      MP_TAC(SPECL [`d:num`; `1`; `n:num`] LE_EXP) THEN
      ASM_REWRITE_TAC[EXP_1] THEN DISCH_THEN SUBST1_TAC THEN ASM_ARITH_TAC];
    ALL_TAC] THEN
  MP_TAC(SPECL [`n:num`; `d EXP n`] SHARP_DESCENT_ALG_EXT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `CC:real` (X_CHOOSE_THEN `K:num`
    (LABEL_TAC "ext"))) THEN
  MAP_EVERY EXISTS_TAC [`CC:real`; `K:num`] THEN
  REWRITE_TAC[sharp_bound_property_alg] THEN
  MAP_EVERY X_GEN_TAC
   [`lg:num->complex`; `a:num->num->real`; `dd:num->num`; `bb:num->real`;
    `A:real`; `B:real`; `g0:real`] THEN
  STRIP_TAC THEN
  USE_THEN "ext" (MP_TAC o SPECL
   [`IMAGE (\r. cexp((lg:num->complex) r)) (1..n)`;
    `\r. if r = 1 then ii * Cx pi else (lg:num->complex)(r - 1)`;
    `\r. if r = 1 then (\j. if j <= 1 then &1 else &0)
         else (a:num->num->real)(r - 1)`;
    `\r. if r = 1 then 1 else (dd:num->num)(r - 1)`;
    `\r. if r = 1 then &0 else (bb:num->real)(r - 1)`;
    `A:real`; `B:real`; `g0:real`]) THEN
  SUBGOAL_THEN
   `vsum(1..n+1) (\r. Cx(if r = 1 then &0 else (bb:num->real)(r - 1)) *
                      (if r = 1 then ii * Cx pi
                       else (lg:num->complex)(r - 1))) =
    vsum(1..n) (\r. Cx(bb r) * lg r)`
  (fun th -> BETA_TAC THEN REWRITE_TAC[th]) THENL
   [MP_TAC(BETA_RULE(ISPECL [`n:num`; `lg:num->complex`;
      `\r. Cx((bb:num->real) r)`; `ii * Cx pi`] SHARP_SHIFT_VSUM)) THEN
    DISCH_THEN(SUBST1_TAC o SYM) THEN MATCH_MP_TAC VSUM_EQ_NUMSEG THEN
    X_GEN_TAC `r:num` THEN STRIP_TAC THEN REWRITE_TAC[] THEN
    ASM_CASES_TAC `r = 1` THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
  RULE_ASSUM_TAC(BETA_RULE o REWRITE_RULE[sharp_algdata]) THEN
  SUBGOAL_THEN `&1 <= exp g0` ASSUME_TAC THENL
   [MP_TAC(SPEC `g0:real` REAL_EXP_LE_X) THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  REPEAT CONJ_TAC THENL
   [SIMP_TAC[FINITE_IMAGE; FINITE_NUMSEG];
    REWRITE_TAC[FORALL_IN_IMAGE] THEN X_GEN_TAC `r:num` THEN DISCH_TAC THEN
    REWRITE_TAC[ALGEBRAIC_NUMBER_EXPLICIT] THEN
    MAP_EVERY EXISTS_TAC [`(dd:num->num) r`; `(a:num->num->real) r`] THEN
    ASM_SIMP_TAC[];
    TRANS_TAC LE_TRANS `nproduct(1..n) (dd:num->num)` THEN CONJ_TAC THENL
     [MATCH_MP_TAC COMPLEX_SUBFIELD_GENERATED_DEGREE THEN
      EXISTS_TAC `a:num->num->real` THEN ASM_SIMP_TAC[];
      TRANS_TAC LE_TRANS `nproduct(1..n) (\r:num. d)` THEN CONJ_TAC THENL
       [MATCH_MP_TAC NPRODUCT_LE_NUMSEG THEN REPEAT STRIP_TAC THEN
        REWRITE_TAC[] THEN ASM_MESON_TAC[IN_NUMSEG];
        REWRITE_TAC[NPRODUCT_CONST_NUMSEG; ADD_SUB; LE_REFL]]];
    REWRITE_TAC[sharp_algdata] THEN BETA_TAC THEN
    X_GEN_TAC `q:num` THEN DISCH_TAC THEN
    ASM_CASES_TAC `q = 1` THENL
     [ASM_REWRITE_TAC[LE_REFL; ARITH_RULE `1 <= 1`] THEN
      SUBGOAL_THEN `~(1 = n + 1)` (fun th -> REWRITE_TAC[th]) THENL
       [ASM_ARITH_TAC; ASM_REWRITE_TAC[]] THEN
      CONJ_TAC THENL
       [GEN_TAC THEN COND_CASES_TAC THEN
        REWRITE_TAC[INTEGER_CLOSED; REAL_ABS_NUM] THEN ASM_REAL_ARITH_TAC;
        ALL_TAC] THEN
      SIMP_TAC[VSUM_CLAUSES_LEFT; LE_0; ADD_CLAUSES; VSUM_SING_NUMSEG] THEN
      REWRITE_TAC[ARITH_RULE `0 <= 1 /\ 1 <= 1`; CEXP_II_PI; complex_pow;
                  COMPLEX_POW_1; REAL_OF_NUM_EQ; ARITH_EQ] THEN
      CONV_TAC COMPLEX_RING;
      ALL_TAC] THEN
    SUBGOAL_THEN `(q - 1) IN 1..n /\ (q = n + 1 <=> q - 1 = n)`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `q IN 1..n+1` THEN UNDISCH_TAC `~(q = 1)` THEN
      REWRITE_TAC[IN_NUMSEG] THEN ARITH_TAC;
      ALL_TAC] THEN
    SUBGOAL_THEN
     `1 <= (dd:num->num)(q - 1) /\
      &1 <= (if q - 1 = n then A else exp g0) /\
      (!j. integer((a:num->num->real) (q - 1) j) /\
           abs(a (q - 1) j) <= (if q - 1 = n then A else exp g0)) /\
      ~(a (q - 1) (dd(q - 1)) = &0) /\
      vsum(0..dd(q - 1)) (\j. Cx(a (q - 1) j) *
                              cexp((lg:num->complex)(q - 1)) pow j) =
      Cx(&0)`
    STRIP_ASSUME_TAC THENL
     [FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
        is_forall(concl th) && free_in `a:num->num->real` (concl th))) THEN
      ASM_REWRITE_TAC[];
      ASM_REWRITE_TAC[]];
    X_GEN_TAC `q:num` THEN DISCH_TAC THEN ASM_CASES_TAC `q = 1` THENL
     [ASM_REWRITE_TAC[INTEGER_CLOSED; REAL_ABS_NUM; CEXP_II_PI] THEN
      REWRITE_TAC[IM_MUL_II; RE_CX; REAL_LE_REFL] THEN
      REPEAT CONJ_TAC THENL
       [REWRITE_TAC[GSYM CX_NEG] THEN
        MATCH_MP_TAC BRIDGE_NF_SUBFIELD_RATIONAL THEN
        SIMP_TAC[RATIONAL_CLOSED];
        MP_TAC PI_POS THEN REAL_ARITH_TAC;
        ASM_REAL_ARITH_TAC];
      ALL_TAC] THEN
    SUBGOAL_THEN `(q - 1) IN 1..n /\ (q = n + 1 <=> q - 1 = n)`
    STRIP_ASSUME_TAC THENL
     [UNDISCH_TAC `q IN 1..n+1` THEN UNDISCH_TAC `~(q = 1)` THEN
      REWRITE_TAC[IN_NUMSEG] THEN ARITH_TAC;
      ALL_TAC] THEN
    SUBGOAL_THEN
     `(dd:num->num)(q - 1) <= d /\ --pi < Im((lg:num->complex)(q - 1)) /\
      Im(lg(q - 1)) <= pi /\ integer((bb:num->real)(q - 1)) /\
      abs(bb(q - 1)) <= B`
    STRIP_ASSUME_TAC THENL
     [FIRST_X_ASSUM(MATCH_MP_TAC o check (fun th ->
        is_forall(concl th) && free_in `bb:num->real` (concl th))) THEN
      ASM_REWRITE_TAC[];
      ASM_REWRITE_TAC[]] THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
      REWRITE_TAC[in_complex_ring; IN_IMAGE] THEN
      EXISTS_TAC `q - 1` THEN ASM_REWRITE_TAC[];
      ASM_ARITH_TAC]]);;
