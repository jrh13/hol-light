(* ========================================================================= *)
(* Sharpening I: the tools of both descents and the descent for integer      *)
(* coefficients (Baker, A sharpening of the bounds for linear forms in       *)
(* logarithms I, Acta Arith. 21 (1972) 117-129, end of sec. 4).              *)
(*                                                                           *)
(* Purpose: (a) the tools shared by the two descents (this file and          *)
(* Baker/sharpc_descent.ml): a Kummer relation cexp(lg(n+1)) = prod_r        *)
(* cexp(lg r)^jj_r g^pr with g in a field F gives g a polynomial of degree   *)
(* <= [F:Q] and height exp(log A / 2 + 4 D^2 (n+1) g0)                       *)
(* (SHARP_DESCENT_HEIGHT_ALG, by COMPLEX_ROOT_DENOMINATOR and                *)
(* COMPLEX_SUBFIELD_ELEMENT_POLY), and lg(n+1) = sum_r cc_r lg r + pr clog g *)
(* with integers |cc_r| <= (2n+3) pr (SHARP_DESCENT_LOG_ALG, by              *)
(* CLOG_MUL_CPRODUCT_POW); the shift of the data by -1 at index 1            *)
(* (SHARP_SHIFT_VSUM) and the drop of a vanishing last coefficient           *)
(* (SHARP_DESCENT_DROP_LAST), stated for complex coefficients. (b) The       *)
(* descent for integer coefficients: from the core property                  *)
(* sharp_core_property_alg (a tiny linear form in principal logarithms       *)
(* forces a Kummer relation with a prime pr >= 4 D^2) the bound property     *)
(* sharp_bound_property_alg (Sharpening I: Lambda = 0 or |Lambda| >=         *)
(* exp(-C g0^K log A log B), C and K depending only on n and the degree      *)
(* bound d). The data are extended by -1 at index 1 (with logarithm pi i),   *)
(* which absorbs the 2 pi i t of principal logarithms; all later numbers lie *)
(* in the field F generated by the original ones, [F:Q] <= d^n. Induction on *)
(* a natural bound N >= log A: the uniform bound SHARP_UNIFORM_ALG when the  *)
(* last coefficient vanishes or log A <= 16 D^2 (n+1) g0, Liouville for      *)
(* small B, and otherwise the descent step, which gives the same linear form *)
(* with coefficients at most (2n+4)(pr+1) B.                                 *)
(*                                                                           *)
(* Main results: SHARP_BAKER_ALGEBRAIC; SHARP_DESCENT_ALG_EXT (the extended  *)
(* form in a fixed field), SHARP_LIOUVILLE_ALG (Liouville bound linear in    *)
(* B), SHARP_DESCENT_STEP_ALG; the shared tools SHARP_DESCENT_HEIGHT_ALG,    *)
(* SHARP_DESCENT_LOG_ALG, SHARP_SHIFT_VSUM, SHARP_DESCENT_DROP_LAST.         *)
(*                                                                           *)
(* Uses: Baker/sharp_defs.ml (sharp_algdata, sharp_nfbound,                  *)
(* sharp_core_property_alg, sharp_bound_property_alg), Baker/sharp_num.ml    *)
(* (SHARP_CORE_ALGEBRAIC), Baker/sharp_tools.ml (COMPLEX_ROOT_DENOMINATOR,   *)
(* COMPLEX_SUBFIELD_GENERATED_DEGREE, COMPLEX_SUBFIELD_ELEMENT_POLY,         *)
(* SHARP_NFBOUND_EMBEDDING, SHARP_NFBOUND_DEN, SHARP_NFBOUND_SUB1_LOWER,     *)
(* SHARP_NFBOUND_CEXP_VSUM), Baker/sharp_uniform.ml (SHARP_UNIFORM_ALG),     *)
(* Baker/auxiliary.ml (NORM_CEXP_SUB_1_LE), Baker/lemmas.ml                  *)
(* (CLOG_MUL_CPRODUCT_POW, EXP_1_LE_3, LOG_2_LE_1, REAL_LE_1_MUL),           *)
(* Baker/bridge.ml (ALGEBRAIC_NUMBER_EXPLICIT), Baker/ant_bridge_complex.ml  *)
(* (BRIDGE_NF_SUBFIELD_RATIONAL), ANT/complex_embeddings.ml                  *)
(* (complex_embeddings), Library/fieldtheory.ml (SUBFIELD_GENERATED_INC_GEN, *)
(* SUBFIELD_GENERATED_MINIMAL, SUBFIELD_SUBFIELD_GENERATED).                 *)
(* ========================================================================= *)

