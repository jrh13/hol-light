let SHARPC_DESCENT_FORM = prove
 (`!n (lg:num->complex) (bb:num->complex) (cc:num->real) pr lgn.
        ~(pr = 0) /\ bb(n + 1) = Cx(&1) /\
        lg(n + 1) = vsum(1..n) (\r. Cx(cc r) * lg r) + Cx(&pr) * lgn
        ==> vsum(1..n+1) (\r. (if r = n + 1 then bb r
                               else (bb r + Cx(cc r)) / Cx(&pr)) *
                              (if r = n + 1 then lgn else lg r)) =
