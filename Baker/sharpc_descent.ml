  REPEAT GEN_TAC THEN REWRITE_TAC[GSYM ADD1] THEN STRIP_TAC THEN
  REWRITE_TAC[VSUM_CLAUSES_NUMSEG; ARITH_RULE `1 <= SUC n`] THEN
  SUBGOAL_THEN
