(* ========================================================================= *)
(* Sharpening I with algebraic coefficients: the descent and the bound       *)
(* property (Baker, A central theorem in transcendence theory, 1973, sec.    *)
(* 4).                                                                       *)
(*                                                                           *)
(* Purpose: from the core property sharpc_core_property (a tiny normalised   *)
(* linear form, bb n = 1, forces a Kummer relation with a prime pr >= 4 D^2, *)
(* pr <= cB g0^K, g in the field generated by the alphas and the betas) and  *)
(* the uniform base bound SHARPC_UNIFORM_ALG, the bound property             *)
(* sharpc_bound_property: Lambda = 0 or |Lambda| >= exp(-C g0^K log A log(B  *)
(* log A)), C and K depending only on n and the degree bound d.              *)
(*                                                                           *)
(* Method. (a) SHARPC_DESCENT_EXT, the extended form in a fixed finite set s *)
(* of algebraic numbers with [Q(s):Q] <= D: n + 1 numbers with -1 at index 1 *)
(* (logarithm pi i, it absorbs the 2 pi i t of principal logarithms), all    *)
(* cexp(lg r) and all coefficients bb r in Q(s), bb(n+1) = 1. Induction on a *)
(* natural bound N >= log A. Base case log A <= c7 g0^k7: SHARPC_UNIFORM_ALG *)
(* with G = c7 g0^k7. Step: a smaller |Lambda| gives the core relation       *)
(* cexp(lg(n+1)) = prod_r cexp(lg r)^jj_r g^pr with g in Q(s)                *)
(* (SUBFIELD_GENERATED_MINIMAL); g is a root of an integer polynomial of     *)
(* degree <= D and height exp(log A / 2 + 4 D^2 (n+1) g0)                    *)
(* (SHARP_DESCENT_HEIGHT_ALG); lg(n+1) = sum_r cc_r lg r + pr clog g with    *)
(* integers |cc_r| <= (2n+3) pr (SHARP_DESCENT_LOG_ALG); the new form Lambda *)
(* / pr has the coefficients (bb r + cc_r) / pr (Baker: the new beta_r =     *)
(* (beta_r - j_r) / p), roots of ab r (pr X - cc_r) of the same degree and   *)
(* of height <= (D+1) ((2n+4) pr)^D B (SHARPC_POLY_AFFINE_ROOT); finally log *)
(* A1 log(B1 log A1) <= log A log(B log A) once log A > c7 g0^k7             *)
(* (SHARPC_DESCENT_LOGPROD). (b) SHARPC_BAKER: if bb n = 0 the last number   *)
(* is replaced by 1 and SHARPC_UNIFORM_ALG applies; otherwise s = the alphas *)
(* and the betas, [Q(s):Q] <= d^(2n) (SHARPC_FIELD_DEGREE), the normalised   *)
(* coefficients bb r / bb n have degree <= d^(2n) and height <= B^(d^(2n)    *)
(* (d+6)) (SHARPC_QUOTIENT_POLY, by sharp_nfbound), -1 is added at index 1   *)
(* with coefficient 0, and |Lambda| >= |Lambda / bb n| / (2B)                *)
(* (ALGEBRAIC_ROOT_LOWER_BOUND).                                             *)
(*                                                                           *)
(* Main results: SHARPC_BAKER; SHARPC_DESCENT_EXT, SHARPC_DESCENT_STEP;      *)
(* SHARPC_POLY_AFFINE_ROOT (a root z of an integer polynomial of degree d    *)
(* gives the root (z + c) / p of one of the same degree),                    *)
(* SHARPC_QUOTIENT_POLY, SHARPC_FIELD_DEGREE.                                *)
(*                                                                           *)
(* Uses: Baker/uniform.ml (sharpc_coefdata), Baker/sharp_defs.ml             *)
(* (sharp_algdata, sharp_nfbound, sharpc_core_property,                      *)
(* sharpc_bound_property), Baker/sharpc_num.ml (SHARPC_CORE),                *)
(* Baker/sharp_uniform.ml (SHARPC_UNIFORM_ALG), Baker/sharp_descent.ml       *)
(* (SHARP_DESCENT_HEIGHT_ALG, SHARP_DESCENT_LOG_ALG, SHARP_SHIFT_VSUM,       *)
(* SHARP_DESCENT_DROP_LAST), Baker/sharp_tools.ml (SHARP_NFBOUND_ROOT,       *)
(* SHARP_NFBOUND_INV_ROOT, SHARP_NFBOUND_MUL, SHARP_NFBOUND_DEN,             *)
(* COMPLEX_SUBFIELD_ELEMENT_POLY, COMPLEX_SUBFIELD_GENERATED_DEGREE),        *)
(* Baker/simple.ml (ALGEBRAIC_ROOT_LOWER_BOUND), Baker/bridge.ml             *)
(* (EXPLICIT_IMP_ALGEBRAIC_NUMBER), Baker/lemmas.ml                          *)
(* (COMPLEX_BINOMIAL_THEOREM, REAL_LE_1_MUL), Baker/ant_bridge_complex.ml    *)
(* (BRIDGE_NF_SUBFIELD_RATIONAL, BRIDGE_NF_SUBRING_INTEGER), Baker/kummer.ml *)
(* (COMPLEX_SUBFIELD_CLOSED), Library/binomial.ml (REAL_BINOMIAL_THEOREM,    *)
(* BINOM_LT), Library/fieldtheory.ml (SUBFIELD_GENERATED_MINIMAL,            *)
(* SUBFIELD_GENERATED_INC_GEN, SUBFIELD_SUBFIELD_GENERATED,                  *)
(* SUBRING_SUBFIELD_GENERATED).                                              *)
(* ========================================================================= *)

