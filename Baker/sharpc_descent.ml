let SHARPC_POLY_AFFINE_ROOT = prove
 (`!(a:num->real) d H z p c.
        (!j. integer(a j) /\ abs(a j) <= H) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * z pow j) = Cx(&0) /\
        integer p /\ ~(p = &0) /\ integer c
        ==> ?b. (!j. integer(b j) /\
                     abs(b j) <= &(d + 1) * H * (abs p + abs c) pow d) /\
                ~(b d = &0) /\
                vsum(0..d) (\j. Cx(b j) * ((z + Cx c) / Cx p) pow j) =
                Cx(&0)`,
  REPEAT STRIP_TAC THEN
  EXISTS_TAC `\i. sum(0..d) (\j. (a:num->real) j * &(binom(j,i)) *
                                 p pow i * (--c) pow (j - i))` THEN
  REWRITE_TAC[] THEN
  SUBGOAL_THEN `&1 <= abs p + abs c` ASSUME_TAC THENL
   [MP_TAC(SPEC `p:real` REAL_ABS_INTEGER_LEMMA) THEN ASM_REWRITE_TAC[] THEN
    REAL_ARITH_TAC;
    ALL_TAC] THEN
  REPEAT CONJ_TAC THENL
   [X_GEN_TAC `i:num` THEN CONJ_TAC THENL
     [MATCH_MP_TAC INTEGER_SUM THEN X_GEN_TAC `j:num` THEN DISCH_TAC THEN
      REWRITE_TAC[] THEN
      REPEAT(MATCH_MP_TAC INTEGER_MUL THEN CONJ_TAC) THEN
      ASM_SIMP_TAC[INTEGER_POW; INTEGER_NEG; INTEGER_CLOSED];
      ALL_TAC] THEN
    TRANS_TAC REAL_LE_TRANS
     `sum(0..d) (\j:num. H * (abs p + abs c) pow d)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SUM_ABS_LE THEN REWRITE_TAC[FINITE_NUMSEG; IN_NUMSEG] THEN
      X_GEN_TAC `j:num` THEN STRIP_TAC THEN
      REWRITE_TAC[REAL_ABS_MUL; REAL_ABS_POW; REAL_ABS_NEG; REAL_ABS_NUM] THEN
      MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[REAL_ABS_POS] THEN
      SUBGOAL_THEN `&0 <= abs p /\ &0 <= abs c` STRIP_ASSUME_TAC THENL
       [REWRITE_TAC[REAL_ABS_POS]; ALL_TAC] THEN
      CONJ_TAC THENL
       [REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
        ASM_SIMP_TAC[REAL_POS; REAL_POW_LE];
        ALL_TAC] THEN
      TRANS_TAC REAL_LE_TRANS `(abs p + abs c) pow j` THEN CONJ_TAC THENL
       [ASM_CASES_TAC `i:num <= j` THENL
         [MP_TAC(ISPECL
           [`\k. &(binom(j,k)) * abs p pow k * abs c pow (j - k)`;
            `(abs p + abs c) pow j`; `0..j`] SUM_POS_BOUND) THEN
          REWRITE_TAC[GSYM REAL_BINOMIAL_THEOREM; REAL_LE_REFL;
                      FINITE_NUMSEG] THEN
          ANTS_TAC THENL
           [X_GEN_TAC `k:num` THEN DISCH_TAC THEN
            REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
            ASM_SIMP_TAC[REAL_POS; REAL_POW_LE];
            DISCH_THEN(MP_TAC o SPEC `i:num`) THEN
            ASM_REWRITE_TAC[IN_NUMSEG; LE_0]];
          SUBGOAL_THEN `binom(j,i) = 0` SUBST1_TAC THENL
           [MATCH_MP_TAC BINOM_LT THEN ASM_ARITH_TAC;
            REWRITE_TAC[REAL_MUL_LZERO] THEN MATCH_MP_TAC REAL_POW_LE THEN
            ASM_REAL_ARITH_TAC]];
        MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[]];
      REWRITE_TAC[SUM_CONST_NUMSEG; SUB_0; REAL_LE_REFL]];
    SUBGOAL_THEN
     `sum(0..d) (\j. (a:num->real) j * &(binom(j,d)) * p pow d *
                     (--c) pow (j - d)) =
      sum(0..d) (\j. if j = d then a d * p pow d else &0)`
    SUBST1_TAC THENL
     [MATCH_MP_TAC SUM_EQ_NUMSEG THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
      REWRITE_TAC[] THEN COND_CASES_TAC THENL
       [ASM_REWRITE_TAC[BINOM_REFL; SUB_REFL; real_pow; REAL_MUL_LID;
                        REAL_MUL_RID];
        SUBGOAL_THEN `binom(j,d) = 0` SUBST1_TAC THENL
         [MATCH_MP_TAC BINOM_LT THEN ASM_ARITH_TAC;
          REWRITE_TAC[REAL_MUL_LZERO; REAL_MUL_RZERO]]];
      REWRITE_TAC[SUM_DELTA; IN_NUMSEG; LE_0; LE_REFL] THEN
      ASM_REWRITE_TAC[REAL_ENTIRE; REAL_POW_EQ_0]];
    ALL_TAC] THEN
  ABBREV_TAC `w = (z + Cx c) / Cx p` THEN
  SUBGOAL_THEN `z = Cx p * w + --Cx c` ASSUME_TAC THENL
   [EXPAND_TAC "w" THEN UNDISCH_TAC `~(p = &0)` THEN
    REWRITE_TAC[GSYM CX_INJ] THEN CONV_TAC COMPLEX_FIELD;
    ALL_TAC] THEN
  TRANS_TAC EQ_TRANS
   `vsum(0..d) (\i. vsum(0..d) (\j. Cx((a:num->real) j) *
       (Cx(&(binom(j,i))) * (Cx p * w) pow i * (--Cx c) pow (j - i))))` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `i:num` THEN STRIP_TAC THEN
    REWRITE_TAC[GSYM VSUM_CX_NUMSEG] THEN BETA_TAC THEN
    SIMP_TAC[GSYM VSUM_COMPLEX_RMUL; FINITE_NUMSEG] THEN
    MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
    REWRITE_TAC[CX_MUL; CX_POW; CX_NEG; COMPLEX_POW_MUL] THEN
    CONV_TAC COMPLEX_RING;
    ALL_TAC] THEN
  GEN_REWRITE_TAC LAND_CONV [VSUM_SWAP_NUMSEG] THEN
  SIMP_TAC[VSUM_COMPLEX_LMUL; FINITE_NUMSEG] THEN
  TRANS_TAC EQ_TRANS `vsum(0..d) (\j. Cx((a:num->real) j) * z pow j)` THEN
  CONJ_TAC THENL [ALL_TAC; FIRST_ASSUM ACCEPT_TAC] THEN
  MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
  REWRITE_TAC[] THEN AP_TERM_TAC THEN
  FIRST_X_ASSUM(SUBST1_TAC o check (fun th ->
    is_eq(concl th) && lhs(concl th) = `z:complex`)) THEN
  REWRITE_TAC[COMPLEX_BINOMIAL_THEOREM] THEN
  MATCH_MP_TAC VSUM_SUPERSET THEN
  REWRITE_TAC[SUBSET; IN_NUMSEG; COMPLEX_VEC_0] THEN
  CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  X_GEN_TAC `i:num` THEN STRIP_TAC THEN
  SUBGOAL_THEN `binom(j,i) = 0` SUBST1_TAC THENL
   [MATCH_MP_TAC BINOM_LT THEN ASM_ARITH_TAC;
    REWRITE_TAC[COMPLEX_MUL_LZERO]]);;

let SHARPC_QUOTIENT_ARITH = prove
 (`!B d dx u v.
        &2 <= B /\ &1 <= u /\ u <= B /\ &1 <= v /\ v <= B /\ dx <= d
        ==> &1 <= &2 * (u * v) * (&1 + &dx * B) * &2 * B /\
            &2 * (u * v) * (&1 + &dx * B) * &2 * B <= B pow (d + 6)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `&0 <= &dx * B /\ &dx * B <= &d * B` STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
      ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_LE_RMUL THEN
      ASM_REWRITE_TAC[REAL_OF_NUM_LE] THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= u * v` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  CONJ_TAC THENL
   [REPEAT(MATCH_MP_TAC REAL_LE_1_MUL THEN CONJ_TAC) THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 + &d * B <= B pow (d + 1)` ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `(&1 + &d) * B` THEN CONJ_TAC THENL
     [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[REAL_POW_ADD; REAL_POW_1] THEN
    MATCH_MP_TAC REAL_LE_RMUL THEN
    CONJ_TAC THENL [ALL_TAC; ASM_REAL_ARITH_TAC] THEN
    TRANS_TAC REAL_LE_TRANS `&2 pow d` THEN CONJ_TAC THENL
     [REWRITE_TAC[REAL_OF_NUM_POW; REAL_OF_NUM_ADD; REAL_OF_NUM_LE] THEN
      MP_TAC(SPEC `d:num` LT_POW2_REFL) THEN ARITH_TAC;
      MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `&4 <= B pow 2 /\ u * v <= B pow 2` STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[REAL_POW_2] THEN CONJ_TAC THENL
     [MATCH_MP_TAC(REAL_ARITH `&2 * &2 <= B * B ==> &4 <= B * B`) THEN
      MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `&2 * (u * v) * (&1 + &dx * B) * &2 * B =
    &4 * (u * v) * (&1 + &dx * B) * B /\
    B pow (d + 6) = B pow 2 * B pow 2 * B pow (d + 1) * B`
  (CONJUNCTS_THEN SUBST1_TAC) THENL
   [CONJ_TAC THENL
     [REAL_ARITH_TAC;
      REWRITE_TAC[REAL_POW_ADD; REAL_POW_1] THEN CONV_TAC REAL_RING];
    ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_MUL2 THEN
  CONJ_TAC THENL [REAL_ARITH_TAC; ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL
   [REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REAL_ARITH_TAC);;

let SHARPC_QUOTIENT_POLY = prove
 (`!s x y (ax:num->real) dx (ay:num->real) dy B d E.
        FINITE s /\ (!z. z IN s ==> algebraic_number z) /\
        extension_degree (subfield_generated complex_ring {Cx(&0)},
                          subfield_generated complex_ring s) I <= E /\
        x IN ring_carrier(subfield_generated complex_ring s) /\
        y IN ring_carrier(subfield_generated complex_ring s) /\
        ~(y = Cx(&0)) /\ &2 <= B /\ dx <= d /\
        (!j. integer(ax j) /\ abs(ax j) <= B) /\ ~(ax dx = &0) /\
        vsum(0..dx) (\j. Cx(ax j) * x pow j) = Cx(&0) /\
        (!j. integer(ay j) /\ abs(ay j) <= B) /\ ~(ay dy = &0) /\
        vsum(0..dy) (\j. Cx(ay j) * y pow j) = Cx(&0)
        ==> ?dq aq. 1 <= dq /\ dq <= E /\
                    (!j. integer(aq j) /\ abs(aq j) <= B pow (E * (d + 6))) /\
                    ~(aq dq = &0) /\
                    vsum(0..dq) (\j. Cx(aq j) * (x / y) pow j) = Cx(&0)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`s:complex->bool`; `x:complex`; `ax:num->real`; `dx:num`;
                 `B:real`] SHARP_NFBOUND_ROOT) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`s:complex->bool`; `y:complex`; `ay:num->real`; `dy:num`;
                 `B:real`] SHARP_NFBOUND_INV_ROOT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `den:real` STRIP_ASSUME_TAC) THEN
  MP_TAC(ISPECL [`s:complex->bool`; `x:complex`; `inv(y:complex)`;
                 `abs((ax:num->real) dx)`; `den:real`; `&1 + &dx * B`;
                 `&2 * B`] SHARP_NFBOUND_MUL) THEN
  ASM_REWRITE_TAC[GSYM complex_div] THEN
  REWRITE_TAC[sharp_nfbound] THEN STRIP_TAC THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP SHARP_NFBOUND_DEN o check (fun th ->
    is_comb(concl th) && free_in `den:real` (concl th) &&
    fst(strip_comb(concl th)) = `sharp_nfbound`)) THEN
  SUBGOAL_THEN `&1 <= abs((ax:num->real) dx) /\ abs(ax dx) <= B`
  STRIP_ASSUME_TAC THENL
   [ASM_SIMP_TAC[REAL_ABS_INTEGER_LEMMA]; ALL_TAC] THEN
  MP_TAC(ISPECL [`B:real`; `d:num`; `dx:num`; `abs((ax:num->real) dx)`;
                 `den:real`] SHARPC_QUOTIENT_ARITH) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`s:complex->bool`; `x / y:complex`;
                 `abs((ax:num->real) dx) * den`;
                 `(&1 + &dx * B) * &2 * B`]
    COMPLEX_SUBFIELD_ELEMENT_POLY) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_LE_1_MUL THEN CONJ_TAC THENL
     [MATCH_MP_TAC(REAL_ARITH `&0 <= x ==> &1 <= &1 + x`) THEN
      MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
      ASM_REAL_ARITH_TAC;
      ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `dq:num` THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `aq:num->real` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  X_GEN_TAC `j:num` THEN ASM_REWRITE_TAC[] THEN
  TRANS_TAC REAL_LE_TRANS
   `(&2 * (abs((ax:num->real) dx) * den) * (&1 + &dx * B) * &2 * B) pow dq` THEN
  ASM_REWRITE_TAC[] THEN
  TRANS_TAC REAL_LE_TRANS `(B pow (d + 6)) pow dq` THEN CONJ_TAC THENL
   [MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[] THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  REWRITE_TAC[REAL_POW_POW] THEN
  GEN_REWRITE_TAC (RAND_CONV o RAND_CONV) [MULT_SYM] THEN
  MATCH_MP_TAC REAL_POW_MONO THEN
  CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  REWRITE_TAC[LE_MULT_LCANCEL] THEN ASM_ARITH_TAC);;

(* ------------------------------------------------------------------------- *)
(* Part 2. The descent step: the new coefficients (bb r + cc r) / pr, the    *)
(* new normalised form Lambda / pr, and the new data in the fixed field.     *)
(* ------------------------------------------------------------------------- *)

let SHARPC_DESCENT_COEF_ARITH = prove
 (`!db D n pr c B.
        db <= D /\ 1 <= pr /\ abs c <= &(2 * n + 3) * &pr /\ &0 <= B
        ==> &(db + 1) * B * (abs(&pr) + abs c) pow db <=
            (&D + &1) * (&(2 * n + 4) * &pr) pow D * B`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[REAL_ABS_NUM] THEN
  SUBGOAL_THEN `&1 <= &pr` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[REAL_OF_NUM_LE]; ALL_TAC] THEN
  SUBGOAL_THEN `&pr + abs c <= &(2 * n + 4) * &pr` ASSUME_TAC THENL
   [UNDISCH_TAC `abs c <= &(2 * n + 3) * &pr` THEN
    REWRITE_TAC[GSYM REAL_OF_NUM_ADD; GSYM REAL_OF_NUM_MUL] THEN
    REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= &(2 * n + 4) * &pr` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_REWRITE_TAC[REAL_OF_NUM_LE] THEN
    ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(&pr + abs c) pow db <= (&(2 * n + 4) * &pr) pow D`
  ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `(&(2 * n + 4) * &pr) pow db` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[] THEN
      MP_TAC(SPEC `c:real` REAL_ABS_POS) THEN ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN `&(db + 1) <= &D + &1` ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_ADD; REAL_OF_NUM_LE] THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= (&pr + abs c) pow db` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_POW_LE THEN MP_TAC(SPEC `c:real` REAL_ABS_POS) THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `&(db + 1) * B * (&pr + abs c) pow db =
    (&(db + 1) * (&pr + abs c) pow db) * B /\
    (&D + &1) * (&(2 * n + 4) * &pr) pow D * B =
    ((&D + &1) * (&(2 * n + 4) * &pr) pow D) * B`
  (CONJUNCTS_THEN SUBST1_TAC) THENL
   [CONJ_TAC THEN REAL_ARITH_TAC; ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[REAL_POS]);;

let SHARPC_DESCENT_COEFDATA = prove
 (`!n (bb:num->complex) (ab:num->num->real) (db:num->num) B (cc:num->real)
    pr D.
        sharpc_coefdata (n+1) bb ab db B /\
        (!r. r IN 1..n+1 ==> db r <= D) /\ &0 <= B /\ 1 <= pr /\
        (!r. integer(cc r) /\ abs(cc r) <= &(2 * n + 3) * &pr)
        ==> ?ab'. sharpc_coefdata (n+1)
                    (\r. if r = n + 1 then bb r
                         else (bb r + Cx(cc r)) / Cx(&pr))
                    ab' db ((&D + &1) * (&(2 * n + 4) * &pr) pow D * B)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `B <= (&D + &1) * (&(2 * n + 4) * &pr) pow D * B`
  ASSUME_TAC THENL
