     [ASM_ARITH_TAC; CONV_TAC COMPLEX_RING];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `~(Cx(&pr) = Cx(&0))` MP_TAC THENL
   [ASM_REWRITE_TAC[CX_INJ; REAL_OF_NUM_EQ]; CONV_TAC COMPLEX_FIELD]);;

