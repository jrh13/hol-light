                     else (bb r + Cx(cc r)) / Cx(&pr)) *
                    (if r = SUC n then lgn else (lg:num->complex) r)) =
    (vsum(1..n) (\r. bb r * lg r) + vsum(1..n) (\r. Cx(cc r) * lg r)) /
    Cx(&pr)`
  SUBST1_TAC THENL
   [REWRITE_TAC[complex_div; GSYM VSUM_ADD_NUMSEG] THEN
