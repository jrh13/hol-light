(* The ring of integers of an imaginary quadratic field: definitions.        *)
(*                                                                           *)
(* Purpose: quad_omega d, the generator (1 + sqrt(-d))/2 if d = 3 mod 4 and  *)
(* sqrt(-d) otherwise; imag_quadratic_field d, the field Q(sqrt(-d)) as a    *)
(* set of complex numbers; imag_quadratic_integers d, the subring of         *)
(* complex_ring generated by the algebraic integers of that field (its       *)
(* carrier is exactly that set and it is the ring of integers of the field:  *)
(* Baker/quadint_ant.ml; it is Z[omega] for squarefree d:                    *)
(* Baker/quadint_ring.ml). With UFD and PID of Library/ringtheory.ml these   *)
(* give the ring-theoretic form of the class number one theorem              *)
(* (Baker/quadint_main.ml).                                                  *)
(*                                                                           *)
(* Main results: the definitions quad_omega, imag_quadratic_field,           *)
(* imag_quadratic_integers.                                                  *)
(*                                                                           *)
(* Uses: Baker/algint.ml (algebraic_integer), Library/ringtheory.ml          *)
(* (subring_generated), Multivariate/complex_ring.ml (complex_ring),         *)
(* Library/floor.ml (rational).                                              *)
(* ========================================================================= *)

needs "Baker/algint.ml";;

prioritize_real();;
prioritize_num();;

(* The generator of the ring of integers of Q(sqrt(-d)) for squarefree d:   *)
(* (1 + sqrt(-d)) / 2 if d = 3 mod 4 (discriminant -d), else sqrt(-d).      *)

let quad_omega = new_definition
 `quad_omega (d:num) =
    if d MOD 4 = 3 then (Cx(&1) + ii * Cx(sqrt(&d))) / Cx(&2)
    else ii * Cx(sqrt(&d))`;;

(* The imaginary quadratic field Q(sqrt(-d)) as a set of complex numbers.  *)

let imag_quadratic_field = new_definition
 `imag_quadratic_field (d:num) =
    {z | ?a b. rational a /\ rational b /\
               z = Cx a + Cx b * ii * Cx(sqrt(&d))}`;;

(* Its ring of integers: the algebraic integers of the field, as a subring  *)
(* of complex_ring.                                                         *)

let imag_quadratic_integers = new_definition
 `imag_quadratic_integers (d:num) =
    subring_generated complex_ring
      {z | algebraic_integer z /\ z IN imag_quadratic_field d}`;;
