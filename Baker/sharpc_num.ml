(* ------------------------------------------------------------------------- *)
(* The Liouville bounds: a generic domination lemma (the extra power of the  *)
(* max term absorbs a factor W <= Iold), small positivity facts, the         *)
(* degree monotonicity of the factors H (1 + dd H), then the bounds at the   *)
(* integers and at l/q.                                                      *)
(* ------------------------------------------------------------------------- *)

let SHARPC_LIOU_DOMINATE = prove
 (`!Dp Dq Inew Iold W PH.
     1 <= Dp /\ Dp < Dq /\ Inew <= Iold /\ &0 < W /\ W <= Iold /\ &1 <= PH
     ==> &(FACT Dp) * (max (&1) Inew) pow (Dp - 1) * W * PH <=
         &(FACT Dq) * (max (&1) Iold) pow (Dq - 1) * PH`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `M = max (&1) Iold` THEN
  SUBGOAL_THEN `&1 <= M /\ max (&1) Inew <= M /\ W <= M /\
                &0 <= max (&1) Inew`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "M" THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN
   `(max (&1) Inew) pow (Dp - 1) * W <= M pow (Dq - 1)`
  ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `M pow (Dp - 1) * M` THEN CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL2 THEN
      ASM_SIMP_TAC[REAL_POW_LE; REAL_LT_IMP_LE; REAL_POW_LE2];
      ALL_TAC] THEN
    SUBGOAL_THEN `M pow (Dp - 1) * M = M pow Dp` SUBST1_TAC THENL
     [GEN_REWRITE_TAC (RAND_CONV o RAND_CONV)
       [MATCH_MP (ARITH_RULE `1 <= d ==> d = SUC(d - 1)`)
                 (ASSUME `1 <= Dp`)] THEN
      REWRITE_TAC[real_pow] THEN REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `&(FACT Dp) <= &(FACT Dq)` ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LE] THEN MATCH_MP_TAC FACT_MONO THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  GEN_REWRITE_TAC LAND_CONV
   [REAL_ARITH `(f:real) * p * w * h = f * (p * w) * h`] THEN
  MATCH_MP_TAC REAL_LE_MUL2 THEN REWRITE_TAC[REAL_POS] THEN
  ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN
      ASM_SIMP_TAC[REAL_POW_LE; REAL_LT_IMP_LE];
      ASM_REAL_ARITH_TAC];
    MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
    ASM_REAL_ARITH_TAC]);;

