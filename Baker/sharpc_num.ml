(* ========================================================================= *)
(* Sharpening I with algebraic coefficients: the numeric layer.              *)
(*                                                                           *)
(* Purpose: the ending for algebraic coefficients of the parametric core     *)
(* SHARP_CORE_PARAMETRIC (Baker/sharp_core.ml): for n principal logarithms   *)
(* of algebraic numbers of degree at most D and normalised algebraic         *)
(* coefficients (bb n = 1) of degree at most D and height at most B, the     *)
(* core property sharpc_core_property n D C K cB (SHARPC_CORE; the property  *)
(* is defined in Baker/sharp_defs.ml): a tiny linear form forces a Kummer    *)
(* relation for the last number with a prime pr, 4 D^2 <= pr <= cB g0^K, and *)
(* g in the field generated by the alphas and the betas.                     *)
(*                                                                           *)
(* Method: the Q-power design of Baker/sharp_num.ml (SHARP_CORE_DESIGN) with *)
(* the radius exponent c = 2 D^(2n) instead of D^n: a = (8 c + 3) n,         *)
(* J = (a + 1)(n + 2), e = J + 72 n + 256 + 8 c, Q = 2^e g0N, L = gN Q^a,    *)
(* Ln = Q^(a+1), Lm = gN Q^(a+1), S0 = gN Q^(a+8c+3), X = h Q^J, the         *)
(* analytic size bound Bp = (2 Lm + S0) (1 + D)^n B^(3n) (the betas satisfy  *)
(* |bb r| <= 1 + D B <= Bp by INTEGER_POLY_ROOT_BOUND) and                   *)
(* h >= log(4 Bp + 2); Bp depends on gN and Q only, not on h. The arithmetic *)
(* is that of the Delta representation of algebraic coefficients             *)
(* (SHARP_DELTAREP_ALG: multiplier prod_r m_r!, sizes (2 Lm + s)^s, degree s *)
(* in the betas).                                                            *)
(*                                                                           *)
(* Part B (the key check of the design): the generic bound functions         *)
(* sharp_psize, sharp_liou5, sharp_lb8 at the algebraic instance             *)
(* (W s = (2 Lm + s)^s, E s = s, Mb s = s^s; the body lemmas                 *)
(* SHARP_PSIZE_ALG_BODY, SHARP_LIOU5_ALG_BODY, SHARP_LB8_ALG_BODY) are       *)
(* dominated by the same functions at the integer instance of                *)
(* Baker/sharp_num.ml with Bp for B and any degree data dd1 >= dd with       *)
(* nproduct dd nproduct db < nproduct dd1: the extra power of the max term   *)
(* absorbs the factorial bound S0^S0 and the beta heights outside the max    *)
(* (SHARPC_LIOU_DOMINATE).                                                   *)
(*                                                                           *)
(* Part E: SHARPC_CORE_DATA, the assembly: the design facts                  *)
(* SHARP_CORE_DESIGN for Bq = Bp and the degree data                         *)
(* dd1 r = (if r = n then 2 dd n nproduct db else dd r) with                 *)
(* nproduct dd1 = 2 nproduct dd nproduct db <= c and                         *)
(* dd1 r <= D1 = 2 D^(n+1) <= c (SHARPC_NUM_DD1_FACTS), then                 *)
(* SHARP_CORE_PARAMETRIC at the algebraic instance; its step and Lemma 8     *)
(* hypotheses follow from those of the design in the integer form by the     *)
(* domination of Part B.                                                     *)
(*                                                                           *)
(* Part F: the final inequality                                              *)
(*   17 h gN Q^M <= C g0^(M+1) log A log(B log A),   M = J + a + 8 c + 3,    *)
(*   C = 17 (2 (11 + D + (a + b)(e + 1) + n D) + 2 (a + b) + 1 + 3 n)        *)
(*       (D + 7) 2^((e+1) M),   b = 8 c + 3,                                 *)
(* for g0N = ceil g0, gN = ceil(log A + D + 5), h = ceil(log(4 Bp + 2))      *)
(* (SHARPC_NUM_FINAL_INEQ:                                                   *)
(* log(4 Bp + 2) <= 4 log 2 + log gN + (a + b) log Q +                       *)
(* n log(1 + D) + 3 n log B, gN <= (D + 7) log A, log Q <= e + 1 + g0,       *)
(* Q <= 2^(e+1) g0, log B and log log A at most Y = log(B log A), 1 <= 2 Y), *)
(* and SHARPC_CORE with K = M + 1 and cB = 2^(70 + (e+1)(a+1)) (the prime of *)
(* PRIME_IN_INTERVAL in (Q^(a+1), 2^70 Q^(a+1)]).                            *)
(*                                                                           *)
(* Main results: SHARPC_CORE, SHARPC_CORE_DATA; SHARPC_PSIZE_LE_ALG,         *)
(*   SHARPC_LIOU5_GE_ALG, SHARPC_LB8_GE_ALG, SHARPC_LIOU_DOMINATE,           *)
(*   SHARPC_BETA_FACTOR_LE (Part B), the body lemmas of the algebraic        *)
(*   instance; helper names SHARPC_NUM_*.                                    *)
(*                                                                           *)
(* Uses: Baker/sharp_defs.ml (sharp_index, sharp_algdata, sharp_lv,          *)
(*   sharp_psize, sharp_liou5, sharp_lb8, sharpc_core_property),             *)
(*   Baker/uniform.ml (sharpc_coefdata), Baker/sharp_num.ml                  *)
(*   (SHARP_CORE_DESIGN, SHARP_PSIZE_INT_BODY, SHARP_LIOU5_INT_BODY,         *)
(*   SHARP_LB8_INT_BODY, SHARP_QPOW_GE, SHARP_CPOLY_BOUNDS),                 *)
(*   Baker/sharp_core.ml (SHARP_CORE_PARAMETRIC), Baker/sharp_arith.ml       *)
(*   (SHARP_DELTAREP_ALG, SHARP_INDEX_NONEMPTY, PRODUCT_POW_GE_1),           *)
(*   Baker/sharp_aux.ml (FINITE_SHARP_INDEX), Baker/liouville_inequality.ml  *)
