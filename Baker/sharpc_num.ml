let SHARPC_PSIZE_LE_ALG = prove
 (`!n h L0 Lv Lm S0 (H:num->real) Hb Bp D.
     1 <= D /\ &1 <= Hb /\ (!r. r IN 1..n ==> &1 <= H r) /\
     (&2 * &Lm + &S0) * (&1 + &D) pow n * Hb pow (3 * n) <= &4 * Bp + &2
     ==> sharp_psize n h L0 Lv S0 H Hb (\s. (&2 * &Lm + &s) pow s) (\s. s)
         <= sharp_psize n h L0 Lv S0 H Hb
              (\s. (&4 * Bp + &2) pow s * &2 pow ((n - 1) * Lm)) (\s. 0)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`n:num`; `Lm:num`; `S0:num`; `S0:num`; `Hb:real`; `Bp:real`;
                `D:num`] SHARPC_BETA_BASE_LE) THEN
  ASM_REWRITE_TAC[LE_REFL] THEN STRIP_TAC THEN
  SUBGOAL_THEN `&0 <= Hb /\ &2 <= &1 + &D /\ &1 <= Hb pow 2`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [ASM_REAL_ARITH_TAC;
      UNDISCH_TAC `1 <= D` THEN REWRITE_TAC[GSYM REAL_OF_NUM_LE] THEN
      REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_POW_LE_1 THEN ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(&2 * &Lm + &S0) pow S0 * (&2 * Hb) pow (n * S0) <=
    (&4 * Bp + &2) pow S0 * &2 pow ((n - 1) * Lm)`
  ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `(&4 * Bp + &2) pow S0` THEN CONJ_TAC THENL
     [REWRITE_TAC[GSYM REAL_POW_POW; GSYM REAL_POW_MUL] THEN
      MATCH_MP_TAC REAL_POW_LE2 THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC THENL
         [REAL_ARITH_TAC;
          MATCH_MP_TAC REAL_POW_LE THEN ASM_REAL_ARITH_TAC];
        ALL_TAC] THEN
      TRANS_TAC REAL_LE_TRANS
       `(&2 * &Lm + &S0) * Hb pow n * ((&1 + &D) * Hb pow 2) pow n` THEN
      ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN CONJ_TAC THENL
       [REAL_ARITH_TAC; ALL_TAC] THEN
      REWRITE_TAC[GSYM REAL_POW_MUL] THEN MATCH_MP_TAC REAL_POW_LE2 THEN
      CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
      TRANS_TAC REAL_LE_TRANS `(&1 + &D) * Hb` THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
      SUBGOAL_THEN `Hb * (&1 + &D) * Hb pow 2 = ((&1 + &D) * Hb) * Hb pow 2`
      SUBST1_TAC THENL [REAL_ARITH_TAC; ALL_TAC] THEN
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_RID] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC;
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_RID] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_POW_LE THEN
        TRANS_TAC REAL_LE_TRANS `&S0 * Hb pow n` THEN ASM_REWRITE_TAC[] THEN
        MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
        MATCH_MP_TAC REAL_POW_LE THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC REAL_POW_LE_1 THEN REAL_ARITH_TAC]];
    ALL_TAC] THEN
  REWRITE_TAC[SHARP_PSIZE_ALG_BODY; SHARP_PSIZE_INT_BODY] THEN
  MATCH_MP_TAC REAL_LE_LMUL THEN REWRITE_TAC[REAL_POS] THEN
  MATCH_MP_TAC(REAL_ARITH `x <= y ==> max (&1) x <= max (&1) y`) THEN
  ABBREV_TAC
   `PH = product(1..n) (\r. (&2 * (H:num->real) r) pow (Lv r * h))` THEN
  SUBGOAL_THEN `&0 <= PH` ASSUME_TAC THENL
   [EXPAND_TAC "PH" THEN MATCH_MP_TAC PRODUCT_POS_LE_NUMSEG THEN
    X_GEN_TAC `r:num` THEN STRIP_TAC THEN REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_POW_LE THEN
    MATCH_MP_TAC(REAL_ARITH `&1 <= x ==> &0 <= &2 * x`) THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[IN_NUMSEG];
    ALL_TAC] THEN
  REPEAT(MATCH_MP_TAC REAL_LE_LMUL THEN CONJ_TAC THENL
   [TRY(MATCH_MP_TAC REAL_POW_LE) THEN REWRITE_TAC[REAL_EXP_POS_LE] THEN
    REAL_ARITH_TAC;
    ALL_TAC]) THEN
