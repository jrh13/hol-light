(* Part B. The key check of the design: the generic bound functions          *)
(* sharp_psize, sharp_liou5, sharp_lb8 of Baker/sharp_defs.ml at the         *)
(* algebraic instance (the Delta representation of algebraic coefficients:   *)
(* W s = (2 Lm + s)^s, E s = s, Mb s = s^s) are dominated by the same        *)
(* functions at the integer instance (W s = (4 B + 2)^s 2^((n-1) Lm),        *)
(* E = 0, Mb = 1, db = 1) once B is replaced by any Bp with                  *)
(* (2 Lm + S0) (1 + D)^n Hb^(3n) <= 4 Bp + 2 (D a bound for the beta degrees *)
(* db, Hb the beta height) and dd by any dd1 >= dd with                      *)
(* nproduct dd nproduct db < nproduct dd1; so the numeric hypotheses of the  *)
(* parametric core in the integer form (SHARP_CORE_DESIGN with Bp, dd1)      *)
(* give those at the algebraic instance. The body lemmas                     *)
(* SHARP_PSIZE_ALG_BODY, SHARP_LIOU5_ALG_BODY, SHARP_LB8_ALG_BODY give the   *)
(* three functions at the algebraic instance explicitly.                     *)
(* ------------------------------------------------------------------------- *)

let SHARP_PSIZE_ALG_BODY = prove
 (`!n h L0 Lv Lm S0 (H:num->real) Hb.
     sharp_psize n h L0 Lv S0 H Hb (\s. (&2 * &Lm + &s) pow s) (\s. s) =
    &(CARD(sharp_index h L0 Lv n)) *
    max (&1)
        (exp(&36 * &h * &S0) * &2 pow ((L0 + 2) * (2 * h + 1)) *
         (&2 * &Lm + &S0) pow S0 *
         product(1..n) (\r. (&2 * H r) pow (Lv r * h)) *
         (&2 * Hb) pow (n * S0))`,
  REPEAT GEN_TAC THEN REWRITE_TAC[sharp_psize]);;

let SHARP_LIOU5_ALG_BODY = prove
 (`!n h L0 Lv Lm P S0 (dd:num->num) (H:num->real) (db:num->num) Hb l.
     sharp_liou5 n h L0 Lv P S0 dd H db Hb
       (\s. (&2 * &Lm + &s) pow s) (\s. s) (\s. &s pow s) l =
    inv((exp(&19) * (&l + &h) / &h) pow (h * S0) * &S0 pow S0 *
        &(FACT(nproduct(1..n) dd * nproduct(1..n) db)) *
        (max (&1)
          ((&(CARD(sharp_index h L0 Lv n)) * P *
            (exp(&19) * (&l + &h) / &h) pow (h * S0) *
            &2 pow ((L0 + 2) * ((l + 1) + h)) *
            (&2 * &Lm + &S0) pow S0) *
           product(1..n) (\r. H r pow (Lv r * l)) * Hb pow (n * S0) *
           product(1..n) (\r. (H r * (&1 + &(dd r) * H r)) pow (Lv r * l)) *
           product(1..n) (\r. (Hb * (&1 + &(db r) * Hb)) pow S0)))
        pow (nproduct(1..n) dd * nproduct(1..n) db - 1) *
        product(1..n) (\r. H r pow (Lv r * l)) * Hb pow (n * S0))`,
  REPEAT GEN_TAC THEN REWRITE_TAC[sharp_liou5]);;

let SHARP_LB8_ALG_BODY = prove
 (`!n h L0 Lv Lm P (dd:num->num) (H:num->real) (db:num->num) Hb (m:num->num)
    l q Nz.
     sharp_lb8 n h L0 Lv P dd H db Hb
       (\s. (&2 * &Lm + &s) pow s) (\s. s) (\s. &s pow s) m l q Nz =
    inv(&(FACT(nproduct(1..n) (\r. q * dd r) * nproduct(1..n) db)) *
        (max (&1)
          ((&(CARD(sharp_index h L0 Lv n)) * P *
            (&q pow (2 * h * (L0 + 2)) * exp(&18 * &(l + q * h)) pow (m 0)) *
            &2 pow ((L0 + 2) * (Nz + h)) *
            (&2 * &Lm + &(nsum(1..n-1) m)) pow (nsum(1..n-1) m)) *
           product(1..n) (\r. H r pow (Lv r * l)) *
           Hb pow (n * nsum(1..n-1) m) *
           product(1..n) (\r. (H r * (&1 + &(q * dd r) * H r))
                              pow (Lv r * l)) *
           product(1..n) (\r. (Hb * (&1 + &(db r) * Hb))
                              pow (nsum(1..n-1) m))))
        pow (nproduct(1..n) (\r. q * dd r) * nproduct(1..n) db - 1) *
        product(1..n) (\r. H r pow (Lv r * l)) *
        Hb pow (n * nsum(1..n-1) m)) /
    (&q pow (2 * h * (L0 + 2)) * exp(&18 * &(l + q * h)) pow (m 0) *
     &(nsum(1..n-1) m) pow (nsum(1..n-1) m))`,
  REPEAT GEN_TAC THEN REWRITE_TAC[sharp_lb8]);;

(* ------------------------------------------------------------------------- *)
(* The beta factors: (2 Lm + Sm)^Sm Hb^(n Sm) prod_r (Hb (1 + db r Hb))^Sm   *)
(* and Sm^Sm Hb^(n Sm) are at most (4 Bp + 2)^Sm when Sm <= S0.              *)
(* ------------------------------------------------------------------------- *)

let SHARPC_BETA_BASE_LE = prove
 (`!n Lm S0 Sm Hb Bp D.
     &1 <= Hb /\ Sm <= S0 /\
     (&2 * &Lm + &S0) * (&1 + &D) pow n * Hb pow (3 * n) <= &4 * Bp + &2
     ==> (&2 * &Lm + &Sm) * Hb pow n * ((&1 + &D) * Hb pow 2) pow n <=
         &4 * Bp + &2 /\
         &Sm * Hb pow n <= &4 * Bp + &2`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `&1 <= Hb pow n /\ Hb pow n <= Hb pow (3 * n) /\
                &1 <= (&1 + &D) pow n /\
                &2 * &Lm + &Sm <= &2 * &Lm + &S0 /\ &Sm <= &2 * &Lm + &S0`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THENL
     [MATCH_MP_TAC REAL_POW_LE_1 THEN ASM_REWRITE_TAC[];
      MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[] THEN ARITH_TAC;
      MATCH_MP_TAC REAL_POW_LE_1 THEN MP_TAC(SPEC `D:num` REAL_POS) THEN
      REAL_ARITH_TAC;
      ASM_REWRITE_TAC[REAL_LE_LADD; REAL_OF_NUM_LE];
      MATCH_MP_TAC(REAL_ARITH
       `&0 <= (l:real) /\ s <= t ==> s <= &2 * l + t`) THEN
      ASM_REWRITE_TAC[REAL_POS; REAL_OF_NUM_LE]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `(&2 * &Lm + &Sm) * Hb pow n * ((&1 + &D) * Hb pow 2) pow n =
    (&2 * &Lm + &Sm) * (&1 + &D) pow n * Hb pow (3 * n)`
  SUBST1_TAC THENL
   [REWRITE_TAC[REAL_POW_MUL; REAL_POW_POW;
                ARITH_RULE `3 * n = n + 2 * n`; REAL_POW_ADD] THEN
    REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= Hb pow (3 * n) /\ &0 <= (&1 + &D) pow n /\
                &0 <= &2 * &Lm + &S0`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THEN TRY(MATCH_MP_TAC REAL_POW_LE) THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  CONJ_TAC THEN
  FIRST_X_ASSUM(MATCH_MP_TAC o MATCH_MP (REAL_ARITH
   `(x:real) <= b ==> y <= x ==> y <= b`) o
   check (fun th -> is_binary "real_le" (concl th) &&
                    free_in `Bp:real` (concl th))) THENL
   [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_LE_MUL THEN ASM_REWRITE_TAC[];
    TRANS_TAC REAL_LE_TRANS `(&2 * &Lm + &S0) * Hb pow (3 * n)` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[REAL_POS] THEN
      ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[] THEN
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[]]]);;

let SHARPC_BETA_PRODUCT_LE = prove
 (`!n Hb D (db:num->num) Sm.
     &1 <= Hb /\ (!r. r IN 1..n ==> db r <= D)
     ==> product(1..n) (\r. (Hb * (&1 + &(db r) * Hb)) pow Sm) <=
         ((&1 + &D) * Hb pow 2) pow (n * Sm)`,
  REPEAT STRIP_TAC THEN
  TRANS_TAC REAL_LE_TRANS
   `product(1..n) (\r:num. ((&1 + &D) * Hb pow 2) pow Sm)` THEN
  CONJ_TAC THENL
   [ALL_TAC;
    REWRITE_TAC[PRODUCT_CONST_NUMSEG_1; REAL_POW_POW] THEN
    REWRITE_TAC[MULT_SYM; REAL_LE_REFL]] THEN
  MATCH_MP_TAC PRODUCT_LE_NUMSEG THEN X_GEN_TAC `r:num` THEN
  STRIP_TAC THEN REWRITE_TAC[] THEN
  SUBGOAL_THEN `(db:num->num) r <= D` ASSUME_TAC THENL
   [FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[IN_NUMSEG];
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= Hb * (&1 + &((db:num->num) r) * Hb)` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC THENL
     [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC(REAL_ARITH `&0 <= (x:real) ==> &0 <= &1 + x`) THEN
    MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  CONJ_TAC THENL [MATCH_MP_TAC REAL_POW_LE THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `Hb <= Hb pow 2 /\
                &((db:num->num) r) * Hb pow 2 <= &D * Hb pow 2`
  MP_TAC THENL
   [CONJ_TAC THENL
     [REWRITE_TAC[REAL_POW_2] THEN
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC REAL_LE_RMUL THEN
      ASM_REWRITE_TAC[REAL_OF_NUM_LE; REAL_LE_POW_2]];
    REWRITE_TAC[REAL_POW_2] THEN REAL_ARITH_TAC]);;

let SHARPC_BETA_FACTOR_LE = prove
 (`!n Lm S0 Sm Hb Bp D (db:num->num).
     &1 <= Hb /\ Sm <= S0 /\ (!r. r IN 1..n ==> db r <= D) /\
     (&2 * &Lm + &S0) * (&1 + &D) pow n * Hb pow (3 * n) <= &4 * Bp + &2
     ==> (&2 * &Lm + &Sm) pow Sm * Hb pow (n * Sm) *
         product(1..n) (\r. (Hb * (&1 + &(db r) * Hb)) pow Sm)
         <= (&4 * Bp + &2) pow Sm /\
         &Sm pow Sm * Hb pow (n * Sm) <= (&4 * Bp + &2) pow Sm`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(SPECL [`n:num`; `Lm:num`; `S0:num`; `Sm:num`; `Hb:real`; `Bp:real`;
                `D:num`] SHARPC_BETA_BASE_LE) THEN
  ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
  MP_TAC(SPECL [`n:num`; `Hb:real`; `D:num`; `db:num->num`; `Sm:num`]
         SHARPC_BETA_PRODUCT_LE) THEN
  ASM_REWRITE_TAC[] THEN DISCH_TAC THEN
  SUBGOAL_THEN `&0 <= Hb /\ &0 <= &1 + &D` STRIP_ASSUME_TAC THENL
   [MP_TAC(SPEC `D:num` REAL_POS) THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  CONJ_TAC THENL
   [TRANS_TAC REAL_LE_TRANS
     `((&2 * &Lm + &Sm) * Hb pow n * ((&1 + &D) * Hb pow 2) pow n) pow Sm`
    THEN CONJ_TAC THENL
     [REWRITE_TAC[REAL_POW_MUL; REAL_POW_POW] THEN
      REPEAT(MATCH_MP_TAC REAL_LE_LMUL THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_POW_LE THEN REWRITE_TAC[REAL_POS] THEN
        TRY(MATCH_MP_TAC REAL_POW_LE) THEN ASM_REAL_ARITH_TAC;
        ALL_TAC]) THEN
      FIRST_X_ASSUM(MP_TAC o check (fun th -> is_binary "real_le" (concl th) &&
        can (find_term ((=) `product:(num->bool)->(num->real)->real`))
            (concl th))) THEN
      REWRITE_TAC[REAL_POW_MUL; REAL_POW_POW];
      MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[] THEN
      REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
      TRY(MATCH_MP_TAC REAL_POW_LE) THEN
      TRY(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
      TRY(MATCH_MP_TAC REAL_POW_LE) THEN ASM_REAL_ARITH_TAC];
    REWRITE_TAC[GSYM REAL_POW_POW; GSYM REAL_POW_MUL] THEN
    ONCE_REWRITE_TAC[MULT_SYM] THEN
    REWRITE_TAC[GSYM REAL_POW_POW; GSYM REAL_POW_MUL] THEN
    MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
    MATCH_MP_TAC REAL_POW_LE THEN ASM_REWRITE_TAC[]]);;

