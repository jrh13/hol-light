  REWRITE_TAC[GSYM RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD] THEN
  SIMP_TAC[NUMBER_FIELD_CLASS_GROUP_FINITE;
           IMAG_QUADRATIC_FIELD_NUMBER_FIELD]);;

let IMAG_QUADRATIC_INTEGERS_PID_EQ_CLASS_NUMBER_1 = prove
