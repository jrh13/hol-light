  SIMP_TAC[NUMBER_FIELD_PID_EQ_CLASS_NUMBER_1;
           IMAG_QUADRATIC_FIELD_NUMBER_FIELD]);;

let PID_IMAG_QUADRATIC_INTEGERS_0 = prove
 (`PID(imag_quadratic_integers 0)`,
  SUBGOAL_THEN `integer_ring isomorphic_ring imag_quadratic_integers 0`
   (fun th -> REWRITE_TAC[GSYM(MATCH_MP ISOMORPHIC_RING_PIDNESS th);
