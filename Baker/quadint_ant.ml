(* ------------------------------------------------------------------------- *)
(* The field Q(sqrt(-d)) inside the complex numbers (any d): a subring and a *)
(* subfield of complex_ring, generated by sqrt(-d), a number field.          *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_FIELD_IN = prove
 (`!d z. z IN imag_quadratic_field d <=>
         ?a b. rational a /\ rational b /\
               z = Cx a + Cx b * ii * Cx(sqrt(&d))`,
  REWRITE_TAC[imag_quadratic_field; IN_ELIM_THM]);;

let QUAD_SQRT_POW_2 = prove
 (`!d. Cx(sqrt(&d)) pow 2 = Cx(&d)`,
  SIMP_TAC[GSYM CX_POW; SQRT_POW_2; REAL_POS]);;

let IMAG_QUADRATIC_FIELD_SUBRING = prove
 (`!d. imag_quadratic_field d subring_of complex_ring`,
  GEN_TAC THEN
  REWRITE_TAC[subring_of; COMPLEX_RING_CLAUSES; SUBSET_UNIV;
              IMAG_QUADRATIC_FIELD_IN] THEN
  REPEAT CONJ_TAC THENL
   [MAP_EVERY EXISTS_TAC [`&0`; `&0`] THEN REWRITE_TAC[RATIONAL_NUM] THEN
    CONV_TAC COMPLEX_RING;
    MAP_EVERY EXISTS_TAC [`&1`; `&0`] THEN REWRITE_TAC[RATIONAL_NUM] THEN
    CONV_TAC COMPLEX_RING;
    REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`z:complex`; `a:real`; `b:real`] THEN
    STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MAP_EVERY EXISTS_TAC [`--a:real`; `--b:real`] THEN
    ASM_SIMP_TAC[RATIONAL_NEG; CX_NEG] THEN CONV_TAC COMPLEX_RING;
    REWRITE_TAC[LEFT_AND_EXISTS_THM; RIGHT_AND_EXISTS_THM;
                LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`z:complex`; `w:complex`; `a:real`; `b:real`;
                         `a':real`; `b':real`] THEN
    STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MAP_EVERY EXISTS_TAC [`a + a':real`; `b + b':real`] THEN
    ASM_SIMP_TAC[RATIONAL_ADD; CX_ADD] THEN CONV_TAC COMPLEX_RING;
    REWRITE_TAC[LEFT_AND_EXISTS_THM; RIGHT_AND_EXISTS_THM;
                LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`z:complex`; `w:complex`; `a:real`; `b:real`;
                         `a':real`; `b':real`] THEN
    STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MAP_EVERY EXISTS_TAC
     [`a * a' - &d * b * b':real`; `a * b' + b * a':real`] THEN
    ASM_SIMP_TAC[RATIONAL_CLOSED; CX_ADD; CX_SUB; CX_MUL] THEN
    MP_TAC(SPEC `d:num` QUAD_SQRT_POW_2) THEN MP_TAC COMPLEX_POW_II_2 THEN
    CONV_TAC COMPLEX_RING]);;

let IMAG_QUADRATIC_FIELD_INV = prove
 (`!d z. z IN imag_quadratic_field d ==> inv z IN imag_quadratic_field d`,
  REWRITE_TAC[IMAG_QUADRATIC_FIELD_IN; LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`d:num`; `z:complex`; `a:real`; `b:real`] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
   (CONJUNCTS_THEN2 ASSUME_TAC SUBST1_TAC)) THEN
  SUBGOAL_THEN `rational(a pow 2 + b pow 2 * &d)` ASSUME_TAC THENL
   [ASM_SIMP_TAC[RATIONAL_CLOSED]; ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC
   [`a / (a pow 2 + b pow 2 * &d)`; `--b / (a pow 2 + b pow 2 * &d)`] THEN
  ASM_SIMP_TAC[RATIONAL_CLOSED] THEN
  REWRITE_TAC[COMPLEX_INV_CNJ; GSYM CX_POW; COMPLEX_SQNORM] THEN
  REWRITE_TAC[CNJ_ADD; CNJ_MUL; CNJ_CX; CNJ_II; RE_ADD; IM_ADD; RE_CX; IM_CX;
              RE_MUL_CX; IM_MUL_CX; RE_MUL_II; IM_MUL_II] THEN
  REWRITE_TAC[REAL_NEG_0; REAL_MUL_RZERO; REAL_ADD_RID; REAL_ADD_LID] THEN
  SIMP_TAC[REAL_POW_MUL; SQRT_POW_2; REAL_POS] THEN
  REWRITE_TAC[CX_DIV; CX_NEG; complex_div] THEN CONV_TAC COMPLEX_RING);;

let IMAG_QUADRATIC_FIELD_SUBFIELD = prove
 (`!d. imag_quadratic_field d subfield_of complex_ring`,
  GEN_TAC THEN MATCH_MP_TAC SUBFIELD_OF_FIELD_INV THEN
  REWRITE_TAC[FIELD_COMPLEX_RING; IMAG_QUADRATIC_FIELD_SUBRING;
              COMPLEX_RING_INV; IMAG_QUADRATIC_FIELD_INV]);;

let IMAG_QUADRATIC_FIELD_GENERATOR = prove
 (`!d. ii * Cx(sqrt(&d)) IN imag_quadratic_field d`,
  GEN_TAC THEN REWRITE_TAC[IMAG_QUADRATIC_FIELD_IN] THEN
  MAP_EVERY EXISTS_TAC [`&0`; `&1`] THEN REWRITE_TAC[RATIONAL_NUM] THEN
  CONV_TAC COMPLEX_RING);;

let IMAG_QUADRATIC_FIELD_GENERATED = prove
 (`!d. subring_generated complex_ring (imag_quadratic_field d) =
       subfield_generated complex_ring {ii * Cx(sqrt(&d))}`,
  GEN_TAC THEN
  REWRITE_TAC[RINGS_EQ; CONJUNCT2 SUBRING_GENERATED;
              CONJUNCT2 SUBFIELD_GENERATED] THEN
  SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING;
           IMAG_QUADRATIC_FIELD_SUBRING] THEN
  MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [ALL_TAC;
    MATCH_MP_TAC SUBFIELD_GENERATED_MINIMAL THEN
    REWRITE_TAC[SING_SUBSET; IMAG_QUADRATIC_FIELD_GENERATOR;
                IMAG_QUADRATIC_FIELD_SUBFIELD]] THEN
  SUBGOAL_THEN
   `ring_carrier(subfield_generated complex_ring {ii * Cx(sqrt(&d))})
    subfield_of complex_ring /\
    ii * Cx(sqrt(&d)) IN
    ring_carrier(subfield_generated complex_ring {ii * Cx(sqrt(&d))})`
  MP_TAC THENL
   [SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING] THEN
    MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
    REWRITE_TAC[in_complex_ring; IN_SING];
    SPEC_TAC(`ring_carrier(subfield_generated complex_ring
                             {ii * Cx(sqrt(&d))})`,
             `k:complex->bool`)] THEN
  GEN_TAC THEN STRIP_TAC THEN
  REWRITE_TAC[SUBSET; IMAG_QUADRATIC_FIELD_IN; LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`z:complex`; `a:real`; `b:real`] THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`complex_ring`; `k:complex->bool`] IN_SUBFIELD_ADD) THEN
  MP_TAC(ISPECL [`complex_ring`; `k:complex->bool`] IN_SUBFIELD_MUL) THEN
  ASM_SIMP_TAC[COMPLEX_RING_CLAUSES; RATIONAL_IN_COMPLEX_SUBFIELD]);;

let QUAD_ALGEBRAIC_INTEGER_QUADRATIC = prove
 (`!z b c. integer b /\ integer c /\ z pow 2 + Cx b * z + Cx c = Cx(&0)
           ==> algebraic_integer z`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[ALGEBRAIC_INTEGER_MONIC] THEN
  MAP_EVERY EXISTS_TAC [`2`; `\i. if i = 0 then (c:real) else b`] THEN
  CONV_TAC NUM_REDUCE_CONV THEN CONJ_TAC THENL
   [GEN_TAC THEN COND_CASES_TAC THEN ASM_REWRITE_TAC[]; ALL_TAC] THEN
  CONV_TAC(LAND_CONV(RAND_CONV EXPAND_VSUM_CONV)) THEN
  REWRITE_TAC[ARITH; complex_pow; COMPLEX_POW_1; COMPLEX_MUL_RID] THEN
  UNDISCH_TAC `z pow 2 + Cx b * z + Cx c = Cx(&0)` THEN
  CONV_TAC COMPLEX_RING);;

let IMAG_QUADRATIC_FIELD_NUMBER_FIELD = prove
 (`!d. number_field (subring_generated complex_ring (imag_quadratic_field d))`,
  GEN_TAC THEN REWRITE_TAC[IMAG_QUADRATIC_FIELD_GENERATED] THEN
  MATCH_MP_TAC NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED THEN
  REWRITE_TAC[FINITE_SING; IN_SING] THEN
  GEN_TAC THEN DISCH_THEN SUBST1_TAC THEN
  MATCH_MP_TAC ALGEBRAIC_INTEGER_IMP_ALGEBRAIC_NUMBER THEN
  MATCH_MP_TAC QUAD_ALGEBRAIC_INTEGER_QUADRATIC THEN
  MAP_EVERY EXISTS_TAC [`&0`; `&d`] THEN REWRITE_TAC[INTEGER_CLOSED] THEN
  MP_TAC(SPEC `d:num` QUAD_SQRT_POW_2) THEN MP_TAC COMPLEX_POW_II_2 THEN
  CONV_TAC COMPLEX_RING);;

(* ------------------------------------------------------------------------- *)
(* The basis 1, sqrt(-d) and the degree 2 (d <> 0); sqrt(-d) squared.       *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_FIELD_COORDS_0 = prove
 (`!d a b. ~(d = 0) /\ Cx a + Cx b * ii * Cx(sqrt(&d)) = Cx(&0)
           ==> a = &0 /\ b = &0`,
  REPEAT GEN_TAC THEN DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
   (fun th -> MP_TAC(AP_TERM `Re` th) THEN MP_TAC(AP_TERM `Im` th))) THEN
  REWRITE_TAC[RE_ADD; IM_ADD; RE_CX; IM_CX; RE_MUL_CX; IM_MUL_CX;
              RE_MUL_II; IM_MUL_II; REAL_NEG_0; REAL_MUL_RZERO;
              REAL_ADD_LID; REAL_ADD_RID] THEN
  ASM_REWRITE_TAC[REAL_ENTIRE; SQRT_EQ_0; REAL_OF_NUM_EQ] THEN
  MESON_TAC[]);;

let IMAG_QUADRATIC_FIELD_RING_SUM_LT_2 = prove
 (`!d c. c 0 IN imag_quadratic_field d /\ c 1 IN imag_quadratic_field d
         ==> ring_sum (subring_generated complex_ring (imag_quadratic_field d))
               {i | i < 2} (\i. c i * (ii * Cx(sqrt(&d))) pow i) =
             c 0 + c 1 * ii * Cx(sqrt(&d))`,
  REPEAT STRIP_TAC THEN
  W(MP_TAC o PART_MATCH (lhand o rand) RING_SUM_LT_2 o lhand o snd) THEN
  REWRITE_TAC[CONJUNCT2 SUBRING_GENERATED; COMPLEX_RING_CLAUSES] THEN
  SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING;
           IMAG_QUADRATIC_FIELD_SUBRING] THEN
  REWRITE_TAC[COMPLEX_POW_1; complex_pow; COMPLEX_MUL_RID] THEN
  DISCH_THEN MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`complex_ring`; `imag_quadratic_field d`;
                 `(c:num->complex) 1`; `ii * Cx(sqrt(&d))`]
    IN_SUBRING_MUL) THEN
  ASM_REWRITE_TAC[COMPLEX_RING_CLAUSES; IMAG_QUADRATIC_FIELD_SUBRING;
                  IMAG_QUADRATIC_FIELD_GENERATOR]);;

let IMAG_QUADRATIC_FIELD_FREE_BASIS = prove
 (`!d. ~(d = 0)
       ==> free_basis (subfield_generated complex_ring {Cx(&0)},
                       subring_generated complex_ring (imag_quadratic_field d))
                      I 2 (\i. (ii * Cx(sqrt(&d))) pow i)`,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[free_basis; I_THM; FORALL_LT_2] THEN
  REWRITE_TAC[CONJUNCT2 SUBRING_GENERATED; CONJUNCT2 SUBFIELD_GENERATED;
              COMPLEX_RING_CLAUSES; COMPLEX_PRIME_SUBFIELD; IN_ELIM_THM] THEN
  SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING;
           IMAG_QUADRATIC_FIELD_SUBRING] THEN
  REWRITE_TAC[complex_pow; COMPLEX_POW_1; IMAG_QUADRATIC_FIELD_GENERATOR] THEN
  REPEAT CONJ_TAC THENL
   [MP_TAC(MATCH_MP IN_SUBRING_1
     (SPEC `d:num` IMAG_QUADRATIC_FIELD_SUBRING)) THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES];
    REWRITE_TAC[IMAG_QUADRATIC_FIELD_IN; LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`x:complex`; `a:real`; `b:real`] THEN STRIP_TAC THEN
    EXISTS_TAC `\i:num. if i = 0 then Cx a else Cx b` THEN
    MP_TAC(SPECL [`d:num`; `\i:num. if i = 0 then Cx a else Cx b`]
      IMAG_QUADRATIC_FIELD_RING_SUM_LT_2) THEN
    ASM_SIMP_TAC[ARITH_EQ; RATIONAL_IN_COMPLEX_SUBFIELD;
                 IMAG_QUADRATIC_FIELD_SUBFIELD] THEN
    ASM_MESON_TAC[];
    X_GEN_TAC `c:num->complex` THEN
    REWRITE_TAC[LEFT_AND_EXISTS_THM; RIGHT_AND_EXISTS_THM;
                LEFT_IMP_EXISTS_THM] THEN
    MAP_EVERY X_GEN_TAC [`p:real`; `q:real`] THEN STRIP_TAC THEN
    MP_TAC(SPECL [`d:num`; `c:num->complex`]
      IMAG_QUADRATIC_FIELD_RING_SUM_LT_2) THEN
    ANTS_TAC THENL
     [ASM_SIMP_TAC[RATIONAL_IN_COMPLEX_SUBFIELD;
                   IMAG_QUADRATIC_FIELD_SUBFIELD];
      ASM_REWRITE_TAC[CX_INJ]] THEN
    DISCH_THEN(ASSUME_TAC o SYM) THEN
    MATCH_MP_TAC IMAG_QUADRATIC_FIELD_COORDS_0 THEN
    EXISTS_TAC `d:num` THEN ASM_REWRITE_TAC[]]);;

let IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD = prove
 (`!d. subfield_generated
         (subring_generated complex_ring (imag_quadratic_field d))
         {ring_0 (subring_generated complex_ring (imag_quadratic_field d))} =
       subfield_generated complex_ring {Cx(&0)}`,
  GEN_TAC THEN REWRITE_TAC[CONJUNCT2 SUBRING_GENERATED] THEN
  SIMP_TAC[PRIME_SUBFIELD_SUBFIELD; IMAG_QUADRATIC_FIELD_SUBFIELD] THEN
  REWRITE_TAC[COMPLEX_RING_CLAUSES]);;

let IMAG_QUADRATIC_FIELD_DEGREE = prove
 (`!d. ~(d = 0)
       ==> extension_degree
             (subfield_generated complex_ring {Cx(&0)},
              subring_generated complex_ring (imag_quadratic_field d)) I = 2`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`subring_generated complex_ring (imag_quadratic_field d)`;
                 `2`; `\i. (ii * Cx(sqrt(&d))) pow i`]
    NUMBER_FIELD_FREE_BASIS_DEGREE) THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD;
               IMAG_QUADRATIC_FIELD_NUMBER_FIELD;
               IMAG_QUADRATIC_FIELD_FREE_BASIS] THEN
  MESON_TAC[]);;

let IMAG_QUADRATIC_FIELD_SQRT = prove
 (`!d. ii * Cx(sqrt(&d)) IN
       ring_carrier(subring_generated complex_ring (imag_quadratic_field d)) /\
       ring_pow (subring_generated complex_ring (imag_quadratic_field d))
                (ii * Cx(sqrt(&d))) 2 =
       ring_of_int (subring_generated complex_ring (imag_quadratic_field d))
                   (-- &d)`,
  GEN_TAC THEN
  SIMP_TAC[CARRIER_SUBRING_GENERATED_SUBRING; IMAG_QUADRATIC_FIELD_SUBRING;
           IMAG_QUADRATIC_FIELD_GENERATOR; RING_POW_SUBRING_GENERATED;
           RING_OF_INT_SUBRING_GENERATED; COMPLEX_RING_POW;
           COMPLEX_RING_OF_INT; int_neg_th; int_of_num_th; CX_NEG] THEN
  MP_TAC(SPEC `d:num` QUAD_SQRT_POW_2) THEN MP_TAC COMPLEX_POW_II_2 THEN
  CONV_TAC COMPLEX_RING);;

(* ------------------------------------------------------------------------- *)
(* The discriminant is qdisc d (squarefree d); the field of m^2 k.           *)
(* ------------------------------------------------------------------------- *)

let QUAD_DMOD4_CONG = prove
 (`!d. (-- &d:int == &1) (mod &4) <=> d MOD 4 = 3`,
  GEN_TAC THEN
  SUBGOAL_THEN `d MOD 4 = 3 <=> (d == 3) (mod 4)` SUBST1_TAC THENL
   [REWRITE_TAC[CONG] THEN CONV_TAC NUM_REDUCE_CONV;
    REWRITE_TAC[num_congruent; int_congruent]] THEN
  EQ_TAC THEN DISCH_THEN(X_CHOOSE_TAC `q:int`) THEN
  EXISTS_TAC `--q - &1:int` THEN POP_ASSUM MP_TAC THEN INT_ARITH_TAC);;

let QDISC_ALT = prove
 (`!d. qdisc d = if (-- &d:int == &1) (mod &4) then -- &d else &4 * -- &d`,
  REWRITE_TAC[qdisc; QUAD_DMOD4_CONG; INT_MUL_RNEG]);;

let IMAG_QUADRATIC_FIELD_DISCRIMINANT = prove
 (`!d. squarefree d
       ==> number_field_discriminant
             (subring_generated complex_ring (imag_quadratic_field d)) =
           qdisc d`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`subring_generated complex_ring (imag_quadratic_field d)`;
                 `ii * Cx(sqrt(&d))`; `-- &d:int`]
    QUADRATIC_FIELD_DISCRIMINANT) THEN
  REWRITE_TAC[IMAG_QUADRATIC_FIELD_SQRT; IMAG_QUADRATIC_FIELD_NUMBER_FIELD;
              IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD; GSYM QDISC_ALT] THEN
  DISCH_THEN MATCH_MP_TAC THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_FIELD_DEGREE; SQUAREFREE_IMP_NZ] THEN
  ASM_REWRITE_TAC[INT_ABS_NEG; INT_ABS_NUM; NUM_OF_INT_OF_NUM] THEN
  INT_ARITH_TAC);;

let IMAG_QUADRATIC_FIELD_SQUARE_MUL = prove
 (`!m k. ~(m = 0)
         ==> imag_quadratic_field (m EXP 2 * k) = imag_quadratic_field k`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[EXTENSION; IMAG_QUADRATIC_FIELD_IN] THEN
  X_GEN_TAC `z:complex` THEN
  REWRITE_TAC[GSYM REAL_OF_NUM_MUL; GSYM REAL_OF_NUM_POW] THEN
  SIMP_TAC[SQRT_MUL; REAL_LE_POW_2; REAL_POS; POW_2_SQRT] THEN
  SUBGOAL_THEN `~(&m:real = &0)` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[REAL_OF_NUM_EQ]; ALL_TAC] THEN
  EQ_TAC THEN REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
  MAP_EVERY X_GEN_TAC [`a:real`; `b:real`] THEN STRIP_TAC THENL
   [MAP_EVERY EXISTS_TAC [`a:real`; `b * &m:real`];
    MAP_EVERY EXISTS_TAC [`a:real`; `b / &m:real`]] THEN
  ASM_SIMP_TAC[RATIONAL_CLOSED] THEN
  REWRITE_TAC[CX_MUL; CX_DIV] THEN
  UNDISCH_TAC `~(&m:real = &0)` THEN REWRITE_TAC[GSYM CX_INJ] THEN
  CONV_TAC COMPLEX_FIELD);;

(* ------------------------------------------------------------------------- *)
(* The ring imag_quadratic_integers d (any d): its carrier is the set of the *)
(* algebraic integers of the field, its operations those of complex_ring.   *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_SUBRING = prove
 (`!d. {z | algebraic_integer z /\ z IN imag_quadratic_field d}
       subring_of complex_ring`,
  GEN_TAC THEN
  SUBGOAL_THEN `{z | algebraic_integer z /\ z IN imag_quadratic_field d} =
                {z | algebraic_integer z} INTER imag_quadratic_field d`
  SUBST1_TAC THENL
   [SET_TAC[];
    MATCH_MP_TAC SUBRING_OF_INTER THEN
    REWRITE_TAC[ALGEBRAIC_INTEGER_SUBRING;
                IMAG_QUADRATIC_FIELD_SUBRING]]);;

let IMAG_QUADRATIC_INTEGERS_CARRIER_ALT = prove
 (`!d. ring_carrier(imag_quadratic_integers d) =
       {z | algebraic_integer z /\ z IN imag_quadratic_field d}`,
  SIMP_TAC[imag_quadratic_integers; CARRIER_SUBRING_GENERATED_SUBRING;
           IMAG_QUADRATIC_INTEGERS_SUBRING]);;

let IMAG_QUADRATIC_INTEGERS_IN_ALT = prove
 (`!d z. z IN ring_carrier(imag_quadratic_integers d) <=>
         algebraic_integer z /\ z IN imag_quadratic_field d`,
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_CARRIER_ALT; IN_ELIM_THM]);;

let IMAG_QUADRATIC_INTEGERS_CLAUSES = prove
 (`!d. ring_0 (imag_quadratic_integers d) = Cx(&0) /\
       ring_1 (imag_quadratic_integers d) = Cx(&1) /\
       ring_neg (imag_quadratic_integers d) = (--) /\
       ring_add (imag_quadratic_integers d) = (+) /\
       ring_mul (imag_quadratic_integers d) = ( * )`,
  REWRITE_TAC[imag_quadratic_integers; SUBRING_GENERATED;
              COMPLEX_RING_CLAUSES]);;

let IMAG_QUADRATIC_INTEGERS_SUB_POW = prove
 (`!d. ring_sub (imag_quadratic_integers d) = (-) /\
       ring_pow (imag_quadratic_integers d) = (pow)`,
  REWRITE_TAC[imag_quadratic_integers; RING_SUB_SUBRING_GENERATED;
              RING_POW_SUBRING_GENERATED; COMPLEX_RING_SUB;
              COMPLEX_RING_POW]);;

let IMAG_QUADRATIC_INTEGERS_INTEGRAL_DOMAIN = prove
 (`!d. integral_domain (imag_quadratic_integers d)`,
  GEN_TAC THEN REWRITE_TAC[imag_quadratic_integers] THEN
  MATCH_MP_TAC INTEGRAL_DOMAIN_SUBRING_GENERATED THEN
  REWRITE_TAC[INTEGRAL_DOMAIN_COMPLEX_RING]);;

let IMAG_QUADRATIC_INTEGERS_SQUARE_MUL = prove
 (`!m k. ~(m = 0)
         ==> imag_quadratic_integers (m EXP 2 * k) =
             imag_quadratic_integers k`,
  SIMP_TAC[imag_quadratic_integers; IMAG_QUADRATIC_FIELD_SQUARE_MUL]);;

(* ------------------------------------------------------------------------- *)
(* The ring of integers of the field: Dedekind, UFD iff PID iff class number *)
(* one, finitely many ideal classes; the ring Z for d = 0.                   *)
(* ------------------------------------------------------------------------- *)

let RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD = prove
 (`!d. ring_of_integers
         (subring_generated complex_ring (imag_quadratic_field d)) =
       imag_quadratic_integers d`,
  GEN_TAC THEN REWRITE_TAC[RINGS_EQ; IMAG_QUADRATIC_INTEGERS_CARRIER_ALT] THEN
  SIMP_TAC[RING_OF_INTEGERS_COMPLEX_SUBFIELD;
           IMAG_QUADRATIC_FIELD_SUBFIELD] THEN
  REWRITE_TAC[ring_of_integers; imag_quadratic_integers;
              CONJUNCT2 SUBRING_GENERATED] THEN
  SET_TAC[]);;

let DEDEKIND_IMAG_QUADRATIC_INTEGERS = prove
 (`!d. dedekind_domain (imag_quadratic_integers d)`,
  REWRITE_TAC[GSYM RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD] THEN
  SIMP_TAC[DEDEKIND_RING_OF_INTEGERS; IMAG_QUADRATIC_FIELD_NUMBER_FIELD]);;

let IMAG_QUADRATIC_INTEGERS_UFD_EQ_PID = prove
 (`!d. UFD (imag_quadratic_integers d) <=> PID (imag_quadratic_integers d)`,
  SIMP_TAC[DEDEKIND_UFD_IFF_PID; DEDEKIND_IMAG_QUADRATIC_INTEGERS]);;

let IMAG_QUADRATIC_INTEGERS_CLASSES_FINITE = prove
