(* ========================================================================= *)
(* The field Q(sqrt(-d)) inside the complex numbers as a number field of     *)
(* ANT/: its ring of integers, its discriminant, square factors of d.        *)
(*                                                                           *)
(* Purpose: the field imag_quadratic_field d = {a + b sqrt(-d) | a, b        *)
(* rational} (sqrt(-d) = ii sqrt d) is a subfield of complex_ring for every  *)
(* d (IMAG_QUADRATIC_FIELD_SUBFIELD); as a ring it is the subfield generated *)
(* by sqrt(-d) (IMAG_QUADRATIC_FIELD_GENERATED), a number field              *)
(* (IMAG_QUADRATIC_FIELD_NUMBER_FIELD) whose prime subfield is that of C     *)
(* (IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD), of degree 2 for d <> 0             *)
(* (IMAG_QUADRATIC_FIELD_DEGREE), with the square root sqrt(-d) of -d        *)
(* (IMAG_QUADRATIC_FIELD_SQRT). For squarefree d its discriminant is qdisc d *)
(* (IMAG_QUADRATIC_FIELD_DISCRIMINANT), and the field of m^2 k is that of k  *)
(* for m <> 0 (IMAG_QUADRATIC_FIELD_SQUARE_MUL). The ring                    *)
(* imag_quadratic_integers d has the algebraic integers of the field as      *)
(* carrier and the operations of complex_ring                                *)
(* (IMAG_QUADRATIC_INTEGERS_CARRIER_ALT, IMAG_QUADRATIC_INTEGERS_CLAUSES,    *)
(* IMAG_QUADRATIC_INTEGERS_SUB_POW); it is the ring of integers of the field *)
(* (RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD), so ANT/ makes it a Dedekind      *)
(* domain (DEDEKIND_IMAG_QUADRATIC_INTEGERS) with finitely many ideal        *)
(* classes which is a UFD iff a PID (IMAG_QUADRATIC_INTEGERS_UFD_EQ_PID) iff *)
(* its class number is 1 (IMAG_QUADRATIC_INTEGERS_PID_EQ_CLASS_NUMBER_1).    *)
(* The ring of m^2 k is that of k for m <> 0                                 *)
(* (IMAG_QUADRATIC_INTEGERS_SQUARE_MUL), and the ring for d = 0 is Z, a PID  *)
(* (PID_IMAG_QUADRATIC_INTEGERS_0).                                          *)
(*                                                                           *)
(* Method: the field is a subring closed under inverses (inv z = cnj z /     *)
(* |z|^2), hence a subfield; it contains the rationals                       *)
(* (RATIONAL_IN_COMPLEX_SUBFIELD) and sqrt(-d), a root of x^2 + d, so it is  *)
(* the subfield generated by the algebraic number sqrt(-d), a number field   *)
(* (NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED). For d <> 0, real and imaginary *)
(* parts give the uniqueness of the coordinates in the basis 1, sqrt(-d)     *)
(* (IMAG_QUADRATIC_FIELD_FREE_BASIS), so the degree is 2                     *)
(* (NUMBER_FIELD_FREE_BASIS_DEGREE). With x = sqrt(-d), x^2 = D = -d, the    *)
(* discriminant D or 4 D of ANT/quadratic.ml (QUADRATIC_FIELD_DISCRIMINANT)  *)
(* is qdisc d (QDISC_ALT). The rings of integers of subfields of C are their *)
(* algebraic integers (RING_OF_INTEGERS_COMPLEX_SUBFIELD); ANT/ gives        *)
(* DEDEKIND_RING_OF_INTEGERS, DEDEKIND_UFD_IFF_PID,                          *)
(* NUMBER_FIELD_CLASS_GROUP_FINITE and NUMBER_FIELD_PID_EQ_CLASS_NUMBER_1.   *)
(* For d = 0 the canonical map ring_of_int from Z, n |-> Cx(real_of_int n),  *)
(* is an isomorphism onto the ring (RING_MONOMORPHISM_INTEGER_RING_OF_INT,   *)
(* ISOMORPHIC_RING_PIDNESS, PID_INTEGER_RING).                               *)
(*                                                                           *)
(* Main results: the theorems above; general tools: IMAG_QUADRATIC_FIELD_IN, *)
(* IMAG_QUADRATIC_FIELD_SUBRING, IMAG_QUADRATIC_FIELD_FREE_BASIS,            *)
(* IMAG_QUADRATIC_INTEGERS_IN_ALT, IMAG_QUADRATIC_INTEGERS_INTEGRAL_DOMAIN,  *)
(* IMAG_QUADRATIC_INTEGERS_CLASSES_FINITE, QDISC_ALT; helper names QUAD_*    *)
(* and IMAG_QUADRATIC_*.                                                     *)
(*                                                                           *)
(* Uses: Baker/quadint_defs.ml (imag_quadratic_field,                        *)
(* imag_quadratic_integers); Baker/ant_bridge_complex.ml                     *)
(* (RATIONAL_IN_COMPLEX_SUBFIELD, RING_OF_INTEGERS_COMPLEX_SUBFIELD,         *)
(* NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED); Baker/algint.ml                 *)
(* (algebraic_integer, ALGEBRAIC_INTEGER_MONIC, ALGEBRAIC_INTEGER_RATIONAL,  *)
(* closure lemmas); ANT/complex_embeddings.ml (COMPLEX_PRIME_SUBFIELD);      *)
(* Baker/classno_defs.ml (qdisc); ANT/algmisc.ml (FORALL_LT_2);              *)
(* Library/ringtheory.ml (RING_SUM_LT_2); ANT/numfield.ml                    *)
(* (NUMBER_FIELD_FREE_BASIS_DEGREE); ANT/ring_of_integers.ml                 *)
(* (DEDEKIND_RING_OF_INTEGERS); ANT/dedekind_struct.ml                       *)
(* (DEDEKIND_UFD_IFF_PID); ANT/classgroup.ml                                 *)
(* (NUMBER_FIELD_CLASS_GROUP_FINITE, NUMBER_FIELD_PID_EQ_CLASS_NUMBER_1);    *)
(* ANT/quadratic.ml (QUADRATIC_FIELD_DISCRIMINANT); Library/fieldtheory.ml   *)
(* (PRIME_SUBFIELD_SUBFIELD, SUBFIELD_OF_FIELD_INV,                          *)
(* SUBFIELD_GENERATED_MINIMAL); Library/ringtheory.ml                        *)
(* (CARRIER_SUBRING_GENERATED_SUBRING, SUBRING_OF_INTER,                     *)
(* RING_MONOMORPHISM_INTEGER_RING_OF_INT, ISOMORPHIC_RING_PIDNESS,           *)
(* PID_INTEGER_RING); Library/pocklington.ml (squarefree,                    *)
(* SQUAREFREE_IMP_NZ); Multivariate/complex_ring.ml (complex_ring,           *)
(* FIELD_COMPLEX_RING, COMPLEX_RING_INV, COMPLEX_RING_OF_INT).               *)
(* ========================================================================= *)

