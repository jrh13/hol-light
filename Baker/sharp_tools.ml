(* ========================================================================= *)
(* Sharpening I: number field tools.                                         *)
(*                                                                           *)
(* Purpose: the number field facts used by the uniform base of Sharpening I  *)
(* (Baker/sharp_uniform.ml), by its two descents (Baker/sharp_descent.ml,    *)
(* integer coefficients; Baker/sharpc_descent.ml, algebraic coefficients)    *)
(* and by the Schinzel-Tijdeman theorem (Baker/schinzel_sunit.ml,            *)
(* Baker/schinzel_general.ml), for fields F = subfield_generated             *)
(* complex_ring s generated by a finite set s of algebraic numbers (number   *)
(* fields by NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED), of degree             *)
(* D = extension_degree (Q, F) I with Q = subfield_generated complex_ring    *)
(* {Cx(&0)}; the conjugates of x in F are the g x for the complex            *)
(* embeddings g of F (ANT/complex_embeddings.ml). No Weil height is used:    *)
(* heights are classical heights of integer polynomials, as in the Baker     *)
(* core; elements of F are measured by an integer denominator and a bound    *)
(* for their conjugates (sharp_nfbound s x den R of Baker/sharp_defs.ml).    *)
(*                                                                           *)
(* Main results:                                                             *)
(*  - COMPLEX_ROOT_DENOMINATOR (Baker, Stark 1971, Lemma 4): if d x^p is an  *)
(*    algebraic integer for an integer d >= 1, then so is b x for an         *)
(*    integer b >= 1 with b^p <= d^D. From NUMBER_FIELD_ROOT_DENOMINATOR of  *)
(*    ANT/nf_valuation.ml (denominator ideal, valuations and ideal norms)    *)
(*    and N((d)) = d^D (RING_OF_INTEGERS_IDEAL_NORM_INTEGER).                *)
(*  - COMPLEX_SUBFIELD_GENERATED_DEGREE: the field generated by roots al r   *)
(*    (r = 1..n) of nonzero integer polynomials of degrees dd r has degree   *)
(*    at most the product of the dd r (tower law EXTENSION_DEGREE_TOWER_LAW  *)
(*    and the degree bound COMPLEX_SUBFIELD_ROOT_DEGREE for one root).       *)
(*  - COMPLEX_SUBFIELD_ELEMENT_POLY: an element x of F with b x an algebraic *)
(*    integer (b >= 1 an integer) and conjugates of modulus at most R >= 1   *)
(*    is a root of an integer polynomial of degree at most D with            *)
(*    coefficients at most (2 b R)^D. The monic integer polynomial c of b x  *)
(*    with the conjugates as roots (RING_OF_INTEGERS_CONJUGATES_POLYFUN)     *)
(*    gives the monic polynomial c(b X) / b^n whose roots have modulus at    *)
(*    most R, so its coefficients are at most (1 + R)^n                      *)
(*    (COMPLEX_POLYFUN_MONIC_COEFF_BOUND of ANT/complex_embeddings.ml).      *)
(*  - COMPLEX_EMBEDDING_POLY_ROOT: complex embeddings map roots of integer   *)
(*    polynomials to roots (BRIDGE_NF_HOM_POLY).                             *)
(*  - INTEGER_POLY_ROOT_LEADING_INTEGER, INTEGER_POLY_ROOT_INV_INTEGER: for  *)
(*    a root z of an integer polynomial a of degree d, a d z is an algebraic *)
(*    integer, and so is a k / z for some k <= d with a k <> 0 if z <> 0.    *)
(*  - The calculus of sharp_nfbound: SHARP_NFBOUND_EMBEDDING, _ONE, _MUL,    *)
(*    _POW, _CPRODUCT, _MONO, _DEN; SHARP_NFBOUND_ROOT and                   *)
(*    SHARP_NFBOUND_INV_ROOT (a root x in F of an integer polynomial of      *)
(*    degree d and height H has denominator |a d| and conjugates at most     *)
(*    1 + d H, its inverse denominator <= H and conjugates at most 2 H);     *)
(*    SHARP_NFBOUND_SUB1_LOWER (x <> 1 gives |x - 1| >= 1 / (2 (2 den        *)
(*    (R + 1))^E) for [F:Q] <= E: the polynomial of x - 1 of                 *)
(*    COMPLEX_SUBFIELD_ELEMENT_POLY and ALGEBRAIC_ROOT_LOWER_BOUND);         *)
(*    SHARP_NFBOUND_CEXP_INT and SHARP_NFBOUND_CEXP_VSUM (exponentials of    *)
(*    integer linear forms in logarithms of roots in F).                     *)
(*  - SHARP_LOG_ALG_SIZE: a principal logarithm lg of a root of an integer   *)
(*    polynomial of degree d <= D and height H <= exp G (G >= 1) has         *)
(*    |lg| <= (D + 5) G and is 0 or of size >= exp(-(D + 2) (D + 3) G);      *)
(*    SHARP_LOG_ALG_ARITH.                                                   *)
(*                                                                           *)
(* Also: RING_OF_INTEGERS_COMPLEX_SUBFIELD_GENERATED (the ring of integers   *)
(* of F is the set of algebraic integers of F, a subring of C),              *)
(* COMPLEX_SUBFIELD_GENERATED_ALGEBRAIC (the                                 *)
(* elements of F are algebraic), COMPLEX_EMBEDDING_CMUL_INTEGER,             *)
(* COMPLEX_SUBFIELD_INSERT_DEGREE ([F(z):Q] <= [F:Q] d for a root z of an    *)
(* integer polynomial of degree d).                                          *)
(*                                                                           *)
(* Uses: ANT/nf_valuation.ml (NUMBER_FIELD_ROOT_DENOMINATOR),                *)
(* ANT/ring_of_integers.ml (RING_OF_INTEGERS_IDEAL_NORM_INTEGER),            *)
(* ANT/numfield.ml (RING_OF_INTEGERS_SUBRING), ANT/complex_embeddings.ml     *)
(* (complex_embeddings, RING_OF_INTEGERS_CONJUGATES_POLYFUN,                 *)
(* COMPLEX_EMBEDDINGS_RESTRICTION, COMPLEX_POLYFUN_MONIC_COEFF_BOUND),       *)
(* Library/fieldtheory.ml (EXTENSION_DEGREE_TOWER_LAW,                       *)
(* FINITE_IMP_FIELD_EXTENSION, SUBFIELD_GENERATED_INSERT,                    *)
(* SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED, SUBFIELD_SUBFIELD_GENERATED,    *)
(* SUBFIELD_OF_ALGEBRAIC_OVER, IN_SUBFIELD_INV), 100/transcendence.ml        *)
(* (ALGEBRAIC_OVER_QINC_COMPLEX), Baker/ant_bridge_complex.ml                *)
(* (RING_OF_INTEGERS_COMPLEX_SUBFIELD,                                       *)
(* NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED, BRIDGE_NF_PRIME_SUBFIELD,        *)
(* BRIDGE_NF_SUBFIELD_RATIONAL, BRIDGE_NF_SUBFIELD_CLOSED,                   *)
(* BRIDGE_NF_GEN_IN, BRIDGE_NF_HOM_CLAUSES, BRIDGE_NF_HOM_POLY,              *)
(* BRIDGE_NF_HOM_INTEGER), Baker/algint.ml (algebraic_integer,               *)
(* ALGEBRAIC_INTEGER_MONIC and the closure lemmas), Baker/kummer.ml          *)
(* (COMPLEX_SUBFIELD_ROOT_DEGREE), Baker/sharp_defs.ml (sharp_algdata,       *)
(* sharp_nfbound), Baker/sharp_num.ml (SHARP_ALGDATA_LG_BOUND),              *)
(* Baker/bridge.ml (EXPLICIT_IMP_ALGEBRAIC_NUMBER,                           *)
(* ALGEBRAIC_NUMBER_EXPLICIT), Baker/liouville_inequality.ml                 *)
(* (INTEGER_POLY_ROOT_BOUND), Baker/simple.ml (ALGEBRAIC_ROOT_LOWER_BOUND),  *)
(* Baker/auxiliary.ml (NORM_CEXP_SUB_1_LE), Baker/lemmas.ml                  *)
(* (COMPLEX_SUBRING_OF, REAL_LE_1_MUL).                                      *)
(* ========================================================================= *)

