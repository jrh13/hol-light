let SHARP_LOG_ALG_ARITH = prove
 (`!X d D G y.
        &1 <= X /\ X <= exp(&(D + 4) * G) /\ d <= D /\ &1 <= G /\
        &0 <= y /\ inv(&2 * X pow d) <= y * exp(&(D + 5) * G)
        ==> exp(--(&((D + 2) * (D + 3)) * G)) <= y`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `X pow d <= exp(&(D * (D + 4)) * G)` ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `exp(&(D + 4) * G) pow D` THEN CONJ_TAC THENL
     [TRANS_TAC REAL_LE_TRANS `X pow D` THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_POW_MONO THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC];
      REWRITE_TAC[GSYM REAL_EXP_N; REAL_EXP_MONO_LE] THEN
      REWRITE_TAC[GSYM REAL_OF_NUM_MUL; REAL_MUL_ASSOC; REAL_LE_REFL]];
    ALL_TAC] THEN
  SUBGOAL_THEN `&2 <= exp G` ASSUME_TAC THENL
   [MP_TAC(SPEC `G:real` REAL_EXP_LE_X) THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `&0 < X pow d` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_POW_LT THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `exp(--(G + &(D * (D + 4)) * G)) <= inv(&2 * X pow d)`
  ASSUME_TAC THENL
   [REWRITE_TAC[REAL_EXP_NEG] THEN MATCH_MP_TAC REAL_LE_INV2 THEN
    CONJ_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[REAL_EXP_ADD] THEN MATCH_MP_TAC REAL_LE_MUL2 THEN
    ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `&((D + 2) * (D + 3)) * G = (G + &(D * (D + 4)) * G) + &(D + 5) * G`
  SUBST1_TAC THENL
   [REWRITE_TAC[GSYM REAL_OF_NUM_MUL; GSYM REAL_OF_NUM_ADD] THEN
    CONV_TAC REAL_RING;
    ALL_TAC] THEN
  ONCE_REWRITE_TAC[REAL_ARITH `--(a + b:real) = --a - b`] THEN
  REWRITE_TAC[REAL_EXP_SUB] THEN
  SIMP_TAC[REAL_LE_LDIV_EQ; REAL_EXP_POS_LT] THEN
  TRANS_TAC REAL_LE_TRANS `inv(&2 * X pow d)` THEN ASM_REWRITE_TAC[]);;

let SHARP_LOG_ALG_SIZE = prove
 (`!lg (a:num->real) d H G D.
        --pi < Im lg /\ Im lg <= pi /\ 1 <= d /\ d <= D /\ &1 <= G /\
        H <= exp G /\ (!j. integer(a j) /\ abs(a j) <= H) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * cexp lg pow j) = Cx(&0)
        ==> norm lg <= &(D + 5) * G /\
            (lg = Cx(&0) \/ exp(--(&((D + 2) * (D + 3)) * G)) <= norm lg)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `&1 <= H` ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `abs((a:num->real) d)` THEN
    ASM_SIMP_TAC[REAL_ABS_INTEGER_LEMMA];
    ALL_TAC] THEN
  SUBGOAL_THEN `norm(cexp lg) <= &1 + &d * H` ASSUME_TAC THENL
   [MATCH_MP_TAC INTEGER_POLY_ROOT_BOUND THEN EXISTS_TAC `a:num->real` THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `inv(&2 * H) <= norm(cexp lg)` ASSUME_TAC THENL
   [MATCH_MP_TAC ALGEBRAIC_ROOT_LOWER_BOUND THEN
    MAP_EVERY EXISTS_TAC [`a:num->real`; `d:num`] THEN
    ASM_REWRITE_TAC[CEXP_NZ];
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= &D /\ &d <= &D /\ &0 <= &d` STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LE] THEN ASM_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `&2 <= exp(&1)` ASSUME_TAC THENL
   [MP_TAC(SPEC `&1` REAL_EXP_LE_X) THEN REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `norm(lg:complex) <= &(D + 5) * G` ASSUME_TAC THENL
   [MP_TAC(ISPECL [`1`; `\r:num. (lg:complex)`; `\r:num. (a:num->real)`;
                   `\r:num. (d:num)`; `\r:num. (H:real)`; `D:num`; `1`]
      SHARP_ALGDATA_LG_BOUND) THEN
    ASM_REWRITE_TAC[sharp_algdata; NUMSEG_SING; IN_SING] THEN
    SUBGOAL_THEN `log H <= G /\ &D <= &D * G` MP_TAC THENL
     [CONJ_TAC THENL
       [GEN_REWRITE_TAC RAND_CONV [GSYM LOG_EXP] THEN
        MATCH_MP_TAC LOG_MONO_LE_IMP THEN ASM_REAL_ARITH_TAC;
        GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_RID] THEN
        MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REAL_ARITH_TAC];
      REWRITE_TAC[GSYM REAL_OF_NUM_ADD] THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN
  ASM_CASES_TAC `lg = Cx(&0)` THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `~(cexp lg = Cx(&1))` ASSUME_TAC THENL
   [REWRITE_TAC[CEXP_EQ_1] THEN
    DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (X_CHOOSE_THEN `k:real`
      STRIP_ASSUME_TAC)) THEN
    UNDISCH_TAC `~(lg = Cx(&0))` THEN
    REWRITE_TAC[COMPLEX_EQ; RE_CX; IM_CX] THEN ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `k = &0` THEN
    ASM_REWRITE_TAC[REAL_MUL_LZERO; REAL_MUL_RZERO] THEN
    MP_TAC(SPEC `k:real` REAL_ABS_INTEGER_LEMMA) THEN ASM_REWRITE_TAC[] THEN
    DISCH_TAC THEN
    SUBGOAL_THEN `pi <= abs(k * pi)` MP_TAC THENL
     [REWRITE_TAC[REAL_ABS_MUL] THEN
      SUBGOAL_THEN `abs pi = pi` SUBST1_TAC THENL
       [MP_TAC PI_POS THEN REAL_ARITH_TAC; ALL_TAC] THEN
      GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_LID] THEN
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
      MP_TAC PI_POS THEN REAL_ARITH_TAC;
      ALL_TAC] THEN
    UNDISCH_TAC `--pi < Im lg` THEN UNDISCH_TAC `Im lg <= pi` THEN
    ASM_REWRITE_TAC[] THEN MP_TAC PI_POS THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  MP_TAC(ISPECL [`{cexp lg}`; `cexp lg`; `abs((a:num->real) d)`;
                 `&1 + &d * H`; `d:num`] SHARP_NFBOUND_SUB1_LOWER) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[FINITE_SING; IN_SING] THEN REPEAT CONJ_TAC THENL
     [GEN_TAC THEN DISCH_THEN SUBST1_TAC THEN
      REWRITE_TAC[ALGEBRAIC_NUMBER_EXPLICIT] THEN
      MAP_EVERY EXISTS_TAC [`d:num`; `a:num->real`] THEN ASM_SIMP_TAC[];
      MP_TAC(ISPECL [`1`; `\r:num. cexp lg`; `\r:num. (a:num->real)`;
                     `\r:num. (d:num)`] COMPLEX_SUBFIELD_GENERATED_DEGREE) THEN
      REWRITE_TAC[NUMSEG_SING; IN_SING; IMAGE_CLAUSES; NPRODUCT_SING] THEN
      DISCH_THEN MATCH_MP_TAC THEN GEN_TAC THEN DISCH_THEN(K ALL_TAC) THEN
      ASM_SIMP_TAC[];
      MATCH_MP_TAC SHARP_NFBOUND_ROOT THEN ASM_REWRITE_TAC[BRIDGE_NF_GEN_IN];
      MATCH_MP_TAC REAL_LE_ADD THEN REWRITE_TAC[REAL_POS] THEN
      MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC;
      ASM_REWRITE_TAC[]];
    ALL_TAC] THEN
  DISCH_TAC THEN MATCH_MP_TAC SHARP_LOG_ALG_ARITH THEN
  MAP_EVERY EXISTS_TAC
   [`&2 * abs((a:num->real) d) * ((&1 + &d * H) + &1)`; `d:num`] THEN
  ASM_REWRITE_TAC[NORM_POS_LE] THEN REPEAT CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_1_MUL THEN CONJ_TAC THENL
     [REAL_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_SIMP_TAC[REAL_ABS_INTEGER_LEMMA] THEN
    SUBGOAL_THEN `&0 <= &d * H` MP_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC; REAL_ARITH_TAC];
    SUBGOAL_THEN `&(D + 4) * G = (&D + &2) * G + G + G` SUBST1_TAC THENL
     [REWRITE_TAC[GSYM REAL_OF_NUM_ADD] THEN REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[REAL_EXP_ADD] THEN
    SUBGOAL_THEN `abs((a:num->real) d) <= exp G /\ &0 <= abs(a d)`
    STRIP_ASSUME_TAC THENL
     [ASM_MESON_TAC[REAL_LE_TRANS; REAL_ABS_POS]; ALL_TAC] THEN
    SUBGOAL_THEN `&2 * (&2 + &D) <= exp((&D + &2) * G)` ASSUME_TAC THENL
     [TRANS_TAC REAL_LE_TRANS `exp(&1) * exp(&1 + &D)` THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[] THEN
        MP_TAC(SPEC `&1 + &D` REAL_EXP_LE_X) THEN ASM_REAL_ARITH_TAC;
        REWRITE_TAC[GSYM REAL_EXP_ADD; REAL_EXP_MONO_LE] THEN
        SUBGOAL_THEN `(&D + &2) * &1 <= (&D + &2) * G` MP_TAC THENL
         [MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REAL_ARITH_TAC;
          REAL_ARITH_TAC]];
      ALL_TAC] THEN
    SUBGOAL_THEN `(&1 + &d * H) + &1 <= (&2 + &D) * exp G` ASSUME_TAC THENL
     [TRANS_TAC REAL_LE_TRANS `(&2 + &D) * H` THEN CONJ_TAC THENL
       [SUBGOAL_THEN `&d * H <= &D * H` MP_TAC THENL
         [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC;
          ASM_REAL_ARITH_TAC];
        MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REAL_ARITH_TAC];
      ALL_TAC] THEN
    TRANS_TAC REAL_LE_TRANS `(&2 * (&2 + &D)) * exp G * exp G` THEN
    CONJ_TAC THENL
     [SUBGOAL_THEN
       `(&2 * (&2 + &D)) * exp G * exp G =
        &2 * exp G * ((&2 + &D) * exp G)` SUBST1_TAC THENL
       [REAL_ARITH_TAC; ALL_TAC] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN CONJ_TAC THENL
       [REAL_ARITH_TAC; ALL_TAC] THEN
      MATCH_MP_TAC REAL_LE_MUL2 THEN ASM_REWRITE_TAC[] THEN
      SUBGOAL_THEN `&0 <= &d * H` MP_TAC THENL
       [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC; REAL_ARITH_TAC];
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_EXP_POS_LE]];
    TRANS_TAC REAL_LE_TRANS `norm(cexp lg - Cx(&1))` THEN
    ASM_REWRITE_TAC[] THEN
    TRANS_TAC REAL_LE_TRANS `norm(lg:complex) * exp(norm lg)` THEN
    REWRITE_TAC[NORM_CEXP_SUB_1_LE] THEN MATCH_MP_TAC REAL_LE_LMUL THEN
    ASM_REWRITE_TAC[NORM_POS_LE; REAL_EXP_MONO_LE]]);;
