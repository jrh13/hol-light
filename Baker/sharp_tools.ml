(* ------------------------------------------------------------------------- *)
(* The ring of integers of a generated subfield of C.                        *)
(* ------------------------------------------------------------------------- *)

let RING_OF_INTEGERS_COMPLEX_SUBFIELD_GENERATED = prove
 (`!s. ring_carrier(ring_of_integers(subfield_generated complex_ring s)) =
       {z | z IN ring_carrier(subfield_generated complex_ring s) /\
            algebraic_integer z} /\
       (ring_carrier(ring_of_integers(subfield_generated complex_ring s)))
         subring_of complex_ring`,
  GEN_TAC THEN CONJ_TAC THENL
   [MP_TAC(ISPEC `ring_carrier(subfield_generated complex_ring s)`
      RING_OF_INTEGERS_COMPLEX_SUBFIELD) THEN
    SIMP_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED;
             SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING];
    MESON_TAC[RING_OF_INTEGERS_SUBRING; SUBRING_OF_SUBFIELD_GENERATED_EQ]]);;

(* The elements of a subfield of C generated by algebraic numbers are        *)
(* algebraic (the algebraic numbers form a subfield of C,                    *)
(* SUBFIELD_OF_ALGEBRAIC_OVER).                                              *)

let COMPLEX_SUBFIELD_GENERATED_ALGEBRAIC = prove
 (`!s x. (!z. z IN s ==> algebraic_number z) /\
         x IN ring_carrier(subfield_generated complex_ring s)
         ==> algebraic_number x`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`complex_ring`; `{z | algebraic_number z}`;
                 `s:complex->bool`] SUBFIELD_GENERATED_MINIMAL) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN
    MP_TAC(ISPECL [`I:complex->complex`; `QinC_ring`; `complex_ring`]
      SUBFIELD_OF_ALGEBRAIC_OVER) THEN
    REWRITE_TAC[FIELD_EXTENSION_QINC_COMPLEX; ALGEBRAIC_OVER_QINC_COMPLEX];
    REWRITE_TAC[SUBSET; IN_ELIM_THM] THEN DISCH_THEN MATCH_MP_TAC THEN
    FIRST_ASSUM ACCEPT_TAC]);;

(* ------------------------------------------------------------------------- *)
(* Denominators of p-th roots (Baker and Stark 1971, Lemma 4).               *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_ROOT_DENOMINATOR = prove
 (`!s x d p.
        FINITE s /\ (!z. z IN s ==> algebraic_number z) /\
        x IN ring_carrier(subfield_generated complex_ring s) /\
        integer d /\ &1 <= d /\ 1 <= p /\ algebraic_integer(Cx d * x pow p)
        ==> ?b. integer b /\ &1 <= b /\
                b pow p <=
                d pow
                extension_degree (subfield_generated complex_ring {Cx(&0)},
                                  subfield_generated complex_ring s) I /\
                algebraic_integer(Cx b * x)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPEC `d:real` INTEGER_POS) THEN
  ANTS_TAC THENL [ASM_REAL_ARITH_TAC; ASM_REWRITE_TAC[]] THEN
  DISCH_THEN(X_CHOOSE_THEN `n:num` SUBST_ALL_TAC) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[REAL_OF_NUM_LE]) THEN
  MP_TAC(ISPECL [`subfield_generated complex_ring s`; `x:complex`;
                 `Cx(&n)`; `p:num`] NUMBER_FIELD_ROOT_DENOMINATOR) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED;
               RING_OF_INTEGERS_COMPLEX_SUBFIELD_GENERATED; IN_ELIM_THM;
               ALGEBRAIC_INTEGER_NUM;
               BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_NUM;
               BRIDGE_NF_SUBFIELD_CLOSED; CONJUNCT2 SUBFIELD_GENERATED;
               RING_POW_SUBFIELD_GENERATED; COMPLEX_RING_CLAUSES;
               COMPLEX_RING_POW; CX_INJ; REAL_OF_NUM_EQ;
               ARITH_RULE `1 <= n ==> ~(n = 0)`] THEN
  MP_TAC(ISPECL [`subfield_generated complex_ring s`; `&n:int`]
    RING_OF_INTEGERS_IDEAL_NORM_INTEGER) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED; RING_OF_INT_OF_NUM;
               RING_OF_NUM_SUBFIELD_GENERATED; COMPLEX_RING_OF_NUM;
               INT_OF_NUM_EQ; INT_ABS_NUM; NUM_OF_INT_OF_NUM;
               BRIDGE_NF_PRIME_SUBFIELD; ARITH_RULE `1 <= n ==> ~(n = 0)`] THEN
  DISCH_THEN SUBST1_TAC THEN
  DISCH_THEN(X_CHOOSE_THEN `b:num` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `&b:real` THEN
  ASM_REWRITE_TAC[INTEGER_CLOSED; REAL_OF_NUM_LE; REAL_OF_NUM_POW]);;

(* ------------------------------------------------------------------------- *)
(* Complex embeddings fix the integers and map roots of integer polynomials  *)
(* to roots.                                                                 *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_EMBEDDING_POLY_ROOT = prove
 (`!s g z (a:num->real) d.
        g IN complex_embeddings(subfield_generated complex_ring s) /\
        z IN ring_carrier(subfield_generated complex_ring s) /\
        (!j. integer(a j)) /\ vsum(0..d) (\j. Cx(a j) * z pow j) = Cx(&0)
        ==> vsum(0..d) (\j. Cx(a j) * g z pow j) = Cx(&0)`,
  REWRITE_TAC[complex_embeddings; IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`s:complex->bool`; `g:complex->complex`; `z:complex`;
                 `a:num->real`; `d:num`] BRIDGE_NF_HOM_POLY) THEN
  ASM_SIMP_TAC[RATIONAL_INTEGER] THEN DISCH_THEN(SUBST1_TAC o SYM) THEN
  MATCH_MP_TAC BRIDGE_NF_HOM_INTEGER THEN
  EXISTS_TAC `s:complex->bool` THEN ASM_REWRITE_TAC[INTEGER_CLOSED]);;

let COMPLEX_EMBEDDING_CMUL_INTEGER = prove
 (`!s g b x.
        g IN complex_embeddings(subfield_generated complex_ring s) /\
        integer b /\ x IN ring_carrier(subfield_generated complex_ring s)
        ==> g(Cx b * x) = Cx b * g x`,
  REWRITE_TAC[complex_embeddings; IN_ELIM_THM] THEN REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP BRIDGE_NF_HOM_CLAUSES) THEN
  ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_INTEGER]);;

(* ------------------------------------------------------------------------- *)
(* An element with denominator b and conjugates of modulus at most R is a    *)
(* root of an integer polynomial of degree at most D with coefficients at    *)
(* most (2 b R)^D.                                                           *)
(* ------------------------------------------------------------------------- *)

let COMPLEX_SUBFIELD_ELEMENT_POLY = prove
 (`!s x b R.
        FINITE s /\ (!z. z IN s ==> algebraic_number z) /\
        x IN ring_carrier(subfield_generated complex_ring s) /\
        integer b /\ &1 <= b /\ algebraic_integer(Cx b * x) /\ &1 <= R /\
        (!g. g IN complex_embeddings(subfield_generated complex_ring s)
             ==> norm(g x) <= R)
        ==> ?dx (ax:num->real).
              1 <= dx /\
              dx <= extension_degree (subfield_generated complex_ring {Cx(&0)},
                                      subfield_generated complex_ring s) I /\
              (!j. integer(ax j) /\ abs(ax j) <= (&2 * b * R) pow dx) /\
              ~(ax dx = &0) /\
              vsum(0..dx) (\j. Cx(ax j) * x pow j) = Cx(&0)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `Cx b * x IN ring_carrier(ring_of_integers
                              (subfield_generated complex_ring s))`
  ASSUME_TAC THENL
   [ASM_REWRITE_TAC[RING_OF_INTEGERS_COMPLEX_SUBFIELD_GENERATED;
                    IN_ELIM_THM] THEN
    MATCH_MP_TAC(CONJUNCT1(CONJUNCT2 BRIDGE_NF_SUBFIELD_CLOSED)) THEN
    ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_INTEGER];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`subfield_generated complex_ring s`; `Cx b * x`]
    RING_OF_INTEGERS_CONJUGATES_POLYFUN) THEN
  ASM_SIMP_TAC[NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED;
               BRIDGE_NF_PRIME_SUBFIELD] THEN
  DISCH_THEN(X_CHOOSE_THEN `n:num` (X_CHOOSE_THEN `c:num->real`
    STRIP_ASSUME_TAC)) THEN
  SUBGOAL_THEN
   `!w. vsum(0..n) (\i. Cx(c i) * w pow i) = Cx(&0)
        ==> ?g. g IN complex_embeddings(subfield_generated complex_ring s) /\
                w = Cx b * g x`
  ASSUME_TAC THENL
   [X_GEN_TAC `w:complex` THEN DISCH_TAC THEN
    SUBGOAL_THEN
     `w IN IMAGE (\g. g(Cx b * x))
                 (complex_embeddings(subfield_generated complex_ring s))`
    MP_TAC THENL [ASM_REWRITE_TAC[IN_ELIM_THM]; REWRITE_TAC[IN_IMAGE]] THEN
    MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `g:complex->complex` THEN
    STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC COMPLEX_EMBEDDING_CMUL_INTEGER THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `vsum(0..n) (\i. Cx(c i) * (Cx b * x) pow i) = Cx(&0)`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`subfield_generated complex_ring s`; `\z:complex. z`]
      COMPLEX_EMBEDDINGS_RESTRICTION) THEN
    ANTS_TAC THENL
     [MP_TAC(ISPECL [`complex_ring`;
                     `ring_carrier(subfield_generated complex_ring s)`]
        RING_HOMOMORPHISM_INCLUSION) THEN
      REWRITE_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED];
      DISCH_THEN(X_CHOOSE_THEN `g0:complex->complex`
        (STRIP_ASSUME_TAC o BETA_RULE))] THEN
    SUBGOAL_THEN
     `Cx b * x IN IMAGE (\g. g(Cx b * x))
                   (complex_embeddings(subfield_generated complex_ring s))`
    MP_TAC THENL
     [REWRITE_TAC[IN_IMAGE] THEN EXISTS_TAC `g0:complex->complex` THEN
      ASM_REWRITE_TAC[] THEN CONV_TAC SYM_CONV THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN
      MATCH_MP_TAC(CONJUNCT1(CONJUNCT2 BRIDGE_NF_SUBFIELD_CLOSED)) THEN
      ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_INTEGER];
      ASM_REWRITE_TAC[IN_ELIM_THM]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!i. i <= n ==> abs(c i * b pow i) <= (&2 * b * R) pow n`
  ASSUME_TAC THENL
   [MP_TAC(ISPECL [`n:num`; `\i. Cx((c i * b pow i) / b pow n)`; `R:real`]
      COMPLEX_POLYFUN_MONIC_COEFF_BOUND) THEN
    ANTS_TAC THENL
     [CONJ_TAC THENL
       [ASM_SIMP_TAC[REAL_MUL_LID; REAL_DIV_REFL; REAL_POW_EQ_0;
                     REAL_ARITH `&1 <= b ==> ~(b = &0)`];
        X_GEN_TAC `w:complex` THEN BETA_TAC THEN DISCH_TAC] THEN
      SUBGOAL_THEN `vsum(0..n) (\i. Cx(c i) * (Cx b * w) pow i) = Cx(&0)`
      MP_TAC THENL
       [MP_TAC(ISPECL [`inv(Cx b pow n)`;
                       `\i. Cx(c i) * (Cx b * w) pow i`; `0..n`]
          VSUM_COMPLEX_LMUL) THEN
        REWRITE_TAC[FINITE_NUMSEG] THEN
        SUBGOAL_THEN `~(Cx b pow n = Cx(&0))` ASSUME_TAC THENL
         [REWRITE_TAC[COMPLEX_POW_EQ_0; CX_INJ] THEN ASM_REAL_ARITH_TAC;
          ALL_TAC] THEN
        SUBGOAL_THEN
         `vsum(0..n) (\i. inv(Cx b pow n) * Cx(c i) * (Cx b * w) pow i) =
          vsum(0..n) (\i. Cx((c i * b pow i) / b pow n) * w pow i)`
        SUBST1_TAC THENL
         [MATCH_MP_TAC VSUM_EQ_NUMSEG THEN REPEAT STRIP_TAC THEN
          REWRITE_TAC[CX_MUL; CX_DIV; CX_POW; complex_div;
                      COMPLEX_POW_MUL] THEN
          CONV_TAC COMPLEX_RING;
          ASM_REWRITE_TAC[] THEN DISCH_THEN(MP_TAC o SYM) THEN
          ASM_REWRITE_TAC[COMPLEX_ENTIRE; COMPLEX_INV_EQ_0]];
        DISCH_THEN(MP_TAC o MATCH_MP (ASSUME
         `!w. vsum(0..n) (\i. Cx(c i) * w pow i) = Cx(&0)
              ==> ?g. g IN complex_embeddings
                             (subfield_generated complex_ring s) /\
                      w = Cx b * g x`)) THEN
        DISCH_THEN(X_CHOOSE_THEN `g:complex->complex` STRIP_ASSUME_TAC) THEN
        SUBGOAL_THEN `w = (g:complex->complex) x` SUBST1_TAC THENL
         [MATCH_MP_TAC(COMPLEX_FIELD
           `!b. ~(b = Cx(&0)) /\ b * w = b * y ==> w = y`) THEN
          EXISTS_TAC `Cx b` THEN ASM_REWRITE_TAC[CX_INJ] THEN
          ASM_REAL_ARITH_TAC;
          ASM_SIMP_TAC[]]];
      ALL_TAC] THEN
    DISCH_TAC THEN X_GEN_TAC `i:num` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `i:num`) THEN
    ASM_REWRITE_TAC[COMPLEX_NORM_CX] THEN
    SUBGOAL_THEN `&0 < b pow n` ASSUME_TAC THENL
     [MATCH_MP_TAC REAL_POW_LT THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    ASM_SIMP_TAC[REAL_ABS_DIV; REAL_ARITH `&0 < x ==> abs x = x`;
                 REAL_LE_LDIV_EQ] THEN
    MATCH_MP_TAC(REAL_ARITH `(y:real) <= z ==> x <= y ==> x <= z`) THEN
    REWRITE_TAC[GSYM REAL_POW_MUL] THEN MATCH_MP_TAC REAL_POW_LE2 THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC;
      ONCE_REWRITE_TAC[REAL_ARITH `&2 * b * R = (&2 * R) * b`] THEN
      MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  MAP_EVERY EXISTS_TAC
   [`n:num`; `\j. if j <= n then c j * b pow j else &0`] THEN
  ASM_REWRITE_TAC[LE_REFL; REAL_MUL_LID] THEN REPEAT CONJ_TAC THENL
   [X_GEN_TAC `j:num` THEN COND_CASES_TAC THEN
    ASM_SIMP_TAC[INTEGER_CLOSED; REAL_ABS_NUM] THEN
    MATCH_MP_TAC REAL_POW_LE THEN
    REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN ASM_REAL_ARITH_TAC;
    REWRITE_TAC[REAL_POW_EQ_0] THEN ASM_REAL_ARITH_TAC;
    FIRST_X_ASSUM(SUBST1_TAC o SYM o check (is_eq o concl)) THEN
    MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `j:num` THEN STRIP_TAC THEN
    ASM_REWRITE_TAC[CX_MUL; CX_POW; COMPLEX_POW_MUL] THEN
    CONV_TAC COMPLEX_RING]);;

(* ------------------------------------------------------------------------- *)
(* The degree of the field generated by roots of integer polynomials.        *)
(* ------------------------------------------------------------------------- *)

(* Adjoining a root z of an integer polynomial of exact degree d multiplies  *)
(* the degree by at most d: [F(z):F] <= d (COMPLEX_SUBFIELD_ROOT_DEGREE over *)
(* the subfield F) and the tower law.                                        *)

let COMPLEX_SUBFIELD_INSERT_DEGREE = prove
 (`!t z (a:num->real) d.
        FINITE t /\ (!w. w IN t ==> algebraic_number w) /\
        (!j. integer(a j)) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * z pow j) = Cx(&0)
        ==> extension_degree (subfield_generated complex_ring {Cx(&0)},
                              subfield_generated complex_ring (z INSERT t)) I
            <= extension_degree (subfield_generated complex_ring {Cx(&0)},
                                 subfield_generated complex_ring t) I * d`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`ring_carrier(subfield_generated complex_ring t)`;
                 `\j. Cx((a:num->real) j)`; `d:num`; `z:complex`]
    COMPLEX_SUBFIELD_ROOT_DEGREE) THEN
  ASM_SIMP_TAC[SUBFIELD_GENERATED_BY_SUBFIELD_GENERATED;
               SUBFIELD_GENERATED_INSERT; SUBFIELD_SUBFIELD_GENERATED;
               FIELD_COMPLEX_RING; BRIDGE_NF_SUBFIELD_RATIONAL;
               RATIONAL_INTEGER; CX_INJ] THEN
  ANTS_TAC THENL
   [DISCH_THEN(MP_TAC o SPEC `d:num`) THEN ASM_REWRITE_TAC[LE_REFL];
    STRIP_TAC] THEN
  MP_TAC(ISPECL [`I:complex->complex`; `I:complex->complex`;
                 `subfield_generated complex_ring {Cx(&0)}`;
                 `subfield_generated complex_ring t`;
                 `subfield_generated complex_ring (z INSERT t)`]
    EXTENSION_DEGREE_TOWER_LAW) THEN
  REWRITE_TAC[I_O_ID] THEN ANTS_TAC THENL
   [CONJ_TAC THEN MATCH_MP_TAC FINITE_IMP_FIELD_EXTENSION THEN
    ASM_REWRITE_TAC[] THEN
    MP_TAC(ISPEC `t:complex->bool` NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED) THEN
    ASM_REWRITE_TAC[number_field] THEN
    DISCH_THEN(MP_TAC o CONJUNCT2) THEN REWRITE_TAC[BRIDGE_NF_PRIME_SUBFIELD];
    DISCH_THEN SUBST1_TAC THEN ASM_REWRITE_TAC[LE_MULT_LCANCEL]]);;

let COMPLEX_SUBFIELD_GENERATED_DEGREE = prove
 (`!n (al:num->complex) (a:num->num->real) (dd:num->num).
        (!r. r IN 1..n
             ==> 1 <= dd r /\ (!j. integer(a r j)) /\ ~(a r (dd r) = &0) /\
                 vsum(0..dd r) (\j. Cx(a r j) * al r pow j) = Cx(&0))
        ==> extension_degree (subfield_generated complex_ring {Cx(&0)},
                              subfield_generated complex_ring
                                (IMAGE al (1..n))) I
            <= nproduct(1..n) dd`,
  INDUCT_TAC THEN REPEAT STRIP_TAC THENL
   [REWRITE_TAC[NUMSEG_CLAUSES; ARITH; IMAGE_CLAUSES;
                NPRODUCT_CLAUSES_NUMSEG] THEN
    SUBGOAL_THEN `subfield_generated complex_ring {} =
                  subfield_generated complex_ring {Cx(&0)}`
    SUBST1_TAC THENL
     [MATCH_MP_TAC SUBFIELDS_GENERATED_EQ THEN
      REWRITE_TAC[COMPLEX_RING_CLAUSES; INTER_EMPTY; EMPTY_SUBSET;
                  INTER_UNIV; SING_SUBSET] THEN
      MESON_TAC[IN_SUBFIELD_0; COMPLEX_RING_CLAUSES];
      SIMP_TAC[EXTENSION_DEGREE_REFL; FIELD_SUBFIELD_GENERATED;
               FIELD_COMPLEX_RING; LE_REFL]];
    ALL_TAC] THEN
  REWRITE_TAC[NUMSEG_CLAUSES; ARITH_RULE `1 <= SUC n`; IMAGE_CLAUSES;
              NPRODUCT_CLAUSES_NUMSEG] THEN
  TRANS_TAC LE_TRANS
   `extension_degree (subfield_generated complex_ring {Cx(&0)},
                      subfield_generated complex_ring (IMAGE al (1..n))) I *
    dd(SUC n)` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC COMPLEX_SUBFIELD_INSERT_DEGREE THEN
    EXISTS_TAC `(a:num->num->real) (SUC n)` THEN
    SIMP_TAC[FINITE_IMAGE; FINITE_NUMSEG; FORALL_IN_IMAGE] THEN
    CONJ_TAC THENL
     [X_GEN_TAC `r:num` THEN DISCH_TAC THEN
      MATCH_MP_TAC EXPLICIT_IMP_ALGEBRAIC_NUMBER THEN
      MAP_EVERY EXISTS_TAC [`(dd:num->num) r`; `(a:num->num->real) r`] THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `r:num`) THEN ANTS_TAC THENL
       [POP_ASSUM MP_TAC THEN REWRITE_TAC[IN_NUMSEG] THEN ARITH_TAC;
        SIMP_TAC[]];
      FIRST_X_ASSUM(MP_TAC o SPEC `SUC n`) THEN
      REWRITE_TAC[IN_NUMSEG] THEN ANTS_TAC THENL [ARITH_TAC; SIMP_TAC[]]];
    REWRITE_TAC[LE_MULT_RCANCEL] THEN DISJ1_TAC THEN
    FIRST_X_ASSUM MATCH_MP_TAC THEN EXISTS_TAC `a:num->num->real` THEN
    X_GEN_TAC `r:num` THEN REWRITE_TAC[IN_NUMSEG] THEN STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `r:num`) THEN REWRITE_TAC[IN_NUMSEG] THEN
    ANTS_TAC THENL [ASM_ARITH_TAC; SIMP_TAC[]]]);;

(* ------------------------------------------------------------------------- *)
(* Roots of integer polynomials: the leading coefficient times a root and    *)
(* the lowest non-zero coefficient times the inverse of a non-zero root are  *)
(* algebraic integers.                                                       *)
(* ------------------------------------------------------------------------- *)

let INTEGER_POLY_ROOT_LEADING_INTEGER = prove
 (`!(a:num->real) d z.
        (!j. integer(a j)) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * z pow j) = Cx(&0)
        ==> algebraic_integer(Cx(a d) * z)`,
  REPEAT STRIP_TAC THEN ASM_CASES_TAC `d = 0` THENL
   [UNDISCH_TAC `vsum(0..d) (\j. Cx((a:num->real) j) * z pow j) = Cx(&0)` THEN
    ASM_REWRITE_TAC[VSUM_SING_NUMSEG; complex_pow; COMPLEX_MUL_RID; CX_INJ] THEN
    ASM_MESON_TAC[];
    ALL_TAC] THEN
  REWRITE_TAC[ALGEBRAIC_INTEGER_MONIC] THEN
  MAP_EVERY EXISTS_TAC
   [`d:num`; `\i. (a:num->real) i * a d pow (d - 1 - i)`] THEN
  ASM_SIMP_TAC[INTEGER_MUL; INTEGER_POW; LE_1] THEN
  FIRST_X_ASSUM(X_CHOOSE_THEN `e:num` SUBST_ALL_TAC o
                MATCH_MP LE_1_SUC_EXISTS o MATCH_MP
                (ARITH_RULE `~(d = 0) ==> 1 <= d`)) THEN
  REWRITE_TAC[SUC_SUB1] THEN
  SUBGOAL_THEN
   `vsum(0..e) (\i. Cx((a:num->real) i * a(SUC e) pow (e - i)) *
                    (Cx(a(SUC e)) * z) pow i) =
    Cx(a(SUC e)) pow e * vsum(0..e) (\i. Cx(a i) * z pow i)`
  SUBST1_TAC THENL
   [SIMP_TAC[GSYM VSUM_COMPLEX_LMUL; FINITE_NUMSEG] THEN
    MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `i:num` THEN STRIP_TAC THEN
    REWRITE_TAC[CX_MUL; CX_POW; COMPLEX_POW_MUL] THEN
    SUBGOAL_THEN
     `Cx((a:num->real)(SUC e)) pow e =
      Cx(a(SUC e)) pow (e - i) * Cx(a(SUC e)) pow i`
    SUBST1_TAC THENL
     [REWRITE_TAC[GSYM COMPLEX_POW_ADD] THEN AP_TERM_TAC THEN ASM_ARITH_TAC;
      CONV_TAC COMPLEX_RING];
    ALL_TAC] THEN
  UNDISCH_TAC
   `vsum(0..SUC e) (\i. Cx((a:num->real) i) * z pow i) = Cx(&0)` THEN
  REWRITE_TAC[VSUM_CLAUSES_NUMSEG; LE_0; COMPLEX_POW_MUL; complex_pow] THEN
  CONV_TAC COMPLEX_RING);;

let INTEGER_POLY_ROOT_INV_INTEGER = prove
 (`!(a:num->real) d z.
        (!j. integer(a j)) /\ ~(a d = &0) /\ ~(z = Cx(&0)) /\
        vsum(0..d) (\j. Cx(a j) * z pow j) = Cx(&0)
        ==> ?k. k <= d /\ ~(a k = &0) /\
                algebraic_integer(Cx(a k) * inv z)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `?k. ~((a:num->real) k = &0) /\ !j. j < k ==> a j = &0`
  STRIP_ASSUME_TAC THENL
   [MP_TAC(ISPEC `\n. ~((a:num->real) n = &0)` num_WOP) THEN
    REWRITE_TAC[] THEN ASM_MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `k <= d` ASSUME_TAC THENL
   [REWRITE_TAC[GSYM NOT_LT] THEN ASM_MESON_TAC[]; ALL_TAC] THEN
  EXISTS_TAC `k:num` THEN ASM_REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`\j. (a:num->real)(d - j)`; `d - k`; `inv(z:complex)`]
    INTEGER_POLY_ROOT_LEADING_INTEGER) THEN
  ASM_SIMP_TAC[ARITH_RULE `k <= d ==> d - (d - k) = k`] THEN
  DISCH_THEN MATCH_MP_TAC THEN
  SUBGOAL_THEN
   `vsum(0..d - k) (\j. Cx((a:num->real)(d - j)) * inv z pow j) =
    vsum(0..d) (\j. Cx(a(d - j)) * inv z pow j)`
  SUBST1_TAC THENL
   [CONV_TAC SYM_CONV THEN MATCH_MP_TAC VSUM_SUPERSET THEN
    REWRITE_TAC[SUBSET; IN_NUMSEG; COMPLEX_VEC_0] THEN
    CONJ_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    X_GEN_TAC `j:num` THEN STRIP_TAC THEN
    SUBGOAL_THEN `(a:num->real)(d - j) = &0` SUBST1_TAC THENL
     [FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_ARITH_TAC;
      REWRITE_TAC[COMPLEX_MUL_LZERO]];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `vsum(0..d) (\i. Cx((a:num->real)(d - i)) * inv z pow i) =
    inv z pow d * vsum(0..d) (\i. Cx(a i) * z pow i)`
  SUBST1_TAC THENL
   [ALL_TAC; ASM_REWRITE_TAC[COMPLEX_MUL_RZERO]] THEN
  SIMP_TAC[GSYM VSUM_COMPLEX_LMUL; FINITE_NUMSEG] THEN
  GEN_REWRITE_TAC LAND_CONV [VSUM_REFLECT] THEN
  REWRITE_TAC[LT; SUB_0] THEN
  MATCH_MP_TAC VSUM_EQ_NUMSEG THEN X_GEN_TAC `i:num` THEN STRIP_TAC THEN
  REWRITE_TAC[] THEN
  ASM_SIMP_TAC[ARITH_RULE `i <= d ==> d - (d - i) = i`] THEN
  UNDISCH_TAC `i <= d` THEN REWRITE_TAC[LE_EXISTS] THEN
  DISCH_THEN(X_CHOOSE_THEN `m:num` SUBST1_TAC) THEN
  REWRITE_TAC[ADD_SUB2; COMPLEX_POW_ADD; COMPLEX_POW_INV] THEN
  SUBGOAL_THEN `~(z pow i = Cx(&0))` MP_TAC THENL
   [ASM_REWRITE_TAC[COMPLEX_POW_EQ_0]; CONV_TAC COMPLEX_FIELD]);;

(* ------------------------------------------------------------------------- *)
(* Elements of a subfield of C with an integer denominator and bounded       *)
(* conjugates (sharp_nfbound of Baker/sharp_defs.ml): closure under products *)
(* and powers, roots of the data and their inverses, the lower bound for     *)
(* |x - 1|, and exponentials of integer linear forms in the data.            *)
(* ------------------------------------------------------------------------- *)

let SHARP_NFBOUND_EMBEDDING = prove
 (`!s g. g IN complex_embeddings(subfield_generated complex_ring s)
         ==> (!x y. x IN ring_carrier(subfield_generated complex_ring s) /\
                    y IN ring_carrier(subfield_generated complex_ring s)
                    ==> g(x + y) = g x + g y /\ g(x * y) = g x * g y) /\
             (!x m. x IN ring_carrier(subfield_generated complex_ring s)
                    ==> g(x pow m) = g x pow m) /\
             (!q. rational q ==> g(Cx q) = Cx q)`,
  REWRITE_TAC[complex_embeddings; IN_ELIM_THM] THEN
  MESON_TAC[BRIDGE_NF_HOM_CLAUSES]);;

let SHARP_NFBOUND_ONE = prove
 (`!s. sharp_nfbound s (Cx(&1)) (&1) (&1)`,
  GEN_TAC THEN REWRITE_TAC[sharp_nfbound; REAL_LE_REFL; INTEGER_CLOSED] THEN
  SIMP_TAC[BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_NUM] THEN
  REWRITE_TAC[COMPLEX_MUL_LID; ALGEBRAIC_INTEGER_NUM] THEN
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o SPEC `&1` o CONJUNCT2 o CONJUNCT2 o
    MATCH_MP SHARP_NFBOUND_EMBEDDING) THEN
  SIMP_TAC[RATIONAL_NUM; COMPLEX_NORM_CX; REAL_ABS_NUM; REAL_LE_REFL]);;

let SHARP_NFBOUND_MUL = prove
 (`!s x y d1 d2 R1 R2.
        sharp_nfbound s x d1 R1 /\ sharp_nfbound s y d2 R2
        ==> sharp_nfbound s (x * y) (d1 * d2) (R1 * R2)`,
  REWRITE_TAC[sharp_nfbound] THEN REPEAT STRIP_TAC THENL
   [ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_CLOSED];
    ASM_SIMP_TAC[INTEGER_MUL];
    ASM_SIMP_TAC[REAL_LE_1_MUL];
    SUBGOAL_THEN `Cx(d1 * d2) * x * y = (Cx d1 * x) * (Cx d2 * y)`
    SUBST1_TAC THENL
     [REWRITE_TAC[CX_MUL] THEN CONV_TAC COMPLEX_RING;
      ASM_SIMP_TAC[ALGEBRAIC_INTEGER_MUL]];
    FIRST_ASSUM(MP_TAC o MATCH_MP SHARP_NFBOUND_EMBEDDING) THEN
    DISCH_THEN(fun th -> ASM_SIMP_TAC[th]) THEN
    REWRITE_TAC[COMPLEX_NORM_MUL] THEN MATCH_MP_TAC REAL_LE_MUL2 THEN
    ASM_SIMP_TAC[NORM_POS_LE]]);;

let SHARP_NFBOUND_POW = prove
 (`!s x d R k. sharp_nfbound s x d R
               ==> sharp_nfbound s (x pow k) (d pow k) (R pow k)`,
  GEN_TAC THEN GEN_TAC THEN GEN_TAC THEN GEN_TAC THEN
  REWRITE_TAC[RIGHT_FORALL_IMP_THM] THEN DISCH_TAC THEN
  INDUCT_TAC THEN REWRITE_TAC[complex_pow; real_pow; SHARP_NFBOUND_ONE] THEN
  MATCH_MP_TAC SHARP_NFBOUND_MUL THEN ASM_REWRITE_TAC[]);;

let SHARP_NFBOUND_CPRODUCT = prove
 (`!s (f:A->complex) d R t.
        FINITE t /\ (!i. i IN t ==> sharp_nfbound s (f i) (d i) (R i))
        ==> sharp_nfbound s (cproduct t f) (product t d) (product t R)`,
  GEN_TAC THEN GEN_TAC THEN GEN_TAC THEN GEN_TAC THEN
  REWRITE_TAC[IMP_CONJ] THEN MATCH_MP_TAC FINITE_INDUCT_STRONG THEN
  SIMP_TAC[CPRODUCT_CLAUSES; PRODUCT_CLAUSES; FORALL_IN_INSERT;
           SHARP_NFBOUND_ONE] THEN
  REPEAT STRIP_TAC THEN MATCH_MP_TAC SHARP_NFBOUND_MUL THEN ASM_SIMP_TAC[]);;

let SHARP_NFBOUND_MONO = prove
 (`!s x d R R'. sharp_nfbound s x d R /\ R <= R'
                ==> sharp_nfbound s x d R'`,
  REWRITE_TAC[sharp_nfbound] THEN MESON_TAC[REAL_LE_TRANS]);;

let SHARP_NFBOUND_ROOT = prove
 (`!s x (a:num->real) d H.
        x IN ring_carrier(subfield_generated complex_ring s) /\
        (!j. integer(a j) /\ abs(a j) <= H) /\ ~(a d = &0) /\
