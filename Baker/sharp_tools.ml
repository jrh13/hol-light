    ASM_SIMP_TAC[] THEN REWRITE_TAC[real_abs] THEN COND_CASES_TAC THEN
    REWRITE_TAC[CX_NEG; COMPLEX_MUL_LNEG] THEN
    MESON_TAC[ALGEBRAIC_INTEGER_NEG];
    X_GEN_TAC `g:complex->complex` THEN DISCH_TAC THEN
