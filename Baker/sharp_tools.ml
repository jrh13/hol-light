    EXISTS_TAC `a:num->real` THEN ASM_SIMP_TAC[] THEN
    MATCH_MP_TAC COMPLEX_EMBEDDING_POLY_ROOT THEN
    EXISTS_TAC `s:complex->bool` THEN ASM_SIMP_TAC[]]);;

let SHARP_NFBOUND_INV_ROOT = prove
 (`!s x (a:num->real) d H.
        x IN ring_carrier(subfield_generated complex_ring s) /\
        ~(x = Cx(&0)) /\
        (!j. integer(a j) /\ abs(a j) <= H) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * x pow j) = Cx(&0)
        ==> ?den. den <= H /\ sharp_nfbound s (inv x) den (&2 * H)`,
  REPEAT STRIP_TAC THEN
  MP_TAC(SPECL [`a:num->real`; `d:num`; `x:complex`]
    INTEGER_POLY_ROOT_INV_INTEGER) THEN
  ASM_SIMP_TAC[] THEN DISCH_THEN(X_CHOOSE_THEN `k:num` STRIP_ASSUME_TAC) THEN
  EXISTS_TAC `abs((a:num->real) k)` THEN ASM_REWRITE_TAC[sharp_nfbound] THEN
  ASM_SIMP_TAC[INTEGER_ABS; REAL_ABS_INTEGER_LEMMA] THEN
  SUBGOAL_THEN `inv x IN ring_carrier(subfield_generated complex_ring s)`
  ASSUME_TAC THENL
   [REWRITE_TAC[GSYM COMPLEX_RING_INV] THEN MATCH_MP_TAC IN_SUBFIELD_INV THEN
    ASM_SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING];
    ASM_REWRITE_TAC[]] THEN
  CONJ_TAC THENL
   [UNDISCH_TAC `algebraic_integer(Cx((a:num->real) k) * inv x)` THEN
    REWRITE_TAC[real_abs] THEN COND_CASES_TAC THEN
    REWRITE_TAC[CX_NEG; COMPLEX_MUL_LNEG] THEN
    MESON_TAC[ALGEBRAIC_INTEGER_NEG];
    ALL_TAC] THEN
  X_GEN_TAC `g:complex->complex` THEN DISCH_TAC THEN
  SUBGOAL_THEN `(g:complex->complex) x * g(inv x) = Cx(&1)` ASSUME_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP SHARP_NFBOUND_EMBEDDING) THEN
    DISCH_THEN(fun th ->
      MP_TAC(SPECL [`x:complex`; `inv(x:complex)`] (CONJUNCT1 th)) THEN
      MP_TAC(SPEC `&1` (CONJUNCT2(CONJUNCT2 th)))) THEN
    ASM_SIMP_TAC[RATIONAL_NUM; COMPLEX_MUL_RINV];
    ALL_TAC] THEN
  SUBGOAL_THEN `~((g:complex->complex) x = Cx(&0))` ASSUME_TAC THENL
   [DISCH_TAC THEN
    UNDISCH_TAC `(g:complex->complex) x * g(inv x) = Cx(&1)` THEN
    ASM_REWRITE_TAC[COMPLEX_MUL_LZERO; CX_INJ] THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(g:complex->complex)(inv x) = inv(g x)` SUBST1_TAC THENL
   [CONV_TAC SYM_CONV THEN MATCH_MP_TAC COMPLEX_MUL_RINV_UNIQ THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MP_TAC(SPECL [`a:num->real`; `d:num`; `H:real`; `(g:complex->complex) x`]
    ALGEBRAIC_ROOT_LOWER_BOUND) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN MATCH_MP_TAC COMPLEX_EMBEDDING_POLY_ROOT THEN
    EXISTS_TAC `s:complex->bool` THEN ASM_SIMP_TAC[];
    ALL_TAC] THEN
  DISCH_TAC THEN REWRITE_TAC[COMPLEX_NORM_INV] THEN
  SUBGOAL_THEN `&1 <= H` ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `abs((a:num->real) d)` THEN
    ASM_SIMP_TAC[REAL_ABS_INTEGER_LEMMA];
    ALL_TAC] THEN
  GEN_REWRITE_TAC RAND_CONV [GSYM REAL_INV_INV] THEN
  MATCH_MP_TAC REAL_LE_INV2 THEN ASM_REWRITE_TAC[] THEN
  MATCH_MP_TAC REAL_LT_INV THEN ASM_REAL_ARITH_TAC);;

let SHARP_NFBOUND_SUB1_LOWER = prove
 (`!s x den R E.
        FINITE s /\ (!z. z IN s ==> algebraic_number z) /\
        extension_degree (subfield_generated complex_ring {Cx(&0)},
                          subfield_generated complex_ring s) I <= E /\
        sharp_nfbound s x den R /\ &0 <= R /\ ~(x = Cx(&1))
        ==> inv(&2 * (&2 * den * (R + &1)) pow E) <= norm(x - Cx(&1))`,
  REWRITE_TAC[sharp_nfbound] THEN REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `x - Cx(&1) = x + Cx(--(&1))` SUBST1_TAC THENL
   [REWRITE_TAC[CX_NEG] THEN CONV_TAC COMPLEX_RING; ALL_TAC] THEN
  SUBGOAL_THEN
   `Cx(--(&1)) IN ring_carrier(subfield_generated complex_ring s)`
  ASSUME_TAC THENL
   [MATCH_MP_TAC BRIDGE_NF_SUBFIELD_RATIONAL THEN
    SIMP_TAC[RATIONAL_CLOSED];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`s:complex->bool`; `x + Cx(--(&1))`; `den:real`; `R + &1`]
    COMPLEX_SUBFIELD_ELEMENT_POLY) THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_CLOSED] THEN REPEAT CONJ_TAC THENL
     [SUBGOAL_THEN `Cx den * (x + Cx(--(&1))) = Cx den * x - Cx den`
      SUBST1_TAC THENL
       [REWRITE_TAC[CX_NEG] THEN CONV_TAC COMPLEX_RING;
        MATCH_MP_TAC ALGEBRAIC_INTEGER_SUB THEN
        ASM_SIMP_TAC[ALGEBRAIC_INTEGER_INTEGER]];
      ASM_REAL_ARITH_TAC;
      X_GEN_TAC `g:complex->complex` THEN DISCH_TAC THEN
      SUBGOAL_THEN
       `(g:complex->complex)(x + Cx(--(&1))) = g x + Cx(--(&1))`
      SUBST1_TAC THENL
       [FIRST_ASSUM(MP_TAC o MATCH_MP SHARP_NFBOUND_EMBEDDING) THEN
        DISCH_THEN(fun th ->
          MP_TAC(SPECL [`x:complex`; `Cx(--(&1))`] (CONJUNCT1 th)) THEN
          MP_TAC(SPEC `--(&1)` (CONJUNCT2(CONJUNCT2 th)))) THEN
        ASM_SIMP_TAC[RATIONAL_CLOSED];
        ALL_TAC] THEN
      TRANS_TAC REAL_LE_TRANS
       `norm((g:complex->complex) x) + norm(Cx(--(&1)))` THEN
      REWRITE_TAC[NORM_TRIANGLE; COMPLEX_NORM_CX; REAL_ABS_NEG;
                  REAL_ABS_NUM] THEN
      MATCH_MP_TAC(REAL_ARITH `x <= R ==> x + &1 <= R + &1`) THEN
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  DISCH_THEN(X_CHOOSE_THEN `dx:num` (X_CHOOSE_THEN `ax:num->real`
    STRIP_ASSUME_TAC)) THEN
  MATCH_MP_TAC ALGEBRAIC_ROOT_LOWER_BOUND THEN
  MAP_EVERY EXISTS_TAC [`ax:num->real`; `dx:num`] THEN
  ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [X_GEN_TAC `j:num` THEN ASM_REWRITE_TAC[] THEN
    TRANS_TAC REAL_LE_TRANS `(&2 * den * (R + &1)) pow dx` THEN
    ASM_REWRITE_TAC[] THEN MATCH_MP_TAC REAL_POW_MONO THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_1_MUL THEN CONJ_TAC THENL
       [REAL_ARITH_TAC;
        MATCH_MP_TAC REAL_LE_1_MUL THEN ASM_REAL_ARITH_TAC];
      ASM_ARITH_TAC];
    REWRITE_TAC[CX_NEG; GSYM complex_sub; COMPLEX_SUB_0] THEN
    ASM_REWRITE_TAC[]]);;

let SHARP_NFBOUND_DEN = prove
 (`!s x den R. sharp_nfbound s x den R ==> &1 <= den`,
  SIMP_TAC[sharp_nfbound]);;

let SHARP_NFBOUND_CEXP_INT = prove
 (`!s lg (a:num->real) d H D b k.
        1 <= D /\ cexp lg IN ring_carrier(subfield_generated complex_ring s) /\
        d <= D /\ (!j. integer(a j) /\ abs(a j) <= H) /\ ~(a d = &0) /\
        vsum(0..d) (\j. Cx(a j) * cexp lg pow j) = Cx(&0) /\
        integer b /\ abs b = &k
        ==> ?den. den <= H pow k /\
                  sharp_nfbound s (cexp(Cx b * lg)) den
                                (((&1 + &D) * H) pow k)`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `&1 <= H` ASSUME_TAC THENL
   [TRANS_TAC REAL_LE_TRANS `abs((a:num->real) d)` THEN
    ASM_SIMP_TAC[REAL_ABS_INTEGER_LEMMA];
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= &D /\ &d <= &D` STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LE] THEN ASM_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `&2 * H <= (&1 + &D) * H /\ &1 + &d * H <= (&1 + &D) * H`
  STRIP_ASSUME_TAC THENL
   [CONJ_TAC THENL
     [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC;
      SUBGOAL_THEN `&d * H <= &D * H` MP_TAC THENL
       [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC;
        ASM_REAL_ARITH_TAC]];
    ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= &d * H` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_MUL THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  ASM_CASES_TAC `&0 <= b` THENL
   [SUBGOAL_THEN `b = &k` SUBST1_TAC THENL
     [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[CEXP_N] THEN EXISTS_TAC `abs((a:num->real) d) pow k` THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REWRITE_TAC[REAL_ABS_POS];
      MATCH_MP_TAC SHARP_NFBOUND_MONO THEN
      EXISTS_TAC `(&1 + &d * H) pow k` THEN CONJ_TAC THENL
       [MATCH_MP_TAC SHARP_NFBOUND_POW THEN
        MATCH_MP_TAC SHARP_NFBOUND_ROOT THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC]];
    SUBGOAL_THEN `b = --(&k)` SUBST1_TAC THENL
     [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[CX_NEG; COMPLEX_MUL_LNEG; CEXP_NEG; CEXP_N;
                GSYM COMPLEX_POW_INV] THEN
    MP_TAC(ISPECL [`s:complex->bool`; `cexp lg`; `a:num->real`; `d:num`;
                   `H:real`] SHARP_NFBOUND_INV_ROOT) THEN
    ASM_REWRITE_TAC[CEXP_NZ] THEN
    DISCH_THEN(X_CHOOSE_THEN `den:real` STRIP_ASSUME_TAC) THEN
    FIRST_ASSUM(ASSUME_TAC o MATCH_MP SHARP_NFBOUND_DEN) THEN
    EXISTS_TAC `den pow k` THEN CONJ_TAC THENL
     [MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC;
      MATCH_MP_TAC SHARP_NFBOUND_MONO THEN
      EXISTS_TAC `(&2 * H) pow k` THEN CONJ_TAC THENL
       [MATCH_MP_TAC SHARP_NFBOUND_POW THEN ASM_REWRITE_TAC[];
        MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC]]]);;

let SHARP_NFBOUND_CEXP_VSUM = prove
 (`!s m (lg:num->complex) (a:num->num->real) (dd:num->num) (H:num->real)
    D (bb:num->real) (k:num->num).
        1 <= D /\
        (!r. r IN 1..m
             ==> cexp(lg r) IN
                 ring_carrier(subfield_generated complex_ring s) /\
                 dd r <= D /\ (!j. integer(a r j) /\ abs(a r j) <= H r) /\
                 ~(a r (dd r) = &0) /\
                 vsum(0..dd r) (\j. Cx(a r j) * cexp(lg r) pow j) = Cx(&0) /\
                 integer(bb r) /\ abs(bb r) = &(k r))
        ==> ?den. den <= product(1..m) (\r. H r pow k r) /\
                  sharp_nfbound s (cexp(vsum(1..m) (\r. Cx(bb r) * lg r))) den
                  (product(1..m) (\r. ((&1 + &D) * H r) pow k r))`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN
   `?den. !r. r IN 1..m
              ==> den r <= (H:num->real) r pow k r /\
                  sharp_nfbound s (cexp(Cx(bb r) * lg r)) (den r)
                                (((&1 + &D) * H r) pow k r)`
  STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[GSYM SKOLEM_THM; RIGHT_EXISTS_IMP_THM] THEN
    X_GEN_TAC `r:num` THEN DISCH_TAC THEN
    MATCH_MP_TAC SHARP_NFBOUND_CEXP_INT THEN
    MAP_EVERY EXISTS_TAC [`(a:num->num->real) r`; `(dd:num->num) r`] THEN
    ASM_SIMP_TAC[];
    ALL_TAC] THEN
  EXISTS_TAC `product(1..m) den` THEN CONJ_TAC THENL
   [MATCH_MP_TAC PRODUCT_LE_NUMSEG THEN X_GEN_TAC `r:num` THEN STRIP_TAC THEN
    SUBGOAL_THEN `(r:num) IN 1..m` ASSUME_TAC THENL
     [ASM_REWRITE_TAC[IN_NUMSEG]; ALL_TAC] THEN
    ASM_SIMP_TAC[] THEN
    MATCH_MP_TAC(REAL_ARITH `&1 <= x ==> &0 <= x`) THEN
    MATCH_MP_TAC SHARP_NFBOUND_DEN THEN
    MAP_EVERY EXISTS_TAC
     [`s:complex->bool`; `cexp(Cx((bb:num->real) r) * lg r)`;
      `((&1 + &D) * (H:num->real) r) pow k r`] THEN
    ASM_SIMP_TAC[];
    SIMP_TAC[CEXP_VSUM; FINITE_NUMSEG] THEN
    MATCH_MP_TAC SHARP_NFBOUND_CPRODUCT THEN ASM_SIMP_TAC[FINITE_NUMSEG]]);;

