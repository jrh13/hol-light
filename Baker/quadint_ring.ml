(* ------------------------------------------------------------------------- *)
(* The generator omega: square, conjugate, real and imaginary parts, the     *)
(* norm form, uniqueness of coordinates, conjugates and products in          *)
(* coordinates; omega is an algebraic integer.                               *)
(* ------------------------------------------------------------------------- *)

let QUAD_DMOD4_REAL = prove
 (`!d. d MOD 4 = 3 ==> &4 * &((d + 1) DIV 4) = &d + &1`,
  GEN_TAC THEN DISCH_TAC THEN
  REWRITE_TAC[REAL_OF_NUM_MUL; REAL_OF_NUM_ADD; REAL_OF_NUM_EQ] THEN
  MP_TAC(SPECL [`d:num`; `4`] DIVISION) THEN ASM_REWRITE_TAC[ARITH_EQ] THEN
  DISCH_THEN(SUBST1_TAC o CONJUNCT1) THEN
  REWRITE_TAC[ARITH_RULE `(q * 4 + 3) + 1 = 4 * (q + 1)`] THEN
  SIMP_TAC[DIV_MULT; ARITH_EQ]);;

let QUAD_OMEGA_SQUARE = prove
 (`!d. quad_omega d pow 2 =
       if d MOD 4 = 3 then quad_omega d - Cx(&((d + 1) DIV 4))
       else --Cx(&d)`,
  GEN_TAC THEN REWRITE_TAC[quad_omega] THEN
  MP_TAC(SPEC `d:num` QUAD_SQRT_POW_2) THEN MP_TAC COMPLEX_POW_II_2 THEN
  COND_CASES_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP QUAD_DMOD4_REAL) THEN
    REWRITE_TAC[GSYM CX_INJ; CX_MUL; CX_ADD] THEN CONV_TAC COMPLEX_FIELD;
    CONV_TAC COMPLEX_RING]);;

let QUAD_OMEGA_CNJ = prove
 (`!d. cnj(quad_omega d) =
       if d MOD 4 = 3 then Cx(&1) - quad_omega d else --quad_omega d`,
  GEN_TAC THEN REWRITE_TAC[quad_omega] THEN COND_CASES_TAC THEN
  REWRITE_TAC[CNJ_DIV; CNJ_ADD; CNJ_MUL; CNJ_CX; CNJ_II] THEN
  CONV_TAC COMPLEX_FIELD);;

let QUAD_OMEGA_RE_IM = prove
 (`!d. Re(quad_omega d) = (if d MOD 4 = 3 then &1 / &2 else &0) /\
       Im(quad_omega d) = (if d MOD 4 = 3 then sqrt(&d) / &2 else sqrt(&d))`,
  GEN_TAC THEN REWRITE_TAC[quad_omega] THEN COND_CASES_TAC THEN
  REWRITE_TAC[RE_DIV_CX; IM_DIV_CX; RE_ADD; IM_ADD; RE_MUL_II; IM_MUL_II;
              RE_CX; IM_CX] THEN
  REAL_ARITH_TAC);;

let QUAD_OMEGA_NORM = prove
 (`!d x y. norm(Cx x + Cx y * quad_omega d) pow 2 =
           if d MOD 4 = 3 then x pow 2 + x * y + &((d + 1) DIV 4) * y pow 2
           else x pow 2 + &d * y pow 2`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[COMPLEX_SQNORM; RE_ADD; IM_ADD; RE_CX; IM_CX; RE_MUL_CX;
              IM_MUL_CX; QUAD_OMEGA_RE_IM] THEN
  MP_TAC(SPEC `&d` SQRT_POW_2) THEN REWRITE_TAC[REAL_POS] THEN
  COND_CASES_TAC THENL
   [FIRST_ASSUM(MP_TAC o MATCH_MP QUAD_DMOD4_REAL) THEN CONV_TAC REAL_FIELD;
    CONV_TAC REAL_RING]);;

let QUAD_OMEGA_IM_POS = prove
 (`!d. 1 <= d ==> &0 < Im(quad_omega d)`,
  GEN_TAC THEN DISCH_TAC THEN REWRITE_TAC[QUAD_OMEGA_RE_IM] THEN
  SUBGOAL_THEN `&0 < sqrt(&d)` MP_TAC THENL
   [MATCH_MP_TAC SQRT_POS_LT THEN REWRITE_TAC[REAL_OF_NUM_LT] THEN
    ASM_ARITH_TAC;
    COND_CASES_TAC THEN REAL_ARITH_TAC]);;

let QUAD_OMEGA_COORDS = prove
 (`!d x y x' y'.
        1 <= d /\ Cx x + Cx y * quad_omega d = Cx x' + Cx y' * quad_omega d
        ==> x = x' /\ y = y'`,
  REPEAT GEN_TAC THEN
  DISCH_THEN(CONJUNCTS_THEN2 (ASSUME_TAC o MATCH_MP QUAD_OMEGA_IM_POS)
    (fun th -> MP_TAC(AP_TERM `Re` th) THEN MP_TAC(AP_TERM `Im` th))) THEN
  REWRITE_TAC[RE_ADD; IM_ADD; RE_CX; IM_CX; RE_MUL_CX; IM_MUL_CX] THEN
  REWRITE_TAC[REAL_ADD_LID] THEN
  ASM_SIMP_TAC[REAL_EQ_MUL_RCANCEL; REAL_LT_IMP_NZ] THEN
  DISCH_THEN SUBST1_TAC THEN REAL_ARITH_TAC);;

let QUAD_OMEGA_CNJ_COORDS = prove
 (`!d x y. cnj(Cx x + Cx y * quad_omega d) =
           if d MOD 4 = 3 then Cx(x + y) + Cx(--y) * quad_omega d
           else Cx x + Cx(--y) * quad_omega d`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[CNJ_ADD; CNJ_MUL; CNJ_CX; QUAD_OMEGA_CNJ] THEN
  COND_CASES_TAC THEN REWRITE_TAC[CX_ADD; CX_NEG] THEN
  CONV_TAC COMPLEX_RING);;

let QUAD_OMEGA_MUL_COORDS = prove
 (`!d x y x' y'.
        (Cx x + Cx y * quad_omega d) * (Cx x' + Cx y' * quad_omega d) =
        if d MOD 4 = 3
        then Cx(x * x' - &((d + 1) DIV 4) * y * y') +
             Cx(x * y' + y * x' + y * y') * quad_omega d
        else Cx(x * x' - &d * y * y') + Cx(x * y' + y * x') * quad_omega d`,
  REPEAT GEN_TAC THEN MP_TAC(SPEC `d:num` QUAD_OMEGA_SQUARE) THEN
  COND_CASES_TAC THEN REWRITE_TAC[CX_ADD; CX_SUB; CX_MUL] THEN
  CONV_TAC COMPLEX_RING);;

let QUAD_OMEGA_ALGEBRAIC_INTEGER = prove
 (`!d. algebraic_integer(quad_omega d)`,
  GEN_TAC THEN MATCH_MP_TAC QUAD_ALGEBRAIC_INTEGER_QUADRATIC THEN
  MP_TAC(SPEC `d:num` QUAD_OMEGA_SQUARE) THEN
  COND_CASES_TAC THEN DISCH_TAC THENL
   [MAP_EVERY EXISTS_TAC [`-- &1:real`; `&((d + 1) DIV 4):real`];
    MAP_EVERY EXISTS_TAC [`&0:real`; `&d:real`]] THEN
  ASM_REWRITE_TAC[INTEGER_CLOSED; INTEGER_NEG; CX_NEG] THEN
  CONV_TAC COMPLEX_RING);;

(* ------------------------------------------------------------------------- *)
(* Integers: a tactic for integer closure goals, parity.                     *)
(* ------------------------------------------------------------------------- *)

let QUAD_INTEGER_TAC =
  REPEAT(FIRST_ASSUM ACCEPT_TAC ORELSE
         ((MATCH_MP_TAC INTEGER_ADD ORELSE MATCH_MP_TAC INTEGER_SUB ORELSE
           MATCH_MP_TAC INTEGER_MUL) THEN CONJ_TAC)) THEN
  ASM_SIMP_TAC[INTEGER_CLOSED];;

let QUAD_INTEGER_PARITY = prove
 (`!x. integer x ==> ?p r. integer p /\ (r = &0 \/ r = &1) /\ x = &2 * p + r`,
  GEN_TAC THEN DISCH_THEN(DISJ_CASES_THEN (X_CHOOSE_THEN `n:num` SUBST1_TAC) o
    REWRITE_RULE[INTEGER_CASES]) THEN
  DISJ_CASES_THEN (X_CHOOSE_THEN `m:num` SUBST1_TAC)
   (REWRITE_RULE[EVEN_EXISTS; ODD_EXISTS] (SPEC `n:num` EVEN_OR_ODD)) THEN
  REWRITE_TAC[GSYM REAL_OF_NUM_MUL; GSYM REAL_OF_NUM_SUC] THENL
   [MAP_EVERY EXISTS_TAC [`&m:real`; `&0:real`];
    MAP_EVERY EXISTS_TAC [`&m:real`; `&1:real`];
    MAP_EVERY EXISTS_TAC [`--(&m):real`; `&0:real`];
    MAP_EVERY EXISTS_TAC [`--(&m) - &1:real`; `&1:real`]] THEN
  SIMP_TAC[INTEGER_CLOSED] THEN REAL_ARITH_TAC);;

(* ------------------------------------------------------------------------- *)
(* Elements in coordinates, the rational integers, omega and conjugates in   *)
(* the ring, closure (any d).                                                *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_COORDS_IN = prove
 (`!d x y. integer x /\ integer y
           ==> algebraic_integer(Cx x + Cx y * quad_omega d) /\
               Cx x + Cx y * quad_omega d IN imag_quadratic_field d`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN CONJ_TAC THENL
   [MATCH_MP_TAC ALGEBRAIC_INTEGER_ADD THEN CONJ_TAC THENL
     [ASM_SIMP_TAC[ALGEBRAIC_INTEGER_INTEGER];
      MATCH_MP_TAC ALGEBRAIC_INTEGER_MUL THEN
      ASM_SIMP_TAC[ALGEBRAIC_INTEGER_INTEGER; QUAD_OMEGA_ALGEBRAIC_INTEGER]];
    REWRITE_TAC[IMAG_QUADRATIC_FIELD_IN; quad_omega] THEN
    COND_CASES_TAC THENL
     [MAP_EVERY EXISTS_TAC [`x + y / &2`; `y / &2`] THEN
      ASM_SIMP_TAC[RATIONAL_CLOSED] THEN REWRITE_TAC[CX_ADD; CX_DIV] THEN
      CONV_TAC COMPLEX_FIELD;
      MAP_EVERY EXISTS_TAC [`x:real`; `y:real`] THEN
      ASM_SIMP_TAC[RATIONAL_CLOSED]]]);;

let IMAG_QUADRATIC_INTEGERS_IN_COORDS = prove
 (`!d x y. integer x /\ integer y
           ==> Cx x + Cx y * quad_omega d
               IN ring_carrier(imag_quadratic_integers d)`,
  SIMP_TAC[IMAG_QUADRATIC_INTEGERS_IN_ALT;
           IMAG_QUADRATIC_INTEGERS_COORDS_IN]);;

let IMAG_QUADRATIC_INTEGERS_CX = prove
 (`!d x. Cx x IN ring_carrier(imag_quadratic_integers d) <=> integer x`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_IN_ALT; IMAG_QUADRATIC_FIELD_IN] THEN
  EQ_TAC THENL
   [DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC
     (X_CHOOSE_THEN `a:real` (X_CHOOSE_THEN `b:real` STRIP_ASSUME_TAC))) THEN
    MATCH_MP_TAC ALGEBRAIC_INTEGER_RATIONAL THEN ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN `x:real = a` (fun th -> ASM_REWRITE_TAC[th]) THEN
    FIRST_X_ASSUM(MP_TAC o AP_TERM `Re`) THEN
    REWRITE_TAC[RE_ADD; RE_CX; RE_MUL_CX; RE_MUL_II; IM_CX] THEN
    REAL_ARITH_TAC;
    DISCH_TAC THEN ASM_SIMP_TAC[ALGEBRAIC_INTEGER_INTEGER] THEN
    MAP_EVERY EXISTS_TAC [`x:real`; `&0`] THEN
    ASM_SIMP_TAC[RATIONAL_CLOSED] THEN CONV_TAC COMPLEX_RING]);;

let IMAG_QUADRATIC_INTEGERS_OMEGA = prove
 (`!d. quad_omega d IN ring_carrier(imag_quadratic_integers d)`,
  GEN_TAC THEN
  MP_TAC(SPECL [`d:num`; `&0`; `&1`] IMAG_QUADRATIC_INTEGERS_COORDS_IN) THEN
  REWRITE_TAC[INTEGER_CLOSED; IMAG_QUADRATIC_INTEGERS_IN_ALT] THEN
  REWRITE_TAC[COMPLEX_ADD_LID; COMPLEX_MUL_LID]);;

let IMAG_QUADRATIC_INTEGERS_CNJ = prove
 (`!d z. z IN ring_carrier(imag_quadratic_integers d)
         ==> cnj z IN ring_carrier(imag_quadratic_integers d)`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_IN_ALT; IMAG_QUADRATIC_FIELD_IN] THEN
  DISCH_THEN(CONJUNCTS_THEN2 (ASSUME_TAC o MATCH_MP ALGEBRAIC_INTEGER_CNJ)
   (X_CHOOSE_THEN `a:real` (X_CHOOSE_THEN `b:real` STRIP_ASSUME_TAC))) THEN
  ASM_REWRITE_TAC[] THEN
  MAP_EVERY EXISTS_TAC [`a:real`; `--b:real`] THEN
  ASM_SIMP_TAC[RATIONAL_NEG] THEN
  REWRITE_TAC[CNJ_ADD; CNJ_MUL; CNJ_CX; CNJ_II; CX_NEG] THEN
  CONV_TAC COMPLEX_RING);;

let IMAG_QUADRATIC_INTEGERS_CLOSED = prove
 (`!d. (!x. integer x ==> Cx x IN ring_carrier(imag_quadratic_integers d)) /\
       quad_omega d IN ring_carrier(imag_quadratic_integers d) /\
       (!x y. x IN ring_carrier(imag_quadratic_integers d) /\
              y IN ring_carrier(imag_quadratic_integers d)
              ==> x + y IN ring_carrier(imag_quadratic_integers d)) /\
       (!x y. x IN ring_carrier(imag_quadratic_integers d) /\
              y IN ring_carrier(imag_quadratic_integers d)
              ==> x - y IN ring_carrier(imag_quadratic_integers d)) /\
       (!x y. x IN ring_carrier(imag_quadratic_integers d) /\
              y IN ring_carrier(imag_quadratic_integers d)
              ==> x * y IN ring_carrier(imag_quadratic_integers d)) /\
       (!x. x IN ring_carrier(imag_quadratic_integers d)
            ==> --x IN ring_carrier(imag_quadratic_integers d)) /\
       (!x n. x IN ring_carrier(imag_quadratic_integers d)
              ==> x pow n IN ring_carrier(imag_quadratic_integers d)) /\
       (!x. x IN ring_carrier(imag_quadratic_integers d)
            ==> cnj x IN ring_carrier(imag_quadratic_integers d))`,
  GEN_TAC THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_CX; IMAG_QUADRATIC_INTEGERS_OMEGA;
              IMAG_QUADRATIC_INTEGERS_CNJ] THEN
  MP_TAC(ISPEC `imag_quadratic_integers d` RING_ADD) THEN
  MP_TAC(ISPEC `imag_quadratic_integers d` RING_SUB) THEN
  MP_TAC(ISPEC `imag_quadratic_integers d` RING_MUL) THEN
  MP_TAC(ISPEC `imag_quadratic_integers d` RING_NEG) THEN
  MP_TAC(ISPEC `imag_quadratic_integers d` RING_POW) THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_CLAUSES;
              IMAG_QUADRATIC_INTEGERS_SUB_POW] THEN
  SIMP_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The carrier: for squarefree d the algebraic integers of the field are     *)
(* exactly the x + y omega with integers x and y (the integral basis of      *)
(* ANT/quadratic.ml).                                                        *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_CARRIER = prove
 (`!d. squarefree d
       ==> ring_carrier (imag_quadratic_integers d) =
           {z | ?x y. integer x /\ integer y /\
                      z = Cx x + Cx y * quad_omega d}`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`subring_generated complex_ring (imag_quadratic_field d)`;
                 `ii * Cx(sqrt(&d))`; `-- &d:int`]
    QUADRATIC_FIELD_INTEGRAL_BASIS) THEN
  REWRITE_TAC[IMAG_QUADRATIC_FIELD_SQRT; IMAG_QUADRATIC_FIELD_NUMBER_FIELD;
              IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD;
              RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD; QUAD_DMOD4_CONG] THEN
  ANTS_TAC THENL
   [ASM_SIMP_TAC[IMAG_QUADRATIC_FIELD_DEGREE; SQUAREFREE_IMP_NZ] THEN
    ASM_REWRITE_TAC[INT_ABS_NEG; INT_ABS_NUM; NUM_OF_INT_OF_NUM] THEN
    INT_ARITH_TAC;
    ALL_TAC] THEN
  SIMP_TAC[ring_div; CONJUNCT2 SUBRING_GENERATED;
           RING_OF_NUM_SUBRING_GENERATED; RING_OF_INT_SUBRING_GENERATED;
           COMPLEX_RING_CLAUSES; COMPLEX_RING_OF_NUM; COMPLEX_RING_OF_INT;
           RING_INV_SUBRING_GENERATED;
           IMAG_QUADRATIC_FIELD_SUBFIELD; RATIONAL_IN_COMPLEX_SUBFIELD;
           RATIONAL_NUM; COMPLEX_RING_INV; CX_INJ; REAL_OF_NUM_EQ;
           ARITH_EQ] THEN
  REWRITE_TAC[GSYM complex_div; GSYM quad_omega] THEN
  REWRITE_TAC[free_basis; FORALL_LT_2] THEN
  DISCH_THEN(MP_TAC o CONJUNCT1 o CONJUNCT2) THEN DISCH_TAC THEN
  REWRITE_TAC[EXTENSION; IN_ELIM_THM] THEN X_GEN_TAC `z:complex` THEN
  EQ_TAC THENL
   [DISCH_THEN(fun th -> FIRST_X_ASSUM(MP_TAC o C MATCH_MP th)) THEN
    REWRITE_TAC[INTEGER_RING; IN_UNIV] THEN
    DISCH_THEN(X_CHOOSE_THEN `c:num->int` SUBST1_TAC) THEN
    MAP_EVERY EXISTS_TAC [`real_of_int(c 0)`; `real_of_int(c 1)`] THEN
    REWRITE_TAC[INTEGER_REAL_OF_INT] THEN
    W(MP_TAC o PART_MATCH (lhand o rand) RING_SUM_LT_2 o lhand o snd) THEN
    REWRITE_TAC[ARITH_EQ; IMAG_QUADRATIC_INTEGERS_CLAUSES;
                COMPLEX_MUL_RID] THEN
    SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CLOSED; INTEGER_REAL_OF_INT];
    STRIP_TAC THEN ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_IN_COORDS]]);;

let IMAG_QUADRATIC_INTEGERS_IN = prove
 (`!d z. squarefree d
         ==> (z IN ring_carrier(imag_quadratic_integers d) <=>
              ?x y. integer x /\ integer y /\ z = Cx x + Cx y * quad_omega d)`,
  SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CARRIER; IN_ELIM_THM]);;

(* ------------------------------------------------------------------------- *)
(* Norms, units and divisibility (for every d unless stated).                *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_NORM_POW_2 = prove
 (`!d z. z IN ring_carrier(imag_quadratic_integers d)
         ==> ?n. norm z pow 2 = &n`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `integer(norm(z:complex) pow 2)` MP_TAC THENL
   [REWRITE_TAC[GSYM(SPEC `d:num` IMAG_QUADRATIC_INTEGERS_CX)] THEN
    REWRITE_TAC[CX_POW; COMPLEX_NORM_POW_2] THEN
    ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CLOSED];
    SIMP_TAC[INTEGER_POS; REAL_POW_LE; NORM_POS_LE]]);;

let IMAG_QUADRATIC_INTEGERS_UNIT = prove
 (`!d u. ring_unit (imag_quadratic_integers d) u <=>
         u IN ring_carrier(imag_quadratic_integers d) /\ norm u = &1`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[ring_unit; IMAG_QUADRATIC_INTEGERS_CLAUSES] THEN
  ASM_CASES_TAC `u IN ring_carrier(imag_quadratic_integers d)` THEN
  ASM_REWRITE_TAC[] THEN EQ_TAC THENL
   [DISCH_THEN(X_CHOOSE_THEN `v:complex` STRIP_ASSUME_TAC) THEN
    MP_TAC(SPECL [`d:num`; `u:complex`]
      IMAG_QUADRATIC_INTEGERS_NORM_POW_2) THEN
    MP_TAC(SPECL [`d:num`; `v:complex`]
      IMAG_QUADRATIC_INTEGERS_NORM_POW_2) THEN
    ASM_REWRITE_TAC[LEFT_IMP_EXISTS_THM] THEN
    X_GEN_TAC `n:num` THEN DISCH_TAC THEN
    X_GEN_TAC `m:num` THEN DISCH_TAC THEN
    FIRST_X_ASSUM(MP_TAC o AP_TERM `norm:complex->real`) THEN
    REWRITE_TAC[COMPLEX_NORM_MUL; COMPLEX_NORM_CX; REAL_ABS_NUM] THEN
    DISCH_THEN(MP_TAC o AP_TERM `\x:real. x pow 2`) THEN
    ASM_REWRITE_TAC[REAL_POW_MUL; REAL_POW_ONE] THEN
    REWRITE_TAC[REAL_OF_NUM_MUL; REAL_OF_NUM_EQ; MULT_EQ_1] THEN
    STRIP_TAC THEN
    MP_TAC(SPECL [`norm(u:complex)`; `2`] REAL_POW_EQ_1_IMP) THEN
    ASM_REWRITE_TAC[ARITH_EQ] THEN
    SIMP_TAC[NORM_POS_LE; REAL_ARITH `&0 <= x ==> abs x = x`];
    DISCH_TAC THEN EXISTS_TAC `cnj u` THEN
    ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CNJ] THEN
    ASM_REWRITE_TAC[COMPLEX_MUL_CNJ] THEN CONV_TAC COMPLEX_RING]);;

let IMAG_QUADRATIC_INTEGERS_UNIT_INV = prove
 (`!d u. ring_unit (imag_quadratic_integers d) u <=>
         u IN ring_carrier(imag_quadratic_integers d) /\ ~(u = Cx(&0)) /\
         inv u IN ring_carrier(imag_quadratic_integers d)`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[ring_unit; IMAG_QUADRATIC_INTEGERS_CLAUSES] THEN
  ASM_CASES_TAC `u = Cx(&0)` THEN
  ASM_REWRITE_TAC[COMPLEX_MUL_LZERO; CX_INJ; REAL_OF_NUM_EQ; ARITH_EQ] THEN
  AP_TERM_TAC THEN EQ_TAC THENL
   [DISCH_THEN(X_CHOOSE_THEN `v:complex` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN `inv u = v:complex` (fun th -> ASM_REWRITE_TAC[th]) THEN
    MATCH_MP_TAC COMPLEX_MUL_RINV_UNIQ THEN ASM_REWRITE_TAC[];
    DISCH_TAC THEN EXISTS_TAC `inv u:complex` THEN
    ASM_SIMP_TAC[COMPLEX_MUL_RINV]]);;

let IMAG_QUADRATIC_INTEGERS_NORM_GE_2 = prove
 (`!d z. z IN ring_carrier(imag_quadratic_integers d) /\ ~(z = Cx(&0)) /\
         ~(ring_unit (imag_quadratic_integers d) z)
         ==> &2 <= norm z pow 2`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_UNIT] THEN
  STRIP_TAC THEN
  MP_TAC(SPECL [`d:num`; `z:complex`] IMAG_QUADRATIC_INTEGERS_NORM_POW_2) THEN
  ASM_REWRITE_TAC[] THEN DISCH_THEN(X_CHOOSE_TAC `n:num`) THEN
  ASM_REWRITE_TAC[REAL_OF_NUM_LE] THEN
  ASM_CASES_TAC `n = 0` THENL
   [UNDISCH_TAC `norm(z:complex) pow 2 = &n` THEN
    ASM_REWRITE_TAC[REAL_POW_EQ_0; COMPLEX_NORM_ZERO; ARITH_EQ];
    ALL_TAC] THEN
  ASM_CASES_TAC `n = 1` THENL
   [MP_TAC(SPECL [`norm(z:complex)`; `2`] REAL_POW_EQ_1_IMP) THEN
    ASM_REWRITE_TAC[ARITH_EQ] THEN
    SIMP_TAC[NORM_POS_LE; REAL_ARITH `&0 <= x ==> abs x = x`] THEN
    ASM_MESON_TAC[];
    ASM_ARITH_TAC]);;

let IMAG_QUADRATIC_INTEGERS_DIVIDES = prove
 (`!d a b. ring_divides (imag_quadratic_integers d) a b <=>
           a IN ring_carrier(imag_quadratic_integers d) /\
           b IN ring_carrier(imag_quadratic_integers d) /\
           ?c. c IN ring_carrier(imag_quadratic_integers d) /\ b = a * c`,
  REWRITE_TAC[ring_divides; IMAG_QUADRATIC_INTEGERS_CLAUSES]);;

let IMAG_QUADRATIC_INTEGERS_DIVIDES_DIV = prove
 (`!d a b. ~(a = Cx(&0))
           ==> (ring_divides (imag_quadratic_integers d) a b <=>
                a IN ring_carrier(imag_quadratic_integers d) /\
                b IN ring_carrier(imag_quadratic_integers d) /\
                b / a IN ring_carrier(imag_quadratic_integers d))`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_DIVIDES] THEN
  AP_TERM_TAC THEN AP_TERM_TAC THEN EQ_TAC THENL
   [DISCH_THEN(X_CHOOSE_THEN `c:complex` STRIP_ASSUME_TAC) THEN
    SUBGOAL_THEN `b / a = c:complex` (fun th -> ASM_REWRITE_TAC[th]) THEN
    ASM_REWRITE_TAC[] THEN UNDISCH_TAC `~(a = Cx(&0))` THEN
    CONV_TAC COMPLEX_FIELD;
    DISCH_TAC THEN EXISTS_TAC `b / a:complex` THEN ASM_REWRITE_TAC[] THEN
    UNDISCH_TAC `~(a = Cx(&0))` THEN CONV_TAC COMPLEX_FIELD]);;

let IMAG_QUADRATIC_INTEGERS_DIVIDES_CX = prove
 (`!d n x y.
        squarefree d /\ integer n /\ ~(n = &0) /\ integer x /\ integer y
        ==> (ring_divides (imag_quadratic_integers d) (Cx n)
               (Cx x + Cx y * quad_omega d) <=>
             integer(x / n) /\ integer(y / n))`,
  REPEAT STRIP_TAC THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_DIVIDES_DIV; CX_INJ] THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CX;
               IMAG_QUADRATIC_INTEGERS_IN_COORDS] THEN
  SUBGOAL_THEN `(Cx x + Cx y * quad_omega d) / Cx n =
                Cx(x / n) + Cx(y / n) * quad_omega d`
  SUBST1_TAC THENL
   [REWRITE_TAC[CX_DIV] THEN UNDISCH_TAC `~(n = &0)` THEN
    REWRITE_TAC[GSYM CX_INJ] THEN CONV_TAC COMPLEX_FIELD;
    ALL_TAC] THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_IN] THEN EQ_TAC THENL
   [DISCH_THEN(X_CHOOSE_THEN `u:real` (X_CHOOSE_THEN `v:real`
      STRIP_ASSUME_TAC)) THEN
    MP_TAC(SPECL [`d:num`; `x / n:real`; `y / n:real`; `u:real`; `v:real`]
      QUAD_OMEGA_COORDS) THEN
    ASM_SIMP_TAC[LE_1; SQUAREFREE_IMP_NZ];
    STRIP_TAC THEN MAP_EVERY EXISTS_TAC [`x / n:real`; `y / n:real`] THEN
    ASM_REWRITE_TAC[]]);;

let IMAG_QUADRATIC_INTEGERS_DIVIDES_NORM = prove
 (`!d a b. ring_divides (imag_quadratic_integers d) a b
           ==> ?n. norm b pow 2 = norm a pow 2 * &n`,
  REPEAT GEN_TAC THEN REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_DIVIDES] THEN
  DISCH_THEN(CONJUNCTS_THEN2 ASSUME_TAC (CONJUNCTS_THEN2 ASSUME_TAC
   (X_CHOOSE_THEN `c:complex` STRIP_ASSUME_TAC))) THEN
  MP_TAC(SPECL [`d:num`; `c:complex`] IMAG_QUADRATIC_INTEGERS_NORM_POW_2) THEN
  ASM_REWRITE_TAC[COMPLEX_NORM_MUL; REAL_POW_MUL] THEN
  MESON_TAC[]);;

let IMAG_QUADRATIC_INTEGERS_ASSOCIATES_NORM = prove
 (`!d a b. ring_associates (imag_quadratic_integers d) a b
           ==> norm a = norm b`,
  REPEAT GEN_TAC THEN
  SIMP_TAC[INTEGRAL_DOMAIN_ASSOCIATES;
           IMAG_QUADRATIC_INTEGERS_INTEGRAL_DOMAIN] THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_UNIT;
              IMAG_QUADRATIC_INTEGERS_CLAUSES] THEN
  STRIP_TAC THEN FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  ASM_REWRITE_TAC[COMPLEX_NORM_MUL; REAL_MUL_RID]);;

(* ------------------------------------------------------------------------- *)
(* The units for squarefree d other than 1 and 3 are +-1 (from the units of  *)
(* imaginary quadratic fields of ANT/quadratic_units.ml).                    *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_UNIT_GENERIC = prove
 (`!d u. squarefree d /\ ~(d = 1) /\ ~(d = 3)
         ==> (ring_unit (imag_quadratic_integers d) u <=>
              u = Cx(&1) \/ u = --Cx(&1))`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`subring_generated complex_ring (imag_quadratic_field d)`;
                 `ii * Cx(sqrt(&d))`; `-- &d:int`]
         QUADRATIC_FIELD_UNITS_IMAGINARY_GENERIC) THEN
  REWRITE_TAC[IMAG_QUADRATIC_FIELD_NUMBER_FIELD; IMAG_QUADRATIC_FIELD_SQRT;
              RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD] THEN
  ANTS_TAC THENL
   [FIRST_ASSUM(ASSUME_TAC o MATCH_MP SQUAREFREE_IMP_NZ) THEN
    ASM_SIMP_TAC[IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD;
                 IMAG_QUADRATIC_FIELD_DEGREE] THEN
    REWRITE_TAC[INT_ABS_NEG; INT_ABS_NUM; NUM_OF_INT_OF_NUM] THEN
    ASM_REWRITE_TAC[INT_NEG_EQ; INT_NEG_NEG; INT_OF_NUM_EQ] THEN
    REWRITE_TAC[INT_ARITH `-- &d:int < &0 <=> &0:int < &d`; INT_OF_NUM_LT] THEN
    ASM_ARITH_TAC;
    DISCH_THEN(MP_TAC o SPEC `u:complex` o REWRITE_RULE[EXTENSION]) THEN
    REWRITE_TAC[IN_ELIM_THM; IN_INSERT; NOT_IN_EMPTY;
                SUBRING_GENERATED; COMPLEX_RING_CLAUSES]]);;

(* ------------------------------------------------------------------------- *)
(* The Euclidean algorithm for d = 1, 2, 3, 7, 11, with the norm as the      *)
(* Euclidean function: every complex number is at distance < 1 from the      *)
(* ring (round the coordinates in the basis 1, omega, INTEGER_ROUND), since  *)
(* Im(omega)^2 < 3; hence a PID and a UFD (EUCLIDEAN_DOMAIN_IMP_PID,         *)
(* PID_IMP_UFD of Library/ringtheory.ml).                                    *)
(* ------------------------------------------------------------------------- *)

let IMAG_QUADRATIC_INTEGERS_NEAR = prove
 (`!d z. d IN {1,2,3,7,11}
         ==> ?q. q IN ring_carrier(imag_quadratic_integers d) /\
                 norm(z - q) < &1`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  SUBGOAL_THEN `1 <= d /\ Im(quad_omega d) pow 2 < &3` STRIP_ASSUME_TAC THENL
   [REWRITE_TAC[QUAD_OMEGA_RE_IM] THEN
    FIRST_X_ASSUM(REPEAT_TCL DISJ_CASES_THEN SUBST1_TAC o
      REWRITE_RULE[IN_INSERT; NOT_IN_EMPTY]) THEN
    CONV_TAC NUM_REDUCE_CONV THEN
    SIMP_TAC[REAL_POW_DIV; SQRT_POW_2; REAL_POS] THEN
    CONV_TAC REAL_RAT_REDUCE_CONV;
    ALL_TAC] THEN
  FIRST_ASSUM(ASSUME_TAC o MATCH_MP QUAD_OMEGA_IM_POS) THEN
  ABBREV_TAC `w = quad_omega d` THEN
  X_CHOOSE_THEN `n:real` STRIP_ASSUME_TAC
   (SPEC `Im z / Im w` INTEGER_ROUND) THEN
  X_CHOOSE_THEN `m:real` STRIP_ASSUME_TAC
   (SPEC `Re z - n * Re w` INTEGER_ROUND) THEN
  EXISTS_TAC `Cx m + Cx n * w` THEN CONJ_TAC THENL
   [EXPAND_TAC "w" THEN MATCH_MP_TAC IMAG_QUADRATIC_INTEGERS_IN_COORDS THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  MATCH_MP_TAC REAL_POW_LT2_REV THEN EXISTS_TAC `2` THEN
  REWRITE_TAC[REAL_POS; REAL_POW_ONE; COMPLEX_SQNORM] THEN
  REWRITE_TAC[RE_SUB; IM_SUB; RE_ADD; IM_ADD; RE_CX; IM_CX; RE_MUL_CX;
              IM_MUL_CX; REAL_ADD_LID] THEN
  SUBGOAL_THEN `Im z - n * Im w = (Im z / Im w - n) * Im w` SUBST1_TAC THENL
   [UNDISCH_TAC `&0 < Im w` THEN CONV_TAC REAL_FIELD; ALL_TAC] THEN
  REWRITE_TAC[REAL_POW_MUL] THEN
  MATCH_MP_TAC(REAL_ARITH
   `a <= &1 / &4 /\ b * c <= &1 / &4 * c /\ c < &3 ==> a + b * c < &1`) THEN
  ASM_REWRITE_TAC[] THEN CONJ_TAC THENL
   [ALL_TAC; MATCH_MP_TAC REAL_LE_RMUL THEN REWRITE_TAC[REAL_LE_POW_2]] THEN
  ONCE_REWRITE_TAC[GSYM REAL_POW2_ABS] THEN
  MATCH_MP_TAC(REAL_ARITH `x <= (&1 / &2) pow 2 ==> x <= &1 / &4`) THEN
  MATCH_MP_TAC REAL_POW_LE2 THEN ASM_REAL_ARITH_TAC);;

let IMAG_QUADRATIC_INTEGERS_NORM_EUCLIDEAN = prove
 (`!d a b. d IN {1,2,3,7,11} /\
           a IN ring_carrier(imag_quadratic_integers d) /\
           b IN ring_carrier(imag_quadratic_integers d) /\ ~(b = Cx(&0))
           ==> ?q. q IN ring_carrier(imag_quadratic_integers d) /\
                   norm(a - q * b) < norm b`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o SPEC `a / b:complex` o
    MATCH_MP IMAG_QUADRATIC_INTEGERS_NEAR) THEN
  MATCH_MP_TAC MONO_EXISTS THEN X_GEN_TAC `q:complex` THEN
  STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `a - q * b = (a / b - q) * b:complex` SUBST1_TAC THENL
   [UNDISCH_TAC `~(b = Cx(&0))` THEN CONV_TAC COMPLEX_FIELD; ALL_TAC] THEN
  REWRITE_TAC[COMPLEX_NORM_MUL] THEN
  GEN_REWRITE_TAC RAND_CONV [GSYM REAL_MUL_LID] THEN
  MATCH_MP_TAC REAL_LT_RMUL THEN ASM_REWRITE_TAC[COMPLEX_NORM_NZ]);;

let IMAG_QUADRATIC_INTEGERS_EUCLIDEAN = prove
 (`!d. d IN {1,2,3,7,11} ==> euclidean_ring(imag_quadratic_integers d)`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[euclidean_ring] THEN
  EXISTS_TAC `\z:complex. @n. norm z pow 2 = &n` THEN
  REWRITE_TAC[IMAG_QUADRATIC_INTEGERS_CLAUSES] THEN
  MAP_EVERY X_GEN_TAC [`a:complex`; `b:complex`] THEN STRIP_TAC THEN
  MP_TAC(SPECL [`d:num`; `a:complex`; `b:complex`]
    IMAG_QUADRATIC_INTEGERS_NORM_EUCLIDEAN) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(X_CHOOSE_THEN `q:complex` STRIP_ASSUME_TAC) THEN
  MAP_EVERY EXISTS_TAC [`q:complex`; `a - b * q:complex`] THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CLOSED] THEN
  CONJ_TAC THENL [CONV_TAC COMPLEX_RING; DISJ2_TAC] THEN
  SUBGOAL_THEN `!z. z IN ring_carrier(imag_quadratic_integers d)
                    ==> norm z pow 2 = &(@n. norm z pow 2 = &n)`
  MP_TAC THENL
   [GEN_TAC THEN DISCH_THEN(MP_TAC o MATCH_MP
      IMAG_QUADRATIC_INTEGERS_NORM_POW_2) THEN
    CONV_TAC(ONCE_DEPTH_CONV SELECT_CONV) THEN REWRITE_TAC[];
    DISCH_THEN(fun th -> MP_TAC(SPEC `b:complex` th) THEN
      MP_TAC(SPEC `a - b * q:complex` th))] THEN
  ASM_SIMP_TAC[IMAG_QUADRATIC_INTEGERS_CLOSED; GSYM REAL_OF_NUM_LT] THEN
  REPEAT(DISCH_THEN(SUBST1_TAC o SYM)) THEN
  MATCH_MP_TAC REAL_POW_LT2 THEN REWRITE_TAC[NORM_POS_LE; ARITH_EQ] THEN
  ONCE_REWRITE_TAC[COMPLEX_MUL_SYM] THEN ASM_REWRITE_TAC[]);;

let IMAG_QUADRATIC_INTEGERS_PID = prove
 (`!d. d IN {1,2,3,7,11} ==> PID(imag_quadratic_integers d)`,
  SIMP_TAC[EUCLIDEAN_DOMAIN_IMP_PID; IMAG_QUADRATIC_INTEGERS_EUCLIDEAN;
           IMAG_QUADRATIC_INTEGERS_INTEGRAL_DOMAIN]);;

let IMAG_QUADRATIC_INTEGERS_UFD = prove
 (`!d. d IN {1,2,3,7,11} ==> UFD(imag_quadratic_integers d)`,
  SIMP_TAC[PID_IMP_UFD; IMAG_QUADRATIC_INTEGERS_PID]);;
