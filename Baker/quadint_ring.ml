(* ========================================================================= *)
(* The ring of integers of Q(sqrt(-d)): the carrier Z[omega], the units, the *)
(* Euclidean algorithm for d = 1, 2, 3, 7, 11.                               *)
(*                                                                           *)
(* Purpose: for squarefree d, the ring imag_quadratic_integers d (the        *)
(* algebraic integers of the field imag_quadratic_field d, as a subring of   *)
(* complex_ring: Baker/quadint_ant.ml) has the carrier Z[omega] = {x + y     *)
(* omega | x, y integers}, where omega = quad_omega d is (1 + sqrt(-d))/2 if *)
(* d = 3 mod 4 and sqrt(-d) otherwise (IMAG_QUADRATIC_INTEGERS_CARRIER). The *)
(* arithmetic of omega: square, conjugate, norm form and uniqueness of       *)
(* coordinates (QUAD_OMEGA_SQUARE, QUAD_OMEGA_CNJ, QUAD_OMEGA_NORM,          *)
(* QUAD_OMEGA_COORDS); elements, norms, units and divisibility in the ring.  *)
(* For squarefree d other than 1, 3 the units are +-1                        *)
(* (IMAG_QUADRATIC_INTEGERS_UNIT_GENERIC); for d = 1, 2, 3, 7, 11 the ring   *)
(* is Euclidean for the norm (IMAG_QUADRATIC_INTEGERS_NORM_EUCLIDEAN,        *)
(* _EUCLIDEAN), hence a PID and a UFD (IMAG_QUADRATIC_INTEGERS_PID, _UFD),   *)
(* without the class number one theorem (for Baker/lebesgue.ml and the       *)
(* applications of section 17).                                              *)
(*                                                                           *)
(* Method: Z[omega] is a corollary of the integral basis of quadratic number *)
(* fields (QUADRATIC_FIELD_INTEGRAL_BASIS of ANT/quadratic.ml): if x^2 = D   *)
(* in a number field of degree 2, D squarefree and D <> 1, the ring of       *)
(* integers has the Z-basis 1, (1 + x)/2 if D = 1 mod 4 and 1, x otherwise.  *)
(* Here the field is the subring of complex_ring generated by                *)
(* imag_quadratic_field d, its ring of integers is imag_quadratic_integers d *)
(* (RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD), x = sqrt(-d), D = -d, and -d = 1 *)
(* mod 4 iff d = 3 mod 4 (QUAD_DMOD4_CONG), so the second basis element is   *)
(* omega. Conversely every x + y omega with integers x and y is an algebraic *)
(* integer of the field (IMAG_QUADRATIC_INTEGERS_COORDS_IN): omega is a root *)
(* of z^2 - z + (d + 1)/4, resp. z^2 + d (QUAD_OMEGA_ALGEBRAIC_INTEGER). The *)
(* units: QUADRATIC_FIELD_UNITS_IMAGINARY_GENERIC of ANT/quadratic_units.ml. *)
(* Euclid: rounding the coordinates of z in the basis 1, omega               *)
(* (INTEGER_ROUND) gives q in the ring with norm(z - q)^2 <= 1/4 +           *)
(* Im(omega)^2/4 < 1 (IMAG_QUADRATIC_INTEGERS_NEAR; Im(omega)^2 = d/4 resp.  *)
(* d is < 3); for z = a/b this is division with remainder for the squared    *)
(* norm, a natural number on the ring; then EUCLIDEAN_DOMAIN_IMP_PID and     *)
(* PID_IMP_UFD of Library/ringtheory.ml.                                     *)
(*                                                                           *)
(* Main results: the theorems above; general tools (for every d unless       *)
(* stated): IMAG_QUADRATIC_INTEGERS_IN (membership by coordinates,           *)
(* squarefree d), IMAG_QUADRATIC_INTEGERS_IN_COORDS,                         *)
(* IMAG_QUADRATIC_INTEGERS_CLOSED (closure, also under cnj),                 *)
(* IMAG_QUADRATIC_INTEGERS_CX (the rational integers),                       *)
(* IMAG_QUADRATIC_INTEGERS_NORM_POW_2 (norms are natural numbers),           *)
(* IMAG_QUADRATIC_INTEGERS_UNIT (units are the elements of norm 1),          *)
(* IMAG_QUADRATIC_INTEGERS_NORM_GE_2 (non-zero non-units),                   *)
(* IMAG_QUADRATIC_INTEGERS_DIVIDES, IMAG_QUADRATIC_INTEGERS_DIVIDES_DIV,     *)
(* IMAG_QUADRATIC_INTEGERS_DIVIDES_CX (divisibility by rational integers),   *)
(* IMAG_QUADRATIC_INTEGERS_DIVIDES_NORM,                                     *)
(* IMAG_QUADRATIC_INTEGERS_ASSOCIATES_NORM, QUAD_OMEGA_CNJ_COORDS,           *)
(* QUAD_OMEGA_MUL_COORDS, QUAD_INTEGER_PARITY, QUAD_INTEGER_TAC,             *)
(* IMAG_QUADRATIC_INTEGERS_NEAR; helper names QUAD_* and IMAG_QUADRATIC_*.   *)
(*                                                                           *)
(* Uses: Baker/quadint_ant.ml (the field and the ring:                       *)
(* IMAG_QUADRATIC_FIELD_IN, IMAG_QUADRATIC_FIELD_SUBFIELD,                   *)
(* IMAG_QUADRATIC_FIELD_SQRT, IMAG_QUADRATIC_FIELD_DEGREE,                   *)
(* IMAG_QUADRATIC_FIELD_NUMBER_FIELD, IMAG_QUADRATIC_FIELD_PRIME_SUBFIELD,   *)
(* RING_OF_INTEGERS_IMAG_QUADRATIC_FIELD, IMAG_QUADRATIC_INTEGERS_IN_ALT,    *)
(* IMAG_QUADRATIC_INTEGERS_CLAUSES, IMAG_QUADRATIC_INTEGERS_INTEGRAL_DOMAIN, *)
(* QUAD_SQRT_POW_2, QUAD_ALGEBRAIC_INTEGER_QUADRATIC, QUAD_DMOD4_CONG);      *)
(* Baker/ant_bridge_complex.ml (RATIONAL_IN_COMPLEX_SUBFIELD);               *)
(* ANT/quadratic.ml (QUADRATIC_FIELD_INTEGRAL_BASIS); ANT/quadratic_units.ml *)
(* (QUADRATIC_FIELD_UNITS_IMAGINARY_GENERIC); ANT/algmisc.ml (FORALL_LT_2);  *)
(* Baker/algint.ml (algebraic_integer, ALGEBRAIC_INTEGER_CNJ,                *)
(* ALGEBRAIC_INTEGER_RATIONAL, closure lemmas); Library/floor.ml             *)
(* (INTEGER_ROUND); Library/fieldtheory.ml (RING_INV_SUBRING_GENERATED);     *)
(* Library/ringtheory.ml (INTEGRAL_DOMAIN_ASSOCIATES, RING_SUM_LT_2,         *)
(* euclidean_ring, EUCLIDEAN_DOMAIN_IMP_PID, PID_IMP_UFD);                   *)
(* Library/pocklington.ml (squarefree, SQUAREFREE_IMP_NZ);                   *)
(* Multivariate/complex_ring.ml (COMPLEX_RING_CLAUSES, COMPLEX_RING_INV).    *)
(* ========================================================================= *)

