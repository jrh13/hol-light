(* ========================================================================= *)
(* Sharpening I: the extrapolation and the parametric core.                  *)
(*                                                                           *)
(* Purpose: SHARP_CORE_PARAMETRIC, the parametric core of Sharpening I       *)
(* (Baker, Acta Arith. 21, 1972, sections 3 and 4; A central theorem in      *)
(* transcendence theory, 1973, sections 3 and 4) for complex logarithms lg r *)
(* of algebraic numbers (sharp_algdata: cexp(lg r) is a root of the integer  *)
(* polynomial a r of degree dd r with coefficients of size at most H r) and  *)
(* complex coefficients bb r (sharpc_coefdata: bb r is a root of the integer *)
(* polynomial ab r of degree db r with coefficients of size at most Hb),     *)
(* norm(bb r) <= B and norm(bb n) >= 1, for any Delta representation         *)
(* (sharp_deltarep; SHARP_DELTAREP_INT for integer coefficients,             *)
(* SHARP_DELTAREP_ALG for algebraic ones). If the parameters satisfy the     *)
(* Siegel count with the degree product of the alphas and the betas, the     *)
(* extrapolation inequalities at the integers (Lemma 6, lower bound          *)
(* sharp_liou5) and the Lemma 8 inequalities at the points l/pr (lower bound *)
(* sharp_lb8), then cexp(lg n) is a product of powers cexp(lg r)^jj r        *)
(* (r < n, jj r < pr) times the pr-th power of an element of the subfield of *)
(* C generated by the numbers cexp(lg r) and bb r. The two endings           *)
(* (Baker/make.ml sections 6 and 7: integer and algebraic coefficients) are  *)
(* instances.                                                                *)
(*                                                                           *)
(* Method: SHARP_CORE_EXTRAPOLATION is the analytic part, generic in the     *)
(* logarithms lg r, the coefficients bb r, the degrees Lv, the coefficient   *)
(* bound P of the auxiliary polynomial p and two lower bounds lb5 (for       *)
(* non-zero values of the counterpart sharp_alg at the integers l) and lb8   *)
(* (for non-zero values at l/pr): if sharp_alg vanishes at 1..h for all      *)
(* derivative orders with sum at most S0, the two extrapolation inductions   *)
(* (EXTRAPOLATION_INDUCTION_COEFF from the integers to the integers,         *)
(* RATIONAL_EXTRAPOLATION_COEFF from the integers to l/pr) force it to       *)
(* vanish at all l/pr with derivative orders m i <= L. SHARP_CORE_PARAMETRIC *)
(* supplies the arithmetic: Siegel (SHARP_LEMMA5, bound sharp_psize), the    *)
(* dichotomy at the integers (SHARP_DICHOTOMY, bound sharp_liou5 for all     *)
(* derivative orders up to S0), Lemma 8 at l/pr (SHARP_LEMMA8, bound         *)
(* sharp_lb8, Nz = l + 1 by SHARP_RAT_POINT_NORM) and section 4 (SHARP_SEC4, *)
(* bb n <> 0 from norm(bb n) >= 1). The size functions sharp_ubd and         *)
(* sharp_errb are pure real functions of the analytic size bound B.          *)
(*                                                                           *)
(* Main results: SHARP_CORE_PARAMETRIC, SHARP_CORE_EXTRAPOLATION,            *)
(* SHARP_RAT_POINT_NORM.                                                     *)
(*                                                                           *)
(* Uses: Baker/sharp_defs.ml (sharp_index, sharp_omega, sharp_aux,           *)
(* sharp_alg, sharp_coeff, sharp_coeff0, sharp_algdata, sharp_deltarep,      *)
(* sharp_psize, sharp_liou5, sharp_lb8, sharp_ubd, sharp_errb, sharp_lv),    *)
(* Baker/uniform.ml (sharpc_coefdata), Baker/sharp_aux.ml                    *)
(* (SHARP_AUX_HOLOMORPHIC, SHARP_AUX_DERIVATIVE, SHARP_COEFF_BOUND,          *)
(* SHARP_AUX_UBD, SHARP_AUX_ERRB), Baker/sharp_arith.ml (SHARP_LEMMA5,       *)
(* SHARP_DICHOTOMY, SHARP_LEMMA8), Baker/sharp_sec4.ml (SHARP_SEC4),         *)
(* Baker/extrap.ml (EXTRAPOLATION_INDUCTION_COEFF,                           *)
(* RATIONAL_EXTRAPOLATION_COEFF).                                            *)
(* ========================================================================= *)

needs "Baker/sharp_arith.ml";;
needs "Baker/sharp_sec4.ml";;

prioritize_real();;
prioritize_num();;

(* ------------------------------------------------------------------------- *)
(* The points l/q (q >= 1) of Lemma 8: their norm and the bound Nz = l + 1.  *)
(* ------------------------------------------------------------------------- *)

let SHARP_RAT_POINT_NORM = prove
 (`!l q. 1 <= q
         ==> norm(Cx(&l) / Cx(&q)) = &l / &q /\ &l / &q + &1 <= &(l + 1)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  REWRITE_TAC[COMPLEX_NORM_DIV; COMPLEX_NORM_CX; REAL_ABS_NUM] THEN
  REWRITE_TAC[GSYM REAL_OF_NUM_ADD; REAL_LE_RADD] THEN
  SUBGOAL_THEN `&0 < &q` ASSUME_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LT] THEN UNDISCH_TAC `1 <= q` THEN ARITH_TAC;
    ALL_TAC] THEN
  ASM_SIMP_TAC[REAL_LE_LDIV_EQ] THEN
  GEN_REWRITE_TAC LAND_CONV [GSYM REAL_MUL_RID] THEN
  MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REWRITE_TAC[REAL_POS; REAL_OF_NUM_LE]);;

(* ------------------------------------------------------------------------- *)
(* The analytic part of the core: extrapolation from the zeros at 1..h to    *)
(* the vanishing at the points l/pr, given lower bounds lb5 at the integers  *)
(* and lb8 at the points l/pr for the non-zero values of the counterpart     *)
(* sharp_alg. Generic in the logarithms lg, the complex coefficients bb,     *)
(* the degrees Lv and the bound P (SHARP_CORE_EXTRAPOLATION with complex     *)
(* coefficients).                                                            *)
(* ------------------------------------------------------------------------- *)

let SHARP_CORE_EXTRAPOLATION = prove
 (`!n h L0 Lv Lm (p:num#num#(num->num)->real) (bb:num->complex)
    (lg:num->complex) P B S0 T0 d0 Nl eps J (R:num->num) (S:num->num)
    (rho:num->real) (NR:num->num) (V:num->real) L X Y rhoX NX pr K8
    (lb5:num->real) (lb8:(num->num)->num->real).
     1 <= n /\ 1 <= h /\ &1 <= B /\ &0 <= P /\ &0 <= d0 /\
     &1 <= norm(bb n) /\
     (!x. x IN sharp_index h L0 Lv n ==> abs(p x) <= P) /\
     (!r. r IN 1..n ==> norm(bb r) <= B /\ Lv r <= Lm) /\
     (!mu. mu IN cartesian_product (1..n) (\r. 0..Lv r)
           ==> norm(sharp_omega n bb lg mu) <= T0 /\
               norm(sharp_omega n bb lg mu -
                    vsum(1..n) (\r. Cx(&(mu r)) * lg r)) <= d0) /\
     &1 + &2 * sum(1..n-1) (\i. norm(lg i)) <= &Nl /\
     (!m l. nsum(0..n-1) m <= S0 /\ 1 <= l /\ l <= h
            ==> sharp_alg n h L0 Lv p bb lg m (Cx(&l)) = Cx(&0)) /\
     (!m l. nsum(0..n-1) m <= S0 /\ 1 <= l /\
            ~(sharp_alg n h L0 Lv p bb lg m (Cx(&l)) = Cx(&0))
            ==> lb5 l <= norm(sharp_alg n h L0 Lv p bb lg m (Cx(&l)))) /\
     (!m l. (!i. i < n ==> m i <= L) /\ 1 <= l /\ l <= K8 /\
            ~(pr divides l) /\
            ~(sharp_alg n h L0 Lv p bb lg m (Cx(&l) / Cx(&pr)) = Cx(&0))
            ==> lb8 m l <=
                norm(sharp_alg n h L0 Lv p bb lg m (Cx(&l) / Cx(&pr)))) /\
     (!l. 1 <= l /\ l <= h
          ==> sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l) <= eps) /\
     R 0 = h /\ S 0 = S0 /\
     (!K. K < J
          ==> R K <= R(K + 1) /\ 2 * S(K + 1) <= S K /\
              &4 * &(R(K + 1)) <= rho K /\ rho K + &1 <= &(NR K) /\
              (!l. R K < l /\ l <= R(K + 1)
                   ==> sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l)
                       <= eps /\
                       V K + sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l)
                       < lb5 l) /\
              &2 * sharp_ubd n h L0 Lv Lm P B S0 T0 (NR K) (rho K) *
              (&4 * &(R(K + 1)) / rho K) pow (R K * (S(K + 1) + 1)) +
              eps * &2 * &(R K) * &2 pow (S(K + 1)) * exp(&(S0 * Nl)) *
              (&(R(K + 1)) * &16 pow (R(K + 1))) pow (S(K + 1) + 1)
              <= V K) /\
     1 <= X /\ X <= R J /\ n * L + Y <= S J /\ &4 * &X <= rhoX /\
     rhoX + &1 <= &NX /\ K8 <= pr * X /\ 1 <= pr /\
     (!m l. (!i. i < n ==> m i <= L) /\ 1 <= l /\ l <= K8 /\
            ~(pr divides l)
            ==> (&2 * sharp_ubd n h L0 Lv Lm P B S0 T0 NX rhoX *
                 (&4 * &X / rhoX) pow (X * (Y + 1)) +
                 eps * &2 * &pr * &X * (&2 * &pr) pow Y * exp(&(S0 * Nl)) *
                 (&X * &16 pow X) pow (Y + 1)) +
                sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l / &pr)
                < lb8 m l)
     ==> !m l. (!i. i < n ==> m i <= L) /\ 1 <= l /\ l <= K8 /\
               ~(pr divides l)
               ==> sharp_alg n h L0 Lv p bb lg m (Cx(&l) / Cx(&pr)) =
                   Cx(&0)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN
   `!mu. mu IN cartesian_product (1..n) (\r. 0..(Lv:num->num) r)
         ==> norm(sharp_omega n bb lg mu) <= T0`
  ASSUME_TAC THENL
   [MP_TAC(ASSUME
     `!mu. mu IN cartesian_product (1..n) (\r. 0..(Lv:num->num) r)
           ==> norm(sharp_omega n bb lg mu) <= T0 /\
               norm(sharp_omega n bb lg mu -
                    vsum(1..n) (\r. Cx(&(mu r)) * lg r)) <= d0`) THEN
    MESON_TAC[];
    ALL_TAC] THEN
  ABBREV_TAC `f = \m. sharp_aux n h L0 Lv p bb lg m` THEN
  SUBGOAL_THEN
   `(!m. (f:(num->num)->complex->complex) m holomorphic_on (:complex)) /\
    (!m. complex_derivative (f m) =
         \z. vsum(0..n-1) (\i. sharp_coeff n bb lg m i *
                               f (\r. if r = i then m r + 1 else m r) z) +
             sharp_coeff0 n bb lg m * f m z) /\
    (!m. nsum(0..n-1) m < S0
         ==> sum(0..n-1) (\i. norm(sharp_coeff n bb lg m i)) +
             norm(sharp_coeff0 n bb lg m) <= &(S0 * Nl))`
  STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "f" THEN REWRITE_TAC[SHARP_AUX_HOLOMORPHIC] THEN
    ASM_SIMP_TAC[SHARP_AUX_DERIVATIVE] THEN REPEAT STRIP_TAC THEN
    MATCH_MP_TAC SHARP_COEFF_BOUND THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!m z N. nsum(0..n-1) m <= S0 /\ norm z + &1 <= &N
            ==> norm((f:(num->num)->complex->complex) m z) <=
                sharp_ubd n h L0 Lv Lm P B S0 T0 N (norm z) /\
                norm(f m z - sharp_alg n h L0 Lv p bb lg m z) <=
                sharp_errb n h L0 Lv Lm P B S0 T0 d0 N (norm z)`
  ASSUME_TAC THENL
   [REPEAT GEN_TAC THEN STRIP_TAC THEN EXPAND_TAC "f" THEN
    SUBGOAL_THEN `nsum(1..n-1) m <= S0` ASSUME_TAC THENL
     [TRANS_TAC LE_TRANS `nsum(0..n-1) m` THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC NSUM_SUBSET_SIMPLE THEN
      REWRITE_TAC[FINITE_NUMSEG; SUBSET; IN_NUMSEG] THEN ARITH_TAC;
      ALL_TAC] THEN
    CONJ_TAC THENL
     [MATCH_MP_TAC SHARP_AUX_UBD; MATCH_MP_TAC SHARP_AUX_ERRB] THEN
    ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `!K. K <= J ==> (S:num->num) K <= S0` ASSUME_TAC THENL
   [INDUCT_TAC THENL [ASM_REWRITE_TAC[LE_REFL]; ALL_TAC] THEN
    DISCH_TAC THEN FIRST_X_ASSUM(MP_TAC o check (is_imp o concl)) THEN
    ANTS_TAC THENL [UNDISCH_TAC `SUC K <= J` THEN ARITH_TAC; ALL_TAC] THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `K:num` o check (fun th ->
      is_forall(concl th) && free_in `V:num->real` (concl th))) THEN
    ANTS_TAC THENL [UNDISCH_TAC `SUC K <= J` THEN ARITH_TAC; ALL_TAC] THEN
    REWRITE_TAC[ADD1] THEN ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN
   `!m l. nsum(0..n-1) m <= S0 /\ 1 <= l /\
          sharp_alg n h L0 Lv p bb lg m (Cx(&l)) = Cx(&0)
          ==> norm((f:(num->num)->complex->complex) m (Cx(&l))) <=
              sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l)`
  ASSUME_TAC THENL
   [REPEAT STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPECL [`m:num->num`; `Cx(&l)`; `l + 1`] o
      check (fun th -> is_forall(concl th) &&
                       free_in `sharp_errb` (concl th))) THEN
    ASM_REWRITE_TAC[COMPLEX_NORM_CX; REAL_ABS_NUM; GSYM REAL_OF_NUM_ADD;
                    REAL_LE_REFL; COMPLEX_SUB_RZERO] THEN
    SIMP_TAC[];
    ALL_TAC] THEN
  MP_TAC(ISPECL
   [`f:(num->num)->complex->complex`; `sharp_coeff n bb lg`;
    `sharp_coeff0 n bb lg`; `n:num`; `R:num->num`; `S:num->num`;
    `rho:num->real`;
    `\K:num. sharp_ubd n h L0 Lv Lm P B S0 T0 ((NR:num->num) K)
                       ((rho:num->real) K)`;
    `V:num->real`; `eps:real`; `J:num`; `S0 * Nl`]
   EXTRAPOLATION_INDUCTION_COEFF) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[LE_REFL] THEN REPEAT CONJ_TAC THENL
     [X_GEN_TAC `K:num` THEN DISCH_TAC THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `K:num` o check (fun th ->
        is_forall(concl th) && free_in `V:num->real` (concl th))) THEN
      ASM_REWRITE_TAC[] THEN STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
      SUBGOAL_THEN `S(K + 1) <= S0` ASSUME_TAC THENL
       [FIRST_X_ASSUM MATCH_MP_TAC THEN UNDISCH_TAC `K < J` THEN ARITH_TAC;
        ALL_TAC] THEN
      CONJ_TAC THENL
       [REPEAT STRIP_TAC THEN
        FIRST_X_ASSUM(MP_TAC o SPECL [`m:num->num`; `z:complex`;
          `(NR:num->num) K`] o check (fun th -> is_forall(concl th) &&
                                     free_in `sharp_ubd` (concl th))) THEN
        ASM_REWRITE_TAC[] THEN ANTS_TAC THENL
         [MAP_EVERY UNDISCH_TAC
           [`nsum(0..n-1) m <= S(K + 1)`; `S(K + 1) <= S0`] THEN ARITH_TAC;
          SIMP_TAC[]];
        ALL_TAC] THEN
      MAP_EVERY X_GEN_TAC [`m:num->num`; `l:num`] THEN STRIP_TAC THEN
      SUBGOAL_THEN `1 <= l /\ nsum(0..n-1) m <= S0` STRIP_ASSUME_TAC THENL
       [CONJ_TAC THENL
         [UNDISCH_TAC `(R:num->num) K < l` THEN ARITH_TAC;
          MAP_EVERY UNDISCH_TAC
           [`nsum(0..n-1) m <= S(K + 1)`; `S(K + 1) <= S0`] THEN ARITH_TAC];
        ALL_TAC] THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `l:num` o check (fun th ->
        is_forall(concl th) && free_in `V:num->real` (concl th))) THEN
      ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
      ASM_CASES_TAC
       `sharp_alg n h L0 Lv p bb lg m (Cx(&l)) = Cx(&0)` THENL
       [DISJ1_TAC THEN TRANS_TAC REAL_LE_TRANS
         `sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l)` THEN
        ASM_REWRITE_TAC[] THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
        ASM_REWRITE_TAC[];
        DISJ2_TAC] THEN
      FIRST_ASSUM(MP_TAC o SPECL [`m:num->num`; `l:num`] o check (fun th ->
        is_forall(concl th) && free_in `lb5:num->real` (concl th))) THEN
      ANTS_TAC THENL
       [REPEAT CONJ_TAC THEN FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
      FIRST_ASSUM(MP_TAC o check (fun th ->
        free_in `V:num->real` (concl th) &&
        free_in `lb5:num->real` (concl th))) THEN
      FIRST_X_ASSUM(MP_TAC o SPECL [`m:num->num`; `Cx(&l)`; `l + 1`] o
        check (fun th -> is_forall(concl th) &&
                         free_in `sharp_errb` (concl th) &&
                         free_in `sharp_ubd` (concl th))) THEN
      REWRITE_TAC[COMPLEX_NORM_CX; REAL_ABS_NUM; GSYM REAL_OF_NUM_ADD;
                  REAL_LE_REFL] THEN
      ANTS_TAC THENL [FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
      MP_TAC(ISPECL [`sharp_alg n h L0 Lv p bb lg m (Cx(&l))`;
                     `(f:(num->num)->complex->complex) m (Cx(&l))`]
                    NORM_TRIANGLE_SUB) THEN
      MP_TAC(ISPECL [`(f:(num->num)->complex->complex) m (Cx(&l))`;
                     `sharp_alg n h L0 Lv p bb lg m (Cx(&l))`] NORM_SUB) THEN
      REAL_ARITH_TAC;
      MAP_EVERY X_GEN_TAC [`m:num->num`; `l:num`] THEN STRIP_TAC THEN
      TRANS_TAC REAL_LE_TRANS
       `sharp_errb n h L0 Lv Lm P B S0 T0 d0 (l + 1) (&l)` THEN
      CONJ_TAC THENL
       [FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[] THEN
        FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[];
        FIRST_X_ASSUM MATCH_MP_TAC THEN ASM_REWRITE_TAC[]]];
    DISCH_TAC] THEN
  MAP_EVERY X_GEN_TAC [`m:num->num`; `l:num`] THEN STRIP_TAC THEN
  MATCH_MP_TAC(TAUT `(~p ==> F) ==> p`) THEN DISCH_TAC THEN
  SUBGOAL_THEN `nsum(0..n-1) m <= n * L` ASSUME_TAC THENL
   [TRANS_TAC LE_TRANS `nsum(0..n-1) (\i:num. L)` THEN CONJ_TAC THENL
     [MATCH_MP_TAC NSUM_LE_NUMSEG THEN REPEAT STRIP_TAC THEN BETA_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN
      MAP_EVERY UNDISCH_TAC [`i <= n - 1`; `1 <= n`] THEN ARITH_TAC;
      REWRITE_TAC[NSUM_CONST_NUMSEG] THEN
      SUBGOAL_THEN `((n - 1) + 1) - 0 = n` SUBST1_TAC THENL
       [UNDISCH_TAC `1 <= n` THEN ARITH_TAC; REWRITE_TAC[LE_REFL]]];
    ALL_TAC] THEN
  SUBGOAL_THEN `nsum(0..n-1) m <= S0 /\ nsum(0..n-1) m + Y <= S0`
  STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `S(J:num) <= S0` MP_TAC THENL
     [FIRST_X_ASSUM MATCH_MP_TAC THEN ARITH_TAC;
      MAP_EVERY UNDISCH_TAC
       [`nsum(0..n-1) m <= n * L`;
        `n * L + Y <= (S:num->num) J`] THEN ARITH_TAC];
    ALL_TAC] THEN
  MP_TAC(ISPECL [`f:(num->num)->complex->complex`; `sharp_coeff n bb lg`;
                 `sharp_coeff0 n bb lg`; `n:num`; `X:num`; `Y:num`;
                 `m:num->num`; `pr:num`; `l:num`; `rhoX:real`;
                 `sharp_ubd n h L0 Lv Lm P B S0 T0 NX rhoX`; `eps:real`;
                 `S0 * Nl`] RATIONAL_EXTRAPOLATION_COEFF) THEN
  ANTS_TAC THENL
   [ASM_REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
     [REPEAT STRIP_TAC THEN FIRST_X_ASSUM MATCH_MP_TAC THEN
      MAP_EVERY UNDISCH_TAC
       [`nsum(0..n-1) m' < nsum(0..n-1) m + Y`;
        `nsum(0..n-1) m + Y <= S0`] THEN
      ARITH_TAC;
      TRANS_TAC LE_TRANS `K8:num` THEN ASM_REWRITE_TAC[];
      REPEAT STRIP_TAC THEN
      FIRST_X_ASSUM(MP_TAC o SPECL [`m:num->num`; `z:complex`; `NX:num`] o
        check (fun th -> is_forall(concl th) &&
                         free_in `sharp_ubd` (concl th) &&
                         free_in `sharp_errb` (concl th))) THEN
      ASM_REWRITE_TAC[] THEN SIMP_TAC[];
      MAP_EVERY X_GEN_TAC [`m':num->num`; `r:num`] THEN STRIP_TAC THEN
      FIRST_X_ASSUM MATCH_MP_TAC THEN
      MAP_EVERY UNDISCH_TAC
       [`nsum(0..n-1) m' <= nsum(0..n-1) m + Y`; `nsum(0..n-1) m <= n * L`;
        `n * L + Y <= (S:num->num) J`; `1 <= r`; `r <= X`;
        `X <= (R:num->num) J`] THEN
      ARITH_TAC];
    ALL_TAC] THEN
  MP_TAC(SPECL [`l:num`; `pr:num`] SHARP_RAT_POINT_NORM) THEN
  ANTS_TAC THENL [FIRST_ASSUM ACCEPT_TAC; STRIP_TAC] THEN
  FIRST_ASSUM(MP_TAC o SPECL [`m:num->num`; `l:num`] o check (fun th ->
    is_forall(concl th) && free_in `lb8:(num->num)->num->real` (concl th) &&
    not(free_in `sharp_ubd` (concl th)))) THEN
  ANTS_TAC THENL [REPEAT CONJ_TAC THEN FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
  FIRST_ASSUM(MP_TAC o SPECL [`m:num->num`; `Cx(&l) / Cx(&pr)`; `l + 1`] o
    check (fun th -> is_forall(concl th) &&
                     free_in `sharp_ubd` (concl th) &&
                     free_in `sharp_errb` (concl th))) THEN
  REWRITE_TAC[ASSUME `norm(Cx(&l) / Cx(&pr)) = &l / &pr`] THEN
  ANTS_TAC THENL [CONJ_TAC THEN FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
  FIRST_ASSUM(MP_TAC o SPECL [`m:num->num`; `l:num`] o check (fun th ->
    is_forall(concl th) && free_in `lb8:(num->num)->num->real` (concl th) &&
    free_in `sharp_ubd` (concl th))) THEN
  ANTS_TAC THENL [REPEAT CONJ_TAC THEN FIRST_ASSUM ACCEPT_TAC; ALL_TAC] THEN
  MP_TAC(ISPECL [`sharp_alg n h L0 Lv p bb lg m (Cx(&l) / Cx(&pr))`;
                 `(f:(num->num)->complex->complex) m (Cx(&l) / Cx(&pr))`]
                NORM_TRIANGLE_SUB) THEN
  MP_TAC(ISPECL [`(f:(num->num)->complex->complex) m (Cx(&l) / Cx(&pr))`;
                 `sharp_alg n h L0 Lv p bb lg m (Cx(&l) / Cx(&pr))`]
                NORM_SUB) THEN
  REAL_ARITH_TAC);;

(* ------------------------------------------------------------------------- *)
(* The parametric core for algebraic data, complex coefficients and any      *)
(* Delta representation.                                                     *)
