let SHARP_CORE_PARAMETRIC = prove
 (`!n (lg:num->complex) (a:num->num->real) (dd:num->num) (bb:num->complex)
    (ab:num->num->real) (db:num->num) (H:num->real) Hb (W:num->real)
    (E:num->num) (Mb:num->real) (M:(num->num)->num) B h L0 L Ln Lm S0
    T0 d0 Nl eps J (R:num->num) (S:num->num) (rho:num->real) (NR:num->num)
