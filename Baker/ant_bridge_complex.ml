(* ========================================================================= *)
(* Number fields inside the complex numbers: the bridge between              *)
(* ANT/, 100/transcendence.ml and the algebraic integers of Baker/algint.ml. *)
(*                                                                           *)
(* The homomorphism from Z into complex_ring is n |-> Cx(real_of_int n)      *)
(* (COMPLEX_RING_OF_INT of Multivariate/complex_ring.ml). Integrality over Z *)
(* in complex_ring is algebraic_integer (INTEGRAL_ELEMENT_COMPLEX_RING of    *)
(* Baker/algint.ml), so the ring of integers of a subfield K of C is the set *)
(* of the algebraic integers in K. The prime subfield of C is                *)
(* {Cx q | rational q} (COMPLEX_PRIME_SUBFIELD of                            *)
(* ANT/complex_embeddings.ml), that is QinC_ring of transcendence.ml,        *)
(* contained in every subfield of C, and a subfield of C generated by        *)
(* finitely many algebraic numbers is a number field                         *)
(* (NUMBER_FIELD_SUBFIELD_GENERATED_ALGEBRAIC of ANT/numfield.ml). Generic   *)
(* lemmas on subrings and subfields of C (integers, rationals, integer       *)
(* polynomials and sums stay inside; ring sums and products are vsum and     *)
(* cproduct) and on ring homomorphisms from subfields of C (they fix the     *)
(* rationals and commute with sums, products and integer polynomials): the   *)
(* BRIDGE_NF_* lemmas, used by Sharpening I (section 6), the bridge          *)
(* Baker/ant_bridge_nf.ml, the S-unit descent (section 12) and the           *)
(* Schinzel-Tijdeman files (section 20).                                     *)
(*                                                                           *)
(* Main results: RING_OF_INTEGERS_COMPLEX_SUBFIELD,                          *)
(* RATIONAL_IN_COMPLEX_SUBFIELD, COMPLEX_PRIME_SUBFIELD_QINC,                *)
(* NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED; BRIDGE_NF_SUBFIELD_RATIONAL,     *)
(* BRIDGE_NF_SUBFIELD_CLOSED, BRIDGE_NF_PRIME_SUBFIELD,                      *)
(* BRIDGE_NF_RING_SUM_SUBFIELD, COMPLEX_SUBFIELD_RING_PRODUCT,               *)
(* BRIDGE_NF_HOM_CLAUSES, BRIDGE_NF_HOM_INTEGER, BRIDGE_NF_HOM_POLY,         *)
(* BRIDGE_NF_HOM_VSUM, BRIDGE_NF_HOM_CPRODUCT.                               *)
(*                                                                           *)
(* Uses: ANT/integral.ml (integral_element,                                  *)
(* INTEGRAL_ELEMENT_SUBRING_GENERATED); ANT/numfield.ml (number_field,       *)
(* ring_of_integers, RING_OF_INTEGERS_CARRIER,                               *)
(* NUMBER_FIELD_SUBFIELD_GENERATED_ALGEBRAIC); Multivariate/complex_ring.ml  *)
(* (complex_ring, COMPLEX_RING_OF_INT, COMPLEX_RING_SUM,                     *)
(* COMPLEX_RING_PRODUCT); Library/ringtheory.ml                              *)
(* (RING_PRODUCT_SUBRING_GENERATED, RING_HOMOMORPHISM_SUM,                   *)
(* RING_HOMOMORPHISM_PRODUCT); Library/fieldtheory.ml                        *)
(* (PRIME_SUBFIELD_SUBFIELD, PRIME_SUBFIELD_MINIMAL,                         *)
(* SUBFIELD_GENERATED_MINIMAL, SUBFIELD_SUBFIELD_GENERATED,                  *)
(* RING_HOMOMORPHISMS_EQ_FROM_SUBFIELD_GENERATED,                            *)
(* RING_SUM_SUBFIELD_GENERATED); 100/transcendence.ml (QinC_ring,            *)
(* algebraic_number, ALGEBRAIC_OVER_QINC_COMPLEX, complex_field_clauses);    *)
(* Baker/lemmas.ml (COMPLEX_SUBRING_CLOSED, COMPLEX_SUBRING_VSUM);           *)
(* Baker/algint.ml (algebraic_integer, INTEGRAL_ELEMENT_COMPLEX_RING);       *)
(* ANT/complex_embeddings.ml (COMPLEX_PRIME_SUBFIELD).                       *)
(* ========================================================================= *)

needs "ANT/discriminant_compositum.ml";;
needs "Baker/algint.ml";;

prioritize_real();;
prioritize_num();;

(* ------------------------------------------------------------------------- *)
(* The ring of integers of a subfield of C (its algebraic integers).         *)
(* ------------------------------------------------------------------------- *)

let RING_OF_INTEGERS_COMPLEX_SUBFIELD = prove
 (`!s. s subfield_of complex_ring
       ==> ring_carrier(ring_of_integers (subring_generated complex_ring s)) =
           {z | z IN s /\ algebraic_integer z}`,
  X_GEN_TAC `s:complex->bool` THEN DISCH_TAC THEN
  REWRITE_TAC[RING_OF_INTEGERS_CARRIER; RING_OF_INT_SUBRING_GENERATED;
              EXTENSION; IN_ELIM_THM] THEN
  X_GEN_TAC `z:complex` THEN
  MP_TAC(ISPECL [`integer_ring`; `complex_ring`; `ring_of_int complex_ring`;
                 `s:complex->bool`; `z:complex`]
                INTEGRAL_ELEMENT_SUBRING_GENERATED) THEN
  ASM_SIMP_TAC[RING_HOMOMORPHISM_INTEGER_RING_OF_INT; SUBFIELD_IMP_SUBRING_OF;
               SUBSET; FORALL_IN_IMAGE; IN_SUBRING_INT;
               INTEGRAL_ELEMENT_COMPLEX_RING] THEN
  CONV_TAC TAUT);;

(* ------------------------------------------------------------------------- *)
(* The prime subfield of complex_ring (the rationals, COMPLEX_PRIME_SUBFIELD *)
(* of ANT/complex_embeddings.ml) lies in every subfield; it is QinC_ring.    *)
(* ------------------------------------------------------------------------- *)

let RATIONAL_IN_COMPLEX_SUBFIELD = prove
 (`!k q. k subfield_of complex_ring /\ rational q ==> Cx q IN k`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`complex_ring`; `k:complex->bool`; `{Cx(&0)}`]
    SUBFIELD_GENERATED_MINIMAL) THEN
  ASM_REWRITE_TAC[COMPLEX_PRIME_SUBFIELD; SING_SUBSET] THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP IN_SUBFIELD_0) THEN
  REWRITE_TAC[COMPLEX_RING_CLAUSES] THEN ASM SET_TAC[]);;

let COMPLEX_PRIME_SUBFIELD_QINC = prove
 (`subfield_generated complex_ring {Cx(&0)} = QinC_ring`,
  REWRITE_TAC[GSYM subring_complex_QinC] THEN
  GEN_REWRITE_TAC LAND_CONV [GSYM SUBRING_GENERATED_BY_SUBFIELD_GENERATED] THEN
  AP_TERM_TAC THEN MATCH_MP_TAC SUBSET_ANTISYM THEN CONJ_TAC THENL
   [MP_TAC(ISPECL [`complex_ring`; `QinC`] PRIME_SUBFIELD_MINIMAL) THEN
    REWRITE_TAC[COMPLEX_RING_CLAUSES; subfield_of; QinC_subring_complex;
                subring_complex_QinC; field_QinC];
    REWRITE_TAC[COMPLEX_PRIME_SUBFIELD; SUBSET; QinC; IN_ELIM_THM] THEN
    X_GEN_TAC `z:complex` THEN
    DISCH_THEN(X_CHOOSE_THEN `i:int` (X_CHOOSE_THEN `d:num`
      STRIP_ASSUME_TAC)) THEN
    EXISTS_TAC `real_of_int i / &d` THEN
    SIMP_TAC[RATIONAL_CLOSED; INTEGER_REAL_OF_INT; CX_DIV] THEN
    UNDISCH_TAC `Cx(&d) * z = Cx(real_of_int i)` THEN
    UNDISCH_TAC `~(d = 0)` THEN
    REWRITE_TAC[GSYM REAL_OF_NUM_EQ; GSYM CX_INJ] THEN
    CONV_TAC COMPLEX_FIELD]);;

(* ------------------------------------------------------------------------- *)
(* Finitely many algebraic numbers generate a number field.                  *)
(* ------------------------------------------------------------------------- *)

let NUMBER_FIELD_COMPLEX_SUBFIELD_GENERATED = prove
 (`!s. FINITE s /\ (!z. z IN s ==> algebraic_number z)
       ==> number_field (subfield_generated complex_ring s)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC NUMBER_FIELD_SUBFIELD_GENERATED_ALGEBRAIC THEN
  ASM_REWRITE_TAC[FIELD_COMPLEX_RING; RING_CHAR_COMPLEX_RING;
                  COMPLEX_RING_CLAUSES; COMPLEX_PRIME_SUBFIELD_QINC;
                  ALGEBRAIC_OVER_QINC_COMPLEX]);;

(* ------------------------------------------------------------------------- *)
(* Subrings and subfields of the complex numbers: integers, rationals,       *)
(* integer polynomials and ring sums.                                        *)
(* ------------------------------------------------------------------------- *)

let BRIDGE_NF_CX_INTEGER = prove
 (`!x. integer x ==> Cx x = ring_of_int complex_ring (int_of_real x)`,
  REWRITE_TAC[COMPLEX_RING_OF_INT; CX_INJ] THEN
  MESON_TAC[int_tybij]);;

let BRIDGE_NF_SUBRING_INTEGER = prove
 (`!h x. h subring_of complex_ring /\ integer x ==> Cx x IN h`,
  SIMP_TAC[BRIDGE_NF_CX_INTEGER; IN_SUBRING_INT]);;

let BRIDGE_NF_SUBRING_POLY = prove
 (`!h z (p:num->real) m.
        h subring_of complex_ring /\ z IN h /\ (!i. integer(p i))
        ==> vsum(0..m) (\i. Cx(p i) * z pow i) IN h`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC COMPLEX_SUBRING_VSUM THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP COMPLEX_SUBRING_CLOSED) THEN
  ASM_SIMP_TAC[FINITE_NUMSEG; BRIDGE_NF_SUBRING_INTEGER]);;

let BRIDGE_NF_SUBFIELD_RATIONAL = prove
 (`!s q. rational q
         ==> Cx q IN ring_carrier(subfield_generated complex_ring s)`,
  SIMP_TAC[RATIONAL_IN_COMPLEX_SUBFIELD; SUBFIELD_SUBFIELD_GENERATED;
           FIELD_COMPLEX_RING]);;

let BRIDGE_NF_SUBFIELD_CLOSED = prove
 (`(!s x y. x IN ring_carrier(subfield_generated complex_ring s) /\
            y IN ring_carrier(subfield_generated complex_ring s)
            ==> x + y IN ring_carrier(subfield_generated complex_ring s)) /\
   (!s x y. x IN ring_carrier(subfield_generated complex_ring s) /\
            y IN ring_carrier(subfield_generated complex_ring s)
            ==> x * y IN ring_carrier(subfield_generated complex_ring s)) /\
   (!s x m. x IN ring_carrier(subfield_generated complex_ring s)
            ==> x pow m IN ring_carrier(subfield_generated complex_ring s))`,
  REWRITE_TAC[GSYM complex_field_clauses] THEN
  SIMP_TAC[RING_ADD_IN_SUBFIELD_GENERATED; RING_MUL_IN_SUBFIELD_GENERATED;
           RING_POW_IN_SUBFIELD_GENERATED]);;

let BRIDGE_NF_GEN_IN = prove
 (`!z. z IN ring_carrier(subfield_generated complex_ring {z})`,
  GEN_TAC THEN MATCH_MP_TAC SUBFIELD_GENERATED_INC_GEN THEN
  REWRITE_TAC[in_complex_ring; IN_SING]);;

let BRIDGE_NF_SUBFIELD_POLY = prove
 (`!s z (p:num->real) m d.
        z IN ring_carrier(subfield_generated complex_ring s) /\
        (!i. integer(p i)) /\ integer d
        ==> inv(Cx d) * vsum(0..m) (\i. Cx(p i) * z pow i) IN
            ring_carrier(subfield_generated complex_ring s)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC(CONJUNCT1(CONJUNCT2 BRIDGE_NF_SUBFIELD_CLOSED)) THEN
  ASM_SIMP_TAC[GSYM CX_INV; BRIDGE_NF_SUBFIELD_RATIONAL; RATIONAL_INV;
               RATIONAL_INTEGER; BRIDGE_NF_SUBRING_POLY;
               SUBRING_SUBFIELD_GENERATED]);;

let BRIDGE_NF_RING_SUM_SUBFIELD = prove
 (`!s k (f:A->complex).
        FINITE k /\
        (!i. i IN k ==> f i IN ring_carrier(subfield_generated complex_ring s))
        ==> ring_sum (subfield_generated complex_ring s) k f = vsum k f`,
  SIMP_TAC[RING_SUM_SUBFIELD_GENERATED; COMPLEX_RING_SUM]);;

let COMPLEX_SUBFIELD_RING_PRODUCT = prove
 (`!s t (f:A->complex).
        FINITE t /\
        (!i. i IN t ==> f i IN ring_carrier(subfield_generated complex_ring s))
        ==> ring_product (subfield_generated complex_ring s) t f =
            cproduct t f`,
  REPEAT STRIP_TAC THEN
  MP_TAC(ISPECL [`complex_ring`;
                 `ring_carrier(subfield_generated complex_ring s)`;
                 `t:A->bool`; `f:A->complex`]
    RING_PRODUCT_SUBRING_GENERATED) THEN
  REWRITE_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED;
              SUBRING_SUBFIELD_GENERATED] THEN
  DISCH_THEN SUBST1_TAC THEN ASM_SIMP_TAC[GSYM COMPLEX_RING_PRODUCT] THEN
  AP_THM_TAC THEN AP_TERM_TAC THEN ASM SET_TAC[]);;

let BRIDGE_NF_PRIME_SUBFIELD = prove
 (`!s. subfield_generated (subfield_generated complex_ring s)
                          {ring_0 (subfield_generated complex_ring s)} =
       subfield_generated complex_ring {Cx(&0)}`,
  GEN_TAC THEN REWRITE_TAC[CONJUNCT2 SUBFIELD_GENERATED] THEN
  MP_TAC(ISPECL [`complex_ring`;
                 `ring_carrier(subfield_generated complex_ring s)`]
    PRIME_SUBFIELD_SUBFIELD) THEN
  REWRITE_TAC[SUBRING_GENERATED_BY_SUBFIELD_GENERATED] THEN
  SIMP_TAC[SUBFIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING;
           COMPLEX_RING_CLAUSES]);;

(* ------------------------------------------------------------------------- *)
(* Ring homomorphisms from subfields of the complex numbers: they fix the    *)
(* rationals and commute with sums and integer polynomials.                  *)
(* ------------------------------------------------------------------------- *)

let BRIDGE_NF_HOM_VSUM = prove
 (`!s f k (g:A->complex).
        ring_homomorphism(subfield_generated complex_ring s,complex_ring) f /\
        FINITE k /\
        (!i. i IN k ==> g i IN ring_carrier(subfield_generated complex_ring s))
        ==> f(vsum k g) = vsum k (\i. f(g i))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o ISPECL [`g:A->complex`; `k:A->bool`] o
    MATCH_MP RING_HOMOMORPHISM_SUM) THEN
  ASM_SIMP_TAC[BRIDGE_NF_RING_SUM_SUBFIELD; COMPLEX_RING_SUM; o_DEF]);;

let BRIDGE_NF_HOM_CPRODUCT = prove
 (`!s f k (g:A->complex).
        ring_homomorphism(subfield_generated complex_ring s,complex_ring) f /\
        FINITE k /\
        (!i. i IN k ==> g i IN ring_carrier(subfield_generated complex_ring s))
        ==> f(cproduct k g) = cproduct k (\i. f(g i))`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(MP_TAC o ISPECL [`g:A->complex`; `k:A->bool`] o
    MATCH_MP RING_HOMOMORPHISM_PRODUCT) THEN
  ASM_SIMP_TAC[COMPLEX_SUBFIELD_RING_PRODUCT; COMPLEX_RING_PRODUCT; o_DEF]);;

let BRIDGE_NF_HOM_CLAUSES = prove
 (`!s f. ring_homomorphism(subfield_generated complex_ring s,complex_ring) f
         ==> (!x y. x IN ring_carrier(subfield_generated complex_ring s) /\
                    y IN ring_carrier(subfield_generated complex_ring s)
                    ==> f(x + y) = f x + f y /\ f(x * y) = f x * f y) /\
             (!x m. x IN ring_carrier(subfield_generated complex_ring s)
                    ==> f(x pow m) = f x pow m) /\
             (!q. rational q ==> f(Cx q) = Cx q)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  MP_TAC(ISPECL [`f:complex->complex`; `I:complex->complex`;
                 `subfield_generated complex_ring s`; `complex_ring`;
                 `{ring_0(subfield_generated complex_ring s)}`]
    RING_HOMOMORPHISMS_EQ_FROM_SUBFIELD_GENERATED) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP RING_HOMOMORPHISM_0) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP RING_HOMOMORPHISM_POW) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP RING_HOMOMORPHISM_MUL) THEN
  FIRST_ASSUM(MP_TAC o MATCH_MP RING_HOMOMORPHISM_ADD) THEN
  ASM_SIMP_TAC[FIELD_SUBFIELD_GENERATED; FIELD_COMPLEX_RING; IN_SING; I_THM;
               RING_HOMOMORPHISM_SUBFIELD_INCLUSION;
               BRIDGE_NF_PRIME_SUBFIELD] THEN
  REWRITE_TAC[CONJUNCT2 SUBFIELD_GENERATED; RING_POW_SUBFIELD_GENERATED;
              complex_field_clauses; COMPLEX_PRIME_SUBFIELD;
              FORALL_IN_GSPEC] THEN
  SIMP_TAC[]);;

let BRIDGE_NF_HOM_INTEGER = prove
 (`!s f x.
        ring_homomorphism(subfield_generated complex_ring s,complex_ring) f /\
        integer x
        ==> f(Cx x) = Cx x`,
  MESON_TAC[BRIDGE_NF_HOM_CLAUSES; RATIONAL_INTEGER]);;

let BRIDGE_NF_HOM_POLY = prove
 (`!s f z (p:num->real) m.
        ring_homomorphism(subfield_generated complex_ring s,complex_ring) f /\
        z IN ring_carrier(subfield_generated complex_ring s) /\
        (!i. rational(p i))
        ==> f(vsum(0..m) (\i. Cx(p i) * z pow i)) =
            vsum(0..m) (\i. Cx(p i) * f z pow i)`,
  REPEAT STRIP_TAC THEN
  FIRST_ASSUM(STRIP_ASSUME_TAC o MATCH_MP BRIDGE_NF_HOM_CLAUSES) THEN
  MP_TAC(ISPECL [`s:complex->bool`; `f:complex->complex`; `0..m`;
                 `\i. Cx(p i) * (z:complex) pow i`] BRIDGE_NF_HOM_VSUM) THEN
  ASM_SIMP_TAC[FINITE_NUMSEG; BRIDGE_NF_SUBFIELD_CLOSED;
               BRIDGE_NF_SUBFIELD_RATIONAL] THEN
  DISCH_THEN(K ALL_TAC) THEN MATCH_MP_TAC VSUM_EQ_NUMSEG THEN
  ASM_SIMP_TAC[BRIDGE_NF_SUBFIELD_CLOSED; BRIDGE_NF_SUBFIELD_RATIONAL]);;
